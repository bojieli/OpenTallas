    ab.add_argument("--work", required=True)
    ab.add_argument("--nick", required=True)
    ab.add_argument("--platform", default="asap7")
    ab.add_argument("--corner", default="TT")
    t = sub.add_parser("sta-scripts")
    t.add_argument("--gen", required=True)
    t.add_argument("--work", required=True)
    t.add_argument("--flat-work")
    t.add_argument("--nick", required=True)
    t.add_argument("--top")
    t.add_argument("--platform", default="asap7")
    t.add_argument("--lib", action="append", required=True)
    t.add_argument("--top-v", help="top netlist (default WORK top 6_final.v)")
    t.add_argument("--top-spef", help="top SPEF (default 6_final.spef; scripts/grt_spef.sh for a GRT estimate)")
    t.add_argument("--flat-v")
    t.add_argument("--flat-spef")
    t.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "plan" and not a.clock_port:
        a.clock_port = ["clk"]
    return {"plan": cmd_plan, "verify": cmd_verify, "compare": cmd_compare,
            "sta-scripts": cmd_sta_scripts, "abstract": cmd_abstract}[a.cmd](a)


