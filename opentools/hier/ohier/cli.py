def _libs(args):
    files = []
    for g in args.lib or []:
        files += sorted(glob.glob(g)) or [g]
    cells = L.read_liberty(files)
    lefs = []
    for g in args.lef or []:
        lefs += sorted(glob.glob(g)) or [g]
    macros = L.read_lef_macros(lefs)
    L.mark_macros(cells, macros)
    return cells, macros


def cmd_plan(a):
    cells, macros = _libs(a)
    nl = N.load_yosys_json(a.netlist, a.top, cells)
    base, rmap, die_wh = None, None, None
    if a.region_map:
        base, rmap = S.region_map(a.region_map)
        die_wh = (base["die"]["w"], base["die"]["h"])
    o = PL.Options(block_margin_um=a.block_margin_um, k=a.k, cap_cells=a.cap_cells, unit_max_cells=a.unit_max_cells,
                   period_ps=a.period_ps, latency_ps=a.latency_ps, io_budget_ps=a.io_budget_ps,
                   util=a.util, channel_um=a.channel_um, macro_halo_um=a.macro_halo_um, clock_ports=tuple(a.clock_port),
                   ps_per_um=a.ps_per_um, balance_eps=a.balance_eps, grid_um=a.grid_um,
                   wire_ff_per_um=a.wire_ff_per_um, context=not a.no_context,
                   default_drive_cell=a.drive_cell, default_drive_pin=a.drive_pin)
    plan, leaf_part, part_ports = PL.build_plan(nl, cells, macros, o, a.design, region_map=rmap,
                                                 die_wh=die_wh)
    errs = S.validate(plan)
    plan["metrics"]["schema_errors"] = errs
    out = a.out
    root = a.flow_root or os.path.abspath(out)
    os.makedirs(out, exist_ok=True)
    S.save(plan, os.path.join(out, "plan.json"), base=base)
    sdcs = PL.partition_sdcs(plan, part_ports, o)
    pins_by = {}
    for d in plan["pins"]:
        pins_by.setdefault(d["region"], []).append(d)
    modules = [r["module"] for r in plan["regions"]]
    macro_lefs = [m for m in (a.macro_lef or [])]
    macro_libs = [m for m in (a.macro_lib or [])]
    for r in plan["regions"]:
        rid, mod = r["id"], r["module"]
        x0, y0, x1, y1 = r["bbox_um"]
        E.write(os.path.join(out, mod, f"{mod}.v"),
                E.partition_verilog(nl, leaf_part, rid, mod, part_ports[rid]))
        E.write(os.path.join(out, mod, "constraint.sdc"), sdcs[rid])
        local = [dict(d, offset_um=d["offset_um"]) for d in pins_by.get(rid, [])]
        E.write(os.path.join(out, mod, "io.tcl"), PI.io_tcl(local, r["bbox_um"], o.pin_pitch_um))
        has_mac = bool(r["macros"])
        E.write(os.path.join(out, mod, "config.mk"),
                E.block_config(a.platform, a.nick, mod, root, (x1 - x0, y1 - y0), a.block_margin_um,
                               macro_lefs if has_mac else [], macro_libs if has_mac else [],
                               a.block_density, halo=a.macro_halo_um))
    die = plan["die"]["bbox_um"]
    m = plan["die"]["core_margin_um"]
    E.write(os.path.join(out, "top.v"), E.top_verilog(nl, modules, part_ports))
    E.write(os.path.join(out, "macro_place.tcl"),
            E.macro_place_tcl([(f"u_{r['module']}", r["bbox_um"][0], r["bbox_um"][1])
                               for r in plan["regions"]]))
    sdc_root = f"{root}/design.sdc"
    if a.sdc:
        with open(a.sdc) as fh:
            E.write(os.path.join(out, "design.sdc"), fh.read())
    E.write(os.path.join(out, "config.mk"),
            # top core one grid step larger than the slot margin: a slot that touches the
            # margin must still be strictly inside the core (measured: rtl_macro_placer
            # MPL-0006 on an 89.64-um slot in an 89.64-um core)
            E.top_config(a.platform, a.nick, nl.top, root, modules, (die[2], die[3]),
                         max(0.0, m - o.grid_um), sdc_root))
    # flat baseline on the identical leaf netlist and die
    E.write(os.path.join(out, "flat", f"{nl.top}.v"), E.flat_verilog(nl))
    flat_cfg = [
        "# generated by opentools/hier: flat baseline, same cells, same die",
        f"export PLATFORM = {a.platform}", f"export DESIGN_NAME = {nl.top}",
        f"export DESIGN_NICKNAME = {a.nick}_flat",
        f"export SYNTH_NETLIST_FILES = {root}/flat/{nl.top}.v", f"export SDC_FILE = {sdc_root}",
        f"export DIE_AREA = 0 0 {die[2]:.3f} {die[3]:.3f}",
        f"export CORE_AREA = {m:.3f} {m:.3f} {die[2] - m:.3f} {die[3] - m:.3f}",
        "export PLACE_DENSITY = 0.60", f"export MACRO_PLACE_HALO = {a.macro_halo_um:g} {a.macro_halo_um:g}", "export TNS_END_PERCENT = 100",
    ]
    if macro_lefs:
        flat_cfg += ["export ADDITIONAL_LEFS = " + " ".join(macro_lefs),
                     "export ADDITIONAL_LIBS = " + " ".join(macro_libs)]
    E.write(os.path.join(out, "flat", "config.mk"), "\n".join(flat_cfg) + "\n")
    summ = {k: plan["metrics"][k] for k in ("mode", "cells", "items", "glue_items", "crossing_bits", "pairs",
                                            "ports_per_partition", "floorplan_macro_fit")}
    summ["regions"] = [{k: r[k] for k in ("id", "module", "cells", "bbox_um", "macros", "ports", "util")}
                       for r in plan["regions"]]
    summ["schema_errors"] = errs
    print(json.dumps(summ, indent=1))
    return 0 if not errs and plan["metrics"]["floorplan_macro_fit"] else 2


def cmd_verify(a):
    cells, _ = _libs(a)
    with open(a.orig) as fh:
        oj = json.load(fh)
    with open(a.part) as fh:
        pj = json.load(fh)
    res = V.compare(oj, pj, a.top, cells)
    print(json.dumps(res, indent=1))
    return 0 if res["equivalent"] else 1


def cmd_compare(a):
    d = a.sta_dir
    insts = None
    if a.gen:
        insts = [f"u_{r['module']}" for r in S.load(os.path.join(a.gen, "plan.json"))["regions"]]
    res = {}
    ends = {}
    for mode in ("flat", "stitched", "etm"):
        log = os.path.join(d, f"{mode}.log")
        if not os.path.exists(log):
            continue
        with open(log) as fh:
            res[mode] = H.parse_scalars(fh.read())
        for kind in ("max", "min"):
            p = os.path.join(d, f"{mode}_end_{kind}.txt")
            if os.path.exists(p):
                with open(p) as fh:
                    ends[(mode, kind)] = {H.norm(k, insts): v for k, v in H.parse_end(fh.read()).items()}
            b = os.path.join(d, f"{mode}_boundary_{kind}.txt")
            if os.path.exists(b):
                with open(b) as fh:
                    res[mode][f"boundary_wns_{kind}"] = H.parse_worst_slack(fh.read())
    corr = {}
    bp = {}
    for mode in ("stitched", "etm"):
        f = os.path.join(d, f"{mode}_bpins.txt")
        if os.path.exists(f):
            with open(f) as fh:
                bp[mode] = H.parse_bpins(fh.read())
    if len(bp) == 2:
        # the abstraction check: worst slack through every partition boundary pin,
        # full partition netlists + SPEF (stitched) vs partition ETMs (etm)
        for i, kind in enumerate(("max", "min")):
            a_ = {k: v[i] for k, v in bp["stitched"].items() if v[i] is not None}
            b_ = {k: v[i] for k, v in bp["etm"].items() if v[i] is not None}
            corr[f"boundary_pin_stitched_vs_etm_{kind}"] = H.correlate(a_, b_)
    for kind in ("max", "min"):
        if ("flat", kind) in ends and ("stitched", kind) in ends:
            corr[f"flat_vs_stitched_{kind}"] = H.correlate(ends[("flat", kind)], ends[("stitched", kind)])
        if ("stitched", kind) in ends and ("etm", kind) in ends:
            corr[f"stitched_vs_etm_{kind}"] = H.correlate(ends[("stitched", kind)], ends[("etm", kind)])
    out = {"views": res, "endpoint_correlation": corr}
    with open(a.out, "w") as fh:
        json.dump(out, fh, indent=1)
    print(json.dumps(out, indent=1))
    return 0


def cmd_abstract(a):
    """Check every partition abstract (LEF + ETM) against the plan and write each
    partition's measured clock insertion into the shared plan."""
    path = os.path.join(a.gen, "plan.json")
    doc = S.load_shared(path)
    hv = doc["hier"]
    res = {}
    for r in hv["regions"]:
        rd = os.path.join(a.work, "results", a.platform, f"{a.nick}_{r['module']}", "base")
        lef, etm = os.path.join(rd, f"{r['module']}.lef"), os.path.join(rd, f"{r['module']}_typ.lib")
        if not (os.path.exists(lef) and os.path.exists(etm)):
            res[r["module"]] = {"ok": False, "problems": [f"missing {lef if not os.path.exists(lef) else etm}"]}
            continue
        ports = [p["port"] for p in hv["pins"] if p["region"] == r["id"]]
        with open(lef) as fl, open(etm) as fe:
            c = A.check(r, fl.read(), fe.read(), ports)
        c.update(lef=lef, etm=etm)
        res[r["module"]] = c
        for m in doc["macros"]:
            if m.get("master") == r["module"] and c["insertion_ps"]:
                for cp in m.get("clock_pins", []):
                    cp["insertion_ps"] = {a.corner: round(c["insertion_ps"].get("max", 0.0), 2)}
                    cp["insertion_min_ps"] = {a.corner: round(c["insertion_ps"].get("min", 0.0), 2)}
    doc["hier"]["abstracts"] = res
    S.CP.save(doc, path)
    print(json.dumps({k: {kk: v[kk] for kk in ("ok", "problems", "insertion_ps", "n_pins") if kk in v}
                      for k, v in res.items()}, indent=1))
    return 0 if all(v["ok"] for v in res.values()) else 1


def cmd_sta_scripts(a):
    plan = S.load(os.path.join(a.gen, "plan.json"))
    top = plan["design"] if not a.top else a.top
    libs = []
    for g in a.lib:
        libs += sorted(glob.glob(g)) or [g]
    res = lambda nick: os.path.join(a.work, "results", a.platform, nick, "base")
    sdc = os.path.join(a.gen, "design.sdc")
    os.makedirs(a.out, exist_ok=True)
    fr = res(f"{a.nick}_flat") if not a.flat_work else os.path.join(a.flat_work, "results", a.platform, f"{a.nick}_flat", "base")
    fv, fs = a.flat_v or f"{fr}/6_final.v", a.flat_spef or f"{fr}/6_final.spef"
    if os.path.exists(fv) and os.path.exists(fs):
        E.write(os.path.join(a.out, "flat.tcl"), H.tcl_flat(libs, fv, top, fs, sdc, a.out))
    tr = res(a.nick)
    tv, ts = a.top_v or f"{tr}/6_final.v", a.top_spef or f"{tr}/6_final.spef"
    blocks, etms, insts = [], [], []
    for r in plan["regions"]:
        br = res(f"{a.nick}_{r['module']}")
        inst = f"u_{r['module']}"
        blocks.append((inst, f"{br}/6_final.v", f"{br}/6_final.spef"))
        etms.append(f"{br}/{r['module']}_typ.lib")
        insts.append(inst)
    E.write(os.path.join(a.out, "stitched.tcl"),
            H.tcl_stitched(libs, tv, top, ts, blocks, sdc, a.out))
    E.write(os.path.join(a.out, "etm.tcl"),
            H.tcl_etm(libs, etms, tv, top, ts, insts, sdc, a.out))
    print(a.out)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ohier")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--netlist", required=True)
    p.add_argument("--top")
    p.add_argument("--design")
    p.add_argument("--lib", action="append")
    p.add_argument("--lef", action="append")
    p.add_argument("--macro-lef", action="append", help="flow-side path, written into config.mk")
    p.add_argument("--macro-lib", action="append", help="flow-side path, written into config.mk")
    p.add_argument("--sdc")
    p.add_argument("--region-map", help="opentools.plan/1 doc: regions[] + hier.region_members -> 1 partition each")
    p.add_argument("--k", type=int, default=4)
    p.add_argument("--cap-cells", type=int, default=400_000)
    p.add_argument("--unit-max-cells", type=int, default=0)
    p.add_argument("--balance-eps", type=float, default=0.3)
    p.add_argument("--period-ps", type=float, default=1000.0)
    p.add_argument("--latency-ps", type=float, default=100.0)
    p.add_argument("--io-budget-ps", type=float, default=0.0)
    p.add_argument("--util", type=float, default=0.55)
    p.add_argument("--channel-um", type=float, default=4.0)
    p.add_argument("--macro-halo-um", type=float, default=4.0)
    p.add_argument("--ps-per-um", type=float, default=1.0)
    p.add_argument("--grid-um", type=float, default=2.16, help="region corner grid: lcm(row/site grid, pin track pitch)")
    p.add_argument("--wire-ff-per-um", type=float, default=0.20)
    p.add_argument("--drive-cell", default="BUFx2_ASAP7_75t_R")
    p.add_argument("--drive-pin", default="Y")
    p.add_argument("--no-context", action="store_true", help="no set_driving_cell/set_load in partition SDCs")
    p.add_argument("--clock-port", action="append", default=None)
    p.add_argument("--platform", default="asap7")
    p.add_argument("--nick", default="ohier")
    p.add_argument("--block-margin-um", type=float, default=1.08)
    p.add_argument("--block-density", type=float, default=0.60)
    p.add_argument("--flow-root", help="path of OUT as the flow container sees it")
    p.add_argument("--out", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--orig", required=True)
    v.add_argument("--part", required=True)
    v.add_argument("--top", required=True)
    v.add_argument("--lib", action="append")
    v.add_argument("--lef", action="append")
    c = sub.add_parser("compare")
    c.add_argument("--sta-dir", required=True)
    c.add_argument("--out", required=True)
    c.add_argument("--gen", help="plan dir: partition instance names for endpoint matching")
