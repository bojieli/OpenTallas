"""Hierarchical STA scripts and flat-vs-hierarchical correlation.

Three OpenSTA (openroad) views of the same design and SDC:
  flat     : flat P&R result (6_final.v + 6_final.spef)
  stitched : top 6_final.v + every partition's 6_final.v, top SPEF and
             per-instance partition SPEF (read_spef -path) -- the exact
             timing of the hierarchical implementation, ILM-like but with
             full netlists
  etm      : top 6_final.v with partitions as ETM liberty cells
             (write_timing_model, clock insertion inside) + top SPEF --
             what a die-level STA on abstracts sees
Correlation is reported per endpoint (flat vs stitched, common register
names) and per view (WNS/TNS, boundary-crossing WNS).
"""
from __future__ import annotations

import math
import re

_HDR = """# generated by opentools/hier hsta.py ({mode})
foreach f [list {libs}] {{ read_liberty $f }}
"""

_TAIL = """read_sdc {sdc}
set_propagated_clock [all_clocks]
puts "OHIER_WNS_MAX [sta::worst_slack_cmd max]"
puts "OHIER_WNS_MIN [sta::worst_slack_cmd min]"
puts "OHIER_TNS_MAX [sta::total_negative_slack_cmd max]"
{extra}
report_checks -path_delay max -group_path_count 1000000 -endpoint_path_count 1 -format end > {out}/{mode}_end_max.txt
report_checks -path_delay min -group_path_count 1000000 -endpoint_path_count 1 -format end > {out}/{mode}_end_min.txt
report_checks -path_delay max -fields {{slew cap input_pins}} -digits 1 > {out}/{mode}_worst_max.txt
report_checks -path_delay min -digits 1 > {out}/{mode}_worst_min.txt
"""

_BOUNDARY = """set ohier_bp [get_pins -of_objects [get_cells {{{insts}}}] -filter "direction != internal"]
set ohier_bp_data {{}}
foreach p $ohier_bp {{ if {{![string match {{*/{clk}}} [get_full_name $p]]}} {{ lappend ohier_bp_data $p }} }}
report_checks -path_delay max -through $ohier_bp_data -digits 1 > {out}/{mode}_boundary_max.txt
report_checks -path_delay min -through $ohier_bp_data -digits 1 > {out}/{mode}_boundary_min.txt
set ohier_fh [open {out}/{mode}_bpins.txt w]
foreach p $ohier_bp_data {{
  puts $ohier_fh "[get_full_name $p] [get_property $p slack_max] [get_property $p slack_min]"
}}
close $ohier_fh
"""


def tcl_flat(libs, verilog, top, spef, sdc, out):
    return (_HDR.format(mode="flat", libs=" ".join(libs)) +
            f"read_verilog {verilog}\nlink_design {top}\nread_spef {spef}\n" +
            _TAIL.format(sdc=sdc, out=out, mode="flat", extra=""))


def tcl_stitched(libs, top_v, top, top_spef, blocks, sdc, out, clk="clk"):
    """blocks: [(inst, verilog, spef)]"""
    s = _HDR.format(mode="stitched", libs=" ".join(libs))
    s += f"read_verilog {top_v}\n"
    for _, v, _ in blocks:
        s += f"read_verilog {v}\n"
    s += f"link_design {top}\nread_spef {top_spef}\n"
    for inst, _, sp in blocks:
        s += f"read_spef -path {inst} {sp}\n"
    extra = _BOUNDARY.format(insts=" ".join(i for i, _, _ in blocks), clk=clk, out=out, mode="stitched")
    return s + _TAIL.format(sdc=sdc, out=out, mode="stitched", extra=extra)


def tcl_etm(libs, etm_libs, top_v, top, top_spef, insts, sdc, out, clk="clk"):
    s = _HDR.format(mode="etm", libs=" ".join(list(libs) + list(etm_libs)))
    s += f"read_verilog {top_v}\nlink_design {top}\nread_spef {top_spef}\n"
    extra = _BOUNDARY.format(insts=" ".join(insts), clk=clk, out=out, mode="etm")
    return s + _TAIL.format(sdc=sdc, out=out, mode="etm", extra=extra)


# ------------------------------------------------------------- parsing
_NUM = re.compile(r"^-?\d+(\.\d+)?$")


def parse_end(text):
    """OpenSTA `-format end` table -> {endpoint: slack}."""
    out = {}
    for line in text.splitlines():
        t = line.split()
        if len(t) >= 4 and _NUM.match(t[-1]) and _NUM.match(t[-2]) and _NUM.match(t[-3]):
            out[t[0]] = float(t[-1])
    return out


def parse_bpins(text):
    """`<pin> <slack_max> <slack_min>` lines -> {pin: (max, min)} (None for unconstrained)."""
    out = {}
    for line in text.splitlines():
        t = line.split()
        if len(t) != 3:
            continue
        v = []
        for x in t[1:]:
            try:
                f = float(x)
                v.append(f if abs(f) < 1e20 else None)
            except ValueError:
                v.append(None)
        out[t[0].replace("\\", "")] = tuple(v)
    return out


def parse_scalars(log):
    vals = {}
    for m in re.finditer(r"OHIER_(\w+) (\S+)", log):
        try:
            vals[m.group(1)] = float(m.group(2))
        except ValueError:
            vals[m.group(1)] = None
    return vals


def parse_worst_slack(report):
    m = re.search(r"(-?\d+(?:\.\d+)?)\s+slack", report)
    return float(m.group(1)) if m else None


def norm(name, insts=None, strip=r"^u_[A-Za-z0-9_]+_P\d+[./]"):
    """Endpoint name without the partition instance prefix (insts: partition instance names)."""
    n = name.replace("\\", "")
    if insts:
        strip = r"^(?:%s)[./]" % "|".join(re.escape(i) for i in insts)
    n = re.sub(strip, "", n)
    return n.replace("/", ".")


def correlate(a, b):
    """a, b: {endpoint: slack} (normalized names). Returns stats dict."""
    common = sorted(set(a) & set(b))
    out = {"n_a": len(a), "n_b": len(b), "n_common": len(common)}
    if len(common) < 2:
        return out
    xs = [a[k] for k in common]
    ys = [b[k] for k in common]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    d = [y - x for x, y in zip(xs, ys)]
    out.update({
        "pearson_r": round(sxy / math.sqrt(sxx * syy), 4) if sxx > 0 and syy > 0 else None,
        "mean_diff_ps": round(sum(d) / len(d), 2),
        "mean_abs_diff_ps": round(sum(abs(v) for v in d) / len(d), 2),
        "max_abs_diff_ps": round(max(abs(v) for v in d), 2),
        "p95_abs_diff_ps": round(sorted(abs(v) for v in d)[int(0.95 * (len(d) - 1))], 2),
        "worst_a": round(min(xs), 2), "worst_b": round(min(ys), 2),
    })
    return out
