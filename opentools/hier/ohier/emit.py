"""Netlist + ORFS design-directory emission.

* flat_verilog: the whole leaf graph as one module (the flat baseline uses
  exactly the same cells and instance names as the partitions).
* partition_verilog / top_verilog: one module per region (leaf cells only,
  hierarchical names kept as escaped identifiers) and a top that wires the
  partitions and the chip ports.
* orfs_dirs: ORFS config.mk per partition (BLOCKS convention) + top.
"""
from __future__ import annotations

# ORFS library corner for every emitted flow (asap7: BC=FF, TC=TT, WC=SS; ORFS default is BC).
# The hier STA reads TT libraries, so blocks, abstracts, top and flat are all built at TC.
CORNER = "TC"

import os
import re

_SAFE = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*$")


def esc(name):
    return name if _SAFE.match(name) else "\\" + name + " "


def sanitize(name):
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not s or not (s[0].isalpha() or s[0] == "_"):
        s = "n_" + s
    return s


def _const(b):
    return {"0": "1'b0", "1": "1'b1", "x": "1'bx", "z": "1'bz"}[b]


def _expr(bits, netref):
    parts = [(_const(b) if not isinstance(b, int) else netref(b)) for b in bits]
    if len(parts) == 1:
        return parts[0]
    return "{" + ", ".join(reversed(parts)) + "}"   # Yosys bits are LSB first


def _cell_lines(lf, netref, out):
    conns = ", ".join(f".{p}({_expr(bits, netref)})" for p, bits in sorted(lf.conns.items()))
    out.append(f"  {lf.type} {esc(lf.name)} ({conns});")


def flat_verilog(nl, module=None):
    module = module or nl.top
    lines = []
    port_bit = {}
    decl = []
    for pn, p in nl.ports.items():
        w = len(p["bits"])
        rng = f" [{w - 1}:0]" if w > 1 else ""
        decl.append(f"  {p['direction']}{rng} {esc(pn)};")
        for i, b in enumerate(p["bits"]):
            if isinstance(b, int) and b not in port_bit:
                port_bit[b] = esc(pn) + (f"[{i}]" if w > 1 else "")

    def ref(n):
        return port_bit.get(n, f"_n{n}_")

    used = set()
    for lf in nl.leaves:
        for bits in lf.conns.values():
            used.update(b for b in bits if isinstance(b, int))
    lines.append(f"module {esc(module)} ({', '.join(esc(p) for p in nl.ports)});")
    lines += decl
    for n in sorted(used - set(port_bit)):
        lines.append(f"  wire _n{n}_;")
    lines += _port_assigns(nl, port_bit)
    for lf in nl.leaves:
        _cell_lines(lf, ref, lines)
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def _port_assigns(nl, port_bit):
    """Output port bits that are constants or aliases of another port bit."""
    out = []
    for pn, p in nl.ports.items():
        if p["direction"] != "output":
            continue
        w = len(p["bits"])
        for i, b in enumerate(p["bits"]):
            me = esc(pn) + (f"[{i}]" if w > 1 else "")
            if not isinstance(b, int):
                out.append(f"  assign {me} = {_const(b)};")
            elif port_bit.get(b) != me:
                out.append(f"  assign {me} = {port_bit[b]};")
    return out


def partition_ports(nl, leaf_part, k):
    """Return per-partition {net: (port name, direction)} and net->parts map."""
    pins = nl.net_pins()
    pnets = nl.port_nets()
    names = {}
    used = set()
    part_ports = [dict() for _ in range(k)]
    net_parts = {}
    for net, pl in pins.items():
        parts = sorted({leaf_part[li] for li, _, _ in pl})
        net_parts[net] = parts
        if len(parts) == 1 and net not in pnets:
            continue
        # name: chip port bit if any, else sanitized net name
        if net in pnets:
            pn, bi, _ = pnets[net][0]
            w = len(nl.ports[pn]["bits"])
            base = sanitize(pn if w == 1 else f"{pn}_{bi}_")
        else:
            base = sanitize(nl.net_names[net])
        nm = base
        j = 1
        while nm in used:
            nm = f"{base}_{j}"
            j += 1
        used.add(nm)
        names[net] = nm
        # direction per partition: output if a leaf in it drives the net
        for p in parts:
            drives = False
            for li, port, _ in pl:
                if leaf_part[li] != p:
                    continue
                if nl.pin_dirs.get(nl.leaves[li].type, {}).get(port) == "output":
                    drives = True
            part_ports[p][net] = (nm, "output" if drives else "input")
    return part_ports, net_parts, names


def partition_verilog(nl, leaf_part, pid, module, ports):
    lines = [f"// generated by opentools/hier: partition {pid}",
             f"module {module} ({', '.join(nm for nm, _ in sorted(ports.values()))});"]
    for net, (nm, d) in sorted(ports.items(), key=lambda t: t[1][0]):
        lines.append(f"  {d} {nm};")
    internal = set()
    members = [lf for li, lf in enumerate(nl.leaves) if leaf_part[li] == pid]
    for lf in members:
        for bits in lf.conns.values():
            internal.update(b for b in bits if isinstance(b, int) and b not in ports)
    for n in sorted(internal):
        lines.append(f"  wire _n{n}_;")

    def ref(n):
        return ports[n][0] if n in ports else f"_n{n}_"

    for lf in members:
        _cell_lines(lf, ref, lines)
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def top_verilog(nl, modules, part_ports):
    port_bit = {}
    lines = [f"// generated by opentools/hier: top assembly",
             f"module {esc(nl.top)} ({', '.join(esc(p) for p in nl.ports)});"]
    for pn, p in nl.ports.items():
        w = len(p["bits"])
        rng = f" [{w - 1}:0]" if w > 1 else ""
        lines.append(f"  {p['direction']}{rng} {esc(pn)};")
        for i, b in enumerate(p["bits"]):
            if isinstance(b, int) and b not in port_bit:
                port_bit[b] = esc(pn) + (f"[{i}]" if w > 1 else "")
    wires = set()
    for pp in part_ports:
        wires.update(n for n in pp if n not in port_bit)
    for n in sorted(wires):
        lines.append(f"  wire _n{n}_;")
    lines += _port_assigns(nl, port_bit)
    for pid, (mod, pp) in enumerate(zip(modules, part_ports)):
        conns = ", ".join(f".{nm}({port_bit.get(n, f'_n{n}_')})"
                          for n, (nm, _) in sorted(pp.items(), key=lambda t: t[1][0]))
        lines.append(f"  {mod} u_{mod} ({conns});")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------- ORFS dirs
def write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


def block_config(platform, nick, module, root, die_wh, margin, macro_lefs, macro_libs,
                 place_density, extra=None, halo=4.0):
    w, h = die_wh
    lines = [
        "# generated by opentools/hier (ORFS BLOCKS convention)",
        f"export PLATFORM = {platform}",
        f"export CORNER = {CORNER}",
        f"export DESIGN_NAME = {module}",
        f"export DESIGN_NICKNAME = {nick}_{module}",
        f"export SYNTH_NETLIST_FILES = {root}/{module}/{module}.v",
        f"export SDC_FILE = {root}/{module}/constraint.sdc",
        f"export IO_CONSTRAINTS = {root}/{module}/io.tcl",
        f"export DIE_AREA = 0 0 {w:.3f} {h:.3f}",
        f"export CORE_AREA = {margin:.3f} {margin:.3f} {w - margin:.3f} {h - margin:.3f}",
        "export PDN_TCL = $(PLATFORM_DIR)/openRoad/pdn/BLOCK_grid_strategy.tcl",
        "export MAX_ROUTING_LAYER = M5",
        f"export PLACE_DENSITY = {place_density}",
        f"export MACRO_PLACE_HALO = {halo:g} {halo:g}",
        "export TNS_END_PERCENT = 100",
        "export GND_NETS_VOLTAGES =",
        "export PWR_NETS_VOLTAGES =",
    ]
    if macro_lefs:
        lines.append("export ADDITIONAL_LEFS = " + " ".join(macro_lefs))
        lines.append("export ADDITIONAL_LIBS = " + " ".join(macro_libs))
    lines += list(extra or [])
    return "\n".join(lines) + "\n"


def top_config(platform, nick, top, root, blocks, die_wh, margin, sdc, extra=None):
    w, h = die_wh
    lines = [
        "# generated by opentools/hier: top-level assembly on partition abstracts",
        f"export PLATFORM = {platform}",
        f"export CORNER = {CORNER}",
        f"export DESIGN_NAME = {top}",
        f"export DESIGN_NICKNAME = {nick}",
        f"export SYNTH_NETLIST_FILES = {root}/top.v",
        f"export SDC_FILE = {sdc}",
        f"export BLOCKS = {' '.join(blocks)}",
        f"export DIE_AREA = 0 0 {w:.3f} {h:.3f}",
        f"export CORE_AREA = {margin:.3f} {margin:.3f} {w - margin:.3f} {h - margin:.3f}",
        f"export MACRO_PLACEMENT_TCL = {root}/macro_place.tcl",
        "export PDN_TCL = $(PLATFORM_DIR)/openRoad/pdn/BLOCKS_grid_strategy.tcl",
        "export MIN_ROUTING_LAYER = M2",
        "export MAX_ROUTING_LAYER = M9",
        "export ROUTING_LAYER_ADJUSTMENT = 0.3",
        "export PLACE_DENSITY = 0.30",
        # partitions are fixed at their plan slots; a slot may touch the core edge, and ORFS
        # still runs rtl_macro_placer on fixed macros, which rejects any halo past the core
        # (measured: MPL-0006 on a core-wide slot with halo 1)
        "export MACRO_PLACE_HALO = 0 0",
        # keep std-cell rows in the top channels for top repeaters / clock buffers (platform
        # default 2 um cut every row of a 4.3-um channel: PDN-0190 "no rows"; 0.54 left
        # 0.54-um slivers in the 1.08-um core margin: PDN-0179 channel repair)
        "export MACRO_ROWS_HALO_X = 1.08",
        "export MACRO_ROWS_HALO_Y = 1.08",
        "export TNS_END_PERCENT = 100",
        "export GND_NETS_VOLTAGES =",
        "export PWR_NETS_VOLTAGES =",
    ]
    lines += list(extra or [])
    return "\n".join(lines) + "\n"


def macro_place_tcl(placements):
    """placements: [(inst, x, y)] lower-left in um."""
    out = ["# generated by opentools/hier: partitions at their plan regions"]
    for inst, x, y in placements:
        out.append(f"place_macro -macro_name {{{inst}}} -location {{{x:.3f} {y:.3f}}} -orientation R0")
    return "\n".join(out) + "\n"
