"""Top-down timing budgets for partition ports, and per-partition SDC.

Budget model (single clock, all partitions in one clock domain):
* Every partition's internal clock insertion is planned to a COMMON latency
  L (1 clock region == 1 partition; the clock tool balances to L).  All
  port delays are written with -network_latency_included, so the numbers
  below are absolute times after the ideal edge at the clock root.
* For a crossing net n driven in A and read in B, the full register-to-
  register path is split in proportion to the logic depth before and after
  n (levels from a flat levelization of the leaf graph):
      avail = T - setup_margin - wire(n)
      budget_A = avail * dA / (dA + dB)    (clamped to [min_frac, 1-min_frac])
      A: set_output_delay  T - L - budget_A       (required at A's port)
      B: set_input_delay   L + budget_A + wire(n) (arrival at B's port)
  Hold: input -min = L, output -min = -L (zero-logic neighbour, same L).
* Context (context=True): crossing inputs get set_driving_cell of the real driver leaf
  (default buffer when it is a macro or a chip input), crossing outputs get set_load =
  far-side input pin caps + top wire cap, so the block's ETM arcs see real slews/loads.
  The driver cell delay into the port load is counted on both sides (a few ps).
* Chip IO ports: input arrival L + io_budget, output delay io_budget
  (io_budget = the design SDC IO delay; approximate, see README).
These are first-pass budgets; re-budgeting from the measured abstracts is
listed in the README as open work.
"""
from __future__ import annotations

import sys


def levelize(nl, libcells):
    """Return (arr, req): comb levels before / after every net."""
    sys.setrecursionlimit(max(10000, sys.getrecursionlimit()))
    driver = {}
    sinks = {}
    seq = []
    for li, lf in enumerate(nl.leaves):
        c = libcells.get(lf.type)
        dirs = nl.pin_dirs.get(lf.type, {})
        is_seq = bool(c and (c.sequential or c.is_macro))
        seq.append(is_seq)
        for port, bits in lf.conns.items():
            d = dirs.get(port, "input")
            for b in bits:
                if not isinstance(b, int):
                    continue
                if d == "output":
                    driver[b] = li
                else:
                    sinks.setdefault(b, []).append(li)
    outs = {}
    ins = {}
    for li, lf in enumerate(nl.leaves):
        dirs = nl.pin_dirs.get(lf.type, {})
        for port, bits in lf.conns.items():
            tgt = outs if dirs.get(port, "input") == "output" else ins
            tgt.setdefault(li, []).extend(b for b in bits if isinstance(b, int))

    arr, req = {}, {}
    ON = object()

    def a(net):
        v = arr.get(net)
        if v is ON:
            return 0          # combinational loop: cut it
        if v is not None:
            return v
        li = driver.get(net)
        if li is None or seq[li]:
            arr[net] = 0
            return 0
        arr[net] = ON
        v = 1 + max((a(n) for n in ins.get(li, [])), default=0)
        arr[net] = v
        return v

    def r(net):
        v = req.get(net)
        if v is ON:
            return 0
        if v is not None:
            return v
        req[net] = ON
        best = 0
        for li in sinks.get(net, []):
            if seq[li]:
                continue
            best = max(best, 1 + max((r(n) for n in outs.get(li, [])), default=0))
        req[net] = best
        return best

    nets = set(driver) | set(sinks)
    for n in nets:
        a(n)
        r(n)
    return arr, req, driver


def make_budgets(crossings, arr, req, period_ps, latency_ps, wire_ps_of,
                 setup_margin_ps=0.0, min_frac=0.2):
    """crossings: {net: (src_region, [dst regions])} -> list of budget dicts."""
    out = []
    for net, (src, dsts) in sorted(crossings.items()):
        dA = max(arr.get(net, 0), 0) + 1        # +1: launch clk->q / port cell
        dB = max(req.get(net, 0), 0) + 1        # +1: capture setup
        w = wire_ps_of(net)
        avail = period_ps - setup_margin_ps - w
        frac = min(max(dA / (dA + dB), min_frac), 1 - min_frac)
        bA = avail * frac
        out.append({"net": net, "from_region": src, "to_regions": dsts, "period_ps": period_ps,
                    "src_budget_ps": round(bA, 1), "wire_ps": round(w, 1),
                    "dst_budget_ps": round(avail - bA, 1), "clock_latency_ps": latency_ps,
                    "levels": [dA, dB]})
    return out


def partition_sdc(rid, clock_port, period_ps, latency_ps, budgets_by_port, io_budget,
                  uncertainty_ps=0.0, context=False, default_drive=None):
    """budgets_by_port: {port: ("in"|"out", budget dict or None for chip IO)}."""
    T = period_ps
    L = latency_ps
    lines = [
        f"# generated by opentools/hier budget.py for partition {rid}",
        "# units: ps (ASAP7 liberty time unit); delays include network latency L",
        f"create_clock -name clk -period {T} [get_ports {{{clock_port}}}]",
    ]
    if uncertainty_ps:
        lines.append(f"set_clock_uncertainty {uncertainty_ps} [get_clocks clk]")
    for port, (d, b) in sorted(budgets_by_port.items()):
        if port == clock_port:
            continue
        p = f"[get_ports {{{port}}}]"
        if d == "in":
            v = (L + b["src_budget_ps"] + b["wire_ps"]) if b else (L + io_budget)
            lines.append(f"set_input_delay -max {v:.1f} -clock clk -network_latency_included "
                         f"-source_latency_included {p}")
            lines.append(f"set_input_delay -min {L:.1f} -clock clk -network_latency_included "
                         f"-source_latency_included {p}")
            if context:
                cell, pin = ((b["drive_cell"], b["drive_pin"]) if b and b.get("drive_cell")
                             else (default_drive or (None, None)))
                if cell:
                    lines.append(f"set_driving_cell -lib_cell {cell} -pin {pin} {p}")
        else:
            v = (T - L - b["src_budget_ps"]) if b else io_budget
            lines.append(f"set_output_delay -max {v:.1f} -clock clk -network_latency_included "
                         f"-source_latency_included {p}")
            lines.append(f"set_output_delay -min {-L:.1f} -clock clk -network_latency_included "
                         f"-source_latency_included {p}")
            if context and b and b.get("load_ff") is not None:
                lines.append(f"set_load -pin_load {b['load_ff']:.4f} {p}")
    return "\n".join(lines) + "\n"
