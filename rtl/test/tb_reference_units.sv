`timescale 1ns/1ps
module tb_reference_units;
    reg clk = 0;
    reg rst_n = 0;
    always #5 clk = ~clk;
    integer failures = 0;

    // Numeric dot: two experts, two lanes, signed INT_DV behavior.
    reg dot_valid = 0, dot_poison = 0;
    reg [1:0] dot_enable = 2'b11;
    reg [15:0] dot_acts = 16'b0;
    reg [31:0] dot_weights = 32'b0;
    wire dot_out_valid, dot_out_poison;
    wire signed [23:0] dot_sum;
    wire [3:0] dot_status;
    ot_numeric_dot #(.NUM_EXPERTS(2),.LANES(2),.ACT_W(8),.WEIGHT_W(8),.ACC_W(24)) dot (
        .clk(clk),.rst_n(rst_n),.in_valid(dot_valid),.in_poison(dot_poison),
        .expert_enable(dot_enable),.activations(dot_acts),.weights(dot_weights),
        .out_valid(dot_out_valid),.out_poison(dot_out_poison),.result(dot_sum),.status(dot_status));

    // Route record checker.  CRC is generated by the same canonical bit order
    // in this testbench's helper, independently of the RTL decoder.
    reg route_valid = 0;
    reg [223:0] route_record = 0;
    wire route_ready, ctx_valid, ctx_poison, route_bad_crc, route_bad_field;
    wire [15:0] ctx_mask, ctx_txn, ctx_dup;
    wire [7:0] ctx_epoch;
    wire [6:0] ctx_layer;
    wire [4:0] ctx_topk;
    reg ctx_ready = 0;
    ot_route_mask #(.NUM_EXPERTS(16),.TOP_K(6),.EXPERT_ID_W(10)) route (
        .clk(clk),.rst_n(rst_n),.route_valid(route_valid),.route_ready(route_ready),
        .route_record(route_record),.ctx_valid(ctx_valid),.ctx_ready(ctx_ready),
        .ctx_mask(ctx_mask),.ctx_transaction_id(ctx_txn),.ctx_epoch_id(ctx_epoch),
        .ctx_layer_id(ctx_layer),.ctx_top_k_count(ctx_topk),.ctx_poison(ctx_poison),
        .ctx_duplicate_slots(ctx_dup),.bad_crc_seen(route_bad_crc),.bad_field_seen(route_bad_field));

    function automatic [15:0] crc16_208;
        input [207:0] d;
        integer by, bi;
        reg [15:0] c; reg fb;
        begin
            c=16'hffff;
            for(by=0;by<26;by=by+1) for(bi=7;bi>=0;bi=bi-1) begin
                fb=c[15]^d[by*8+bi]; c={c[14:0],1'b0}; if(fb)c=c^16'h1021;
            end
            crc16_208=c;
        end
    endfunction

    task automatic send_route;
        input integer id0;
        input integer id1;
        input integer dup;
        reg [207:0] body;
        begin
            body=208'b0;
            body[0 +: 10]=id0;
            body[10 +: 10]=id1;
            body[160 +: 16]=16'h1234;
            body[176 +: 8]=8'h2;
            body[184 +: 7]=7'h3;
            body[191 +: 5]=dup ? 5'd2 : 5'd1;
            route_record={crc16_208(body),body};
            @(negedge clk); route_valid=1'b1;
            @(negedge clk); route_valid=1'b0;
        end
    endtask

    // Schedule controller smoke: shadow write, blocked commit, then boundary.
    reg sched_wr_valid=0, sched_commit=0, sched_quiescent=0, sched_boundary=0, sched_crc_ok=1;
    reg [7:0] sched_commit_id=8'h34;
    reg [1:0] sched_slot=0; reg [4:0] sched_data=0;
    wire sched_wr_ready,sched_ack,sched_err,sched_valid;
    wire [7:0] sched_epoch;
    wire [7:0] sched_active_id;
    wire [2:0] sched_src; wire sched_expect,sched_idle;
    wire [31:0] sched_crc;
    ot_schedule_controller #(.PORTS(8),.SLOTS(4)) sched (
        .clk(clk),.rst_n(rst_n),.shadow_wr_valid(sched_wr_valid),.shadow_wr_ready(sched_wr_ready),
        .shadow_wr_slot(sched_slot),.shadow_wr_data(sched_data),.commit_req(sched_commit),
        .quiescent(sched_quiescent),.epoch_boundary(sched_boundary),.manifest_crc_ok(sched_crc_ok),
        .commit_schedule_id(sched_commit_id),.commit_ack(sched_ack),.commit_error(sched_err),
        .schedule_valid(sched_valid),.epoch_id(sched_epoch),.active_schedule_id(sched_active_id),
        .active_slot(2'd0),.active_slot_valid(),.active_source_port(sched_src),.active_expect_valid(sched_expect),
        .active_idle(sched_idle),.active_schedule_crc(sched_crc),.commit_pending());

    initial begin
        repeat(3) @(negedge clk); rst_n=1;
        // dot products: a=[1,2], weights expert0=[3,4], expert1=[-1,2] => 1*3+2*4+1*-1+2*2=14
        @(negedge clk); dot_acts={8'sd2,8'sd1}; dot_weights={8'sd2,-8'sd1,8'sd4,8'sd3}; dot_valid=1;
        @(negedge clk); dot_valid=0;
        wait(dot_out_valid); #1;
        if(dot_sum!==24'sd14) begin $display("FAIL dot got %0d",dot_sum); failures=failures+1; end
        send_route(3,3,1);
        wait(ctx_valid); #1;
        if(ctx_mask!==16'b0000000000001000 || ctx_dup[1]!==1'b1 || ctx_poison!==1'b0) begin
            $display("FAIL route mask=%h dup=%h poison=%b",ctx_mask,ctx_dup,ctx_poison); failures=failures+1;
        end
        @(negedge clk); ctx_ready=1; @(negedge clk); ctx_ready=0;
        // Load every shadow slot; partial banks are never activatable.
        @(negedge clk); sched_slot=0; sched_data={1'b0,1'b1,3'd2}; sched_wr_valid=1;
        @(negedge clk); sched_slot=1; sched_data={1'b1,1'b0,3'd0};
        @(negedge clk); sched_slot=2; sched_data={1'b1,1'b0,3'd0};
        @(negedge clk); sched_slot=3; sched_data={1'b1,1'b0,3'd0};
        @(negedge clk); sched_wr_valid=0; sched_commit=1;
        @(negedge clk); sched_commit=0; sched_quiescent=1; sched_boundary=1;
        @(negedge clk); sched_quiescent=0; sched_boundary=0;
        if((!sched_ack && !sched_valid) || sched_active_id!==8'h34) begin
            $display("FAIL schedule commit/id"); failures=failures+1;
        end
        if(failures==0) begin
            $display("PASS: reference unit blocks");
            $finish;
        end else begin
            $fatal(1,"%0d failures",failures);
        end
    end
endmodule
