`timescale 1ns/1ps
// ---------------------------------------------------------------------------------------------------------------------
// TOKSIM-S81B/LEG (2026-10-19): stage bench of the ON-DIE leg of every S81 cross-die crossing on the MU release die
// (GEN mu4c 19bf4121e).  The xdie co-sim (tb_xdie_s81_2) starts and ends at the END SLICE ring stop (its inward port);
// the part of a crossing between the end slice and the slice that owns the data was priced (record.py ONDIE 134 = 2 x 67:
// farthest slice <-> end slice).  This bench simulates that part on the real release modules:
//   source slice ring stop (ot_s81sl_rstop, control-plane line inject ci_b/ci_dir)
//   -> per ring link, 4 lanes x [hop-0 clock gate + dsfd_dvrlyh_276_<dir> half-cycle relays + dsfd_dvland_276 strap k]
//   -> intermediate ring stops (line forward) -> ... -> end slice ring stop input pin   (OUTBOUND, flows 0 / 1)
//   end slice ring stop (beat from its outer port, as the lep delivers it) -> its inward output pin
//   -> links / stops -> owning slice ring stop delivery register dl_e / dl_w (consumer side)  (INBOUND, flows 2 / 3)
// Both tiers (S, N), all 8 columns, every link exactly as die.v (leg_chain_gen.sv, generated by gen_chain.py).
// Cycle definitions (edges; same convention as tb_xdie_s81_2's E = issue edge at the end stop's ri -> edge its ro loads):
//   OUT: edge the source stop samples ci_b -> edge the end stop samples ri (= the xdie vehicle's issue edge).
//   IN : edge the end stop loads its inward ro (= the xdie vehicle's landing edge) -> edge the owning stop loads dl.
// Checks: every beat arrives bit-exact (full 1,104 b; hops field as compiled), in order per flow, no ring-stop fault,
// no landing (epoch) fault.  One clock (the die's regions are landed: E = K + R0 - G with R0 = G as the xdie vehicle).
// stim.hex entries {cycle 32, flow 8, tier 8, src 4, dst 4, beat 1104, exp 1104}; flow 0 = W-bound to the W end (stop 0),
// 1 = E-bound to the E end (stop 7), 2 = E-bound in from stop 0's outer port, 3 = W-bound in from stop 7's outer port.
// Beat tag (bench-only, payload spare [40:33]): {tier, flow[1:0]}; [32:13] beat index.
// ---------------------------------------------------------------------------------------------------------------------
module tb_leg_s81 #(parameter integer NSMAX = 65536, parameter integer QD = 65536, parameter integer MAXCYC = 2000000);
    reg clk = 0; always #0.4167 clk = ~clk;
    reg rs = 0;
    integer cyc = 0;
    always @(posedge clk) cyc <= cyc + 1;
    reg  [2*8*1104-1:0] ci_b = 0; reg [2*8*3-1:0] ci_dir = 0; reg [2*1104-1:0] ext_w = 0, ext_e = 0;
    wire [2*8*1104-1:0] riw, rie, roe, row, dle, dlw; wire [15:0] dlev, dlwv, sf; wire [111:0] lf;
    toksim_leg_chain u_c (.clk(clk), .rs(rs), .ci_b(ci_b), .ci_dir(ci_dir), .ext_w(ext_w), .ext_e(ext_e),
        .ri_w_o(riw), .ri_e_o(rie), .ro_e_o(roe), .ro_w_o(row), .dl_ev_o(dlev), .dl_e_o(dle), .dl_wv_o(dlwv), .dl_w_o(dlw),
        .sfault(sf), .lfault(lf));

    reg [2263:0] stim [0:NSMAX-1];
    integer ns = 0, si = 0;
    // per (tier, flow) queue: q = tier * 4 + flow
    reg [1103:0] qexp [0:7][0:QD-1];
    integer qis [0:7][0:QD-1];
    integer qst [0:7][0:QD-1];
    integer qdst[0:7][0:QD-1];
    integer qsrc[0:7][0:QD-1];
    integer nin [0:7], nst [0:7], nout [0:7];
    integer bad = 0, extra = 0, nchk = 0, qq;
    reg go = 0;
    initial begin
        for (qq = 0; qq < 8; qq = qq + 1) begin nin[qq] = 0; nst[qq] = 0; nout[qq] = 0; end
        if (!$value$plusargs("NS=%d", ns)) ns = 0;
        $readmemh("stim.hex", stim);
        $display("LEG_CFG NS %0d", ns);
        repeat (8) @(posedge clk); rs = 1;
        go = 1;
    end
    // drive on the negedge before the issue edge: an entry at cycle c is sampled at edge c (cyc == c after it)
    integer t3, f3, s3, d3, q3; reg [2263:0] w;
    always @(negedge clk) if (go) begin
        ci_b = 0; ci_dir = 0; ext_w = 0; ext_e = 0;
        while (si < ns && stim[si][2263:2232] == cyc + 1) begin
            w = stim[si];
            f3 = w[2231:2224]; t3 = w[2223:2216]; s3 = w[2215:2212]; d3 = w[2211:2208]; q3 = t3 * 4 + f3;
            case (f3)
                0: begin if (ci_dir[(t3*8+s3)*3 +: 3] != 0) bad = bad + 1; ci_b[(t3*8+s3)*1104 +: 1104] = w[2207:1104]; ci_dir[(t3*8+s3)*3 +: 3] = 3'b010; end
                1: begin if (ci_dir[(t3*8+s3)*3 +: 3] != 0) bad = bad + 1; ci_b[(t3*8+s3)*1104 +: 1104] = w[2207:1104]; ci_dir[(t3*8+s3)*3 +: 3] = 3'b001; end
                2: begin if (ext_w[t3*1104]) bad = bad + 1; ext_w[t3*1104 +: 1104] = w[2207:1104]; end
                default: begin if (ext_e[t3*1104]) bad = bad + 1; ext_e[t3*1104 +: 1104] = w[2207:1104]; end
            endcase
            qexp[q3][nin[q3]] = w[1103:0]; qis[q3][nin[q3]] = cyc + 1; qdst[q3][nin[q3]] = d3; qsrc[q3][nin[q3]] = s3;
            nin[q3] = nin[q3] + 1;
            si = si + 1;
        end
    end
    // ---- checkpoints (posedge, pre-update pin values; p = cyc before this edge = label of the previous edge)
    function automatic [2:0] tagq(input [1103:0] b); begin tagq = {b[40], b[39:38]}; end endfunction
    integer t, q, k, p, n0, n7, nd;
    reg [1103:0] bt;
    always @(posedge clk) if (go) begin
        p = cyc;
        for (t = 0; t < 2; t = t + 1) begin
            n0 = t * 8; n7 = t * 8 + 7;
            // flow 0: W end stop samples ri_e
            bt = rie[n0*1104 +: 1104];
            if (bt[0] && tagq(bt) == {t[0], 2'd0}) begin
                q = t * 4; k = nout[q];
                if (k >= nin[q]) extra = extra + 1;
                else begin
                    if (bt !== qexp[q][k]) begin bad = bad + 1; if (bad < 8) $display("MISMATCH t %0d f 0 k %0d cyc %0d", t, k, p + 1); end
                    $display("LB %0d 0 %0d %0d %0d %0d %0d", t, qsrc[q][k], qdst[q][k], k, qis[q][k], p + 1);
                    nout[q] = k + 1; nchk = nchk + 1;
                end
            end
            // flow 1: E end stop samples ri_w
            bt = riw[n7*1104 +: 1104];
            if (bt[0] && tagq(bt) == {t[0], 2'd1}) begin
                q = t * 4 + 1; k = nout[q];
                if (k >= nin[q]) extra = extra + 1;
                else begin
                    if (bt !== qexp[q][k]) begin bad = bad + 1; if (bad < 8) $display("MISMATCH t %0d f 1 k %0d cyc %0d", t, k, p + 1); end
                    $display("LB %0d 1 %0d %0d %0d %0d %0d", t, qsrc[q][k], qdst[q][k], k, qis[q][k], p + 1);
                    nout[q] = k + 1; nchk = nchk + 1;
                end
            end
            // flow 2: start = W end stop loaded ro_e; end = owning stop loaded dl_e
            bt = roe[n0*1104 +: 1104];
            if (bt[0] && tagq(bt) == {t[0], 2'd2}) begin q = t * 4 + 2; if (nst[q] < nin[q]) begin qst[q][nst[q]] = p; nst[q] = nst[q] + 1; end else extra = extra + 1; end
            q = t * 4 + 2;
            if (nout[q] < nst[q]) begin
                k = nout[q]; nd = t * 8 + qdst[q][k]; bt = dle[nd*1104 +: 1104];
                if (dlev[nd] && tagq(bt) == {t[0], 2'd2}) begin
                    if (bt !== qexp[q][k]) begin bad = bad + 1; if (bad < 8) $display("MISMATCH t %0d f 2 k %0d cyc %0d", t, k, p); end
                    $display("LB %0d 2 %0d %0d %0d %0d %0d", t, qsrc[q][k], qdst[q][k], k, qst[q][k], p);
                    nout[q] = k + 1; nchk = nchk + 1;
                end
            end
            // flow 3: start = E end stop loaded ro_w; end = owning stop loaded dl_w
            bt = row[n7*1104 +: 1104];
            if (bt[0] && tagq(bt) == {t[0], 2'd3}) begin q = t * 4 + 3; if (nst[q] < nin[q]) begin qst[q][nst[q]] = p; nst[q] = nst[q] + 1; end else extra = extra + 1; end
            q = t * 4 + 3;
            if (nout[q] < nst[q]) begin
                k = nout[q]; nd = t * 8 + qdst[q][k]; bt = dlw[nd*1104 +: 1104];
                if (dlwv[nd] && tagq(bt) == {t[0], 2'd3}) begin
                    if (bt !== qexp[q][k]) begin bad = bad + 1; if (bad < 8) $display("MISMATCH t %0d f 3 k %0d cyc %0d", t, k, p); end
                    $display("LB %0d 3 %0d %0d %0d %0d %0d", t, qsrc[q][k], qdst[q][k], k, qst[q][k], p);
                    nout[q] = k + 1; nchk = nchk + 1;
                end
            end
        end
    end
    reg [15:0] sfs = 0; reg [111:0] lfs = 0;
    always @(posedge clk) begin sfs <= sfs | sf; lfs <= lfs | lf; end
    integer e2, ninall;
    initial begin
        wait (go);
        while (nchk < ns && cyc < MAXCYC) @(posedge clk);
        repeat (200) @(posedge clk);
        $display("LEG_STATS beats %0d checked %0d mismatches %0d extra %0d stop_faults %h land_faults %h last_cycle %0d",
                 ns, nchk, bad, extra, sfs, lfs, cyc);
        if (ns > 0 && nchk == ns && bad == 0 && extra == 0 && sfs == 0 && lfs == 0)
            $display("PASS leg_s81: %0d beats crossed the on-die leg bit-exact, in order, no ring-stop or landing fault", ns);
        else
            $display("FAIL leg_s81: checked %0d/%0d mismatches %0d extra %0d faults %h/%h", nchk, ns, bad, extra, sfs, lfs);
        $finish;
    end
endmodule
