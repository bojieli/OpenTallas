// by tools/qwen_rom_rt_vprm_w12.py).  qwen_rom_rt_w12_rm.cpp (unchanged) with a PLAN instead of a stage list:
//
//   ACCEPT <pending> <d1> .. <dg>       slot 0 and the drafts written into the die's accept unit at start
//   XBASES <b0>,<b1>,..                 per-position X bases (vm_map_p) dumped after every stage
//   STAGE <name> <layer|-1> <region> <pos> <np> <commit_before> <arm_accept> <xpreload|-> <dir0> .. <dir3>
//     layer >= 0: a decoder layer whose KV window lives in HBM region <region> (preloaded once from
//     --kv-dir L<layer>_die<d>.bin or --kv-src REGION_FILE); -1: no KV (the verify head).
//     commit_before n > 0: before the stage the host commits n block positions of the previous stage
//     (layer-parallel jobs; the serial flow commits from the accept unit itself, ACCEPT_COMMIT).
//     xpreload: a fresh vector memory (zero + the file's @-addressed words) before the stage.
// After each stage: every die's X of each position (<stage>_p<j>_die<d>_x.hex), the block's K/V rows as
// written back to HBM (<stage>_die<d>_kvblk.hex), MEMSTAT, VERIFY_TOKENS; ACCEPT when the accept unit fires.
// --dump-hbm writes the region after the last stage (<stage>_die<d>_hbm.bin).
//
// Parent description (qwen_rom_rt_w12_rm.cpp):
// REAL_MEM runtime host of the Qwen3-8B O4 ROM TP4 dies at the W12 design point (default-off;
// built only by tools/qwen_rom_rt_token_w12_rm.py --real-mem).  Derived from qwen_rom_rt_w12.cpp
// (pinned, unchanged), with every on-demand memory service removed from the host:
//
//   Vdie   ot_qwen_rom_rt_die_w12_rm: sequencer + core + RTL program/descriptor/constant ROMs,
//          vector memory, scale-ROM macro banks, the KV fill/write service and the HBM model
//   Vcoll  ot_rom_oneshot_allreduce (unchanged)
//   Vtile  ot_qwen_rom_tile_w12, the HARDENED element: tile logic (KV_LOCAL = 1) + its
//          2 x CODE_BANKS ot_rom_4096x266_m8 code-ROM macros + 2 ot_sram_1r1w_128x256 KV slices
//
// The host only: (1) PRELOADS memory contents -- between stages the ROM via masks (code, scale),
// program/descriptors/constants, and once at start the HBM model's per-layer KV history and the
// X row in the vector memory; (2) wires the tile fabric exactly as qwen_rom_rt_w12.cpp does, plus
// the die's KV-slice write ports to the tiles (pure wires; the fill network registers are RTL);
// (3) wires the collective.  It never answers a read.
//
// Tile clock: the engine clock gate (ME_IDLE_GATE) gates the tile models as before; a tile is also
