[[noreturn]] static void fatal(const char* m, long a = -1, long b = -1) {
    printf("FATAL %s %ld %ld\n", m, a, b); fflush(stdout); exit(2);
}
template <class A> static inline uint64_t getb(const A& w, size_t pos, int n) {
    if constexpr (std::is_integral_v<A>) {
        return (uint64_t(w) >> pos) & (n >= 64 ? ~0ull : ((1ull << n) - 1));
    } else {
        uint64_t r = 0;
        for (int k = 0; k < n; ) {
            size_t word = (pos + k) / 32, off = (pos + k) % 32;
            int take = std::min(n - k, int(32 - off));
            r |= uint64_t((w[word] >> off) & ((take == 32) ? 0xffffffffu : ((1u << take) - 1))) << k;
            k += take;
        }
        return r;
    }
}
template <class A> static inline void setb(A& w, size_t pos, int n, uint64_t v) {
    if constexpr (std::is_integral_v<A>) {
        uint64_t m = (n >= 64 ? ~0ull : ((1ull << n) - 1)) << pos;
        w = A((uint64_t(w) & ~m) | ((v << pos) & m));
    } else {
        for (int k = 0; k < n; ) {
            size_t word = (pos + k) / 32, off = (pos + k) % 32;
            int take = std::min(n - k, int(32 - off));
            uint32_t mask = (take == 32) ? 0xffffffffu : (((1u << take) - 1) << off);
            w[word] = (w[word] & ~mask) | (uint32_t(v >> k << off) & mask);
            k += take;
        }
    }
}
static std::vector<uint64_t> as64(const std::vector<uint32_t>& w) {
    std::vector<uint64_t> r(w.size() / 2);
    for (size_t i = 0; i < r.size(); i++) r[i] = w[2 * i] | (uint64_t(w[2 * i + 1]) << 32);
    return r;
}
// ---- via-mask writers: bit b of word a of a macro (MUX m) is arr[a / m][b * m + a % m] ---------
static inline void via_set(uint32_t* arr, int row_words, int mux, uint32_t a, int b, bool v) {
    size_t row = a / mux, col = size_t(b) * mux + a % mux;
    uint32_t& w = arr[row * row_words + col / 32];
    if (v) w |= 1u << (col % 32); else w &= ~(1u << (col % 32));
}
// ---- FP32 -> E4M3 (exact; the KV service's f32_e4m3) ---------------------------------------
static int f32_e4m3(uint32_t b) {
    uint32_t s = b >> 31, e = (b >> 23) & 255, m = b & 0x7fffff;
    if (e == 0 && m == 0) return s << 7;
    if (e >= 121 && e <= 135 && (m & 0xfffff) == 0) return (s << 7) | ((e - 120) << 3) | (m >> 20);
    if (e == 120 && (m & 0x1fffff) == 0) return (s << 7) | 4 | (m >> 21);
    if (e == 119 && (m & 0x3fffff) == 0) return (s << 7) | 2 | (m >> 22);
    if (e == 118 && m == 0) return (s << 7) | 1;
    return -1;
}

struct DieMem {
    std::vector<uint32_t> prog, codes, scales;
    std::vector<uint64_t> desc, crom;
    size_t code_words = 0, scale_words = 0, crom_words = 0;
};
static void load_images(DieMem& m, const std::string& p) {
    m.prog = QwenHex::load(p + "/program.hex", 32);
    m.desc = as64(QwenHex::load(p + "/segments.hex", 2));
    m.codes = QwenHex::load(p + "/matrix_int8.hex", size_t(G) * WPG);
    m.code_words = m.codes.size() / (size_t(G) * WPG);
    m.scales = QwenHex::load(p + "/matrix_scale_bf16.hex", 8);
    m.scale_words = m.scales.size() / 8;
    m.crom = as64(QwenHex::load(p + "/crom.hex", 2));
    m.crom_words = m.crom.size();
    if (m.prog.size() > size_t(NPROG) * 32 || m.desc.size() > size_t(NDESC)) fatal("program/descriptor image exceeds the ROM");
    m.prog.resize(size_t(NPROG) * 32, 0); m.desc.resize(NDESC, 0);
    if (m.code_words > size_t(CB) * 4096) fatal("code image exceeds the tile ROM banks", long(m.code_words));
    if (m.scale_words > size_t(RM_SCALE_BANKS) * 4096) fatal("scale image exceeds the scale ROM banks", long(m.scale_words));
    if (m.crom_words > RM_CROM_WORDS) fatal("constant image exceeds the constant ROM", long(m.crom_words));
}
struct Stage { std::string name, dir[D], xpre; int layer = -1, region = 0, pos = 0, np = 1, commit = 0, arm = 0; };

struct Fabric {
    Vdie& die;
    RtPool& pool;
    std::vector<std::unique_ptr<Vtile>> t;
    std::vector<int> hl, hp;
    std::vector<int> host;
    struct Line { VlWide<16> a, b; uint8_t va; };
    std::vector<std::vector<Line>> ext;
    std::vector<uint8_t> kv_ce_prev;
    Fabric(Vdie& d, RtPool& p, int die_id) : die(d), pool(p) {
        host.assign((TCUT + 1) * NT, -1);
        for (int i = 0; i < NT; i++) {
            t.emplace_back(new Vtile(pool.ctx(i % pool.size()), ("d" + std::to_string(die_id) + "t" + std::to_string(i)).c_str()));
            t.back()->tile_id = i;
            t.back()->kvw_ce = 0;
            int L = 0, P = 0;
            for (int k = 1; k <= TCUT - LT && !L; k++)
                if ((i % (1 << k)) == (1 << (k - 1)) - 1 && (i >> k) < (G >> (LT + k))) { L = LT + k; P = i >> k; }
            hl.push_back(L); hp.push_back(P);
            if (L) host[L * NT + P] = i;
            ext.emplace_back(NWS_EXT);
            for (auto& l : ext.back()) { for (auto& x : l.a.m_storage) x = 0; for (auto& x : l.b.m_storage) x = 0; l.va = 0; }
        }
        kv_ce_prev.assign(NT, 0);
    }
    const VlWide<16>& word(int lv, int p) const { return lv == LT ? t[p]->t_out : t[host[lv * NT + p]]->n_y; }
    uint8_t valid(int lv, int p) const { return lv == LT ? t[p]->t_vout : t[host[lv * NT + p]]->n_vy; }
    void set_clk(uint8_t c) { for (auto& x : t) x->clk = c; }
    void eval() { pool.run(t.size(), [&](size_t i) { t[i]->eval(); }); }
    void edge() {
        bool lo = false;
        for (auto& x : t) if (x->clk) { lo = true; break; }
        if (lo) { set_clk(0); eval(); }
        if (NWS_EXT > 0)
            pool.run(t.size(), [&](size_t i) {
                if (!hl[i]) return;
                auto& e = ext[i];
                for (int s = NWS_EXT - 1; s > 0; s--) e[s] = e[s - 1];
                e[0].a = word(hl[i] - 1, 2 * hp[i]); e[0].b = word(hl[i] - 1, 2 * hp[i] + 1);
                e[0].va = valid(hl[i] - 1, 2 * hp[i]);
            });
        set_clk(1);
        eval();
    }
    // any KV slice write port active now (the die's registered outputs) or in a tile's input register
    bool kv_active() const {
        for (int w = 0; w < (NT + 31) / 32; w++) if (die.kvw_ce[w]) return true;
        for (int i = 0; i < NT; i++) if (kv_ce_prev[i]) return true;
        return false;
    }
    bool propagate() {
        std::atomic<bool> any{false};
        const uint8_t rst = die.rt_rst_n, go = die.tgo;
        pool.run(t.size(), [&](size_t i) {
            Vtile& x = *t[i];
            bool ch = false;
            ch |= rt_set(x.rst_n, rst); ch |= rt_set(x.ib_go, go); ch |= rt_set(x.ib, die.tb);
            VlWide<4> xl;
            for (int k = 0; k < 4; k++) xl[k] = die.xl_d[(i % NXL) * 4 + k];
            ch |= rt_set(x.xl, xl);
            if (hl[i]) {
                if (NWS_EXT > 0) {
                    auto& e = ext[i][NWS_EXT - 1];
                    ch |= rt_set(x.n_a, e.a); ch |= rt_set(x.n_b, e.b); ch |= rt_set(x.n_va, e.va);
                } else {
                    ch |= rt_set(x.n_a, word(hl[i] - 1, 2 * hp[i])); ch |= rt_set(x.n_b, word(hl[i] - 1, 2 * hp[i] + 1));
                    ch |= rt_set(x.n_va, valid(hl[i] - 1, 2 * hp[i]));
                }
            }
            // KV slice write port (wires from the die's registered fill-network outputs)
            uint8_t ce = (die.kvw_ce[i / 32] >> (i % 32)) & 1;
            ch |= rt_set(x.kvw_ce, ce);
            if (ce) {
                ch |= rt_set(x.kvw_addr, uint8_t(getb(die.kvw_addr, size_t(i) * 7, 7)));
                for (int k = 0; k < 16; k++) { ch |= rt_set(x.kvw_data[k], die.kvw_data[i * 16 + k]); ch |= rt_set(x.kvw_mask[k], die.kvw_mask[i * 16 + k]); }
            }
            if (ch) any.store(true, std::memory_order_relaxed);
        });
        bool c2 = false;
        std::remove_reference_t<decltype(die.t_lvl)> tl;
        for (int p = 0; p < NPT; p++) { const auto& w = word(TCUT, p); for (int k = 0; k < 16; k++) tl[p * 16 + k] = w[k]; }
        c2 |= rt_set(die.t_lvl, tl);
        uint8_t f = 0;
        for (auto& x : t) f |= x->fault;
        c2 |= rt_set(die.fab_fault, f);
        return any || c2;
    }
};

// ---- preloads ------------------------------------------------------------------------------------
static void preload_die_roms(Vdie& v, const DieMem& m, RtPool& pool) {
    auto* r = v.rootp;
    for (int a = 0; a < NPROG; a++) for (int w = 0; w < 32; w++) rm_prog(r)[a][w] = m.prog[size_t(a) * 32 + w];
    for (int a = 0; a < NDESC; a++) { rm_desc(r)[a] = m.desc[a]; }
    for (size_t a = 0; a < RM_CROM_WORDS; a++) rm_crom(r)[a] = a < m.crom_words ? m.crom[a] : 0;
    rm_crom_words(r) = uint32_t(m.crom_words);
    // scale ROM: every result port's bank holds the stage's scale image (word w: macro w >> 12, row w & 4095)
    pool.run(NPORT, [&](size_t g) {
        for (int b = 0; b < RM_SCALE_BANKS; b++) {
            uint32_t* arr = rm_scale_arr(r, int(g), b);
            std::memset(arr, 0, sizeof(uint32_t) * RM_ROM_ROWS * RM_ROM_ROWW);
            for (uint32_t a = 0; a < 4096; a++) {
                size_t w = size_t(b) * 4096 + a;
                if (w >= m.scale_words) break;
                for (int bit = 0; bit < 256; bit++)
                    if ((m.scales[w * 8 + bit / 32] >> (bit % 32)) & 1) via_set(arr, RM_ROM_ROWW, 8, a, bit, true);
            }
        }
    });
}
static void preload_tile_roms(Fabric& f, const DieMem& m) {
    f.pool.run(NT, [&](size_t i) {
        Vtile& x = *f.t[i];
        for (int p = 0; p < 2; p++)
            for (int b = 0; b < CB; b++) {
                uint32_t* arr = rm_tile_rom_arr(x.rootp, p, b);
                std::memset(arr, 0, sizeof(uint32_t) * RM_ROM_ROWS * RM_ROM_ROWW);
                for (uint32_t a = 0; a < 4096; a++) {
                    size_t w = size_t(b) * 4096 + a;
                    if (w >= m.code_words) break;
                    for (int k = 0; k < 8; k++) {
                        uint32_t v = m.codes[(w * G + i * TG + 2 * p) * WPG + k];
                        for (int bit = 0; v; bit++, v >>= 1) if (v & 1) via_set(arr, RM_ROM_ROWW, 8, a, 32 * k + bit, true);
                    }
                }
            }
    });
}
// KV history (before P) of one layer, E4M3 codes: element e -> word e >> 4, lane e & 15
static std::vector<uint8_t> load_kv_codes(const std::string& path) {
    FILE* fp = fopen(path.c_str(), "rb");
    if (!fp) fatal(("KV history " + path).c_str());
    std::vector<uint32_t> v(KV_ELEMS);
    if (fread(v.data(), 4, KV_ELEMS, fp) != KV_ELEMS) fatal("KV history size");
    fclose(fp);
    std::vector<uint8_t> c(KV_ELEMS);
    for (size_t e = 0; e < KV_ELEMS; e++) {
        int k = f32_e4m3(v[e]);
        if (k < 0) fatal("KV history value is not E4M3", long(e), long(v[e]));
        c[e] = uint8_t(k);
    }
    return c;
}
static void preload_hbm(Vdie& v, int region, const std::vector<uint8_t>& codes) {
    auto* r = v.rootp;
    for (size_t s = 0; s < KV_ELEMS / 32; s++)
        for (int k = 0; k < 8; k++) {
            uint32_t w = 0;
            for (int j = 0; j < 4; j++) w |= uint32_t(codes[s * 32 + 4 * k + j]) << (8 * j);
            rm_hbm_mem(r)[size_t(region) * 131072 + s][k] = w;
        }
}
// KV_IDEAL: the slices hold exactly what the real fill writes (K tiles 0..P/16 with the open tile's
// lanes < P mod 16, V positions < P), via the tile's KV_LOCAL map
static void preload_slices_ideal(Fabric& f, const std::vector<uint8_t>& codes, int P) {
    const int T = P >> 4, PL = P & 15;
    auto put = [&](int tile, int local, int byte, uint8_t c) {
        Vtile& x = *f.t[tile];
        int p = byte / 32, bit0 = (byte % 32) * 8;
        uint32_t* arr = rm_tile_kv_arr(x.rootp, p);
        for (int b = 0; b < 8; b++) via_set(arr, RM_KV_ROWW, 1, local, bit0 + b, (c >> b) & 1);
    };
    for (int h = 0; h < 2; h++)
        for (int t = 0; t <= T; t++)
            for (int d = 0; d < 128; d++) {
                int g = (t % 48) * 128 + d, tile = g / 4, gi = g % 4, lk = (t / 48) * 2 + h;
                for (int l = 0; l < 16; l++) {
                    if (t == T && l >= PL) continue;
                    size_t e = ((size_t(h) * 512 + t) * 128 + d) * 16 + l;
                    put(tile, lk, gi * 16 + l, codes[e]);
                }
            }
    for (int h = 0; h < 2; h++)
        for (int p = 0; p < P; p++)
            for (int q = 0; q < 8; q++) {
                int g = q * 512 + (p % 512), tile = g / 4, gi = g % 4, lv = 22 + (p / 512) * 2 + h;
                for (int l = 0; l < 16; l++) {
                    size_t e = 2097152 + (size_t(h) * 8192 + p) * 128 + q * 16 + l;
                    put(tile, lv, gi * 16 + l, codes[e]);
                }
            }
}

// HBM region dump/load (E4M3 codes as the model holds them: 131,072 sectors x 32 bytes)
static void dump_region(Vdie& v, int region, const std::string& path) {
    FILE* fp = fopen(path.c_str(), "wb");
    if (!fp) fatal(("dump " + path).c_str());
    auto* r = v.rootp;
    for (size_t s = 0; s < 131072; s++) fwrite(&rm_hbm_mem(r)[size_t(region) * 131072 + s][0], 4, 8, fp);
    fclose(fp);
}
static std::vector<uint8_t> load_region_codes(const std::string& path) {
    FILE* fp = fopen(path.c_str(), "rb");
    if (!fp) fatal(("region " + path).c_str());
    std::vector<uint8_t> c(KV_ELEMS);
    if (fread(c.data(), 1, KV_ELEMS, fp) != KV_ELEMS) fatal("region size");
    fclose(fp);
    return c;
}
static void load_vm(Vdie& v, const std::string& path) {
    auto* r = v.rootp;
    for (size_t i = 0; i < VM_ELEMS; i++) rm_vm(r)[i] = 0;
    auto x = QwenHex::load(path, 1);
    if (x.size() > VM_ELEMS) fatal("X preload beyond the vector memory", long(x.size()));
    for (size_t i = 0; i < x.size(); i++) rm_vm(r)[i] = x[i];
}

int main(int argc, char** argv) {
    if (argc < 4 || strcmp(argv[1], "--plan")) {
        fprintf(stderr, "usage: %s --plan FILE OUTDIR [--kv-dir DIR] [--kv-src REGION_PREFIX] [--dump-hbm 1] [--max-cycles N]\n", argv[0]);
        return 2;
    }
    const std::string dir = argv[3];
    long max_cycles = 400000000L;
    std::string kv_dir, kv_src;
    bool dump_hbm = false;
    for (int i = 4; i + 1 < argc; i += 2) {
        std::string k = argv[i];
        if (k == "--kv-dir") kv_dir = argv[i + 1];
        else if (k == "--kv-src") kv_src = argv[i + 1];
        else if (k == "--max-cycles") max_cycles = atol(argv[i + 1]);
        else if (k == "--dump-hbm") dump_hbm = atoi(argv[i + 1]) != 0;
        else if (k.rfind("+", 0) == 0) { i--; continue; }
        else fatal("unknown option");
    }
    int threads = 16;
    if (const char* s = getenv("RT_THREADS")) threads = atoi(s);
    RtPool pool(threads);
    for (int i = 0; i < pool.size(); i++) pool.ctx(i)->commandArgs(argc, argv);
    auto t0 = std::chrono::steady_clock::now();
    std::vector<Stage> stages;
    std::vector<size_t> xbases;
    std::vector<uint32_t> acc_toks;
    {
        FILE* fp = fopen(argv[2], "r");
        if (!fp) fatal("plan file");
        char line[8192];
        while (fgets(line, sizeof line, fp)) {
            std::vector<std::string> t;
            for (char* q = strtok(line, " \t\r\n"); q; q = strtok(nullptr, " \t\r\n")) t.push_back(q);
            if (t.empty()) continue;
            if (t[0] == "ACCEPT") { for (size_t i = 1; i < t.size(); i++) acc_toks.push_back(uint32_t(std::stoul(t[i]))); }
            else if (t[0] == "XBASES") {
                std::string s = t.at(1); size_t p0 = 0;
                while (p0 < s.size()) { size_t q = s.find(',', p0); if (q == std::string::npos) q = s.size(); xbases.push_back(std::stoul(s.substr(p0, q - p0))); p0 = q + 1; }
            } else if (t[0] == "STAGE") {
                if (t.size() != 9 + D) fatal("STAGE line fields", long(t.size()));
                Stage st; st.name = t[1]; st.layer = atoi(t[2].c_str()); st.region = atoi(t[3].c_str());
                st.pos = atoi(t[4].c_str()); st.np = atoi(t[5].c_str()); st.commit = atoi(t[6].c_str()); st.arm = atoi(t[7].c_str());
                st.xpre = t[8] == "-" ? "" : t[8];
                for (int d = 0; d < D; d++) st.dir[d] = t[9 + d];
                if (st.layer >= 0 && st.region >= RM_HBM_LAYERS) fatal("region beyond the HBM model", st.region);
                if (st.np < 1 || st.np > 8) fatal("np");
                stages.push_back(st);
            } else fatal(("plan keyword " + t[0]).c_str());
        }
        fclose(fp);
        if (stages.empty()) fatal("no stages");
        if (stages[0].xpre.empty()) fatal("the first stage needs an X preload");
    }
    DieMem mem[D];
    for (int d = 0; d < D; d++) load_images(mem[d], stages[0].dir[d]);
    printf("images loaded in %.1f s\n", std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count());
    VerilatedContext dctx[D], cctx;
    for (int d = 0; d < D; d++) dctx[d].commandArgs(argc, argv);
    cctx.commandArgs(argc, argv);
    std::unique_ptr<Vdie> die[D];
    std::unique_ptr<Fabric> fab[D];
    for (int d = 0; d < D; d++) {
        dctx[d].randReset(0);
        die[d].reset(new Vdie(&dctx[d], ("die" + std::to_string(d)).c_str()));
        die[d]->tp_token = 0; die[d]->tp_pos = stages[0].pos; die[d]->h_start = 0;
        die[d]->rm_layer = uint8_t(stages[0].layer < 0 ? 255 : stages[0].region);
        die[d]->rm_npos = stages[0].np; die[d]->rm_kv_ideal = 0;
        die[d]->h_commit_v = 0; die[d]->h_commit_n = 0;
        die[d]->acc_start_v = 0; die[d]->acc_tokx_v = 0; die[d]->acc_arm = 0;
        die[d]->acc_commit_en = getenv("RT_ACC_COMMIT") && atoi(getenv("RT_ACC_COMMIT"));
        fab[d].reset(new Fabric(*die[d], pool, d));
    }
    cctx.randReset(0);
    Vcoll coll(&cctx, "coll");
    // The ASAP7 macro models clear their arrays in an initial block, which Verilator runs at a model's first
    // eval: evaluate every model once BEFORE any preload (the parent host's first stage is the embedding
    // stage, which reads none of these ROMs, so its stage-0 preload being cleared went unnoticed there).
    for (int d = 0; d < D; d++) { die[d]->clk = 0; die[d]->eval(); fab[d]->set_clk(0); fab[d]->eval(); }
    coll.clk = 0; coll.eval();
    // ---- preloads: X of stage 0, ROMs of stage 0, HBM KV history of every region (first stage using it) ----
    for (int d = 0; d < D; d++) {
        load_vm(*die[d], stages[0].xpre);
        preload_die_roms(*die[d], mem[d], pool);
        preload_tile_roms(*fab[d], mem[d]);
    }
    {
        std::vector<int> seen;
        for (auto& st : stages) {
            if (st.layer < 0 || std::find(seen.begin(), seen.end(), st.region) != seen.end()) continue;
            seen.push_back(st.region);
            for (int d = 0; d < D; d++) {
                std::vector<uint8_t> codes;
                if (!kv_src.empty()) codes = load_region_codes(kv_src + "_die" + std::to_string(d) + ".bin");
                else if (!kv_dir.empty()) codes = load_kv_codes(kv_dir + "/L" + std::to_string(st.layer) + "_die" + std::to_string(d) + ".bin");
                else codes.assign(KV_ELEMS, 0);
                preload_hbm(*die[d], st.region, codes);
            }
        }
    }
    printf("models constructed and preloaded in %.1f s (tiles/die=%d, stages=%zu, pos0=%d np0=%d)\n",
           std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count(), NT, stages.size(), stages[0].pos, stages[0].np);
    fflush(stdout);

    auto wire_coll = [&]() -> bool {
        bool ch = false;
        uint8_t iv = 0, il = 0, im = 0;
        std::remove_reference_t<decltype(coll.in_data)> idat;
        std::remove_reference_t<decltype(coll.in_tag)> itag{};
        for (int d = 0; d < D; d++) {
            iv |= die[d]->c_valid << d; il |= die[d]->c_last << d; im |= die[d]->c_mode << d;
            for (int w = 0; w < 16; w++) idat[d * 16 + w] = die[d]->c_data[w];
            setb(itag, 32 * d, 32, die[d]->c_tag);
        }
        ch |= rt_set(coll.rst_n, die[0]->rt_rst_n);
        ch |= rt_set(coll.in_valid, iv); ch |= rt_set(coll.in_last, il); ch |= rt_set(coll.in_mode, im);
        ch |= rt_set(coll.in_data, idat); ch |= rt_set(coll.in_tag, itag);
        for (int d = 0; d < D; d++) {
            Vdie& t = *die[d];
            ch |= rt_set(t.c_ready, uint8_t((coll.in_ready >> d) & 1));
            ch |= rt_set(t.r_valid, uint8_t((coll.out_valid >> d) & 1));
            ch |= rt_set(t.r_last, uint8_t((coll.out_last >> d) & 1));
            ch |= rt_set(t.r_rank, uint8_t(getb(coll.out_rank, d * RB, RB)));
            ch |= rt_set(t.r_err, uint8_t((coll.out_err >> d) & 1));
            std::remove_reference_t<decltype(t.r_data)> rd;
            for (int w = 0; w < 16; w++) rd[w] = coll.out_data[d * 16 + w];
            ch |= rt_set(t.r_data, rd);
        }
        return ch;
    };
    uint8_t tile_en[D];
    for (int d = 0; d < D; d++) tile_en[d] = 1;
    int max_settle = 0;
    long passes = 0;
    auto settle = [&](bool fabric_live[D]) {
        for (int n = 0;; n++) {
            if (n > 64) fatal("settle did not converge");
            passes++;
            for (int d = 0; d < D; d++) die[d]->eval();
            coll.eval();
            bool ch = wire_coll();
            for (int d = 0; d < D; d++)
                if (fabric_live[d] && fab[d]->propagate()) { ch = true; fab[d]->eval(); }
            if (!ch) { max_settle = std::max(max_settle, n + 1); return; }
        }
    };
    long me_busy[D] = {}, tile_edges[D] = {}, edges = 0;
    long progress_every = getenv("RT_PROGRESS") ? atol(getenv("RT_PROGRESS")) : 4096;
    bool stage_done = false, next_stage = false, done_armed = true;
    size_t cur = 0; long stage_start = 7, busy0[D] = {};
    uint32_t prev_stat[D][12] = {};
    auto tstart = std::chrono::steady_clock::now();
    bool live_all[D];
    for (int d = 0; d < D; d++) live_all[d] = true;
    int acc_feed = acc_toks.empty() ? -1 : 0;   // host writes of the accept unit's slot 0 and drafts, one a cycle
    bool acc_seen[D] = {};
    int commit_pending = 0;
    bool arm0 = false;
    for (long tick = 0;; tick++) {
        for (int d = 0; d < D; d++) die[d]->clk = 0;
        coll.clk = 0;
        settle(live_all);
        {
            uint32_t cyc = die[0]->cyc;
            // RT_OPTRACE=1 (default off): die 0's instruction fetch address on every change (op-level profile)
            static const bool optrace = getenv("RT_OPTRACE") && atoi(getenv("RT_OPTRACE"));
            static int prev_pa = -1;
            if (optrace && int(die[0]->dbg_prog_a) != prev_pa) {
                prev_pa = int(die[0]->dbg_prog_a);
                printf("OPTRACE cyc=%u prog_a=%d me=%d\n", cyc, prev_pa, int(die[0]->me_clk_en));
            }
            uint8_t all_done = 1;
            for (int d = 0; d < D; d++) all_done &= die[d]->s_done;
            if (!done_armed) {
                bool any_done = false;
                for (int d = 0; d < D; d++) any_done |= die[d]->s_done;
                if (!any_done) done_armed = true;
                all_done = 0;
            }
            uint8_t mf = 0;
            for (int d = 0; d < D; d++) mf |= die[d]->mem_fault << d;
            if (mf) {
                printf("MEMORY FAULT stage=%s cyc=%u dies=%x kv_code=%04x/%04x/%04x/%04x\n", stages[cur].name.c_str(), cyc, mf,
                       die[0]->kv_fault_code, die[D > 1 ? 1 : 0]->kv_fault_code, die[D > 2 ? 2 : 0]->kv_fault_code, die[D - 1]->kv_fault_code);
                return 1;
            }
            for (int d = 0; d < D; d++)
                if (die[d]->acc_done && !acc_seen[d]) {
                    acc_seen[d] = true;
                    printf("ACCEPT die=%d a=%u n_emit=%u bonus=%u cyc=%u kv_committed_len=%u\n", d, unsigned(die[d]->acc_a),
                           unsigned(die[d]->acc_n_emit), unsigned(die[d]->acc_bonus), cyc, unsigned(die[d]->kv_committed_len));
                }
            if (cyc > 8 && all_done && !stage_done) {
                stage_done = true;
                uint8_t sf = 0, cf = 0;
                for (int d = 0; d < D; d++) { sf |= die[d]->s_fault << d; cf |= die[d]->core_fault << d; }
                uint8_t lf = coll.fault;
                double sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - tstart).count();
                const Stage& S = stages[cur];
                printf("STAGE %s done cycles=%ld start_cyc=%ld end_cyc=%u me_busy=%ld/%ld pos=%d np=%d layer=%d "
                       "seq_fault=%d core_fault=%d coll_fault=%d wall=%.0fs\n", S.name.c_str(), long(cyc) - stage_start,
                       stage_start, cyc, me_busy[0] - busy0[0], me_busy[D - 1] - busy0[D - 1], S.pos, S.np, S.layer, sf, cf, lf, sec);
                for (int d = 0; d < D; d++) {
                    Vdie& v = *die[d];
                    uint32_t s[12] = {v.st_fill_cycles, v.st_fill_sectors, v.st_wr_sectors, v.st_rsp_stall, v.st_kvok_low_desc,
                                      v.st_drain_low, v.st_wr_lat_max, v.st_stall_kv, v.st_stall_drain, v.st_stall_bridge,
                                      v.st_stall_retire, v.st_stall_mem};
                    printf("MEMSTAT %s die%d fill_cycles=%u fill_sectors=%u wr_sectors=%u rsp_tile_stall=%u kvok_low_with_desc=%u "
                           "drain_low=%u wr_lat_max=%u stall_kv=%u stall_drain=%u stall_bridge=%u stall_retire=%u stall_mem=%u tile_edges=%ld\n",
                           S.name.c_str(), d, s[0], s[1] - prev_stat[d][1], s[2] - prev_stat[d][2], s[3] - prev_stat[d][3],
                           s[4] - prev_stat[d][4], s[5] - prev_stat[d][5], s[6], s[7] - prev_stat[d][7], s[8] - prev_stat[d][8],
                           s[9] - prev_stat[d][9], s[10] - prev_stat[d][10], s[11] - prev_stat[d][11], tile_edges[d]);
                    for (int k = 0; k < 12; k++) prev_stat[d][k] = s[k];
                    std::vector<size_t> xb = xbases.empty() ? std::vector<size_t>{size_t(X_BASE)} : xbases;
                    for (size_t j = 0; j < xb.size(); j++) {
                        FILE* fp = fopen((dir + "/" + S.name + "_p" + std::to_string(j) + "_die" + char('0' + d) + "_x.hex").c_str(), "w");
                        for (int i = 0; i < H; i++) fprintf(fp, "%08x\n", rm_vm(v.rootp)[xb[j] + i]);
                        fclose(fp);
                    }
                    if (S.layer >= 0) {
                        // the block's K (lane p of its tile) and V (row p) as written back to HBM
                        FILE* fp = fopen((dir + "/" + S.name + "_die" + char('0' + d) + "_kvblk.hex").c_str(), "w");
                        const size_t lb = size_t(S.region) * 131072;
                        for (int j = 0; j < S.np; j++) {
                            int P = S.pos + j;
                            for (int h = 0; h < 2; h++) for (int dd = 0; dd < 128; dd++) {
                                size_t a = (size_t(h) << 16) + (P >> 4) * 128 + dd;
                                uint32_t w = rm_hbm_mem(v.rootp)[lb + a / 2][((a & 1) * 16 + (P & 15)) / 4];
                                fprintf(fp, "K %d %d %d %02x\n", j, h, dd, (w >> (8 * (((a & 1) * 16 + (P & 15)) % 4))) & 0xff);
                            }
                            for (int h = 0; h < 2; h++) for (int dd = 0; dd < 128; dd++) {
                                size_t a = 131072 + (size_t(h) << 16) + size_t(P) * 8 + dd / 16;
                                uint32_t w = rm_hbm_mem(v.rootp)[lb + a / 2][((a & 1) * 16 + dd % 16) / 4];
                                fprintf(fp, "V %d %d %d %02x\n", j, h, dd, (w >> (8 * (((a & 1) * 16 + dd % 16) % 4))) & 0xff);
                            }
                        }
                        fclose(fp);
                    }
                    printf("VERIFY_TOKENS die=%d n=%u", d, unsigned(v.seq_n_tok));
                    for (unsigned j = 0; j < v.seq_n_tok && j < 8; j++)
                        printf(" t%u=%u/%08x", j, unsigned(getb(v.seq_tok_vec, j * COUNTWIDTH, COUNTWIDTH)), unsigned(getb(v.seq_val_vec, j * 32, 32)));
                    printf("\n");
                }
                fflush(stdout);
                if (sf || cf || lf) { printf("TOKEN FAULT stage=%s\n", S.name.c_str()); return 1; }
                if (cur + 1 == stages.size()) {
                    // let an armed accept fire (it starts on this stage's done)
                    for (int k = 0; k < 64; k++) {
                        for (int d = 0; d < D; d++) die[d]->clk = 1;
                        for (int d = 0; d < D; d++) die[d]->eval();
                        for (int d = 0; d < D; d++) die[d]->clk = 0;
                        for (int d = 0; d < D; d++) die[d]->eval();
                        for (int d = 0; d < D; d++)
                            if (die[d]->acc_done && !acc_seen[d]) {
                                acc_seen[d] = true;
                                printf("ACCEPT die=%d a=%u n_emit=%u bonus=%u kv_committed_len=%u kv_committed_v=%u kv_fault=%04x\n", d,
                                       unsigned(die[d]->acc_a), unsigned(die[d]->acc_n_emit), unsigned(die[d]->acc_bonus),
                                       unsigned(die[d]->kv_committed_len), unsigned(die[d]->kv_committed_v), die[d]->kv_fault_code);
                            }
                    }
                    for (int d = 0; d < D; d++) if (die[d]->mem_fault) { printf("MEMORY FAULT after accept die=%d kv_code=%04x\n", d, die[d]->kv_fault_code); return 1; }
                    if (dump_hbm)
                        for (int d = 0; d < D; d++)
                            if (S.layer >= 0) dump_region(*die[d], S.region, dir + "/" + S.name + "_die" + char('0' + d) + "_hbm.bin");
                    struct rusage ru; getrusage(RUSAGE_SELF, &ru);
                    printf("QWEN_ROM_VPRM PASS stages=%zu cycles=%u edges=%ld settle_max=%d wall_s=%.1f RSS_KiB=%ld threads=%d\n",
                           stages.size(), cyc, edges, max_settle, sec, ru.ru_maxrss, threads);
                    return 0;
                }
                next_stage = true;
            }
            // first rise of each die's core / sequencer fault and of the collective's error / fault (observation only)
            {
                static bool tr_core[8] = {}, tr_seq[8] = {}, tr_coll = false;
                for (int d = 0; d < D; d++) {
                    if (die[d]->core_fault && !tr_core[d]) {
                        tr_core[d] = true;
                        printf("FAULTTRACE core_fault die=%d cyc=%u pc_base=%u prog_a=%u src=%04x stage=%s\n", d, cyc, unsigned(die[d]->prog_base),
                               unsigned(die[d]->dbg_prog_a), unsigned(die[d]->dbg_fault_src), stages[cur].name.c_str());
                    }
                    if (die[d]->dbg_fault_src && !tr_seq[d] && !tr_core[d]) {
                        static int tr_src_n[8] = {};
                        if (tr_src_n[d]++ < 4)
                            printf("FAULTTRACE src die=%d cyc=%u prog_a=%u src=%04x\n", d, cyc, unsigned(die[d]->dbg_prog_a), unsigned(die[d]->dbg_fault_src));
                    }
                    if (die[d]->s_fault && !tr_seq[d]) {
                        tr_seq[d] = true;
                        printf("FAULTTRACE seq_fault die=%d cyc=%u pc_base=%u core_fault=%d coll_err=%u coll_fault=%u stage=%s\n", d, cyc,
                               unsigned(die[d]->prog_base), int(die[d]->core_fault), unsigned(coll.out_err), unsigned(coll.fault),
                               stages[cur].name.c_str());
                    }
                }
                if ((coll.out_err || coll.fault) && !tr_coll) {
                    tr_coll = true;
                    printf("FAULTTRACE coll out_err=%u fault=%u cyc=%u\n", unsigned(coll.out_err), unsigned(coll.fault), cyc);
                }
            }
            if (cyc > max_cycles) { printf("timeout cyc=%u\n", cyc); return 3; }
        }
        // ---- tile clock enables, sampled on pre-edge values -------------------------------
        for (int d = 0; d < D; d++) {
            uint8_t me = die[d]->me_clk_en;
            if (me) me_busy[d]++;
            tile_en[d] = me || fab[d]->kv_active();
            if (tile_en[d]) {
                tile_edges[d]++;
                for (int i = 0; i < NT; i++) fab[d]->kv_ce_prev[i] = fab[d]->t[i]->kvw_ce;
            }
        }
        // ---- rising edge --------------------------------------------------------------------
        for (int d = 0; d < D; d++) die[d]->clk = 1;
        coll.clk = 1;
        for (int d = 0; d < D; d++) die[d]->eval();
        coll.eval();
        for (int d = 0; d < D; d++) if (tile_en[d]) fab[d]->edge();
        edges++;
        // ---- host writes (applied after the edge, sampled at the next): accept slots, commit, stage switch
        for (int d = 0; d < D; d++) { die[d]->h_start = 0; die[d]->acc_start_v = 0; die[d]->acc_tokx_v = 0; die[d]->acc_arm = 0; die[d]->h_commit_v = 0; }
        if (acc_feed >= 0 && die[0]->rt_rst_n) {
            for (int d = 0; d < D; d++) {
                if (acc_feed == 0) { die[d]->acc_start_v = 1; die[d]->acc_start_tok = acc_toks[0]; }
                else { die[d]->acc_tokx_v = 1; die[d]->acc_tokx_slot = acc_feed; die[d]->acc_tokx_tok = acc_toks[acc_feed]; }
            }
            if (++acc_feed >= int(acc_toks.size()) || acc_feed > 7) acc_feed = -1;
        }
        if (cur == 0 && stages[0].arm && !arm0 && die[0]->rt_rst_n) {
            for (int d = 0; d < D; d++) die[d]->acc_arm = 1;
            arm0 = true;
        }
        if (next_stage && stages[cur + 1].commit > 0 && commit_pending == 0) {
            // commit the previous stage's block (the service accepts it only after every token K/V is acknowledged)
            bool drained = true;
            for (int d = 0; d < D; d++) drained &= die[d]->kv_drained_o;
            if (drained) {
                for (int d = 0; d < D; d++) { die[d]->h_commit_v = 1; die[d]->h_commit_n = stages[cur + 1].commit; }
                commit_pending = 1;
            }
        } else if (next_stage && (stages[cur + 1].commit == 0 || commit_pending == 2)) {
            next_stage = false; stage_done = false; done_armed = false; cur++; commit_pending = 0;
            auto tp = std::chrono::steady_clock::now();
            const Stage& S = stages[cur];
            for (int d = 0; d < D; d++) {
                load_images(mem[d], S.dir[d]);
                preload_die_roms(*die[d], mem[d], pool);
                preload_tile_roms(*fab[d], mem[d]);
                if (!S.xpre.empty()) load_vm(*die[d], S.xpre);
                die[d]->rm_layer = uint8_t(S.layer < 0 ? 255 : S.region);
                die[d]->rm_npos = S.np;
                die[d]->tp_pos = S.pos;
                die[d]->h_start = 1;
                if (S.arm) die[d]->acc_arm = 1;
                busy0[d] = me_busy[d];
            }
            stage_start = long(die[0]->cyc);
            printf("stage %s loaded (layer %d region %d pos %d np %d): code_words=%zu scale_words=%zu crom_words=%zu preload %.1f s\n",
                   S.name.c_str(), S.layer, S.region, S.pos, S.np, mem[0].code_words, mem[0].scale_words, mem[0].crom_words,
                   std::chrono::duration<double>(std::chrono::steady_clock::now() - tp).count());
            fflush(stdout);
        } else if (commit_pending == 1) {
            for (int d = 0; d < D; d++)
                if (!die[d]->kv_committed_v || int(die[d]->kv_committed_len) != stages[cur].pos + stages[cur + 1].commit)
                    fatal("host commit not registered", long(die[d]->kv_committed_len), long(stages[cur].pos + stages[cur + 1].commit));
            printf("COMMIT %d of block %d..%d: committed_len=%u (rollback %d..%d)\n", stages[cur + 1].commit, stages[cur].pos,
                   stages[cur].pos + stages[cur].np - 1, unsigned(die[0]->kv_committed_len),
                   stages[cur].pos + stages[cur + 1].commit, stages[cur].pos + stages[cur].np - 1);
            commit_pending = 2;
        }
        bool live[D];
        for (int d = 0; d < D; d++) live[d] = tile_en[d];
        settle(live);
        if (tick % progress_every == 0) {
            double sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - tstart).count();
            printf("progress tick=%ld cyc=%u pc_base=%u/%u me_busy=%ld/%ld kv_ok=%d drained=%d wall=%.0fs passes=%ld\n", tick, die[0]->cyc,
                   die[0]->prog_base, die[D - 1]->prog_base, me_busy[0], me_busy[D - 1], die[0]->kv_ok_o, die[0]->kv_drained_o, sec, passes);
            fflush(stdout);
        }
    }
}
