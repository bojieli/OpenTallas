#!/usr/bin/env python3
"""QW-S5-SCRED 10-21: write the scalar-port kit top qfd_dv_s5_<kind>2_leaf.sv around the bounded netlist
qfd_dv_s5_<kind>2_k<CFG> (ports identical to qfd_dv_s5_red / qfd_dv_s5_sc as instantiated by qfd_dv_s5b_su8p2_lp).
Usage: gen_leaf.py red|sc CFG"""
import sys
from pathlib import Path
kind,cfg=sys.argv[1],sys.argv[2]
P={'red':[('input','',  'ck'),('input','','rst_n'),('input','[7:0]','l_ov'),('input','[8*32-1:0]','l_out'),('input','[1:0]','l_red0'),
          ('input','','l_redsq0'),('input','','l_last0'),('input','[23:0]','l_raddr0'),('output','','red_we'),('output','[23:0]','red_addr'),
          ('output','[31:0]','red_data'),('output','','rd_v'),('output','','busy'),('output','','fault')],
   'sc':[('input','','ck'),('input','','rst_n'),('input','[100:0]','sc_cfg'),('input','[47:0]','dn_i'),('output','[47:0]','dn_o'),
         ('input','[47:0]','up_i'),('output','[47:0]','up_o'),('input','','red_we'),('input','[23:0]','red_addr'),('input','[31:0]','red_data'),
         ('input','[7:0]','vm_we'),('input','[1:0]','vm_win0'),('input','[31:0]','vm_wdata0'),('input','','am_v'),('input','[23:0]','am_idx'),
         ('input','[31:0]','am_val'),('input','[1:0]','am_u'),('output','','w1_we'),('output','[23:0]','w1_addr'),('output','[31:0]','w1_data'),
         ('output','','tok_v'),('output','[23:0]','tok_idx'),('output','','tok_own'),('output','[31:0]','tok_val'),('output','[1:0]','tok_user'),
         ('output','','busy'),('output','','fault')]}[kind]
la,lm=cfg[0],cfg[1]; n=f"qfd_dv_s5_{kind}2_k{cfg}"
L=["`timescale 1ns/1ps",
   f"// QW-S5-SCRED kit top (generated by rtl/test/qwen_dv/s5_scred2/gen_leaf.py): scalar-port wrapper of the bounded netlist {n}",
   f"// = qfd_dv_s5_{kind}2 #(LA {la}, LM {lm}) through tools/qwen_dv/bound_math_netlist.py --load-cap 8 --transparent-inverters --retain-mux",
   "// --shared-helpers --retain-keep (rtl/test/qwen_dv/s5_scred2/native_k.sh).  Ports = the instantiated qfd_dv_s5_%s." % kind,
   "// OT_S5_SCRED2_MUT_NETLIST (bench only): the constructed mutant netlist instead.",
   f"module qfd_dv_s5_{kind}2_leaf ("]
L+=[f"    {d:6s} wire {w:10s} {p}{',' if i<len(P)-1 else ''}" for i,(d,w,p) in enumerate(P)]
L+=[");","`ifdef OT_S5_SCRED2_MUT_NETLIST",f"    {n}_mut u (","`else",f"    {n} u (","`endif",
    "        "+", ".join(f".{p}({p})" for _,_,p in P)+");","endmodule",""]
Path(f"rtl/qwen_dv/s5/qfd_dv_s5_{kind}2_leaf.sv").write_text("\n".join(L))
