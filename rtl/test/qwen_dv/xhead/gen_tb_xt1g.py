#!/usr/bin/env python3
"""QW-LAYERB 10-20: generate tb_xt1g.sv = the XT1n near+far matvec bench ON A GEN DIE NETLIST CARVE.

The carve (tools/qwen_layerbench/die_carve.py, seeds dvs_W5 c16_W5_2 c16_W5_3) is the die.v instance lines of the slice,
the near and far band-2 clusters and every landing between them, byte-for-byte.  The bench drives the die-side lane ends
the tt_ctlm / neighbours would drive (cmd_wi, hr_wi, st_wi landed nets = the XT1 event ports 0/1/2), every clock net from
one bench clock and every reset-field net from one bench reset; every other carve input is 0 (S clusters, W4 neighbour).
Log lines are the tb_xt1n ones, so xt1n_bench.py checks them unchanged, but RS / RSO are sampled at the SLICE PINS
after the die landings (n_dv_rs_W5_2_{a,b}__r1 = real die cycles); RSC / RSOC are the cluster outputs before landing.

    gen_tb_xt1g.py carve.json rom_bind.vh OUT_DIR     -> OUT_DIR/tb_xt1g.sv, OUT_DIR/rom_bind_xt1g.vh
"""
import json, re, sys
from pathlib import Path

carve = json.loads(Path(sys.argv[1]).read_text())
rb = Path(sys.argv[2]).read_text().splitlines()
out = Path(sys.argv[3]); out.mkdir(parents=True, exist_ok=True)
seeds = set(carve['seeds'])
keep = [l for l in rb if l.startswith('defparam') and re.search(r'\.(\w+)\.u_t_', l) and re.search(r'\.(\w+)\.u_t_', l).group(1) in seeds]
assert len(keep) == 32, len(keep)
(out / 'rom_bind_xt1g.vh').write_text('// rom_bind.vh lines of the carved clusters (GEN output, unchanged)\n' + '\n'.join(keep) + '\n')
DRIVE = {'n_dvw_cmd_wi__r27': 'cmd0', 'n_dvw_hr_wi__r26': 'hr0', 'n_dvw_st_wi__r23': 'swi'}
conns = []
for n, w in carve['inputs'].items():
    if n.startswith('n_clk_'):
        v = 'ck'
    elif n.startswith('n_rst_field'):
        v = 'rst_n'
    elif n in DRIVE:
        v = DRIVE[n]
    else:
        v = f"{w}'d0"
    conns.append(f'.{n}({v})')
OBS = {'n_q3h_col_0_2': 'cw_n0', 'n_q3h_col_1_2': 'cw_n1', 'n_q3h_col_2_2': 'cw_n2', 'n_q3h_col_3_2': 'cw_n3',
       'n_dv_rs_W5_2_a__r1': 'rs', 'n_dv_rs_W5_2_b__r1': 'rs_o', 'n_dv_rs_W5_2_a': 'rsc', 'n_dv_rs_W5_2_b': 'rsoc'}
for n in carve['outputs']:
    conns.append(f'.{n}({OBS.get(n, "")})')
for n in DRIVE:
    assert n in carve['inputs'], n
for n in OBS:
    assert n in carve['outputs'], n
tb = f'''`timescale 1ns/1ps
// GENERATED by rtl/test/qwen_dv/xhead/gen_tb_xt1g.py (QW-LAYERB 10-20) from {carve['die_v']} sha256 {carve['die_v_sha256']}
// XT1g: XT1n events/log on the GEN die-netlist carve {sorted(seeds)} ({carve['kept_relays']} die landings kept).
module tb_xt1g (input wire ck);
    reg rst_n = 1'b0;
    reg  [115:0]  cmd0;
    reg  [452:0]  hr0;
    reg  [1087:0] swi;
    wire [515:0]  cw_n0, cw_n1, cw_n2, cw_n3;
    wire [513:0]  rs, rs_o, rsc, rsoc;
    xt1g_carve u_d ({', '.join(conns)});
`define OT_ROM_BIND_TOP tb_xt1g.u_d
`include "rom_bind_xt1g.vh"
    integer fd, lg, cyc, ncyc, ec, ep, r, pre = 0, nrst;
    reg [1087:0] ev;
    reg have, hdf, stf, rsf, rof;
    reg [1023:0] evf, lgf;
    wire [3:0] cwgo = {{cw_n3[0], cw_n2[0], cw_n1[0], cw_n0[0]}};
    task automatic apply(input integer p, input [1087:0] v);
        begin
            if (p == 0) cmd0 = v[115:0];
            else if (p == 1) hr0 = v[452:0];
            else if (p == 2) swi = v;
            else $fatal(1, "bad port %0d", p);
        end
    endtask
    initial begin
        if (!$value$plusargs("EV=%s", evf)) $fatal(1, "+EV");
        if (!$value$plusargs("LOG=%s", lgf)) $fatal(1, "+LOG");
        if (!$value$plusargs("NCYC=%d", ncyc)) ncyc = 4000;
        if (!$value$plusargs("NRST=%d", nrst)) nrst = 16;
        fd = $fopen(evf, "r"); lg = $fopen(lgf, "w");
        cmd0 = 0; hr0 = 0; swi = 0; cyc = 0; hdf = 0; stf = 0; rsf = 0; rof = 0;
        r = $fscanf(fd, "%d %d %h\\n", ec, ep, ev); have = (r == 3);
    end
    always @(negedge ck) begin
        if (pre < nrst) begin pre = pre + 1; if (pre == nrst) rst_n = 1'b1; end
        else begin
            if (hr0[452]) $fdisplay(lg, "%0d HRGO", cyc);
            if (hr0[1])   $fdisplay(lg, "%0d HRXPF", cyc);
            if (|cwgo)    $fdisplay(lg, "%0d CWGO %h", cyc, cwgo);
            if (rs[512] || rs[513]) $fdisplay(lg, "%0d RS %0d %h", cyc, rs[513], rs[511:0]);
            if (rs_o[512] || rs_o[513]) $fdisplay(lg, "%0d RSO %0d %h", cyc, rs_o[513], rs_o[511:0]);
            if (rsc[512] || rsc[513]) $fdisplay(lg, "%0d RSC %0d", cyc, rsc[513]);
            if (rsoc[512] || rsoc[513]) $fdisplay(lg, "%0d RSOC %0d", cyc, rsoc[513]);
            if (u_d.dvs_W5.u_core.hd_fault && !hdf) begin $fdisplay(lg, "%0d FAULT heads", cyc); hdf = 1; end
            if (u_d.dvs_W5.u_core.stm_fault && !stf) begin $fdisplay(lg, "%0d FAULT stream", cyc); stf = 1; end
            if (rs[513] && !rsf) begin $fdisplay(lg, "%0d FAULT near_cluster", cyc); rsf = 1; end
            if (rs_o[513] && !rof) begin $fdisplay(lg, "%0d FAULT far_cluster", cyc); rof = 1; end
            cmd0 = 0; hr0 = 0; swi = 0;
            while (have && ec == cyc) begin
                apply(ep, ev);
                r = $fscanf(fd, "%d %d %h\\n", ec, ep, ev); have = (r == 3);
            end
            if (have && ec < cyc) $fatal(1, "event file not sorted at cycle %0d", ec);
            cyc = cyc + 1;
            if (cyc >= ncyc) begin
                $fdisplay(lg, "%0d END hd_fault %0d stm_fault %0d near_fault %0d far_fault %0d", cyc, u_d.dvs_W5.u_core.hd_fault, u_d.dvs_W5.u_core.stm_fault, rsf, rof);
                $fclose(lg);
                $finish;
            end
        end
    end
endmodule
'''
(out / 'tb_xt1g.sv').write_text(tb)
print('tb_xt1g.sv', len(conns), 'conns; rom_bind lines', len(keep))
