#!/usr/bin/env python3
"""Emit both scalar variants from one current source, differing only by opt-in."""
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[4]
sys.path.insert(0,str(ROOT/'tools'))
import die_port_bind as P
s=(ROOT/'rtl/qwen_dv/qfd_dv_scalar2.sv').read_text()
for name,defs in [('legacy',{}),('safe',{'OT_QFD_DV_SAFE_STORAGE':''})]:
 t=P.preprocess(P.strip_comments(s),defs).replace('module qfd_dv_scalar2 #(',f'module qfd_dv_scalar2_{name} #(')
 Path(__file__).with_name(f'{name}.sv').write_text('// GENERATED by safe_scalar/generate.py from qfd_dv_scalar2.sv\n'+t)
