`timescale 1ns/1ps
// el1013-hbm-seq-split (2026-10-13): QUALIFICATION bench of the R25GQ sequencer split.
//   side A = `SEQ_A_MOD (default ot_hgi_seq, the flat routed design hgi_seq_v26s; the runner compiles a mutant-free copy
//            named ot_hgi_seq_ref), side B = `SEQ_B_MOD (default ot_hgi_seq_split).
// Two complete, independent environments (hgi_seq_split_env: fetch responder, VM, 15 unit responders, doorbell driver,
// completion sink; the models of tb_hgi_seq.sv) run the SAME job list with the SAME per-model pseudo-random streams
// (own xorshift generators: no $urandom, so the two sides and the two simulators draw identical numbers).  Each side
// logs its transactions; the top compares them per job, in order, bit-exact, per channel:
//   doorbell accept {token, pos, job, gen}            exactly one a job
//   dispatch {u_v, d_hdr, d_sut, d_desc, d_n, d_pos1, d_pslot1, d_L, d_L1}   every one, count equal
//   completion beats {tokx, token, pos, job, gen, status}                   every one, count equal (cpl_cycles is
//            EXCLUDED: the split adds latency; both values are recorded and the bench-side cycle counts printed)
//   VM reads {vr_addr}   every one, count equal; PREFIX only for a job ended by a unit fault (status 1) or by a mid-job
//            reset: the indexed resolver reads AHEAD of the head record, so the number of reads made before an
//            asynchronous abort is timing-dependent in the flat design itself
//   fetch    {first f_req_addr of the job}; inside each environment every later request must be the previous + 32
//            (the stream is sequential by construction) and at most 2 requests of the previous job may precede the
//            first one (the 2-entry request FIFO is not flushed at a job end).  The request COUNT is not compared:
//            the prefetcher runs ahead until stopped, so it is timing-dependent in the flat design itself.
// Also on both sides (as tb_hgi_seq.sv): one-hot dispatch port = header unit, the `wait` rule against the bench's own
// outstanding counts, and (jobs marked gold, sets 0 / 1) completion token / status / dispatch count / TOKX beats = the
// vector cfg (DS set: differences from the committed cfg are only counted, ds_cfg_stale).
// FAIL: any mismatch, count mismatch, a transaction outside a job, timeout, busy not falling, seam_err on side B
// (`SEQ_B_SEAM_ERR, an expression over `dut.`), missing coverage on side A, DS mode-0 cycle ratio > RATIO_MAX_PM.
// Job list (one simulation, no reset between jobs unless stated), per mode m:
//   mode 0  zero backpressure: every ready 1, fetch / VM latency minimal, units retire at once; the doorbell waits for
//           busy low (the throughput measurement: SPLIT_TPUT, the DS gate)
//   mode 1  random backpressure (tb_hgi_seq.sv distributions), doorbell right after the completion (no busy wait)
//   mode 2  heavy backpressure (ready 1/4, long latencies, wr_quiet toggling), doorbell right after the completion
//   each: the 43 tb cases, the 66 conformance cases, the 41 DS production-shape layer jobs, the 9 G24 LOOP-from-VM
//   cases (vectors generated by the runner), then: CF-PROG reset
//   after K dispatches (mid-job reset), a DS job, a DS job reset mid-job, the unit-fault case, a DS job, an idle
//   reset (units possibly outstanding) and a DS job.  Modes 1 / 2 start with a reset.
// plusargs: +SEED=n (default 1)  +SKEW=n (side B's generators start from other seeds: other timing, same function)
//           +MODES=mask (default 7)  +CORRUPT=k (comparator self-test, corrupts one LOGGED transaction of side B:
//           1 dispatch bit, 2 VM address, 3 dropped dispatch, 4 completion token, 5 fetch first address, 6 doorbell)
// Prints  HGI_SEQ_SPLIT PASS programs=<n> tx=<n> cycles_flat=<n> cycles_split=<n> ratio=<r>  /  HGI_SEQ_SPLIT FAIL <reason>
`ifndef SEQ_A_MOD
`define SEQ_A_MOD ot_hgi_seq
`endif
`ifndef SEQ_B_MOD
`define SEQ_B_MOD ot_hgi_seq_split
`endif
`ifndef RATIO_MAX_PM
`define RATIO_MAX_PM 1300   // regression guard against the FLAT design in the sequencer-limited mode 0 (no fetch latency,
                            // instant retire), NOT the qualification: that is the priced production bench (CP.FETCH,
                            // tools/tput_map_1011/run_cp_fetch.sh with -DOT_HGI_SEQ_SPLIT: <= 1.10x of the 31,831-cycle price;
                            // measured 0.953x).  The split adds ~5 cycles of record residence on a 4-entry queue.
`endif

module hgi_seq_split_env #(parameter integer SIDE = 0) (input wire clk);
`include "hgi_seq_sizes.svh"
`include "hgi_seq_sizes_conf.svh"
`include "hgi_seq_sizes_ds.svh"
`include "hgi_seq_sizes_g24.svh"    // GENERATED by tools/run_hgi_seq_split.py (the G24 LOOP-from-VM cases)
    localparam integer QD = 4;                 // = the ot_hgi_seq default (the routed hgi_seq_v26s value)
    localparam integer PAGE = 32'h10;
    localparam integer MAXJOB = 1024, DMAX = 65536, VMAX = 262144, CMAX = 16384;
    localparam integer DW = 2413, CW = 79;
    localparam [39:0] IMG = PAGE * 4096;
    // ---------------------------------------------------------------- DUT pins
    reg rst_n = 0;
    reg [159:0] md_d = 0; reg [17:0] vocab = 0; reg [20:0] ctxmax = 0; reg [7:0] rank = 0;
    reg db_v = 0; reg [17:0] db_token = 0; reg [19:0] db_pos = 0; reg [31:0] db_job = 0; reg [3:0] db_gen = 0, db_ncol = 1;
    wire db_rdy;
    wire f_req_v; reg f_req_rdy = 0; wire [39:0] f_req_addr; reg f_rsp_v = 0; reg [255:0] f_rsp_data = 0;
    wire vr_v; reg vr_rdy = 0; wire [17:0] vr_addr; reg vr_rsp_v = 0; reg [31:0] vr_rsp_data = 0;
    wire [15:0] u_v; reg [15:0] u_rdy = 0; wire [127:0] d_hdr; wire [255:0] d_sut; wire [1791:0] d_desc;
    wire [146:0] d_n; wire [20:0] d_pos1, d_pslot1; wire [15:0] d_L, d_L1;
    reg [15:0] u_done = 0, u_fault = 0; reg wr_quiet = 1;
    wire cpl_v; reg cpl_rdy = 0; wire [17:0] cpl_token; wire [19:0] cpl_pos; wire [31:0] cpl_job, cpl_cycles;
    wire [3:0] cpl_gen, cpl_status; wire busy; wire cpl_tokx;
    integer cyc = 0; always @(posedge clk) cyc <= cyc + 1;
    // ---------------------------------------------------------------- coverage (side A, flat names) / seam flag (side B)
    integer cov_inj = 0, cov_nest = 0, cov_fence = 0, cov_lvm = 0, cov_qfull = 0, cov_abort = 0, cov_b2b = 0;
    reg seam_seen = 0;
`define SEQ_PORTS (.clk(clk), .rst_n(rst_n), .md_d(md_d), .cfg_vocab(vocab), .cfg_ctx_max(ctxmax), .rank(rank), \
        .hold(1'b0), .busy(busy), .db_v(db_v), .db_rdy(db_rdy), .db_token(db_token), .db_pos(db_pos), .db_job(db_job), \
        .db_gen(db_gen), .db_entry(2'd0), .db_ncol(db_ncol), .db_kernel(4'd0), .db_loff(32'd0), .md_k(352'd0), \
        .f_req_v(f_req_v), .f_req_rdy(f_req_rdy), .f_req_addr(f_req_addr), .f_rsp_v(f_rsp_v), .f_rsp_data(f_rsp_data), \
        .vr_v(vr_v), .vr_rdy(vr_rdy), .vr_addr(vr_addr), .vr_rsp_v(vr_rsp_v), .vr_rsp_data(vr_rsp_data), .u_v(u_v), \
        .u_rdy(u_rdy), .d_hdr(d_hdr), .d_sut(d_sut), .d_desc(d_desc), .d_n(d_n), .d_pos1(d_pos1), .d_pslot1(d_pslot1), \
        .d_L(d_L), .d_L1(d_L1), .u_done(u_done), .u_fault(u_fault), .wr_quiet(wr_quiet), .cpl_v(cpl_v), \
        .cpl_rdy(cpl_rdy), .cpl_token(cpl_token), .cpl_pos(cpl_pos), .cpl_job(cpl_job), .cpl_gen(cpl_gen), \
        .cpl_status(cpl_status), .cpl_cycles(cpl_cycles), .cpl_tokx(cpl_tokx))
    generate if (SIDE == 0) begin : g
        `SEQ_A_MOD #(.QD(QD)) dut `SEQ_PORTS;
        // flat names of ot_hgi_seq.sv; S_FEN = 5'd9 (the runner checks the source still says so)
        reg p_inj = 0, p_nest = 0, p_fen = 0, p_full = 0, p_ab = 0;
        always @(posedge clk) if (rst_n) begin
            p_inj <= dut.be_inj; p_nest <= (dut.depth == 2'd2); p_fen <= (dut.st == 5'd9);
            p_full <= (dut.q_cnt == QD); p_ab <= dut.be_abort;
            if (dut.be_inj && !p_inj) cov_inj = cov_inj + 1;                    // an indexed descriptor re-injected
            if (dut.depth == 2'd2 && !p_nest) cov_nest = cov_nest + 1;          // two loop levels open
            if (dut.st == 5'd9 && !p_fen) cov_fence = cov_fence + 1;            // S_FEN
            if (dut.lv_rsp) cov_lvm = cov_lvm + 1;                              // a LOOP count from VM
            if (dut.q_cnt == QD && !p_full) cov_qfull = cov_qfull + 1;          // the record queue full
            if (dut.be_abort && !p_ab) cov_abort = cov_abort + 1;               // a job aborted by a unit fault
            if (dut.job_start && (dut.busy_u & 16'hFFFE) != 16'd0) cov_b2b = cov_b2b + 1;   // a job starts over outstanding units
        end
    end else begin : g
        `SEQ_B_MOD #(.QD(QD)) dut `SEQ_PORTS;
`ifdef SEQ_B_SEAM_ERR
        always @(posedge clk) if (rst_n && ((`SEQ_B_SEAM_ERR) === 1'b1)) seam_seen <= 1'b1;
`endif
    end endgenerate
    // ---------------------------------------------------------------- vectors (four sets: 0 tb cases, 1 conformance, 2 DS,
    // 3 the G24 LOOP-from-VM cases of tools/run_hgi_seq_g24.py, generated by the runner)
    reg [127:0] img0 [0:SEQ_NW-1]; reg [127:0] img1 [0:CONF_NW-1]; reg [127:0] img2 [0:DS_NW-1]; reg [127:0] img3 [0:G24_NW-1];
    reg [31:0] cfg0 [0:SEQ_NCASE*12-1]; reg [31:0] cfg1 [0:CONF_NCASE*12-1]; reg [31:0] cfg2 [0:DS_NCASE*12-1]; reg [31:0] cfg3 [0:G24_NCASE*12-1];
    reg [95:0] vmi1 [0:CONF_NVMI-1]; reg [95:0] vmi2 [0:DS_NVMI-1]; reg [95:0] vmi3 [0:G24_NVMI-1]; reg [95:0] vmw3 [0:4095];
    reg [95:0] vmw [0:4095]; reg [63:0] vm0 [0:SEQ_NVM0-1];
    reg [31:0] vm [0:262143];
    function automatic [31:0] cfgw(input integer s, input integer c, input integer k);
        cfgw = (s == 0) ? cfg0[c*12 + k] : (s == 1) ? cfg1[c*12 + k] : (s == 2) ? cfg2[c*12 + k] : cfg3[c*12 + k];
    endfunction
    function automatic integer ncase(input integer s);
        ncase = (s == 0) ? SEQ_NCASE : (s == 1) ? CONF_NCASE : (s == 2) ? DS_NCASE : G24_NCASE;
    endfunction
    function automatic [31:0] xs(input [31:0] x);
        reg [31:0] y; begin y = x ^ (x << 13); y = y ^ (y >> 17); xs = y ^ (y << 5); end
    endfunction
    // ---------------------------------------------------------------- the job list (identical on both sides)
    integer njob = 0;
    integer job_set [0:MAXJOB-1]; integer job_c [0:MAXJOB-1]; integer job_mode [0:MAXJOB-1]; integer job_rst_at [0:MAXJOB-1];
    reg job_fast [0:MAXJOB-1]; reg job_rstb [0:MAXJOB-1]; reg job_gold [0:MAXJOB-1]; reg job_tp [0:MAXJOB-1];
    task automatic add(input integer s, input integer c, input integer m, input reg f, input integer ra, input reg rb,
                       input reg gd, input reg tp);
        begin
            job_set[njob] = s; job_c[njob] = c; job_mode[njob] = m; job_fast[njob] = f; job_rst_at[njob] = ra;
            job_rstb[njob] = rb; job_gold[njob] = gd; job_tp[njob] = tp; njob = njob + 1;
        end
    endtask
    integer seed = 1, skew = 0, modes = 7, corrupt = 0;
    integer bi, bs, bc, bm, cfault;
    reg ready = 0;
    initial begin
        if (!$value$plusargs("SEED=%d", seed)) seed = 1;
        if (!$value$plusargs("MODES=%d", modes)) modes = 7;
        if (SIDE == 1) begin
            if (!$value$plusargs("SKEW=%d", skew)) skew = 0;
            if (!$value$plusargs("CORRUPT=%d", corrupt)) corrupt = 0;
        end
        $readmemh("hgi_seq_image.mem", img0); $readmemh("hgi_seq_image_conf.mem", img1); $readmemh("hgi_seq_image_ds.mem", img2);
        $readmemh("hgi_seq_cfg.mem", cfg0); $readmemh("hgi_seq_cfg_conf.mem", cfg1); $readmemh("hgi_seq_cfg_ds.mem", cfg2);
        $readmemh("hgi_seq_vmi_conf.mem", vmi1); $readmemh("hgi_seq_vmi_ds.mem", vmi2);
        for (bi = 0; bi < 4096; bi = bi + 1) vmw[bi] = {96{1'b1}};
        $readmemh("hgi_seq_vmw.mem", vmw); $readmemh("hgi_seq_vm0.mem", vm0);
        $readmemh("hgi_seq_image_g24.mem", img3); $readmemh("hgi_seq_cfg_g24.mem", cfg3); $readmemh("hgi_seq_vmi_g24.mem", vmi3);
        for (bi = 0; bi < 4096; bi = bi + 1) vmw3[bi] = {96{1'b1}};
        $readmemh("hgi_seq_vmw_g24.mem", vmw3);
        for (bi = 0; bi < 262144; bi = bi + 1) vm[bi] = 0;
        cfault = -1;
        for (bc = 0; bc < SEQ_NCASE; bc = bc + 1) if (cfg0[bc*12 + 9] != 32'hFFFF && cfault < 0) cfault = bc;
        for (bm = 0; bm < 3; bm = bm + 1) if (modes[bm]) begin
            for (bs = 0; bs < 4; bs = bs + 1)
                for (bc = 0; bc < ncase(bs); bc = bc + 1)
                    add(bs, bc, bm, bm != 0, -1, (bm != 0 && bs == 0 && bc == 0), 1'b1, 1'b1);
            add(0, 0, bm, 1'b1, 200 + 37*bm, 1'b0, 1'b0, 1'b0);       // CF-PROG, reset inside the layer loop
            add(2, 1, bm, 1'b1, -1, 1'b0, 1'b1, 1'b0);                // a DS job right after the reset
            add(2, 1, bm, 1'b1, 11 + bm, 1'b0, 1'b0, 1'b0);           // the same DS job, reset mid-job
            if (cfault >= 0) add(0, cfault, bm, 1'b1, -1, 1'b0, 1'b0, 1'b0);   // the unit-fault abort ...
            add(2, 0, bm, 1'b1, -1, 1'b0, 1'b1, 1'b0);                // ... and a DS job over its outstanding units
            add(2, 3, bm, 1'b1, -1, 1'b1, 1'b1, 1'b0);                // idle reset, then a DS job
        end
        ready = 1;
    end
    // ---------------------------------------------------------------- logs
    reg [DW-1:0] d_log [0:DMAX-1]; reg [17:0] v_log [0:VMAX-1]; reg [CW-1:0] c_log [0:CMAX-1];
    integer nd_tot = 0, nv_tot = 0, nc_tot = 0, nd_seen = 0;
    integer jd0 [0:MAXJOB-1]; integer jd1 [0:MAXJOB-1]; integer jv0 [0:MAXJOB-1]; integer jv1 [0:MAXJOB-1];
    integer jc0 [0:MAXJOB-1]; integer jc1 [0:MAXJOB-1]; integer jf_cnt [0:MAXJOB-1]; integer jf_stale [0:MAXJOB-1];
    integer jcyc [0:MAXJOB-1]; integer jdbn [0:MAXJOB-1]; integer jdisp [0:MAXJOB-1];
    reg [31:0] jcc [0:MAXJOB-1]; reg [39:0] jf_first [0:MAXJOB-1]; reg jf_seen [0:MAXJOB-1]; reg jrst [0:MAXJOB-1];
    reg [3:0] jstat [0:MAXJOB-1]; reg [73:0] jdb [0:MAXJOB-1];
    integer jobs_done = 0; reg all_done = 0;
    reg failed = 0;
    integer cur_j = 0, cur_set = 0, mode = 0;
`define EFAIL(MSG) begin if (!failed) begin $display("HGI_SEQ_SPLIT FAIL side %s job %0d (set %0d case %0d mode %0d): %s", \
        (SIDE == 0) ? "A" : "B", cur_j, cur_set, job_c[cur_j], mode, MSG); failed = 1; $finish; end end
    // ---------------------------------------------------------------- reset machine (the only writer of rst_n)
    integer rq_u = 0, rq_d = 0, ak_u = 0, ak_d = 0, rst_cnt = 4, rst_w = 5, n_rst_mid = 0, n_rst_idle = 0;
    always @(negedge clk) begin
        if (rst_cnt > 0) begin rst_cnt = rst_cnt - 1; if (rst_cnt == 0) rst_n = 1'b1; end
        else if (rq_u != ak_u || rq_d != ak_d) begin
            if (rq_u != ak_u) n_rst_mid = n_rst_mid + 1; else n_rst_idle = n_rst_idle + 1;
            ak_u = rq_u; ak_d = rq_d; rst_n = 1'b0; rst_cnt = rst_w;
        end
    end
    wire rst_busy = (rq_u != ak_u) || (rq_d != ak_d) || (rst_cnt != 0) || !rst_n;
    // ---------------------------------------------------------------- HBM: the image at byte PAGE*4096, in-order sectors
    function automatic [127:0] word_at(input [39:0] a);
        reg signed [41:0] w; begin
            w = ($signed({2'b0, a}) - $signed({2'b0, IMG})) / 16;
            word_at = 128'hDEAD;
            if (cur_set == 0) begin if (w >= 0 && w < SEQ_NW) word_at = img0[w]; end
            else if (cur_set == 1) begin if (w >= 0 && w < CONF_NW) word_at = img1[w]; end
            else if (cur_set == 2) begin if (w >= 0 && w < DS_NW) word_at = img2[w]; end
            else begin if (w >= 0 && w < G24_NW) word_at = img3[w]; end
        end
    endfunction
    reg [39:0] fq [0:255]; integer fqh = 0, fqn = 0, fdel = 0;
    reg [31:0] rf = 1, rv = 1, ru = 1, rc = 1;
    reg f_newp = 0; reg [39:0] f_S = 0, f_last = {40{1'b1}}; integer f_stale_left = 0;
    always @(posedge clk) begin
        if (!rst_n) begin fqh = 0; fqn = 0; fdel = 0; f_req_rdy <= 1'b0; f_rsp_v <= 1'b0; end
        else begin
            rf = xs(rf);
            f_req_rdy <= (mode == 0) ? 1'b1 : (mode == 1) ? ((rf[7:0] % 3) != 0) : (rf[1:0] == 2'd0);
            if (f_req_v && f_req_rdy) begin
                if (fqn >= 256) `EFAIL("fetch: more than 256 requests outstanding")
                fq[(fqh + fqn) % 256] = f_req_addr; fqn = fqn + 1;
                // the request stream: [<= 2 requests of the previous job] first = the job's entry sector, then + 32 each
                if (f_newp && f_req_addr == f_S) begin
                    f_newp = 0; jf_seen[cur_j] = 1'b1; jf_first[cur_j] = f_req_addr; jf_cnt[cur_j] = 1;
                    if (SIDE == 1 && corrupt == 5 && cur_j == 3) jf_first[cur_j] = f_req_addr ^ 40'h20;
                end else if (f_newp) begin
                    if (f_req_addr != f_last + 40'd32 || f_stale_left == 0) begin
                        $display("  fetch %h, previous %h, job entry sector %h", f_req_addr, f_last, f_S);
                        `EFAIL("fetch: a request before the job's entry sector that is not a queued request of the previous job")
                    end
                    f_stale_left = f_stale_left - 1; jf_stale[cur_j] = jf_stale[cur_j] + 1;
                end else if (f_req_addr == f_S && jf_cnt[cur_j] <= 2 && f_req_addr != f_last + 40'd32) begin
                    jf_cnt[cur_j] = 1;         // the entry sector again: the first one was a queued request of the previous job
                end else begin
                    if (f_req_addr != f_last + 40'd32) begin
                        $display("  fetch %h, previous %h", f_req_addr, f_last);
                        `EFAIL("fetch: request not sequential")
                    end
                    jf_cnt[cur_j] = jf_cnt[cur_j] + 1;
                end
                f_last = f_req_addr;
            end
            f_rsp_v <= 1'b0;
            if (fqn > 0) begin
                if (fdel > 0) fdel = fdel - 1;
                else begin
                    f_rsp_v <= 1'b1; f_rsp_data <= {word_at(fq[fqh] + 40'd16), word_at(fq[fqh])};
                    fqh = (fqh + 1) % 256; fqn = fqn - 1;
                    fdel = (mode == 0) ? 0 : (mode == 1) ? (rf[15:8] % 3) : (rf[15:8] % 8);
                end
            end
        end
    end
    // ---------------------------------------------------------------- VM read port (one outstanding)
    integer vdl = 0; reg vpend = 0; reg [17:0] va = 0;
    always @(posedge clk) begin
        if (!rst_n) begin vpend = 0; vdl = 0; vr_rdy <= 1'b0; vr_rsp_v <= 1'b0; wr_quiet <= 1'b1; end
        else begin
            rv = xs(rv);
            vr_rdy <= (mode == 0) ? 1'b1 : (mode == 1) ? rv[0] : (rv[1:0] == 2'd0);
            wr_quiet <= (mode == 2) ? (rv[22:20] != 3'd0) : 1'b1;
            vr_rsp_v <= 1'b0;
            if (vr_v && vr_rdy && !vpend) begin
                vpend = 1; va = vr_addr; vdl = (mode == 0) ? 1 : (mode == 1) ? 1 + rv[9:8] : 1 + rv[10:8];
                if (nv_tot >= VMAX) `EFAIL("VM read log overflow")
                v_log[nv_tot] = (SIDE == 1 && corrupt == 2 && nv_tot == 5) ? (vr_addr ^ 18'd1) : vr_addr;
                nv_tot = nv_tot + 1;
            end else if (vpend) begin
                vdl = vdl - 1;
                if (vdl <= 0) begin vr_rsp_v <= 1'b1; vr_rsp_data <= vm[va]; vpend = 0; end
            end
        end
    end
    // ---------------------------------------------------------------- units: accept, check, retire after a delay
    integer outst [0:15]; integer pend [0:15][0:63]; integer pdi [0:15][0:63]; integer pjb [0:15][0:63]; integer pn [0:15];
    integer uu, k, w, q, n0 = 0, kd = 0, fault_k = -1, rst_at = -1, nacc;
    reg [3:0] cu;
    task automatic retire_writes(input integer ws, input integer di);
        integer qq; reg stop; reg [95:0] e; begin
            stop = 0;
            for (qq = 0; qq < 4096 && !stop && (ws == 0 || ws == 3); qq = qq + 1) begin
                e = (ws == 0) ? vmw[qq] : vmw3[qq];
                if (e === {96{1'b1}}) stop = 1;
                else if (e[95:64] == di) vm[e[49:32]] = e[31:0];
            end
        end
    endtask
    initial for (uu = 0; uu < 16; uu = uu + 1) begin outst[uu] = 0; pn[uu] = 0; end
    always @(posedge clk) begin
        if (!rst_n) begin
            for (uu = 0; uu < 16; uu = uu + 1) begin outst[uu] = 0; pn[uu] = 0; end
            u_rdy <= 16'd0; u_done <= 16'd0; u_fault <= 16'd0;
        end else begin
            ru = xs(ru);
            u_rdy <= (mode == 0) ? 16'hFFFF : (mode == 1) ? ru[15:0] : (ru[15:0] & ru[31:16]);
            u_done <= 16'd0; u_fault <= 16'd0;
            for (uu = 1; uu < 16; uu = uu + 1) begin
                for (k = 0; k < pn[uu]; k = k + 1) pend[uu][k] = pend[uu][k] - 1;
                if (pn[uu] > 0 && pend[uu][0] <= 0) begin
                    u_done[uu] <= 1'b1; outst[uu] = outst[uu] - 1;
                    // a unit's VM writes land at its RETIRE (set 0: vmw, dispatch index -> addr, value); a retire of an
                    // older job is applied by the driver at the next job's start (deterministic), not here
                    if (pjb[uu][0] == cur_j) retire_writes(cur_set, pdi[uu][0]);
                    for (k = 0; k < 63; k = k + 1) begin
                        pend[uu][k] = pend[uu][k + 1]; pdi[uu][k] = pdi[uu][k + 1]; pjb[uu][k] = pjb[uu][k + 1];
                    end
                    pn[uu] = pn[uu] - 1;
                end
            end
            if (|(u_v & u_rdy)) begin
                cu = d_hdr[127:124];
                if (u_v !== (16'd1 << cu)) `EFAIL("dispatch port is not the one-hot of the header's unit")
                for (w = 1; w < 16; w = w + 1) if (d_hdr[102 + w] && outst[w] != 0) begin
                    $display("  unit %0d dispatched while unit %0d has %0d outstanding (dispatch %0d of the job)", cu, w, outst[w], kd);
                    `EFAIL("wait rule")
                end
                if (nd_tot >= DMAX) `EFAIL("dispatch log overflow")
                if (!(SIDE == 1 && corrupt == 3 && nd_seen == 50)) begin
                    d_log[nd_tot] = {u_v, d_L1, d_L, d_pslot1, d_pos1, d_n, d_desc, d_sut, d_hdr};
                    if (SIDE == 1 && corrupt == 1 && nd_seen == 100) d_log[nd_tot][384 + 8] = ~d_log[nd_tot][384 + 8];
                    nd_tot = nd_tot + 1;
                end
                nd_seen = nd_seen + 1;
                if (kd == fault_k) u_fault[cu] <= 1'b1;         // a faulted record retires by its fault (no done)
                else begin
                    if (pn[cu] >= 64) `EFAIL("more than 64 records outstanding on one unit")
                    outst[cu] = outst[cu] + 1;
                    pend[cu][pn[cu]] = (mode == 0) ? 0 : (cu == 9 || cu == 7) ? 200 + (ru[23:16] % 41) : (ru[23:16] % 21);
                    pdi[cu][pn[cu]] = n0 + kd; pjb[cu][pn[cu]] = cur_j;
                    pn[cu] = pn[cu] + 1;
                end
                kd = kd + 1;
                if (kd == rst_at) rq_u = rq_u + 1;              // mid-job reset: rst_n falls at the next negedge
            end
        end
    end
    // ---------------------------------------------------------------- doorbell accept monitor
    always @(posedge clk) if (rst_n && db_v && db_rdy) begin
        jdb[cur_j] = {db_token, db_pos, db_job, db_gen}; jdbn[cur_j] = jdbn[cur_j] + 1;
        if (SIDE == 1 && corrupt == 6 && cur_j == 2) jdb[cur_j][4] = ~jdb[cur_j][4];
    end
    // ---------------------------------------------------------------- driver
    integer j, c, set, t, a, nbeat, prev_set = -1, prev_n0 = 0, prev_kd = 0, cyc0 = 0;
    reg fin;
    integer cov_ds = 0, cov_tokx = 0, cov_st3 = 0, n_ds_stale = 0;
    task automatic log_cpl;
        begin
            if (nc_tot >= CMAX) `EFAIL("completion log overflow")
            c_log[nc_tot] = {cpl_tokx, cpl_token, cpl_pos, cpl_job, cpl_gen, cpl_status};
            if (SIDE == 1 && corrupt == 4 && nc_tot == 10) c_log[nc_tot][60] = ~c_log[nc_tot][60];
            nc_tot = nc_tot + 1;
        end
    endtask
    initial begin
        for (j = 0; j < MAXJOB; j = j + 1) begin
            jf_seen[j] = 0; jf_cnt[j] = 0; jf_stale[j] = 0; jrst[j] = 0; jdbn[j] = 0; jcyc[j] = 0; jcc[j] = 0; jstat[j] = 4'hF;
            jf_first[j] = 0; jdb[j] = 0; jdisp[j] = 0;
        end
        @(posedge clk); while (!ready) @(posedge clk);
        rf = xs(32'h9E3779B9 ^ (seed * 32'd2654435761) ^ (skew * 32'h85EBCA6B) ^ 32'd1);
        rv = xs(32'h7F4A7C15 ^ (seed * 32'd40503) ^ (skew * 32'hC2B2AE35) ^ 32'd2);
        ru = xs(32'h165667B1 ^ (seed * 32'd69069) ^ (skew * 32'h27D4EB2F) ^ 32'd3);
        rc = xs(32'h3C6EF372 ^ (seed * 32'd1664525) ^ (skew * 32'h9E3779B1) ^ 32'd4);
        if (rf == 0) rf = 1; if (rv == 0) rv = 1; if (ru == 0) ru = 1; if (rc == 0) rc = 1;
        while (rst_busy) @(posedge clk);
        repeat (3) @(negedge clk);
        for (j = 0; j < njob; j = j + 1) begin
            set = job_set[j]; c = job_c[j];
            if (job_rstb[j]) begin                      // reset between two jobs (units of the previous one may be outstanding)
                @(posedge clk); rst_w = 1 + 4*(j % 2); rq_d = rq_d + 1;      // posedge: the reset machine reads them at negedge
                @(posedge clk); while (rst_busy) @(posedge clk);
                repeat (2) @(negedge clk);
            end
            if (!job_fast[j]) begin
                t = 0; while (busy && t < 50000) begin @(negedge clk); t = t + 1; end
                if (busy) `EFAIL("busy does not fall before the job")
            end
            // the previous job's unit writes that have not retired yet land now, in dispatch order
            if (prev_set == 0 || prev_set == 3) for (a = 0; a < prev_kd; a = a + 1) retire_writes(prev_set, prev_n0 + a);
            cur_j = j; cur_set = set; mode = job_mode[j];
            if (set == 0) begin
                if (c == 0) for (a = 0; a < 262144; a = a + 1) vm[a] = 0;
                for (a = 0; a < SEQ_NVM0; a = a + 1) vm[vm0[a][49:32]] = vm0[a][31:0];
                for (a = 0; a < 16; a = a + 1) begin vm[32'hF000 + a] = 0; vm[32'hF010 + a] = 0; end
                vm[32'hF000] = 3; vm[32'hF100] = 1 << 21;
            end else begin
                for (a = 0; a < 262144; a = a + 1) vm[a] = 0;
                if (set == 1) begin for (a = 0; a < CONF_NVMI; a = a + 1) if (vmi1[a][95:64] == c) vm[vmi1[a][49:32]] = vmi1[a][31:0]; end
                else if (set == 3) begin for (a = 0; a < G24_NVMI; a = a + 1) if (vmi3[a][95:64] == c) vm[vmi3[a][49:32]] = vmi3[a][31:0]; end
                else begin for (a = 0; a < DS_NVMI; a = a + 1) if (vmi2[a][95:64] == c) vm[vmi2[a][49:32]] = vmi2[a][31:0]; end
            end
            md_d = {32'd1, PAGE, 32'd0, 32'd0, cfgw(set, c, 0)};
            vocab = cfgw(set, c, 4); ctxmax = cfgw(set, c, 5); rank = cfgw(set, c, 3);
            fault_k = (cfgw(set, c, 9) == 32'hFFFF) ? -1 : cfgw(set, c, 9);
            n0 = cfgw(set, c, 10); kd = 0; rst_at = job_rst_at[j]; rst_w = 1 + 4*(j % 2);
            jd0[j] = nd_tot; jv0[j] = nv_tot; jc0[j] = nc_tot;
            f_S = (IMG + {cfgw(set, c, 0), 4'd0}) & ~40'd31; f_newp = 1; f_stale_left = 2;
            @(negedge clk); t = 0; while (!db_rdy && t < 50000) begin @(negedge clk); t = t + 1; end
            if (!db_rdy) `EFAIL("db_rdy does not rise")
            db_ncol = cfgw(set, c, 11) >> 8; db_token = cfgw(set, c, 1); db_pos = cfgw(set, c, 2);
            db_job = 32'h12340000 + j * 7919; db_gen = j + 5; db_v = 1; @(negedge clk); db_v = 0;
            cyc0 = cyc; nbeat = 0; t = 0; fin = 0;
            while (!fin) begin
                if (rst_busy) begin                     // the mid-job reset: the job ends here
                    @(posedge clk); while (rst_busy) @(posedge clk);
                    repeat (2) @(negedge clk);
                    jrst[j] = 1; fin = 1;
                end else if (cpl_v && cpl_tokx) begin   // a CTL.TOKX beat
                    log_cpl; nbeat = nbeat + 1; cov_tokx = cov_tokx + 1;
                    if (mode == 2) begin rc = xs(rc); repeat (rc[9:8]) @(negedge clk); end
                    cpl_rdy = 1; @(negedge clk); cpl_rdy = 0;
                end else if (cpl_v) begin
                    log_cpl; jcyc[j] = cyc - cyc0; jcc[j] = cpl_cycles; jstat[j] = cpl_status; jdisp[j] = kd;
                    if (cpl_status == 4'd3) cov_st3 = cov_st3 + 1;
                    if (set == 2 && cpl_status == 4'd0) cov_ds = cov_ds + 1;
                    if (job_gold[j] && (cpl_token !== cfgw(set, c, 7) || cpl_status !== cfgw(set, c, 8) || kd !== cfgw(set, c, 6) ||
                                        nbeat !== (cfgw(set, c, 11) & 32'h1F))) begin
                        if (set != 2) $display("  token %0d/%0d status %0d/%0d dispatches %0d/%0d TOKX beats %0d/%0d", cpl_token, cfgw(set, c, 7),
                                 cpl_status, cfgw(set, c, 8), kd, cfgw(set, c, 6), nbeat, cfgw(set, c, 11) & 32'h1F);
                        // DS set: the committed hgi_seq_cfg_ds.mem predates RTL changes (some layers no longer fault): counted, not failed
                        if (set == 2) n_ds_stale = n_ds_stale + 1;
                        else `EFAIL("completion differs from the vector reference")
                    end
                    if (mode != 0) begin rc = xs(rc); repeat ((mode == 1) ? (rc[15:8] % 3) : rc[11:8]) @(negedge clk); end
                    cpl_rdy = 1; @(negedge clk); cpl_rdy = 0; fin = 1;
                end else @(negedge clk);
                t = t + 1;
                if (t > 3000000) `EFAIL("timeout: no completion")
            end
            jd1[j] = nd_tot; jv1[j] = nv_tot; jc1[j] = nc_tot;
            prev_set = set; prev_n0 = n0; prev_kd = kd;
            jobs_done = j + 1;
        end
        t = 0; while (busy && t < 50000) begin @(negedge clk); t = t + 1; end
        if (busy) `EFAIL("busy does not fall at the end")
        repeat (4) @(negedge clk);
        all_done = 1;
    end
endmodule

module tb_hgi_seq_split;
    localparam integer MAXJOB = 1024, DW = 2413, CW = 79;
    reg clk = 0; always #1 clk = ~clk;
    hgi_seq_split_env #(.SIDE(0)) A (.clk(clk));
    hgi_seq_split_env #(.SIDE(1)) B (.clk(clk));
    integer cmpj = 0, tx = 0, i, nA, nB, nmin, s, c, m, np, tcyc = 0;
    reg failed = 0, vexact;
    reg [DW-1:0] da, db; reg [CW-1:0] ca, cb;
    integer accA [0:4*128-1]; integer accB [0:4*128-1]; integer accN [0:4*128-1];
    integer totA [0:11]; integer totB [0:11];
    integer sumA = 0, sumB = 0, cov_rst_mid, cov_rst_idle;
    initial begin
        for (i = 0; i < 4*128; i = i + 1) begin accA[i] = 0; accB[i] = 0; accN[i] = 0; end
        for (i = 0; i < 12; i = i + 1) begin totA[i] = 0; totB[i] = 0; end
    end
`define TFAIL(MSG) begin if (!failed && !A.failed && !B.failed) begin $display("HGI_SEQ_SPLIT FAIL job %0d (set %0d case %0d mode %0d): %s", \
        cmpj, A.job_set[cmpj], A.job_c[cmpj], A.job_mode[cmpj], MSG); end failed = 1; end
    function automatic [8*5-1:0] sname(input integer q); sname = (q == 0) ? "base" : (q == 1) ? "conf" : (q == 2) ? "ds" : "g24"; endfunction
    task automatic cmp_job(input integer j);
        integer e, jj;
        begin
            if (A.jrst[j] !== B.jrst[j]) `TFAIL("mid-job reset on one side only")
            if (A.jdbn[j] != 1 || B.jdbn[j] != 1 || A.jdb[j] !== B.jdb[j]) begin
                $display("  doorbell accepts flat %0d split %0d payload %h / %h", A.jdbn[j], B.jdbn[j], A.jdb[j], B.jdb[j]);
                `TFAIL("doorbell accept")
            end
            tx = tx + 1;
            if (j > 0 && (A.jd0[j] != A.jd1[j-1] || B.jd0[j] != B.jd1[j-1])) `TFAIL("a dispatch outside a job")
            if (j > 0 && (A.jv0[j] != A.jv1[j-1] || B.jv0[j] != B.jv1[j-1])) `TFAIL("a VM read outside a job")
            if (j > 0 && (A.jc0[j] != A.jc1[j-1] || B.jc0[j] != B.jc1[j-1])) `TFAIL("a completion outside a job")
            // dispatches
            nA = A.jd1[j] - A.jd0[j]; nB = B.jd1[j] - B.jd0[j]; nmin = (nA < nB) ? nA : nB;
            for (e = 0; e < nmin && !failed; e = e + 1) begin
                da = A.d_log[A.jd0[j] + e]; db = B.d_log[B.jd0[j] + e];
                if (da !== db) begin
                    $display("  dispatch %0d of the job: u_v %h/%h hdr %0d sut %0d n %0d pos1 %0d pslot1 %0d L %0d/%0d L1 %0d/%0d (1 = equal)", e,
                        da[2412:2397], db[2412:2397], da[127:0] === db[127:0], da[383:128] === db[383:128],
                        da[2322:2176] === db[2322:2176], da[2343:2323] === db[2343:2323], da[2364:2344] === db[2364:2344],
                        da[2380:2365], db[2380:2365], da[2396:2381], db[2396:2381]);
                    for (jj = 0; jj < 7; jj = jj + 1) if (da[384 + jj*256 +: 256] !== db[384 + jj*256 +: 256])
                        $display("  descriptor %0d: flat %h split %h", jj, da[384 + jj*256 +: 256], db[384 + jj*256 +: 256]);
                    `TFAIL("dispatch mismatch")
                end
                tx = tx + 1;
            end
            if (nA != nB && !failed) begin
                $display("  dispatches flat %0d split %0d", nA, nB);
                `TFAIL("dispatch count")
            end
            // completions
            nA = A.jc1[j] - A.jc0[j]; nB = B.jc1[j] - B.jc0[j]; nmin = (nA < nB) ? nA : nB;
            for (e = 0; e < nmin && !failed; e = e + 1) begin
                ca = A.c_log[A.jc0[j] + e]; cb = B.c_log[B.jc0[j] + e];
                if (ca !== cb) begin
                    $display("  completion beat %0d: flat tokx %0d token %0d pos %0d job %h gen %h status %0d / split tokx %0d token %0d pos %0d job %h gen %h status %0d",
                        e, ca[78], ca[77:60], ca[59:40], ca[39:8], ca[7:4], ca[3:0], cb[78], cb[77:60], cb[59:40], cb[39:8], cb[7:4], cb[3:0]);
                    `TFAIL("completion mismatch")
                end
                tx = tx + 1;
            end
            if (nA != nB && !failed) begin
                $display("  completion beats flat %0d split %0d", nA, nB);
                `TFAIL("completion count")
            end
            // VM reads (prefix only when the job was cut asynchronously: unit fault or mid-job reset)
            vexact = !A.jrst[j] && (A.jstat[j] == 4'd0 || A.jstat[j] == 4'd3);
            nA = A.jv1[j] - A.jv0[j]; nB = B.jv1[j] - B.jv0[j]; nmin = (nA < nB) ? nA : nB;
            for (e = 0; e < nmin && !failed; e = e + 1) begin
                if (A.v_log[A.jv0[j] + e] !== B.v_log[B.jv0[j] + e]) begin
                    $display("  VM read %0d of the job: flat %h split %h", e, A.v_log[A.jv0[j] + e], B.v_log[B.jv0[j] + e]);
                    `TFAIL("VM read mismatch")
                end
                tx = tx + 1;
            end
            if (vexact && nA != nB && !failed) begin
                $display("  VM reads flat %0d split %0d", nA, nB);
                `TFAIL("VM read count")
            end
            // fetch
            if (!failed && (A.jf_seen[j] !== B.jf_seen[j] || (A.jf_seen[j] && A.jf_first[j] !== B.jf_first[j]))) begin
                $display("  fetch flat seen %0d first %h (%0d requests) split seen %0d first %h (%0d requests)", A.jf_seen[j],
                         A.jf_first[j], A.jf_cnt[j], B.jf_seen[j], B.jf_first[j], B.jf_cnt[j]);
                `TFAIL("fetch mismatch")
            end
            if (A.jf_seen[j]) tx = tx + 1;
            if (!A.jrst[j] && A.job_tp[j]) begin
                s = A.job_set[j]; c = A.job_c[j]; m = A.job_mode[j];
                accA[s*128 + c] = accA[s*128 + c] + A.jcyc[j]; accB[s*128 + c] = accB[s*128 + c] + B.jcyc[j];
                accN[s*128 + c] = accN[s*128 + c] + 1;
                totA[m*4 + s] = totA[m*4 + s] + A.jcyc[j]; totB[m*4 + s] = totB[m*4 + s] + B.jcyc[j];
                sumA = sumA + A.jcyc[j]; sumB = sumB + B.jcyc[j];
            end
        end
    endtask
    task automatic report;
        integer rs, rc2, rm;
        begin
            cov_rst_mid = A.n_rst_mid; cov_rst_idle = A.n_rst_idle;
            $display("SPLIT_COV indexed_reinject=%0d nested_loop=%0d fence=%0d loop_from_vm=%0d queue_full=%0d unit_fault_abort=%0d back_to_back_outstanding=%0d ds_jobs_ok=%0d tokx_beats=%0d status3=%0d reset_mid_job=%0d reset_idle=%0d jobs=%0d ds_cfg_stale=%0d",
                A.cov_inj, A.cov_nest, A.cov_fence, A.cov_lvm, A.cov_qfull, A.cov_abort, A.cov_b2b, A.cov_ds, A.cov_tokx,
                A.cov_st3, cov_rst_mid, cov_rst_idle, A.njob, A.n_ds_stale);
            np = 0;
            for (rs = 0; rs < 4; rs = rs + 1) for (rc2 = 0; rc2 < 128; rc2 = rc2 + 1) if (accN[rs*128 + rc2] != 0) begin
                np = np + 1;
                $display("SPLIT_TPUT %0s.c%0d flat=%0d split=%0d ratio=%0.4f", sname(rs), rc2, accA[rs*128 + rc2], accB[rs*128 + rc2],
                         (accA[rs*128 + rc2] == 0) ? 1.0 : (1.0 * accB[rs*128 + rc2]) / accA[rs*128 + rc2]);
            end
            for (rm = 0; rm < 3; rm = rm + 1) for (rs = 0; rs < 4; rs = rs + 1) if (totA[rm*4 + rs] != 0)
                $display("SPLIT_TPUT %0s.mode%0d flat=%0d split=%0d ratio=%0.4f", sname(rs), rm, totA[rm*4 + rs], totB[rm*4 + rs],
                         (1.0 * totB[rm*4 + rs]) / totA[rm*4 + rs]);
            if (A.cov_inj < 1) $display("HGI_SEQ_SPLIT FAIL coverage indexed record (re-injection)");
            else if (A.cov_nest < 1) $display("HGI_SEQ_SPLIT FAIL coverage nested loop");
            else if (A.cov_fence < 1) $display("HGI_SEQ_SPLIT FAIL coverage FENCE");
            else if (A.cov_lvm < 1) $display("HGI_SEQ_SPLIT FAIL coverage LOOP-from-VM");
            else if (A.cov_qfull < 1) $display("HGI_SEQ_SPLIT FAIL coverage record queue full");
            else if (A.cov_abort < 1) $display("HGI_SEQ_SPLIT FAIL coverage job aborted by a unit fault");
            else if (A.cov_b2b < 1) $display("HGI_SEQ_SPLIT FAIL coverage two jobs back to back with outstanding state");
            else if (A.cov_ds < 1) $display("HGI_SEQ_SPLIT FAIL coverage DS image job");
            else if (cov_rst_mid < 1 || cov_rst_idle < 1) $display("HGI_SEQ_SPLIT FAIL coverage reset (mid-job %0d, idle %0d)", cov_rst_mid, cov_rst_idle);
            else if (totA[2] != 0 && totB[2] * 1000 > totA[2] * `RATIO_MAX_PM)
                $display("HGI_SEQ_SPLIT FAIL tput DS mode-0 cycles flat %0d split %0d ratio %0.4f > %0.3f", totA[2], totB[2],
                         (1.0 * totB[2]) / totA[2], `RATIO_MAX_PM / 1000.0);
            else if (totA[2] == 0) $display("HGI_SEQ_SPLIT FAIL coverage DS mode-0 throughput (mode 0 not run)");
            else $display("HGI_SEQ_SPLIT PASS programs=%0d tx=%0d cycles_flat=%0d cycles_split=%0d ratio=%0.4f", np, tx, sumA, sumB,
                          (1.0 * sumB) / sumA);
        end
    endtask
    always @(posedge clk) begin
        tcyc = tcyc + 1;
        if (!failed && !A.failed && !B.failed) begin
            if (B.seam_seen) begin $display("HGI_SEQ_SPLIT FAIL seam_err raised in side B (job %0d on side B)", B.cur_j); failed = 1; end
            while (!failed && cmpj < A.jobs_done && cmpj < B.jobs_done) begin cmp_job(cmpj); if (!failed) cmpj = cmpj + 1; end
            if (!failed && A.all_done && B.all_done && A.ready && cmpj == A.njob) begin report; failed = 1; $finish; end
            if (!failed && tcyc > 400000000) begin $display("HGI_SEQ_SPLIT FAIL timeout (compared %0d jobs)", cmpj); failed = 1; end
            if (failed) $finish;
        end
    end
endmodule
