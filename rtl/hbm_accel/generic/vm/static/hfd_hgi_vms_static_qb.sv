// parameterised in NC / RG / WG / sid); these wrappers only fix the parameters and the strap sid.  Each hub still serves
// only its own 8 banks (bk_* ports); the VM ring stays the cross-quadrant (XQ) lane.  No credits / ready: static slots.
//   hfd_hgi_vms_static_<Q>b       full slice (banks inside, STRAP_BANKS=1 -> q0-shape physical banks with sid = <Q>):
