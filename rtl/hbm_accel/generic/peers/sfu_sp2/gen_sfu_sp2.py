#!/usr/bin/env python3
"""HBM-P5-RTLA (2026-10-23): generate the store-side pin-register twin (_sp2) of ot_hgi_sfu_core_split3.

The over-cap split (physical/die_plan/hbm/over_cap_split/ot_hgi_sfu_core_split3.split.json) cuts the SFU core into 16
lane cores, 2 operand-store cores and 1 control core.  In the pinned unit the store side of the lane <-> store crossing
is unregistered (lane rd regs -> bank crossbar -> SRAM; SRAM Q -> crossbar -> lane CAPR register; lane vm regs ->
output-group crossbar -> SRAM).  The twin registers the store side of every one of those pins:
  * operand read request (rd_re / rd_addr / rd_src) +1 edge, read data (rd_q) +1 edge  => operand read latency +2;
  * lane output-group write (vm_we / vm_waddr / vm_wdata) +1 edge.
The lane captures the operand words with its read tags delayed by RDX = 2 more edges (ot_hdc_v41x_vec_lane_sp2), so
every element flows 2 edges later through the lane, writes land 3 edges later; with every op's control held stable
through its drain horizon (sfu_vector_calendar) the compiler adds +3 edges to the op horizon.  No pinned file is edited:
the lane twin is generated from the CLOSED lane source (ae5899467 physical/ref_tile/sfu_lane_ring3_rt, the source
run_sfu_static_engine.sh binds); the grid / quarter / engine / split2 / split3 twins are the pinned files with module
names renamed.  Usage: gen_sfu_sp2.py FROZEN_LANE_C12 FROZEN_SU_C12_PHYS OUT_DIR  (repo root = cwd)."""
import re, sys
from pathlib import Path

lane_src, phys_src, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
P = Path('rtl/hbm_accel/generic/peers')
HDR = ('// GENERATED by rtl/hbm_accel/generic/peers/sfu_sp2/gen_sfu_sp2.py (HBM-P5-RTLA 2026-10-23) from {src}.\n'
       '// Store-side pin-register twin of the SFU core split (edits marked HBM-P5-RTLA).  Do not edit by hand.\n')


def module(text, name):
    m = re.search(r'^module %s\b.*?^endmodule\b' % re.escape(name), text, re.S | re.M)
    assert m, name
    return m.group(0)


def sub1(text, old, new):
    assert text.count(old) == 1, (old, text.count(old))
    return text.replace(old, new)


# ---- lane: tags delayed RDX edges in front of the CAPR register --------------------------------------------------
lane = module(lane_src.read_text(), 'ot_hdc_v41x_vec_lane')
lane = sub1(lane, 'module ot_hdc_v41x_vec_lane #(', 'module ot_hdc_v41x_vec_lane_sp2 #(\n'
            '    parameter integer RDX = 2,          // HBM-P5-RTLA: store-side pin registers add RDX edges to the operand read\n')
lane = sub1(lane, """        always @(posedge clk or negedge rst_n) begin
            if (!rst_n) cr_v <= 1'b0; else cr_v <= m_v;
        end
        always @(posedge clk) begin cr_o <= m_o; cr_par <= m_par; cr_q <= rd_q; end""",
"""        // HBM-P5-RTLA: the store registers the request (+1) and the data (+1): the read tags wait RDX edges more so
        // the CAPR register pairs each word with its own tag (bench mutant OT_SFU_SP2_MUT_RDX1: one edge short)
`ifdef OT_SFU_SP2_MUT_RDX1
        localparam integer RDXE = RDX - 1;
`else
        localparam integer RDXE = RDX;
`endif
        reg [RDXE:0] dl_v; reg [AW-1:0] dl_o [0:RDXE]; reg [RDXE:0] dl_par;
        always @* begin dl_v[0] = m_v; dl_o[0] = m_o; dl_par[0] = m_par; end
        for (genvar gd = 1; gd <= RDXE; gd = gd + 1) begin : g_rdx
            always @(posedge clk or negedge rst_n) if (!rst_n) dl_v[gd] <= 1'b0; else dl_v[gd] <= dl_v[gd-1];
            always @(posedge clk) begin dl_o[gd] <= dl_o[gd-1]; dl_par[gd] <= dl_par[gd-1]; end
        end
        always @(posedge clk or negedge rst_n) begin
            if (!rst_n) cr_v <= 1'b0; else cr_v <= dl_v[RDXE];
        end
        always @(posedge clk) begin cr_o <= dl_o[RDXE]; cr_par <= dl_par[RDXE]; cr_q <= rd_q; end""")
phys = phys_src.read_text()
sul = module(phys, 'ot_su12_lane')
sul = sub1(sul, 'module ot_su12_lane #(', 'module ot_su12_lane_sp2 #(\n    parameter integer RDX = 2,')
sul = sub1(sul, 'ot_hdc_v41x_vec_lane #(.AW(24)', 'ot_hdc_v41x_vec_lane_sp2 #(.RDX(RDX), .AW(24)')
sus = module(phys, 'ot_su12_sfu')
sus = sub1(sus, 'module ot_su12_sfu #(', 'module ot_su12_sfu_sp2 #(')
sus = sub1(sus, 'ot_su12_lane #(.KIND(1)', 'ot_su12_lane_sp2 #(.KIND(1)')
(out / 'ot_su12_sfu_sp2.sv').write_text(HDR.format(src=f'{lane_src} + {phys_src}') + '`timescale 1ns/1ps\n'
                                        + lane + '\n\n' + sul + '\n\n' + sus + '\n')

# ---- renamed hierarchy ------------------------------------------------------------------------------------------------
REN = [('ot_hgi_sfu_core_split3', 'ot_hgi_sfu_core_split3_sp2'), ('ot_hgi_sfu_core_split2', 'ot_hgi_sfu_core_split2_sp2'),
       ('ot_hgi_sfu_static_engine', 'ot_hgi_sfu_static_engine_sp2'),
       ('ot_hgi_sfu_static_quarter', 'ot_hgi_sfu_static_quarter_sp2'),
       ('ot_hgi_sfu_arithmetic_grid', 'ot_hgi_sfu_arithmetic_grid_sp2'),
       ('ot_hgi_sfu_static_operand_store', 'ot_hgi_sfu_static_operand_store_sp2'), ('ot_su12_sfu', 'ot_su12_sfu_sp2')]
for f in ['ot_hgi_sfu_core_split3', 'ot_hgi_sfu_core_split2', 'ot_hgi_sfu_static_engine', 'ot_hgi_sfu_static_quarter',
          'ot_hgi_sfu_arithmetic_grid']:
    t = (P / f'{f}.sv').read_text()
    for a, b in REN:
        t = re.sub(r'\b%s\b' % a, b, t)
    (out / f'{f}_sp2.sv').write_text(HDR.format(src=P / f'{f}.sv') + t)

# ---- operand store twin: the pinned store behind its store-side pin registers ------------------------------------------
(out / 'ot_hgi_sfu_static_operand_store_sp2.sv').write_text(HDR.format(src=P / 'ot_hgi_sfu_static_operand_store.sv') + r"""`timescale 1ns/1ps
`default_nettype none
`ifndef OT_SFU_ARST
`ifdef OT_SFU_SYNC_RST
`define OT_SFU_ARST(r)
`else
`define OT_SFU_ARST(r) or negedge r
`endif
`endif
// HBM-P5-RTLA: the pinned ot_hgi_sfu_static_operand_store with a register on every lane-facing store pin.  In the core
// split each group's pin registers sit in that group's opstore core (rd_*[4*l+g] with operand group g, rd_q likewise;
// vm_* with the output group): the lane <-> store crossings become REG -> REG.
//   rd_re / rd_addr / rd_src  +1 edge (request pin)    rd_q  +1 edge (data pin)   => operand read latency +2 edges
//   vm_we / vm_waddr / vm_wdata  +1 edge (output-group write pin)
// stage / drain / scalar ports are the control core's (unchanged).
module ot_hgi_sfu_static_operand_store_sp2 #(
 parameter integer LWB=15, MUT_XBAR=0
)(
 input wire clk,rst_n,
 input wire [3:0] scalar_load,scalar_enable,
 input wire [95:0] scalar_addr,
 input wire [127:0] scalar_data,
 input wire [63:0] rd_re,
 input wire [1535:0] rd_addr,
 input wire [127:0] rd_src,
 output reg [2047:0] rd_q,
 input wire [15:0] vm_we,
 input wire [383:0] vm_waddr,
 input wire [511:0] vm_wdata,
 input wire [7:0] stage_v,
 input wire [15:0] stage_group,
 input wire [8*LWB-1:0] stage_addr,
 input wire [63:0] stage_mask,
 input wire [2047:0] stage_data,
 input wire [1:0] drain_v,
 input wire [2*LWB-1:0] drain_addr,
 output wire [511:0] drain_data,
 output wire [1:0] drain_result_v,
 output wire fault
);
 reg [63:0] rd_re_q; reg [1535:0] rd_addr_q; reg [127:0] rd_src_q;
 reg [15:0] vm_we_q; reg [383:0] vm_waddr_q; reg [511:0] vm_wdata_q;
 wire [2047:0] rd_q_s;
 always @(posedge clk `OT_SFU_ARST(rst_n))
  if(!rst_n)begin rd_re_q<=0;vm_we_q<=0;end else begin rd_re_q<=rd_re;vm_we_q<=vm_we;end
 always @(posedge clk)begin
  rd_addr_q<=rd_addr;rd_src_q<=rd_src;vm_waddr_q<=vm_waddr;vm_wdata_q<=vm_wdata;rd_q<=rd_q_s;
 end
 ot_hgi_sfu_static_operand_store #(.LWB(LWB),.MUT_XBAR(MUT_XBAR)) u_store(
  .clk(clk),.rst_n(rst_n),.scalar_load(scalar_load),.scalar_enable(scalar_enable),.scalar_addr(scalar_addr),.scalar_data(scalar_data),
  .rd_re(rd_re_q),.rd_addr(rd_addr_q),.rd_src(rd_src_q),.rd_q(rd_q_s),
  .vm_we(vm_we_q),.vm_waddr(vm_waddr_q),.vm_wdata(vm_wdata_q),
  .stage_v(stage_v),.stage_group(stage_group),.stage_addr(stage_addr),.stage_mask(stage_mask),.stage_data(stage_data),
  .drain_v(drain_v),.drain_addr(drain_addr),.drain_data(drain_data),.drain_result_v(drain_result_v),.fault(fault));
endmodule
`default_nettype wire
""")
print('SFU_SP2_GENERATED', sorted(p.name for p in out.glob('*.sv')))
