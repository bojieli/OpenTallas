#!/usr/bin/env python3
"""DIE-HBM-61/SPLIT 11-03 (OWNER TWO-STRIKES RE-FORM, HBM-RF1 / d44v): ot_hgi_sfu_split3_lane_core__idpin
(one SFU lane = ot_hgi_sfu_lane_map + ot_su12_sfu_sp2 KIND 1, 253k ASAP7 cells > 150k) cut on its PIPELINE-STAGE
boundaries into three hardened sub-blocks (one SFU lane = fr + ex + bk; every lane of the 16-lane grid identical):

  _fr  map + lane broadcast register + F0 / G1 / G2 / reads / X / PRE / M1 / M2 / AD   (map_clk + sfu_clk, as the uncut
       core; all vector / constant / weight memory ports stay here: the gather / read loop is NOT shifted)
  _ex  the SFU exponential unit ot_hdc_v41x_exp (LM 6, LA 6; D_EXP = 94 edges)             (sfu_clk)
  _bk  rest of S (sigmoid den add, numerator line, divider, S insertion line u_l4), E1, E2, OUT, status (sfu_clk)

Crossings (every one register to register: the kit face shell puts one flop per pin bit on each side, +2 edges):
  fr -> ex : exp operand {v, x} (33 b)                         +2
  ex -> bk : exp result {y, fault} (33 b)                      +2   (y reaches bk +4 after the uncut S-in edge)
  fr -> bk : the S-in bus (v3, R, B, C', O, S/E1/E2/OUT control, front fault + collision; 201 b)  +2, then a 2-edge
             pure alignment line inside bk (ALIGN = 2) so the whole bk pipeline runs exactly 4 edges behind the uncut one.
Result (declared cycle-shift map): every bk output (vm_we/waddr/wdata, kv_we/waddr/wdata, ro_v/ro_x, fault, coll) is
the uncut output 4 edges later; every fr output (vi_re/vi_addr, rd_addr/rd_re/rd_src) is unshifted.  Same words,
same order, same addresses.  The reads cannot run ahead of a write by fewer edges than before: the controller's
write->read hazard distance grows by +4 (the latency table row; the parent controller prices it like DENR).

Usage: gen_split3_lane.py SRC_DIR OUT_DIR
  SRC_DIR holds ot_su12_sfu_sp2.sv (rtl/hbm_accel/generic/peers/sfu_sp2) and ot_hgi_sfu_split3_lane_core.sv
  (rtl/hbm_accel/cores_split/ot_hgi_sfu_core_split3); both are read, never edited.
MUT (bench only, parameter of _bk): 1 = ALIGN 1 (bk one edge early against the exp result), 2 = the front fault
term dropped from the status OR, 3 = the fr -> ex operand without the sign flip for sigmoid.
"""
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
lane = open(os.path.join(src, 'ot_su12_sfu_sp2.sv')).read().split('\n')
core = open(os.path.join(src, 'ot_hgi_sfu_split3_lane_core.sv')).read()


def find(pat, start=0):
    for i in range(start, len(lane)):
        if re.search(pat, lane[i]):
            return i
    raise SystemExit(f'pattern not found: {pat}')


i_mod = find(r'^module ot_hdc_v41x_vec_lane_sp2 #\(')
i_side = find(r'^    // ---- scalar side pipe \(lane 0\)', i_mod)
i_hend = find(r'^\);', i_side)
i_s = find(r'^    // ---- S -----', i_hend)
i_e1 = find(r'^    // ---- E1 -----', i_s)
i_stat = find(r'^    // ---- status -----', i_e1)
i_end = find(r'^endmodule', i_stat)
i_lane = find(r'^module ot_su12_lane_sp2 #\(')
i_lend = find(r'^endmodule', i_lane)
i_sfu = find(r'^module ot_su12_sfu_sp2 #\(')
i_send = find(r'^endmodule', i_sfu)
hdr = lane[i_mod:i_side]                        # module line .. memory + control ports
loc_from = i_hend + 1                           # localparams, functions, traps, LEAF ... AD
CTL = [('ci_sfu', 3), ('cs_sfu', 3), ('cs_e1', 3), ('cs_imm2', 32), ('ce_e2', 2), ('ce_imm1', 32), ('co_rnd', 1),
       ('co_dst', 2)]
BW = 1 + 32 * 3 + 24 + sum(w for _, w in CTL) + 2
assert BW == 201, BW
G = '// GENERATED by rtl/hbm_accel/cores_split/reform_1103/ot_hgi_sfu_split3_lane_core__idpin/gen_split3_lane.py (DIE-HBM-61/SPLIT 11-03). Do not edit.'

# ---------------------------------------------------------------- front lane (vec_lane_sp2_fr)
fr = [G, '`timescale 1ns/1ps']
fr += [hdr[0].replace('ot_hdc_v41x_vec_lane_sp2', 'ot_hdc_v41x_vec_lane_sp2_fr')] + hdr[1:]
fr += ['    // ---- DIE-HBM-61/SPLIT: the S-in cut (to _ex and _bk)',
       '    output wire              x_exp_v,', '    output wire [31:0]       x_exp_x,',
       f'    output wire [{BW-1}:0]      x_bus', ');']
fr += lane[loc_from:i_s]
fr += ['    // ---- DIE-HBM-61/SPLIT cut at S in: the exp operand (to _ex) and the S-in bus (to _bk) ----------------',
       '    wire is_exp_x = (ci_sfu == SFU_EXP), is_sig_x = (ci_sfu == SFU_SIGM || ci_sfu == SFU_SILU);',
       '    assign x_exp_v = v3 && (is_exp_x || is_sig_x);',
       '    assign x_exp_x = (is_exp_x || MUT == 3) ? R : {~R[31], R[30:0]};',
       '    assign x_bus = {v3, R, r_b, r_c, r_o, ' + ', '.join(n for n, _ in CTL) + ', f_m1 | f_d1 | f_m2 | f_q | f_ad, c1};',
       'endmodule', '']
fr = '\n'.join(fr)
fr = fr.replace('    parameter integer DRING = 0 ', '    parameter integer MUT = 0,\n    parameter integer DRING = 0 ', 1)
assert 'parameter integer MUT = 0' in fr

# lane wrapper (broadcast register b_q) + sfu wrapper for the front
lw = '\n'.join(lane[i_lane:i_lend + 1])
lw = lw.replace('module ot_su12_lane_sp2 #(', 'module ot_su12_lane_sp2_fr #(\n    parameter integer MUT = 0,')
lw = re.sub(r'\n    output wire side_v, output wire \[31:0\] side_x, input wire \[31:0\] side_y\n\);',
            f'\n    output wire x_exp_v, output wire [31:0] x_exp_x, output wire [{BW-1}:0] x_bus\n);', lw)
lw = lw.replace('output wire vm_we, output wire [23:0] vm_waddr, output wire [31:0] vm_wdata, output wire kv_we,\n'
                '    output wire [23:0] kv_waddr, output wire [31:0] kv_wdata, output wire ro_v, output wire [31:0] ro_x,\n'
                '    output wire fault, output wire coll,\n', '')
lw = lw.replace('ot_hdc_v41x_vec_lane_sp2 #(.RDX(RDX)', 'ot_hdc_v41x_vec_lane_sp2_fr #(.MUT(MUT), .RDX(RDX)')
lw = re.sub(r'\n        \.side_v\(side_v\), \.side_x\(side_x\), \.side_y\(side_y\),\n        \.vm_we\(vm_we\).*?\.coll\(coll\)\);',
            '\n        .x_exp_v(x_exp_v), .x_exp_x(x_exp_x), .x_bus(x_bus));', lw, flags=re.S)
assert 'x_bus(x_bus)' in lw and 'vm_we' not in lw, lw[-800:]
sw = '\n'.join(lane[i_sfu:i_send + 1])
sw = sw.replace('module ot_su12_sfu_sp2 #(parameter integer GSH = 0,', 'module ot_su12_sfu_sp2_fr #(parameter integer MUT = 0, parameter integer GSH = 0,')
sw = sw.replace('output wire vm_we, output wire [23:0] vm_waddr, output wire [31:0] vm_wdata, output wire kv_we,\n'
                '    output wire [23:0] kv_waddr, output wire [31:0] kv_wdata, output wire ro_v, output wire [31:0] ro_x,\n'
                '    output wire fault, output wire coll,\n', '')
sw = sw.replace('    output wire side_v, output wire [31:0] side_x, input wire [31:0] side_y\n);',
                f'    output wire x_exp_v, output wire [31:0] x_exp_x, output wire [{BW-1}:0] x_bus\n);')
sw = sw.replace('ot_su12_lane_sp2 #(.KIND(1)', 'ot_su12_lane_sp2_fr #(.MUT(MUT), .KIND(1)')
sw = re.sub(r'\.vm_we\(vm_we\),.*?\.side_y\(32\'d0\)\);', '.x_exp_v(x_exp_v), .x_exp_x(x_exp_x), .x_bus(x_bus));', sw, flags=re.S)
sw = re.sub(r'\n    // DIE-HBM-47 \(RTL lint\).*?assign side_x = 32\'d0;', '', sw, flags=re.S)
assert 'side_' not in sw and 'x_bus(x_bus)' in sw, sw

# core-level _fr (map + front)
c = core
c = re.sub(r'^// GENERATED by .*?\n(?=`timescale)', G + '\n// Front of ot_hgi_sfu_split3_lane_core (generated from it): map + SFU lane front, cut at S in.\n', c, flags=re.S)
c = c.replace('module ot_hgi_sfu_split3_lane_core (', 'module ot_hgi_sfu_split3_lane_core_fr #(parameter integer MUT = 0) (')
c = re.sub(r'    output wire sfu_vm_we,.*?    output wire sfu_coll\n\);',
           f'    output wire x_exp_v,\n    output wire [31:0] x_exp_x,\n    output wire [{BW-1}:0] x_bus\n);', c, flags=re.S)
c = c.replace('ot_su12_sfu_sp2 #(.GSH(1)', 'ot_su12_sfu_sp2_fr #(.MUT(MUT), .GSH(1)')
c = re.sub(r'        \.vm_we\(u_sfu__vm_we\),.*?\.side_y\(u_sfu__side_y\)\);',
           '        .x_exp_v(x_exp_v),\n        .x_exp_x(x_exp_x),\n        .x_bus(x_bus));', c, flags=re.S)
c = re.sub(r'    assign sfu_vm_we = .*?    assign sfu_coll = u_sfu__coll;\n', '', c, flags=re.S)
c = re.sub(r'    wire \[31:0\] u_sfu__side_y = .*?\n', '', c)
for n in ['vm_we', 'vm_waddr', 'vm_wdata', 'kv_we', 'kv_waddr', 'kv_wdata', 'ro_v', 'ro_x', 'fault', 'coll', 'side_v', 'side_x']:
    c = re.sub(r'    wire (\[\d+:0\] )?u_sfu__%s;\n' % n, '', c)
assert 'sfu_vm_we' not in c and 'u_sfu__fault' not in c and 'x_bus(x_bus)' in c
open(os.path.join(out, 'ot_hgi_sfu_split3_lane_core_fr.sv'), 'w').write(c + '\n' + fr + '\n' + lw + '\n\n' + sw + '\n')

# ---------------------------------------------------------------- exp sub-block
ex = f'''{G}
`timescale 1ns/1ps
`default_nettype none
// The SFU lane's exponential unit (ot_hdc_v41x_exp LM 6 / LA 6 of ot_su12_sfu_sp2 KIND 1), hardened on its own.
module ot_hgi_sfu_split3_lane_core_ex (
    input  wire        sfu_clk,
    input  wire        sfu_rst_n,
    input  wire        x_exp_v,
    input  wire [31:0] x_exp_x,
    output wire [31:0] x_exp_y,
    output wire        x_exp_f
);
    ot_hdc_v41x_exp #(.LM(6), .LA(6)) u_exp (.clk(sfu_clk), .rst_n(sfu_rst_n), .v(x_exp_v), .x(x_exp_x), .y(x_exp_y),
                                           .vo(), .fault(x_exp_f));
endmodule
`default_nettype wire
'''
open(os.path.join(out, 'ot_hgi_sfu_split3_lane_core_ex.sv'), 'w').write(ex)

# ---------------------------------------------------------------- back lane (vec_lane_sp2_bk)
params = '\n'.join(hdr[:hdr.index(') (')]) if ') (' in hdr else None
k = [i for i, l in enumerate(hdr) if l.strip() == ') (']
assert k, 'param list end'
params = hdr[:k[0]]
bk = [G, '`timescale 1ns/1ps']
bk += [params[0].replace('ot_hdc_v41x_vec_lane_sp2', 'ot_hdc_v41x_vec_lane_sp2_bk')] + params[1:]
bk += [') (', '    input  wire              clk,', '    input  wire              rst_n,',
       f'    input  wire [{BW-1}:0]      x_bus,           // S-in bus from _fr (face +2)',
       '    input  wire [31:0]       x_exp_y,         // exp result from _ex (face +2 +2)', '    input  wire              x_exp_f,',
       '    output reg               vm_we,', '    output reg  [AW-1:0]     vm_waddr,', '    output reg  [31:0]       vm_wdata,',
       '    output reg               kv_we,', '    output reg  [AW-1:0]     kv_waddr,', '    output reg  [31:0]       kv_wdata,',
       '    output wire              ro_v,', '    output wire [31:0]       ro_x,', '    output wire              fault,',
       '    output wire              coll', ');']
# localparams + functions + traps (up to the LEAF section)
i_leaf = find(r'^    // ---- LEAF: ', loc_from)
bk += lane[loc_from:i_leaf]
bk += ['    // ---- DIE-HBM-61/SPLIT: the S-in bus, aligned 2 more edges so it meets the exp result (fr->ex->bk = +4) ---',
       '    localparam integer ALIGN = (MUT == 1) ? 1 : 2;',
       f'    wire [{BW-1}:0] xb;',
       f'    ot_hdc_delay #(.W({BW}), .D(ALIGN)) u_align (.clk(clk), .rst_n(1\'b1), .d(x_bus), .q(xb));',
       '    wire v3; wire [31:0] R, r_b, r_c; wire [AW-1:0] r_o; wire f_front, c1;',
       '    wire [2:0] ci_sfu, cs_sfu, cs_e1; wire [31:0] cs_imm2, ce_imm1; wire [1:0] ce_e2, co_dst; wire co_rnd;',
       '    assign {v3, R, r_b, r_c, r_o, ' + ', '.join(n for n, _ in CTL) + ', f_front, c1} = xb;',
       '    wire [31:0] side_y = 32\'d0;              // ot_su12_sfu_sp2 ties the lane side_y 0']
body = lane[i_s:i_end]
txt = '\n'.join(body)
# the exp unit lives in _ex: its result / fault arrive on x_exp_y / x_exp_f, on the same (shifted) edge
txt, n = re.subn(r'            ot_hdc_v41x_exp #\(\.LM\(MLAT\), \.LA\(ALAT\)\) u_exp \(.*?\.fault\(f_e\)\);',
                 '            assign y_exp = x_exp_y; assign f_e = x_exp_f;   // DIE-HBM-61/SPLIT: u_exp is sub-block _ex',
                 txt, flags=re.S)
assert n == 1
# side pipe outputs are not lane-0 here (FULL 0): drop them
txt, n = re.subn(r'    wire side_vc = .*?    end endgenerate\n', '', txt, count=1, flags=re.S)
assert n == 1
txt, n = re.subn(r'f_m1 \| f_d1 \| f_m2 \| f_q \| f_ad \| f_sfu', "(MUT == 2 ? 1'b0 : f_front) | f_sfu", txt)
assert n == 1
bk += [txt, 'endmodule', '']
bk = '\n'.join(bk)
bk = bk.replace('    parameter integer DRING = 0 ', '    parameter integer MUT = 0,\n    parameter integer DRING = 0 ', 1)
bk += f'''
`default_nettype none
// Back of the SFU lane: rest of S, E1, E2, OUT, status (ot_su12_sfu_sp2 KIND 1 parameters).
module ot_hgi_sfu_split3_lane_core_bk #(parameter integer MUT = 0) (
    input  wire        sfu_clk,
    input  wire        sfu_rst_n,
    input  wire [{BW-1}:0] x_bus,
    input  wire [31:0] x_exp_y,
    input  wire        x_exp_f,
    output wire        sfu_vm_we,
    output wire [23:0] sfu_vm_waddr,
    output wire [31:0] sfu_vm_wdata,
    output wire        sfu_kv_we,
    output wire [23:0] sfu_kv_waddr,
    output wire [31:0] sfu_kv_wdata,
    output wire        sfu_ro_v,
    output wire [31:0] sfu_ro_x,
    output wire        sfu_fault,
    output wire        sfu_coll
);
    ot_hdc_v41x_vec_lane_sp2_bk #(.MUT(MUT), .RDX(2), .AW(24), .LN(10), .KIND(1), .LEAF(1), .MLAT(6), .ALAT(6), .OPR(1),
        .DDIV(21), .SIDEX(4), .CAPR(1), .GSH(1), .KIMM(1), .DENR(1), .DRING(3)) u (
        .clk(sfu_clk), .rst_n(sfu_rst_n), .x_bus(x_bus), .x_exp_y(x_exp_y), .x_exp_f(x_exp_f),
        .vm_we(sfu_vm_we), .vm_waddr(sfu_vm_waddr), .vm_wdata(sfu_vm_wdata), .kv_we(sfu_kv_we), .kv_waddr(sfu_kv_waddr),
        .kv_wdata(sfu_kv_wdata), .ro_v(sfu_ro_v), .ro_x(sfu_ro_x), .fault(sfu_fault), .coll(sfu_coll));
endmodule
`default_nettype wire
'''
open(os.path.join(out, 'ot_hgi_sfu_split3_lane_core_bk.sv'), 'w').write(bk)
print('BW', BW, 'written', out)
