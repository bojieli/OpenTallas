#!/usr/bin/env python3
"""Generate registered 65-bit partials without changing canonical KP4 coefficients."""
import argparse
from pathlib import Path
import re

p = argparse.ArgumentParser()
p.add_argument('matrix', type=Path)
p.add_argument('output', type=Path)
a = p.parse_args()
rows = re.findall(r"assign e_p([01])\[(\d+)\] = \^\(ch_q(?:\[.*?\])? & 260'h([0-9a-f]+)\);", a.matrix.read_text())
assert len(rows) == 600
out = ['// Generated by exact 65-bit slicing of canonical KP4 e_p0/e_p1 masks.\n// Each cq copy owns one 75-bit parity region; no coefficient changes.\n']
seen = set()
for h, o, m in rows:
    h, o, m = int(h), int(o), int(m, 16)
    assert (h, o) not in seen
    seen.add((h, o))
    slices = [(m >> (65*c)) & ((1 << 65)-1) for c in range(4)]
    assert m == sum(v << (65*c) for c, v in enumerate(slices))
    for c, v in enumerate(slices):
        out.append(f"assign fp[{h*4+c}][{o}] = ^(cq[{o//75}][{h*260+c*65} +: 65] & 65'h{v:017x});\n")
a.output.write_text(''.join(out))
print('PASS: 600 original rows reconstructed exactly from 2400 disjoint 65-bit masks')
