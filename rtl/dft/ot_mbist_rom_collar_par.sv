    assign fold_n[31] = (^(sig & 32'hc6655221)) ^ (^(rd_q & 274'h01344077d206d396bc60be81fad1b78bc5e0c28d31bc0195f3b8f5405d120844aa663));
`ifndef SYNTHESIS
    initial if (DW != 274) $fatal(1, "ot_mbist_rom_collar_par: masks are generated for DW = 274");
`endif
    assign m_ce   = t_en ? t_req : f_ce;
    assign m_addr = t_en ? t_addr[AW-1:0] : f_addr;
    assign f_rd   = m_rd;

    // The macro's read word is registered before the CRC fold, so the macro's
    // clock-to-output and the fold's XOR tree are in different cycles.
    reg pend, pend2;
    reg [DW-1:0] rd_q;
    always @(posedge clk) if (pend) rd_q <= m_rd;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pend <= 1'b0;
            pend2 <= 1'b0;
            sig <= 32'hFFFFFFFF;
        end else begin
            pend <= t_en & t_req;
            pend2 <= pend;
            if (t_en & t_clear) sig <= 32'hFFFFFFFF;
            else if (pend2) sig <= fold_n;
        end
    end
    assign sig_match = (sig == exp_sig);
    assign sig_busy = pend | pend2;
endmodule
