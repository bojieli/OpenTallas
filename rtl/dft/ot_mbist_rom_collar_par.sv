    assign fold_n[5] = (^(sig & 32'ha6f402b7)) ^ (^(rd_q & 274'h37c90723017a9dc575fcfc06944c663ddeeed8d35ae1d0bc225aecdb3f807ed402f65));
    assign fold_n[6] = (^(sig & 32'h4de8056f)) ^ (^(rd_q & 274'h1be4839180bd4ee2bafe7e034a26331eef776c69ad70e85e112d766d9fc03f6a017b2));
    assign fold_n[7] = (^(sig & 32'h171aae9d)) ^ (^(rd_q & 274'h2d6861f3295dceba034f6041587bc24a954bd7724e6674e5f14ac196e1691b97558e8));
    assign fold_n[8] = (^(sig & 32'ha2fff979)) ^ (^(rd_q & 274'h362e10c27dad8e965f97ef6051553ae0a8558affbfed3ab801791a6b5e3d89e9fff45));
    assign fold_n[9] = (^(sig & 32'h45fff2f2)) ^ (^(rd_q & 274'h1b1708613ed6c74b2fcbf7b028aa9d70542ac57fdff69d5c00bc8d35af1ec4f4fffa2));
