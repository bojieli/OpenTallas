    input  wire [3:0]    cs_d,
    output wire          hf_v,                                 // to the RO-side HFWD hold (relayed)
    output wire [511:0]  hf_d,
    input  wire          r_v,                                  // RESULT copy from the RO stage (relayed)
    input  wire [511:0]  r_d,
    output wire          f16b
);
    localparam [3:0] T_HFWD = 4'd7, T_RES = 4'd9;
    wire [1:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(2)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    reg hrv_q; reg [527:0] hrd_q;
    always @(posedge ck) hrd_q <= hrx_d[527:0];
    always @(posedge ck or negedge rr[0]) if (!rr[0]) hrv_q <= 1'b0; else hrv_q <= hrx_v;
    assign hf_v = hrv_q && hrd_q[3:0] == T_HFWD;
    assign hf_d = hrd_q[527:16];
    assign f16b = hrv_q && hrd_q[3:0] != T_HFWD;
    reg [1:0] c_rank, c_grp; reg htv_q; reg [552:0] htd_q;
    always @(posedge ck or negedge rr[1])
        if (!rr[1]) begin c_rank <= 2'd0; c_grp <= 2'd0; htv_q <= 1'b0; end
        else begin
            if (cs_rk) c_rank <= cs_d[1:0];
            if (cs_gp) c_grp <= cs_d[1:0];
            htv_q <= r_v;
        end
    always @(posedge ck) htd_q <= {1'b1, 24'd0, r_d, 8'd0, c_grp, c_rank, T_RES};
    assign htx_v = htv_q; assign htx_d = htd_q;
endmodule

// ================================================================== WH1: host lane 1 (CSR in, STATUS out), fault vector
module ot_s81hd_g_h1 (
    input  wire          ck, rn,
    input  wire          hrx_v,
    input  wire [552:0]  hrx_d,
    output wire          htx_v,
    output wire [552:0]  htx_d,
    // decoded CSR writes (registered; relayed to their zones)
    output reg           ce_pl, ce_gl, ce_rk, ce_gp, ce_rb, ce_hd, ce_cp, ce_run,
    output reg  [31:0]   csr_d,
    // seq accumulator (relayed from the N face)
    input  wire [56:0]   acc,
    // lane faults (relayed pin flops), lane order mesh 0..5, host 0..1, draft 0..4 (the original lflt)
    input  wire [51:0]   lflt,
    // fault events from the zones (relayed)
    input  wire          f0, f1, f2, f3, f4n, f4s, f5, f6, f7, f8, f9, f10, f13, f14, f15a, f15b, f16a, f16b, f16c,
    output reg           ctlf
);
    localparam [3:0] T_STAT = 4'd8, T_CSRW = 4'd6;
    wire [3:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(4)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    reg hrv_q; reg [87:0] hrd_q;
    always @(posedge ck) hrd_q <= hrx_d[87:0];
    always @(posedge ck or negedge rr[0]) if (!rr[0]) hrv_q <= 1'b0; else hrv_q <= hrx_v;
    wire csr_w = hrv_q && hrd_q[3:0] == T_CSRW;
    wire [7:0] csr_a = hrd_q[23:16];
    always @(posedge ck) begin
        csr_d <= hrd_q[55:24];
        ce_pl <= csr_w && csr_a == 8'd0; ce_gl <= csr_w && csr_a == 8'd1; ce_rk <= csr_w && csr_a == 8'd2;
        ce_gp <= csr_w && csr_a == 8'd3; ce_rb <= csr_w && csr_a == 8'd4; ce_hd <= csr_w && csr_a == 8'd5;
        ce_cp <= csr_w && csr_a == 8'd6; ce_run <= csr_w && csr_a == 8'd8;
    end
    reg [1:0] c_rank, c_grp;
    always @(posedge ck or negedge rr[1])
        if (!rr[1]) begin c_rank <= 2'd0; c_grp <= 2'd0; end
        else begin if (ce_rk) c_rank <= csr_d[1:0]; if (ce_gp) c_grp <= csr_d[1:0]; end
    wire stat_req = csr_w && csr_a == 8'd7;
    // STATUS
    wire [63:0] acc_h;
    ot_s81hd_hreg32 u_ah0 (.ck(ck), .en(acc[55]), .d(acc[31:0]), .q(acc_h[31:0]));
    ot_s81hd_hreg32 u_ah1 (.ck(ck), .en(acc[55]), .d({7'd0, acc[56:32]}), .q(acc_h[63:32]));
    reg [16:0] fv, fv_l, fset;
    always @(*) begin
        fset = 17'd0;
        fset[0] = f0; fset[1] = f1; fset[2] = f2; fset[3] = f3; fset[4] = f4n || f4s; fset[5] = f5; fset[6] = f6;
        fset[7] = f7; fset[8] = f8; fset[9] = f9; fset[10] = f10; fset[11] = acc[56]; fset[12] = |lflt; fset[13] = f13;
        fset[14] = f14; fset[15] = f15a || f15b;
        fset[16] = f16a || f16b || f16c || (hrv_q && hrd_q[3:0] != T_CSRW);
    end
    reg htv_q, spend, acc_l; reg [552:0] htd_q;
    wire s_send = spend && !htv_q;
    always @(posedge ck) htd_q <= {1'b1, 390'd0, c_grp, c_rank, acc_h[56:0], lflt, 16'd0, fv, 8'd0, c_grp, c_rank, T_STAT};
    always @(posedge ck or negedge rr[2])
        if (!rr[2]) begin htv_q <= 1'b0; spend <= 1'b0; acc_l <= 1'b0; fv_l <= 17'd0; end
        else begin
            htv_q <= s_send;
            acc_l <= acc[55];
            spend <= (spend && !s_send) || stat_req || acc_l || (fv != fv_l);
            fv_l <= fv;
        end
    always @(posedge ck or negedge rr[3]) if (!rr[3]) begin fv <= 17'd0; ctlf <= 1'b0; end
                                           else begin fv <= fv | fset; ctlf <= |fv; end
    assign htx_v = htv_q; assign htx_d = htd_q;
endmodule
