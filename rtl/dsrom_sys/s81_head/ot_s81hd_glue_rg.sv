// ================================================================== WL: lep face (INGEST, forward, RO stage, HFWD hold)
module ot_s81hd_g_wl (
    input  wire          ck, rn,
    input  wire [1103:0] ri,
    input  wire [31:0]   mu_rt,
    input  wire          lep_f,
    output wire [1103:0] ro,
    output wire [33:0]   mu_c,
    // CSR (relayed from WH1): group / ngroup (csr 3) and calendar (csr 6)
    input  wire          cs_gp,
    input  wire [1:0]    cs_cp,                                // two strobe copies (cper / coff, <= 32 loads each)
    input  wire [31:0]   cs_d,
    // x store write stream to the core (registered by the first relay stage = the original P2 edge)
    output wire          xs_v,
    output wire [6:0]    xs_gx,
    output wire [1023:0] xs_d,
    output wire [31:0]   xs_rt,
    // token from the N face (one in flight) and its free pulse
    input  wire          tk_v,
    input  wire [511:0]  tk_d,
    output wire          tk_free,
    // RESULT copy to host lane 0 (WH0)
    output wire          r_v,
    output wire [511:0]  r_d,
    // HFWD frames from host lane 0 (WH0): valid = {hrv, type == HFWD}, payload hrd0_q[527:16]
    input  wire          hf_v,
    input  wire [511:0]  hf_d,
    // faults (pulses / levels) to the fault vector (WH1)
    output wire          f1, f10, f13, f15a
);
    localparam integer NB = 80;
    localparam [2:0] K_XB = 3'd2, K_TOK = 3'd5, K_HOST = 3'd6;
    localparam integer NRL = 7;
    wire [NRL-1:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(NRL)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    integer i;
    genvar k, g;
    function [1:0] mod3(input [20:0] x);
        reg [5:0] s; reg [3:0] s2; reg [2:0] s3; integer j;
        begin
            s = 6'd0;
            for (j = 0; j < 10; j = j + 1) s = s + {4'd0, x[2*j +: 2]};
            s = s + {5'd0, x[20]};
            s2 = {2'd0, s[5:4]} + {2'd0, s[3:2]} + {2'd0, s[1:0]};
            s3 = {1'b0, s2[3:2]} + {1'b0, s2[1:0]};
            mod3 = (s3 >= 3'd3) ? 2'(s3 - 3'd3) : s3[1:0];
        end
    endfunction
    // CSR copies
    reg [1:0] c_grp, c_ngrp; reg [15:0] c_cper, c_coff;
    always @(posedge ck or negedge rr[5])
        if (!rr[5]) begin c_grp <= 2'd0; c_ngrp <= 2'd0; c_cper <= 16'd0; end
        else begin
            if (cs_gp) begin c_grp <= cs_d[1:0]; c_ngrp <= cs_d[3:2]; end
            if (cs_cp[0]) c_cper <= cs_d[15:0];
        end
    always @(posedge ck or negedge rr[6]) if (!rr[6]) c_coff <= 16'd0; else if (cs_cp[1]) c_coff <= cs_d[31:16];
    // ---------------------------------------------------------------- INGEST P1 (pin flops)
    reg ri_v; reg [1103:1] ri_q; reg [31:0] rt_q;
    always @(posedge ck) begin ri_q <= ri[1103:1]; rt_q <= mu_rt; end
    always @(posedge ck or negedge rr[0]) if (!rr[0]) ri_v <= 1'b0; else ri_v <= ri[0];
    wire       p1_xb  = ri_v && ri_q[3:1] == K_XB;
    wire [7:0] p1_gx  = ri_q[20:13];
    wire       p1_tv  = rt_q[31];
    wire       p1_own = !p1_tv || c_ngrp <= 2'd1 || (c_ngrp == 2'd2 ? (rt_q[0] == c_grp[0]) : (mod3(rt_q[20:0]) == c_grp));
    reg [6:0]  fcnt;
    wire       p1_xw  = p1_xb && p1_own;
    wire       p1_fw  = ri_v && !p1_xw;
    wire       p1_op  = p1_xb && !p1_own && p1_tv && fcnt == 7'd0;
    assign xs_v = p1_xw && p1_gx < 8'd80;
    assign xs_gx = p1_gx[6:0];
    assign xs_d = ri_q[1044:21];
    assign xs_rt = rt_q;
    assign f1 = p1_xw && p1_gx >= 8'd80;
    // forward pipeline P2..P5
    reg f2v, f3v, f4v, f5v, x2, x3, x4, x5, o2, o3;
    reg [1103:0] f2d, f3d, f4d, f5d;
    reg [31:0] t2w;
    always @(posedge ck) begin f2d <= {ri_q, ri_v}; f3d <= f2d; f4d <= f3d; f5d <= f4d; t2w <= rt_q; end
    always @(posedge ck or negedge rr[0])
        if (!rr[0]) begin f2v <= 1'b0; f3v <= 1'b0; f4v <= 1'b0; f5v <= 1'b0;
                          x2 <= 1'b0; x3 <= 1'b0; x4 <= 1'b0; x5 <= 1'b0; o2 <= 1'b0; o3 <= 1'b0; end
        else begin
            f2v <= p1_fw; f3v <= f2v; f4v <= f3v; f5v <= f4v;
            x2 <= p1_xb && !p1_own; x3 <= x2; x4 <= x3; x5 <= x4; o2 <= p1_op; o3 <= o2;
        end
    // window tag (tagged opening beats only: the tag is the raw mu_rt, as the original p1_tag of a tagged beat)
    reg [30:0] t3o; reg [33:1] muc_d; reg muc_v;
    always @(posedge ck) begin t3o <= {t2w[20:0], t2w[30:21]}; muc_d <= {t3o, 2'b00}; end
    reg [6:0] wcnt;
    wire sel_fx = f5v && x5;
    always @(posedge ck or negedge rr[1])
        if (!rr[1]) begin fcnt <= 7'd0; wcnt <= 7'd0; muc_v <= 1'b0; end
        else begin
            if (p1_xb && !p1_own) fcnt <= (fcnt == 7'(NB - 1)) ? 7'd0 : fcnt + 7'd1;
            muc_v <= o3;
            if (o3) wcnt <= 7'(NB);
            else if (sel_fx && wcnt != 7'd0) wcnt <= wcnt - 7'd1;
        end
    assign mu_c = {muc_d, muc_v};
    assign f15a = o3 && wcnt != 7'd0;
    // ---------------------------------------------------------------- token hold (RO side of the 1-credit transfer)
    wire [511:0] tk_q;
    reg [511:0] tk_p;
    always @(posedge ck) tk_p <= tk_d;
    wire [1:0] tke;
    ot_s81hd_kf u_tke0 (.ck(ck), .d(tk_v), .q(tke[0])); ot_s81hd_kf u_tke1 (.ck(ck), .d(tk_v), .q(tke[1]));
    generate for (g = 0; g < 16; g = g + 1) begin : g_tk
        ot_s81hd_hreg32 u_h (.ck(ck), .en(tke[g / 8]), .d(tk_p[32*g +: 32]), .q(tk_q[32*g +: 32]));
    end endgenerate
    reg tk_l0, tk_l, tk_hv, htv0_l;
    wire tk_pop;
    always @(posedge ck or negedge rr[2])
        if (!rr[2]) begin tk_l0 <= 1'b0; tk_l <= 1'b0; tk_hv <= 1'b0; htv0_l <= 1'b0; end
        else begin tk_l0 <= tk_v; tk_l <= tk_l0; tk_hv <= (tk_hv && !tk_pop) || tk_l; htv0_l <= tk_pop; end
    assign tk_free = tk_pop;
    assign r_v = tk_pop;
    assign r_d = tk_q;
    // ---------------------------------------------------------------- HFWD hold (16 x hreg32)
    wire [511:0] hf_q;
    reg [511:0] hf_p;
    always @(posedge ck) hf_p <= hf_d;
    wire [1:0] hfe;
    ot_s81hd_kf u_hfe0 (.ck(ck), .d(hf_v), .q(hfe[0])); ot_s81hd_kf u_hfe1 (.ck(ck), .d(hf_v), .q(hfe[1]));
    generate for (g = 0; g < 16; g = g + 1) begin : g_hf
        ot_s81hd_hreg32 u_h (.ck(ck), .en(hfe[g / 8]), .d(hf_p[32*g +: 32]), .q(hf_q[32*g +: 32]));
    end endgenerate
    reg hf_l0, hf_l, hf_hv; wire hf_pop;
    reg [15:0] cal;
    wire cslot = cal == c_coff;
    always @(posedge ck or negedge rr[3])
        if (!rr[3]) begin hf_l0 <= 1'b0; hf_l <= 1'b0; hf_hv <= 1'b0; cal <= 16'd0; end
        else begin
            hf_l0 <= hf_v; hf_l <= hf_l0; hf_hv <= (hf_hv && !hf_pop) || hf_l;
            cal <= (cal >= c_cper) ? 16'd0 : cal + 16'd1;
        end
    assign f13 = hf_l && hf_hv && !hf_pop;
    // ---------------------------------------------------------------- RO stage (forward > token > host)
    wire blk = (wcnt != 7'd0) || o2 || o3 || p1_op;
    assign tk_pop = tk_hv && !f5v && !blk && !htv0_l;
    assign hf_pop = hf_hv && !f5v && !blk && !tk_pop && cslot;
    wire [16:0] sf_c, st_c, sh_c;
    generate for (k = 0; k < 17; k = k + 1) begin : g_rsel
        ot_s81hd_kf u_f (.ck(ck), .d(f5v), .q(sf_c[k]));
        ot_s81hd_kf u_t (.ck(ck), .d(tk_pop), .q(st_c[k]));
        ot_s81hd_kf u_h (.ck(ck), .d(hf_pop), .q(sh_c[k]));
    end endgenerate
    reg [1103:0] f6d; reg [531:0] t6d, h6d; reg ro_v6;
    always @(posedge ck) begin
        f6d <= f5d;
        t6d <= {tk_q, 8'd0, 4'd0, 5'd1, K_TOK};
        h6d <= {hf_q, 8'd0, 4'd0, 5'd1, K_HOST};
    end
    always @(posedge ck or negedge rr[4]) if (!rr[4]) ro_v6 <= 1'b0; else ro_v6 <= f5v || tk_pop || hf_pop;
    reg [1103:0] ro_q;
    always @(posedge ck) begin
        ro_q[1103:533] <= f6d[1103:533];
        for (i = 1; i < 533; i = i + 1)
            ro_q[i] <= (sf_c[(i-1)/32] & f6d[i]) | (st_c[(i-1)/32] & t6d[i-1]) | (sh_c[(i-1)/32] & h6d[i-1]);
    end
    reg ro_v;
    always @(posedge ck or negedge rr[4]) if (!rr[4]) ro_v <= 1'b0; else ro_v <= ro_v6;
    assign ro = {ro_q[1103:1], ro_v};
    reg lepf_q;
    always @(posedge ck) lepf_q <= lep_f;
    assign f10 = lepf_q;
endmodule

// ================================================================== C: core (X STORE, STREAM, TAG FIFO, N/S FINAL,
// RANK MERGE, MU landing replay)
module ot_s81hd_g_core (
    input  wire          ck, rn,
    // x store write stream (relayed from WL; arrives in the original P1 role)
    input  wire          xs_v,
    input  wire [6:0]    xs_gx,
    input  wire [1023:0] xs_d,
    input  wire [31:0]   xs_rt,
    input  wire [2:0]    xs_rtv,                               // three relayed copies of mu_rt[31] (kept fan-out)
    // MU landing window (relayed lw pin flops)
    input  wire          lw_v,
    input  wire [9:0]    lw_u,
    output reg           rc_v,
    output reg  [9:0]    rc_u,
    // CSR row base (csr 4)
    input  wire [1:0]    cs_rb,                                // two strobe copies (9 / 8 bits)
    input  wire [16:0]   cs_d,
    // N / S spine returns (relayed pin flops: valid sn_i[514], data sn_i[563:515])
    input  wire          sn_v, ss_v,
    input  wire [48:0]   sn_d, ss_d,
    // 6 mesh lane returns (relayed pin flops: valid, HSF0 header + BEST payload [96:0])
    input  wire [5:0]    m_v,
    input  wire [6*97-1:0] m_d,
    // stream to N and S (go2 / xv2 / xb2 / xa2)
    output wire          st_go, st_xv,
    output wire [255:0]  st_xb, st_xa,
    // own BEST record to the 6 mesh lanes (mtv_q / mtd_q payload)
    output wire          ov,
    output wire [80:0]   orec,
    // merged RESULT to the N face (mg4 pulse + {pos, user, bits, row})
    output wire          mg_v,
    output wire [79:0]   mg_d,
    // faults
    output wire          f0, f2, f3, f5, f6, f7, f8, f15b, f16c
);
    localparam integer SK = 8, NSL = 8192 + 7 * SK, NEND = 5 + NSL;
    localparam integer NB = 80;
    localparam [3:0] T_BEST = 4'd1;
    localparam integer NRL = 12;
    wire [NRL-1:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(NRL)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    integer i;
    genvar g, k;
    function isnan(input [31:0] x);
        isnan = (x[30:23] == 8'hFF) && (x[22:0] != 23'd0);
    endfunction
    reg [16:0] c_rbase;
    always @(posedge ck or negedge rr[11])
        if (!rr[11]) c_rbase <= 17'd0;
        else begin if (cs_rb[0]) c_rbase[8:0] <= cs_d[8:0]; if (cs_rb[1]) c_rbase[16:9] <= cs_d[16:9]; end
    // ---------------------------------------------------------------- P1 tag (untagged beats take {user 0, pos upos})
    reg [20:0] upos;
    reg [31:0] p1_tag;
    always @(*) begin
        p1_tag[31] = xs_rt[31];
        for (i = 0; i < 21; i = i + 1) p1_tag[i] = xs_rtv[i / 11] ? xs_rt[i] : upos[i];
        p1_tag[30:21] = xs_rt[30:21] & {10{xs_rtv[2]}};
    end
    // P2 write port
    reg wv2; reg [6:0] wa2; reg [1023:0] wd2; reg [31:0] t2;
    always @(posedge ck) begin wa2 <= xs_gx; wd2 <= xs_d; t2 <= p1_tag; end
    always @(posedge ck or negedge rr[0]) if (!rr[0]) wv2 <= 1'b0; else wv2 <= xs_v;
    reg [6:0] nbeat;
    reg busy;
    reg mt_v; reg [30:0] mt_tag;
    wire wa_xa = wa2 < 7'd64;
    wire [1:0] mf_c;
    wire p1_first = xs_v && nbeat == 7'd0 && !wv2;
    ot_s81hd_kf u_mf0 (.ck(ck), .d(p1_first), .q(mf_c[0]));
    ot_s81hd_kf u_mf1 (.ck(ck), .d(p1_first), .q(mf_c[1]));
    always @(posedge ck) begin
        if (mf_c[0]) mt_tag[15:0] <= t2[15:0];
        if (mf_c[1]) begin mt_tag[30:16] <= t2[30:16]; mt_v <= t2[31]; end
    end
    wire xrdy = nbeat == 7'(NB);
    wire start = xrdy && !busy;
    always @(posedge ck or negedge rr[1])
        if (!rr[1]) nbeat <= 7'd0;
        else if (start) nbeat <= 7'd0;
        else if (wv2) nbeat <= nbeat + 7'd1;
    // ---------------------------------------------------------------- X STORE (4 x 64x512 macros)
    reg [13:0] n;
    wire go0 = busy && n == 14'd0;
    wire xv0 = busy && n >= 14'd5;
    wire [13:0] m0 = n - 14'd5;
    wire [511:0] ra0, ra1, rb0, rb1;
    ot_sram_1r1w_64x512_m1_r2c2 u_xa0 (.clk(ck), .r_ce_in(xv0), .r_addr_in(m0[7:2]), .rd_out(ra0),
        .w_ce_in(wv2 && wa_xa), .w_addr_in(wa2[5:0]), .wd_in(wd2[511:0]), .w_mask_in({512{1'b1}}),
        .rr_en(2'b00), .rr_addr(12'd0), .cr_en(2'b00), .cr_sel(18'd0));
    ot_sram_1r1w_64x512_m1_r2c2 u_xa1 (.clk(ck), .r_ce_in(xv0), .r_addr_in(m0[7:2]), .rd_out(ra1),
        .w_ce_in(wv2 && wa_xa), .w_addr_in(wa2[5:0]), .wd_in(wd2[1023:512]), .w_mask_in({512{1'b1}}),
        .rr_en(2'b00), .rr_addr(12'd0), .cr_en(2'b00), .cr_sel(18'd0));
    ot_sram_1r1w_64x512_m1_r2c2 u_xb0 (.clk(ck), .r_ce_in(xv0), .r_addr_in({2'b00, m0[5:2]}), .rd_out(rb0),
        .w_ce_in(wv2 && !wa_xa), .w_addr_in({2'b00, wa2[3:0]}), .wd_in(wd2[511:0]), .w_mask_in({512{1'b1}}),
        .rr_en(2'b00), .rr_addr(12'd0), .cr_en(2'b00), .cr_sel(18'd0));
    ot_sram_1r1w_64x512_m1_r2c2 u_xb1 (.clk(ck), .r_ce_in(xv0), .r_addr_in({2'b00, m0[5:2]}), .rd_out(rb1),
        .w_ce_in(wv2 && !wa_xa), .w_addr_in({2'b00, wa2[3:0]}), .wd_in(wd2[1023:512]), .w_mask_in({512{1'b1}}),
        .rr_en(2'b00), .rr_addr(12'd0), .cr_en(2'b00), .cr_sel(18'd0));
    // ---------------------------------------------------------------- STREAM
    reg [30:0] tf0, tf1; reg [1:0] tfn; reg tfw, tfr;
    (* keep = "true" *) reg tfr_a, tfr_b, tfr_c;
    reg st1;
    always @(posedge ck or negedge rr[2])
        if (!rr[2]) begin busy <= 1'b0; n <= 14'd0; end
        else if (start) begin busy <= 1'b1; n <= 14'd0; end
        else if (busy) begin n <= n + 14'd1; if (n == 14'(NEND - 1)) busy <= 1'b0; end
`ifdef OT_S81HD_CTL_MUT_SLICE
    wire [3:0] sa0 = 4'b0001 << m0[1:0];
    wire [3:0] sa_n = {2'b00, sa0[1:0]};
`else
    wire [3:0] sa_n = 4'b0001 << m0[1:0];
`endif
    wire [3:0] sb_n = 4'b0001 << m0[1:0];
    wire [31:0] sa_c, sb_c;
    generate for (k = 0; k < 8; k = k + 1) begin : g_sc
        for (g = 0; g < 4; g = g + 1) begin : g_b
            ot_s81hd_kf u_a (.ck(ck), .d(sa_n[g]), .q(sa_c[4*k + g]));
            ot_s81hd_kf u_b (.ck(ck), .d(sb_n[g]), .q(sb_c[4*k + g]));
        end
    end endgenerate
    reg go1, xv1, go2, xv2;
    always @(posedge ck or negedge rr[2])
        if (!rr[2]) begin go1 <= 1'b0; xv1 <= 1'b0; go2 <= 1'b0; xv2 <= 1'b0; end
        else begin go1 <= go0; xv1 <= xv0; go2 <= go1; xv2 <= xv1; end
    reg [255:0] xa2, xb2;
    always @(posedge ck)
        for (i = 0; i < 256; i = i + 1) begin
            xa2[i] <= (sa_c[4*(i/32)+0] & ra0[i]) | (sa_c[4*(i/32)+1] & ra0[256+i]) |
                      (sa_c[4*(i/32)+2] & ra1[i]) | (sa_c[4*(i/32)+3] & ra1[256+i]);
            xb2[i] <= (sb_c[4*(i/32)+0] & rb0[i]) | (sb_c[4*(i/32)+1] & rb0[256+i]) |
                      (sb_c[4*(i/32)+2] & rb1[i]) | (sb_c[4*(i/32)+3] & rb1[256+i]);
        end
    assign st_go = go2; assign st_xv = xv2; assign st_xb = xb2; assign st_xa = xa2;
    // tag FIFO: push at start, pop at the N/S final
    wire nsf_fire;
    wire [3:0] tfe;
    ot_s81hd_kf u_tfe0 (.ck(ck), .d(start && !tfw), .q(tfe[0])); ot_s81hd_kf u_tfe1 (.ck(ck), .d(start && !tfw), .q(tfe[1]));
    ot_s81hd_kf u_tfe2 (.ck(ck), .d(start && tfw), .q(tfe[2]));  ot_s81hd_kf u_tfe3 (.ck(ck), .d(start && tfw), .q(tfe[3]));
    always @(posedge ck) begin
        if (tfe[0]) tf0[15:0] <= mt_tag[15:0]; if (tfe[1]) tf0[30:16] <= mt_tag[30:16];
        if (tfe[2]) tf1[15:0] <= mt_tag[15:0]; if (tfe[3]) tf1[30:16] <= mt_tag[30:16];
    end
    always @(posedge ck or negedge rr[3])
        if (!rr[3]) begin tfn <= 2'd0; tfw <= 1'b0; tfr <= 1'b0; tfr_a <= 1'b0; tfr_b <= 1'b0; tfr_c <= 1'b0; upos <= 21'd0; st1 <= 1'b0; end
        else begin
            st1 <= start;
            if (start) tfw <= ~tfw;
            if (st1 && !mt_v) upos <= upos + 21'd1;
            if (nsf_fire && tfn != 2'd0) begin tfr <= ~tfr; tfr_a <= ~tfr_a; tfr_b <= ~tfr_b; tfr_c <= ~tfr_c; end
            tfn <= tfn + {1'b0, start && tfn != 2'd2} - {1'b0, nsf_fire && tfn != 2'd0};
        end
    wire [30:0] tf_head = {tfr_c ? tf1[30:21] : tf0[30:21], tfr_b ? tf1[20:11] : tf0[20:11], tfr_a ? tf1[10:0] : tf0[10:0]};
    // ---------------------------------------------------------------- N/S FINAL (the relay output plays the pin)
    reg [48:0] sni_c, ssi_c; reg nrv, srv;
    always @(posedge ck) begin sni_c <= sn_d; ssi_c <= ss_d; end
    always @(posedge ck or negedge rr[4]) if (!rr[4]) begin nrv <= 1'b0; srv <= 1'b0; end
                                           else begin nrv <= sn_v; srv <= ss_v; end
    wire [3:0] nen, sen;
    generate for (k = 0; k < 4; k = k + 1) begin : g_nse
        ot_s81hd_kf u_n (.ck(ck), .d(sn_v), .q(nen[k]));
        ot_s81hd_kf u_s (.ck(ck), .d(ss_v), .q(sen[k]));
    end endgenerate
    reg [48:0] nb, sb;
    always @(posedge ck) begin
        if (nen[0]) nb[12:0] <= sni_c[12:0];   if (nen[1]) nb[24:13] <= sni_c[24:13];
        if (nen[2]) nb[36:25] <= sni_c[36:25]; if (nen[3]) nb[48:37] <= sni_c[48:37];
        if (sen[0]) sb[12:0] <= ssi_c[12:0];   if (sen[1]) sb[24:13] <= ssi_c[24:13];
        if (sen[2]) sb[36:25] <= ssi_c[36:25]; if (sen[3]) sb[48:37] <= ssi_c[48:37];
    end
    reg nh, sh, bv1, bv;
    assign nsf_fire = nh && sh;
    always @(posedge ck or negedge rr[4])
        if (!rr[4]) begin nh <= 1'b0; sh <= 1'b0; bv1 <= 1'b0; bv <= 1'b0; end
        else begin
            nh <= (nh && !nsf_fire) || nrv; sh <= (sh && !nsf_fire) || srv; bv1 <= nsf_fire; bv <= bv1;
        end
    wire [31:0] n_bits = nb[48:17], s_bits = sb[48:17];
    wire [48:0] b_rb;
    ot_s81hd_pick u_pns (.ck(ck), .u(nb), .v(sb), .y(b_rb));
    reg [30:0] bt1, b_tag;
    always @(posedge ck) begin bt1 <= tf_head; b_tag <= bt1; end
    reg ov_p; reg [80:0] orec_d;
    always @(posedge ck) orec_d <= {b_tag[20:0], b_tag[30:21], b_rb[48:17], b_rb[16:0] + c_rbase, 1'b1};
    always @(posedge ck or negedge rr[4]) if (!rr[4]) ov_p <= 1'b0; else ov_p <= bv;
    assign ov = ov_p; assign orec = orec_d;
    // ---------------------------------------------------------------- RANK MERGE (the relay outputs play mrv_q / mrd_q)
    wire [6:0] sl_en;
    wire [7*96-1:0] sl_q;
    generate for (k = 0; k < 6; k = k + 1) begin : g_ms
        assign sl_en[k] = m_v[k] && m_d[k*97 +: 4] == T_BEST;
        wire [95:0] dk = {15'd0, m_d[k*97 + 16 +: 81]};
        for (g = 0; g < 3; g = g + 1) begin : g_h
            ot_s81hd_hreg32 u_h (.ck(ck), .en(sl_en[k]), .d(dk[32*g +: 32]), .q(sl_q[96*k + 32*g +: 32]));
        end
    end endgenerate
    assign sl_en[6] = ov_p;
    generate for (g = 0; g < 3; g = g + 1) begin : g_os
        wire [95:0] dk = {15'd0, orec_d};
        ot_s81hd_hreg32 u_h (.ck(ck), .en(ov_p), .d(dk[32*g +: 32]), .q(sl_q[96*6 + 32*g +: 32]));
    end endgenerate
    reg [6:0] sl_l, sl_v;
    wire mg_fire = &sl_v;
    reg [6:0] sl_ovw;
    always @(posedge ck or negedge rr[5])
        if (!rr[5]) begin sl_l <= 7'd0; sl_v <= 7'd0; end
        else begin sl_l <= sl_en; sl_v <= (sl_v & {7{!mg_fire}}) | sl_l; end
    always @(*) sl_ovw = sl_l & sl_v & {7{!mg_fire}};
    wire [80:0] r_own = sl_q[96*6 +: 81], r_p0 = sl_q[0 +: 81], r_p0b = sl_q[96 +: 81],
                r_p1 = sl_q[192 +: 81], r_p1b = sl_q[288 +: 81], r_p2 = sl_q[384 +: 81], r_p2b = sl_q[480 +: 81];
    wire [48:0] c1a, c1b, mg_rb;
    ot_s81hd_pick u_p1a (.ck(ck), .u(r_own[49:1]), .v(r_p0[49:1]), .y(c1a));
    ot_s81hd_pick u_p1b (.ck(ck), .u(r_p1[49:1]), .v(r_p2[49:1]), .y(c1b));
    ot_s81hd_pick u_p2  (.ck(ck), .u(c1a), .v(c1b), .y(mg_rb));
    reg mg1, mg2, mg3, mg4, mchk_tag, mchk_cpy, mchk_nan; reg [30:0] mg_t;
    always @(posedge ck) begin
        mg_t <= r_own[80:50];
        mchk_tag <= (r_p0[80:50] != r_own[80:50]) || (r_p1[80:50] != r_own[80:50]) || (r_p2[80:50] != r_own[80:50]);
        mchk_cpy <= (r_p0 != r_p0b) || (r_p1 != r_p1b) || (r_p2 != r_p2b);
        mchk_nan <= isnan(r_own[49:18]) || isnan(r_p0[49:18]) || isnan(r_p1[49:18]) || isnan(r_p2[49:18]);
    end
    always @(posedge ck or negedge rr[6]) if (!rr[6]) begin mg1 <= 1'b0; mg2 <= 1'b0; mg3 <= 1'b0; mg4 <= 1'b0; end
                                           else begin mg1 <= mg_fire; mg2 <= mg1; mg3 <= mg2; mg4 <= mg3; end
    assign mg_v = mg4;
    assign mg_d = {mg_t[30:0], mg_rb[48:0]};
    // ---------------------------------------------------------------- MU landing replay (mu_rc)
    reg [6:0] lcnt; reg lpend; reg [9:0] luser;
    always @(posedge ck) begin if (lw_v && lcnt == 7'd0) luser <= lw_u; rc_u <= luser; end
    wire rc_go = lpend && !busy && nbeat == 7'd0 && !wv2;
    always @(posedge ck or negedge rr[7])
        if (!rr[7]) begin lcnt <= 7'd0; lpend <= 1'b0; rc_v <= 1'b0; end
        else begin
            rc_v <= rc_go;
            if (rc_go) begin lpend <= 1'b0; lcnt <= 7'd0; end
            else if (lw_v) begin
                lcnt <= lcnt + 7'd1;
                if (lcnt == 7'(NB - 1)) lpend <= 1'b1;
            end
        end
    // ---------------------------------------------------------------- faults
    assign f0  = (wv2 && busy) || (wv2 && xrdy);
    assign f2  = wv2 && nbeat != 7'd0 && (t2[31] != mt_v || t2[30:0] != mt_tag);
    assign f3  = bv && (isnan(n_bits) || isnan(s_bits)) || (mg1 && mchk_nan);
    assign f5  = (nsf_fire && tfn == 2'd0) || (start && tfn == 2'd2) || (nrv && nh && !nsf_fire) || (srv && sh && !nsf_fire);
    assign f6  = mg1 && mchk_tag;
    assign f7  = mg1 && mchk_cpy;
    assign f8  = |sl_ovw;
    assign f15b = lw_v && lpend;
    assign f16c = |(m_v & ~sl_en[5:0]);
endmodule

// ================================================================== N: seq peer, RESULT, DRAFT RX q/w, grant receivers,
// DRAFT TX source, token source, spine N pins
module ot_s81hd_g_n (
    input  wire          ck, rn,
    output wire [564:0]  sn_o,
    // stream from the core (relayed) and the fault flag (relayed from WH1)
    input  wire          st_go, st_xv,
    input  wire [255:0]  st_xb, st_xa,
    input  wire          ctlf,
    // CSR: plen (0), glen (1), hds (5), run (8)
    input  wire [1:0]    cs_pl, cs_gl,                         // two strobe copies each (11 / 10 bits)
    input  wire          cs_hd, cs_run,
    input  wire [20:0]   cs_d,
    // merged RESULT (relayed from the core)
    input  wire          mg_v,
    input  wire [79:0]   mg_d,
    // draft lane returns (relayed pin flops, equal age): valid, data [49:0]
    input  wire [4:0]    d_v,
    input  wire [5*50-1:0] d_d,
    // draft TX source (to the 5 draft lane pin stages, relayed equal age)
    output wire          dt_v,
    output wire [114:0]  dt_p,
    // token to the RO stage (one in flight) and the returning free pulse
    output wire          tk_v,
    output wire [511:0]  tk_d,
    input  wire          tk_free,
    // dsfd_mtp_seq peer (direct same-zone pins)
    output wire [0:0]    seq_rst,
    output wire [41:0]   seq_f_cfg,
    output wire [0:0]    seq_f_rv,
    output wire [511:0]  seq_f_rd,
    input  wire [0:0]    seq_t_rg,
    input  wire [0:0]    seq_t_tv,
    input  wire [511:0]  seq_t_td,
    output wire [0:0]    seq_f_tg,
    input  wire [0:0]    seq_t_sv,
    input  wire [76:0]   seq_t_sd,
    output wire [0:0]    seq_f_sg,
    output wire [0:0]    seq_f_wv,
    output wire [9:0]    seq_f_wd,
    input  wire [0:0]    seq_t_wg,
    input  wire [0:0]    seq_t_hv,
    input  wire [33:0]   seq_t_hd,
    output wire [0:0]    seq_f_hg,
    output wire [0:0]    seq_f_qv,
    output wire [33:0]   seq_f_qd,
    input  wire [0:0]    seq_t_qg,
    // faults
    output wire          f9, f14, f16a
);
    localparam integer NW = 21, UW = 10, SW = UW + 3 * NW + 4, DW = UW + 3 + NW;
    localparam [3:0] T_SEED = 4'd2, T_DHS = 4'd3, T_DHR = 4'd4, T_ROWS = 4'd5;
    localparam integer NRL = 10;
    wire [NRL-1:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(NRL)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    integer i;
    genvar g, k;
    // ---------------------------------------------------------------- CSR copies + seq configuration
    reg [NW-1:0] c_plen, c_glen; reg [15:0] c_hds; reg c_run;
    always @(posedge ck or negedge rr[0])
        if (!rr[0]) begin c_plen <= 21'd0; c_run <= 1'b0; end
        else begin
            if (cs_pl[0]) c_plen[10:0] <= cs_d[10:0]; if (cs_pl[1]) c_plen[20:11] <= cs_d[20:11];
            if (cs_run) c_run <= cs_d[0];
        end
    always @(posedge ck or negedge rr[7])
        if (!rr[7]) c_glen <= 21'd0;
        else begin if (cs_gl[0]) c_glen[10:0] <= cs_d[10:0]; if (cs_gl[1]) c_glen[20:11] <= cs_d[20:11]; end
    always @(posedge ck or negedge rr[8]) if (!rr[8]) c_hds <= 16'd0; else if (cs_hd) c_hds <= cs_d[15:0];
    reg seq_rn;
    always @(posedge ck or negedge rr[1]) if (!rr[1]) seq_rn <= 1'b0; else seq_rn <= c_run;
    assign seq_rst = seq_rn;
    assign seq_f_cfg = {c_glen, c_plen};
    // ---------------------------------------------------------------- spine N pin stage (one landing stage + pins)
    reg [513:0] s2;
    always @(posedge ck) s2 <= {st_xv, st_go, st_xb, st_xa};
    wire gon;
    ot_s81hd_kf u_gon (.ck(ck), .d(st_go), .q(gon));
    reg [564:0] sno_q;
    always @(posedge ck) sno_q <= {ctlf, gon, {8{gon}}, 23'd0, {17{gon}}, s2[512], s2[513], s2[512], s2[511:256], s2[255:0]};
    assign sn_o = sno_q;
    // ---------------------------------------------------------------- RESULT -> dsfd_mtp_seq
    wire [95:0] res_h;
    generate for (g = 0; g < 3; g = g + 1) begin : g_rh
        wire [95:0] dk = {16'd0, mg_d};
        ot_s81hd_hreg32 u_h (.ck(ck), .en(mg_v), .d(dk[32*g +: 32]), .q(res_h[32*g +: 32]));
    end endgenerate
    reg res_l, rpend; wire r_cr;
    always @(posedge ck or negedge rr[2])
        if (!rr[2]) begin res_l <= 1'b0; rpend <= 1'b0; end
        else begin res_l <= mg_v; rpend <= (rpend && !r_cr) || res_l; end
    wire [16:0] rs_row = res_h[16:0]; wire [31:0] rs_bits = res_h[48:17];
    wire [9:0] rs_user = res_h[58:49]; wire [20:0] rs_pos = res_h[79:59];
    wire [511:0] rflit = {359'd0, rs_user[9:8], 37'd0, rs_bits, 4'd0, rs_row, rs_pos, rs_user[7:0], 8'd0, 4'd0, 4'd2, c_hds};
    ot_dsrom_mtp_ltx #(.W(512)) u_ltr (.clk(ck), .rst_n(rr[2]), .c_valid(rpend), .c_ready(r_cr), .c_data(rflit),
        .l_valid(seq_f_rv[0]), .l_ready(seq_t_rg[0]), .l_data(seq_f_rd));
    assign f9 = res_l && rpend && !r_cr;
    // ---------------------------------------------------------------- draft-lane RX (the relay outputs play drv_q / drd_q)
    wire [4:0] dq_n, dw_n, dx_n;
    wire [9:0] dqc;
    wire [4:0] dwc;
    reg [33:0] pq2 [0:4]; reg [9:0] pw2 [0:4];
    generate for (k = 0; k < 5; k = k + 1) begin : g_drx
        assign dq_n[k] = d_v[k] && d_d[k*50 +: 4] == T_DHR;
        assign dw_n[k] = d_v[k] && d_d[k*50 +: 4] == T_ROWS;
        assign dx_n[k] = d_v[k] && !dq_n[k] && !dw_n[k];
        ot_s81hd_kf u_q0 (.ck(ck), .d(dq_n[k]), .q(dqc[2*k])); ot_s81hd_kf u_q1 (.ck(ck), .d(dq_n[k]), .q(dqc[2*k+1]));
        ot_s81hd_kf u_w0 (.ck(ck), .d(dw_n[k]), .q(dwc[k]));
    end endgenerate
    always @(posedge ck) for (i = 0; i < 5; i = i + 1) begin pq2[i] <= d_d[i*50 + 16 +: 34]; pw2[i] <= d_d[i*50 + 16 +: 10]; end
    reg [33:0] qsel; reg [9:0] wsel;
    always @(*) begin
        qsel = 34'd0; wsel = 10'd0;
        for (i = 0; i < 5; i = i + 1) begin
            qsel[16:0]  = qsel[16:0]  | ({17{dqc[2*i]}} & pq2[i][16:0]);
            qsel[33:17] = qsel[33:17] | ({17{dqc[2*i+1]}} & pq2[i][33:17]);
            wsel = wsel | ({10{dwc[i]}} & pw2[i]);
        end
    end
    wire [63:0] qw_h;
    ot_s81hd_hreg32 u_qh0 (.ck(ck), .en(|dqc), .d(qsel[31:0]), .q(qw_h[31:0]));
    ot_s81hd_hreg32 u_qh1 (.ck(ck), .en(|dqc), .d({20'd0, wsel, qsel[33:32]}), .q(qw_h[63:32]));
    wire [33:0] q_hold = qw_h[33:0]; wire [9:0] w_hold = qw_h[43:34];
    reg dq_l, dw_l, qpend, wpend; wire q_cr, w_cr;
    always @(posedge ck or negedge rr[3])
        if (!rr[3]) begin dq_l <= 1'b0; dw_l <= 1'b0; qpend <= 1'b0; wpend <= 1'b0; end
        else begin
            dq_l <= |dq_n; dw_l <= |dw_n;
            qpend <= (qpend && !q_cr) || dq_l; wpend <= (wpend && !w_cr) || dw_l;
        end
    ot_dsrom_mtp_ltx #(.W(DW)) u_ltq (.clk(ck), .rst_n(rr[3]), .c_valid(qpend), .c_ready(q_cr), .c_data(q_hold),
        .l_valid(seq_f_qv[0]), .l_ready(seq_t_qg[0]), .l_data(seq_f_qd));
    ot_dsrom_mtp_ltx #(.W(UW)) u_ltw (.clk(ck), .rst_n(rr[3]), .c_valid(wpend), .c_ready(w_cr), .c_data(w_hold),
        .l_valid(seq_f_wv[0]), .l_ready(seq_t_wg[0]), .l_data(seq_f_wd));
    assign f14 = (dq_l && qpend && !q_cr) || (dw_l && wpend && !w_cr) || (|(dq_n & (dq_n - 5'd1))) || (|(dw_n & (dw_n - 5'd1)))
                 || (|dq_n && |dw_n);
    assign f16a = |dx_n;
    // ---------------------------------------------------------------- grant receivers (direct seq peer)
    wire tk_hv, sd_hv, hs_hv; wire tk_pop, sd_pop, hs_pop;
    wire [511:0] tk_q; wire [SW-1:0] sd_q; wire [DW-1:0] hs_q;
    ot_s81hd_grx #(.W(512)) u_gt (.ck(ck), .rn(rr[4]), .l_v(seq_t_tv[0]), .l_d(seq_t_td), .l_g(seq_f_tg[0]), .hv(tk_hv), .q(tk_q), .pop(tk_pop));
    ot_s81hd_grx #(.W(SW))  u_gs (.ck(ck), .rn(rr[4]), .l_v(seq_t_sv[0]), .l_d(seq_t_sd), .l_g(seq_f_sg[0]), .hv(sd_hv), .q(sd_q), .pop(sd_pop));
    ot_s81hd_grx #(.W(DW))  u_gh (.ck(ck), .rn(rr[4]), .l_v(seq_t_hv[0]), .l_d(seq_t_hd), .l_g(seq_f_hg[0]), .hv(hs_hv), .q(hs_q), .pop(hs_pop));
    // token transfer: one token in flight to the RO-side hold; the free pulse (its pop) re-arms the transfer
    reg tk_inf;
    assign tk_pop = tk_hv && !tk_inf;
`ifdef OT_S81HD_R3_MUT_TKF
    wire tk_free_e = 1'b0;                                     // mutant: the RO-side free pulse is lost
`else
    wire tk_free_e = tk_free;
`endif
    always @(posedge ck or negedge rr[5]) if (!rr[5]) tk_inf <= 1'b0; else tk_inf <= (tk_inf && !tk_free_e) || tk_pop;
    assign tk_v = tk_pop;
    assign tk_d = tk_q;
    // ---------------------------------------------------------------- draft-lane TX source (SEED / DHSTEP)
    reg dtv_l;
    assign sd_pop = sd_hv && !dtv_l;
    assign hs_pop = hs_hv && !sd_hv && !dtv_l;
    always @(posedge ck or negedge rr[6]) if (!rr[6]) dtv_l <= 1'b0; else dtv_l <= sd_pop || hs_pop;
    assign dt_v = sd_pop || hs_pop;
    assign dt_p = {hs_q, sd_q, sd_pop ? T_SEED : T_DHS};
endmodule

