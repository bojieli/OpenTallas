`timescale 1ns/1ps
// S81 HEAD ctl glue R3 "regional glue" (STW-S81c-HEAD-GLUE 10-22): functional zone modules of ot_s81hd_ctl_glue
// (source b4f571642 / eb58f5989 ot_s81hd_ctl_peer.sv), re-partitioned by physical zone of the H10 die reserve.
// Every functional unit of the original glue is kept (INGEST, X STORE, STREAM, TAG FIFO, N/S FINAL, RANK MERGE, RESULT,
// DRAFT RX, SEQ peer interface + grant receivers, DRAFT TX, HOST CSR / HFWD / STATUS / RESULT copy, RO stage, MU landing
// replay, FAULTS); the arithmetic, compares, tie rule and frame layouts are byte-identical.  What changes:
//  * each zone has its own clock (regional CTS root) and its own reset leaf (equal-depth forest, generated top);
//  * every signal between zones travels on kept, non-mergeable relay stages (ot_s81hd_rs32 / rs8 / kf; valid bits
//    ot_s81hd_rv1) with registered hops <= 380 um, generated by tools/s81_head/glue_rg_gen.py with equal ages per bus
//    group, so the original cycle relations hold up to a constant delay per path (ledger in the kit);
//  * the token path seq -> RO (N face -> W lep face, ~2.1 mm) is a one-token-in-flight transfer: the N grant receiver
//    pops into the relay only when the RO-side hold is free (free pulse returns on a relay), exactly the original
//    "one grant in flight, one holding register" rule stretched over the relay.
// The top (per variant MAIN / FALLBACK) is generated: rtl/dsrom_sys/s81_head/ot_s81hd_glue_rg{m,f}.sv.

// ------------------------------------------------------------------ kept relay stages (never merged, never flattened)
(* keep_hierarchy = "yes" *) module ot_s81hd_rs32 (input wire ck, input wire [31:0] d, output reg [31:0] q);
    always @(posedge ck) q <= d;
endmodule
(* keep_hierarchy = "yes" *) module ot_s81hd_rs8 (input wire ck, input wire [7:0] d, output reg [7:0] q);
    always @(posedge ck) q <= d;
endmodule
// valid / control relay: reset to 0 by the zone's landed reset leaf
(* keep_hierarchy = "yes" *) module ot_s81hd_rv1 (input wire ck, input wire rn, input wire d, output reg q);
    always @(posedge ck or negedge rn) if (!rn) q <= 1'b0; else q <= d;
endmodule
// reset forest relay: async assertion cascades, release one edge per hop
(* keep_hierarchy = "yes" *) module ot_s81hd_rr1 (input wire ck, input wire rn, output reg q);
    always @(posedge ck or negedge rn) if (!rn) q <= 1'b0; else q <= 1'b1;
endmodule

// ------------------------------------------------------------------ lane TX pin stages (kept: one per lane, so the
// header flops of two lanes are never merged into one flop that drives two faces)
(* keep_hierarchy = "yes" *) module ot_s81hd_g_mtx (
    input wire ck, input wire rn,
    input wire v, input wire [80:0] rec,                       // own BEST record {pos, user, bits, row, v}
    input wire cs_rk, input wire cs_gp, input wire [3:0] cs_d, // CSR rank / group writes (relayed)
    output reg tx_v, output reg [552:0] tx_d);
    wire [0:0] rr;
    ot_rst_relay_tree3 #(.REGIONS(1)) u_rr (.clk(ck), .rst_n_in(rn), .rst_n(rr));
    reg [1:0] c_rank, c_grp;
    always @(posedge ck or negedge rr[0])
        if (!rr[0]) begin c_rank <= 2'd0; c_grp <= 2'd0; tx_v <= 1'b0; end
        else begin
            if (cs_rk) c_rank <= cs_d[1:0];
            if (cs_gp) c_grp <= cs_d[1:0];
            tx_v <= v;
        end
    always @(posedge ck) tx_d <= {1'b1, 455'd0, rec, 8'd0, c_grp, c_rank, 4'd1};   // frm(T_BEST, ...)
endmodule

