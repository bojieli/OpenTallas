// ot_s81_engram_hash_static (S-ENGRAM+NORM, 2026-10-16): the S81 static-lookup copy of
// ot_s81_engram_hash_clock_roots (clock_partition_1015, left untouched for the superseded 13/14-root
// credit lookup).  Same arithmetic, same stages, same LATENCY 12, bit-identical rows.  Re-timed for the
// multi-root gate (770 ps gate period, 150 ps inter-root uncertainty) after the static14 gate measured
// -99..-172 ps (placement STA, 2026-10-16 00:50):
//   * 64-bit product adds (pa, prod) as 2x32 carry-select (one 32-bit carry chain, not 64);
//   * the rolling-XOR register of (layer l, order s) is owned by its column clock clk_columns[3l+s-1]
//     (the 8 head columns of that order are exactly that clock's 8 columns), so the residue-lookup /
//     first-add stage is intra-root; only the 2-level XOR crosses ck_seed -> column root;
//   * the 8q/4q and 2q/q conditional-subtraction pairs are a parallel carry-select (one subtract level);
//   * new out_res: the residue m2 registered in the row_q stage (row_q - OFF exactly), so the lookup's
//     column-root -> core-root crossing is an 8:1 AND-OR select instead of mux + 24-bit subtract.
// All roots must be phase-related 1:1 at 1.2 GHz with actual phi-R delivery.
`timescale 1ns/1ps
// GENERATED by tools/hdc_v41_engram_shipped.py --emit from rtl/hdc/v41/ot_hdc_engram_hash.sv:
// the shipped-scale hash unit (ot_hdc_engram_tables_shipped_pkg: 17-bit compressed ids, primes
// near 16,000,000, 29-bit row addresses).  Only the package, the module name and the digit
// width of the product stage differ from the reduced source.  Do not edit.
// ---------------------------------------------------------------------------
// Engram n-gram hash unit of the V4.1 decode core: every hash column of every
// Engram layer for one token position per cycle.  II 1, fixed LATENCY 12.
//
// FUNCTION (tools/hdc_golden_v41.EngramTables.hashes, bit for bit).  The unit
// keeps the last ENG_N compressed token ids (newest first; before a sequence's
// first token the history is the pad id).  For layer l and n-gram order s:
//
//     p[l][s]    = tok[s] * mult[l][s]                  (exact, < 2^64)
//     roll[l][s] = p[l][0] ^ p[l][1] ^ ... ^ p[l][s]
//     row[l][(s-1)*H + h] = roll[l][s] mod prime[l][s-1][h] + offset[l][(s-1)*H + h]
//
// for s = 1 .. N-1 and head h.  The row is the address of that column's row in
// layer l's concatenated embedding table (offsets are the cumulative primes).
//
// ARITHMETIC, and why it is exact.
// * The multiply by a constant is three table lookups, one per ENG_DIG_W-bit
//   digit of the id (ENG_NIB[p][n] = n * mult, entries < 2^64 because each partial
//   product is at most the whole product), and two 64-bit adds.
// * The modulo by a constant prime q folds the 64-bit value in sixteen 4-bit
//   digits d_j: x = sum_j d_j 2^(4j), so x = sum_j (d_j 2^(4j) mod q)  (mod q).
//   Each term is a constant-table lookup (ENG_RES[c][j][d] = d*2^(4j) mod q),
//   their sum is below 16q, and four conditional subtractions of 8q, 4q, 2q
//   and q leave the residue in [0, q).  No divider, no reciprocal, no rounding:
//   every step is an integer identity, so the result equals Python's `%`.
// * Any 17-bit id is exact (the product stays below 2^64); ids beyond the
//   compressed vocabulary are not the model's, but the unit still hashes them
//   as the golden's integers would.
//
// Stages: 1 window, 2 digit products, 3-4 product adds, 5 XOR prefix,
// 6 residue lookups + pair adds, 7-9 residue adder tree, 10-11 conditional
// subtractions, 12 offset add (output register).
//
// One stream: in_first marks a sequence's first position and resets the
// history to the pad id in the same cycle.
// ---------------------------------------------------------------------------
import ot_hdc_engram_tables_shipped_pkg::*;

module ot_s81_engram_hash_static (
    input  wire                                   clk,
    input  wire [5:0]                             clk_columns,
    input  wire                                   rst_n,
    input  wire                                   in_valid,
    input  wire                                   in_first,
    input  wire [ENG_ID_W-1:0] in_cid,
    output wire                                   out_valid,
    //: column c of layer l at [ENG_ROW_W*(l*ENG_COLS + c) +: ENG_ROW_W]
    output wire [ENG_ROW_W*ENG_LAYERS*
                 ENG_COLS-1:0] out_row,
    //: residue (out_row minus the column offset) of column c of layer l at [ENG_RES_W*(l*ENG_COLS + c) +: ENG_RES_W]
    output wire [ENG_RES_W*ENG_LAYERS*
                 ENG_COLS-1:0] out_res
);
    localparam integer LATENCY = 12;
    localparam integer NP = ENG_LAYERS * ENG_N;          // products
    localparam integer NC = ENG_LAYERS * ENG_COLS;       // columns
    localparam integer RW = ENG_RES_W;
    //: local copies: Yosys resolves a package constant under a variable
    //: part-select as an implicit wire, so the tables are indexed through these
    localparam [$bits(ENG_NIB)-1:0] NIB = ENG_NIB;
    localparam [$bits(ENG_RES)-1:0] RES = ENG_RES;

    reg [LATENCY:1] vl;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) vl <= {LATENCY{1'b0}};
        else vl <= {vl[LATENCY-1:1], in_valid};
    end
    assign out_valid = vl[LATENCY];

    // ---- 1: the n-gram window (w[0] newest) -------------------------------------
    reg [ENG_ID_W-1:0] hist [1:ENG_N-1];   // hist[k]: the id k positions back
    reg [ENG_ID_W-1:0] w    [0:ENG_N-1];
    integer k;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (k = 1; k < ENG_N; k = k + 1) hist[k] <= ENG_PAD;
        end else if (in_valid) begin
            hist[1] <= in_cid;
            for (k = 2; k < ENG_N; k = k + 1) hist[k] <= in_first ? ENG_PAD : hist[k-1];
        end
    end
    always @(posedge clk) begin
        w[0] <= in_cid;
        for (k = 1; k < ENG_N; k = k + 1) w[k] <= in_first ? ENG_PAD : hist[k];
    end

    // ---- 2-4: tok * mult by digit tables --------------------------------------------
    wire [64*NP-1:0] prod_all;
    // 64-bit add as two 32-bit halves, the upper half formed for both carries and selected (exact)
    function automatic [63:0] add64cs(input [63:0] a, input [63:0] b);
        reg [32:0] lo;
        reg [31:0] h0, h1;
        begin
            lo = {1'b0, a[31:0]} + {1'b0, b[31:0]};
            h0 = a[63:32] + b[63:32];
            h1 = a[63:32] + b[63:32] + 32'd1;
            add64cs = {lo[32] ? h1 : h0, lo[31:0]};
        end
    endfunction
    genvar p, c, j;
    generate
        for (p = 0; p < NP; p = p + 1) begin : g_prod
            localparam integer ND = 1 << ENG_DIG_W;              // entries per product table
            wire [3*ENG_DIG_W-1:0] t = {{(3*ENG_DIG_W-ENG_ID_W){1'b0}}, w[p % ENG_N]};
            localparam [64*ND-1:0] TP = NIB[64*ND*p +: 64*ND];   // this product's 2^DIG_W entries
            reg [63:0] pp0, pp1, pp2, pa, pb, prod;
            always @(posedge clk) begin
                pp0  <= TP[64*t[ENG_DIG_W-1:0] +: 64];
                pp1  <= TP[64*t[2*ENG_DIG_W-1:ENG_DIG_W] +: 64] << ENG_DIG_W;
                pp2  <= TP[64*t[3*ENG_DIG_W-1:2*ENG_DIG_W] +: 64] << (2*ENG_DIG_W);
                pa   <= add64cs(pp0, pp1);
                pb   <= pp2;
                prod <= add64cs(pa, pb);
            end
            assign prod_all[64*p +: 64] = prod;
        end
    endgenerate

    // ---- 5: rolling XOR, one value per (layer, s >= 1), owned by that order's column clock ------
    //: roll_all[64*(l*N + s) +: 64] for s >= 1 (s = 0 slots are unused zeros)
    wire [64*NP-1:0] roll_all;
    genvar rl, rs, rx;
    generate
        if (ENG_COLS != (ENG_N - 1) * 8 || ENG_HEADS != 8) begin : g_bad_geometry
            initial $fatal(1, "ot_s81_engram_hash_static: one column clock per (layer, order) needs 8 heads");
        end
        for (rl = 0; rl < ENG_LAYERS; rl = rl + 1) begin : g_roll_l
            assign roll_all[64*(rl*ENG_N) +: 64] = 64'd0;
            for (rs = 1; rs < ENG_N; rs = rs + 1) begin : g_roll_s
                wire [63:0] xr [0:rs];
                assign xr[0] = prod_all[64*(rl*ENG_N) +: 64];
                for (rx = 1; rx <= rs; rx = rx + 1) begin : g_x
                    assign xr[rx] = xr[rx-1] ^ prod_all[64*(rl*ENG_N + rx) +: 64];
                end
                reg [63:0] roll;
                always @(posedge clk_columns[rl*(ENG_N-1) + rs - 1]) roll <= xr[rs];
                assign roll_all[64*(rl*ENG_N + rs) +: 64] = roll;
            end
        end
    endgenerate

    // ---- 6-12: per column, x mod q + offset ------------------------------------------
    generate
        for (c = 0; c < NC; c = c + 1) begin : g_col
            localparam integer L_ = c / ENG_COLS;
            localparam integer S_ = (c % ENG_COLS) / ENG_HEADS + 1;
            localparam [RW-1:0] Q = ENG_PRIME[RW*c +: RW];
            localparam [ENG_ROW_W-1:0] OFF = ENG_OFFSET[ENG_ROW_W*c +: ENG_ROW_W];
            wire [63:0] x = roll_all[64*(L_*ENG_N + S_) +: 64];
            wire [RW-1:0] r [0:15];
            for (j = 0; j < 16; j = j + 1) begin : g_dig
                localparam [RW*16-1:0] TD = RES[RW*16*(c*16 + j) +: RW*16];   // this digit's 16 residues
                assign r[j] = TD[RW*x[4*j +: 4] +: RW];
            end
            reg [RW:0]   s1 [0:7];
            reg [RW+1:0] s2 [0:3];
            reg [RW+2:0] s3 [0:1];
            reg [RW+3:0] s4;
            reg [RW+2:0] m1;          // < 4q after the 8q and 4q steps
            reg [RW-1:0] m2;          // < q
            integer i;
            // candidates (one extra sign bit each)
            wire [RW+4:0] d12 = {1'b0, s4} - (({5'b0, Q} << 3) + ({5'b0, Q} << 2));
            wire [RW+4:0] d8  = {1'b0, s4} - ({5'b0, Q} << 3);
            wire [RW+4:0] d4  = {1'b0, s4} - ({5'b0, Q} << 2);
            wire [RW+3:0] e3  = {1'b0, m1} - (({4'b0, Q} << 1) + {4'b0, Q});
            wire [RW+3:0] e2  = {1'b0, m1} - ({4'b0, Q} << 1);
            wire [RW+3:0] e1  = {1'b0, m1} - {4'b0, Q};
            reg [ENG_ROW_W-1:0] row_q;
            reg [RW-1:0] res_q;
            assign out_row[ENG_ROW_W*c +: ENG_ROW_W] = row_q;
            assign out_res[RW*c +: RW] = res_q;
            // Six actual clock owners, eight complete columns per owner.
            always @(posedge clk_columns[c / 8]) begin
                for (i = 0; i < 8; i = i + 1) s1[i] <= r[2*i] + r[2*i+1];
                for (i = 0; i < 4; i = i + 1) s2[i] <= s1[2*i] + s1[2*i+1];
                for (i = 0; i < 2; i = i + 1) s3[i] <= s2[2*i] + s2[2*i+1];
                s4 <= s3[0] + s3[1];
                // Parallel (carry-select) form of the two chained conditional subtractions: the three
                // candidates s4-12q / s4-8q / s4-4q are formed side by side and the first non-negative one
                // wins.  Bit-identical to csub(csub(s4,8q),4q) for every s4 (one subtract level, not two).
                m1 <= !d12[RW+4] ? d12[RW+2:0] : !d8[RW+4] ? d8[RW+2:0] : !d4[RW+4] ? d4[RW+2:0] : s4[RW+2:0];
                // Same for csub(csub(m1,2q),q): candidates m1-3q / m1-2q / m1-q.
                m2 <= !e3[RW+3] ? e3[RW-1:0] : !e2[RW+3] ? e2[RW-1:0] : !e1[RW+3] ? e1[RW-1:0] : m1[RW-1:0];
                row_q <= {{(ENG_ROW_W-RW){1'b0}}, m2} + OFF;
                res_q <= m2;
            end
        end
    endgenerate
endmodule
