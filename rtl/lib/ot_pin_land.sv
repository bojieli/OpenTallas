`timescale 1ns/1ps
// Face landing stage for late tile input pins (HKV-RSTCAP 2026-10-19, coordinator: one shared KV reset/pin landing standard).
//
// A tile input pin whose first sinks are a high-fanout enable / valid / select (kvs_attn fin[0] 372 ps, i_ctl[2] 338 ps
// native capture at the pin + R against 190) is landed in ONE flop per bit at the face: the pin net then has exactly one
// sink, tools/ref_tile io_flop_at_pins anchors that flop at the pin, and the original fan-out starts from a flop output
// with a full cycle.  No reset (a pin capture flop is data; the reset pin must not fan into it).  Latency: LAT rising clk
// edges on every bit of the landed bus (the whole bus moves together, so valid / beat / data stay aligned); the die
// schedule prices it (lanes/HKV-RSTCAP.md).  The reset half of the standard is rtl/lib/ot_rst_relay.sv; the per-tile
// wrapper that combines both is generated by tools/ref_tile/face_land.py (never hand copied).
// MUT != 0: bypass (q = d) -- the bench mutant that must FAIL the exact landing contract.
module ot_pin_land #(
    parameter integer W   = 1,
    parameter integer LAT = 1,
    parameter integer MUT = 0
) (
    input  wire         clk,
    input  wire [W-1:0] d,
    output wire [W-1:0] q
);
    generate
        if (MUT != 0) begin : g_bypass
            assign q = d;
        end else if (LAT == 1) begin : g_land1
            // packed registers only (no unpacked arrays: Yosys memory inference must not see a landing stage)
            reg [W-1:0] st;
            always @(posedge clk) st <= d;
            assign q = st;
        end else begin : g_landn
            reg [W*LAT-1:0] st;
            always @(posedge clk) st <= {st[W*(LAT-1)-1:0], d};
            assign q = st[W*LAT-1 -: W];
        end
    endgenerate
`ifndef SYNTHESIS
    initial if (LAT < 1) $error("ot_pin_land: LAT must be >= 1");
`endif
endmodule
