    input  wire               u_flush,
    output wire               u_v,
    input  wire               u_ready,
    output wire [IW-1:0]      u_id,
    output wire [PMAX-1:0]    u_mask,
    output wire               u_last,
    // observation
    output wire               step_v,
    output wire [2:0]         step_a,
    output wire [3:0]         step_g,
    output wire [15:0]        steps,
    output wire [31:0]        cyc_total,
    output wire [31:0]        cyc_engine,
    output wire [31:0]        cyc_markov,
    // Prepared native SM passes for the current held control command. No command replay/host eng_done.
    input wire plan_v, output wire plan_ready,
    input wire [3:0] plan_cmd_op, input wire [7:0] plan_cmd_idx,
    input wire [31:0] plan_cmd_pos,
    input wire [$clog2(RMAX):0] plan_rows,
    input wire [7:0] plan_g, input wire plan_gs, input wire [1:0] plan_fmt,
    input wire [31:0] plan_base, input wire [23:0] plan_lines,
    input wire plan_last, input wire result_reserved,
    output wire req_v, input wire req_ready, output wire [31:0] req_addr,
    output wire [9:0] req_tag, input wire rsp_v, input wire [9:0] rsp_tag,
    input wire [1087:0] rsp_data,
    input wire xw_en, input wire [$clog2(XD)-1:0] xw_addr,
    input wire [6:0] xw_grp, input wire [2047:0] xw_data,
    output wire rv, output wire [$clog2(RMAX)-1:0] rrow,
    output wire [NC*32-1:0] rdata, output wire sm_busy, output wire fault,
    output wire arrive, input wire release_in, output wire released
);
    ot_dshbm_dspark_top_ctl_snapshot #(.B(B),.PMAX(PMAX),.TW(TW),.NL(NL),.NST(NST),
      .MAXPOS(MAXPOS),.W(W),.WR(WR),.SR(SR),.TR(TR),.NG(NG),.NSRC(NSRC),.RLOG(RLOG),
      .CKMAX(CKMAX),.AW(AW),.LP(LP),.FLAT(FLAT),.NEXP(NEXP),.KV(KV),.NDEXP(NDEXP),
      .KD(KD),.RP(RP),.IW(IW),.MUT(MUT),.ACCEPT_LEAF(ACCEPT_LEAF),.CTL_FAST(CTL_FAST),.FAST(0)) u_ctl (
      .clk(clk),
      .rst_n(rst_n),
      .start(start),
      .cfg_gamma(cfg_gamma),
      .cfg_force(cfg_force),
      .cfg_ngen(cfg_ngen),
      .cfg_plen(cfg_plen),
      .p_addr(p_addr),
      .p_tok(p_tok),
      .f_addr(f_addr),
      .f_tok(f_tok),
      .e_v(e_v),
      .e_tok(e_tok),
      .e_idx(e_idx),
      .done(done),
      .cmd_v(cmd_v),
