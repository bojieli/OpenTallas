      .sa_tok(sa_tok),
      .sa_pad(sa_pad),
      .sa_last(sa_last),
      .sa_err(sa_err),
      .n_committed(n_committed),
      .rv_v(rv_v),
      .rv_draft(rv_draft),
      .rv_vals(rv_vals),
      .rv_last(rv_last),
      .rv_col(rv_col),
      .t_v(t_v),
      .t_ids(t_ids),
      .t_col(t_col),
      .u_clr(u_clr),
      .u_flush(u_flush),
      .u_v(u_v),
      .u_ready(u_ready),
      .u_id(u_id),
      .u_mask(u_mask),
      .u_last(u_last),
      .step_v(step_v),
      .step_a(step_a),
      .step_g(step_g),
      .steps(steps),
      .cyc_total(cyc_total),
      .cyc_engine(cyc_engine),
      .cyc_markov(cyc_markov));
    ot_hbm_ctl_sm_bridge #(.SM_ENABLE(SM_ENABLE),.NC(NC),.RMAX(RMAX),.XD(XD)) u_engine (.*);
endmodule
