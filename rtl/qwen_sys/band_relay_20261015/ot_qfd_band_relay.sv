`timescale 1ns/1ps
// q15 r13 BAND relay successor (2026-10-15) for die master qfd_sp_band_lanes (16 x CLOSED qfd_bl_lane).
// Measured predecessor failure (qfd_sp_band_lanes_quarter, EPYC1TB run -20261015-010515, receipt 9488900c5): one
// std-cell clock root over 10,798 pin flops on three faces (TT insertion 997..1756 ps) AND single-cycle port <-> lane
// register paths of 1.4-1.8 mm (tw 1768, ty 1800, rst 1561, pw 1440, c 1425, tt 1411 um Manhattan at the c17 pin
// plan: every lane's 256 tw / ty bits are interleaved over the whole 393 um face range).  No clock retune closes it.
// Structure here (static, fixed-cycle; no valid/ready/credit/enable anywhere):
//   * face pin flops (one per port bit, same as before) split over TEN local std-cell roots: ck (S face straps / reset),
//     ck_fn0..3 (ty face quarters), ck_fn4..7 (tw face quarters), ck_fe0 (E face pw / pw_l / c / f / f_up), ck_fe1 (tt);
//   * per lane and bus group (TW 256, TY 256, TT 98, CP = c 26 + pw 32, S = rst / leaf lnk / b0) two relay STATIONS at
//     planned points (tools/qwen_band_relay/plan_stations.py: worst planned hop 666 um vs the predecessor's 1,652 um
//     single-cycle path, lanes mirrored MX), each station's flops on one of 42 LOCAL std-cell roots ck_st[] (stations
//     clustered within 120 um; <= 1,792 sinks / root);
//   * valid / fault: Codex tree3 (ot_qfd_band_fault_q4 x4 on ck_fq0..3 near each quarter, join on ck_fj, capture at the
//     E face pins on ck_fe0): exact old function, 3 edges instead of 1.
// Fixed edge accounting vs the predecessor (exact, proved by tb_qfd_band_relay_equiv):
//   lane sees tw / c / rst / b0 / lnk  +2 edges (A);  tt -> lane +2 and lane -> pw +2 (B): the lane lnk strap is
//   lnk + 1 + B = lnk + 3 (one LNK unit = the parent's out + return edge pair, as before);  lane -> ty +2 (C).
//   At the ports: pw, pw_l*, f, f_up are the predecessor's outputs 4 edges later and ty 8 edges later (+2 in, +2 out,
//   +4 longer ring wait for the 2-LNK-unit round trip) for the same tw / c / rst stream, provided the returned tt arrives
//   4 edges later (the die/upper sees the band 2 LNK units longer: strap the upper's
//   lnk for this band + 2).  Reset release reaches the lanes 2 edges later (3 from rst_n).
// Bench-only mutants (MUT): 1 = lane lnk strap +2 instead of +3; 2 = lane 5 tw station 1 skipped (one edge short);
// 3 = fault tree q4 MUT 1 on quarter 0 (its lane faults dropped).
module ot_qfd_band_relay_core #(parameter integer MUT=0) (
    input  wire          ck,
    input  wire [15:0]   ck_l,
    input  wire [7:0]    ck_fn,
    input  wire          ck_fe0, ck_fe1,
    input  wire [41:0]   ck_st,         // station roots (station_plan.json)
    input  wire [3:0]    ck_fq,
    input  wire          ck_fj,
    input  wire          rst_n,
    input  wire          b0,
    input  wire [5:0]    lnk,
    input  wire [4095:0] tw,
    input  wire [25:0]   c,
    input  wire [1537:0] tt,
    output wire [512:0]  pw,
    output wire [128:0]  pw_l0, pw_l1, pw_l2, pw_l3,
    output wire [3:0]    f_up,
    output wire [4095:0] ty,
    output wire          f
);
    // ---- S face pin flops (root ck) -------------------------------------------------------------------------------
    (* keep *) reg rst_f, b0_f;
    (* keep *) reg [5:0] lnk_f;
    always @(posedge ck) begin rst_f <= rst_n; b0_f <= b0; lnk_f <= lnk; end
    wire [5:0] leaf_lnk = lnk_f + ((MUT == 1) ? 6'd2 : 6'd3);
    // ---- E face input pin flops -------------------------------------------------------------------------------------
    (* keep *) reg [25:0] c_f;
    (* keep *) reg [1537:0] tt_f;
    always @(posedge ck_fe0) c_f <= c;
    always @(posedge ck_fe1) tt_f <= tt;
    // ---- N face pin flops: tw in, ty out, four face quarters each ----------------------------------------------------
    (* keep *) reg [4095:0] tw_f, ty_f;
    wire [4095:0] ty_i;
    genvar s, l, k;
    generate for (s = 0; s < 4; s = s + 1) begin : g_fn
        always @(posedge ck_fn[s])     ty_f[1024*s +: 1024] <= ty_i[1024*s +: 1024];
        always @(posedge ck_fn[4 + s]) tw_f[1024*s +: 1024] <= tw[1024*s +: 1024];
    end endgenerate
    assign ty = ty_f;
    // ---- station clock-root map ----
    // generated by tools/qwen_band_relay/plan_stations.py (results/rtl/qwen_band_relay_1015/station_plan.json): DO NOT EDIT
    localparam integer NR = 42;
    // station clock root of (lane l, group g: 0 TW, 1 TY, 2 TT, 3 CP, 4 S, stage s 1..2): ST_ROOT[8*(10*l + 2*g + s - 1) +: 8]
    localparam [1279:0] ST_ROOT = 1280'h1a0b0d0d1f1d282827260c0217171d1e252324290d0213131c1e271f2026150b1616191d27252224060212121d1e211c24260d010c0c1312251918240e071313191827211c2406020f0f17121f161d2608010c110c12251418240b04100c1417251916200301050a0a121f0d132402010c0c0c0f1f141320040406060d0f25140c200201050505121b08132001000609060f1f0d0c2000000306030a2114061d;
    // ---- lanes and their stations -----------------------------------------------------------------------------------
    wire [15:0] lf, lpv, lrst;
    wire [511:0] pw_d;
    wire [6*16-1:0] llnk;
    generate for (l = 0; l < 16; l = l + 1) begin : g_lane
        wire [255:0] ftw, fty;
        wire [97:0]  ftt;
        for (k = 0; k < 8; k = k + 1) begin : g_k
            assign ftw[32*k +: 32] = tw_f[32*(16*k + l) +: 32];
            assign ty_i[32*(16*k + l) +: 32] = fty[32*k +: 32];
        end
        for (k = 0; k < 3; k = k + 1) begin : g_t
            assign ftt[32*k +: 32] = tt_f[32*(16*k + l) +: 32];
        end
        assign ftt[97:96] = tt_f[1537:1536];
        // stations: group g (0 TW, 1 TY, 2 TT, 3 CP, 4 S), stage 1 / 2, each on its planned local root
        localparam integer R_TW1 = ST_ROOT[8*(10*l + 0) +: 8], R_TW2 = ST_ROOT[8*(10*l + 1) +: 8];
        localparam integer R_TY1 = ST_ROOT[8*(10*l + 2) +: 8], R_TY2 = ST_ROOT[8*(10*l + 3) +: 8];
        localparam integer R_TT1 = ST_ROOT[8*(10*l + 4) +: 8], R_TT2 = ST_ROOT[8*(10*l + 5) +: 8];
        localparam integer R_CP1 = ST_ROOT[8*(10*l + 6) +: 8], R_CP2 = ST_ROOT[8*(10*l + 7) +: 8];
        localparam integer R_S1  = ST_ROOT[8*(10*l + 8) +: 8], R_S2  = ST_ROOT[8*(10*l + 9) +: 8];
        (* keep *) reg [255:0] tw_s1, tw_s2, ty_s1, ty_s2;
        (* keep *) reg [97:0]  tt_s1, tt_s2;
        (* keep *) reg [25:0]  c_s1, c_s2;
        (* keep *) reg [31:0]  pw_s1, pw_s2;   // data only: the valid travels the fault tree
        (* keep *) reg [7:0]   st_s1, st_s2;   // {rst, leaf lnk 6, b0}
        wire [255:0] lty;
        wire [32:0]  lpw;
        always @(posedge ck_st[R_TW1]) tw_s1 <= ftw;
        always @(posedge ck_st[R_TW2]) tw_s2 <= (MUT == 2 && l == 5) ? ftw : tw_s1;
        always @(posedge ck_st[R_TY1]) ty_s1 <= lty;
        always @(posedge ck_st[R_TY2]) ty_s2 <= ty_s1;
        always @(posedge ck_st[R_TT1]) tt_s1 <= ftt;
        always @(posedge ck_st[R_TT2]) tt_s2 <= tt_s1;
        always @(posedge ck_st[R_CP1]) begin c_s1 <= c_f; pw_s1 <= lpw[31:0]; end
        always @(posedge ck_st[R_CP2]) begin c_s2 <= c_s1; pw_s2 <= pw_s1; end
        always @(posedge ck_st[R_S1])  st_s1 <= {rst_f, leaf_lnk, b0_f};
        always @(posedge ck_st[R_S2])  st_s2 <= st_s1;
        assign fty = ty_s2;
        assign pw_d[32*l +: 32] = pw_s2;
        assign lrst[l] = st_s2[7];
        assign llnk[6*l +: 6] = st_s2[6:1];
        assign lpv[l] = lpw[32];
        qfd_bl_lane u_lane (.ck(ck_l[l]), .rst_n(st_s2[7]), .b0(st_s2[0]), .lnk(st_s2[6:1]), .tw(tw_s2),
                            .c(c_s2), .tt(tt_s2), .pw(lpw), .ty(lty), .f(lf[l]));
    end endgenerate
    // ---- valid / fault reduction: Codex tree3 stages (q4 x4, join), outputs captured at the E face pins ------------
    wire [19:0] local_q;
    wire [8:0]  joined;
    generate for (s = 0; s < 4; s = s + 1) begin : g_fq
        // the quarter's reset / link copy is lane 4s's own lane-pin control (same age as its lf / lpv); the raw strap
        // is recovered exactly: &raw == (leaf == raw + 3 == 2)
        ot_qfd_band_fault_q4 #(.MUT((MUT == 3 && s == 0) ? 1 : 0)) u_q4 (.clk(ck_fq[s]), .reset_q(lrst[4*s]),
            .rawlnk(llnk[6*(4*s) +: 6] - 6'd3), .lf(lf[4*s +: 4]), .lpv(lpv[4*s +: 4]), .q(local_q[5*s +: 5]));
    end endgenerate
    ot_qfd_band_fault_join u_join (.clk(ck_fj), .d(local_q), .q(joined));
    // joined = {globalf, quarter_fault[3:0], quarter_pv[3:0]}; pw[512] == quarter_pv[0] (old: reset_q & lpv[0])
    (* keep *) reg f_f, pwv_f;
    (* keep *) reg [3:0] fup_f, qpv_f;
    (* keep *) reg [511:0] pw_f, pwl_f;
    always @(posedge ck_fe0) begin
        f_f <= joined[8]; fup_f <= joined[7:4]; qpv_f <= joined[3:0]; pwv_f <= joined[0];
        pw_f <= pw_d; pwl_f <= pw_d;
    end
    assign pw = {pwv_f, pw_f};
    assign pw_l0 = {qpv_f[0], pwl_f[127:0]};
    assign pw_l1 = {qpv_f[1], pwl_f[255:128]};
    assign pw_l2 = {qpv_f[2], pwl_f[383:256]};
    assign pw_l3 = {qpv_f[3], pwl_f[511:384]};
    assign f_up = fup_f;
    assign f = f_f;
endmodule

