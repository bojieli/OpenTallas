function automatic [31:0] raw(input integer addr);
 begin case(addr%8)
 0:raw=32'h80000000;1:raw=32'h7f800001;2:raw=32'hff800000;3:raw=32'h00000001;
 default:raw=32'h3f000000^(32'(addr)*32'h9e3779b1);
 endcase end
endfunction
function automatic [511:0] image(input integer row);
