function automatic [511:0] image(input integer row);
integer l;begin for(l=0;l<16;l=l+1)image[32*l+:32]=32'h3f800000+16*row+l+epoch*32768;end
endfunction
always @(negedge clk) if(rst_n)begin
qcr=q[523];
if(q[523])begin
 if(q[516:512]!==beats[4:0] || q[511:0]!==image(856+beats))begin errors=errors+1;$display("FAIL beat=%0d tag=%0d",beats,q[516:512]);end
 beats=beats+1;
end
if(acr)arcredits=arcredits+1;
end
integer i,t;
initial begin
repeat(5)@(negedge clk);rst_n=1;
repeat(8)@(negedge clk);qe=1;@(negedge clk);qe=0;
// Both row sources active: attention writes must not replace sequencer Q writes or lose credits.
for(i=0;i<32;i=i+1)begin
 svw={1'b1,20'(856+i),image(856+i)};
 ar={1'b1,1'b0,6'(i),image(3167+i)};
 @(negedge clk);
end
svw=0;ar=0;
for(t=0;t<200 && !qsr;t=t+1)@(negedge clk);
if(!qsr)begin $display("FAIL committed Q fence never opened OBS_MUT=%0d",OBS_MUT);$finish;end
if(arcredits!=32)begin errors=errors+1;$display("FAIL attention credit count %0d",arcredits);end
qs=1;@(negedge clk);qs=0;
for(t=0;t<2000 && beats<32;t=t+1)@(negedge clk);
if(beats!=32 || fault)begin errors=errors+1;$display("FAIL beats=%0d fault=%0d",beats,fault);end
// Read the actual attention bank image after all queued writes committed.
for(i=0;i<32;i=i+1)begin
 svr={1'b1,20'(3167+i)};@(negedge clk);svr=0;
 for(t=0;t<100 && !svq_v;t=t+1)@(negedge clk);
 if(!svq_v || svq!==image(3167+i))begin errors=errors+1;$display("FAIL attention row %0d",i);end
 @(negedge clk);
end
// Repeat via the REAL shared native SU producer pack; fresh coverage cannot inherit the prior epoch.
repeat(3)@(negedge clk);epoch=1;beats=0;qe=1;@(negedge clk);qe=0;
for(i=0;i<8;i=i+1)begin
 swa0=24'(13696+64*i);swa1=swa0+1;swmask=64'hffffffffffffffff;
 swdata={image(859+4*i),image(858+4*i),image(857+4*i),image(856+4*i)};
 @(negedge clk);
end
swmask=0;
for(t=0;t<200 && !qsr;t=t+1)@(negedge clk);
if(!qsr)begin $display("FAIL SU committed fence did not open PACK_MUT=%0d",PACK_MUT);$finish;end
qs=1;@(negedge clk);qs=0;
for(t=0;t<2000 && beats<32;t=t+1)@(negedge clk);
if(beats!=32 || fault)begin errors=errors+1;$display("FAIL SU beats=%0d fault=%0d",beats,fault);end
if(errors==0)$display("PASS vm_die real_Q_rows=64 words=1024 attention_rows=32 credits=%0d",arcredits);
else $display("FAIL vm_die errors=%0d",errors);
$finish;
end
