 .pb_q(pb_q),
 .pb_fault(pb_fault),
 .pr(pr),
 .tk8(tk8),
 .kst8(kst8),
 .hc(hc));
 // NSLOT1 is fixed in u_control: addressbit13 is the constant-zero slot bit.
