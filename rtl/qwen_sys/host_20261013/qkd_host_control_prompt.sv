    input  wire               m_wready,
    output wire [63:0]        m_wdata,
    output wire [7:0]         m_wstrb,
    output wire               m_wlast,
    input  wire               m_bvalid,
    output wire               m_bready,
    input  wire [1:0]         m_bresp,
    output wire               irq,
    // reset / boot
    input  wire [6-1:0]      link_up,
    input  wire [8-1:0]       boot_done,
    input  wire [8-1:0]       boot_ok,
    output wire               host_rst_n,
    output wire               link_rst_n,
    output wire               hbm_rst_n,
    output wire               boot_go,
    output wire               die_rst_n,
    output wire               sys_ready,
    // package control channel
    output wire               c_start,
    output wire [18-1:0]      c_token,
    output wire [18-1:0]      c_pos,
    output wire [24-1:0]      c_kv_base,
    output wire [1:0]         c_gen,
    input wire [7:0] transport_fault, physical_fault,
    input  wire               crom_fault,
    output wire [31:0]        fault_src,
    input wire [142:0] pr,
    input wire [743:0] tk8,
    input wire [79:0] kst8,
    output wire [181:0] hc
);
 wire pb_we,pb_re,pb_fault;wire[13:0]pb_waddr,pb_raddr;wire[17:0]pb_wdata,pb_q;
 qkd_host_fullcontrol #(.T_LINK(T_LINK),.T_HBM(T_HBM),.WDOG(WDOG),.PROMPT_READ_LATENCY(3))u_control(
 .ck_host(ck_host),
 .ck_csr(ck_csr),
 .ck_rst(ck_rst),
