    input wire [2:0] die_id,
    input  wire               por_n,
    // host AXI4-Lite slave (13-bit byte address: [12] = 0 host interface, 1 system CSRs)
    input  wire               s_awvalid,
    output wire               s_awready,
    input  wire [12:0]        s_awaddr,
    input  wire               s_wvalid,
    output wire               s_wready,
