`timescale 1ns/1ps
// KV-PC 2026-10-19 SAFE redesign (owner safe-design checklist item 5 "storage > ~2 kb into SRAM macros, never flop
// arrays indexed at runtime"; items 3 "no register drives > ~32 loads").  Opt-in successors of the five runtime-indexed
// flop arrays of the PC tile (terminal gate 1248d0585: front 9216 FF on 4 storage roots, read-pointer copies 2405
// loads; tag queue tq 64 x 34 with tr[1] 2051 loads; return ring 8 x 288; embedding CDC FIFOs down 8 x 349 / up 8 x 258
// with rd_bin 854 loads).  Every array is now banks of the project-native dual-clock register file
// ot_sram_1r1w2c_32x64_m1 (32 x 64, write port on wclk, REGISTERED read on rclk; e26d92503, escape coupon DRC0
// 3e95aae81).  The originals are unchanged; the clone chain that instantiates these is generated by
// tools/qwen_kv_die/kv_pc_sram_gen.py (qkd_kvpc_sram_clones_1019.sv).
//
// Zero added cycles.  Each original read is asynchronous (mem[ptr] at edge t); here the macro is read one edge earlier
// at the pointer's NEXT value (ptr(t) is known at edge t-1: ptr + advance), so rd_out holds mem[ptr(t)] at edge t.
// Equivalence conditions (benched in tools/qwen_kv_die/kvpc_sram_bench.py, mutants must fail):
//   * same-clock arrays (tag queue): a write at edge t-1 to the entry read at t is BYPASSED (registered write data), so
//     h_c0 / h_c1 equal the flop array on every edge, consumed or not (exact);
//   * front: the entry taken at t is never written at t-1 under the front's own block contract (a block starts only
//     after all its sectors landed); a same-edge same-address read is blocked (r_ce low: no physical collision) and a
//     sim-only check flags a consumed blocked read.  out_q loads only on take, so the front outputs are exact;
//   * dual-clock arrays (return ring, CDC FIFOs): an entry is consumed only after its write was published through the
//     2-flop synchroniser, i.e. >= 2 read-clock edges after the write; reading it one edge early is therefore after the
//     write.  Unconsumed reads (an empty FIFO head, an unpublished slot) may see a concurrent write: their data is
//     don't-care in the original too (an async read across domains) and reaches no state except data registers that
//     are qualified by the same valid (er_d with er_v; c_d with c_v).
`ifndef OT_KVPC_SRAM_1019_SV
`define OT_KVPC_SRAM_1019_SV

// Logical WORDS x BITS memory on ceil(BITS/64) native 32 x 64 dual-clock banks.  WCLK_MAP: bank k writes on
// wclk[WCLK_MAP[4k+:4]] (several storage roots; all the same clock family).  Unused high data bits are written 0.
module qkd_kvpc_ram2c #(
    parameter integer WORDS = 32,
    parameter integer BITS = 64,
    parameter integer NW = 1,                 // write clock entries
    parameter [63:0] WCLK_MAP = 64'd0,
    parameter integer MUT = 0,                // bench only: 1 bank permutation
    parameter integer NB = (BITS + 63) / 64   // banks (derived; do not override)
)(
    input  wire [NW-1:0] wclk,
    input  wire rclk,
    input  wire r_ce,
    input  wire [$clog2(WORDS)-1:0] r_addr,
    output wire [BITS-1:0] rd,
    input  wire [NB-1:0] w_ce,                // per bank (a bank-split writer enables only its bank)
    input  wire [$clog2(WORDS)-1:0] w_addr,
    input  wire [BITS-1:0] wd
);
    localparam integer AW = $clog2(WORDS);
    initial if (WORDS > 32 || WORDS < 2 || NB != (BITS + 63) / 64) $error("qkd_kvpc_ram2c: WORDS 2..32, NB derived");
    wire [NB*64-1:0] wdp = {{(NB*64-BITS){1'b0}}, wd};
    wire [NB*64-1:0] rdp;
    wire [4:0] ra = {{(5-AW){1'b0}}, r_addr};
    wire [4:0] wa = {{(5-AW){1'b0}}, w_addr};
    assign rd = rdp[BITS-1:0];
    genvar k;
    generate for (k = 0; k < NB; k = k + 1) begin : g_b
        localparam integer O = (MUT == 1) ? ((k + 1) % NB) : k;
        localparam integer WC = (WCLK_MAP >> (4 * k)) & 15;
        ot_sram_1r1w2c_32x64_m1 u_m (.wclk(wclk[WC]), .rclk(rclk), .r_ce_in(r_ce), .r_addr_in(ra),
            .rd_out(rdp[O*64 +: 64]), .w_ce_in(w_ce[k]), .w_addr_in(wa), .wd_in(wdp[k*64 +: 64]),
            .w_mask_in({64{1'b1}}));
    end endgenerate
endmodule

// ---- elastic front (qkd_kv_hbm_elastic_front_mc_nc successor) ----------------------------------------------------
// KV-PC2 10-19: ONE clock.  The landing registers land_v / land_d and the write pointer wp are pll_hbm flops, so the
// banks now WRITE on pll_hbm too (sr1 wrote on the four PHY storage roots pll_hbm_data[k] under an unproven "same phase
// as pll_hbm" claim: a crossing timed as same-clock).  pll_hbm_data is kept as an unused port (die binding unchanged;
// the die may drop the 4 storage-root bindings at adoption).  Write and read share pll_hbm: no CDC, no age claim.
// (sr1 text:) 32 x 297 {epoch16, co[281:1]} on 5 banks; bank k writes on its storage root pll_hbm_data[min(k,3)] (the original
// 4 roots, same phase as pll_hbm), reads on pll_hbm.  The 16 read-pointer copies (2405-load roots) are gone: the read
// address is one 5-bit next-pointer into 5 macro address pins.  Control logic is the original, line for line.
module qkd_kvpc_s_front #(
    parameter integer NBLK = 4,
    parameter integer BLK = 8,
    parameter integer STRIDE = 1,
    parameter integer MUT = 0   // 1: read address +1, 2: ready one sector early, 3: release ignores ready, 4: bank permutation, 5: no prefetch
)(
    input wire pll_hbm, hrst,
    input wire [3:0] pll_hbm_data,
    input wire [281:0] co_in,
    input wire [15:0] epoch_in,
    input wire blk_go,
    output wire [281:0] co_out,
    output wire [15:0] epoch_out,
    output wire compiled_hbm_put,
    output reg blk_freed,
    output reg hold,
    output reg [15:0] stall_edges,
    output reg [$clog2(NBLK*BLK):0] occupancy,
    output reg idle,
    output reg fault_overflow, fault_go
);
    localparam integer DEPTH = NBLK * BLK;
    localparam integer AW = $clog2(DEPTH);
    localparam integer BW = $clog2(BLK);
    localparam integer SW = (STRIDE > 1) ? $clog2(STRIDE) : 1;
    localparam integer PW = $clog2(NBLK + 1) + 1;
    localparam [AW:0] C_BLK = BLK, C_BLK1 = BLK - 1, C_DEPTH = DEPTH;
    localparam [SW-1:0] C_S1 = STRIDE - 1, C_S0 = 0;
    localparam [BW-1:0] C_B1 = BLK - 1;
    localparam [PW-1:0] C_NBLK = NBLK, C_P1 = 1, C_P0 = 0;
    localparam [AW-1:0] C_RA0 = (MUT == 1) ? 1 : 0;
    initial if (NBLK < 2 || (NBLK & (NBLK-1)) != 0 || BLK < 2 || (BLK & (BLK-1)) != 0 || STRIDE < 1 || DEPTH > 32)
        $error("elastic front: NBLK>=2 and BLK>=2 powers of two, STRIDE>=1, NBLK*BLK<=32");

    // item 3: hr (50 loads) and emitting (606: take = emitting enables the 297-bit out_q) are kept copy families
    (* keep, ot_rst_split *) reg [2:0] hr__qv;
    wire hr = hr__qv[0];
    always @(posedge pll_hbm) hr__qv <= {3{hrst}};
    (* keep *) reg land_v;
    (* keep *) reg [296:0] land_d;
    always @(posedge pll_hbm or negedge hr)
        if (!hr) land_v <= 1'b0; else land_v <= co_in[0];
    always @(posedge pll_hbm) land_d <= {epoch_in, co_in[281:1]};
    wire [296:0] mem_rd;
    reg [AW:0] wp, rp, bs;
    wire [AW:0] filled = wp - bs;
    wire ready = (MUT == 3) ? 1'b1 : (MUT == 2) ? (filled >= C_BLK1) : (filled >= C_BLK);

    (* keep *) reg go_q;
    always @(posedge pll_hbm or negedge hr) if (!hr) go_q <= 1'b0; else go_q <= blk_go;
    reg [PW-1:0] pending;
    (* keep, ot_rst_split *) reg [25:0] emitting__qv;
    wire emitting = emitting__qv[0];
    reg [BW-1:0] cnt;
    reg [SW-1:0] sc;
    wire last = emitting && sc == C_S1 && cnt == C_B1;
    wire idle_next = !emitting || last;
    wire start = pending != 0 && idle_next && ready;
    wire take = emitting && sc == C_S1;
    // KV-PC2: emitting as master + identical copies (the copies' own-Q hold made bit 0 a DFFE and the family REFUSED by
    // ot_rst_copies, gate 164813: 590 loads on one flop).  emitting_m holds the state; every copy loads emitting_nx.
    (* keep *) reg emitting_m;
    wire emitting_nx = start ? 1'b1 : (last ? 1'b0 : emitting_m);
    always @(posedge pll_hbm or negedge hr)
        if (!hr) begin emitting_m <= 1'b0; emitting__qv <= 26'd0; end
        else begin emitting_m <= emitting_nx; emitting__qv <= {26{emitting_nx}}; end
    reg put_q;
    reg [296:0] out_q;

    // storage: registered read of mem[ra(t)] issued at t-1 with ra(t) = ra + take (the original pointer copies advance
    // on take exactly as rp).  A same-edge write to that entry blocks the read (no physical collision).
    reg [AW-1:0] ra;
    wire [AW-1:0] ra_next = (MUT == 5) ? ra : take ? ra + 1'b1 : ra;
    wire w_hit = land_v && wp[AW-1:0] == ra_next;
`ifdef OT_KVPC_FRONT_MUT4
    localparam integer RAM_MUT = 1;                 // tile-bench mutant: bank permutation inside the tile
`else
    localparam integer RAM_MUT = (MUT == 4) ? 1 : 0;
`endif
    qkd_kvpc_ram2c #(.WORDS(DEPTH), .BITS(297), .NW(1), .WCLK_MAP(64'd0), .MUT(RAM_MUT)) u_mem (
        .wclk(pll_hbm), .rclk(pll_hbm), .r_ce(!w_hit), .r_addr(ra_next), .rd(mem_rd),
        .w_ce({5{land_v}}), .w_addr(wp[AW-1:0]), .wd(land_d));
`ifndef SYNTHESIS
    reg blk_q;
    always @(posedge pll_hbm) begin
        blk_q <= w_hit;
        if (blk_q && take && hr && MUT == 0) $error("qkd_kvpc_s_front: a consumed read collided with its write");
    end
`endif

    always @(posedge pll_hbm or negedge hr)
        if (!hr) begin
            wp <= 0; rp <= 0; bs <= 0; pending <= 0; cnt <= 0; sc <= 0; ra <= C_RA0;
            put_q <= 0; blk_freed <= 0; hold <= 0; stall_edges <= 0; fault_overflow <= 0; fault_go <= 0; idle <= 1'b1;
            occupancy <= 0;
        end else begin
            put_q <= 0; blk_freed <= 0;
            occupancy <= wp - rp;
            idle <= wp == rp && !land_v && pending == 0 && !emitting;
            if (land_v) begin
                wp <= wp + 1'b1;
                if (wp - rp == C_DEPTH) fault_overflow <= 1'b1;
            end
            pending <= pending + (go_q ? C_P1 : C_P0) - (start ? C_P1 : C_P0);
            if (go_q && pending == C_NBLK) fault_go <= 1'b1;
            hold <= pending != 0 && idle_next && !ready;
            if (pending != 0 && idle_next && !ready && stall_edges != 16'hffff) stall_edges <= stall_edges + 1'b1;
            if (emitting) begin
                sc <= (sc == C_S1) ? C_S0 : sc + 1'b1;
                if (take) begin
                    put_q <= 1'b1; rp <= rp + 1'b1; cnt <= cnt + 1'b1; ra <= ra + 1'b1;
                    if (last) blk_freed <= 1'b1;
                end
            end
            if (start) begin cnt <= 0; sc <= C_S1; bs <= bs + C_BLK; end
        end
    always @(posedge pll_hbm) if (take) out_q <= mem_rd;
    assign co_out = {out_q[280:0], put_q};
    assign epoch_out = out_q[296:281];
    assign compiled_hbm_put = put_q;
endmodule

// ---- static return ring (qkd_static_kv_return_slots_mc_nc successor) ---------------------------------------------
// KV-PC2 10-19: the banks WRITE on pll_hbm (the clock of hd / write_slot / wp / published, which launch the write) and
// read on ck: a real dual-clock FIFO.  The crossing is the per-slot published / consumed toggle bits through 2-flop
// synchronisers (one bit per slot, each toggles once per wrap: no multi-bit skew), and a slot is read only after its
// toggle is visible on ck (fault_core flags a compiled read of an unpublished slot).  No storage-root clocks, no
// same-phase claim (sr1 wrote on pll_hbm_data[k]; port kept unused).
// (sr1 text:) 8 x 288 on 5 banks: bank k writes on its storage root pll_hbm_data[min(k,3)] (HBM clock family), reads on ck.  The 16
// read-pointer copies (rq) are gone: one registered read of slot rp(t) = rp + slot issued at t-1.  Everything else is
// the original.
module qkd_kvpc_s_return #(parameter integer DEPTH = 8, parameter integer MUT = 0)(   // MUT 1 bank permutation, 2 no prefetch
 input wire pll_hbm,hrst,ck,rsi,
 input wire [3:0] pll_hbm_data,
 input wire [281:0] controller_co,input wire [15:0] controller_epoch,
 input wire compiled_hbm_put,
 input wire expected_put,input wire [9:0] expected_sector,
 input wire [15:0] expected_epoch,input wire [5:0] expected_layer,
 output reg actual_valid,output reg [9:0] actual_sector,
 output reg [15:0] actual_epoch,output reg [5:0] actual_layer,
 output reg [255:0] actual_data,output reg fault_hbm,output reg fault_core,
 output reg idle_hbm,output reg idle_core
);
 localparam integer AW=$clog2(DEPTH);
 initial if(DEPTH<4 || (DEPTH&(DEPTH-1))!=0 || DEPTH>32)$error("static return depth must be power of two 4..32");
 // item 3: hr (44 loads), rs_c (51), slot (61) are kept copy families
 (* keep, ot_rst_split *)reg [1:0] hr__qv;
 wire hr=hr__qv[0];
 always @(posedge pll_hbm)hr__qv<={2{hrst}};
 (* keep *)reg rs_a,rs_b;
 (* keep, ot_rst_split *)reg [2:0] rs_c__qv;
 wire rs_c=rs_c__qv[0];
 always @(posedge ck)begin rs_a<=rsi;rs_b<=rsi;rs_c__qv<={3{rsi}};end
 (* keep *)reg observed,write_slot;
 (* keep *)reg [287:0] hd;
 always @(posedge pll_hbm)hd<={controller_epoch,controller_co[17:12],controller_co[11:9],controller_co[7:1],controller_co[281:26]};
 always @(posedge pll_hbm or negedge hr)
  if(!hr)begin observed<=0;write_slot<=0;end
  else begin observed<=controller_co[0];write_slot<=compiled_hbm_put;end
 (* keep, ot_rst_split *)reg [2:0] slot__qv;
 wire slot=slot__qv[0];
 (* keep *)reg [31:0] meta;
 always @(posedge ck)meta<={expected_epoch,expected_layer,expected_sector};
 always @(posedge ck or negedge rs_c)if(!rs_c)slot__qv<=3'd0;else slot__qv<={3{expected_put}};
 wire [287:0] read_data;
 reg [DEPTH-1:0] published,consumed,observed_valid;
 (* async_reg="true" *)reg [DEPTH-1:0] pub_sync1,pub_sync2,done_sync1,done_sync2;
 (* keep *)reg idle_hbm_pre;
 always @(posedge pll_hbm or negedge hr)
  if(!hr)idle_hbm_pre<=0;
  else idle_hbm_pre<=(published==done_sync2) && !observed && !write_slot;
 always @(posedge pll_hbm)idle_hbm<=hr && idle_hbm_pre && !observed && !write_slot;
 (* keep *)reg idle_core_pre,slot_d;
 always @(posedge ck or negedge rs_c)
  if(!rs_c)idle_core_pre<=0;
  else idle_core_pre<=(pub_sync2==consumed) && !slot && !slot_d;
 always @(posedge ck)idle_core<=rs_c && idle_core_pre && !slot;
 reg [AW:0] wp,rp;
 wire [AW-1:0] wa=wp[AW-1:0];
`ifdef OT_KV_RETURN_MUT_READ_ADDR
 wire [AW-1:0] ra=rp[AW-1:0]+1'b1;
`else
 wire [AW-1:0] ra=rp[AW-1:0];
`endif
 // registered read issued one ck edge early: the address the original reads at edge t is ra(t) = ra + slot
 wire [AW-1:0] ra_next = (MUT == 2) ? ra : slot ? ra + 1'b1 : ra;
 (* keep *)reg fault_hbm_s,fault_core_s;
 wire fault_hbm_set=(observed !== write_slot) || (write_slot && done_sync2[wa] !== wp[AW]);
 wire fault_core_set=slot && (pub_sync2[ra] !== ~rp[AW] || observed_valid[ra] !== 1'b1 || read_data[287:256] !== meta);
 always @(posedge pll_hbm or negedge hr)
  if(!hr)begin wp<=0;published<=0;observed_valid<=0;done_sync1<=0;done_sync2<=0;fault_hbm_s<=0;end
  else begin
   done_sync1<=consumed;done_sync2<=done_sync1;
   if(fault_hbm_set)fault_hbm_s<=1;
   if(write_slot)begin
    published[wa]<=~wp[AW];observed_valid[wa]<=observed;
    wp<=wp+1'b1;
   end
  end
 always @(posedge pll_hbm)fault_hbm<=hr && (fault_hbm_s || fault_hbm_set);
 qkd_kvpc_ram2c #(.WORDS(DEPTH), .BITS(288), .NW(1), .WCLK_MAP(64'd0), .MUT(MUT == 1 ? 1 : 0)) u_mem (
  .wclk(pll_hbm), .rclk(ck), .r_ce(1'b1), .r_addr(ra_next), .rd(read_data),
  .w_ce({5{hr && write_slot}}), .w_addr(wa), .wd(hd));
 always @(posedge ck or negedge rs_b)
  if(!rs_b)begin pub_sync1<=0;pub_sync2<=0;end
  else begin pub_sync1<=published;pub_sync2<=pub_sync1;end
 always @(posedge ck or negedge rs_a)
  if(!rs_a)begin rp<=0;consumed<=0;actual_valid<=0;slot_d<=0;fault_core_s<=0;end
  else begin
   actual_valid<=slot;slot_d<=slot;
   if(fault_core_set)fault_core_s<=1;
   if(slot)begin
    actual_data<=read_data[255:0];actual_sector<=read_data[265:256];
    actual_layer<=read_data[271:266];actual_epoch<=read_data[287:272];
    consumed[ra]<=~rp[AW];rp<=rp+1'b1;
   end
  end
 always @(posedge ck)fault_core<=rs_a && (fault_core_s || fault_core_set);
endmodule

// ---- dual-clock Gray FIFO (ot_async_fifo EXT_RST 0, default build) with the array in native banks -----------------
// Pointer, reset-conditioner, online-rendezvous and flag logic are ot_async_fifo's, line for line (no OT_* variant
// defines).  rd_data(t) = mem[rd_bin(t)] is read at t-1 at rd_bin_next.
module ot_async_fifo_kvpc_s #(
    parameter integer WIDTH = 32,
    parameter integer DEPTH = 8,
    parameter integer MUT = 0,     // 1 bank permutation, 2 read at rd_bin (no prefetch)
    parameter integer SRAM = 1     // 0: flop array (the 1-bit credit FIFO), read as ot_async_fifo
) (
    input  wire             wr_clk,
    input  wire             wr_rst_n,
    input  wire             wr_valid,
    output wire             wr_ready,
    input  wire [WIDTH-1:0] wr_data,
    output reg              wr_overflow,
    input  wire             rd_clk,
    input  wire             rd_rst_n,
    output wire             rd_valid,
    input  wire             rd_ready,
    output wire [WIDTH-1:0] rd_data,
    output reg              rd_underflow
);
    initial begin
        if (DEPTH < 4 || (DEPTH & (DEPTH-1)) != 0 || DEPTH > 32)
            $error("ot_async_fifo_kvpc_s DEPTH must be a power of two 4..32");
    end
    localparam integer ADDR_W = $clog2(DEPTH);
    localparam integer PTR_W = ADDR_W + 1;
    wire fifo_async_rst_n = wr_rst_n && rd_rst_n;
    // the two reset conditioners of ot_async_fifo (ot_reset_sync, 2 stages each), inline: the released stage is a kept
    // copy family (item 3: the credit FIFO conditioner drove 74 loads), same release edge
    (* async_reg = "true" *) reg wr_rs1, rd_rs1;
    (* keep, ot_rst_split *) reg [3:0] wr_rs2__qv;
    (* keep, ot_rst_split *) reg [3:0] rd_rs2__qv;
    wire wr_domain_rst_n = wr_rs2__qv[0];
    wire rd_domain_rst_n = rd_rs2__qv[0];
    always @(posedge wr_clk or negedge fifo_async_rst_n)
        if (!fifo_async_rst_n) begin wr_rs1 <= 1'b0; wr_rs2__qv <= 4'd0; end
        else begin wr_rs1 <= 1'b1; wr_rs2__qv <= {4{wr_rs1}}; end
    always @(posedge rd_clk or negedge fifo_async_rst_n)
        if (!fifo_async_rst_n) begin rd_rs1 <= 1'b0; rd_rs2__qv <= 4'd0; end
        else begin rd_rs1 <= 1'b1; rd_rs2__qv <= {4{rd_rs1}}; end
    reg [PTR_W-1:0] wr_bin, wr_gray;
    reg [PTR_W-1:0] rd_bin, rd_gray;
    (* async_reg = "true" *) reg [PTR_W-1:0] rd_gray_w1, rd_gray_w2;
    (* async_reg = "true" *) reg [PTR_W-1:0] wr_gray_r1, wr_gray_r2;
    reg wr_online, rd_online;
    (* async_reg = "true" *) reg rd_online_w1, rd_online_w2;
    (* async_reg = "true" *) reg wr_online_r1, wr_online_r2;
    wire [PTR_W-1:0] wr_gray_seam=wr_gray,rd_gray_seam=rd_gray;
    wire wr_online_seam=wr_online,rd_online_seam=rd_online;
    reg wr_full, rd_empty;
    wire wr_fire = wr_valid && wr_ready;
    wire rd_fire = rd_valid && rd_ready;
    wire [PTR_W-1:0] wr_increment = {{(PTR_W-1){1'b0}},wr_fire};
    wire [PTR_W-1:0] wr_bin_next = wr_bin + wr_increment;
    wire [PTR_W-1:0] wr_gray_next = (wr_bin_next >> 1) ^ wr_bin_next;
    wire [PTR_W-1:0] rd_increment = {{(PTR_W-1){1'b0}},rd_fire};
    wire [PTR_W-1:0] rd_bin_next = rd_bin + rd_increment;
    wire [PTR_W-1:0] rd_gray_next = (rd_bin_next >> 1) ^ rd_bin_next;
    wire wr_full_next;
    wire rd_empty_next;
    assign wr_full_next = (wr_gray_next ==
                           {~rd_gray_w2[PTR_W-1:PTR_W-2],
                            rd_gray_w2[PTR_W-3:0]});
    assign rd_empty_next = (rd_gray_next == wr_gray_r2);
    assign wr_ready = wr_domain_rst_n && rd_online_w2 && !wr_full;
    assign rd_valid = rd_domain_rst_n && wr_online_r2 && !rd_empty;
    // storage: native banks; the write is the original's (inside the wr_domain_rst_n-released branch, on wr_fire)
    generate if (SRAM != 0) begin : g_sram
        qkd_kvpc_ram2c #(.WORDS(DEPTH), .BITS(WIDTH), .NW(1), .WCLK_MAP(64'd0), .MUT(MUT == 1 ? 1 : 0)) u_mem (
            .wclk(wr_clk), .rclk(rd_clk), .r_ce(1'b1), .r_addr(MUT == 2 ? rd_bin[ADDR_W-1:0] : rd_bin_next[ADDR_W-1:0]),
            .rd(rd_data), .w_ce({((WIDTH + 63) / 64){wr_domain_rst_n && wr_fire}}), .w_addr(wr_bin[ADDR_W-1:0]),
            .wd(wr_data));
    end else begin : g_flop
        reg [WIDTH-1:0] mem [0:DEPTH-1];
        assign rd_data = mem[rd_bin[ADDR_W-1:0]];
        always @(posedge wr_clk) if (wr_domain_rst_n && wr_fire) mem[wr_bin[ADDR_W-1:0]] <= wr_data;
    end endgenerate

    always @(posedge wr_clk or negedge wr_domain_rst_n) begin
        if (!wr_domain_rst_n) begin
            rd_gray_w1 <= {PTR_W{1'b0}};
