// ---- read tag queue of qkd_ctrl_pc_sched_nc: tq[0:63] x 34 (one clock) -------------------------------------------
// Even entries in bank 0, odd in bank 1 (row = index >> 1).  The two heads the scheduler reads every edge, h0 = tq[tr]
// and h1 = tq[tr1] (tr1 == tr + 1 always), are in different banks: each bank is read once per edge, issued at t-1 at
// the pointers' next values.  A write at t-1 to an entry read at t is bypassed from a register (exact, every edge).
module qkd_kvpc_s_tq #(parameter integer TQD = 64, parameter integer MUT = 0)(   // MUT 1: bypass dropped
    input wire clk,
    input wire we,
    input wire [$clog2(TQD)-1:0] wa,
    input wire [33:0] wd,
    input wire [$clog2(TQD)-1:0] a0_next,      // tr(t) presented at t-1
    output wire [33:0] h0,                     // tq[tr(t)] at edge t (as the flop array)
    output wire [33:0] h1                      // tq[tr(t) + 1]
);
    localparam integer A = $clog2(TQD);
    initial if (TQD != 64) $error("qkd_kvpc_s_tq: TQD must be 64 (2 x 32-row banks)");
    wire [A-1:0] a1_next = a0_next + 1'b1;
    wire s = a0_next[0];
    wire [A-2:0] ra_e = s ? a1_next[A-1:1] : a0_next[A-1:1];
    wire [A-2:0] ra_o = s ? a0_next[A-1:1] : a1_next[A-1:1];
    wire hit0 = we && wa == a0_next, hit1 = we && wa == a1_next;
    wire [63:0] rd_e, rd_o;
    ot_sram_1r1w2c_32x64_m1 u_e (.wclk(clk), .rclk(clk), .r_ce_in(!(we && !wa[0] && wa[A-1:1] == ra_e)),
        .r_addr_in(ra_e), .rd_out(rd_e), .w_ce_in(we && !wa[0]), .w_addr_in(wa[A-1:1]), .wd_in({30'd0, wd}),
        .w_mask_in({64{1'b1}}));
    ot_sram_1r1w2c_32x64_m1 u_o (.wclk(clk), .rclk(clk), .r_ce_in(!(we && wa[0] && wa[A-1:1] == ra_o)),
        .r_addr_in(ra_o), .rd_out(rd_o), .w_ce_in(we && wa[0]), .w_addr_in(wa[A-1:1]), .wd_in({30'd0, wd}),
        .w_mask_in({64{1'b1}}));
    reg s_q, b0_q, b1_q;
    reg [33:0] bd_q;
    always @(posedge clk) begin
        s_q <= s;
        b0_q <= (MUT == 1) ? 1'b0 : hit0;
        b1_q <= (MUT == 1) ? 1'b0 : hit1;
        bd_q <= wd;
    end
    wire [33:0] m0 = s_q ? rd_o[33:0] : rd_e[33:0];
    wire [33:0] m1 = s_q ? rd_e[33:0] : rd_o[33:0];
    assign h0 = b0_q ? bd_q : m0;
    assign h1 = b1_q ? bd_q : m1;
endmodule

