#!/usr/bin/env python3
"""Behavioural Verilog models of the ASAP7 combinational cells used by a netlist, from the liberty 'function'
attributes; sequential cells (DFFHQNx1, DFFASRHQNx1, ICGx1, TIE*) are written by hand from the liberty ff/statetable.
usage: gen_cells.py NETLIST OUT.v LIB...   (LEC-ICG-2 co-simulation; independent of tools/die_plan/lec.py)"""
import gzip, re, sys

net, out, libs = sys.argv[1], sys.argv[2], sys.argv[3:]
used = set()
for line in open(net):
    m = re.match(r'\s+([A-Za-z0-9_]+_ASAP7_75t_R)\s', line)
    if m:
        used.add(m.group(1))

HAND = {
    'DFFHQNx1_ASAP7_75t_R': '''module DFFHQNx1_ASAP7_75t_R(input CLK, input D, output QN);
  reg q = 1'b0; always @(posedge CLK) q <= D; assign QN = ~q;
endmodule''',
    # liberty: ff (IQN) clear "!SETN" (IQN=0, Q=1), preset "!RESETN" (IQN=1, Q=0), both low: clear_preset_var1 L -> Q=1
    'DFFASRHQNx1_ASAP7_75t_R': '''module DFFASRHQNx1_ASAP7_75t_R(input CLK, input D, input RESETN, input SETN, output QN);
  reg q = 1'b0;
  always @(posedge CLK or negedge RESETN or negedge SETN)
    if (!SETN) q <= 1'b1; else if (!RESETN) q <= 1'b0; else q <= D;
  assign QN = ~q;
endmodule''',
    # liberty statetable: IQ follows ENA|SE while CLK is low; GCLK = CLK & IQ
    'ICGx1_ASAP7_75t_R': '''module ICGx1_ASAP7_75t_R(input CLK, input ENA, input SE, output GCLK);
  reg iq = 1'b0;
  /* verilator lint_off COMBDLY */
  always_latch if (!CLK) iq = ENA | SE;
  /* verilator lint_on COMBDLY */
  assign GCLK = CLK & iq;
endmodule''',
    'TIEHIx1_ASAP7_75t_R': 'module TIEHIx1_ASAP7_75t_R(output H); assign H = 1\'b1; endmodule',
    'TIELOx1_ASAP7_75t_R': 'module TIELOx1_ASAP7_75t_R(output L); assign L = 1\'b0; endmodule',
}

text = ''
for lib in libs:
    op = gzip.open if lib.endswith('.gz') else open
    with op(lib, 'rt') as f:
        text += f.read()

def cells(txt):
    for m in re.finditer(r'\n\s*cell\s*\(\s*"?([A-Za-z0-9_]+)"?\s*\)\s*\{', txt):
        name = m.group(1)
        i = m.end(); depth = 1
        while depth:
            c = txt[i]
            depth += (c == '{') - (c == '}')
            i += 1
        yield name, txt[m.end():i]

def pins(body):
    for m in re.finditer(r'\n\s*pin\s*\(\s*"?([A-Za-z0-9_]+)"?\s*\)\s*\{', body):
        i = m.end(); depth = 1
        while depth:
            c = body[i]; depth += (c == '{') - (c == '}'); i += 1
        pb = body[m.end():i]
        d = re.search(r'direction\s*:\s*"?(\w+)', pb).group(1)
        fn = re.search(r'\bfunction\s*:\s*"([^"]*)"', pb)
        yield m.group(1), d, fn.group(1) if fn else None

def vexpr(fn):
    s = fn.replace('!', '~').replace('*', '&').replace('+', '|')
    # implicit AND: identifier or ')' followed by space(s) and identifier / '(' / '~'
    s = re.sub(r'([A-Za-z0-9_)])\s+(?=[A-Za-z(~])', r'\1 & ', s)
    return s

out_mods = []
lib_cells = dict(cells(text))
missing = []
for c in sorted(used):
    if c in HAND:
        out_mods.append(HAND[c]); continue
    if c not in lib_cells:
        missing.append(c); continue
    ps = list(pins(lib_cells[c]))
    ins = [p for p, d, _ in ps if d == 'input']
    outs = [(p, f) for p, d, f in ps if d == 'output']
    if any(f is None for _, f in outs):
        missing.append(c); continue
    hdr = ', '.join([f'input {p}' for p in ins] + [f'output {p}' for p, _ in outs])
    body = '\n'.join(f'  assign {p} = {vexpr(f)};' for p, f in outs)
    out_mods.append(f'module {c}({hdr});\n{body}\nendmodule')
if missing:
    sys.exit('no model for: ' + ' '.join(missing))
open(out, 'w').write('// generated by gen_cells.py from ' + ' '.join(libs) + '\n' + '\n'.join(out_mods) + '\n')
print(f'{len(out_mods)} cell models -> {out}')
