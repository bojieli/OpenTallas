# HEAD-CORE-LAT v2 kit: copy kit inputs (no run), centred island + ROM moves (island_spec), F4 chain leaves, structured CTS args
import json,os,re,shutil,sys
src,dst,short,spec=sys.argv[1:5]
S=json.load(open(spec)); mod='ot_s81hd_%s_cv'%short; t=S['types'][mod]
os.makedirs(dst,exist_ok=True)
for f in os.listdir(src):
    if f in ('run','trial.log') or f.startswith(('gate','cts_gate','sta_','4_')): continue
    p=os.path.join(src,f)
    (shutil.copytree(p,os.path.join(dst,f),dirs_exist_ok=True) if os.path.isdir(p) else shutil.copy2(p,dst))
# io: replace clk/rst_n lines
io=[l for l in open(dst+'/io.tcl').read().splitlines() if not re.match(r'place_pin -pin_name \{(clk|rst_n)\}',l)]
for pn,p in t['pins'].items():
    io.append('place_pin -pin_name {%s} -layer %s -location {%.4f %.4f} -pin_size {0.1920 0.1920}'%(pn,p['layer'],p['xy'][0],p['xy'][1]))
open(dst+'/io.tcl','w').write('\n'.join(io)+'\n')
# macro_place: ROM sites + island hook
mp=open(dst+'/macro_place.tcl').read()
mp=mp[:mp.find('# GENERATED by tools/s81_head/infra_island.py')] if 'infra_island.py' in mp else mp
roms=' '.join('u_m.u_rom%d %s %s %s'%(k,r[0],r[1],r[2]) for k,r in enumerate(t['roms']))
mp=re.sub(r'foreach \{name x y orient\} \{[^}]*\}','foreach {name x y orient} {%s}'%roms,mp)
open(dst+'/macro_place.tcl','w').write(mp+'\n'+open((os.path.dirname(spec) or '.')+'/island_%s.tcl'%short).read())
c=open(dst+'/config.mk').read()
c+='''
# HEAD-CORE-LAT v2 (METHODOLOGY 12.8): clock entry at the core centre (island), ROMs moved apart about the centre,
# structured tree: equal-load leaf clusters (16 sinks / 20 um), zero-logic Q->D chain pairs on one leaf (F4), no tap
# alignment / padding / clock ECO.  Target 250 TT / 202.5 FF at the clk pin (gate on 5_1_grt GRT RC).
override export CTS_ARGS = -sink_clustering_enable -repair_clock_nets -delay_buffer_derate 0.5 -sink_clustering_max_diameter 20 -sink_clustering_size 16 -balance_levels -dont_use_dummy_load
override export OT_F4_NEXT_TCL = %s
override export POST_CTS_TCL = /work/f4_chain_leaf.tcl
override export PRE_CTS_TCL = /work/noop.tcl
override export OT_VCLK_TT = 250
override export OT_VCLK_FF = 202.5
''' % ('/work/post_cts_gate.tcl' if os.path.exists(dst+'/post_cts_gate.tcl') else '')
open(dst+'/config.mk','w').write(c)
print('v2 kit',dst,'pins',t['pins'],'roms',roms)
