"""MESO-INTEG-1 loop bench generator: plan + bind a small region graph with loop-closing crossings, emit a Verilator
bench wired the way clock_landings.py emits a die (root ot_dp_landing_root, child ot_dp_landing_origin syncing the
parent's forwarded start, every crossing an ot_dp_clk_landing_ca with t_rst_n = sender start, rst_n = receiver start,
K/DEPTH/EDGE_FALL/PAD from count_align_bind).  The C++ driver draws region clock phases inside each crossing's derated
d interval and raw-reset release times, and checks every receiver: no fault, ready, q == word(c - K) (local counts).

GRAPH "single" (default, MESO-INTEG-1): one landed partition per region.  GRAPH "multi" (DIE-KV-3/CAORIGIN, COORD
21:14 ASK 3): regions r, a, c hold 2, 2 and 3 landed partitions; count_align_bind gives each region ONE origin
partition and relays its start to the others through two ot_dp_landing_relay flops on the region clock (tx in the
origin partition, rx in the relay partition), exactly as clock_landings.py wires it; every partition counts from its
own start and every ring uses the bind's partition-frame K.
Usage: gen_loop.py REPO OUTDIR [single|multi] [mutant_noshift]"""
import json
import sys
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
graph = sys.argv[3] if len(sys.argv) > 3 else "single"
sys.path.insert(0, str(repo / "tools/die_plan"))
import count_align_bind as CB  # noqa: E402
import count_align_plan as CAP  # noqa: E402

T = 833.0
# region nominal clock phases (ps); d = phase(dst) - phase(src); every crossing's derated interval +-60 ps
PH = dict(r=0, a=310, b=-280, c=520, e=140)
EDGES = [("r", "a"), ("a", "b"), ("b", "c"), ("c", "r"), ("r", "b"), ("a", "c"), ("c", "a"), ("b", "e"), ("e", "r"),
         ("a", "e"), ("e", "c")]
if graph == "multi":
    # partition-level crossings: relayed receivers, relayed senders, relay -> relay, relay-sent tree candidates,
    # and several crossings per region pair (the planner picks the tree port; the origin follows it)
    PREG = dict(r="r", r2="r", a="a", a2="a", b="b", c="c", c2="c", c3="c", e="e")
    EDGES = [("r", "a"), ("a", "b"), ("b", "c"), ("c", "r"), ("r2", "b"), ("a2", "c2"), ("c3", "a"), ("b", "e"),
             ("e", "r2"), ("a", "e"), ("e", "c"), ("c2", "a2"), ("r2", "a2"), ("c3", "r2"), ("a2", "b"), ("b", "c3"),
             ("e", "a2")]
else:
    PREG = {x: x for x in PH}
SPREAD = 60.0
rows = [dict(port=f"{u}{v}", src=PREG[u], dst=PREG[v], d_ps=PH[PREG[v]] - PH[PREG[u]], p_up_ps=SPREAD, p_dn_ps=SPREAD,
             unshared_a_ps=400.0, unshared_b_ps=400.0, margin_ps=0.0) for u, v in EDGES]
parts = {f"{u}{v}": (u, v) for u, v in EDGES} if graph == "multi" else None
summ, o = CAP.plan([dict(r) for r in rows], T, T / 8, 0.05)
b = CB.bind(summ, o, T, 0, parts)
v = CB.verify(b, {r["port"]: r for r in rows}, 500, T / 8, 0.05)
assert not v["identity_and_loop_errors"] and v["sim_window_violations"] == 0, v
if parts and len(sys.argv) > 4 and sys.argv[4] == "mutant_noshift":
    # negative control: ignore the relay offset (region-frame K on every non-tree crossing) -> words must go wrong
    rel = {q: (v["stages"] if v["role"] == "relay" else 0) for q, v in b["parts"].items()}
    for c in b["ports"].values():
        if not c["tree"]:
            c["K"] += rel[c["dst_part"]] - rel[c["src_part"]]
regs = sorted(PH)
qs = sorted(PREG)                    # partitions (== regions for the single graph)
qreg = {q: regs.index(PREG[q]) for q in qs}


def sp(c):
    return (c["src_part"], c["dst_part"]) if parts else (c["src"], c["dst"])


SETTLE = 16
sv = ["// generated by gen_loop.py (MESO-INTEG-1 / DIE-KV-3 CAORIGIN): die-style count-aligned wiring, graph " + graph,
      "module tb_ca_loop (", "    input wire [%d:0] clk, input wire [%d:0] rst_raw_n," % (len(regs) - 1, len(regs) - 1)]
sv += ["    input wire [31:0] d_%s," % x for x in qs]
sv += ["    output wire [31:0] q_%s, output wire rdy_%s, output wire flt_%s," % (p, p, p) for p in sorted(b["ports"])]
sv += ["    output wire [%d:0] start" % (len(qs) - 1), ");"]
role = b.get("parts", {q: dict(role="origin", region=q) for q in qs})
for x in regs:
    i = regs.index(x)
    R = b["regions"][x]
    oq = R.get("origin_part", x)
    k = qs.index(oq)
    if R["parent"] is None:
        sv.append(f"    ot_dp_landing_root #(.SETTLE({SETTLE})) u_o_{x} (.clk(clk[{i}]), .rst_raw_n(rst_raw_n[{i}]), "
                  f".start(start[{k}]));")
    else:
        snd = sp(b["ports"][R["tree_port"]])[0]      # the tree port's sender partition forwards its own start
        sv.append(f"    ot_dp_landing_origin #(.PAD({R['pad']}), .EDGE_FALL({int(R['edge_fall'])})) u_o_{x} (.clk(clk[{i}]), "
                  f".rst_raw_n(rst_raw_n[{i}]), .p_start(start[{qs.index(snd)}]), .start(start[{k}]));")
    rel = [q for q in qs if role[q]["role"] == "relay" and role[q]["region"] == x]
    if rel:
        sv.append(f"    wire rstart_{x};")
        sv.append(f"    ot_dp_landing_relay u_tx_{x} (.clk(clk[{i}]), .rst_raw_n(rst_raw_n[{i}]), .d(start[{k}]), "
                  f".q(rstart_{x}));")
    for q in rel:
        assert role[q]["src"] == oq and role[q]["stages"] == 2
        sv.append(f"    ot_dp_landing_relay u_rx_{q} (.clk(clk[{i}]), .rst_raw_n(rst_raw_n[{i}]), .d(rstart_{x}), "
                  f".q(start[{qs.index(q)}]));")
for p, c in sorted(b["ports"].items()):
    s, t = sp(c)
    sv.append(f"    ot_dp_clk_landing_ca #(.W(32), .DEPTH({c['depth']}), .K({c['K']})) u_{p} (.fclk(clk[{qreg[s]}]), "
              f".t_rst_n(start[{qs.index(s)}]), .clk(clk[{qreg[t]}]), .rst_n(start[{qs.index(t)}]), .d(d_{s}), .q(q_{p}), "
              f".ready(rdy_{p}), .fault(flt_{p}));")
sv.append("endmodule")
(out / "tb_ca_loop.sv").write_text("\n".join(sv) + "\n")
h = [f"static const int NR = {len(regs)}, NQ = {len(qs)}, NP = {len(b['ports'])};",
     "static const long PH[] = {%s};" % ", ".join(str(int(PH[x])) for x in regs),
     "static const int QREG[] = {%s};" % ", ".join(str(qreg[q]) for q in qs),
     "#define DPTRS(m) {%s}" % ", ".join(f"&m.d_{q}" for q in qs),
     "static const long SPREAD = %d;" % int(SPREAD // 2), "#define PORTS(X) \\"]
h += ["  X(%s, %d, %d, %d, %d) \\" % (p, qs.index(sp(c)[0]), qs.index(sp(c)[1]), c["K"], qreg[sp(c)[1]])
      for p, c in sorted(b["ports"].items())]
h.append("")
(out / "loop_params.h").write_text("\n".join(h) + "\n")
(out / "loop_bind.json").write_text(json.dumps(dict(bind=b, verify=v), indent=1) + "\n")
print(json.dumps(dict(graph=graph, regions=regs, partitions=qs, root=b["root"],
                      relay=CB.relay_summary(b) if parts else None,
                      roles={q: [r["role"], r.get("src"), r["n_nominal"]] for q, r in b.get("parts", {}).items()},
                      ports={p: [*sp(c), c["K"], c["depth"], c["sched_lat"], c["tree"]] for p, c in sorted(b["ports"].items())},
                      loops=v["fundamental_cycles"]), indent=None))
