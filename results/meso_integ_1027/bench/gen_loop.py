"""MESO-INTEG-1 loop bench generator: plan + bind a small region graph with loop-closing crossings, emit a Verilator
bench wired the way clock_landings.py emits a die (root ot_dp_landing_root, child ot_dp_landing_origin syncing the
parent's forwarded start, every crossing an ot_dp_clk_landing_ca with t_rst_n = sender start, rst_n = receiver start,
K/DEPTH/EDGE_FALL/PAD from count_align_bind).  The C++ driver draws region clock phases inside each crossing's derated
d interval and raw-reset release times, and checks every receiver: no fault, ready, q == word(c - K) (local counts).
Usage: gen_loop.py REPO OUTDIR"""
import json
import sys
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
sys.path.insert(0, str(repo / "tools/die_plan"))
import count_align_bind as CB  # noqa: E402
import count_align_plan as CAP  # noqa: E402

T = 833.0
# region nominal clock phases (ps); d = phase(dst) - phase(src); every crossing's derated interval +-60 ps
PH = dict(r=0, a=310, b=-280, c=520, e=140)
EDGES = [("r", "a"), ("a", "b"), ("b", "c"), ("c", "r"), ("r", "b"), ("a", "c"), ("c", "a"), ("b", "e"), ("e", "r"),
         ("a", "e"), ("e", "c")]
SPREAD = 60.0
rows = [dict(port=f"{u}{v}", src=u, dst=v, d_ps=PH[v] - PH[u], p_up_ps=SPREAD, p_dn_ps=SPREAD, unshared_a_ps=400.0,
             unshared_b_ps=400.0, margin_ps=0.0) for u, v in EDGES]
summ, o = CAP.plan([dict(r) for r in rows], T, T / 8, 0.05)
b = CB.bind(summ, o, T, 0)
v = CB.verify(b, {r["port"]: r for r in rows}, 500, T / 8, 0.05)
assert not v["identity_and_loop_errors"] and v["sim_window_violations"] == 0, v
regs = sorted(PH)
SETTLE = 16
sv = ["// generated by gen_loop.py (MESO-INTEG-1): die-style count-aligned wiring, one region per clock",
      "module tb_ca_loop (", "    input wire [%d:0] clk, input wire [%d:0] rst_raw_n," % (len(regs) - 1, len(regs) - 1)]
sv += ["    input wire [31:0] d_%s," % x for x in regs]
sv += ["    output wire [31:0] q_%s, output wire rdy_%s, output wire flt_%s," % (p, p, p) for p in sorted(b["ports"])]
sv += ["    output wire [%d:0] start" % (len(regs) - 1), ");"]
for i, x in enumerate(regs):
    R = b["regions"][x]
    if R["parent"] is None:
        sv.append(f"    ot_dp_landing_root #(.SETTLE({SETTLE})) u_o_{x} (.clk(clk[{i}]), .rst_raw_n(rst_raw_n[{i}]), "
                  f".start(start[{i}]));")
    else:
        p = regs.index(R["parent"])
        sv.append(f"    ot_dp_landing_origin #(.PAD({R['pad']}), .EDGE_FALL({int(R['edge_fall'])})) u_o_{x} (.clk(clk[{i}]), "
                  f".rst_raw_n(rst_raw_n[{i}]), .p_start(start[{p}]), .start(start[{i}]));")
for p, c in sorted(b["ports"].items()):
    s, t = regs.index(c["src"]), regs.index(c["dst"])
    sv.append(f"    ot_dp_clk_landing_ca #(.W(32), .DEPTH({c['depth']}), .K({c['K']})) u_{p} (.fclk(clk[{s}]), "
              f".t_rst_n(start[{s}]), .clk(clk[{t}]), .rst_n(start[{t}]), .d(d_{c['src']}), .q(q_{p}), .ready(rdy_{p}), "
              f".fault(flt_{p}));")
sv.append("endmodule")
(out / "tb_ca_loop.sv").write_text("\n".join(sv) + "\n")
h = [f"static const int NR = {len(regs)}, NP = {len(b['ports'])};",
     "static const long PH[] = {%s};" % ", ".join(str(int(PH[x])) for x in regs),
     "static const long SPREAD = %d;" % int(SPREAD // 2), "#define PORTS(X) \\"]
h += ["  X(%s, %d, %d, %d) \\" % (p, regs.index(c["src"]), regs.index(c["dst"]), c["K"]) for p, c in sorted(b["ports"].items())]
h.append("")
(out / "loop_params.h").write_text("\n".join(h) + "\n")
(out / "loop_bind.json").write_text(json.dumps(dict(bind=b, verify=v), indent=1) + "\n")
print(json.dumps(dict(regions=regs, root=b["root"], ports={p: [c["src"], c["dst"], c["K"], c["depth"], c["sched_lat"],
                      c["tree"]] for p, c in sorted(b["ports"].items())}, loops=v["fundamental_cycles"]), indent=None))
