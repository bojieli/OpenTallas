#!/usr/bin/env python3
"""Build reference.sv from the VERBATIM selected dsdv_svc_att.sv rowword function and kc_w loop (RX=0, no OT_SVC_ALLQ).

The reference is the unchanged native land helper (native_memory.sv, 4c805) read at the bound addresses 4*(rc-1)+j, the
verbatim rowword/kc_w composition, and the unconditional ekv_w <= kc_w capture.  Refuses any att source other than 107c4a.
"""
import hashlib, sys
from pathlib import Path

ATT_SHA = "107c4addac40494f621b463ca40a58bb47e560acddfc8d261aa1fe60c1ae5a88"
att = Path(sys.argv[1])
out = Path(sys.argv[2])
b = att.read_bytes()
if hashlib.sha256(b).hexdigest() != ATT_SHA:
    sys.exit("att source hash mismatch")
L = b.decode().splitlines()
rowword = L[433:441]          # lines 434-441
loop = L[468:482]             # lines 469-482 (second for-loop of the kc_w always block)
assert rowword[0].lstrip().startswith("function automatic [264:0] rowword")
assert loop[0].strip() == "for (j = 0; j < NL; j = j + 1) begin" and "rel_bad[j] = need && !ok;" in loop[-3]
ifdef_at = [i for i, s in enumerate(loop) if s.strip().startswith("`ifdef OT_SVC_ALLQ")]
assert len(ifdef_at) == 1
body = "\n".join(loop)
src = f"""// GENERATED by prepare_reference.py from dsdv_svc_att.sv sha256 {ATT_SHA} lines 434-441 and 469-482 (verbatim).
module land_reference #(parameter integer NL = 4) (
    input  wire clk,
    input  wire [9:0] rc, input wire [9:0] tjob, input wire [7:0] wcount, input wire [20:0] wfirst,
    input  wire [1023:0] wsc, input wire [511:0] sel_held, input wire [3:0] tile, input wire [1:0] st_r,
    input  wire [639:0] pres, input wire [3:0] spres,
    input  wire [1023:0] RD_DATA, output wire [127:0] RD_ADDR,
    output reg  [NL*265-1:0] ekv_w, output reg [NL-1:0] ekv_m);
    reg [NL-1:0] kc_m; reg [NL*265-1:0] kc_w; reg [NL-1:0] rel_bad;
{chr(10).join(rowword)}
    // bound read addresses (bound537/542/547/552_Y): 4*(rc-1)+j, 32 bits
    genvar ga;
    for (ga = 0; ga < NL; ga = ga + 1) begin : g_ra
        assign RD_ADDR[32*ga +: 32] = 4 * (32'(rc) - 1) + ga;
    end
    reg [255:0] lrd [0:NL-1];
    integer j;
    integer row; reg need, ok;
    always @(*) begin
        kc_w = '0; kc_m = '0; rel_bad = '0; row = 0; need = 1'b0; ok = 1'b0;
        for (j = 0; j < NL; j = j + 1) lrd[j] = RD_DATA[256*j +: 256];
{body}
    end
    always @(posedge clk) begin
        ekv_w <= kc_w; ekv_m <= kc_m;
    end
endmodule
"""
out.write_text(src)
print("reference written", out, hashlib.sha256(src.encode()).hexdigest())
