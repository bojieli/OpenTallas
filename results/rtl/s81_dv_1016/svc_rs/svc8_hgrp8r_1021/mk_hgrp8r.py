#!/usr/bin/env python3
"""hgrp8 -> hgrp8r: every ot_sram_1r1w_32x64_m1 instance becomes ot_s81svc8_sram_wreg (write inputs registered at
the macro face).  Only the top module name and the 17 macro instance master names change; every other byte is
identical to svc8_hgrp8_bounded.v."""
import re, sys, hashlib
src, dst = sys.argv[1], sys.argv[2]
t = open(src).read()
old_top = 'module ot_s81svc8_hgrp_s81_bounded('
assert t.count(old_top) == 1
t = t.replace(old_top, 'module ot_s81svc8_hgrp8r_s81_bounded(')
pat = re.compile(r'^(  )ot_sram_1r1w_32x64_m1( c\d+ \()$', re.M)
t, n = pat.subn(r'\1ot_s81svc8_sram_wreg\2', t)
assert n == 17, n
assert 'ot_sram_1r1w_32x64_m1 ' not in t
t = t.replace('/* Generated by Yosys', '/* hgrp8r (claude/s81-hgrp8r-1021): svc8_hgrp8_bounded.v with the 17 ring SRAMs wrapped by\n   ot_s81svc8_sram_wreg (registered w_ce/w_addr/wd at the macro face; ring delay unchanged, D>=4).\n   Generated by Yosys', 1)
open(dst, 'w').write(t)
print('instances', n, 'sha256', hashlib.sha256(t.encode()).hexdigest(), 'bytes', len(t))
