#!/usr/bin/env python3
"""Writes mutants.sv: four renamed copies of the unchanged staging module, each with one injected macro-path fault."""
from pathlib import Path
src = Path(__file__).with_name('staging.sv').read_text()
body = src[src.index('module ot_hdc_v41x_attn_staging'):]
muts = {
    1: ('.wd_in(padded_in[b*256 +: 256]),\n                    .w_mask_in({256{1\'b1}}), .rr_en(2\'b0), .rr_addr(14\'b0),',
        '.wd_in(padded_in[0 +: 256]),\n                    .w_mask_in({256{1\'b1}}), .rr_en(2\'b0), .rr_addr(14\'b0),'),
    2: ('.w_ce_in(wr_en[l]), .w_addr_in({{(8-AW){1\'b0}}, wr_addr}),',
        '.w_ce_in(wr_en[(l+1)%NL]), .w_addr_in({{(8-AW){1\'b0}}, wr_addr}),'),
    3: ('.clk(clk), .r_ce_in(1\'b1), .r_addr_in({{(8-AW){1\'b0}}, rd_addr}),',
        '.clk(clk), .r_ce_in(1\'b1), .r_addr_in({{(8-AW){1\'b0}}, rd_addr ^ AW\'(1)}),'),
    4: ('assign rd_data[l*ROWW +: ROWW] = padded_out[ROWW-1:0];',
        'reg [ROWW-1:0] fwd; reg hit; always @(posedge clk) begin hit <= wr_en[l] && wr_addr == rd_addr; fwd <= wr_data[l*ROWW +: ROWW]; end\n            assign rd_data[l*ROWW +: ROWW] = hit ? fwd : padded_out[ROWW-1:0];'),
}
out = []
for k, (old, new) in muts.items():
    assert body.count(old) == 1, (k, old)
    out.append(body.replace('module ot_hdc_v41x_attn_staging', f'module stg_mut{k}', 1).replace(old, new))
Path(__file__).with_name('mutants.sv').write_text('`timescale 1ns/1ps\n// GENERATED by make_mutants.py: negative controls only\n' + '\n'.join(out))
