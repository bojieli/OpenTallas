module terminal_policy;
integer bad=0;
integer de=0;
integer ee=0;
integer errors=0;
integer golden_mismatches=0;
integer mism=0;
integer mismatches=0;
integer nerr=0;
integer ops=0;
integer re=0;
integer results=0;
integer se=0;
integer tmism=0;
integer unit_mismatch=0;
integer which=0; integer allowed_refusals=17, rsq_fm=19;
initial begin
results=1; ops=4;
if (!$value$plusargs("BAD=%d", which)) which=0;
if (which==1) bad=1;
if (which==2) bad=1;
if (which==3) bad=1;
if (which==4) errors=1;
if (which==5) mismatches=1;
if (which==6) bad=1;
if (which==7) mism=1;
if (which==8) de=1;
if (which==9) mism=1;
if (which==10) mism=1;
if (which==11) errors=1;
if (which==12) nerr=1;
if (bad != 0) $fatal(1,"POLICY_FAIL 1");
if (bad != 0) $fatal(1,"POLICY_FAIL 2");
if (bad != 0) $fatal(1,"POLICY_FAIL 3");
if (errors != 0) $fatal(1,"POLICY_FAIL 4");
if (mismatches != 0 || golden_mismatches != 0) $fatal(1,"POLICY_FAIL 5");
if (bad != 0) $fatal(1,"POLICY_FAIL 6");
if (mism != 0 || tmism != 0) $fatal(1,"POLICY_FAIL 7");
if (de != 0 || ee != 0 || re != 0 || se != 0) $fatal(1,"POLICY_FAIL 8");
if (mism != 0) $fatal(1,"POLICY_FAIL 9");
if (!(mism == 0 && results > 0 && ops == 4)) $fatal(1,"POLICY_FAIL 10");
if (errors != 0) $fatal(1,"POLICY_FAIL 11");
if (nerr != 0 || unit_mismatch) $fatal(1,"POLICY_FAIL 12");
$display("PASS terminal policy only"); $finish; end endmodule
