"""S81-KITS-RTLA: apply physical/die_plan/s81/inputs/const_pins_dropped.json (drop + rename) to a kit's pins.json (synth +
face_guard checks only; P&R kits are regenerated by gen_kit_repin).   kitpins.py KITDIR const_pins_dropped.json"""
import json, re, sys
k, L = sys.argv[1:3]
top = re.search(r"^export DESIGN_NAME = (\S+)", open(k + "/config.mk").read(), re.M).group(1)
e = json.load(open(L))["modules"].get(top, {})
gone, ren = set(e.get("pins", ())), e.get("rename", {})
nm = lambda p: p["bus"] if p.get("bit") is None else "%s[%d]" % (p["bus"], p["bit"])
P = json.load(open(k + "/pins.json"))
out = []
for p in P:
    n = nm(p)
    if n in gone:
        continue
    if n in ren:
        b, i = re.match(r"(.+)\[(\d+)\]$", ren[n]).groups(); p = dict(p, bus=b, bit=int(i))
    out.append(p)
json.dump(out, open(k + "/pins.json", "w"), indent=1)
print(top, "pins", len(P), "->", len(out))
