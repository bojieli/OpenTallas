#!/usr/bin/env python3
"""DIE-HEAD-36 (2026-10-29, OWNER (A) fault paths, COORD DIE-HEAD-35-PARK (1)): HEAD source src25q = src25p + sidecar
plan field collector.types[T].local_status_depth for hd_st_str / hd_st_n3_transit / hd_st_m.  Status only, 0 data
cycles, no outline / pin change.  Depth per local status output b = ceil(max Manhattan(local source pin -> b pin) /
450 um) (OWNER repeater reach 450 um), i.e. every hop between consecutive status registers <= 450 um.
The 3 type wrappers are regenerated by gen_rtl.write_rtl (main tools) with and without the field; the textual delta
(only the relay stage lines) is applied to the src25p wrapper files, which are otherwise copied unchanged.
usage: src25q_status_depth.py SRC25P_DIR OUT_DIR [TYPE ...]"""
import difflib, hashlib, json, math, os, shutil, sys, tempfile
from pathlib import Path
ROOT = Path(os.environ.get("OT_ROOT") or Path(__file__).resolve().parents[3])
sys.path[:0] = [str(ROOT / "tools/die_plan")]
import clock_landing_plan as CP, gen_rtl as G
REACH = 450.0
src, out = Path(sys.argv[1]), Path(sys.argv[2])
types = sys.argv[3:] or ["hd_st_str", "hd_st_n3_transit", "hd_st_m"]
if out.exists():
    sys.exit(f"{out} exists")
raw = json.loads((src / "source_plan.json").read_text())
side = json.loads((src / "source_sidecar.json").read_text())
rep = dict(base=str(src), base_sidecar_sha256=hashlib.sha256((src / "source_sidecar.json").read_bytes()).hexdigest(),
           reach_um=REACH, types={})
for tn in types:
    ty = side["collector"]["types"][tn]; t = raw["partition_types"][tn]; tb = ty["mask"].get("tree_bus")
    d = {}
    for b in ty["mask"]["outputs"]:
        if b == tb:
            continue
        o = CP._bus_xy(t, b)
        far = max(abs(s["xy_um"][0] - o[0]) + abs(s["xy_um"][1] - o[1]) for s in ty["local_sources"])
        d[b] = max(1, math.ceil(far / REACH))
        rep["types"][tn] = dict(rep["types"].get(tn, {}), **{b: dict(path_um=round(far, 3), depth=d[b], hop_um=round(far / d[b], 3))})
    assert "local_status_depth" not in ty, tn
    ty["local_status_depth"] = d
shutil.copytree(src, out)
(out / "source_sidecar.json").write_text(json.dumps(side, indent=1))
base_side = json.loads((src / "source_sidecar.json").read_text())
with tempfile.TemporaryDirectory() as tmp:
    a, b = Path(tmp) / "a", Path(tmp) / "b"
    G.write_rtl(json.loads((src / "source_plan.json").read_text()), a, plan_path=str(src / "source_plan.json"), landing=base_side, rtl_root=str(ROOT))
    G.write_rtl(json.loads((src / "source_plan.json").read_text()), b, plan_path=str(src / "source_plan.json"), landing=side, rtl_root=str(ROOT))
    changed = sorted(f.name for f in b.glob("*.sv") if f.read_bytes() != (a / f.name).read_bytes())
    want = sorted(raw["partition_types"][tn]["module"] + ".sv" for tn in types)
    assert changed == want, (changed, want)
    for name in changed:
        old, new = (a / name).read_text().splitlines(True), (b / name).read_text().splitlines(True)
        cur = (src / name).read_text().splitlines(True)
        # apply the generator delta to the src25p file: every changed block must match the src25p file verbatim
        sm = difflib.SequenceMatcher(None, old, new, autojunk=False)
        res, pos = [], 0
        for tag, i1, i2, j1, j2 in sm.get_opcodes():
            if tag == "equal":
                continue
            anchor = old[i1 - 1]                     # last equal line before the change (unique in the file)
            k = [n for n, l in enumerate(cur) if l == anchor]
            assert len(k) == 1, (name, anchor)
            k = k[0] + 1
            assert cur[k:k + (i2 - i1)] == old[i1:i2], (name, i1)
            res += cur[pos:k] + new[j1:j2]; pos = k + (i2 - i1)
        res += cur[pos:]
        (out / name).write_text("".join(res))
        rep["types"].setdefault(name, {})["rtl"] = dict(src_sha256=hashlib.sha256((src / name).read_bytes()).hexdigest(),
            out_sha256=hashlib.sha256((out / name).read_bytes()).hexdigest(),
            lines_added=sum(j2 - j1 for t_, i1, i2, j1, j2 in sm.get_opcodes() if t_ != "equal"),
            lines_removed=sum(i2 - i1 for t_, i1, i2, j1, j2 in sm.get_opcodes() if t_ != "equal"))
rep["sidecar_sha256"] = hashlib.sha256((out / "source_sidecar.json").read_bytes()).hexdigest()
rep["plan_sha256"] = hashlib.sha256((out / "source_plan.json").read_bytes()).hexdigest()
(out / "src25q_report.json").write_text(json.dumps(rep, indent=1))
print(json.dumps(rep, indent=1))
