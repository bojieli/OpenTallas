#!/usr/bin/env python3
"""KV-KITS-8 10-28 (COORD 06:26 ruling, pv_pair DRT-0255): hard placement blockage over every inter-macro channel
narrower than GAP_MAX um (two MACRO_PLACE_HALOs leave a ~2.4-um std-cell strip in an 11-um channel; DRT-0255 x83 in
R0 d64406953e63 / fMX 6454828e359c sat on the W 2x2 cluster channel).  Rects from the kit's own static macro sites
(macro_place.tcl) + LEF SIZE; collinear channel rects whose gap is itself a channel are merged (the 2x2 cross centre).

    macro_channel.py KITDIR   -> writes KITDIR/macro_channel_blk.tcl + macro_channel_blk.json, appends a source line
                                 to KITDIR/pv_tree_pre_gpl.tcl (after the FIRM clock-tree nodes are placed)
The tcl is fail-closed: every rect must touch no macro and no FIRM/PLACED std cell at creation time."""
import json, re, sys
from pathlib import Path

GAP_MAX = 12.0
kd = Path(sys.argv[1])
mp = (kd / "macro_place.tcl").read_text()
m = re.search(r"foreach \{master sites\} \{(\S+) \{(.*?)\}\} \{", mp)
master, sites = m.group(1), re.findall(r"\{([\d.]+) ([\d.]+) (\w+)\}", m.group(2))
lef = next(kd.glob(f"macros/{master}.lef")).read_text()
w, h = map(float, re.search(r"SIZE ([\d.]+) BY ([\d.]+)", lef).groups())
boxes = []
for x, y, o in sites:
    x, y = float(x), float(y)
    ww, hh = (h, w) if o in ("R90", "R270", "MXR90", "MYR90") else (w, h)
    boxes.append((x, y, round(x + ww, 3), round(y + hh, 3)))
rv, rh = [], []
for i, a in enumerate(boxes):
    for b in boxes[i + 1:]:
        for p, q in ((a, b), (b, a)):
            g = q[0] - p[2]                     # p left of q
            lo, hi = max(p[1], q[1]), min(p[3], q[3])
            if 0 < g <= GAP_MAX and hi > lo:
                rv.append((p[2], lo, q[0], hi))
            g = q[1] - p[3]                     # p below q
            lo, hi = max(p[0], q[0]), min(p[2], q[2])
            if 0 < g <= GAP_MAX and hi > lo:
                rh.append((lo, p[3], hi, q[1]))


def merge(rs, ax):
    rs = sorted(set(rs), key=lambda r: (r[ax], r[ax + 2], r[1 - ax]))
    out = []
    for r in rs:
        if out and out[-1][ax] == r[ax] and out[-1][ax + 2] == r[ax + 2] and 0 <= r[1 - ax] - out[-1][3 - ax] <= GAP_MAX:
            o = out[-1]
            out[-1] = (o[0], o[1], r[2], r[3]) if ax == 0 else (o[0], o[1], r[2], r[3])
            out[-1] = tuple(min(o[k], r[k]) if k < 2 else max(o[k], r[k]) for k in range(4))
        else:
            out.append(r)
    return out


rects = merge(rv, 0) + merge(rh, 1)
rects = [tuple(round(v, 3) for v in r) for r in rects]
tcl = ["# GENERATED by results/kv_kits_8_1028/macro_channel.py (KV-KITS-8 10-28, COORD 06:26 pv_pair DRT-0255 ruling):",
       f"# hard placement blockages over the inter-macro channels <= {GAP_MAX} um of {kd.name} ({len(rects)} rects, um).",
       "set mcb_b [ord::get_db_block]", "set mcb_u [[ord::get_db_tech] getDbUnitsPerMicron]", "set mcb_n 0",
       "foreach {x0 y0 x1 y1} {" + " ".join(f"{v:g}" for r in rects for v in r) + "} {",
       "  set X0 [expr {round($x0 * $mcb_u)}]; set Y0 [expr {round($y0 * $mcb_u)}]; set X1 [expr {round($x1 * $mcb_u)}]; set Y1 [expr {round($y1 * $mcb_u)}]",
       "  foreach i [$mcb_b getInsts] {",
       "    if {[$i getPlacementStatus] eq \"NONE\" || [$i getPlacementStatus] eq \"UNPLACED\"} { continue }",
       "    set q [$i getBBox]",
       "    if {[$q xMin] < $X1 && [$q xMax] > $X0 && [$q yMin] < $Y1 && [$q yMax] > $Y0} {",
       "      if {[[$i getMaster] isBlock]} { error \"KV macro channel: rect $x0 $y0 $x1 $y1 overlaps macro [$i getName]\" }",
       "      if {[$i getPlacementStatus] eq \"FIRM\" || [$i getPlacementStatus] eq \"LOCKED\"} { error \"KV macro channel: rect $x0 $y0 $x1 $y1 overlaps fixed cell [$i getName]\" }",
       "    }", "  }",
       "  set k [odb::dbBlockage_create $mcb_b $X0 $Y0 $X1 $Y1]", "  incr mcb_n", "}",
       "puts \"KV macro channel: $mcb_n hard placement blockages over inter-macro channels\""]
(kd / "macro_channel_blk.tcl").write_text("\n".join(tcl) + "\n")
(kd / "macro_channel_blk.json").write_text(json.dumps(dict(master=master, size_um=[w, h], macros=boxes, gap_max_um=GAP_MAX,
                                                           rects_um=rects), indent=1) + "\n")
pre = kd / "pv_tree_pre_gpl.tcl"
t = pre.read_text()
line = "source /work/macro_channel_blk.tcl"
if line not in t:
    pre.write_text(t.rstrip("\n") + "\n" + line + "\n")
print(json.dumps(dict(kit=kd.name, rects=rects)))
