#!/usr/bin/env python3
"""DIE-HBM-10 TOK-HBM-4: C25b as-built -> plan instance map (S role = q0 half, N role = q1) + PHY split map.

Inputs (read-only): the canon map (DIE-HBM-7), the C25b plan, the composed top, the TOK-HBM-2 S-role census and
the C25b S-role fold map. Outputs:
  asbuilt_map_c25b.json   bind map_file: canon parts with
      (1) every hub instance whose plan family has distinct __q0/__q1 hard cores renamed to its OWN half
          (S role -> __q0, N role -> __q1; no S role is an alias of an N instance);
      (2) phy_NW (one 32-PC leaf) -> three C23q slice instances in PHY_NW / PHY_NC / PHY_NE.
  instance_map_c25b.json  per as-built top instance: partition, plan local name, plan module, as-built module,
      as-built params, plan params; plus the 88 S-role fold nets with their q0 serving plan instance status.

usage: mk_c25b_instmap.py CANON_MAP PLAN TOP CENSUS FOLDMAP OUT_DIR
"""
import collections
import hashlib
import json
import re
import sys
from pathlib import Path

HUBS = {"NW_hub", "NE_hub"}
S_ROLE = re.compile(r"(^|_)S[EW](\d*|_.*)?$|_S[EW]\d*$|_S[EW]_")
PHY = {"phy_NW_pc0_9": ["PHY_NW", "u_phy_Q"], "phy_NW_pc10_21": ["PHY_NC", "u_phy_Q"],
       "phy_NW_pc22_31": ["PHY_NE", "u_phy_Q"]}


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def role_of(inst):
    m = re.search(r"_(NW|NE|SW|SE)(?=\d|_|$)", inst)
    return m.group(1) if m else None


def top_instances(top):
    """inst -> (module, param string) from the composed top (one instance header per line)."""
    out = {}
    for m in re.finditer(r"^\s+([A-Za-z_][\w$\\]*)\s+(?:#\((.*?)\)\s+)?([A-Za-z_]\w*)\s*\(\s*$",
                         Path(top).read_text(), re.M):
        if m.group(1) in ("module", "input", "output", "wire", "assign"):
            continue
        out[m.group(3)] = (m.group(1), (m.group(2) or "").strip())
    return out


def main(canon, plan_p, top, census_p, fold_p, out_dir):
    out = Path(out_dir)
    cm = json.loads(Path(canon).read_text())
    parts = dict(cm["parts"])
    plan = json.loads(Path(plan_p).read_text())
    pt, ptype = plan["partition_types"], {p["name"]: p["type"] for p in plan["partitions"]}
    hard = {p: {h["inst"]: h for h in pt[t].get("hard_cores", [])} for p, t in ptype.items()}
    cont = {p: {c["inst"]: c for c in pt[t].get("contents", []) if isinstance(c, dict) and "inst" in c}
            for p, t in ptype.items()}
    inst = top_instances(top)

    renamed, kept_n_only = {}, []
    for k, v in sorted(parts.items()):
        if not (isinstance(v, list) and v[0] in HUBS and len(v) > 1):
            continue
        p, base = v
        if f"{base}__q0" in hard[p] and f"{base}__q1" in hard[p]:
            r = role_of(k)
            if r is None:
                raise SystemExit(f"{k}: hub family with q halves but no role in the instance name")
            half = "__q0" if r in ("SW", "SE") else "__q1"
            parts[k] = [p, base + half]
            renamed[k] = {"partition": p, "from": base, "to": base + half, "role": r}
    # one as-built instance per plan half: no aliasing
    tgt = collections.defaultdict(list)
    for k, v in parts.items():
        if isinstance(v, list) and len(v) > 1:
            tgt[tuple(v)].append(k)
    clash = {f"{a}.{b}": ks for (a, b), ks in tgt.items() if len(ks) > 1 and a in HUBS}
    if clash:
        raise SystemExit(f"hub local-name clash after the fold rename: {clash}")
    if parts.pop("phy_NW", None) is None:
        raise SystemExit("canon map has no phy_NW")
    parts.update(PHY)
    for k, (p, lo) in PHY.items():
        if p not in ptype or lo not in cont[p]:
            raise SystemExit(f"plan lacks {p}.{lo}")

    note = ("DIE-HBM-10 TOK-HBM-4 10-28 (COORD default YES): canon map + (1) S role = OWN q0-half plan instance, N role = "
            "q1 half, for every hub family the C25b plan carries as distinct __q0/__q1 hard cores (no S role aliases an N "
            "instance; request queues not shared; 8 SMs unchanged); (2) phy_NW -> C23q slices PHY_NW PC0-9 / PHY_NC PC10-21 "
            "/ PHY_NE PC22-31 (needs the phy-split top, phy_split_top.py). Generated by mk_c25b_instmap.py.")
    mp = {"note": note, "parts": parts, "rules": cm.get("rules", [])}
    (out / "asbuilt_map_c25b.json").write_text(json.dumps(mp, indent=1) + "\n")

    # instance map: every top instance the map binds
    rows = {}
    for k, v in sorted(parts.items()):
        if "." in k:
            continue
        p, lo = (v[0], v[1] if len(v) > 1 else None) if isinstance(v, list) else (v, None)
        hc = hard.get(p, {}).get(lo) if lo else None
        cc = cont.get(p, {}).get(lo) if lo else None
        if cc is None and lo and lo.endswith(("__q0", "__q1")):
            cc = cont.get(p, {}).get(lo[:-4])
        pe = hc or cc or {}
        am, ap = inst.get(k, (None, None))
        rows[k] = {"partition": p, "plan_type": ptype.get(p), "plan_inst": lo, "role": role_of(k),
                   "half": (lo[-2:] if lo and lo.endswith(("__q0", "__q1")) else None),
                   "plan_module": pe.get("module"), "plan_params": pe.get("params", {}),
                   "plan_hard_core": bool(hc), "asbuilt_module": am, "asbuilt_params": ap,
                   "module_match": (am == pe.get("module")) if am and pe.get("module") else None}
    # S-role fold nets (die inputs of the composed top today): their q0 serving instance in C25b
    census = {n["net"]: n for n in json.loads(Path(census_p).read_text())["nets"]}
    fold = json.loads(Path(fold_p).read_text())
    nets, st = [], collections.Counter()
    for n in fold["nets"]:
        c = census.get(n["net"], {})
        md = c.get("mirror_driver") or {}
        tmpl = md.get("instance")
        tv = parts.get(tmpl) if tmpl else None
        rec = {"net": n["net"], "width": n["width"], "role": n["role"], "partition": n["partition"],
               "template_asbuilt": tmpl, "template_master": md.get("master"), "template_params": md.get("params"),
               "template_plan_inst": tv[1] if isinstance(tv, list) and len(tv) > 1 else None}
        if n["status"] == "MAPPED":
            si = n["serving_instance"].split(".", 1)[1]
            s = "Q0_PLAN_INSTANCE_NO_ASBUILT_DRIVER"
            rec.update(serving_plan_inst=n["serving_instance"],
                       plan_module=hard[n["partition"]].get(si, {}).get("module"),
                       why="plan has the family's own __q0 copy; the composed top has no S-role producer (die input "
                           "today), so the copy is emitted with the plan leg params, never the N template's")
        elif n["status"] == "NO_PROVIDER":
            s = "NO_PROVIDER_8SM"
            rec.update(why=n.get("why"))
        else:
            fam = rec["template_plan_inst"]
            s = "PLAN_HAS_NO_Q0_COPY"
            rec.update(n_half_plan_inst=fam, plan_q0_candidates=n.get("candidates", []),
                       why=(f"C25b carries {fam} once (no __q0/__q1 halves) in {n['partition']}; the q0 serving instance "
                            "must be added by a plan event (q0 copy of the family) before the bind can emit it"))
        rec["status"] = s
        st[s] += 1
        nets.append(rec)
    by_fam = collections.defaultdict(collections.Counter)
    for r in nets:
        by_fam[re.sub(r"_S[EW].*", "_S*", r["net"])][r["status"]] += 1
    im = {"schema": "opentallas.hbm.instance_map_c25b.v1", "note": note,
          "plan": plan_p, "plan_sha256": sha(plan_p), "top": top, "top_sha256": sha(top),
          "canon_map_sha256": sha(canon), "fold_map_sha256": sha(fold_p),
          "renamed_to_own_half": renamed, "n_renamed": len(renamed),
          "phy_split": {k: v for k, v in PHY.items()},
          "instances": rows,
          "s_role_fold_nets": {"counts": dict(st), "by_family": {k: dict(v) for k, v in sorted(by_fam.items())},
                               "nets": nets}}
    (out / "instance_map_c25b.json").write_text(json.dumps(im, indent=1) + "\n")
    print("renamed", len(renamed), "instances", len(rows), "fold", dict(st))
    for k, v in sorted(by_fam.items()):
        print(" ", k, dict(v))


if __name__ == "__main__":
    main(*sys.argv[1:7])
