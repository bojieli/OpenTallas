#!/bin/bash
# DIE-HBM-97 (C) accept-early EQ (yosys in openroad/orfs). Usage: run_eq_c.sh BEFORE.sv AFTER.sv OUTDIR [TESTS]
#  inv      : sat -tempinduct of the OT_DMA_ACCEPT_EARLY FORMAL invariants                    -> must PASS
#  neg1..3  : same with NEG (c_valid drops hok) / NEG2 (b_hend+1) / NEG3 (carry-select hi+2)    -> must FAIL
#  bmc      : miter old (no define) vs new (define), all outputs, SEQ cycles from reset          -> must PASS
#  negbmc   : miter old vs NEG                                                                  -> must FAIL
#  identity : define off, controller elaborated under every user parameter set, sha before == after
B=$1; A=$2; O=$3; T=${4:-"identity inv neg1 neg2 neg3 bmc negbmc"}; SEQ=${SEQ:-16}; mkdir -p $O
cp $B $O/before.sv; cp $A $O/after.sv
M=ot_hgi_dma_back_static_vp4_controller
inv() { cat <<YS
read_verilog -sv -formal -DSYNTHESIS -DOT_DMA_ACCEPT_EARLY -DFORMAL $1 /eq/after.sv
hierarchy -top $M
proc; flatten; opt_clean; async2sync
sat -tempinduct -prove-asserts -set-at 1 rst_n 0 -maxsteps 30 -verify
YS
}
bmc() { cat <<YS
read_verilog -sv -DSYNTHESIS /eq/before.sv
hierarchy -top $M
proc
rename $M core_old
read_verilog -sv -DSYNTHESIS -DOT_DMA_ACCEPT_EARLY $1 /eq/after.sv
delete ot_hgi_dma_back_static_vp4_banks
proc
rename $M core_new
miter -equiv -flatten -make_assert -ignore_gold_x core_old core_new miter
hierarchy -top miter
flatten; opt_clean; async2sync
sat -prove-asserts -set-init-zero -set-at 1 in_rst_n 0 -seq $SEQ -verify
YS
}
inv "" > $O/inv.ys; inv "-DOT_DMA_ACCEPT_EARLY_NEG" > $O/neg1.ys; inv "-DOT_DMA_ACCEPT_EARLY_NEG2" > $O/neg2.ys
inv "-DOT_DMA_ACCEPT_EARLY_NEG3" > $O/neg3.ys; bmc "" > $O/bmc.ys; bmc "-DOT_DMA_ACCEPT_EARLY_NEG" > $O/negbmc.ys
SETS=("defaults:" "mut1:-set MUT 1" "mut2:-set MUT 2" "mut3:-set MUT 3" "rr80:-set RR_RT 80" "rr9:-set RR_RT 9"
"local1:-set LOCAL_CTRL 1" "rr80_local1:-set RR_RT 80 -set LOCAL_CTRL 1" "stack_small:-set STACK_BYTES 36'd1000000")
identity() {
  echo -e "set\tsha_before\tsha_after\tverdict" > $O/identity.tsv
  for s in "${SETS[@]}"; do n=${s%%:*}; p=${s#*:}
    for w in before after; do
      { echo "read_verilog -sv -DSYNTHESIS /eq/$w.sv"; [ -n "$p" ] && echo "chparam $p $M";
        echo "hierarchy -top $M"; echo "proc; opt_clean"; echo "write_verilog -noattr /eq/id_$w.v"; } > $O/id_$w.ys
      docker run --rm --memory 8g -v $O:/eq openroad/orfs:latest bash -c "yosys -q -s /eq/id_$w.ys" >/dev/null 2>&1 || echo "yosys fail $n $w"
      # function-local wires carry the source file:line in their name (\inc32$func$/eq/before.sv:171$911.x); strip it
      eval "h_$w=\$(grep -v '^/\\*\\|Generated by' $O/id_$w.v | sed -E 's#\\$func\\$[^$]*\\$#$func$#g' | sha256sum | cut -c1-16)"
    done
    v=SAME; [ "$h_before" = "$h_after" ] || v=DIFF; echo -e "$n\t$h_before\t$h_after\t$v" >> $O/identity.tsv
  done
  cat $O/identity.tsv
}
rm -f $O/rc.txt
for t in $T; do
  if [ $t = identity ]; then identity; echo "identity rc $(grep -c DIFF $O/identity.tsv) DIFF" | tee -a $O/rc.txt; continue; fi
  timeout 3000 docker run --rm --memory 16g -v $O:/eq openroad/orfs:latest bash -c "yosys -q -l /eq/$t.log -s /eq/$t.ys" > /dev/null 2>&1; echo "$t rc $?" | tee -a $O/rc.txt
done
