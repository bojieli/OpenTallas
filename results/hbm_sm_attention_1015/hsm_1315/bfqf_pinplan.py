#!/usr/bin/env python3
"""bfqf even pin plan with literal clock pins (H-SM 10-16, pin-density rule <= 6 pins/um per face).

Starts from tools/ref_tile/spread_face_pins.py output (bus order, layers, tracks) but keeps every clock port at its
literal spec pin_ranges position (H-DIE contract: clk/clk_n N, clk_s S, clk_m0..7 at the SRAM clk-pin y on W/E) and
spreads the data pins of each face evenly over the face minus a +-0.5 um window around each clock pin.
Usage: bfqf_pinplan.py SPEC.json SPREAD.tcl OUT.tcl
"""
import json, re, sys

PITCH = {"M3": 0.036, "M4": 0.048, "M5": 0.048}
OFF = {"M3": 0.009, "M4": 0.036, "M5": 0.012}
SIZE = {"M3": (0.018, 0.144), "M5": (0.024, 0.192), "M4": (0.192, 0.024)}
KEEP = 0.5
MARGIN = 4.32


def snap(v, layer):
    p, o = PITCH[layer], OFF[layer]
    return o + p * round((v - o) / p)


def main():
    spec = json.load(open(sys.argv[1]))
    lines = [l for l in open(sys.argv[2]) if l.startswith("place_pin")]
    W, H = spec["outline"]["w"], None
    die = json.load(open(sys.argv[1].replace("spec.json", "floorplan.json")))["die"]
    W, H = die[2], die[3]
    clocks = set(spec["clock_ports"])
    rx = re.compile(r"-pin_name \{([^}]+)\} -layer (\S+) -location \{([\d.]+) ([\d.]+)\}")
    faces = {"N": [], "S": [], "W": [], "E": []}
    face_of = {p: f for f, ps in spec["pins"].items() for p in ps}
    for l in lines:
        n, lay, x, y = rx.search(l).groups()
        f = face_of[n.split("[")[0]]
        faces[f].append((n, lay))
    out = ["# generated by results/hbm_sm_attention_1015/hsm_1315/bfqf_pinplan.py: even data pins, literal clock pins"]
    density = {}
    for f, pins in faces.items():
        horiz = f in ("N", "S")
        L = W if horiz else H
        fixed = []
        for n, _ in pins:
            if n in clocks:
                lo, hi = spec["pin_ranges"][n]
                lay = "M5" if horiz else "M4"
                fixed.append((n, lay, snap((lo + hi) / 2, lay)))
        data = [(n, lay) for n, lay in pins if n not in clocks]
        segs, a = [], MARGIN
        for _, _, c in sorted(fixed, key=lambda t: t[2]):
            if c - KEEP > a:
                segs.append((a, c - KEEP))
            a = max(a, c + KEEP)
        if L - MARGIN > a:
            segs.append((a, L - MARGIN))
        tot = sum(b - a for a, b in segs)
        step = tot / len(data) if data else 0.0
        pos = []
        for i in range(len(data)):
            t = step * (i + 0.5)
            for a, b in segs:
                if t <= b - a:
                    pos.append(a + t)
                    break
                t -= b - a
        placed = [(n, lay, snap(p, lay)) for (n, lay), p in zip(data, pos)] + fixed
        seen = {}
        for n, lay, c in placed:
            k = (lay, round(c, 3))
            assert k not in seen, f"track collision {n} {seen.get(k)} {k}"
            seen[k] = n
        cs = sorted(c for _, _, c in placed)
        density[f] = (max(sum(1 for c in cs if s <= c < s + 20.0) for s in cs) / 20.0) if cs else 0
        for n, lay, c in placed:
            x, y = (c, H if f == "N" else 0.0) if horiz else (0.0 if f == "W" else W, c)
            out.append(f"place_pin -pin_name {{{n}}} -layer {lay} -location {{{x:.3f} {y:.3f}}} "
                       f"-pin_size {{{SIZE[lay][0]} {SIZE[lay][1]}}} -force_to_die_boundary")
    open(sys.argv[3], "w").write("\n".join(out) + "\n")
    print("BFQF_PINPLAN", {f: len(p) for f, p in faces.items()}, "peak pins/um (20 um window):", density)


if __name__ == "__main__":
    main()
