#!/usr/bin/env python3
"""QC-SU-LAT-R2 variant T spec: binary structured tree from the centre entry (METHODOLOGY 12.8b). Equal-load leaves by
recursive median bisection of the PLACED sinks into 2^m leaves (<= TAPMAX each); one branch buffer per bisection cell at its
sink centroid; every leaf at the same depth.  Usage: mkspec_tree.py GEO OUT IX IY [TAPMAX]"""
import sys, math, json
geo, out, ix, iy = sys.argv[1], sys.argv[2], float(sys.argv[3]), float(sys.argv[4]); TAPMAX = int(sys.argv[5]) if len(sys.argv) > 5 else 280
HALO, ISL = 4.32, 8.64
sinks, macros = [], []
for ln in open(geo):
    f = ln.split()
    if not f: continue
    if f[0] == 'CORE': cx0, cy0, cx1, cy1 = map(float, f[1:5])
    elif f[0] == 'MACRO': macros.append((f[1], tuple(map(float, f[3:7])), (float(f[8]), float(f[9]))))
    elif f[0] == 'SINK': sinks.append((float(f[1]), float(f[2])))
blk = [(a - HALO, b - HALO, c + HALO, d + HALO) for _, (a, b, c, d), _ in macros] + [(ix - ISL/2 - 1, iy - ISL/2 - 1, ix + ISL/2 + 1, iy + ISL/2 + 1)]
def free(p, m=0.6):
    x, y = p
    return (cx0 + 1 <= x <= cx1 - 3 and cy0 + 1 <= y <= cy1 - 1) and not any(a - m < x < c + m and b - m < y < d + m for a, b, c, d in blk)
def snap(p):
    if free(p): return p
    for r in [i * 0.5 for i in range(1, 600)]:
        for dx, dy in [(r, 0), (-r, 0), (0, r), (0, -r)]:
            if free((p[0] + dx, p[1] + dy)): return (p[0] + dx, p[1] + dy)
cen = lambda P: (sum(p[0] for p in P) / len(P), sum(p[1] for p in P) / len(P))
m = max(1, math.ceil(math.log2(len(sinks) / TAPMAX))); K = 2 ** m
R = snap((ix + ISL / 2 + 2.0, iy))
nodes, leaves = [], []
def rec(name, parent, rect, P, lvl):
    c = snap(cen(P))
    if lvl == m:
        leaves.append((name, parent, c, rect, len(P))); return
    nodes.append((name, parent, c))
    x0, y0, x1, y1 = rect; ax = 0 if (x1 - x0) >= (y1 - y0) else 1
    P = sorted(P, key=lambda p: p[ax]); h = len(P) // 2; cut = (P[h - 1][ax] + P[h][ax]) / 2
    r1, r2 = ((x0, y0, cut, y1), (cut, y0, x1, y1)) if ax == 0 else ((x0, y0, x1, cut), (x0, cut, x1, y1))
    rec(name + 'a', name, r1, P[:h], lvl + 1); rec(name + 'b', name, r2, P[h:], lvl + 1)
rec('T', 'root', (0.0, 0.0, cx1 + HALO, cy1 + HALO), sinks, 0)
mac = []
for nm, (a, b, c, d), ck in macros:
    site = snap((ck[0] - HALO - 1.0, ck[1]) if abs(ck[0] - a) < abs(ck[0] - c) else (ck[0] + HALO + 1.0, ck[1]))
    lf = min(leaves, key=lambda l: 0 if (l[3][0] <= site[0] <= l[3][2] and l[3][1] <= site[1] <= l[3][3]) else 1)
    mac.append((nm.replace('\\', '').replace('[', '*').replace(']', '*'), lf[0], site))
d1 = lambda p, q: abs(p[0] - q[0]) + abs(p[1] - q[1])
pos = {'root': R}; pos.update({n: c for n, _, c in nodes})
plen = {}
for n, par, c in nodes: plen[n] = plen.get(par, 0.0) + d1(pos[par], c)
L = [plen[par] + d1(pos[par], c) for _, par, c, _, _ in leaves]
o = ['# QC-SU-LAT-R2 variant T (METHODOLOGY 12.8b) GENERATED by mkspec_tree.py from %s' % geo,
     '# entry island (%.3f, %.3f) 8.64 um; root (%.2f, %.2f); binary tree depth %d, %d leaves (%d..%d sinks); root->leaf Manhattan %.0f..%.0f um' % (ix, iy, R[0], R[1], m, K, min(l[4] for l in leaves), max(l[4] for l in leaves), min(L), max(L)),
     'set ot_ms_port ck', 'set ot_ms_root {%.3f %.3f}' % R, 'set ot_ms_tree {']
o += [' {%s %s %.3f %.3f}' % (n, p, c[0], c[1]) for n, p, c in nodes] + ['}', 'set ot_ms_leaves {']
o += [' {%s %s {%.3f %.3f} {{%.3f %.3f %.3f %.3f}}}' % (n, p, c[0], c[1], *r) for n, p, c, r, _ in leaves] + ['}', 'set ot_ms_macros {']
o += [' {%s %s {%.3f %.3f}}' % x[:2] + '' if False else ' {%s %s {%.3f %.3f}}' % (x[0], x[1], x[2][0], x[2][1]) for x in mac] + ['}']
open(out, 'w').write('\n'.join(o) + '\n')
json.dump({'entry': [ix, iy], 'root': R, 'depth': m, 'leaves': K, 'leaf_sinks': [l[4] for l in leaves], 'root_to_leaf_um': [min(L), max(L)],
           'max_entry_to_sink_manhattan': max(d1((ix, iy), p) for p in sinks), 'max_entry_to_sink_euclid': max(math.hypot(ix - p[0], iy - p[1]) for p in sinks)}, open(out + '.json', 'w'))
print(o[1])
