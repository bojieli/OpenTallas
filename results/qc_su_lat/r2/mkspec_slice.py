#!/usr/bin/env python3
"""QC-SU-LAT-R2 variant S: structured tree through the MASTER-PLAN slice's in-core leaf islands (pushdown driver at each
leaf-island centre, 12.2a1): root (entry) -> one driver per tree_leaf island -> binary equal-load sub-tree of the sinks
nearest that island (same depth everywhere).  Usage: mkspec_slice.py GEO SLICE.json OUT [TAPMAX]"""
import sys, math, json
geo, sl, out = sys.argv[1:4]; TAPMAX = int(sys.argv[4]) if len(sys.argv) > 4 else 280
S = json.load(open(sl)); isl = {i['name']: i for i in S['islands']}
ix, iy = isl['clock_entry']['clock_pin']['xy_um']; leafs = [isl[k]['centre_um'] for k in sorted(isl) if k.startswith('tree_leaf')]
HALO = 4.32
sinks, macros = [], []
for ln in open(geo):
    f = ln.split()
    if not f: continue
    if f[0] == 'CORE': cx0, cy0, cx1, cy1 = map(float, f[1:5])
    elif f[0] == 'MACRO': macros.append((f[1], tuple(map(float, f[3:7])), (float(f[8]), float(f[9]))))
    elif f[0] == 'SINK': sinks.append((float(f[1]), float(f[2])))
er = isl['clock_entry']['rect_um']
blk = [(a - HALO, b - HALO, c + HALO, d + HALO) for _, (a, b, c, d), _ in macros] + [(er[0] - 1, er[1] - 1, er[2] + 1, er[3] + 1)]
def free(p, m=0.6):
    x, y = p
    return (cx0 + 1 <= x <= cx1 - 3 and cy0 + 1 <= y <= cy1 - 1) and not any(a - m < x < c + m and b - m < y < d + m for a, b, c, d in blk)
def snap(p):
    if free(p): return p
    for r in [i * 0.5 for i in range(1, 600)]:
        for dx, dy in [(r, 0), (-r, 0), (0, r), (0, -r)]:
            if free((p[0] + dx, p[1] + dy)): return (p[0] + dx, p[1] + dy)
d1 = lambda p, q: abs(p[0] - q[0]) + abs(p[1] - q[1])
for l in leafs:
    inmac = [n for n, (a, b, c, d), _ in macros if a < l[0] < c and b < l[1] < d]
    if inmac: raise SystemExit('slice leaf island %s lies inside macro %s' % (l, inmac))
cen = lambda P: (sum(p[0] for p in P) / len(P), sum(p[1] for p in P) / len(P))
groups = [[] for _ in leafs]
for p in sinks: groups[min(range(len(leafs)), key=lambda i: d1(p, leafs[i]))].append(p)
m = max(1, math.ceil(math.log2(max(len(g) for g in groups) / TAPMAX)))
R = snap((er[2] + 2.0, iy))
nodes, leaves = [], []
def rec(name, parent, rect, P, lvl):
    c = snap(cen(P))
    if lvl == m: leaves.append((name, parent, c, rect, len(P))); return
    nodes.append((name, parent, c))
    x0, y0, x1, y1 = rect; ax = 0 if (x1 - x0) >= (y1 - y0) else 1
    P = sorted(P, key=lambda p: p[ax]); h = len(P) // 2; cut = (P[h - 1][ax] + P[h][ax]) / 2
    r1, r2 = ((x0, y0, cut, y1), (cut, y0, x1, y1)) if ax == 0 else ((x0, y0, x1, cut), (x0, cut, x1, y1))
    rec(name + 'a', name, r1, P[:h], lvl + 1); rec(name + 'b', name, r2, P[h:], lvl + 1)
for i, (l, g) in enumerate(zip(leafs, groups)):
    q = 'Q%d' % i; nodes.append((q, 'root', tuple(l)))
    bb = (min(p[0] for p in g) - 0.5, min(p[1] for p in g) - 0.5, max(p[0] for p in g) + 0.5, max(p[1] for p in g) + 0.5)
    # sub-tree root = the island driver itself: its children are the first bisection
    x0, y0, x1, y1 = bb; ax = 0 if (x1 - x0) >= (y1 - y0) else 1
    P = sorted(g, key=lambda p: p[ax]); h = len(P) // 2; cut = (P[h - 1][ax] + P[h][ax]) / 2
    r1, r2 = ((x0, y0, cut, y1), (cut, y0, x1, y1)) if ax == 0 else ((x0, y0, x1, cut), (x0, cut, x1, y1))
    rec(q + 'a', q, r1, P[:h], 1); rec(q + 'b', q, r2, P[h:], 1)
mac = []
for nm, (a, b, c, d), ck in macros:
    site = snap((ck[0] - HALO - 1.0, ck[1]) if abs(ck[0] - a) < abs(ck[0] - c) else (ck[0] + HALO + 1.0, ck[1]))
    lf = min(leaves, key=lambda l: d1(l[2], site))
    mac.append((nm.replace('\\', '').replace('[', '*').replace(']', '*'), lf[0], site))
pos = {'root': R}; plen = {'root': 0.0}
for n, par, c in nodes: pos[n] = c; plen[n] = plen[par] + d1(pos[par], c)
L = [plen[par] + d1(pos[par], c) for _, par, c, _, _ in leaves]
o = ['# QC-SU-LAT-R2 variant S (12.8b + 12.2a1) GENERATED by mkspec_slice.py from %s + slice %s (master_plan %s)' % (geo, sl, S['master_plan_sha256'][:12]),
     '# entry (%.2f, %.2f) -> %d leaf-island drivers %s -> binary sub-trees depth %d, %d leaves (%d..%d sinks); root->leaf %.0f..%.0f um' % (ix, iy, len(leafs), leafs, m, len(leaves), min(l[4] for l in leaves), max(l[4] for l in leaves), min(L), max(L)),
     'set ot_ms_port ck', 'set ot_ms_root {%.3f %.3f}' % R, 'set ot_ms_tree {']
o += [' {%s %s %.3f %.3f}' % (n, p, c[0], c[1]) for n, p, c in nodes] + ['}', 'set ot_ms_leaves {']
o += [' {%s %s {%.3f %.3f} {{%.3f %.3f %.3f %.3f}}}' % (n, p, c[0], c[1], *r) for n, p, c, r, _ in leaves] + ['}', 'set ot_ms_macros {']
o += [' {%s %s {%.3f %.3f}}' % (x[0], x[1], x[2][0], x[2][1]) for x in mac] + ['}']
open(out, 'w').write('\n'.join(o) + '\n'); print(o[1])
