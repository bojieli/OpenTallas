#!/usr/bin/env python3
"""KV-CORES-R2 pass 1 (placement + GEOM render before any tree build): reserve the KV core slice island sites
(12.8a entry island, 12.8b in-core H-tree islands, 12.2a1 R15 die pushdown islands) as placement blockages so the
pass-2 fixed core_infra cells land on free sites.  Pass 2 replaces them with the pushdown cells (core_infra).
    pass1_reserve.py SLICE.json KITDIR"""
import json, sys
from pathlib import Path
sl = json.load(open(sys.argv[1]))["slice"]; kd = Path(sys.argv[2])
rects = []
if sl.get("entry"): rects.append(("entry", sl["entry"]["island_um"]))
for i, q in enumerate((sl.get("core_tree") or {}).get("islands") or []): rects.append((f"core_tree_{i}", q["rect_um"]))
for i, q in enumerate((sl.get("die_islands") or {}).get("points") or []): rects.append((f"die_{q.get('role')}_{i}", q["rect_um"]))
L = ["# GENERATED by KV-CORES-R2 pass1_reserve.py from " + sys.argv[1], "set kvr2_b [ord::get_db_block]",
     "proc kvr2_blk {b x0 y0 x1 y1} { foreach k [$b getBlockages] { set q [$k getBBox]",
     "  if {[$q xMin]==$x0 && [$q yMin]==$y0 && [$q xMax]==$x1 && [$q yMax]==$y1} { return } }",
     "  odb::dbBlockage_create $b $x0 $y0 $x1 $y1 }"]
for n, r in rects:
    x0, y0, x1, y1 = (int(round(v * 1000)) for v in r)
    L.append(f"kvr2_blk $kvr2_b {x0} {y0} {x1} {y1}   ;# {n} {r}")
L.append(f'puts "KVR2_PASS1_RESERVE {len(rects)} island sites"')
(kd / "kvr2_reserve.tcl").write_text("\n".join(L) + "\n")
h = kd / "face_flops.tcl"
t = h.read_text()
if "kvr2_reserve.tcl" not in t:
    h.write_text("source /work/kvr2_reserve.tcl\n" + t)
print(kd.name, len(rects), [n for n, _ in rects])
