#!/bin/bash
# make_io_vclk_margin.sh <L_ps>...: io_vclk_m_<L>.sdc, the owner margin-first variant (OWNER_RULE_MARGIN_FIRST 2026-10-06)
# of io_vclk_<L>.sdc: routed over-constrained to an effective 770 ps (setup uncertainty 60 + 63 ps on the 833 ps clock),
# signed off at 833 ps / 60 ps by signoff_unc60.sdc (corner_sta --post-sdc, route_view.sh POSTSDC); IO budgets 0.2 T plus
# a 150 ps die clock-arrival allowance against vclk at the view's measured insertion L; reset-release multicycle as in
# make_io_vclk.sh.
cd "$(dirname "$0")"
for L in "$@"; do ./make_io_vclk.sh $L >/dev/null; sed -e "s/^# generated by make_io_vclk.sh $L (see there)/# generated by make_io_vclk_margin.sh $L (see there), from make_io_vclk.sh/" \
  -e "s/^set_clock_uncertainty -setup 60 \[get_clocks vclk\]/set_clock_uncertainty -setup 123 [get_clocks {core_clk vclk}]/" \
  -e "s/\* 0.2}\] -clock vclk/* 0.2 + 150}] -clock vclk/" io_vclk_$L.sdc > io_vclk_m_$L.sdc; done
