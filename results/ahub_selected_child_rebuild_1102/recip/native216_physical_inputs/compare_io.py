#!/usr/bin/env python3
from pathlib import Path
import json,re,hashlib
r=Path(__file__).resolve().parent
io=(r/'io.tcl').read_text();cfg=(r/'config.mk').read_text();selected=json.loads((r.parent/'selected_pin_shapes.json').read_text())
assert re.search(r'export DIE_AREA = 0 0 216 216\n',cfg)
assert re.search(r'export CORE_AREA = 2.16 2.16 213.84 213.84\n',cfg)
actual={}
for m in re.finditer(r'place_pin -pin_name \{([^}]+)\} -layer (\w+) -location \{([\d.]+) ([\d.]+)\} -pin_size \{([\d.]+) ([\d.]+)\}',io):
 name,layer=m[1],m[2];x,y,w,h=map(float,m.group(3,4,5,6))
 assert name not in actual
 actual[name]=[dict(layer=layer,rect_um=[round(x-w/2,6),round(y-h/2,6),round(x+w/2,6),round(y+h/2,6)])]
assert len(actual)==69
# The original literal extra shape is generated by dbBox_create under x[31].
assert 'set nt [$nb findBTerm {x[31]}]' in io
match=re.search(r'odb::dbBox_create \$np \[\[ord::get_db_tech\] findLayer \{(\w+)\}\] (.*)',io)
assert match
coords=[float(x) for x in re.findall(r'round\(([\d.]+) \* \$nu\)',match[2])]
assert len(coords)==4
actual['x[31]'].append(dict(layer=match[1],rect_um=coords))
assert set(actual)==set(selected['signal_pins'])
for name,rects in actual.items():
 def key(x):return (x['layer'],*[round(v,6) for v in x['rect_um']])
 assert sorted(map(key,rects))==sorted(map(key,selected['signal_pins'][name]['rects'])),name
log=(r/'original_5_1_grt.log').read_text()
assert '[ERROR DRT-0302] Unsupported multiple pins on bterm x[31]' in log
assert 'read_db /work/run/results/asap7/hc_ot_qkh_recip_leaf__216x216/base/4_cts.odb' in log
res=dict(status='PASS_PASSIVE_IO_TO_PUBLISHED_GEOMETRY',master=selected['master'],outline=[216,216],signal_bits=len(actual),rectangles=sum(map(len,actual.values())),all_signal_rectangles_exact=True,x31_rectangles=actual['x[31]'],native_original_GRT='FAIL_DRT0302_multiple_BPINS_x31',native_io_second_BPin=True,minimum_candidate='Preserve exact two rectangles but coalesce into one BPin only in OWN copy, subject to actual checkpoint query and normal gate/review authorization',actual_4CTS_geometry='NOT_QUERIED; IO/log correspondence is not actual DB inspection',reuse_or_GRT_authorized=False,sha256={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in r.iterdir() if p.is_file() and p.name != 'IO_COMPARISON.json' and p.suffix in ('.mk','.tcl','.json','.log')})
(r/'IO_COMPARISON.json').write_text(json.dumps(res,indent=2)+'\n');print(json.dumps({k:res[k] for k in ['status','signal_bits','rectangles','native_original_GRT','reuse_or_GRT_authorized']}))
