#!/bin/bash
# Identity proof for every other user: without OT_CMD_FIRE_EARLY the core elaborates byte-identically before/after.
# identity.sh BEFORE.sv AFTER.sv OUTDIR   -> OUTDIR/identity.tsv (param set, sha before, sha after, SAME/DIFF)
B=$1; A=$2; O=$3; mkdir -p $O; cp $B $O/before.sv; cp $A $O/after.sv
SETS=("dma_collar_repo:-set MODE 1 -set CW 308 -set RELF 2 -set TGT_PIN 1"
"svc_xcal_t:-set TARGET 255 -set MODE 0 -set AWA 10 -set AWB 7 -set RBW 7 -set RCW 8 -set TGT_PIN 1"
"svc_xcal_t_mut2:-set TARGET 255 -set MODE 0 -set AWA 10 -set AWB 7 -set RBW 7 -set RCW 8 -set TGT_PIN 1 -set MUT 2"
"vm_wr_q_t(_lanes,_faces,_faces4):-set TARGET 255 -set MODE 1 -set CW 26 -set RELF 0 -set TGT_PIN 1"
"vm_wr_q_t_mut1:-set TARGET 255 -set MODE 1 -set CW 26 -set RELF 0 -set TGT_PIN 1 -set MUT 1"
"vm_wr_q_t_lanes4:-set TARGET 255 -set MODE 1 -set CW 27 -set RELF 0 -set TGT_PIN 1"
"xload_cl2(p):-set TARGET 255 -set MODE 1 -set CW 108 -set RELF 0 -set TGT_PIN 1"
"xload_cl2_mut1:-set TARGET 255 -set MODE 1 -set CW 108 -set RELF 0 -set TGT_PIN 1 -set MUT 1"
"defaults:")
echo -e "set\tsha_before\tsha_after\tverdict" > $O/identity.tsv
for s in "${SETS[@]}"; do n=${s%%:*}; p=${s#*:}
  for w in before after; do
    { echo "read_verilog -sv -DSYNTHESIS /o/$w.sv"; echo "delete ot_static_cmd_target"; [ -n "$p" ] && echo "chparam $p ot_static_cmd_target_core";
      echo "hierarchy -top ot_static_cmd_target_core"; echo "proc; opt_clean"; echo "write_verilog -noattr /o/$w.v"; } > $O/id_$w.ys
    docker run --rm --memory 8g -v $O:/o openroad/orfs:latest bash -c "yosys -q -s /o/id_$w.ys" >/dev/null 2>&1 || echo "yosys fail $n $w"
    eval "h_$w=\$(grep -v '^/\\*\\|Generated by' $O/$w.v | sha256sum | cut -c1-16)"
  done
  v=SAME; [ "$h_before" = "$h_after" ] || v=DIFF; echo -e "$n\t$h_before\t$h_after\t$v" >> $O/identity.tsv
done
cat $O/identity.tsv
