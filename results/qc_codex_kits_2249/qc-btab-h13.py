from pathlib import Path
D=Path('/srv/opentallas-scratch2/claude/codex-qc-kits-2249/btabH13')
s=(D/'macro_place.tcl').read_text().split('# GENERATED by gen_core_kit_qc.py (QC-SU-SRAMHALO)')[0]
s+='''
# CODEX BTAB MIF1 H13: permanent E/W pin-column channels; no clock assignment before new tree replan.
set dbu [[ord::get_db_tech] getDbUnitsPerMicron]
set n 0
foreach i [$b getInsts] {
 if {![[$i getMaster] isBlock]} {continue}
 set r [$i getBBox];set core [$b getCoreArea]
 foreach side {W E} {
  if {$side eq "W"} {set x0 [expr {max([$core xMin],[$r xMin]-round(12.96*$dbu))}];set x1 [$r xMin]} else {set x0 [$r xMax];set x1 [expr {min([$core xMax],[$r xMax]+round(12.96*$dbu))}]}
  set y0 [expr {max([$core yMin],[$r yMin]-round(6.3*$dbu))}];set y1 [expr {min([$core yMax],[$r yMax]+round(6.3*$dbu))}]
  odb::dbBlockage_create $b $x0 $y0 $x1 $y1;incr n
 }
}
puts "BTAB_H13 permanent_pincolumn_blockages $n"
'''
(D/'macro_place.tcl').write_text(s)
with (D/'config.mk').open('a') as f:f.write('\n# BTAB H13: MIF1 placement census only; old tree unqualified, CTS not launched.\nexport OT_MPF_HALO_UM = 12.96\noverride export PRE_GLOBAL_PLACE_TCL = /work/pre_gpl_mpf.tcl\noverride export PRE_DETAIL_PLACE_TCL = /work/pre_dpl_mpf.tcl\n')
