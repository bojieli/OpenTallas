#!/usr/bin/env python3
"""Read-only validation and owned-copy transfer of a successful frontend closure."""
import json,hashlib,shutil,os
from pathlib import Path

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def digest(value):return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()
def read(path):return json.loads(Path(path).read_text())
def properties(raw):return dict(l.split('=',1) for l in raw.splitlines() if '=' in l)

def validate_profile(path,source_pins,compiler,command,caps,inventory):
 root=Path(path).resolve()
 if Path(path).is_symlink():raise ValueError('profile root symlink')
 required=['record.json','service_receipt.json','frontend_closure.json','caps_before_frontend.json','output_owner.json','baseline/snapshot_sha256.json','baseline/frontend.log','resource_samples.jsonl','service_journal.txt']
 if any(not (root/p).is_file() or (root/p).is_symlink() for p in required):raise ValueError('profile not terminal/closed or receipt symlink')
 record=read(root/'record.json');terminal=read(root/'service_receipt.json');closure=read(root/'frontend_closure.json')
 state=properties(terminal['terminal'])
 if record.get('verdict')!='PASS_FRONTEND_GENERATION_ONLY' or record.get('CXX_compiles')!=0 or record.get('simulations')!=0:raise ValueError('profile verdict/CXX boundary')
 if terminal.get('returncode')!=0 or terminal.get('worker_record_exists') is not True or terminal.get('outside_worker_cgroup') is not True or state.get('Result')!='success' or state.get('MainPID')!='0' or state.get('ExecMainStatus')!='0' or state.get('ActiveState')!='inactive':raise ValueError('profile service not successful terminal')
 if closure.get('status')!='GENERATED_SOURCES_CLOSED_NOT_RUNTIME_PASS' or closure.get('source_pins')!=source_pins:raise ValueError('profile source closure pin')
 actual=read(root/'caps_before_frontend.json')['systemd']
 for k in ('MemoryMax','MemorySwapMax','LimitFSIZE','LimitCORE','KillMode','KillSignal','OOMPolicy'):
  if str(actual.get(k))!=str(caps[k]):raise ValueError('profile actual cap '+k)
 if actual.get('CPUAffinity') not in ('30 31','30-31') or actual.get('RuntimeMaxUSec') not in ('10min','600000000'):raise ValueError('profile actual affinity/runtime cap')
 if closure.get('inventory_sha256')!=digest(closure.get('files')):raise ValueError('generated inventory digest')
 generated=inventory(root/'baseline/obj')
 if generated!=closure['files']:raise ValueError('generated closure changed')
 if not generated or 'Vtb.mk' not in generated or not any(n.endswith('.cpp') for n in generated):raise ValueError('generated closure incomplete')
 if any(n.endswith(('.o','.a','.so')) or n=='Vtb' for n in generated):raise ValueError('profile includes CXX output')
 if closure.get('generated_bytes')!=sum(v['bytes'] for v in generated.values()):raise ValueError('generated byte accounting')
 sources=inventory(root/'baseline/sources');snapshot=read(root/'baseline/snapshot_sha256.json')
 if {k:v['sha256'] for k,v in sources.items()}!=snapshot:raise ValueError('profile source snapshot changed')
 if any(snapshot.get(p)!=h for p,h in source_pins.items()):raise ValueError('profile source snapshot missingpin')
 bench='rtl/test/w17_window_core_cancel_join_r7/tb.sv'
 if snapshot.get('tb.sv')!=source_pins[bench]:raise ValueError('profile top bench identity')
 steps=closure.get('steps',[])
 if len(steps)!=1 or steps[0].get('returncode')!=0 or steps[0].get('command')!=command or steps[0].get('log_sha256')!=sha(root/'baseline/frontend.log') or Path(steps[0]['log']).resolve()!=root/'baseline/frontend.log':raise ValueError('profile frontend command/log identity')
 if not 0<steps[0]['wall_seconds']<=540:raise ValueError('profile frontend elapsed cap')
 peaks=[];samples=0
 with (root/'resource_samples.jsonl').open() as stream:
  for line in stream:
   row=json.loads(line);samples+=1
   if row.get('memory.peak') is not None:peaks.append(int(row['memory.peak']))
   if row.get('memory.events') is not None:
    events=properties(row['memory.events'].replace(' ','='))
    if any(int(events.get(k,-1))!=0 for k in ('max','oom','oom_kill','oom_group_kill')):raise ValueError('profile resource events')
 if not samples or not peaks:raise ValueError('profile resource samples absent')
 if max(peaks)>caps['MemoryMax']:raise ValueError('profile observed peak exceeds cap')
 expected_wrapper=compiler['wrapper_sha256'];owner=read(root/'output_owner.json')
 if owner.get('GO_commit')!=record.get('GO_commit') or len(owner.get('GO_commit',''))!=40:raise ValueError('profile GO ownership identity')
 return {'profile_path':str(root),'receipt_sha256':{p:sha(root/p) for p in required},'generated_inventory':generated,'generated_inventory_sha256':digest(generated),'source_snapshot_sha256':sha(root/'baseline/snapshot_sha256.json'),'frontend_step':steps[0],'observed_cumulative_peak_bytes':max(peaks),'samples':samples,'generated_bytes':closure['generated_bytes'],'prior_frontend_wall_seconds':steps[0]['wall_seconds'],'compiler':compiler,'prior_GO_commit':record['GO_commit'],'prior_plan_sha256':record['plan_sha256'],'baseline_frontend_repeats':0,'original_profile_writes':0}

def transfer(profile,home,receipt,inventory):
 """Copy generated files only into fresh owned phase; original closure retained."""
 profile=Path(profile).resolve();home=Path(home).resolve();obj=home/'obj'
 if obj.exists() or home.is_symlink() or obj.is_symlink():raise ValueError('fresh owned obj required')
 if inventory(profile/'baseline/obj')!=receipt['generated_inventory']:raise ValueError('profile changed before transfer')
 obj.mkdir()
 for name,entry in receipt['generated_inventory'].items():
  source=profile/'baseline/obj'/name;target=obj/name
  if source.is_symlink() or not source.is_file():raise ValueError('profile file type')
  target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,target)
  if target.stat().st_size!=entry['bytes'] or sha(target)!=entry['sha256']:raise ValueError('generated transfer mismatch')
 if inventory(obj)!=receipt['generated_inventory']:raise ValueError('owned transferred inventory mismatch')
 shutil.copyfile(profile/'baseline/frontend.log',home/'frontend.log')
 return {'status':'PASS_BYTE_EXACT_GENERATED_COPY_NO_FRONTEND','profile_path':str(profile),'owned_obj':str(obj),'generated_inventory_sha256':receipt['generated_inventory_sha256'],'files':len(receipt['generated_inventory']),'bytes':receipt['generated_bytes'],'original_profile_untouched':True}
