#!/usr/bin/env python3
"""DIE-KV-63/start: build the START-skeleton vehicle of the integrated native START provider on the current KV bind.
Every partition is reduced to its START/reset/landing infrastructure (skel.py); u_host = dkv63_host_stub (real
qkd_d2d_boot_event_bridge + the C45 'installed' predicate: mode 0 = main/fixed local install, mode 1 = old program_ready
closed loop); the joined top + provider are used unchanged."""
import re, sys, json, subprocess, os
W, BIND, SRC, JOINED, PROV, BRIDGE = sys.argv[1:7]
os.makedirs(f'{W}/skel', exist_ok=True)
parts = sorted(f for f in os.listdir(f'{BIND}/rtl') if f.startswith('kv3_') and f.endswith('.sv'))
stats = {}
for f in parts:
    inj = ['--inject', 'w_kvs_ctl_boot_setup_ready[0]=$root.tb.setup_inj', '--inject', 'w_pll_locked[0]=$root.tb.pll_locked'] if f == 'kv3_hub_C_part.sv' else []
    r = subprocess.run([sys.executable, '-I', f'{W}/skel.py', f'{BIND}/rtl/{f}', f'{W}/skel/{f}'] + inj, capture_output=True, text=True, check=True)
    stats[f] = json.loads(r.stdout)['stats']
json.dump(stats, open(f'{W}/skel/skel_stats.json', 'w'), indent=1)
# module definitions of the infrastructure cells
cells = [f'{BIND}/rtl/bind_cells.sv'] + [f'{SRC}/rtl/common/{x}' for x in ('ot_dp_clk_landing.sv', 'ot_dp_clk_landing_ca.sv', 'ot_dp_dly_cnt.sv')] + \
        [f'{SRC}/rtl/lib/ot_dp_efault.sv', f'{SRC}/rtl/lib/ot_dp_id.sv']
open(f'{W}/dkv63_host_stub.sv', 'w').write('''`timescale 1ns/1ps
// DIE-KV-63/start: HOST stand-in for the START-skeleton vehicle. The real C45 ordered D2D boot event bridge with the C45
// 'installed' predicate. mode 0 = main (f4fc168ee): setup && program_installed_local && mission_start. mode 1 = the
// pre-f4fc168ee text compiled into veh60: setup && program_ready && mission_start, where program_ready = local install &&
// peer witness commit, and the witness arrives only after this event starts the d2d epoch (closed loop).
module dkv63_host_stub (input wire ck_ctl, input wire por_n, input wire mission_start, input wire static_setup_ready,
                        output wire d2d_boot_begin);
    wire request = $root.tb.req, local_inst = $root.tb.local_inst;
    reg running = 1'b0, committed = 1'b0;
    wire program_ready = local_inst && committed;
    wire installed = static_setup_ready && (($root.tb.mode == 1) ? program_ready : local_inst) && mission_start;
    qkd_d2d_boot_event_bridge #(.ENABLE(1)) u_d2d_boot_event (.ck(ck_ctl), .rst_n(por_n), .request(request),
        .installed(installed), .boot_begin(d2d_boot_begin));
    always @(posedge ck_ctl) begin
        if (d2d_boot_begin) running <= 1'b1;
        if (running && local_inst) committed <= 1'b1;
    end
endmodule
''')
# tb from the joined wrapper's port list
t = open(JOINED).read()
i = t.index('module qwen_kvsys_bound_top (')
hdr_end = t.index(');', i)
body = t[hdr_end:t.index('endmodule', hdr_end)]
dirs = {}
for m in re.finditer(r'^\s*(input|output)\s+wire\s*(\[[^\]]*\])?\s*(\w+)\s*;', body, re.M):
    dirs[m.group(3)] = (m.group(1), m.group(2) or '')
conns = []
for n, (d, w) in dirs.items():
    if d == 'output': continue
    if n == 'pad_por_n': v = 'por_n'
    elif n == 'start': v = 'start'
    elif n == 'pad_die_id': v = "3'd1"
    elif n.startswith('clk_') or n.startswith('t_') and n.endswith('__clk') or n == 'pad_refclk': v = 'ck'
    else: v = "'0"
    conns.append(f'.{n}({v})')
pst = sorted(n for n in re.findall(r'\.(pst_\w+)\(', t[t.index('ot_die_start_stages u_start_provider'):]))
pst = sorted(set(pst))
mon = []
for k, p in enumerate(pst):
    mon.append(f'        if (dut.{p} && pst_cyc[{k}] < 0) pst_cyc[{k}] = cyc;')
names = '{' + ', '.join(f'"{p}"' for p in pst) + '}'
tb = f'''`timescale 1ns/1ps
// DIE-KV-63/start START-skeleton vehicle tb (generated by mk_vehicle.py). One die clock; reset pad pad_por_n; START pad.
module tb;
    reg ck = 0; always #0.4165 ck = ~ck;
    reg por_n = 0, start = 0, req = 0, local_inst = 0, setup_inj = 0, pll_locked = 0;
    integer mode = 0, cyc = 0, T_REQ = 1231, T_LOCAL = 2000, T_SETUP = 3000, T_START = 4000, T_END = 6000;
    qwen_kvsys_bound_top dut ({', '.join(conns)});
    localparam integer NP = {len(pst)};
    string pst_name [0:NP-1] = {names};
    integer pst_cyc [0:NP-1];
    integer c_hubC = -1, c_hubWi = -1, c_hubWo = -1, c_hrWN = -1, c_hrWS = -1, c_hrEN = -1, c_hrES = -1, c_t13 = -1, c_t13_pre = 0,
            c_setup_wi = -1, c_begin = -1, n_begin = 0, c_go_d1 = -1, n_go_d1 = 0, c_por_root = -1;
    initial begin
        void'($value$plusargs("MODE=%d", mode));
        for (int k = 0; k < NP; k++) pst_cyc[k] = -1;
    end
    always @(negedge ck) begin
        cyc <= cyc + 1;
        por_n <= (cyc >= 16); pll_locked <= (cyc >= 20);
        req <= (cyc == T_REQ); local_inst <= (cyc >= T_LOCAL); setup_inj <= (cyc >= T_SETUP); start <= (cyc >= T_START);
    end
    always @(posedge ck) begin
{chr(10).join(mon)}
        if (dut.u_bound.hub_C.rst_root_n && c_por_root < 0) c_por_root = cyc;
        if (dut.u_bound.hub_C.cland_start && c_hubC < 0) c_hubC = cyc;
        if (dut.u_bound.hub_Wi.cland_start && c_hubWi < 0) c_hubWi = cyc;
        if (dut.u_bound.hub_Wo.cland_start && c_hubWo < 0) c_hubWo = cyc;
        if (dut.u_bound.hroot_WN.cland_start && c_hrWN < 0) c_hrWN = cyc;
        if (dut.u_bound.hroot_WS.cland_start && c_hrWS < 0) c_hrWS = cyc;
        if (dut.u_bound.hroot_EN.cland_start && c_hrEN < 0) c_hrEN = cyc;
        if (dut.u_bound.hroot_ES.cland_start && c_hrES < 0) c_hrES = cyc;
        if (dut.u_bound.hub_Wi.start_t13 && cyc < T_START) c_t13_pre++;
        if (dut.u_bound.hub_Wi.start_t13 && c_t13 < 0) c_t13 = cyc;
        if (dut.u_bound.hub_Wi.i_kvs_ctl_boot__setup_ready_q[0] && c_setup_wi < 0) c_setup_wi = cyc;
        if (dut.u_bound.hub_Wi.w_host_d2d_boot_begin[0]) begin n_begin++; if (c_begin < 0) c_begin = cyc; end
        if (dut.u_bound.x_hub_Wi_o_host_boot_go_d1_hgi_WN_7[0]) begin n_go_d1++; if (c_go_d1 < 0) c_go_d1 = cyc; end
        if (cyc == T_END) begin
            integer npst = 0, worst = -1;
            for (int k = 0; k < NP; k++) begin
                if (pst_cyc[k] >= 0) npst++;
                if (pst_cyc[k] > worst) worst = pst_cyc[k];
                if (pst_cyc[k] < 0) $display("PST_NEVER %s", pst_name[k]);
            end
            $display("PST rose %0d/%0d latest_cyc %0d", npst, NP, worst);
            for (int k = 0; k < NP; k++) if (pst_name[k].substr(0, 8) == "pst_hroot" || pst_name[k].substr(0, 6) == "pst_hub")
                $display("PST %s cyc %0d", pst_name[k], pst_cyc[k]);
            $display("CLAND_START hub_C %0d hub_Wi %0d hub_Wo %0d hroot_WN %0d hroot_WS %0d hroot_EN %0d hroot_ES %0d (root reset released %0d)",
                     c_hubC, c_hubWi, c_hubWo, c_hrWN, c_hrWS, c_hrEN, c_hrES, c_por_root);
            $display("HUBWI mission_start(start_t13) first %0d (START+%0d) high_before_START %0d; static_setup_ready landed %0d (inject %0d, +%0d)",
                     c_t13, c_t13 - T_START, c_t13_pre, c_setup_wi, T_SETUP, c_setup_wi - T_SETUP);
            $display("BOOT mode %0d d2d_boot_begin first %0d n %0d; o_host_boot_go_d1 first %0d (START+%0d) n %0d",
                     mode, c_begin, n_begin, c_go_d1, c_go_d1 - T_START, n_go_d1);
            if (mode == 0) begin
                if (npst == NP && n_go_d1 == 1 && c_go_d1 > T_START && c_t13_pre == 0) $display("VERDICT PASS mode0 boot_go_d1 rises once after START (START+%0d)", c_go_d1 - T_START);
                else $display("VERDICT FAIL mode0");
            end else begin
                if (n_go_d1 == 0) $display("VERDICT EXPECTED mode1 old predicate: boot_go_d1 never rises (closed loop, = native veh60)");
                else $display("VERDICT UNEXPECTED mode1 boot_go_d1 rose");
            end
            $finish;
        end
    end
endmodule
'''
open(f'{W}/tb_start_skel.sv', 'w').write(tb)
fl = cells + [BRIDGE, f'{W}/dkv63_host_stub.sv', PROV] + [f'{W}/skel/{f}' for f in parts] + [JOINED, f'{W}/tb_start_skel.sv']
open(f'{W}/files.f', 'w').write('\n'.join(fl) + '\n')
print(json.dumps({'parts': len(parts), 'pst': len(pst), 'tb_inputs': len(conns)}))
