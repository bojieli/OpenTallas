#!/usr/bin/env python3
"""TOK-HEAD-LAND-1: bench top for the LANDED HEAD die top (gen rtl --clock-landing, strap form).

Every region clock input clk_region_<R> of s81_head_top is driven from the bench clock delayed by that region's
routed die-clock tap arrival (DIE-HEAD-17 GATE combo GRT-RC, proof_t/tap_arrivals_<C>.json, late_ps), so each
count-aligned crossing sees its planned phase d (plan d_ps = late_dst - late_src within +-29 ps, CHECKED).  Region R
takes the tap of the partition(s) in R (region = partition in the part map); a region with several taps takes
their mean and the spread is reported.  --zero drives every region clock with 0 delay (control: no phases).
Other inputs (PHY rx, rck) are tied 0.  rst_n / start as TOK-ALL-15 tb_die.sv.

  mk_tb_land.py TOP.sv TAP_ARRIVALS.json REGIONS.json OUT.sv [--zero] [--scale S] [--stages START_STAGES.sv]

--stages: the die START tree (start_stage_emit.py ot_die_start_stages, DIE-HEAD-17 358 stages): the top's pst_<part>
inputs are driven by its outputs, its rs_<part> inputs by the top's rs_ outputs, rst_raw_n = the bench rst_n, and each
stage clock t_st_<cell>__clk = bench clock delayed by that tree cell's routed arrival (node_late_ps of the node whose
node_cell is <cell>; same arrival table).  Without --stages the pst_ inputs are tied 0 (no START tree).
"""
import json, re, sys
from pathlib import Path

top, arr, regs, out = map(Path, sys.argv[1:5])
zero = '--zero' in sys.argv
scale = float(sys.argv[sys.argv.index('--scale') + 1]) if '--scale' in sys.argv else 1.0
txt = top.read_text()
hdr = txt[txt.index('module s81_head_top'):txt.index(');')]
ins = re.findall(r'input\s+wire\s*(\[[^\]]+\])?\s*(\w+)', hdr)
outs = re.findall(r'output\s+wire\s*(\[[^\]]+\])?\s*(\w+)', hdr)
AJ = json.loads(arr.read_text())
taps = {x['part']: x['late_ps'] for x in AJ['taps']}
cell_arr = {AJ['node_cell'][n]: AJ['node_late_ps'][n] for n in AJ['node_cell']}
stages = Path(sys.argv[sys.argv.index('--stages') + 1]) if '--stages' in sys.argv else None
R = json.loads(regs.read_text())
# region -> partitions: from the region table boxes (part centre inside box), as clock_landings.py does
# Each delayed clock is its own free-running 833 ps clock started at 0.4165 ns + (delay mod T): physically identical to
# the bench clock delayed by the arrival (periodic clock, all edges well before rst_n release).  NOT `x <= #d ck`:
# Verilator 5.050 --timing evaluates that RHS at the END of the delay (x = ck(t+d)), inverting every clock whose delay
# lies in an odd half-period window (found TOK-HEAD-LAND-1: lk_HOST0 2920 ps ran inverted vs sst5 2889 ps).
# Precision 100 fs: #0.4165 is exact (1 ps precision rounded it to 0.417 -> 834 ps period, 1 ps/cycle drift).
def dclk(n, d_ps):
    ph = (d_ps % 833.0) / 1000.0
    return f' reg {n} = 0; initial begin #({0.4165 + ph:.4f}); forever begin {n} = 1; #0.4165; {n} = 0; #0.4165; end end'
lines = ['`timescale 1ns/100fs', '// GENERATED by mk_tb_land.py (TOK-HEAD-LAND-1): landed HEAD die top bench', 'module tb;',
         ' reg ck = 0; always #0.4165 ck = ~ck;', ' reg rst_n = 0, start = 0;']
conn = ['.rst_n(rst_n)', '.start(start)']
rep = []
for w, n in ins:
    if n in ('rst_n', 'start'):
        continue
    if n.startswith('clk_region_'):
        tag = n[len('clk_region_'):]
        parts = [tag] if tag in taps else []   # region = partition (part map); fail-closed otherwise
        if not parts:
            raise SystemExit(f'no tap for region {tag}')
        vals = [taps[p] for p in parts]
        d = 0.0 if zero else scale * sum(vals) / len(vals)
        rep.append((tag, d, max(vals) - min(vals)))
        lines.append(dclk(n, d))
        conn.append(f'.{n}({n})')
    elif stages and n.startswith('pst_'):
        lines.append(f' wire {n};')
        conn.append(f'.{n}({n})')
    else:
        lines.append(f' wire {w or ""} {n} = 0;')
        conn.append(f'.{n}({n})')
for w, n in outs:
    lines.append(f' wire {w or ""} {n};')
    conn.append(f'.{n}({n})')
lines.append(' s81_head_top dut (' + ', '.join(conn) + ');')
nst = 0
if stages:
    st = stages.read_text()
    sh = st[st.index('module ot_die_start_stages'):st.index(');')]
    sc = ['.rst_raw_n(rst_n)']
    for n in re.findall(r'(?:input|output)\s+wire\s+(\w+)', sh):
        if n == 'rst_raw_n':
            continue
        m = re.fullmatch(r't_st_(\w+)__clk', n)
        if m:
            d = 0.0 if zero else scale * cell_arr[m.group(1)]
            lines.append(dclk(n, d))
            nst += 1
        sc.append(f'.{n}({n})')
    lines.append(' ot_die_start_stages u_start_stages (' + ', '.join(sc) + ');')
lines += [' integer maxc;', ' initial begin',
          '  if (!$value$plusargs("MAXC=%d", maxc)) maxc = 12000;',
          '  repeat (8) @(negedge ck); rst_n = 1; repeat (4) @(negedge ck); start = 1;',
          '  repeat (maxc) @(negedge ck);', '  $finish;', ' end']
# boot monitor (ctl region): count origin, local START tap, die-wide landing ready/fault, first GO / result beats
lines += [' integer dc = 0; always @(posedge ck) dc <= dc + 1;',
          ' reg p_cs = 0, p_t20 = 0, p_rdy = 0, p_flt = 0, p_go = 0, p_b = 0;',
          ' always @(posedge ck) begin']
for sig, var in (('dut.ctl.cland_start', 'p_cs'), ('dut.ctl.start_t20', 'p_t20'), ('dut.ctl.cland_up_ready', 'p_rdy'),
                 ('dut.ctl.cland_up_fault', 'p_flt')):
    lines.append(f'  if ({sig} !== {var}) begin $display("BOOT cyc%0d {sig[4:]}=%b", dc, {sig}); {var} <= {sig}; end')
lines += ['  if (dut.ctl.x_o[512] && !p_go) $display("BOOT cyc%0d ctl.x_o GO", dc); p_go <= dut.ctl.x_o[512];',
          '  if (dut.ctl.b_i[514] && !p_b) $display("BOOT cyc%0d ctl.b_i result", dc); p_b <= dut.ctl.b_i[514];',
          ' end', 'endmodule']
out.write_text('\n'.join(lines) + '\n')
ds = [d for _, d, _ in rep]
print(json.dumps(dict(regions=len(rep), zero=zero, scale=scale, min_ps=min(ds), max_ps=max(ds),
                      max_in_region_spread_ps=max(s for _, _, s in rep), start_stage_clocks=nst)))
