#!/usr/bin/env python3
"""TOK-ALL-15: MEASURED-VIEW ot_s81hd_bundle_native (same header as main): go -> res_v after LB cycles (calibrated so
the partition GO->result equals the TOK-14 measured 8,429 and checked cycle-by-cycle by the TOK-14 lock-step tb
against the real legacy reference tile on real ROM images), result {row, bits} = that tile's RTL-measured argmax
(TOK-14 per_tile.json, == golden), selected by the tile's own row0 strap.  The whole die top (spine, chains, turns,
stations, ctl wrapper, reset/START wavefront) stays the real generated RTL."""
import json, re, sys
from pathlib import Path
root, gold, per_tile, out, lb = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]), int(sys.argv[5])
txt = (root / 'rtl/dsrom_sys/s81_head/ot_s81hd_bundle_native.sv').read_text()
m = re.search(r'\bmodule\s+ot_s81hd_bundle_native\b', txt)
t2 = re.sub(r'//[^\n]*', lambda x: ' ' * len(x.group(0)), txt)
i, d = m.end(), 0
while not (t2[i] == ';' and d == 0):
    d += t2[i] == '('; d -= t2[i] == ')'; i += 1
hdr = re.sub(r'`[A-Za-z_]+[^\n]*', '', t2[m.start():i + 1])
G = json.loads(gold.read_text())['tiles']
P = {r['tile']: r for r in json.loads(per_tile.read_text())}
case = []
for n, g in sorted(G.items(), key=lambda kv: kv[1]['row0']):
    p = P[n]; assert p['row'] == g['row'] and p['bits'] == g['bits'] and p['go_to_result'] == 8429, n
    case.append(f"            17'd{g['row0']}: begin r_row = 17'd{p['row']}; r_bits = 32'h{p['bits']}; end   // {n}")
ft = '\n'.join(f'    assign hci{k}_{n}_o = hci{k}_{n}_i;' for k in range(5) for n in ('ck0', 'ck1', 'mesh', 'rst'))
body = f'''
    integer LB = {lb};
    integer boost = -1;
    initial begin if ($value$plusargs("LB=%d", LB)) begin end if ($value$plusargs("BOOST_ROW0=%d", boost)) begin end end
    // die-owned clock/reset/mesh FT pins: pass-through, as the real bundle
{ft}
    assign fault = 1'b0; assign head_v = '0; assign head_d = '0; assign head_row = '0;
    reg [16:0] r_row; reg [31:0] r_bits;
    always @* begin
        r_row = 17'h1FFFF; r_bits = 32'hFF800000;
        case (row0)
{chr(10).join(case)}
            default: begin r_row = 17'h1FFFF; r_bits = 32'hFF800000; end
        endcase
        if (boost >= 0 && row0 == boost[16:0]) begin r_row = row0 + 17'd7; r_bits = 32'h7F000000; end   // control: +BOOST_ROW0
    end
    integer cnt; reg go_d;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) begin cnt <= -1; res_v <= 1'b0; go_d <= 1'b0; end
        else begin
            go_d <= go;
            if (go && !go_d) begin cnt <= 1; res_v <= 1'b0; end
            else if (cnt > 0) begin
                if (cnt == LB) begin res_v <= 1'b1; res_row <= r_row; res_bits <= r_bits; cnt <= -1; end
                else cnt <= cnt + 1;
            end
        end
endmodule
'''
rest = txt[txt.index('endmodule', i) + len('endmodule'):]   # the file's other modules (ot_s81hd_kreg ...), unchanged
out.write_text('`timescale 1ns/1ps\n// GENERATED by mkbstub.py (TOK-ALL-15) -- measured-view bundle, simulation only\n' + hdr + body + rest)
print('cases', len(case), 'LB', lb)
