#!/usr/bin/env python3
"""HBM-REFORM-A d44v part 17 inputs: lanes canon -> 4 x ot_hbm_su_pg_lane1_core, lanes_plain -> 4 x ot_hbm_su_pg_lane1p_core.
Both rows are ot_hbm_su_pg_lanes4_core, the RTL already cut by part 6 on lanes8_11 (4 independent lane + bank pairs, 0 crossings).
lane1p = lane1 text with the module renamed (+ LDCS 1, HBM-GAPS-4-L1P 11-05): the plain slot 440.64x457.92 cannot hold 2x2 lane1 (380.16x622.08), so one more outline: 440.64x112.32, 4 stacked (A3; the first 216x224.64 2x2 outline stopped at GRT-0116).
    gen_p17.py REPO KIT_CANON_RTL KIT_PLAIN_RTL OUT     writes RTL into REPO, glue + conn + split_p17.json into OUT"""
import json, re, subprocess, sys
from pathlib import Path
repo, kc, kp, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]); out.mkdir(parents=True, exist_ok=True)
A = repo / "rtl/hbm_accel/cores_split/reform_1103/ot_hbm_su_static_pgslice_lg__lanes8_11"
B = repo / "rtl/hbm_accel/cores_split/reform_1104a/lanes4"; B.mkdir(parents=True, exist_ok=True)
R = repo / "results/die_hbm_1103/reform/split_p6"
L1, LP, C4, CP = "ot_hbm_su_pg_lane1_core", "ot_hbm_su_pg_lane1p_core", "ot_hbm_su_pg_lanes4_core__split", "ot_hbm_su_pg_lanes4_core__splitp"
HDR = "// HBM-REFORM-A 11-04 d44v part 17: GENERATED by results/die_hbm_1104/reform_a/part17/gen_p17.py from reform_1103 lanes8_11 (module names only). Do not edit.\n"
# HBM-GAPS-4-L1P 11-05 (lane1p RE-FORM, COORD 19:2x): lane1p = lane1 text renamed (MLAT 5 comes with it, HBM-26) plus the
# opt-in carry-save offset load LDCS 1 of ot_hbm_su_static_lane (bit-exact, same cycles; bench reform_a/part17/ldcs_bench)
LP_PARAM = "    parameter integer ALAT = 3,\n"
LP_LDCS = LP_PARAM + "    parameter integer LDCS = 1,   // HBM-GAPS-4-L1P: carry-save LEAF offset load (ot_hbm_su_static_lane g_ld3c)\n"
LP_INST = ".MLAT(MLAT),.ALAT(ALAT),.LEAF(1)"
lp = (A / f"{L1}.sv").read_text().replace(L1, LP)
assert lp.count(LP_PARAM) == 1 and lp.count(LP_INST) == 1, "lane1 text changed: re-check the LP LDCS edit"
lp = lp.replace(LP_PARAM, LP_LDCS).replace(LP_INST, ".MLAT(MLAT),.ALAT(ALAT),.LDCS(LDCS),.LEAF(1)")
(B / f"{LP}.sv").write_text(HDR + lp)
(B / f"{CP}.sv").write_text(HDR + (A / f"{C4}.sv").read_text().replace(L1, LP).replace(C4, CP))
CANON = dict(canon=("ot_hbm_su_static_pgslice_lg__lanes__canon_cf1e77", kc, C4, A / f"{C4}.sv", A / f"{L1}.sv", "lanes_canon"),
             plain=("ot_hbm_su_static_pgslice_lg__lanes_plain__canon_663526", kp, CP, B / f"{CP}.sv", B / f"{LP}.sv", "lanes_plain"))
for k, (core, kit, comp, comp_sv, sub, tag) in CANON.items():
    g = out / f"{core}__p17glue.sv"
    subprocess.run([sys.executable, "-I", str(R / "split_glue.py"), str(kit / f"{core}__wrap.sv"), "ot_hbm_su_pg_lanes4_core", comp, str(comp_sv), str(g)], check=True)
    nj = out / f"{tag}.netlist.json"
    subprocess.run(["bash", str(R / "netlist2.sh"), str(nj), core, str(g), str(comp_sv), str(sub)], check=True)
    subprocess.run([sys.executable, "-I", str(R / "split_conn.py"), str(nj), core, str(out / f"{tag}.conn.json")], check=True)
    nj.unlink()
M, MW, MH = "ot_sram_1r1w_128x256_m1_r2c2", 94.824, 41.064
X = (28.944, 173.016, 317.088); Y = (5.4, 46.488)    # 3 x 2 grid: macro pins are W/E on M4, so each column edge needs a real band. End bands 24.6, mid bands 49.2 (2 vs 4 macro edges); 20.4 cell strip on top. A3: the 2 x 3 grid in 216 x 224.64 had W/E bands of 3.5 and 10.8 and stopped at GRT-0116
macs = []
for i, (y, x) in enumerate((y, x) for y in Y for x in X):
    macs.append(dict(name=f"u_core.u_bank0.u_data.g_read[{i}].u_m", master=M, orient="R0", rect_um=[x, y, round(x + MW, 3), round(y + MH, 3)]))
ENTRY = [220.32, 95.04]                           # centre x, in the top cell strip 87.552..108 (island +-4.32 clear)
PRE = "u_fcore.u_core."
LW, LH = 190.08, 311.04; PW, PH = 440.64, 112.32
Y0 = 207.36                                       # canon: strip centred on the 725.76 slot height
lay_c = {PRE + f"u_p{i}": dict(xy=[round(i * LW, 3), Y0], wh=[LW, LH]) for i in range(4)}
spec = [dict(core=CANON["canon"][0], sha="8dd205e8bcc", part="p17", glue=CANON["canon"][0] + "__p17glue.sv", conn="lanes_canon.conn.json",
             subs=[dict(module=L1, cells=86270)], added_cycles="0 on every port", layout=lay_c, clock_entry={L1: [164.16, 155.52]}),
        dict(core=CANON["plain"][0], sha="8dd205e8bcc", part="p17", glue=CANON["plain"][0] + "__p17glue.sv", conn="lanes_plain.conn.json",
             subs=[dict(module=LP, cells=86270)], added_cycles="0 on every port", layout="LEAST_DISPLACEMENT", clock_entry={LP: ENTRY},
             macros={LP: macs}, macro_basis="HBM-REFORM-A d44v part 17: 3 x 2 grid in the 440.64 x 112.32 tile, 4 stacked in the slot; W/E bands 24.6, 49.2, 49.2, 24.6, top cell strip 20.4; clock entry in the top strip")]
(out / "split_p17.json").write_text(json.dumps(spec, indent=1) + "\n")
print("wrote", out)
