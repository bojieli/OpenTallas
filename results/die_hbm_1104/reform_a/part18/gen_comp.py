#!/usr/bin/env python3
"""HBM-REFORM-A part 18: compositions with the ports of the uncut lane cores: lane_x (__fs) + sfu_s (__fs), seam wires only.
    gen_comp.py REPO OUTDIR    MUT 1: XS 3; MUT 2: y_exp and y_div swapped at the seam; MUT 3: seam R bit 7 flipped; MUT 4: seam fn bit 2 tied 0; MUT 5: seam fault tied 0"""
import re, sys
repo, out = sys.argv[1:3]
S = f"{repo}/rtl/hbm_accel/cores_split/ot_hbm_su_static_pgslice_lg"
for base, x in (("ot_hbm_su_pg_lane_exp_core", "ot_hbm_su_pg_lane_exp_x_core"), ("ot_hbm_su_pg_lane_full_core", "ot_hbm_su_pg_lane_full_x_core")):
    t = open(f"{S}/{base}.sv").read()
    m = re.search(r"module " + base + r"\s*#\(.*?\)\s*\((.*?)\n\);", t, re.S)
    ports = re.findall(r"(input|output)\s+wire\s+(\[[^\]]*\]\s*)?(\w+)", m[1])
    decl = ",\n".join(f"    {d} wire {w or ''}{n}" for d, w, n in ports)
    cn = ",\n".join(f"        .{n}({n})" for _, _, n in ports)
    comp = base + "__splitx"
    open(f"{out}/{comp}.sv", "w").write(f"""// HBM-REFORM-A 11-04 part 18: GENERATED by results/die_hbm_1104/reform_a/part18/gen_comp.py. Composition of {base} (same ports):
// u_l = {x} and u_s = ot_hbm_su_pg_sfu_s_core, each in its kit face shell (__fs), the seam only wires.
`timescale 1ns/1ps
`default_nettype none
module {comp} #(parameter integer MUT = 0) (
{decl}
);
    wire sx_v, sx_fault;
    wire [31:0] sx_r, sx_y_exp, sx_y_div;
    wire [2:0] sx_fn;
    {x}__fs #(.XS(MUT == 1 ? 3 : 4)) u_l (
{cn},
        .sx_v(sx_v), .sx_r(sx_r), .sx_fn(sx_fn), .sx_y_exp(MUT == 2 ? sx_y_div : sx_y_exp), .sx_y_div(MUT == 2 ? sx_y_exp : sx_y_div),
        .sx_fault(MUT == 5 ? 1'b0 : sx_fault));
    ot_hbm_su_pg_sfu_s_core__fs u_s (.clk(lane_clk_stage[4]), .rst_n(lane_rst_n), .v(sx_v), .R(MUT == 3 ? sx_r ^ 32'h80 : sx_r),
        .ci_sfu(MUT == 4 ? {{1'b0, sx_fn[1:0]}} : sx_fn), .y_exp(sx_y_exp), .y_div(sx_y_div), .fault(sx_fault));
endmodule
`default_nettype wire
""")
print("ok")
