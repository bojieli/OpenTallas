#!/usr/bin/env python3
"""HBM-REFORM-A 11-04: lane_exp / lane_exp0 RE-FORM generator.

Cuts the S-stage special-function chain (exp, +1, divide) out of the KIND 1/2 SU lane into its own hard core
ot_hbm_su_pg_sfu_s_core.  The seam is thin (36 in, 65 out), one clock, every bit a registered face.  Each seam direction
crosses 2 face flops (kit face shell on both sub-cores), so exp and sigmoid/SiLU take S-stage depth + XS (XS = 4); no
other op depth moves.  The lane's insertion line takes the same +XS.  Arithmetic members are verbatim.

    gen_lane_x.py REPO OUTDIR  -> ot_hbm_su_static_lane_x.sv, ot_hbm_su_static_lane_pinreg_x.sv,
                                  ot_hbm_su_pg_lane_exp_x_core.sv, ot_hbm_su_pg_lane_full_x_core.sv, ot_hbm_su_pg_sfu_s_core.sv
"""
import re, sys
repo, out = sys.argv[1:3]
A = f'{repo}/rtl/hbm_accel/generic/adapters/static_su/arithmetic'
S = f'{repo}/rtl/hbm_accel/cores_split/ot_hbm_su_static_pgslice_lg'
HDR = '// HBM-REFORM-A 11-04: GENERATED by results/die_hbm_1104/reform_a/part18/gen_lane_x.py from %s. Do not edit.\n'


def sub1(txt, a, b):
    assert txt.count(a) == 1, (a, txt.count(a))
    return txt.replace(a, b)


# ---- lane: S-stage chain out through seam ports
t = open(f'{A}/ot_hbm_su_static_lane.sv').read()
t = sub1(t, 'module ot_hbm_su_static_lane #(', 'module ot_hbm_su_static_lane_x #(\n    parameter integer XS = 4,           // seam edges added to exp and sigmoid/SiLU (2 face flops each way)')
t = sub1(t, '    output wire              fault,\n    output wire              coll\n);',
         '    output wire              fault,\n    output wire              coll,\n'
         '    // ---- seam to ot_hbm_su_pg_sfu_s_core\n'
         '    output wire              sx_v,\n    output wire [31:0]       sx_r,\n    output wire [2:0]        sx_fn,\n'
         '    input  wire [31:0]       sx_y_exp,\n    input  wire [31:0]       sx_y_div,\n    input  wire              sx_fault\n);')
t = sub1(t, 'H_EXP = D_EXP, H_SIG = D_SIG,', 'H_EXP = D_EXP + XS, H_SIG = D_SIG + XS,')
a = t.index('            // sigmoid chain: exp(-R); +1; (1 | R) / that')
b = t.index('            wire [6:0] sel;')
chain = t[a:b]
t = t[:a] + ('            // sigmoid chain lives in ot_hbm_su_pg_sfu_s_core (HBM-REFORM-A)\n'
             '            wire is_exp = (ci_sfu == SFU_EXP), is_sig = (ci_sfu == SFU_SIGM || ci_sfu == SFU_SILU);\n'
             '            wire [31:0] y_exp = sx_y_exp, y_div = sx_y_div;\n') + t[b:]
t = sub1(t, '.DMAX(D_SIG)) u_l4', '.DMAX(D_SIG + XS)) u_l4')
t = sub1(t, '            assign f_sfu = f_e | f_den | f_div;\n', '            assign f_sfu = sx_fault;\n')
t = sub1(t, '            assign t4 = {R, r_b, r_c, r_o}; assign v4 = v3; assign c4 = 1\'b0;\n',
         '            assign t4 = {R, r_b, r_c, r_o}; assign v4 = v3; assign c4 = 1\'b0;\n')
t = sub1(t, '    assign side_x = R;\n', '    assign side_x = R;\n    assign sx_v = v3; assign sx_r = R; assign sx_fn = ci_sfu;\n')
open(f'{out}/ot_hbm_su_static_lane_x.sv', 'w').write(HDR % 'ot_hbm_su_static_lane.sv' + t)

# ---- SFU core: the chain verbatim, MLAT 4 / ALAT 3, own pin-registered reset
c = chain.replace('v3 &&', 'v &&').replace('.x(is_exp ? R : {~R[31], R[30:0]})', '.x(is_exp ? R : {~R[31], R[30:0]})')
c = '\n'.join(l[8:] if l.startswith('        ') else l for l in c.splitlines())
sfu = HDR % 'the g_sfu block of ot_hbm_su_static_lane.sv (chain verbatim)' + f'''`timescale 1ns/1ps
`default_nettype none
module ot_hbm_su_pg_sfu_s_core #(
    parameter integer MLAT = 4,
    parameter integer ALAT = 3,
    parameter integer PIN_RST = 1
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        v,
    input  wire [31:0] R,
    input  wire [2:0]  ci_sfu,
    output wire [31:0] y_exp,
    output wire [31:0] y_div,
    output wire        fault
);
    localparam [2:0] SFU_EXP = 1, SFU_SIGM = 4, SFU_SILU = 5;
    localparam integer D_DIV = 19, D_EXP = 7 * MLAT + 8 * ALAT + 4;
    localparam integer K = (MLAT != 3 || ALAT != 3) ? 1 : 0;
    wire [7:0] clk_stage = {{8{{clk}}}};
    wire rst_i;
    generate if (PIN_RST != 0) begin : g_pin_rst
        reg rst_q;
        always @(posedge clk) rst_q <= rst_n;
        assign rst_i = rst_q;
    end else begin : g_async_rst
        assign rst_i = rst_n;
    end endgenerate
{c.replace('rst_n(rst_n)', 'rst_n(rst_i)').replace('clk_stage[4], rst_n,', 'clk_stage[4], rst_i,').replace('wire [31:0] y_exp, den, num_d, y_div;', 'wire [31:0] den, num_d;')}    assign fault = f_e | f_den | f_div;
endmodule
`default_nettype wire
'''
open(f'{out}/ot_hbm_su_pg_sfu_s_core.sv', 'w').write(sfu)

# ---- pinreg wrapper: seam ports pass through
p = open(f'{A}/ot_hbm_su_static_lane_pinreg.sv').read()
p = sub1(p, 'module ot_hbm_su_static_lane_pinreg #(', 'module ot_hbm_su_static_lane_pinreg_x #(\n    parameter integer XS = 4,')
p = sub1(p, '    output wire              fault,\n    output wire              coll\n);' if '    output wire              fault,\n    output wire              coll\n);' in p else '    output wire fault,\n    output wire coll\n);',
         '    output wire fault,\n    output wire coll,\n    output wire sx_v,\n    output wire [31:0] sx_r,\n    output wire [2:0] sx_fn,\n'
         '    input wire [31:0] sx_y_exp,\n    input wire [31:0] sx_y_div,\n    input wire sx_fault\n);')
p = sub1(p, 'ot_hbm_su_static_lane #(.FETCH_EXTRA_EDGES(FETCH_EXTRA_EDGES + 2),', 'ot_hbm_su_static_lane_x #(.XS(XS), .FETCH_EXTRA_EDGES(FETCH_EXTRA_EDGES + 2),')
p = sub1(p, '.kv_wdata(l_kv_wdata), .ro_v(l_ro_v), .ro_x(l_ro_x), .fault(l_fault), .coll(l_coll));',
         '.kv_wdata(l_kv_wdata), .ro_v(l_ro_v), .ro_x(l_ro_x), .fault(l_fault), .coll(l_coll),\n'
         '        .sx_v(sx_v), .sx_r(sx_r), .sx_fn(sx_fn), .sx_y_exp(sx_y_exp), .sx_y_div(sx_y_div), .sx_fault(sx_fault));')
open(f'{out}/ot_hbm_su_static_lane_pinreg_x.sv', 'w').write(HDR % 'ot_hbm_su_static_lane_pinreg.sv' + p)

# ---- lane + bank cores
for name, new in (('ot_hbm_su_pg_lane_exp_core', 'ot_hbm_su_pg_lane_exp_x_core'), ('ot_hbm_su_pg_lane_full_core', 'ot_hbm_su_pg_lane_full_x_core')):
    q = open(f'{S}/{name}.sv').read()
    q = '\n'.join(l for l in q.splitlines() if not l.startswith('//'))
    q = sub1(q, f'module {name} #(', f'module {new} #(\n    parameter integer XS = 4,')
    q = re.sub(r',?\n\);', ',\n    output wire sx_v,\n    output wire [31:0] sx_r,\n    output wire [2:0] sx_fn,\n    input wire [31:0] sx_y_exp,\n'
               '    input wire [31:0] sx_y_div,\n    input wire sx_fault\n);', q, count=1)
    q = sub1(q, 'ot_hbm_su_static_lane_pinreg #(.LN(7)', 'ot_hbm_su_static_lane_pinreg_x #(.XS(XS),.LN(7)')
    m = re.search(r'ot_hbm_su_static_lane_pinreg_x #\(.*?\) u_lane \(\n', q, re.S)
    assert m
    q = q[:m.end()] + '        .sx_v(sx_v), .sx_r(sx_r), .sx_fn(sx_fn), .sx_y_exp(sx_y_exp), .sx_y_div(sx_y_div), .sx_fault(sx_fault),\n' + q[m.end():]
    open(f'{out}/{new}.sv', 'w').write(HDR % f'{name}.sv' + q + '\n')
print('ok')
