#!/usr/bin/env python3
"""HBM-REFORM-B d44v part 21: ot_hbm_idx_selector_static_sel -> the proven s3 cluster as plan tiles (ot_hidx_s3_ctl + 4 x ot_hidx_s3_q),
wires-only composition (no landed parent, no landing rings). One template in two forms, so the wiring is the same by construction.
  __p21fs.sv    bench form: tiles are <tile>__fs (kit face shell model), MUT seam mutants
  __p21comp.sv  plan form
  __p21glue.sv  __fcore + the plan module
clk_mem stays a port of the master and is unloaded: every SRAM runs on its quadrant clock (as ot_hbm_idx_selector_s3).
    gen_p21.py OUT"""
import sys
from pathlib import Path
out = Path(sys.argv[1]); CORE = "ot_hbm_idx_selector_static_sel"
PORTS = """input wire clk_ctl, input wire [3:0] clk_q, input wire [11:0] clk_mem, input wire rst_n,
    input wire [3:0] op, input wire [1:0] pass, input wire [7:0] addr, input wire [9:0] k, input wire [2367:0] in_line,
    output wire [3:0] selected_v, output wire [2367:0] selected_line, output wire fault"""
NAMES = "clk_ctl clk_q clk_mem rst_n op pass addr k in_line selected_v selected_line fault".split()
def comp(name, fs):
    sfx = "__fs" if fs else ""
    par = "#(.DMUT(DMUT)) " if fs else ""
    hdr = "#(parameter integer DMUT = 0, parameter integer MUT = 0) " if fs else ""
    t = [f"// HBM-REFORM-B d44v part 21: GENERATED by gen_p21.py. {'Bench' if fs else 'Plan'} form of the composition.",
         "`default_nettype none",
         f"module {name} {hdr}(\n    {PORTS});",
         "    wire [13:0] cw; wire [15:0] thr; wire [13:0] ties_0, ties_1, ties_2, ties_3;",
         "    wire [24:0] ret_0, ret_1, ret_2, ret_3; wire qf_0, qf_1, qf_2, qf_3;"]
    if fs:
        t += ["    // bench seam mutants: each must FAIL the bench",
              "    reg [13:0] ties_d; reg [13:0] cw_d; always @(posedge clk_ctl) begin ties_d <= ties_0; cw_d <= cw; end",
              "    wire [13:0] ties_q0 = (MUT == 1) ? ties_d : ties_0;",
              "    wire [13:0] cw_q2 = (MUT == 2) ? cw_d : cw;",
              "    wire [24:0] ret_3m = (MUT == 3) ? (ret_3 ^ 25'd1) : ret_3;",
              "    wire [591:0] il_1 = (MUT == 4) ? {in_line[1183:594], in_line[592], in_line[593]} : in_line[592+:592];"]
        w = dict(t0="ties_q0", cw2="cw_q2", r3="ret_3m", il1="il_1")
    else:
        w = {}
    g = lambda k, d: w.get(k, d)
    t += [f"    ot_hidx_s3_ctl{sfx} {par}u_ctl (.clk(clk_ctl), .rst_n(rst_n), .op(op), .pass(pass), .addr(addr), .k(k), .cw(cw), .thr(thr),",
          "        .ties_0(ties_0), .ties_1(ties_1), .ties_2(ties_2), .ties_3(ties_3), .ret_0(ret_0), .ret_1(ret_1), .ret_2(ret_2),",
          f"        .ret_3({g('r3', 'ret_3')}), .qf_0(qf_0), .qf_1(qf_1), .qf_2(qf_2), .qf_3(qf_3), .fault(fault));"]
    for q in range(4):
        cw = g("cw2", "cw") if q == 2 else "cw"; ties = g("t0", "ties_0") if q == 0 else f"ties_{q}"
        il = g("il1", f"in_line[{q * 592}+:592]") if q == 1 else f"in_line[{q * 592}+:592]"
        t += [f"    ot_hidx_s3_q{sfx} {par}u_q{q} (.clk(clk_q[{q}]), .rst_n(rst_n), .cw({cw}), .thr(thr), .ties({ties}), .in_line({il}),",
              f"        .ret(ret_{q}), .qfault_o(qf_{q}), .selected_v_o(selected_v[{q}]), .selected_line_o(selected_line[{q * 592}+:592]));"]
    t += ["endmodule", "`default_nettype wire", ""]
    return "\n".join(t)
(out / f"{CORE}__p21fs.sv").write_text(comp(f"{CORE}__p21fs", True))
(out / f"{CORE}__p21comp.sv").write_text(comp(f"{CORE}__p21comp", False))
pm = ", ".join(f".{n}({n})" for n in NAMES)
(out / f"{CORE}__p21glue.sv").write_text(
    f"// HBM-REFORM-B d44v part 21: plan module {CORE} = thin parent glue of the split hard core (wires only).\n`default_nettype none\n"
    f"module {CORE}__fcore (\n    {PORTS});\n    {CORE}__p21comp u_core ({pm});\nendmodule\n"
    f"module {CORE} (\n    {PORTS});\n    {CORE}__fcore u_fcore ({pm});\nendmodule\n`default_nettype wire\n")
