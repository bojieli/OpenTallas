#!/usr/bin/env python3
"""HBM-REFORM-B5: ot_hfd_coll_q2n2_body_core = rest + ot_q2nf_qout, 0 added cycles: the kit face flops ARE the qslots registers.
    gen_q2n.py SRC_TREE OLD_BODY.sv OUT_MASTER.sv OUT_TILE.sv
Flat: source -> g_qcap.captured -> qso.captured_p -> switch -> qso.dst_d -> pin out-face, or -> link.wr_flit_pin.
Split, same edge count on every path:
  source -> rest out-face (= captured) -> tile in-face (= captured_p) -> switch -> tile dst_d -> tile out-face -> pin
  link dest: switch -> tile out-face (= dst_d) -> rest in-face (= wr_flit_pin)
  sink_slot/select: from upipe d1 (inst - 2), through out-face + in-face, into the tile's own sink_*_p
  captured_slot: from upipe d2 (inst - 1), through out-face + in-face, into the tile's own captured_slot_p
  dest_v in rest: a local 2-flop copy of sink_slot, the same value as dst_v (slice 0)
Fault only: select_fault / unavailable_fault +2 edges to u_fj; both sticky, no effect on data, valid or reservation.
"""
import re, sys
from pathlib import Path
src, old, om, ot = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4])
P = "rtl/hbm_accel/generic/collective/p2p/"
m = (src / (P + "ot_hfd_coll_q2_hard_v8g_s.sv")).read_text()
def rp(s, a, b):
    assert s.count(a) == 1, a
    return s.replace(a, b)
m = rp(m, " ot_hgi_coll_upipe_sliced_v7 u_upipe(.clk(clk_upipe),.d1(inst_d1),.d2(inst_d2),.d3(inst));\n",
 """ ot_hgi_coll_upipe_sliced_v7 u_upipe(.clk(clk_upipe),.d1(inst_d1),.d2(inst_d2),.d3(inst));
 wire [ND-1:0] q2f_sink_slot=inst_d1[10+:ND];wire [ND*SELW-1:0] q2f_sink_select=inst_d1[26+:ND*SELW];wire [NS-1:0] q2f_cap_slot=inst_d2[0+:NS];
""")
a = m.index(" // ---- qslots (pin_v2 partition"); b = m.index(" assign dest_v=slice_v[0];\n") + len(" assign dest_v=slice_v[0];\n")
m = m[:a] + """ // ---- qslots: capture checks stay here, the source word and the switch are the tile ot_q2nf_qout (see gen_q2n.py)
 for(genvar s=0;s<NS;s=s+1)begin:g_qcap
  ot_q2nf_cap u_cap(.clk(clk_qslots[s]),.rst_n(rst_n),.src_v(source_v[s]),.capture_slot(capture_calendar[s]),.fault(capture_fault[s]));
 end
 wire [2*PWT-1:0] q2f_lk_d;wire [4772:0] q2f_pin_d;wire [ND*PWT-1:0] q2f_dst_d;
@@PINMAP@@
 ot_q2nf_qout u_qout(.clk(clk_qslots[NS]),.rst_n(rst_n),.captured(source_d),.cap_slot(q2f_cap_slot),.sink_slot(q2f_sink_slot),.sink_select(q2f_sink_select),
  .lk_d(q2f_lk_d),.pin_d(q2f_pin_d),.select_fault(select_fault),.unavailable_fault(unavailable_fault));
 reg [ND-1:0] q2f_sp,q2f_dv;
 always @(posedge clk_qslots[NS] or negedge rst_n)if(!rst_n)begin q2f_sp<=0;q2f_dv<=0;end else begin q2f_sp<=p_sink_slot[ND-1:0];q2f_dv<=q2f_sp;end
 assign dest_v=q2f_dv;
 assign dest_d={q2f_dst_d[ND*PWT-1:2*PWT],q2f_lk_d};
""" + m[b:]
m = rp(m, "ot_hgi_coll_link_e u_link(", "ot_q2nf_link_e u_link(")
assert "g_qout" not in m and "slice_v" not in m
PIN_D = [2, 3, 4, 5, 6, 7, 8, 9, 14]
def slice_dests(k): return PIN_D if k < 16 else [2, 3, 4, 5, 14]
pm_l, off = [], 0
for k in range(18):
    cw = 32 if k < 17 else 1
    for d in slice_dests(k):
        pm_l.append((k, d, off, cw)); off += cw
assert off == 4773
_used = {}
for k, d, o, cw in pm_l:
    for i in range(cw): _used[d * 545 + k * 32 + i] = o + i
pmtxt = "".join(f" assign q2f_dst_d[{b}]=" + (f"q2f_pin_d[{_used[b]}]" if b in _used else "1'b0") + ";\n" for b in range(15 * 545))
m = rp(m, "@@PINMAP@@", pmtxt)
om.write_text(m)
# pin map of the old core: pin bus -> (slice, dst bit)
t = old.read_text()
i = t.index("module ot_hfd_coll_q2n2_body_core ("); w = t[i:]
pm = {}
for mm in re.finditer(r"\.\\u_body\.g_qout\[(\d+)\]\.g2\.[wn]\.o\.u_out\.u\.dst_([dv])\[(\d+)\] \((u_body_g_qout_\d+_g2_[wn]_o_u_out_u_dst_[dv])\[(\d+)\]\)", w):
    k, kind, b, pin, j = int(mm[1]), mm[2], int(mm[3]), mm[4], int(mm[5])
    pm.setdefault(pin, {})[j] = (k, kind, b)
hdr = re.findall(r"output wire \[(\d+):0\] (u_body_g_qout_\S+?),", w[:w.index(");")])
assert hdr and all(len(pm[n]) == int(h) + 1 for h, n in hdr), [(h, n, len(pm.get(n, {}))) for h, n in hdr if len(pm.get(n, {})) != int(h) + 1]
NS, ND, PWT, NSL, SELW = 9, 15, 545, 18, 4
L = ["`timescale 1ns/1ps", "`default_nettype none",
 "// GENERATED by results/die_hbm_1104/reform_b/split_q2n/gen_q2n.py (HBM-REFORM-B5). qslots switch of ot_hfd_coll_q2n2_body_core with the kit face flops as its registers: 0 added cycles.",
 "// MUT (bench): 1 = slice 3 sink_select one edge early (no inner flop), 2 = link dest 0 selects source 1 on slice 5, 3 = captured_slot one edge late, no 4: dst_v is in the rest.",
 """module ot_q2nf_cap(input wire clk,rst_n,src_v,capture_slot,output reg fault);
 reg src_v_p,captured_slot;
 always @(posedge clk or negedge rst_n)
  if(!rst_n)begin src_v_p<=0;captured_slot<=0;fault<=0;end
  else begin src_v_p<=src_v;captured_slot<=capture_slot;if(src_v_p!=captured_slot)fault<=1;end
endmodule
module ot_q2nf_sl #(parameter integer CW=32,parameter integer K=0,parameter integer MUT=0,parameter integer NS=9,parameter integer ND=15,parameter integer SELW=4)(
 input wire clk,rst_n,input wire [NS*CW-1:0] captured,input wire [NS-1:0] cap_slot,input wire [ND-1:0] sink_slot,input wire [ND*SELW-1:0] sink_select,
 output reg [ND-1:0] dst_v,output reg [ND*CW-1:0] sel_d,output reg [ND*CW-1:0] dst_d,output reg select_fault,unavailable_fault);
 reg [NS-1:0] cs_p,cs_q;reg [ND-1:0] ss_p;reg [ND*SELW-1:0] sl_p;
 wire [NS-1:0] cs=(MUT==3)?cs_q:cs_p;
 wire [ND*SELW-1:0] sl=(MUT==1&&K==3)?sink_select:sl_p;
 always @(posedge clk)sl_p<=sink_select;
 always @(posedge clk or negedge rst_n)if(!rst_n)begin cs_p<=0;cs_q<=0;ss_p<=0;end else begin cs_p<=cap_slot;cs_q<=cs_p;ss_p<=sink_slot;end
 always @(posedge clk or negedge rst_n)
  if(!rst_n)begin dst_v<=0;select_fault<=0;unavailable_fault<=0;end
  else begin
   dst_v<=ss_p;
   for(integer d=0;d<ND;d=d+1)if(ss_p[d])begin
    if(int'(sl[d*SELW+:SELW])>=NS)select_fault<=1;
    else if(!cs[sl[d*SELW+:SELW]])unavailable_fault<=1;
   end
  end
 always @* begin : mux
  integer sn;
  sel_d='0;
  for(integer d=0;d<ND;d=d+1)begin
   sn=int'(sl[d*SELW+:SELW]);
   if(MUT==2&&K==5&&d==0)sn=(sn+1)%NS;
   for(integer s=0;s<NS;s=s+1)if(s==sn)sel_d[d*CW+:CW]=sel_d[d*CW+:CW]|captured[s*CW+:CW];
  end
 end
 always @(posedge clk)dst_d<=sel_d;
endmodule
module ot_q2nf_qout #(parameter integer MUT=0,parameter integer NS=9,parameter integer ND=15,parameter integer PWT=545,parameter integer NSL=18,parameter integer SELW=4)(
 input wire clk,rst_n,input wire [NS*PWT-1:0] captured,input wire [NS-1:0] cap_slot,input wire [ND-1:0] sink_slot,input wire [ND*SELW-1:0] sink_select,
 output wire [2*PWT-1:0] lk_d,output wire [4772:0] pin_d,output wire [NSL-1:0] select_fault,unavailable_fault);
 // Sources that arrive at core pins (inj 0 1, vm 4..7 data, reduce 8) keep their two flat flops here: pin face, captured, captured_p.
 // The rest's words (link rx, meta) use its out face as captured and this in face as captured_p.
 wire [NS*PWT-1:0] cq;
 for(genvar s=0;s<NS;s=s+1)begin:g_src
  localparam integer PB=(s==8)?PWT:(s<2||(s>=4&&s<8))?512:0;
  if(PB>0)begin:p reg [PB-1:0] q1,q2;always @(posedge clk)begin q1<=captured[s*PWT+:PB];q2<=q1;end assign cq[s*PWT+:PB]=q2;end
  if(PB<PWT)begin:r assign cq[s*PWT+PB+:PWT-PB]=captured[s*PWT+PB+:PWT-PB];end
 end
 for(genvar k=0;k<NSL;k=k+1)begin:g_s
  localparam integer CW=(k<NSL-1)?32:1;
  wire [NS*CW-1:0] w;wire [ND*CW-1:0] r,c;
  for(genvar s=0;s<NS;s=s+1)begin:g_in assign w[s*CW+:CW]=cq[s*PWT+k*32+:CW];end
  ot_q2nf_sl #(.CW(CW),.K(k),.MUT(MUT),.NS(NS),.ND(ND),.SELW(SELW)) u(.clk(clk),.rst_n(rst_n),.captured(w),.cap_slot(cap_slot),.sink_slot(sink_slot),.sink_select(sink_select),
   .dst_v(),.sel_d(c),.dst_d(r),.select_fault(select_fault[k]),.unavailable_fault(unavailable_fault[k]));
  for(genvar d=0;d<2;d=d+1)begin:g_l assign lk_d[d*PWT+k*32+:CW]=c[d*CW+:CW];end
 end
@@PINASG@@
endmodule"""]
# link: the rest in-face is wr_flit_pin
v5 = (src / (P + "ot_hfd_coll_q_hard_v5.sv")).read_text()
a = v5.index("module ot_hgi_coll_link_e("); b = v5.index("endmodule", a) + 9
lk = rp(v5[a:b].replace("module ot_hgi_coll_link_e(", "module ot_q2nf_link_e("), "ot_hgi_coll_capture_ctl_e u_ctl(", "ot_q2nf_capture_ctl_e u_ctl(")
a = v5.index("module ot_hgi_coll_capture_ctl_e("); b = v5.index("endmodule", a) + 9
ce = rp(v5[a:b].replace("module ot_hgi_coll_capture_ctl_e(", "module ot_q2nf_capture_ctl_e("), "ot_hgi_coll_static_capture_ctl u(", "ot_q2nf_static_capture_ctl u(")
cc = (src / (P + "ot_hgi_coll_static_capture_ctl.sv")).read_text()
a = cc.index("module ot_hgi_coll_static_capture_ctl"); b = cc.index("endmodule", a) + 9
cc = cc[a:b].replace("module ot_hgi_coll_static_capture_ctl", "module ot_q2nf_static_capture_ctl")
cc = rp(cc, " reg [544:0] wr_flit_pin;\n", ""); cc = rp(cc, "  wr_flit_pin<=wr_flit;\n", ""); cc = rp(cc, ".wr_flit(wr_flit_pin),", ".wr_flit(wr_flit),")
L[-1] = L[-1].replace("@@PINASG@@", "\n".join(f" assign pin_d[{o}+:{cw}]=g_s[{k}].r[{d}*{cw}+:{cw}];" for k, d, o, cw in pm_l))
L += [lk, ce, cc, "`default_nettype wire", ""]
ot.write_text("\n".join(L))
# composition glue data
import json
pins = {n: [pm[n][j] for j in range(int(h) + 1)] for h, n in hdr}
(ot.parent / "q2n_pinmap.json").write_text(json.dumps(pins))
(ot.parent / "q2n_tilebus.json").write_text(json.dumps(pm_l))
print("master", om, "tile", ot, "dst pins", len(pins), sum(len(v) for v in pins.values()))
