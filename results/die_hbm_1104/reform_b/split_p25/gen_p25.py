#!/usr/bin/env python3
"""HBM-REFORM-B4 d44v part 25: ot_hbm_svc_wb_kport_q = 4 x ot_wbq_root + ot_wbq_sw, wires-only composition. One template in two forms.
  __p25fs.sv    bench form: tiles are <tile>__fs (kit face shell model), MUT seam mutants
  __p25comp.sv  plan form
  __p25glue.sv  __fcore + the plan module
    gen_p25.py OUT"""
import sys
from pathlib import Path
out = Path(sys.argv[1]); CORE = "ot_hbm_svc_wb_kport_q"
PORTS = """input wire stream_clk, input wire stream_rst_n, input wire hbm_clk, input wire hbm_rst_n, input wire [3:0] stream_fifo_clk,
    input wire [1:0] stk, input wire quad, input wire wb_reserve_v, input wire wb_reserve_bank, input wire wb_fill_bank,
    input wire [15:0] wb_reserve_epoch, input wire [15:0] wb_fill_epoch, input wire [11:0] wb_reserve_sectors, input wire [31:0] wb_reserve_base,
    input wire wb_fill_start, input wire [2311:0] wd, output wire wb_ready, output wire [11:0] wa,
    output wire wbw_v, output wire [29:0] wbw_base, output wire [11:0] wbw_total,
    output wire [15:0] w_k_v, input wire [15:0] w_k_rdy, output wire [479:0] w_k_addr, output wire [4095:0] w_k_wdata, input wire [15:0] w_k_wr_done,
    output wire fault"""
NAMES = "stream_clk stream_rst_n hbm_clk hbm_rst_n stream_fifo_clk stk quad wb_reserve_v wb_reserve_bank wb_fill_bank wb_reserve_epoch wb_fill_epoch wb_reserve_sectors wb_reserve_base wb_fill_start wd wb_ready wa wbw_v wbw_base wbw_total w_k_v w_k_rdy w_k_addr w_k_wdata w_k_wr_done fault".split()
def comp(name, fs):
    sfx = "__fs" if fs else ""
    hdr = "#(parameter integer MUT = 0, parameter integer RMUT = 0) " if fs else ""
    t = [f"// HBM-REFORM-B4 d44v part 25: GENERATED by gen_p25.py. {'Bench' if fs else 'Plan'} form of the composition.", "`default_nettype none",
         f"module {name} {hdr}(\n    {PORTS});",
         "    wire [3:0] root_ready; wire [7:0] g_v, g_credit, root_id; wire [2287:0] g_d; wire copy_on, copy_sel, s_stop, h_stop;",
         "    wire [263:0] wd_c;"]
    for s in range(8):
        t.append(f"    assign wd_c[{33*s}+:33] = {{wd[{289*s+288}], wd[{289*s+256}+:32]}};")
    if fs:
        t += ["    // bench seam mutants: each must FAIL the bench",
              "    wire [7:0] id_m = (MUT == 1) ? {root_id[7:4], root_id[1:0], root_id[1:0]} : root_id;",
              "    wire [2287:0] gd_m = (MUT == 2) ? (g_d ^ (2288'd1 << 1000)) : g_d;",
              "    wire cb_m = (MUT == 3) ? ~copy_sel : copy_sel;",
              "    wire [255:0] wd3_m = (MUT == 4) ? {wd[" + str(289*3+255) + ":" + str(289*3+1) + "], wd[" + str(289*3) + "] ^ 1'b1} : wd[" + str(289*3) + "+:256];"]
    w = (lambda k, d: {"id": "id_m", "gd": "gd_m", "cb": "cb_m", "wd3": "wd3_m"}.get(k, d)) if fs else (lambda k, d: d)
    par = "#(.MUT(RMUT)) " if fs else ""
    for r in range(4):
        wds = ", ".join(f".wd{s}({w('wd3', f'wd[{289*3}+:256]') if s == 3 else f'wd[{289*s}+:256]'})" for s in range(8))
        wv = "{" + ", ".join(f"wd[{289*s+288}]" for s in reversed(range(8))) + "}"
        t += [f"    ot_wbq_root{sfx} {par}u_r{r} (.hbm_clk(hbm_clk), .fifo_clk(stream_fifo_clk[{r}]), .stream_rst_n(stream_rst_n), .hbm_rst_n(hbm_rst_n),",
              f"        .root_id({w('id', 'root_id')}[{2*r}+:2]), .reserve_v(wb_reserve_v), .reserve_bank(wb_reserve_bank), .reserve_total(wb_reserve_sectors), .reserve_base(wb_reserve_base[29:0]),",
              f"        .fill_start(wb_fill_start), .fill_start_bank(wb_fill_bank), {wds}, .wd_v({wv}),",
              f"        .copy_on(copy_on), .copy_bank({w('cb', 'copy_sel')}), .s_stop(s_stop), .h_stop(h_stop), .g_credit(g_credit[{2*r}+:2]),",
              f"        .root_ready(root_ready[{r}]), .g_v(g_v[{2*r}+:2]), .g_d(g_d[{572*r}+:572]));"]
    t += [f"    ot_wbq_sw{sfx} u_sw (.stream_clk(stream_clk), .stream_rst_n(stream_rst_n), .hbm_clk(hbm_clk), .hbm_rst_n(hbm_rst_n), .stk(stk), .quad(quad),",
          "        .wb_reserve_v(wb_reserve_v), .wb_reserve_bank(wb_reserve_bank), .wb_fill_bank(wb_fill_bank), .wb_reserve_epoch(wb_reserve_epoch), .wb_fill_epoch(wb_fill_epoch),",
          "        .wb_reserve_sectors(wb_reserve_sectors), .wb_reserve_base(wb_reserve_base), .wb_fill_start(wb_fill_start), .wd_c(wd_c), .wb_ready(wb_ready), .wa(wa),",
          "        .wbw_v(wbw_v), .wbw_base(wbw_base), .wbw_total(wbw_total), .w_k_v(w_k_v), .w_k_rdy(w_k_rdy), .w_k_addr(w_k_addr), .w_k_wdata(w_k_wdata), .w_k_wr_done(w_k_wr_done), .fault(fault),",
          f"        .root_ready(root_ready), .g_v(g_v), .g_d({w('gd', 'g_d')}), .g_credit(g_credit), .root_id(root_id), .copy_on(copy_on), .copy_sel(copy_sel), .s_stop(s_stop), .h_stop(h_stop));",
          "endmodule", "`default_nettype wire", ""]
    return "\n".join(t)
(out / f"{CORE}__p25fs.sv").write_text(comp(f"{CORE}__p25fs", True))
(out / f"{CORE}__p25comp.sv").write_text(comp(f"{CORE}__p25comp", False))
pm = ", ".join(f".{n}({n})" for n in NAMES)
(out / f"{CORE}__p25glue.sv").write_text(
    f"// HBM-REFORM-B4 d44v part 25: plan module {CORE} = thin parent glue of the split hard core (wires only).\n`default_nettype none\n"
    f"module {CORE}__fcore (\n    {PORTS});\n    {CORE}__p25comp u_core ({pm});\nendmodule\n"
    f"module {CORE} (\n    {PORTS});\n    {CORE}__fcore u_fcore ({pm});\nendmodule\n`default_nettype wire\n")
