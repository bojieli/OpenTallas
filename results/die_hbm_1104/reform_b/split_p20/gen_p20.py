#!/usr/bin/env python3
"""HBM-REFORM-B d44v part 20: ot_pdie_serdes composition from ONE template in two forms, so the wiring is the same by construction.
  ot_pdie_serdes__p20fs.sv    bench form: tx / rx are <sub>__fs (kit face shell model), dchn plain, SMUT seam mutants
  ot_pdie_serdes__p20comp.sv  plan form
  ot_pdie_serdes__p20glue.sv  ot_pdie_serdes__fcore + wires-only plan module ot_pdie_serdes
    gen_p20.py OUT"""
import sys
from pathlib import Path
out = Path(sys.argv[1]); CORE = "ot_pdie_serdes"
PORTS = """input wire clk, input wire rst, input wire [511:0] tx, output wire [511:0] rx, output wire [1:0] st,
    output wire [543:0] pma_tx, output wire pma_tck, input wire [543:0] pma_rx, input wire pma_rck"""
NAMES = "clk rst tx rx st pma_tx pma_tck pma_rx pma_rck".split()
# seam net -> (width, bench mutant expression over the net, SMUT)
def comp(name, fs):
    sfx = "__fs" if fs else ""
    t = [f"// HBM-REFORM-B d44v part 20: GENERATED by gen_p20.py. {'Bench' if fs else 'Plan'} form of the composition.",
         "`default_nettype none",
         f"module {name} {'#(parameter integer SMUT = 0) ' if fs else ''}(\n    {PORTS});",
         "    wire ef; wire [3:0] k_v; wire [309:0] k_lo; wire [4:0] k_L; wire k_any;",
         "    wire [543:0] cw_q; wire [7:0] apply; wire o_unc; wire [4:0] o_ne; wire fs;"]
    if fs:
        t += ["    // bench seam mutants: each must FAIL the lockstep",
              "    reg k_any_d, fs_d; always @(posedge pma_rck) begin k_any_d <= k_any; fs_d <= fs; end",
              "    wire ef_m = (SMUT == 2) ? 1'b0 : ef;",
              "    wire [3:0] k_v_m = (SMUT == 3) ? (k_v & 4'b1110) : k_v;",
              "    wire k_any_m = (SMUT == 4) ? k_any_d : k_any;",
              "    wire [543:0] cw_m = (SMUT == 5) ? {cw_q[543:102], cw_q[100], cw_q[101], cw_q[99:0]} : cw_q;",
              "    wire [7:0] apply_m = (SMUT == 6) ? (apply & 8'hF7) : apply;",
              "    wire fs_m = (SMUT == 7) ? fs_d : fs;",
              "    wire o_unc_m = (SMUT == 8) ? 1'b0 : o_unc;",
              "    wire [309:0] k_lo_m = (SMUT == 9) ? {k_lo[309:1], ~k_lo[0]} : k_lo;"]
        rp = "#(.SEAM((SMUT == 1) ? 0 : 2)) "
        w = dict(ef="ef_m", k_v="k_v_m", k_any="k_any_m", k_lo="k_lo_m", cw_q="cw_m", apply="apply_m", fs="fs_m", o_unc="o_unc_m")
    else:
        rp = ""; w = {}
    g = lambda n: w.get(n, n)
    t += [f"    ot_pdie_serdes_tx{sfx} u_tx (.clk(clk), .rst(rst), .tx(tx), .pma_tx(pma_tx), .e_flt_o(ef));",
          "    assign pma_tck = clk;",
          f"    ot_pdie_serdes_rx{sfx} {rp}u_rx (.clk(clk), .rck_clk(pma_rck), .rst(rst), .rx(rx), .st(st), .pma_rx(pma_rx), .e_flt_i({g('ef')}),",
          "        .k_v(k_v), .k_lo(k_lo), .k_L(k_L), .k_any(k_any),",
          f"        .cw_q({g('cw_q')}), .apply({g('apply')}), .o_unc({g('o_unc')}), .o_ne(o_ne), .fs({g('fs')}));",
          f"    ot_s81_kp4_dchn u_chn (.clk(pma_rck), .rst_n(rst), .k_v({g('k_v')}), .k_lo({g('k_lo')}), .k_L(k_L), .k_any({g('k_any')}),",
          "        .cw_q(cw_q), .apply(apply), .o_unc(o_unc), .o_ne(o_ne), .fs(fs), .n_corr(), .n_unc());",
          "endmodule", "`default_nettype wire", ""]
    return "\n".join(t)
(out / f"{CORE}__p20fs.sv").write_text(comp(f"{CORE}__p20fs", True))
(out / f"{CORE}__p20comp.sv").write_text(comp(f"{CORE}__p20comp", False))
pm = ", ".join(f".{n}({n})" for n in NAMES)
(out / f"{CORE}__p20glue.sv").write_text(
    f"// HBM-REFORM-B d44v part 20: plan module {CORE} = thin parent glue of the split hard core (wires only).\n`default_nettype none\n"
    f"module {CORE}__fcore (\n    {PORTS});\n    {CORE}__p20comp u_core ({pm});\nendmodule\n"
    f"module {CORE} (\n    {PORTS});\n    {CORE}__fcore u_fcore ({pm});\nendmodule\n`default_nettype wire\n")
