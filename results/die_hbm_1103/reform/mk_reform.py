#!/usr/bin/env python3
"""DIE-HBM-61/PLAN 11-03: HBM d44v RE-FORM slot re-shape class (OWNER 11-03 TWO-STRIKES -> RE-FORM shape rules).

    python3 mk_reform.py PLAN_DIR OUT_DIR TOOLS_DIE_PLAN_DIR REFORM_CENSUS.json

REFORM_CENSUS.json = reform.py output (per RE-FORM core: cell area from the d44o AUTO-GEOM fill_of_free, pins per face,
macros, parent room).  A core is re-shaped here only when ALL hold (else it is left unchanged and listed with the reason):
  - cells <= 150k (OWNER block cap; larger cores are SPLIT source events, a slot change now would be redone);
  - target outline = old - k x 8.64 per axis (centre kept on the 4.32 lattice -> die clock taps unchanged), the smallest
    with est fill <= 0.45 (OWNER band 0.35-0.45, target 0.40), aspect <= 2.0 (AUTO-GEOM), every face >= pins/5 per um
    (remap_pins 0.192 spacing, one pin layer: cores pin on M4/M5 under the M5 ceiling) and clock reach (W+H)/2 <= 220;
  - macros (if any) shifted by the centre offset keep the kit_contract 10.8-um channels (core_macros_fix.channel_errors)
    AND every macro side keeps its PIN-COUNT channel (pins on that side x 0.048 / 2 vertical layers) to the core edge or the
    neighbour macro (OWNER: channels from pin count x track pitch);
  - the parent stations regenerated by hub_repack keep their register count (no latency change).
The resize itself is the shared MASTER-PLAN-R6 hub_repack.run (as d44w mk_shrink.py); core_macros / clock_entries follow.
"""
import json, math, sys
from pathlib import Path

plan, out, tools, census = map(Path, sys.argv[1:5])
# part 2: lane-supplied outlines (MEM channel_fit, pin-spread growth) applied as given, no search: [{module, outline_um,
# reason, macros_unknown}] (macros_unknown: the macro set changes in the RE-FORM kit -> core_macros status UNKNOWN)
OV = {o['module']: o for o in json.loads(Path(sys.argv[5]).read_text())} if len(sys.argv) > 5 else {}
sys.path.insert(0, str(tools))
sys.path.insert(0, str(tools.parent.parent / 'physical' / 'die_plan' / 'hbm'))
import hub_repack as HR  # noqa: E402
import core_macros_fix as CMF  # noqa: E402

STEP, PPL, FILL_HI, FILL_T, ASP, REACH, CELLS_MAX = 8.64, 5.0, 0.45, 0.40, 2.0, 220.0, 150000
TP = 0.048 / 2
MPINS = {'ot_sram_1r1w_64x512_m1_r2c2': (793, 792), 'ot_sram_1r1w_128x256_m1_r2c2': (410, 409),
         'ot_sram_1r1w_1024x256_m2_r2c2': (415, 414), 'ot_sram_1r1w_256x256_m2_r2c2': (411, 410)}   # LEF W/E M4 signal pins
P = json.loads((plan / 'die_plan.json').read_text())
CM = json.loads((plan / 'core_macros.json').read_text())
C = json.loads(census.read_text())
# re-shapes refused by the latency guard on a first pass (a parent station would gain a register): kept unchanged
EXCLUDE = {'ot_hfd_coll_q2_hard_v8g__reduce': 'UNCHANGED: the shrink adds 1 station register on 13 u_hcollgi_Q -> u_hb_coll_Q_reduce '
           'crossings (last hop 358.6 -> 384-393 um > 360 with the old sites); fill 0.29 kept, RE-FORM = 5 clock regions',
           'ot_hbm_hc_subtree32_core': 'UNCHANGED: the shrink adds 1 station register on bus L43_o (u_hc_Q.u_cen.subtree32_3 glue, hop '
           '371.5 -> 397.4 with the old sites); fill 0.23 kept, RE-FORM = registered face (pin_unreg 63, DIE-HBM-61/RTL)',
           'ot_hbm_svc_pc_ctrl_leaf_cfg_h9b': 'UNCHANGED: the 160.7 shrink adds 1 station register on q_hub_ne u_ctl_Q_p01.kr_data -> '
           'u_vmks_Q0 (hop 402.2 -> 406.0) and the odd-k 152.1 form put 32 origins off the 8.64 lattice + 8 core_faces; fill 0.32 kept'}


def pin_channel_errors(rows, W, H):
    """every macro W/E side needs >= pins x TP of free width to the core edge (- inset) or the neighbour macro in its row band"""
    err = []
    for r in rows:
        x0, y0, x1, y1 = r['rect_um']
        pw, pe = MPINS.get(r.get('master'), (400, 400))
        if r.get('orient') in ('MY', 'R180'):
            pw, pe = pe, pw
        left = [o['rect_um'][2] for o in rows if o is not r and o['rect_um'][2] <= x0 + 1e-6 and o['rect_um'][3] > y0 and o['rect_um'][1] < y1]
        right = [o['rect_um'][0] for o in rows if o is not r and o['rect_um'][0] >= x1 - 1e-6 and o['rect_um'][3] > y0 and o['rect_um'][1] < y1]
        gl = x0 - (max(left) if left else CMF.INSET)
        gr = (min(right) if right else W - CMF.INSET) - x1
        need_l, need_r = max(CMF.CH, pw * TP), max(CMF.CH, pe * TP)
        if left: need_l = max(CMF.CH, (pw + 400) * TP)
        if right: need_r = max(CMF.CH, (pe + 400) * TP)
        if gl < need_l - 1e-6: err.append((r['name'], 'W', round(gl, 2), round(need_l, 2)))
        if gr < need_r - 1e-6: err.append((r['name'], 'E', round(gr, 2), round(need_r, 2)))
    return err


def shifted(rows, dx, dy):
    o = []
    for r in rows:
        q = dict(r); x0, y0, x1, y1 = r['rect_um']
        q['rect_um'] = [round(x0 - dx, 4), round(y0 - dy, 4), round(x1 - dx, 4), round(y1 - dy, 4)]
        o.append(q)
    return o


decisions, spec, plan_rows = [], [], {}
for c in C:
    m = c['module']; d = dict(module=m, old=c.get('old'), old_fill=c.get('old_fill'), old_aspect=c.get('old_aspect'))
    if m in OV:
        continue
    decisions.append(d)
    if m in EXCLUDE:
        d['decision'] = EXCLUDE[m]; continue
    if not c.get('cell_area'):
        d['decision'] = 'UNCHANGED: no AUTO-GEOM cell-area data'; continue
    if (c.get('cells') or 0) > CELLS_MAX:
        d['decision'] = 'UNCHANGED: SPLIT source event (%d cells > 150k)' % c['cells']; continue
    W, H = c['old']; A = c['cell_area']; MA = c['macro_area']
    rows = (CM['cores'].get(m) or {}).get('macros') or []
    old_pin_err = pin_channel_errors(rows, W, H) if rows else []
    nw = max(c['pin_need_wh'][0], 1); nh = max(c['pin_need_wh'][1], 1)
    best = None
    for kx in range(0, int(W / STEP), 2):          # even k: origin shift k x 4.32 stays on the 8.64 lattice (check.py hard_cores)
        for ky in range(0, int(H / STEP), 2):
            W2, H2 = round(W - kx * STEP, 3), round(H - ky * STEP, 3)
            if W2 < nw or H2 < nh or max(W2, H2) / min(W2, H2) > ASP + 1e-6 or (W2 + H2) / 2 > REACH:
                continue
            free = W2 * H2 - MA
            if free <= 0 or A / free > FILL_HI:
                continue
            dx, dy = (W - W2) / 2, (H - H2) / 2
            if rows:
                R2 = shifted(rows, dx, dy)
                e1, _ = CMF.channel_errors(R2, [W2, H2])
                if e1 or len(pin_channel_errors(R2, W2, H2)) > len(old_pin_err):
                    continue
                cx, cy = HR.sn(W2 / 2), HR.sn(H2 / 2)          # centre clock entry island (8.64) must not sit on a macro (12.8a)
                if any(r['rect_um'][0] < cx + 4.32 and r['rect_um'][2] > cx - 4.32 and r['rect_um'][1] < cy + 4.32 and r['rect_um'][3] > cy - 4.32 for r in R2):
                    continue
            sc = abs(A / free - FILL_T)
            if best is None or sc < best[0] - 1e-9:
                best = (sc, W2, H2, A / free)
    if best is None or (best[1], best[2]) == (W, H):
        d['decision'] = 'UNCHANGED: no lattice outline meets fill<=0.45 + aspect<=2 + pins/face + reach + macro channels'
        if rows: d['macro_pin_channel_errors_old'] = len(old_pin_err)
        continue
    _, W2, H2, f2 = best
    d.update(decision='RESHAPE', new=[W2, H2], new_fill=round(f2, 3), new_aspect=round(max(W2, H2) / min(W2, H2), 2),
             clock_regions=c.get('clock_regions'))
    if rows: d['macro_pin_channel_errors'] = [len(old_pin_err), len(pin_channel_errors(shifted(rows, (W - W2) / 2, (H - H2) / 2), W2, H2))]
    plan_rows[m] = dict(old=[W, H], new=[W2, H2])
    spec.append(dict(module=m, outline_um=[W2, H2], est_fill=round(f2, 4), macro_fit=True,
                     source='DIE-HBM-61/PLAN d44v RE-FORM slot class'))


for m, o in OV.items():
    W, H = next(h['outline_um'] for t in P['partition_types'].values() for h in t.get('hard_cores') or [] if h['module'] == m)
    W2, H2 = o['outline_um']
    assert round((W - W2) / 8.64) % 2 == 0 and round((H - H2) / 8.64) % 2 == 0, (m, W, H, W2, H2)
    decisions.append(dict(module=m, old=[W, H], decision='RESHAPE (part 2: %s)' % o['reason'], new=[W2, H2],
                          new_aspect=round(max(W2, H2) / min(W2, H2), 2)))
    plan_rows[m] = dict(old=[W, H], new=[W2, H2], macros_unknown=bool(o.get('macros_unknown')))
    cc = next((c for c in C if c['module'] == m), {})
    A = o.get('cell_area', cc.get('cell_area')); MA = o.get('macro_area', cc.get('macro_area') or 0)
    ef = round(A / (W2 * H2 - MA), 4)
    decisions[-1]['new_fill'] = ef
    if [W2, H2] != [W, H]:
        spec.append(dict(module=m, outline_um=[W2, H2], est_fill=ef, macro_fit=True, source='DIE-HBM-61/PLAN d44v p2: ' + o['reason']))


def taps_of(PP):
    return {tn: sorted((tp['name'], round(tp['xy'][0], 3), round(tp['xy'][1], 3)) for tp in (t.get('clock') or {}).get('taps', []))
            for tn, t in PP['partition_types'].items()}


old_taps = taps_of(P)
for o_ in OV.values():
    if o_.get("pin_pitch"): HR.PIN_PITCH = o_["pin_pitch"]      # part 24: the pin count sets the face, tighter pitch on request
rep = HR.run(plan, out, [], spec, log=print)
P2 = json.loads((out / 'die_plan.json').read_text())
for tn, t in P2['partition_types'].items():
    if (t.get('clock') or {}).get('taps'):
        t['clock']['taps'] = P['partition_types'][tn]['clock']['taps']
assert taps_of(P2) == old_taps
if (plan / 'entries.json').exists():
    (out / 'entries.json').unlink()
    (out / 'entries.json').write_bytes((plan / 'entries.json').read_bytes())
# latency guard: a regenerated station that gained a register keeps its OLD register sites with the moved endpoints when
# every hop stays <= reach (all re-shapes here are shrinks, so old sites stay outside every core + halo) -> count unchanged
kept_old, lat_left = [], []
for tn, s in rep['stations'].items():
    for u in s['latency_up']:
        k = u['station']; st_new = P2['partition_types'][tn]['internal_stations'][k]
        st_old = P['partition_types'][tn]['internal_stations'][k]
        pts = [st_new['from_um']] + [r[:2] for r in st_old.get('regs_um', [])] + [st_new['to_um']]
        hop = max(abs(a[0] - b[0]) + abs(a[1] - b[1]) for a, b in zip(pts, pts[1:]))
        po = [st_old['from_um']] + [r[:2] for r in st_old.get('regs_um', [])] + [st_old['to_um']]
        hop0 = max(abs(a[0] - b[0]) + abs(a[1] - b[1]) for a, b in zip(po, po[1:]))
        u['max_hop_before'] = round(hop0, 1)
        if hop <= max(360.0, hop0) + 1e-6:      # no hop longer than the 360 rule or than the station already had
            st_new['regs_um'] = [list(r) for r in st_old['regs_um']]
            st_new['note'] = 'DIE-HBM-61 RE-FORM: endpoints follow the re-shaped core, old register sites kept (max hop %.1f um, count unchanged)' % hop
            kept_old.append(dict(type=tn, station=k, conn=u['conn'], max_hop=round(hop, 1)))
        else:
            lat_left.append(dict(u, type=tn, max_hop_old_sites=round(hop, 1)))
dropped = []
for tn, t in P2['partition_types'].items():
    for h in t.get('hard_cores') or []:
        if h['module'] in plan_rows and (h.get('lef') or h.get('lib')):
            dropped.append(dict(type=tn, inst=h['inst'], lef=h.pop('lef', None), lib=h.pop('lib', None)))
            h['note'] += ' | DIE-HBM-61: fixed abstract lef/lib at the old outline dropped (kit re-cut gives the new one)'
(out / 'die_plan.json').unlink()
(out / 'die_plan.json').write_text(json.dumps(P2, indent=1) + '\n')
for m, r in plan_rows.items():
    e = CM['cores'].get(m)
    if not e:
        continue
    dx, dy = (r['old'][0] - r['new'][0]) / 2, (r['old'][1] - r['new'][1]) / 2
    e['outline_um'] = r['new']
    if r.get('macros_unknown'):
        e['status'] = 'UNKNOWN'
        e['note'] = (e.get('note') or '') + ' | DIE-HBM-61 d44v p2: right-width macro set (DIE-HBM-61/MEM recipe_delta) -> positions from the RE-FORM kit'
        e['macros_r2c2_old'] = e.pop('macros', [])
        continue
    if e.get('macros'):
        e['macros'] = shifted(e['macros'], dx, dy)
        err, _ = CMF.channel_errors(e['macros'], r['new'])
        assert not err, (m, err[:3])
    e['note'] = (e.get('note') or '') + ' | DIE-HBM-61 d44v RE-FORM %gx%g -> %gx%g (centre kept, rects shifted)' % (*r['old'], *r['new'])
for name in ('core_macros.json', 'clock_entries.json'):
    if (out / name).exists() or (out / name).is_symlink():
        (out / name).unlink()
(out / 'core_macros.json').write_text(json.dumps(CM, indent=1))
CE = json.loads((plan / 'clock_entries.json').read_text())
moved = 0
for tn, dd in CE.items():
    for inst, e in dd.items():
        m = e.get('module')
        if m in plan_rows:
            W2, H2 = plan_rows[m]['new']
            cx, cy = HR.sn(W2 / 2), HR.sn(H2 / 2)
            e['xy_um'] = [cx, cy]
            e['island_um'] = [round(cx - 4.32, 3), round(cy - 4.32, 3), round(cx + 4.32, 3), round(cy + 4.32, 3)]
            e['source'] = e.get('source', '') + ' | DIE-HBM-61 RE-FORM: new centre (same die position)'
            moved += 1
(out / 'clock_entries.json').write_text(json.dumps(CE, indent=1))
lat_up = lat_left
failed = {tn: s['failed'] for tn, s in rep['stations'].items() if s['failed']}
summary = dict(schema='opentallas.hbm_plan_event.v1', event='d44v-reform', decisions=decisions, stations_old_sites_kept=kept_old, clock_entries_moved=moved,
               lef_dropped=dropped, stations_latency_up=lat_up, stations_failed=failed,
               hub_repack=dict(shrinks=rep['shrinks'], new_pin_files=rep['new_pin_files'], plan_sha256=rep['plan_sha256']))
(out / 'reform_event.json').write_text(json.dumps(summary, indent=1))
for d in decisions:
    print(d['module'][:46], d['decision'][:60], d.get('old'), '->', d.get('new'), d.get('new_fill'), d.get('new_aspect'), d.get('macro_pin_channel_errors', ''))
print('moved', moved, 'dropped', len(dropped), 'latency_up_left', len(lat_up), 'old_sites_kept', len(kept_old), 'failed', sum(map(len, failed.values())))
