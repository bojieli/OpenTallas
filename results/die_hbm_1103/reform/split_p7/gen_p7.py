def unroll(txt, var, n, rename):
    """write out the one generate loop: wire names and generate-scope instance names get the loop index."""
    m = re.search(r"\n\s*genvar %s;\s*\n\s*generate for \(%s = 0; %s < %d; %s = %s \+ 1\) begin : \w+\n(.*?)\n\s*end endgenerate" %
                  (var, var, var, n, var, var), txt, re.S)
    assert m, var
    body = m.group(1); res = []
    for i in range(n):
        b = body
        b = re.sub(r"\[([^\[\]]*\b%s\b[^\[\]]*)\]" % var, lambda k: "[" + re.sub(r"\b%s\b" % var, str(i), k.group(1)) + "]", b)
        for a, c in rename.items():
            b = re.sub(r"\b%s\b" % a, c.format(i=i), b)
        res.append(b)
    return txt[:m.start()] + "\n" + "\n".join(res) + txt[m.end():]


def comp(core, src, var, n, rename):
    t = (src).read_text()
    assert f"module {core}__split" in t
    t = unroll(t, var, n, rename)
    t = t.replace(f"module {core}__split", f"module {core}__p7comp")
    t = re.sub(r"\b(\w+)__fs\b", r"\1", t)
    t = t.replace("#(.MUT(MUT)) ", "").replace("#(.SMUT(SMUT)) ", "")
    t = re.sub(r"#\s*\(parameter integer S?MUT = 0\)\s*", "", t)
    (out / f"{core}__p7comp.sv").write_text(f"// DIE-HBM-62/BIG d44v part 7: generated by gen_p7.py from {src.name}; loops written out, no bench mutants.\n" + t)
    return t


def ports(t, mod):
    m = re.search(r"module\s+%s\s*\((.*?)\);" % mod, t, re.S)
    decl = m.group(1)
    return decl, re.findall(r"(?:input|output)\s+wire\s*(?:\[[^\]]*\]\s*)?(\w+)", decl)


