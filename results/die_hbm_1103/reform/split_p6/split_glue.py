#!/usr/bin/env python3
"""DIE-HBM-61/SPLIT d44v part 6: thin parent glue of a split hard core.
The kit's pass-through wrapper (<core>__fcore, plan pins -> canonical RTL top, wires only) with its u_core swapped to
the SPLIT composition (same ports as the canonical top; ports the composition does not have -- tied by the uncut
shell -- are left open), plus the plan module <core> itself as a wires-only shell around u_fcore (no face registers:
every sub-core carries its own kit face shell).  Physical sub-core paths: <inst>.u_fcore.u_core.<u_sub>.
    split_glue.py KIT_WRAP.sv CANON_INST_RE COMPOSITION_MODULE COMPOSITION.sv OUT.sv"""
import re, sys
wrap, canon_re, comp, comp_sv, out = sys.argv[1:6]
W = open(wrap).read(); C = open(comp_sv).read()
hdr = re.search(r"module\s+" + re.escape(comp) + r"\s*(#\s*\((?:[^()]|\([^()]*\))*\))?\s*\((.*?)\);", C, re.S)
cports = set(re.findall(r"(?:input|output|inout)\s+(?:wire|reg|logic)?\s*(?:\[[^\]]*\]\s*)?(\w+)", hdr.group(2)))
m = re.search(r"(\n\s*)(" + canon_re + r")(\s+u_core\s*\()(.*?)(\);)", W, re.S)
assert m, "canonical u_core instance not found"
conns = [c for c in re.findall(r"\.\s*(\w+)\s*\(([^()]*)\)", m.group(4))]
keep = [f".{p}({e})" for p, e in conns if p in cports]
drop = [p for p, e in conns if p not in cports]
missing = sorted(cports - {p for p, _ in conns})
assert not missing, f"composition ports not driven by the kit wrapper: {missing}"
params = re.findall(r"#\s*\((.*?)\)\s*$", m.group(2), re.S)
cp = re.findall(r"parameter\s+(?:integer\s+)?(\w+)", hdr.group(1) or "")
pv = dict(re.findall(r"\.(\w+)\s*\(([^()]*)\)", params[0])) if params else {}
pv = {k: v for k, v in pv.items() if k in cp}
pstr = (" #(" + ", ".join(f".{k}({v})" for k, v in pv.items()) + ")") if pv else ""
inst = f"{m.group(1)}{comp}{pstr} u_core (\n        " + ",\n        ".join(keep) + ");"
body = W[:m.start()] + inst + W[m.end():]
fm = re.search(r"module\s+(\w+)__fcore\s*\((.*?)\);", body, re.S)
core = fm.group(1)
decl = fm.group(2)
names = re.findall(r"(?:input|output|inout)\s+(?:wire\s+)?(?:\[[^\]]*\]\s*)?(\w+)", decl)
top = (f"// DIE-HBM-61/SPLIT d44v part 6: plan module {core} = thin parent glue of the split hard core (wires only; the\n"
       f"// sub-cores of {comp} are the hard cores, each with its own kit face shell).  Ports open in the composition: "
       f"{', '.join(drop) or 'none'}.\n`default_nettype none\nmodule {core} (" + decl + ");\n"
       f"    {core}__fcore u_fcore (" + ", ".join(f".{n}({n})" for n in names) + ");\nendmodule\n`default_nettype wire\n")
open(out, "w").write(body.replace("// GENERATED by gen_core_kit_hbm.py", "// DIE-HBM-61/SPLIT d44v part 6 (u_core -> " + comp + "); from gen_core_kit_hbm.py", 1) + "\n" + top)
print(core, comp, "conns kept", len(keep), "open", drop)
