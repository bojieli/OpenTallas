#!/usr/bin/env python3
"""DIE-HBM-62/CUTS d44v part 8: pslice_c5 composition, from ONE template in two forms, so the wiring is the same by construction.
  ot_hbm_su_programme_pslice_c5__p8fs.sv    bench form: subs are <sub>__fs (kit face shell model), SMUT bench mutants
  ot_hbm_su_programme_pslice_c5__p8comp.sv  plan form: plain subs, each hardened with its kit face shell
  ot_hbm_su_programme_pslice_c5__p8glue.sv  <core>__fcore + wires-only plan module <core>
  split_p8.json                              mk_split spec: explicit tiles + macro sites
    gen_p8.py OUT"""
import json, sys
from pathlib import Path
out = Path(sys.argv[1]); L = {1, 2, 3}; CORE = "ot_hbm_su_programme_pslice_c5"
PORTS = """input wire clk, input wire rst_n, input wire cfg_we, input wire [15:0] cfg_bank, input wire [6:0] cfg_row,
    input wire [255:0] cfg_data, input wire start, input wire [15:0] length, output wire busy, output wire valid,
    output wire done, output wire fault, output wire [15:0] edge_index, output wire [2469:0] command"""
NAMES = "clk rst_n cfg_we cfg_bank cfg_row cfg_data start length busy valid done fault edge_index command".split()

def comp(name, fs):
    sfx = "__fs" if fs else ""
    t = [f"// DIE-HBM-62/CUTS d44v part 8: GENERATED by gen_p8.py. {'Bench' if fs else 'Plan'} form of the per-column composition.",
         "`default_nettype none",
         f"module {name} {'#(parameter integer SMUT = 0) ' if fs else ''}(\n    {PORTS});",
         "    wire [9:0] we, st, l_valid, l_fault; wire [159:0] len; wire any; wire [4:0] bank; wire [6:0] row; wire [255:0] data;",
         "    wire [89:0] nc9;"]
    hp = "#(.HMUT((SMUT==4)?1:(SMUT==5)?2:(SMUT==6)?3:(SMUT==7)?4:0)) " if fs else ""
    t.append(f"    ot_hbm_su_pcol_h{sfx} {hp}u_h (.clk(clk), .rst_n(rst_n), .cfg_we(cfg_we), .cfg_bank(cfg_bank), .cfg_row(cfg_row), .cfg_data(cfg_data),\n"
             "        .start(start), .length(length), .l_fault(l_fault), .l_valid(l_valid), .o_we(we), .o_any(any), .o_bank(bank), .o_row(row),\n"
             "        .o_data(data), .o_start(st), .o_length(len), .fault(fault));")
    for c in range(10):
        m = "l" if c in L else "s"
        cmd = f"command[{256*c+255}:{256*c}]" if c < 9 else "{nc9, command[2469:2304]}"
        pp = ""
        if fs:
            p = {5: "(SMUT==1)", 3: "(SMUT==8)"}.get(c, "0")
            mu = {2: "(SMUT==2)", 6: "(SMUT==3)"}.get(c, "0")
            pp = f"#(.PMUT({p}), .MUT({mu})) "
        if c == 0:
            ctl = ".busy(busy), .valid(l_valid[0]), .done(done), .edge_index(edge_index)"
        else:
            ctl = f".busy(), .valid(l_valid[{c}]), .done(), .edge_index()"
        t.append(f"    ot_hbm_su_pcol_{m}{sfx} {pp}u_c{c} (.clk(clk), .rst_n(rst_n), .cfg_we(we[{c}]), .cfg_any(any), .cfg_bank(bank), .cfg_row(row), .cfg_data(data),\n"
                 f"        .start(st[{c}]), .length(len[{16*c+15}:{16*c}]), {ctl}, .fault(l_fault[{c}]), .command({cmd}));")
    t += ["    assign valid = l_valid[0];", "endmodule", "`default_nettype wire", ""]
    return "\n".join(t)

(out / f"{CORE}__p8fs.sv").write_text(comp(f"{CORE}__p8fs", True))
(out / f"{CORE}__p8comp.sv").write_text(comp(f"{CORE}__p8comp", False))
pm = ", ".join(f".{n}({n})" for n in NAMES)
(out / f"{CORE}__p8glue.sv").write_text(
    f"// DIE-HBM-62/CUTS d44v part 8: plan module {CORE} = thin parent glue of the split hard core (wires only).\n`default_nettype none\n"
    f"module {CORE}__fcore (\n    {PORTS});\n    {CORE}__p8comp u_core ({pm});\nendmodule\n"
    f"module {CORE} (\n    {PORTS});\n    {CORE}__fcore u_fcore ({pm});\nendmodule\n`default_nettype wire\n")

# ---- tiles (core frame). 939.6 = 108.75 x 8.64 and all four slots are MY, so x and the mirrored x stay on the lattice only
# when a tile width is k.75 x 8.64: S 118.8, L 257.04, H 136.08. Bands abut: L y 0..423.36, S y 423.36..760.32 (command pins
# are on the N face; L's command wires pass over the S band, keep_face). S c0 under its bits, c4..c9 right-aligned.
PRE = "u_fcore.u_core."
SW, SH, LW, LH, HW, HH = 118.8, 336.96, 257.04, 423.36, 136.08, 216.0
Y0 = 423.36
lay = {PRE + "u_h": dict(xy=[0.0, 207.36], wh=[HW, HH])}
for c, x in ((1, 146.88), (2, 414.72), (3, 682.56)):
    lay[PRE + f"u_c{c}"] = dict(xy=[x, 0.0], wh=[LW, LH])
for c, x in ((0, 0.0), (4, 172.8), (5, 302.4), (6, 432.0), (7, 561.6), (8, 691.2), (9, 820.8)):
    lay[PRE + f"u_c{c}"] = dict(xy=[x, Y0], wh=[SW, SH])
M = "ot_sram_1r1w_128x256_m1_r2c2"; MW, MH, PP, ST = 94.824, 41.064, 41.112, 93.024  # pair pitch, pair stride (as the d44v grid)
def rows(y0, n):
    return [round(y0 + (i // 2) * ST + (i % 2) * PP, 3) for i in range(n)]
def rect(n, x, y):
    return dict(name=f"u_fcore.u_c.g_p.u_p.g_m4.{n}.mem", master=M, orient="R0", rect_um=[x, y, round(x + MW, 3), round(y + MH, 3)])
ix = [f"ix[0].mem.g[{i}]" for i in range(4)]
s_names = ix + [f"dt[0].mem.g[{i}]" for i in range(3)]
l_names = ix + [f"dt[0].mem.g[{i}]" for i in range(13)]
s_m = [rect(n, 12.0, y) for n, y in zip(s_names, rows(8.4, 7))]
lx0, lx1 = 10.8, round(LW - 10.8 - MW, 3)
ly = rows(5.04, 9)
l_sites = [(lx0, y) for y in ly] + [(lx1, y) for y in ly[:8]]
l_m = [rect(n, *q) for n, q in zip(l_names, l_sites)]
spec = [dict(core=CORE, sha="pcol", part="p8", glue=f"{CORE}__p8glue.sv", conn=f"{CORE}.conn.json",
             subs=[dict(module="ot_hbm_su_pcol_s", cells=8000), dict(module="ot_hbm_su_pcol_l", cells=14000), dict(module="ot_hbm_su_pcol_h", cells=5000)],
             added_cycles="start/length/cfg inputs +2, command/busy/valid/done/edge_index +2, fault +4; reform_1103/cycles/pcol.tsv (TOK-VERIFY batch)",
             boundary_sub=PRE + "u_h", hub_sub=PRE + "u_h", keep_face=True, layout=lay,
             clock_entry={"ot_hbm_su_pcol_s": [60.48, 190.08]},
             macros=dict(ot_hbm_su_pcol_s=s_m, ot_hbm_su_pcol_l=l_m),
             macro_basis="DIE-HBM-62/CUTS d44v part 8: column stacks with the d44v pair pitch 41.112 / stride 93.024; W and E macro pin channels >= 10.8")]
(out / "split_p8.json").write_text(json.dumps(spec, indent=1) + "\n")
