#!/usr/bin/env python3
"""HBM-FORM-TIMING-11 d44v part 37: ot_hgi_sfu_core_split3__ctl = ot_hgi_sfu_split3_ctl_rest_1c + ot_hgi_sfu_split3_ctl_pipe_1c
(the I205 delay-line cut of HBM-FORM-TIMING-10, plan form).
  * rest_1c = the ctl oneclk wrapper (SAME 105 plan ports / 11,813 pins, every clock from clk) around
    ot_hgi_sfu_split3_ctl_rest_core, plus the seam ports seam_d[279:0] (out) / seam_q[279:0] (in); rest_core's rst_vm_n
    output stays open (the pipe makes its own copy, below).
  * pipe_1c = ot_hgi_sfu_split3_ctl_pipe_core with clk_lg from clk, plus a LOCAL copy of the ctl reset synchroniser
    (gold u_rst: sync_q <= {sync_q[0], 1'b1}; relay_q[0][0] <= sync_q[1]; async clear by rst_n, posedge clk), so no
    reset crosses the seam (one reset tree per core, OWNER safe form).  Seam = 280 FF->FF bits each way, zero logic.
  * ot_hgi_sfu_core_split3__ctl__split = composition with the ctl plan ports (u_rest + u_pipe).
Writes rtl/hbm_accel/cores_split/ot_hgi_sfu_core_split3/ot_hgi_sfu_split3_ctl_{rest_1c,pipe_1c,split}.sv (one module each),
OUT/<core>__p37comp.sv (composition only) and OUT/<core>__p37glue.sv (__fcore + plan module, wires only).
    gen_p37.py REPO OUTDIR"""
import re, sys
from pathlib import Path
R, out = Path(sys.argv[1]), Path(sys.argv[2]); CORE = "ot_hgi_sfu_core_split3__ctl"
RD = R / "rtl/hbm_accel/cores_split/ot_hgi_sfu_core_split3"
H = "// HBM-FORM-TIMING-11 2026-11-06 d44v part 37: GENERATED by results/die_hbm_1106/ctlsplit_p37/gen_p37.py. Do not edit.\n"
w = (R / f"physical/die_plan/hbm_arch_cores/wrappers/oneclk/{CORE}.sv").read_text()
w = w[w.index(f"module {CORE} ("):]
w = w[:w.index("endmodule")]
hd = w[:w.index(");")]
plist = hd.split("(", 1)[1].rstrip()
pn = re.findall(r"wire (?:\[\d+:\d+\] )?(\w+)", plist)
assert len(pn) == 105 and "clk" in pn, len(pn)
body = w[w.index(");") + 2:]
assert body.count("    ot_hgi_sfu_split3_ctl_core u_core (") == 1
body = body.replace("    ot_hgi_sfu_split3_ctl_core u_core (",
                    "    ot_hgi_sfu_split3_ctl_rest_core u_core (\n        .seam_d(seam_d),\n        .seam_q(seam_q),\n        .rst_vm_n(),")
seam_ports = ",\n    output wire [279:0] seam_d,\n    input wire [279:0] seam_q"
rest = ("// rest sub-core (hard core) = the ctl oneclk wrapper around the rest core: same plan ports as the uncut ctl + seam.\n"
        f"module ot_hgi_sfu_split3_ctl_rest_1c ({plist}{seam_ports}\n);{body}endmodule\n\n")
pipe = ("// pipe sub-core (hard core): the 21,816 delay-line flops + a local copy of the ctl reset synchroniser.\n"
        "module ot_hgi_sfu_split3_ctl_pipe_1c (\n    input wire clk,\n    input wire rst_n,\n    input wire [3:0] rst_lg_n,\n"
        "    input wire [279:0] seam_d,\n    output wire [279:0] seam_q\n);\n"
        "    reg [1:0] sync_q;\n    reg relay_q0;\n"
        "    always @(posedge clk, negedge rst_n)\n        if (!rst_n) sync_q <= 2'b00;\n        else sync_q <= {sync_q[0], 1'b1};\n"
        "    always @(posedge clk, negedge rst_n)\n        if (!rst_n) relay_q0 <= 1'b0;\n        else relay_q0 <= sync_q[1];\n"
        "    ot_hgi_sfu_split3_ctl_pipe_core u_pipe (.clk(clk), .clk_lg({4{clk}}), .rst_lg_n(rst_lg_n), .rst_vm_n(relay_q0), .seam_d(seam_d), .seam_q(seam_q));\n"
        "endmodule\n")
comp = ("// split composition (plan form) of the ctl hard core: ctl plan ports; u_rest + u_pipe, seam FF->FF.\n"
        f"module {CORE}__split ({plist}\n);\n    wire [279:0] seam_d, seam_q;\n"
        "    ot_hgi_sfu_split3_ctl_rest_1c u_rest (" + ", ".join(f".{n}({n})" for n in pn) + ", .seam_d(seam_d), .seam_q(seam_q));\n"
        "    ot_hgi_sfu_split3_ctl_pipe_1c u_pipe (.clk(clk), .rst_n(rst_n), .rst_lg_n(rst_lg_n), .seam_d(seam_d), .seam_q(seam_q));\n"
        "endmodule\n")
for nm, body_ in (("ot_hgi_sfu_split3_ctl_rest_1c", rest), ("ot_hgi_sfu_split3_ctl_pipe_1c", pipe), ("ot_hgi_sfu_split3_ctl_split", comp)):
    (RD / f"{nm}.sv").write_text(H + "`default_nettype none\n" + body_ + "`default_nettype wire\n")
(out / "subs_only.sv").write_text(H + "`default_nettype none\n" + rest + pipe + "`default_nettype wire\n")
(out / f"{CORE}__p37comp.sv").write_text(H + "`default_nettype none\n" + comp + "`default_nettype wire\n")
conn = ", ".join(f".{n}({n})" for n in pn)
glue = (H + "`default_nettype none\n"
        f"module {CORE}__fcore ({plist}\n);\n    {CORE}__split u_core ({conn});\nendmodule\n\n"
        "// plan module = thin parent glue of the split hard core (wires only; the sub-cores of __split are the hard cores,\n"
        "// each with its own kit face shell; seam_d/seam_q are native registered passthrough, 0 wrapper cycles).\n"
        f"module {CORE} ({plist}\n);\n    {CORE}__fcore u_fcore ({conn});\nendmodule\n`default_nettype wire\n")
(out / f"{CORE}__p37glue.sv").write_text(glue)
print("plan ports", len(pn))
