#!/usr/bin/env python3
"""HBM-FORM-TIMING-13 d44v part 50 (plan-owner approved DIE-HBM-82 11-06): rest_1c scalar-data pin cycle.

ot_hgi_sfu_split3_ctl_rest_1c output u_core_u_vm_scalar_data[127:0] gets ONE register stage between the rest core and
the port when OT_REST1C_SCALAR_PIPE1 is defined (recipe ot_hgi_sfu_split3_ctl_rest_1c__spipe1): PIN CYCLE +1 on that
bus, every other port exact.  Without the define the port is a plain wire from the rest core (same function as part 37).
Why: vA (-81.68 ps, 119 endpoints) and vB2 (-92.83 ps, 126 endpoints) both missed TT only on the path rest flops ->
32-fanout select + AO222 3:1 mux -> ~350 ps of wire -> the vm_scalar_data output face (792 ps of data at 833 ps).
The new register lets the placer put the mux and the long wire in different cycles.
Edits rtl/.../ot_hgi_sfu_split3_ctl_rest_1c.sv in place (run after gen_p37.py; idempotent).
    gen_p50.py REPO"""
import sys
from pathlib import Path
R = Path(sys.argv[1])
F = R / "rtl/hbm_accel/cores_split/ot_hgi_sfu_core_split3/ot_hgi_sfu_split3_ctl_rest_1c.sv"
s = F.read_text()
TAG = "// part 50: scalar-data pin cycle"
if TAG not in s:
    old = "        .u_core_u_engine_scalar_data(u_core_u_vm_scalar_data),\n"
    assert s.count(old) == 1
    s = s.replace(old, "        .u_core_u_engine_scalar_data(__p50_scalar_d),\n")
    hdr_end = "    input wire [279:0] seam_q\n);\n"
    assert s.count(hdr_end) == 1
    blk = (f"    {TAG} (HBM-FORM-TIMING-13 d44v part 50, gen_p50.py): OT_REST1C_SCALAR_PIPE1 = +1 cycle on\n"
           "    // u_core_u_vm_scalar_data (recipe ot_hgi_sfu_split3_ctl_rest_1c__spipe1); default = wire (part 37 function).\n"
           "    wire [127:0] __p50_scalar_d;\n"
           "`ifdef OT_REST1C_SCALAR_PIPE1\n"
           "    reg [127:0] __p50_scalar_q;\n"
           "    always @(posedge clk) __p50_scalar_q <= __p50_scalar_d;\n"
           "    assign u_core_u_vm_scalar_data = __p50_scalar_q;\n"
           "`else\n"
           "    assign u_core_u_vm_scalar_data = __p50_scalar_d;\n"
           "`endif\n")
    s = s.replace(hdr_end, hdr_end + blk)
    s = s.replace("GENERATED by results/die_hbm_1106/ctlsplit_p37/gen_p37.py. Do not edit.",
                  "GENERATED by results/die_hbm_1106/ctlsplit_p37/gen_p37.py + results/die_hbm_1106/rest1c_spipe_p50/gen_p50.py. Do not edit.", 1)
    F.write_text(s)
print("part 50 rest_1c", F)
