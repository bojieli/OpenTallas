// Native extraction: PTILE32, NT64, PIPE1, HOP2,FRT4,CB21 gives XL151.
// conv_q launched after E0 -> raw up captured at E154 -> up0_q consumed at E155.
// Sample actual commands at E0.5; 154 slots put the response at E153.5.
// Each DUT has its OWN queue and state. Payload is an arbitrary deterministic
// function of that DUT's actual entry/clear history and conversion-command ID.
module native_return_model(input clk,rst_n,entry_v,conv,clr,input[343:0]entry,output[343:0]up,output return_v);
  reg [343:0] data[0:153];reg[153:0] valid;
  reg[31:0] accumulator,ordinal,clear_id;
  reg[343:0] response;
  function automatic[31:0] digest(input[343:0]e,input[31:0]h0);
    reg[351:0] ext;reg[31:0]h;
    begin ext={8'd0,e};h=h0;for(integer i=0;i<11;i++)h={h[26:0],h[31:27]}^ext[32*i+:32];digest=h;end
  endfunction
  always @*begin
    response=0;
    for(integer i=0;i<4;i++)response[i*86+:86]={1'b0,1'b1,(32'hbf800000^(accumulator+ordinal+32'(i))),~(accumulator^(ordinal*4+32'(i))),8'd0,11'd0,1'b0};
  end
  always @(negedge clk)begin
    if(!rst_n)begin valid<=0;accumulator<=32'h12345678;ordinal<=0;clear_id<=0;end
    else begin
      valid<={valid[152:0],conv};data[0]<=response;
      for(integer i=1;i<154;i++)data[i]<=data[i-1];
      if(clr)begin accumulator<=32'h12345678;ordinal<=0;clear_id<=clear_id+1;end
      else begin
        if(entry_v)accumulator<=digest(entry,accumulator);
        if(conv)ordinal<=ordinal+1;
      end
    end
  end
  assign up=data[153];assign return_v=valid[153];
endmodule
