def read_pins(kit):
    by = {}
    for l in (RT / kit / 'assigned_pins.tcl').open():
        if not l.startswith('ot_assigned_pin_exact'):
            continue
        t = l.split()
        by.setdefault(t[3], []).append((float(t[4]), t[1].strip('{}'), t[2]))
    for f in by:
        by[f].sort()
    return by

def base(n):
    return re.sub(r'\[\d+\]$', '', n)

def spread(names, edge, layer, face, fixed=None):
    """centre names on the face at 0.192 um (every 4th 0.048 track, offset 0.012); fixed = {name: pos} kept."""
    fixed = fixed or {}
    n = len(names) + len(fixed)
    span = (n - 1) * 0.192
    k0 = round((edge / 2 - span / 2 - 0.012) / 0.192)
    slots = [round(0.012 + 0.192 * (k0 + i), 3) for i in range(n + 4)]
    taken = set(round(v, 3) for v in fixed.values())
    out = [(p, nm) for nm, p in fixed.items()]
    it = iter(names)
    for s in slots:
        if any(abs(s - t) < 0.19 for t in taken):
            continue
        try:
            out.append((s, next(it)))
        except StopIteration:
            break
    assert len(out) == n, (face, len(out), n)
    assert min(p for p, _ in out) > 2.0 and max(p for p, _ in out) < edge - 2.0, (face, min(out), max(out))
    return [(p, nm, layer, face) for p, nm in sorted(out)]

def sf7_pins(W, H):
    by = read_pins('qfd_d2d_static_sf5')
    n = [nm for _, nm, _ in by['N'] if nm != 'ck' and base(nm) not in PROG]
    prog = [nm for _, nm, _ in by['N'] if base(nm) in PROG]
    rec = [nm for nm in prog if base(nm) == 'prog_tx_record']
    small = [nm for nm in prog if base(nm) != 'prog_tx_record']
    rec.sort(key=lambda x: int(re.search(r'\[(\d+)\]', x).group(1)))
    e = rec[:274] + [nm for _, nm, _ in by['E']] + small + rec[274:]
    ck = round(0.012 + 0.048 * round((W / 2 - 0.012) / 0.048), 3)
    rows = (spread(n, W, 'M5', 'N', {'ck': ck}) + spread([nm for _, nm, _ in by['S']], W, 'M5', 'S')
            + spread([nm for _, nm, _ in by['W']], H, 'M4', 'W') + spread(e, H, 'M4', 'E'))
    assert len(rows) == sum(len(v) for v in by.values()) == 3668
    hdr = (f"# QW-D2D3 sf7 ({W} x {H}): sf5 actual scalar port inventory and along-face order; the 553 prog_* ports move\n"
           f"# N -> E (prog_tx_record halves around the E control group) so N fits {W} um; all pins at 0.192 um (5.208/um,\n"
           f"# every 4th legal M4/M5 track); clock ck on the N-face centre track {ck}.  Generated by {A}/make_kits.py.\n"
           "source /src/physical/common_flow/assigned_pin_exact.tcl\n")
    body = ''.join(f"ot_assigned_pin_exact {{{nm}}} {ly} {f} {p:.6f}\n" for p, nm, ly, f in rows)
    dem = {}
    for p, nm, ly, f in rows:
        dem.setdefault(f, []).append(p)
    demand = {f: dict(pins=len(v), span_um=round(max(v) - min(v), 3), edge_um=(W if f in 'NS' else H),
                      occupancy=round((max(v) - min(v)) / (W if f in 'NS' else H), 3)) for f, v in dem.items()}
    return hdr + body, demand, ck

