#!/bin/bash
# Near-HBM attention service f46073090 with RTL FP units (no C-DPI), r7 "shim" build.
#
# Measured failure of r6 (build_attn_hier.sh, hier_block on ot_qwen_nearhbm_attn_stack_h):
# all four stack_h children verilated (4.37 GB C++ / 107.5 GB each) and compiled, but the
# PARENT Verilation still elaborated the stack bodies (WIDTHCONCAT in instance
# gs[3].u_h.u_pv inside the parent run) and was OOM-killed at 200 GB (scope 1004940).
# Structural correction: the parent never sees the stack_h body. The frozen stack_h module
# is renamed in a build-only overlay copy (body byte-identical, unused, removed by
# --top-module), and a parameter shim of the same name instantiates the already compiled
# protect-lib wrappers of the four exact variants (S=0/1/2/3, R=8, DQ=128) produced by r6
# from the same frozen source. Every other hier block (pv256 slice, hub, join16, FP units)
# is built normally. No RTL arithmetic, latency or port changes; instance path gs[s].u_h
# is kept (one extra level .g.u inside it).
# Usage: build_attn_hier_shim.sh <frozen f460 root> <r6 obj dir> <out>
set -euo pipefail
root=$(realpath "$1"); r6=$(realpath "$2"); out=$3
vl=${VL:-$HOME/.local/opentallas-tools/verilator-5.050/bin/verilator}
here=$(cd "$(dirname "$0")" && pwd)
src='rtl/hdc/nearhbm/ot_qwen_tp8_attention_service.sv rtl/hdc/nearhbm/ot_qwen_tp8_vrow_merge.sv rtl/hdc/nearhbm/ot_qwen_tp8_pv256_pair.sv rtl/hdc/nearhbm/ot_qwen_tp8_pv256_slice.sv rtl/hdc/nearhbm/ot_qwen_tp8_pv256_finalize.sv rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv rtl/hdc/nearhbm/ot_qkd_ectl_parts.sv rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_hub_p.sv rtl/hdc/nearhbm/ot_qwen_nearhbm_prod.sv rtl/hdc/ot_hdc_sfu_q.sv rtl/hdc/nearhbm/ot_qwen_nearhbm_sfu_p.sv rtl/hdc/ot_hdc_sfu.sv rtl/hdc/ot_hdc_delay.sv rtl/hdc/ot_hdc_fpu.sv rtl/hdc/ot_hdc_fp32_mul_pipe.sv rtl/proto/ot_fp32_add_rne_pipe.sv rtl/hdc/ot_hdc_fp32_add_lat_nr.sv rtl/hdc/ot_hdc_fp32_add_lat.sv rtl/hdc/ot_hdc_fp32_mul_lat.sv rtl/hdc/ot_hdc_fastfp.sv rtl/hdc/ot_hdc_prefix.sv rtl/model/hbm_pc40_native_sim_20261003/ot_sram_1r1w_128x256_m1_r2c2_sim.sv'
declare -A var=([0]=c [1]=a [2]=d [3]=3)
mkdir -p "$out"; out=$(realpath "$out")
exec 9>"$out/build.lock"; flock -n 9 || { echo 'live builder holds this cache' >&2; exit 2; }
start=$(date +%s)
# Frozen inputs: source files, r6 stack wrappers + libraries, r6 add_lat_8 (used inside the stacks).
( cd "$root" && sha256sum $src ) > "$out/source.sha256"
: > "$out/reused_r6.sha256"
for s in 0 1 2 3; do v=${var[$s]}; d="$r6/Vot_qwen_nearhbm_attn_stack_h_$v"
 sha256sum "$d/ot_qwen_nearhbm_attn_stack_h_$v.sv" "$d/libot_qwen_nearhbm_attn_stack_h_$v.a" >> "$out/reused_r6.sha256"; done
# Variant <-> parameter binding is checked against r6's own hierarchy plan, never assumed.
args="$r6/Vot_qwen_tp8_attention_service__hierMkArgs.f"
grep -q "attn_stack_h_c,R,\\\\'sh8,DQ,\\\\'sh80$" "$args"
for s in 1 2 3; do grep -q "attn_stack_h_${var[$s]},S,\\\\'sh$s,R,\\\\'sh8,DQ,\\\\'sh80$" "$args"; done
grep -q "^ *parameter integer S = 0,$" "$root/rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv"
# Build-only overlay: rename the frozen stack_h module (body unchanged) and add the shim.
ov="$out/src"; rm -rf "$ov"; mkdir -p "$ov"
for f in $src; do mkdir -p "$ov/$(dirname "$f")"; cp -p "$root/$f" "$ov/$f"; done
st="$ov/rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv"
[[ $(grep -c '^module ot_qwen_nearhbm_attn_stack_h #($' "$st") == 1 ]]
sed -i 's/^module ot_qwen_nearhbm_attn_stack_h #($/module ot_qwen_nearhbm_attn_stack_h__body_in_r6_lib #(/' "$st"
diff <(sed 's/^module ot_qwen_nearhbm_attn_stack_h__body_in_r6_lib #($/module ot_qwen_nearhbm_attn_stack_h #(/' "$st") "$root/rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv"
w="$r6/Vot_qwen_nearhbm_attn_stack_h_a/ot_qwen_nearhbm_attn_stack_h_a.sv"
ports=$(sed -n '/^module /,/^ *);/p' "$w" | sed '1d;$d')
{
 echo '// Generated by build_attn_hier_shim.sh: selects the compiled exact stack_h variant.'
 echo 'module ot_qwen_nearhbm_attn_stack_h #(parameter integer HD=128, parameter integer S=0, parameter integer R=1,'
 echo '  parameter integer ADD_LAT=7, parameter integer MUL_LAT=6, parameter integer DQ=32, parameter integer ZW=4,'
 echo '  parameter integer LFB=4, parameter integer ND=1, parameter [31:0] SCALE=32'"'"'h3DB504F3) ('
 echo "$ports"
 echo ');'
 echo ' generate'
 echo '  if (HD!=128||R!=8||DQ!=128||ADD_LAT!=7||MUL_LAT!=6||ZW!=4||LFB!=4||ND!=1||SCALE!=32'"'"'h3DB504F3) begin: g_bad'
 echo '   initial $fatal(1, "stack_h shim: no compiled variant for these parameters");'
 for s in 0 1 2 3; do
  echo "  end else if (S==$s) begin: g ot_qwen_nearhbm_attn_stack_h_${var[$s]} u(.*);"
 done
 echo '  end else begin: g_bad_s initial $fatal(1, "stack_h shim: S out of range"); end'
 echo ' endgenerate'
 echo 'endmodule'
} > "$ov/stack_h_shim.sv"
grep -v 'ot_qwen_nearhbm_attn_stack_h"' "${HIER_VLT:-$here/hier_attn.vlt}" > "$out/hier_attn_shim.vlt"
! grep -q stack_h "$out/hier_attn_shim.vlt"
wr=""; for s in 0 1 2 3; do v=${var[$s]}; wr="$wr $r6/Vot_qwen_nearhbm_attn_stack_h_$v/ot_qwen_nearhbm_attn_stack_h_$v.sv"; done
sha256sum "$ov/stack_h_shim.sv" "$out/hier_attn_shim.vlt" "$0" > "$out/build_inputs.sha256"
cd "$ov"
$vl --cc --hierarchical -j 1 -O2 -Wno-fatal -Wno-lint -Wno-style -Wno-TIMESCALEMOD -Wno-MULTIDRIVEN --top-module ot_qwen_tp8_attention_service \
 +define+KVD_HEADS=1 +define+KVD_Q_FP32=1 +define+KVD_QK_ONLY=1 +define+KVD_ECTL3 -CFLAGS "-O2 -fPIC" --Mdir "$out/obj" \
 "$out/hier_attn_shim.vlt" $src stack_h_shim.sv $wr > "$out/build.log" 2>&1
cd "$out/obj"
make -f Vot_qwen_tp8_attention_service_hier.mk -j1 "MAKE=make -j${JOBS:-16}" hier_build >> "$out/build.log" 2>&1
# Libraries: r7 blocks, plus r6 stack libraries and any r6 block the stacks need that r7 did not build.
mapfile -t libs < <(find . -name '*.a' ! -name libverilated.a | sort)
have=$(printf '%s\n' "${libs[@]}" | xargs -n1 basename)
for a in $(find "$r6" -name 'lib*.a' ! -name libverilated.a | sort); do
 b=$(basename "$a"); grep -qx "$b" <<<"$have" || { libs+=("$a"); echo "reused $a" >> "$out/build.log"; }
done
g++ -shared -o "$out/libot_qwen_tp8_attention_service.so" -Wl,--whole-archive "${libs[@]}" -Wl,--no-whole-archive >> "$out/build.log" 2>&1
nm -D "$out/libot_qwen_tp8_attention_service.so" > "$out/dynamic-symbols.txt"
if grep -Eq '\b(nhb_fadd|nhb_fmul|ot_v41x_fadd|ot_v41x_fmul)\b' "$out/dynamic-symbols.txt"; then echo 'C-DPI FP symbol present' >&2; exit 3; fi
if nm -D --undefined-only "$out/libot_qwen_tp8_attention_service.so" | grep -q protectlib; then echo 'unresolved protectlib symbol' >&2; exit 4; fi
sha256sum "$out/libot_qwen_tp8_attention_service.so" > "$out/binary.sha256"
printf '%s\n' "${libs[@]}" | xargs sha256sum > "$out/archives.sha256"
echo "{\"seconds\": $(( $(date +%s) - start )), \"fp_units\": \"RTL ot_hdc_fp32_add_lat/mul_lat\", \"hierarchical\": true, \"stack_h\": \"r6 protect-lib variants c/a/d/3 via parameter shim\", \"parallel_cpp_jobs\": ${JOBS:-16}}" > "$out/receipt.json"
cat "$out/binary.sha256"
