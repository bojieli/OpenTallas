#!/usr/bin/env python3
"""S81-ARCH-RTL-2 slice-4 (b) qbank pin cycle: the LP-spec form of frame_band_plan.py --qb-pin-cycle, for the schedule
extractor (tools/s81_dv/frame_schedule.py).  Inserts the SAME relay stage (ot_s81_rly W RSREG 1, the qbank's own ck / rs)
on every o_x0 / o_x1 / o_go / o_cfg output of the named qbanks of the flat col_<M>_l4 frame source (fresh per-bit n<id>
nets, the spec parser's bit naming), places the relays in the qbank's region, and writes a spec copy reading it.
  mk_qbpc_spec.py --master col_h9 --qbanks u_bs2,u_bs3 --out-dir <repo-relative dir>"""
import argparse, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[0]
ap = argparse.ArgumentParser()
ap.add_argument('--root', required=True)
ap.add_argument('--master', default='col_h9')
ap.add_argument('--qbanks', default='u_bs2,u_bs3')
ap.add_argument('--out-dir', required=True)
a = ap.parse_args()
R = Path(a.root)
spec_p = R / f'results/arch/s81_dv_1016/frame_l4_cluster/compiler/{a.master}_spec.json'
spec = json.loads(spec_p.read_text())
src, = spec['sources']
txt = (R / src).read_text()
nmax = max(int(x) for x in re.findall(r'\bn(\d+)\b', txt))
L = txt.split('\n')
qb = a.qbanks.split(',')
new_wires, log, regadd = [], [], {}
for i, ln in enumerate(L):
    m = re.match(r'^(\s+)(dsfd_qbank_\w+) (u_bs\d+) \((\..*)\);\s*$', ln)
    if not m or m.group(3) not in qb:
        continue
    ind, q = m.group(1), m.group(3)
    c = dict(re.findall(r'\.(\w+)\(((?:[^()]|\([^()]*\))*)\)', m.group(4)))
    add = []
    for p in ('o_x0', 'o_x1', 'o_go', 'o_cfg'):
        e = c[p]
        bits = re.findall(r'\bn\d+\b', e)
        assert e == bits[0] or e == '{' + ', '.join(bits) + '}', (q, p, e[:80])
        nn = [f'n{nmax + 1 + k}' for k in range(len(bits))]
        nmax += len(bits)
        ne = nn[0] if len(nn) == 1 else '{' + ', '.join(nn) + '}'
        L[i] = L[i].replace(f'.{p}({e})', f'.{p}({ne})', 1)
        new_wires += nn
        inst = f'u_y_{q[2:]}_pc_{p[2:]}'
        add.append(f'{ind}ot_s81_rly #(.W({len(bits)}), .RSREG(1)) {inst} (.ck({c["ck"]}), .rs({c["rs"]}), .i({ne}), .o({e}));')
        regadd.setdefault(q, []).append(inst)
        log.append(f'{a.master}_l4 (l) {q}.{p} {len(bits)} b: +1 relay stage {inst}')
    L[i] = '\n'.join([L[i]] + add)
assert len(log) == 4 * len(qb), log
# wire declarations after the last existing 'wire n' line
last = max(i for i, ln in enumerate(L) if re.match(r'^    wire n\d+', ln))
decl = ['    wire ' + ', '.join(new_wires[k:k + 16]) + ';' for k in range(0, len(new_wires), 16)]
L[last + 1:last + 1] = decl
od = R / a.out_dir
od.mkdir(parents=True, exist_ok=True)
out_sv = od / f'{a.master}_l4_qbpc.sv'
out_sv.write_text('// GENERATED by mk_qbpc_spec.py (S81 slice-4 (b) qbank pin cycle, LP-spec form of frame_band_plan.py '
                  f'--qb-pin-cycle {a.qbanks}) from {src}\n' + '\n'.join(L))
s2 = dict(spec)
s2['sources'] = [str(out_sv.relative_to(R))]
if 'rtl/dsrom_sys/s81_glue/ot_s81_rly.sv' not in s2['child_sources']:
    s2['child_sources'] = s2['child_sources'] + ['rtl/dsrom_sys/s81_glue/ot_s81_rly.sv']
regs = []
for r in spec['regions']:
    r = dict(r, insts=list(r['insts']))
    for q, ins in regadd.items():
        if q in r['insts']:
            r['insts'] += ins
    regs.append(r)
s2['regions'] = regs
(od / f'{a.master}_qbpc_spec.json').write_text(json.dumps(s2, indent=1) + '\n')
(od / 'qbpc_spec_map.json').write_text(json.dumps(dict(source=src, qb_pin_cycle=log), indent=1) + '\n')
print('\n'.join(log))
