#!/usr/bin/env python3
"""S81-L20DIE (10-19): the die's index-tree SECTION as a structural netlist (die.v style: wires + instances only) for
tools/die_port_bind.py -- 16 dsdv_idx_rg readers (sid = region, abutted stations on their rq / rd links, query /
score chains W -> E), dsdv_idx_qf (query fan-out: local source s_3S + parent link -> reader 0 + 2 child links),
dsdv_idx_vmux (bk_sel S-face ingress: rung + score tail + 2 child lanes), dsdv_idx_tx (vi_s / vo_s taps -> parent link).
Every boundary net is a section port: the die GEN (S81-DIECHAIN) maps them onto the plan links (hrq_/hrd_ svc side,
hrqc_/hrdc_ ctrl side, iq_src, is_tail with its relays, the bk_sel vi_s / vo_s nets, the tree links).
Pads (pads.json): the chain ends -- reader 0 si (no upstream region: the score chain starts empty) and reader 15 qo (no
downstream region).  Straps (straps.json): dsdv_idx_rg sid (the region index, a die constant).
usage: mk_idx_die_sec.py OUTDIR"""
import json
import sys
from pathlib import Path

out = Path(sys.argv[1])
out.mkdir(parents=True, exist_ok=True)
R = 16
P = ['input wire ck', 'input wire rst', 'input wire [7:0] idx_uid', 'input wire [512:0] qs', 'input wire [512:0] ql',
     'output wire [512:0] qc0', 'output wire [512:0] qc1', 'input wire [275:0] vr', 'output wire [275:0] vi_s',
     'input wire [275:0] vo_s', 'input wire [275:0] tl_a', 'input wire [275:0] tl_b', 'output wire [275:0] tl_o',
     'output wire [3:0] qf_st', 'output wire vm_fault', 'output wire [15:0] tx_st']
for k in range(R):
    P += [f'input wire [681:0] rqi_{k:02d}', f'output wire [681:0] rqo_{k:02d}', f'input wire [561:0] rdi_{k:02d}',
          f'output wire [561:0] rdo_{k:02d}', f'output wire [9:0] rst_{k:02d}']
import re
W = {}
for p_ in P:
    m = re.match(r'(input|output) wire (?:\[(\d+):0\] )?(\w+)', p_)
    W[m.group(3)] = int(m.group(2)) + 1 if m.group(2) else 1
L = ['// generated by results/arch/s81_l20_1019/die/mk_idx_die_sec.py -- do not edit',
     'module dsdv_idx_die_sec (' + ', '.join(W) + ');']
L += ['  ' + p_ + ';' for p_ in P]
for k in range(R + 1):
    L.append(f'  wire [512:0] w_q_{k:02d};'); W[f'w_q_{k:02d}'] = 513
    L.append(f'  wire [275:0] w_s_{k:02d};'); W[f'w_s_{k:02d}'] = 276
L.append('  wire [512:0] w_qtail_nc;'); W['w_qtail_nc'] = 513


def c(n):
    return n if "'" in n or W[n] == 1 else '{%s[%d:0]}' % (n, W[n] - 1)


def inst(m, par, nm, conns):
    L.append(f'  {m} {par}{nm} (' + ', '.join(f'.{a}({c(b)})' for a, b in conns) + ');')


inst('dsdv_idx_qf', '', 'u_iqf', [('ck', 'ck'), ('rst', 'rst'), ('uid', 'idx_uid'), ('qs', 'qs'), ('ql', 'ql'), ('qr', 'w_q_00'),
                                  ('qc0', 'qc0'), ('qc1', 'qc1'), ('st', 'qf_st')])
for k in range(R):
    si = "276'd0" if k == 0 else f'w_s_{k:02d}'
    qo = 'w_qtail_nc' if k == R - 1 else f'w_q_{k + 1:02d}'
    inst('dsdv_idx_rg', '#(.SRAM_MACRO(1)) ', f'u_irg_{k:02d}',
         [('ck', 'ck'), ('rst', 'rst'), ('sid', f"4'd{k}"), ('qi', f'w_q_{k:02d}'), ('qo', qo), ('si', si), ('so', f'w_s_{k + 1:02d}'),
          ('rqi', f'rqi_{k:02d}'), ('rqo', f'rqo_{k:02d}'), ('rdi', f'rdi_{k:02d}'), ('rdo', f'rdo_{k:02d}'), ('st', f'rst_{k:02d}')])
inst('dsdv_idx_vmux', '', 'u_ivm', [('ck', 'ck'), ('rst', 'rst'), ('i_r', 'vr'), ('i_s', 'w_s_16'), ('i_a', 'tl_a'), ('i_b', 'tl_b'),
                                     ('o', 'vi_s'), ('fault', 'vm_fault')])
inst('dsdv_idx_tx', '#(.SRAM_MACRO(1)) ', 'u_itx', [('ck', 'ck'), ('rst', 'rst'), ('vi', 'vi_s'), ('vo', 'vo_s'), ('lo', 'tl_o'), ('st', 'tx_st')])
L.append('endmodule')
(out / 'dsdv_idx_die_sec.v').write_text('\n'.join(L) + '\n')
why = 'index chain end (S81-L20DIE): %s'
(out / 'pads.json').write_text(json.dumps({'pads': {}, 'instances': {
    'u_irg_00': {'master': 'dsdv_idx_rg', 'reason': why % 'reader 0 has no upstream region, the score chain starts empty (si 0)',
                 'ports': {'si': [[0, 275]]}},
    'u_irg_15': {'master': 'dsdv_idx_rg', 'reason': why % 'reader 15 has no downstream region (query forward qo unread)',
                 'ports': {'qo': [[0, 512]]}}}}, indent=1) + '\n')
(out / 'straps.json').write_text(json.dumps({'straps': [['dsdv_idx_rg', 'sid']]}) + '\n')
print('wrote', out)
