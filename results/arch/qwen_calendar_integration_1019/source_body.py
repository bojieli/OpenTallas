import sys,json,hashlib
from pathlib import Path
root=Path(sys.argv[1]).resolve()
sys.path.insert(0,str(root/'tools/qwen_layerbench'))
import dv_layer as L,dv_lower as D,dv_lower_mat as M
captured=[]
orig=L.CI.compile_image
def capture(a):
    result=orig(a);captured.append(result);return result
L.CI.compile_image=capture
try:rec=L.compose()
finally:L.CI.compile_image=orig
image,ctlm=captured[0]
pw=image[:1024]
metadata_words=ctlm['programme']['words']
if not ctlm['programme']['fused_native_capability'] or not (pw[1023]>>12)&1:
    raise ValueError('actual source does not certify cap1')
# Remove only the obsolete SRAM calendar region. Programme and ME/XPF controls
# remain source-generated bytes; the complete DV calendar is immutable ROM.
pw[16*metadata_words:976]=[0]*(976-16*metadata_words)
pw_text=''.join(f'{x:016x}\n' for x in pw)
Path('pw_metadata.hex').write_text(pw_text)
Path('ctlm_metadata_source.json').write_text(json.dumps(ctlm,indent=2)+'\n')

decode=[(x['edge_w5'],int(x['cmd'],16)) for x in rec['events']]
# Preserve lowerer entry edges, with explicit lowerer t0 parameter receipts.
ch=M.Chain(D.slice_map());M.lower_lm(300,M.load_ages(),ch)
head=[(x['edge'],int(x['cmd'],16)) for x in ch.commands()]
ch=M.Chain(D.slice_map());M.lower_embed(300,ch)
embed=[(x['edge'],int(x['cmd'],16)) for x in ch.commands()]
# Source-bound token-start prefix from the existing CTLM admission contract.
pw=[int(x,16) for x in Path('prefix_pw.hex').read_text().split()]
dw=[int(x,16) for x in Path('prefix_dw.hex').read_text().split()]
base=(dw[0]>>16)&1023;first=dw[1]>>16;count=dw[1]&65535
prefix=[];t=0
for i in range(first,first+count):
    word=pw[base+2*i]|(pw[base+2*i+1]<<64);t+=word>>116
    prefix.append((t,word&((1<<116)-1)))
segments=dict(embed=prefix+embed,decode=decode,head=head,boot=[(8,D.cmd_setid(0))])
sources={str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest()
         for p in sorted((root/'tools/qwen_layerbench').glob('*.py'))}
source=dict(lowerer_sha256=hashlib.sha256(json.dumps(sources,sort_keys=True).encode()).hexdigest(),
 programme_sha256=hashlib.sha256((root/L.CI.DEF_PROGRAM).read_bytes()).hexdigest(),
 metadata_pw_sha256=hashlib.sha256(pw_text.encode()).hexdigest(),metadata_words=metadata_words,native_capability=True,
 phase_manifest_sha256='0'*64,production_bound=False,embed_word0_parameter=300,head_word0_parameter=300,
 prefix_pw_sha256=hashlib.sha256(Path('prefix_pw.hex').read_bytes()).hexdigest(),
 prefix_dw_sha256=hashlib.sha256(Path('prefix_dw.hex').read_bytes()).hexdigest(),
 cap1_metadata_source=True,cap1_production=False,reason='source-lowered body; provider phase and head/finalnorm payload unbound')
Path('body.json').write_text(json.dumps(dict(segments=segments,source=source),indent=2)+'\n')
Path('lowerer_sources.json').write_text(json.dumps(sources,indent=2)+'\n')
Path('composition.json').write_text(json.dumps(rec,indent=2)+'\n')
print('ACTUAL_LOWERER_COUNTS',dict(decode=len(decode),head=len(head),embed=len(embed),prefix=len(prefix)))
