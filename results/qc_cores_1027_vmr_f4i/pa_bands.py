# QC-CORES-2 F4I: plan-level pin-access keep-out bands = the M3 escape gap between each PG stripe pair's M2-M5 via-stack
# columns (VSS pad column | gap | VDD pad column), widened by half an M3 width, snapped outward to the site grid, full core height.
# Derived from the PDN in the floorplan DB (pdn.tcl: M5 w0.12 sp0.072 pitch 4.32 off 2.064), deterministic; writes a Tcl file of
# hard placement blockages + a JSON receipt.  Also reports which already-fixed cells (pushdown / face) overlap a band.
import os, odb, json, collections
db = odb.dbDatabase.create(); odb.read_db(db, os.environ["ODB"]); b = db.getChip().getBlock(); u = b.getDbUnitsPerMicron()
cols = collections.defaultdict(lambda: [10**12, -10**12])
for n in b.getNets():
    if n.getSigType() not in ("POWER", "GROUND"): continue
    for sw in n.getSWires():
        for s in sw.getWires():
            if not s.isVia(): continue
            v = s.getTechVia() or s.getBlockVia(); x0, y0 = s.getViaXY()
            for vb in v.getBoxes():
                tl = vb.getTechLayer()
                if tl is None or tl.getName() != "M3": continue
                c = cols[(n.getName(), x0)]; c[0] = min(c[0], x0 + vb.xMin()); c[1] = max(c[1], x0 + vb.xMax())
vss = sorted(k[1] for k in cols if k[0] == "VSS"); vdd = sorted(k[1] for k in cols if k[0] == "VDD")
rows = list(b.getRows()); site = rows[0].getSite(); sw_ = site.getWidth(); ox = min(r.getOrigin()[0] for r in rows)
core = b.getCoreArea(); y0, y1 = core.yMin(), core.yMax(); half_m3 = int(0.009 * u)
bands = []
for xs in vss:
    xd = min((x for x in vdd if x > xs), default=None)
    if xd is None or xd - xs > 0.5 * u: continue
    g0 = cols[("VSS", xs)][1] - half_m3; g1 = cols[("VDD", xd)][0] + half_m3
    s0 = ox + ((g0 - ox) // sw_) * sw_; s1 = ox + -(-(g1 - ox) // sw_) * sw_
    bands.append((s0, s1))
w = sum(s1 - s0 for s0, s1 in bands); cw = core.xMax() - core.xMin()
fixed = []
for i in b.getInsts():
    if i.getPlacementStatus() not in ("FIRM", "LOCKED", "COVER") or i.getMaster().isBlock(): continue
    bb = i.getBBox()
    for s0, s1 in bands:
        if bb.xMax() > s0 and bb.xMin() < s1: fixed.append((i.getName(), i.getMaster().getName(), bb.xMin() / u, bb.yMin() / u)); break
out = os.environ["OUT"]
with open(out + ".tcl", "w") as f:   # band list only; pre_gpl_f4i.tcl creates the blockages after pushdown, cut around fixed cells
    f.write("# GENERATED by pa_bands.py (QC-CORES-2 F4I): %d PG stripe-pair M3 escape-gap bands, %.3f um of %.3f um core width (%.2f %%); x0 x1 y0 y1 dbu\n"
            % (len(bands), w / u, cw / u, 100.0 * w / cw))
    f.write("set ot_pab_bands {\n" + "".join("  {%d %d %d %d}\n" % (s0, s1, y0, y1) for s0, s1 in bands) + "}\n")
json.dump({"bands_um": [(s0 / u, s1 / u) for s0, s1 in bands], "n": len(bands), "band_um": w / u, "core_w_um": cw / u,
           "pct_core_width": 100.0 * w / cw, "site_um": sw_ / u, "fixed_overlap": fixed}, open(out + ".json", "w"), indent=1)
print("PA_BANDS n", len(bands), "width_um %.3f pct %.2f" % (w / u, 100.0 * w / cw), "first", [(s0 / u, s1 / u) for s0, s1 in bands[:3]],
      "marker_band", [(s0 / u, s1 / u) for s0, s1 in bands if s0 <= 118.8 * u <= s1], "fixed_overlap", len(fixed), fixed[:8])
