#!/usr/bin/env python3
"""HBM-MU-QUAD-4 (COORD ruling 3, 10-27): generate the opt-in CLOCK-ENABLE twins of the split HC tail.
usage: gen_sk_en.py REPO OUTDIR
Inputs (read-only, copied verbatim except the replaced lines; every replacement must hit exactly once):
  rtl/hdc/v41/ot_hdc_sinkhorn_s.sv                                     -> ot_hdc_sinkhorn_se.sv
  rtl/hbm_accel/generic/peers/static_hc/ot_hgi_hc_tail_static_s.sv     -> ot_hgi_hc_tail_static_se.sv
  rtl/hbm_accel/generic/peers/static_hc/ot_hbm_hc_tail_unit_static_s.sv-> ot_hbm_hc_tail_unit_static_se.sv
Form: the sk cores run on the die clock clk; every sk flop is enabled by sk_en (landed in each core by one register,
EN_LAND=1; EN_LAND=0 only for the reduced LEC instance).  The tail unit emits sk_en_o one cycle (+ NSTA station
cycles) ahead, so the landed pulse is high exactly in the core cycle in which the old divided clock sclk was high:
each sk flop updates on edge E+1 with the values the old RTL sampled at the sclk rising edge E.  No generated clock,
no gated clock.  MUT_EN=1 (bench only): pulse one cycle early = sk flops update ON edge E (pre-edge values) -> must FAIL."""
import re, sys
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
HDR = ("// GENERATED by results/hbm_mu_quad_4/sk_en/gen_sk_en.py (HBM-MU-QUAD-4 10-27, COORD ruling 3) from {src}:\n"
       "// opt-in CLOCK-ENABLE twin (div-7 generated sink clock removed; sk flops on clk, enabled by sk_en). Arithmetic verbatim.\n")


def sub(text, old, new, count=1, regex=False):
    n = len(re.findall(old if regex else re.escape(old), text))
    if (n < 1) if count is None else (n != count):
        raise SystemExit(f"replacement hit {n} times (want {count}): {old!r}")
    return re.sub(old if regex else re.escape(old), (new if regex else new.replace("\\", "\\\\")), text)


# ---------------- Sinkhorn split cores ----------------
src = "rtl/hdc/v41/ot_hdc_sinkhorn_s.sv"; t = (repo / src).read_text()
t = sub(t, r"\bot_hdc_sk_step0\b", "ot_hdc_sk_step0_en", count=None, regex=True)
t = sub(t, r"\bot_hdc_sk_steady\b", "ot_hdc_sk_steady_en", count=None, regex=True)
t = sub(t, r"\bot_hdc_sinkhorn_s\b", "ot_hdc_sinkhorn_se", count=None, regex=True)
# step0: enable port + landing register; the one data always block becomes enabled
t = sub(t, "    parameter integer MUT = 0\n) (\n    input  wire         clk,\n    input  wire         load,",
        "    parameter integer MUT = 0,\n    parameter integer EN_LAND = 1\n) (\n    input  wire         clk,\n"
        "    input  wire         sk_en_i,               // 1-in-SDIV enable from the tail (registered there)\n"
        "    input  wire         load,")
t = sub(t, "    integer k;\n    always @(posedge clk) begin\n        for (k = 0; k < 16; k = k + 1) begin\n            if (load)",
        "    reg sk_en_q;                               // landing register (boundary pin registered)\n"
        "    always @(posedge clk) sk_en_q <= sk_en_i;\n"
        "    wire sk_en = (EN_LAND != 0) ? sk_en_q : sk_en_i;\n"
        "    integer k;\n    always @(posedge clk) if (sk_en) begin\n        for (k = 0; k < 16; k = k + 1) begin\n            if (load)")
# steady: enable port + landing register (reset); both always blocks enabled
t = sub(t, "    parameter [31:0]  EPS = 32'h358637BD\n) (\n    input  wire         clk,\n    input  wire         rst_n,\n    input  wire         in_valid,",
        "    parameter [31:0]  EPS = 32'h358637BD,\n    parameter integer EN_LAND = 1\n) (\n    input  wire         clk,\n"
        "    input  wire         sk_en_i,\n    input  wire         rst_n,\n    input  wire         in_valid,")
t = sub(t, "    assign in_ready = (ph == P_IDLE);",
        "    reg sk_en_q;\n    always @(posedge clk or negedge rst_n) if (!rst_n) sk_en_q <= 1'b0; else sk_en_q <= sk_en_i;\n"
        "    wire sk_en = (EN_LAND != 0) ? sk_en_q : sk_en_i;\n    assign in_ready = (ph == P_IDLE);")
t = sub(t, "        end else begin\n            out_valid <= 1'b0;\n            r_pa <= 1'b0; r_pb <= 1'b0;",
        "        end else if (sk_en) begin\n            out_valid <= 1'b0;\n            r_pa <= 1'b0; r_pb <= 1'b0;")
t = sub(t, "    integer k;\n    always @(posedge clk) begin\n        for (k = 0; k < 16; k = k + 1) begin\n            if (ph == P_B2)",
        "    integer k;\n    always @(posedge clk) if (sk_en) begin\n        for (k = 0; k < 16; k = k + 1) begin\n            if (ph == P_B2)")
# wrapper
t = sub(t, "    input  wire         clk,\n    input  wire         rst_n,\n    input  wire         in_valid,\n    output wire         in_ready,\n    input  wire [511:0] in_e,",
        "    input  wire         clk,\n    input  wire         sk_en,\n    input  wire         rst_n,\n    input  wire         in_valid,\n    output wire         in_ready,\n    input  wire [511:0] in_e,")
t = sub(t, "u_s0 (.clk(clk), .load(load)", "u_s0 (.clk(clk), .sk_en_i(sk_en), .load(load)")
t = sub(t, "u_ss (.clk(clk), .rst_n(rst_n)", "u_ss (.clk(clk), .sk_en_i(sk_en), .rst_n(rst_n)")
(out / "ot_hdc_sinkhorn_se.sv").write_text(HDR.format(src=src) + t)

# ---------------- tail (rest + Sinkhorn) ----------------
src = "rtl/hbm_accel/generic/peers/static_hc/ot_hgi_hc_tail_static_s.sv"; t = (repo / src).read_text()
t = sub(t, r"\bot_hgi_hc_tail_static_s\b", "ot_hgi_hc_tail_static_se", count=None, regex=True)
t = sub(t, "    parameter integer MUT_PRE=0\n)(\n    input wire clk,sink_clk,rst_n,",
        "    parameter integer MUT_PRE=0,\n    parameter integer NSTA=0          // die stations on the sk_en hop (plan: 0, hop < 405 um)\n)(\n"
        "    input wire clk,rst_n,\n    input wire sk_en,                 // rest-local enable, aligned with the sk cores' landed enable\n"
        "    input wire sk_en_sk,              // to the sk cores (landed there)")
t = sub(t, "    ot_hdc_sinkhorn_s #(.ITERS(ITERS),.EPS(HC_EPS)) sink(\n        .clk(sink_clk),",
        "    wire sk_en_hop;\n    generate if(NSTA==0)begin:g_nosta assign sk_en_hop=sk_en_sk; end\n"
        "    else begin:g_sta reg [NSTA-1:0] q; always @(posedge clk or negedge rst_n) if(!rst_n)q<=0; else q<={q,sk_en_sk};\n"
        "        assign sk_en_hop=q[NSTA-1]; end endgenerate\n"
        "    ot_hdc_sinkhorn_se #(.ITERS(ITERS),.EPS(HC_EPS)) sink(\n        .clk(clk),.sk_en(sk_en_hop),")
t = sub(t, "    always @(posedge sink_clk or negedge rst_n)begin\n        if(!rst_n)sink_fault<=0;\n        else if((sink_launch&&!sr)||sf)sink_fault<=1;",
        "    always @(posedge clk or negedge rst_n)begin\n        if(!rst_n)sink_fault<=0;\n        else if(sk_en&&((sink_launch&&!sr)||sf))sink_fault<=1;")
assert "sink_clk" not in t.split("`default_nettype none", 1)[1].replace("sink_clk edge", ""), "sink_clk left"
(out / "ot_hgi_hc_tail_static_se.sv").write_text(HDR.format(src=src) + t)

# ---------------- tail unit (divider -> enable generator) ----------------
src = "rtl/hbm_accel/generic/peers/static_hc/ot_hbm_hc_tail_unit_static_s.sv"; t = (repo / src).read_text()
t = sub(t, r"\bot_hbm_hc_tail_unit_static_s\b", "ot_hbm_hc_tail_unit_static_se", count=None, regex=True)
t = sub(t, r"\bot_hgi_hc_tail_static_s\b", "ot_hgi_hc_tail_static_se", count=None, regex=True)
t = sub(t, "    parameter integer MUT_PRE = 0,\n",
        "    parameter integer MUT_PRE = 0,\n    parameter integer NSTA = 0,       // stations on the rest -> sk sk_en hop\n"
        "    parameter integer MUT_EN = 0,     // bench only: 1 = sk_en one cycle early (must FAIL)\n")
t = sub(t, "    wire wrap = (cnt == SDIV - 1);                 // the edge on which sclk rises",
        "    wire wrap = (cnt == SDIV - 1);                 // the edge on which sclk rises\n"
        "    // sclk is no longer a clock: it is the rest-local 1-in-SDIV enable (high in the cycle after each wrap edge).\n"
        "    // sk_en_o leads it by 1 (sk-core landing register) + NSTA (stations) cycles, so the landed enable == sclk.\n"
        "    localparam integer LEAD = 1 + NSTA + MUT_EN;\n"
        "    localparam integer EPH = ((SDIV - 1 - LEAD) % SDIV + SDIV) % SDIV;\n"
        "    reg sk_en_o;\n"
        "    always @(posedge clk or negedge rst_n) if (!rst_n) sk_en_o <= 1'b0; else sk_en_o <= (cnt == CW'(EPH));")
t = sub(t, ".clk(clk), .sink_clk(sclk), .rst_n(rst_n)", ".clk(clk), .sk_en(sclk), .sk_en_sk(sk_en_o), .rst_n(rst_n)")
t = sub(t, "ot_hgi_hc_tail_static_se #(.MUT_PRE(MUT_PRE))", "ot_hgi_hc_tail_static_se #(.MUT_PRE(MUT_PRE), .NSTA(NSTA))")
(out / "ot_hbm_hc_tail_unit_static_se.sv").write_text(HDR.format(src=src) + t)
print("wrote", *sorted(p.name for p in out.glob("*.sv")))
