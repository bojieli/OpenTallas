#!/usr/bin/env python3
"""HBM-FORM-SPLIT-8+REFORM-B11 glue: the 3 split pieces of hfd_hgi_vms_glue_nw_t + their composition.
    mk_pieces.py PIECES.sv COMP.sv
pieces: hfd_hgi_vms_gnw_cw (u_cw ring stop), hfd_hgi_vms_gnw_ccw (u_ccw ring stop), hfd_hgi_vms_gnw_hub (hub + replay + status).
composition hfd_hgi_vms_glue_nw_t__p11comp: the same ports as hfd_hgi_vms_glue_nw_t__fcore; XREG=0 (plan form) = wires,
XREG=2 (bench form) = the two kit face flops (piece out + piece in) on every crossing net."""
import sys
from pathlib import Path
B = range(8)
L = []
w = L.append
w("""`timescale 1ns/1ps
`default_nettype none
// HBM-FORM-SPLIT-8+REFORM-B11 (glue_d15r RE-FORM, owner 11-03 two strikes -> conservative form): hfd_hgi_vms_glue_nw_t
// (331,797 placed cells, 2 GRT congestion strikes) split on its natural submodule boundaries into 3 hard pieces.
// GENERATED by results/die_hbm_1105/form_split/glue_b11/mk_pieces.py.  Piece logic = ot_vms_glue_pc.sv port-cut
// copies: each crossing keeps exactly two registers (the two kit face flops), so every crossing and every die pin keeps
// its cycle (0 added cycles; lock-step results/die_hbm_1105/form_split/glue_b11/).  NW constants: sid 2, NC 0, CW 1,
// ring-stop COMMIT_DELAY 5 + BANK_PIN_IN 1.
""")
def stop(name, dirv, pfx, xq):
    w(f"module {name} #(parameter integer DMUT=0) (")
    p = ["    input wire clk", "    input wire rst_n", "    input wire tx_enable", "    input wire [2:0] tx_source",
         f"    input wire [2223:0] {pfx}_in", f"    output wire [2223:0] {pfx}_out"]
    for b in B:
        p += [f"    output wire [275:0] b{b}_{xq}", f"    input wire b{b}_{xq}_done", f"    input wire [275:0] b{b}_eg"]
    p += ["    input wire [289:0] pi", "    output wire [287:0] rce", "    input wire [265:0] ri", "    output wire [263:0] cco",
          "    output wire [2:0] wko", "    input wire [2:0] wki", "    output wire ack_o", "    input wire ack_i",
          "    output wire mirror_busy", "    output wire fault"]
    w(",\n".join(p) + "\n);")
    w("    wire [2207:0] xq_w;")
    for b in B:
        w(f"    assign b{b}_{xq}=xq_w[{b*276+275}:{b*276}];")
    w("    ot_vms_rstop_static_pc #(.DMUT(DMUT),.COMMIT_DELAY(6)) u_stop(.clk(clk),.rst_n(rst_n),.sid(2'd2),.dir(1'b" + dirv + "),")
    w(f"        .tx_enable(tx_enable),.tx_source(tx_source),.l_in({pfx}_in),.l_out({pfx}_out),.pi(pi),")
    w("        .eg({" + ",".join(f"b{b}_eg" for b in reversed(B)) + "}),.xq(xq_w),")
    w("        .xq_done({" + ",".join(f"b{b}_{xq}_done" for b in reversed(B)) + "}),")
    w("        .rce(rce),.ri(ri),.wko(wko),.wki(wki),.cco(cco),.ack_o(ack_o),.ack_i(ack_i),.mirror_busy(mirror_busy),.fault(fault));")
    w("endmodule")
stop("hfd_hgi_vms_gnw_cw", "0", "cw", "xq")
stop("hfd_hgi_vms_gnw_ccw", "1", "ccw", "xq2")
# hub piece
w("module hfd_hgi_vms_gnw_hub #(parameter integer DMUT=0) (")
p = ["    input wire clk", "    input wire rst_n", "    input wire [1:0] client_seq", "    input wire response_enable",
     "    input wire [1:0] response_seq", "    input wire [7:0] bank_enable", "    input wire [7:0] bank_client",
     "    input wire [1:0] hub_ring_enable", "    input wire [1:0] hub_ring_client", "    input wire replay_enable",
     "    input wire replay_source"]
for b in B:
    p += [f"    output wire [284:0] b{b}_pq", f"    input wire [265:0] b{b}_pr", f"    input wire [17:0] b{b}_status", f"    input wire b{b}_flt"]
p += ["    output wire [2:0] hub_status", "    output wire [18:0] vmstat", "    output wire replay_fault",
      "    output wire [289:0] pi0", "    output wire [289:0] pi1", "    input wire [263:0] cco0", "    input wire [263:0] cco1",
      "    input wire [287:0] rce0", "    input wire [287:0] rce1", "    output wire [265:0] ri0", "    output wire [265:0] ri1",
      "    input wire ring_fault0", "    input wire ring_fault1"]
w(",\n".join(p) + "\n);")
w("""    wire [2279:0] pq;
    wire [337:0] hq;
    wire [273:0] hr;
    wire [143:0] bank_status_m;""")
for b in B:
    w(f"    assign b{b}_pq=pq[{b*285+284}:{b*285}];")
    w(f"    assign bank_status_m[{b*18+17}:{b*18}]={{b{b}_status[17]|b{b}_flt,b{b}_status[16:0]}};")
w("    ot_vms_hub_static_pc #(.DMUT(DMUT),.NC(0),.CW(1)) u_hub(.clk(clk),.rst_n(rst_n),.sid(2'd2),.cq(hq),.cr(hr),")
w("        .client_seq(client_seq),.response_enable(response_enable),.response_seq(response_seq),")
w("        .bank_enable(bank_enable),.bank_client(bank_client),")
w("        .cw_enable(hub_ring_enable[0]),.cw_client(hub_ring_client[0]),.ccw_enable(hub_ring_enable[1]),.ccw_client(hub_ring_client[1]),")
w("        .pq(pq),.pr({" + ",".join(f"b{b}_pr" for b in reversed(B)) + "}),.cwi(pi0),.cci(pi1),.cco0(cco0),.cco1(cco1),.status(hub_status));")
w("    ot_vms_rcl_static_pc #(.DMUT(DMUT)) u_replay(.clk(clk),.rst_n(rst_n),.sid(2'd2),.rx_enable(replay_enable),.rx_source(replay_source),")
w("        .rce0(rce0),.rce1(rce1),.hq(hq),.hr(hr),.ri0(ri0),.ri1(ri1),.fault(replay_fault));")
w("    ot_vms_status_static_pc #(.DMUT(DMUT)) u_status(.clk(clk),.rst_n(rst_n),.bank_status(bank_status_m),.hub_status(hub_status),")
w("        .ring_fault(replay_fault),.ring_fault_late(ring_fault0|ring_fault1),.vmstat(vmstat));")
w("endmodule")
# crossing stage
w("""// crossing stage of the composition: XREG=0 wires (plan form), XREG=2 the two kit face flops (bench form)
module hfd_hgi_vms_gnw_xing #(parameter integer W=1, parameter integer XREG=0) (input wire clk, input wire [W-1:0] d, output wire [W-1:0] q);
    generate if(XREG==0) begin : g_w
        assign q=d;
    end else begin : g_r
        reg [W-1:0] s [0:XREG-1];
        always @(posedge clk) begin
            s[0]<=d;
            for(integer i=1;i<XREG;i=i+1) s[i]<=s[i-1];
        end
        assign q=s[XREG-1];
    end endgenerate
endmodule""")
# composition
w("module hfd_hgi_vms_glue_nw_t__p11comp #(parameter integer XREG=0, parameter integer DMUT=0) (")
p = ["    input wire clk", "    input wire rst_n", "    input wire [1:0] client_seq", "    input wire response_enable",
     "    input wire [1:0] response_seq", "    input wire [7:0] bank_enable", "    input wire [7:0] bank_client",
     "    input wire [1:0] hub_ring_enable", "    input wire [1:0] hub_ring_client", "    input wire [2223:0] cw_in",
     "    input wire [2223:0] ccw_in", "    output wire [2223:0] cw_out", "    output wire [2223:0] ccw_out",
     "    input wire [1:0] ring_tx_enable", "    input wire [5:0] ring_tx_source", "    input wire replay_enable", "    input wire replay_source"]
for b in B:
    p += [f"    output wire [275:0] b{b}_xq", f"    output wire [275:0] b{b}_xq2", f"    input wire b{b}_xq_done", f"    input wire b{b}_xq2_done",
          f"    input wire [275:0] b{b}_eg", f"    output wire [284:0] b{b}_pq", f"    input wire [265:0] b{b}_pr", f"    input wire [17:0] b{b}_status",
          f"    input wire b{b}_flt"]
p += ["    output wire [2:0] hub_status", "    output wire [1:0] mirror_busy", "    output wire [18:0] vmstat", "    output wire [2:0] ring_fault"]
w(",\n".join(p) + "\n);")
X = [("pi0", 290, "h", "a"), ("pi1", 290, "h", "b"), ("cco0", 264, "a", "h"), ("cco1", 264, "b", "h"),
     ("rce0", 288, "a", "h"), ("rce1", 288, "b", "h"), ("ri0", 266, "h", "a"), ("ri1", 266, "h", "b"),
     ("wk01", 3, "a", "b"), ("wk10", 3, "b", "a"), ("ack01", 1, "a", "b"), ("ack10", 1, "b", "a"),
     ("rf0", 1, "a", "h"), ("rf1", 1, "b", "h")]
for n, wd, s, d in X:
    w(f"    wire [{wd-1}:0] {s}_{n}, {d}_{n};")
    w(f"    hfd_hgi_vms_gnw_xing #(.W({wd}),.XREG(XREG)) x_{n}(.clk(clk),.d({s}_{n}),.q({d}_{n}));")
w("    assign ring_fault[0]=a_rf0; assign ring_fault[1]=b_rf1;")
for nm, pfx, xq, tag, en, wk_o, wk_i, ak_o, ak_i, pi, cco, rce, ri, rf, mb in (
        ("hfd_hgi_vms_gnw_cw", "cw", "xq", "u_a", 0, "a_wk01", "a_wk10", "a_ack01", "a_ack10", "a_pi0", "a_cco0", "a_rce0", "a_ri0", "a_rf0", 0),
        ("hfd_hgi_vms_gnw_ccw", "ccw", "xq2", "u_b", 1, "b_wk10", "b_wk01", "b_ack10", "b_ack01", "b_pi1", "b_cco1", "b_rce1", "b_ri1", "b_rf1", 1)):
    c = [".clk(clk)", ".rst_n(rst_n)", f".tx_enable(ring_tx_enable[{en}])", f".tx_source(ring_tx_source[{en*3+2}:{en*3}])",
         f".{pfx}_in({pfx}_in)", f".{pfx}_out({pfx}_out)"]
    for b in B:
        c += [f".b{b}_{xq}(b{b}_{xq})", f".b{b}_{xq}_done(b{b}_{xq}_done)", f".b{b}_eg(b{b}_eg)"]
    c += [f".pi({pi})", f".rce({rce})", f".ri({ri})", f".cco({cco})", f".wko({wk_o})", f".wki({wk_i})", f".ack_o({ak_o})",
          f".ack_i({ak_i})", f".mirror_busy(mirror_busy[{mb}])", f".fault({rf})"]
    w(f"    {nm} #(.DMUT(DMUT)) {tag}(" + ",".join(c) + ");")
c = [".clk(clk)", ".rst_n(rst_n)"] + [f".{n}({n})" for n in ("client_seq", "response_enable", "response_seq", "bank_enable", "bank_client",
     "hub_ring_enable", "hub_ring_client", "replay_enable", "replay_source")]
for b in B:
    c += [f".b{b}_pq(b{b}_pq)", f".b{b}_pr(b{b}_pr)", f".b{b}_status(b{b}_status)", f".b{b}_flt(b{b}_flt)"]
c += [".hub_status(hub_status)", ".vmstat(vmstat)", ".replay_fault(ring_fault[2])", ".pi0(h_pi0)", ".pi1(h_pi1)", ".cco0(h_cco0)",
      ".cco1(h_cco1)", ".rce0(h_rce0)", ".rce1(h_rce1)", ".ri0(h_ri0)", ".ri1(h_ri1)", ".ring_fault0(h_rf0)", ".ring_fault1(h_rf1)"]
w("    hfd_hgi_vms_gnw_hub #(.DMUT(DMUT)) u_h(" + ",".join(c) + ");")
w("endmodule\n`default_nettype wire")
s = "\n".join(L) + "\n"; i = s.index("// crossing stage"); h = s[:s.index("module ")]
Path(sys.argv[1]).write_text(s[:i] + "`default_nettype wire\n")       # the 3 pieces (kit RTL)
Path(sys.argv[2]).write_text(h + s[i:])                               # crossing stage + composition (plan glue / bench)
print("wrote", sys.argv[1], sys.argv[2])
