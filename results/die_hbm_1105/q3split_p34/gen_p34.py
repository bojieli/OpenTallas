#!/usr/bin/env python3
"""HBM-GAPS-4-Q3SPLIT d44v part 34: ot_hfd_coll_q3_edge_core = 3 x ot_hfd_coll_q3_edge_link + ot_hfd_coll_q3_edge_arg (plan form).
Inputs on main: the EQ-proven bench composition rtl/hbm_accel/cores_split/reform_1103/ot_hfd_coll_q3_edge_core/
ot_hfd_coll_q3_edge_core__split.sv (subs in their kit face-shell form __fs, MUT bench mutants) and the kit hand wrapper
physical/die_plan/hbm_arch_cores/wrappers/ot_hfd_coll_q3_edge_core.sv.  Writes:
  ot_hfd_coll_q3_edge_core__p34comp.sv  the composition with plain subs and MUT = 0 folded (same text otherwise)
  ot_hfd_coll_q3_edge_core__p34glue.sv  __fcore (the hand wrapper, u_core = the composition, one clk) + the plan module
                                         (wires only); physical sub path <inst>.u_fcore.u_core.u_<sub>
    gen_p34.py REPO OUTDIR"""
import re, sys
from pathlib import Path
R, out = Path(sys.argv[1]), Path(sys.argv[2]); CORE = "ot_hfd_coll_q3_edge_core"
s = (R / f"rtl/hbm_accel/cores_split/reform_1103/{CORE}/{CORE}__split.sv").read_text()
c = s.replace(" #(parameter integer MUT = 0)", "").replace("__fs u_", " u_")
for a, b in [("(MUT == 1) ? (link0_epoch_new ^ 8'd1) : link0_epoch_new", "link0_epoch_new"),
             ("(MUT == 2) ? link2_rx_pin_flit : link1_rx_pin_flit", "link1_rx_pin_flit"),
             ("(MUT == 2) ? link1_rx_pin_flit : link2_rx_pin_flit", "link2_rx_pin_flit"),
             ("(MUT == 3) ? 1'b0 : arg_rst_n", "arg_rst_n")]:
    assert c.count(a) == 1, a
    c = c.replace(a, b)
body = c[c.index("\nmodule "):]
assert "__fs" not in body and "MUT" not in body, "bench-only text left in the plan form"
c = ("// HBM-GAPS-4-Q3SPLIT d44v part 34: GENERATED by gen_p34.py from " + f"{CORE}__split.sv (MUT = 0, plain subs). Plan form.\n" + c)
(out / f"{CORE}__p34comp.sv").write_text(c)
w = (R / f"physical/die_plan/hbm_arch_cores/wrappers/{CORE}.sv").read_text()
w = w.replace(f"module {CORE} (", f"module {CORE}__fcore (", 1)
w2 = re.sub(r"ot_hfd_coll_q3_edge_core__mc u_core \(\n        \.arg_clk\(clk\),\n        \.link0_ck\(\{5\{clk\}\}\),\n        \.link1_ck\(\{5\{clk\}\}\),\n        \.link2_ck\(\{5\{clk\}\}\),",
            f"{CORE}__split u_core (\n        .clk(clk),", w)
assert w2 != w; w = w2
hdr = w[w.index(f"module {CORE}__fcore ("):]
ports = hdr[:hdr.index(");")].split("(", 1)[1]
names = re.findall(r"wire (?:\[\d+:\d+\] )?(\w+)", ports)
plan = ("\n// HBM-GAPS-4-Q3SPLIT d44v part 34: plan module " + CORE + " = thin parent glue of the split hard core (wires only; the\n"
        "// sub-cores of " + CORE + "__split are the hard cores, each with its own kit face shell).\n`default_nettype none\n"
        f"module {CORE} ({ports});\n    {CORE}__fcore u_fcore (" + ", ".join(f".{n}({n})" for n in names) + ");\nendmodule\n`default_nettype wire\n")
(out / f"{CORE}__p34glue.sv").write_text("// HBM-GAPS-4-Q3SPLIT d44v part 34: GENERATED by gen_p34.py (kit hand wrapper with u_core = the split composition).\n" + w + plan)
print("ports", len(names))
