#!/usr/bin/env python3
"""DIE-HBM-77-EXPX 11-05: vB (safe-by-construction) form of ot_hbm_su_pg_lane_exp_x_core.

Derives ot_hbm_su_static_lane_xb / ot_hbm_su_static_lane_pinreg_xb from the part-18 lane_x / pinreg_x and patches the
exp_x core to use them at MLAT 5 / ALAT 4 (input-cut multiplier lat5i and input-cut add lat4i, both existing units).
Self-contained: every INPUT pin keeps its cycle.  The per-stage control fields are delayed inside the pin wrapper by the
stage growth, so the controller and the sfu_s core are unchanged.  Port cycle deltas at the core (PIN CYCLES):
  write / reducer / fault / coll outputs (vm_*, kv_*, ro_*, fault, coll)  +T = 4 dM + dA = +5
  SFU seam out (sx_v, sx_r, sx_fn) and its return (sx_y_exp, sx_y_div, sx_fault)  +S = 2 dM + dA = +3 (pair moves together)
  fetch side (rd_*, vi_*, bank_*) and all other inputs                              0
with dM = MLAT - SMLAT = 1, dA = ALAT - SALAT = 1.  SMLAT / SALAT keep the SFU chain depths (exp, sigmoid) at the
sfu_s_core values.  The M1 insertion line (mul | div) grows by dM on both depths (div output delayed dM), so the
controller's checkpoint spacing is unchanged.  Fault sources are aligned to +T so the fault stream is the old one +T.
Also (same cycles, same values): the l1r LDCS carry-save offset load, and the leaf sums vb + off0 / vb + off1 both
computed with the bank select after the adders (the select fans out to 120 bits).
With SMLAT = SALAT = 0 (default) the generated modules equal lane_x / pinreg_x in behaviour.

    gen_lane_xb.py REPO OUTDIR
"""
import re, sys
repo, out = sys.argv[1:3]
X = f'{repo}/rtl/hbm_accel/cores_split/reform_1104a/lane_x'
FR = f'{repo}/results/die_hbm_1105/expx_vb'
HDR = '// DIE-HBM-77-EXPX 11-05: GENERATED by results/die_hbm_1105/expx_vb/gen_lane_xb.py from %s. Do not edit.\n'


def sub1(txt, a, b):
    assert txt.count(a) == 1, (a[:80], txt.count(a))
    return txt.replace(a, b)


t = open(f'{X}/ot_hbm_su_static_lane_x.sv').read()
t = t.split('\n', 1)[1]                                     # drop the generated header line
t = sub1(t, 'module ot_hbm_su_static_lane_x #(', 'module ot_hbm_su_static_lane_xb #(\n'
         '    parameter integer SMLAT = 0,        // SFU chain multiplier latency (0: MLAT); depths of the sfu_s_core seam\n'
         '    parameter integer SALAT = 0,        // SFU chain add latency (0: ALAT)\n'
         '    parameter integer MUT = 0,          // bench mutants only (0 in every build)')
t = sub1(t, '    localparam integer D_DIV = 19, D_EXP = 7 * MLAT + 8 * ALAT + 4, D_SIG = D_EXP + ALAT + D_DIV;',
         '    localparam integer SM = (SMLAT > 0) ? SMLAT : MLAT, SA = (SALAT > 0) ? SALAT : ALAT;\n'
         '    localparam integer DM = MLAT - SM, DA = ALAT - SA;     // stage growth of a multiply / an add stage\n'
         '    localparam integer DMX = (MUT == 3) ? 0 : DM;          // M1 line growth (div side)\n'
         '    localparam integer D_DIV = 19, D_EXP = 7 * SM + 8 * SA + 4, D_SIG = D_EXP + SA + D_DIV;')
t = sub1(t, '    localparam integer D_RSQ = 1 + 9 * MLAT + 3 * ALAT, D_SQRT = 31;',
         '    localparam integer D_RSQ = 1 + 9 * SM + 3 * SA, D_SQRT = 31;')
t = sub1(t, '    localparam integer D_SP = D_EXP + 11 * MLAT + 10 * ALAT + 50;',
         '    localparam integer D_SP = D_EXP + 11 * SM + 10 * SA + 50;')
t = sub1(t, 'localparam [15:0] H_DIV = D_DIV, H_M = MLAT,', 'localparam [15:0] H_DIV = D_DIV + DMX, H_M = MLAT,')
# divider: same unit, its result and fault wait DM so the M1 line keeps the mul/div spacing
t = sub1(t, '            ot_hdc_v41x_fdiv u_d1 (.clk(clk_stage[1]), .rst_n(rst_n), .v(p_v && p_div), .a(p_a),\n'
            '                                   .b((cp_m1 == M1_DIVB) ? p_b : cp_imm1), .y(div1_y), .vo(), .fault(f_d1));\n'
            '            ot_hdc_v41x_ins #(.W(T1W), .K(2), .DEPTHS({H_DIV, H_M}), .DMAX(19)) u_l1 (',
         '            wire [31:0] div1_y0;\n            wire        f_d10;\n'
         '            ot_hdc_v41x_fdiv u_d1 (.clk(clk_stage[1]), .rst_n(rst_n), .v(p_v && p_div), .a(p_a),\n'
         '                                   .b((cp_m1 == M1_DIVB) ? p_b : cp_imm1), .y(div1_y0), .vo(), .fault(f_d10));\n'
         '            ot_hdc_delay #(.W(32), .D(DMX)) u_d1y (.clk(clk_stage[1]), .rst_n(rst_n), .d(div1_y0), .q(div1_y));\n'
         '            ot_hdc_delay #(.W(1), .D(DMX), .RESET(1)) u_d1f (.clk(clk_stage[1]), .rst_n(rst_n), .d(f_d10), .q(f_d1));\n'
         '            ot_hdc_v41x_ins #(.W(T1W), .K(2), .DEPTHS({H_DIV, H_M}), .DMAX(D_DIV + DMX)) u_l1 (')
# leaf sums: both banks added, select after the adders
t = sub1(t, '        ot_hdc_kadd #(.W(AW), .K(K)) u_s (.a(vb[gs*AW +: AW]), .b(bank ? off1[gs] : off0[gs]), .cin(1\'b0),\n'
            '                                          .s(sum_c[gs*AW +: AW]), .cout(unused_cs));',
         '        wire [AW-1:0] s0, s1;\n        wire unused_cs1;\n'
         '        ot_hdc_kadd #(.W(AW), .K(K)) u_s (.a(vb[gs*AW +: AW]), .b(off0[gs]), .cin(1\'b0), .s(s0), .cout(unused_cs));\n'
         '        ot_hdc_kadd #(.W(AW), .K(K)) u_s1 (.a(vb[gs*AW +: AW]), .b(off1[gs]), .cin(1\'b0), .s(s1), .cout(unused_cs1));\n'
         '        assign sum_c[gs*AW +: AW] = ((MUT == 5) ? !bank : bank) ? s1 : s0;')
# LDCS carry-save offset load (l1r form, HBM-FORM-TIMING 11-05)
a = t.index('    end else begin : g_ld3k')
b = t.index('    end endgenerate', a) + len('    end endgenerate')
ldcs = open(f'{FR}/ldcs_g_ld3k.svfrag').read().rstrip('\n')
ldcs = sub1(ldcs, 'wire [AW-1:0] sd = sc ^ cc ^ cb,', 'wire [AW-1:0] sd = sc ^ cc ^ ((MUT == 4) ? ca : cb),')
t = t[:a] + ldcs + t[b:]
# fault sources aligned to +T (the old fault stream, T edges later); coll likewise
TT = '(4 * DM + DA)'
al = [('f_m1', f'{TT} - DM'), ('f_d1', f'{TT} - DM'), ('f_m2', f'{TT} - 2 * DM'), ('f_q', f'{TT} - 2 * DM'),
      ('f_ad', f'{TT} - 2 * DM - DA'), ('f_sfu', f'{TT} - 2 * DM - DA'), ('f_e1m', f'{TT} - 3 * DM - DA'),
      ('f_e1a', f'{TT} - 3 * DM - DA'), ('f_e2', '(MUT == 6) ? 1 : 0')]
blk = '    // fault sources and collisions aligned to +T = 4 DM + DA (DIE-HBM-77-EXPX vB)\n'
for n, d in al:
    blk += f'    wire {n}_t;\n    ot_hdc_delay #(.W(1), .D({d}), .RESET(1)) u_al_{n} (.clk(clk_stage[7]), .rst_n(rst_n), .d({n}), .q({n}_t));\n'
blk += f'    wire c1_t, c4_t;\n    ot_hdc_delay #(.W(1), .D({TT}), .RESET(1)) u_al_c1 (.clk(clk_stage[7]), .rst_n(rst_n), .d(c1), .q(c1_t));\n'
blk += f'    ot_hdc_delay #(.W(1), .D({TT} - 2 * DM - DA), .RESET(1)) u_al_c4 (.clk(clk_stage[7]), .rst_n(rst_n), .d(c4), .q(c4_t));\n'
t = sub1(t, '    reg fault_r;\n', blk + '    reg fault_r;\n')
t = sub1(t, 'fault_r <= f_m1 | f_d1 | f_m2 | f_q | f_ad | f_sfu | f_e1m | f_e1a | f_e2;',
         'fault_r <= f_m1_t | f_d1_t | f_m2_t | f_q_t | f_ad_t | f_sfu_t | f_e1m_t | f_e1a_t | f_e2_t;')
t = sub1(t, '    assign coll = c1 | c4;', '    assign coll = c1_t | c4_t;')
open(f'{out}/ot_hbm_su_static_lane_xb.sv', 'w').write(HDR % 'ot_hbm_su_static_lane_x.sv' + t)

# ---- pin wrapper: per-stage control fields delayed by the stage growth
p = open(f'{X}/ot_hbm_su_static_lane_pinreg_x.sv').read()
p = p.split('\n', 1)[1]
p = sub1(p, 'module ot_hbm_su_static_lane_pinreg_x #(', 'module ot_hbm_su_static_lane_pinreg_xb #(\n'
         '    parameter integer SMLAT = 0, SALAT = 0, MUT = 0,')
p = sub1(p, '    ot_hbm_su_static_lane_x #(.XS(XS),', '''    // ---- DIE-HBM-77-EXPX vB: each control field reaches its stage DM / DA edges later per grown stage before it
    localparam integer SM = (SMLAT > 0) ? SMLAT : MLAT, SA = (SALAT > 0) ? SALAT : ALAT;
    localparam integer DM = MLAT - SM, DA = ALAT - SA;
    localparam integer D_CM = (MUT == 1) ? 0 : DM, D_CA = 2 * DM, D_CS = 2 * DM + DA, D_CE = 3 * DM + DA,
                       D_CO = (MUT == 2) ? 4 * DM + DA - 1 : 4 * DM + DA;
    wire [2:0] y_cm_m1, y_cm_qm, y_ca_ad, y_ci_sfu, y_cs_sfu, y_cs_e1; wire [1:0] y_cm_m2, y_ce_e2, y_co_dst;
    wire [31:0] y_cm_imm1, y_ca_imm2, y_cs_imm2, y_ce_imm1, y_side_y; wire y_co_rnd;
    ot_hdc_delay #(.W(40), .D(D_CM)) u_dcm (.clk(c0), .rst_n(rst_i), .d({q_cm_m1, q_cm_m2, q_cm_qm, q_cm_imm1}),
                                           .q({y_cm_m1, y_cm_m2, y_cm_qm, y_cm_imm1}));
    ot_hdc_delay #(.W(35), .D(D_CA)) u_dca (.clk(c0), .rst_n(rst_i), .d({q_ca_ad, q_ca_imm2}), .q({y_ca_ad, y_ca_imm2}));
    ot_hdc_delay #(.W(73), .D(D_CS)) u_dcs (.clk(c0), .rst_n(rst_i), .d({q_ci_sfu, q_cs_sfu, q_cs_e1, q_cs_imm2, q_side_y}),
                                           .q({y_ci_sfu, y_cs_sfu, y_cs_e1, y_cs_imm2, y_side_y}));
    ot_hdc_delay #(.W(34), .D(D_CE)) u_dce (.clk(c0), .rst_n(rst_i), .d({q_ce_e2, q_ce_imm1}), .q({y_ce_e2, y_ce_imm1}));
    ot_hdc_delay #(.W(3), .D(D_CO)) u_dco (.clk(c0), .rst_n(rst_i), .d({q_co_rnd, q_co_dst}), .q({y_co_rnd, y_co_dst}));
    ot_hbm_su_static_lane_xb #(.SMLAT(SMLAT), .SALAT(SALAT), .MUT(MUT), .XS(XS),''')
for f in ('cm_m1', 'cm_m2', 'cm_qm', 'cm_imm1', 'ca_ad', 'ca_imm2', 'ci_sfu', 'cs_sfu', 'cs_e1', 'cs_imm2', 'ce_e2',
          'ce_imm1', 'co_rnd', 'co_dst'):
    p = sub1(p, f'.{f}(q_{f})', f'.{f}(y_{f})')
p = sub1(p, '.side_y((KIND == 2) ? side_y : q_side_y)', '.side_y((KIND == 2) ? side_y : y_side_y)')
open(f'{out}/ot_hbm_su_static_lane_pinreg_xb.sv', 'w').write(HDR % 'ot_hbm_su_static_lane_pinreg_x.sv' + p)

# ---- the exp_x core: MLAT 5 / ALAT 4 on the lane, SFU seam depths at 4 / 3
c = open(f'{X}/ot_hbm_su_pg_lane_exp_x_core.sv').read()
c = sub1(c, '    parameter integer MLAT = 4,\n    parameter integer ALAT = 3,',
         '    parameter integer MLAT = 5,         // DIE-HBM-77-EXPX vB: lat5i input-cut multiplier\n'
         '    parameter integer ALAT = 4,         // lat4i input-cut add\n'
         '    parameter integer SMLAT = 4,        // sfu_s_core chain (unchanged)\n'
         '    parameter integer SALAT = 3,\n    parameter integer MUT = 0,')
c = sub1(c, 'ot_hbm_su_static_lane_pinreg_x #(.XS(XS),', 'ot_hbm_su_static_lane_pinreg_xb #(.SMLAT(SMLAT),.SALAT(SALAT),.MUT(MUT),.XS(XS),')
c = c.replace('// HBM-REFORM-A 11-04: GENERATED by results/die_hbm_1104/reform_a/part18/gen_lane_x.py from ot_hbm_su_pg_lane_exp_core.sv. Do not edit.',
              '// HBM-REFORM-A 11-04: GENERATED by results/die_hbm_1104/reform_a/part18/gen_lane_x.py from ot_hbm_su_pg_lane_exp_core.sv,\n'
              '// then DIE-HBM-77-EXPX 11-05 vB (results/die_hbm_1105/expx_vb/gen_lane_xb.py): MLAT 5 / ALAT 4 lane, seam depths 4 / 3. Do not edit.', 1)
open(f'{out}/ot_hbm_su_pg_lane_exp_x_core.sv', 'w').write(c)
print('ok')
