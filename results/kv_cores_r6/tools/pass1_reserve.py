#!/usr/bin/env python3
"""KV-CORES-R6 pass1_reserve (successor of results/kv_cores_r2/pass1_reserve.py): same island reservation, but the
placement blockage is CARVED around fixed instances already inside the island (the floorplan tap cells): a blockage
over a fixed tap cell fails DPL check_placement ('Placed in rows check failed', e6 R5 pass 1: 16 TAP_TAPCELL_ROW_369..399
in the 12.8a entry island).  The island stays reserved for every movable cell; only the tap-cell columns stay open, and
nothing movable can land there (a tap column is the tap cell width).
    pass1_reserve.py SLICE.json KITDIR"""
import json, sys
from pathlib import Path
sl = json.load(open(sys.argv[1]))["slice"]; kd = Path(sys.argv[2])
rects = []
if sl.get("entry"): rects.append(("entry", sl["entry"]["island_um"]))
for i, q in enumerate((sl.get("core_tree") or {}).get("islands") or []): rects.append((f"core_tree_{i}", q["rect_um"]))
for i, q in enumerate((sl.get("die_islands") or {}).get("points") or []): rects.append((f"die_{q.get('role')}_{i}", q["rect_um"]))
L = ["# GENERATED by KV-CORES-R6 pass1_reserve.py (tap-carved) from " + sys.argv[1], "set kvr2_b [ord::get_db_block]",
     "proc kvr2_blk1 {b x0 y0 x1 y1} { if {$x1 <= $x0} { return 0 }; foreach k [$b getBlockages] { set q [$k getBBox]",
     "  if {[$q xMin]==$x0 && [$q yMin]==$y0 && [$q xMax]==$x1 && [$q yMax]==$y1} { return 1 } }",
     "  odb::dbBlockage_create $b $x0 $y0 $x1 $y1; return 1 }",
     "proc kvr2_blk {b x0 y0 x1 y1} {",
     "  set cut {}",
     "  foreach i [$b getInsts] { if {![$i isFixed]} { continue }; set q [$i getBBox]",
     "    if {[$q xMax] <= $x0 || [$q xMin] >= $x1 || [$q yMax] <= $y0 || [$q yMin] >= $y1} { continue }",
     "    lappend cut [list [$q xMin] [$q xMax]] }",
     "  set cut [lsort -integer -index 0 $cut]; set n 0; set cx $x0",
     "  foreach c $cut { lassign $c a z; if {$a > $cx} { incr n [kvr2_blk1 $b $cx $y0 $a $y1] }; if {$z > $cx} { set cx $z } }",
     "  incr n [kvr2_blk1 $b $cx $y0 $x1 $y1]",
     "  puts \"KVR2_PASS1_RESERVE rect $x0 $y0 $x1 $y1: [llength $cut] fixed insts carved, $n blockages\" }"]
for n, r in rects:
    x0, y0, x1, y1 = (int(round(v * 1000)) for v in r)
    L.append(f"kvr2_blk $kvr2_b {x0} {y0} {x1} {y1}   ;# {n} {r}")
L.append(f'puts "KVR2_PASS1_RESERVE {len(rects)} island sites"')
(kd / "kvr2_reserve.tcl").write_text("\n".join(L) + "\n")
h = kd / "face_flops.tcl"
t = h.read_text()
if "kvr2_reserve.tcl" not in t:
    h.write_text("source /work/kvr2_reserve.tcl\n" + t)
print(kd.name, len(rects), [n for n, _ in rects])
