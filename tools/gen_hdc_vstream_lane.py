#!/usr/bin/env python3
"""Generate rtl/hdc/ot_hdc_vstream_lane.sv: one lane of the vector stream unit.

    python3 tools/gen_hdc_vstream_lane.py [--check]

The lane IS the scalar stream unit's element datapath: the text from the
address cycle to the writes of rtl/hdc/ot_hdc_stream.sv (its localparams and
everything between "-- address cycle" and "-- reducer"), wrapped with the
lane's ports.  The qualified scalar datapath stays the single source; a change
there reaches every lane by regenerating (tests check the file is current).

What the wrapper adds: the lane's element addresses are lane 0's plus
LANE x the inner stride (lane l of vector v is element v*SW + l), the lane
emits only when its element exists (`live`), and the element's result and
reducer tags leave on ports for the vector reducer (ot_hdc_vreduce).
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "rtl/hdc/ot_hdc_stream.sv"
OUT = ROOT / "rtl/hdc/ot_hdc_vstream_lane.sv"

HEADER = '''`timescale 1ns/1ps
// GENERATED by tools/gen_hdc_vstream_lane.py from rtl/hdc/ot_hdc_stream.sv -- do not edit.
// One lane of the vector stream unit (rtl/hdc/ot_hdc_vstream.sv): the scalar
// stream unit's element datapath, its addresses offset by LANE x the inner
// stride, emitting only when its element exists.
module ot_hdc_vstream_lane #(
    parameter integer WR   = 64,
    parameter integer AW   = 24,
    parameter integer NW   = 16,
    parameter integer LANE = 0,
    parameter integer KV_FP8 = 1,     // the vector core's KV cache is FP8 E4M3 (hdc_golden.KV_FMT)
    parameter integer ML = 0          // extra memory-read latency: every memory answers 1 + ML edges after its read
                                      // strobe (the element's tag and valid wait ML more cycles before S1); 0 = original
) (
    input  wire              clk,
    input  wire              rst_n,
    // controller state (lane 0's view) and this lane's element
    input  wire              emit0,
    input  wire              live,
    input  wire [NW-1:0]     i,
    input  wire [NW:0]       fin_th,
    input  wire              i_last_r,
    input  wire [AW-1:0]     cura0, curb0, curc0, curd0, rrow,
    input  wire [AW-1:0]     asi, bsi, csi, dsi,
    input  wire              asrc, bsrc, csrc, mc, md, redsq,
    input  wire [1:0]        ma, mb, dst, red,
    input  wire [2:0]        ad,
    input  wire [31:0]       imm1, imm2,
    input  wire [2:0]        cls,
    input  wire              accept,
    input  wire [2:0]        i_sfu,
    // memories
    output reg               va_re,
    output reg  [AW-1:0]     va_addr,
    input  wire [31:0]       va_q,
    output reg               vb_re,
    output reg  [AW-1:0]     vb_addr,
    input  wire [31:0]       vb_q,
    output reg               vc_re,
    output reg  [AW-1:0]     vc_addr,
    input  wire [31:0]       vc_q,
    output reg               wrom_re,
    output reg  [AW-1:0]     wrom_addr,
    input  wire [WR*16-1:0]  wrom_q,
    output reg               crom_re,
    output reg  [AW-1:0]     crom_addr,
    input  wire [63:0]       crom_q,
    output reg               vm_we,
    output reg  [AW-1:0]     vm_waddr,
    output reg  [31:0]       vm_wdata,
    output reg               kv_we,
    output reg  [AW-1:0]     kv_waddr,
    output reg  [31:0]       kv_wdata,
    // to the vector reducer
    output wire              l_ov,
    output wire [31:0]       l_out,
    output wire [1:0]        l_red,
    output wire              l_redsq,
    output wire [AW-1:0]     l_raddr,
    output wire              l_last,
    output wire              retire,
    output wire              l_fault
);
    wire emit = emit0 && live;
    wire [AW-1:0] cura = cura0 + LANE * asi;
    wire [AW-1:0] curb = curb0 + LANE * bsi;
    wire [AW-1:0] curc = curc0 + LANE * csi;
    wire [AW-1:0] curd = curd0 + LANE * dsi;
'''

FOOTER = '''
    assign l_ov = ov;
    assign l_out = out;
    assign l_red = o_red;
    assign l_redsq = o_redsq;
    assign l_raddr = o_raddr;
    assign l_last = o_last;
    reg lf;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) lf <= 1'b0;
        else lf <= fa | fb_ | fad | f_exp | f_e1 | f_rcp | f_rsq | fmc | fmd;
    end
    assign l_fault = lf;
endmodule
'''


def generate():
    src = SRC.read_text()
    lp0 = src.index("    localparam integer LW")
    lp1 = src.index("    // -- issue loop")
    b0 = src.index("    // -- address cycle")
    b1 = src.index("    // -- reducer")
    body = src[lp0:lp1] + src[b0:b1]
    # ML (qwen-rtl-finish 2026-10-07): the S1 stage takes the element's tag and valid ML cycles late, so memories that
    # answer 1 + ML edges after the strobe (a far constant / weight ROM behind stations) are captured exactly
    for old, new in (("    always @(posedge clk) s1_tag <= e_tag;\n",
                      "    wire [FT-1:0] e_tag_m;\n"
                      "    ot_hdc_delay #(.W(FT), .D(ML)) u_ml_tag (.clk(clk), .rst_n(rst_n), .d(e_tag), .q(e_tag_m));\n"
                      "    always @(posedge clk) s1_tag <= e_tag_m;\n"),
                     ("    reg          e_v;\n", "    reg          e_v;\n    wire         e_v_m;\n"
                      "    ot_hdc_delay #(.W(1), .D(ML), .RESET(1)) u_ml_v (.clk(clk), .rst_n(rst_n), .d(e_v), .q(e_v_m));\n"),
                     ("else begin s1_v <= e_v; s2_v <= s1_v;", "else begin s1_v <= e_v_m; s2_v <= s1_v;")):
        if body.count(old) != 1:
            raise SystemExit(f"lane ML anchor: {old!r}")
        body = body.replace(old, new)
    return HEADER + body + FOOTER


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file is stale")
    args = ap.parse_args()
    text = generate()
    if args.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("current" if ok else f"STALE: {OUT.relative_to(ROOT)}")
        return 0 if ok else 1
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
