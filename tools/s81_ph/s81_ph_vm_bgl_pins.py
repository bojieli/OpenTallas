#!/usr/bin/env python3
"""el1013-s81-bgq28: N/S pin file of the one-bank leaf dsfd_vm_bgl28 = the dsfd_vm_bgr28 tile's N/S pins at the SAME x and
layer (physical/ref_tile_specs/ds_vm/dsfd_vm_bgr28_pins.tcl), so the 8-leaf parent dsfd_vm_bgq28h keeps the tile's N / S
abutment with the FE, the BE and the neighbouring tiles; only the N-face y moves to the leaf height.  W face (M4):
ck, rs, grp[1:0], bi[2:0] around mid-height.

    python3 tools/s81_ph/s81_ph_vm_bgl_pins.py H_UM   -> physical/ref_tile_specs/ds_vm/dsfd_vm_bgl28_pins.tcl"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
H = float(sys.argv[1])
src = (ROOT / 'physical/ref_tile_specs/ds_vm/dsfd_vm_bgr28_pins.tcl').read_text().splitlines()
out = [f'# dsfd_vm_bgl28 (el1013-s81-bgq28) leaf 345.6 x {H:g}: N/S pins = dsfd_vm_bgr28_pins.tcl x / layer (N face y {H:g}); '
       'W: ck rs grp bi on M4.  Generated by tools/s81_ph/s81_ph_vm_bgl_pins.py']
n = 0
for l in src:
    m = re.match(r'place_pin -pin_name \{((?:i_|f_|r_|o_)\w+\[\d+\])\} -layer (M\d) -location \{([\d.]+) ([\d.]+)\}(.*)', l)
    if not m:
        continue
    y = 0.0 if float(m.group(4)) == 0.0 else H
    out.append(f'place_pin -pin_name {{{m.group(1)}}} -layer {m.group(2)} -location {{{m.group(3)} {y:g}}}{m.group(5)}'); n += 1
assert n == 2 * 5441, n
y0 = round((H / 2 - 3.0) / 0.048) * 0.048 + 0.012     # M4 track (pitch 0.048), 1.008 um apart as the tile's W pins
for k, p in enumerate(['ck', 'rs', 'grp[0]', 'grp[1]', 'bi[0]', 'bi[1]', 'bi[2]']):
    out.append(f'place_pin -pin_name {{{p}}} -layer M4 -location {{0.0 {y0 + 1.008 * k:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary')
(ROOT / 'physical/ref_tile_specs/ds_vm/dsfd_vm_bgl28_pins.tcl').write_text('\n'.join(out) + '\n')
print('pins', n + 7, 'H', H)
