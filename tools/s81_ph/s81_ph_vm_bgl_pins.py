#!/usr/bin/env python3
"""el1013-s81-bgq28: N/S pin file of the one-bank leaf dsfd_vm_bgl28 = the dsfd_vm_bgr28 tile's N/S pins at the SAME x and
layer (physical/ref_tile_specs/ds_vm/dsfd_vm_bgr28_pins.tcl), so the 8-leaf parent dsfd_vm_bgq28h keeps the tile's N / S
abutment with the FE, the BE and the neighbouring tiles; only the N-face y moves to the leaf height.  W face (M4):
ck, rs, grp[1:0], bi[2:0] around mid-height.

    python3 tools/s81_ph/s81_ph_vm_bgl_pins.py H_UM   -> physical/ref_tile_specs/ds_vm/dsfd_vm_bgl28_pins.tcl"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
H = float(sys.argv[1])
src = (ROOT / 'physical/ref_tile_specs/ds_vm/dsfd_vm_bgr28_pins.tcl').read_text().splitlines()
out = [f'# dsfd_vm_bgl28 (el1013-s81-bgq28) leaf 345.6 x {H:g}: N/S pins = dsfd_vm_bgr28_pins.tcl x / layer (N face y {H:g}); '
       'W: ck rs grp bi on M4.  Generated by tools/s81_ph/s81_ph_vm_bgl_pins.py']
n = 0
for l in src:
    m = re.match(r'place_pin -pin_name \{((?:i_|f_|r_|o_)\w+\[\d+\])\} -layer (M\d) -location \{([\d.]+) ([\d.]+)\}(.*)', l)
    if not m:
        continue
    y = 0.0 if float(m.group(4)) == 0.0 else H
    out.append(f'place_pin -pin_name {{{m.group(1)}}} -layer {m.group(2)} -location {{{m.group(3)} {y:g}}}{m.group(5)}'); n += 1
assert n == 2 * 5441, n
# ---- REBALANCE (2026-10-13, leaf r1 FLOORPLAN_MARGIN: N / S M3 13.2 b/um over 100 um, limit 12).  The tile's file keeps
# M3 off the SRAM x span (its feed-throughs ran over the macros); in the leaf every N / S bit ends in a pin flop in the
# 24-um channel between the face and the SRAM, so M3 is usable along the whole face.  Pins keep their x ORDER and stay
# within MAXSHIFT um of the tile's x (die pin_align notes a jog above 20 um): walking the face W -> E, each pin takes the
# earlier free track of M5 (2-track pitch 0.096 = 10.4 b/um) or M3 (2 / 3 tracks alternating, 0.090 = 11.1 b/um) at or E
# of its tile x.  The S-face partner (f_* / o_*) takes the same x and layer.
MAXSHIFT = 21.0      # worst 20.5 um at the E end of the dense W third (26 b/um demanded, 21.5 placed); die pin_align notes > 20, refuses > 36
BACK = 0.0
rows = []
for l in out[1:]:
    m = re.match(r'place_pin -pin_name \{(\w+\[\d+\])\} -layer (M\d) -location \{([\d.]+) ([\d.]+)\}', l)
    rows.append((m.group(1), m.group(2), float(m.group(3)), float(m.group(4))))
north = sorted((r for r in rows if r[3] > 0), key=lambda r: r[2])
south = sorted((r for r in rows if r[3] == 0), key=lambda r: r[2])
assert len(north) == len(south) == 5441 and all(abs(a[2] - b[2]) < 1e-6 and a[1] == b[1] for a, b in zip(north, south))
P3, O3, P5, O5 = 0.036, 0.009, 0.048, 0.012
up = lambda x, p, o: round(o + -(-(x - o - 1e-9) // p) * p, 3)      # first track at or E of x
nx3 = nx5 = 0.0
k3 = 0
plan, worst = [], 0.0
for nm, lay, x, _ in north:
    c3, c5 = max(nx3, up(max(x - BACK, 2.4), P3, O3)), max(nx5, up(max(x - BACK, 2.4), P5, O5))
    if c5 < c3 or (abs(c5 - c3) < 1e-9 and lay == 'M5'):
        plan.append(('M5', c5)); nx5 = round(c5 + 2 * P5, 3)
    else:
        plan.append(('M3', c3)); nx3 = round(c3 + (2 + k3 % 2) * P3, 3); k3 += 1
    worst = max(worst, abs(plan[-1][1] - x))
assert worst <= MAXSHIFT and plan[-1][1] <= 343.2, (worst, plan[-1])
SZ = {'M3': '{0.018 0.144}', 'M5': '{0.024 0.192}'}
out = [out[0] + f'; M3 / M5 rebalanced along the whole face (max shift {worst:.2f} um vs the tile x)']
for (nn, _, _, _), (sn, _, _, _), (lay, x) in zip(north, south, plan):
    out.append(f'place_pin -pin_name {{{nn}}} -layer {lay} -location {{{x:.3f} {H:g}}} -pin_size {SZ[lay]} -force_to_die_boundary')
    out.append(f'place_pin -pin_name {{{sn}}} -layer {lay} -location {{{x:.3f} 0}} -pin_size {SZ[lay]} -force_to_die_boundary')
import bisect, collections
for lay in ('M3', 'M5'):
    xs = sorted(x for l, x in plan if l == lay)
    print(lay, len(xs), 'pins, worst 100-um window', max(bisect.bisect(xs, x + 100) - i for i, x in enumerate(xs)) / 100, 'b/um')
rng = collections.OrderedDict()
for (nn, _, _, _), (lay, x) in zip(north, plan):
    b = nn.split('[')[0]
    rng[b] = [min(rng.get(b, [x, x])[0], x), max(rng.get(b, [x, x])[1], x)]
print('max shift', round(worst, 2), 'um; ranges', {b: [round(v[0], 2), round(v[1], 2)] for b, v in rng.items()})
y0 = round((H / 2 - 3.0) / 0.048) * 0.048 + 0.012     # M4 track (pitch 0.048), 1.008 um apart as the tile's W pins
for k, p in enumerate(['ck', 'rs', 'grp[0]', 'grp[1]', 'bi[0]', 'bi[1]', 'bi[2]']):
    out.append(f'place_pin -pin_name {{{p}}} -layer M4 -location {{0.0 {y0 + 1.008 * k:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary')
(ROOT / 'physical/ref_tile_specs/ds_vm/dsfd_vm_bgl28_pins.tcl').write_text('\n'.join(out) + '\n')
print('pins', n + 7, 'H', H)

# ---- the parent dsfd_vm_bgq28h (coordinator 2026-10-13 12:45): 8 abutted leaves E of a STRAP-um W strap column (bank-index
# ties + clock spine buffers), outline (345.6 + STRAP) x 8 H; N / S pins = leaf 0's N pins / leaf 7's S pins at x + STRAP
import json
STRAP, NL, W = 21.6, 8, 345.6
PH = round(NL * H, 3)
pout = [f'# dsfd_vm_bgq28h (el1013-s81-bgq28) wires-only parent {W + STRAP:g} x {PH:g}: W strap column {STRAP:g} um, 8 leaves '
        f'at x {STRAP:g}; N / S pins = the leaf pins at x + {STRAP:g} (N face y {PH:g}); W: ck rs grp on M4 at mid-height.  '
        'Generated by tools/s81_ph/s81_ph_vm_bgl_pins.py']
for (nn, _, _, _), (sn, _, _, _), (lay, x) in zip(north, south, plan):
    pout.append(f'place_pin -pin_name {{{nn}}} -layer {lay} -location {{{x + STRAP:.3f} {PH:g}}} -pin_size {SZ[lay]} -force_to_die_boundary')
    pout.append(f'place_pin -pin_name {{{sn}}} -layer {lay} -location {{{x + STRAP:.3f} 0}} -pin_size {SZ[lay]} -force_to_die_boundary')
py0 = round((PH / 2 - 2.0) / 0.048) * 0.048 + 0.012
for k, p in enumerate(['ck', 'rs', 'grp[0]', 'grp[1]']):
    pout.append(f'place_pin -pin_name {{{p}}} -layer M4 -location {{0.0 {py0 + 1.008 * k:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary')
(ROOT / 'physical/ref_tile_specs/ds_vm/dsfd_vm_bgq28h_pins.tcl').write_text('\n'.join(pout) + '\n')
S2N = {'i_v': 'f_v', 'i_we': 'f_we', 'i_row': 'f_row', 'i_mask': 'f_mask', 'i_d': 'f_d', 'r_v': 'o_v', 'r_d': 'o_d', 'r_f': 'o_f', 'r_o': 'o_o'}
lp = ROOT / 'tools/ref_tile/specs/dsfd_vm_bgl28_a.json'
ls = json.loads(lp.read_text())
ls['outline'] = {'w': W, 'h': H}
ls['pin_ranges'] = {}
for b, (a, z) in rng.items():
    ls['pin_ranges'][b] = ls['pin_ranges'][S2N[b]] = [round(a - 0.05, 3), round(z + 0.05, 3)]
mh = 29.74                                                    # ot_sram_1r1w_512x128_m4_r2c2 height
ls['macros'][0]['at'] = [85.536, round(round((H - mh) / 2 / 2.16) * 2.16, 3)]
lp.write_text(json.dumps(ls, indent=1) + '\n')
cp = ROOT / 'tools/ref_tile/specs/dsfd_vm_bgq28h_a.json'
cs = json.loads(cp.read_text())
cs['outline'] = {'w': round(W + STRAP, 3), 'h': PH}
for k, ch in enumerate(cs['children']):
    ch['at'] = [STRAP, round((NL - 1 - k) * H, 3)]
cp.write_text(json.dumps(cs, indent=1) + '\n')
print('parent', W + STRAP, 'x', PH, 'leaf macro at', ls['macros'][0]['at'])
