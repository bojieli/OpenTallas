#!/usr/bin/env python3
"""Generate rtl/dsrom_sys/s81_ph/ctrl_c/dsfd_sp_gather_c_cl.sv: the gather master as a CLUSTER of hardened leaves
(s81-gather 2026-10-13).  Ports = dsfd_sp_gather_c's.  Lane table = results/rtl/s81_ph_20261006/gather/contract.json
inputs.lane_to_root (lane j of trunk r<half><tier> = root).  No logic at this level: wires only.

    python3 tools/s81_ph/gen_gather_cl.py [--check]
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "rtl/dsrom_sys/s81_ph/ctrl_c/dsfd_sp_gather_c_cl.sv"
TRUNKS = ["rW0", "rW1", "rW2", "rW3", "rW4", "rW5", "rE0", "rE1", "rE2", "rE3", "rE4", "rE5"]


def text():
    tab = json.loads((ROOT / "results/rtl/s81_ph_20261006/gather/contract.json").read_text())["inputs"]["lane_to_root"]
    lane = {}
    for t in TRUNKS:
        for j, r in enumerate(tab[t]):
            lane[r] = (t, j)
    assert sorted(lane) == list(range(128))
    L = []
    a = L.append
    a("`timescale 1ns/1ps")
    a("// GENERATED by tools/s81_ph/gen_gather_cl.py -- do not edit.")
    a("// " + "-" * 111)
    a("// dsfd_sp_gather_c as a CLUSTER (s81-gather 2026-10-13): 32 hardened root leaves (dsfd_gth_rw on the W half,")
    a("// dsfd_gth_re on the E half; 4 roots each, ot_s81ph_ret_root_s) in 8 columns x 4 rows + the control leaf")
    a("// dsfd_gth_ctl.  Same ports and function as the flat ctrl_c/dsfd_sp_gather_c.sv (128 x ot_s81ph_ret_root_p, 2.9 M")
    a("// flops); wires only at this level, every net leaf pin flop -> leaf pin flop or die pin <-> leaf pin flop.")
    a("//   column g (0..7, W to E) = capture bundle g = roots 16 g .. 16 g + 15; leaf k (0 = bottom row) holds roots")
    a("//   16 g + 4 k + s.  Row k of a half is fed from the half's outer face: lane slot 4 c + s, c = leaves passed")
    a("//   (W half c = g, E half c = 7 - g).  The column chain runs south: t_capture[53 (16 g + i) +: 53] = slot i of")
    a("//   the bottom leaf of column g.")
    a("// Row latency against the flat master, root r = 16 g + 4 k + s:  c + k - 2 cycles (-2 .. +4).  Control lane,")
    a("// t_xgo, c_done, c_st: identical cycles.  Capacity (contract): each root holds partials of at most 8 open")
    a("// (pos, row, nseg) at a time; a partial of a 9th raises the sticky fault (t_capture[6944]).")
    a("// " + "-" * 111)
    a("`ifndef S81PH_GTH_CL_NAME")
    a("`define S81PH_GTH_CL_NAME dsfd_sp_gather_c")
    a("`endif")
    a("module `S81PH_GTH_CL_NAME #(parameter integer ROOTD = 128, parameter integer MUT = 0) (")
    a("    input wire [0:0] ck, input wire [0:0] rst, input wire [0:0] ckv, input wire [0:0] rsv,")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    input wire [31:0] ck_l, // one compensated die clock pin per hardened root leaf; no parent tree")
    a("`endif")
    a("`ifdef S81PH_GTH_CONTROL_STRIP")
    a("    input wire [132:0] ck_r, // one compensated clock per actual CLOSED relay instance")
    a("`endif")
    a("    input wire [511:0] f_vm,")
    a("    output wire [6946:0] t_capture,")
    a("    input wire [691:0] rW0, input wire [760:0] rW1, input wire [760:0] rW2, input wire [760:0] rW3,")
    a("    input wire [760:0] rW4, input wire [691:0] rW5,")
    a("    input wire [691:0] rE0, input wire [760:0] rE1, input wire [760:0] rE2, input wire [760:0] rE3,")
    a("    input wire [760:0] rE4, input wire [691:0] rE5,")
    a("    input wire [84:0] c_cmd, output wire [8:0] c_done, output wire [1:0] c_st,")
    a("    input wire [11:0] f_cd,")
    a("    output wire [10:0] t_xgo")
    a(");")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    wire [31:0] leaf_ck = ck_l;")
    a("`else")
    a("    wire [31:0] leaf_ck = {32{ck[0]}}; // behavioural compatibility, never a physical cluster tree")
    a("`endif")
    a("    wire [69*128-1:0] ln;                 // lane of root r: {word 68, lane valid}")
    for r in range(128):
        t, j = lane[r]
        a(f"    assign ln[{69 * r} +: 69] = {t}[{69 * j} +: 69];")
    a("`ifdef S81PH_GTH_CL_MUT_LANE")
    a("    wire [69*128-1:0] lm = {ln[69*128-1:69*2], ln[0 +: 69], ln[69 +: 69]};   // MUTANT: lanes of roots 0 / 1 swapped")
    a("`else")
    a("    wire [69*128-1:0] lm = ln;")
    a("`endif")
    a("    wire [23:0] tst = {" + ", ".join(f"{t}[{69 * len(tab[t])} +: 2]" for t in reversed(TRUNKS)) + "};")
    a("    wire [7:0] rc; wire [15:0] cs; wire [162:0] tc;")
    a("`ifdef S81PH_GTH_CONTROL_STRIP")
    a("    wire [23:0] tst_ctl; wire [15:0] cs_ctl; wire [7:0] rc_ctl; wire [162:0] tc_ctl; wire [11:0] fcd_ctl; wire [7:0] roots_ready;")
    a("    dsfd_gth_strip u_strip (.ck_r(ck_r), .rst(rst[0]), .rsv(rsv[0]), .tst_i(tst), .cs_i(cs), .ready_i({rs_a[35],rs_a[30],rs_a[25],rs_a[20],rs_a[15],rs_a[10],rs_a[5],rs_a[0]}), .rc_i(rc_ctl), .tc_i(tc_ctl), .fcd_i(f_cd),")
    a("        .tst_o(tst_ctl), .cs_o(cs_ctl), .ready_o(roots_ready), .rc_o(rc), .tc_o(tc), .fcd_o(fcd_ctl));")
    a("`else")
    a("    wire [23:0] tst_ctl = tst; wire [15:0] cs_ctl = cs; wire [7:0] rc_ctl; wire [162:0] tc_ctl; wire [11:0] fcd_ctl = f_cd; wire [7:0] roots_ready = 8'hFF;")
    a("    assign rc = rc_ctl; assign tc = tc_ctl;")
    a("`endif")
    a("    // leaf (g, k) = index 4 g + k; plain buses (no hierarchical references)")
    a("    wire [828*32-1:0] lo_a;               // lanes passed on by leaf (g, k)")
    a("    wire [848*40-1:0] ch_a;               // [848 (5 g + k) +: 848] = chain out of leaf (g, k); k = 4: none")
    a("    wire [2*40-1:0] fs_a; wire [39:0] rs_a;")
    a("    genvar g, k;")
    a("    generate for (g = 0; g < 8; g = g + 1) begin : g_c")
    a("        assign ch_a[848*(5*g + 4) +: 848] = 848'd0; assign fs_a[2*(5*g + 4) +: 2] = 2'b00; assign rs_a[5*g + 4] = rc[g];")
    a("        for (k = 0; k < 4; k = k + 1) begin : g_k")
    a("            wire [1103:0] li;")
    a("            if (g == 0) begin : g_wo")
    a("                assign li = {lm[69*(48 + 4*k) +: 276], lm[69*(32 + 4*k) +: 276], lm[69*(16 + 4*k) +: 276], lm[69*(4*k) +: 276]};")
    a("            end else if (g == 7) begin : g_eo")
    a("                assign li = {lm[69*(64 + 4*k) +: 276], lm[69*(80 + 4*k) +: 276], lm[69*(96 + 4*k) +: 276], lm[69*(112 + 4*k) +: 276]};")
    a("            end else if (g < 4) begin : g_wi")
    a("                assign li = {276'd0, lo_a[828*(4*(g-1) + k) +: 828]};")
    a("            end else begin : g_ei")
    a("                assign li = {276'd0, lo_a[828*(4*(g+1) + k) +: 828]};")
    a("            end")
    a("            if (g < 4) begin : g_w")
    a("                dsfd_gth_rw u_l (.ck(leaf_ck[4*g+k]), .rs(rs_a[5*g + k + 1]), .rso(rs_a[5*g + k]), .li(li), .lo(lo_a[828*(4*g + k) +: 828]),")
    a("                    .ci(ch_a[848*(5*g + k + 1) +: 636]), .co(ch_a[848*(5*g + k) +: 848]), .fi(fs_a[2*(5*g + k + 1) +: 2]),")
    a("                    .fo(fs_a[2*(5*g + k) +: 2]));")
    a("            end else begin : g_e")
    a("                dsfd_gth_re u_l (.ck(leaf_ck[4*g+k]), .rs(rs_a[5*g + k + 1]), .rso(rs_a[5*g + k]), .li(li), .lo(lo_a[828*(4*g + k) +: 828]),")
    a("                    .ci(ch_a[848*(5*g + k + 1) +: 636]), .co(ch_a[848*(5*g + k) +: 848]), .fi(fs_a[2*(5*g + k + 1) +: 2]),")
    a("                    .fo(fs_a[2*(5*g + k) +: 2]));")
    a("            end")
    a("        end")
    a("        assign t_capture[848*g +: 848] = ch_a[848*(5*g) +: 848];")
    a("        assign cs[2*g +: 2] = fs_a[2*(5*g) +: 2];")
    a("    end endgenerate")
    a("`ifdef S81PH_GTH_HARD")
    a("    dsfd_gth_ctl u_ctl (")
    a("`else")
    a("    dsfd_gth_ctl #(.MUT(MUT)) u_ctl (")
    a("`endif")
    a("        .ck(ck[0]), .rst(rst[0]), .ckv(ckv[0]), .rsv(rsv[0]), .f_vm(f_vm[159:0]), .tst(tst_ctl), .cs(cs_ctl), .roots_ready(roots_ready),")
    a("        .c_cmd(c_cmd), .c_done(c_done), .c_st(c_st), .f_cd(fcd_ctl), .t_xgo(t_xgo), .tc(tc_ctl), .rc(rc_ctl));")
    a("    assign t_capture[6946:6784] = tc;")
    a("endmodule")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = text()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == t
        print("gen_gather_cl: " + ("current" if ok else "STALE"))
        return 0 if ok else 1
    OUT.write_text(t)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
