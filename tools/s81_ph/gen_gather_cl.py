#!/usr/bin/env python3
"""Generate rtl/dsrom_sys/s81_ph/ctrl_c/dsfd_sp_gather_c_cl.sv: the gather master as a CLUSTER of hardened leaves
(s81-gather 2026-10-13).  Ports = dsfd_sp_gather_c's.  Lane table = results/rtl/s81_ph_20261006/gather/contract.json
inputs.lane_to_root (lane j of trunk r<half><tier> = root).  No logic at this level: wires only.

    python3 tools/s81_ph/gen_gather_cl.py [--check]
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "rtl/dsrom_sys/s81_ph/ctrl_c/dsfd_sp_gather_c_cl.sv"
TRUNKS = ["rW0", "rW1", "rW2", "rW3", "rW4", "rW5", "rE0", "rE1", "rE2", "rE3", "rE4", "rE5"]


def text():
    tab = json.loads((ROOT / "results/rtl/s81_ph_20261006/gather/contract.json").read_text())["inputs"]["lane_to_root"]
    lane = {}
    for t in TRUNKS:
        for j, r in enumerate(tab[t]):
            lane[r] = (t, j)
    assert sorted(lane) == list(range(128))
    L = []
    a = L.append
    a("`timescale 1ns/1ps")
    a("// GENERATED by tools/s81_ph/gen_gather_cl.py -- do not edit.")
    a("// " + "-" * 111)
    a("// dsfd_sp_gather_c as a CLUSTER (s81-gather v4 'direct', 2026-10-14): 32 hardened 4-root leaves (dsfd_gth_rw on the")
    a("// W half, dsfd_gth_re on the E half; ot_s81ph_ret_root_s) in 8 columns x 4 rows, 48 relay tiles in the channels and")
    a("// the control leaf dsfd_gth_ctl.  Same ports and function as the flat ctrl_c/dsfd_sp_gather_c.sv (128 flop roots);")
    a("// wires only at this level: every net is leaf / relay pin flop -> leaf / relay pin flop, or die pin <-> pin flop.")
    a("//   column g (0..7, W to E) = capture bundle g = roots 16 g .. 16 g + 15; leaf k (0 = bottom row) holds roots")
    a("//   16 g + 4 k + s and delivers them straight to t_capture[848 g + 212 k +: 212] (k 2: one relay, k 3: two).")
    a("//   A leaf takes ONLY its own 4 lanes from its half's outer face (c = leaves from that face: c 2 one relay, c 3")
    a("//   two).  No lane or result passes through a leaf (v3 chained 828 + 636 bits through every leaf: GRT-0116).")
    a("// Row latency against the flat master, root r = 16 g + 4 k + s:  R(c) + R(k) - 2 cycles, R = (0, 0, 1, 2)")
    a("// (-2 .. +2).  Control lane, t_xgo, c_done, c_st: identical cycles.  Capacity (contract): each root holds partials")
    a("// of at most 8 open (pos, row, nseg) at a time; a partial of a 9th raises the sticky fault (t_capture[6944]).")
    a("// " + "-" * 111)
    a("`ifndef S81PH_GTH_CL_NAME")
    a("`define S81PH_GTH_CL_NAME dsfd_sp_gather_c")
    a("`endif")
    a("module `S81PH_GTH_CL_NAME #(parameter integer ROOTD = 128, parameter integer MUT = 0) (")
    a("    input wire [0:0] ck, input wire [0:0] rst, input wire [0:0] ckv, input wire [0:0] rsv,")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    input wire [31:0] ck_l, // one compensated die clock pin per hardened root leaf; no parent tree")
    a("`endif")
    a("`ifdef S81PH_GTH_CONTROL_STRIP")
    a("    input wire [132:0] ck_r, // one compensated clock per actual CLOSED relay instance")
    a("`endif")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    input wire [47:0] ck_q,  // one compensated die clock pin per lane / result relay (gather v4 direct)")
    a("`endif")
    a("    input wire [511:0] f_vm,")
    a("    output wire [6946:0] t_capture,")
    a("    input wire [691:0] rW0, input wire [760:0] rW1, input wire [760:0] rW2, input wire [760:0] rW3,")
    a("    input wire [760:0] rW4, input wire [691:0] rW5,")
    a("    input wire [691:0] rE0, input wire [760:0] rE1, input wire [760:0] rE2, input wire [760:0] rE3,")
    a("    input wire [760:0] rE4, input wire [691:0] rE5,")
    a("    input wire [84:0] c_cmd, output wire [8:0] c_done, output wire [1:0] c_st,")
    a("    input wire [11:0] f_cd,")
    a("    output wire [10:0] t_xgo")
    a(");")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    wire [31:0] leaf_ck = ck_l;")
    a("`else")
    a("    wire [31:0] leaf_ck = {32{ck[0]}}; // behavioural compatibility, never a physical cluster tree")
    a("`endif")
    a("    wire [69*128-1:0] ln;                 // lane of root r: {word 68, lane valid}")
    for r in range(128):
        t, j = lane[r]
        a(f"    assign ln[{69 * r} +: 69] = {t}[{69 * j} +: 69];")
    a("`ifdef S81PH_GTH_CL_MUT_LANE")
    a("    wire [69*128-1:0] lm = {ln[69*128-1:69*2], ln[0 +: 69], ln[69 +: 69]};   // MUTANT: lanes of roots 0 / 1 swapped")
    a("`else")
    a("    wire [69*128-1:0] lm = ln;")
    a("`endif")
    a("    wire [23:0] tst = {" + ", ".join(f"{t}[{69 * len(tab[t])} +: 2]" for t in reversed(TRUNKS)) + "};")
    a("    wire [7:0] rc; wire [63:0] cs; wire [162:0] tc;")
    a("    wire [39:0] rs_a;                    // [5 g + k] = rso of leaf (g, k); [5 g + 4] = column reset copy rc[g]")
    a("`ifdef S81PH_GTH_CONTROL_STRIP")
    a("    wire [23:0] tst_ctl; wire [63:0] cs_ctl; wire [7:0] rc_ctl; wire [162:0] tc_ctl; wire [11:0] fcd_ctl; wire [7:0] roots_ready;")
    a("    dsfd_gth_strip u_strip (.ck_r(ck_r), .rst(rst[0]), .rsv(rsv[0]), .tst_i(tst), .cs_i(cs), .ready_i({rs_a[35],rs_a[30],rs_a[25],rs_a[20],rs_a[15],rs_a[10],rs_a[5],rs_a[0]}), .rc_i(rc_ctl), .tc_i(tc_ctl), .fcd_i(f_cd),")
    a("        .tst_o(tst_ctl), .cs_o(cs_ctl), .ready_o(roots_ready), .rc_o(rc), .tc_o(tc), .fcd_o(fcd_ctl));")
    a("`else")
    a("    wire [23:0] tst_ctl = tst; wire [63:0] cs_ctl = cs; wire [7:0] rc_ctl; wire [162:0] tc_ctl; wire [11:0] fcd_ctl = f_cd; wire [7:0] roots_ready = 8'hFF;")
    a("    assign rc = rc_ctl; assign tc = tc_ctl;")
    a("`endif")
    a("`ifdef S81PH_GTH_DIE_CLOCKS")
    a("    wire [47:0] rq_ck = ck_q;")
    a("`else")
    a("    wire [47:0] rq_ck = {48{ck[0]}}; // behavioural compatibility, never a physical cluster tree")
    a("`endif")
    a("    // ---- lanes: leaf (g, k) takes lanes B + 16 c + 4 k .. + 3 (B = 0 W half / 64 E half, c = leaves from the outer")
    a("    //      face: g on W, 7 - g on E).  c 0 / 1 direct, c 2 one relay (channel c0|c1), c 3 two relays (c0|c1, c1|c2).")
    a("    // ---- results: leaf (g, k) -> t_capture[848 g + 212 k +: 212]; its st -> cs[8 g + 2 k +: 2] ({busy, fault}).")
    a("    //      k 0 / 1 direct, k 2 one relay (row channel 0|1), k 3 two relays (row channels 1|2, 0|1).")
    q = 0
    for h, (hn, m) in enumerate((("W", "dsfd_rly_276_WE"), ("E", "dsfd_rly_276_EW"))):
        for k in range(4):
            for c in range(4):
                base = 64 * h + 16 * c + 4 * k
                src = f"lm[{69 * base} +: 276]"
                nm = f"ln_{hn}{k}_{c}"
                a(f"    wire [275:0] {nm}_0 = {src};")
                for st in range((0, 0, 1, 2)[c]):
                    a(f"    wire [275:0] {nm}_{st + 1};")
                    a(f"    {m} u_rq_{hn}{k}_{c}_{st} (.ck(rq_ck[{q}]), .rs(rst[0]), .i({nm}_{st}), .o({nm}_{st + 1}));")
                    q += 1
    for g in range(8):
        for k in range(4):
            nm = f"rt_{g}_{k}"
            a(f"    wire [213:0] {nm}_0;")
            for st in range((0, 0, 1, 2)[k]):
                a(f"    wire [213:0] {nm}_{st + 1};")
                a(f"    dsfd_rly_214_NS u_rq_c{g}_{k}_{st} (.ck(rq_ck[{q}]), .rs(rst[0]), .i({nm}_{st}), .o({nm}_{st + 1}));")
                q += 1
            n = (0, 0, 1, 2)[k]
            a(f"    assign t_capture[{848 * g + 212 * k} +: 212] = {nm}_{n}[211:0]; assign cs[{8 * g + 2 * k} +: 2] = {nm}_{n}[213:212];")
    assert q == 48, q
    for g in range(8):
        hn = "W" if g < 4 else "E"
        c = g if g < 4 else 7 - g
        a(f"    assign rs_a[{5 * g + 4}] = rc[{g}];")
        for k in range(4):
            a(f"    wire [211:0] co_{g}_{k}; wire [1:0] st_{g}_{k}; assign rt_{g}_{k}_0 = {{st_{g}_{k}, co_{g}_{k}}};")
            a(f"    {'dsfd_gth_rw' if g < 4 else 'dsfd_gth_re'} u_l_{g}_{k} (.ck(leaf_ck[{4 * g + k}]), .rs(rs_a[{5 * g + k + 1}]), "
              f".rso(rs_a[{5 * g + k}]), .li(ln_{hn}{k}_{c}_{(0, 0, 1, 2)[c]}), .co(co_{g}_{k}), .st(st_{g}_{k}));")
    a("`ifdef S81PH_GTH_HARD")
    a("    dsfd_gth_ctl u_ctl (")
    a("`else")
    a("    dsfd_gth_ctl #(.MUT(MUT)) u_ctl (")
    a("`endif")
    a("        .ck(ck[0]), .rst(rst[0]), .ckv(ckv[0]), .rsv(rsv[0]), .f_vm(f_vm[159:0]), .tst(tst_ctl), .cs(cs_ctl), .roots_ready(roots_ready),")
    a("        .c_cmd(c_cmd), .c_done(c_done), .c_st(c_st), .f_cd(fcd_ctl), .t_xgo(t_xgo), .tc(tc_ctl), .rc(rc_ctl));")
    a("    assign t_capture[6946:6784] = tc;")
    a("endmodule")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = text()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == t
        print("gen_gather_cl: " + ("current" if ok else "STALE"))
        return 0 if ok else 1
    OUT.write_text(t)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
