#!/usr/bin/env python3
"""CLAUDE S81-PH: write rtl/dsrom_sys/s81_ph/dsfd_ctrl.sv, the die-named top of the S81 HBM controller boundary.

phy[i] is the PHY abstract pin dfi[i] (tools/dsrom_s81_fulldie.py real_ports_r8: PHY pins sorted by x, recorded in
results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json); a PHY input is driven here, a PHY output is read here.
Ports follow the CLAUDE S81-PH ctrl contract (OT_S81_PH_CTRL generator option)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NPC, AW, TW = 32, 30, 17
PHY_IN = {'clk', 'rst_n', 'k_v', 'k_addr', 'k_len', 'k_tag', 'k_we', 'k_wdata', 'k_wstrb', 'kr_rdy', 'w_v', 'w_addr',
          'w_len', 'w_tag', 'wr_rdy'}
WID = dict(k_v=1, k_rdy=1, k_addr=AW, k_len=4, k_tag=TW, k_we=1, k_wdata=256, k_wstrb=32, k_wr_done=1, kr_v=1, kr_rdy=1,
           kr_tag=TW, kr_beat=4, kr_data=256)


def main():
    dfi = json.loads((ROOT / 'results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json').read_text())
    assert len(dfi) == 22238
    L = ['`timescale 1ns/1ps',
         '// GENERATED by tools/s81_ph/gen_ctrl_top.py (CLAUDE S81-PH): dsfd_ctrl, the S81 HBM controller boundary.',
         '// Contract results/rtl/s81_ph_20261006/ctrl/contract.json; per-PC channel ot_s81ph_ctrl_pc.',
         '// rd = {kr_v 32 | kr_beat 32x4 | kr_tag 32x17 | kr_data 32x256} (stream); rq = 32 x {wdata 256, wstrb 32, tag 17,',
         '// len 4, addr 30, we, v}; rk / wd = per-PC credit / write-done pulses; st = {fault, live}.',
         '// The PHY W port (QE weight region) is unused on the S81 die (weights live in the ROM field): tied off.',
         '`default_nettype none',
         'module dsfd_ctrl (',
         # 1-bit die ports are [0:0] buses, as the generator's ports.svh declares them (pins ckh[0], cks[0], rst[0])
         '    input  wire [0:0] ckh,', '    input  wire [0:0] cks,', '    input  wire [0:0] rst,',
         '    inout  wire [22237:0] phy,',
         f'    output wire [{8864 + NPC - 1}:0] rd,',
         f'    input  wire [{NPC * 341 - 1}:0] rq,',
         f'    output wire [{NPC - 1}:0] rk,', f'    output wire [{NPC - 1}:0] wd,', '    output reg  [1:0] st', ');']
    L += ['    // v2 (redesign pass): composed of 32 per-PC tiles dsfd_ctrl_pc + the centre tile dsfd_ctrl_ctr (resets, PHY',
          '    // reset, status); the unused PHY W port inputs are tie cells of the composition',
          '    wire [0:0] phy_rst_q;']
    for n, w in WID.items():
        L.append(f'    wire [{NPC * w - 1}:0] p_{n};')
    L += ['    wire p_k_oor, p_w_oor;']
    # PHY binding
    for i, nm in enumerate(dfi):
        base, idx = re.match(r'^(\w+)(?:\[(\d+)\])?$', nm).groups()
        b = f'[{idx}]' if idx is not None else ''
        if base == 'clk':
            L.append(f'    assign phy[{i}] = ckh;')
        elif base == 'rst_n':
            L.append(f'    assign phy[{i}] = phy_rst_q;')
        elif base in PHY_IN:
            src = f'p_{base}{b}' if base in WID else "1'b0"
            L.append(f'    assign phy[{i}] = {src};')
        elif base in WID:
            L.append(f'    assign p_{base}{b} = phy[{i}];')
        elif base == 'k_oor':
            L.append(f'    assign p_k_oor = phy[{i}];')
        elif base == 'w_oor':
            L.append(f'    assign p_w_oor = phy[{i}];')
        # other PHY outputs (W port responses, refresh / read counters): not used by the S81 die
    L += ['    wire [31:0] rv;', '    genvar g;',
          '    // status chains {fault, live}: PC 0 -> PC 15 (W faces) and PC 31 -> PC 16 (E faces), one register per tile',
          "    // input; the unused face of every tile is tied {0, 1} (neutral)",
          '    wire [1:0] co [0:31];',
          '    generate for (g = 0; g < 32; g = g + 1) begin : g_pc',
          '        wire [1:0] ciw, cie;',
          "        if (g == 0) begin : g_w0 assign ciw = 2'b01; assign cie = 2'b01; end",
          "        else if (g < 16) begin : g_w assign ciw = co[g - 1]; assign cie = 2'b01; end",
          "        else if (g == 31) begin : g_e0 assign ciw = 2'b01; assign cie = 2'b01; end",
          "        else begin : g_e assign ciw = 2'b01; assign cie = co[g + 1]; end",
          '        dsfd_ctrl_pc u_pc (.cks(cks), .ckh(ckh), .rst(rst), .ci_w(ciw), .ci_e(cie), .co_w(co[g]), .co_e(),',
          '            .rq(rq[g*341 +: 341]), .rk(rk[g]), .rv(rv[g]), .r_data(rd[g*256 +: 256]), .r_tag(rd[8192 + g*17 +: 17]),',
          '            .r_beat(rd[8736 + g*4 +: 4]), .wd(wd[g]),',
          '            .k_v(p_k_v[g]), .k_rdy(p_k_rdy[g]), .k_addr(p_k_addr[g*30 +: 30]), .k_len(p_k_len[g*4 +: 4]),',
          '            .k_tag(p_k_tag[g*17 +: 17]), .k_we(p_k_we[g]), .k_wdata(p_k_wdata[g*256 +: 256]),',
          '            .k_wstrb(p_k_wstrb[g*32 +: 32]), .k_wr_done(p_k_wr_done[g]), .kr_v(p_kr_v[g]), .kr_rdy(p_kr_rdy[g]),',
          '            .kr_tag(p_kr_tag[g*17 +: 17]), .kr_beat(p_kr_beat[g*4 +: 4]), .kr_data(p_kr_data[g*256 +: 256]));',
          '    end endgenerate',
          '    assign rd[8895:8864] = rv;',
          '    wire [1:0] st_w;',
          '    dsfd_ctrl_ctr u_ctr (.cks(cks), .ckh(ckh), .rst(rst), .co_w(co[15]), .co_e(co[16]), .k_oor(p_k_oor), .w_oor(p_w_oor),',
          '        .phy_rst_n(phy_rst_q), .st(st_w));',
          '    always @* st = st_w;',
          'endmodule', '`default_nettype wire', '']
    (ROOT / 'rtl/dsrom_sys/s81_ph/dsfd_ctrl.sv').write_text('\n'.join(L))



def tb_bind():
    """rtl/dsrom_sys/s81_ph/test/ot_s81ph_phy_on_bus.sv: the functional PHY model on the 22238-b phy bundle (bench)."""
    dfi = json.loads((ROOT / 'results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json').read_text())
    W = dict(WID, w_v=1, w_rdy=1, w_addr=30, w_len=6, w_tag=10, w_room=8, wr_v=8, wr_rdy=8, wr_tag=80, wr_beat=40,
             wr_data=2048, k_oor=1, w_oor=1, refreshes=64, w_reads=32)
    L = ['`timescale 1ns/1ps', '// GENERATED by tools/s81_ph/gen_ctrl_top.py: bench-only binder of the functional PHY model',
         'module ot_s81ph_phy_on_bus #(parameter integer CLK_PS = 1000, parameter integer K_MEM = 1 << 18) (inout wire [22237:0] phy);']
    for n in ('k_v', 'k_rdy', 'k_addr', 'k_len', 'k_tag', 'k_we', 'k_wdata', 'k_wstrb', 'k_wr_done', 'kr_v', 'kr_rdy',
              'kr_tag', 'kr_beat', 'kr_data'):
        L.append(f'    wire [{NPC * WID[n] - 1}:0] {n};')
    L.append('    wire clk, rst_n, k_oor, w_oor;')
    for i, nm in enumerate(dfi):
        base, idx = re.match(r'^(\w+)(?:\[(\d+)\])?$', nm).groups()
        b = f'[{idx}]' if idx is not None else ''
        if base in ('clk', 'rst_n') or (base in PHY_IN and base in WID):
            L.append(f'    assign {base}{b} = phy[{i}];')
        elif base in WID or base in ('k_oor', 'w_oor'):
            L.append(f'    assign phy[{i}] = {base}{b};')
        elif base not in PHY_IN:
            L.append(f"    assign phy[{i}] = 1'b0;")
    L += ['    ot_chip_v41x_hbm3e_phy #(.NPC(32), .K_AW(30), .K_MEM(K_MEM), .W_PORT(0), .KTAGW(17), .CLK_PS(CLK_PS)) u_phy (',
          '        .clk(clk), .rst_n(rst_n), .k_v(k_v), .k_rdy(k_rdy), .k_addr(k_addr), .k_len(k_len), .k_tag(k_tag), .k_we(k_we),',
          '        .k_wdata(k_wdata), .k_wstrb(k_wstrb), .k_wr_done(k_wr_done), .kr_v(kr_v), .kr_rdy(kr_rdy), .kr_tag(kr_tag),',
          '        .kr_beat(kr_beat), .kr_data(kr_data), .w_v(1\'b0), .w_rdy(), .w_addr(24\'d0), .w_len(6\'d0), .w_tag(10\'d0),',
          '        .w_room(), .wr_v(), .wr_rdy(8\'d0), .wr_tag(), .wr_beat(), .wr_data(), .k_oor(k_oor), .w_oor(w_oor),',
          '        .refreshes(), .w_reads());', 'endmodule', '']
    (ROOT / 'rtl/dsrom_sys/s81_ph/test/ot_s81ph_phy_on_bus.sv').write_text('\n'.join(L))


if __name__ == '__main__':
    main()
    tb_bind()
