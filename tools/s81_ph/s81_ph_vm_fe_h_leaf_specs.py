def v(name, lo, hi=None):
    """pin names of bus bits [lo, hi) (hi None: one bit)"""
    return [f'{name}[{i}]' for i in range(lo, lo + 1 if hi is None else hi)]


def tracks(layer, lo, hi):
    off, p = TRK[layer]; out = []; k = int((lo - off) / p) + 1
    while off + p * k <= hi + 1e-9:
        x = round(off + p * k, 3)
        if layer == 'M4' or not (0.18 <= x % 5.4 <= 0.74):
            out.append(x)
        k += 1
    return out


def spread(names, layers, lo, hi):
    """names in order along [lo, hi], alternating layers, each on a free track nearest its uniform position, >= 2 tracks apart"""
    n = len(names); per = {L: tracks(L, lo, hi)[::2] for L in layers}; nxt = {L: 0 for L in layers}; out = []
    for i, nm in enumerate(names):
        L = layers[i % len(layers)]; t = per[L]; want = lo + (hi - lo) * (i + 0.5) / n; j = nxt[L]
        while j + 1 < len(t) and abs(t[j + 1] - want) <= abs(t[j] - want):
            j += 1
        left = (n - i + len(layers) - 1) // len(layers)
        j = min(j, len(t) - left)
        assert j >= nxt[L], f'out of {L} tracks in [{lo}, {hi}] at {nm} ({n} pins)'
        out.append((nm, L, t[j])); nxt[L] = j + 1
    return out


def plan(w, h, faces):
    """faces {face: [(names, lo, hi) | names]} -> [(face, name, layer, pos)]; a face's groups share it in proportion to their bits"""
    out = []
    for f, groups in faces.items():
        L = h if f in 'WE' else w; lay = ['M4'] if f in 'WE' else ['M5', 'M3']
        groups = [g if isinstance(g, tuple) else (g, None, None) for g in groups]
        free = [g for g in groups if g[1] is None]; tot = sum(len(g[0]) for g in free)
        fixed = [(g[1], g[2]) for g in groups if g[1] is not None]
        lo0 = max([MARGIN] + [b for a, b in fixed if a <= MARGIN + 1e-6]); a = lo0
        for names, lo, hi in groups:
            if lo is None:
                b = a + (L - MARGIN - lo0) * len(names) / tot; lo, hi, a = a, b, b
            out += [(f, *p) for p in spread(names, lay, lo, hi)]
    seen = set()
    for f, nm, lay, pos in out:
        assert (f, lay, pos) not in seen, (nm, f, lay, pos); seen.add((f, lay, pos))
    return out


def emit(pins, w, h, title):
    L = [f'# {title}', '# generated by tools/s81_ph/s81_ph_vm_fe_h_leaf_specs.py -- do not edit']
    for f, nm, lay, pos in pins:
        if f in 'NS':
            size = ' -pin_size {.024 .192}' if lay == 'M5' else ''
            L.append(f'place_pin -pin_name {{{nm}}} -layer {lay} -location {{{pos:.3f} {h if f == "N" else 0.0:.3f}}}{size} -force_to_die_boundary')
        else:
            L.append(f'place_pin -pin_name {{{nm}}} -layer M4 -location {{{0.0 if f == "W" else w:.3f} {pos:.3f}}} -pin_size {{.192 .024}} -force_to_die_boundary')
    return '\n'.join(L) + '\n'


def clt_pins():
    """dsfd_vm_clt at M5 (S3): f_c in bit order on N, the capture word in bit order on S, both on M5 + M3 CLEAR of the kit's M5
    PG stripes.  The closed clt8a view had every pin on M5 at a 0.096 pitch (its PG was M6): an M5-capped tile cannot keep
    that row (the stripes at 0.300 / 0.492 + 5.4 k would short 2 pins in 56), so the FE N-face f_cap pins follow THIS plan
    (slot statement in el1011-s81die.log)."""
    w, h = 80.64, 230.04
    return plan(w, h, {'N': [v('f_c', 0, 832)],
                       'S': [['w_v'] + v('w_row', 0, 14) + v('w_m', 0, 16) + v('w_d', 0, 512) + v('flt', 0, 4) + ['sok', 'rn', 'ck'] + v('gid', 0, 4)]})


def relay_groups(d, tags=None):
    """(in names, out names) of a bundle relay master: data words first (port order), then every port's control bits + valid"""
    data, ctl = [], []
    for j, (off, n, df) in enumerate(d):
        if df: data += list(range(off, off + 128))
        ctl += list(range(off + 128 * df, off + n)) + [('v', j)]
    order = data + (tags or []) + ctl
    f = lambda p: [(f'{p}_v[{k[1]}]' if isinstance(k, tuple) else f'{p}[{k}]') for k in order]
    return f('i'), f('o')


