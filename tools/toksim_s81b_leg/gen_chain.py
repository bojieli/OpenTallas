#!/usr/bin/env python3
"""TOKSIM-S81B/LEG (10-19): emit the on-die ring-line leg chain of the S81 MU release die (GEN mu4c 19bf4121e die.v)
as one bench module, link by link EXACTLY as die.v instantiates it: for every xring link xr{E,W}_<c><S|N>_l<0..3>
the hop-0 clock gate (ICGx4 on the source slice's ck_line), the dsfd_dvrlyh_276_<dir> half-cycle relay stations (master
and count from die.v) and the dsfd_dvland_276 landing with die.v's strap k.  The 16 slice ring stops are ot_s81sl_rstop
(the slice's ri_*/ro_* pins go straight to ot_s81sl_xg u_r in ot_s81sl_slice; ck_line = clk).
usage: gen_chain.py <die.v> <out.sv> <out.json>"""
import json, re, sys
from collections import defaultdict

die, out_sv, out_js = sys.argv[1:4]
txt = open(die).read()
L = defaultdict(lambda: {"st": [], "land": None, "k": None, "icg": None})
for m in re.finditer(r'^\s*(dsfd_dvrlyh_\w+) st_(xr[EW]_\d[SN]_l\d)_(\d+) ', txt, re.M):
    L[m.group(2)]["st"].append((int(m.group(3)), m.group(1)))
for m in re.finditer(r'^\s*(dsfd_dvland_\w+) ld_(xr[EW]_\d[SN]_l\d) \((.*?)\);', txt, re.M):
    L[m.group(2)]["land"] = m.group(1)
    L[m.group(2)]["k"] = int(re.search(r"\.k\(3'd(\d)\)", m.group(3)).group(1))
for m in re.finditer(r'ICGx4_ASAP7_75t_R fwd_(xr[EW]_\d[SN]_l\d) \(\.CLK\((\S+?)\),', txt):
    L[m.group(1)]["icg"] = m.group(2)
assert len(L) == 2 * 2 * 7 * 4, len(L)
# slice straps (sid) from die.v
sid = {}
for m in re.finditer(r'^\s*(ot_s81sl_slice\w*)[^\n]*? u_s_(\d)([SN]) \(.*?\.sid\(4\'d(\d+)\)', txt, re.M):
    sid[(int(m.group(2)), m.group(3))] = int(m.group(4))
assert len(sid) == 16, sid
o = []
o.append("`timescale 1ns/1ps")
o.append("// GENERATED by tools/toksim_s81b_leg/gen_chain.py from GEN mu4c die.v (19bf4121e bind_main): do not edit.")
o.append("module toksim_leg_icg (input wire CLK, input wire ENA, output wire GCLK);  // ICGx4 behaviour (std cell, no RTL)")
o.append("    reg en_l = 1'b0;")
o.append("    always @(CLK or ENA) if (!CLK) en_l = ENA;")
o.append("    assign GCLK = CLK & en_l;")
o.append("endmodule")
o.append("module toksim_leg_chain (")
o.append("    input wire clk, input wire rs,")
o.append("    input  wire [2*8*1104-1:0] ci_b, input wire [2*8*3-1:0] ci_dir,          // per stop [t*8+c]")
o.append("    input  wire [2*1104-1:0] ext_w, input wire [2*1104-1:0] ext_e,            // outer ports: stop 0 ri_w / stop 7 ri_e per tier")
o.append("    output wire [2*8*1104-1:0] ri_w_o, output wire [2*8*1104-1:0] ri_e_o,     // every stop's ring input pins")
o.append("    output wire [2*8*1104-1:0] ro_e_o, output wire [2*8*1104-1:0] ro_w_o,")
o.append("    output wire [2*8-1:0] dl_ev_o, output wire [2*8*1104-1:0] dl_e_o, output wire [2*8-1:0] dl_wv_o, output wire [2*8*1104-1:0] dl_w_o,")
o.append("    output wire [2*8-1:0] sfault, output wire [2*7*2*4-1:0] lfault);")
meta = {"links": {}, "sid": {f"{c}{t}": v for (c, t), v in sid.items()}}
for ti, t in enumerate("SN"):
    for c in range(8):
        n = ti * 8 + c
        o.append(f"    wire [1103:0] riw_{c}{t}, rie_{c}{t}, roe_{c}{t}, row_{c}{t};")
    for c in range(8):
        n = ti * 8 + c
        riw = f"ext_w[{ti}*1104 +: 1104]" if c == 0 else f"riw_{c}{t}"
        rie = f"ext_e[{ti}*1104 +: 1104]" if c == 7 else f"rie_{c}{t}"
        if c == 0: o.append(f"    assign riw_0{t} = ext_w[{ti}*1104 +: 1104];")
        if c == 7: o.append(f"    assign rie_7{t} = ext_e[{ti}*1104 +: 1104];")
        o.append(f"    ot_s81sl_rstop u_r_{c}{t} (.clk(clk), .rst_n(rs), .sid(4'd{sid[(c, t)]}), .ri_w(riw_{c}{t}), .ri_e(rie_{c}{t}),"
                 f" .ro_e(roe_{c}{t}), .ro_w(row_{c}{t}), .vi(276'd0), .vo(), .xf_v(5'd0), .xf_s(5'd0), .xf({{5*276{{1'b0}}}}),"
                 f" .nx_wi(), .nx_ei(), .nx_eo(173'd0), .nx_wo(173'd0), .g_v(), .g_fam(), .g_idx(), .g_d(),"
                 f" .dl_ev(dl_ev_o[{n}]), .dl_e(dl_e_o[{n}*1104 +: 1104]), .dl_wv(dl_wv_o[{n}]), .dl_w(dl_w_o[{n}*1104 +: 1104]),"
                 f" .dl_vv(), .dl_vb(), .ci_dir(ci_dir[{n}*3 +: 3]), .ci_b(ci_b[{n}*1104 +: 1104]), .fault(sfault[{n}]));")
        o.append(f"    assign ri_w_o[{n}*1104 +: 1104] = riw_{c}{t}; assign ri_e_o[{n}*1104 +: 1104] = rie_{c}{t};"
                 f" assign ro_e_o[{n}*1104 +: 1104] = roe_{c}{t}; assign ro_w_o[{n}*1104 +: 1104] = row_{c}{t};")
    for c in range(7):
        for d in "EW":
            for l in range(4):
                nm = f"xr{d}_{c}{t}_l{l}"
                x = L[nm]
                st = [m for _, m in sorted(x["st"])]
                src = f"roe_{c}{t}" if d == "E" else f"row_{c+1}{t}"
                dst = f"riw_{c+1}{t}" if d == "E" else f"rie_{c}{t}"
                fi = ((ti * 7 + c) * 2 + (0 if d == "E" else 1)) * 4 + l
                ns = len(st)
                o.append(f"    wire [{ns}:0] f_{nm}; wire [275:0] d_{nm} [0:{ns}];")
                o.append(f"    toksim_leg_icg g_{nm} (.CLK(clk), .ENA(rs), .GCLK(f_{nm}[0]));   // die: fwd_{nm} CLK {x['icg']}")
                o.append(f"    assign d_{nm}[0] = {src}[{276*l} +: 276];")
                for i, m in enumerate(st):
                    o.append(f"    {m} st_{nm}_{i} (.i(d_{nm}[{i}]), .o(d_{nm}[{i+1}]), .ck(f_{nm}[{i}]), .ck_o(f_{nm}[{i+1}]), .rs(rs));")
                o.append(f"    {x['land']} ld_{nm} (.ck_f(f_{nm}[{ns}]), .i(d_{nm}[{ns}]), .ck(clk), .rs(rs), .k(3'd{x['k']}),"
                         f" .o({dst}[{276*l} +: 276]), .fault(lfault[{fi}]));")
                meta["links"][nm] = {"stations": ns, "relay": sorted(set(st)), "land": x["land"], "k": x["k"], "icg_clk": x["icg"]}
o.append("endmodule")
open(out_sv, "w").write("\n".join(o) + "\n")
json.dump(meta, open(out_js, "w"), indent=1, sort_keys=True)
print("links", len(meta["links"]), "sid", meta["sid"])
