def oracle_x(oracle: Path, n: int, d: int) -> Path:
    for name in (f"L{n:02d}_die{d}_x.hex", f"L{n}_die{d}_x.hex"):
        if (oracle / name).exists():
            return oracle / name
    raise SystemExit(f"oracle {oracle} lacks layer {n} die {d} x")


def words(p: Path):
    return [int(x, 16) for x in p.read_text().split() if not x.startswith("@")]


def host_vm_elems(src_root: Path) -> int:
    m = re.search(r"VM_ELEMS = (\d+)", (src_root / HOST_CPP).read_text())
    return int(m.group(1))


def entry_for(a, stages, i, D, jd: Path) -> str:
    """Write jd/entry.hex for a job whose first stage is stages[i]; return the entry's source.

    With --poison WORD every vector-memory word outside the x window is preloaded with WORD instead of 0, so a
    stage whose result depended on pre-stage state outside x would not reproduce the golden exit."""
    if i == 0:
        w = words(a.preload)
        txt = a.preload.read_text().split()
        if txt[0] != f"@{X_BASE:x}" or len(w) != H:
            if a.poison:
                raise SystemExit("--poison needs an L0 preload of exactly the x window (@1000 + 4096 words)")
            (jd / "entry.hex").write_bytes(a.preload.read_bytes())
            return str(a.preload)
        src = str(a.preload)
    else:
        prev = stages[i - 1][0]
        dies = [oracle_x(a.oracle, int(prev[1:]), d) for d in range(D)]
        if len({sha(p) for p in dies}) != 1:
            raise SystemExit(f"golden exit of {prev} differs between dies; the single-preload host cannot enter {stages[i][0]}")
        w = words(dies[0])
        if len(w) != H:
            raise SystemExit(f"{dies[0]}: {len(w)} words, expected {H}")
        src = str(dies[0])
    if a.poison:
        n, pw = host_vm_elems(a.source_root), f"{int(a.poison, 16):08x}\n"
        (jd / "entry.hex").write_text("@0\n" + pw * X_BASE + "".join(f"{v:08x}\n" for v in w) + pw * (n - X_BASE - H))
    else:
        (jd / "entry.hex").write_text(f"@{X_BASE:x}\n" + "".join(f"{v:08x}\n" for v in w))
    return src


def cmd_plan(a):
    pd = a.plan_dir.resolve()
    if (pd / "plan.json").exists():
        raise SystemExit(f"{pd}/plan.json exists; plans are immutable evidence, use a new directory")
    stages = [l.split() for l in a.stages.read_text().splitlines() if l.strip()]
    D = len(stages[0]) - 2
    fleet = json.loads(a.fleet.read_text())
    oracle_json = json.loads((a.oracle / "oracle.json").read_text())
    ref = json.loads(a.reference.read_text()) if a.reference else None
    idx = {s[0]: i for i, s in enumerate(stages)}

    def stage_rec(i, entered_by):
        st = stages[i]
        r = {"stage": st[0], "index": i, "kv_reset": st[-1] == "1", "entered_by": entered_by, "expected_exit": {}}
        if st[0].startswith("L"):
            for d in range(D):
                p = oracle_x(a.oracle, int(st[0][1:]), d)
                r["expected_exit"][f"die{d}"] = {"path": str(p), "sha256": sha(p)}
        else:
            r["expected_token"] = {"next_token": oracle_json.get("next_token"),
                                   "next_logit_bits": oracle_json.get("next_logit_bits")}
        if ref and st[0] in ref.get("stages", {}):
            r["reference_chained_cycles"] = ref["stages"][st[0]]["cycles"]
        return r

    specs = [(n, "single", [idx[n]]) for n in ([s[0] for s in stages] if not a.only else a.only.split(","))]
    # supplementary chained pairs (previous stage, this stage) from a golden entry: the second stage is
    # entered through the host's h_start exactly as in the chained run, after the previous stage's state
    specs += [(n + "+pair", "pair", [idx[n] - 1, idx[n]]) for n in (a.pairs.split(",") if a.pairs else []) if idx[n] > 0]
    jobs = []
    for name, kind, ii in specs:
        jd = pd / "jobs" / name
        jd.mkdir(parents=True, exist_ok=True)
        src = entry_for(a, stages, ii[0], D, jd)
        lines = [stages[i] for i in ii]
        (jd / "stages.txt").write_text("".join(" ".join(l) + "\n" for l in lines))
        recs = [stage_rec(i, ("wrapper_start" if k == 0 else "host_h_start")) for k, i in enumerate(ii)]
        jobs.append({"name": name, "kind": kind, "index": ii[-1], "stage_lines": lines, "stages": recs,
                     "entry": {"source": src, "sha256": sha(jd / "entry.hex")}})
    # assignment: pairs (two stages long) first, then fill each host's slots in fleet order
    slots = [(h["name"], s) for h in fleet["hosts"] for s in range(h["slots"])]
    order = sorted(jobs, key=lambda j: -len(j["stage_lines"]))
    if len(order) > len(slots):
        raise SystemExit(f"{len(order)} jobs > {len(slots)} fleet slots")
    for j, (hn, s) in zip(order, slots):
        j["host"], j["slot"] = hn, s
