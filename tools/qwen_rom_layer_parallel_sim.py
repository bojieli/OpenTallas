def gparam(params, name):
    for p in params:
        if p.startswith(f"-G{name}="):
            return p.split("=", 1)[1]
    raise SystemExit(f"build_params.json lacks -G{name}")


def link_cmd(work: Path, src_root: Path, cpp: Path, out: Path, verilator: str):
    """The exact link of tools/qwen_rom_rt_token_w12.py, rebuilt from build_params.json."""
    bp = json.loads((work / "build_params.json").read_text())
    die, tile = bp["die"], bp["tile"]
    vroot = re.search(r"VERILATOR_ROOT\s*=\s*(\S+)", subprocess.check_output([verilator, "-V"], text=True)).group(1)
    rt, rr = src_root / "rtl/test/qwen_runtime", src_root / "rtl/test/qwen_rom_runtime"
    archives, includes = [], {f"-I{vroot}/include", f"-I{vroot}/include/vltstd", f"-I{rt}", f"-I{rr}"}
    for prefix in ("die", "coll", "tile"):                     # the driver's model order
        archives += sorted((work / prefix).rglob("*.a"))
        includes.add(f"-I{work / prefix}")
        for h in (work / prefix).rglob("V*.h"):
            includes.add(f"-I{h.parent}")
    defs = [f"-DGROUPS={gparam(die, 'G')}", f"-DCOUNTWIDTH={gparam(die, 'NW')}", f"-DSWIDTH={gparam(die, 'SW')}",
            f"-DSMAXB={gparam(die, 'SMAX')}", f"-DTCUTL={gparam(die, 'TCUT')}", f"-DNWSD={gparam(die, 'NWS')}",
            f"-DXVMD={gparam(die, 'XVM')}", f"-DTPD={gparam(die, 'D')}", f"-DCBANKS={gparam(tile, 'CODE_BANKS')}",
            f"-DSMINV={gparam(die, 'SMIN')}"]
    return ["g++", "-std=c++20", "-O2", "-pthread", *defs, *sorted(includes), str(cpp), "-Wl,--start-group",
            *map(str, archives), "-Wl,--end-group", f"{vroot}/include/verilated.cpp",
            f"{vroot}/include/verilated_threads.cpp", f"{vroot}/include/verilated_dpi.cpp", "-o", str(out)]


def git_state(root: Path):
    try:
        head = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
        dirty = subprocess.check_output(["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"],
                                        text=True).strip()
        return {"commit": head, "tracked_dirty": dirty.splitlines()}
    except Exception as e:  # noqa: BLE001
        return {"commit": None, "error": str(e)}


def cmd_build(a, rest):
    work, src = a.workdir.resolve(), a.source_root.resolve()
    work.mkdir(parents=True, exist_ok=True)
    gs = git_state(src)
    if gs.get("tracked_dirty"):
        raise SystemExit(f"source root {src} has tracked changes; build from a pinned clean worktree")
    driver = src / a.driver
    t0 = time.monotonic()
    rec = {"schema": SCHEMA + "-build.v1", "at": now(), "source_root": str(src), "source_git": gs,
           "driver": str(driver.relative_to(src)), "driver_args": rest, "host": os.uname().nodename}
    if not a.skip_models:
        cmd = [sys.executable, str(driver), "--workdir", str(work), "--stages", "/dev/null", "--token-oracle",
               "/dev/null", "--preload", "/dev/null", *rest, "--build-only"]
        p = subprocess.run(cmd, cwd=src)
        if p.returncode:
            raise SystemExit("driver build failed")
    rec["models_seconds"] = round(time.monotonic() - t0, 1)
    ref_bin = work / "qwen_rom_rt"
    pinned = src / HOST_CPP
    gen = work / "gen" / "qwen_rom_rt_w12_lp.cpp"
    gen.parent.mkdir(exist_ok=True)
    gen.write_text(emit_host(pinned.read_text()))
    steps = {}
    for name, cpp, out in (("relink_pinned", pinned, work / "qwen_rom_rt_relink"), ("link_audited", gen, work / "qwen_rom_rt_lp")):
        t1 = time.monotonic()
        p = subprocess.run(link_cmd(work, src, cpp, out, a.verilator), cwd=work, capture_output=True, text=True)
        (work / f"{name}.log").write_text(p.stdout + p.stderr)
        if p.returncode:
            raise SystemExit(f"{name} failed: see {work / (name + '.log')}")
        steps[name] = round(time.monotonic() - t1, 1)
    rec.update({
        "link_seconds": steps,
        "build_params": json.loads((work / "build_params.json").read_text()),
        "pinned_host_sha256": sha(pinned), "generated_host_sha256": sha(gen),
        "driver_binary_sha256": sha(ref_bin) if ref_bin.exists() else None,
        "relinked_pinned_binary_sha256": sha(work / "qwen_rom_rt_relink"),
        "audited_binary_sha256": sha(work / "qwen_rom_rt_lp"),
        "audited_binary": str(work / "qwen_rom_rt_lp"),
        "tool_sha256": sha(Path(__file__)),
        "source_sha256": {str(p.relative_to(src)): sha(p) for p in sorted(
            [*src.glob("rtl/hdc/*.sv"), *src.glob("rtl/rom/*.sv"), *src.glob("rtl/proto/*.sv"),
             *src.glob("rtl/test/qwen_rom_runtime/*"), *src.glob("rtl/test/qwen_runtime/*.hpp"),
             *src.glob("tools/qwen_rom_rt_*.py")]) if p.is_file()},
    })
    rec["link_reconstruction_byte_identical"] = rec["driver_binary_sha256"] == rec["relinked_pinned_binary_sha256"]
    (work / "lp_build.json").write_text(json.dumps(rec, indent=1, sort_keys=True) + "\n")
    print(json.dumps({k: rec[k] for k in ("audited_binary", "audited_binary_sha256", "link_reconstruction_byte_identical")}, indent=1))
    if not rec["link_reconstruction_byte_identical"]:
        raise SystemExit("re-linked pinned host differs from the driver's binary: the audited link is not like-for-like")


