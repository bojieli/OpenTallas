def kvline(s):
    return dict(item.split("=", 1) for item in s.split() if "=" in item)


def check_stage(sr, out: Path, log: str, last_in_job: bool):
    """Exactness, faults, dependency audit and cycles of one stage of one job."""
    name = sr["stage"]
    r = {"stage": name, "entered_by": sr["entered_by"], "kv_reset": sr["kv_reset"]}
    st = {m.group(1): kvline(m.group(2)) for m in re.finditer(r"STAGE (\S+) done (.*)", log)}.get(name)
    r["cycles"] = int(st["cycles"]) if st else None
    r["faults"] = {k: int(st[k]) for k in ("seq_fault", "core_fault", "coll_fault")} if st else None
    deps = [kvline(m.group(1)) for m in re.finditer(r"^DEP (.*)$", log, re.M)]
    deps = [d for d in deps if d.get("stage") == name]
    r["dep_audit"] = [{k: d[k] for k in ("die", "vm_rbw_x", "vm_rbw_other", "kv_rbw", "vm_other_ranges")} for d in deps]
    dep_ok = bool(deps) and all((out / f"{name}_die{d['die']}_dep.txt").exists() for d in deps)
    drains = [kvline(m.group(1)) for m in re.finditer(r"^DRAIN (.*)$", log, re.M)]
    drains = [d for d in drains if d.get("stage") == name]
    r["drain_after_done"] = [{k: d[k] for k in ("die", "cycles", "vm_writes", "x_writes", "kv_writes")} for d in drains]
    if last_in_job and name != "head":                 # the head has no successor
        dep_ok = dep_ok and bool(drains) and all(int(d["x_writes"]) == 0 for d in drains)
    r["audit_complete"] = dep_ok
    checks = {}
    for die, e in sr["expected_exit"].items():
        got = out / f"{name}_{die}_x.hex"
        gw = words(got) if got.exists() else []
        ew = words(Path(e["path"]))
        checks[die] = {"words": len(gw), "mismatches": sum(x != y for x, y in zip(gw, ew)) + abs(len(gw) - len(ew)),
                       "actual_sha256": sha(got) if got.exists() else None, "expected_sha256": e["sha256"]}
    r["exit_checks"] = checks
    exact = bool(checks) and all(c["mismatches"] == 0 for c in checks.values())
    if "expected_token" in sr:
        m = re.search(r"PASS stages=\d+ token=(\d+) val=([0-9a-f]+) die1_token=(\d+)", log)
        r["rtl_token"] = int(m.group(1)) if m else None
        r["rtl_logit_bits"] = m.group(2) if m else None
        exact = bool(m) and r["rtl_token"] == sr["expected_token"]["next_token"] and int(m.group(3)) == r["rtl_token"] \
            and r["rtl_logit_bits"] == sr["expected_token"]["next_logit_bits"]
    r["exact"] = exact
    rc = sr.get("reference_chained_cycles")
    if rc is not None and r["cycles"] is not None:
        # the reference's first stage and every isolated stage start from the wrapper's cycle-7 pulse, counted from
        # cycle 7 while the sequencer samples it at cycle 8: one cycle more than an h_start entry, which is counted
        # from the cycle the sequencer samples it
        offset = 1 if (sr["entered_by"] == "wrapper_start" and sr["index"] > 0) else 0
        r.update(reference_chained_cycles=rc, cycle_offset_applied=offset, cycles_match_reference=r["cycles"] - offset == rc)
    r["pass"] = (exact and dep_ok and r["faults"] is not None and not any(r["faults"].values())
                 and r.get("cycles_match_reference", True))
    return r


def dep_sets(path: Path):
    sets = {}
    if path.exists():
        for line in path.read_text().splitlines():
            t, lo, hi = line.split()
            sets.setdefault(t, []).append((int(lo), int(hi)))
    return sets


def merge(iv):
    out = []
    for lo, hi in sorted(iv):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def intersect(a, b):
    a, b, i, j, out = merge(a), merge(b), 0, 0, []
    while i < len(a) and j < len(b):
        lo, hi = max(a[i][0], b[j][0]), min(a[i][1], b[j][1])
        if lo <= hi:
            out.append((lo, hi))
        if a[i][1] < b[j][1]:
            i += 1
        else:
            j += 1
    return out


def composition_check(pd: Path, singles, dies: int):
    """Entry state of stage k in the chained run vs the isolated job, from the audited sets.

    Chained VM at entry to k = the L0 preload (zero outside x) + writes of stages < k; isolated VM outside x = 0.
    So a pre-stage VM read outside x is harmless iff no earlier stage wrote that word.  Chained KV at entry to a
    stage without KV reset = writes of earlier stages (zero-initialised); isolated KV = 0.  The x window itself is
    the golden exit of k-1 in both (the previous job proves RTL exit == golden exit, and DRAIN shows no x write
    after its dump)."""
    res = {}
    for d in range(dies):
        vm_w, kv_w = [], []
        for j in singles:
            st = j["stages"][-1]
            ds = dep_sets(pd / "jobs" / j["name"] / "out" / f"{st['stage']}_die{d}_dep.txt")
            other = [(lo, hi) for lo, hi in ds.get("vm_rbw", []) if not (lo >= X_BASE and hi < X_BASE + H)]
            hit_vm = intersect(other, vm_w)
            if st["kv_reset"]:
                kv_w = []                                 # the host zeroes KV when it switches to this stage
            hit_kv = intersect(ds.get("kv_rbw", []), kv_w)
            r = res.setdefault(j["name"], {"vm_rbw_outside_x": sum(h - l + 1 for l, h in other),
                                           "vm_reads_of_earlier_stage_writes": 0, "kv_reads_of_earlier_stage_writes": 0,
                                           "examples": []})
            r["vm_reads_of_earlier_stage_writes"] += sum(h - l + 1 for l, h in hit_vm)
            r["kv_reads_of_earlier_stage_writes"] += sum(h - l + 1 for l, h in hit_kv)
            r["examples"] += [f"die{d}:vm{l}-{h}" for l, h in hit_vm[:4]] + [f"die{d}:kv{l}-{h}" for l, h in hit_kv[:4]]
            r["dep_files_present"] = r.get("dep_files_present", True) and bool(ds)
            vm_w = merge(vm_w + ds.get("vm_w", []))
            kv_w = merge(kv_w + ds.get("kv_w", []))
    for r in res.values():
        r["entry_state_equivalent"] = r["dep_files_present"] and r["vm_reads_of_earlier_stage_writes"] == 0 \
            and r["kv_reads_of_earlier_stage_writes"] == 0
    return res


def cmd_verify(a):
    pd = a.plan_dir.resolve()
    plan = json.loads((pd / "plan.json").read_text())
    ref_img = json.loads(Path(plan["reference"]).read_text()).get("stage_image_sha256", {}) if plan.get("reference") else {}
    jobs, walls, starts, ends = {}, [], [], []
    for j in plan["jobs"]:
        out = pd / "jobs" / j["name"] / "out"
        log = (out / "token.log").read_text() if (out / "token.log").exists() else ""
        ex = json.loads((out / "exit.json").read_text()) if (out / "exit.json").exists() else None
        la = json.loads((out / "launch.json").read_text()) if (out / "launch.json").exists() else None
        r = {"host": j["host"], "kind": j["kind"], "exit_rc": ex["rc"] if ex else None,
             "entry_sha256": j["entry"]["sha256"], "entry_source": j["entry"]["source"]}
        if ex and la:
            r["wall_seconds"] = round(ex["end_epoch"] - la["start_epoch"], 1)
            if j["kind"] == "single":
                walls.append(r["wall_seconds"]); starts.append(la["start_epoch"]); ends.append(ex["end_epoch"])
        if (out / "time.txt").exists():
            t = (out / "time.txt").read_text().split()
            if len(t) >= 4:
                r["max_rss_kib"], r["user_s"], r["sys_s"] = int(t[0]), float(t[2]), float(t[3])
        m = re.search(r"threads=(\d+)", log)
        r["threads"] = int(m.group(1)) if m else None
        imgs = {}
        if (out / "image_sha256.txt").exists():
            imgs = dict(l.split() for l in (out / "image_sha256.txt").read_text().splitlines() if l.strip())
        r["image_files_hashed_on_host"] = len(imgs)
        r["images_match_reference"] = (all(ref_img.get(k) == v for k, v in imgs.items()) if ref_img and imgs else None)
        r["stages"] = [check_stage(sr, out, log, k == len(j["stages"]) - 1) for k, sr in enumerate(j["stages"])]
        r["pass"] = r["exit_rc"] == 0 and all(s["pass"] for s in r["stages"]) and r["images_match_reference"] is not False
        jobs[j["name"]] = r
    singles = sorted((j for j in plan["jobs"] if j["kind"] == "single"), key=lambda j: j["index"])
    pairs = [j for j in plan["jobs"] if j["kind"] == "pair"]
    # chain links: each single job's entry is the previous single job's golden exit (same file on every die)
    links = []
    for prev, cur in zip(singles, singles[1:]):
        pe = prev["stages"][-1]["expected_exit"]
        links.append({"from": prev["name"], "to": cur["name"],
                      "entry_is_previous_golden_exit": any(cur["entry"]["source"] == v["path"] for v in pe.values())
                      and len({v["sha256"] for v in pe.values()}) == 1})
    covers = bool(singles) and [j["index"] for j in singles] == list(range(len(singles))) and singles[-1]["name"] == "head"
    chain_ok = covers and all(l["entry_is_previous_golden_exit"] for l in links) and \
        singles[0]["entry"]["sha256"] == plan["preload_sha256"]
    comp = composition_check(pd, singles, plan["dies"]) if covers else {}
    if a.poison_verdict:
        pv = json.loads(a.poison_verdict.read_text())
        for name, r in comp.items():
            pj = pv["jobs"].get(name)
            r["poisoned_job_exact"] = bool(pj and pj["pass"] and pv.get("poison_outside_x"))
            if not r["entry_state_equivalent"] and r["poisoned_job_exact"]:
                r["entry_state_equivalent"] = True
                r["discharged_by"] = f"poisoned job exact ({a.poison_verdict}, poison {pv.get('poison_outside_x')})"
    comp_ok = bool(comp) and all(r["entry_state_equivalent"] for r in comp.values())
    singles_ok = bool(singles) and all(jobs[j["name"]]["pass"] for j in singles)
    composed = None
    cyc = [jobs[j["name"]]["stages"][0]["cycles"] for j in singles]
    if covers and all(cyc):
        # chained total = 7 (wrapper start) + chained stage cycles + one host cycle per stage switch
        composed = 7 + sum(c - (1 if k else 0) for k, c in enumerate(cyc)) + (len(cyc) - 1)
    verdict = {
        "schema": SCHEMA + "-verdict.v1", "at": now(), "plan_sha256": sha(pd / "plan.json"),
        "poison_outside_x": plan.get("poison_outside_x"), "poison_verdict": str(a.poison_verdict) if a.poison_verdict else None,
        "tool_sha256": sha(Path(__file__)), "jobs": jobs, "chain_links": links,
        "chain_covers_every_stage_from_preload_to_head": chain_ok,
        "all_single_stage_jobs_pass": singles_ok,
        "pair_jobs": {j["name"]: jobs[j["name"]]["pass"] for j in pairs},
        "entry_state_composition": comp, "entry_state_composition_ok": comp_ok,
        "composed_full_token_exact": bool(singles_ok and chain_ok and comp_ok),
        "composed_total_cycles": composed, "reference_total_cycles": plan.get("reference_total_cycles"),
        "composed_total_matches_reference": (composed == plan["reference_total_cycles"]) if composed and plan.get("reference_total_cycles") else None,
        "wall_seconds_max_single_job": max(walls) if walls else None,
        "wall_seconds_first_start_to_last_end_singles": round(max(ends) - min(starts), 1) if ends else None,
        "single_job_wall_seconds_sum": round(sum(walls), 1) if walls else None,
    }
    tgt = a.result or (pd / "verdict.json")
    if tgt.exists():
        raise SystemExit(f"{tgt} exists; verdicts are never overwritten -- pass --result NEWPATH")
    tgt.write_text(json.dumps(verdict, indent=1, sort_keys=True) + "\n")
    keys = ("composed_full_token_exact", "all_single_stage_jobs_pass", "chain_covers_every_stage_from_preload_to_head",
            "entry_state_composition_ok",
            "pair_jobs", "composed_total_cycles", "reference_total_cycles", "wall_seconds_max_single_job",
            "wall_seconds_first_start_to_last_end_singles")
    print(json.dumps({k: verdict[k] for k in keys}, indent=1))
    for n, r in jobs.items():
        if not r["pass"]:
            print("FAIL", n, r["exit_rc"], [{k: s.get(k) for k in ("stage", "exact", "audit_complete",
                                                                    "cycles", "cycles_match_reference", "faults")} for s in r["stages"]])
    if not verdict["composed_full_token_exact"]:
        raise SystemExit(1)


