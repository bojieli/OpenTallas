#!/usr/bin/env python3
"""Layer-parallel exact full-token check for the Qwen3-8B ROM runtime (W12 companion host).

The connected runtime (rtl/test/qwen_rom_runtime/qwen_rom_rt_w12.cpp) simulates a
stage list in sequence: each stage loads its image bank, optionally zeroes the KV
window, starts the TP sequencer and, at done, dumps the residual x (vector memory
words X_BASE..X_BASE+H) of every die.  A full token is 36 layers + the LM head,
~171 k cycles at ~2 cycles/s, i.e. about a day of wall time.

This tool runs every stage as its OWN job, in parallel, entered from the golden
(ISA-oracle) checkpoint:

    job k:  preload x = golden exit_{k-1}  (golden embedding for L0)
            run stage k alone from reset
            check  RTL exit_k == golden exit_k  bit-exactly on every die
                   (head: token id and logit bits == oracle)

Because golden exit_{k-1} IS the input of golden stage k, the per-stage proofs
compose into the full token, PROVIDED a stage's result depends only on the state
the job reproduces.  Two things are carried between stages in the chained run:

  * memories: vector memory (VM) and KV.  The job's host is an audited copy of the
    pinned host (generated by `emit_host`, never edited in place) that records, per
    stage and die, every VM / KV word READ BEFORE the stage WROTE it.  The
    composition is accepted only if the pre-stage VM dependence is confined to the
    x window and, for stages without a KV reset, there is no pre-stage KV
    dependence.  (A KV-reset stage sees all-zero KV in both the chained and the
    isolated run.)
  * RTL registers.  Every stage is started by the sequencer's start/h_start, which
    re-initialises the segment walk; the residual-state claim is checked by
    comparing each stage's cycle count with the chained reference run
    (isolated = chained + 1 for stages after the first: the first stage's start is
    the wrapper's cycle-7 pulse, later ones the host's h_start, see `cycles_check`)
    and, optionally, by `--pairs` jobs that chain two stages from a golden entry.

Subcommands (one per invocation):
  --build    build the Verilated models with tools/qwen_rom_rt_token_w12.py --build-only
             (unchanged), re-link the PINNED host and prove the link byte-identical to
             the driver's, then link the audited host qwen_rom_rt_lp.
  --plan     make one job per stage (entry preload, expected exit, stage line) and a
             manifest that assigns jobs to hosts from a fleet file.
  --launch   copy each job to its host and start it detached (nohup/setsid).
  --status   show job progress.
  --collect  fetch logs and exit vectors back into the plan directory.
  --verify   per-stage exactness, dependency audit, cycle cross-check, chain links and
             the composed full-token verdict; writes verdict.json.
"""
