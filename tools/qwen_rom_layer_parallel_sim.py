AUDIT_HEADER = r'''
// ---- layer-parallel dependency audit (tools/qwen_rom_layer_parallel_sim.py) -------------------
// RT_DEP_AUDIT=1: per stage and die, mark every vector-memory / KV word read before the stage
// wrote it (its value comes from before the stage) and report the set at stage done.  Unset,
// the host behaves and prints exactly as the pinned host.
static const bool lp_audit = [] { const char* s = getenv("RT_DEP_AUDIT"); return s && s[0] == '1'; }();
static std::vector<std::vector<uint8_t>> lp_vm_w, lp_vm_r, lp_kv_w, lp_kv_r;
// first pre-stage reads outside the x window: (die, address, port, cycle); ports 0-2 stream-unit a/b/c,
// 3 spine x-chunk, 4 sequencer, 5 KV
struct LpSite { int d; size_t a; int port; uint32_t cyc; };
static std::vector<LpSite> lp_sites;
static std::mutex lp_sites_m;
static uint32_t lp_cyc = 0;
constexpr int LP_DRAIN = 512;                    // cycles clocked after the last stage's done
static int lp_drain = 0;
static long lp_dvm[8], lp_dx[8], lp_dkv[8];      // writes landing after done (per die)
static void lp_init(int d, size_t vm, size_t kv) {
    lp_vm_w.assign(d, std::vector<uint8_t>(vm, 0)); lp_vm_r = lp_vm_w;
    lp_kv_w.assign(d, std::vector<uint8_t>(kv, 0)); lp_kv_r = lp_kv_w;
}
static void lp_reset() {
    lp_sites.clear();
    for (auto* v : {&lp_vm_w, &lp_vm_r, &lp_kv_w, &lp_kv_r}) for (auto& x : *v) std::fill(x.begin(), x.end(), 0);
}
static inline void lp_rd(std::vector<std::vector<uint8_t>>& w, std::vector<std::vector<uint8_t>>& r, int d, size_t a, int port) {
    if (!lp_audit || a >= w[d].size() || w[d][a]) return;
    if (std::atomic_ref<uint8_t>(r[d][a]).exchange(1, std::memory_order_relaxed)) return;
    if (port < 5 && a >= 4096 && a < 8192) return;
    std::lock_guard<std::mutex> g(lp_sites_m);
    if (lp_sites.size() < 64) {
        lp_sites.push_back({d, a, port, lp_cyc});
        printf("DEPSITE die=%d addr=%zu port=%d cyc=%u\n", d, a, port, lp_cyc);
    }
}
static std::string lp_ranges(const std::vector<uint8_t>& r, size_t lo, size_t hi, bool inside, long& n) {
    std::string s; int shown = 0; n = 0;
    for (size_t a = 0; a < r.size(); a++) {
        if (!r[a] || ((a >= lo && a < hi) != inside)) continue;
        size_t b = a;
        while (b + 1 < r.size() && r[b + 1] && ((b + 1 >= lo && b + 1 < hi) == inside)) b++;
        n += long(b - a + 1);
        if (shown++ < 16) s += (s.empty() ? "" : ",") + std::to_string(a) + "-" + std::to_string(b);
        a = b;
    }
    return s.empty() ? "-" : s;
}
static void lp_dump(FILE* f, const char* tag, const std::vector<uint8_t>& r) {
    for (size_t a = 0; a < r.size(); a++) {
        if (!r[a]) continue;
        size_t b = a;
        while (b + 1 < r.size() && r[b + 1]) b++;
        fprintf(f, "%s %zu %zu\n", tag, a, b);
        a = b;
    }
}
static void lp_report(const std::string& stage, int d, size_t xb, size_t h, const std::string& dir) {
    // full sets for the composition check: vm reads-before-write, vm writes, kv reads-before-write, kv writes
    if (FILE* f = fopen((dir + "/" + stage + "_die" + std::to_string(d) + "_dep.txt").c_str(), "w")) {
        lp_dump(f, "vm_rbw", lp_vm_r[d]); lp_dump(f, "vm_w", lp_vm_w[d]);
        lp_dump(f, "kv_rbw", lp_kv_r[d]); lp_dump(f, "kv_w", lp_kv_w[d]);
        fclose(f);
    }
    long nx = 0, no = 0, nk = 0;
    std::string rx = lp_ranges(lp_vm_r[d], xb, xb + h, true, nx);
    std::string ro = lp_ranges(lp_vm_r[d], xb, xb + h, false, no);
    std::string rk = lp_ranges(lp_kv_r[d], 0, 0, false, nk);
    printf("DEP stage=%s die=%d vm_rbw_x=%ld vm_rbw_other=%ld kv_rbw=%ld vm_x_ranges=%s vm_other_ranges=%s kv_ranges=%s\n",
           stage.c_str(), d, nx, no, nk, rx.c_str(), ro.c_str(), rk.c_str());
}
'''

