def host_of(plan, name):
    return next(h for h in plan["fleet"]["hosts"] if h["name"] == name)


def sh(host, script: str, check=True, capture=True):
    cmd = ["bash", "-c", script] if not host.get("ssh") else ["ssh", host["ssh"], script]
    p = subprocess.run(cmd, capture_output=capture, text=True)
    if check and p.returncode:
        raise SystemExit(f"{host['name']}: {script[:200]}\n{p.stderr}")
    return p.stdout


def remap(path: str, host) -> str:
    for old, new in host.get("path_map", {}).items():
        if path.startswith(old):
            return new + path[len(old):]
    return path


RUN_SH = """#!/bin/bash
# generated by tools/qwen_rom_layer_parallel_sim.py --launch
J={jobdir}
cd "$J"
echo "{{\\"host\\": \\"$(hostname)\\", \\"pid\\": $$, \\"start_epoch\\": $(date +%s.%N)}}" > launch.json
for st in $(awk '{{for (i = 2; i < NF; i++) print $1 "/die" (i - 2) " " $i}}' stages.txt | tr ' ' '|'); do
  n=${{st%%|*}}; dir=${{st#*|}}
  for f in program.hex segments.hex matrix_int8.hex matrix_scale_bf16.hex crom.hex; do
    echo "$n/$f $(sha256sum "$dir/$f" | cut -d' ' -f1)"
  done
done > image_sha256.txt
/usr/bin/time -f "%M %e %U %S" -o time.txt env RT_THREADS={threads} RT_DEP_AUDIT=1 RT_SCALE_LOCAL=0 {extra_env} \\
  {binary} --stages "$J/stages.txt" "$J" "$J/entry.hex" {max_cycles} > token.log 2>&1
rc=$?
echo "{{\\"rc\\": $rc, \\"end_epoch\\": $(date +%s.%N)}}" > exit.json
"""


def cmd_launch(a):
    pd = a.plan_dir.resolve()
    plan = json.loads((pd / "plan.json").read_text())
    want = set(a.only.split(",")) if a.only else None
    launched, deferred = [], False
    for j in plan["jobs"]:
        if (want and j["name"] not in want) or (a.host and j["host"] != a.host):
            continue
        h = host_of(plan, j["host"])
        jobdir = f"{h['workroot']}/{pd.name}/{j['name']}"
        stage_txt = "".join(" ".join([l[0], *(remap(p, h) for p in l[1:-1]), l[-1]]) + "\n" for l in j["stage_lines"])
        extra = " ".join(f"{k}={shlex.quote(str(v))}" for k, v in h.get("env", {}).items())
        run = RUN_SH.format(jobdir=jobdir, threads=h["threads"], binary=h["binary"], extra_env=extra,
                            max_cycles=plan["max_cycles"])
        exists = sh(h, f"test -e {jobdir}/launch.json && echo yes || true").strip()
        if exists == "yes":
            if a.fill:
                continue
            raise SystemExit(f"{j['name']} already launched on {h['name']} ({jobdir}); never relaunch over evidence")
        # schedule against measured headroom: MemAvailable must cover this job plus the host's reserve
        need = float(h.get("mem_per_job_gb", 2.0)) + float(h.get("mem_reserve_gb", 16.0))
        avail = int(sh(h, "awk '/MemAvailable/ {print $2}' /proc/meminfo").strip()) / 1048576
        # ...and the 1-minute load plus this job's threads must fit the host's cores (times max_load_per_core)
        load, cores = sh(h, "cut -d' ' -f1 /proc/loadavg; nproc").split()
        cpu_cap = int(cores) * float(h.get("max_load_per_core", 1.0))
        burst = sum(1 for l in launched if l["host"] == h["name"])     # the load average lags this call's launches
        if avail < need + burst * float(h.get("mem_per_job_gb", 2.0)) or float(load) + h["threads"] * (1 + burst) > cpu_cap:
            print(f"deferred {j['name']} on {h['name']}: MemAvailable {avail:.1f} GB (need {need:.1f}), "
                  f"load {load} + {h['threads']} vs {cpu_cap:.0f}")
            deferred = True
            continue
        sh(h, f"mkdir -p {jobdir}")
        files = {"stages.txt": stage_txt, "run.sh": run, "entry.hex": (pd / "jobs" / j["name"] / "entry.hex").read_text()}
        for fn, txt in files.items():
            if h.get("ssh"):
                subprocess.run(["ssh", h["ssh"], f"cat > {jobdir}/{fn}"], input=txt, text=True, check=True)
            else:
                Path(jobdir, fn).write_text(txt)
        sh(h, f"chmod +x {jobdir}/run.sh && cd {jobdir} && setsid -f nohup ./run.sh > run.out 2>&1 < /dev/null; echo ok")
        launched.append({"name": j["name"], "host": h["name"], "jobdir": jobdir, "at": now()})
        print("launched", j["name"], "on", h["name"])
    lf = pd / "launches.json"
    prior = json.loads(lf.read_text()) if lf.exists() else []
    lf.write_text(json.dumps(prior + launched, indent=1) + "\n")
    if deferred:
        raise SystemExit(3)                               # some jobs wait for memory: re-run with --fill


def cmd_reassign(a):
    """Move not-yet-launched jobs from one fleet host to another (recorded in the plan as an amendment)."""
    pd = a.plan_dir.resolve()
    plan = json.loads((pd / "plan.json").read_text())
    src, dst = a.reassign.split("=")
    host_of(plan, dst)
    launched = {l["name"] for l in json.loads((pd / "launches.json").read_text())} if (pd / "launches.json").exists() else set()
    moved = [j["name"] for j in plan["jobs"] if j["host"] == src and j["name"] not in launched]
    for j in plan["jobs"]:
        if j["name"] in moved:
            j["host"] = dst
    plan.setdefault("assignment_amendments", []).append({"at": now(), "from": src, "to": dst, "jobs": moved,
                                                          "reason": a.reason})
    (pd / "plan.json").write_text(json.dumps(plan, indent=1) + "\n")
    print("moved", len(moved), "jobs", src, "->", dst)


