def emit_host(text: str) -> str:
    for anchor, repl in AUDIT_EDITS:
        n = text.count(anchor)
        if n != 1:
            raise SystemExit(f"audit anchor occurs {n} times in the pinned host (expected 1): {anchor[:70]!r}")
        text = text.replace(anchor, repl)
    return "// GENERATED by tools/qwen_rom_layer_parallel_sim.py from " + str(HOST_CPP) + "; do not edit.\n" + text


