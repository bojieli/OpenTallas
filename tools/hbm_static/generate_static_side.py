#!/usr/bin/env python3
"""Clock-only additive SIDE derivative; original byte hashes remain unchanged."""
from pathlib import Path
import hashlib,re
root=Path(__file__).resolve().parents[2]
original=root/'rtl/hdc/v41x/ot_hdc_v41x_vec_side.sv'
assert hashlib.sha256(original.read_bytes()).hexdigest()=='71b52f3016e76f1ef9ed3ca81333a73a0866b071dd4fa1c9f5727c49701c550b'
sfusource=root/'rtl/hdc/v41x/ot_hdc_v41x_sfu.sv'
assert hashlib.sha256(sfusource.read_bytes()).hexdigest()=='804cf233a0e051d0d72fb3cf1a8b11d3e8c65bdbab3d8f664d98c07ae7c8797b'
s=sfusource.read_text()
sp=s[s.index('module ot_hdc_v41x_softplus #('):];sp=sp[:sp.index('endmodule')+len('endmodule')]
sp=sp.replace('module ot_hdc_v41x_softplus #(', 'module ot_hbm_su_static_side_softplus #(')
sp=sp.replace('input  wire        clk,','input wire [2:0] clk,')
root1=['d_u2','u_m','u_a','d_u','m_up','m_l']
root2=['d_mx','a_sp','u_sq','d_sp','d_fsp']
lines=sp.splitlines()
for i,line in enumerate(lines):
 if 'clk' not in line or 'input wire' in line:continue
 group=next((g for g,names in [(1,root1),(2,root2)] if any(re.search(r'\b'+n+r'\s*\(',line) for n in names)),0)
 if 'always @(posedge clk)' in line:group=2
 lines[i]=re.sub(r'(?<!\.)\bclk\b','clk['+str(group)+']',line)
sp='\n'.join(lines)
s=original.read_text();s=s[s.index('module ot_hdc_v41x_vec_side #('):]
s=re.sub(r'module ot_hdc_v41x_vec_side #\(.*?\) \(', 'module ot_hbm_su_static_side #(parameter integer MUT=0) (',s,count=1,flags=re.S)
s=s.replace('input  wire        clk,','input wire [5:0] clk,')
s=s.replace('    localparam [2:0]', '    localparam integer MLAT=3, ALAT=3;\n    wire [2:0] output_fn=fn_out ^ (MUT==1 ? 3\'d1:3\'d0);\n    localparam [2:0]',1)
s=re.sub(r'(?<!\.)\bclk\b','clk[5]',s)
s=s.replace('input wire [5:0] clk[5],','input wire [5:0] clk,')
s=s.replace('u_rsq (.clk(clk[5])','u_rsq (.clk(clk[0])').replace('u_sq (.clk(clk[5])','u_sq (.clk(clk[1])')
s=s.replace('ot_hdc_v41x_softplus #','ot_hbm_su_static_side_softplus #').replace('u_sp (.clk(clk[5])','u_sp (.clk(clk[4:2])')
s=s.replace('eg_r[31] ^ eg_sgn[31],','eg_r[31] ^ eg_sgn[31] ^ (MUT==2),')
s=s.replace('assign y = (fn_out', 'assign y = (output_fn').replace(' : (fn_out', ' : (output_fn')
header='''`timescale 1ns/1ps
// ADDITIVE clock-only partition of original SIDE71b52f3016e76f1ef9ed3ca81333a73a0866b071dd4fa1c9f5727c49701c550b.
// Generated by tools/hbm_static/generate_static_side.py. No original file edits.
// clk[0] RSQRT8521;[1]SQRT3814;[2]SPexp10813;[3]SPpoly10794;
// [4]SPfinish9139;[5]EGATE13902 register sinks before optimization.
// All roots related1:1 phase0. No added input/output register or function edge.
// MLAT3/ALAT3 arithmetic is PHYSICALLY UNQUALIFIED at production833ps.
// MUT1 changes actual result mux function;MUT2 changes actual Engram sign.
'''
out=root/'rtl/hbm_accel/generic/adapters/static_su/arithmetic/ot_hbm_su_static_side.sv'
out.parent.mkdir(parents=True,exist_ok=True);out.write_text(header+s+'\n\n'+sp+'\n')
