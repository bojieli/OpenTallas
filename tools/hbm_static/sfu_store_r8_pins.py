#!/usr/bin/env python3
"""Exact pin plan (io_tcl) for the SFU programme store r8 in its H-DIE slot 820.8 x 734.4 um (H-SU 2026-10-17).

Grant (H-DIE 10-17 01:50, d4f sfus_<q>): W face io_word + compiler_control over ~700 um with rst_n + clock entry at the
W centre; N / S west halves carry the host configuration / start inputs and the status outputs; E face empty.
  W (M4, centre y = 0.012 + k*0.048): io_word[0..470], compiler_control[0..1741] in bit order, evenly over [MARGIN, H-MARGIN]
    (~3.07 pins/um), clk + rst_n inserted at the middle of the sequence (the W centre, next to the W register band).
  N (M3, x <= W/2): programme cfg/start inputs + programme status + fault (345 pins, ~0.87/um).
  S (M3, x <= W/2): IO cfg/start inputs + IO status (344 pins).
Usage: sfu_store_r8_pins.py OUT.tcl [--w 820.8 --h 734.4 --aw 11]
"""
import argparse

PITCH = {"M3": 0.036, "M4": 0.048, "M5": 0.048}
CENTRE = {"M3": 0.009, "M4": 0.012, "M5": 0.012}          # track centres measured on closed views (r7c / bank6 LEFs)
SIZE = {"M3": (0.018, 0.144), "M5": (0.024, 0.192), "M4": (0.192, 0.024)}


def bits(name, w):
    return [name] if w is None else [f"{name}[{i}]" for i in range(w)]


def snap(c, layer):
    p, o = PITCH[layer], CENTRE[layer]
    return round(round((c - o) / p) * p + o, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--w", type=float, default=820.8)
    ap.add_argument("--h", type=float, default=734.4)
    ap.add_argument("--aw", type=int, default=11)
    ap.add_argument("--margin", type=float, default=6.0)
    a = ap.parse_args()
    AW, W, H, M = a.aw, a.w, a.h, a.margin
    west = bits("io_word", 471) + bits("compiler_control", 1742)
    mid = len(west) // 2
    west[mid:mid] = ["clk", "rst_n"]
    north = (bits("cfg_we", None) + bits("cfg_stripe", 3) + bits("cfg_addr", AW) + bits("start_base", AW)
             + bits("start_limit", AW + 1) + bits("start_loops", 16) + bits("cfg_data", 256)
             + bits("programme_active", None) + bits("programme_done", None) + bits("programme_ordinal", 32) + bits("fault", None))
    south = (bits("io_cfg_we", None) + bits("io_cfg_stripe", 2) + bits("io_cfg_addr", AW) + bits("io_start_v", None)
             + bits("io_start_base", AW) + bits("io_start_limit", AW + 1) + bits("io_start_loops", 16) + bits("io_cfg_data", 256)
             + bits("io_active", None) + bits("io_done", None) + bits("io_ordinal", 32))
    lines = [f"# generated by tools/hbm_static/sfu_store_r8_pins.py ({W} x {H}): W {len(west)} pins over "
             f"[{M}, {H - M}], N {len(north)} / S {len(south)} pins over the west half [{M}, {W / 2 - M}]"]
    seen = set()
    def put(face, seq, lo, hi):
        step = (hi - lo) / len(seq)
        assert step >= (0.096 if face in "WE" else 0.072), (face, step)
        for i, b in enumerate(seq):
            c = lo + step * (i + 0.5)
            if face in "WE":
                layer = "M4"; y = snap(c, layer)
                while (face, layer, y) in seen: y = round(y + PITCH[layer], 3)
                seen.add((face, layer, y)); loc = f"{0.0 if face == 'W' else W:.3f} {y:.3f}"
            else:
                layer = "M3"; x = snap(c, layer)   # M3 only: no PG on M3 (the tile M5 PG stripes, pitch 5.4, would short an M5 pin)
                while (face, layer, x) in seen: x = round(x + PITCH[layer], 3)
                seen.add((face, layer, x)); loc = f"{x:.3f} {0.0 if face == 'S' else H:.3f}"
            sx, sy = SIZE[layer]
            lines.append(f"place_pin -pin_name {{{b}}} -layer {layer} -location {{{loc}}} -pin_size {{{sx} {sy}}} -force_to_die_boundary")
    put("W", west, M, H - M)
    put("N", north, M, W / 2 - M)
    put("S", south, M, W / 2 - M)
    names = [l.split("{")[1].split("}")[0] for l in lines[1:]]
    assert len(names) == len(set(names)) == 2215 + len(north) + len(south)
    open(a.out, "w").write("\n".join(lines) + "\n")
    print(f"SFU_STORE_R8_PINS {len(names)} pins -> {a.out}")


if __name__ == "__main__":
    main()
