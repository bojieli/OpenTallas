def offsets(fields):
    """{name: (lsb, width)} for an MSB-first concatenation"""
    tot, out = sum(w for _, w in fields), {}
    pos = tot
    for n, w in fields:
        pos -= w
        out[n] = (pos, w)
    return out


def sel(net, lsb, w):
    return f"{net}[{lsb}]" if w == 1 else f"{net}[{lsb + w - 1}:{lsb}]"


