def ranges(ports, centre):
    tot = sum(w for _, w in ports) * PITCH
    lo, out = round(centre - tot / 2, 3), {}
    for n, w in ports:
        hi = round(lo + w * PITCH, 3)
        out[n] = [lo, hi]
        lo = round(hi + 0.4, 3)
    return out


