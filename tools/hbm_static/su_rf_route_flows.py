#!/usr/bin/env python3
"""Per-stage relay flow vectors for the 16 SU RF routes (H-SM 2026-10-15).

Input: H-DIE's su_rf_route_pins.json (compact660_v5): per route the pin-to-pin path (channel / relay-row polyline) and
RF_RELAY (= max stages over the 16 routes at the reach).  Every route is padded to RF_RELAY stages (equal static
latency, compiler RF deadline = n + 12 + RF_RELAY).  The route's own stages sit at equal spacing L / (N + 1) along the
path (N = ceil(L / reach) - 1, so every hop <= reach); the RF_RELAY - N padding stages sit at the destination pin.
Each stage's hard relay master is chosen from the direction of travel at its home:
  FLOW 0 = hbfd_rly_48_WE (x increasing), 1 = _EW (x decreasing), 2 = _SN (y increasing), 3 = _NS (y decreasing).
Output: a JSON record + an SV include with one localparam FLOWS_<src>_<dst> [2*RF_RELAY-1:0] per route (stage k in bits
[2k+1:2k]) for ot_hbm_su_rf_route #(.STAGES(RF_RELAY), .FLOWS(...)).
"""
import argparse, json, math, pathlib


def direction(a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    if abs(dx) >= abs(dy):
        return 0 if dx > 0 else 1
    return 2 if dy > 0 else 3


def route_stages(path, reach, total):
    segs = [(path[i], path[i + 1]) for i in range(len(path) - 1)]
    lens = [math.dist(a, b) for a, b in segs]
    L = sum(lens)
    n = max(0, math.ceil(L / reach) - 1) if L > 0 else 0
    if n > total:
        raise SystemExit(f'route needs {n} stages > RF_RELAY {total}')
    # direction at a path position s (skip zero-length segments)
    live = [(a, b, l) for (a, b), l in zip(segs, lens) if l > 1e-6]
    last_dir = direction(live[-1][0], live[-1][1]) if live else 0
    homes = []
    for k in range(1, n + 1):
        s = L * k / (n + 1)
        acc = 0.0
        for a, b, l in live:
            if s <= acc + l:
                t = (s - acc) / l
                homes.append(dict(xy=[round(a[0] + t * (b[0] - a[0]), 3), round(a[1] + t * (b[1] - a[1]), 3)],
                                  flow=direction(a, b), pad=False))
                break
            acc += l
    for _ in range(total - n):
        homes.append(dict(xy=list(path[-1]), flow=last_dir, pad=True))
    hop = L / (n + 1) if L > 0 else 0.0
    return L, n, hop, homes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pins', default='results/arch/hbm_die_v15/compact660_v5/su_rf_route_pins.json')
    ap.add_argument('--out', default='results/arch/hbm_su_f2_static_1014/register_file/rf_route_1103/rf_route_flows_v5.json')
    ap.add_argument('--svh', default='rtl/hbm_accel/generic/adapters/static_su/register_file/ot_hbm_su_rf_route_flows_v5.svh')
    a = ap.parse_args()
    d = json.load(open(a.pins))
    reach, total = float(d['reach_um']), int(d['RF_RELAY'])
    routes, lines = [], []
    for r in d['routes']:
        L, n, hop, homes = route_stages(r['path'], reach, total)
        if r.get('stages_at_reach') is not None and int(r['stages_at_reach']) != n:
            raise SystemExit(f"{r['src']}>{r['dst']}: stages {n} != H-DIE stages_at_reach {r['stages_at_reach']}")
        flows = 0
        for k, h in enumerate(homes):
            flows |= h['flow'] << (2 * k)
        name = f"FLOWS_{r['src']}_{r['dst']}"
        lines.append(f"localparam [{2 * total - 1}:0] {name} = {2 * total}'h{flows:0{(2 * total + 3) // 4}x};")
        routes.append(dict(src=r['src'], dst=r['dst'], length_um=round(L, 1), route_stages=n, pad_stages=total - n,
                           max_hop_um=round(hop, 1), flows_hex=f'{flows:x}', homes=homes))
    out = dict(schema='opentallas.hbm_su_rf_route_flows.v1', pins=a.pins, reach_um=reach, RF_RELAY=total,
               relay_masters=16 * total, relay_flops=16 * total * 48,
               flow_code={'0': 'hbfd_rly_48_WE', '1': 'hbfd_rly_48_EW', '2': 'hbfd_rly_48_SN', '3': 'hbfd_rly_48_NS'},
               compiler='RF write commit n + 12 + RF_RELAY (ot_hbm_su_static_top RF_RELAY parameter); equal on all 16 routes',
               routes=routes)
    pathlib.Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    json.dump(out, open(a.out, 'w'), indent=1)
    hdr = ['// generated by tools/hbm_static/su_rf_route_flows.py from ' + a.pins + ' -- do not edit',
           f'localparam integer RF_ROUTE_STAGES_V5 = {total};'] + lines
    pathlib.Path(a.svh).write_text('\n'.join(hdr) + '\n')
    print(json.dumps(dict(RF_RELAY=total, routes={f"{x['src']}>{x['dst']}": [x['route_stages'], x['max_hop_um']] for x in routes})))


if __name__ == '__main__':
    main()
