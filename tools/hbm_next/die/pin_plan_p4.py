#!/usr/bin/env python3
"""HBM-NEXT-DIE 10-19: top-down pin plan for the P = 4 tiles and parents (owner rule 10-13: die tools assign pins of
new / unclosed tiles and cluster parents; tile kits consume the file).

hnx_rp4lp4 (SM P = 4 matrix tile, 2 leaves x 4 lanes): the lane addressing is internal (x-target / result-lane
registers, lane-major publish), so the tile PIN SET is the rp4lp set unchanged (D2 3.1, 'SM column pin set unchanged');
only the outline grows 457.92 x 1598.4 -> TW x TH.  Every pin keeps its face, layer and order; positions are scaled by
the face growth (x by TW / 457.92 on N/S, y by TH / 1598.4 on W/E), so abutting tiles in the 4 x 4 column grid stay
aligned (rin/rout, bin/bout, gin/gout, xs/xss pairs) and pin density falls by the growth factor; grid 0.024 um.
Pin registers by default (pin_regs.json of the rp4lp kit carries over).  hnx_rp4a4 (attention variant) = the same set
plus the ATT4 line-mask input (pending ATT4 geometry.json).
SM column parent and COLL: face bits / pins per um / densest 10-um window from the plan pin model (v6_eval pins).

    pin_plan_p4.py --plan results/arch/hbm_next_1019/die/plan/f4c --tag f4c --out physical/hbm_next/die/f4c
"""
import argparse, collections, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'physical/hbm_next/die/frame_d4g_copy/smh_tile_rp4lp_pins.tcl'   # claude/pl-smt-1018 copy
TW0, TH0 = 457.92, 1598.4


def face_of(x, y):
    if abs(x) < 1e-6:
        return 'W'
    if abs(x - TW0) < 1e-3:
        return 'E'
    if abs(y) < 1e-6:
        return 'S'
    return 'N'


def win(vals, w=10.0):
    vals = sorted(vals); best = 0; j = 0
    for i in range(len(vals)):
        while vals[i] - vals[j] > w:
            j += 1
        best = max(best, i - j + 1)
    return best


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--plan', required=True); ap.add_argument('--tag', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--tile-w', type=float, default=673.92); ap.add_argument('--tile-h', type=float, default=1684.8)
    a = ap.parse_args()
    out = ROOT / a.out; out.mkdir(parents=True, exist_ok=True)
    TW, TH = a.tile_w, a.tile_h
    sx, sy = TW / TW0, TH / TH0
    rx = re.compile(r'-pin_name \{([^}]+)\} -layer (\S+) -location \{([\d.]+) ([\d.]+)\}(.*)$')
    lines = [f'# HBM-NEXT-DIE 10-19 pin plan for hnx_rp4lp4 ({TW} x {TH}); generated by tools/hbm_next/die/pin_plan_p4.py from '
             f'the rp4lp pin file (claude/pl-smt-1018, {TW0} x {TH0}): same pins / faces / layers / order, positions scaled x{sx:.4f} (N/S) '
             f'and x{sy:.4f} (W/E)']
    faces = collections.defaultdict(list); faces0 = collections.defaultdict(list); clocks = {}
    for ln in SRC.read_text().splitlines():
        m = rx.search(ln)
        if not m:
            continue
        name, layer, x, y, rest = m.group(1), m.group(2), float(m.group(3)), float(m.group(4)), m.group(5)
        f = face_of(x, y)
        if f in ('W', 'E'):
            nx, ny = (0.0 if f == 'W' else TW), y * sy
            faces[f].append(ny); faces0[f].append(y)
        else:
            nx, ny = x * sx, (0.0 if f == 'S' else TH)
            faces[f].append(nx); faces0[f].append(x)
        nx, ny = round(round(nx / 0.024) * 0.024, 3), round(round(ny / 0.024) * 0.024, 3)
        if name in ('ck_n', 'ck_s', 'clk'):
            clocks[name] = dict(face=f, at=[nx, ny])
        lines.append(f'place_pin -pin_name {{{name}}} -layer {layer} -location {{{nx:.3f} {ny:.3f}}}{rest}')
    (out / 'hnx_rp4lp4_pins.tcl').write_text('\n'.join(lines) + '\n')
    tile = {}
    for f in ('N', 'S', 'W', 'E'):
        L, L0 = (TW, TW0) if f in ('N', 'S') else (TH, TH0)
        v, v0 = faces[f], faces0[f]
        tile[f] = dict(pins=len(v), face_um=L, span_um=round(max(v) - min(v), 1) if v else 0, pins_per_um_face=round(len(v) / L, 2),
                       densest_10um=win(v), densest_10um_rp4lp=win(v0), span_um_rp4lp=round(max(v0) - min(v0), 1) if v0 else 0)
    # parent / COLL from the plan pin model
    pd = ROOT / a.plan
    pins = json.loads((pd / 'pins' / f'{a.tag}.pins.json').read_text())
    P = json.loads((pd / 'compact.P.json').read_text())
    par = {}
    for b, v in pins['blocks'].items():
        if not re.match(r'^(sm_|coll_)', b):
            continue
        r = P[b]; fo = {}
        for f, fx in v['faces'].items():
            L = r['w'] if f in ('N', 'S') else r['h']
            bits = sum(p['bits'] for p in fx['pins'])
            pos = [p['x'] if f in ('N', 'S') else p['y'] for p in fx['pins']]
            cls = collections.Counter()
            for p in fx['pins']:
                cls[p['cls']] += p['bits']
            fo[f] = dict(bits=bits, face_um=round(L, 1), bits_per_um_face=round(bits / L, 2), links=len(fx['pins']), classes=dict(cls),
                         span_um=round(max(pos) - min(pos), 1) if pos else 0)
        par[b] = fo
    worst = {}
    for b, fo in par.items():
        for f, d in fo.items():
            k = b.split('_')[0] + '_' + f
            worst[k] = max(worst.get(k, 0), d['bits_per_um_face'])
    res = dict(schema='opentallas.hbm_next.pin_plan.v1', tag=a.tag, rule='owner 10-13 top-down pins; <= 6 pins/um on full faces; pin registers by default',
               hnx_rp4lp4=dict(outline_um=[TW, TH], source='physical/hbm_next/die/frame_d4g_copy/smh_tile_rp4lp_pins.tcl (claude/pl-smt-1018)',
                               file=f'{a.out}/hnx_rp4lp4_pins.tcl', faces=tile, clocks=clocks,
                               note='pin set unchanged (lane addressing internal); clock entries ck_n / ck_s keep their relative face '
                                    'position (beside the register mass of each landed region); pin_regs.json of rp4lp carries over'),
               hnx_rp4a4=dict(outline_um=[TW, TH], rule='hnx_rp4lp4 set + ATT4 line-mask input (P-bit lane mask per KV line) on the N face '
                              'next to gin; pending results/arch/hbm_next_1019/att4/geometry.json'),
               parents=par, worst_bits_per_um_by_kind_face=worst)
    (out / f'pin_plan_{a.tag}.json').write_text(json.dumps(res, indent=1))
    print(json.dumps(dict(tile={f: (d['pins'], d['pins_per_um_face'], d['densest_10um'], d['densest_10um_rp4lp']) for f, d in tile.items()}, worst=worst)))


if __name__ == '__main__':
    main()
