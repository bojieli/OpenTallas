"""HEAD hd_serdes PHY clock / CDC packet (DIE-HEAD-9, COORD 06:09 + 06:30 rulings 2026-10-28).

Runs the reviewed_gray_fifos engine (tools/ref_tile/gray_fifo_cdc_constraints.py, rules a-d, exact BDD/SAT proofs over
the actual Yosys elaboration) on ot_s81hd_serdes_cdc, the shell that holds EVERY pma_rck <-> clk dependence of the head
SerDes link (rtl/dsrom_sys/s81_head/ot_s81hd_serdes_link.sv), and writes:
  record.json      roles / fifos / levels / resets of the admitted crossings
  cdc_shell.sdc    clock_entry_constraints.generate() output for the shell (families core 833.333 | serdes 833.333)
  phy_clocks.sdc   the hd_serdes partition clock roles: pma_tck generated from clk, pma_rck primary at the word rate,
                   pma_tx / pma_rx timed against their PMA clocks (pma IO budgets UNCHECKED: no PMA spec yet)
The enc/dec/PMA models are single-clock modules (one clock port each, every input from their own family), so they hold
no crossing; the shell census is therefore the whole link's census.  Usage: head_serdes_cdc.py OUTDIR [--mut N]
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools' / 'ref_tile'))
import clock_entry_constraints as C          # noqa: E402
import gray_fifo_cdc_constraints as G        # noqa: E402

LINK = 'rtl/dsrom_sys/s81_head/ot_s81hd_serdes_link.sv'
SOURCES = [G.RESET_SYNC[1], G.REVIEWED['ot_s81_rate_match']['path'], LINK]
CDC_INST = 'u_phy/u_link/u_cdc'              # shell path inside the hd_serdes partition (contents u_phy)


def spec(mut=0, levels=None):
    lv = [dict(name='lock', source='lock_r', chain=['lk_s[0]', 'lk_s[1]'],
               why='#5 FEC lock level (pma_rck) -> clk status, rule (d)'),
          dict(name='unc', source='unc_r', chain=['uf_s[0]', 'uf_s[1]'],
               why='#6 sticky uncorrectable-frame level (pma_rck) -> clk status, rule (d)')] if levels is None else levels
    return dict(name='hd_serdes_cdc', top='ot_s81hd_serdes_cdc', kind='tile', sources=list(SOURCES),
                params=dict(MUT=mut), clock='multiple_cts_roots', clock_port='clk', clock_ports=['clk', 'pma_rck'],
                clock_data_paths=G.POLICY,
                clock_relationship=dict(kind=G.RELATIONSHIP_KIND, periods_ps=dict(core=833.333, serdes=833.333)),
                clock_entry_domains=dict(
                    core=dict(ratio=G.family_ratio('core'), ports=['clk'], inputs=['rst', 'e_flt'],
                              outputs=['rn_t', 'rx', 'st']),
                    serdes=dict(ratio=G.family_ratio('serdes'), ports=['pma_rck'],
                                inputs=['q_v', 'q_d', 'q_first', 'q_unc', 'lock'], outputs=['rn_r'])),
                reviewed_gray_fifo_extensions=dict(level_synchronizers=lv,
                                                   why='HEAD SerDes status levels outside the rate matcher'))


PHY_SDC = """# hd_serdes PHY clock roles (DIE-HEAD-9 2026-10-28, COORD 06:09 ruling). Generated by tools/s81_head/head_serdes_cdc.py.
# TX: pma_tck is the forwarded TX word clock = clk (assign in ot_s81hd_pdie_serdes); pma_tx launches on clk.
create_generated_clock -name pma_tck -source [get_ports clk] -divide_by 1 [get_ports pma_tck]
set_output_delay -max {omax} -clock pma_tck [get_ports {{pma_tx[*]}}]   ;# PMA TX budget UNCHECKED (no PMA spec)
set_output_delay -min {omin} -clock pma_tck [get_ports {{pma_tx[*]}}]
# RX: recovered word clock = primary clock at the KP4 word rate (plesiochronous with clk: own family 'serdes').
create_clock -name pma_rck -period 833.333 [get_ports pma_rck]
set_input_delay -max {imax} -clock pma_rck [get_ports {{pma_rx[*]}}]  ;# source-synchronous to pma_rck, UNCHECKED budget
set_input_delay -min {imin} -clock pma_rck [get_ports {{pma_rx[*]}}]
# CDC: only the engine-proved crossings of {inst} (cdc_shell.sdc: set_max/min_delay -ignore_clock_latency on the
# actual launch -> D / async pins); no set_clock_groups / set_false_path between clk and pma_rck.
"""


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--mut', type=int, default=0)
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    s = spec(a.mut)
    record = G.lint(s, ROOT)
    (out / 'record.json').write_text(json.dumps(record, indent=1, sort_keys=True, default=sorted))
    (out / 'cdc_shell.sdc').write_text(C.generate(s, ROOT))
    (out / 'phy_clocks.sdc').write_text(PHY_SDC.format(omax=166.667, omin=0.0, imax=166.667, imin=-40.0, inst=CDC_INST))
    f = record['fifos']
    print(json.dumps(dict(fifos={k: (v['module'], v['writer'], v['reader'], v['chains'], v['storage_bits'],
                                     v['pointer_max_delay_ps'], v['storage_max_delay_ps']) for k, v in f.items()},
                          levels=record.get('levels'), resets=record.get('resets')), default=sorted))


if __name__ == '__main__':
    main()
