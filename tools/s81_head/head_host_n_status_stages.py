#!/usr/bin/env python3
"""DIE-HEAD-53 (hd_host_n, plan l48x frozen, one-block fix): cut the cross-block landing STATUS reductions.

hd_host_n (1442.88 x 656.64 um) lands five rings on three faces (au W, ad/bd/h_tx_ft N, bu E) and drives four LOCAL
status outputs cland_up_{ready,fault}_<b> on three faces (ad_o W, bd_o E, bu_o/h_rx_ft_o N).  Each local output is
ONE ot_dp_landing_collect of all five landing_ready/landing_fault bits, so e.g. bu_i (E) -> cland_up_ready_ad_o (W)
is ~1.42 mm of wire in one 833 ps cycle (TT placement STA -362 ps on u_cland_up_bd_o, all eight up_{ad,bd,bu,h_rx}
collector flops negative; Yosys also shares one AND tree between the four identical collectors, which pulls it to
the centroid of the inputs).

Fix: the existing opt-in plan knob clock.landing_status_input_stages (DIE-HEAD-38 R2; precedent hd_st_str /
hd_st_m / hd_st_n4 / hd_st_k5 local outputs): n registered 1-input ot_dp_landing_collect relays on ONE ring's
ready/fault before the target's N-input collect, at sites evenly spaced on the straight line from the ring's
landing band centre to the target status pin.  n = ceil(d / hop) - 1 with d the Manhattan distance.
  variant a: hop 900 um  (only the >900 um pairs; max +1 status cycle per input)
  variant b: hop 700 um  (every >700 um pair; >1400 um pairs get 2 stages, max +2 status cycles)
Status only (ready = level AND, fault = sticky OR, both monotone through a relay), 0 data cycles; the landing ring,
its CA protocol, depth and every data path are unchanged.

usage: head_host_n_status_stages.py ROOT SOURCE_DIR OUT_SOURCE_DIR {a|b|a2|b2|c2}
Writes OUT_SOURCE_DIR = SOURCE_DIR (symlinks) + edited source_plan.json + the republished ot_s81hd_host_nstrip.sv
regenerated by gen.py phys exactly as head_rekit_current.py does (so its published-source equality check holds),
and stages_receipt.json.  The source dir is never modified."""
import json, math, re, subprocess, sys, tempfile
from pathlib import Path

TYPE = "hd_host_n"
HOP = {"a": 900.0, "b": 700.0, "a2": 900.0, "b2": 700.0, "c2": 500.0}
# *2 variants (round 2, after the a/b placement STA): the status data paths closed; the next limiters were (1) the ONE raw
# ring reset u_cland_rst_ad_i (synchronous rst_n of every collect, placed mid-block) driving the face collectors
# u_cland_up_bd_o / u_cland_fstart_bd_o (E) and u_cland_up_ad_o (W) ~1 mm away, and (2) bu_i (E) -> u_cland_agg_1
# (placed at the bands' centroid).  Fixed with the two other existing opt-in knobs: clock.landing_local_resets
# (DIE-HEAD-38 R1: kept same-depth reset copies from a depth-3 wavefront relay next to the consumers; the generator
# proves depth(raw)+1 == depth(old), so every release edge is unchanged) and an "agg" target in
# landing_status_input_stages.
LOCAL_RESETS = [dict(name="e", raw="rst_rl_7", xy_um=[1400.0, 262.0], consumers=["u_cland_up_bd_o", "u_cland_fstart_bd_o"]),
                dict(name="w", raw="rst_rl_13", xy_um=[40.0, 262.0], consumers=["u_cland_up_ad_o", "u_cland_fstart_ad_o"])]


def stages_for(t, hop):
    lc = t["clock"]["landing_contract"]
    pins = {p["name"]: p["xy_um"] for p in lc["pins"]}
    bands = lc["bands"]
    outs = sorted(n[len("cland_up_ready_"):] for n in pins if n.startswith("cland_up_ready_"))
    cfg, rows = {}, []
    for b in outs:
        px, py = pins["cland_up_ready_" + b]
        for ring, band in sorted(bands.items()):
            r = band["rect_um"]
            cx, cy = (r[0] + r[2]) / 2, (r[1] + r[3]) / 2
            d = abs(px - cx) + abs(py - cy)
            n = max(0, math.ceil(d / hop) - 1)
            rows.append(dict(target=b, ring=ring, d_um=round(d, 1), stages=n))
            if n:
                cfg.setdefault(b, {})[ring] = [
                    {"xy_um": [round(cx + (px - cx) * (k + 1) / (n + 1), 3), round(cy + (py - cy) * (k + 1) / (n + 1), 3)]}
                    for k in range(n)]
    return cfg, rows


def agg_stages(t, hop):
    """agg target = the N-input u_cland_agg_1, which the placer puts at the centroid of the landing bands."""
    bands = {k: v["rect_um"] for k, v in t["clock"]["landing_contract"]["bands"].items()}
    cen = {k: ((r[0] + r[2]) / 2, (r[1] + r[3]) / 2) for k, r in bands.items()}
    gx, gy = sum(c[0] for c in cen.values()) / len(cen), sum(c[1] for c in cen.values()) / len(cen)
    cfg, rows = {}, []
    for ring, (cx, cy) in sorted(cen.items()):
        d = abs(gx - cx) + abs(gy - cy); n = max(0, math.ceil(d / hop) - 1)
        rows.append(dict(target="agg", ring=ring, d_um=round(d, 1), stages=n))
        if n:
            cfg[ring] = [{"xy_um": [round(cx + (gx - cx) * (k + 1) / (n + 1), 3), round(cy + (gy - cy) * (k + 1) / (n + 1), 3)]}
                         for k in range(n)]
    return cfg, rows


def main():
    root, source, out = (Path(a).resolve() for a in sys.argv[1:4]); var = sys.argv[4]
    sys.path[:0] = [str(root / "tools/die_plan"), str(root / "tools/s81_head")]
    from head_count_strap_sites import apply as count_strap_sites
    from head_start_raw_private import prepare_plan
    from head_start_reset_aliases import patch_rtl
    plan = json.loads((source / "source_plan.json").read_text())
    t = plan["partition_types"][TYPE]
    if "landing_status_input_stages" in t["clock"]:
        raise SystemExit(f"{TYPE} already has landing_status_input_stages")
    # the tree bus (aggregate chain) is not a local status output: never a target here
    tree_bus = json.loads((source / "source_sidecar.json").read_text())["collector"]["types"][TYPE]["mask"].get("tree_bus")
    cfg, rows = stages_for(t, HOP[var])
    cfg.pop(tree_bus, None); rows = [r for r in rows if r["target"] != tree_bus]
    if var.endswith("2"):
        acfg, arows = agg_stages(t, HOP[var]); rows += arows
        if acfg:
            cfg["agg"] = acfg
        t["clock"]["landing_local_resets"] = LOCAL_RESETS
    t["clock"]["landing_status_input_stages"] = cfg
    out.mkdir(parents=True)
    module = t["module"]
    for f in source.iterdir():
        if f.name not in ("source_plan.json", f"{module}.sv"):
            (out / f.name).symlink_to(f.resolve())
    (out / "source_plan.json").write_text(json.dumps(plan, indent=1) + "\n")
    # regenerate the published wrapper exactly as head_rekit_current.py does before its private-raw copy
    p2, _ = count_strap_sites(json.loads(json.dumps(plan)), out / "source_plan.json", root, types={TYPE})
    p2, _ = prepare_plan(p2, {TYPE})
    with tempfile.TemporaryDirectory(dir=out) as td:
        td = Path(td); cand = td / "source_plan_rekit.json"; cand.write_text(json.dumps(p2, indent=1) + "\n")
        for f in source.iterdir():
            if f.is_dir():
                (td / f.name).symlink_to(f.resolve())
        cmd = [sys.executable, str(root / "tools/die_plan/gen.py"), "phys", str(cand), "--clock-landing",
               str(source / "source_sidecar.json"), "--types", TYPE, "--out", str(td / "gen"), "--rtl-root", str(root), "--trial"]
        r = subprocess.run(cmd, capture_output=True, text=True); (out / "stages_gen.log").write_text(r.stdout + r.stderr)
        if r.returncode:
            raise SystemExit(f"gen.py phys exit {r.returncode}: {(r.stdout + r.stderr)[-1500:]}")
        text = patch_rtl((td / "gen" / "_rtl" / f"{module}.sv").read_text(), p2["partition_types"][TYPE].get("reset_start_raw_exports", []))
    old = (source / f"{module}.sv").read_text()
    # the edit may only ADD status relays and rewire collector inputs: every removed line is a collect input line
    norm = lambda s: [l.strip() for l in s.splitlines() if l.strip()]
    removed = sorted(set(norm(old)) - set(norm(text)))
    bad = [l for l in removed if not re.match(r"\.clk\(clk\), \.rst_n\(\w+\), \.ready_i\(|\.fault_i\(", l)
           and not re.match(r"ot_dp_landing_relay u_cland_fstart_\w+ \(\.clk\(clk\), \.rst_raw_n\(", l)]
    if bad:
        raise SystemExit(f"unexpected removed RTL lines: {bad[:5]}")
    (out / f"{module}.sv").write_text(text)
    nst = sum(len(s) for rr in cfg.values() for s in rr.values())
    rec = dict(type=TYPE, variant=var, hop_um=HOP[var], tree_bus_untouched=tree_bus, source=str(source),
               landing_status_input_stages=cfg, pairs=rows, relay_stages=nst, flops_added=2 * nst,
               max_status_cycles_added=max((len(s) for rr in cfg.values() for s in rr.values()), default=0),
               data_cycles_added=0, collector_lines_rewired=len(removed),
               landing_local_resets=t["clock"].get("landing_local_resets"))
    (out / "stages_receipt.json").write_text(json.dumps(rec, indent=1) + "\n")
    print(json.dumps({k: rec[k] for k in ("variant", "relay_stages", "flops_added", "max_status_cycles_added", "collector_lines_rewired")}))


if __name__ == "__main__":
    main()
