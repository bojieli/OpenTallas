#!/usr/bin/env python3
"""LAND-HEAD-BIND-1: the 8-FT-port physical adapter of the hd_tile A/B hard cores for the LANDED form (12.11).

The signed core views (results/head_core_clockfreeze_release/elem{A,B}_signed, R16+) expose ft_mstrap_i (the functional
clock) plus EIGHT pass-through FT pins per core (ft_{ck0,ck1,mesh,rst}_{i,o}: the in-core island buffers, 12.2a1).
The plan leaf ot_s81hd_tile still instantiates the logical models with `.clk`, so its netlist does not bind to the
signed LEF.  This delta switches hd_tile to the explicit native variant (ot_s81hd_tile_native, generated by
tools/s81_head/head_native_sources.py: .clk -> ft_mstrap_i, all 40 FT pins as tile ports, zero added cycles) and binds
those 40 pins INSIDE the partition, because in the landed form region = partition: no die mesh crosses the core
islands, so there is no die infrastructure provider to bind them to (head_native_plan_delta's die-level infra_ports
would require one and fail closed).

Binding (declared, no ties):
  hci<k>_{ck0,ck1,mesh}_i <- clk     (the partition's region clock: island buffers are loads of the region tree)
  hci<k>_rst_i            <- rst_n   (the partition reset tap)
  hci<k>_*_o              -> ftspare:<port>, a declared unread wire with an owner (type ft_spare_outputs)
The clock topology itself (which island, if any, becomes a region-tree stage or a core entry leaf buffer) belongs to
LAND-HEAD-3; it may rebind any of these 40 pins by editing the plan's contents[0].bind / ft_spare_outputs.
The hard cores' lef/lib move to the signed views so the kit binds the same pins the netlist has.
"""
import argparse
import copy
import json
from pathlib import Path

FTS = ("ck0", "ck1", "mesh", "rst")
NATIVE = {"ot_s81hd_tile.sv": "ot_s81hd_tile_native.sv", "ot_s81hd_bundle.sv": "ot_s81hd_bundle_native.sv",
          "ot_s81hd_elem_cv_bb.v": "ot_s81hd_elem_cv_bb_native.v"}
SIGNED = {"ot_s81hd_elemA_cv": ("results/head_core_clockfreeze_release/elemA_signed/ot_s81hd_elemA_cv.lef",
                                "results/head_core_clockfreeze_release/elemA_signed/ot_s81hd_elemA_cv_tc.lib"),
          "ot_s81hd_elemB_cv": ("results/head_core_clockfreeze_release/elemB_signed/ot_s81hd_elemB_cv.lef",
                                "results/head_core_clockfreeze_release/elemB_signed/ot_s81hd_elemB_cv_tc.lib")}
OWNER = "LAND-HEAD-3"
REASON = "landed form: no die mesh/reset crosses this core island; region-tree use is LAND-HEAD-3's call"


class AdapterError(Exception):
    pass


def apply(raw, owner=OWNER, signed=SIGNED, repo=None):
    P = copy.deepcopy(raw)
    t = P["partition_types"]["hd_tile"]
    if len(t.get("contents", [])) != 1:
        raise AdapterError("hd_tile must have exactly one leaf")
    c = t["contents"][0]
    if c["module"] != "ot_s81hd_tile":
        raise AdapterError(f"hd_tile leaf is {c['module']}, expected the logical ot_s81hd_tile")
    if t.get("infra_ports") or t.get("ft_spare_outputs"):
        raise AdapterError("hd_tile already carries native infra ports / FT spares (adapter applied twice?)")
    c["module"] = "ot_s81hd_tile_native"
    srcs = t.get("sources", [])
    hit = [s for s in srcs if Path(s).name in NATIVE]
    if len(hit) != len(NATIVE):
        raise AdapterError(f"hd_tile sources lack {sorted(set(NATIVE) - {Path(s).name for s in hit})}")
    t["sources"] = [str(Path(s).with_name(NATIVE[Path(s).name])) if Path(s).name in NATIVE else s for s in srcs]
    bb = next(s for s in t["sources"] if Path(s).name == "ot_s81hd_elem_cv_bb_native.v")
    t["simulation_substitutions"] = {bb: str(Path(bb).with_name("ot_s81hd_elem_cv_native.sv"))}
    idx = {}
    for h in t["hard_cores"]:
        k = 4 if "elemB" in h["module"] else int(h["inst"][-1])
        if k in idx:
            raise AdapterError(f"duplicate core index {k}")
        idx[k] = h
        if signed:
            lef, lib = signed[h["module"]]
            if repo is not None and not ((Path(repo) / lef).is_file() and (Path(repo) / lib).is_file()):
                raise AdapterError(f"signed view of {h['module']} missing under {repo}")
            h["lef"], h["lib"] = lef, lib
    if sorted(idx) != [0, 1, 2, 3, 4]:
        raise AdapterError(f"expected cores 0..4, found {sorted(idx)}")
    bind = c.setdefault("bind", {})
    spares, rows = [], []
    for k in range(5):
        for n in FTS:
            pi, po = f"hci{k}_{n}_i", f"hci{k}_{n}_o"
            if pi in bind or po in bind:
                raise AdapterError(f"{pi}/{po} already bound")
            bind[pi] = "rst_n" if n == "rst" else "clk"
            bind[po] = f"ftspare:{po}"
            spares.append(dict(port=po, core=idx[k]["inst"], core_port=f"ft_{n}_o", owner=owner, reason=REASON))
            rows.append(dict(core=idx[k]["inst"], ft=n, input=pi, driver=bind[pi], output=po, output_use="declared unread"))
    t["ft_spare_outputs"] = spares
    rep = dict(schema="opentallas.head.landed_ft_adapter.v1", type="hd_tile", leaf="ot_s81hd_tile_native",
               cores=len(idx), ft_ports_per_core=8, ports_bound=len(rows) * 2, functional_clock="ft_mstrap_i <- ck (clk)",
               data_cycles_added=0, ties=0, spare_outputs=len(spares), owner=owner,
               signed_views={m: dict(lef=v[0], lib=v[1]) for m, v in (signed or {}).items()}, bindings=rows)
    return P, rep


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("plan", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    a = ap.parse_args()
    P, rep = apply(json.loads(a.plan.read_text()), repo=a.repo)
    a.out.write_text(json.dumps(P, indent=1) + "\n")
    a.out.with_suffix(".ft_adapter.json").write_text(json.dumps(rep, indent=1) + "\n")
    print(json.dumps({k: v for k, v in rep.items() if k != "bindings"}, indent=1))


if __name__ == "__main__":
    main()
