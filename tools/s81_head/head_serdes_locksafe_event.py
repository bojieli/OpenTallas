#!/usr/bin/env python3
"""DH81-SEQ (COORD 11-07 on OWNER 11-02 17:55 decision 1): HEAD plan event l48um_seq on a PREPARED plan dir, hd_serdes only.

Applies head_serdes_locksafe_delta.apply (u_phy -> ot_s81hd_serdes_link_ls LOCKSAFE=1 HOLD_EDGES=64, pad pma_lock, sources)
to SRC_PREPARED_DIR/source_plan.json, adds the physical site of the pad beside the pad clocks on the PHY side of the
strip (M7, not on any neighbour seam: no neighbour pin, bus, lane or outline moves), records the sequencer in the pma_rck
cdc_evidence, republishes the hd_serdes wrapper, adds the die ports to source/s81_head_top.sv and refreshes wave_prepare.json and SHA256SUMS.
Instance paths of u_phy.u_link.* (the hard children) do not change; the sidecar must stay byte-identical (asserted).
pma_lock timing: plain seam-input budget, no new exception; it lands only on the clear pins of its 2-flop synchroniser.

usage: head_serdes_locksafe_event.py SRC_PREPARED_DIR OUT_DIR --republish TOOLS_ROOT [--event l48um_seq] [--site X Y]
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

TYPE = "hd_serdes"
LAYER = "M7"
CDC_NOTE = ("; DH81-SEQ: the link reset is held by ot_pdie_pma_reset_hold on pma_rck (async assert on rst_n low or "
            "pma_lock low, 2-flop release synchroniser + 64-edge count), then the per-domain rs_t/rs_r synchronisers")


def apply_event(plan, site, hold_edges=64):
    import head_serdes_locksafe_delta as L
    out = L.apply(plan, hold_edges)
    t = out["partition_types"][TYPE]
    pad = [p for p in t["pads"] if p["name"] == L.PAD["name"]]
    assert len(pad) == 1
    pad[0]["layer"] = LAYER
    pad[0]["sites_um"] = [list(site)]
    rck = [p for p in t["clock"]["pad_clock"]["pins"] if p["name"] == "pma_rck"]
    assert len(rck) == 1 and "cdc_evidence" in rck[0]
    rck[0]["cdc_evidence"] += CDC_NOTE
    return out


def patch_source_top(path, parts):
    """prepared source/s81_head_top.sv (assembled top, not regenerated by republish): one die input + one instance binding per part."""
    t = path.read_text()
    for p in parts:
        decl = f"    input  wire [0:0] {p}_pma_rck,\n"
        conn = f".pma_rck({p}_pma_rck)"
        assert t.count(decl) == 1 and t.count(conn) == 1, p
        t = t.replace(decl, decl + f"    input  wire [0:0] {p}_pma_lock,\n")
        t = t.replace(conn, conn + f",\n        .pma_lock({p}_pma_lock)")
    path.write_text(t)


def default_site(plan):
    """One 8.64-um pad-clock step east of the eastern pad clock pin, same row."""
    pins = plan["partition_types"][TYPE]["clock"]["pad_clock"]["pins"]
    xs = [p["xy_um"] for p in pins]
    x = max(a[0] for a in xs)
    y = {a[1] for a in xs}
    assert len(y) == 1, xs
    return [round(x + 8.64, 4), y.pop()]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("src", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--republish", type=Path, required=True, help="tools root with gen.py and the wrapper RTL")
    ap.add_argument("--event", default="l48um_seq")
    ap.add_argument("--site", type=float, nargs=2)
    a = ap.parse_args(argv)
    root = a.republish.resolve()
    sys.path[:0] = [str(root / "tools/die_plan"), str(root / "tools/s81_head")]
    import head_cland_stage_delta as D
    import pad_clock as PC
    import schema
    if a.out.exists():
        raise SystemExit(f"{a.out} exists: an event never overwrites")
    base = json.loads((a.src / "source_plan.json").read_text())
    site = a.site or default_site(base)
    plan = apply_event(base, site)
    P = schema.Plan(json.loads(json.dumps(plan)))           # schema + fail-closed pad_clock validation
    PC.pins(P, TYPE)
    old_rec = json.loads((a.src / "wave_prepare.json").read_text())
    shutil.copytree(a.src, a.out, symlinks=True)
    D.writable(a.out)
    (a.out / "source_plan.json").write_text(json.dumps(plan, indent=1) + "\n")
    D.republish(a.out, root, [TYPE], a.out / "source_sidecar.json")
    parts = sorted(p["name"] for p in plan["partitions"] if p["type"] == TYPE)
    if (a.out / "source/s81_head_top.sv").is_file():
        patch_source_top(a.out / "source/s81_head_top.sv", parts)
    rec = json.loads((a.out / "wave_prepare.json").read_text())
    assert rec["sidecar_sha256"] == old_rec["sidecar_sha256"]
    for t, w in old_rec["published_wrappers"].items():
        if t != TYPE:
            assert rec["published_wrappers"][t] == w, t
    rec[a.event] = dict(event=a.event, tool="tools/s81_head/head_serdes_locksafe_event.py", type=TYPE,
                        base_prepared=str(a.src), base_prepared_plan_sha256=old_rec["prepared_plan_sha256"],
                        pad="pma_lock", pad_site_um=site, layer=LAYER, hold_edges=64, ff_per_link=9, mission_cycles=0,
                        boot_rck_edges=dict(guard=66, native_recovered_reset=68),
                        owner="OWNER 2026-11-02 17:55 decision 1; COORD 11-07 DH81-SEQ")
    (a.out / "wave_prepare.json").write_text(json.dumps(rec, indent=1) + "\n")
    sums = a.out / "SHA256SUMS"
    if sums.exists():
        lines = []
        for ln in sums.read_text().splitlines():
            _h, _, name = ln.partition("  ")
            p = a.out / name
            lines.append(f"{D.digest(p)}  {name}" if p.is_file() and not p.is_symlink() else ln)
        sums.write_text("\n".join(lines) + "\n")
    report = dict(event=a.event, type=TYPE, plan_sha256=rec["prepared_plan_sha256"], sidecar_sha256=rec["sidecar_sha256"],
                  base_plan_sha256=old_rec["prepared_plan_sha256"], wrapper=rec["published_wrappers"][TYPE], pad_site_um=site,
                  die_ports=[f"{p}_pma_lock" for p in parts])
    (a.out / "locksafe_report.json").write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
