#!/usr/bin/env python3
"""HEAD-CORE-LAT-R2 c3' kit (METHODOLOGY 12.8b, GEOM-REVIEW-16 06:37 PASS-COND [HEAD-CORE-LAT-R2 C2-PLACE]).

12.2a1 (OWNER 06:39) PUSHDOWN island: the v2 top-owned hole (OBS, row cut, keep-out) is removed; the die clock/reset
driver cells of the centre island are core netlist cells at plan-fixed coordinates, FIXED + dont_touch, wired only to
dedicated ft ports (quad.json die_cells / ft_ports).
Internal H-tree with in-core islands, computed from geometry BEFORE build (no post-measurement value):
  clk pin (centre island) -> CT_c BUFx24 at the centre -> trunk clk_t W/E along the ROM channel -> CT_w / CT_e at the
  channel ends -> N/S to 4 quadrant nodes CT_q<k> BUFx24 on reserved in-core islands (keep-out + rows cut, 8.64 x 8.64, 4.32 lattice, mirror-
  symmetric, equal Manhattan length from the centre) -> one TritonCTS tree per quadrant net clk_q<k> with EQUAL LEAF
  COUNT L per quadrant: cluster size = ceil(n_q / L) from the c2 placement sink census (load balance by construction,
  12.8d1).  ROM clock pins stay on their own short net clk_m (CT_m at the centre island), as in c2.
  No F4, no padding, no post-CTS clock ECO; POST_CTS = the structural CTS gate.  SDC clk source 0, gate bound 250/202.5.
usage: infra_island_kit_v3q.py SRC_V2_KIT DST QUAD_JSON
  QUAD_JSON: {"centre": c, "nodes": {"WS": [x,y], ...}, "size": {"WS": s, ...}, "diam": 40, "L": 128}
"""
import json, os, re, shutil, sys

src, dst, qj = sys.argv[1:4]
Q = json.load(open(qj))
os.makedirs(dst, exist_ok=True)
for f in os.listdir(src):
    if f in ('run', 'trial.log') or f.startswith(('gate', 'cts_gate', 'sta_', '4_')):
        continue
    p = os.path.join(src, f)
    (shutil.copytree(p, os.path.join(dst, f), dirs_exist_ok=True) if os.path.isdir(p) else shutil.copy2(p, dst))

H = 4.32
c = Q['centre']
for k, (x, y) in sorted(Q['nodes'].items()):
    assert abs(x / H - round(x / H)) < 1e-6 and abs(y / H - round(y / H)) < 1e-6, (k, x, y)
# ---- strip the v2 top-owned hole (12.2a1: LEF holes / parent cells inside a core are BANNED)
mp = open(dst + '/macro_place.tcl').read()
i = mp.find('# GENERATED by tools/s81_head/infra_island.py')
if i >= 0:
    mp = mp[:i]
open(dst + '/macro_place.tcl', 'w').write(mp)

# ---- PRE_GLOBAL_PLACE: pushdown island cells, FIXED + dont_touch, at plan coordinates (same every instance)
# die cells (12.2a1): connected ONLY through dedicated ft ports; core trunk cells CT_* (core-owned internal H-tree).
die = Q['die_cells']       # [[name, master, dx, dy, {pin: net}], ...]
core = [['CT_c', 'BUFx24_ASAP7_75t_R', c - 3.0, c - 0.27], ['CT_m', 'BUFx24_ASAP7_75t_R', c - 3.0, c - 0.54]]
xw = Q['nodes']['WS'][0]; xe = Q['nodes']['ES'][0]
core += [['CT_w', 'BUFx24_ASAP7_75t_R', xw, c], ['CT_e', 'BUFx24_ASAP7_75t_R', xe, c]]
core += [['CT_q' + k, 'BUFx24_ASAP7_75t_R', x, y] for k, (x, y) in sorted(Q['nodes'].items())]
g = ['# GENERATED by infra_island_kit_v3q.py (12.2a1 pushdown island + 12.8b internal H-tree nodes); runs after face_flops',
     'source /work/face_flops.tcl',
     'uplevel #0 {',
     'set pi_b [ord::get_db_block]; set pi_u [$pi_b getDbUnitsPerMicron]; set pi_db [ord::get_db]',
     'proc pi_free {me x0 y0 x1 y1} {',
     '  foreach i [$::pi_b getInsts] {',
     '    if {$i eq $me} continue',
     '    set st [$i getPlacementStatus]; if {$st ne "FIRM" && $st ne "LOCKED" && $st ne "FIXED" && ![string match "u_isl_*" [$i getName]] && ![string match "CT_*" [$i getName]]} continue',
     '    set z [$i getBBox]',
     '    if {[$z xMin] < $x1 && [$z xMax] > $x0 && [$z yMin] < $y1 && [$z yMax] > $y0} { return 0 } }',
     '  return 1',
     '}',
     'proc pi_cell {nm mn x y} {',
     '  set m [$::pi_db findMaster $mn]; set w [$m getWidth]; set h [$m getHeight]',
     '  set yy [expr {round($y * $::pi_u)}]; set row ""',
     '  foreach r [$::pi_b getRows] { set z [$r getBBox]; if {[$z yMin] <= $yy && $yy < [$z yMax]} { set row $r; break } }',
     '  if {$row eq ""} { error "PI no row at $nm $x $y" }',
     '  set z [$row getBBox]; set sw [[$row getSite] getWidth]',
     '  set x0 [expr {[$z xMin] + round((round($x * $::pi_u) - $w / 2 - [$z xMin]) / double($sw)) * $sw}]',
     '  set i [odb::dbInst_create $::pi_b $m $nm]',
     '  return [pi_cell_at $i $x $y]',
     '}',
     'proc pi_cell_at {i x y} {',
     '  set m [$i getMaster]; set w [$m getWidth]; set nm [$i getName]; set mn [$m getName]',
     '  set yy [expr {round($y * $::pi_u)}]; set row ""',
     '  foreach r [$::pi_b getRows] { set z [$r getBBox]; if {[$z yMin] <= $yy && $yy < [$z yMax]} { set row $r; break } }',
     '  if {$row eq ""} { error "PI no row at $nm $x $y" }',
     '  set z [$row getBBox]; set sw [[$row getSite] getWidth]',
     '  set x0 [expr {[$z xMin] + round((round($x * $::pi_u) - $w / 2 - [$z xMin]) / double($sw)) * $sw}]',
     '  $i setOrient [$row getOrient]',
     '  for {set t 0} {$t < 400} {incr t} {',
     '    set dx [expr {(($t + 1) / 2) * ($t % 2 ? 1 : -1) * $sw}]',
     '    if {[pi_free $i [expr {$x0 + $dx}] [$z yMin] [expr {$x0 + $dx + $w}] [$z yMax]]} break',
     '  }',
     '  $i setLocation [expr {$x0 + $dx}] [$z yMin]; $i setPlacementStatus FIRM; $i setPlacementStatus FIXED; $i setDoNotTouch 1',
     '  puts [format "PI_CELL %s %s %.3f %.3f shift_sites %d" $nm $mn [expr {($x0 + $dx) / double($::pi_u)}] [expr {[$z yMin] / double($::pi_u)}] [expr {$dx / $sw}]]',
     '  return $i',
     '}',
     'proc pi_fix {nm lx ly} {',
     '  set i [$::pi_b findInst $nm]; if {$i eq "NULL"} { error "PI no inst $nm" }',
     '  set m [$i getMaster]; set w [$m getWidth]',
     '  set ins [pi_cell_at $i [expr {$lx + $w / 2.0 / $::pi_u}] [expr {$ly + 0.135}]]',
     '}',
     'proc pi_net {nm} { set n [$::pi_b findNet $nm]; if {$n eq "NULL"} { set n [odb::dbNet_create $::pi_b $nm] }; return $n }',
     'proc pi_port {nm dir x y} {',
     '  set n [pi_net $nm]; set bt [odb::dbBTerm_create $n $nm]; $bt setIoType $dir; $bt setSigType SIGNAL',
     '  set bp [odb::dbBPin_create $bt]; set l [[ord::get_db_tech] findLayer M5]',
     '  set h [expr {round(0.096 * $::pi_u)}]; set cx [expr {round($x * $::pi_u)}]; set cy [expr {round($y * $::pi_u)}]',
     '  odb::dbBox_create $bp $l [expr {$cx - $h}] [expr {$cy - $h}] [expr {$cx + $h}] [expr {$cy + $h}]',
     '  $bp setPlacementStatus FIRM',
     '  puts "PI_PORT $nm $dir $x $y M5"',
     '}']
for nm, mn, lx, ly, conn in die:
    g.append('pi_fix %s %.3f %.3f' % (nm, lx, ly))
for nm, mn, x, y in core:
    g.append('pi_cell %s %s %.3f %.3f' % (nm, mn, x, y))
g += ['puts "PI_ISLAND pushdown done"', '}']
open(dst + '/pre_gpl_island.tcl', 'w').write('\n'.join(g) + '\n')

# ---- PRE_CTS: wire the trunk + sink re-wiring + per-quadrant TritonCTS (equal leaf count)
t = ['# GENERATED by infra_island_kit_v3q.py: c3\' internal H-tree trunk (12.8b), plan values recorded in quad.json',
     'set b [ord::get_db_block]; set u [$b getDbUnitsPerMicron]',
     'set clk [$b findNet clk]',
     'proc v3q_net {nm} { set n [odb::dbNet_create $::b $nm]; $n setSigType CLOCK; return $n }',
     'set ct_c [$b findInst CT_c]; set ct_m [$b findInst CT_m]',
     'set clk_t [v3q_net clk_t]; set clk_m [v3q_net clk_m]',
     '[$ct_c findITerm Y] connect $clk_t; [$ct_m findITerm Y] connect $clk_m',
     'set ct_w [$b findInst CT_w]; set ct_e [$b findInst CT_e]',
     'set clk_tW [v3q_net clk_tw]; set clk_tE [v3q_net clk_te]',
     '[$ct_w findITerm A] connect $clk_t; [$ct_e findITerm A] connect $clk_t',
     '[$ct_w findITerm Y] connect $clk_tW; [$ct_e findITerm Y] connect $clk_tE',
     'set q_net {}']
for k in sorted(Q['nodes']):
    t += ['set ct_%s [$b findInst CT_q%s]' % (k, k),
          'set clk_%s [v3q_net clk_q%s]; [$ct_%s findITerm Y] connect $clk_%s; [$ct_%s findITerm A] connect $clk_t%s' % (k, k, k, k, k, k[0]),
          'dict set q_net %s $clk_%s' % (k, k)]
t += ['set cnt [dict create WS 0 WN 0 ES 0 EN 0 M 0]',
      'foreach it [$clk getITerms] {',
      '  set inst [$it getInst]',
      '  if {[$it getIoType] ne "INPUT"} continue',
      '  if {[string match "u_isl_*" [$inst getName]]} continue',
      '  set m [$inst getMaster]',
      '  $it disconnect',
      '  if {[$m isBlock]} { $it connect $clk_m; dict incr cnt M; continue }',
      '  set bb [$inst getBBox]',
      '  set x [expr {([$bb xMin] + [$bb xMax]) / 2.0 / $u}]; set y [expr {([$bb yMin] + [$bb yMax]) / 2.0 / $u}]',
      '  set k [expr {$x < %.3f ? "W" : "E"}][expr {$y < %.3f ? "S" : "N"}]' % (c, c),
      '  $it connect [dict get $q_net $k]; dict incr cnt $k',
      '}',
      '[$ct_c findITerm A] connect $clk; [$ct_m findITerm A] connect $clk',
      'puts "V3Q_TRUNK sinks $cnt"']
for k in sorted(Q['nodes']):
    t.append('log_cmd clock_tree_synthesis -clk_nets clk_q%s -sink_clustering_enable -repair_clock_nets '
             '-sink_clustering_size %d -sink_clustering_max_diameter %g -dont_use_dummy_load' % (k, Q['size'][k], Q['diam']))
t.append('puts "V3Q_CTS quadrants done"')
open(dst + '/pre_cts_trunk.tcl', 'w').write('\n'.join(t) + '\n')
json.dump(Q, open(dst + '/quad.json', 'w'), indent=1)

# ---- netlist pushdown (12.2a1): after `make synth`, patch 1_synth.odb: remove the clk / rst_n ports, add the ft ports,
# instantiate the island cells (dont_touch) and wire them; the core clock net 'clk' is then driven by u_isl_root.
ps = ['# GENERATED by infra_island_kit_v3q.py: 12.2a1 pushdown netlist patch of 1_synth.odb',
      'read_db $::env(ODB_IN)', 'set b [ord::get_db_block]',
      'foreach p {%s} { set bt [$b findBTerm $p]; if {$bt ne "NULL"} { odb::dbBTerm_destroy $bt; puts "PS removed port $p" } }' % ' '.join(Q.get('remove_ports', [])),
      'proc ps_net {nm} { set n [$::b findNet $nm]; if {$n eq "NULL"} { set n [odb::dbNet_create $::b $nm] }; return $n }']
for nm, d, x, y in Q['ft_ports']:
    ps.append('set bt [odb::dbBTerm_create [ps_net %s] %s]; $bt setIoType %s; $bt setSigType SIGNAL' % (nm, nm, d))
for nm, mn, lx, ly, conn in Q['die_cells']:
    ps.append('set i [odb::dbInst_create $b [[ord::get_db] findMaster %s] %s]' % (mn, nm))
    for pin, net in conn.items():
        ps.append('[$i findITerm %s] connect [ps_net %s]' % (pin, net))
    ps.append('$i setDoNotTouch 1')
ps += ['foreach n {clk} { [$b findNet $n] setSigType CLOCK }', 'write_db $::env(ODB_IN)', 'puts "PS pushdown done"']
open(dst + '/patch_synth.tcl', 'w').write('\n'.join(ps) + '\n')
io = [l for l in open(dst + '/io.tcl').read().splitlines() if not re.match(r'place_pin -pin_name \{(clk|rst_n)\}', l)]
for nm, d, x, y in Q['ft_ports']:
    io.append('place_pin -pin_name {%s} -layer M5 -location {%.4f %.4f} -pin_size {0.1920 0.1920}' % (nm, x, y))
open(dst + '/io.tcl', 'w').write('\n'.join(io) + '\n')

cm = open(dst + '/config.mk').read()
cm = re.sub(r'^(override )?export OT_VCLK_TT\s*\??=.*$', 'export OT_VCLK_TT = 250', cm, flags=re.M)
cm = re.sub(r'^(override )?export OT_VCLK_FF\s*\??=.*$', 'export OT_VCLK_FF = 202.5', cm, flags=re.M)
cm = re.sub(r'^override export (CTS_ARGS|POST_CTS_TCL|PRE_CTS_TCL|OT_F4_NEXT_TCL|PRE_GLOBAL_PLACE_TCL)\s*=.*$', '', cm, flags=re.M)
cm += '''
# HEAD-CORE-LAT-R2 c3' (12.8b, GEOM-REVIEW-16 PASS-COND): internal H-tree, centre -> 4 quadrant islands, per-quadrant
# TritonCTS with equal leaf count (pre_cts_trunk.tcl, quad.json); the main CTS call only buffers the ROM net clk_m.
override export PRE_CTS_TCL = /work/pre_cts_trunk.tcl
override export PRE_GLOBAL_PLACE_TCL = /work/pre_gpl_island.tcl
override export CTS_ARGS = -clk_nets clk_m -sink_clustering_enable -repair_clock_nets -dont_use_dummy_load
override export POST_CTS_TCL = /work/post_cts_gate.tcl
'''
open(dst + '/config.mk', 'w').write(cm)

s = open(dst + '/constraint.sdc').read()
s = re.sub(r'^# CP2 early core tap.*\n', '# 12.3 common latency: die delivers clk at T to the centre pin, no early tap\n', s, flags=re.M)
s, m = re.subn(r'^set_clock_latency -source -clock clk -?[0-9.]+ \[get_ports \{clk\}\]$',
               'set_clock_latency -source -clock clk 0.0 [get_ports {clk}]', s, flags=re.M)
assert m == 1
open(dst + '/constraint.sdc', 'w').write(s)   # synth-time SDC: ports clk / rst_n still exist
if Q.get('remove_ports'):   # post-patch SDC, copied over 1_synth.sdc after patch_synth.tcl
    s = s.replace('[get_ports {clk}]', '[get_ports {ft_mstrap_i}]').replace('[get_ports {rst_n}]', '[get_ports {ft_rst_i}]')
    open(dst + '/constraint_pd.sdc', 'w').write(s)
print('c3q kit', dst, Q)
