#!/usr/bin/env python3
"""Factor the exact HD-CTL sequencer instance into a die peer, without adding state."""
import re, json, hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
# dsfd_mtp_seq direction and width, literal default widths (FLIT512,NW21,UW10,G5).
PORTS=[('input',1,'rst','seq_rn'),('input',42,'f_cfg','{c_glen, c_plen}'),
 ('input',1,'f_rv','f_rv'),('input',512,'f_rd','f_rd'),('output',1,'t_rg','t_rg'),
 ('output',1,'t_tv','t_tv'),('output',512,'t_td','t_td'),('input',1,'f_tg','f_tg'),
 ('output',1,'t_sv','t_sv'),('output',77,'t_sd','t_sd'),('input',1,'f_sg','f_sg'),
 ('input',1,'f_wv','f_wv'),('input',10,'f_wd','f_wd'),('output',1,'t_wg','t_wg'),
 ('output',1,'t_hv','t_hv'),('output',34,'t_hd','t_hd'),('input',1,'f_hg','f_hg'),
 ('input',1,'f_qv','f_qv'),('input',34,'f_qd','f_qd'),('output',1,'t_qg','t_qg'),
 ('output',57,'t_acc','t_acc')]
def generate():
 src=ROOT/'rtl/dsrom_sys/s81_head/ot_s81hd_ctl.sv'; text=src.read_text()
 body=re.search(r'module ot_s81hd_ctl \(.*?endmodule',text,re.S).group()
 header,rest=body.split(');',1)
 ext=[]
 for dr,w,n,net in PORTS:
  ext.append(f"    {'output' if dr=='input' else 'input'} wire [{w-1}:0] seq_{n}")
 glue=header.replace('module ot_s81hd_ctl (','module ot_s81hd_ctl_glue (')+',\n'+',\n'.join(ext)+'\n);'+rest
 inst=re.search(r'    dsfd_mtp_seq u_seq \(.*?\);',glue,re.S).group()
 assigns=[]
 for dr,w,n,net in PORTS:
  assigns.append(f'    assign seq_{n} = {net};' if dr=='input' else f'    assign {net} = seq_{n};')
 glue=glue.replace(inst,'    // Direct same-region peer wires. Zero added pipeline state.\n'+'\n'.join(assigns))
 ports=re.findall(r'(?:input|output)\s+wire\s*(?:\[[^\]]+\])?\s*(\w+)',header)
 wires='\n'.join(f'    wire [{w-1}:0] seq_{n};' for dr,w,n,net in PORTS)
 wrapper=header.replace('module ot_s81hd_ctl (','module ot_s81hd_ctl_peer (')+');\n'+wires+'\n'
 wrapper+='    ot_s81hd_ctl_glue u_glue ('+', '.join(f'.{n}({n})' for n in ports)+', '+', '.join(f'.seq_{n}(seq_{n})' for dr,w,n,net in PORTS)+');\n'
 wrapper+='    dsfd_mtp_seq u_seq (.ck(ck), '+', '.join(f'.{n}(seq_{n})' for dr,w,n,net in PORTS)+');\nendmodule\n'
 out=ROOT/'rtl/dsrom_sys/s81_head/ot_s81hd_ctl_peer.sv'
 out.write_text('// Generated by tools/s81_head/split_ctl_peer.py; exact original HSF0 and cycle contract.\n'+glue+'\n\n'+wrapper)
 rec={'schema':'opentallas.head.ctl-peer.v1','source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'generated_sha256':hashlib.sha256(out.read_bytes()).hexdigest(),'removed_instance':inst,'added_state_bits':0,'added_data_cycles':0,'added_reset_cycles':0,'region':'clctl','seq_ports':[{'direction':dr,'width':w,'port':n,'original_net':net} for dr,w,n,net in PORTS]}
 (ROOT/'results/arch/s81_head_1021/ctl_peer.json').write_text(json.dumps(rec,indent=2)+'\n')
if __name__=='__main__':generate()
