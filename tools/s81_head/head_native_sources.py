#!/usr/bin/env python3
"""Generate explicit native hard-core port variants without changing released defaults."""
from pathlib import Path
import argparse,json,hashlib
FTS=('ck0','ck1','mesh','rst')
def vect_ports():
 return '\n'.join('    '+d+' wire hci'+str(i)+'_'+n+'_'+s+',' for i in range(5) for d,s in [('input','i'),('output','o')] for n in FTS)
def core_ports():
 return '\n'.join('    '+d+' wire ft_'+n+'_'+s+',' for d,s in [('input','i'),('output','o')] for n in FTS)
def core_conns(i,continued=False):
 pref='hci``Q``_' if i=='Q' else 'hci'+i+'_'
 lines=['.ft_mstrap_i(clk),']+['.ft_'+n+'_'+s+'('+pref+n+'_'+s+'), ' for s in ('i','o') for n in FTS]
 return ' '.join(lines)
def generate(root):
 r=root/'rtl/dsrom_sys/s81_head'; hashes={}
 for stem in ('ot_s81hd_tile','ot_s81hd_bundle','ot_s81hd_elem_cv','ot_s81hd_elem_cv_bb'):
  ext='.v' if stem.endswith('_bb') else '.sv';src=r/(stem+ext);s=src.read_text();hashes[str(src.relative_to(root))]=hashlib.sha256(src.read_bytes()).hexdigest()
  if stem=='ot_s81hd_tile':
   s=s.replace('module ot_s81hd_tile #','module ot_s81hd_tile_native #',1).replace('    input  wire         ck,',vect_ports()+'\n    input  wire         ck,',1)
   s=s.replace('    ot_s81hd_bundle #','    ot_s81hd_bundle_native #',1)
   key='        .clk(ck), .rst_n(rst_n),'
   con=' '.join('.hci'+str(i)+'_'+n+'_'+f+'(hci'+str(i)+'_'+n+'_'+f+'),' for i in range(5) for f in ('i','o') for n in FTS)
   assert key in s;s=s.replace(key,'        '+con+'\n'+key,1)
  elif stem=='ot_s81hd_bundle':
   s=s.replace('module ot_s81hd_bundle #','module ot_s81hd_bundle_native #',1).replace('    input  wire         clk,',vect_ports()+'\n    input  wire         clk,',1)
   b='.clk(clk), .rst_n(rst_n), .go(go_d), .x(xsb)';assert b in s;s=s.replace(b,core_conns('4')+' .rst_n(rst_n), .go(go_d), .x(xsb)',1)
   a='.clk(clk), .rst_n(rst_n), .go(a_go[Q])';assert a in s;s=s.replace(a,core_conns('Q')+' .rst_n(rst_n), .go(a_go[Q])',1)
  elif stem=='ot_s81hd_elem_cv':
   assert s.count('input  wire clk,')==2
   s=s.replace('    input  wire clk,',core_ports()+'\n    input wire ft_mstrap_i,')
   alias='    wire clk = ft_mstrap_i;\n'+''.join('    assign ft_'+n+'_o = ft_'+n+'_i;\n' for n in FTS)
   assert s.count('    wire nc_hv;')==2;s=s.replace('    wire nc_hv;',alias+'    wire nc_hv;')
  else:
   assert s.count('    input clk,')==2;s=s.replace('    input clk,',core_ports()+'\n    input ft_mstrap_i,')
  out=r/(stem+'_native'+ext)
  out.write_text('// GENERATED by tools/s81_head/head_native_sources.py; native infrastructure pins, zero added data cycles.\n'+s)
 return hashes
if __name__=='__main__':
 a=argparse.ArgumentParser();a.add_argument('root',type=Path);o=a.parse_args();print(json.dumps(generate(o.root),indent=1))
