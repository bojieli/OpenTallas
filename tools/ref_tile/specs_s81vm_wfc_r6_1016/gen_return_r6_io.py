#!/usr/bin/env python3
"""Exact pin plan (io_tcl) of dsfd_vm_wfc_return r6 (S-VM-RET 2026-10-16).

Mux-local, bit-interleaved order: r_q[j] / r_q[513+j] select among e_d[j], e_d[512+j], e_d[1024+j], e_d[1536+j]
(lane512 one-hot AND-OR, RTL 320d5b77d), so the four candidates sit adjacent on E and the two outputs s_d[j],
s_d[513+j] adjacent on N.  The parent pin plan must use the same order (recorded in the spec slot_change_request).

Track grid (read from the r5 routed DEF, ASAP7 ORFS): M4 Y 0.012 + 0.048k; M2 Y 0.27r + {0.045..0.225 step 0.036}
(6 tracks per row, rail at 0.27r) -- place_pin -layer M2 used only the first pattern (one pin per row: r4 off-die
pile-up), this plan uses offsets 0.081 and 0.189 (3 tracks apart, 2 tracks from each rail); M5 X 0.012 + 0.048k;
M3 X 0.009 + 0.036k.  Pin centres: E M4 x = W - 0.042, E M2 x = W - 0.019, N M5 y = H - 0.042, N M3 y = H - 0.019,
W M4 x = 0.042 (as place_pins placed them in r5, routed DRC 0).

usage: gen_return_r6_io.py W H OUT.tcl
"""
import math
import sys

CORNER = 1.0


def snap_series(n, lo, hi, legal, sep):
    """n positions spread uniformly over [lo, hi], each snapped to the nearest legal coordinate >= previous + sep"""
    out, prev = [], -1e9
    for i in range(n):
        want = max(lo + (hi - lo) * (i + 0.5) / n, prev + sep)
        p = legal(want)
        while p < prev + sep - 1e-9:
            p = legal(p + 1e-3, up=True)
        if p > hi + 1e-9:
            raise SystemExit(f"plan overflow: {i}/{n} at {p:.3f} > {hi}")
        out.append(p)
        prev = p
    return out


def grid(origin, pitch):
    def f(v, up=False):
        k = math.ceil((v - origin) / pitch - 1e-9) if up else round((v - origin) / pitch)
        return round(origin + k * pitch, 4)
    return f


def m2_rows(offsets=(0.081, 0.189)):
    def f(v, up=False):
        r = math.floor(v / 0.27)
        cands = sorted(round(0.27 * rr + o, 4) for rr in (r - 1, r, r + 1) for o in offsets)
        if up:
            return min(c for c in cands if c >= v - 1e-9)
        return min(cands, key=lambda c: abs(c - v))
    return f


def main():
    W, H, out = float(sys.argv[1]), float(sys.argv[2]), sys.argv[3]
    lines = [f"# generated by tools/ref_tile/specs_s81vm_wfc_r6_1016/gen_return_r6_io.py {W:g} {H:g} -- do not edit",
             "# E: e_d[j], e_d[512+j], e_d[1024+j], e_d[1536+j] adjacent (lane512 candidates); e_v[0..3] at the centre",
             "# N: s_d[j], s_d[513+j] adjacent; s_d[512], s_d[1025], s_v, r_bad at the centre; W: ck at the face centre"]

    def pp(name, layer, x, y):
        lines.append(f"place_pin -pin_name {{{name}}} -layer {layer} -location {{{x:.4f} {y:.4f}}} -force_to_die_boundary")

    # E face
    e = []
    for j in range(512):
        e += [f"e_d[{j + 512 * q}]" for q in range(4)]
        if j == 255:
            e += [f"e_v[{q}]" for q in range(4)]
    assert len(e) == 2052 and len(set(e)) == 2052
    m4 = e[0::2]
    m2 = e[1::2]
    ys4 = snap_series(len(m4), CORNER, H - CORNER, grid(0.012, 0.048), 0.096)
    ys2 = snap_series(len(m2), CORNER, H - CORNER, m2_rows(), 0.108)
    for n, y in zip(m4, ys4):
        pp(n, "M4", W - 0.042, y)
    for n, y in zip(m2, ys2):
        pp(n, "M2", W - 0.019, y)

    # N face
    nn = []
    for j in range(512):
        nn += [f"s_d[{j}]", f"s_d[{513 + j}]"]
        if j == 255:
            nn += ["s_d[512]", "s_d[1025]", "s_v", "r_bad"]
    assert len(nn) == 1028 and len(set(nn)) == 1028
    m5 = nn[0::2]
    m3 = nn[1::2]
    xs5 = snap_series(len(m5), CORNER, W - CORNER, grid(0.012, 0.048), 0.096)
    xs3 = snap_series(len(m3), CORNER, W - CORNER, grid(0.009, 0.036), 0.072)
    for n, x in zip(m5, xs5):
        pp(n, "M5", x, H - 0.042)
    for n, x in zip(m3, xs3):
        pp(n, "M3", x, H - 0.019)

    # W face: ck on the M4 track nearest the centre, rn above, return_lane / return_valid below (8-track steps)
    g = grid(0.012, 0.048)
    yc = g(H / 2)
    w = ["return_valid[0]", "return_valid[1]", "return_lane[0]", "return_lane[1]", "return_lane[2]", "return_lane[3]",
         "ck", "rn"]
    for i, n in enumerate(w):
        pp(n, "M4", 0.042, round(yc + (i - 6) * 0.384, 4))

    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: E M4 {len(m4)} [{ys4[0]:.3f}..{ys4[-1]:.3f}] M2 {len(m2)} [{ys2[0]:.3f}..{ys2[-1]:.3f}]; "
          f"N M5 {len(m5)} [{xs5[0]:.3f}..{xs5[-1]:.3f}] M3 {len(m3)} [{xs3[0]:.3f}..{xs3[-1]:.3f}]; ck y {yc}")


if __name__ == "__main__":
    main()
