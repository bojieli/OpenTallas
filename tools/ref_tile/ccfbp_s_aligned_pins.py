#!/usr/bin/env python3
"""Bit-aligned N-face pin plan for the CCF bankpipe S leaf (ot_s81_hc_ccf_bankpipe_control), HC-COMB-2 2026-10-16.

Why: s81hc_ccfbp_s_ref-v1-2b1061e5e failed GRT-0116 (835 horizontal-congestion gcells, all in x 140-190 um, full
height).  spread_face_pins concatenated the N-face buses (fd_pin 1,128 bits in x 5..153, bank_heads_pin 2,560 bits in
x 153..488) while the S-face output ch_fd (2,920 bits) spreads over the whole face; ch_fd[j] = pop ? heads[j-O_D] :
fd[j] (and ch_fd[j] = fd[j] for the header j < O_D), so every bit crossed the face horizontally and all of them
crossed near x = 150.  This plan keeps the S face as generated (ch_rst, ch_fv, ch_fd evenly spread) and places every
N-face input straight above the output bit it feeds:  fd_pin[j] above ch_fd[j] (M3), bank_heads_pin[k] above
ch_fd[O_D + k] (M5), fv_pin[i] above ch_fv[i], srs_pin above ch_rst, n_yacc_pin beside fv, sk at the face centre.
Same RTL, outline, faces and pin count; only N-face x positions change.

Usage: ccfbp_s_aligned_pins.py IO_TCL_IN IO_TCL_OUT [--od 104]
"""
import argparse, re
from pathlib import Path

PITCH = {"M3": 0.036, "M5": 0.048}
OFF = {"M3": 0.009, "M5": 0.012}
SIZE = {"M3": (0.018, 0.144), "M5": (0.024, 0.192)}
PIN = re.compile(r"-pin_name \{(\w+)(?:\[(\d+)\])?\} -layer (\w+) -location \{([\d.]+) ([\d.]+)\}")


def snap(x, layer):
    p, o = PITCH[layer], OFF[layer]
    return round(round((x - o) / p) * p + o, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src"); ap.add_argument("out")
    ap.add_argument("--od", type=int, default=None, help="O_D (header width); default FSW - 1024")
    a = ap.parse_args()
    lines = Path(a.src).read_text().splitlines()
    pins, s_lines, n_y = {}, [], None
    for l in lines:
        m = PIN.search(l)
        if not m:
            continue
        name, idx, layer, x, y = m.group(1), int(m.group(2) or 0), m.group(3), float(m.group(4)), float(m.group(5))
        pins.setdefault(name, {})[idx] = (x, y, layer, l)
        if y == 0.0:
            s_lines.append(l)
        else:
            n_y = y
    fsw = len(pins["fd_pin"]); nh = len(pins["bank_heads_pin"])
    od = a.od if a.od is not None else fsw - 1024
    ox = lambda name, i: pins[name][i][0]
    want = []                                   # (pin text, preferred layer, target x)
    want.append(("srs_pin", "M3", ox("ch_rst", 0)))
    for i in range(len(pins["fv_pin"])):
        want.append((f"fv_pin[{i}]", "M5", ox("ch_fv", i)))
    want.append(("n_yacc_pin", "M3", ox("ch_fv", len(pins["ch_fv"]) - 1)))
    for j in range(fsw):
        want.append((f"fd_pin[{j}]", "M3", ox("ch_fd", j)))
    for k in range(nh):
        want.append((f"bank_heads_pin[{k}]", "M5", ox("ch_fd", od + k)))
    want.append(("sk", "M3", pins["sk"][0][0]))
    used, out = set(), [f"# generated by tools/ref_tile/ccfbp_s_aligned_pins.py from {a.src}: S face kept; N-face inputs "
                        f"bit-aligned above their ch_fd / ch_fv / ch_rst outputs (O_D {od})"]
    out += s_lines
    for name, layer, x in want:
        xs = snap(x, layer)
        step = 0
        while (layer, xs) in used:              # nearest free track, alternating sides
            step += 1
            cand = round(xs + (step // 2 + 1) * PITCH[layer] * (1 if step % 2 else -1), 3)
            if (layer, cand) not in used and 1.0 < cand < 491.0:
                xs = cand
        used.add((layer, xs))
        sx, sy = SIZE[layer]
        out.append(f"place_pin -pin_name {{{name}}} -layer {layer} -location {{{xs:.3f} {n_y:.3f}}} "
                   f"-pin_size {{{sx} {sy}}} -force_to_die_boundary")
    n_in = sum(1 for l in lines if PIN.search(l))
    assert len(out) - 1 == n_in, (len(out) - 1, n_in)
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"ALIGNED_PINS {len(out) - 1} pins (fsw {fsw}, heads {nh}, O_D {od}) -> {a.out}")


if __name__ == "__main__":
    main()
