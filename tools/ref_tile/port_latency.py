#!/usr/bin/env python3
"""Export compiler boundary edges from an actual elaborated pin-register table.

Usage: python3 tools/ref_tile/port_latency.py --table RESULTS/ot_pin_regs.tsv
  --wrapper RESULTS/ot_pin_regs_wrapper.v --source-commit FULL_SHA --top TOP
  --out KIT_OR_EVIDENCE/port_latency.json

This reports only the additional generic wrapper stages. Existing RTL stages
belong in the measured core duration. Generation cannot infer parameterized
ports before elaboration; missing tables (including opt-outs) fail closed.
Copy this report with the source-pinned synthesis evidence and bind its SHA in
the compiler's kit_boundary record. It is not a physical timing qualification.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import re


def export(table: Path, wrapper: Path, top: str, source_commit: str) -> dict:
    if not re.fullmatch(r'[0-9a-f]{40}', source_commit):
        raise ValueError('source commit must be a full immutable Git SHA')
    raw = table.read_bytes()
    wrapped = wrapper.read_bytes()
    text = wrapped.decode()
    if ('generated by physical/common_flow/ot_pin_regs.tcl (OT_PIN_REGS=1)' not in text
            or not re.search(r'\bmodule\s+' + re.escape(top) + r'\s*\(', text)):
        raise ValueError('expected actual generated pin-register wrapper for top')
    reader = csv.DictReader(io.StringIO(raw.decode()), delimiter='\t')
    if reader.fieldnames != ['port', 'dir', 'width', 'cycles', 'why']:
        raise ValueError('pin-register table header mismatch')
    ports = {}
    for row in reader:
        name = row['port']
        if not name or name in ports or None in row:
            raise ValueError('missing/duplicate port or malformed table row')
        direction = row['dir']
        width, edges = int(row['width']), int(row['cycles'])
        why = row['why']
        if direction not in ('input', 'output', 'inout') or width < 1 or edges not in (0, 1):
            raise ValueError('invalid elaborated port record: ' + name)
        if (edges == 1 and (direction == 'inout' or why != 'pin register')) or (
                edges == 0 and why not in ('clock', 'reset', 'excluded', 'inout')):
            raise ValueError('inconsistent pin-register stage/reason: ' + name)
        ports[name] = dict(dir=direction, register_edges=edges, width=width, reason=why)
    if not ports:
        raise ValueError('empty elaborated pin-register table')
    return dict(schema='opentallas.ref_tile.port_latency.v1', top=top, ports=ports,
                source_commit=source_commit,
                evidence={p.name: hashlib.sha256(data).hexdigest()
                          for p, data in ((table, raw), (wrapper, wrapped))},
                scope='Additional generic wrapper edges only; core RTL stages remain in measured core duration; no physical qualification')


def validate_roles(report, wrapper, spec, read_source):
    """Require declared control ports to remain direct wires in actual wrapper.

    Reset polarity and synchronous/asynchronous meaning remain owned by the
    source RTL: a direct wire preserves both. No reset-name inference is used.
    Literal partial buses are rejected by the synthesis helper, not widened.
    """
    from audit_registered_clocks import clock_ports as sdc_clocks
    clocks = set(spec.get('clock_ports', []))
    if spec.get('clock_port'):
        clocks.add(spec['clock_port'])
    source_hashes = {}
    for source in spec.get('sdc_extra', []):
        text = read_source(source)
        if text is None:
            raise ValueError('unresolved clock-role source: ' + source)
        source_hashes[source] = hashlib.sha256(text.encode()).hexdigest()
        found, unknown = sdc_clocks(text)
        if unknown:
            raise ValueError('unresolved clock-role expressions: ' + source)
        clocks.update(found)
    resets = set(spec.get('reset_ports', []))
    base = lambda name: re.sub(r'\[\d+\]$', '', name)
    clocks, resets = {base(n) for n in clocks}, {base(n) for n in resets}
    if clocks & resets:
        raise ValueError('conflicting clock/reset declarations: ' + ','.join(sorted(clocks & resets)))
    text = wrapper.read_text()
    for role, names in [('clock', clocks), ('reset', resets)]:
        for name in names:
            rec = report['ports'].get(name)
            if not rec or rec['register_edges'] != 0:
                raise ValueError('declared ' + role + ' selected as data or absent: ' + name)
            direct = r'\.' + re.escape(name) + r'\s*\(\s*' + re.escape(name) + r'\s*\)'
            if not re.search(direct, text) or re.search(r'(?<![A-Za-z0-9_$])' + re.escape(name) + r'__ot_q\b', text):
                raise ValueError('declared ' + role + ' is not direct in transformed wrapper: ' + name)
    return dict(clocks=sorted(clocks), resets=sorted(resets), source_sha256=source_hashes,
                reset_meaning='source RTL polarity and reset semantics preserved by direct wiring')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('table', 'wrapper', 'out'):
        parser.add_argument('--' + name, required=True, type=Path)
    parser.add_argument('--top', required=True)
    parser.add_argument('--source-commit', required=True)
    args = parser.parse_args()
    report = export(args.table, args.wrapper, args.top, args.source_commit)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, sort_keys=True) + '\n')


if __name__ == '__main__':
    main()
