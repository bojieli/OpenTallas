#!/usr/bin/env python3
"""Even per-face pin spreading for wide-bus tiles (S-ELEM-B 10-15).

Three PQ tiles (bc_slice0, QB headp, QB align) failed GRT-0116 with the same cause: wide output buses packed
into one dense band of the face (auto pin placement clusters a bus where its flops sit) plus two recipe-2 output
hold pads per pin in that band. This writes an explicit io_tcl that spreads every face's pins evenly over the
whole face (bus bits in order, buses in the spec's face order), on legal tracks:
  N/S faces: alternate M3 (pitch 0.036) / M5 (pitch 0.048) like the closed bc0_ns plan, each pin on its layer's track;
  W/E faces: M4 (pitch 0.048).
Usage: spread_face_pins.py SPEC.json OUT.tcl [--src-root ROOT] [--margin UM]
Port widths come from verilator --json-only on the spec's sources/top/params/defines.
"""
import argparse, json, os, subprocess, tempfile
from pathlib import Path

V = os.environ.get("OT_VERILATOR", str(Path.home() / ".local/opentallas-tools/verilator-5.050/bin/verilator"))
PITCH = {"M3": 0.036, "M4": 0.048, "M5": 0.048}
# track offsets as in the closed bc0_ns / headw pin plans (asap7 make_tracks)
OFF = {"M3": 0.009, "M4": 0.036, "M5": 0.012}
SIZE = {"M3": (0.018, 0.144), "M5": (0.024, 0.192), "M4": (0.192, 0.024)}


def port_widths(spec, root):
    with tempfile.TemporaryDirectory() as td:
        cmd = [V, "--json-only", "-Wno-fatal", "-Wno-lint", "-Wno-style", "--Mdir", td, "--top-module", spec["top"]]
        cmd += [f"-G{k}={v}" for k, v in spec.get("params", {}).items()]
        cmd += [f"-D{d}" for d in spec.get("defines", [])] + ["-DSYNTHESIS"]
        cmd += [str(root / s) for s in spec["sources"]]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
        tree = json.loads(next(Path(td).glob("*.tree.json")).read_text())
    types = {}
    def walk(n):
        if isinstance(n, dict):
            if n.get("type") in ("BASICDTYPE",) and "addr" in n:
                types[n["addr"]] = n
            for v in n.values(): walk(v)
        elif isinstance(n, list):
            for v in n: walk(v)
    walk(tree)
    widths = {}
    def find_top(n):
        if isinstance(n, dict):
            if n.get("type") == "MODULE" and spec["top"] in (n.get("origName"), n.get("name")):   # origName mangles "__" (___05F)
                for st in n.get("stmtsp", []):
                    if st.get("type") == "VAR" and st.get("direction") in ("INPUT", "OUTPUT", "INOUT"):
                        dt = types.get(st.get("dtypep"), {})
                        rng = dt.get("range")
                        w = 1
                        if rng:
                            a, b = [int(x) for x in rng.strip("[]").split(":")]
                            w = abs(a - b) + 1
                        widths[st["name"]] = (w, bool(rng))
                return True
            return any(find_top(v) for v in n.values() if isinstance(v, (dict, list)))
        if isinstance(n, list):
            return any(find_top(v) for v in n)
        return False
    find_top(tree)
    return widths


def snap(x, p, off=0.0):
    return round(round((x - off) / p) * p + off, 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec"); ap.add_argument("out")
    ap.add_argument("--src-root", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--margin", type=float, default=4.32)
    a = ap.parse_args()
    spec = json.loads(Path(a.spec).read_text()); root = Path(a.src_root)
    W, H = spec["outline"]["w"], spec["outline"]["h"]
    widths = port_widths(spec, root)
    clock_ports = set(spec.get("clock_ports") or []) | ({spec["clock_port"]} if spec.get("clock_port") else {"clk"})
    lines = [f"# generated by tools/ref_tile/spread_face_pins.py from {a.spec}: every face spread evenly, buses in face order"]
    for face, ports in spec["pins"].items():
        bits = []
        for p in ports:
            if p not in widths:
                raise SystemExit(f"port {p} not in {spec['top']}")
            w, vec = widths[p]
            bits += [f"{p}[{i}]" if vec else p for i in range(w)]
        if not bits:
            continue
        # Clock ports go to the CENTRE of their face, not to the face's first slot: the CTS root sits at the clock
        # pin, so a corner pin on a wide tile stretches every leaf path across the whole face (CALCAP c3, clk at
        # (4.5, 0) of a 432 um face: TT insertion 419 ps / spread 115.9 vs 257.5 / 70.9 with the pin near its flops).
        clocks = [b for b in bits if b in clock_ports]
        if clocks:
            bits = [b for b in bits if b not in clock_ports]
            mid = len(bits) // 2
            bits[mid:mid] = clocks
        horiz = face in ("N", "S")
        span = (W if horiz else H) - 2 * a.margin
        step = span / len(bits)
        need = 0.072 if horiz else 0.096
        if step < need:
            raise SystemExit(f"face {face}: {len(bits)} pins need {len(bits)*need:.1f} um > {span:.1f}")
        used = {}
        for i, b in enumerate(bits):
            c = a.margin + step * (i + 0.5)
            if horiz:
                layer = "M3" if i % 2 == 0 else "M5"
                x = snap(c, PITCH[layer], OFF[layer])
                while (layer, x) in used: x = round(x + PITCH[layer], 3)
                used[(layer, x)] = 1
                y = 0.0 if face == "S" else H
                loc = f"{x:.3f} {y:.3f}"
            else:
                layer = "M4"
                y = snap(c, PITCH[layer], OFF[layer])
                while (layer, y) in used: y = round(y + PITCH[layer], 3)
                used[(layer, y)] = 1
                x = 0.0 if face == "W" else W
                loc = f"{x:.3f} {y:.3f}"
            sx, sy = SIZE[layer]
            lines.append(f"place_pin -pin_name {{{b}}} -layer {layer} -location {{{loc}}} -pin_size {{{sx} {sy}}} -force_to_die_boundary")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"SPREAD_PINS {spec['name']}: {len(lines)-1} pins -> {a.out}")


if __name__ == "__main__":
    main()
