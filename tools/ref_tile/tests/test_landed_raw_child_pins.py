"""HF-4d 10-19 (coordinator option A, Q.STA.TTC.2): raw SRAM clock pins of a hard child in a LANDED cluster.

h16c (ot_qfd_tt_ctlm_static_hr, hybrid_entries leaf) exposes ck_head (its CTS root) plus direct SRAM clock entries
ck_pm0/ck_pm1.  Its ETM has only min/max_clock_tree_path (15 ps) on them and no arcs, so all_registers never reaches them
(qfd_tt_ctlm_dv gate: "OT_LANDED: 1 of 3 bound hard-child clock pins reached").  The requirement lives in the leaf's
CLOSED RECORD: its sign-off compensated every entry to one phase (latency = phi - wire - R, raw SRAM rows R 0), so each
SRAM clock pin is co-timed with ck_head's boundary flops, within the record's per-pair hold die-skew reserve (100 - 50).
The parent judges  wire(raw) + leaf wire  ==  wire(ck_head) + R(ck_head)  within that tolerance at TT and FF.

Wrong models refused here: (1) the reverted b669161f6 ancestor (c0b7638d7 (a)) took the raw pin's ETM / insertion 'all'
arrival as its reference with no record -> a child without a closed record now fails closed; (2) the old gate added the
child's CTS-root R to EVERY clock pin of the child (raw pin + 303 ps); (3) "equal pin arrival with ck_head" (the
co-timed requirement is at ck_head's flops, not its pin) -> skew -R -> FAIL."""
