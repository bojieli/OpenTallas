ROOT = Path(__file__).resolve().parents[3]
JOB = 'leaf-r1-0123456789'

# CLK carries the leaf's clock-tree insertion (90/110 as R) like a real ETM; CKP only its 15 ps pin -> SRAM wire
ETM = K.ETM.replace('pin(CLK) { direction : input; clock : true; capacitance : 1; }', '''pin(CLK) { direction : input; clock : true; capacitance : 1;
      timing() { timing_type : min_clock_tree_path; cell_rise(scalar) { values("90"); } cell_fall(scalar) { values("90"); } }
      timing() { timing_type : max_clock_tree_path; cell_rise(scalar) { values("110"); } cell_fall(scalar) { values("110"); } } }''', 1).replace('    pin(D) {', '''    pin(CKP) { direction : input; clock : true; capacitance : 1;
      timing() { timing_type : min_clock_tree_path; cell_rise(scalar) { values("15"); } cell_fall(scalar) { values("15"); } }
      timing() { timing_type : max_clock_tree_path; cell_rise(scalar) { values("15"); } cell_fall(scalar) { values("15"); } } }
    pin(D) {''', 1)
LEF = K.LEF.replace('PIN D DIRECTION', 'PIN CKP DIRECTION INPUT ; USE CLOCK ; PORT LAYER M4 ; RECT 0.1 0.7 0.2 0.8 ; END END CKP\nPIN D DIRECTION', 1)
RTL = K.RTL.replace('hard h(.CLK(ck_ra),', 'hard h(.CLK(ck_ra), .CKP(ck_ra),')
# the closed leaf's sign-off SDC lines landed_raw_pins reads (as generated by this module for a hybrid_entries leaf)
SIGNOFF = '''set ::ot_ce_cts_roots {{CLK}}
set ::ot_ce_ports {{CLK} {CKP}}
set ::ot_ce_direct_entries {{{ram} {*u_pm} {CKP} {clk} {{tt} {{ram_tt} {00}} {ff} {{ram_ff} {00}} {ss} {{ram_ss} {00}}}}}
    lappend rows [list [lindex $sources 0] $pin $wire 0 0 0 $clock 0 $domain]
    set latency [expr {$ref - $wire - $mean}]
      set_clock_uncertainty -setup [expr {($an in $ot_ce_high || $bn in $ot_ce_high) ? 210 : 150}] -from $a -to $b
      set_clock_uncertainty -hold HOLD -from $a -to $b
'''


def leaf(root, hold='100', status='CLOSED', record=True, clocks=('CLK', 'CKP')):
    """a closed hybrid-entries leaf view 'hard' (CLK = CTS root, R 90/100/110; CKP = raw SRAM entry, leaf wire 15)"""
    v = root / 'hard'
    v.mkdir()
    for c in CE.CORNERS:
        (v / f'hard_{c}.lib').write_text(ETM.replace('hard_tt', 'hard_' + c))
    (v / 'hard.lef').write_text(LEF)
    bd = dict(n=4, min=90, mean=100, max=110)
    cm = dict(CLK={c: dict(boundary=bd, all=bd, errors=[]) for c in CE.CORNERS},
              CKP={c: dict(boundary=None, all=dict(n=1, min=15, mean=15, max=15), errors=[],
                           macros=dict(n=1, pins=[dict(pin='u_pm/clk', arr=15)])) for c in CE.CORNERS})
    (v / 'insertion.json').write_text(json.dumps(dict(lib_clock_pin='CLK', clock='ck', clock_measurements=cm,
                                                      **{c: dict(boundary=bd) for c in CE.CORNERS})))
    (v / 'port_latency.json').write_text(json.dumps(dict(job=JOB, control_roles=dict(clocks=list(clocks)))))
    if record:
        rd = root / 'results' / 'rtl' / 'ref_tile' / 'leaf' / JOB
        rd.mkdir(parents=True)
        (rd / 'signoff.sdc').write_text(SIGNOFF.replace('HOLD', hold))
        vd = root / 'results' / 'closure_loop' / JOB
        vd.mkdir(parents=True)
        (vd / 'verdict.json').write_text(json.dumps(dict(job=JOB, status=status, job_spec=dict(record=[
            dict(**{'from': '{RUN}/record/views', 'to': 'views'}),
            dict(**{'from': '{RUN}/record/route', 'to': f'results/rtl/ref_tile/leaf/{JOB}'})]))))
    return v


def spec(root):
    s = K.spec(root)
    (root / 'top.v').write_text(RTL)
    return s


class RawPinRecord(unittest.TestCase):
    def test_reference_and_tolerance_come_from_the_closed_record(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            raw = CE.landed_raw_pins(leaf(root), root)
            self.assertEqual(sorted(raw), ['CKP'])
            self.assertEqual(raw['CKP']['ref'], 'CLK')
            self.assertEqual(raw['CKP']['tol'], 50.0)            # record hold 100 - rule H1 margin 50
            self.assertEqual(raw['CKP']['refs']['ff'], [15.0, 15.0, 15.0])
            self.assertEqual(raw['CKP']['record'], f'results/rtl/ref_tile/leaf/{JOB}/signoff.sdc')
            # a child with no raw entry (every clock pin has a routed boundary) has nothing to read
            (root / 'plain').mkdir()
            self.assertEqual(CE.landed_raw_pins(K.view(root / 'plain'), root), {})

    def test_refusals_fail_closed(self):
        cases = {
            # the reverted wrong model: a raw pin referenced by its ETM / insertion 'all' with no closed record
            'no closed record (ETM / all-arrival reference refused)': dict(record=False),
            'record not CLOSED': dict(status='FAILED'),
            'no die-skew tolerance in the record': dict(hold='50'),
            'bound pin list differs from the record': dict(clocks=('CLK',)),
        }
        for why, kw in cases.items():
            with tempfile.TemporaryDirectory() as d, self.subTest(why=why):
                root = Path(d)
                v = leaf(root, **kw)
                with self.assertRaises(ValueError):
                    CE.landed_raw_pins(v, root)
                s = spec(root)
                with self.assertRaises((ValueError, RT.SpecError)):
                    CE.generate(K.load(root, s), root)

    def test_record_sdc_without_the_entry_model_refused(self):
        for drop in ('lappend rows [list [lindex $sources 0] $pin $wire 0 0 0 $clock 0 $domain]',
                     'set ::ot_ce_direct_entries', 'set_clock_uncertainty -hold'):
            with tempfile.TemporaryDirectory() as d, self.subTest(drop=drop):
                root = Path(d)
                v = leaf(root)
                p = root / 'results' / 'rtl' / 'ref_tile' / 'leaf' / JOB / 'signoff.sdc'
                p.write_text('\n'.join(x for x in p.read_text().splitlines() if drop not in x))
                with self.assertRaises(ValueError):
                    CE.landed_raw_pins(v, root)

    def test_generated_sdc_binds_raw_pins_and_keeps_plain_landed_bytes(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            leaf(root)
            text = CE.generate(K.load(root, spec(root)), root)
            self.assertIn('set ::ot_ce_landed_child_pins 2\n', text)
            self.assertIn('set ::ot_ce_landed_raw [dict create {hard/CKP} {ref CLK tol 50 record '
                          f'results/rtl/ref_tile/leaf/{JOB}/signoff.sdc}}]\n', text)
            self.assertIn('{hard/CKP} {tt {15.0 15.0 15.0} ff {15.0 15.0 15.0} ss {15.0 15.0 15.0}}', text)
            self.assertIn('OT_LANDED RAW_PIN', text)
            self.assertTrue(text.endswith(CE.strip_hold_budget(CE.landed_raw_body(CE.LANDED_BODY), False)))
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            K.view(root)
            plain = CE.generate(K.load(root, K.spec(root)), root)
            self.assertTrue(plain.endswith(CE.strip_hold_budget(CE.LANDED_BODY, False)))
            self.assertNotIn('ot_ce_landed_raw', plain)
            self.assertNotIn('RAW_PIN', CE.LANDED_BODY)


class RawPinTapTargets(unittest.TestCase):
    def test_targets_are_the_record_offsets_and_hooks_arm_the_tap(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            leaf(root)
            s = K.load(root, spec(root))
            tg = CE.landed_raw_targets(s, root)
            self.assertEqual(tg['hard/CKP']['ref'], 'CLK')
            self.assertEqual([tg['hard/CKP'][c] for c in CE.CORNERS], [85.0, 85.0, 85.0])   # R 100 - leaf wire 15
            tcl = CE.landed_raw_tcl(s, root)
            self.assertEqual(tcl, ['set ::ot_lrt_targets [dict create {hard/CKP} {ref CLK tt 85 ff 85 ss 85}]',
                                   'source /src/physical/common_flow/landed_raw_tap.tcl'])
            old = RT.ROOT
            RT.ROOT = root
            try:
                pre = json.dumps(RT.gen_hooks(s, 'kit'))
            finally:
                RT.ROOT = old
            i, j = pre.find('clock_entries.tcl'), pre.find('landed_raw_tap.tcl')
            # one mechanism: the CTS-time dicts clock_entries.tcl needs are set BEFORE it (pslice real3 / b895c55d9)
            self.assertTrue(0 < pre.find('set ::ot_ce_counts [dict create {hard} 1]') < i, pre[:2000])
            self.assertTrue(0 < pre.find('set ::ot_ce_landed_raw [dict create {hard/CKP} {ref CLK}]') < i, pre[:2000])
            self.assertTrue(0 < i < j, pre[:2000])                 # the tap wraps clock_entries' CTS
            self.assertLess(j, pre.find('rename clock_tree_synthesis ::ot_ref_cts_boundary_orig'))
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            K.view(root)
            s = K.load(root, K.spec(root))
            self.assertEqual(CE.landed_raw_tcl(s, root), [])
            self.assertEqual(CE.landed_pre_cts_tcl(s, root), ['set ::ot_ce_counts [dict create {hard} 1]'])
            old = RT.ROOT
            RT.ROOT = root
            try:
                hooks = json.dumps(RT.gen_hooks(s, 'kit'))
            finally:
                RT.ROOT = old
            self.assertNotIn('landed_raw', hooks)
            self.assertLess(hooks.find('set ::ot_ce_counts'), hooks.find('clock_entries.tcl'))
        self.assertEqual(CE.landed_pre_cts_tcl(dict(kind='tile', clock='multiple_cts_roots'), ROOT), [])


class RawPinGate(unittest.TestCase):
    """pre_route_gate.root_child_flops on a measured ck_insertion domain: raw pin at its leaf wire, judged vs CLK flops"""

    def domain(self, ckp_arr, clk_arr=20.0):
        pins = [dict(pin='h/CLK', arr=clk_arr), dict(pin='h/CKP', arr=ckp_arr)]
        return dict(source='ck_ra', **{c: dict(all=dict(n=8, min=110, max=130), macros=dict(n=2, pins=pins),
                                               child_flop=dict(soft=dict(all=dict(n=6, min=110, max=130))))
                                       for c in ('tt', 'ff')})

    def judge(self, ckp_arr):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            leaf(root)
            s = dict(children=[dict(view='hard', inst='h')])
            old = G.ROOT
            G.ROOT = root
            try:
                return G.root_child_flops(self.domain(ckp_arr), s, None)
            finally:
                G.ROOT = old

    def test_co_timed_at_the_flops_passes(self):
        out = self.judge(20.0 + 100 - 15)                       # CKP 85 ps after CLK pin: SRAM at CLK's flop mean
        self.assertNotIn('raw_pin_fail', out)
        row = [r for r in out['raw_pins'] if r['corner'] == 'tt'][0]
        self.assertEqual((row['skew'], row['verdict'], row['co_timed']), (0.0, 'PASS', 'h/CLK'))
        # the raw pin is measured at its leaf wire (eff 120), not raw + CLK's R (205: the old per-child boundary)
        self.assertEqual(out['tt_root_child_flop_span'], [110.0, 130.0])

    def test_equal_pin_arrival_model_fails(self):
        out = self.judge(20.0)                                  # CKP with CLK's pin arrival: SRAM 85 ps before flops
        self.assertIn('raw_pin_fail', out)
        self.assertRegex(out['raw_pin_fail'][0], r'TT raw child clock pin h/CKP -85\.0 ps vs h/CLK \(leaf sign-off tolerance 50\)')

    def test_tolerance_edges(self):
        self.assertNotIn('raw_pin_fail', self.judge(20.0 + 85 + 50))
        self.assertIn('raw_pin_fail', self.judge(20.0 + 85 + 50.2))
        self.assertIn('raw_pin_fail', self.judge(20.0 + 85 - 50.2))


