"""S81-FRAME4 10-19: the FORWARDED-CLOCK class of a LANDED cluster (spec "forwarded_clock_ports").

The S81 frames col_h9 / col_h10 (landed 3-region clusters) take a forwarded lane clock on input port xk[3:0]: it feeds the
crs4 landing's write side (dsfd_cfifo_crs4 xk[0..3]) and the four dvrly xo relays (dsfd_dvrly_276_NS u_xo0..3/ck).
xk is not a region CTS root, so the landed body counted those 8 bound hard-child clock pins as unreached
("OT_LANDED: 112 of 132 bound hard-child clock pins reached from the region roots", gate s81frame_col_h9_sr 12:04).
With forwarded_clock_ports [xk] such a pin (net traced structurally to the port) is a FORWARDED sink: counted, owned by
its port, and judged per port bit at the child flops (pin arrival + insertion boundary min..max), spread <= 80 at TT/FF.
Kits without the key keep their generated bytes."""
