# region ra = {h (hard child on ck_ra), r0, r1, landing write}, rb = {landing read, s0}; forwarded port xk[1:0]:
# xk[0] -> f0 (fwd) + f1 (fwd2), xk[1] -> f2 (fwd); the forwarded children launch (clk->Q) so they are registers
RTL = '''module top(input ck_ra, input ck_rb, input d, input [1:0] xk, output y, output z, output w0, output w1, output w2);
hard h(.CLK(ck_ra), .D(d), .Q(hq));
fwd f0(.CLK(xk[0]), .D(d), .Q(w0));
fwd2 f1(.CLK(xk[0]), .D(d), .Q(w1));
fwd f2(.CLK(xk[1]), .D(d), .Q(w2));
DFFHQNx1_ASAP7_75t_R r0 (.CLK(ck_ra), .D(hq), .QN(q0));
DFFHQNx1_ASAP7_75t_R r1 (.CLK(ck_ra), .D(d), .QN(y));
DFFHQNx1_ASAP7_75t_R u_lpl_0_w.bank_reg (.CLK(ck_ra), .D(q0), .QN(b0));
DFFHQNx1_ASAP7_75t_R u_lpl_0_r.o_reg (.CLK(ck_rb), .D(b0), .QN(l0));
DFFHQNx1_ASAP7_75t_R s0 (.CLK(ck_rb), .D(l0), .QN(z));
endmodule
'''


def named_view(root, name, bd):
    v = root / name
    v.mkdir()
    for c in CE.CORNERS:
        (v / f'{name}_{c}.lib').write_text(K.ETM.replace('hard', name).replace(f'{name}_tt', f'{name}_{c}'))
    (v / f'{name}.lef').write_text(K.LEF.replace('hard', name))
    (v / 'insertion.json').write_text(json.dumps(dict(lib_clock_pin='CLK', clock='ck',
                                                      **{c: dict(boundary=dict(n=4, **bd)) for c in CE.CORNERS})))
    return v


def fixture(root, fwd2=None):
    K.view(root)
    named_view(root, 'fwd', dict(min=90, mean=100, max=110))
    named_view(root, 'fwd2', fwd2 or dict(min=95, mean=100, max=105))
    s = K.spec(root)
    (root / 'top.v').write_text(RTL)
    s['children'] = [dict(view=str(root / 'hard'), inst='h'), dict(view=str(root / 'fwd'), inst='f0'),
                     dict(view=str(root / 'fwd2'), inst='f1'), dict(view=str(root / 'fwd'), inst='f2')]
    s['clock_entry_domains']['core'].update(inputs=['d', 'xk'], outputs=['y', 'w0', 'w1', 'w2'])
    s['pins'] = dict(W=['ck_ra', 'ck_rb', 'd', 'xk'], E=['y', 'z', 'w0', 'w1', 'w2'])
    s['forwarded_clock_ports'] = ['xk']
    return s


class ForwardedSpec(unittest.TestCase):
    def test_opt_in_and_byte_identical_without_the_key(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            s = fixture(root)
            text = CE.generate(K.load(root, s), root)
            self.assertIn('set ::ot_ce_fwd_ports {{xk}}\n', text)
            self.assertIn('set ::ot_ce_landed_child_pins 4\n', text)
            self.assertIn('incr ot_ce_landed_hits [ot_ce_forwarded_visit $corner]', text)
            self.assertIn('proc ot_ce_forwarded_visit', text)
            self.assertIn('dict set cells $cell [ot_ce_fwd_domain', text)
            s.pop('forwarded_clock_ports')
            plain = CE.generate(K.load(root, s), root)
            self.assertNotIn('ot_ce_fwd', plain)
            self.assertNotIn('FORWARDED', plain)
            self.assertTrue(plain.endswith(CE.strip_hold_budget(CE.LANDED_BODY, False)))
            s['forwarded_clock_ports'] = []
            self.assertEqual(CE.generate(K.load(root, s), root), plain)

    def test_refusals(self):
        bad = {
            'not a list': 'xk',
            'bus spelling': ['xk[0]'],
            'duplicate': ['xk', 'xk'],
            'also a region root': ['ck_rb'],
            'in no domain inputs': ['d2'],
        }
        for why, value in bad.items():
            with tempfile.TemporaryDirectory() as d, self.subTest(why=why):
                root = Path(d)
                s = fixture(root)
                s['forwarded_clock_ports'] = value
                with self.assertRaises((RT.SpecError, ValueError)):
                    CE.generate(K.load(root, s), root)
        tile = dict(kind='tile', clock='multiple_cts_roots', clock_port='ck', clock_ports=['ck', 'ck2'],
                    forwarded_clock_ports=['xk'],
                    clock_entry_domains=dict(core=dict(ratio=[1, 1], ports=['ck'], inputs=['d'], outputs=[]),
                                             two=dict(ratio=[1, 1], ports=['ck2'], inputs=[], outputs=['q'])))
        with self.assertRaises(ValueError):
            CE.generate(tile, ROOT)


@unittest.skipUnless(K.available(), 'real OpenROAD ORFS image required')
class ForwardedOpenroad(unittest.TestCase):
    """Real clock_entries.tcl + TritonCTS on the two region roots; xk stays a data input (no create_clock); routed
    require-wire scene (judged)."""

    def run_flow(self, mutant='', restart_pre_cts=None):
        with tempfile.TemporaryDirectory() as d:
            w = Path(d)
            s = fixture(w, fwd2=dict(min=290, mean=300, max=310) if mutant == 'skewed' else None)
            for ch in s['children']:
                ch['view'] = Path(ch['view']).name
            s['landed_record'] = 'top_lp_record.json'
            if mutant == 'no_forwarded_class':
                s.pop('forwarded_clock_ports')
            rtl = RTL.replace('u_lpl_0_w.bank_reg', '\\u_lpl_0_w.bank_reg ').replace('u_lpl_0_r.o_reg', '\\u_lpl_0_r.o_reg ')
            (w / 't.v').write_text(rtl)
            pre = mutant == 'pre_cts'
            entries = ('set ::ot_ref_pre_cts 1\n' if pre else 'set ::ot_ce_require_wire 1\n') + CE.generate(s, w) + CE.landed_sdc(s, w)
            (w / 'clocks.tcl').write_text(CE.clocks(s, 833.333))
            (w / 'entries.tcl').write_text(entries)
            flow = r'''
set_thread_count 2
set P /OpenROAD-flow-scripts/flow/platforms/asap7
read_lef $P/lef/asap7_tech_1x_201209.lef
read_lef $P/lef/asap7sc7p5t_28_R_1x_220121a.lef
foreach m {hard fwd fwd2} { read_lef /w/$m/$m.lef }
foreach l [glob $P/lib/NLDM/*RVT_TT*] { read_liberty $l }
foreach m {hard fwd fwd2} { read_liberty /w/$m/${m}_tt.lib }
read_verilog /w/t.v
link_design top
initialize_floorplan -die_area {0 0 100 100} -core_area {5.4 5.4 94.6 94.6} -site asap7sc7p5t
source $P/openRoad/make_tracks.tcl
place_pins -hor_layers M4 -ver_layers M5
source /w/clocks.tcl
source $P/setRC.tcl
set u [[ord::get_db_block] getDbUnitsPerMicron]
set at [dict create h {20 60} f0 {15 15} f1 {75 15} f2 {45 40}]
set k 0
foreach i [[ord::get_db_block] getInsts] {
  set n [$i getName]
  if {[dict exists $at $n]} {
    lassign [dict get $at $n] x y
    $i setLocation [expr {int($x*$u)}] [expr {int($y*$u)}]; $i setPlacementStatus FIRM
  } else {
    $i setLocation [expr {int((15+6*$k)*$u)}] [expr {int(80*$u)}]
    $i setPlacementStatus PLACED; incr k
  }
}
detailed_placement
set ::ot_ce_cts_roots {ck_ra ck_rb}
set ::ot_ce_landed_cluster 1
set ::ot_ce_counts [dict create hard 1 fwd 2 fwd2 1]
source /src/physical/common_flow/clock_entries.tcl
clock_tree_synthesis -sink_clustering_enable -buf_list BUFx4_ASAP7_75t_R -root_buf BUFx4_ASAP7_75t_R
estimate_parasitics -placement
source /w/entries.tcl
puts "LANDED_RESULT PASS"
'''
            if restart_pre_cts is not None:
                metadata = CE.forwarded_pre_cts_tcl(s, CE.generate(s, w)) if restart_pre_cts else []
                restore = 'unset -nocomplain ::ot_ce_fwd_soft ::ot_ce_refs ::ot_ce_fwd_outputs\n' + '\n'.join(metadata) + '\n'
                flow = flow.replace('source /src/physical/common_flow/clock_entries.tcl',
                                    restore + 'source /src/physical/common_flow/clock_entries.tcl')
            if pre:
                flow = flow.replace(flow[flow.index('set ::ot_ce_cts_roots'):flow.index('source /w/entries.tcl')],
                                    'set ::ot_ce_cts_roots {ck_ra ck_rb}\n')
            if os.environ.get('OT_FORWARDED_CTS_TRACE') == '1':
                command = 'clock_tree_synthesis -sink_clustering_enable -buf_list BUFx4_ASAP7_75t_R -root_buf BUFx4_ASAP7_75t_R'
                flow = flow.replace(command, 'if {[catch {' + command + '} message options]} {\nputs stderr "OT_FORWARDED_CTS_TRACE [dict get $options -errorinfo]"\nerror $message\n}')
            (w / 'run.tcl').write_text(flow)
            proc = subprocess.run(['docker', 'run', '--rm', '-v', f'{w}:/w', '-v', f'{ROOT}:/src:ro',
                                   K.IMAGE, K.OR, '-no_init', '-exit', '/w/run.tcl'], capture_output=True, text=True,
                                  timeout=180)
            return proc.returncode, proc.stdout + proc.stderr

    def test_forwarded_sinks_counted_owned_and_judged(self):
        rc, out = self.run_flow()
        self.assertEqual(rc, 0, out[-6500:])
        self.assertRegex(out, r'OT_LANDED CHILD_SINK tt ck_ra h/CLK wire=')
        for port, pin, r in (('xk\\[0\\]', 'f0/CLK', 100), ('xk\\[0\\]', 'f1/CLK', 100), ('xk\\[1\\]', 'f2/CLK', 100)):
            m = re.search(rf'OT_LANDED FORWARDED_SINK tt {port} {pin} wire=([\d.eE+-]+) R={r}(?:\.0)? min=([\d.eE+-]+)', out)
            self.assertIsNotNone(m, out[-6500:])
        self.assertRegex(out, r'OT_LANDED FORWARDED_CLOCK tt xk\[0\] sinks=2 child_flop_spread=[\d.]+ ps \(<= 80 at TT and FF\) PASS')
        self.assertRegex(out, r'OT_LANDED FORWARDED_CLOCK tt xk\[1\] sinks=1 child_flop_spread=20\.0 ps')
        self.assertIn('OT_MULTI_ROOT OWNERSHIP PASS roots=2', out)
        self.assertIn('LANDED_RESULT PASS', out)

    def test_pre_cts_reports_only(self):
        rc, out = self.run_flow('pre_cts')
        self.assertEqual(rc, 0, out[-6500:])
        self.assertRegex(out, r'OT_LANDED FORWARDED_CLOCK tt xk\[0\] sinks=2 ')
        self.assertIn('LANDED_RESULT PASS', out)

    def test_mutants_fail_closed(self):
        for mutant, why in (('no_forwarded_class', r'OT_LANDED: 1 of 4 bound hard-child clock pins'),
                            ('skewed', r'OT_LANDED: forwarded clock xk\[0\] child-flop spread [\d.]+ ps > 80 at tt')):
            with self.subTest(mutant=mutant):
                rc, out = self.run_flow(mutant)
                self.assertNotEqual(rc, 0, out[-4000:])
                self.assertRegex(out, why)


