"""PL-KIT 10-18 (landed-regions standard): ref_tile accepts a LANDED cluster -- kind "cluster" + clock "multiple_cts_roots"
+ clock_ports (one region CTS root each, TritonCTS per root as the multi-root leaf tile) + "landed_record" (the lp.py
<top>_lp_record.json).  Hard-child clock pins are ordinary sinks of their region root and are measured at the child's
flops (entry-wire arrival + views/<child>/insertion.json boundary); landings get the cell multicycles of the record.
Leaf multi-root tiles and every other clock mode keep their generated bytes (LEAF_BODY untouched)."""
