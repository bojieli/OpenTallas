#!/usr/bin/env python3
"""SEAM-PAD-R3 (S81-INT-R3-SEAM, class C-PARENT-SEAM-HOLD): per-pin seam hold pad sizing from MEASURED parent arrivals.

Problem: a routed hard core signs LOCAL_PASS_NEEDS_PARENT because its port-start FF hold ends are timed against the
flat kit contract (set_input_delay -min -40 vs vclk, legacy io_hold).  A blanket pad (2 x HB4) is the same count on
every pin whatever the parent really delivers.  This tool sizes one pad per INPUT PIN:

  measured pin  (a real parent + real child seam row exists: parent_core_hold.py FF.tsv / TT.tsv 'B'/'A' rows)
                -> requirement = real FF hold slack of that seam pin (the contract is REPLACED by the measured arrival)
  contract pin  (no measured row; or measured row not usable)
                -> requirement = the child's standalone FF slack at the contract (conservative)

  n_hb4(pin) = ceil((guard - ff_slack) / per_cell_ff) if ff_slack < guard else 0       (same rule as face_hold_pad.cells_for)
  TT cost    = n_hb4 x per_cell_tt ; the pin must keep tt_slack - cost >= tt_floor (setup is judged at the real seam)

No pin is padded to a silent cap: a pin that exceeds n_max or whose TT slack cannot pay is listed under 'refused'.
Reads only; the pads are installed by stage() below (gen_core_kit_legacy --seam-pad / recipe key `seam_pad`, default off;
the hook is seam_pad_port.tcl, one chain per input PORT net), or proven in memory by seam_pad_measure.tcl (PAD_SPEC).
MEASURED-basis sizing is an estimate for a provisional parent: the kit SDC still carries the -40 contract, so a kit verdict
only changes when the matched parent receipt (io_hold_parent) passes; the contract basis is what removes NEEDS_PARENT at the kit.

  seam_pad_per_pin.py size --child CHILD.tsv [--parent-ff FF.tsv --parent-tt TT.tsv] --out SPEC.json [--audit AUDIT.tsv]
     CHILD.tsv  port<TAB>endpoint<TAB>ff_hold_slack_ps<TAB>tt_setup_slack_ps [...]  (seam_pad_measure.tcl row, contract frame)
     FF.tsv/TT.tsv  parent_core_hold.py rows: kind port pin start end slack_ps arrival ; B = hold row, A = setup row
"""
import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import face_hold_pad as F

SCHEMA = "opentallas.seam_pad_per_pin.v1"
GUARD_PS = 10.0                  # contract basis (the kit gate itself is FF slack >= 0)
MEASURED_GUARD_PS = 30.0         # measured-parent basis: one cell of margin over a provisional / single-instance parent read
# MEASURED in memory on the retained routed LLfd / LLfu final ODBs and the l5f GRT ODB (seam_pad_measure.tcl, port-ingress chain of
# 2-3 HB4 on 128 + 128 + 67 input pins): FF hold gain per HB4 min 35.46 / med 40.6-42.4 / max 44.1 ps; TT setup cost per HB4 max 64.76 ps.
# (The earlier 23.8 ps/cell "2 x HB4 = +47.6" figure was an estimate; the measured gain is 1.5-1.8x that.)
HB4_FF_PS = 35.0                 # conservative: below the measured minimum 35.46
HB4_TT_PS = 65.0                 # conservative: above the measured maximum 64.76
TT_FLOOR_PS = 0.0                # a padded PORT path must keep nonnegative TT setup (the -42 gate is for the whole core)
N_MAX = 6
HOOK_TCL = HERE / "seam_pad_port.tcl"


def tcl_dict(spec):
    """seam_pad_port_n.tcl: ::ot_sp_per {port n} (the kit has no JSON reader)."""
    if spec.get("schema") != F.SCHEMA or spec.get("by") != "port":
        raise ValueError("seam_pad spec must be a face_hold_pad.v1 spec with by=port")
    per = spec.get("per_endpoint") or {}
    nmax = int(spec.get("n_max", N_MAX))
    if any(int(n) < 1 or int(n) > nmax for n in per.values()):
        raise ValueError("seam_pad spec: sizes out of range")
    for k in per:
        if any(c in k for c in "{}\\ ") or not k:
            raise ValueError(f"port name not brace-quotable: {k!r}")
    lines = ["# GENERATED by seam_pad_per_pin.py: per-port HB4 counts (measured seam slack), SEAM-PAD-R3",
             "set ::ot_sp_per [dict create \\"]
    lines += [f" {{{k}}} {int(v)} \\" for k, v in sorted(per.items())]
    lines.append("]")
    return "\n".join(lines) + "\n"


def stage(kd, spec):
    """Install the port-ingress pad hook in a generated kit dir (PRE_CTS hold_budget.tcl).  spec = dict or JSON path.  Fail closed."""
    kd = Path(kd)
    if not isinstance(spec, dict):
        spec = json.loads(Path(spec).read_text())
    body = tcl_dict(spec)                       # validates
    hb = kd / "hold_budget.tcl"
    if not hb.exists():
        raise SystemExit("seam_pad: kit has no hold_budget.tcl (PRE_CTS hook); refusing")
    (kd / "seam_pad_port.tcl").write_text(HOOK_TCL.read_text())
    (kd / "seam_pad_port_n.tcl").write_text(body)
    (kd / "seam_pad.json").write_text(json.dumps(spec, indent=1) + "\n")
    t = hb.read_text()
    src = "source /work/seam_pad_port.tcl\n"
    if src not in t:
        lines = t.splitlines(True)
        hb.write_text(lines[0] + src + "".join(lines[1:]) if lines and lines[0].startswith("#") else src + t)
    per = spec.get("per_endpoint") or {}
    return dict(kit=str(kd), pins=spec.get("endpoints"), padded=len(per), cells=sum(per.values()))


def read_child(text):
    """port -> dict(endpoint, ff, tt) from seam_pad_measure.tcl rows (nan -> None)."""
    out = {}
    for ln in text.splitlines():
        f = ln.rstrip("\n").split("\t")
        if len(f) < 4 or not f[0]:
            continue
        def num(x):
            try:
                v = float(x)
            except ValueError:
                return None
            return v if math.isfinite(v) else None
        out[f[0]] = dict(endpoint=f[1], ff=num(f[2]), tt=num(f[3]))
    return out


def read_parent(text, kind):
    """parent_core_hold.py FF.tsv / TT.tsv -> {port: slack_ps} for rows of `kind` ('B' hold FF, 'A' setup TT).  Worst per port."""
    out = {}
    for ln in text.splitlines():
        f = ln.split("\t")
        if len(f) < 6 or f[0] != kind:
            continue
        try:
            s = float(f[5])
        except ValueError:
            continue
        out[f[1]] = min(s, out.get(f[1], s))
    return out


def size(child, parent_ff=None, parent_tt=None, guard=GUARD_PS, per_ff=HB4_FF_PS, per_tt=HB4_TT_PS,
         tt_floor=TT_FLOOR_PS, n_max=N_MAX, extra_ff=None, measured_guard=MEASURED_GUARD_PS):
    """extra_ff: {port: ff_slack} measured on a parent for pins the table does not cover (e.g. reset removal)."""
    parent_ff, parent_tt, extra_ff = parent_ff or {}, parent_tt or {}, extra_ff or {}
    rows, refused = [], []
    for port in sorted(child):
        c = child[port]
        if port in parent_ff:
            basis, ff = "measured_parent", parent_ff[port]
            tt = parent_tt.get(port, c["tt"])
            tt_basis = "measured_parent" if port in parent_tt else "child_contract"
        elif port in extra_ff:
            basis, ff = "measured_parent_extra", extra_ff[port]
            tt, tt_basis = c["tt"], "child_contract"
        else:
            basis, ff, tt, tt_basis = "contract", c["ff"], c["tt"], "child_contract"
        if ff is None:
            refused.append(dict(port=port, why="no FF slack"))
            continue
        g = guard if basis == "contract" else measured_guard
        n = F.cells_for(ff, per_ff, g, 10 ** 6)
        row = dict(port=port, endpoint=c["endpoint"], basis=basis, guard_ps=g, ff_slack_ps=round(ff, 3), need_ps=round(max(0.0, g - ff), 3),
                   n_hb4=n, tt_basis=tt_basis, tt_slack_ps=None if tt is None else round(tt, 3))
        if n:
            cost = n * per_tt
            row["tt_cost_ps"] = round(cost, 3)
            row["tt_after_ps"] = None if tt is None else round(tt - cost, 3)
            row["ff_after_ps"] = round(ff + n * per_ff, 3)
            if n > n_max:
                refused.append(dict(port=port, why=f"needs {n} HB4 > n_max {n_max}", ff_slack_ps=round(ff, 3)))
                row["n_hb4"] = 0
            elif tt is None or tt - cost < tt_floor:
                refused.append(dict(port=port, why="TT setup cannot pay", tt_slack_ps=tt, cost_ps=cost))
                row["n_hb4"] = 0
        rows.append(row)
    per = {r["port"]: r["n_hb4"] for r in rows if r["n_hb4"]}
    by_basis = {}
    for r in rows:
        b = by_basis.setdefault(r["basis"], dict(pins=0, padded=0, cells=0))
        b["pins"] += 1
        b["padded"] += 1 if r["n_hb4"] else 0
        b["cells"] += r["n_hb4"]
    spec = dict(schema=F.SCHEMA, by="port", match="", per_cell_ps=per_ff, guard_ps=guard, measured_guard_ps=measured_guard, n_max=n_max, default_n=0,
                endpoints=len(rows), padded=len(per), cells=sum(per.values()), per_endpoint=per,
                source="seam_pad_per_pin", seam_pad_schema=SCHEMA)
    audit = dict(schema=SCHEMA, guard_ps=guard, measured_guard_ps=measured_guard, per_cell_ff_ps=per_ff, per_cell_tt_ps=per_tt, tt_floor_ps=tt_floor,
                 pins=len(rows), padded=len(per), cells=sum(per.values()), by_basis=by_basis, refused=refused, rows=rows)
    return spec, audit


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    z = sub.add_parser("size")
    z.add_argument("--child", required=True)
    z.add_argument("--parent-ff")
    z.add_argument("--parent-tt")
    z.add_argument("--extra-ff", help="JSON {port: ff_slack_ps} measured on a real parent for pins outside the table")
    z.add_argument("--out", required=True)
    z.add_argument("--audit")
    z.add_argument("--pad-tsv", help="port<TAB>n rows for seam_pad_measure.tcl PAD_SPEC")
    z.add_argument("--guard", type=float, default=GUARD_PS)
    z.add_argument("--measured-guard", type=float, default=MEASURED_GUARD_PS)
    z.add_argument("--per-cell-ff", type=float, default=HB4_FF_PS)
    z.add_argument("--per-cell-tt", type=float, default=HB4_TT_PS)
    z.add_argument("--tt-floor", type=float, default=TT_FLOOR_PS)
    z.add_argument("--n-max", type=int, default=N_MAX)
    a = ap.parse_args(argv)
    child = read_child(Path(a.child).read_text())
    if not child:
        print("seam_pad_per_pin: no child rows", file=sys.stderr)
        return 2
    pff = read_parent(Path(a.parent_ff).read_text(), "B") if a.parent_ff else None
    ptt = read_parent(Path(a.parent_tt).read_text(), "A") if a.parent_tt else None
    extra = json.loads(Path(a.extra_ff).read_text()) if a.extra_ff else None
    spec, audit = size(child, pff, ptt, a.guard, a.per_cell_ff, a.per_cell_tt, a.tt_floor, a.n_max, extra, a.measured_guard)
    Path(a.out).write_text(json.dumps(spec, indent=1) + "\n")
    if a.audit:
        Path(a.audit).write_text(json.dumps(audit, indent=1) + "\n")
    if a.pad_tsv:
        Path(a.pad_tsv).write_text("".join(f"{p}\t{n}\n" for p, n in sorted(spec["per_endpoint"].items())))
    print(json.dumps({k: audit[k] for k in ("pins", "padded", "cells", "by_basis")} | dict(refused=len(audit["refused"]))))
    return 1 if audit["refused"] else 0


if __name__ == "__main__":
    sys.exit(main())
