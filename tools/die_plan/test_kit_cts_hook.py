def _snap(kd):
    return {p.name: p.read_bytes() for p in sorted(kd.iterdir())}


def _kit(kd, files, tree=True):
    for n, t in files.items():
        (kd / n).write_text(t)
    if tree:
        (kd / "core_infra_plan.json").write_text(json.dumps({"core_tree": {"cts_open": []}}))
        (kd / "core_infra_cts.tcl").write_text("set ::ot_ci_cts_plan_open 0\n")
    return kd


def _no_tree_identical(tmp_path, files, cfg):
    """no core_infra_plan.json, and a pushdown slice WITHOUT a core tree: kit files + config lines unchanged"""
    for plan in (None, {"core_tree": None}):
        kd = tmp_path / f"n{len(list(tmp_path.iterdir()))}"
        kd.mkdir()
        _kit(kd, files, tree=False)
        if plan is not None:
            (kd / "core_infra_plan.json").write_text(json.dumps(plan))
        before, c = _snap(kd), list(cfg)
        assert MS.plan_tree_cts(kd, c) is False
        assert _snap(kd) == before and c == cfg


@pytest.mark.parametrize("gen", sorted(GENS))
def test_generator_calls_shared_hook_before_config_mk(gen):
    src = GENS[gen].read_text()
    call = "    planned_tree_cts(kd, cfg)\n" if gen == "s81_legacy" else "MS.plan_tree_cts(kd, cfg)"
    assert src.count(call) == 1, gen
    i_apply, i_call = src.index("MS.kit_apply("), src.index(call)
    i_cfg = src.index('(kd / "config.mk").write_text("\\n".join(cfg) + "\\n")', i_call)
    assert i_apply < i_call < i_cfg
    between = src[i_call + len(call):i_cfg]
    assert "cfg" not in between, f"{gen}: cfg edited after the CTS hook"
    if gen == "s81_legacy":   # legacy delegates (no second copy of the hook logic)
        body = src[src.index("def planned_tree_cts(kd, cfg):"):src.index("def main():")]
        assert "_ms().plan_tree_cts(kd, cfg)" in body and "write_text" not in body


def _no_cts_hooks(tmp_path):
    """generators with stock TritonCTS (no PRE/POST_CTS): one generated PRE_CTS hook, nothing else"""
    cfg = ["export CORNER = TC", "export CTS_ARGS = -sink_clustering_enable -repair_clock_nets"]
    _no_tree_identical(tmp_path, {"face_flops.tcl": "x\n"}, cfg)
    (tmp_path / "t").mkdir()
    kd = _kit(tmp_path / "t", {"face_flops.tcl": "x\n"})
    assert MS.plan_tree_cts(kd, cfg) is True
    assert cfg[-1] == f"override export PRE_CTS_TCL = /work/{CI.CTS_PRE_CHAIN}"
    assert CI.cfg_effective(cfg, "PRE_CTS_TCL") == f"/work/{CI.CTS_PRE_CHAIN}"
    assert CI.cfg_effective(cfg, "POST_CTS_TCL") is None
    assert (kd / CI.CTS_PRE_CHAIN).read_text().endswith("source /work/core_infra_cts.tcl\n")


