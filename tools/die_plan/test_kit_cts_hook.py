def test_qc_insertion_balance(tmp_path):
    # gen_core_kit_qc: PRE_CTS hold_budget.tcl, POST_CTS cts_post.tcl (sources tap_balance.tcl) -> in place
    files = {"hold_budget.tcl": "# GENERATED by gen_core_kit_qc.py\nproc a {} {}\n",
             "cts_post.tcl": "source /work/tap_balance.tcl\nestimate_parasitics -placement\n",
             "tap_balance.tcl": "set tb_ronly 0\n"}
    cfg = ["export SKIP_CTS_REPAIR_TIMING = 1", "export POST_CTS_TCL = /work/cts_post.tcl",
           "export PRE_CTS_TCL = /work/hold_budget.tcl"]
    _no_tree_identical(tmp_path, files, cfg)
    (tmp_path / "t").mkdir()
    kd = _kit(tmp_path / "t", files)
    c = list(cfg)
    assert MS.plan_tree_cts(kd, c) is True and c == cfg
    assert (kd / "hold_budget.tcl").read_text() == files["hold_budget.tcl"] + CI.CTS_PRE_LINES
    assert (kd / "cts_post.tcl").read_text() == CI.CTS_POST_LINES + files["cts_post.tcl"]
    assert (kd / "tap_balance.tcl").read_text() == files["tap_balance.tcl"]


def test_kv_flow_basis(tmp_path):
    # gen_core_kit_kv flow basis: PRE_CTS max_fanout.tcl is also PRE_RESIZE / PRE_GLOBAL_ROUTE -> chained, never edited
    files = {"max_fanout.tcl": "set_max_fanout 64 [current_design]\n", "leaf_affinity.tcl": "set la_ronly 0\n"}
    cfg = ["export POST_CTS_TCL = /work/leaf_affinity.tcl", "export PRE_RESIZE_TCL = /work/max_fanout.tcl",
           "export PRE_CTS_TCL = /work/max_fanout.tcl", "export PRE_GLOBAL_ROUTE_TCL = /work/max_fanout.tcl"]
    _no_tree_identical(tmp_path, files, cfg)
    (tmp_path / "t").mkdir()
    kd = _kit(tmp_path / "t", files)
    c = list(cfg)
    assert MS.plan_tree_cts(kd, c) is True
    assert (kd / "max_fanout.tcl").read_text() == files["max_fanout.tcl"]
    assert CI.cfg_effective(c, "PRE_CTS_TCL") == f"/work/{CI.CTS_PRE_CHAIN}"
    assert CI.cfg_effective(c, "PRE_RESIZE_TCL") == CI.cfg_effective(c, "PRE_GLOBAL_ROUTE_TCL") == "/work/max_fanout.tcl"
    pre = (kd / CI.CTS_PRE_CHAIN).read_text()
    assert pre.index("source /work/max_fanout.tcl") < pre.index("source /work/core_infra_cts.tcl")
    assert (kd / "leaf_affinity.tcl").read_text() == CI.CTS_POST_LINES + files["leaf_affinity.tcl"]


def test_kv_head_lane_taps_refused(tmp_path):
    # --head-lane-taps builds its own per-lane clock taps at PRE_CTS: a competing clock method -> fail closed
    files = {"max_fanout.tcl": "x\n", "head_lane_taps.tcl": "x\n",
             "lane_pre_cts.tcl": "source /work/max_fanout.tcl\nsource /work/head_lane_taps.tcl\n"}
    cfg = ["export PRE_CTS_TCL = /work/lane_pre_cts.tcl"]
    _no_tree_identical(tmp_path, files, cfg)
    (tmp_path / "t").mkdir()
    with pytest.raises(SystemExit, match="head_lane_taps.tcl"):
        MS.plan_tree_cts(_kit(tmp_path / "t", files), list(cfg))


def test_hbm_arch(tmp_path):
    # gen_core_kit_hbm: POST_CTS tap_balance.tcl, then `override` f4_chain_leaf.tcl (default) -> F4 re-leafs flops
    # post-CTS (no report-only mode) -> refused for a plan tree; with --no-f4 the tap balance runs report-only
    files = {"tap_balance.tcl": "set tb_ronly 0\n", "f4_chain_leaf.tcl": "x\n",
             "core_pre_cts.tcl": "unset_clock_latency -clock clk [get_ports {clk}]\n"}
    f4 = ["export POST_CTS_TCL = /work/tap_balance.tcl", "override export POST_CTS_TCL = /work/f4_chain_leaf.tcl",
          "export OT_F4_NEXT_TCL = /work/tap_balance.tcl"]
    _no_tree_identical(tmp_path, files, f4)
    (tmp_path / "t").mkdir()
    with pytest.raises(SystemExit, match="f4_chain_leaf.tcl"):
        MS.plan_tree_cts(_kit(tmp_path / "t", files), list(f4))
    no_f4 = ["export POST_CTS_TCL = /work/tap_balance.tcl", "override export PRE_CTS_TCL = /work/core_pre_cts.tcl"]
    _no_tree_identical(tmp_path, files, no_f4)
    (tmp_path / "u").mkdir()
    kd = _kit(tmp_path / "u", files)
    c = list(no_f4)
    assert MS.plan_tree_cts(kd, c) is True and c == no_f4
    assert (kd / "core_pre_cts.tcl").read_text() == files["core_pre_cts.tcl"] + CI.CTS_PRE_LINES
    assert (kd / "tap_balance.tcl").read_text() == CI.CTS_POST_LINES + files["tap_balance.tcl"]
    dens = ["export PRE_CTS_TCL = /work/core_density_taps.tcl"]
    (tmp_path / "v").mkdir()
    with pytest.raises(SystemExit, match="core_density_taps.tcl"):
        MS.plan_tree_cts(_kit(tmp_path / "v", dict(files, **{"core_density_taps.tcl": "x\n"})), dens)


