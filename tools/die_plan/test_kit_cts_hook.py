def test_fail_closed_inputs(tmp_path):
    kd = _kit(tmp_path, {})
    with pytest.raises(SystemExit, match="not a kit Tcl file"):
        MS.plan_tree_cts(kd, ["export PRE_CTS_TCL = $(PLATFORM_DIR)/x.tcl"])
    with pytest.raises(SystemExit, match="not a kit Tcl file"):
        MS.plan_tree_cts(kd, ["export POST_CTS_TCL = /work/missing.tcl"])
    (kd / "core_infra_cts.tcl").unlink()
    with pytest.raises(SystemExit, match="core_infra.install too old"):
        MS.plan_tree_cts(kd, [])


def test_cfg_effective_make_semantics():
    cfg = ["export A = 1", "override export A = 2", "export A = 3", "export B ?= 4", "export B = 5"]
    assert CI.cfg_effective(cfg, "A") == "2" and CI.cfg_effective(cfg, "B") == "5"
    assert CI.cfg_effective(cfg, "C") is None
