"""CTS-HOOK-PORT-1: the one shared plan-tree CTS hook (core_infra.kit_cts_hook via master_slice.plan_tree_cts) in every
core-kit generator.  One test per generator: (1) the generator calls the hook after master_slice.kit_apply and right
before config.mk is written; (2) with that generator's own PRE/POST_CTS hook shape, a kit without a plan tree is
byte-identical and a plan-tree kit gets TritonCTS-on-CTS-open-nets-only + report-only post-CTS balancing.
    python3 -m pytest -q tools/die_plan/test_kit_cts_hook.py"""
