#!/usr/bin/env python3
"""S81-CORES-1 (COORD 11-11, T51W-FORM): port-scope hold pad for forwarded-clock capture flops.

Class FCLK-FACE-IO-HOLD: a core whose input face is captured by flops on a forwarded clock (fclk_in_*) that
tap_balance pads to the plan insertion has port -> D paths that are PORT-START paths.  The kit GRT hold repair runs
with OT_HOLD_SCOPE=nonport (and a buffer cap), so it never repairs them, while signoff hold_ff counts them
(native_w v3: FF hold -96.93 on 2351 endpoints, 88 percent of them face capture flops).  The repair that class lacks
is data-side delay on the D pin, sized per endpoint from the MEASURED FF hold slack (not a flat count).

  face_hold_pad.py size (--report FF_END_REPORT | --port-rows FHP_ROWS) --out SPEC.json [--match GLOB] [--guard PS] [--per-cell PS] [--n-max N]
      FF_END_REPORT = OpenROAD `report_checks -path_delay min -to <D pins> -format end -group_path_count N` text of the
      FF corner (the same frame as signoff hold_ff).  -> per_endpoint {instance: HB4 cells}, endpoints with
      slack >= guard get none.
  gen_core_kit_legacy.py --face-hold-pad SPEC.json  (or recipe key face_hold_pad) -> stage(): kit/face_hold_pad.tcl +
      kit/face_hold_pad_n.tcl (the per-endpoint dict) and `source /work/face_hold_pad.tcl` first in hold_budget.tcl
      (PRE_CTS).  Function-preserving (buffers only); DPL legalises the cells later.
"""
import argparse
import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCHEMA = "opentallas.face_hold_pad.v1"
HB4_FF_PS = 37.0      # FF delay of one HB4xp67 (hold_pad_hb4.tcl header, measured on s81hc_ctfxnt_ref v5 CTS)
GUARD_PS = 10.0       # estimation margin on the sized slack (the gate itself is FF slack >= 0)
N_MAX = 12
MATCH = "g_freg.u_face"

_END = re.compile(r"^\s*(\S+)(?:\s+\([^)]*\))?\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)(?:\s+\(\w+\))?\s*$")


def cells_for(slack_ps, per_cell=HB4_FF_PS, guard=GUARD_PS, n_max=N_MAX):
    """HB4 cells that lift `slack_ps` to >= guard; 0 when it already is.  Capped at n_max (never silently larger)."""
    if per_cell <= 0:
        raise ValueError("per_cell must be positive")
    if slack_ps >= guard:
        return 0
    return min(int(n_max), int(math.ceil((guard - slack_ps) / per_cell)))


def parse_end_report(text):
    """OpenROAD `report_checks -format end` -> {instance: slack_ps}; the endpoint pin '<inst>/D' becomes '<inst>'.
    The worst (minimum) slack of an instance wins when it is listed twice."""
    out = {}
    for ln in text.splitlines():
        m = _END.match(ln)
        if not m:
            continue
        pin = m.group(1)
        if "/" not in pin:
            continue
        inst, _, term = pin.rpartition("/")
        if term != "D":
            continue
        s = float(m.group(4))
        out[inst] = min(s, out.get(inst, s))
    return out


def parse_port_rows(text):
    """'FHP <input port> <capture pin> <slack_ps>' rows (written by an STA helper that asks find_timing_paths for the
    worst path to each D pin) -> {port: slack_ps}.  Instance names differ between stage DBs (3_place has _NNNN_,
    the routed DB has q[i]$_DFF_P_), the input port that feeds the D pin does not, so port is the stable key."""
    out = {}
    for ln in text.splitlines():
        f = ln.split()
        if len(f) != 4 or f[0] != "FHP" or f[1] == "NONE":
            continue
        try:
            s = float(f[3])
        except ValueError:
            continue
        out[f[1]] = min(s, out.get(f[1], s))
    return out


def make_spec(slacks, match=MATCH, per_cell=HB4_FF_PS, guard=GUARD_PS, n_max=N_MAX, source="", by="inst"):
    per = {}
    for inst, s in sorted(slacks.items()):
        n = cells_for(s, per_cell, guard, n_max)
        if n:
            per[inst] = n
    if by not in ("inst", "port"):
        raise ValueError("by must be inst or port")
    return dict(schema=SCHEMA, by=by, match=match, per_cell_ps=per_cell, guard_ps=guard, n_max=n_max, default_n=0,
                endpoints=len(slacks), padded=len(per), cells=sum(per.values()), source=source, per_endpoint=per)


def _tcl_word(s):
    if any(c in s for c in "{}") or s.endswith("\\"):
        raise ValueError(f"instance name not brace-quotable: {s!r}")
    return "{" + s + "}"


def tcl_dict(spec):
    """face_hold_pad_n.tcl: the per-endpoint sizes as Tcl (the kit has no JSON reader)."""
    if spec.get("schema") != SCHEMA:
        raise ValueError("face_hold_pad spec schema")
    per = spec.get("per_endpoint") or {}
    default = int(spec.get("default_n", 0))
    if default < 0 or any(int(n) < 1 or int(n) > int(spec.get("n_max", N_MAX)) for n in per.values()):
        raise ValueError("face_hold_pad spec: sizes out of range")
    lines = ["# GENERATED by face_hold_pad.py: per-endpoint HB4 counts from the measured FF hold slack",
             f"set ::ot_fp_match {_tcl_word('*' + spec.get('match', MATCH) + '*')}",
             f"set ::ot_fp_default {default}",
             f"set ::ot_fp_by {spec.get('by', 'inst')}",
             "set ::ot_fp_per [dict create \\"]
    lines += [f" {_tcl_word(k)} {int(v)} \\" for k, v in sorted(per.items())]
    lines.append("]")
    return "\n".join(lines) + "\n"


def stage(kd, spec):
    """Install the hook in a generated kit dir kd.  spec = dict or path to a spec JSON.  Fail closed."""
    kd = Path(kd)
    if not isinstance(spec, dict):
        spec = json.loads(Path(spec).read_text())
    body = tcl_dict(spec)                       # validates
    hb = kd / "hold_budget.tcl"
    if not hb.exists():
        raise SystemExit("face_hold_pad: kit has no hold_budget.tcl (PRE_CTS hook); refusing")
    (kd / "face_hold_pad.tcl").write_text((HERE / "face_hold_pad.tcl").read_text())
    (kd / "face_hold_pad_n.tcl").write_text(body)
    (kd / "face_hold_pad.json").write_text(json.dumps(spec, indent=1) + "\n")
    t = hb.read_text()
    src = "source /work/face_hold_pad.tcl\n"
    if src not in t:
        lines = t.splitlines(True)
        hb.write_text(lines[0] + src + "".join(lines[1:]) if lines and lines[0].startswith("#") else src + t)
    return dict(kit=str(kd), endpoints=spec.get("endpoints"), padded=len(spec.get("per_endpoint") or {}),
                cells=sum((spec.get("per_endpoint") or {}).values()))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    z = sub.add_parser("size")
    z.add_argument("--report", help="OpenROAD report_checks -format end text (keyed by instance)")
    z.add_argument("--port-rows", help="'FHP port pin slack' rows (keyed by input port; stable across stage DBs)")
    z.add_argument("--out", required=True)
    z.add_argument("--match", default=MATCH)
    z.add_argument("--guard", type=float, default=GUARD_PS)
    z.add_argument("--per-cell", type=float, default=HB4_FF_PS)
    z.add_argument("--n-max", type=int, default=N_MAX)
    a = ap.parse_args(argv)
    if bool(a.report) == bool(a.port_rows):
        print("face_hold_pad: give exactly one of --report / --port-rows", file=sys.stderr)
        return 2
    by = "port" if a.port_rows else "inst"
    src = a.port_rows or a.report
    sl = (parse_port_rows if a.port_rows else parse_end_report)(Path(src).read_text())
    if not sl:
        print("face_hold_pad: no endpoint rows in the report", file=sys.stderr)
        return 2
    spec = make_spec(sl, a.match, a.per_cell, a.guard, a.n_max, source=str(src), by=by)
    Path(a.out).write_text(json.dumps(spec, indent=1) + "\n")
    print(f"face_hold_pad size: {spec['endpoints']} endpoints, {spec['padded']} padded, {spec['cells']} HB4 cells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
