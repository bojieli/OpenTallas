PKG_USE = re.compile(r"\b([A-Za-z_]\w*)::")


def kit_closure(names, idx, prefer, picks=None):
    """E.closure for a G3 kit (KV-P6 18:51 hub_Wi): (1) a module with a hardened view (macro dir <m>/<m>.lef) is a
    HARD MACRO: its black box (<m>_bb.v, else the model) goes in the list, its lef/libs in the manifest, no descent;
    (2) a *_sim.sv definition is never picked while a non-sim candidate exists.  -> files, missing, macros
    QC-KITS 10-25: descends only into the NEEDED module bodies (not every module of a picked file: a file picked for
    one module dragged in the instantiations of its unrelated siblings, e.g. sle_ctl got ot_v41_attn_eng_ctl_endpoint_phys
    + ot_hdc_fastfp, two different ot_hdc_qadd -> yosys Re-definition of module at the kit preflight).  `picks`
    (optional dict) receives {module: file} for every needed module (kit_strip_dups keeps those definitions)."""
    seen, files, missing, macros = set(), [], set(), {}
    picks = {} if picks is None else picks
    todo = list(names)
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.add(n)
        cands = idx.get(n, [])
        hard = [f for f in cands if Path(f).parent.name == n and (Path(f).parent / f"{n}.lef").is_file()]
        if hard:
            d = Path(hard[0]).parent
            bb, mdl = d / f"{n}_bb.v", d / f"{n}.v"
            macros[n] = dict(dir=str(d.resolve()), lef=str((d / f"{n}.lef").resolve()),
                             libs=[str(x.resolve()) for x in sorted(d.glob(f"{n}*.lib"))],
                             bb=str(bb.resolve()) if bb.is_file() else None, model=str(mdl.resolve()) if mdl.is_file() else None)
            f = macros[n]["bb"] or macros[n]["model"]
            if f and f not in files:
                files.append(f)
            continue
        nonsim = [f for f in cands if not SIM_FILE.search(f)]
        sub = dict(idx)
        if nonsim and len(nonsim) < len(cands):
            sub[n] = nonsim
        f, _ = E.pick(sub, n, prefer)
        if f is None:
            missing.add(n)
            continue
        picks[n] = f
        if f not in files:
            files.append(f)
        todo += sorted(E.instantiated(E.module_body(f, n), idx))
    return files, sorted(missing), macros


def kit_strip_dups(fl, kd, picks):
    """QC-KITS 10-25: a module defined in more than one kit file (a needed file also carries an unrelated sibling that
    another needed file defines too) would stop yosys (Re-definition of module) -- the as-built elab hides it with
    read_verilog -overwrite (last read wins).  The definition kept is the one the closure picked for that module (else
    the first in the list); every other file gets a KIT/dedup copy with that module removed (original unchanged), in
    its place in the list.  -> files, {copy: record}"""
    defs = {}
    for f in fl:
        for m in E.MOD_RE.finditer(E._strip(Path(f).read_text(errors="replace"))):
            defs.setdefault(m.group(1), [])
            if f not in defs[m.group(1)]:
                defs[m.group(1)].append(f)
    drop = defaultdict(set)                      # file -> modules to remove from it
    for m, fs in defs.items():
        if len(fs) < 2:
            continue
        keep = next((f for f in fs if m in picks and Path(f).resolve() == Path(picks[m]).resolve()), fs[0])
        for f in fs:
            if f != keep:
                drop[f].add(m)
    out, rec = [], {}
    for f in fl:
        if f not in drop:
            out.append(f)
            continue
        t = Path(f).read_text(errors="replace")
        new = t
        for m in sorted(drop[f]):
            new, k = re.subn(r"^[ \t]*(?:\(\*[^\n]*?\*\)\s*)?module\s+" + re.escape(m) + r"\b.*?^[ \t]*endmodule\b[^\n]*\n?",
                             "", new, count=1, flags=re.S | re.M)
            if k != 1:
                raise BindError(f"kit-rtl: cannot strip duplicate module {m} from {f}")
        d = Path(kd) / "dedup"
        d.mkdir(exist_ok=True)
        c = d / Path(f).name
        c.write_text(new)
        rec[str(c)] = dict(original=str(f), removed=sorted(drop[f]),
                           original_sha256=hashlib.sha256(t.encode()).hexdigest()[:16])
        out.append(c)
    return out, rec


def kit_packages(files, roots, base):
    """the package files the kit's sources reference (pkg::x / import pkg::*), transitively, in dependency order --
    they must precede their users in the filelist (KV-P6 18:51: ot_qfd_emb_pkg missing -> yosys 'unexpected import')."""
    uses = {f: set(PKG_USE.findall(E._strip(Path(f).read_text(errors="replace")))) for f in files}
    # packages live beside their users: index the kit files' own directories first, the whole RTL roots only when a
    # referenced *pkg* name is still unresolved
    pidx = _pkg_index(sorted({str(Path(f).resolve().parent) for f in files}), base, recurse=False)
    want = {u for us in uses.values() for u in us if "pkg" in u.lower()}
    if want - set(pidx):
        key = (tuple(roots), str(base))
        if key not in _PKG_CACHE:
            _PKG_CACHE[key] = _pkg_index(roots, base)
        pidx = {**_PKG_CACHE[key], **pidx}
    order, seen = [], set()

    def need(f, us=None):
        for u in sorted(us if us is not None else set(PKG_USE.findall(E._strip(Path(f).read_text(errors="replace"))))):
            if u in pidx and u not in seen:
                seen.add(u)
                need(pidx[u])               # its own imports first
                order.append(Path(pidx[u]))
    for f in files:
        need(f, uses[f])
    return order                            # kit_dedupe keeps the first (package-first) occurrence


_PKG_CACHE = {}


def _pkg_index(roots, base, recurse=True):
    pidx = {}
    for r in roots:
        rp = Path(r) if Path(r).is_absolute() else Path(base) / r
        g = rp.rglob if recurse else rp.glob
        for p in (sorted(list(g("*.sv")) + list(g("*.v"))) if rp.is_dir() else [rp]):
            if E.SKIP_DIR.search(str(p)):
                continue
            try:
                t = p.read_text(errors="replace")
            except OSError:
                continue
            if "package" in t:
                for m in PKG_DEF.finditer(E._strip(t)):
                    pidx.setdefault(m.group(1), str(p.resolve()))
    return pidx


BODY_IMPORT = re.compile(r"^[ \t]+import\s+([A-Za-z_]\w*)::\*\s*;[ \t]*$", re.M)


KIT_INCLUDE = re.compile(r'^([ \t]*)`include\s+"([^"]+)"[^\n]*$', re.M)


def kit_inline_includes(fl, kd):
    """gen.py phys flattens the kit RTL into KIT/rtl/, so a source `include "sub/x.svh"` (resolved by the simulator
    relative to the including file) no longer opens in the kit (QC-KITS 10-25: qwen_compute glue, SELRANGE "Can't open
    include file ovl_release_rope/ovl_release_img.svh").  A file with includes is copied into KIT/inline/ with each
    include replaced by the included text (recursively, relative to the including file; original sources unchanged);
    the copy takes the original's place in the list.  A missing include is a BindError.  -> files, {copy: record}"""
    def expand(path, depth, seen):
        if depth > 8:
            raise BindError(f"kit-rtl: `include nesting > 8 at {path}")
        t = path.read_text(errors="replace")

        def sub(m):
            q = (path.parent / m.group(2)).resolve()
            if not q.is_file():
                raise BindError(f'kit-rtl: {path}: `include "{m.group(2)}" not found next to the including file')
            seen.append(str(q))
            return f'{m.group(1)}// kit-rtl inlined `include "{m.group(2)}"\n' + expand(q, depth + 1, seen) + "\n"
        return KIT_INCLUDE.sub(sub, t)
    out, rec = [], {}
    for f in fl:
        f = Path(f)
        t = f.read_text(errors="replace")
        if not KIT_INCLUDE.search(t):
            out.append(f)
            continue
        seen = []
        new = expand(f, 0, seen)
        d = Path(kd) / "inline"
        d.mkdir(exist_ok=True)
        c = d / f.name
        c.write_text(new)
        rec[str(c)] = dict(original=str(f), includes=seen, original_sha256=hashlib.sha256(t.encode()).hexdigest()[:16])
        out.append(c)
    return out, rec


def kit_inline_imports(fl, kd):
    """Yosys read_verilog rejects a package import inside a module body ('unexpected TOK_IMPORT'): such a file is
    copied into KIT/inline/ with each `import P::*;` replaced by P's body (the tools/emb_hbm_synth_sources.py transform,
    original sources unchanged); the copy takes the original's place in the list.  -> files, {copy: record}"""
    pk = {}
    for f in fl:
        t = Path(f).read_text(errors="replace")
        for m in re.finditer(r"^\s*package\s+(\w+)\s*;(.*?)^\s*endpackage\b", t, re.S | re.M):
            pk[m.group(1)] = m.group(2)
    out, rec = [], {}
    for f in fl:
        t = Path(f).read_text(errors="replace")
        hits = [m for m in BODY_IMPORT.finditer(t) if m.group(1) in pk]
        if not hits:
            out.append(f)
            continue
        new = BODY_IMPORT.sub(lambda m: pk[m.group(1)] if m.group(1) in pk else m.group(0), t)
        d = Path(kd) / "inline"
        d.mkdir(exist_ok=True)
        c = d / Path(f).name
        c.write_text(new)
        rec[str(c)] = dict(original=str(f), packages=sorted({m.group(1) for m in hits}),
                           original_sha256=hashlib.sha256(t.encode()).hexdigest()[:16])
        out.append(c)
    return out, rec


def bindf_prefer(out, base):
    """QC-A0 10-24: the RTL files the bind itself listed (OUT/bind.f, relative to the source tree) win every module-name
    ambiguity in the kit closure.  A later tree that adds a second definition of a bound module (the A0 snapshot dirs
    rtl/physical/a0_rc1[45]_selected_2000/ sort before rtl/physical/qfd_tile_*) must not silently swap the bound
    module for another RTL in the G3 kit."""
    f = Path(out) / "bind.f"
    if not f.is_file():
        return []
    res = []
    for ln in f.read_text().split():
        p = Path(ln) if Path(ln).is_absolute() else Path(base) / ln
        if p.is_file():
            res.append(str(p))
    return res


def kit_dedupe(tn, fl):
    """one file per basename (gen_phys flattens rtl/): identical copies are dropped, different contents are an error."""
    out, by = [], {}
    for f in fl:
        f = Path(f)
        if f.name in by:
            if by[f.name].read_bytes() != f.read_bytes():
                raise BindError(f"kit-rtl {tn}: two different files named {f.name}: {by[f.name]} vs {f}")
            continue
        by[f.name] = f
        out.append(f)
    return out


