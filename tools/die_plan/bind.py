class BindError(Exception):
    pass


def sv_id(s):
    s = re.sub(r"[^A-Za-z0-9_]", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    return s if s and not s[0].isdigit() else "n" + s


def short_id(s, n=60):
    s = sv_id(s)
    if len(s) <= n:
        return s
    return s[: n - 9] + "_" + hashlib.sha1(s.encode()).hexdigest()[:8]


# ------------------------------------------------------------------------------------------------ rules
class Rules:
    def __init__(self, ab):
        self.transport = [(re.compile(r["module"]), r) for r in ab.get("transport", [])]
        self.reducers = [(re.compile(r["module"]), r) for r in ab.get("reducers", [])]
        self.sources = [(re.compile(r["module"]), r) for r in ab.get("sources", [])]
        self.clocks = [(re.compile(r["pin"]), r.get("domain", "core")) for r in ab.get("clocks", [])]
        self.resets = [(re.compile(r["pin"]), r.get("polarity", "low")) for r in ab.get("resets", [])]
        self.straps = [re.compile(r) for r in ab.get("straps", [])]
        mp = dict(ab.get("map", {}))
        if ab.get("map_file"):
            mf = json.loads(Path(ab["map_file"]).read_text())
            mp = dict(parts={**mf.get("parts", {}), **mp.get("parts", {})}, rules=mp.get("rules", []) + mf.get("rules", []))
        self.parts = dict(mp.get("parts", {}))
        self.rules = [(re.compile(a), b) for a, b in mp.get("rules", [])]
        self.ignore_out = [re.compile(r) for r in ab.get("open_outputs", [])]

    @staticmethod
    def _first(lst, s):
        for rx, r in lst:
            if rx.fullmatch(s):
                return r
        return None

    def transport_of(self, m):
        return self._first(self.transport, m)

    def reducer_of(self, m):
        return self._first(self.reducers, m)

    def source_of(self, m):
        return self._first(self.sources, m)

    def clock_of(self, pin):
        return self._first(self.clocks, pin)

    def reset_of(self, pin):
        return self._first(self.resets, pin)

    def is_strap(self, pin):
        return any(rx.fullmatch(pin) for rx in self.straps)

    def part_of(self, path):
        p = path
        while True:
            if p in self.parts:
                return self.parts[p]
            if "." not in p:
                break
            p = p.rsplit(".", 1)[0]
        for rx, part in self.rules:
            m = rx.fullmatch(path)
            if m:
                return m.expand(part) if "\\" in part else part
        return None


def _bitlist(spec):
    """'a' / 'a[3:0]' style port selector -> (port, lo, hi or None)"""
    m = re.fullmatch(r"(\w+)(?:\[(\d+)(?::(\d+))?\])?", spec)
    if not m:
        raise BindError(f"bad port selector {spec}")
    if m.group(2) is None:
        return m.group(1), None, None
    hi = int(m.group(2))
    lo = int(m.group(3)) if m.group(3) is not None else hi
    return m.group(1), lo, hi


# ------------------------------------------------------------------------------------------------ the as-built graph
class Graph:
    """the flattened as-built die with transport removed: per leaf/glue input bit its logical source."""

    def __init__(self, F, rules, errors):
        self.F, self.R, self.err = F, rules, errors
        self.drv = defaultdict(list)       # net -> [(cell idx, port, bit)]
        self.loads = defaultdict(list)     # net -> [(cell idx, port, bit)]
        self.kind = []                     # per cell: leaf | glue | transport | reducer | source
        self.spec = []
        self.dirs = []
        for ci, c in enumerate(F.cells):
            t = rules.transport_of(c.module)
            r = rules.reducer_of(c.module) if t is None else None
            s = rules.source_of(c.module) if t is None and r is None else None
            if t is not None:
                k, sp = "transport", t
            elif r is not None:
                k, sp = "reducer", r
            elif s is not None:
                k, sp = "source", s
            elif c.kind == "unknown":
                errors.append(f"UNKNOWN_MODULE {c.path} ({c.module}): no RTL and no transport/source rule")
                k, sp = "unknown", None
            else:
                k, sp = c.kind, None
            self.kind.append(k)
            self.spec.append(sp)
            d = dict(c.dirs)
            if k in ("transport", "reducer", "source") and sp is not None:
                d = self._rule_dirs(c, k, sp, d)
            self.dirs.append(d)
            for pn, bits in c.ports.items():
                dd = d.get(pn)
                if dd is None:
                    errors.append(f"PORT_DIR {c.path}.{pn} ({c.module}): direction unknown")
                    continue
                for i, b in enumerate(bits):
                    if isinstance(b, str):
                        continue
                    if dd == "output":
                        self.drv[b].append((ci, pn, i))
                    elif dd == "input":
                        self.loads[b].append((ci, pn, i))
                    else:
                        self.drv[b].append((ci, pn, i))
                        self.loads[b].append((ci, pn, i))
        self.top_in = {}
        for pn, (d, bits) in F.top_ports.items():
            for i, b in enumerate(bits):
                if not isinstance(b, str) and d == "input":
                    self.top_in[b] = (pn, i)
        self._src = {}

    def _rule_dirs(self, c, k, sp, d):
        if k == "transport":
            outs = {p for p in c.ports if _tmap(sp, p)} | set(sp.get("drop_out", []))
            ins = set(sp.get("map", {}).values()) | set(sp.get("drop_in", []))
        elif k == "reducer":
            outs = {sp["out"]}
            ins = {p for p in c.ports if p != sp["out"]}
        else:
            outs = {p for p in c.ports if _src_out(sp, p) is not None} | set(sp.get("drop_out", []))
            ins = set(sp.get("drop_in", []))
        for pn in c.ports:
            if pn in outs:
                d[pn] = "output"
            elif pn in ins:
                d[pn] = "input"
            elif pn not in d:
                self.err.append(f"RULE_PORT {c.path}.{pn} ({c.module}): port not covered by its {k} rule")
        return d

    def pin(self, ci, pn):
        return f"{self.F.cells[ci].path}.{pn}"

    def source(self, net, depth=0):
        """logical source of a net: ('pin', ci, port, bit, stages) | ('const', v, where) | ('top', port, bit, 0) |
        ('clock', domain) | ('reset', polarity, stages) | ('or', [sources], stages) | ('undriven',) | ('multi', n)"""
        if isinstance(net, str):
            return ("const", net, "literal")
        if net in self._src:
            return self._src[net]
        if depth > 10000:
            raise BindError("transport loop")
        self._src[net] = ("undriven",)          # loop guard
        ds = self.drv.get(net, [])
        cd = self.F.const_drivers.get(net)
        res = None
        if len(ds) + (cd is not None) + (net in self.top_in) > 1:
            res = ("multi", len(ds) + (cd is not None) + (net in self.top_in), [self.pin(ci, pn) for ci, pn, _ in ds])
        elif cd is not None:
            res = ("const", cd[0], cd[1])
        elif net in self.top_in:
            res = ("top",) + self.top_in[net] + (0,)
        elif not ds:
            res = ("undriven",)
        else:
            ci, pn, bit = ds[0]
            k = self.kind[ci]
            c = self.F.cells[ci]
            if k == "transport":
                sp = self.spec[ci]
                ip = _tmap(sp, pn)
                if ip is None:
                    res = ("dropped", self.pin(ci, pn))
                else:
                    ib = c.ports[ip]
                    if sp.get("replicate") and ib:
                        bit = bit % len(ib)     # q = {N{d}} (station fan-out copies / landing ring slots)
                    up = self.source(ib[bit] if bit < len(ib) else "z", depth + 1)
                    st = int(sp.get("stages", 1))
                    if sp.get("stages_param"):
                        st = int(str(c.params.get(sp["stages_param"], st)).strip('"'))
                    res = _add_stages(up, st)
            elif k == "reducer":
                ups = []
                for ip, bits in sorted(c.ports.items()):
                    if ip == self.spec[ci]["out"] or ip in self.spec[ci].get("drop_in", []):
                        continue
                    for b in bits:
                        u = self.source(b, depth + 1)
                        if u[0] in ("const",) and u[1] == "0":
                            continue
                        if u[0] in ("dropped", "undriven"):
                            continue
                        if u[0] == "or":
                            ups.extend(u[1])
                        else:
                            ups.append(u)
                res = ("or", ups, int(self.spec[ci].get("stages", 0)))
            elif k == "source":
                sp = self.spec[ci]
                o = _src_out(sp, pn)
                if o is None:
                    res = ("dropped", self.pin(ci, pn))
                elif o[0] == "clock":
                    res = ("clock", o[1])
                else:
                    res = ("reset", o[1], 0)
            elif k == "glue" and c.ytype in ("$not", "$pos", "$buf") and pn == "Y" and bit < len(c.ports.get("A", [])):
                # a constant expression of the as-built die (e.g. far_n = ~far): folded, so a declared strap stays a
                # strap (partition parameter) on the far side of the inverter
                up = self.source(c.ports["A"][bit], depth + 1)
                if up[0] == "const" and up[1] in ("0", "1"):
                    v = up[1] if c.ytype != "$not" else ("1" if up[1] == "0" else "0")
                    res = ("const", v, f"{c.ytype}({up[2]})")
                else:
                    res = ("pin", ci, pn, bit, 0)
            else:
                pin = self.pin(ci, pn)
                ck = self.R.clock_of(pin)
                rs = self.R.reset_of(pin)
                if ck is not None:
                    res = ("clock", ck)
                elif rs is not None:
                    res = ("reset", rs, 0)
                else:
                    res = ("pin", ci, pn, bit, 0)
        self._src[net] = res
        return res


def _tmap(sp, pn):
    """a transport rule's input for output port pn: map {output port (regex, full match): input port}"""
    m = sp.get("map", {})
    if pn in m:
        return m[pn]
    for rx, ip in m.items():
        if re.fullmatch(rx, pn):
            return ip
    return None


def _src_out(sp, pn):
    """a source rule's output: outputs {port regex: domain | polarity | {"kind": clock|reset, "value": ...}}"""
    for rx, v in sp.get("outputs", {}).items():
        if re.fullmatch(rx, pn):
            if isinstance(v, dict):
                return (v.get("kind", sp.get("kind", "clock")), v.get("value", v.get("domain", v.get("polarity"))))
            return (sp.get("kind", "clock"), v)
    return None


def _add_stages(s, n):
    if s[0] == "pin":
        return s[:4] + (s[4] + n,)
    if s[0] == "reset":
        return (s[0], s[1], s[2] + n)
    if s[0] == "top":
        return s[:3] + (s[3] + n,)
    if s[0] == "or":
        return ("or", s[1], s[2] + n)
    return s


# ------------------------------------------------------------------------------------------------ binding
def common_root(paths):
    parents = [p.rsplit(".", 1)[0] if "." in p else "" for p in paths]
    if not parents:
        return ""
    sp = [p.split(".") if p else [] for p in parents]
    out = []
    for parts in zip(*sp):
        if all(x == parts[0] for x in parts):
            out.append(parts[0])
        else:
            break
    return ".".join(out)


def rel(path, root):
    return path[len(root) + 1:] if root and path.startswith(root + ".") else path


class Binder:
    def __init__(self, plan, yjs, plan_dir):
        self.plan = plan
        self.ab = plan["asbuilt"]
        self.errors, self.warns = [], []
        self.R = Rules(self.ab)
        self.F = E.flatten(yjs, self.ab["top"])
        self.G = Graph(self.F, self.R, self.errors)
        self.parts = {p["name"]: dict(p) for p in plan["partitions"]}
        self.types = {k: dict(v) for k, v in plan["partition_types"].items()}
        self.findings, self.type_splits = [], []
        self.strict_types = False
        self.tied_by_port = defaultdict(int)

    # -- mapping
    def map_cells(self):
        G, F = self.G, self.F
        self.cpart = {}
        self.members = defaultdict(list)
        unmapped = []
        for ci, c in enumerate(F.cells):
            if G.kind[ci] in ("transport", "reducer", "source", "unknown"):
                continue
            p = self.R.part_of(c.path)
            if p is None:
                unmapped.append(c.path)
                continue
            if p not in self.parts:
                self.errors.append(f"MAP_PARTITION {c.path} -> {p}: not a plan partition")
                continue
            self.cpart[ci] = p
            self.members[p].append(ci)
        for u in unmapped[:200]:
            self.errors.append(f"UNMAPPED {u} ({F.cells[[c.path for c in F.cells].index(u)].module})")
        if len(unmapped) > 200:
            self.errors.append(f"UNMAPPED ... {len(unmapped) - 200} more")
        self.n_unmapped = len(unmapped)
        empty = [p for p in self.parts if p not in self.members]
        for p in empty:
            self.errors.append(f"EMPTY_PARTITION {p}: no as-built cell maps to it")
        self.root = {p: (F.cells[m[0]].path if len(m) == 1 else common_root([F.cells[ci].path for ci in m]))
                     for p, m in self.members.items()}

    def rel_of(self, ci):
        p = self.cpart[ci]
        if self.F.cells[ci].path == self.root[p]:
            return "core"           # a one-leaf partition: type-invariant instance name
        return rel(self.F.cells[ci].path, self.root[p])

    # -- per load bit: what drives it in the bound design
    def analyse(self):
        G, F = self.G, self.F
        self.cross = defaultdict(lambda: defaultdict(set))   # (src part, dst part) -> {(src ci, port): {bits}}
        self.cross_sinks = defaultdict(set)                  # (sp, dp, src ci, port) -> {(dst rel, dst port)}
        self.cross_stages = defaultdict(list)                # (sp, dp, src ci, port) -> [as-built stages]
        self.intra_dly = defaultdict(set)                    # part -> {(src ci, port, stages)}
        self.clk_dom = defaultdict(set)                      # part -> {domain}
        self.sinks = {}                                      # (ci, port, bit) -> descriptor
        self.reset_age = defaultdict(list)                   # part -> as-built release stages of replaced resets
        cnt = defaultdict(int)
        for ci, c in enumerate(F.cells):
            if ci not in self.cpart:
                continue
            p = self.cpart[ci]
            d = G.dirs[ci]
            for pn, bits in c.ports.items():
                if d.get(pn) != "input":
                    continue
                for i, b in enumerate(bits):
                    s = G.source(b)
                    self.sinks[(ci, pn, i)] = self._classify(p, ci, pn, i, s, cnt)
        self.counts = dict(cnt)

    def _src_desc(self, p, s, cnt, ci, pn, i):
        """a non-OR logical source as seen from partition p"""
        k = s[0]
        if k == "pin":
            sci, spn, sb, st = s[1], s[2], s[3], s[4]
            sp = self.cpart.get(sci)
            if sp is None:
                cnt["source_unmapped"] += 1
                return ("err", "source cell unmapped")
            if sp == p:
                if st:
                    self.intra_dly[p].add((sci, spn, st))
                    cnt["intra_kept_stages"] += 1
                cnt["intra"] += 1
                return ("int", sci, spn, sb, st)
            self.cross[(sp, p)][(sci, spn)].add(sb)
            self.cross_sinks[(sp, p, sci, spn)].add((self.rel_of(ci), pn))
            self.cross_stages[(sp, p, sci, spn)].append(st)
            cnt["crossing"] += 1
            return ("x", sp, sci, spn, sb, st)
        if k == "clock":
            self.clk_dom[p].add(s[1])
            cnt["clock"] += 1
            return ("clk", s[1])
        if k == "reset":
            cnt["reset"] += 1
            self.reset_age[p].append(s[2])
            return ("rst", s[1])
        if k == "const":
            pin = f"{self.F.cells[ci].path}.{pn}"
            if self.R.is_strap(pin):
                cnt["strap"] += 1
                return ("strap", s[1])
            cnt["tied"] += 1
            self.tied_by_port[f"{self.F.cells[ci].module}.{pn} <- {s[2]}"] += 1
            self.errors.append(f"TIED {pin}[{i}] = {s[1]} ({s[2]})") if cnt["tied"] <= 200 else None
            return ("tied", s[1])
        if k == "top":
            cnt["die_io"] += 1
            return ("top", s[1], s[2])
        if k == "multi":
            cnt["multi_driven"] += 1
            self.errors.append(f"MULTI_DRIVEN {self.F.cells[ci].path}.{pn}[{i}] <- {s[2][:4]}")
            return ("err", "multi")
        if k in ("undriven", "dropped"):
            pin = f"{self.F.cells[ci].path}.{pn}"
            cnt["undriven"] += 1
            if cnt["undriven"] <= 200:
                self.errors.append(f"UNDRIVEN {pin}[{i}]" + (f" (only driver {s[1]} removed)" if k == "dropped" else ""))
            return ("err", k)
        return ("err", k)

    def _classify(self, p, ci, pn, i, s, cnt):
        if s[0] == "or":
            subs = [self._src_desc(p, u, cnt, ci, pn, i) for u in s[1]]
            subs = [x for x in subs if x[0] in ("int", "x", "strap", "tied", "top")]
            cnt["or_input"] += 1
            if not subs:
                cnt["or_empty"] += 1
                self.errors.append(f"OR_EMPTY {self.F.cells[ci].path}.{pn}[{i}]: fault tree with no live source")
                return ("err", "or_empty")
            return ("or", tuple(sorted(subs, key=repr)))
        return self._src_desc(p, s, cnt, ci, pn, i)

    # -- buses
    def build_buses(self):
        """one out bus per (src part, dst part, src cell port) on the source, one in bus on the destination."""
        self.out_bus = defaultdict(list)     # part -> [bus]
        self.in_bus = defaultdict(list)
        self.links = []
        for (sp, dp), groups in sorted(self.cross.items()):
            for (sci, spn), bits in sorted(groups.items(), key=lambda kv: (self.F.cells[kv[0][0]].path, kv[0][1])):
                bl = sorted(bits)
                srel = self.rel_of(sci)
                link = dict(src=sp, dst=dp, sci=sci, port=spn, bits=bl, width=len(bl),
                            srel=srel, stages=self.cross_stages[(sp, dp, sci, spn)])
                self.links.append(link)
        # names, stable across replicas and mirrored halves: an out bus is named by its source pin (relative to the
        # source partition), an in bus by its first sink pin (relative to the destination): the same module serves
        # replicas whose sinks are fed from different partitions
        for L in self.links:
            dr, dpn = min(self.cross_sinks[(L["src"], L["dst"], L["sci"], L["port"])])
            L["dsink"] = f"{dr}__{dpn}"
            L["okey"] = (L["srel"], L["port"])
            L["ikey"] = (L["dsink"],)
        for side, kk, pk in (("o", "okey", "src"), ("i", "ikey", "dst")):
            per = defaultdict(lambda: defaultdict(list))
            for L in self.links:
                per[L[pk]][L[kk]].append(L)
            for part, d in per.items():
                for key, ls in d.items():
                    if side == "o":
                        ls.sort(key=lambda L: (L["dsink"], self.parts[L["dst"]]["type"], L["dst"]))
                        base = f"o__{key[0]}__{key[1]}"
                    else:
                        ls.sort(key=lambda L: (L["srel"], L["port"], self.parts[L["src"]]["type"], L["src"]))
                        base = f"i__{key[0]}"
                    for n, L in enumerate(ls):
                        L[f"{side}name"] = short_id(base, 72) + (f"__{n}" if len(ls) > 1 else "")
        for L in self.links:
            self.out_bus[L["src"]].append(L)
            self.in_bus[L["dst"]].append(L)

    # -- types
    def type_signature(self, p):
        """canonical description of partition p (relative names); per-instance values separated out."""
        F = self.F
        leaves = {}
        inst_vals = {}
        for ci in self.members[p]:
            c = F.cells[ci]
            r = self.rel_of(ci)
            leaves[r] = (c.module, tuple(sorted(c.params)), self.G.kind[ci], c.ytype if self.G.kind[ci] == "glue" else None)
            for k, v in sorted(c.params.items()):
                inst_vals[("param", r, k)] = v
        conns = {}
        for ci in self.members[p]:
            r = self.rel_of(ci)
            for pn, bits in self.F.cells[ci].ports.items():
                if self.G.dirs[ci].get(pn) != "input":
                    continue
                row = []
                for i in range(len(bits)):
                    d = self.sinks[(ci, pn, i)]
                    row.append(self._rel_desc(p, d, inst_vals, (r, pn, i)))
                conns[(r, pn)] = tuple(row)
        obus = sorted((L["oname"], L["srel"], L["port"], tuple(L["bits"])) for L in self.out_bus[p])
        ibus = sorted((L["iname"], L["width"]) for L in self.in_bus[p])     # the source is outside the module
        sig = dict(leaves=leaves, conns=conns, obus=obus, ibus=ibus, clocks=tuple(sorted(self.clk_dom[p])))
        return sig, inst_vals

    def _rel_desc(self, p, d, inst_vals, where):
        k = d[0]
        if k == "int":
            return ("int", self.rel_of(d[1]), d[2], d[3], d[4])
        if k == "x":
            L = self._link_for(d[1], p, d[2], d[3])
            return ("bus", L["iname"], L["bits"].index(d[4]))
        if k == "strap":
            inst_vals[("strap",) + where] = d[1]
            return ("strap",)
        if k == "or":
            return ("or", tuple(self._rel_desc(p, x, inst_vals, where + (j,)) for j, x in enumerate(d[1])))
        return d

    def _link_for(self, sp, dp, sci, spn):
        key = (sp, dp, sci, spn)
        if not hasattr(self, "_lk"):
            self._lk = {(L["src"], L["dst"], L["sci"], L["port"]): L for L in self.links}
        return self._lk[key]

    def check_types(self):
        self.tsig, self.tvals, self.tparams = {}, {}, {}
        split_more = []
        by_type = defaultdict(list)
        for p in self.members:
            by_type[self.parts[p]["type"]].append(p)
        self.by_type = by_type
        for tn, ps in sorted(by_type.items()):
            sigs = {}
            for p in ps:
                sigs[p] = self.type_signature(p)
            groups = []                 # instances with identical contents share one module
            for p in ps:
                for g in groups:
                    if sigs[g[0]][0] == sigs[p][0]:
                        g.append(p)
                        break
                else:
                    groups.append([p])
            if len(groups) > 1:
                ref = groups[0][0]
                s0 = sigs[ref][0]
                bad = []
                for g in groups[1:]:
                    p = g[0]
                    s = sigs[p][0]
                    diff = [k for k in s0 if s0[k] != s[k]]
                    detail = ""
                    if "leaves" in diff:
                        a, b = set(s0["leaves"].items()), set(s["leaves"].items())
                        detail = f" leaves only-in-{ref} {sorted(a - b)[:2]} only-in-{p} {sorted(b - a)[:2]}"
                    elif "conns" in diff:
                        ks = [k for k in s0["conns"] if s0["conns"].get(k) != s["conns"].get(k)][:2]
                        detail = f" e.g. input {ks}"
                    elif "obus" in diff or "ibus" in diff:
                        kk = "obus" if "obus" in diff else "ibus"
                        a, b = set(s0[kk]), set(s[kk])
                        detail = f" {kk} only-in-{ref} {[x[0] for x in sorted(a - b)][:3]} only-in-{p} {[x[0] for x in sorted(b - a)][:3]}"
                    bad.append(f"{p} ({', '.join(diff)}{detail})")
                msg = (f"TYPE_SPLIT {tn}: {len(ps)} instances bind as {len(groups)} variants (as-built contents differ "
                       f"from {ref}): " + "; ".join(bad[:3]) + (f" ... {len(bad) - 3} more" if len(bad) > 3 else ""))
                self.type_splits.append(dict(type=tn, variants=[list(g) for g in groups], detail=bad))
                (self.errors if self.strict_types else self.findings).append(msg)
                for k, g in enumerate(groups[1:], 1):
                    vt = f"{tn}__v{k}"
                    self.types[vt] = dict(self.types[tn], module=f"{self.types[tn]['module']}_v{k}", split_of=tn)
                    for p in g:
                        self.parts[p] = dict(self.parts[p], type=vt)
                    split_more.append((vt, g, sigs))
                ps = groups[0]
                by_type[tn] = ps
            self._type_vals(tn, ps, sigs)
        for vt, g, sigs in split_more:
            by_type[vt] = g
            self._type_vals(vt, g, sigs)
        # generated module names must be unique and must not shadow a leaf master (a plan type named after its hard
        # macro, e.g. a PHY partition): such a type gets a wrapper name, recorded as a finding
        leafmods = {c.module for ci, c in enumerate(self.F.cells) if self.G.kind[ci] == "leaf"}
        used = defaultdict(list)
        for tn in sorted(by_type):
            used[self.types[tn]["module"]].append(tn)
        for m, tns in sorted(used.items()):
            for tn in tns:
                new = m
                if len(tns) > 1:
                    new = f"{m}__{sv_id(tn)}"
                if new in leafmods:
                    new = f"{new}_part"
                if new != m:
                    self.findings.append(f"MODULE_RENAME {tn}: plan module {m} -> {new} "
                                         f"({'shared by ' + ','.join(tns) if len(tns) > 1 else 'name of a leaf master'})")
                    self.types[tn] = dict(self.types[tn], module=new)

    def _type_vals(self, tn, ps, sigs):
        s0 = sigs[ps[0]][0]
        if True:
            # per-instance values: parameters where they differ across the type's instances (or always for straps)
            keys = set()
            for p in ps:
                keys |= set(sigs[p][1])
            params = {}
            for k in sorted(keys, key=repr):
                vals = [sigs[p][1].get(k) for p in ps]
                if k[0] == "strap" or len(set(vals)) > 1:
                    params[k] = vals
            self.tsig[tn] = s0
            self.tvals[tn] = {p: sigs[p][1] for p in ps}
            self.tparams[tn] = params

    # ------------------------------------------------------------------------------------------ RTL emission
    def emit(self, out):
        out = Path(out) / "rtl"            # generated RTL only; rewritten from scratch on every bind
        if out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True)
        (out / "bind_cells.sv").write_text(CELLS)
        files = [out / "bind_cells.sv"]
        self.pnames = {}
        for tn, ps in sorted(self.by_type.items()):
            t = self.types[tn]
            txt, pnames = self.emit_type(tn, ps[0])
            self.pnames[tn] = pnames
            f = out / f"{t['module']}.sv"
            f.write_text(txt)
            files.append(f)
        f = out / f"{sv_id(self.plan['die']['name'])}_bound_top.sv"
        f.write_text(self.emit_top())
        files.append(f)
        return files

    def _pname(self, k):
        if k[0] == "param":
            return short_id(f"P_{k[1]}__{k[2]}", 80)
        return short_id(f"S_{k[1]}__{k[2]}", 80)

    def emit_type(self, tn, p):
        t = self.types[tn]
        F, G = self.F, self.G
        mod = t["module"]
        params = self.tparams[tn]
        pdecl, pnames = [], {}
        # strap parameters: one per (leaf, port), the port width, constant bits in place
        straps = defaultdict(dict)
        for k, vals in params.items():
            if k[0] == "strap":
                straps[(k[1], k[2])][k[3]] = vals
        cell_by_rel = {self.rel_of(ci): ci for ci in self.members[p]}
        for (r, pn), bitsv in sorted(straps.items()):
            ci = cell_by_rel[r]
            w = len(F.cells[ci].ports[pn])
            nm = short_id(f"S_{r}__{pn}", 80)
            v0 = ["0"] * w
            for b, vals in bitsv.items():
                v0[b] = vals[0] if vals[0] in "01" else "0"
            pdecl.append(f"    parameter [{w - 1}:0] {nm} = {w}'b{''.join(reversed(v0))}")
            pnames[("strap", r, pn)] = (nm, w)
        for k, vals in params.items():
            if k[0] == "param":
                nm = short_id(f"P_{k[1]}__{k[2]}", 80)
                pdecl.append(f"    parameter {nm} = {vals[0]}")
                pnames[k] = (nm, None)
        ports = ["    input  wire clk", "    input  wire arst_n"]
        doms = sorted(self.clk_dom[p] - {self.default_domain(p)})
        for d in doms:
            ports.append(f"    input  wire clk_{sv_id(d)}")
        decl, body = [], []
        body.append(f"    wire rst_n;\n    ot_reset_sync #(.ASYNC_STAGES({int(t.get('reset', {}).get('sync_stages', 2))})) "
                    f"u_rst_sync (.clk(clk), .async_rst_n(arst_n), .sync_rst_n(rst_n));")
        need_rst = False
        obus = sorted(self.out_bus[p], key=lambda L: L["oname"])
        ibus = sorted(self.in_bus[p], key=lambda L: L["iname"])
        for L in ibus:
            n, W = L["iname"], L["width"]
            ports.append(f"    input  wire [{W}:0] {n}   // {W} data + epoch [{W}]: {L['src']} {L['srel']}.{L['port']}")
            decl.append(f"    wire [{W - 1}:0] {n}_q;\n    wire {n}_eq;")
            body.append(f"    ot_dp_st #(.W({W})) u_bin_{n} (.clk(clk), .rst_n(rst_n), .d({n}[{W - 1}:0]), .ea({n}[{W}]), "
                        f".q({n}_q), .eq({n}_eq));")
        # driver wires: one per (cell, output port)
        drv_w = {}
        for ci in self.members[p]:
            c = F.cells[ci]
            for pn, bits in c.ports.items():
                if G.dirs[ci].get(pn) == "output":
                    nm = short_id(f"w_{self.rel_of(ci)}__{pn}", 90)
                    drv_w[(ci, pn)] = nm
                    decl.append(f"    wire [{len(bits) - 1}:0] {nm};")
        for L in obus:
            n, W = L["oname"], L["width"]
            ports.append(f"    output wire [{W}:0] {n}   // {W} data + epoch [{W}]: {L['srel']}.{L['port']} -> {L['dst']}")
            src = drv_w[(L["sci"], L["port"])]
            d = "{" + ", ".join(f"{src}[{b}]" for b in reversed(L["bits"])) + "}" if L["bits"] != list(range(len(F.cells[L['sci']].ports[L['port']]))) else src
            body.append(f"    ot_dp_st #(.W({W})) u_bout_{n} (.clk(clk), .rst_n(rst_n), .d({_compress(d)}), .ea(rst_n), "
                        f".q({n}[{W - 1}:0]), .eq({n}[{W}]));")
        # intra-partition kept transport stages
        dly_w = {}
        for (sci, spn, st) in sorted(self.intra_dly[p], key=lambda x: (F.cells[x[0]].path, x[1], x[2])):
            W = len(F.cells[sci].ports[spn])
            nm = short_id(f"d{st}_{self.rel_of(sci)}__{spn}", 90)
            dly_w[(sci, spn, st)] = nm
            decl.append(f"    wire [{W - 1}:0] {nm};")
            body.append(f"    ot_dp_dly #(.W({W}), .D({st})) u_{nm} (.clk(clk), .d({drv_w[(sci, spn)]}), .q({nm}));")
        orn = {}
        ub = []

        def expr(d, ci, pn, i):
            nonlocal need_rst
            k = d[0]
            if k == "int":
                w = dly_w[(d[1], d[2], d[4])] if d[4] else drv_w[(d[1], d[2])]
                return f"{w}[{d[3]}]"
            if k == "x":
                L = self._link_for(d[1], p, d[2], d[3])
                return f"{L['iname']}_q[{L['bits'].index(d[4])}]"
            if k == "clk":
                return "clk" if d[1] == self.default_domain(p) else f"clk_{sv_id(d[1])}"
            if k == "rst":
                if d[1] == "low":
                    return "rst_n"
                need_rst = True
                return "rst"
            if k == "strap":
                nm, _w = pnames[("strap", self.rel_of(ci), pn)]
                return f"{nm}[{i}]"
            if k in ("tied", "top", "err"):
                # never a constant: an unresolved bit stays an undriven wire, reported (bind_report proof)
                nm = f"ub_{len(ub)}"
                ub.append(nm)
                decl.append(f"    wire {nm};  // UNBOUND {k}: {self.F.cells[ci].path}.{pn}[{i}] (see bind_report errors)")
                return nm
            if k == "or":
                key = d
                if key not in orn:
                    nm = f"or_{len(orn)}"
                    orn[key] = nm
                    decl.append(f"    wire {nm};")
                    ins = [expr(x, ci, pn, i) for x in d[1]]
                    body.append(f"    ot_dp_or #(.N({len(ins)})) u_{nm} (.a({_concat(ins)}), .y({nm}));  // re-emitted fault OR")
                return orn[key]
            raise BindError(f"no expression for {d}")
        insts = []
        for ci in sorted(self.members[p], key=lambda ci: self.rel_of(ci)):
            c = F.cells[ci]
            r = self.rel_of(ci)
            conns = []
            for pn, bits in sorted(c.ports.items()):
                dd = G.dirs[ci].get(pn)
                if dd == "output":
                    conns.append((pn, drv_w[(ci, pn)]))
                elif dd == "input":
                    e = [expr(self.sinks[(ci, pn, i)], ci, pn, i) for i in range(len(bits))]
                    conns.append((pn, _concat(e)))
            if G.kind[ci] == "glue":
                insts.append(_glue(c, dict(conns), r))
                continue
            ps = []
            for k, v in sorted(c.params.items()):
                if ("param", r, k) in pnames:
                    ps.append(f".{k}({pnames[('param', r, k)][0]})")
                else:
                    ps.append(f".{k}({v})")
            pstr = (" #(" + ", ".join(ps) + ")") if ps else ""
            cs = ",\n".join(f"        .{pn}({e})" for pn, e in conns)
            insts.append(f"    // as-built {c.path}\n    {c.module}{pstr} {short_id('u_' + r, 90)} (\n{cs}\n    );")
        if need_rst:
            decl.append("    wire rst = ~rst_n;")
        head = (f"// GENERATED by tools/die_plan/bind.py from die_plan {self.plan['die']['name']} + the as-built die "
                f"({self.ab['top']}), partition type {tn}.  Do not edit.\n"
                f"// {len(self.by_type[tn])} instance(s); leaves = the as-built modules unchanged; intra-partition nets as built;\n"
                "// every crossing registered on both sides (ot_dp_st, data + epoch); one clock, one reset synchroniser.\n"
                "`timescale 1ns/1ps\n`default_nettype none\n")
        pblock = (" #(\n" + ",\n".join(pdecl) + "\n)") if pdecl else ""
        return head + f"module {mod}{pblock} (\n" + "\n".join(_strip_comment_comma(ports)) + "\n);\n" + "\n".join(decl) + \
            "\n" + "\n".join(body) + "\n" + "\n".join(insts) + f"\nendmodule\n`default_nettype wire\n", pnames

    def default_domain(self, p):
        t = self.types[self.parts[p]["type"]]
        d = t.get("clock", {}).get("domain")
        if d:
            return d
        doms = sorted(self.clk_dom[p])
        return doms[0] if len(doms) == 1 else self.ab.get("default_clock", "core")

    def emit_top(self):
        die = sv_id(self.plan["die"]["name"])
        doms = sorted({d for p in self.members for d in self.clk_dom[p]} | {self.ab.get("default_clock", "core")})
        ports = ["    input  wire rst_n"] + [f"    input  wire clk_{sv_id(d)}" for d in doms]
        wires, insts = [], []
        for L in self.links:
            nm = short_id(f"x_{L['src']}__{L['oname']}__{L['dst']}", 120)
            L["wire"] = nm
            wires.append(f"    wire [{L['width']}:0] {nm};")
        for p in sorted(self.members):
            tn = self.parts[p]["type"]
            t = self.types[tn]
            pn = self.pnames[tn]
            ov = []
            for k, (nm, w) in sorted(pn.items(), key=lambda kv: kv[1][0]):
                if k[0] == "strap":
                    r, port = k[1], k[2]
                    ci = {self.rel_of(c): c for c in self.members[p]}[r]
                    width = len(self.F.cells[ci].ports[port])
                    v = ["0"] * width
                    for kk, val in self.tvals[tn][p].items():
                        if kk[0] == "strap" and kk[1] == r and kk[2] == port:
                            v[kk[3]] = val if val in "01" else "0"
                    ov.append(f".{nm}({width}'b{''.join(reversed(v))})")
                else:
                    ov.append(f".{nm}({self.tvals[tn][p].get(k)})")
            dd = self.default_domain(p)
            cs = [f"        .clk(clk_{sv_id(dd)})", "        .arst_n(rst_n)"]
            for d in sorted(self.clk_dom[p] - {dd}):
                cs.append(f"        .clk_{sv_id(d)}(clk_{sv_id(d)})")
            for L in sorted(self.out_bus[p], key=lambda L: L["oname"]):
                cs.append(f"        .{L['oname']}({L['wire']})")
            for L in sorted(self.in_bus[p], key=lambda L: L["iname"]):
                cs.append(f"        .{L['iname']}({L['wire']})")
            pstr = (" #(" + ", ".join(ov) + ")") if ov else ""
            insts.append(f"    {t['module']}{pstr} {sv_id(p)} (\n" + ",\n".join(cs) + "\n    );")
        return (f"// GENERATED by tools/die_plan/bind.py: bound die top of {self.plan['die']['name']} (as-built "
                f"{self.ab['top']} re-partitioned by the plan).  Do not edit.\n`timescale 1ns/1ps\n`default_nettype none\n"
                f"module {die}_bound_top (\n" + ",\n".join(ports) + "\n);\n" + "\n".join(wires) + "\n" + "\n".join(insts) +
                f"\nendmodule\n`default_nettype wire\n")

