#!/usr/bin/env python3
"""bind: the as-built die RTL, re-partitioned by a die plan (generic for all four dies; BINDER 10-23).

    python3 tools/die_plan/bind.py elab   PLAN.json --out DIR [--mem 32]      Yosys: as-built top + RTL -> DIR/asbuilt.json
    python3 tools/die_plan/bind.py bind   PLAN.json --out DIR [--strict]      partitions RTL + die top + DIR/bind_report.json
    python3 tools/die_plan/bind.py verify PLAN.json --out DIR [--mem 32]      re-elaborate the generated RTL, prove connectivity
    python3 tools/die_plan/bind.py all    PLAN.json --out DIR                 elab + bind + verify (+ Verilator lint)

Inputs (die_plan.json, key `asbuilt`; README "As-built binding"):
  netlist / top / rtl_roots / files / prefer / defines / substitute   the as-built die top and its RTL
  dissolve      structural parents descended through (their leaves go to different partitions)
  transport     die transport the plan replaces (relays, landings, reset repeaters, stations): module regex -> the
                out <- in bit map and the register stages; removed, every path through them collapsed to its source
  reducers      fault-OR trees: module regex -> OR of the inputs; removed and re-emitted per sink partition
  clocks        clock source pins (regex on "path.port") -> domain; a partition loads one die clock per domain
  resets        reset source pins replaced by the partition's own synchroniser (polarity low/high)
  straps        constant leaf inputs that are declared position straps (-> partition parameters); others are TIED
  map           {"parts": {path prefix: partition}, "rules": [[regex, partition], ...]}: every leaf / glue cell of the
                as-built die maps to exactly one partition (longest prefix, then the first rule)

Outputs (DIR): one module per partition TYPE (`<type.module>.sv`; replicated instances share it, per-instance values are
parameters), `<die>_bound_top.sv`, `bind_cells.sv` (ot_dp_st boundary flop / station, ot_dp_dly intra-partition delay),
`bind.f` (file list), `bind_report.json` (connectivity proof, crossings, latency deltas), `bind_latency.json`.

Construction rules:
  * leaves are the original modules, unchanged, with the parameters Yosys derived for the as-built instance;
  * an intra-partition net is wired as the as-built die wired it; transport stages inside one partition are kept as an
    ot_dp_dly of the same depth (the as-built latency of an intra-partition path is unchanged);
  * every net crossing a partition boundary becomes a bus pair: out boundary flop in the source partition, in boundary
    flop in the destination (data + one epoch bit, reset-less data).  The as-built stages of that path (relays,
    landings) are removed; old and new stage counts are recorded per bus in bind_latency.json, never hidden;
  * clock loads take their partition's clock port, replaced resets the partition's synchronised reset;
  * no constant is generated: an as-built constant on a leaf input is either a declared strap (a parameter) or TIED.
"""
