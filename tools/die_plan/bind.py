_AB_OVERRIDE = {}


def load_plan(path):
    raw = json.loads(Path(path).read_text())
    if _AB_OVERRIDE.get("path"):
        ab = json.loads(Path(_AB_OVERRIDE["path"]).read_text())
        ab.setdefault("base", str(E.REPO))
        if ab.get("map_file") and not Path(ab["map_file"]).is_absolute():
            ab["map_file"] = str(Path(_AB_OVERRIDE["path"]).parent / ab["map_file"])
        raw["asbuilt"] = ab
    if "asbuilt" not in raw:
        raise BindError(f"{path}: no `asbuilt` section (README: As-built binding)")
    return raw


def plan_base(path, raw):
    b = raw["asbuilt"].get("base")
    if _AB_OVERRIDE.get("path") and b and not Path(b).is_absolute():
        return str((Path(_AB_OVERRIDE["path"]).parent / b).resolve())
    if b:
        return str((Path(path).parent / b).resolve()) if not Path(b).is_absolute() else b

    return str(E.REPO)


def cmd_elab(a):
    raw = load_plan(a.plan)
    rec = E.elab(raw["asbuilt"], plan_base(a.plan, raw), a.out, a.mem)
    print(json.dumps({k: (v if k not in ("ambiguous", "undefined") else len(v)) for k, v in rec.items()}))
    return 0


def cmd_bind(a):
    raw = load_plan(a.plan)
    out = Path(a.out)
    yjs = json.loads((out / "asbuilt.json").read_text())
    B = Binder(raw, yjs, Path(a.plan).parent)
    B.strict_types = bool(getattr(a, "strict", False))
    B.map_cells()
    B.analyse()
    B.build_buses()
    B.check_types()
    files = []
    try:
        files = B.emit(out)
    except BindError as e:
        B.errors.append(f"EMIT {e}")
    rep, lat = B.report()
    srcs = json.loads((out / "asbuilt_sources.json").read_text()) if (out / "asbuilt_sources.json").exists() else {}
    fl = [str(f) for f in srcs.get("lib", [])] + [str(f) for f in files]
    (out / "bind.f").write_text("\n".join(fl) + "\n")
    rep["files"] = [str(f) for f in files]
    rep["findings"] = B.findings
    rep["type_splits"] = B.type_splits
    rep["tied_by_port"] = dict(sorted(B.tied_by_port.items(), key=lambda kv: -kv[1]))
    names = {}
    for ci, p in B.cpart.items():
        if B.G.kind[ci] != "glue":
            names[f"{sv_id(p)}.{short_id('u_' + B.rel_of(ci), 90)}"] = B.F.cells[ci].path
    (out / "bind_names.json").write_text(json.dumps(names, indent=0))
    sinks = {}
    for (ci, pn, i), d in B.sinks.items():
        sinks[f"{B.F.cells[ci].path}.{pn}[{i}]"] = _desc_json(B, d)
    (out / "bind_sinks.json").write_text(json.dumps(sinks))
    (out / "bind_report.json").write_text(json.dumps(rep, indent=1))
    (out / "bind_latency.json").write_text(json.dumps(dict(schema=SCHEMA, die=raw["die"]["name"],
                                                           note="per crossing bus: as-built stages (relays / landings "
                                                                "removed) vs bound stages (2 boundary flops)",
                                                           buses=lat), indent=1))
    pr = rep["proof"]
    print(json.dumps(dict(partitions=rep["partitions"], types=len(rep["types"]), crossings=rep["crossings"],
                          crossing_bits=rep["crossing_bits"], errors=rep["n_errors"], **pr)))
    for e in B.errors[:30]:
        print("  ", e)
    return 1 if (B.errors and a.strict) else 0


def _desc_json(B, d):
    k = d[0]
    if k == "int":
        return ["pin", f"{B.F.cells[d[1]].path}.{d[2]}[{d[3]}]", d[4], B.G.kind[d[1]] == "glue"]
    if k == "x":
        return ["pin", f"{B.F.cells[d[2]].path}.{d[3]}[{d[4]}]", 2, B.G.kind[d[2]] == "glue"]
    if k == "or":
        return ["or", sorted(_desc_json(B, x)[1] for x in d[1] if x[0] in ("int", "x"))]
    return [k] + list(d[1:2])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for n in ("elab", "bind", "verify", "all"):
        s = sub.add_parser(n)
        s.add_argument("plan")
        s.add_argument("--out", required=True)
        s.add_argument("--mem", type=int, default=32)
        s.add_argument("--strict", action="store_true")
        s.add_argument("--asbuilt", help="as-built binding section in its own file (overrides the plan's `asbuilt`)")
    a = ap.parse_args(argv)
    _AB_OVERRIDE["path"] = a.asbuilt
    try:
        if a.cmd == "elab":
            return cmd_elab(a)
        if a.cmd == "bind":
            return cmd_bind(a)
        if a.cmd == "verify":
            import bind_verify
            return bind_verify.cmd_verify(a)
        if a.cmd == "all":
            import bind_verify
            r = cmd_elab(a)
            r = r or cmd_bind(a)
            return r or bind_verify.cmd_verify(a)
    except (BindError, E.ElabError) as e:
        print(f"bind: ERROR {e}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
