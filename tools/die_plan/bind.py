class BindError(Exception):
    pass


def sv_id(s):
    s = re.sub(r"[^A-Za-z0-9_]", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    return s if s and not s[0].isdigit() else "n" + s


def short_id(s, n=60):
    s = sv_id(s)
    if len(s) <= n:
        return s
    return s[: n - 9] + "_" + hashlib.sha1(s.encode()).hexdigest()[:8]


# ------------------------------------------------------------------------------------------------ rules
class Rules:
    def __init__(self, ab):
        self.transport = [(re.compile(r["module"]), r) for r in ab.get("transport", [])]
        self.reducers = [(re.compile(r["module"]), r) for r in ab.get("reducers", [])]
        self.sources = [(re.compile(r["module"]), r) for r in ab.get("sources", [])]
        self.clocks = [(re.compile(r["pin"]), r.get("domain", "core")) for r in ab.get("clocks", [])]
        self.resets = [(re.compile(r["pin"]), r.get("polarity", "low")) for r in ab.get("resets", [])]
        self.straps = [re.compile(r) for r in ab.get("straps", [])]
        mp = dict(ab.get("map", {}))
        if ab.get("map_file"):
            mf = json.loads(Path(ab["map_file"]).read_text())
            mp = dict(parts={**mf.get("parts", {}), **mp.get("parts", {})}, rules=mp.get("rules", []) + mf.get("rules", []))
        self.parts = dict(mp.get("parts", {}))
        self.rules = [(re.compile(a), b) for a, b in mp.get("rules", [])]
        self.ignore_out = [re.compile(r) for r in ab.get("open_outputs", [])]
        self.keep_reducer = set()            # reducer instances the plan keeps as contents (stay leaves)

    @staticmethod
    def _first(lst, s):
        for rx, r in lst:
            if rx.fullmatch(s):
                return r
        return None

    def transport_of(self, m):
        return self._first(self.transport, m)

    def reducer_of(self, m, path=None):
        """reducer rule of module m (optionally scoped to instances by the rule's `inst` regex on the cell path)"""
        for rx, r in self.reducers:
            if rx.fullmatch(m) and (not r.get("inst") or path is not None and re.fullmatch(r["inst"], path)):
                return r
        return None

    def source_of(self, m):
        return self._first(self.sources, m)

    def clock_of(self, pin):
        return self._first(self.clocks, pin)

    def reset_of(self, pin):
        return self._first(self.resets, pin)

    def is_strap(self, pin):
        return any(rx.fullmatch(pin) for rx in self.straps)

    def _lookup(self, path):
        """(partition, local name or None).  map.parts values are a partition or [partition, local instance name]
        (the plan's canonical content name, identical across the replicas of a type); a parent's local name extends
        to its descendants.  Paths through a substitution shim (`.u_sub.`) also match the map key without it."""
        for cand in (path, path.replace(".u_sub.", ".")) if ".u_sub." in path else (path,):
            p, tail = cand, ""
            while True:
                if p in self.parts:
                    v = self.parts[p]
                    if isinstance(v, list):
                        return v[0], (v[1] + tail if len(v) > 1 and v[1] else None)
                    return v, None
                if "." not in p:
                    break
                p, last = p.rsplit(".", 1)
                tail = "." + last + tail
        for rx, part in self.rules:
            m = rx.fullmatch(path)
            if m:
                return (m.expand(part) if "\\" in part else part), None
        return None, None

    def part_of(self, path):
        return self._lookup(path)[0]

    def local_of(self, path):
        return self._lookup(path)[1]


def _bitlist(spec):
    """'a' / 'a[3:0]' style port selector -> (port, lo, hi or None)"""
    m = re.fullmatch(r"(\w+)(?:\[(\d+)(?::(\d+))?\])?", spec)
    if not m:
        raise BindError(f"bad port selector {spec}")
    if m.group(2) is None:
        return m.group(1), None, None
    hi = int(m.group(2))
    lo = int(m.group(3)) if m.group(3) is not None else hi
    return m.group(1), lo, hi


# ------------------------------------------------------------------------------------------------ the as-built graph
class Graph:
    """the flattened as-built die with transport removed: per leaf/glue input bit its logical source."""

    def __init__(self, F, rules, errors):
        self.F, self.R, self.err = F, rules, errors
        self.drv = defaultdict(list)       # net -> [(cell idx, port, bit)]
        self.loads = defaultdict(list)     # net -> [(cell idx, port, bit)]
        self.kind = []                     # per cell: leaf | glue | transport | reducer | source
        self.spec = []
        self.dirs = []
        self.leaf_src = {}                 # source cells kept as leaves (rule keep_leaf): ci -> rule
        for ci, c in enumerate(F.cells):
            t = rules.transport_of(c.module)
            r = rules.reducer_of(c.module, c.path) if t is None else None
            if r is not None and c.path in rules.keep_reducer and c.kind == "leaf":
                r = None            # a plan content (status reuse): instantiated as a leaf in its partition
            s = rules.source_of(c.module) if t is None and r is None else None
            if t is not None:
                k, sp = "transport", t
            elif r is not None:
                k, sp = "reducer", r
            elif s is not None and s.get("keep_leaf") and c.kind == "leaf":
                # a plan content (e.g. the PLL in its partition): instantiated as a leaf; the outputs its rule names
                # are still clock / reset sources (the bound die takes those from its top ports), the rest are pins
                k, sp = "leaf", None
                self.leaf_src[ci] = s
            elif s is not None:
                k, sp = "source", s
            elif c.kind == "unknown":
                errors.append(f"UNKNOWN_MODULE {c.path} ({c.module}): no RTL and no transport/source rule")
                k, sp = "unknown", None
            else:
                k, sp = c.kind, None
            self.kind.append(k)
            self.spec.append(sp)
            d = dict(c.dirs)
            if k in ("transport", "reducer", "source") and sp is not None:
                d = self._rule_dirs(c, k, sp, d)
            self.dirs.append(d)
            for pn, bits in c.ports.items():
                dd = d.get(pn)
                if dd is None:
                    errors.append(f"PORT_DIR {c.path}.{pn} ({c.module}): direction unknown")
                    continue
                for i, b in enumerate(bits):
                    if isinstance(b, str):
                        continue
                    if dd == "output":
                        self.drv[b].append((ci, pn, i))
                    elif dd == "input":
                        self.loads[b].append((ci, pn, i))
                    else:
                        self.drv[b].append((ci, pn, i))
                        self.loads[b].append((ci, pn, i))
        self.top_in = {}
        for pn, (d, bits) in F.top_ports.items():
            for i, b in enumerate(bits):
                if not isinstance(b, str) and d == "input":
                    self.top_in[b] = (pn, i)
        self._src = {}

    def _rule_dirs(self, c, k, sp, d):
        if k == "transport":
            outs = {p for p in c.ports if _tmap(sp, p)} | set(sp.get("drop_out", []))
            ins = {_tmap(sp, p) for p in c.ports if _tmap(sp, p)} | set(sp.get("drop_in", []))
        elif k == "reducer":
            outs = {sp["out"]}
            ins = {p for p in c.ports if p != sp["out"]}
        else:
            outs = {p for p in c.ports if _src_out(sp, p) is not None} | set(sp.get("drop_out", []))
            ins = set(sp.get("drop_in", []))
        for pn in c.ports:
            if pn in outs:
                d[pn] = "output"
            elif pn in ins:
                d[pn] = "input"
            elif pn not in d:
                self.err.append(f"RULE_PORT {c.path}.{pn} ({c.module}): port not covered by its {k} rule")
        return d

    def pin(self, ci, pn):
        return f"{self.F.cells[ci].path}.{pn}"

    def source(self, net, depth=0):
        """logical source of a net: ('pin', ci, port, bit, stages) | ('const', v, where) | ('top', port, bit, 0) |
        ('clock', domain) | ('reset', polarity, stages) | ('or', [sources], stages) | ('undriven',) | ('multi', n)"""
        if isinstance(net, str):
            return ("const", net, "literal")
        if net in self._src:
            return self._src[net]
        if depth > 10000:
            raise BindError("transport loop")
        self._src[net] = ("undriven",)          # loop guard
        ds = self.drv.get(net, [])
        cd = self.F.const_drivers.get(net)
        res = None
        if len(ds) + (cd is not None) + (net in self.top_in) > 1:
            res = ("multi", len(ds) + (cd is not None) + (net in self.top_in), [self.pin(ci, pn) for ci, pn, _ in ds])
        elif cd is not None:
            res = ("const", cd[0], cd[1])
        elif net in self.top_in:
            res = ("top",) + self.top_in[net] + (0,)
        elif not ds:
            res = ("undriven",)
        else:
            ci, pn, bit = ds[0]
            k = self.kind[ci]
            c = self.F.cells[ci]
            if k == "transport":
                sp = self.spec[ci]
                ip = _tmap(sp, pn)
                if ip is None:
                    res = ("dropped", self.pin(ci, pn))
                else:
                    ib = c.ports[ip]
                    if sp.get("replicate") and ib:
                        bit = bit % len(ib)     # q = {N{d}} (station fan-out copies / landing ring slots)
                    up = self.source(ib[bit] if bit < len(ib) else "z", depth + 1)
                    st = int(sp.get("stages", 1))
                    if sp.get("stages_param"):
                        st = int(str(c.params.get(sp["stages_param"], st)).strip('"'))
                    if sp.get("stages_port"):
                        # BINDER4: latency from a constant strap input (e.g. ot_s81_land k: K + 1 edges after the last
                        # station), stages = value + stages_add; a non-constant strap is a RULE error
                        kb = c.ports.get(sp["stages_port"], [])
                        if kb and all(x in ("0", "1") for x in kb):
                            st = int("".join(reversed(kb)), 2) + int(sp.get("stages_add", 0))
                        else:
                            self.err.append(f"RULE_STAGES_PORT {c.path}.{sp['stages_port']}: not a constant strap")
                    res = _add_stages(up, st)
            elif k == "reducer":
                # op or (default): fault OR tree; op and: an AND join (e.g. a link-up AND) re-emitted per sink partition
                op = self.spec[ci].get("op", "or")
                if op == "and" and len(c.ports[self.spec[ci]["out"]]) != 1:
                    self.err.append(f"REDUCER_WIDTH {c.path}: an AND reducer must have a 1-bit output")
                ups = []
                for ip, bits in sorted(c.ports.items()):
                    if ip == self.spec[ci]["out"] or ip in self.spec[ci].get("drop_in", []):
                        continue
                    for b in bits:
                        u = self.source(b, depth + 1)
                        if u[0] in ("const",) and u[1] == ("0" if op == "or" else "1"):
                            continue
                        if u[0] in ("dropped", "undriven"):
                            continue
                        if u[0] == op:
                            ups.extend(u[1])
                        else:
                            ups.append(u)
                res = (op, ups, int(self.spec[ci].get("stages", 0)))
            elif k == "source":
                sp = self.spec[ci]
                o = _src_out(sp, pn)
                if o is None:
                    res = ("dropped", self.pin(ci, pn))
                elif o[0] == "clock":
                    res = ("clock", o[1])
                else:
                    res = ("reset", o[1], 0)
            elif ci in self.leaf_src and _src_out(self.leaf_src[ci], pn) is not None:
                o = _src_out(self.leaf_src[ci], pn)
                res = ("clock", o[1]) if o[0] == "clock" else ("reset", o[1], 0)
            elif k == "glue" and c.ytype in ("$not", "$pos", "$buf") and pn == "Y" and bit < len(c.ports.get("A", [])):
                # a constant expression of the as-built die (e.g. far_n = ~far): folded, so a declared strap stays a
                # strap (partition parameter) on the far side of the inverter
                up = self.source(c.ports["A"][bit], depth + 1)
                if up[0] == "const" and up[1] in ("0", "1"):
                    v = up[1] if c.ytype != "$not" else ("1" if up[1] == "0" else "0")
                    res = ("const", v, f"{c.ytype}({up[2]})")
                else:
                    res = ("pin", ci, pn, bit, 0)
            else:
                pin = self.pin(ci, pn)
                ck = self.R.clock_of(pin)
                rs = self.R.reset_of(pin)
                if ck is not None:
                    res = ("clock", ck)
                elif rs is not None:
                    res = ("reset", rs, 0)
                else:
                    res = ("pin", ci, pn, bit, 0)
        self._src[net] = res
        return res


def _tmap(sp, pn):
    """a transport rule's input for output port pn: map {output port (regex, full match): input port}"""
    m = sp.get("map", {})
    if pn in m:
        return m[pn]
    for rx, ip in m.items():
        mm = re.fullmatch(rx, pn)
        if mm:
            return mm.expand(ip) if "\\" in ip else ip
    return None


def _src_out(sp, pn):
    """a source rule's output: outputs {port regex: domain | polarity | {"kind": clock|reset, "value": ...}}"""
    for rx, v in sp.get("outputs", {}).items():
        if re.fullmatch(rx, pn):
            if isinstance(v, dict):
                return (v.get("kind", sp.get("kind", "clock")), v.get("value", v.get("domain", v.get("polarity"))))
            return (sp.get("kind", "clock"), v)
    return None


def _add_stages(s, n):
    if s[0] == "pin":
        return s[:4] + (s[4] + n,)
    if s[0] == "reset":
        return (s[0], s[1], s[2] + n)
    if s[0] == "top":
        return s[:3] + (s[3] + n,)
    if s[0] in ("or", "and"):
        return (s[0], s[1], s[2] + n)
    return s


