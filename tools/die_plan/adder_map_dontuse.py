#!/usr/bin/env python3
"""Platform adder techmap that honours the platform DONT_USE list (KV-CORES ruling 4, 2026-10-25).

ORFS synth.tcl runs `extract_fa; techmap -map $ADDER_MAP_FILE`. The asap7 map (platforms/asap7/yoSys/cells_adders_R.v)
instantiates HAxp5_ASAP7_75t_R for every $fa bit with a constant-0 input, but the platform marks *xp*_ASAP7* DONT_USE
(DONT_USE_CELLS in platforms/asap7/config.mk): the netlist then carries a cell that placement/resizing may not touch and
whose pin access failed detailed route (KV head_eighth e6, DRT-1231 on an FA/HA CON pin).

  gen   read the platform adder map + the DONT_USE patterns of the platform config.mk, replace every DONT_USE cell
        instance by equivalent generic logic (a cell this tool knows), FAIL on any DONT_USE cell it does not know, and
        write the map (no DONT_USE cell left).  FAx1 (not DONT_USE) stays a cell.
  check FAIL when a synthesised netlist (1_2_yosys.v) instantiates a DONT_USE cell.

Both run inside the ORFS image (platform files there): python3 -I adder_map_dontuse.py gen --platform-dir $PLATFORM_DIR
--out /work/adder_map_dontuse.v ; ... check --platform-dir $PLATFORM_DIR --netlist .../1_2_yosys.v
Exit codes: 0 PASS, 1 FAIL (unknown DONT_USE cell / DONT_USE cell in the netlist), 2 usage / missing input.
"""
import argparse
import fnmatch
import json
import re
import sys
from pathlib import Path

# DONT_USE cell type (exact, any VT suffix) -> generic logic for its output pins, by input pin name.
# HAxp5 (asap7 liberty): CON = !(A & B), SN = !(A ^ B)
KNOWN = {
    r"HAxp5_ASAP7_75t_[RLS]L?": {"CON": "~({A} & {B})", "SN": "~({A} ^ {B})"},
}
INST_RE = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*_ASAP7_[A-Za-z0-9_]+)\s+([A-Za-z_\\][^\s(]*)\s*\(([^;]*?)\)\s*;", re.S)
CONN_RE = re.compile(r"\.([A-Za-z_][A-Za-z0-9_]*)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)")


def dont_use_patterns(config_mk):
    """DONT_USE_CELLS of a platform config.mk (export ... = / += / ?= lines, in order)."""
    pats = []
    for line in Path(config_mk).read_text().splitlines():
        m = re.match(r"\s*(?:export\s+)?DONT_USE_CELLS\s*([+?:]?=)\s*(.*?)\s*(?:#.*)?$", line)
        if m:
            vals = m.group(2).split()
            pats = pats + vals if m.group(1) == "+=" else vals
    return pats


def is_dont_use(cell, pats):
    return any(fnmatch.fnmatchcase(cell, p) for p in pats)


def known_rule(cell):
    for rx, outs in KNOWN.items():
        if re.fullmatch(rx, cell):
            return outs
    return None


def rewrite_map(text, pats):
    """-> (new_text, replaced[{cell, inst}], unknown[cell])"""
    replaced, unknown = [], []

    def sub(m):
        cell, inst, conns = m.group(1), m.group(2), m.group(3)
        if not is_dont_use(cell, pats):
            return m.group(0)
        rule = known_rule(cell)
        if rule is None:
            unknown.append(cell)
            return m.group(0)
        pins = {p: v.strip() for p, v in CONN_RE.findall(conns)}
        need = set(re.findall(r"\{(\w+)\}", " ".join(rule.values())))
        if not need <= set(pins) or not set(rule) <= set(pins):
            unknown.append(f"{cell} (pins {sorted(pins)})")
            return m.group(0)
        replaced.append(dict(cell=cell, inst=inst))
        body = [f"/* {inst} = DONT_USE cell {cell} -> generic logic (adder_map_dontuse.py) */"]
        for o, expr in rule.items():
            body.append(f"assign {pins[o]} = {expr.format(**{k: '(' + v + ')' for k, v in pins.items()})};")
        return "\n          ".join(body)

    return INST_RE.sub(sub, text), replaced, unknown


def netlist_cells(text):
    """cell types instantiated in a flat Yosys netlist"""
    return re.findall(r"^\s*([A-Za-z_][A-Za-z0-9_]*_ASAP7_[A-Za-z0-9_]+)\s+\S+\s*\(", text, re.M)


def cmd_gen(a):
    pd = Path(a.platform_dir)
    src = Path(a.map) if a.map else pd / "yoSys" / f"cells_adders_{a.vt}.v"
    cfg = Path(a.config) if a.config else pd / "config.mk"
    if not src.is_file() or not cfg.is_file():
        print(f"ADDER_MAP_DONTUSE ERROR missing {src if not src.is_file() else cfg}")
        return 2
    pats = a.dont_use.split() if a.dont_use else dont_use_patterns(cfg)
    if not pats:
        print(f"ADDER_MAP_DONTUSE ERROR no DONT_USE_CELLS in {cfg}")
        return 2
    new, rep, unk = rewrite_map(src.read_text(), pats)
    left = sorted({c for c, *_ in INST_RE.findall(new) if is_dont_use(c, pats)})
    rpt = dict(source=str(src), dont_use=pats, replaced=rep, unknown=unk, dont_use_left=left,
               cells_kept=sorted({c for c, *_ in INST_RE.findall(new)}))
    if unk or left:
        print(f"ADDER_MAP_DONTUSE FAIL unknown DONT_USE cells {sorted(set(unk + left))} in {src}")
        if a.report:
            Path(a.report).write_text(json.dumps(dict(rpt, verdict="FAIL"), indent=1) + "\n")
        return 1
    hdr = (f"// GENERATED by tools/die_plan/adder_map_dontuse.py from {src}\n"
           f"// DONT_USE {' '.join(pats)}: {len(rep)} cell instance(s) replaced by generic logic; kept cells "
           f"{', '.join(rpt['cells_kept']) or '-'}\n")
    Path(a.out).write_text(hdr + new)
    if a.report:
        Path(a.report).write_text(json.dumps(dict(rpt, verdict="PASS"), indent=1) + "\n")
    print(f"ADDER_MAP_DONTUSE PASS {a.out}: replaced {len(rep)} ({', '.join(sorted({r['cell'] for r in rep})) or '-'}),"
          f" kept {', '.join(rpt['cells_kept']) or '-'}")
    return 0


def cmd_check(a):
    pd = Path(a.platform_dir) if a.platform_dir else None
    pats = a.dont_use.split() if a.dont_use else (dont_use_patterns(Path(a.config) if a.config else pd / "config.mk")
                                                 if (a.config or pd) else [])
    if not pats:
        print("DONT_USE_CHECK ERROR no DONT_USE patterns (--platform-dir / --config / --dont-use)")
        return 2
    n = Path(a.netlist)
    if not n.is_file():
        print(f"DONT_USE_CHECK ERROR missing netlist {n}")
        return 2
    cnt = {}
    for c in netlist_cells(n.read_text()):
        if is_dont_use(c, pats):
            cnt[c] = cnt.get(c, 0) + 1
    if a.report:
        Path(a.report).write_text(json.dumps(dict(netlist=str(n), dont_use=pats, dont_use_cells=cnt,
                                                  verdict="FAIL" if cnt else "PASS"), indent=1) + "\n")
    if cnt:
        print(f"DONT_USE_CHECK FAIL {n.name}: {sum(cnt.values())} DONT_USE instances {cnt}")
        return 1
    print(f"DONT_USE_CHECK PASS {n.name}: no DONT_USE cell ({' '.join(pats)})")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    g = sp.add_parser("gen")
    g.add_argument("--platform-dir", required=True)
    g.add_argument("--map", help="adder map (default PLATFORM_DIR/yoSys/cells_adders_<vt>.v)")
    g.add_argument("--vt", default="R")
    g.add_argument("--config", help="platform config.mk (default PLATFORM_DIR/config.mk)")
    g.add_argument("--dont-use", help="override the DONT_USE patterns (space separated)")
    g.add_argument("--out", required=True)
    g.add_argument("--report")
    c = sp.add_parser("check")
    c.add_argument("--platform-dir")
    c.add_argument("--config")
    c.add_argument("--dont-use")
    c.add_argument("--netlist", required=True)
    c.add_argument("--report")
    a = ap.parse_args(argv)
    return cmd_gen(a) if a.cmd == "gen" else cmd_check(a)


if __name__ == "__main__":
    sys.exit(main())
