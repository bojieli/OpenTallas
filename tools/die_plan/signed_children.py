"""SIGNED hard-child view/geometry and exact named placement, shared with the established QC flow."""
import copy
import json
import re
from pathlib import Path
REPO = Path(__file__).resolve().parents[2]
CHILD_VIEW_FILES = ("{m}.lef", "{m}_tt.lib", "{m}_ff.lib", "provenance.json", "gates.json")

def child_view_problems(vdir, master):
    """[] when vdir is a SIGNED, complete view of master (export_view.py layout); else the reasons"""
    vdir = Path(vdir)
    probs = [f"missing {f.format(m=master)}" for f in CHILD_VIEW_FILES if not (vdir / f.format(m=master)).is_file()]
    if probs:
        return probs
    try:
        prov = json.loads((vdir / "provenance.json").read_text())
        gates = json.loads((vdir / "gates.json").read_text())
    except (OSError, ValueError) as e:
        return [f"unreadable provenance/gates: {e}"]
    if prov.get("views_status") != "signoff":
        probs.append(f"views_status {prov.get('views_status')!r} (not 'signoff')")
    if not str(prov.get("verdict") or "").upper().startswith("SIGNED"):
        probs.append(f"verdict {str(prov.get('verdict'))[:60]!r} (not SIGNED)")
    if gates.get("view_complete") is not True:
        probs.append(f"gates view_complete {gates.get('view_complete')!r}")
    lef = (vdir / f"{master}.lef").read_text(errors="replace")
    if not re.search(rf"^MACRO\s+{re.escape(master)}\s*$", lef, re.M):
        probs.append(f"{master}.lef defines no MACRO {master}")
    return probs


def hard_children_list(hcr, spec, repo=None):
    """[{inst, master, at, orient}] of the composed core: recipe children_file, else spec children[]"""
    repo = Path(repo or REPO)
    if hcr.get("children_file"):
        doc = json.loads((repo / hcr["children_file"]).read_text())
        rows = doc["children"] if isinstance(doc, dict) else doc
        return [dict(inst=c["inst"], master=c["module"], at=[float(v) for v in c["at"]], orient=c.get("orient", "R0"))
                for c in rows]
    out = []
    for c in spec.get("children", []):
        for _ in range(int(c.get("count") or 1)):
            out.append(dict(inst=c["inst"], master=Path(c["view"]).name, at=[float(v) for v in c["at"]],
                            orient=c.get("orient", "R0")))
    return out


def lef_size(text):
    m = re.search(r"SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", text)
    return float(m.group(1)), float(m.group(2))


def hard_children_check(children, views, sizes, outline, margin=0.0):
    """refusal lines for the composed core plan: unique instances, a view per master, R0/MY/MX/R180 only, inside the
    core area, no two children overlapping.  [] = OK."""
    w, h = outline
    err, rects = [], []
    if len({c["inst"] for c in children}) != len(children):
        err.append("duplicate child instance names")
    for c in children:
        if c["master"] not in views:
            err.append(f"{c['inst']}: no view for master {c['master']}")
            continue
        if c["orient"] not in ("R0", "MY", "MX", "R180"):
            err.append(f"{c['inst']}: orient {c['orient']} not R0/MY/MX/R180")
        cw, ch = sizes[c["master"]]
        x, y = c["at"]
        if not (x >= margin - 1e-6 and y >= margin - 1e-6 and x + cw <= w - margin + 1e-6 and y + ch <= h - margin + 1e-6):
            err.append(f"{c['inst']}: site {x},{y} ({cw}x{ch}) outside the core area of {w}x{h}")
        rects.append((x, y, x + cw, y + ch, c["inst"]))
    for i, a in enumerate(rects):
        for b in rects[i + 1:]:
            if a[0] < b[2] - 1e-6 and b[0] < a[2] - 1e-6 and a[1] < b[3] - 1e-6 and b[1] < a[3] - 1e-6:
                err.append(f"children overlap: {a[4]} / {b[4]}")
    return err


def child_inst_regex(inst):
    """ODB flat-name regex of a planned hierarchical instance: segments joined by '.', escaped brackets tolerated, an
    optional Yosys genblkN. scope between segments (A0 node: g_ndh.u_node elaborates as genblk5.g_ndh.u_node)"""
    segs = [re.escape(s).replace(r"\[", r"\\?\[").replace(r"\]", r"\\?\]") for s in inst.split(".")]
    return "(^|[./])" + r"\.(genblk[0-9]+\.)?".join(segs) + "$"


def hard_children_tcl(children):
    mp = ["# GENERATED by gen_core_kit_qc.py (recipe hard_children): FIRM sites of the SIGNED hard children (plan),",
          "# lower-left of the placed bbox at the planned site; exactly one instance per planned name.",
          "set blk [ord::get_db_block]", "set dbu [$blk getDbUnitsPerMicron]"]
    for c in children:
        mp += ["set hit {}",
               f"foreach i [$blk getInsts] {{ if {{[[$i getMaster] getName] eq \"{c['master']}\" && "
               f"[regexp {{{child_inst_regex(c['inst'])}}} [$i getName]]}} {{ lappend hit $i }} }}",
               f"if {{[llength $hit] != 1}} {{ error \"hard child {c['inst']}: [llength $hit] matches\" }}",
               "set i [lindex $hit 0]",
               f"$i setOrient {c['orient']}",
               "$i setLocation 0 0",
               "set bb [$i getBBox]",
               f"$i setLocation [expr {{round({c['at'][0]} * $dbu) - [$bb xMin]}}] "
               f"[expr {{round({c['at'][1]} * $dbu) - [$bb yMin]}}]",
               "$i setPlacementStatus FIRM",
               f"puts \"hard child {c['inst']} -> [$i getName] {c['orient']} at {c['at'][0]} {c['at'][1]}\""]
    mp.append(f"puts \"OT_HARD_CHILDREN placed {len(children)}\"")
    return "\n".join(mp) + "\n"



def prepare_hard_children(spec, hcr, repo, outline, margin=0.0):
    children = hard_children_list(hcr, spec, repo)
    views = {m: (Path(v) if Path(v).is_absolute() else Path(repo) / v)
             for m, v in hcr["views"].items()}
    used = {c["master"] for c in children}
    missing = used - views.keys()
    if missing:
        raise ValueError("hard children missing views: " + ", ".join(sorted(missing)))
    probs = {m: child_view_problems(views[m], m) for m in used}
    probs = {m: p for m, p in probs.items() if p}
    if probs:
        raise ValueError("hard children not SIGNED views: " + "; ".join(f"{m}: {', '.join(p)}" for m,p in sorted(probs.items())))
    sizes = {m: lef_size((views[m] / f"{m}.lef").read_text()) for m in used}
    errors = hard_children_check(children, views, sizes, outline, margin)
    if errors:
        raise ValueError("hard children plan: " + "; ".join(errors))
    out = copy.deepcopy(spec)
    out.pop("children", None)
    out.setdefault("macros", []).extend(dict(view=str(views[c["master"]]), inst=c["inst"],
        at=c["at"], orient=c["orient"]) for c in children)
    return out, children



def _masked_rtl(text):
    return re.sub(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"',
                  lambda m: re.sub(r'[^\n]', ' ', m[0]), text, flags=re.S)


def _code_rename(text, old, new):
    matches = list(re.finditer(r'\b'+re.escape(old)+r'\b', _masked_rtl(text)))
    for hit in reversed(matches):
        text = text[:hit.start()]+new+text[hit.end():]
    return text


def _instance_type_spans(text, master, instance):
    code = _masked_rtl(text)
    spans = []
    for hit in re.finditer(r'\b'+re.escape(master)+r'\b', code):
        i = hit.end()
        while i < len(code) and code[i].isspace():
            i += 1
        if i < len(code) and code[i] == '#':
            i += 1
            while i < len(code) and code[i].isspace():
                i += 1
            if i == len(code) or code[i] != '(':
                continue
            depth = 1
            i += 1
            while i < len(code) and depth:
                depth += (code[i] == '(') - (code[i] == ')')
                i += 1
            if depth:
                raise ValueError('unbalanced hard-child parameter list')
        while i < len(code) and code[i].isspace():
            i += 1
        if re.match(re.escape(instance)+r'\s*\(', code[i:]):
            spans.append((hit.start(), hit.end(), i))
    return spans


def specialize_native_children(rtl_dir, children):
    """Only selected instances use the hard view; other parameterizations remain native.

    A source module may serve both a hardened bank and soft banks with different
    parameters. Rename its native definition/references, then restore the type of
    each selected instance to the separately staged fixed-port blackbox master.
    The selected hard instance has fixed sealed parameters, so its native
    override block is removed. Soft-instance parameters/ports and native logic
    remain unchanged.
    """
    paths = [p for p in sorted(Path(rtl_dir).iterdir())
             if p.suffix in ('.sv', '.v') and not p.name.endswith('_bb.v')]
    texts = {p:p.read_text() for p in paths}
    masters = {c['master'] for c in children}
    counts = {}
    for master in sorted(masters):
        alias = master+'__soft'
        if any(re.search(r'\b'+re.escape(alias)+r'\b', _masked_rtl(t)) for t in texts.values()):
            raise ValueError('hard child native alias already exists: '+alias)
        n = sum(len(re.findall(r'(?m)^[ \t]*module\s+'+re.escape(master)+r'\b', _masked_rtl(t)))
                for t in texts.values())
        if n != 1:
            raise ValueError(f'expected exactly one native definition for {master}, found {n}')
        texts = {p:_code_rename(t, master, alias) for p,t in texts.items()}
        leaves = {c['inst'].split('.')[-1] for c in children if c['master'] == master}
        for leaf in sorted(leaves):
            hits = [(p, a, b, end) for p,t in texts.items() for a,b,end in _instance_type_spans(t, alias, leaf)]
            if len(hits) != 1:
                raise ValueError(f'hard child {master}/{leaf}: expected one source instance, found {len(hits)}')
            p,a,b,end = hits[0]
            texts[p] = texts[p][:a]+master+' '+texts[p][end:]
        counts[master] = len(leaves)
    for path,text in texts.items():
        if text != path.read_text():
            path.write_text(text)
    return counts
