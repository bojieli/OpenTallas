"""KV-HG-SPLIT-1 11-12: kit-local renamed soft clones of a module that is ALSO a hard core master in the same type.

A type may harden some instances of a leaf module (plan hard_cores, module M, signed view M.lef) and keep other
instances of the same M soft.  The kit flow black-boxes every macro module by name (bind kit_closure views,
gen_phys.strip_module_definition), so a soft instance of M would silently become a second, unplaced macro.  Plan key
partition_types[T].soft_clones = [{"physical_inst": "u_bound.<local>", "base": M, "master": M_clone}]: the kit-rtl step
renames that one bound instantiation `M <local> (` to `M_clone <local> (` and adds M_clone = the exact text of M's
definition with only the module name changed (+ the `ifndef/`define guards of the macros its body uses, copied from
M's file).  No logic, port, parameter or cycle change: the receipt records sha256 of both bodies with the name
normalised, which must be equal.  Absent key = byte-identical kits."""
import hashlib
import re

_HDR = r"(?m)^[ \t]*module[ \t]+{}\b"
_DIRECTIVES = {"timescale", "default_nettype", "ifdef", "ifndef", "elsif", "else", "endif", "define", "undef",
               "include", "resetall", "celldefine", "endcelldefine", "line", "pragma", "begin_keywords",
               "end_keywords", "unconnected_drive", "nounconnected_drive", "__FILE__", "__LINE__"}


def _strip_comments(text):
    """same length text with // and /* */ comments blanked (newlines kept), so offsets stay valid"""
    out, i, n = list(text), 0, len(text)
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            i = min(n, j + 1)
            continue
        else:
            i += 1
            continue
        for k in range(i, j):
            if out[k] != "\n":
                out[k] = " "
        i = j
    return "".join(out)


def module_text(text, mod):
    """exactly one `module mod ... endmodule` definition of text (comments respected) -> its text"""
    clean = _strip_comments(text)
    heads = list(re.finditer(_HDR.format(re.escape(mod)), clean))
    if len(heads) != 1:
        raise ValueError(f"soft_clone: {len(heads)} definitions of module {mod} (need exactly 1)")
    s = heads[0].start()
    e = re.search(r"(?<![\w$])endmodule\b", clean[heads[0].end():])
    if e is None:
        raise ValueError(f"soft_clone: module {mod}: no endmodule")
    end = heads[0].end() + e.end()
    body = clean[s:end]
    if re.search(r"(?<![\w$`])module\b", body[len(heads[0].group(0)):]):
        raise ValueError(f"soft_clone: module {mod}: nested module keyword before endmodule")
    if len(re.findall(r"`if(?:n?def)\b", body)) != len(re.findall(r"`endif\b", body)):
        raise ValueError(f"soft_clone: module {mod}: definition straddles a preprocessor conditional")
    return text[s:end]


def _norm(body, name):
    return re.sub(r"^([ \t]*module[ \t]+)" + re.escape(name) + r"\b", r"\1<M>", body, count=1, flags=re.M)


def body_sha(body, name):
    return hashlib.sha256(_norm(body, name).encode()).hexdigest()


def clone_text(base_file_text, base, master, src=""):
    """-> (generated source text, receipt row) of master = base's definition renamed"""
    body = module_text(base_file_text, base)
    new = re.sub(r"^([ \t]*module[ \t]+)" + re.escape(base) + r"\b", r"\g<1>" + master, body, count=1, flags=re.M)
    guards = []
    for m in sorted(set(re.findall(r"`([A-Za-z_]\w*)", _strip_comments(body))) - _DIRECTIVES):
        d = re.search(r"(?m)^[ \t]*`define[ \t]+" + re.escape(m) + r"\b([^\n]*)$", _strip_comments(base_file_text))
        if d is None:
            raise ValueError(f"soft_clone: {base} uses `{m} with no `define in its source file")
        guards.append(f"`ifndef {m}\n`define {m}{d.group(1).rstrip()}\n`endif\n")
    a, b = body_sha(body, base), body_sha(new, master)
    if a != b:
        raise ValueError(f"soft_clone: {master} body differs from {base}")
    txt = (f"// GENERATED by tools/die_plan/soft_clone.py: {master} = exact text of {base} ({src}), renamed only.\n"
           f"// A kit-local soft copy for instances kept soft while {base} is a hard core master in the same type.\n"
           "`timescale 1ns/1ps\n" + "".join(guards) + new + "\n")
    return txt, dict(base=base, master=master, source=str(src), body_sha256=a, clone_body_sha256=b,
                     macro_guards=len(guards), cycles_changed=0)


def clone_bound(bound, clones):
    """-> (bound, rows): rename every planned soft clone instance in the bound text (sources: clone_sources)"""
    rows = []
    for c in clones or []:
        base, master = c["base"], c["master"]
        inst = (c.get("physical_inst") or "").removeprefix("u_bound.")
        if not inst or "." in inst:
            raise ValueError(f"soft_clone: physical_inst must be u_bound.<local> (got {c.get('physical_inst')})")
        if master == base or re.search(_HDR.format(re.escape(master)), bound):
            raise ValueError(f"soft_clone: master {master} must be a new module name")
        if any(r["master"] == master and r["base"] != base for r in rows):
            raise ValueError(f"soft_clone: master {master} declared for two bases")
        pat = re.compile(r"^([ \t]+)(\w+)([ \t]+(?:#\([^\n]*?\)[ \t]+)?)" + re.escape(inst) + r"[ \t]*\(", re.M)
        hits = list(pat.finditer(bound))
        if len(hits) != 1:
            raise ValueError(f"soft_clone: expected one instance {inst}, got {len(hits)}")
        h = hits[0]
        if h.group(2) != base:
            raise ValueError(f"soft_clone: {inst} is {h.group(2)}, plan says {base}")
        bound = bound[:h.start()] + f"{h.group(1)}{master}{h.group(3)}{inst} (" + bound[h.end():]
        rows.append(dict(base=base, master=master, physical_inst=c["physical_inst"], cycles_changed=0))
    return bound, rows


def clone_sources(rows, read_base):
    """-> (text of all clone modules, receipt rows); read_base(base) -> (text of the file defining base, its name)"""
    out, done, rec = [], {}, []
    for r in rows:
        if r["master"] not in done:
            text, src = read_base(r["base"])
            t, done[r["master"]] = clone_text(text, r["base"], r["master"], src)
            out.append(t)
        rec.append(dict(done[r["master"]], physical_inst=r["physical_inst"]))
    return "".join(out), rec
