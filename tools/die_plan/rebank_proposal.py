#!/usr/bin/env python3
"""REBANK PROPOSAL (SEAM-HOP-1): for the lanes path_respace cannot fix because an exact bit bank cannot move / cannot be
cloned, propose the re-bank: which slots get one more station, where (type frame regs_um), what the bank must be
(stages x (width+1) sites near each regs_um; the current bank shape is the template), and the latency rows / groups.
Bank geometry is NOT generated here (ft_bit_sites sites are regenerated by the owner / kit tool at the proposed regs_um);
this only decides counts and sites with the bank constraint relaxed.  Cycles are the owner's call: nothing is applied.

    python3 tools/die_plan/rebank_proposal.py PLAN[.gz] STAGE_REPORT.json OUT.json
"""
import copy
import json
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import path_respace as PR  # noqa: E402
import schema as S  # noqa: E402


def main(argv=None):
    plan, rep_f, out_f = sys.argv[1:4] if argv is None else argv
    raw = PR._load(plan)
    rep = json.loads(Path(rep_f).read_text())
    todo = [l for l, v in rep["lanes"].items() if v["status"] in ("unresolved", "blocked", "exact_bank_blocked", "exact_snap_over")]
    PR.FREE_BANKS = True
    import gen
    work = copy.deepcopy(raw)
    P = S.Plan(work)
    base_lat = gen.latency_table(P)
    rows = []
    for lid in todo:
        P = S.Plan(work)
        lane = PR.Lane(P, lid)
        res = PR.plan_lane(P, lane, 405.0, True, {})
        row = dict(lane=lid, status=res["status"], hop_before=round(res.get("before", 0), 1))
        if res["status"] != "fixed":
            row["why"] = {k: v for k, v in res.items() if k in ("gstar", "binding", "slot")}
            rows.append(row)
            continue
        slots = []
        for c, pts in res["new"].items():
            cr = lane.cross[c]
            sl = next(s_ for s_ in work["partition_types"][cr["tn"]]["ft_slots"] if s_["name"] == cr["slot"])
            tp = [[round(v, 3) for v in P.to_type(cr["part"], p)] for p in pts]
            moved = tp != [list(map(lambda v: round(v, 3), x)) for x in res["old"][c]]
            if not moved and len(tp) == cr["k"]:
                continue
            slots.append(dict(slot=f"{cr['part']}.{cr['slot']}", type=cr["tn"], stations_before=cr["k"], stations_after=len(tp),
                              regs_um=tp, exact_bank="bit_sites_um" in sl,
                              bank=f"regenerate bit_sites_um: {len(tp) - 1} stages x {sl.get('width', 0) + 1} sites, current "
                                   f"bank shape as template, one stage anchored at each regs_um[1:]" if "bit_sites_um" in sl else None))
            sl["regs_um"], sl["stations"] = tp, len(tp)
            sl.pop("bit_sites_um", None)
            sl.pop("bit_site_cell_um", None)
        row.update(hop_after=round(res["after"], 1), slots=slots, adds=sum(v for v in res.get("adds", {}).values()))
        rows.append(row)
    new_lat = gen.latency_table(S.Plan(work))
    plus = {l: dict(old=base_lat[l].get("cycles"), new=v.get("cycles")) for l, v in new_lat.items()
            if v != base_lat.get(l)}
    P0 = S.Plan(raw)
    groups = defaultdict(list)
    for name, kind, ls in P0.latency_groups():
        for l in ls:
            if l in plus:
                groups[l].append(f"{kind}:{name}")
    for l in plus:
        plus[l]["groups"] = groups.get(l, [])
    summ = dict(lanes=len(todo), fixed=sum(1 for r in rows if r["status"] == "fixed"),
                plus_cycle_lanes=len([1 for v in plus.values() if v["new"] != v["old"]]),
                stations_added=sum(r.get("adds", 0) for r in rows))
    Path(out_f).write_text(json.dumps(dict(summary=summ, lanes=rows, latency_rows=plus), indent=1) + "\n")
    print(json.dumps(summ))


if __name__ == "__main__":
    main()
