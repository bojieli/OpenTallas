def test_scoped_hook_guard_runs_before_existing_editor(tmp_path):
    tree = dict(clock_port='clk_phy',root_scope=scope(),cts_open=[])
    (tmp_path/'core_infra_plan.json').write_text(json.dumps(dict(core_tree=tree)))
    (tmp_path/CI.CTS_HOOK).write_text(CI.emit_cts_tcl(dict(core_tree=tree)))
    (tmp_path/'pre.tcl').write_text('source /work/core_density_taps.tcl\n')
    (tmp_path/'core_density_taps.tcl').write_text('# ordinary roots\n')
    cfg = ['export PRE_CTS_TCL = /work/pre.tcl']
    assert CI.kit_cts_hook(tmp_path,cfg)
    body = (tmp_path/CI.CTS_PRE_CHAIN).read_text()
    assert body.index('core_infra_scope.tcl') < body.index('/work/pre.tcl') < body.index(CI.CTS_HOOK)
    assert (tmp_path/'pre.tcl').read_text() == 'source /work/core_density_taps.tcl\n'
    assert 'OT_CORE_SCOPE_EDITOR_CHANGED' in (tmp_path/CI.ROOT_SCOPE_HOOK).read_text()
    tree['root_scope']['clock_editor_roots'] = {}
    (tmp_path/'core_infra_plan.json').write_text(json.dumps(dict(core_tree=tree)))
    with pytest.raises(SystemExit,match='undeclared clock editors'):
        CI.kit_cts_hook(tmp_path,['export PRE_CTS_TCL = /work/pre.tcl'])


@pytest.mark.skipif(shutil.which('tclsh') is None, reason='tclsh required')
@pytest.mark.parametrize('mutation,expect', [('ordinary','PASS'),('protected','OT_CORE_SCOPE_EDITOR_CHANGED'),
                                            ('both','OT_CORE_SCOPE_EDITOR_CHANGED')])
def test_actual_effect_guard_rejects_rewiring_protected_root(tmp_path,mutation,expect):
    # Exercise the installed source wrapper on an editor. The snapshot oracle
    # stands in for OpenDB here; changes outside the declared root are seeded.
    # Separate graph-walk test below uses actual rooted-net object interfaces.
    tree = dict(clock_port='clk_phy',root_scope=scope())
    script = CI.emit_root_scope_tcl(tree)
    script += '''\nset state [dict create clk_phy original clk original {clk_t1[0]} original]
proc ot_ci_scope_disjoint {} {return {}}
proc ot_ci_scope_snapshot {roots args} {
 set out {}; foreach r $roots {dict set out $r [dict get $::state $r]};return $out
}
'''
    edit = tmp_path/'core_density_taps.tcl'
    edit.write_text({'ordinary':'dict set ::state clk rewired\n',
                     'protected':'dict set ::state clk_phy rewired\n',
                     'both':'dict set ::state clk rewired\ndict set ::state clk_phy rewired\n'}[mutation])
    script += 'if {[catch {source {'+str(edit)+'}} msg]} {puts $msg} else {puts PASS}\n'
    run=subprocess.run(['tclsh'],input=script,text=True,capture_output=True,check=True)
    assert expect in run.stdout, run.stderr+run.stdout

# Minimal OpenDB interface fixture: two input roots, one planned BUF and FF,
# and one ordinary FF. Connections are mutable through the same object APIs
# the production guard follows; no precomputed snapshot oracle is used.
DB_FIXTURE = r'''
set attrs [dict create \
 bphy {kind bterm name clk_phy io INPUT} bcore {kind bterm name clk io INPUT} \
 nphy {kind net name phy_in sig CLOCK dt 0} nleaf {kind net name phy_leaf sig CLOCK dt 1} \
 ncore {kind net name core_in sig CLOCK dt 0} \
 ibuf {kind inst name planned_buf master mbuf terms {ba by} loc {10 10} dt 1} \
 iphy {kind inst name phy_ff master mff terms {pc} loc {11 10} dt 0} \
 icore {kind inst name core_ff master mff terms {cc} loc {30 30} dt 0} \
 mbuf {kind master name BUFx24_ASAP7_75t_R block 0} mff {kind master name DFFHQNx1_ASAP7_75t_R block 0} \
 ba {kind iterm inst ibuf pin pa} by {kind iterm inst ibuf pin py} \
 pc {kind iterm inst iphy pin pcl} cc {kind iterm inst icore pin pcl} \
 pa {kind mterm name A io INPUT} py {kind mterm name Y io OUTPUT} pcl {kind mterm name CLK io INPUT}]
set links [dict create bphy nphy bcore ncore ba nphy by nleaf pc nleaf cc ncore]
proc dbobj {self method args} {
 if {$self eq "blk"} {
  switch $method {
   findBTerm {set k [lindex $args 0];if {![dict exists {clk_phy bphy clk bcore} $k]} {return NULL};return [dict get {clk_phy bphy clk bcore} $k]}
   findNet {return [dict get {phy_in nphy phy_leaf nleaf core_in ncore} [lindex $args 0]]}
  }
 }
 set a [dict get $::attrs $self]
 switch $method {
  getName {return [dict get $a name]}
  getNet {return [dict get $::links $self]}
  getIoType {return [dict get $a io]}
  getSigType {return [dict get $a sig]}
  isDoNotTouch {return [dict get $a dt]}
  getITerms {
   if {[dict get $a kind] eq "inst"} {return [dict get $a terms]}
   set terms {};dict for {q net} $::links {
    if {$net eq $self && [dict get $::attrs $q kind] eq "iterm"} {lappend terms $q}
   };return $terms
  }
  getBTerms {
   set terms {};dict for {q net} $::links {
    if {$net eq $self && [dict get $::attrs $q kind] eq "bterm"} {lappend terms $q}
   };return $terms
  }
  getFirstOutput {
   foreach it [dbobj $self getITerms] {if {[[dbobj $it getMTerm] getIoType] eq "OUTPUT"} {return $it}}
   return NULL
  }
  getInst {return [dict get $a inst]}
  getMTerm {return [dict get $a pin]}
  getMaster {return [dict get $a master]}
  getLocation {return [dict get $a loc]}
  getOrient {return R0}
  getPlacementStatus {return [expr {[dict get $a dt] ? "FIRM" : "PLACED"}]}
  isBlock {return [dict get $a block]}
 }
 error "unhandled interface $self $method"
}
interp alias {} blk {} dbobj blk
dict for {q a} $attrs {interp alias {} $q {} dbobj $q}
namespace eval ord {proc get_db_block {} {return blk}}
namespace eval sta {proc sta_to_db_pin {p} {return $p}}
proc all_registers {args} {return {pc cc}}
proc all_clocks {} {return {phy_clock core_clock virtual_io}}
proc get_property {c p} {return [dict get {phy_clock clk_phy core_clock clk virtual_io {}} $c]}
proc get_full_name {p} {return $p}
'''


def _tcl(script):
    run=subprocess.run(['tclsh'],input=script,text=True,capture_output=True,check=True)
    assert not run.stderr,run.stderr
    return run.stdout


