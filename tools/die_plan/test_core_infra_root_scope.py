def scope():
    return dict(ordinary_roots=['clk', 'clk_t1[0]'], ordinary_cts_roots=['clk', 'clk_t1[0]'],
                clock_editor_roots={'core_density_taps.tcl': ['clk', 'clk_t1[0]']})


def test_explicit_root_scope_validation():
    tree = dict(clock_port='clk_phy', root_scope=scope())
    entries = [dict(port=p) for p in ['clk_phy', 'clk', 'clk_t1[0]']]
    assert CI.validate_root_scope(tree, entries) == scope()
    for change in (lambda t: t['root_scope']['ordinary_roots'].append('clk_phy'),
                   lambda t: t['root_scope']['ordinary_roots'].append('clk'),
                   lambda t: t['root_scope']['clock_editor_roots'].update({'core_density_taps.tcl': ['clk_phy']}),
                   lambda t: t['root_scope']['clock_editor_roots'].update({'invented.tcl': ['clk']}),
                   lambda t: t['root_scope']['clock_editor_roots'].update({'core_density_taps.tcl': [{}]})):
        bad = copy.deepcopy(tree); change(bad)
        with pytest.raises(CI.InfraError):
            CI.validate_root_scope(bad, entries)
    with pytest.raises(CI.InfraError, match='cover clock_entries exactly'):
        CI.validate_root_scope(tree, entries[:-1])


