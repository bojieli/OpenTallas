#!/usr/bin/env python3
"""CLOCK-KV-R9 item 1: ndr016 OpenRCX of the routed KV die clock tree (b5).
The KV combo draws the tree as special M8/M9 SBoxes (RCX never extracts special nets), so this re-draws every
mesh.json fixed_wires net as a FIXED regular dbWire under the clock NDR with clock_routed.routed_tcl (the same
emitter CLOCK-128-R5..R8 uses on QC: exact plan legs + plan-computed pin-access stairs), deletes the net's SWires,
then runs extract_parasitics with tools/die_plan/rcx/asap7_rcx_ndr016.rules (-lef_res + per-layer RPERSQ,
clock_routed.rcx_tcl('ndr')), writes rcx.spef and the tree arrivals (same report as the combo) per corner on
both bases (native geometry SPEF vs RCX SPEF).  Diagnostic re-extraction only: no geometry/plan change.
usage: rcx_kv.py BUILD_DIR OUT_DIR [TOOLS_DIR]   (TOOLS_DIR holds clock_routed.py, rcx_width_rules.py and
asap7_rcx_ndr016.rules; default = this directory, rules from rcx/)

CLOCK-KV-R12: copied from Codex rcx_repair/rcx_kv.py into the repo; emitted Tcl unchanged.  The KV +11.2 ps
leaf-row (j odd vs even) offset is NOT an encoding artifact of this emitter: five geometry-equivalent encodings of
the shared opposite-drop VIA89 (first drop continuing the via path; M9 point junction at the via; M9 point junction
1 dbu along the first drop; trunk split so the shared root is a path end; second drop emitted first) and
-max_res 0 / -no_merge_via_res all give the same n10 SPEF on b7, while emitting the second drop first REVERSES the
sign (j0 - j1 = +9.8 ps).  OpenRCX's resistor graph for two opposite M9 drops from ONE trunk via depends on wire
order; the structural fix is geometric in the builder (each leaf-row drop on its own via/track, as the even
legs already are).  Probes: /srv/opentallas-scratch2/claude/clock-kv-r12-1026/rcxfix."""
import json, sys
from pathlib import Path

b, out = Path(sys.argv[1]), Path(sys.argv[2])
HERE = Path(__file__).resolve().parent
tools = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE
sys.path.insert(0, str(tools))
import clock_routed as CR

_emit0 = CR._emit_steps


def _emit_expand(L, pts, final_junction=False):
    """KV port joins go M9 -> M7 at one point (leg on M9, tap pin on M7): expand every multi-layer jump into the via
    stack between (CR.via only knows adjacent pairs).  Pure geometry, same point."""
    ex = [pts[0]]
    for p in pts[1:]:
        l0, l1 = CR.LAYERS.index(ex[-1][0]), CR.LAYERS.index(p[0])
        if abs(l1 - l0) > 1 and (ex[-1][1], ex[-1][2]) == (p[1], p[2]):
            st = 1 if l1 > l0 else -1
            for k in range(l0 + st, l1, st):
                ex.append((CR.LAYERS[k], p[1], p[2]))
        ex.append(p)
    return _emit0(L, ex, final_junction)


CR._emit_steps = _emit_expand

M = json.loads((b / "mesh.json").read_text())
cells = json.loads((b / "place.json").read_text())
ports = {t["port"]: dict(layer=t.get("layer", M["meta"].get("tap_layer", "M7")), xy=t["xy"]) for t in M["taps"]}
ports["root"] = dict(layer="M9", xy=list(M["meta"]["root_um"]))
lines, rec = CR.routed_tcl(M["fixed_wires"], cells, ports, CR.BUF_DEFAULT, "ot_mesh_ndr")
rules = next(p for p in (tools / "asap7_rcx_ndr016.rules", tools / "rcx" / "asap7_rcx_ndr016.rules")
             if p.exists()).read_text()
out.mkdir(parents=True, exist_ok=True)
(out / "rcx_ndr.rules").write_text(rules)
names = [w["name"] for w in M["fixed_wires"]]
(out / "rcx_nets.txt").write_text("\n".join(names) + "\n")
pre = r"""# GENERATED by kv_r9/rcx/kv_rcx.py (CLOCK-KV-R9): special fixed clock nets -> FIXED regular dbWires, ndr016 OpenRCX
set t0 [clock seconds]
read_db /b/combo_TT.odb
set blk [ord::get_db_block]; set tech [ord::get_db_tech]
set fh [open /out/rcx_nets.txt r]; set nsw 0
foreach nm [split [string trim [read $fh]] "\n"] { set n [$blk findNet $nm]; if {$n == "NULL"} { error "missing $nm" }
  foreach sw [$n getSWires] { odb::dbSWire_destroy $sw; incr nsw } }
close $fh
puts "OT_SWIRES_DESTROYED $nsw"
"""
post = "\n".join([
    'set nn 0; set nw 0; set nsp 0',
    'foreach n [$blk getNets] { if {[$n getSigType] eq "CLOCK"} { incr nn; if {[$n getWire] != "NULL"} { incr nw }; if {[$n isSpecial]} { incr nsp } } }',
    'puts "OT_CLOCK_NETS $nn with_wire $nw special $nsp"',
    'puts "OT_T encode [expr {[clock seconds]-$t0}]"',
    CR.rcx_tcl("ndr", rules),
    'write_spef /out/rcx.spef',
    'puts "OT_T rcx [expr {[clock seconds]-$t0}]"',
    'write_db /out/routed.odb',
    'puts OT_DONE'])
(out / "rcx.tcl").write_text(pre + "\n".join(lines) + "\n" + post + "\n")
sta = r"""# tree arrivals, one corner x one SPEF basis (same report as die_clock_mesh combo tree_<corner>.txt)
foreach f [glob $::env(LIBDIR)/*RVT_$::env(CORNER)_nldm*.lib*] { read_liberty $f }
read_db /out/routed.odb
read_spef /out/$::env(BASIS).spef
foreach c [get_cells -quiet ckm_d_*] { set_disable_timing $c }
create_clock -name vclk -period 833.000
set_driving_cell -lib_cell BUFx24_ASAP7_75t_R -pin Y [get_ports root]
set_input_delay 0 -clock vclk [get_ports root]
set_load 3.0 [get_ports t_*]
report_checks -path_delay min_max -format end
set fh [open /out/tree_$::env(CORNER)_$::env(BASIS).txt w]
foreach c [get_cells ckm_d_*] { set p [get_pins [get_full_name $c]/A]; puts $fh "D [get_full_name $c] [get_property $p arrival_max_rise] [get_property $p arrival_min_rise] [get_property $p slew_max_rise]" }
foreach c [get_cells {ckm_n* ckm_r*}] { set p [get_pins [get_full_name $c]/Y]; puts $fh "N [get_full_name $c] [get_property $p arrival_max_rise] [get_property $p arrival_min_rise] [get_property $p slew_max_rise]" }
close $fh
report_check_types -max_slew -max_capacitance -violators
puts OT_DONE
"""
(out / "sta.tcl").write_text(sta)
json.dump(dict(rec={k: v for k, v in rec.items() if k != "extra_top"}, extra_top=len(rec["extra_top"]), nets=len(names)),
          open(out / "encode_rec.json", "w"), indent=1)
print("nets", len(names), {k: v for k, v in rec.items() if k != "extra_top"}, "extra_top", len(rec["extra_top"]))
