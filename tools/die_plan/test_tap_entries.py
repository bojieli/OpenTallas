# tiny_plan 'mid': 864 x 864 um, R4 grid taps clk (144, 144) .. clk_t8 (720, 720); clk_t4 at (432.48, 432.032)
TENTRY = dict(name='clk_rgn0', tap='clk_t4', take_taps=['clk_t4', 'clk_t5'], xy_um=[600.0, 440.0], stations_um=[],
              cell='BUFx24_ASAP7_75t_R', region_um=[[500.0, 400.0, 700.0, 480.0]], evidence='unit test regional entry')


def tplan(*rows, base=plan):
    p = base()
    p.types['mid']['clock']['tap_entries'] = [dict(copy.deepcopy(TENTRY), **r) for r in (rows or ({},))]
    return p


def test_absent_tap_entries_keep_pad_entry_output():
    assert PC.tap_entries(plan(), 'mid') == [] and PC.entries_tcl(plan(), 'mid') == ''
    tcl = PC.entries_tcl(eplan(), 'mid')
    assert 'tap_entries' not in tcl and tcl.startswith('# GENERATED by tools/die_plan/gen.py phys (plan clock.pad_clock')
    assert tcl.count('\n  {') == 1                     # one 7-field RCK2 row, no tap note


def test_tap_entry_validates_and_emits_8th_field():
    (tap, e), = PC.tap_entries(tplan(), 'mid')
    assert tap == 'clk_t4' and e['name'] == 'clk_rgn0'
    tcl = PC.entries_tcl(tplan(), 'mid')
    assert 'LEAF-CLKENTRY-1109' in tcl and 'source /work/pad_clock_entry.tcl' in tcl
    assert ('{clk_t4 clk_rgn0 BUFx24_ASAP7_75t_R {} {600.0000 440.0000} {{500.0000 400.0000 700.0000 480.0000}} {} '
            '{clk_t4 clk_t5}}') in tcl
    both = PC.entries_tcl(tplan(base=eplan), 'mid')    # pad rows first (unchanged), then tap rows
    assert both.index('{pma_rck pma_rck_e1') < both.index('{clk_t4 clk_rgn0')


@pytest.mark.parametrize('fault', ['extra-key', 'unknown-tap', 'tap-not-taken', 'unknown-take', 'long-hop', 'outside',
                                   'port-name', 'dup-name', 'overlap', 'bad-region', 'no-evidence', 'in-macro'])
def test_bad_tap_entry_fails_closed(fault, monkeypatch):
    rows = [{}]
    if fault == 'extra-key': rows = [dict(note='x')]
    if fault == 'unknown-tap': rows = [dict(tap='clk_t99', take_taps=['clk_t99'])]
    if fault == 'tap-not-taken': rows = [dict(take_taps=['clk_t5'])]
    if fault == 'unknown-take': rows = [dict(take_taps=['clk_t4', 'clk_c0'])]
    if fault == 'long-hop': rows = [dict(xy_um=[850.0, 440.0])]                 # 417.5 + 7.97 um > 405
    if fault == 'outside': rows = [dict(stations_um=[[600.0, 440.0]], xy_um=[870.0, 440.0])]
    if fault == 'port-name': rows = [dict(name='clk_t7')]
    if fault == 'dup-name': rows = [{}, dict(region_um=[[0.0, 0.0, 10.0, 10.0]])]
    if fault == 'overlap': rows = [{}, dict(name='clk_rgn1', region_um=[[690.0, 470.0, 720.0, 500.0]])]
    if fault == 'bad-region': rows = [dict(region_um=[[700.0, 400.0, 500.0, 480.0]])]
    if fault == 'no-evidence': rows = [dict(evidence=' ')]
    if fault == 'in-macro':
        monkeypatch.setattr(placement_obstacles, 'placement_boxes', lambda t, halo=0.0: {'m': (550.0, 420.0, 650.0, 460.0)})
    with pytest.raises(ValueError):
        PC.tap_entries(tplan(*rows), 'mid')


