def _delta():
    path = HERE.parents[1] / 'physical' / 'die_plan' / 's81' / 'delta_leaf_clkentry_1109.py'
    spec = importlib.util.spec_from_file_location('delta_leaf_clkentry_1109', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_delta_field_geometry_t21_order():
    D = _delta()
    B = {D.I['vna']: [552.96, 699.84, 909.36, 864.0], D.I['vnb']: [544.32, 881.28, 900.72, 1054.08],
         D.I['b0']: [708.48, 648.0, 877.85, 677.16], D.I['b1']: [725.76, 596.16, 895.13, 625.32]}
    fg = D.field_geometry(B)
    assert fg['strip'] == [552.96, 864.0, 900.72, 881.28] and fg['strip_gap_um'] == 17.28
    assert fg['band'] == [552.96, 596.16, 895.13, 699.84] and fg['band_gap_um'] == 22.68
    assert fg['band_xy'][1] == 688.5
    flip = dict(B, **{D.I['vnb']: [544.32, 500.0, 900.72, 590.0]})   # vn_b not over vn_a: mirrored field, no entries
    assert D.field_geometry(flip) is None


def test_delta_trunk_points_within_reach():
    D = _delta()
    pts = D.l_points([541.088, 766.304], [541.088, 872.64], [726.84, 872.64], 1)
    assert pts == [[726.84, 872.64]] and D.HOP_UM < PC.ENTRY_HOP_UM
    pts = D.l_points([0.0, 0.0], [0.0, 500.0], [300.0, 500.0], 2)
    assert pts == [[0.0, 400.0], [300.0, 500.0]]
    assert D.CHANNEL_UM == 3 * D.CLEAR and D.CELL == 'BUFx24_ASAP7_75t_R'


