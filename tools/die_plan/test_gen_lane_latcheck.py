def test_nested_ternary_width_and_optional_port():
    import port_bind_gate as P
    assert P._width("[(RSTREP > 0 ? RSTREP : 1)-1:0]", {"RSTREP": "19"}) == 19
    assert P._width("[(RSTREP > 0 ? RSTREP : 1)-1:0]", {"RSTREP": "0"}) == 1
    for bad in ("[__import__(1):0]", "[a=1:0]", "[(1 ? 2):0]"):
        try:
            P._width(bad, {})
            raise AssertionError(bad)
        except ValueError:
            pass
    master = ("module m #(parameter int RSTREP = 0) (input wire a, input wire [(RSTREP > 0 ? RSTREP : 1)-1:0] x);\n"
              "endmodule\n")
    w0 = {"w.sv": "module w (input wire a);\n    m u_0 (.a(a));\nendmodule\n"}
    w3 = {"w.sv": "module w (\n    input wire a,\n    input wire [2:0] q\n);\n    m #(.RSTREP(3)) u_3 (.a(a));\n"
                  "    m #(.RSTREP(3)) u_4 (.a(a), .x(q));\nendmodule\n"}
    assert P.nested_check(w0, [master])["verdict"] == "FAIL"
    opt = [("m", "x", "RSTREP", 0)]
    r = P.nested_check(w0, [master], optional_ports=opt)
    assert r["verdict"] == "PASS" and r["optional_open"] == 1
    r = P.nested_check(w3, [master], optional_ports=opt)
    assert r["verdict"] == "FAIL" and r["unbound"] == 1 and r["width_mismatch"] == 0 and r["unresolved"] == 0


def _rec(delta, src_kit=0, rcv_kit=0, rcv_bound=0):
    return {"lane": "L", "verdict": "FAIL", "delta": delta, "class": ["OTHER"], "problems": [],
            "source": {"kit_ist": src_kit, "bound_ist": 0}, "receiver": {"kit_ist": rcv_kit, "bound_ist": rcv_bound}}


def test_fixed_in_core_with_observed_kit_stations():
    """HEAD-99 11-15: host_rx = fixed 2, one kit station already delivered -> delta -1 passes; coll_HOST1_d fixed 2, none -> -2."""
    import gen_lane_latcheck as G
    plan = {"lanes": [{"id": "L", "fixed_cycles": 2}]}
    for delta, kit, ok in ((-1, 1, True), (-2, 0, True), (-2, 1, False), (-1, 0, False), (0, 2, True), (-3, 0, False)):
        recs = [_rec(delta, 0, kit)]
        G.reclassify(plan, recs, ["LANE_ASBUILT L: x"], True)
        assert (recs[0]["verdict"] == "PASS") is ok, (delta, kit)
    recs = [_rec(-1, 0, 0, 1)]          # z20NC host_rx: the hd_ctl station is realised in the wrapper = bound_ist 1
    G.reclassify(plan, recs, [], True)
    assert recs[0]["verdict"] == "PASS"
    recs = [_rec(-1, 0, 1)]
    G.reclassify(plan, recs, [], False)           # not opt-in: still FAIL
    assert recs[0]["verdict"] == "FAIL"


def test_realized_check_refuses_plan_only_cycles(tmp_path):
    """LATCHECK-REALIZED-1122 (HEAD hd_lep0N L2/L4): a station row on a non-realize type + lane fixed_cycles +1 with no RTL change"""
    base_d = rtl(tmp_path)
    base = plan(cycles=5, fixed=1)
    new = plan(cycles=6, fixed=2)
    new["partition_types"]["A"]["internal_stations"] = [dict(conn="bus:o", launch="u_core.o", regs_um=[[1, 1]])]
    d2 = tmp_path / "new"
    d2.mkdir()
    for f in base_d.iterdir():
        (d2 / f.name).write_bytes(f.read_bytes())
    recs, errs, _ = G.run(new, [d2], fixed_in_core=True)
    assert errs == []                                                  # the old check passes it (the gap)
    recs, errs, _ = G.run(new, [d2], fixed_in_core=True, base_plan=base, base_rtl=[base_d])
    assert any(e.startswith("UNREALIZED_STATION_ROW A bus:o") for e in errs)
    assert any(e.startswith("UNREALIZED_PLAN_CYCLES L:") for e in errs) and recs[0]["verdict"] == "FAIL"
    # the same change with the stage really in the RTL (module text changed) is not refused by this check
    (d2 / "m_a.sv").write_text((d2 / "m_a.sv").read_text().replace("endmodule", "    // core stage o +1\nendmodule"))
    recs, errs, _ = G.run(new, [d2], fixed_in_core=True, base_plan=base, base_rtl=[base_d])
    assert not any(e.startswith("UNREALIZED") for e in errs)
    recs, errs, _ = G.run(base, [base_d], fixed_in_core=True, base_plan=base, base_rtl=[base_d])
    assert errs == []                                                  # no change vs base: unchanged verdict
