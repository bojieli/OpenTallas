"""HEAD-BIND-1: gen_lane_latcheck (LATCHECK-1 on plan-generated wrappers) and head_gen_cohort."""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_lane_latcheck as G  # noqa: E402

HDR = "// GENERATED by tools/die_plan/gen.py rtl from die_plan t, partition type {t}.  Do not edit.\n"


def plan(cycles=4, fixed=None, stations=2):
    ln = dict(id="L", ports=["p0", "p1"])
    if fixed:
        ln["fixed_cycles"] = fixed
    return dict(
        die=dict(name="t"),
        partition_types=dict(
            A=dict(module="m_a", buses=[dict(name="o", dir="out", width=4)]),
            F=dict(module="m_f", ft_slots=[dict(name="t", width=4, stations=stations)]),
            B=dict(module="m_b", buses=[dict(name="i", dir="in", width=4)])),
        partitions=[dict(name="a", type="A"), dict(name="f", type="F"), dict(name="b", type="B")],
        ports=[dict(id="p0", src=dict(part="a", bus="o"), dst=dict(part="f", bus="t_i"), width=4),
               dict(id="p1", src=dict(part="f", bus="t_o"), dst=dict(part="b", bus="i"), width=4)],
        lanes=[ln],
        latency=dict(lanes=dict(L=dict(cycles=cycles))))


def rtl(tmp, stations=2, src_ist=0):
    d = tmp / "rtl"
    d.mkdir()
    st = "    ot_dp_st #(.W(4)) u_{n} (.clk(clk), .d(x), .q(y));\n"
    (d / "m_a.sv").write_text(HDR.format(t="A") + "module m_a ();\n" + st.format(n="bout_o")
                              + "".join(st.format(n=f"ist_o_{j}") for j in range(src_ist)) + "endmodule\n")
    (d / "m_f.sv").write_text(HDR.format(t="F") + "module m_f ();\n"
                              + "".join(st.format(n=f"ft_t_s{j}") for j in range(stations)) + "endmodule\n")
    (d / "m_b.sv").write_text(HDR.format(t="B") + "module m_b ();\n" + st.format(n="bin_i") + "endmodule\n")
    return d


def test_pass_counts_gen_ft_names(tmp_path):
    recs, errs, _ = G.run(plan(), [rtl(tmp_path)])
    assert errs == [] and recs[0]["verdict"] == "PASS" and recs[0]["ft"] == 2 and recs[0]["delivered"] == 4


def test_station_mutant_fails(tmp_path):
    recs, errs, _ = G.run(plan(), [rtl(tmp_path, stations=3)])
    assert recs[0]["verdict"] == "FAIL" and recs[0]["delta"] == 1 and len(errs) == 1


def test_landing_cycles_counted(tmp_path):
    recs, errs, _ = G.run(plan(cycles=6), [rtl(tmp_path)], dict(lane_added_cycles=dict(L=2)))
    assert errs == [] and recs[0]["landing"] == 2


def test_fixed_in_core_opt_in(tmp_path):
    d = rtl(tmp_path)
    recs, errs, _ = G.run(plan(cycles=5, fixed=1), [d])
    assert recs[0]["verdict"] == "FAIL" and errs
    recs, errs, _ = G.run(plan(cycles=5, fixed=1), [d], fixed_in_core=True)
    assert errs == [] and recs[0]["verdict"] == "PASS" and recs[0]["fixed_in_core"] == 1


def test_unpriced_plan_stations_class(tmp_path):
    recs, errs, _ = G.run(plan(), [rtl(tmp_path, src_ist=2)], fixed_in_core=True)
    assert recs[0]["verdict"] == "FAIL" and recs[0]["delta"] == 2
    assert recs[0]["class"] == ["PLAN_STATIONS_UNPRICED"] and len(errs) == 1


def test_missing_wrapper_unobserved_and_first_dir_wins(tmp_path):
    d = rtl(tmp_path)
    (d / "m_b.sv").unlink()
    recs, errs, _ = G.run(plan(), [d])
    assert recs[0]["verdict"] == "UNOBSERVED" and errs == []
    d2 = tmp_path / "pub"
    d2.mkdir()
    (d2 / "m_b.sv").write_text(HDR.format(t="B") + "module m_b ();\n    ot_dp_st u_bin_i (.d(x));\nendmodule\n")
    recs, errs, src = G.run(plan(), [d2, d])
    assert recs[0]["verdict"] == "PASS" and src["m_b"].endswith("pub/m_b.sv")


def test_cli_exit_codes(tmp_path):
    d = rtl(tmp_path)
    p = tmp_path / "plan.json"
    p.write_text(json.dumps(plan()))
    r = subprocess.run([sys.executable, str(HERE / "gen_lane_latcheck.py"), str(p), "--rtl", str(d),
                        "--json", str(tmp_path / "o.json"), "--tsv", str(tmp_path / "o.tsv")], capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr
    assert json.loads((tmp_path / "o.json").read_text())["summary"]["verdict"] == "PASS"
    p.write_text(json.dumps(plan(cycles=3)))
    r = subprocess.run([sys.executable, str(HERE / "gen_lane_latcheck.py"), str(p), "--rtl", str(d)],
                       capture_output=True, text=True)
    assert r.returncode == 4 and "LANE_ASBUILT L:" in r.stdout


def test_head_gen_cohort(tmp_path):
    sys.path.insert(0, str(HERE.parent / "s81_head"))
    import head_gen_cohort as C
    prep, gen = tmp_path / "prep", tmp_path / "gen"
    (prep / "published").mkdir(parents=True)
    gen.mkdir()
    (prep / "source_plan.json").write_text(json.dumps(dict(partition_types=dict(A=dict(module="m_a")))))
    (gen / "m_a.sv").write_text("// gen\nmodule m_a (input wire x);\nendmodule\n")
    (prep / "published" / "m_a.sv").write_text("module m_a (input  wire x);  // other comment\nendmodule\n")
    assert C.compare(prep, gen)["verdict"] == "PASS"
    (prep / "published" / "m_a.sv").write_text("module m_a (input wire y);\nendmodule\n")
    rep = C.compare(prep, gen)
    assert rep["verdict"] == "FAIL" and rep["rows"][0]["verdict"] == "DIFF"
