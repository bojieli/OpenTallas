HDR = "// GENERATED by tools/die_plan/gen.py rtl from die_plan t, partition type {t}.  Do not edit.\n"


def plan(cycles=4, fixed=None, stations=2):
    ln = dict(id="L", ports=["p0", "p1"])
    if fixed:
        ln["fixed_cycles"] = fixed
    return dict(
        die=dict(name="t"),
        partition_types=dict(
            A=dict(module="m_a", buses=[dict(name="o", dir="out", width=4)]),
            F=dict(module="m_f", ft_slots=[dict(name="t", width=4, stations=stations)]),
            B=dict(module="m_b", buses=[dict(name="i", dir="in", width=4)])),
        partitions=[dict(name="a", type="A"), dict(name="f", type="F"), dict(name="b", type="B")],
        ports=[dict(id="p0", src=dict(part="a", bus="o"), dst=dict(part="f", bus="t_i"), width=4),
               dict(id="p1", src=dict(part="f", bus="t_o"), dst=dict(part="b", bus="i"), width=4)],
        lanes=[ln],
        latency=dict(lanes=dict(L=dict(cycles=cycles))))


def rtl(tmp, stations=2, src_ist=0):
    d = tmp / "rtl"
    d.mkdir()
    st = "    ot_dp_st #(.W(4)) u_{n} (.clk(clk), .d(x), .q(y));\n"
    (d / "m_a.sv").write_text(HDR.format(t="A") + "module m_a ();\n" + st.format(n="bout_o")
                              + "".join(st.format(n=f"ist_o_{j}") for j in range(src_ist)) + "endmodule\n")
    (d / "m_f.sv").write_text(HDR.format(t="F") + "module m_f ();\n"
                              + "".join(st.format(n=f"ft_t_s{j}") for j in range(stations)) + "endmodule\n")
    (d / "m_b.sv").write_text(HDR.format(t="B") + "module m_b ();\n" + st.format(n="bin_i") + "endmodule\n")
    return d


