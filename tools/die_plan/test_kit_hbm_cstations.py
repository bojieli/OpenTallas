@pytest.mark.skipif(not YOSYS, reason="no yosys")
def test_proof_sat_base_proves_and_missing_extra_stage_fail(tmp_path):
    out, _, rep, _ = run()
    (tmp_path / "orig.sv").write_text(BOUND)
    (tmp_path / "kit.sv").write_text(out)
    cells = tmp_path / "cells.sv"
    import re
    cells.write_text(re.search(r"module ot_dp_dly\b.*?endmodule", (HERE / "bind.py").read_text(), re.S).group(0) + "\n")
    rc = PR.main([str(tmp_path / "orig.sv"), str(tmp_path / "kit.sv"), str(_receipt(tmp_path, rep)),
                  "--cells", str(cells), "--out", str(tmp_path / "pf"), "--run", "--jobs", "2"])
    v = json.loads((tmp_path / "pf" / "verdict.json").read_text())
    assert rc == 0 and v["bad"] == [] and v["cases"] == 9, v
    exp = {c["dir"]: c["expect"] for c in json.loads((tmp_path / "pf" / "cases.json").read_text())["cases"]}
    assert all((v["rc"][d] == 0) == (e == "PROVE") for d, e in exp.items())
    assert sum(e == "FAIL" for e in exp.values()) == 6
