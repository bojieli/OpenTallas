def test_opt_in_off_by_default(tmp_path):
    import kit_istations
    t = plan()
    t.pop("hbm_core_stations")
    t["internal_stations"] = [e for e in t["internal_stations"] if not e["conn"].startswith("bus:")]
    t["buses"] = []
    raw = dict(partition_types=dict(hub=t))
    (tmp_path / "plan.json").write_text(json.dumps(raw))
    kd = tmp_path / "kit"
    kd.mkdir()
    (kd / "hub_bound.sv").write_text(BOUND)
    (kd / "kit_rtl.json").write_text(json.dumps(dict(files=[str(kd / "hub_bound.sv")], bound_module="hub_bound")))
    import io, contextlib
    with contextlib.redirect_stdout(io.StringIO()):
        kit_istations.main([str(tmp_path / "plan.json"), "hub", str(kd)])
    assert (kd / "hub_bound.sv").read_text() == BOUND           # off: bound text untouched
    with contextlib.redirect_stdout(io.StringIO()):
        kit_istations.main([str(tmp_path / "plan.json"), "hub", str(kd), "--hbm-core"])
    assert "u_hcs_" in (kd / "hub_bound.sv").read_text()
    man = json.loads((kd / "kit_rtl.json").read_text())
    assert man["kit_hbm_core_stations"]["classes"]["u_a_Q|u_b"]["depth"] == 3
    assert (kd / "hcs_chains.json").is_file() and "is_place {*u_hcs_0[./]r\\[0\\]*}" in (kd / "istations.tcl").read_text()


def _receipt(tmp_path, rep):
    p = tmp_path / "rcpt.json"
    p.write_text(json.dumps(dict(report=rep)))
    return p


def test_proof_text_checks(tmp_path):
    out, _, rep, _ = run()
    cl, pair = PR.load_classes(_receipt(tmp_path, rep))
    probs, lines, chains = PR.analyse(BOUND, out, pair)
    assert probs == [] and len(lines) == 4 and len(chains) == 5
    # a stationed link left direct (one edited port line reverted) -> missing stage
    import re
    bad = re.sub(r"\.r\(hcs_\d+\[3:0\]\),", ".r(w_u_a_Q_q1_y[3:0]),", out)
    assert bad != out
    pb = PR.analyse(BOUND, bad, pair)[0]
    assert any("missing stage" in p for p in pb) and any("dangling" in p for p in pb)
    # an edit on a line with no stationed link -> extra stage
    bad2 = out.replace("        .p(w_u_d_y[7:0]),", "        .p(hcs_0[3:0]),")
    assert any("extra stage" in p for p in PR.analyse(BOUND, bad2, pair)[0])


