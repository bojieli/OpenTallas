def plan():
    return dict(
        hbm_core_stations=True,
        hard_cores=[dict(inst="u_a_Q__q0", origin_um=[0, 0], outline_um=[10, 10]),
                    dict(inst="u_a_Q__q1", origin_um=[1300, 600], outline_um=[10, 10])],
        contents=[dict(inst="u_a_Q", origin_um=[1000, 0], outline_um=[10, 10]),
                  dict(inst="u_b", origin_um=[1000, 1000], outline_um=[10, 10]),
                  dict(inst="u_c", origin_um=[1000, 2000], outline_um=[10, 10]),
                  dict(inst="u_d", origin_um=[1000, 2400], outline_um=[10, 10])],
        internal_stations=[
            # class u_a_Q|u_b: q0 route 3 stations, q1 route 1 station -> class depth 3, q1 respread on its route
            dict(conn="u_a_Q.y|u_b", launch="u_a_Q.y", capture="u_b", bits=8, from_um=[5, 5], to_um=[1005, 1005],
                 regs_um=[[300, 5], [700, 5], [1005, 400]]),
            dict(conn="u_a_Q.y|u_b", launch="u_a_Q.y", capture="u_b", bits=4, from_um=[1305, 605], to_um=[1005, 1005],
                 regs_um=[[1305, 1005]]),
            # class u_b|u_c (2 stations): both b->c links (z and y) get it
            dict(conn="u_b.z|u_c", launch="u_b.z", capture="u_c", bits=4, from_um=[1005, 1005], to_um=[1005, 2005],
                 regs_um=[[1005, 1300], [1005, 1700]]),
            # planned only in the reverse direction (c -> d): used reversed for the d -> c link
            dict(conn="u_c.y|u_d", launch="u_c", capture="u_d", bits=2, from_um=[1005, 2005], to_um=[1005, 2405],
                 regs_um=[[1005, 2200]]),
            dict(conn="bus:L1_i", regs_um=[[1, 1]]),
        ])


def run(t=None, txt=BOUND):
    return K.realise(t or plan(), txt, "hub")


def test_classes_depths_and_rewrite():
    out, tcl, rep, chains = run()
    cl = rep["classes"]
    assert cl["u_a_Q|u_b"]["depth"] == 3 and cl["u_a_Q|u_b"]["links"] == 2
    assert cl["u_b|u_c"]["depth"] == 2 and cl["u_b|u_c"]["links"] == 2
    assert cl["u_c|u_d"]["depth"] == 1 and cl["u_c|u_d"]["reversed"] is True
    # u_a_Q_q0 -> u_c has no plan entry: unplanned, left direct
    assert rep["unplanned_links"]["links"] == 1 and "w_u_a_Q_q0_y[1:0]" in out.split("leafC u_u_c")[1].split(");")[0]
    # self loop of u_d is never stationed
    assert rep["skipped_items"] == {"self_loop": 1}
    assert ".p({hcs_0[3:0], 4'b0000})" in out or ".p({hcs_" in out
    assert "{2{1'b0}}" in out                         # replication item kept verbatim
    assert rep["register_bits"] == 4 * 3 + 4 * 3 + 4 * 2 + 2 * 2 + 2 * 1
    # one FIRM site per stage
    assert len(tcl) == sum(c["D"] for c in chains)
    q1 = next(c for c in chains if c["src"] == "u_u_a_Q_q1")
    assert q1["own_depth"] == 1 and q1["D"] == 3 and q1["worst_hop_um"] == 175.0
    q0 = next(c for c in chains if c["src"] == "u_u_a_Q_q0" and c["sink"] == "u_u_b")
    assert q0["sites"] == [[300, 5], [700, 5], [1005, 400]]
    rev = next(c for c in chains if c["cls"] == "u_c|u_d")
    assert rev["sites"] == [[1005, 2200]]


