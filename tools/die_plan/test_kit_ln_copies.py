def _dir(tmp):
    (tmp / f"ot_bind_native_{H}.sv").write_text(NAT)
    return [tmp]


def test_absent_is_byte_identical(tmp_path):
    for cfg in (None, False, {}):
        t, m, r = K.apply(BOUND, cfg, _dir(tmp_path))
        assert t == BOUND and m == "" and r is None


def test_copies_and_relay(tmp_path):
    t, m, r = K.apply(BOUND, True, _dir(tmp_path))
    assert r["cycles_changed"] == 0
    assert f"ot_bind_native_{H} g_u_vp_cf" not in t and "w_u_vp_cf_RD_DATA" not in t
    assert r["cf"]["readers"] == 2 and [c["words"] for c in r["cf"]["copies"]] == [[0, 3], [1, 3]]
    assert t.count("g_lnc_w_x0_Y") == 1 and t.count("g_lnc_w_x1_Y") == 1
    assert "assign w_x0_Y = {lnc_w_x0_Y_RD[3:0], lnc_w_x0_Y_RD[7:4]};" in t
    assert m.count("(* keep = \"true\" *) reg") == 4 and m.count("module ot_lnc_") == 2
    assert "w3[0] <= WR_DATA[0]" in m and "if (WR_EN[4] && WR_ADDR[7:4] == 32'd3) w3[0] <= WR_DATA[4];" in m
    assert "ot_bind_native_" not in m          # bind.py kit_native_glue must not re-add the removed helper
    assert ".REGIONS(4)" in t and "wire [3:0] w_u_vp_u_rr_rst_n;" in t
    assert ".rst_n(w_u_vp_u_rr_rst_n[2])" in t.split("u_u_vp_g_ln_0_u_l")[1].split(");")[0]
    assert ".rst_n(w_u_vp_u_rr_rst_n[3])" in t.split("u_u_vp_g_ln_1_u_l")[1].split(");")[0]
    r["cf"]["native_file"] = str(tmp_path / f"ot_bind_native_{H}.sv")
    ok, why = KP.text_check(BOUND, t, r)
    assert ok, why


def test_fail_closed(tmp_path):
    d = _dir(tmp_path)
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND + "    assign q = w_u_vp_cf_RD_DATA;\n", True, d)              # whole-vector read
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND.replace("w_u_vp_cf_RD_DATA[15:12]", "w_u_vp_cf_RD_DATA[14:11]"), True, d)   # not one word
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND.replace(".rst_n(w_u_vp_2_Y[0]),\n        .o(o0)", ".rst_n(w_u_vp_u_rr_rst_n[0]),\n        .o(o0)"),
                True, d)                                                                  # lanes on two relay bits
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND, {"bogus": 1}, d)
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND, True, [tmp_path / "nowhere"])
    bad = tmp_path / "bad"; bad.mkdir()
    (bad / f"ot_bind_native_{H}.sv").write_text(NAT.replace("<= WR_DATA[0];", "<= ~WR_DATA[0];"))
    with pytest.raises(K.LnCopyError):
        K.apply(BOUND, True, [bad])                                                       # unsupported statement


