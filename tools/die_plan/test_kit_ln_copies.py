BENCH = """`timescale 1ns/1ps
module tb;
  reg clk = 0; always #1 clk = ~clk;
  reg [7:0] a, d, e; integer i, bad = 0;
  wire [15:0] G; wire [7:0] C0, C1;
  ot_bind_native_HASH u_g (.RD_DATA(G), .WR_ADDR({a[7:4], 4'b0000}), .WR_CLK({clk, clk}), .WR_DATA(d), .WR_EN(e));
  M0 u_c0 (.RD_DATA(C0), .WR_ADDR({a[7:4], 4'b0000}), .WR_CLK({clk, clk}), .WR_DATA(d), .WR_EN(e));
  M1 u_c1 (.RD_DATA(C1), .WR_ADDR({a[7:4], 4'b0000}), .WR_CLK({clk, clk}), .WR_DATA(d), .WR_EN(e));
  initial begin
    a = 0; d = 0; e = 8'hff;                                  // equal state: write every word bit once
    for (i = 0; i < 4; i = i + 1) begin a = {i[3:0], 4'b0}; @(negedge clk); end
    for (i = 0; i < 4000; i = i + 1) begin
      a = $random; d = $random; e = $random; @(negedge clk);
      if ({G[3:0], G[7:4]} !== C0 || {G[11:8], G[15:12]} !== C1) bad = bad + 1;   // copy word i = consumer slice i
    end
    $display("BAD %0d", bad); $finish;
  end
endmodule
"""


@pytest.mark.skipif(shutil.which("iverilog") is None, reason="iverilog not on PATH")
@pytest.mark.parametrize("mut", [None, "word", "drop"])
def test_lockstep_bench(tmp_path, mut):
    t, m, r = K.apply(BOUND, True, _dir(tmp_path))
    names = [c["module"] for c in r["cf"]["copies"]]
    if mut == "word":
        m = m.replace("assign RD_DATA[3:0] = w0;", "assign RD_DATA[3:0] = w3;", 1)
    if mut == "drop":
        m = m.replace("    if (WR_EN[5] && WR_ADDR[7:4] == 32'd1) w1[1] <= WR_DATA[5];\n", "", 1)
    (tmp_path / "c.sv").write_text(m)
    (tmp_path / "tb.sv").write_text(BENCH.replace("HASH", H).replace("M0", names[0]).replace("M1", names[1]))
    exe = tmp_path / "a.out"
    subprocess.run(["iverilog", "-g2012", "-o", str(exe), str(tmp_path / "tb.sv"), str(tmp_path / "c.sv"),
                    str(tmp_path / f"ot_bind_native_{H}.sv")], check=True)
    out = subprocess.run(["vvp", str(exe)], capture_output=True, text=True, check=True).stdout
    bad = int(out.split("BAD ")[1].split()[0])
    assert (bad == 0) == (mut is None), out
