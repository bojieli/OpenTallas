"""HBM d44v SU Q0/Q1 lane_exp as-built manifest candidate (DIE-HBM-92-SU-EXP 11-08); never edits a plan or the base.

The plan names u_su_Q<q>_lane_exp<N>.u_fcore.u_core.{u_l,u_s} (q 0/1): the p18 re-form of the lane_exp cores
(results/die_hbm_1104/reform_a/part18, d3f6c84c70): ot_hbm_su_pg_lane_exp_core (N != 0; lane_exp0 excluded, see EXCLUDED)
-> u_l = ot_hbm_su_pg_lane_{exp,full}_x_core + u_s = ot_hbm_su_pg_sfu_s_core.  The bind of record composes each cut
su_N[EW]<q>.__cut_lane_exp<N> flat (ot_hnx_su_exp__rst3), so the kits have no instance at the plan paths.

This adds one compose_split rule per core kind (bind_compose_split, re-formed sub-core):
  module        REFERENCE = the uncut core (as-built leaves pinned_bank + lane_pinreg): the cut members are regrouped
                under it exactly (fail closed, leaf modules/parameters, every bit)
  emit_module   <core>__p18bind (generated here, same ports as the reference): u_l = the signed master's one-clock
                wrapper (recipe wrapper_by_pins_sha256 of the plan pin table) + u_s, seam wires only, as the bench
                composition <core>__splitx without the bench face-shell models (the kit adds the face flops)
  emit_proof    the part18 XEQ bench (reference vs composition; MUT 0 PASS, mutants 1-5 FAIL) and its declared
                added cycles (SFU_EXP/SIGM/SILU and S-chain fault +4), log shas
  same_net      bank_clk / bank_clk_macro / lane_clk_stage / lane_clk_insert one cut net (the wrapper merges them)
and sub_core_leaf u_su_Q<q>_lane_exp<N> -> su_NE<q>.__cut_lane_exp<N> (variant su_NW<q>), replacing the base's
identity rows (no as-built path of that name exists in the bound files).
"""
import argparse
import copy
import hashlib
import json
import re
import shutil
from pathlib import Path

LX = "rtl/hbm_accel/cores_split/reform_1104a/lane_x"
REF_DIR = "rtl/hbm_accel/cores_split/ot_hbm_su_static_pgslice_lg"
ONECLK = "physical/die_plan/hbm_arch_cores/wrappers/oneclk"
P18 = "results/die_hbm_1104/reform_a/part18"
KINDS = {  # cut regex suffix -> (reference core, x core, bench log)
    "exp": ("ot_hbm_su_pg_lane_exp_core", "ot_hbm_su_pg_lane_exp_x_core", "eq_canon.log", r"(?:[1-9]\d*|_l)"),
}
# lane_exp0 is NOT bound here: the plan's u_l is ot_hbm_su_pg_lane_full_x_core (lane_full_core, lane KIND 2 FULL), but
# every as-built su_N[EW][01] g_lane[0] is KIND 1 (HBM-044 (A): side unit removed); the exact regroup refuses it
# (parameter KIND=1 != sub-core KIND=2).  Fix = plan event (exp0 hard core -> lane_exp_x_core), not a bind rule.
EXCLUDED = {"0": "plan lane_full_x_core (KIND 2) vs as-built lane KIND 1: plan event needed"}
SFU = "ot_hbm_su_pg_sfu_s_core"
CLOCKS = ["bank_clk", "bank_clk_macro", "lane_clk_stage", "lane_clk_insert"]
QUAD = {"0": ("su_NE0", "su_NW0"), "1": ("su_NE1", "su_NW1")}
LANE_EXP = re.compile(r"(u_su_Q([01])_lane_exp(\d+|_l))\.u_fcore\.u_core\.u_[ls]")
_PORT = re.compile(r"(input|output)\s+wire\s+(\[[^\]]*\]\s*)?(\w+)")


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def ports_of(text, mod):
    m = re.search(r"module\s+" + mod + r"\s*(?:#\s*\(.*?\)\s*)?\((.*?)\n\);", text, re.S)
    if not m:
        raise ValueError(f"no port list for {mod}")
    return [(d, (w or "").strip(), n) for d, w, n in _PORT.findall(m.group(1))]


def composition(ref, ref_text, x, wrap_text):
    """<ref>__p18bind: the reference's ports; u_l = x (one-clock wrapper ports), u_s = sfu_s_core; seam wires only."""
    rp = ports_of(ref_text, ref)
    rw = {n: w for _, w, n in rp}
    conns = []
    for d, w, n in ports_of(wrap_text, x):
        if n == "clk":
            conns.append(".clk(bank_clk)")
        elif n.startswith("sx_"):
            conns.append(f".{n}({n})")
        elif n in rw and rw[n] == w:
            conns.append(f".{n}({n})")
        else:
            raise ValueError(f"{x}.{n} {w}: not a reference port of the same range")
    comp = ref + "__p18bind"
    decl = ",\n".join(f"    {d} wire {w + ' ' if w else ''}{n}" for d, w, n in rp)
    body = ",\n        ".join(conns)
    return comp, f"""// DIE-HBM-92-SU-EXP 11-08: GENERATED by tools/die_plan/hbm_split_su_exp_asbuilt.py.  Bind form of the HBM d44v
// part 18 re-form of {ref} (same ports): u_l = {x} (the signed master, its one-clock wrapper) and
// u_s = {SFU}, the seam only wires; = {P18} gen_comp.py {ref}__splitx without the bench face-shell
// models (each hard core's kit adds its face flops) and without the bench mutants.  The clock replicas are one net
// (bind same_net check); u_s takes lane_clk_stage[4] as in the bench composition.
`default_nettype none
module {comp} (
{decl}
);
    wire sx_v, sx_fault;
    wire [31:0] sx_r, sx_y_exp, sx_y_div;
    wire [2:0] sx_fn;
    {x} u_l (
        {body});
    {SFU} u_s (.clk(lane_clk_stage[4]), .rst_n(lane_rst_n), .v(sx_v), .R(sx_r), .ci_sfu(sx_fn), .y_exp(sx_y_exp),
        .y_div(sx_y_div), .fault(sx_fault));
endmodule
`default_nettype wire
"""


def stage(source, out):
    src, out = Path(source), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    staged, kinds = [], {}
    for f in (f"{LX}/ot_hbm_su_static_lane_x.sv", f"{LX}/ot_hbm_su_static_lane_pinreg_x.sv", f"{LX}/{SFU}.sv"):
        shutil.copy2(src / f, out / Path(f).name)
        staged.append(str(out / Path(f).name))
    for kind, (ref, x, log, _) in KINDS.items():
        ref_f = out / (ref + ".sv")
        shutil.copy2(src / REF_DIR / (ref + ".sv"), ref_f)
        wrap_f = out / (x + ".sv")
        shutil.copy2(src / ONECLK / (x + ".sv"), wrap_f)
        mc_text = (src / LX / (x + ".sv")).read_text()
        if len(re.findall(r"\bmodule\s+" + x + r"\b", mc_text)) != 1:
            raise ValueError(f"{x}: source must define exactly one {x}")
        mc_f = out / (x + "__mc.sv")
        mc_f.write_text(f"// DIE-HBM-92-SU-EXP 11-08: {LX}/{x}.sv with the core recipe's rename_top {x}__mc "
                        "(recipes_b2.json); otherwise byte-identical.\n" +
                        re.sub(r"\bmodule\s+" + x + r"\b", f"module {x}__mc", mc_text))
        comp, text = composition(ref, ref_f.read_text(), x, wrap_f.read_text())
        comp_f = out / (comp + ".sv")
        comp_f.write_text(text)
        kinds[kind] = dict(ref=str(ref_f), comp=comp, comp_f=str(comp_f),
                           emit=[str(comp_f), str(wrap_f), str(mc_f)], log=str(src / P18 / log))
        staged += [str(wrap_f), str(mc_f), str(comp_f)]
    return staged, kinds


def plan_parents(plan):
    out = set()
    for t in plan["partition_types"].values():
        for h in t.get("hard_cores", []) or []:
            m = LANE_EXP.fullmatch(h.get("physical_inst") or "")
            if m:
                out.add(m.groups())
    return sorted(out)


def candidate(plan, asbuilt, source, stage_dir):
    parents = plan_parents(plan)
    if not [x for x in parents if x[2] not in EXCLUDED]:
        raise ValueError("plan names no SU Q0/Q1 lane_exp sub-cores")
    staged, kinds = stage(source, stage_dir)
    split_rec = json.loads((Path(source) / P18 / "split_p18.json").read_text())
    added = {r["core"]: r.get("added_cycles") for r in split_rec}
    out = copy.deepcopy(asbuilt)
    scl = out.setdefault("sub_core_leaf", {})
    var = out.setdefault("sub_core_leaf_variants", {})
    replaced = {}
    excluded = sorted(p for p, q, n in parents if n in EXCLUDED)
    for parent, q, n in parents:
        if n in EXCLUDED:
            continue
        a, b = QUAD[q]
        leaf = f"{a}.__cut_lane_exp{n}"
        if parent in scl and scl[parent] not in (parent, leaf):
            raise ValueError(f"sub_core_leaf {parent} already maps to {scl[parent]}")
        if scl.get(parent) == parent:
            replaced[parent] = parent
        scl[parent] = leaf
        var[parent] = [f"{b}.__cut_lane_exp{n}"]
    rules = []
    for kind, (ref, x, log, rx) in KINDS.items():
        k = kinds[kind]
        proof = dict(bench=f"{P18}/eq_x.sh (XEQ: reference uncut core in its kit shell vs u_l + u_s in face shells; "
                           "MUT 0 PASS, MUT 1-5 FAIL)", commit="d3f6c84c70", log=f"{P18}/{log}",
                     log_sha256=sha(k["log"]), split=f"{P18}/split_p18.json",
                     added_cycles=sorted({v for v in added.values() if v}))
        rules.append(dict(
            inst=r"su_N[EW][01]\.__cut_lane_exp" + rx, suffix="__p18split", levels=["u_fcore"],
            subs=[dict(name="u_core", module=ref, sources=[k["ref"]],
                       roles={"u_bank": r"\.g_bank\[(\d+)\]\.u_bank$", "u_lane": r"\.g_lane\[(\d+)\]\.g_pr\.u_lane$"},
                       param_diff_ok=["MLAT", "ALAT"], same_net=[CLOCKS],
                       emit_module=k["comp"], emit_sources=k["emit"] + staged[:3], emit_proof=proof)],
            reason=f"d44v p6/p18 split: u_core = {ref} re-formed as {x} + {SFU} (as-built members keep their own "
                   "parameters; MLAT/ALAT differences recorded, pin-cycle lever)"))
    out["compose_split"] = list(out.get("compose_split", [])) + rules
    out["files"] = list(dict.fromkeys(out.get("files", []) + staged))
    out["prefer"] = list(dict.fromkeys(out.get("prefer", []) + staged))
    out["sub_core_leaf_note"] = ((out.get("sub_core_leaf_note") or "") +
                                 f" | DIE-HBM-92-SU-EXP: {len(parents)} lane_exp parents -> su_NE<q>.__cut_lane_exp<N> "
                                 f"(variant su_NW<q>); {len(replaced)} identity rows replaced; not bound: "
                                 f"{excluded} ({EXCLUDED['0']})")
    out["note"] = "DIE-HBM-92-SU p37su_exp: p37su + SU Q0/Q1 lane_exp p18 compose_split | " + out.get("note", "")
    return out


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--plan", required=True)
    p.add_argument("--asbuilt", required=True)
    p.add_argument("--source", required=True)
    p.add_argument("--out", required=True)
    a = p.parse_args()
    if Path(a.out).exists():
        raise SystemExit(f"{a.out} exists: manifests are never edited in place")
    result = candidate(json.loads(Path(a.plan).read_text()), json.loads(Path(a.asbuilt).read_text()), a.source,
                       Path(a.out).resolve().parent / "p37su_exp_sources")
    Path(a.out).write_text(json.dumps(result, indent=2) + "\n")
