          "write_db /work/die_routed.odb",
          "write_verilog /work/6_final.v",
          "if {[catch {define_process_corner -ext_model_index 0 X; "
          "extract_parasitics -ext_model_file $PL/rcx_patterns.rules; write_spef /work/6_final.spef} e]} "
          "{ puts \"OT_RCX_FAIL $e\" }",
          "source $PL/setRC.tcl",
