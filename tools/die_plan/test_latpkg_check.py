import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen  # noqa: E402
import latpkg_check as LP  # noqa: E402


def plan(cyc=5, note=None):
    r = _plan(cyc)
    if note:
        r["partition_types"]["tA"]["note"] = note
    return r


def _plan(cyc):
    return {"die": {"name": "dx", "period_ps": 833},
            "partition_types": {"tA": {"module": "ot_ta"}, "tB": {"module": "ot_tb"}},
            "latency": {"lanes": {"L1": {"cycles": cyc, "param": "LAT_L1"}, "L2": {"cycles": 3, "param": "LAT_L2"}}}}


def write_pkg(d, raw, cyc):
    d.mkdir(parents=True, exist_ok=True)
    dig = LP.plan_digest(raw)
    (d / "dx_latency.json").write_text(json.dumps({"schema": LP.SCHEMA, "die": "dx", "plan_digest": dig,
                                                   "lanes": {"L1": {"cycles": cyc}, "L2": {"cycles": 3}}}))
    (d / "dx_lat_pkg.sv").write_text(f"// GENERATED by tools/die_plan/gen.py latency from die_plan dx (plan digest {dig}). Do not edit.\n"
                                     f"package dx_lat_pkg;\n  localparam int LAT_L1 = {cyc};\n  localparam int LAT_L2 = 3;\nendpackage : dx_lat_pkg\n")


def tree(tmp):
    t = tmp / "tree"
    (t / "tools" / "die_plan").mkdir(parents=True)
    (t / "rtl").mkdir()
    (t / "physical" / "die_plan" / "dx" / "prep_a").mkdir(parents=True)
    return t


def test_digest_equals_gen():
    raw = plan()
    assert LP.plan_digest(raw) == gen.plan_digest(raw)


def test_fresh_package_is_quiet(tmp_path):
    t = tree(tmp_path); pd = t / "physical/die_plan/dx/prep_a"; raw = plan()
    (pd / "p.json").write_text(json.dumps(raw)); write_pkg(pd / "lat", raw, 5)
    out = LP.findings(raw, pd / "p.json", t)
    assert out[-1].startswith("LIST LATPKG files=2 stale=0") and len(out) == 1


def test_copied_forward_package_names_values_and_readers(tmp_path):
    t = tree(tmp_path); pd = t / "physical/die_plan/dx/prep_a"
    old = plan(4); raw = plan(5); raw["partition_types"]["tA"]["note"] = "moved on"
    write_pkg(pd / "lat", old, 4)                                  # the HEAD w3 form: an old package inside the new prep
    (pd / "p.json").write_text(json.dumps(raw))
    (t / "rtl" / "ta.sv").write_text("module ot_ta; import dx_lat_pkg::*; localparam int A = LAT_L1; endmodule\n")
    (t / "tools" / "die_plan" / "cal.py").write_text("p = 'lat/dx_latency.json'\n")
    out = LP.findings(raw, pd / "p.json", t)
    w = [x for x in out if x.startswith("WARN LATPKG")]
    assert len(w) == 2 and not any(x.startswith("FAIL") for x in out)
    sv = next(x for x in w if "_lat_pkg.sv" in x)
    js = next(x for x in w if "_latency.json" in x)
    assert "cycles differ 1" in sv and "types reading it: ['tA']" in sv
    assert "cycles differ 1" in js and "tools/die_plan/cal.py" in js
    assert "stale=2" in out[-1]


def test_die_lat_dir_searched_sibling_preps_not(tmp_path):
    t = tree(tmp_path); dd = t / "physical/die_plan/dx"; pd = dd / "prep_a"; raw = plan()
    (pd / "p.json").write_text(json.dumps(raw))
    write_pkg(dd / "lat", plan(9, "old"), 9)                              # the die's own lat/: searched
    write_pkg(dd / "prep_b" / "lat", plan(8, "older"), 8)                   # another prep's copy: not this plan's
    out = LP.findings(raw, pd / "p.json", t, want_readers=False)
    assert "files=2 stale=2" in out[-1] and all("prep_b" not in x for x in out)


def test_other_die_ignored(tmp_path):
    t = tree(tmp_path); pd = t / "physical/die_plan/dx/prep_a"; raw = plan()
    (pd / "p.json").write_text(json.dumps(raw))
    (pd / "ey_latency.json").write_text(json.dumps({"schema": LP.SCHEMA, "die": "ey", "plan_digest": "0", "lanes": {}}))
    assert LP.findings(raw, pd / "p.json", t)[-1].startswith("LIST LATPKG files=0")


def write_sched(d, raw, cyc, name="nfx_schedule.json"):
    d.mkdir(parents=True, exist_ok=True)
    (d / name).write_text(json.dumps({"schema": LP.SCHED_SCHEMAS[0], "lanes": {"L1": {"raw_cycles": cyc, "cycles": cyc},
                                                                                "L2": {"raw_cycles": 3, "cycles": 3}},
                                      "inputs": {"plan_sha256": "0" * 64}}))


def test_schedule_receipt_stale_warns_closest_only(tmp_path):
    t = tree(tmp_path); pd = t / "physical/die_plan/dx/prep_a"; raw = plan(5)
    (pd / "p.json").write_text(json.dumps(raw))
    write_sched(t / "results/token_pass/head_old_1116", raw, 4)          # the head_nf15b_schedule_1116 form
    write_sched(t / "results/token_pass/head_older_1110", raw, 2)
    out = LP.findings(raw, pd / "p.json", t, want_readers=False)
    w = [x for x in out if x.startswith("WARN LATPKG-SCHED")]
    assert len(w) == 1 and "head_old_1116" in w[0] and "cycles differ 1" in w[0] and "2 receipt(s)" in w[0]
    assert "sched=2 sched_stale=1" in out[-1]


def test_schedule_receipt_current_quiets_history(tmp_path):
    t = tree(tmp_path); pd = t / "physical/die_plan/dx/prep_a"; raw = plan(5)
    (pd / "p.json").write_text(json.dumps(raw))
    write_sched(t / "results/token_pass/head_old_1116", raw, 4)
    write_sched(pd / "sched", raw, 5)                                      # regenerated on the bound plan
    out = LP.findings(raw, pd / "p.json", t, want_readers=False)
    assert not [x for x in out if x.startswith("WARN")] and "sched_stale=0" in out[-1]


