"""m89 form-(d) EQ (X-TIER-OTC 11-12, decomposed): base bound module (gold) vs form-(d) bound module (gate) of one leaf type.

  part A  m89 lane chains: every form-(d) lane ft<s> (gold: N stations in one slot) against the gate bays ft<s>b<j>
          chained bay j out -> bay j+1 in (the die-top net); proven formally (yosys equiv_make/equiv_induct) on a
          two-module extract (stations are ot_dp_st, the real cell).
  part B  reset / clock-landing tree: lines naming the relay tree, the landing collectors or the landing rings; the
          tree is regenerated by reset_tree.py from the tap geometry (bay taps move tap loads), so it is reported by its
          rule line (depth / release) on both sides, not compared line by line.
  part C  everything else: must be textually identical (same lines, same order) -- leaf logic, other ft lanes, buses.

usage: m89_eq.py GOLD.sv GATE.sv OUTDIR       -> OUTDIR/{partC.diff, chain_gold.sv, chain_gate.sv, chain.ys, report.json}
"""
import json, os, re, sys

gold_p, gate_p, out = sys.argv[1:4]
os.makedirs(out, exist_ok=True)
G = open(gold_p).read().splitlines()
D = open(gate_p).read().splitlines()

bays = sorted(set(re.findall(r"\bft(\d+)b\d+_i\b", "\n".join(D))), key=int)          # lanes split into bays
LANE = re.compile(r"\bft(%s)(b\d+)?_(i|o)(_s\d+)?\b|u_ft_ft(%s)(b\d+)?_o_\d+" % ("|".join(bays), "|".join(bays))) if bays else None
TREE = re.compile(r"rst_rl_|cland_|rst_n_t\d+|rst_root_n|landing_(ready|fault)|fclk_in_|OWNER RESET RULE|ot_dp_rrelay|"
                  r"ot_dp_landing_collect|ot_dp_clk_landing|^\s*\.(fault_i|ready_i|clk|fclk|d|q|ready|fault)\(|^\s*\);\s*$")


ST = re.compile(r"ot_dp_st #\(\.W\((\d+)\)\) (u_ft_ft(\d+)(b(\d+))?_o_(\d+)) \(\.clk\(clk\), \.rst_n\(rst_n\), "
                r"\.d\(([^)]*)\), \.ea\(([^)]*)\), \.q\(([^)]*)\), \.eq\(([^)]*)\)\);")


def split(lines):
    a, b, c = [], [], []
    for ln in lines:
        if LANE and LANE.search(ln) and (ST.search(ln) or not re.search(r"cland_|landing_|fclk_in_", ln)):
            a.append(ln)
        elif TREE.search(ln):
            b.append(ln)
        else:
            c.append(ln)
    return a, b, c


ga, gb, gc = split(G)
da, db, dc = split(D)
import difflib
cdiff = list(difflib.unified_diff(gc, dc, "gold.C", "gate.C", lineterm="", n=1))
open(os.path.join(out, "partC.diff"), "w").write("\n".join(cdiff) + "\n")

# part A: extract station instances per lane (gold) and per bay (gate)
lanes = {}
for ln in ga:
    m = ST.search(ln)
    if m:
        lanes.setdefault(m.group(3), {"gold": [], "gate": []})["gold"].append(ln.strip())
for ln in da:
    m = ST.search(ln)
    if m:
        lanes.setdefault(m.group(3), {"gold": [], "gate": []})["gate"].append(ln.strip())

W = {}
for s, v in lanes.items():
    W[s] = int(ST.search(v["gold"][0]).group(1))


def mod(name, s, body, wires, iname):
    w = W[s]
    hdr = [f"module {name} (input wire clk, input wire rst_n, input wire [{w}:0] {iname}, output wire [{w}:0] ft{s}_o);"]
    return hdr + [f"  wire [{w}:0] {x};" for x in wires] + ["  " + b for b in body] + ["endmodule"]


src = ["`default_nettype none"]
ys = [f"read_verilog -sv {os.path.abspath(sys.argv[4]) if len(sys.argv) > 4 else 'bind_cells.sv'}"]
rep = {"lanes": {}, "partC_identical": not cdiff, "partC_gold_lines": len(gc), "partC_gate_lines": len(dc),
       "partB_gold_lines": len(gb), "partB_gate_lines": len(db),
       "partB_rule_gold": [x.strip() for x in gb if "OWNER RESET RULE" in x],
       "partB_rule_gate": [x.strip() for x in db if "OWNER RESET RULE" in x]}
for s, v in sorted(lanes.items(), key=lambda t: int(t[0])):
    gw = sorted(set(re.findall(rf"\bft{s}_o_s\d+\b", "\n".join(v["gold"]))))
    nb = len(v["gate"])
    # gate: bay j in <- bay j-1 out (die-top net); bay 0 in = lane in; last bay out = lane out
    body = []
    for ln in v["gate"]:
        m = ST.search(ln)
        j = int(m.group(5))
        ins = f"ft{s}_i" if j == 0 else f"ft{s}b{j-1}_o"
        ln = ln.replace(m.group(2), f"u_bay{j}")          # distinct instance names (no accidental gold match)
        body.append(ln.replace(f"ft{s}b{j}_i", ins).replace(f"ft{s}b{j}_o", f"ft{s}_o" if j == nb - 1 else f"ft{s}b{j}_o"))
    gwires = [f"ft{s}b{j}_o" for j in range(nb - 1)]
    iname = re.sub(r"\[.*", "", ST.search([x for x in v["gold"] if ST.search(x).group(6) == "0"][0]).group(7))
    src += mod(f"gold_ft{s}", s, v["gold"], gw, iname) + mod(f"gate_ft{s}", s, body, gwires, iname)
    ys += [f"# lane ft{s}: gold {len(v['gold'])} stations / gate {nb} bays"]
    rep["lanes"][s] = dict(width=W[s], gold_stations=len(v["gold"]), gate_bays=nb)
open(os.path.join(out, "chains.sv"), "w").write("\n".join(src) + "\n")
ys += [f"read_verilog -sv {os.path.abspath(os.path.join(out, 'chains.sv'))}",
       "setattr -mod -unset keep_hierarchy *", "hierarchy", "proc", "flatten", "async2sync", "opt_clean"]
for s in sorted(lanes, key=int):
    ys += [f"equiv_make gold_ft{s} gate_ft{s} eq_ft{s}", f"hierarchy -top eq_ft{s}", f"equiv_simple -seq 8 eq_ft{s}",
           f"equiv_induct -seq 8 eq_ft{s}", f"equiv_status -assert eq_ft{s}"]
open(os.path.join(out, "chain.ys"), "w").write("\n".join(ys) + "\n")
json.dump(rep, open(os.path.join(out, "report.json"), "w"), indent=1)
print(json.dumps({k: v for k, v in rep.items() if not k.startswith("partB_rule")}), "\nrule gold:", rep["partB_rule_gold"][:2],
      "\nrule gate:", rep["partB_rule_gate"][:2], "\npartC diff lines:", len(cdiff))
