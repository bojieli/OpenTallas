"""Generators from die_plan.json (TOPDOWN-PLAN step 3).

    python3 tools/die_plan/gen.py latency PLAN.json [--inplace] [--out DIR]
        (c) the latency table: writes the plan's `latency.lanes` (with --inplace), DIR/<die>_lat_pkg.sv (SV package,
            one localparam per lane) and DIR/<die>_latency.json (the compiler's input).  The table is computed by
            schema.Plan.lane_latency() only: stations of the crossed ft slots + 1 + fixed_cycles.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import schema as S  # noqa: E402


def lane_param(lid, ln):
    return ln.get("param") or "LAT_" + re.sub(r"[^A-Z0-9_]", "_", lid.upper())


def latency_table(P):
    out = {}
    for lid, ln in P.lanes.items():
        d = P.lane_latency(lid)
        d["param"] = lane_param(lid, ln)
        out[lid] = d
    params = [d["param"] for d in out.values()]
    dup = {p for p in params if params.count(p) > 1}
    if dup:
        raise SystemExit(f"latency: duplicate parameter names {sorted(dup)}")
    return out


def plan_digest(raw):
    r = dict(raw)
    r.pop("latency", None)
    return hashlib.sha256(json.dumps(r, sort_keys=True).encode()).hexdigest()[:16]


def write_latency(raw, out_dir, inplace_path=None):
    errs = S.validate(raw)
    if errs:
        raise SystemExit("plan invalid:\n  " + "\n  ".join(errs[:20]))
    P = S.Plan(raw)
    tab = latency_table(P)
    dig = plan_digest(raw)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pkg = f"{re.sub(r'[^a-z0-9_]', '_', P.name.lower())}_lat_pkg"
    lines = [f"// GENERATED by tools/die_plan/gen.py latency from die_plan {P.name} (plan digest {dig}). Do not edit.",
             "// Lane latency in cycles from the source partition's out flop to the destination's in flop",
             "// = stations of the crossed ft slots + 1 + fixed_cycles (TOPDOWN-PLAN: the ONLY latency source).",
             f"package {pkg};"]
    for lid, d in sorted(tab.items()):
        ln = P.lanes[lid]
        a, b = P.ports[ln["ports"][0]], P.ports[ln["ports"][-1]]
        lines.append(f"  localparam int {d['param']} = {d['cycles']};  // {lid}: {a['src']['part']}.{a['src']['bus']}"
                     f" -> {b['dst']['part']}.{b['dst']['bus']} ({d['stations']} st, {d['faces']} faces, "
                     f"{d['fixed']} fixed)")
    lines.append(f"endpackage : {pkg}")
    (out_dir / f"{pkg}.sv").write_text("\n".join(lines) + "\n")
    js = dict(schema="opentallas.die_plan.latency.v1", die=P.name, plan_digest=dig, period_ps=P.die["period_ps"],
              lanes={lid: dict(d, src=P.ports[P.lanes[lid]["ports"][0]]["src"],
                               dst=P.ports[P.lanes[lid]["ports"][-1]]["dst"],
                               width=P.ports[P.lanes[lid]["ports"][0]]["width"]) for lid, d in sorted(tab.items())})
    (out_dir / f"{P.name}_latency.json").write_text(json.dumps(js, indent=1) + "\n")
    if inplace_path:
        raw = dict(raw)
        raw["latency"] = {"lanes": tab}
        Path(inplace_path).write_text(json.dumps(raw, indent=1) + "\n")
    return tab, out_dir / f"{pkg}.sv", out_dir / f"{P.name}_latency.json"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    a1 = sub.add_parser("latency")
    a1.add_argument("plan")
    a1.add_argument("--out")
    a1.add_argument("--inplace", action="store_true", help="write latency.lanes back into PLAN.json")
    a = ap.parse_args(argv)
    if a.cmd == "latency":
        raw = S.load(a.plan)
        out = a.out or str(Path(a.plan).resolve().parent / "gen")
        tab, sv, js = write_latency(raw, out, a.plan if a.inplace else None)
        print(f"{len(tab)} lanes -> {sv}, {js}" + (f", {a.plan}" if a.inplace else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
