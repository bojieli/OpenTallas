"""Generators from die_plan.json (TOPDOWN-PLAN step 3).

    python3 tools/die_plan/gen.py rtl PLAN.json --out DIR [--rtl-root REPO]
        (a) partition wrapper RTL per type + ot_dp_cells.sv + the die top netlist (gen_rtl.py docstring)

    python3 tools/die_plan/gen.py dedup PLAN.json --out-plan NEW.json [--fix-order]
        TYPE-DEDUP (opt-in, writes a copy): merge of near-duplicate types (dedup.py)

    python3 tools/die_plan/gen.py latency PLAN.json [--inplace] [--out DIR] [--groups BUS_GROUPS.json]
    python3 tools/die_plan/gen.py phys PLAN.json --out DIR [--rtl-root REPO]      (b) partition ORFS kits (gen_phys.py)
    python3 tools/die_plan/gen.py assembly PLAN.json --out DIR --views VDIR    (d) die assembly kit (gen_phys.py)
        (c) the latency table: writes the plan's `latency.lanes` (with --inplace), DIR/<die>_lat_pkg.sv (SV package,
            one localparam per lane) and DIR/<die>_latency.json (the compiler's input).  The table is computed by
            schema.Plan.lane_latency() only: src out flop + stations of the crossed ft slots + dst in flop + fixed_cycles.
            R8 (COORD 10-23): with --groups (BINDER2's as-built bus_groups.json bound on this plan) it also writes
            DIR/<die>_r8_landing.json (r8.py): the landing pad per as-built bus member so every bus lands at ONE added
            delay, replicated consumers of one source equal, as-built valid/data order kept; the latency JSON gets an
            `r8` block (file, digest, summary) and the binder realises the pads (ot_dp_dly after the in flop).
            R8 options as r8.py pads (--exempt, --landed, --landed-window, --landed-stage-cycles, --landed-over-margin);
            --rebase-bind BIND_LATENCY.json moves the bus groups' bound depths from the bind's plan to this plan
            (r8.rebase: per member, its lane's cycle change).
            --fold-r8 (COORD 10-24 18:55, "price the landed-bundle pads in the latency table"): the latency JSON + SV
            package carry, per lane, `base` (= Plan.lane_latency cycles), `r8_pad` (largest R8 landing pad of the lane's
            members, r8.lane_fold) and `cycles` = base + r8_pad (the compiler's lane depth).  The in-plan table
            (--inplace) stays base: the binder realises R8 as landing pads, not lane pads, and G0 compares it with
            Plan.lane_latency().
"""
import gzip
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import schema as S  # noqa: E402


def lane_param(lid, ln):
    return ln.get("param") or "LAT_" + re.sub(r"[^A-Z0-9_]", "_", lid.upper())


def latency_table(P):
    out = {}
    for lid, ln in P.lanes.items():
        d = P.lane_latency(lid)
        d["param"] = lane_param(lid, ln)
        out[lid] = d
    params = [d["param"] for d in out.values()]
    dup = {p for p in params if params.count(p) > 1}
    if dup:
        raise SystemExit(f"latency: duplicate parameter names {sorted(dup)}")
    return out


def plan_digest(raw):
    r = dict(raw)
    r.pop("latency", None)
    return hashlib.sha256(json.dumps(r, sort_keys=True).encode()).hexdigest()[:16]


def load_json(path):
    """json or json.gz"""
    p = Path(path)
    return json.loads((gzip.open(p, "rt") if p.suffix == ".gz" else p.open()).read())


def write_latency(raw, out_dir, inplace_path=None, r8_fold=None):
    """r8_fold = {lane: dict(r8_pad, ...)} (r8.lane_fold): fold the R8 landing pad into the JSON / SV `cycles`."""
    errs = S.validate(raw)
    if errs:
        raise SystemExit("plan invalid:\n  " + "\n  ".join(errs[:20]))
    P = S.Plan(raw)
    sk = P.landed_skew()
    if sk:
        raise SystemExit("latency: landed bundle over the landing window margin:\n  " + "\n  ".join(sk))
    tab = latency_table(P)
    base_tab = json.loads(json.dumps(tab))
    if r8_fold is not None:
        for lid, d in tab.items():
            f = r8_fold.get(lid, {})
            d["base"], d["r8_pad"] = d["cycles"], f.get("r8_pad", 0)
            d["cycles"] += d["r8_pad"]
            if f.get("r8_padded"):
                d.update(r8_pad_min=f["r8_pad_min"], r8_members=f["r8_members"], r8_padded=f["r8_padded"])
    dig = plan_digest(raw)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pkg = f"{re.sub(r'[^a-z0-9_]', '_', P.name.lower())}_lat_pkg"
    lines = [f"// GENERATED by tools/die_plan/gen.py latency from die_plan {P.name} (plan digest {dig}). Do not edit.",
             "// Lane latency = register stages the lane adds between the source leaf and the destination leaf",
             "// = src out boundary flop + stations of the crossed ft slots + dst in boundary flop + fixed_cycles (TOPDOWN-PLAN: the ONLY latency source)"
             + (" + the R8 landing pad (largest member pad of the lane, r8 block of the JSON)." if r8_fold is not None else "."),
             f"package {pkg};"]
    for lid, d in sorted(tab.items()):
        ln = P.lanes[lid]
        a, b = P.ports[ln["ports"][0]], P.ports[ln["ports"][-1]]
        lines.append(f"  localparam int {d['param']} = {d['cycles']};  // {lid}: {a['src']['part']}.{a['src']['bus']}"
                     f" -> {b['dst']['part']}.{b['dst']['bus']} ({d['stations']} st, {d['faces']} faces, "
                     f"{d['boundary']} boundary, {d['fixed']} fixed" + (f", +{d['pad']} R8 group pad" if d.get("pad") else "")
                     + (f", +{d['r8_pad']} R8 landing pad" if d.get("r8_pad") else "") + ")")
        if d.get("beats"):      # DEC12 multi-beat lane: the whole word lands beats - 1 cycles after the first beat
            lines.append(f"  localparam int {d['param']}_WORD = {d['cycles'] + d['beats'] - 1};  // {lid}: "
                         f"{d['beats']} beats of {ln.get('word_bits')} b")
    lines.append(f"endpackage : {pkg}")
    (out_dir / f"{pkg}.sv").write_text("\n".join(lines) + "\n")
    js = dict(schema="opentallas.die_plan.latency.v1", die=P.name, plan_digest=dig, period_ps=P.die["period_ps"],
              lanes={lid: dict(d, src=P.ports[P.lanes[lid]["ports"][0]]["src"],
                               dst=P.ports[P.lanes[lid]["ports"][-1]]["dst"],
                               width=P.ports[P.lanes[lid]["ports"][0]]["width"]) for lid, d in sorted(tab.items())},
              groups=[dict(name=n, kind=k, lanes=l, cycles=tab[l[0]]["cycles"]) for n, k, l in P.latency_groups()
                      if k == "landed" and all(x in tab for x in l)])
    (out_dir / f"{P.name}_latency.json").write_text(json.dumps(js, indent=1) + "\n")
    if inplace_path:
        raw = dict(raw)
        raw["latency"] = {"lanes": base_tab}
        Path(inplace_path).write_text(json.dumps(raw, indent=1) + "\n")
    return tab, out_dir / f"{pkg}.sv", out_dir / f"{P.name}_latency.json"


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["dedup"]:
        # TYPE-DEDUP (opt-in): gen.py dedup PLAN --out-plan NEW [--fix-order] ... = dedup.py apply (never in place)
        import dedup
        return dedup.main(["apply"] + argv[1:])
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    a1 = sub.add_parser("latency")
    a1.add_argument("plan")
    a1.add_argument("--out")
    a1.add_argument("--inplace", action="store_true", help="write latency.lanes back into PLAN.json")
    a1.add_argument("--groups", help="R8: BINDER2 bus_groups.json -> <die>_r8_landing.json")
    a1.add_argument("--replica", choices=("all", "type"), default="all")
    a1.add_argument("--bus", choices=("part", "leaf"), default="part")
    a1.add_argument("--exempt", action="append", default=[], help="R8: r8.py pads --exempt")
    a1.add_argument("--landed", action="append", default=[], help="R8: r8.py pads --landed (landed bundle lane RX)")
    a1.add_argument("--landed-window", type=int, default=4)
    a1.add_argument("--landed-stage-cycles", type=float, default=0.5)
    a1.add_argument("--landed-over-margin", choices=("keep", "collapse"), default="keep")
    a1.add_argument("--rebase-bind", help="R8: the bind's bind_latency.json[.gz]: rebase bound depths onto this plan")
    a1.add_argument("--fold-r8", action="store_true", help="R8: cycles = base + r8_pad in the JSON / SV table")
    a2 = sub.add_parser("rtl")
    a2.add_argument("plan")
    a2.add_argument("--out", required=True)
    a2.add_argument("--rtl-root", help="repo root for the types' leaf `sources` (enables the leaf port-binding check)")
    a2.add_argument("--types", help="comma list of partition types (default all non-hard)")
    a3 = sub.add_parser("phys")
    a3.add_argument("plan")
    a3.add_argument("--out", required=True)
    a3.add_argument("--rtl-root")
    a3.add_argument("--types")
    a3.add_argument("--util", type=float, default=0.5)
    a3.add_argument("--proof", action="store_true", help="proof kit: SKIP_INCREMENTAL_REPAIR (CP1 seam proofs)")
    a3.add_argument("--hold-mcmm", action="store_true",
                    help="old GRT repair: one MCMM tc+bc pass with the TT-bound vclk (default since FLOW 10-25: "
                         "FF-only GRT hold repair with the FF-bound vclk, --hold-ff-margin)")
    a3.add_argument("--stock-rc", action="store_true",
                    help="platform setRC.tcl for placement/CTS/GRT estimates (default since FLOW 10-25: the "
                         "RCX-calibrated tools/die_plan/setRC_rcx_asap7.tcl)")
    a3.add_argument("--hold-ff-margin", type=float, default=5.0, metavar="PS",
                    help="repair hold at the FF sign-off corner only (CTS-stage combined repair skipped; post-GRT "
                         "repair with CORNERS=bc and this hold margin); TT setup is judged by signoff.py")
    a3.add_argument("--slew-margin", type=float, default=None, metavar="PCT",
                    help="export SLEW_MARGIN (repair_design margin, %% of the liberty max_transition; ELEM-S81 "
                         "station405: 50 fits the routed ASAP7 RCX, the setRC estimate is ~1.8x optimistic in slew)")
    a3.add_argument("--cap-margin", type=float, default=None, metavar="PCT", help="export CAP_MARGIN (e.g. 20)")
    a3.add_argument("--skip-kit-ir", action="store_true",
                    help="clear PWR/GND_NETS_VOLTAGES: skip ORFS 6_report per-kit PDNSim IR (IR NOT RUN; TRIAL IR required)")
    a3.add_argument("--max-wire-um", type=float, default=None, metavar="UM",
                    help="post-GRT repair_design -max_wire_length UM (kit grt_maxwire.tcl as PRE_GLOBAL_ROUTE_TCL; "
                         "repeater pitch so routed M2/M3 segments keep max slew; default off)")
    a3.add_argument("--kit-rtl", action="append", default=[], metavar="TYPE=FILELIST",
                    help="G3: the type's kit RTL = this filelist (bind.py kit-rtl: bound partition inside the plan "
                         "wrapper) instead of the generated plan wrapper + type sources; repeatable")
    a4 = sub.add_parser("assembly")
    a4.add_argument("plan")
    a4.add_argument("--out", required=True)
    a4.add_argument("--views", required=True, help="DIR/<type>/<module>.lef|.lib (each kit's abstract)")
    a5 = sub.add_parser("mockview", help="mock abstract LEFs (exact pins + PG + OBS) for a dry die-flow run")
    a5.add_argument("plan")
    a5.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "mockview":
        import gen_phys
        print("\n".join(str(d) for d in gen_phys.write_mock_views(S.load(a.plan), a.out)))
        return 0
    if a.cmd in ("phys", "assembly"):
        import gen_phys
        import gen_rtl
        try:
            if a.cmd == "phys":
                kits = gen_phys.write_phys(S.load(a.plan), a.out, a.rtl_root,
                                           a.types.split(",") if a.types else None, a.util, a.proof,
                                           dict(x.split("=", 1) for x in a.kit_rtl),
                                           None if a.hold_mcmm else a.hold_ff_margin,
                                           (a.slew_margin, a.cap_margin), a.skip_kit_ir, a.max_wire_um,
                                           plan_path=Path(a.plan).resolve(), rc_cal=not a.stock_rc)
            else:
                kits = [gen_phys.write_assembly(S.load(a.plan), a.out, a.views, plan_path=Path(a.plan).resolve())]
        except gen_rtl.GenError as e:
            print(f"gen {a.cmd}: ERROR {e}")
            return 1
        print("\n".join(str(k) for k in kits))
        return 0
    if a.cmd == "rtl":
        import gen_rtl
        try:
            files = gen_rtl.write_rtl(S.load(a.plan), a.out, a.rtl_root, a.types.split(",") if a.types else None,
                                     plan_path=Path(a.plan).resolve())
        except gen_rtl.GenError as e:
            print(f"gen rtl: ERROR {e}")
            return 1
        print("\n".join(str(f) for f in files))
        return 0
    if a.cmd == "latency":
        raw = S.load(a.plan)
        out = a.out or str(Path(a.plan).resolve().parent / "gen")
        if a.fold_r8 and not a.groups:
            raise SystemExit("latency: --fold-r8 needs --groups")
        fold = r8blk = None
        if a.groups:
            import r8
            r8.configure(a.exempt, a.landed, a.landed_window, a.landed_stage_cycles, a.landed_over_margin)
            bg = load_json(a.groups)
            r8blk = dict(bus_groups_digest=r8.bg_digest(bg), replica=a.replica, bus=a.bus, exempt=a.exempt,
                         landed=dict(rx=a.landed, window=a.landed_window, stage_cycles=a.landed_stage_cycles,
                                     over_margin=a.landed_over_margin))
            if a.rebase_bind:
                bl = load_json(a.rebase_bind)
                bg, rb = r8.rebase(bg, bl, latency_table(S.Plan(raw)))
                r8blk["rebase"] = dict(bind_latency_digest=r8.bg_digest(bl), **rb)
            lp, sm = r8.write_pads(raw, bg, out, a.replica, a.bus)
            r8blk.update(landing=lp.name, summary=sm)
            if a.fold_r8:
                fold, other = r8.lane_fold(json.loads(lp.read_text())["members"], S.Plan(raw).lanes)
                pads = [f["r8_pad"] for f in fold.values() if f["r8_pad"]]
                r8blk["fold"] = dict(folded=True, lanes_padded=len(pads), max_pad=max(pads, default=0),
                                     sum_pad=sum(pads), mean_pad=round(sum(pads) / len(pads), 3) if pads else 0,
                                     not_plan_lanes={k: v["r8_pad"] for k, v in sorted(other.items())},
                                     rule="lane r8_pad = largest R8 landing pad of the lane's members; cycles = base + r8_pad")
        tab, sv, js = write_latency(raw, out, a.plan if a.inplace else None, fold)
        print(f"{len(tab)} lanes -> {sv}, {js}" + (f", {a.plan}" if a.inplace else ""))
        if r8blk is not None:
            d = json.loads(js.read_text())
            d["r8"] = r8blk
            js.write_text(json.dumps(d, indent=1) + "\n")
            print(f"R8 landing -> {Path(out) / r8blk['landing']}: {json.dumps(r8blk['summary'])}"
                  + (f"; folded {json.dumps(r8blk['fold'])}" if fold is not None else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
