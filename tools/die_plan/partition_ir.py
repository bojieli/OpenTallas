#!/usr/bin/env python3
"""Separate partition PDNSim from final timing artifacts, without dropping IR.

Stage this file into a kit. In its DISPOSABLE ORFS container, before make:
  python3 /work/partition_ir.py patch /OpenROAD-flow-scripts/flow/scripts
  export OT_DEFER_PARTITION_IR=1
Normal finish/RCX/signoff then return. IR is explicitly NOT_RUN until a separate
admitted job runs: partition_ir.py sidecar KIT --mem-gb 64 --threads 8
(64 GB follows the measured 48 GB exhaustion; admission remains ot-run's job).
The sidecar loads the SAME final ODB/SDC/SPEF and libraries and executes the
original image's IR Tcl verbatim, with the captured voltage/source contract.
COMPLETED means analysis ran; it does not invent an IR-drop acceptance verdict.
"""
import argparse
import datetime
import json
import os
from pathlib import Path
import shlex
import subprocess
import uuid

MARK = "# OT_PARTITION_IR_V1"
ANCHOR = "  # Static IR drop analysis\n"
END = '} else {\n  puts "OpenRCX is not enabled for this platform."'

HELPER = r'''# Generated by partition_ir.py; original IR block is in partition_ir_analysis.tcl.
proc ot_ir_env_true {key} {
  expr {[info exists ::env($key)] && $::env($key) eq "1"}
}
proc ot_ir_capture {} {
  set path $::env(RESULTS_DIR)/partition_ir_contract.tcl
  set fp [open $path w]
  puts $fp {foreach key [array names ::env PDNSIM_*] {unset ::env($key)}}
  foreach key {PWR_NETS_VOLTAGES GND_NETS_VOLTAGES VSRC_LOC_FILES VSRC_LOC_FILE} {
    puts $fp [list unset -nocomplain ::env($key)]
  }
  foreach key [lsort [array names ::env]] {
    if {$key in {PWR_NETS_VOLTAGES GND_NETS_VOLTAGES VSRC_LOC_FILES VSRC_LOC_FILE} ||
        [string match PDNSIM_* $key]} {
      puts $fp [list set ::env($key) $::env($key)]
    }
  }
  close $fp
}
proc ot_ir_defer_checkpoint {} {
  # Native final_report already wrote ODB/SDC; RCX/SPEF is now complete too.
  foreach suffix {odb sdc spef} {
    if {![file exists $::env(RESULTS_DIR)/6_final.$suffix]} {
      error "partition IR defer requires native final $suffix artifact"
    }
  }
  ot_ir_capture
  set path $::env(RESULTS_DIR)/partition_ir_deferred_[clock microseconds]_[pid].status
  set fp [open $path w]
  puts $fp "NOT_RUN partition_ir_deferred; die_IR_requirement_retained"
  close $fp
  puts "OT_PARTITION_IR NOT_RUN deferred; final ODB/SDC/SPEF checkpoint available"
}
proc ot_ir_sidecar {} {
  source $::env(SCRIPTS_DIR)/load.tcl
  erase_non_stage_variables final
  load_design 6_final.odb 6_final.sdc
  set spef $::env(RESULTS_DIR)/6_final.spef
  set contract $::env(RESULTS_DIR)/partition_ir_contract.tcl
  if {![file exists $spef] || ![file exists $contract]} {
    error "partition IR sidecar requires final RCX SPEF and captured IR contract"
  }
  read_spef $spef
  source $contract
  if {![env_var_exists_and_non_empty PWR_NETS_VOLTAGES] &&
      ![env_var_exists_and_non_empty GND_NETS_VOLTAGES]} {
    error "partition IR sidecar has no captured power or ground voltage contract"
  }
  set_propagated_clock [all_clocks]
  set status $::env(OT_PARTITION_IR_STATUS)
  set fp [open $status w]; puts $fp RUNNING; close $fp
  set code [catch {source $::env(SCRIPTS_DIR)/partition_ir_analysis.tcl} result options]
  set fp [open $status w]
  if {$code} { puts $fp "FAIL $result" } else { puts $fp "COMPLETED analysis_only; assess_IR_reports_separately" }
  close $fp
  if {$code} { return -options $options $result }
  puts "OT_PARTITION_IR COMPLETED analysis_only"
}
'''


def patched(outputs, report):
    """Validate both source anchors before any filesystem mutation."""
    if MARK in outputs or MARK in report:
        if MARK not in outputs or MARK not in report:
            raise ValueError("partial partition IR patch; restore the disposable image")
        return None
    if outputs.count(ANCHOR) != 1 or outputs.count(END) != 1:
        raise ValueError("unrecognized final_outputs IR boundaries")
    if 'read_spef $::env(RESULTS_DIR)/6_final.spef' not in outputs:
        raise ValueError("IR checkpoint must follow final RCX read_spef")
    if report.count('source $::env(SCRIPTS_DIR)/final_outputs.tcl') != 1:
        raise ValueError("unrecognized final_report entry")
    checkpoint = 'orfs_write_db $::env(RESULTS_DIR)/6_final.odb'
    if checkpoint not in report or report.index(checkpoint) > report.index('source $::env(SCRIPTS_DIR)/final_outputs.tcl'):
        raise ValueError("native final ODB checkpoint must precede final_outputs")
    start, end = outputs.index(ANCHOR), outputs.index(END)
    if start >= end:
        raise ValueError("invalid final_outputs IR order")
    analysis = outputs[start:end]
    prefix = MARK + '\nsource $::env(SCRIPTS_DIR)/partition_ir_runtime.tcl\n'
    replacement = ('  if {[ot_ir_env_true OT_DEFER_PARTITION_IR]} {\n'
                   '    ot_ir_defer_checkpoint\n'
                   '  } else {\n' + analysis + '  }\n')
    new_outputs = prefix + outputs[:start] + replacement + outputs[end:]
    dispatch = ('if {[ot_ir_env_true OT_PARTITION_IR_SIDECAR]} {\n'
                '  ot_ir_sidecar\n  return\n}\n')
    return dict(outputs=new_outputs, report=prefix + dispatch + report, analysis=analysis)


def patch(scripts):
    scripts = Path(scripts)
    a, b = scripts / 'final_outputs.tcl', scripts / 'final_report.tcl'
    changes = patched(a.read_text(), b.read_text())
    if changes is None:
        for name in ('partition_ir_runtime.tcl', 'partition_ir_analysis.tcl'):
            if not (scripts / name).is_file():
                raise ValueError("patched source is missing " + name)
        if (scripts / 'partition_ir_runtime.tcl').read_text() != HELPER:
            raise ValueError("partition IR helper version differs; use a fresh disposable image")
        return False
    files = {'partition_ir_runtime.tcl': HELPER,
             'partition_ir_analysis.tcl': changes['analysis'],
             'final_outputs.tcl': changes['outputs'], 'final_report.tcl': changes['report']}
    for path in (a, b):
        backup = path.with_suffix(path.suffix + '.ot_partition_ir.original')
        if backup.exists():
            raise ValueError("unexpected original backup: " + str(backup))
    for path in (a, b):
        path.with_suffix(path.suffix + '.ot_partition_ir.original').write_bytes(path.read_bytes())
    # All anchors passed before installing any helper/source.
    for name, text in files.items():
        dest = scripts / name
        temp = dest.with_name(dest.name + '.ot_partition_ir.tmp')
        temp.write_text(text)
        os.replace(temp, dest)
    return True


def sidecar(kit, mem_gb, threads, image):
    kit = Path(kit).resolve()
    if mem_gb <= 0 or threads <= 0:
        raise ValueError("memory and threads must be positive admission requests")
    tag = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '_' + uuid.uuid4().hex[:8]
    result = kit / 'partition_ir' / tag
    result.mkdir(parents=True)
    rel = '/work/partition_ir/' + tag
    make = ['make', 'DESIGN_CONFIG=/work/config.mk', 'WORK_HOME=/work/run',
            'FLOW_VARIANT=base', f'NUM_CORES={threads}', f'LOG_DIR={rel}/logs',
            f'REPORTS_DIR={rel}/reports', 'do-6_report']
    command = ['docker', 'run', '--rm', f'--cpus={threads}', f'--memory={mem_gb}g',
               f'--memory-swap={mem_gb}g', '-v', f'{kit}:/work', '-v',
               f'{Path(__file__).resolve()}:/ot/partition_ir.py:ro',
               '-w', '/OpenROAD-flow-scripts/flow',
               '-e', 'OT_PARTITION_IR_SIDECAR=1', '-e', 'OT_DEFER_PARTITION_IR=0',
               '-e', f'OT_PARTITION_IR_STATUS={rel}/analysis.status', image, 'bash', '-lc',
               'source /OpenROAD-flow-scripts/env.sh >/dev/null 2>&1; '
               'python3 /ot/partition_ir.py patch /OpenROAD-flow-scripts/flow/scripts && '
               + shlex.join(make)]
    (result / 'command.json').write_text(json.dumps(command, indent=1) + '\n')
    with (result / 'sidecar.log').open('w') as log:
        run = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT)
    # A process error can precede Tcl's RUNNING marker (e.g. missing libraries).
    status = result / 'analysis.status'
    if not status.exists():
        status.write_text(f'FAIL sidecar did not reach IR analysis; exit={run.returncode}\n')
    subprocess.run(['docker', 'run', '--rm', '-v', f'{result}:/out', image,
                    'chown', '-R', f'{os.getuid()}:{os.getgid()}', '/out'], check=False)
    return run.returncode or (0 if status.read_text().startswith('COMPLETED ') else 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('patch'); p.add_argument('scripts', type=Path)
    p = sub.add_parser('sidecar'); p.add_argument('kit', type=Path)
    p.add_argument('--mem-gb', type=int, required=True)
    p.add_argument('--threads', type=int, required=True)
    p.add_argument('--image', default='openroad/orfs:asap7lock')
    args = parser.parse_args()
    if args.cmd == 'patch':
        print('PARTITION_IR_PATCH', 'installed' if patch(args.scripts) else 'already installed')
        return 0
    return sidecar(args.kit, args.mem_gb, args.threads, args.image)


if __name__ == '__main__':
    raise SystemExit(main())
