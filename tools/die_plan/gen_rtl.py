class GenError(Exception):
    pass


def sv_id(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def bus_epochs(P):
    """{(type, bus): bool} -- whether the port bound to each bus carries the epoch bit; all instances must agree."""
    out = {}
    for pid, pr in P.ports.items():
        e = S.has_epoch(pr)
        for side in ("src", "dst"):
            part = pr[side]["part"]
            if part == S.DIE_PART:
                continue
            k = (P.parts[part]["type"], pr[side]["bus"])
            if k in out and out[k] != e:
                raise GenError(f"type {k[0]} bus {k[1]}: epoch differs between instances (port {pid})")
            out[k] = e
    return out


def parse_leaf_ports(text, module):
    """ANSI header of `module` -> {port: (dir, width_expr)}; None if the module is not found."""
    m = re.search(r"\bmodule\s+" + re.escape(module) + r"\b", text)
    if not m:
        return None
    i = m.end()
    # skip a parameter list #( ... )
    j = text.find("(", i)
    hdr_start = text.find("#", i)
    if 0 <= hdr_start < j:
        depth, k = 0, text.find("(", hdr_start)
        while True:
            c = text[k]
            depth += c == "("
            depth -= c == ")"
            k += 1
            if depth == 0:
                break
        j = text.find("(", k)
    depth, k = 0, j
    while True:
        c = text[k]
        depth += c == "("
        depth -= c == ")"
        k += 1
        if depth == 0:
            break
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", text[j + 1:k - 1], flags=re.S)
    # Verilog attributes on a port declaration, e.g. '(* keep *) output reg q' (ot_dp_head_raw_export_pair), are not
    # part of the port (DIE-HEAD-39 10-30: such ports were dropped -> nested port-bind 'unknown').
    body = re.sub(r"\(\*.*?\*\)", " ", body, flags=re.S)
    ports, cur_dir, cur_w = {}, None, ""
    for tok in body.split(","):
        tok = tok.strip()
        mm = re.match(r"(input|output|inout)\b\s*(wire|reg|logic)?\s*(signed)?\s*(\[[^\]]*\])?\s*(\w+)\s*$", tok)
        if mm:
            cur_dir, cur_w = mm.group(1), mm.group(4) or ""
            ports[mm.group(5)] = (cur_dir, cur_w)
            continue
        mm = re.match(r"(\w+)\s*$", tok)
        if mm and cur_dir:
            ports[mm.group(1)] = (cur_dir, cur_w)
    return ports


def leaf_headers(t, root):
    texts = []
    for f in t.get("sources", []):
        p = Path(root) / f
        if not p.is_file():
            raise GenError(f"source {f} not found under {root}")
        texts.append(p.read_text(errors="replace"))
    return "\n".join(texts)


def wrapper(P, tn, epochs, rtl_root=None):
    t = P.types[tn]
    mod = t["module"]
    ns = int(t.get("reset", {}).get("sync_stages", P.reset.get("sync_stages", 2)))
    buses = []
    for b in t.get("buses", []):
        buses.append(dict(b, ep=epochs.get((tn, b["name"]), b.get("kind", "data") in ("data", "ctl"))))
    slots = t.get("ft_slots", [])
    import infra_rtl as IR
    infra = IR.type_ports(t)
    ports = [("input  wire clk", "clock entry: spine tap 0 (one root per tap; R4 tap grid)")]
    for n, x, y in S.tap_grid(P, tn)[1:]:
        ports.append((f"input  wire {n}", f"spine tap at ({x:.0f}, {y:.0f}) um: the kit (clock_taps.tcl) moves the "
                      "nearest sinks onto it before CTS; same die clock"))
    for n, x, y, tp in S.core_taps(P, tn):
        ports.append((f"input  wire {n}", f"EARLY core tap {tp['name']} at ({x:.0f}, {y:.0f}) um (CP2): the kit "
                      "(clock_taps.tcl) hangs the core's clock pins on it; the spine delivers it "
                      f"{S.core_tap_early_ps(P, tp):g} ps early"))
    import reset_tree as RT
    rtree = RT.for_type(P, tn) if RT.delivered(P) else None
    if rtree is None:
        ports.append(("input  wire arst_n", "die reset: asynchronous assert; released through " +
                      ("the per-tap u_rsync_t<i>" if len(S.tap_grid(P, tn)) > 1 else "u_rst_sync")))
    elif RT.wavefront(P):
        ports.append(("input  wire arst_n", (
            "reset IN (OWNER DECISION 13 wavefront): at the root partition the die rst_n (asynchronous, into the ONE "
            "root synchroniser u_rst_root), elsewhere a neighbour's registered rst_o (synchronous)"
            if rtree["entry"] == "sync" else "SYNCHRONOUS reset IN from a neighbour's registered rst_o (OWNER DECISION "
            "13 wavefront): pin register u_rst_in") + f" + {rtree['depth']} relay stages; every tap and rst_o released "
            f"{RT.release_clocks(rtree)} clocks after this pin"))
        for n, x, y in RT.out_pins(P, tn):
            ports.append((f"output wire {n}", f"registered reset OUT to a neighbour's arst_n (wavefront) at "
                          f"({x:.0f}, {y:.0f}) um"))
        if rtree.get("start"):
            ports.append(("input  wire start_i", "START IN (OWNER DECISION 13c broadcast, beside arst_n): " + (
                "the die start pin (asynchronous level) into the ONE START synchroniser u_run_root"
                if rtree["entry"] == "sync" else "a neighbour's registered start_o (synchronous): pin register u_run_in")
                + "; control state releases on reset AND run"))
            for n, x, y in RT.start_out_pins(P, tn):
                ports.append((f"output wire {n}", f"registered START OUT beside rst_o_{n.rsplit('_', 1)[1]} at "
                              f"({x:.0f}, {y:.0f}) um"))
    elif rtree["entry"] == "sync":
        ports.append(("input  wire arst_n", f"die reset (region root): asynchronous, into the region's ONE root "
                      f"synchroniser u_rst_root; every tap released {RT.release_clocks(rtree)} clocks after deassert"))
    else:
        ports.append(("input  wire arst_n", f"SYNCHRONOUS reset from the die reset tree (OWNER RESET RULE 10-24): pin "
                      f"register u_rst_in + {rtree['depth']} relay stages; every tap released "
                      f"{RT.release_clocks(rtree)} clocks after this pin"))
    for ip in infra:
        ports.append((f"{'input' if ip['dir'] == 'in' else 'output'} wire {ip['name']}", "die-owned clock/reset pass-through, no data register"))
    decl, body = [], []
    for b in buses:
        w = b["width"] + (1 if b["ep"] else 0)
        d = "input " if b["dir"] == "in" else "output"
        note = f"{b['width']} data" + (f" + epoch [{b['width']}]" if b["ep"] else "") + \
            (f", leaf {b['leaf']}" if b.get("leaf") else "")
        ports.append((f"{d} wire [{w - 1}:0] {sv_id(b['name'])}", note))
    for sp in t.get("id_straps", []):
        ports.append((f"input  wire [{sp['width'] - 1}:0] {sp['name']}", "ID strap (OWNER 10-25 B): quasi-static, tied "
                      "at the parent per instance, no pin register, set_false_path -from in the kit SDC"))
    for pd in t.get("pads", []):
        ports.append((f"{'input ' if pd['dir'] == 'in' else 'output'} wire [{pd['width'] - 1}:0] {sv_id(pd['name'])}",
                      "PHY pad (no boundary flop: PHY-side timing)" + (", PHY clock" if pd.get("clock") else "")))
    for s in slots:
        for sfx, d in (("_i", "input "), ("_o", "output")):
            w = s["width"] + (1 if epochs.get((tn, s["name"] + sfx), True) else 0)
            ports.append((f"{d} wire [{w - 1}:0] {sv_id(s['name'] + sfx)}", f"ft slot {s['name']} "
                          f"({s['in_face']} -> {s['out_face']}, {s.get('stations', 1)} station(s))"))
    taps = RT.consumer_taps(P, tn) if rtree is not None else S.tap_grid(P, tn)
    if rtree is not None or len(taps) > 1:
        # one local synchroniser per tap region (u_rsync_t<i>, rst_n_t<i>); rst_n = tap 0 (leaves).  Boundary flops and
        # ft stations take the synchroniser of the tap NEAREST their planned site (S81-P9 10-23: the bus's pin centroid;
        # ft station j of k at j/k between the slot's in and out pins).  Round-robin left the face taps without a
        # synchroniser (Yosys drops the unloaded ones), so reset_taps.tcl had to fall back to a farther tap (S81 r0:
        # u_rsync_t3 -> ft1_s0.eq 753-803 um).  The kit (reset_taps.tcl, pre-GPL) still re-points every FIRM placed one
        # to its nearest tap's synchroniser and places each synchroniser FIRM at its tap.
        if rtree is not None:
            # OWNER RESET RULE 10-24: entry stage + equal-depth synchronous relay tree (reset_tree.py); the leaves take
            # the tap nearest the outline centre
            body += RT.rtl_lines(rtree)
            body.append(f"    wire rst_n = rst_n_t{RT.leaf_tap(P, tn)};")
        else:
            if ns not in (2, 3):
                raise GenError(f"type {tn}: reset.sync_stages {ns}: per-tap synchronisers exist for 2 or 3 stages")
            for i in range(len(taps)):
                body.append(f"    wire rst_n_t{i};\n    ot_dp_rsync_s{ns} u_rsync_t{i} "
                            f"(.clk(clk), .async_rst_n(arst_n), .sync_rst_n(rst_n_t{i}));")
            body.append("    wire rst_n = rst_n_t0;")
        rr = [0]
        try:
            import gen_phys
            cen = {}
            for bn, _b, _l, x, y, _f in gen_phys.type_pins(P, tn):
                a = cen.setdefault(bn, [0.0, 0.0, 0])
                a[0] += x
                a[1] += y
                a[2] += 1
            cen = {k: (v[0] / v[2], v[1] / v[2]) for k, v in cen.items()}
        except Exception:      # a plan without pin geometry: round-robin (reset_taps.tcl re-points)
            cen = {}

        def rsel(key=None, key2=None, f=0.0):
            bootstrap = key in (rtree or {}).get('bootstrap_buses', [])
            if key in cen:
                x, y = cen[key]
                if key2 in cen:
                    x, y = x + (cen[key2][0] - x) * f, y + (cen[key2][1] - y) * f
                i = min(range(len(taps)), key=lambda k: abs(taps[k][1] - x) + abs(taps[k][2] - y))
                return f"rst_boot_t{i}" if bootstrap else f"rst_n_t{i}"
            i = rr[0] % len(taps)
            r = f"rst_boot_t{i}" if bootstrap else f"rst_n_t{i}"
            rr[0] += 1
            return r
    else:
        body.append(f"    wire rst_n;\n    ot_reset_sync #(.ASYNC_STAGES({ns})) u_rst_sync "
                    f"(.clk(clk), .async_rst_n(arst_n), .sync_rst_n(rst_n));")

        def rsel(key=None, key2=None, f=0.0):
            return "rst_n"
    def st(ea):
        # an epoch flop that loads a reset net is kept (ot_dp_ste), else opt_merge folds all of them into one
        return "ot_dp_ste" if re.fullmatch(r"rst_n(_t\d+)?", ea) else "ot_dp_st"

    sig = {}          # bind keyword -> expression
    need_rst = False
    pads, bad = P.bus_pads()
    if bad:
        raise GenError("; ".join(bad))
    for b in buses:
        n, W = sv_id(b["name"]), b["width"]
        pad = pads.get((tn, b["name"]), 0)   # R8 latency-group pad stages (Plan.bus_pads)
        if b["dir"] == "in":
            decl.append(f"    wire [{W - 1}:0] {n}_q;\n    wire {n}_eq;")
            r = rsel(b["name"])
            ea = f"{n}[{W}]" if b["ep"] else r
            body.append(f"    {st(ea)} #(.W({W})) u_bin_{n} (.clk(clk), .rst_n({r}), .d({n}[{W - 1}:0]), "
                        f".ea({ea}), .q({n}_q), .eq({n}_eq));")
            q, eq = f"{n}_q", f"{n}_eq"
            for j in range(pad):
                decl.append(f"    wire [{W - 1}:0] {n}_p{j}_q;\n    wire {n}_p{j}_eq;  // R8 latency-group pad")
                body.append(f"    ot_dp_st #(.W({W})) u_bin_{n}_pad{j} (.clk(clk), .rst_n({rsel(b['name'])}), .d({q}), .ea({eq}), "
                            f".q({n}_p{j}_q), .eq({n}_p{j}_eq));")
                q, eq = f"{n}_p{j}_q", f"{n}_p{j}_eq"
            sig[f"bus:{b['name']}"] = q
            sig[f"epoch:{b['name']}"] = eq
        else:
            decl.append(f"    wire [{W - 1}:0] {n}_d;")
            eq = f"{n}[{W}]" if b["ep"] else f"{n}_eo"
            if not b["ep"]:
                decl.append(f"    wire {n}_eo;  // epoch of a die-IO / non-lane output: not carried off the partition")
            r = rsel(b["name"])
            d, ea = f"{n}_d", r
            for j in range(pad):
                decl.append(f"    wire [{W - 1}:0] {n}_p{j}_q;\n    wire {n}_p{j}_eq;  // R8 latency-group pad")
                body.append(f"    {st(ea)} #(.W({W})) u_bout_{n}_pad{j} (.clk(clk), .rst_n({r}), .d({d}), .ea({ea}), "
                            f".q({n}_p{j}_q), .eq({n}_p{j}_eq));")
                d, ea = f"{n}_p{j}_q", f"{n}_p{j}_eq"
            body.append(f"    {st(ea)} #(.W({W})) u_bout_{n} (.clk(clk), .rst_n({r}), .d({d}), .ea({ea}), "
                        f".q({n}[{W - 1}:0]), .eq({eq}));")
            sig[f"bus:{b['name']}"] = f"{n}_d"
    for s in slots:
        n, W, k = sv_id(s["name"]), s["width"], int(s.get("stations", 1))
        ep_i = epochs.get((tn, s["name"] + "_i"), True)
        ep_o = epochs.get((tn, s["name"] + "_o"), True)
        r = rsel(s["name"] + "_i")
        d, ea = f"{n}_i[{W - 1}:0]", (f"{n}_i[{W}]" if ep_i else r)
        for j in range(k):
            last = j == k - 1
            if last:
                q, eq = f"{n}_o[{W - 1}:0]", (f"{n}_o[{W}]" if ep_o else f"{n}_s{j}_eq")
                if not ep_o:
                    decl.append(f"    wire {n}_s{j}_eq;")
            else:
                q, eq = f"{n}_s{j}_q", f"{n}_s{j}_eq"
                decl.append(f"    wire [{W - 1}:0] {q};\n    wire {eq};")
            body.append(f"    {st(ea)} #(.W({W})) u_ft_{n}_s{j} (.clk(clk), .rst_n({r if j == 0 else rsel(s['name'] + '_i', s['name'] + '_o', j / k)}), .d({d}), .ea({ea}), "
                        f".q({q}), .eq({eq}));")
            d, ea = q, eq
    for nt in t.get("nets", []):
        decl.append(f"    wire [{nt['width'] - 1}:0] n_{sv_id(nt['name'])};")
        sig[f"net:{nt['name']}"] = f"n_{sv_id(nt['name'])}"
    sig["clk"], sig["rst_n"], sig["rst"] = "clk", "rst_n", "rst"
    if (rtree or {}).get('bootstrap_contents'):
        sig['bootstrap_rst_n'] = f'rst_boot_t{RT.leaf_tap(P, tn)}'
        sig['bootstrap_rst'] = 'bootstrap_rst'
        decl.append(f"    wire bootstrap_rst = ~{sig['bootstrap_rst_n']};")
    for sp in t.get("id_straps", []):
        sig[f"strap:{sp['name']}"] = sp["name"]
    for pd in t.get("pads", []):
        sig[f"pad:{pd['name']}"] = sv_id(pd["name"])
    if rtree is not None and rtree.get("start_tap") is not None:
        sig["start"] = f"start_t{rtree['start_tap']}"     # bootstrap type: local registered START (reset AND run)
    for ip in infra:
        sig[f"infra:{ip['name']}"] = ip["name"]
    # LAND-HEAD-BIND-1 (opt-in, type ft_spare_outputs): a hard core's pass-through FT OUTPUT that the partition does
    # not consume (landed form: no die mesh crosses the core island) lands on a declared, owned, unread wire --
    # never a tie, never an implicit open pin.  Each entry must bind exactly one leaf OUTPUT port (checked below).
    spares = t.get("ft_spare_outputs", [])
    for fs in spares:
        if not fs.get("owner") or not fs.get("reason"):
            raise GenError(f"type {tn}: ft_spare_outputs {fs.get('port')} needs an owner and a reason")
        nm = "ftspare_" + sv_id(fs["port"])
        decl.append(f"    wire {nm};  // declared unread core FT output (owner {fs['owner']}): {fs['reason']}")
        sig[f"ftspare:{fs['port']}"] = nm
    # leaf bindings: contents[].bind plus bus.leaf
    binds = {c["inst"]: dict(c.get("bind", {})) for c in t.get("contents", [])}
    for inst in (rtree or {}).get('bootstrap_contents', []):
        binds[inst] = {p: ('bootstrap_' + k if k in ('rst_n', 'rst') else k)
                       for p, k in binds[inst].items()}
    for b in buses:
        if b.get("leaf"):
            inst, port = b["leaf"].split(".", 1)
            if inst not in binds:
                raise GenError(f"type {tn}: bus {b['name']} leaf {b['leaf']}: no content instance {inst}")
            if port in binds[inst] and binds[inst][port] != f"bus:{b['name']}":
                raise GenError(f"type {tn}: {b['leaf']} bound twice")
            binds[inst][port] = f"bus:{b['name']}"
    for ip in infra:
        inst, port = ip["leaf"].split(".", 1)
        if inst not in binds or port in binds[inst]:
            raise GenError(f"type {tn}: duplicate/unknown infrastructure leaf {ip['leaf']}")
        binds[inst][port] = f"infra:{ip['name']}"
    use = {}
    for inst, bd in binds.items():
        for port, key in bd.items():
            if key not in sig:
                raise GenError(f"type {tn}: {inst}.{port} -> '{key}' is not a signal of the partition")
            need_rst |= key == "rst"
            use.setdefault(key, []).append(f"{inst}.{port}")
    for b in buses:
        k = f"bus:{b['name']}"
        if k not in use:
            raise GenError(f"type {tn}: bus {b['name']} is not bound to any leaf port (open {'input' if b['dir'] == 'in' else 'output'})")
        if b["dir"] == "out" and len(use[k]) != 1:
            raise GenError(f"type {tn}: out bus {b['name']} driven by {len(use[k])} leaf ports {use[k]}")
    for sp in t.get("id_straps", []):
        if not use.get(f"strap:{sp['name']}"):
            raise GenError(f"type {tn}: id strap {sp['name']} is not bound to any leaf port")
    for pd in t.get("pads", []):
        k = f"pad:{pd['name']}"
        if not use.get(k) or (pd["dir"] == "out" and len(use[k]) != 1):
            raise GenError(f"type {tn}: pad {pd['name']} must bind {'exactly one leaf port' if pd['dir'] == 'out' else 'a leaf port'}: {use.get(k)}")
    for fs in spares:
        if len(use.get(f"ftspare:{fs['port']}", [])) != 1:
            raise GenError(f"type {tn}: ft spare output {fs['port']} must bind exactly one leaf port: "
                           f"{use.get('ftspare:' + fs['port'])}")
    for nt in t.get("nets", []):
        if len(use.get(f"net:{nt['name']}", [])) < 2:
            raise GenError(f"type {tn}: net {nt['name']} has {len(use.get('net:' + nt['name'], []))} leaf ports")
    if need_rst:
        decl.append("    wire rst = ~rst_n;")
    hdrs = leaf_headers(t, rtl_root) if rtl_root and t.get("sources") else None
    for c in t.get("contents", []):
        bd = binds[c["inst"]]
        if hdrs is not None:
            lp = parse_leaf_ports(hdrs, c["module"])
            if lp is None:
                raise GenError(f"type {tn}: module {c['module']} not found in the type sources")
            miss = sorted(set(lp) - set(bd))
            extra = sorted(set(bd) - set(lp))
            if miss:
                raise GenError(f"type {tn}: {c['inst']} ({c['module']}) unbound ports {miss} (no tie-offs: bind them)")
            if extra:
                raise GenError(f"type {tn}: {c['inst']} binds ports {extra} that {c['module']} does not have")
            bad = sorted(p for p, k in bd.items() if k.startswith("ftspare:") and lp[p][0] != "output")
            if bad:
                raise GenError(f"type {tn}: {c['inst']} ft spare binds non-output ports {bad}")
        par = c.get("params", {})
        ps = (" #(" + ", ".join(f".{k}({v})" for k, v in par.items()) + ")") if par else ""
        conns = ",\n".join(f"        .{p}({sig[k]})" for p, k in sorted(bd.items()))
        body.append(f"    {c['module']}{ps} {c['inst']} (\n{conns}\n    );")
    head = (f"// GENERATED by tools/die_plan/gen.py rtl from die_plan {P.name}, partition type {tn}.  Do not edit.\n"
            f"// Outline {t['outline_um'][0]:g} x {t['outline_um'][1]:g} um; one clock root (clk), one reset synchroniser,\n"
            "// a boundary flop on every port, reset-less data + one epoch bit per ft station, leaves bound by name.\n"
            "`timescale 1ns/1ps\n`default_nettype none\n")
    plist = "\n".join(f"    {d}{',' if i < len(ports) - 1 else ' '}  // {c}" for i, (d, c) in enumerate(ports))
    return head + f"module {mod} (\n" + plist + "\n);\n" + "\n".join(decl) + "\n" + "\n".join(body) + \
        f"\nendmodule : {mod}\n`default_nettype wire\n"


def die_top(P, epochs, dropped=None, rtl_root=None):
    io, wires, insts = [], [], []
    for pid, pr in P.ports.items():
        n = S.port_pins_count(pr)
        if pr["src"]["part"] == S.DIE_PART:
            io.append(f"    input  wire [{n - 1}:0] {sv_id(pr['src']['bus'])}")
        elif pr["dst"]["part"] == S.DIE_PART:
            io.append(f"    output wire [{n - 1}:0] {sv_id(pr['dst']['bus'])}")
        else:
            wires.append(f"    wire [{n - 1}:0] w_{sv_id(pid)};  // {pr['src']['part']}.{pr['src']['bus']} -> "
                         f"{pr['dst']['part']}.{pr['dst']['bus']}")
    for name, p in P.parts.items():
        for pd in P.types[p["type"]].get("pads", []):
            io.append(f"    {'input ' if pd['dir'] == 'in' else 'output'} wire [{pd['width'] - 1}:0] "
                      f"{sv_id(name)}_{sv_id(pd['name'])}")
    conn = {}
    for pid, pr in P.ports.items():
        if pr["src"]["part"] == S.DIE_PART:
            net = sv_id(pr["src"]["bus"])
        elif pr["dst"]["part"] == S.DIE_PART:
            net = sv_id(pr["dst"]["bus"])
        else:
            net = f"w_{sv_id(pid)}"
        for side in ("src", "dst"):
            if pr[side]["part"] != S.DIE_PART:
                conn.setdefault(pr[side]["part"], []).append((pr[side]["bus"], net))
    import infra_rtl as IR
    provider_ports = None
    if any(t.get("infra_ports") for t in P.types.values()):
        if not rtl_root:
            raise GenError("native infrastructure requires --rtl-root for actual provider validation")
        srcs = (P.raw.get("infrastructure") or {}).get("sources") or []
        if not srcs:
            raise GenError("infrastructure providers require explicit repo-relative source closure")
        base = Path(rtl_root).resolve()
        for f in srcs:
            if Path(f).is_absolute() or not (base / f).resolve().is_relative_to(base):
                raise GenError("infrastructure provider source must stay repo-relative")
        ih = leaf_headers(dict(sources=srcs), rtl_root)
        provider_ports = lambda mod: IR.provider_ports(ih, mod, parse_leaf_ports)
    iw, ii, ic = IR.die_lines(P, provider_ports)
    wires += iw
    insts += ii
    clock_conn = {}
    clock_names = {tn: {n for n, _, _ in S.tap_grid(P, tn)} | {n for n, _, _, _ in S.core_taps(P, tn)}
                   for tn in {p["type"] for p in P.parts.values()}} if ic else {}
    for pn, rows in ic.items():
        for port, net in rows:
            if port in clock_names[P.parts[pn]["type"]]:
                clock_conn[(pn, port)] = net
            else:
                conn.setdefault(pn, []).append((port, net))
    import reset_tree as RT
    rlines, rnet = RT.die_rtl(P) if RT.pipelined(P) else ([], {})
    wouts, snet = {}, {}
    if RT.wavefront(P):
        rlines, rnet, wouts = RT.wf_die_rtl(P)
        miss = sorted(n for n in P.parts if n not in rnet)
        if miss:
            raise GenError(f"reset wavefront: partitions without a reset source (reset_tree.py offsets): {miss[:10]}")
        if RT.start_broadcast(P):
            sl, snet, souts = RT.wf_die_start(P)
            rlines += sl
            for q, d in souts.items():
                wouts.setdefault(q, {}).update(d)
    for name, p in P.parts.items():
        t = P.types[p["type"]]
        # dropped taps (kit clock_taps.tcl: no sinks, COORD 10-23) stay unconnected: no dead spine drop
        dr = (dropped or {}).get(p["type"], ())
        cs = [f"        .{n}({'' if n in dr else clock_conn.get((name,n), 'clk')})" for n, _, _ in S.tap_grid(P, p["type"])] + \
            [f"        .{n}({clock_conn.get((name,n), 'clk')})" for n, _, _, _ in S.core_taps(P, p["type"])] + \
            [f"        .arst_n({rnet.get(name, 'rst_n')})"] + \
            [f"        .{n}({wouts.get(name, {}).get(n, '')})" for n, _, _ in RT.out_pins(P, p["type"])] + \
            ([f"        .start_i({snet[name]})"] if name in snet else []) + \
            [f"        .{n}({wouts.get(name, {}).get(n, '')})" for n, _, _ in RT.start_out_pins(P, p["type"])] + \
            [f"        .{sv_id(b)}({net})" for b, net in sorted(conn.get(name, []))] + \
            [f"        .{sp['name']}({sp['width']}'d{int(p['id_straps'][sp['name']])})" for sp in t.get("id_straps", [])] + \
            [f"        .{sv_id(pd['name'])}({sv_id(name)}_{sv_id(pd['name'])})" for pd in t.get("pads", [])]
        insts.append(f"    {t['module']} {sv_id(name)} (\n" + ",\n".join(cs) + "\n    );")
    mod = f"{sv_id(P.name)}_top"
    return (f"// GENERATED by tools/die_plan/gen.py rtl: die top of {P.name} (partitions abutted; die nets = clk spine,\n"
            "// rst_n, and the zero-length abutment wires w_<port>).  Do not edit.\n`timescale 1ns/1ps\n"
            "`default_nettype none\n"
            f"module {mod} (\n    input  wire clk,\n    input  wire rst_n" +
            (",\n    input  wire start" if RT.start_broadcast(P) else "") + "".join(",\n" + x for x in io) + "\n);\n"
            + "\n".join(wires + rlines) + "\n" + "\n".join(insts) + f"\nendmodule : {mod}\n`default_nettype wire\n")


def write_rtl(raw, out, rtl_root=None, types=None, plan_path=None, landing=None):
    """landing (opt-in, LAND-HEAD-BIND-1): the clock_landing_plan sidecar of a landed plan.  The SAME emitter the
    as-built binder uses (clock_landings.Landings.type_rtl / top_rtl) is applied to every generated wrapper and to the
    generated die top, so the landed form is one complete source-bound netlist; the declared observer is checked
    against its actual leaf header (one-bit inputs) before any ring is emitted."""
    errs = S.validate(raw)
    if errs:
        raise GenError("plan invalid:\n  " + "\n  ".join(errs[:20]))
    P = S.Plan(raw, plan_path)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    ep = bus_epochs(P)
    L = None
    if landing is not None:
        import clock_landings as CL
        if not raw.get("clock", {}).get("landing_network"):
            raise GenError("clock landing: the plan has no clock.landing_network (not a composed landed plan)")
        if types is not None:
            raise GenError("clock landing: --types is not allowed; every type must carry its landing hardware")
        try:
            L = CL.Landings(raw, landing)
            if landing.get("collector", {}).get("observer") != raw["clock"]["landing_network"].get("root_observer"):
                raise CL.LandingError("sidecar observer differs from the plan's landing_network.root_observer")
            if rtl_root is not None:
                L.validate_observer_native(lambda tn: leaf_headers(P.types[tn], rtl_root), parse_leaf_ports)
        except CL.LandingError as e:
            raise GenError(f"clock landing: {e}") from e
    (out / "ot_dp_cells.sv").write_text(CELLS)
    files = [out / "ot_dp_cells.sv"]
    for tn, t in sorted(P.types.items()):
        if t.get("hard") or (types is not None and tn not in types):
            continue
        f = out / f"{t['module']}.sv"
        text = wrapper(P, tn, ep, rtl_root)
        if L is not None:
            try:
                text = L.type_rtl(tn, text)
            except CL.LandingError as e:
                raise GenError(f"clock landing: {e}") from e
        f.write_text(text)
        files.append(f)
    f = out / f"{sv_id(P.name)}_top.sv"
    text = die_top(P, ep, rtl_root=rtl_root)
    if L is not None:
        try:
            text = L.top_rtl(text, {tn: t["module"] for tn, t in P.types.items()})
        except CL.LandingError as e:
            raise GenError(f"clock landing: {e}") from e
        man = L.manifest()
        if not man["implemented"]:
            raise GenError("clock landing: not every type/top was emitted")
        import json
        mf = out / "gen_clock_landings.json"
        mf.write_text(json.dumps(man, indent=1) + "\n")
        files.append(mf)
    f.write_text(text)
    files.append(f)
    # DIE-HEAD-4b: the type-uniform wavefront relay outs (rst_o_<k> / start_o_<k>) an instance leaves open are declared
    # spare outputs in the strict port-bind's default pad file <top>.sv.pads.json (same writer as bind.py).
    import reset_tree as RT
    try:
        RT.write_wf_open_pads(P, f, text, sv_id, fresh=True)   # not returned: callers compile the returned files
    except ValueError as e:
        raise GenError(str(e)) from e
    man = parent_id_manifest(P)
    if L is not None and getattr(L, "strap", None):
        # MESO-STRAP-1 (OWNER 12.15a): count straps strap_ca_* join the parent strap manifest (same 1.8 rules) and
        # their tie VALUES are audited against the bind (COORD addition, 12.14a): a wrong / missing tie = G0 ERROR
        import json
        import straps as STR
        cexp = L.strap_expected()
        for tn, ports in L.strap_declarations().items():
            man["types"].setdefault(tn, {}).update({sp: dict(width=w, kind="count_strap") for sp, w in ports.items()})
        for q, ports in cexp.items():
            man["instances"].setdefault(q, {}).update({sp: dict(width=w, value=v, kind="count_strap")
                                                       for sp, (w, v) in ports.items()})
        cva = STR.audit_count_strap_values(text, {CL.ident(q): v for q, v in cexp.items()})
        (out / "gen_count_strap_audit.json").write_text(json.dumps(cva, indent=1) + "\n")
        files.append(out / "gen_count_strap_audit.json")
        if cva["verdict"] != "PASS":
            raise GenError(f"count-strap tie-value audit (G0 ERROR): {cva['reason']}")
    if man["types"]:
        import json
        f = out / "parent_id_straps.json"
        f.write_text(json.dumps(man, indent=1) + "\n")
        files.append(f)
    return files


def parent_id_manifest(P):
    """the binder-manifest form (straps.manifest_straps / audit_top_ties) of the plan's partition ID straps."""
    types = {tn: {sp["name"]: dict(width=sp["width"]) for sp in t.get("id_straps", [])}
             for tn, t in sorted(P.types.items()) if t.get("id_straps")}
    inst = {n: {k: dict(width=types[p["type"]][k]["width"], value=v) for k, v in sorted(p["id_straps"].items())}
            for n, p in sorted(P.parts.items()) if p["type"] in types}
    return dict(schema="opentallas.parent_id_straps.v1", types=types, instances=inst, added_data_cycles=0,
                source="die_plan partition_types.<t>.id_straps + partitions[].id_straps (gen_rtl.die_top literals)")
