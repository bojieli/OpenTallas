"""TYPE-SAFE-2 11-06 (OWNER 18:5x types safe by construction; COORD 19:2x (4a)): gen-time ft station SPREAD.

Why: an ft slot whose plan gives station points (regs_um) but no per-bit sites (bit_sites_um) is placed by
face_flops.tcl ff_put_near: every bit of station j spirals round ONE point, so a 500-1500-bit bundle squeezes through a
~30-um clump at each station (TYPE-SAFE-1 19:09 estimate: the wiring overrun on S81/QC/KV/HBM is this clump, not the
corridor width; S81 congested types median track use 1.48 at the clump).

Form: at each planned station point (regs_um[j], unchanged, so hops, cycles, RTL and LEC are unchanged) the bits get a
COLUMN across the bundle in bit order: bit i sits at regs_um[j] + its window offset (in-window offset weighted 1 - j/k,
out-window offset weighted j/k, each along its own face), projected out of macro keep-offs and snapped to a free legal
row site (tools.die_trial RowAllocator, the ft_corridor.py grid and cell envelope).  The result is written as explicit
bit sites (ft_bit_sites.tcl), the form face_flops already places FIRM.

Fallback per slot (never a gate): if a bit cannot be projected within MAX_PROJ_UM, or a hop of the spread is longer
than both the reach budget and the clump's same hop + HOP_TOL_UM, the slot keeps the old clump form and the report
says why.  Slots that already have bit_sites_um, siteless slots (face_flops spreads them along each bit's own
route) and 1-station slots are untouched.

Default ON for every generated type; opt out per type with partition_types.<t>.ft_spread = false.  Signed types are not
regenerated by the kit wave, so their kits do not change.

track_use(): advisory gen-time track-use report (ft_track_use.json in the kit): per slot the window and station track
use (bits / (perpendicular extent x usable tracks/um), TYPE-SAFE-1 track_est method, target <= 0.5).  Report only.
"""
import math

import numpy as np

CELL = (1.404, .27)            # ft_corridor.CELL: bit-site cell envelope (um)
KEEPOFF = 2.0                  # ft_corridor.KEEPOFF: flop keep-off from a macro edge
CORE_MARGIN = 4.32             # gen_phys.CORE_MARGIN_UM
PROJ_STEPS = (1, 3, 6)          # retry radii (x MAX_PROJ_UM), as ft_corridor.place_slot
MAX_PROJ_UM = 40.0             # a bit may move at most this far to reach free space / a free site
HOP_TOL_UM = 5.0               # a spread hop may exceed the budget only if it is within this of the clump's same hop
REACH_UM = 405.0               # repeated reach (COORD GEOM-21 10-27); budget = REACH x 0.98 - 2 (ft_corridor default)
PITCH = dict(M2=.036, M3=.036, M4=.048, M5=.048, M6=.064, M7=.064)
H_LAYERS = ('M2', 'M4', 'M6')
V_LAYERS = ('M3', 'M5', 'M7')
DERATE = 0.25
TARGET = 0.5


def _axis(face):
    """coordinate that runs ALONG a face (x on N/S, y on E/W)."""
    return 0 if face in "NS" else 1


def enabled(t):
    return t.get("ft_spread", True) is not False and not t.get("hard")


def _pins(P, tn):
    from gen_phys import type_pins
    return {(bn, i): (x, y) for bn, i, _, x, y, _ in type_pins(P, tn)}


def _allocator(t):
    import schema as S
    from tools.die_trial.legal_sites import RowAllocator
    w, h = map(float, t["outline_um"])
    boxes = list(S.placed_macro_boxes(t, halo=KEEPOFF).values())
    m = CORE_MARGIN
    alloc = RowAllocator((m, m, w - m, h - m), blocked=boxes, cell_size=CELL, column_pitch=2.16, row_pitch=.27,
                         origin=(m, m))
    return alloc, boxes, (m + 1, m + 1, w - m - 1, h - m - 1)


def _hops(chain):
    return [float(np.abs(q - p).sum(axis=1).max()) for p, q in zip(chain, chain[1:])]


def spread_slot(slot, a, b, regs, alloc, boxes, bounds, budget):
    """-> (sites [(k-1) x (width+1) x 2 cell CENTRES], ledger) or (None, ledger) for the fallback.  Tries a bit
    projection / site search radius of MAX_PROJ_UM, then 3x and 6x (as ft_corridor.place_slot); the hop rule decides."""
    led = {}
    for f in PROJ_STEPS:
        sites, led = _spread_slot(slot, a, b, regs, alloc, boxes, bounds, budget, MAX_PROJ_UM * f)
        if sites is not None:
            return sites, led
    return None, led


def _spread_slot(slot, a, b, regs, alloc, boxes, bounds, budget, max_proj):
    from ft_corridor import project
    k = int(slot.get("stations", 1))
    off_in, off_out = a - a.mean(axis=0), b - b.mean(axis=0)
    e_in, e_out = np.zeros(2), np.zeros(2)
    e_in[_axis(slot.get("in_face", "W"))] = 1.0
    e_out[_axis(slot.get("out_face", "E"))] = 1.0
    base = set(alloc.used)
    sites = []
    for j in range(1, k):
        f = j / k
        c = np.asarray(regs[j], float)
        tgt = c[None] + (1 - f) * off_in * e_in[None] + f * off_out * e_out[None]
        q, dist = project(tgt, boxes, bounds)
        if not np.isfinite(dist).all() or dist.max() > max_proj:
            alloc.used = base
            worst = float(dist[np.isfinite(dist)].max()) if np.isfinite(dist).any() else math.inf
            return None, dict(form="clump", reason=f"station {j}: bit projection {worst:.1f} um > {max_proj:g}")
        perp = e_in if f <= .5 else e_out
        out = np.zeros_like(q)
        try:
            for bi in np.argsort(q @ perp, kind="stable"):
                p, _ = alloc.allocate(q[bi], 1, max_radius_um=max_proj)
                out[bi] = p[0]
        except ValueError as ex:
            alloc.used = base
            return None, dict(form="clump", reason=f"station {j}: {ex}")
        sites.append(out)
    clump = [a] + [np.repeat(np.asarray(regs[j], float)[None], len(a), axis=0) for j in range(1, k)] + [b]
    spread = [a] + sites + [b]
    h_cl, h_sp = _hops(clump), _hops(spread)
    led = dict(max_proj_um=max_proj, hops_um=[round(x, 1) for x in h_sp], clump_hops_um=[round(x, 1) for x in h_cl], budget_um=round(budget, 1))
    worse = [j for j, (s_, c_) in enumerate(zip(h_sp, h_cl)) if s_ > max(budget, c_ + HOP_TOL_UM) + 1e-6]
    if worse:
        alloc.used = base
        j = worse[0]
        led.update(form="clump", reason=f"hop {j}: spread {h_sp[j]:.1f} um > budget {budget:.1f} and clump "
                                        f"{h_cl[j]:.1f} + {HOP_TOL_UM}")
        return None, led
    led["form"] = "spread"
    return sites, led


def spread_type(P, tn, t, reach_um=REACH_UM, margin=.98):
    """-> (ft_slots for ft_bit_sites.table: spread slots carry generated bit_sites_um, others as in the plan, ledger)."""
    slots = list(t.get("ft_slots", []) or [])
    ledger = []
    todo = [s for s in slots if int(s.get("stations", 1)) >= 2 and not s.get("bit_sites_um")
            and len(s.get("regs_um") or []) >= int(s.get("stations", 1))]
    if not enabled(t) or not todo:
        for s in todo:
            ledger.append(dict(slot=s["name"], width=s["width"], form="clump", reason="ft_spread off"))
        return slots, ledger
    pins = _pins(P, tn)
    alloc, boxes, bounds = _allocator(t)
    for s in slots:                                   # plan-audited explicit sites stay reserved
        if s.get("bit_sites_um"):
            cw, ch = s.get("bit_site_cell_um") or CELL
            for st in s["bit_sites_um"]:
                for x, y in st:
                    alloc.reserve_rectangle((x, y, x + cw, y + ch))
    budget = reach_um * margin - 2.0
    out = []
    done = {}
    for s in sorted(todo, key=lambda s: -int(s["width"])):
        name, wd = s["name"], int(s["width"]) + 1
        try:
            a = np.array([pins[(name + "_i", i)] for i in range(wd)], float)
            b = np.array([pins[(name + "_o", i)] for i in range(wd)], float)
        except KeyError as ex:
            ledger.append(dict(slot=name, width=s["width"], form="clump", reason=f"pin missing {ex}"))
            continue
        sites, led = spread_slot(s, a, b, s["regs_um"], alloc, boxes, bounds, budget)
        led.update(slot=name, width=s["width"], stations=int(s["stations"]))
        ledger.append(led)
        if sites is not None:
            done[name] = [(p - np.array([CELL[0] / 2, CELL[1] / 2])).round(6).tolist() for p in sites]
    for s in slots:
        if s["name"] in done:
            s = dict(s, bit_site_cell_um=list(CELL), bit_sites_um=done[s["name"]])
        out.append(s)
    return out, ledger


def _tracks(slot, horiz):
    ls = [l for l in (slot.get("layers") or slot.get("in_layers") or []) if l in (H_LAYERS if horiz else V_LAYERS)]
    ls = ls or (['M4', 'M6'] if horiz else ['M5', 'M7'])
    return (1 - DERATE) * sum(1 / PITCH[l] for l in ls if l in PITCH)


def track_use(slots, ledger=()):
    """advisory per-slot track use (bundle bits / perpendicular extent x usable tracks per um); report only."""
    form = {r["slot"]: r.get("form") for r in ledger}
    rows = []
    for s in slots:
        W, k = int(s["width"]), int(s.get("stations", 1))
        horiz = s.get("in_face", "W") in "EW"           # E/W slot: bits run horizontally, stacked along y
        tpu = _tracks(s, horiz)
        win = [abs(float(w[1]) - float(w[0])) for w in (s.get("in_window_um"), s.get("out_window_um")) if w]
        u_win = (W / (min(win) * tpu)) if win and min(win) > 0 else None
        ext = []
        if s.get("bit_sites_um"):
            for st in s["bit_sites_um"]:
                c = sorted(p[1] if horiz else p[0] for p in st[:W])
                lo, hi = c[int(.02 * len(c))], c[max(int(.98 * len(c)) - 1, 0)]
                ext.append(hi - lo + (CELL[1] if horiz else CELL[0]))
            f = form.get(s["name"]) or "sites"
        elif len(s.get("regs_um") or []) >= k and k >= 2:
            ext = [math.sqrt(W * CELL[0] * CELL[1]) * 1.15] * (k - 1)    # ff_put_near spiral clump
            f = "clump"
        else:
            f = "route" if k >= 2 else "no_station"
        u_st = (W / (min(ext) * tpu)) if ext else None
        rows.append(dict(slot=s["name"], width=W, stations=k, form=f,
                         u_window=None if u_win is None else round(u_win, 3),
                         u_station=None if u_st is None else round(u_st, 3),
                         over_target=bool(u_st is not None and u_st > TARGET)))
    return dict(schema="opentallas.ft_track_use.v1", advisory=True, target=TARGET, derate=DERATE, slots=rows)
