import json
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lane_asbuilt_latency as LAL  # noqa: E402


def st(name, w=8):
    return f"    ot_dp_st #(.W({w})) {name} (.clk(clk), .rst_n(rst_n), .d(a), .ea(b), .q(c), .eq(e));\n"


def module(name, tn, body):
    return (f"// GENERATED by tools/die_plan/bind.py from die_plan t + the as-built die (x), partition type {tn}.  Do not edit.\n"
            f"module {name} (input clk);\n{body}endmodule\n")


def src_rtl(native=0, bout_pads=0):
    return (st("u_bout_o") + "".join(st(f"u_bout_o_pad{j}") for j in range(bout_pads))
            + "".join(st(f"u_ist_o_{j}") for j in range(native)))


def dst_rtl(D=0, core=0, cores=("u_lane4", "u_lane5")):
    b = st("u_bin_i")
    if D:
        b += f"    ot_dp_dly #(.W(9), .D({D})) u_lpad_i (.clk(clk), .d({{i_eb, i_b}}), .q({{i_eq, i_q}}));  // lane pad\n"
    for g, c in enumerate(cores if core else ()):
        b += "".join(st(f"u_ist_i__{c}_{g}_{j}") for j in range(core))
    return b


def plan(table=15, fixed=9, tfixed=None, src_regs=2, dst=None, ft=None, landing=4):
    """one lane L0: p (type S, bus o) -> q (type R, bus i); optional ft partition f (type F, slot out bus fo)"""
    ports = [dict(id="L0__0", src=dict(part="p", bus="o"), dst=dict(part="f" if ft else "q", bus="fi" if ft else "i"))]
    if ft:
        ports.append(dict(id="L0__1", src=dict(part="f", bus="fo"), dst=dict(part="q", bus="i")))
    return dict(
        partitions=[dict(name="p", type="S"), dict(name="q", type="R"), dict(name="f", type="F")],
        partition_types=dict(
            S=dict(module="S", buses=[dict(name="o", dir="out", width=8)],
                   internal_stations=[dict(conn="bus:o", regs_um=[[k, 0] for k in range(src_regs)])] if src_regs else []),
            R=dict(module="R", buses=[dict(name="i", dir="in", width=8)], internal_stations=dst or []),
            F=dict(module="F", buses=[])),
        ports=ports, lanes=[dict(id="L0", ports=[x["id"] for x in ports], fixed_cycles=fixed)],
        latency=dict(lanes=dict(L0=dict(cycles=table, fixed=fixed if tfixed is None else tfixed, clock_landing=landing))))


def run(P, srtl, drtl, landing=4, frtl="", pricing=None, extra_rows=()):
    mods = {"p": LAL.ModuleIndex(srtl), "q": LAL.ModuleIndex(drtl), "f": LAL.ModuleIndex(frtl)}
    rows = [dict(lane="L0", src="p", dst="q", bus_out="o", bus_in="i", plan_cycles=P["latency"]["lanes"]["L0"]["cycles"])]
    rows += list(extra_rows)
    pt = {p["name"]: p["type"] for p in P["partitions"]}
    return LAL.check(P, rows, mods.get, pt.get, P["partition_types"], {"L0": landing}.get, pricing=pricing)


class LaneAsBuilt(unittest.TestCase):
    def test_qc_double_pad_fails(self):
        # QC c_W5_tf_01__b00 shape (bind_c8t, switch off): table 15 = 2 + fixed 9 (7 dest + 2 source) + landing 4;
        # receiver pad D9 already holds the 2 source stations the kit inserts again -> delivered 17
        recs, errs = run(plan(), src_rtl(), dst_rtl(D=9))
        self.assertEqual(recs[0]["delivered"], 17)
        self.assertEqual(recs[0]["source"]["kit_ist"], 2)
        self.assertEqual(recs[0]["verdict"], "FAIL")
        self.assertEqual(recs[0]["class"], ["DOUBLE_PAD"])
        self.assertEqual(len(errs), 1)
        self.assertIn("LANE_ASBUILT L0: delivered 17 != latency table 15 (+2", errs[0])

    def test_qc_double_pad_with_switch_on_passes(self):
        # same lane bound with kit_source_station_pricing on: the bind lands D7 (9 - 2 source stations)
        recs, errs = run(plan(), src_rtl(), dst_rtl(D=7))
        self.assertEqual((recs[0]["delivered"], recs[0]["verdict"], errs), (15, "PASS", []))

    def test_pricing_prediction_both_ways(self):
        recs, errs = run(plan(), src_rtl(), dst_rtl(D=9), pricing="on")        # OFF bind, predicted ON
        self.assertEqual((recs[0]["delivered"], recs[0]["receiver"]["lpad"], errs), (15, 7, []))
        recs, errs = run(plan(), src_rtl(), dst_rtl(D=7), pricing="off")       # ON bind, predicted OFF
        self.assertEqual((recs[0]["delivered"], recs[0]["receiver"]["lpad"]), (17, 9))

    def test_kv_native_stations_pass(self):
        # KV L505 shape: the source stations are native (u_ist_o_* already in the bound RTL), so the kit inserts 0
        recs, errs = run(plan(table=7, fixed=2, landing=0), src_rtl(native=2), dst_rtl(D=3), landing=0)
        self.assertEqual(recs[0]["source"]["kit_ist"], 0)
        self.assertEqual((recs[0]["delivered"], recs[0]["verdict"], errs), (7, "PASS", []))
        recs, _ = run(plan(table=7, fixed=2, landing=0), src_rtl(native=2), dst_rtl(D=3), landing=0, pricing="on")
        self.assertEqual(recs[0]["verdict"], "PASS")                               # native: the switch changes nothing

    def test_receiver_core_chain_unpriced_fails(self):
        # QC su_l1 flt_su_c_i shape (COORD addendum): receiver per-core pin-face chains of 4 (kit core_pin_stations),
        # lane fixed_cycles 4 but the table row still says fixed 0 -> table 4, delivered 8
        dst = [dict(conn="bus:i", core=c, core_bits=[0], bit_route="per_bit", leaf_um=[0, 0],
                    regs_um=[[k, 0] for k in range(4)]) for c in ("u_lane4", "u_lane5")]
        P = plan(table=4, fixed=4, tfixed=0, src_regs=0, dst=dst, landing=2)
        recs, errs = run(P, src_rtl(), dst_rtl(), landing=2)
        self.assertEqual((recs[0]["delivered"], recs[0]["receiver"]["kit_ist"]), (8, 4))
        self.assertEqual(recs[0]["class"], ["STALE_TABLE"])
        self.assertEqual(len(errs), 1)
        # the same chains already in the bound RTL are counted once, not again as kit stations
        recs, _ = run(P, src_rtl(), dst_rtl(core=4), landing=2)
        self.assertEqual((recs[0]["delivered"], recs[0]["receiver"]["kit_ist"]), (8, 0))

    def test_receiver_bus_stations(self):
        dst = [dict(conn="bus:i", regs_um=[[k, 0] for k in range(3)])]
        # a packed receiver pad absorbs the IN stations (kit_istations packed_input_delay): D5 counts 5, kit 0
        recs, errs = run(plan(table=11, fixed=5, src_regs=0, dst=dst), src_rtl(), dst_rtl(D=5))
        self.assertEqual((recs[0]["receiver"]["kit_ist"], recs[0]["verdict"]), (0, "PASS"))
        # no pad: the kit inserts all 3 and the table (fixed 0) never priced them
        recs, errs = run(plan(table=6, fixed=0, src_regs=0, dst=dst), src_rtl(), dst_rtl())
        self.assertEqual((recs[0]["delivered"], recs[0]["class"]), (9, ["UNPRICED_KIT_STATIONS"]))

    def test_ft_stations_counted(self):
        frtl = st("u_ft_fo_0") + st("u_ft_fo_1") + st("u_fx_fo_0")
        recs, errs = run(plan(table=12, fixed=7, ft=True, landing=0, src_regs=2), src_rtl(), dst_rtl(D=5), landing=0,
                         frtl=frtl)
        self.assertEqual((recs[0]["ft"], recs[0]["delivered"], recs[0]["verdict"]), (3, 12, "PASS"))

    def test_every_failing_lane_in_one_pass(self):
        P = plan()
        P["lanes"].append(dict(id="L1", ports=["L0__0"], fixed_cycles=9))
        P["latency"]["lanes"]["L1"] = dict(cycles=15, fixed=9, clock_landing=4)
        recs, errs = run(P, src_rtl(), dst_rtl(D=9),
                         extra_rows=[dict(lane="L1", src="p", dst="q", bus_out="o", bus_in="i", plan_cycles=15)])
        self.assertEqual([e.split(":")[0] for e in errs], ["LANE_ASBUILT L0", "LANE_ASBUILT L1"])
        self.assertEqual(LAL.summary(recs)["failed"], 2)

    def test_registered_hard_end_and_unobserved(self):
        recs, _ = run(plan(), "", dst_rtl(D=9),
                      extra_rows=[])
        self.assertIn("no u_bout_o face register", recs[0]["problems"][0])
        mods = {"p": LAL.ModuleIndex(src_rtl())}
        P = plan()
        recs, errs = LAL.check(P, [dict(lane="L0", src="p", dst="q", bus_out="o", bus_in="i")], mods.get,
                               lambda p: "S", P["partition_types"], lambda lane: 4)
        self.assertEqual((recs[0]["verdict"], errs), ("UNOBSERVED", []))


class Cli(unittest.TestCase):
    def bind_dir(self, d, D):
        rtl = d / "bind" / "rtl"
        rtl.mkdir(parents=True)
        (rtl / "S.sv").write_text(module("S", "S", src_rtl()))
        (rtl / "R.sv").write_text(module("R", "R", dst_rtl(D=D)))
        (rtl / "t_bound_top.sv").write_text("module t_bound_top;\n    S p (\n    .clk(clk));\n    R #(.X(1'b1)) q (\n    .clk(clk));\nendmodule\n")
        (d / "bind" / "bind_latency.json").write_text(json.dumps(dict(buses=[
            dict(lane="L0", src="p", dst="q", bus_out="o", bus_in="i", plan_cycles=15)])))
        (d / "bind" / "bind_clock_landings.json").write_text(json.dumps(dict(lane_added_cycles={"L0": 4})))
        (d / "plan.json").write_text(json.dumps(plan()))
        (d / "ab_off.json").write_text("{}")
        return str(d / "bind"), str(d / "plan.json")

    def test_cli_off_bind(self):
        with tempfile.TemporaryDirectory() as t:
            bd, pl = self.bind_dir(Path(t), 9)
            self.assertEqual(LAL.main([bd, pl, "--tsv", t + "/o.tsv"]), 4)
            self.assertIn("DOUBLE_PAD", Path(t + "/o.tsv").read_text())
            self.assertEqual(LAL.main([bd, pl, "--asbuilt", t + "/ab_off.json", "--pricing", "on"]), 0)

    def test_cli_on_bind_and_no_top(self):
        with tempfile.TemporaryDirectory() as t:
            bd, pl = self.bind_dir(Path(t), 7)
            self.assertEqual(LAL.main([bd, pl, "--json", t + "/o.json"]), 0)
            self.assertEqual(json.loads(Path(t + "/o.json").read_text())["summary"]["passed"], 1)
            (Path(bd) / "rtl" / "t_bound_top.sv").unlink()
            with self.assertRaises(SystemExit):
                LAL.main([bd, pl])


class BindHook(unittest.TestCase):
    def test_bind_check_reads_emitted_rtl(self):
        # the strict-bind hook: B.parts/B.types/B.links + out/rtl/<module>.sv; spine lanes skipped
        with tempfile.TemporaryDirectory() as t:
            rtl = Path(t) / "rtl"
            rtl.mkdir()
            (rtl / "S.sv").write_text(module("S", "S", src_rtl()))
            (rtl / "R.sv").write_text(module("R", "R", dst_rtl(D=9)))
            P = plan()
            B = SimpleNamespace(plan=P, types=P["partition_types"], parts={p["name"]: p for p in P["partitions"]},
                                links=[dict(lane="L0", clock_landing_cycles=4), dict(lane="SP", spine=True)])
            lat = [dict(lane="L0", src="p", dst="q", bus_out="o", bus_in="i", plan_cycles=15),
                   dict(lane="SP", src="p", dst="q", bus_out="o", bus_in="i", plan_cycles=3)]
            recs, errs = LAL.bind_check(B, t, lat)
            self.assertEqual([r["lane"] for r in recs], ["L0"])
            self.assertEqual(len(errs), 1)
            self.assertIn("delivered 17 != latency table 15", errs[0])


if __name__ == "__main__":
    unittest.main()
