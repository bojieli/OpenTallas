#!/usr/bin/env python3
"""R8-REFRESH (QC-PLAN-R8 11-21, COORD: R8_STALE hit QC V2, KV D27c and sle variant B -> one class): refresh the R8 landing
table AND every asbuilt land_r8_extra table from a bind's bus_groups.json, so a re-bind never runs on a stale table.

  1 derive   land_r8_derive.py derive PLAN BUS_GROUPS --like TABLE --out TABLE [--pin-pre PRE --pin-extra N]
             (the QC s29 deliberate pin rides along when --pin-pre is given; same call as qc_r8_pinned.sh)
  2 extras   each table in asbuilt.land_r8_extra is AUTHORITATIVE over the derived table in the bind (Binder.load_r8); a member
             whose id is in the fresh derivation takes its bound/landed from it, its pad and every other field stay
             (tree-align pads are the extra table's own content).  INNER:* members are left alone.
Tables are replaced via tmp + rename.  TREE-WRITE-GUARD (FLOW-FLEET-R1 11-22): every table path must resolve inside its tree root
(--root when the path is under it, else the nearest tree marker; tree_write_guard.py), else exit 3 before anything is written.  Exit 0 = refreshed; the summary line names members changed per table.

UNDERIVED-1125 (KV-PV-ESTRIP: pv_v_pads_ffkpv.json, 68 members bound 43 vs table 42, survived 4 refresh+rebind loops with "rebound 0"): a
table whose members the derive cannot produce (KV pv_v_pads, kind kv_pv_v_landing: pvw_* ids, regenerated by its own law code) was skipped
silently.  Now, when the bind that wrote BUS_GROUPS also wrote r8_stale_all.json (same dir, not older than bus_groups.json) and a table
it names still has stale members this refresh did not rebound, exit 5 "R8_REFRESH FAIL UNDERIVED <table> <n> stale member(s) ...; regenerate: <recipe by
the table's kind>" instead of "OK".  Tables of other kinds get the generic wording.

Use it between a bind that reported R8_STALE and the re-bind (see bind_r8_loop in the die bind scripts):
  python3 -I tools/die_plan/r8_refresh.py PLAN BIND_OUT/bus_groups.json TABLE --asbuilt ASBUILT [--pin-pre PRE] [--pin-extra N]
"""
import argparse, json, os, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def rebound_extra(derived, extra):
    """derived/extra: table dicts. Returns (new extra dict, changed count, {delta: n})."""
    D = {m["id"]: m for m in derived["members"]}
    X = json.loads(json.dumps(extra)); n = 0; delta = {}
    for m in X["members"]:
        if m["id"].startswith("INNER:"):
            continue
        t = D.get(m["id"])
        if t is None or (m.get("bound"), m.get("landed")) == (t["bound"], t["landed"]):
            continue
        k = t["bound"] - m["bound"]; delta[k] = delta.get(k, 0) + 1
        m["bound"], m["landed"] = t["bound"], t["landed"]; n += 1
    return X, n, delta


REGEN_BY_KIND = {
    "kv_pv_v_landing": "python3 -I physical/die_plan/qwen_kvsys/r8/kv_pv_v_pads.py pads BIND_NOPVV R8_LANDING OUT.json --e-min-pad 10 "
                       "(BIND_NOPVV = a strict bind with this table removed from asbuilt.land_r8_extra), install OUT.json as the table, rebind",
}


def underived(bus_groups, summary, tables, clock=os.path.getmtime):
    """-> [(table basename, stale members, recipe)]: tables named by the bind's r8_stale_all.json that this refresh did not rebound.
    tables = {basename: parsed table or None}.  Silent (empty) when the stale report is absent or older than bus_groups."""
    bg = Path(bus_groups)
    sf = bg.with_name("r8_stale_all.json")
    try:
        if clock(sf) < clock(bg) - 60:
            return []
        by = json.loads(sf.read_text()).get("by_table") or {}
    except (OSError, ValueError):
        return []
    out = []
    for name, n in sorted(by.items()):
        if n and name in tables and (summary.get(name) or {}).get("rebound", 0) == 0:
            kind = (tables[name] or {}).get("kind") or "?"
            out.append((name, n, f"kind {kind}: " + REGEN_BY_KIND.get(kind, "re-derive it with its own generator")))
    return out


def _write(path, obj):
    tmp = path.with_name(path.name + ".r8refresh.tmp")
    tmp.write_text(json.dumps(obj, indent=1)); os.replace(tmp, path)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("plan"); ap.add_argument("bus_groups"); ap.add_argument("table")
    ap.add_argument("--asbuilt", required=True, help="asbuilt json (its land_r8_extra list, paths relative to --root)")
    ap.add_argument("--root", default=None, help="tree root the asbuilt paths are relative to (default: cwd); also the write-guard root")
    ap.add_argument("--pin-pre"); ap.add_argument("--pin-extra")
    A = ap.parse_args(argv)
    root = Path(A.root or ".")
    tool = next((t for t in (HERE / "land_r8_derive.py", Path.cwd() / "tools/die_plan/land_r8_derive.py") if t.is_file()), None)
    if tool is None:      # a copied r8_refresh.py outside tools/die_plan (QC b12 11-21): derive from the launch tree (cwd)
        print("R8_REFRESH FAIL no land_r8_derive.py next to this tool or under ./tools/die_plan"); return 2
    sys.path.insert(0, str(tool.parent)); sys.path.append(str(HERE))
    import tree_write_guard as TWG
    extras = json.loads(Path(A.asbuilt).read_text()).get("land_r8_extra", [])
    targets = [Path(A.table)] + [Path(xf) if Path(xf).is_absolute() else root / xf for xf in extras]
    # QC-R8-SYMLINK 11-24: --root applies when the target lies under it lexically or by real path (symlinked launch view)
    bad = [w for w in (TWG.refusal(t, TWG.root_for(t, A.root)) for t in targets) if w]
    if bad:
        print("R8_REFRESH REFUSED " + " | ".join(bad)); return 3
    cmd = [sys.executable, "-I", str(tool), "derive", A.plan, A.bus_groups, "--like", A.table, "--out", A.table]
    troot = TWG.root_for(A.table, A.root)
    if troot and '"--root"' in tool.read_text(errors="replace"):   # the derive's own --out guard judges against the same root
        cmd += ["--root", troot]
    if A.pin_pre:
        cmd += ["--pin-pre", A.pin_pre] + (["--pin-extra", A.pin_extra] if A.pin_extra is not None else [])
    r = subprocess.run(cmd, capture_output=True, text=True)
    sys.stdout.write(r.stdout[-2000:]); sys.stderr.write(r.stderr[-4000:])
    if r.returncode:
        print(f"R8_REFRESH FAIL derive rc {r.returncode}"); return r.returncode
    derived = json.loads(Path(A.table).read_text())
    summary, parsed = {}, {}
    for xf in extras:
        p = Path(xf) if Path(xf).is_absolute() else root / xf
        cur = json.loads(p.read_text())
        parsed[p.name] = cur
        X, n, delta = rebound_extra(derived, cur)
        if n:
            _write(p, X)
        summary[p.name] = dict(rebound=n, delta=delta)
    bad = underived(A.bus_groups, summary, parsed)
    if bad:
        for name, n, recipe in bad:
            print(f"R8_REFRESH FAIL UNDERIVED {name}: {n} stale member(s) in the bind's r8_stale_all.json and this refresh rebound 0 "
                  f"(the derive cannot produce them); regenerate: {recipe}")
        return 5
    print("R8_REFRESH OK table", A.table, "extras", json.dumps(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
