#!/usr/bin/env python3
"""Q-B2 10-16: NEW parameter-free calibrated controller / issuer successors from allocator-derived constants.

The constants come ONLY from tools/qwen_b2_join/allocator_ledger.py on an actual allocator run (never zero-filled):
  controller: qfd_tt_ctlm_b2_<ID>  = qfd_tt_ctlm_b2 with XPF_TRANSPORT_EDGES fixed, its body/tree copies renamed and the
              tree's band-link constants LNK / CLNK set (ot_qfd_tt_ctl_b2: RX = 5 + 2 LNK + CLNK, selects CLNK early)
  issuer:     qfd_res_train_issue_b2_<ID> = parameter-free wrapper of qfd_res_train_issue_b2 #(.TRAIN_EDGES(TE))
The port ABI of each successor is byte-for-byte the original's header (b2_graph.install_calibrated_sources refuses any
ABI change).  Text substitutions are counted: each must hit exactly once or generation fails.
"""
import argparse, hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CTL = 'rtl/qwen_sys/static_schedule_20261014/qfd_tt_ctlm_b2.sv'
PAR = 'rtl/qwen_sys/static_schedule_20261014/ot_qfd_tt_ctlm_b2_parent.sv'
TREE = 'rtl/qwen_sys/static_schedule_20261014/qfd_tt_ctlm_tree_b2.sv'
ISS = 'rtl/qwen_split/qfd_res_train_issue_b2.sv'
OUT = 'rtl/qwen_split/cal_b2'


def once(t, a, b, what):
    n = t.count(a)
    if n != 1:
        raise ValueError(f'{what}: expected exactly one "{a[:60]}", found {n}')
    return t.replace(a, b)


def header(text, mod):
    m = re.search(r'module\s+' + mod + r'\s*#\(.*?\)\s*\((.*?)\);', text, re.S)
    if not m:
        raise ValueError(f'{mod}: header not found')
    return m.group(1)


def make(ident, lnk, clnk, te, xpf, root=ROOT):
    for k, v in dict(lnk=lnk, clnk=clnk, te=te, xpf=xpf).items():
        if type(v) is not int or v < 0:
            raise ValueError(f'{k} must be an actual nonnegative integer from the allocator ledger, got {v!r}')
    if te < 2:
        raise ValueError('TRAIN_EDGES must be >= 2')
    cm, pm, tm, im = (f'qfd_tt_ctlm_b2_{ident}', f'ot_qfd_tt_ctlm_b2_parent_{ident}', f'qfd_tt_ctlm_tree_b2_{ident}',
                      f'qfd_res_train_issue_b2_{ident}')
    src = {p: (root / p).read_text() for p in (CTL, PAR, TREE, ISS)}
    tag = (f'// GENERATED by tools/qwen_b2_join/make_calibrated_sources.py ({ident}): allocator-calibrated successor.\n'
           f'// LNK {lnk}, CLNK {clnk}, TRAIN_EDGES {te}, XPF_TRANSPORT_EDGES {xpf}. Sources: '
           + ', '.join(f'{p} {hashlib.sha256(t.encode()).hexdigest()[:16]}' for p, t in src.items()) + '\n')
    c = src[CTL]
    c = once(c, 'module qfd_tt_ctlm_b2 #(parameter integer XPF_TRANSPORT_EDGES=-1) (',
             f'module {cm} (', 'controller header')
    c = once(c, 'generate if(XPF_TRANSPORT_EDGES<0)', f'localparam integer XPF_TRANSPORT_EDGES={xpf};\n    generate if(XPF_TRANSPORT_EDGES<0)',
             'controller xpf')
    c = once(c, 'ot_qfd_tt_ctlm_b2_parent u_body', f'{pm} u_body', 'controller body')
    p = once(src[PAR], 'module ot_qfd_tt_ctlm_b2_parent (', f'module {pm} (', 'parent header')
    p = once(p, 'qfd_tt_ctlm_tree_b2 u_tree', f'{tm} u_tree', 'parent tree')
    t = once(src[TREE], 'module qfd_tt_ctlm_tree_b2 #(', f'module {tm} #(', 'tree header')
    t = once(t, '.LNK(0), .CLNK(0)', f'.LNK({lnk}), .CLNK({clnk})', 'tree link constants')
    i = src[ISS]
    ports = header(i, 'qfd_res_train_issue_b2')
    names = re.findall(r'(\w+)\s*(?=,|$)', re.sub(r'\[[^\]]*\]', '', re.sub(r'\b(input|output|wire|reg)\b', '', ports)))
    names = [n for n in names if n]
    if 'fault' not in names or 'ck' not in names:
        raise ValueError(f'issuer port parse failed: {names}')
    iw = (f'`timescale 1ns/1ps\nmodule {im}({ports.replace("output reg fault", "output wire fault")});\n'
          f' qfd_res_train_issue_b2 #(.TRAIN_EDGES({te})) u_issue(' + ','.join(f'.{n}({n})' for n in names) + ');\nendmodule\n')
    out = root / OUT / ident
    out.mkdir(parents=True, exist_ok=True)
    files = {}
    for name, text in ((f'{cm}.sv', c), (f'{pm}.sv', p), (f'{tm}.sv', t), (f'{im}.sv', iw)):
        (out / name).write_text(tag + text)
        files[name] = hashlib.sha256((out / name).read_bytes()).hexdigest()
    rel = lambda n: f'{OUT}/{ident}/{n}'
    rec = dict(ident=ident, constants=dict(LNK=lnk, CLNK=clnk, TRAIN_EDGES=te, XPF_TRANSPORT_EDGES=xpf),
               calibrated_sources=dict(controller=dict(module=cm, path=rel(f'{cm}.sv'), sha256=files[f'{cm}.sv']),
                                       issuer=dict(module=im, path=rel(f'{im}.sv'), sha256=files[f'{im}.sv'])),
               support=[rel(f'{pm}.sv'), rel(f'{tm}.sv')], files=files)
    (out / 'calibration_sources.json').write_text(json.dumps(rec, indent=1) + '\n')
    return rec


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('ledger', type=Path, help='allocator_ledger.py output (status LEDGER_OK)')
    ap.add_argument('--ident', required=True)
    a = ap.parse_args(argv)
    L = json.loads(a.ledger.read_text())
    if L.get('status') != 'LEDGER_OK':
        raise SystemExit(f'ledger not OK: {L.get("structural_issues")}')
    k = L['constants']
    print(json.dumps(make(a.ident, k['controller_lnk'], k['controller_clnk'], k['train_edges'], k['xpf_transport_edges']), indent=1))


if __name__ == '__main__':
    main()
