#!/usr/bin/env python3
"""Ask both elaborators whether the two-tile dependent chain can be built yet.

``docs/CHIP_ARCHITECTURE_DESIGN.md`` section 3.6 names the five terms of the
exposed dependent boundary -- "the last result, mesh transfer, operand
readiness, queue admission, and acknowledged completion" -- and section 13
item 13's acceptance is that "RE8 and T64 exist (section 11.4 items 2), a
two-tile dependent chain is simulated on both simulators, its measured
boundary replaces both the 39 and the 120, and ``technology.json#latency`` is
re-derived from it with the grade ``executed``".

**RE8 and T64 existing is not sufficient, and this campaign is what
establishes that rather than asserting it.**  The chain needs a hardware path
from a producer tile's PARTIAL port into the reduction endpoint's leaf port,
and a second one from the endpoint's root, across the mesh, into a consumer
tile's ACTIVATION write port.  Neither exists.  In the vehicle T64 was
qualified in, the endpoint's operands are driven from OUTSIDE the vehicle by
the checker, over partials the checker captured; the tile's partial port and
the activation write port are not brought out of it at all.

That is a claim about module interfaces, so it is put to the tools that
resolve module interfaces instead of being read off the source text: for each
signal the chain would have to carry, both elaborators are asked to connect a
wire to it on an instance of the vehicle.  A port accepts the connection; an
internal net is refused, and the refusal is quoted.  Both elaborators must
agree on every signal.

**This record is deliberately NOT the boundary section 13 item 13 asks for**,
and it says so in ``boundary.is_the_section_13_item_13_boundary``, which
``tools/derive_cycle_machine.py::_boundary_measurement`` reads.  The
calibration therefore still finds the boundary unmeasured and G4 still fails
on it -- with a specific reason instead of a bare absence.  Nothing here
touches ``configs/hardware/technology.json``: its
``latency.pipeline_fill_drain_s`` stays graded ``assumed``, because no
measurement of the thing it prices exists.
"""

