#!/usr/bin/env python3
"""STEWARD-HBMe/IDX 10-23: PRE_GLOBAL_PLACE fences for the selector cluster c19a (MAIN) / c19b (FB).

Coordinator tile review 10-23 (c18 BAD: input pin registers floated to the column gap, p90 pin->reg 506-534 um,
quadrant roots spread 400-700 um).  c19 keeps the c18 RTL (FACE=1 OUTST=2) and the c13 landing ownership, and adds
one EXCLUSIVE box per physical band so every pin register sits at its face and every column crossing is one hop:
  wtop / wbot  W band beside q0 / q2: in_line_0/2 pa+pr, in_line_1/3 pa, q0 / q2 landings (their ctl pins are on W)
  mtop / mbot  mid channel beside q1 / q3 W pins: in_line_1/3 pr, selected_0/2 fr, q1 / q3 landings
  etop / ebot  E band: every fd, selected_1/3 fr
  ctl          row gap around u_ctl: ctl landings, reset run, op/pass/addr/k/rst_n pr, fault fr
  spa          S face under u_ctl: op/pass/addr/k/rst_n pa, fault fd
Usage: hidx_sel_s3p_c19_fences.py c19a|c19b  (writes hidx_sel_s3p_<tag>_fences.tcl next to this file)."""
import sys
from pathlib import Path

HALO = 5.4
CM = 2.16
GEOM = {   # W, H, left x, right x (children 259.2 x 216 on the 43.2 lattice), rows y, ctl origin
    "c19a": dict(W=630.72, H=587.52, xl=43.2, xr=345.6, yb=43.2, yt=345.6, ctl=(302.4, 280.8)),
    "c19b": dict(W=691.2, H=587.52, xl=43.2, xr=388.8, yb=43.2, yt=345.6, ctl=(345.6, 280.8)),
}
CW, CH, CTL = 259.2, 216.0, 29.16

# c13 landing ownership (reader/writer region per landing), unchanged
OWN = ("u_lpl_0_r ctl u_lpl_0_w q0 u_lpl_10_r q0 u_lpl_10_w ctl u_lpl_11_r q1 u_lpl_12_r q1 u_lpl_13_r q1 u_lpl_13_w ctl "
       "u_lpl_14_r q2 u_lpl_15_r q2 u_lpl_16_r q2 u_lpl_16_w ctl u_lpl_17_r q3 u_lpl_18_r q3 u_lpl_19_r q3 u_lpl_19_w ctl "
       "u_lpl_1_r ctl u_lpl_1_w q1 u_lpl_2_r ctl u_lpl_2_w q2 u_lpl_3_r ctl u_lpl_3_w q3 u_lpl_4_r ctl u_lpl_4_w q0 "
       "u_lpl_5_r ctl u_lpl_5_w q1 u_lpl_6_r ctl u_lpl_6_w q2 u_lpl_7_r ctl u_lpl_7_w q3 u_lpl_8_r q0 u_lpl_8_w ctl "
       "u_lpl_9_r q0 u_lpl_9_w ctl u_lpr_ctl ctl u_lpr_ctl_l ctl u_lpr_q0 q0 u_lpr_q0_l q0 u_lpr_q1 q1 u_lpr_q1_l q1 "
       "u_lpr_q2 q2 u_lpr_q2_l q2 u_lpr_q3 q3 u_lpr_q3_l q3 u_lpr_root_ctl ctl u_lpr_root_q0 ctl u_lpr_root_q1 ctl "
       "u_lpr_root_q2 ctl u_lpr_root_q3 ctl u_lprc_u_ctl ctl u_lprc_u_q0 q0 u_lprc_u_q1 q1 u_lprc_u_q2 q2 u_lprc_u_q3 q3 "
       "u_rst_l0 ctl u_rst_l1 ctl")
LAND_BOX = {"q0": "wtop", "q2": "wbot", "q1": "mtop", "q3": "mbot", "ctl": "ctl"}


def boxes(g):
    W, H, xl, xr, yb, yt = g["W"], g["H"], g["xl"], g["xr"], g["yb"], g["yt"]
    cx, cy = g["ctl"]
    wx = (CM, xl - HALO)
    mx = (xl + CW + HALO, xr - HALO)
    ex = (xr + CW + HALO, W - CM)
    gap = (yb + CH + HALO, yt - HALO)
    top = (yt - HALO, H - CM)           # W/E bands run the full height; the mid channel stops at the row gap
    bot = (CM, yb + CH + HALO)
    split = (yb + CH + yt) / 2          # W / E bands: top and bottom halves meet at the middle of the row gap
    return {
        "wtop": (wx[0], split, wx[1], H - CM), "wbot": (wx[0], CM, wx[1], split),
        "etop": (ex[0], split, ex[1], H - CM), "ebot": (ex[0], CM, ex[1], split),
        "mtop": (mx[0], gap[1], mx[1], H - CM), "mbot": (mx[0], yb, mx[1], gap[0]),
        "ctl": (xl + CW - 43.2, gap[0], xr + 43.2, gap[1]),   # the 86.4-um row gap around u_ctl
        "spa": (cx - 21.6, CM, cx + CTL + 21.6, yb - HALO),
    }


# pin-register name -> band.  Names from ot_hidx_s3_flat_lpio FACE=1 (keep regs survive synthesis by name).
PIN_RULES = [
    (r"in_line_0__p[ar]", "wtop"), (r"in_line_1__pa", "wtop"), (r"in_line_1__pr", "mtop"),
    (r"in_line_2__p[ar]", "wbot"), (r"in_line_3__pa", "wbot"), (r"in_line_3__pr", "mbot"),
    (r"selected_(?:line|v)_0__fr", "mtop"), (r"selected_(?:line|v)_0__fd", "etop"),
    (r"selected_(?:line|v)_1__f[rd]", "etop"),
    (r"selected_(?:line|v)_2__fr", "mbot"), (r"selected_(?:line|v)_2__fd", "ebot"),
    (r"selected_(?:line|v)_3__f[rd]", "ebot"),
    (r"(?:op|pass|addr|k|rst_n)__pa", "spa"), (r"(?:op|pass|addr|k|rst_n)__pr", "ctl"),
    (r"fault__fr", "ctl"), (r"fault__fd", "spa"),
]


def tcl(tag):
    g = GEOM[tag]
    bx = boxes(g)
    out = [f"# generated by tools/landed_parent/specs/hidx_sel_s3p_c19_fences.py {tag} -- do not edit",
           "# PRE_GLOBAL_PLACE: one EXCLUSIVE band box per pin-register / landing group (released before DPL by",
           "# tools/landed_parent/lp_fence_release.tcl, like c13).  Boxes (um): " +
           "; ".join(f"{k} {v[0]:.2f},{v[1]:.2f}-{v[2]:.2f},{v[3]:.2f}" for k, v in bx.items()),
           "set ::lpf_blk [ord::get_db_block]", "set ::lpf_dbu [$::lpf_blk getDbUnitsPerMicron]",
           "array set ::lpf_g {}", "array set ::lpf_n {}", "array set ::lpf_c {}"]
    for k, (x0, y0, x1, y1) in bx.items():
        assert x1 - x0 > 5 and y1 - y0 > 5, (tag, k, x0, y0, x1, y1)
        out += [f'set ::lpf_r [odb::dbRegion_create $::lpf_blk "lp_fence_{k}"]',
                f"odb::dbBox_create $::lpf_r [expr {{round({x0:.2f}*$::lpf_dbu)}}] [expr {{round({y0:.2f}*$::lpf_dbu)}}] "
                f"[expr {{round({x1:.2f}*$::lpf_dbu)}}] [expr {{round({y1:.2f}*$::lpf_dbu)}}]",
                f'set ::lpf_g({k}) [odb::dbGroup_create $::lpf_r "lp_fence_grp_{k}"]']
    toks = OWN.split()
    own = " ".join(f"{toks[i]} {LAND_BOX[toks[i + 1]]}" for i in range(0, len(toks), 2))
    out.append("array set ::lpf_own {" + own + "}")
    out.append("set ::lpf_pin_rules {" + " ".join("{" + rx + " " + b + "}" for rx, b in PIN_RULES) + "}")
    out.append(r'''proc lpf_seq {m} {
  foreach mt [$m getMTerms] { if {[$mt getSigType] eq "CLOCK"} { return 1 } }
  return 0
}
set ::lpf_reads {}
foreach i [$::lpf_blk getInsts] {
  if {[[$i getMaster] isBlock] || [[$i getMaster] getType] ne "CORE"} continue
  if {[$i getGroup] ne "NULL"} continue
  regsub -all {\\} [$i getName] {} n
  set r ""
  if {[regexp {^(u_lpl_[0-9]+_[wr]|u_lpr_root_(?:ctl|q[0-3])|u_lpr_(?:ctl|q[0-3])(?:_l)?|u_lprc_u_(?:ctl|q[0-3])|u_rst_l[01])[./]} $n -> h]} {
    if {![info exists ::lpf_own($h)]} { error "LP_FENCE: $n has no landing owner" }
    set r $::lpf_own($h)
    if {[string match *_r $h] && [lpf_seq [$i getMaster]]} { lappend ::lpf_reads [list $i $r] }
  } elseif {[lpf_seq [$i getMaster]]} {
    foreach pr $::lpf_pin_rules {
      if {[regexp "(^|\[./\])[lindex $pr 0](\[^0-9a-z_\]|$)" $n]} { set r [lindex $pr 1]; break }
    }
  }
  if {$r eq ""} continue
  $::lpf_g($r) addInst $i
  incr ::lpf_n($r)
}
# read-mux cone of every landing read register: walk back through ungrouped combinational cells (as c13)
foreach ir $::lpf_reads {
  lassign $ir i r
  set front [list $i]
  for {set d 0} {$d < 16 && [llength $front]} {incr d} {
    set nxt {}
    foreach x $front {
      foreach it [$x getITerms] {
        if {![$it isInputSignal] || [[$it getMTerm] getSigType] eq "CLOCK"} continue
        set net [$it getNet]
        if {$net eq "NULL" || [$net getSigType] ne "SIGNAL"} continue
        foreach dt [$net getITerms] {
          if {![$dt isOutputSignal]} continue
          set di [$dt getInst]
          set dm [$di getMaster]
          if {[$dm isBlock] || [$dm getType] ne "CORE" || [$di getGroup] ne "NULL" || [lpf_seq $dm]} continue
          if {[$di getPlacementStatus] eq "FIRM" || [$di isFixed]} continue
          $::lpf_g($r) addInst $di
          incr ::lpf_c($r)
          lappend nxt $di
        }
      }
    }
    set front $nxt
  }
}''')
    out.append("foreach r {" + " ".join(bx) + "} {")
    out.append(r'''  if {![info exists ::lpf_n($r)] || $::lpf_n($r) < 1} { error "LP_FENCE: band $r got no cells" }
  if {![info exists ::lpf_c($r)]} { set ::lpf_c($r) 0 }
  puts "LP_FENCE $r cells=$::lpf_n($r) read_cone=$::lpf_c($r)"
}''')
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for tag in sys.argv[1:] or ["c19a", "c19b"]:
        p = Path(__file__).with_name(f"hidx_sel_s3p_{tag}_fences.tcl")
        p.write_text(tcl(tag))
        print(p, boxes(GEOM[tag]))
