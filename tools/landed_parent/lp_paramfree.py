#!/usr/bin/env python3
"""S81-SLICERTL (10-20) HARD-NOPARAM: the PARAMETER-FREE top of an lp.py landed parent, for a kit / die bind with no #().

    lp_paramfree.py SPEC.json NAME

Reads the lp.py spec (top_lp, params, out_dir, record_dir) and writes
  <out_dir>/<NAME>.sv             = <top_lp>.sv with the module renamed to NAME and its parameter header replaced by
                                    localparams: every spec "params" value, every other parameter at its lp.py default
                                    (MUT = 0: bench mutants exist only in <top_lp>).  Same body, same instance names,
                                    so the lp record (regions, landings, reset runs, port offsets) applies unchanged;
  <record_dir>/<NAME>_record.json = the lp record with top = NAME and "param_free_of" = {top_lp, params, sha256 of both
                                    RTL files} (ref_tile's landed_record() requires record.top == spec.top).
The kit uses top NAME with params {}; the die binds NAME.  Exactness: tools/s81_slice/slicertl_bench.sh c1k8 runs the
lp.py lockstep bench with NAME in place of <top_lp> #(params) (and a mutant NAME must FAIL).
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec_p, name = sys.argv[1], sys.argv[2]
S = json.loads((ROOT / spec_p).read_text())
top, params = S["top_lp"], {k: int(v) for k, v in S.get("params", {}).items()}
src = ROOT / S["out_dir"] / f"{top}.sv"
t = src.read_text()
m = re.search(r"^module\s+" + re.escape(top) + r"\s*#\((.*?)\)\s*\(", t, re.S | re.M)
assert m, f"no parameterised module {top} in {src}"
decl = re.findall(r"parameter\s+integer\s+(\w+)\s*=\s*([^,\n)]+)", m.group(1))
assert decl, "no parameters found"
names = [k for k, _ in decl]
unknown = sorted(set(params) - set(names))
assert not unknown, f"spec params not in {top}: {unknown}"
lps = []
for k, v in decl:
    val = params.get(k, v.strip())
    lps.append(f"    localparam integer {k} = {val};")
hdr = f"module {name} ("
body = t[m.end():]
# localparams go after the port list
pe = body.index(");\n") + 3
out = t[:m.start()] + hdr + body[:pe] + "\n".join(lps) + "\n" + body[pe:]
out = out.replace(f"// GENERATED by tools/landed_parent/lp.py", f"// GENERATED by tools/landed_parent/lp_paramfree.py from {top} ({S['out_dir']}/{top}.sv: "
                  f"parameters fixed {json.dumps(params)}, MUT 0) -- do not edit.\n// ORIGINAL HEADER: GENERATED by tools/landed_parent/lp.py", 1)
assert re.search(r"\bmodule\s+" + re.escape(name) + r"\s*\(", out) and "#(" not in out[out.index(f"module {name}"):out.index(");\n", out.index(f"module {name}"))]
dst = ROOT / S["out_dir"] / f"{name}.sv"
dst.write_text(out)
rp = ROOT / S["record_dir"] / f"{top}_record.json"
rec = json.loads(rp.read_text())
assert rec.get("top") == top
rec["top"] = name
rec["param_free_of"] = {"top_lp": top, "params": params, "lp_rtl": f"{S['out_dir']}/{top}.sv",
                        "lp_rtl_sha256": hashlib.sha256(src.read_bytes()).hexdigest(),
                        "rtl": f"{S['out_dir']}/{name}.sv", "rtl_sha256": hashlib.sha256(out.encode()).hexdigest(),
                        "generator": "tools/landed_parent/lp_paramfree.py"}
(ROOT / S["record_dir"] / f"{name}_record.json").write_text(json.dumps(rec, indent=1) + "\n")
print(f"{name}: {len(lps)} localparams ({json.dumps(params)}) -> {dst.relative_to(ROOT)}, record {S['record_dir']}/{name}_record.json")
