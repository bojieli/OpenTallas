"""Independent released-checkpoint golden reference for the actual DS PC1-9 prefix.

Arithmetic is hdc_golden_v41, never the native compiler, Machine or provider.
Native metadata supplies only writer identities, rank intervals and home IDs.
Seeded entering state is regenerated by the independent reference initializer
and must match the admitted source image. No host resource limits are imposed.
"""
import argparse
