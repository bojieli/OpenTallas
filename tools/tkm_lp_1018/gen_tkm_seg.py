#!/usr/bin/env python3
"""PL-TP192 (10-18): the TKM TP192 sub-cluster (tkm_SW) as a LANDED parent.

Writes the wires-only flat parent ot_hgi_coll_tkm_m_tp192_seg (ctl leaf + buffer + 32 e86 tiles + ot_pl_hop on every
region seam of the chain) and the lp.py SPEC.  Geometry: 6 x 6 sites at 280.8 um (259.2 tile + 21.6 channel), column
serpentine (odd columns R0 = down, even columns MX = up: e86 has ins/up_out on N, ovf/up_in on S, clr/conv on W), ctl
(soft, 2 sites, S-face ingress) at sites (0,0)-(1,0), buffer at (2,0).  Regions = 3 x 3-site quadrants SW (core: ctl,
buffer, ingress/egress ports), NW, NE, SE (842 um square).  The chain leaves and re-enters regions: 8 segments, 7 seams.
Each seam carries down {conv strobes of later segments, clr, ovf_v, ovf_b} and up {up_out} through an ot_pl_hop N 3;
ot_hgi_coll_tkm_ctl's calendar carries them (SETTLE + 2*3*7, conv_s emitted 6*s edges early).

    gen_tkm_seg.py            (writes the RTL + tools/tkm_lp_1018/tkm_m_tp192_seg_lp.json; prints the plan)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RTL = "rtl/hbm_accel/generic/collective/tkm/ot_hgi_coll_tkm_m_tp192_seg.sv"
SPEC = "tools/tkm_lp_1018/tkm_m_tp192_seg_lp.json"
PITCH, TILE = 280.8, 259.2
EW, NT, HOP = 86, 32, 3
BW = 4 * EW


def chain():
    cols = [(0, range(1, 6)), (1, range(5, 0, -1)), (2, range(1, 6)), (3, range(5, -1, -1)), (4, range(0, 6)),
            (5, range(5, -1, -1))]
    sites = [(c, r) for c, rows in cols for r in rows]
    return sites[:NT]


def region(c, r):
    return ("S" if r < 3 else "N") + ("W" if c < 3 else "E")


def plan():
    sites = chain()
    regs = [region(*s) for s in sites]
    seg, segs = [], []
    for t, rg in enumerate(regs):
        if t == 0 or rg != regs[t - 1]:
            segs.append([])
        segs[-1].append(t)
        seg.append(len(segs) - 1)
    return sites, regs, seg, segs


def main():
    sites, regs, seg, segs = plan()
    NS = len(segs)
    L = ["`timescale 1ns/1ps",
         "// GENERATED by tools/tkm_lp_1018/gen_tkm_seg.py (PL-TP192 10-18) -- do not edit.",
         "// TKM TP192 sub-cluster, FLAT reference for tools/landed_parent/lp.py: ot_hgi_coll_tkm_ctl (the tkm_static",
         f"// calendar) + ot_hgi_coll_tkm_buffer + {NT} ot_hgi_coll_tkm_tile_e86 in one chain, {NS} segments; every seam net",
         f"// goes through an ot_pl_hop N {HOP} (pre-scheduled crossing: lp.py lands it).  Wires only.",
         "module ot_hgi_coll_tkm_m_tp192_seg #(parameter integer CTL_MUT=0)(",
         " input wire clk,rst_n,start,arg_mode,input wire [31:0] tile_clk,input wire buffer_clk,",
         " input wire [11:0] cfg_n,input wire [12:0] cfg_k,cfg_nout,input wire [7:0] cfg_g,cfg_gbase,input wire [15:0] cfg_pf,",
         " input wire [39:0] cfg_obase,cfg_rbase,input wire cfg_has_r,",
         " input wire [3:0] del_slot,del_valid,input wire [2179:0] del_flit,",
         " output wire w_v,output wire [39:0] w_addr,output wire [15:0] w_mask,output wire [511:0] w_data,",
         " output wire busy,done,fault,output wire [31:0] stat_cycles);"]
    w = L.append
    # nets
    for s in range(NS):
        w(f" wire [{NS - 1 - s}:0] cv{s}; wire cl{s};   // segment {s} ({regs[segs[s][0]]}, tiles {segs[s][0]}..{segs[s][-1]})")
    for t in range(NT + 1):
        w(f" wire dv{t}; wire [{BW - 1}:0] db{t}; wire [{BW - 1}:0] up{t};")
    w(f" wire buf_wv,read_v,buf_valid; wire [9:0] buf_wa,read_addr; wire [{BW - 1}:0] buf_wdata,buf_data;")
    seams = []
    for s in range(NS - 1):
        a, b = segs[s][-1], segs[s][0 + 0] if False else segs[s + 1][0]
        wd = (NS - 1 - s) + 1 + 1 + BW          # cv{s}[NS-1-s:1], cl, ovf_v, ovf_b
        seams.append((s, a, b, wd))
        w(f" wire [{wd - 1}:0] hd{s}, ho{s}; wire [{BW - 1}:0] uh{s};   // seam {s}: tile {a} ({regs[a]}) -> tile {b} ({regs[b]})")
    # ctl first (lp.py MUT 4 = first child with a reset), buffer, then up hops (landing 0 = the seam-0 up chain)
    w(" ot_hgi_coll_tkm_ctl #(.KMAX(2048),.MUT(CTL_MUT),.TP(192),.NSEG(%d),.HOP(%d)) u_ctl(.clk(clk),.rst_n(rst_n),.start(start),.arg_mode(arg_mode)," % (NS, HOP))
    w("  .cfg_n(cfg_n),.cfg_k(cfg_k),.cfg_nout(cfg_nout),.cfg_g(cfg_g),.cfg_gbase(cfg_gbase),.cfg_pf(cfg_pf),.cfg_obase(cfg_obase),.cfg_rbase(cfg_rbase),.cfg_has_r(cfg_has_r),")
    w("  .del_slot_i(del_slot),.del_valid_i(del_valid),.del_flit(del_flit),.w_v(w_v),.w_addr(w_addr),.w_mask(w_mask),.w_data(w_data),")
    w("  .busy(busy),.done(done),.fault(fault),.stat_cycles(stat_cycles),.entry_v(dv0),.entry(db0),.up0(up0),.clr(cl0),.conv_s(cv0),")
    w("  .buf_wv(buf_wv),.buf_wa(buf_wa),.buf_wdata(buf_wdata),.read_v(read_v),.read_addr(read_addr),.buf_valid(buf_valid),.buf_data(buf_data));")
    w(f" ot_hgi_coll_tkm_buffer #(.DW({BW})) u_buffer(.clk(buffer_clk),.rst_n(rst_n),.w_v(buf_wv),.w_addr(buf_wa),.w_data(buf_wdata),")
    w("  .r_v(read_v),.r_addr(read_addr),.rd_v(buf_valid),.rd_data(buf_data));")
    for s, a, b, wd in seams:
        w(f" ot_pl_hop #(.W({BW}),.N({HOP})) u_hu{s}(.ck(clk),.i(up{b}),.o(uh{s}));")
    for s, a, b, wd in seams:
        hi = NS - 1 - s
        cvp = f"cv{s}[{hi}:1]," if hi >= 1 else ""
        w(f" assign hd{s} = {{{cvp}cl{s},dv{a + 1},db{a + 1}}};")
        w(f" ot_pl_hop #(.W({wd}),.N({HOP})) u_hd{s}(.ck(clk),.i(hd{s}),.o(ho{s}));")
        if hi >= 1:
            w(f" assign cv{s + 1} = ho{s}[{wd - 1}:{wd - hi}];")
        w(f" assign cl{s + 1} = ho{s}[{BW + 1}];")
    # tiles
    seam_after = {a: s for s, a, b, wd in seams}
    for t in range(NT):
        s = seg[t]
        ins_v = f"dv{t}" if (t == 0 or t - 1 not in seam_after) else f"ho{seam_after[t - 1]}[{BW}]"
        ins_b = f"db{t}" if (t == 0 or t - 1 not in seam_after) else f"ho{seam_after[t - 1]}[{BW - 1}:0]"
        up_in = f"{BW}'b0" if t == NT - 1 else (f"uh{seam_after[t]}" if t in seam_after else f"up{t + 1}")
        ck = f"tile_clk[{t}]"
        w(f" ot_hgi_coll_tkm_tile_e86 u_t{t}(.clk({ck}),.clk_r0({ck}),.clk_r1({ck}),.clk_r2({ck}),.clk_r3({ck}),"
          f".clr(cl{s}),.conv(cv{s}[0]),.ins_v({ins_v}),.ins_b({ins_b}),.ovf_v(dv{t + 1}),.ovf_b(db{t + 1}),"
          f".up_in({up_in}),.up_out(up{t}),.busy());   // site {sites[t]} {regs[t]} seg {s}")
    w(" // dv32/db32 (last tile overflow) and up32 are unused: the chain keeps KMAX = 2048")
    w("endmodule")
    (ROOT / RTL).write_text("\n".join(L) + "\n")
    cen = {}
    for r in ("SW", "NW", "NE", "SE"):
        cx = (0 if r[1] == "W" else 3) * PITCH + 1.5 * PITCH
        cy = (0 if r[0] == "S" else 3) * PITCH + 1.5 * PITCH
        cen[r] = [round(cx, 1), round(cy, 1)]
    tiles = {r: [f"u_t{t}" for t in range(NT) if regs[t] == r] for r in cen}
    regions = [dict(name="SW", insts=["u_ctl", "u_buffer"] + tiles["SW"], centre=cen["SW"])] + \
              [dict(name=r, insts=tiles[r], centre=cen[r]) for r in ("NW", "NE", "SE")]
    C = "rtl/hbm_accel/generic/collective/tkm"
    spec = dict(
        top="ot_hgi_coll_tkm_m_tp192_seg", top_lp="ot_hgi_coll_tkm_m_tp192_lp",
        sources=[RTL],
        child_sources=[f"{C}/ot_hgi_coll_tkm_ctl.sv", f"{C}/ot_hgi_coll_tkm_buffer.sv", f"{C}/ot_hgi_coll_tkm_static.sv",
                       f"{C}/ot_hgi_coll_tkm.sv", "rtl/lib/ot_rst_relay.sv",
                       "physical/asap7_memory_macros/ot_sram_1r1w_1024x256_m2_r2c2/ot_sram_1r1w_1024x256_m2_r2c2.v"],
        out_dir="rtl/hbm_accel/generic/collective/tkm/lp", record_dir="results/arch/pl_tp192_1018",
        params={}, clock_ports=["clk", "tile_clk", "buffer_clk"], clock_pins=["clk", "clk_r0", "clk_r1", "clk_r2", "clk_r3"],
        reset_port="rst_n", reset_pins=["rst_n"], regions=regions,
        bench=dict(cycles=7000, reset_cycles=16, sim="verilator", drive={
            "start": "((cyc >= 16 && cyc < 80) || (($urandom % 64) == 0)) ? 1'b1 : 1'b0",
            "arg_mode": "1'b0", "cfg_n": "12'd128", "cfg_pf": "16'd16", "cfg_g": "8'd16", "cfg_gbase": "8'd0",
            "cfg_k": "13'd2048", "cfg_nout": "13'd2048", "cfg_obase": "40'd0", "cfg_rbase": "40'h10000",
            "cfg_has_r": "1'b1"}),
        plan=dict(sites={f"u_t{t}": list(sites[t]) for t in range(NT)}, ctl_sites=[[0, 0], [1, 0]], buffer_site=[2, 0],
                  pitch_um=PITCH, tile_um=TILE, segments=segs, seams=[dict(seam=s, from_tile=a, to_tile=b, down_bits=wd,
                                                                           up_bits=BW) for s, a, b, wd in seams]))
    (ROOT / SPEC).write_text(json.dumps(spec, indent=1) + "\n")
    print(f"{NT} tiles, {NS} segments {[(regs[x[0]], x[0], x[-1]) for x in segs]}, {len(seams)} seams, "
          f"seam bits down {[x[3] for x in seams]} up {BW}")


if __name__ == "__main__":
    main()
