#!/usr/bin/env python3
"""HBM-DIEGAP/SMHPARENT 10-21 (RELEASE_TREE H.STA.BLK.14 / 14.6): the WIRES-ONLY flat smh_attn parent built from the
rp4a HARDENED HALVES (ot_hbm_smh_rp4ah_n / _s, rtl/hbm_accel/sm/repack/h2a/ot_hbm_smh_rp4ah.sv) instead of the soft
ot_hbm_sm_attn_tile.  Input of tools/landed_parent/lp.py (specs results/arch/smh_attn_parent_1021/lp_spec_{main,fb}.json).

Derived from tools/hbm_sm_attention/smh_attn_flat_gen.py (HF-5c 10-18: front split into launch u_fl / result u_fr, be_cmd
glue u_bc, generate loops unrolled, one wire per consumer slice).  Per tile T = (column c, row pair p):
  u_t<c><p>_n  ot_hbm_smh_rp4ah_n  leaf 0 (row 2p),   rin_n = rin[817:0],    bin,  gin, rout_n, bout, -> xo_b/xo_g0/xo_gp
  u_t<c><p>_s  ot_hbm_smh_rp4ah_s  leaf 1 (row 2p+1), rin_s = rin[1635:818], xi_* <- the n half's crossing, gout
  (the n -> s crossing xo_b 2,069 + xo_g0 50 + xo_gp 100 bits is a NAMED parent wire, so lp.py LANDS it when the two
  halves sit in different clock regions = MAIN; FALLBACK keeps both halves in one region = one parent root per tile).
Schedule (rp4a halves vs ot_hbm_sm_attn_tile, PRICED): every gout lane is +G = 2+GN+GS+LR+2*OS edges (r3 kits: 10) and the
pass lanes add G per tile they cross, so at the BE the row-pair-0 lanes (gout[199:100] of p1) arrive +2G and p1's own lanes
(gout[99:0]) +G.  The parent pads p1's own lanes G more (u_gp<c>, ot_rp4a_relay W 100, valid bits sync-cleared) so every BE
lane is +2G uniform, and the BE control delay grows by 2G (BE_DELAY default 8 + 2G): the BE calendar in command time is
unchanged, results (rv / rrow / rdata) leave 2G edges later (compiler: lat.out + 2G).  Row bundles / x beat per tile hop:
HOPD (rp4 define set: 5 = one pin register a hop, HF-5c finding).
Usage: smh_attn_rp4a_flat_gen.py [--out rtl/hbm_accel/sm/attn/flat/ot_hbm_accel_smh_attn_rp4a.sv]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import smh_attn_flat_gen as F  # noqa: E402

SUB, LBS, LSB, NC, RPT, NP, NL, NH = F.SUB, F.LBS, F.LSB, F.NC, F.RPT, F.NP, F.NL, F.NH
RBW, BBW, GLW, QLW, TRW, TGI = F.RBW, F.BBW, F.GLW, F.QLW, F.TRW, F.TGI
# r3 halves kits (physical/ref_tile/smh_rp4ah{n,s}_r3{a,b}/spec.json params)
GN, GS, XB, LR, OS = 2, 2, 2, 2, 1
G = 2 + GN + GS + LR + 2 * OS          # 10: gout lane delta of one rp4a tile vs the soft tile
TOP = "ot_hbm_accel_smh_attn_rp4a"
SLICE = 720                            # lp.py regional_reset_copies: <= 30 chunks of 24 b per landed net -> slice wide buses


def parts(width):
    n = -(-width // SLICE)
    base, rem = divmod(width, n)
    return [base + (1 if k < rem else 0) for k in range(n)]


def decl(name, width):
    """slice wires of one bus (<= SLICE bits each); returns the declaration text."""
    ps = parts(width)
    if len(ps) == 1:
        return f"wire [{width - 1}:0] {name};"
    return " ".join(f"wire [{w - 1}:0] {name}_{k};" for k, w in enumerate(ps))


def cat(name, width):
    """the bus as a concatenation of its slices (MSB slice first)."""
    ps = parts(width)
    if len(ps) == 1:
        return name
    return "{" + ", ".join(f"{name}_{k}" for k in reversed(range(len(ps)))) + "}"


def gen() -> str:
    L = []
    w = L.append
    w("`timescale 1ns/1ps")
    w("`default_nettype none")
    w("// GENERATED by tools/hbm_sm_attention/smh_attn_rp4a_flat_gen.py (HBM-DIEGAP/SMHPARENT 10-21) -- do not edit.")
    w("// WIRES-ONLY flat smh_attn parent with the rp4a HARDENED HALVES (16 tiles x n/s): front split (u_fl / u_fr), be_cmd glue")
    w(f"// u_bc, 8 BEs, p1 own-lane pads u_gp<c> (+{G}).  rp4a GN {GN} GS {GS} XB {XB} LR {LR} OS {OS}: every BE lane +{2 * G} edges vs")
    w(f"// ot_hbm_accel_smh_attn (BE_DELAY default 8 + {2 * G}); results +{2 * G}.  Input of tools/landed_parent/lp.py.")
    w(f"module {TOP} #(")
    w("    parameter integer KVMUT = 0,")
    w(f"    parameter integer BE_DELAY = {8 + 2 * G},")
    w("    parameter integer HOPD = 5,")
    w(f"    parameter integer GPAD = {G}")
    w(") (")
    w("    input  wire          clk,")
    w("    input  wire          rst_n,")
    w("    input  wire [191:0]  command,")
    w("    input  wire [63:0]   kv_desc,")
    w("    input  wire [1098:0] packet,")
    w("    output wire [42:0]   request,")
    w("    input  wire          xw_en,")
    w("    input  wire [6:0]    xw_addr,")
    w("    input  wire [6:0]    xw_grp,")
    w("    input  wire [2047:0] xw_data,")
    w("    output wire          rv,")
    w("    output wire [11:0]   rrow,")
    w("    output wire [255:0]  rdata,")
    w("    output wire          fault,")
    w("    output wire          schedule_fault")
    w(");")
    for s in ("l", "r"):
        for p in range(NP):
            w(f"    {decl(f'f_r{s}_p{p}n', RBW)} {decl(f'f_r{s}_p{p}s', RBW)}")
            w(f"    {decl(f'f_b{s}_p{p}', BBW)}")
    w("    wire [28:0] be_cmd;")
    for c in range(NC):
        for p in range(NP):
            t = f"t{c}{p}"
            w(f"    {decl(f'{t}n_ro', RBW)} {decl(f'{t}s_ro', RBW)} {decl(f'{t}_bo', BBW)} {decl(f'{t}_xb', BBW)}  "
              f"wire [49:0] {t}_xg0;  wire [99:0] {t}_xgp;  wire [{SUB * GLW - 1}:0] {t}_go;")
        w(f"    wire [{TGI - 1}:0] t{c}0_gol = t{c}0_go[{TGI - 1}:0];")
        w(f"    wire [{TGI - 1}:0] t{c}1_gown = t{c}1_go[{TGI - 1}:0];")
        w(f"    wire [{TGI - 1}:0] t{c}1_gpass = t{c}1_go[{SUB * GLW - 1}:{TGI}];")
        w(f"    wire [{TGI - 1}:0] g{c}_own;")
        w(f"    wire [{NH * QLW - 1}:0] e{c}_qo;")
        w(f"    wire [{(NH - 1) * QLW - 1}:0] e{c}_qol = e{c}_qo[{(NH - 1) * QLW - 1}:0];")
    w("    ot_hbm_sm_attn_front_launch #(.KVMUT(KVMUT)) u_fl (.clk(clk), .rst_n(rst_n), .command(command), .kv_desc(kv_desc), "
      ".packet(packet), .xw_en(xw_en), .xw_addr(xw_addr), .xw_grp(xw_grp), .xw_data(xw_data), .request(request), "
      f".rl({{{cat('f_rl_p1s', RBW)}, {cat('f_rl_p1n', RBW)}, {cat('f_rl_p0s', RBW)}, {cat('f_rl_p0n', RBW)}}}), "
      f".rr({{{cat('f_rr_p1s', RBW)}, {cat('f_rr_p1n', RBW)}, {cat('f_rr_p0s', RBW)}, {cat('f_rr_p0n', RBW)}}}), "
      f".bl({{{cat('f_bl_p1', BBW)}, {cat('f_bl_p0', BBW)}}}), .br({{{cat('f_br_p1', BBW)}, {cat('f_br_p0', BBW)}}}), "
      ".schedule_fault(schedule_fault));")
    w(f"    ot_smh_static_front_result u_fr (.clk(clk), .rst_n(rst_n), .ql(e{NL - 1}_qo), .qr(e{NL}_qo), .rv(rv), .rrow(rrow), "
      ".rdata(rdata), .fault(fault));")
    w("    ot_hbm_sm_attn_becmd u_bc (.clk(clk), .rst_n(rst_n), .d(command[111:83]), .q(be_cmd));")
    hp = f"#(.GN({GN}), .XB({XB}), .LR({LR}), .OS({OS}))"
    sp = f"#(.GN({GN}), .GS({GS}), .XB({XB}), .LR({LR}), .OS({OS}))"
    for c in range(NC):
        for p in range(NP):
            t = f"t{c}{p}"
            if c == NL - 1:
                rn, rs, bi = f"f_rl_p{p}n", f"f_rl_p{p}s", f"f_bl_p{p}"
            elif c < NL - 1:
                rn, rs, bi = f"t{c + 1}{p}n_ro", f"t{c + 1}{p}s_ro", f"t{c + 1}{p}_bo"
            elif c == NL:
                rn, rs, bi = f"f_rr_p{p}n", f"f_rr_p{p}s", f"f_br_p{p}"
            else:
                rn, rs, bi = f"t{c - 1}{p}n_ro", f"t{c - 1}{p}s_ro", f"t{c - 1}{p}_bo"
            rn, rs, bi = cat(rn, RBW), cat(rs, RBW), cat(bi, BBW)
            ron, ros, bo, xb = cat(f"{t}n_ro", RBW), cat(f"{t}s_ro", RBW), cat(f"{t}_bo", BBW), cat(f"{t}_xb", BBW)
            gi = f"{TGI}'d0" if p == 0 else f"t{c}{p - 1}_gol"
            a1, g1, a2, g2 = F.straps(c, p)
            v = lambda s: int(s.split("'h")[1], 16)  # noqa: E731
            a1v, g1v, a2v, g2v = v(a1), v(g1), v(a2), v(g2)
            attn = (p * RPT) << 3 | c
            w(f"    ot_hbm_smh_rp4ah_n {hp} u_{t}_n (.clk(clk), .rst_n(rst_n), .xs_a1(9'h{a1v & 0x1ff:x}), "
              f".xs_g1(5'h{g1v & 0x1f:x}), .xs_a2(7'h{a2v & 0x7f:x}), .xs_g2(5'h{g2v & 0x1f:x}), .attn(5'h{attn:x}), "
              f".rin_n({rn}), .bin({bi}), .gin({gi}), .rout_n({ron}), .bout({bo}), .xo_b({xb}), .xo_g0({t}_xg0), "
              f".xo_gp({t}_xgp));")
            w(f"    ot_hbm_smh_rp4ah_s {sp} u_{t}_s (.clk(clk), .rst_n(rst_n), .xss_a1(9'h{a1v >> 9:x}), "
              f".xss_g1(5'h{g1v >> 5:x}), .xss_a2(7'h{a2v >> 7:x}), .xss_g2(5'h{g2v >> 5:x}), .attn(5'h{attn:x}), "
              f".rin_s({rs}), .rout_s({ros}), .xi_b({xb}), .xi_g0({t}_xg0), .xi_gp({t}_xgp), .gout({t}_go));")
        w(f"    ot_rp4a_relay #(.W(100), .N(GPAD), .VMASK({{2'b11, 48'b0, 2'b11, 48'b0}})) u_gp{c} (.clk(clk), .rst_n(rst_n), "
          f".d(t{c}1_gown), .q(g{c}_own));")
        if c < NL:
            qi = f"{(NH - 1) * QLW}'d0" if c == 0 else f"e{c - 1}_qol"
        else:
            qi = f"{(NH - 1) * QLW}'d0" if c == NC - 1 else f"e{c + 1}_qol"
        hop = (NL - 1 - c) if c < NL else (c - NL)
        w(f"    ot_hbm_sm_attn_be #(.CONTROL_DELAY(BE_DELAY + HOPD * {hop}), .SUB({SUB}), .RPT({RPT}), .IL(8), .RMAX(4096), "
          f".LEV(4), .TAGW(16), .NH({NH})) u_be{c} (.clk(clk), .rst_n(rst_n), .attn_column(3'd{c}), .command(be_cmd), "
          f".gin({{t{c}1_gpass, g{c}_own}}), .qin({qi}), .qout(e{c}_qo));")
    w("endmodule")
    w("`default_nettype wire")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="rtl/hbm_accel/sm/attn/flat/ot_hbm_accel_smh_attn_rp4a.sv")
    a = ap.parse_args()
    (ROOT / a.out).write_text(gen())
    print("wrote", a.out, "G", G)


if __name__ == "__main__":
    main()
