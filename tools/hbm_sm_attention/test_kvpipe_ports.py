#!/usr/bin/env python3
"""KVPIPE (DIE-HBM-97 2026-11-10): the kv_line pipeline change keeps the plan pin table and the shell.

1. ot_hbm_sm_kv_line's port list (name, direction, width, bit for bit) == the plan pin table of the current HBM plan
   (plan_of_record/d44v_gqi_cp1109_q3vm_smk, cores/ot_hbm_sm_kv_line__734.4x233.28__smab1108.json.gz).
2. face_shell.py emit_shell on those ports (lockup stage on every output, clk / rst_n pass-through, as the kit
   ot_hbm_sm_kv_line_66bbd4863f30 was generated) == the bench shell copy in rtl/test/hbm_accel/sm_attn/kv_line_shell,
   except the bench-only MUT parameter pass-through.
3. Every parent that instantiates ot_hbm_sm_kv_line connects exactly the core's ports by name.
Run: python3 -I tools/hbm_sm_attention/test_kvpipe_ports.py   (or pytest)."""
import gzip
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "rtl/hbm_accel/sm/attn/ot_hbm_sm_kv_line.sv"
PLAN = ROOT / "physical/die_plan/hbm/plan_of_record/d44v_gqi_cp1109_q3vm_smk/cores/ot_hbm_sm_kv_line__734.4x233.28__smab1108.json.gz"
SHELL = ROOT / "rtl/test/hbm_accel/sm_attn/kv_line_shell/ot_hbm_sm_kv_line__fshell.sv"
PARENTS = ["rtl/hbm_accel/sm/attn/ot_hbm_sm_attn_front_static.sv",
           "physical/die_plan/hbm_arch_cores/sm/asbuilt_1108/ot_hbm_sm_attn_front_static__sf1109.sv",
           "physical/die_plan/hbm/bind/r18h5_bundle/rtl/hbm_accel/sm/attn/ot_hbm_sm_attn_front_static.sv",
           "rtl/test/hbm_accel/sm_attn/tb_hbm_sm_attn.sv"]


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


def ports(text, module):
    text = strip_comments(text)
    m = re.search(r"\bmodule\s+" + re.escape(module) + r"\b.*?\)\s*\(\s*(.*?)\);", text, re.S)
    assert m, module
    out = {}
    for ln in m.group(1).splitlines():
        ln = ln.split("//")[0].strip().rstrip(",")
        mm = re.match(r"(input|output)\s+(?:wire|reg)?\s*(?:\[(\d+):0\])?\s*(\w+)$", ln)
        if mm:
            out[mm.group(3)] = (mm.group(1), int(mm.group(2) or 0) + 1)
    return out


def core_ports():
    return ports(CORE.read_text(), "ot_hbm_sm_kv_line")


def test_core_ports_equal_plan_pins():
    want = {}
    for p in json.loads(gzip.open(PLAN).read()):
        want[p["name"]] = p["dir"]
    got = {}
    for n, (d, w) in core_ports().items():
        for b in range(w):
            got[n if w == 1 else f"{n}[{b}]"] = d
    assert got == want, (sorted(set(got) ^ set(want))[:10], len(got), len(want))
    assert len(got) == 2158


def test_bench_shell_is_the_kit_shell():
    spec = importlib.util.spec_from_file_location("fs", ROOT / "physical/die_plan/hbm_arch_cores/face_shell.py")
    fs = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fs)
    cp = core_ports()
    widths = {n: w for n, (d, w) in cp.items()}
    dirs = {n: d for n, (d, w) in cp.items()}
    outs = {n for n, d in dirs.items() if d == "output"}
    gen = fs.emit_shell("ot_hbm_sm_kv_line", "ot_hbm_sm_kv_line__fcore", {}, widths, dirs, dict(widths),
                        {"clk", "rst_n"}, "clk", lockup=outs)
    bench = SHELL.read_text()
    bench = bench[bench.index("// GENERATED by face_shell.py"):]      # drop the bench-copy header
    bench = bench.replace("module ot_hbm_sm_kv_line #(parameter integer MUT = 0) (", "module ot_hbm_sm_kv_line (")
    bench = bench.replace("ot_hbm_sm_kv_line__fcore #(.MUT(MUT)) u_fcore", "ot_hbm_sm_kv_line__fcore u_fcore")
    norm = lambda t: [ln.rstrip() for ln in t.strip().splitlines()]
    assert norm(bench) == norm(gen)


def test_parents_connect_the_same_ports():
    names = set(core_ports())
    for rel in PARENTS:
        t = strip_comments((ROOT / rel).read_text())
        m = re.search(r"ot_hbm_sm_kv_line\s*(?:#\s*\(.*?\))?\s*\w+\s*\((.*?)\);", t, re.S)
        assert m, rel
        conn = set(re.findall(r"\.(\w+)\s*\(", m.group(1)))
        assert conn == names, (rel, sorted(conn ^ names))


if __name__ == "__main__":
    for f in (test_core_ports_equal_plan_pins, test_bench_shell_is_the_kit_shell, test_parents_connect_the_same_ports):
        f()
        print("PASS", f.__name__)
