#!/usr/bin/env python3
"""HF-5c 10-18: generate the WIRES-ONLY flat parent ot_hbm_accel_smh_attn_flat (input of tools/landed_parent/lp.py).

It is ot_hbm_accel_smh_attn (rtl/hbm_accel/sm/attn/ot_hbm_accel_smh_attn.sv) with
  * the generate loops unrolled (16 x ot_hbm_sm_attn_tile u_t<c><p>, 8 x ot_hbm_sm_attn_be u_be<c>), straps as literals;
  * the front split into ot_hbm_sm_attn_front_launch u_fl (rl/rr/bl/br/request/schedule_fault) and
    ot_smh_static_front_result u_fr (ql/qr -> rv/rrow/rdata/fault), so front -> tiles -> BE -> q chain -> front is a DAG;
  * the be_cmd register as the soft glue child ot_hbm_sm_attn_becmd u_bc;
  * one named wire per consumer slice (per tile row bundle / beat / gather lane / q chain) so lp.py lands only the bits a
    region reads.
Usage: smh_attn_flat_gen.py [--out rtl/hbm_accel/sm/attn/flat/ot_hbm_accel_smh_attn_flat.sv]
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUB, LBS, LSB, NC, RPT = 4, 2, 16, 8, 2
NP = SUB // RPT
NL = NC // 2
NH = 4
RBW, BBW, GLW, QLW = 818, 2069, 50, 46
TRW = RPT * RBW                  # 1636
TGI = (SUB - RPT) * GLW          # 100
LB, LF = SUB * LBS, SUB * LSB
XC = LB * 266 + LF * 16          # 3152


def lg2g(a, b, c):
    k = 0
    while k < 11 and a % (2 << k) == 0 and b % (2 << k) == 0 and c % (2 << k) == 0:
        k += 1
    return k


A1B = 11 - lg2g(LBS * 266, XC, XC)
A2B = 11 - lg2g(LSB * 16, LB * 266, XC)
assert (A1B, A2B) == (9, 7)


def straps(c, p):
    sa1 = sa2 = sg1 = sg2 = 0
    for j in range(RPT):
        r = p * RPT + j
        fa = c * XC + r * LBS * 266
        fb = c * XC + LB * 266 + r * LSB * 16
        sa1 |= ((fa % 2048) >> (11 - A1B)) << (j * A1B)
        sa2 |= ((fb % 2048) >> (11 - A2B)) << (j * A2B)
        sg1 |= (fa // 2048) << (j * 5)
        sg2 |= (fb // 2048) << (j * 5)
    return (f"{RPT * A1B}'h{sa1:x}", f"{RPT * 5}'h{sg1:x}", f"{RPT * A2B}'h{sa2:x}", f"{RPT * 5}'h{sg2:x}")


def gen() -> str:
    L = []
    w = L.append
    w("`timescale 1ns/1ps")
    w("`default_nettype none")
    w("// GENERATED by tools/hbm_sm_attention/smh_attn_flat_gen.py (HF-5c 10-18) -- do not edit.")
    w("// WIRES-ONLY flat form of ot_hbm_accel_smh_attn (same children, same connections, same cycles): front split into")
    w("// launch (u_fl) and result (u_fr) halves, be_cmd register in the glue child u_bc, generate loops unrolled, one wire")
    w("// per consumer slice.  Input of tools/landed_parent/lp.py (spec results/arch/landed_parent_1018/hf5c/smh_attn_lp_spec.json).")
    w("module ot_hbm_accel_smh_attn_flat #(")
    w("    parameter integer KVMUT = 0,")
    w("    parameter integer BE_DELAY = 8,")
    w("    parameter integer HOPD = 4")
    w(") (")
    w("    input  wire          clk,")
    w("    input  wire          rst_n,")
    w("    input  wire [191:0]  command,")
    w("    input  wire [63:0]   kv_desc,")
    w("    input  wire [1098:0] packet,")
    w("    output wire [42:0]   request,")
    w("    input  wire          xw_en,")
    w("    input  wire [6:0]    xw_addr,")
    w("    input  wire [6:0]    xw_grp,")
    w("    input  wire [2047:0] xw_data,")
    w("    output wire          rv,")
    w("    output wire [11:0]   rrow,")
    w("    output wire [255:0]  rdata,")
    w("    output wire          fault,")
    w("    output wire          schedule_fault")
    w(");")
    # front outputs, one wire per tile-row slice
    for s in ("l", "r"):
        for p in range(NP):
            w(f"    wire [{TRW - 1}:0] f_r{s}_p{p};")
            w(f"    wire [{BBW - 1}:0] f_b{s}_p{p};")
    w("    wire [28:0] be_cmd;")
    for c in range(NC):
        for p in range(NP):
            w(f"    wire [{TRW - 1}:0] t{c}{p}_ro;  wire [{BBW - 1}:0] t{c}{p}_bo;  wire [{SUB * GLW - 1}:0] t{c}{p}_go;")
        w(f"    wire [{TGI - 1}:0] t{c}0_gol = t{c}0_go[{TGI - 1}:0];")
        w(f"    wire [{NH * QLW - 1}:0] e{c}_qo;")
        w(f"    wire [{(NH - 1) * QLW - 1}:0] e{c}_qol = e{c}_qo[{(NH - 1) * QLW - 1}:0];")
    w("    ot_hbm_sm_attn_front_launch #(.KVMUT(KVMUT)) u_fl (.clk(clk), .rst_n(rst_n), .command(command), .kv_desc(kv_desc), "
      ".packet(packet), .xw_en(xw_en), .xw_addr(xw_addr), .xw_grp(xw_grp), .xw_data(xw_data), .request(request), "
      ".rl({f_rl_p1, f_rl_p0}), .rr({f_rr_p1, f_rr_p0}), .bl({f_bl_p1, f_bl_p0}), .br({f_br_p1, f_br_p0}), "
      ".schedule_fault(schedule_fault));")
    w(f"    ot_smh_static_front_result u_fr (.clk(clk), .rst_n(rst_n), .ql(e{NL - 1}_qo), .qr(e{NL}_qo), .rv(rv), .rrow(rrow), "
      ".rdata(rdata), .fault(fault));")
    w("    ot_hbm_sm_attn_becmd u_bc (.clk(clk), .rst_n(rst_n), .d(command[111:83]), .q(be_cmd));")
    tpar = (f"#(.SUB({SUB}), .RPT({RPT}), .LBS({LBS}), .LSB({LSB}), .NC({NC}), .IL(8), .TAGW(16), .XD(128), .NBEAT(13), "
            f".TCK(1), .A1B({A1B}), .A2B({A2B}))")
    for c in range(NC):
        for p in range(NP):
            if c == NL - 1:
                ri, bi = f"f_rl_p{p}", f"f_bl_p{p}"
            elif c < NL - 1:
                ri, bi = f"t{c + 1}{p}_ro", f"t{c + 1}{p}_bo"
            elif c == NL:
                ri, bi = f"f_rr_p{p}", f"f_br_p{p}"
            else:
                ri, bi = f"t{c - 1}{p}_ro", f"t{c - 1}{p}_bo"
            gi = f"{TGI}'d0" if p == 0 else f"t{c}{p - 1}_gol"
            a1, g1, a2, g2 = straps(c, p)
            w(f"    ot_hbm_sm_attn_tile {tpar} u_t{c}{p} (.clk(clk), .rst_n(rst_n), .attn_column(3'd{c}), "
              f".attn_rowbase(2'd{p * RPT}), .xs_a1({a1}), .xs_g1({g1}), .xs_a2({a2}), .xs_g2({g2}), .rin({ri}), .bin({bi}), "
              f".rout(t{c}{p}_ro), .bout(t{c}{p}_bo), .gin({gi}), .gout(t{c}{p}_go));")
        if c < NL:
            qi = f"{(NH - 1) * QLW}'d0" if c == 0 else f"e{c - 1}_qol"
        else:
            qi = f"{(NH - 1) * QLW}'d0" if c == NC - 1 else f"e{c + 1}_qol"
        hop = (NL - 1 - c) if c < NL else (c - NL)
        w(f"    ot_hbm_sm_attn_be #(.CONTROL_DELAY(BE_DELAY + HOPD * {hop}), .SUB({SUB}), .RPT({RPT}), .IL(8), .RMAX(4096), "
          f".LEV(4), .TAGW(16), .NH({NH})) u_be{c} (.clk(clk), .rst_n(rst_n), .attn_column(3'd{c}), .command(be_cmd), "
          f".gin(t{c}{NP - 1}_go), .qin({qi}), .qout(e{c}_qo));")
    w("endmodule")
    w("`default_nettype wire")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="rtl/hbm_accel/sm/attn/flat/ot_hbm_accel_smh_attn_flat.sv")
    a = ap.parse_args()
    (ROOT / a.out).write_text(gen())
    print("wrote", a.out)


if __name__ == "__main__":
    main()
