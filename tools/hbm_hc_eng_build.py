#!/usr/bin/env python3
"""Build the recovered full-shape HC engine bench from canonical tracked sources.
Run the build through ot-run admission. Existing recovery build PID1248279 must finish first;
this tool does not inspect or replace that build. Run the resulting binary in a vector directory
with the arguments in plus.txt (generated by rtl_hbm_hc_eng_static_gate.py).
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
D = 'rtl/hbm_accel/generic/peers/static_hc/'
SOURCES = ['rtl/test/tb_hbm_hc_eng_static.sv'] + [D + n + '.sv' for n in (
    'ot_hbm_hc_eng_static', 'ot_hbm_hc_eng_seq_static', 'ot_hbm_hc_bank_static',
    'ot_hbm_hc_tail_unit_static', 'ot_hdc_v41x_hcp_sys1_static', 'ot_hgi_hc_tail_static')]
SOURCES += ['rtl/hdc/' + n + '.sv' for n in (
    'v41x/ot_hdc_v41x_hcp', 'ot_hdc_prefix', 'ot_hdc_fp32_add_lat', 'ot_hdc_fp32_mul_lat',
    'ot_hdc_fastfp', 'ot_hdc_fastfp_lat', 'ot_hdc_delay', 'ot_hdc_sfu', 'v41x/ot_hdc_v41x_sfu',
    'v41/ot_hdc_fdiv', 'v41/ot_hdc_sinkhorn', 'v41/ot_hdc_sk_arith', 'v41/ot_hdc_sk_recip_rom')]
SOURCES += [f'physical/asap7_memory_macros/{n}/{n}.v' for n in (
    'ot_sram_1r1w_1024x256_m2_r2c2', 'ot_sram_1r1w_128x256_m1_r2c2')]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--objdir', type=Path, required=True)
    ap.add_argument('--mutant', type=int, choices=range(4), default=0)
    ap.add_argument('--jobs', type=int, default=16)
    ap.add_argument('--manifest-only', action='store_true')
    a = ap.parse_args()
    manifest = {s: hashlib.sha256((ROOT / s).read_bytes()).hexdigest() for s in SOURCES}
    a.objdir.mkdir(parents=True, exist_ok=True)
    (a.objdir / 'source_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    if a.manifest_only:
        print(json.dumps(dict(sources=len(manifest), mutant=a.mutant)))
        return 0
    cmd = ['verilator', '--binary', '--timing', '-j', str(a.jobs), '-O2', '-Wno-fatal', '-Wno-WIDTH',
           '-Wno-TIMESCALEMOD', '-Wno-lint', '-Wno-style', f'-DMUT={a.mutant}', '--output-split', '20000',
           '--top-module', 'tb_hbm_hc_eng_static', '-Mdir', str(a.objdir.resolve()), *SOURCES]
    return subprocess.run(cmd, cwd=ROOT).returncode


if __name__ == '__main__':
    raise SystemExit(main())
