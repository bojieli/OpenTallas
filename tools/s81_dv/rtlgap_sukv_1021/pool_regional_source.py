#!/usr/bin/env python3
"""RTLGAP-SUKV (10-22): regional-clock successor of the private pool native sources (SAFE item 7).

Input : rtl/dsrom_sys/s81_dv/slice/pool_native_<variant>.sv (pool_native_source.py output; arithmetic unchanged).
Output: rtl/dsrom_sys/s81_dv/slice/pool_regional_<variant>.sv (+ .json manifest).

Change (structural, no arithmetic edge inside a lane moves):
  * ot_s81sl_cmp_pool gets 8 lane clock ports ck_l[7:0]; `clk` stays the control region's root.  Each lane
    (~1/8 of the flops) is its own clock region (local tree per lane, CTS per clock pin); the control region holds
    the issue calendar, the tag queue and the VM port registers.
  * every control <-> lane crossing is a fixed-latency LANDING RING (ot_s81_land, the die landing contract:
    capture on the source clock, handoff on the destination root, D 4 slots, strap K 1 -> E + 1 = 2 edges each
    way, phase window D x T, epoch fault).  Rings are cut in <=16-bit chunks so each slot enable / read select
    drives <=16 data flops (native census <= 32 loads).
      control -> lane l : {l_v, l_role 2, l_d 32}                = 35 b  (3 rings: 16 + 16 + 3)
      lane l -> control : {o_v, fault, o_y 32, o_y32 32}         = 66 b  (5 rings: 16 x 4 + 2)
  * each landing's ring reset rs is a 2-stage reset leaf on its destination clock (lane: ck_l[l]; control: clk).
  * landing faults: lane-side ring faults ride the lane's fault bit through the out ring; control-side ring faults
    join the top fault.
Cost: +4 edges of pool command latency (2 in, 2 out), all lanes equal (lockstep and the KV lag are lane-local, so
KLAG / TP0 are unchanged); ~8 x (35 + 66) x 5 = 4,040 ring + output flops + 8 x 8 small counters.
The tb's hierarchical probe dut.lo_v[0] keeps its name (landed lane valid).
"""
import hashlib, json, re, sys
from pathlib import Path

R = Path(__file__).resolve().parents[3]
LANE_OLD = """    generate for (l = 0; l < 8; l = l + 1) begin : g_lane
        ot_s81sl_cmp_pool_lane_pooln #(.LM(LM), .LA(LA), .MUT(MUT)) u_l (
            .clk(clk), .rst_n(rst_n), .i_v(l_v), .i_role(l_role), .i_d(l_d[32 * l +: 32]),
            .o_v(lo_v[l]), .o_y(lo_y[32 * l +: 32]), .o_y32(lo_y32[32 * l +: 32]), .fault(lf[l]));
    end endgenerate"""


def rings(name, width, ck_f, ck, rs, i, o, f):
    """<=16-bit ot_s81_land chunks of one crossing; returns SV text; f = OR of the chunk faults"""
    out, fs, lo = [], [], 0
    n = 0
    while lo < width:
        w = min(16, width - lo)
        out.append(f"        ot_s81_land #(.W({w}), .D(4)) {name}{n} (.k(3'd1), .ck_f({ck_f}), .i({i}[{lo + w - 1}:{lo}]), "
                   f".ck({ck}), .rs({rs}), .o({o}[{lo + w - 1}:{lo}]), .fault({name}_f[{n}]));")
        fs.append(n)
        lo += w
        n += 1
    return f"        wire [{n - 1}:0] {name}_f;\n" + '\n'.join(out) + f"\n        assign {f} = |{name}_f;"


LANE_NEW = """    // REGIONAL CLOCK (RTLGAP-SUKV 10-22, SAFE 7): lane l = its own clock region on ck_l[l]; control <-> lane crossings
    // are fixed-latency landing rings (ot_s81_land D 4, K 1: 2 edges each way), cut in <= 16-bit chunks.
    wire [7:0] lif, lof;
    wire [7:0] ors;
    ot_pool_reset_tree #(.N(8),.ID(40)) u_ors(clk,rst_n,ors);
    generate for (l = 0; l < 8; l = l + 1) begin : g_lane
        wire lrs; wire [34:0] li_src = {l_v, l_role, l_d[32 * l +: 32]}; wire [34:0] li;
        wire o_v_r, f_r; wire [31:0] y_r, y32_r; wire [65:0] lo_src, lo_l;
        ot_pool_reset_tree #(.N(1),.ID(48+l)) u_lrs(ck_l[l],rst_n,lrs);
@@IN@@
        ot_s81sl_cmp_pool_lane_pooln #(.LM(LM), .LA(LA), .MUT(MUT)) u_l (
            .clk(ck_l[l]), .rst_n(rst_n), .i_v(li[34]), .i_role(li[33:32]), .i_d(li[31:0]),
            .o_v(o_v_r), .o_y(y_r), .o_y32(y32_r), .fault(f_r));
        assign lo_src = {o_v_r, f_r | lif[l], y_r, y32_r};
@@OUT@@
        assign lo_v[l] = lo_l[65]; assign lf[l] = lo_l[64] | lof[l];
        assign lo_y[32 * l +: 32] = lo_l[63:32]; assign lo_y32[32 * l +: 32] = lo_l[31:0];
    end endgenerate"""


def make(variant):
    src = R / f'rtl/dsrom_sys/s81_dv/slice/pool_native_{variant}.sv'
    t = src.read_text()
    assert t.count(LANE_OLD) == 1, 'lane block'
    new = LANE_NEW.replace('@@IN@@', rings('u_li', 35, 'clk', 'ck_l[l]', 'lrs', 'li_src', 'li', 'lif[l]')) \
                  .replace('@@OUT@@', rings('u_lo', 66, 'ck_l[l]', 'clk', 'ors[l]', 'lo_src', 'lo_l', 'lof[l]'))
    t = t.replace(LANE_OLD, new)
    old_port = """    input  wire         clk,
    input  wire         rst_n,
    input  wire         start,"""
    assert t.count(old_port) == 1
    t = t.replace(old_port, """    input  wire         clk,            // control region root
    input  wire [7:0]   ck_l,           // lane region roots (one local tree per lane)
    input  wire         rst_n,
    input  wire         start,""")
    t = t.replace('// GENERATED by tools/s81_dv/rtlgap_sukv_1021/pool_native_source.py.',
                  '// GENERATED by tools/s81_dv/rtlgap_sukv_1021/pool_regional_source.py from pool_native_' + variant +
                  '.sv (pool_native_source.py).', 1)
    land = (R / 'rtl/dsrom_sys/s81_dv/land/ot_s81_land.sv').read_text()
    out = R / f'rtl/dsrom_sys/s81_dv/slice/pool_regional_{variant}.sv'
    out.write_text(t + '\n// ---- landing ring (verbatim rtl/dsrom_sys/s81_dv/land/ot_s81_land.sv)\n' + land)
    man = dict(variant=variant, base=str(src.relative_to(R)), base_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),
               land_sha256=hashlib.sha256(land.encode()).hexdigest(),
               generated_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),
               clock_ports=dict(control='clk', lanes='ck_l[7:0]'), ring=dict(D=4, K=1, chunk_bits=16,
               in_bits=35, out_bits=66), added_command_edges=4, arithmetic_edges_added=0,
               qualification='UNQUALIFIED until numerical (positive + swap_kv) and native census on this file')
    out.with_suffix('.json').write_text(json.dumps(man, indent=2) + '\n')
    return out





# ---- RTLGAP-POOL 10-22: the same regional construction on the census-safe successor (pool_safe_<variant>.sv)
LANE_OLD_SAFE = """    generate for (l = 0; l < 8; l = l + 1) begin : g_lane
        ot_s81sl_cmp_pool_lane #(.LM(LM), .LA(LA), .MUT(MUT)) u_l (
            .clk(clk), .rst_n(rl[4 + l]), .i_v(l_v[l]), .i_role(l_role[2*l +: 2]), .i_d(l_d[32 * l +: 32]),
            .o_v(lo_v[l]), .o_y(lo_y[32 * l +: 32]), .o_y32(lo_y32[32 * l +: 32]), .fault(lf[l]));
    end endgenerate"""
LANE_NEW_SAFE = (LANE_NEW.replace('    wire [7:0] ors;\n    ot_pool_reset_tree #(.N(8),.ID(40)) u_ors(clk,rst_n,ors);\n', '')
                 .replace('wire lrs;', 'wire [NIN:0] lrs; wire [NOUT-1:0] ors;')
                 .replace('ot_pool_reset_tree #(.N(1),.ID(48+l)) u_lrs(ck_l[l],rst_n,lrs);',
                          'ot_psf_rtree #(.N(NIN + 1)) u_lrs (.clk(ck_l[l]), .rst_n(rst_n), .q(lrs));\n'
                          '        ot_psf_rtree #(.N(NOUT)) u_ors (.clk(clk), .rst_n(rst_n), .q(ors));')
                 .replace('wire [34:0] li_src = {l_v, l_role, l_d[32 * l +: 32]};',
                          'wire [34:0] li_src = {l_v[l], l_role[2*l +: 2], l_d[32 * l +: 32]};')
                 .replace('ot_s81sl_cmp_pool_lane_pooln', 'ot_s81sl_cmp_pool_lane')
                 .replace('.clk(ck_l[l]), .rst_n(rst_n), .i_v', '.clk(ck_l[l]), .rst_n(lrs[NIN]), .i_v'))


# 8-bit chunks: a ring's read-slot select drives its W-bit read mux twice plus the epoch check (16 b: 38-39 loads)
CHUNK_SAFE = 8
NIN, NOUT = (35 + CHUNK_SAFE - 1) // CHUNK_SAFE, (66 + CHUNK_SAFE - 1) // CHUNK_SAFE


def rings_rs(name, width, ck_f, ck, rs_fmt, i, o, f):
    """rings() with a reset leaf per chunk: rs_fmt.format(n)"""
    out, lo, n = [], 0, 0
    while lo < width:
        w = min(CHUNK_SAFE, width - lo)
        out.append(f"        ot_s81_land #(.W({w}), .D(4)) {name}{n} (.k(3'd1), .ck_f({ck_f}), .i({i}[{lo + w - 1}:{lo}]), "
                   f".ck({ck}), .rs({rs_fmt.format(n)}), .o({o}[{lo + w - 1}:{lo}]), .fault({name}_f[{n}]));")
        lo += w
        n += 1
    return f"        wire [{n - 1}:0] {name}_f;\n" + '\n'.join(out) + f"\n        assign {f} = |{name}_f;"


def make_safe(variant):
    src = R / f'rtl/dsrom_sys/s81_dv/slice/pool_safe_{variant}.sv'
    t = src.read_text()
    assert t.count(LANE_OLD_SAFE) == 1, 'safe lane block'
    # one reset leaf per landing ring (a shared per-lane relay drove all 5 rings' rs: 40 loads)
    new = LANE_NEW_SAFE.replace('@@IN@@', rings_rs('u_li', 35, 'clk', 'ck_l[l]', 'lrs[{}]', 'li_src', 'li', 'lif[l]')) \
                       .replace('@@OUT@@', rings_rs('u_lo', 66, 'ck_l[l]', 'clk', 'ors[{}]', 'lo_src', 'lo_l', 'lof[l]'))
    new = new.replace('NIN', str(NIN)).replace('NOUT', str(NOUT))
    new = new.replace('cut in <= 16-bit chunks.', f'cut in <= {CHUNK_SAFE}-bit chunks, one reset leaf per ring.')
    t = t.replace(LANE_OLD_SAFE, new)
    old_port = """    input  wire         clk,
    input  wire         rst_n,
    input  wire         start,"""
    assert t.count(old_port) == 1
    t = t.replace(old_port, """    input  wire         clk,            // control region root
    input  wire [7:0]   ck_l,           // lane region roots (one local tree per lane)
    input  wire         rst_n,
    input  wire         start,""")
    # control-side landing faults join the top fault
    old_f = "                if (|lf) fault <= 1'b1;"
    assert t.count(old_f) == 1
    land = (R / 'rtl/dsrom_sys/s81_dv/land/ot_s81_land.sv').read_text()
    out = R / f'rtl/dsrom_sys/s81_dv/slice/pool_regional_safe_{variant}.sv'
    out.write_text('// GENERATED by tools/s81_dv/rtlgap_sukv_1021/pool_regional_source.py --safe from pool_safe_' + variant +
                   '.sv\n' + t + '\n// ---- landing ring (verbatim rtl/dsrom_sys/s81_dv/land/ot_s81_land.sv)\n' + land)
    man = dict(variant=variant, base=str(src.relative_to(R)), base_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),
               land_sha256=hashlib.sha256(land.encode()).hexdigest(),
               generated_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),
               clock_ports=dict(control='clk', lanes='ck_l[7:0]'), ring=dict(D=4, K=1, chunk_bits=CHUNK_SAFE,
               in_bits=35, out_bits=66), added_command_edges=4, arithmetic_edges_added=0,
               qualification='UNQUALIFIED until numerical (positive + swap_kv) and native census on this file')
    out.with_suffix('.json').write_text(json.dumps(man, indent=2) + '\n')
    return out


if __name__ == '__main__':
    args = sys.argv[1:]
    safe = '--safe' in args
    args = [a for a in args if a != '--safe']
    for v in (args or ['main', 'alternate']):
        print(make_safe(v) if safe else make(v))
