#!/usr/bin/env python3
"""dv_slice_tb.py -- emit the replay bench for a slice cut by dv_slice_cut.py (LAYERBENCH-S81, TOK.DS.BENCH.3, 10-18).

The bench (tb_<top>.sv) instantiates the slice top and:
  * clocks: every die region clock and every forwarded-root clock port (slice_ports kind `clock`) from ONE bench clock
    (functional RTL: the landings and relays are fixed-latency; skew is a timing question, as tb_dv_die_probe);
  * reset: die rst_n asserted at 0.1 ns (a falling edge, so asynchronous clears reach flops whose gated clock is still
    stopped -- the hop-0 lane gate, S81-LBGAP/G1), low NRST cycles, released at a falling edge; cycle k = the k-th rising edge after release (k = 0
    first);
  * replay inputs (+IN=<file>): lines `<cycle> <port index> <hex value>`; an integer cycle k is applied at the falling
    edge before rising edge k (sampled at k); a half cycle k.5 (forwarded half-cycle hop face) is applied right after
    rising edge k (sampled by the falling-edge stage at k + 0.5).  Ports hold their value until the next event (the
    neighbour's output register holds); events must be sorted by cycle;
  * scheduled output checks (+OUT=<file>): lines `<cycle> <port index> <hex mask> <hex value>`: sampled at the falling
    edge after rising edge k; a masked mismatch is a SCHEDULE fault (printed with cycle / port / got / want);
  * sticky faults: every bit of the die `land_fault` vector inside the slice and every output port named *fault*
    must stay 0 after release (static schedule: an overflow / underflow / late lane is a fault, never a stall);
  * trace (+TRACE=<file>): every boundary output port value change `<cycle> <port> <hex>` (what leaves the slice);
  * wall stamps DV_SLICE_T0 / T1 (cycles per wall second), verdict `TB_DV_SLICE PASS|FAIL`.
Port indices are the order of slice_ports.json (written to <out>/tb_ports.json).
Usage: dv_slice_tb.py --ports slice_ports.json --top slice_top --out DIR
"""
import argparse
import json
import re
from pathlib import Path


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--ports', required=True)
    ap.add_argument('--top', default='slice_top')
    ap.add_argument('--out', required=True)
    a = ap.parse_args(argv)
    P = json.loads(Path(a.ports).read_text())['ports']
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    names = list(P)
    W = max(v['width'] + v['lo'] for v in P.values())
    v = ['`timescale 1ns/1ps',
         f'// generated by tools/s81_dv/dv_slice_tb.py from {Path(a.ports).name}: replay bench of {a.top} (see the tool)',
         f'module tb_{a.top};',
         '    parameter integer NRST = 64;',
         '    integer NCYC = 2000;',
         '    reg ck = 1\'b0; always #0.4165 ck = ~ck;',
         '    reg rst_n = 1\'b1;   // power-on: asserted at 0.1 ns (an edge: async clears of stopped gated clocks, LANDING-CONTRACT L3)',
         '    integer cyc = -1;      // rising edges since release (-1 = in reset)',
         f'    localparam integer MAXW = {W};']
    conn, flt = [], []
    for i, n in enumerate(names):
        p = P[n]
        rng = f'[{p["lo"] + p["width"] - 1}:{p["lo"]}]' if (p['width'] > 1 or p['lo']) else ''
        if p['dir'] == 'input':
            if p['kind'] == 'clock':
                v.append(f'    wire {rng} {n} = {{{p["width"]}{{ck}}}};')
            elif p['kind'] == 'die_input' and p['net'] == 'rst_n':
                v.append(f'    wire {n} = rst_n;')
            else:
                v.append(f'    reg {rng} {n} = 0;')
        else:
            v.append(f'    wire {rng} {n};')
            if 'fault' in p['net']:
                bits = ' | '.join(f'(|{n}[{h}:{l}])' for h, l in p['bits'])
                flt.append(bits)
        conn.append(f'.{n}({n})')
    v.append(f'    {a.top} u_slice ({", ".join(conn)});')
    drv = [(i, n) for i, n in enumerate(names) if P[n]['dir'] == 'input' and P[n]['kind'] not in ('clock',) and
           not (P[n]['kind'] == 'die_input' and P[n]['net'] == 'rst_n')]
    outs = [(i, n) for i, n in enumerate(names) if P[n]['dir'] == 'output']
    v += ['    // ---- replay inputs',
          '    integer fin = 0, fout = 0, ftr = 0, rc, n_in = 0, n_chk = 0, n_bad = 0, n_flt = 0, first_flt = -1;',
          '    real ec; integer ep; reg [MAXW-1:0] ev, em; reg have_ev = 0;',
          '    real oc; integer op; reg [MAXW-1:0] ov, om; reg have_ov = 0;',
          '    string fn;',
          '    task automatic put(input integer idx, input reg [MAXW-1:0] val);',
          '        case (idx)']
    for i, n in drv:
        v.append(f'            {i}: {n} = val[{P[n]["lo"] + P[n]["width"] - 1}:0];')
    v += ['            default: begin $display("TB_DV_SLICE replay port %0d is not a driven input", idx); n_bad = n_bad + 1; end',
          '        endcase',
          '        n_in = n_in + 1;',
          '    endtask',
          '    function automatic reg [MAXW-1:0] get(input integer idx);',
          '        get = 0;',
          '        case (idx)']
    for i, n in outs:
        v.append(f'            {i}: get[{P[n]["lo"] + P[n]["width"] - 1}:0] = {n};')
    v += ['            default: get = 0;',
          '        endcase',
          '    endfunction',
          '    task automatic next_in; begin',
          '        have_ev = 0;',
          '        if (fin != 0 && !$feof(fin)) begin rc = $fscanf(fin, "%f %d %h\\n", ec, ep, ev); have_ev = (rc == 3); end',
          '    end endtask',
          '    task automatic next_out; begin',
          '        have_ov = 0;',
          '        if (fout != 0 && !$feof(fout)) begin rc = $fscanf(fout, "%f %d %h %h\\n", oc, op, om, ov); have_ov = (rc == 4); end',
          '    end endtask',
          '    // integer events: at the falling edge before rising edge k (cyc == k - 1 after edge k - 1)',
          '    always @(negedge ck) if (rst_n || cyc == -1) begin',
          '        while (have_ev && ec == $itor(cyc + 1)) begin put(ep, ev); next_in(); end',
          '    end',
          '    // half-cycle events k.5: right after rising edge k',
          '    always @(posedge ck) begin',
          '        if (rst_n) cyc = cyc + 1;',
          '        while (have_ev && ec == $itor(cyc) + 0.5) begin put(ep, ev); next_in(); end',
          '    end',
          '    // scheduled output checks + trace + sticky faults: falling edge after rising edge k',
          '    reg [MAXW-1:0] prev [0:%d];' % (len(names) - 1),
          '    integer k;',
          '    always @(negedge ck) if (rst_n && cyc >= 0) begin',
          '        while (have_ov && oc < $itor(cyc)) begin $display("TB_DV_SLICE missed check at %0.1f port %0d", oc, op); n_bad = n_bad + 1; next_out(); end',
          '        while (have_ov && oc == $itor(cyc)) begin',
          '            n_chk = n_chk + 1;',
          '            if ((get(op) & om) !== (ov & om)) begin',
          '                n_bad = n_bad + 1;',
          '                if (n_bad < 20) $display("TB_DV_SLICE SCHEDULE_MISMATCH cycle %0d port %0d got %h want %h mask %h", cyc, op, get(op) & om, ov & om, om);',
          '            end',
          '            next_out();',
          '        end']
    for i, n in outs:
        v.append(f'        if (ftr != 0 && get({i}) !== prev[{i}]) begin $fdisplay(ftr, "%0d {i} %h", cyc, get({i})); prev[{i}] = get({i}); end')
    if flt:
        v.append(f'        if ({" | ".join(flt)}) begin n_flt = n_flt + 1; if (first_flt < 0) first_flt = cyc; end')
    v += ['    end',
          '    initial begin',
          '        for (k = 0; k < %d; k = k + 1) prev[k] = 0;' % len(names),
          '        if (!$value$plusargs("NCYC=%d", NCYC)) NCYC = 2000;',
          '        if ($value$plusargs("IN=%s", fn)) begin fin = $fopen(fn, "r"); if (fin == 0) begin $display("TB_DV_SLICE FAIL no IN %s", fn); $finish; end end',
          '        if ($value$plusargs("OUT=%s", fn)) begin fout = $fopen(fn, "r"); if (fout == 0) begin $display("TB_DV_SLICE FAIL no OUT %s", fn); $finish; end end',
          '        if ($value$plusargs("TRACE=%s", fn)) ftr = $fopen(fn, "w");',
          '        next_in(); next_out();',
          '        #0.1 rst_n = 1\'b0;',
          '        repeat (NRST) @(posedge ck);',
          '        @(negedge ck);',
          '        $system("date +DV_SLICE_T0=%s.%N");',
          '        rst_n = 1\'b1;',
          '        repeat (NCYC) @(posedge ck);',
          '        @(negedge ck);',
          '        $system("date +DV_SLICE_T1=%s.%N");',
          '        if (have_ov) begin $display("TB_DV_SLICE checks left unrun from cycle %0.1f", oc); n_bad = n_bad + 1; end',
          '        if (have_ev) begin $display("TB_DV_SLICE replay events left unapplied from cycle %0.1f", ec); n_bad = n_bad + 1; end',
          '        $display("DV_SLICE cycles=%0d in_events=%0d out_checks=%0d mismatches=%0d fault_cycles=%0d first_fault=%0d",'
          ' NCYC, n_in, n_chk, n_bad, n_flt, first_flt);',
          '        if (ftr != 0) $fclose(ftr);',
          '        if (n_bad == 0 && n_flt == 0) $display("TB_DV_SLICE PASS"); else $display("TB_DV_SLICE FAIL");',
          '        $finish;',
          '    end',
          'endmodule', '']
    (out / f'tb_{a.top}.sv').write_text('\n'.join(v))
    (out / 'tb_ports.json').write_text(json.dumps([dict(index=i, port=n, dir=P[n]['dir'], kind=P[n]['kind'],
                                                        width=P[n]['width'], lo=P[n]['lo'], bits=P[n]['bits'])
                                                   for i, n in enumerate(names)], indent=0) + '\n')
    print(f'dv_slice_tb: tb_{a.top}.sv ports {len(names)} driven {len(drv)} checked {len(outs)} fault vectors {len(flt)}')


if __name__ == '__main__':
    main()
