#!/usr/bin/env python3
"""seq (B) hardened landing bands (STW-S81c-COLLA2-VP 2026-10-22).

Reads the generated landed parent rtl/dsrom_sys/s81_dv/unit/r3/dsdv_seq_host_c_r3_lp.sv and re-partitions it WITHOUT
changing any register, edge or port:
  * dsdv_sh_lb_lk  : every lk<->sq landing (0..11, both halves), the lk and sq regional reset runs (rst_n_lk / rst_n_sq
                     pads + their kept copies) and the child reset pads of u_l0 / u_l1.  Clocks ck_lk + ck_sq.
  * dsdv_sh_lb_vc  : every sq<->vc landing (12..20), the vc reset run (+ copies), its own copies of the sq run's last stage
                     (lpr_sq_p from dsdv_sh_lb_lk: same edge as the original copies) and the child reset pad of u_l2.
                     Clocks ck_sq + ck_vc.
  * the parent dsdv_seq_host_c_r3_lp (same name, ports, parameters) = u_l0 / u_l1 / u_l2 + the two band children, no
    soft register left.  Each band becomes its own hardened child with its own local CTS (<= ~390 um span), so no parent
    root has to match pin flops strung along the 1,339-um faces (r3c..r3f clock_child_pair 101-485 ps).
Outputs: rtl/dsrom_sys/s81_dv/unit/r3/dsdv_seq_host_c_r3_lb.sv (parent) + dsdv_seq_host_c_r3_lb_bands.sv (bands).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "rtl/dsrom_sys/s81_dv/unit/r3/dsdv_seq_host_c_r3_lp.sv"
OUT_P = ROOT / "rtl/dsrom_sys/s81_dv/unit/r3/dsdv_seq_host_c_r3_lb.sv"
OUT_B = ROOT / "rtl/dsrom_sys/s81_dv/unit/r3/dsdv_seq_host_c_r3_lb_bands.sv"

BANDS = {"lk": {"clocks": ("ck_lk", "ck_sq"), "landings": range(0, 12)},
         "vc": {"clocks": ("ck_sq", "ck_vc"), "landings": range(12, 21)}}

s = SRC.read_text()
lines = s.splitlines()
body_start = next(i for i, l in enumerate(lines) if l.strip() == ");") + 1
end = max(i for i, l in enumerate(lines) if l.strip() == "endmodule")
header = lines[:body_start]
body = lines[body_start:end]

# ---- classify body lines
land = {}           # k -> [lines]
cur = None
rst_pad, rst_copy, child_pad, child_lines, decl = {}, {}, {}, [], []
in_child = False
for l in body:
    m = re.match(r"\s*// ---- LANDING (\d+):", l)
    if m:
        cur = int(m.group(1)); land[cur] = [l]; continue
    if cur is not None and (l.strip().startswith(("wire [2*", "ot_pl_land_", "assign "))):
        land[cur].append(l); continue
    cur = None
    m = re.match(r"\s*wire (lpr_(lk|sq|vc)_p);\s*ot_pl_pad", l)
    if m: rst_pad[m.group(2)] = l; continue
    m = re.match(r"\s*wire (lpr_(lk|sq|vc)_c(\d+));\s*ot_pl_land_rst_copy", l)
    if m: rst_copy[m.group(1)] = l; continue
    m = re.match(r"\s*wire (lpr_c_u_l(\d));\s*ot_pl_pad", l)
    if m: child_pad[int(m.group(2))] = l; continue
    if "---- children" in l: in_child = True
    if in_child: child_lines.append(l); continue
    if l.strip().startswith("wire [") and not land: decl.append(l); continue
assert sorted(land) == list(range(21)), sorted(land)
assert set(rst_pad) == {"lk", "sq", "vc"} and sorted(child_pad) == [0, 1, 2]

def landing_io(k):
    ls = land[k]
    w = next(x for x in ls if "_w (" in x); r = next(x for x in ls if "_r (" in x)
    a = next(x for x in ls if x.strip().startswith("assign "))
    i_sig = re.search(r"\.i\((\w+)\)", w).group(1)
    o_sig = re.search(r"assign (\w+) =", a).group(1)
    dl = next(x for x in ls if x.strip().startswith("wire [2*"))
    mm = re.search(r"wire (?:\[([^\]]+?):0\])?\s*" + o_sig + r", lpl_\d+_o;", dl)
    if not mm: sys.exit(f"landing {k}: {o_sig} not in {dl[-120:]}")
    width = mm.group(1)
    rsts = set(re.findall(r"\.rsi\((lpr_\w+)\)", w + r))
    return i_sig, o_sig, width, rsts

def resets_used(text):
    return sorted(set(re.findall(r"\b(lpr_(?:lk|sq|vc)_c\d+)\b", text)), key=lambda x: (x[4:6], int(x.split("_c")[1])))

bands_v = ["`timescale 1ns/1ps",
           "// GENERATED by tools/s81_dv/seq_three_roots_1021/build_bands_b1.py from dsdv_seq_host_c_r3_lp.sv -- do not edit.",
           "// seq (B) hardened landing bands: the landing halves, regional reset runs and child reset pads of the landed",
           "// parent, regrouped by seam band.  Every register, reset depth and edge is the original's (same lines)."]
ports_of = {}
for b, cfg in BANDS.items():
    ks = list(cfg["landings"])
    ios = {k: landing_io(k) for k in ks}
    text = "\n".join("\n".join(land[k]) for k in ks)
    pads = {"lk": ["lk", "sq"], "vc": ["vc"]}[b]
    cpads = {"lk": [0, 1], "vc": [2]}[b]
    text_all = text + "\n" + "\n".join(child_pad[c] for c in cpads)
    copies = resets_used(text_all)
    ports = [("input", "", c) for c in cfg["clocks"]]
    ports += [("input", "", "rst_n_" + p) for p in pads]
    if b == "vc":
        ports.append(("input", "", "lpr_sq_p"))
    for k in ks:
        i_sig, o_sig, width, _ = ios[k]
        wd = f"[{width}:0] " if width else ""
        ports.append(("input", wd, i_sig))
        ports.append(("output", wd, o_sig))
    ports += [("output", "", f"lpr_c_u_l{c}") for c in cpads]
    if b == "lk":
        ports.append(("output", "", "lpr_sq_p_o"))
    ports_of[b] = ports
    mod = f"dsdv_sh_lb_{b}"
    bands_v.append(f"module {mod} #(")
    bands_v.append("    parameter integer V = 276, parameter integer MUT = 0")
    bands_v.append(") (")
    bands_v.append(",\n".join(f"    {d} wire {w}{n}" for d, w, n in ports))
    bands_v.append(");")
    for p in pads:
        bands_v.append(rst_pad[p])
    if b == "lk":
        bands_v.append("    assign lpr_sq_p_o = lpr_sq_p;   // the sq run's last pad stage, to dsdv_sh_lb_vc (it keeps its own copies)")
    for c in copies:
        bands_v.append(rst_copy[c])
    for k in ks:
        ls = list(land[k])
        # the band's input/output are ports: drop them from the landing's local wire declarations
        i_sig, o_sig, width, _ = ios[k]
        ls = [re.sub(r"wire (\[[^\]]+?:0\])?\s*" + o_sig + r", ", lambda m: "wire " + (m.group(1) + " " if m.group(1) else ""), x) for x in ls]
        bands_v.extend(ls)
    for c in cpads:
        bands_v.append(child_pad[c].replace(f"wire lpr_c_u_l{c};", ""))
    bands_v.append("endmodule")
    bands_v.append("")
OUT_B.write_text("\n".join(bands_v) + "\n")

# ---- parent
par = ["`timescale 1ns/1ps",
       "// GENERATED by tools/s81_dv/seq_three_roots_1021/build_bands_b1.py from dsdv_seq_host_c_r3_lp.sv -- do not edit.",
       "// seq (B) hardened landing bands: same module, ports and edges as dsdv_seq_host_c_r3_lp.sv; its landing halves and",
       "// reset runs live in the hard band children dsdv_sh_lb_lk (lk<->sq, south of u_l1) and dsdv_sh_lb_vc (sq<->vc,",
       "// north of u_l1).  Bands: dsdv_seq_host_c_r3_lb_bands.sv."]
par += [l for l in header if not l.startswith("`timescale") and not l.startswith("//")]
par += decl
for k in range(21):
    _, o_sig, width, _ = landing_io(k)
    par.append(f"    wire {'[' + width + ':0] ' if width else ''}{o_sig};")
par.append("    wire lpr_c_u_l0, lpr_c_u_l1, lpr_c_u_l2, lpr_sq_p;")
for b in BANDS:
    conn = []
    for d, w, n in ports_of[b]:
        net = {"lpr_sq_p_o": "lpr_sq_p"}.get(n, n)
        conn.append(f".{n}({net})")
    par.append(f"    dsdv_sh_lb_{b}")
    par.append("`ifndef SYNTHESIS")
    par.append("    #(.V(V), .MUT(MUT))")
    par.append("`endif")
    par.append(f"    u_b{b} (" + ", ".join(conn) + ");")
par += child_lines
par.append("endmodule")
OUT_P.write_text("\n".join(par) + "\n")
print(f"wrote {OUT_P.relative_to(ROOT)} and {OUT_B.relative_to(ROOT)}")
for b in BANDS:
    print(b, "ports", len(ports_of[b]), "bits", sum(eval(w.strip().strip('[]').split(':')[0].replace('V', '276')) + 1 if w else 1 for _, w, _ in ports_of[b]))
