#!/usr/bin/env python3
"""frame_seam_ref.py -- S81-P7 (10-23): the SEAM_REF hook of tb_s81dv_frame (tools/s81_dv/frame_seam_bench.sh).

  frame_seam_ref.py --master col_h9 --dut DUT.sv --ref REF.sv --out-ref REF_RENAMED.sv --out-svh seam_ref.svh [--t0 N]

REF.sv (the vgch banded twin) is copied with every module col_<M>_l4_lp* renamed col_<M>_l4_lp_ref*; seam_ref.svh
instantiates it as ref_f on the tb's framed traffic and compares, every edge from --t0 on, each DUT band-seam output
(u_lpl_<N>_r.o inside the band instance u_b<k> / u_r<k> of the DUT frame) with the reference landing output of the
same seam.  A difference prints 'FAULT SEAM_MISMATCH ...' (frame_bench.py check counts FAULT lines as errors).
"""
import argparse, re
from pathlib import Path


def seam_bands(text, top):
    """{seam number: band instance} -- the band module that holds u_lpl_<N>_r"""
    out = {}
    for m in re.split(r'^module ', text, flags=re.M)[1:]:
        name = m.split()[0]
        b = re.match(r'%s_(b|r)(\d+)$' % re.escape(top), name)
        if not b:
            continue
        for n in re.findall(r'\bu_lpl_(\d+)_r \(', m):
            out[int(n)] = f'u_{b.group(1)}{b.group(2)}'
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--master', default='col_h9')
    ap.add_argument('--dut', required=True)
    ap.add_argument('--ref', required=True)
    ap.add_argument('--out-ref', required=True)
    ap.add_argument('--out-svh', required=True)
    ap.add_argument('--t0', type=int, default=0, help='first compared edge (reset warm-up)')
    a = ap.parse_args()
    top = f'{a.master}_l4_lp'
    rt = Path(a.ref).read_text()
    dt = Path(a.dut).read_text()
    ref_b, dut_b = seam_bands(rt, top), seam_bands(dt, top)
    assert ref_b and set(ref_b) == set(dut_b), (sorted(ref_b), sorted(dut_b))
    Path(a.out_ref).write_text(re.sub(r'\b%s(?=(_b\d+)?\b)' % re.escape(top), top + '_ref', rt))
    L = ['    // GENERATED by tools/s81_dv/frame_seam_ref.py',
         f'    wire [1103:0] ref_xo; wire [3:0] ref_xok; wire [69:0] ref_ret; integer nseam = 0;',
         f'    {top}_ref #(.INSTANCE("f"), .MUT(0)) ref_f (.ck_r0(clk), .ck_r1(clk), .ck_r2(clk), .rst_n(rst_n), .x(xin),',
         '`ifdef TB_FWD_GATE',
         '        .xk({4{xkg}}),', '`else', '        .xk({4{clk}}),', '`endif',
         "        .lk({4{3'd`LK}}), .xo(ref_xo), .xok(ref_xok), .ret(ref_ret));",
         '    always @(posedge clk) if (rst_n && edge_n >= %d) begin' % a.t0]
    for n in sorted(ref_b):
        d, r = f'dut.u_f.{dut_b[n]}.u_lpl_{n}_r.o', f'ref_f.{ref_b[n]}.u_lpl_{n}_r.o'
        L.append(f'        if ({d} !== {r}) begin if (nseam < 8) $display("FAULT SEAM_MISMATCH lpl_{n} edge %0d", edge_n); '
                 'nseam = nseam + 1; end')
    L.append('    end')
    # activity: a seam whose output never toggles cannot show a re-timing; report toggles per seam at the end
    for n in sorted(ref_b):
        d = f'dut.u_f.{dut_b[n]}.u_lpl_{n}_r.o'
        L.append(f'    logic [$bits({d})-1:0] sa_pv_{n}; integer sa_tg_{n} = 0;')
        L.append(f'    always @(posedge clk) begin if ({d} !== sa_pv_{n}) sa_tg_{n} = sa_tg_{n} + 1; sa_pv_{n} <= {d}; end')
    L.append('    final begin')
    for n in sorted(ref_b):
        L.append(f'        $display("SEAM_ACT lpl_{n} toggles %0d", sa_tg_{n});')
    L.append('    end')
    Path(a.out_svh).write_text('\n'.join(L) + '\n')
    print(f'seams compared: {len(ref_b)}')


if __name__ == '__main__':
    main()
