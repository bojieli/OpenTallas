#!/usr/bin/env python3
"""Generate regional ENDP source and nonoverlapping existing-E2 ML fences.

The endpoint pins are conservatively the ENTIRE proposed bands for every bit.
The land pins are from its actual R0 LEF. This is a source/placement constraint
candidate: actual DPL/CTS cell bounds and exported endpoint pins must be checked.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


def box(x, y, size):
    return [x-size/2, y-size/2, x+size/2, y+size/2]


def corners(b):
    return [(x,y) for x in (b[0],b[2]) for y in (b[1],b[3])]


def distance(a,b):
    return max(abs(x-u)+abs(y-v) for x,y in a for u,v in b)


def hook(text):
    assert text.count('module ot_s81sl_slice_lepw_mab_mu_lra_lp #(')==1
    text=text.replace('module ot_s81sl_slice_lepw_mab_mu_lra_lp #(', 'module ot_s81sl_slice_lepw_mab_mu_regional_e2_lp #(')
    text=text.replace('    input wire ck_K,', '    input wire ck_K,\n    input wire ck_A,\n    input wire ck_B,')
    text=text.replace('    input wire rst_n_K,', '    input wire rst_n_K,\n    input wire rst_n_A,\n    input wire rst_n_B,')
    marker='    // ---- regional reset runs '
    assert text.count(marker)==1
    extra='    // Manual regional hook: preserve existing K/ML/S/P E2 and reset ages.\n'
    for r in ('A','B'):
        extra+=f'    wire [1:0] lpr_{r}_lanes;\n    ot_pl_land_reset_forest #(.DEPTH(10),.LEAVES(2),.ROOT_LOADS(1)) u_lpr_{r} (.ck(ck_{r}),.d(rst_n_{r}),.q(lpr_{r}_lanes));\n'
    text=text.replace(marker,extra+marker)
    for n in range(4):
        r='A' if n<2 else 'B'
        pat=rf'(    wire lpr_c_u_ln{n};[^\n]+)'
        old=re.search(pat,text).group(1)
        new=old.replace('.ck(ck_K)',f'.ck(ck_{r})').replace('.d(lpr_K)',f'.d(lpr_{r}_lanes[{n%2}])')
        text=text.replace(old,new)
        pat=rf'(    dsfd_coll_lane_w_safe8_ntf u_ln{n} [^\n]+)'
        old=re.search(pat,text).group(1)
        text=text.replace(old,old.replace('.ck(ck_K)',f'.ck(ck_{r})').replace('// region K',f'// region {r}'))
    old='    ot_s81sl_lep_mu_ab\n`ifndef SYNTHESIS\n    #(.RX_SRAM(1), .IN_PIPE(1), .NATIVE32(1))\n`endif\n    u_lep (.clk(ck_K),'
    assert text.count(old)==1
    text=text.replace(old,'    ot_s81sl_lep_mu_ab_regional #(.DR(12),.CRED(12),.RX_SRAM(1),.IN_PIPE(1),.NATIVE32(1))\n    u_lep (.clk(ck_K),.clk_a(ck_A),.clk_b(ck_B),')
    text=text.replace('// GENERATED by tools/landed_parent/lp.py', '// DERIVED by dv_endp_regional_e2_1021.py from immutable tools/landed_parent/lp.py output',1)
    return '// Regional candidate: baseline four regions plus independent A/B lane roots; no extra parent data stage.\n'+text


def main():
    p=argparse.ArgumentParser()
    for n in ('parent-rtl','land-lef','writer-stat','reader-stat','out-dir'):p.add_argument('--'+n,required=True)
    p.add_argument('--variant',choices=('main','fallback'),required=True)
    a=p.parse_args();out=Path(a.out_dir);out.mkdir(parents=True,exist_ok=True)
    fb=a.variant=='fallback';dx=86.4 if fb else 0;dy=86.4 if fb else 0
    landx,landy=1425.6+dx,2592+dy;ex=1382.4+dx
    text=Path(a.land_lef).read_text();pins={}
    for name,body in re.findall(r'  PIN (\S+)\n(.*?)  END \1',text,re.S):
        q=re.search(r'RECT\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)',body)
        if q:
            x0,y0,x1,y1=map(float,q.groups());pins[name]=(landx+(x0+x1)/2,landy+(y0+y1)/2)
    assert all(f'{s}[{i}]' in pins for s in ('wd','rd') for i in range(1104))
    wa=json.loads(Path(a.writer_stat).read_text())['design']['area']
    ra=json.loads(Path(a.reader_stat).read_text())['design']['area']
    assert wa/(6.48**2)<0.50 and ra/(4.32**2)<0.50,(wa,ra)
    cells=[];reach=[]
    def emit(direction,n,scalar=None):
        c,r=n%12,n//12
        if direction=='WD':
            w=box(1418+7.02*c+dx,2360+7.02*r+dy,6.48)
            q=box(1600+5.4*c+dx,2502+5.4*r+dy,4.32)
            src=[(ex,2160+dy),(ex,2592+dy)]
            dst=[pins[f'wd[{i}]'] for i in range(n*8,(n+1)*8)] if scalar is None else [pins['wv']]
            roots=('K','ML');idx=8 if scalar is None else 7
        else:
            w=box(1430+7.02*c+dx,2490+7.02*r+dy,6.48)
            q=box(1389+4.86*(n%6)+dx,2709+4.86*(n//6)+dy,4.32)
            src=[pins[f'rd[{i}]'] for i in range(n*8,(n+1)*8)] if scalar is None else [pins[scalar]]
            dst=[(ex,2635.2+dy),(ex,3067.2+dy)]
            roots=('ML','K');idx=5 if scalar is None else {'rv':4,'fault':6}[scalar]
        chunk=n if scalar is None else 0
        for suffix,b,root in zip(('w','r'),(w,q),roots):
            cells.append(dict(name=f'{direction}_{scalar or n}_{suffix}',box_um=[round(t,6) for t in b],
                hierarchy=f'u_lpl_{idx}_{suffix}.g_chunk[{chunk}].u_local',clock=f'ck_{root}',
                mapped_area_upper_um2=wa if suffix=='w' else ra,area_scope='actual W8 D4/K2 map; conservatively also bounds scalar local'))
        legs=[distance(src,corners(w)),distance(corners(w),corners(q)),distance(corners(q),dst)]
        assert max(legs)<=405+1e-6,(direction,n,legs)
        reach.append(dict(direction=direction,chunk=n,scalar=scalar,registered_arcs_um=legs))
    for d in ('WD','RD'):
        for n in range(138):emit(d,n)
    emit('WD',138,'wv');emit('RD',138,'rv');emit('RD',139,'fault')
    macros=[dict(name='u_lep',box_um=[820.8,1728,ex,1728+1900.8+(172.8 if fb else 0)]),
            dict(name='u_land',box_um=[landx,landy,landx+475.2,landy+216]),
            dict(name='u_sl',box_um=[1944+dx,43.2,3196.8+dx,6782.4])]
    for i,b in enumerate(cells):
        for c in cells[i+1:]+macros:
            u,v=b['box_um'],c['box_um']
            assert max(v[0]-u[2],u[0]-v[2],v[1]-u[3],u[1]-v[3])>=0.50-1e-6,(b,c)
    rtl=hook(Path(a.parent_rtl).read_text())
    (out/'ot_s81sl_slice_lepw_mab_mu_regional_e2_lp.sv').write_text(rtl)
    tcl=['# Existing E2 groups, cell-inclusive <=405 model. MUST audit post DPL/CTS; do not release these fences silently.',
         'set b [ord::get_db_block]','set dbu [$b getDbUnitsPerMicron]']
    for cell in cells:
        name=cell['name'];pat='^'+re.escape(cell['hierarchy']).replace('\\.','[./]')+r'[./]'
        tcl += [f'set r [odb::dbRegion_create $b "ml_e2_{name}"]',
                'odb::dbBox_create $r '+' '.join('[expr {round('+str(z)+'*$dbu)}]' for z in cell['box_um']),
                f'set g [odb::dbGroup_create $r "ml_e2_{name}"]',
                'set matched 0',
                f'foreach i [$b getInsts] {{ regsub -all {{\\\\}} [$i getName] {{}} n; if {{[regexp {{{pat}}} $n]}} {{ $g addInst $i; incr matched }} }}',
                f'if {{$matched == 0}} {{error "ML E2 hierarchy has no cells: {cell["hierarchy"]}"}}']
    (out/'ml_e2_fences.tcl').write_text('\n'.join(tcl)+'\n')
    record=dict(variant=a.variant,parent_width_um=3326.4 if fb else 3240,macros=macros,
        existing_E2_no_added_edges=True,groups=cells,reach=reach,max_arc_um=max(max(r['registered_arcs_um']) for r in reach),
        writer_mapped_um2=wa,reader_mapped_um2=ra,writer_fence_util=wa/6.48**2,reader_fence_util=ra/4.32**2,
        endpoint_pin_scope='entire proposed MAIN band for EVERY bit, FB +86.4; actual PPL must remain inside bands',
        source_clock_binding={'u_lep.clk':'ck_K','u_lep.clk_a':'ck_A','u_lep.clk_b':'ck_B','u_ln0/1':'ck_A','u_ln2/3':'ck_B'},
        port_clock_required=[f'{p}{i}.{s}' for i in range(4) for p,s in [('tx','o'),('rx','i')]],
        ports={f'{p}{i}.{s}':{'clock_port':'ck_A' if i<2 else 'ck_B'} for i in range(4) for p,s in [('tx','o'),('rx','i')]},
        source_stage_price='existing D4/K2 +3 each direction unchanged; endpoint outer +2 each / +4 RTT must be composed; regional reset A/B depth10 matches old K parent frontend; endpoint internal forests unchanged',
        outstanding=['source hierarchy lint','actual macro abstracts/pins','postDPL/CTS grouped-cell bbox/reach and fanout','other parent S/P and reset routes','end-to-end static producer/calendar ages','die relay-body capacity and STA'],
        adoption=False,inputs={n:hashlib.sha256(Path(getattr(a,n.replace('-','_'))).read_bytes()).hexdigest() for n in ('parent-rtl','land-lef','writer-stat','reader-stat')})
    (out/'ml_e2_record.json').write_text(json.dumps(record,indent=1)+'\n')
    print(json.dumps({k:record[k] for k in ('variant','max_arc_um','writer_mapped_um2','reader_mapped_um2','writer_fence_util','reader_fence_util','adoption')}))


if __name__=='__main__':main()
