#!/usr/bin/env python3
"""Emit source-exact, bounded fanout predecode banks for GUNIT CONTROL_SAFE."""
import re
from pathlib import Path
root = Path(__file__).resolve().parents[3]
rom = (root / "rtl/hdc/v41/ot_hdc_sk_recip_rom.sv").read_text()
rows = re.findall(r"9'd(\d+): begin c0 = 33'h([0-9a-f]+); c1 = 23'h([0-9a-f]+); c2 = 13'h([0-9a-f]+); end", rom)
sqs = re.findall(r"9'd(\d+): sq = 14'h([0-9a-f]+);", rom)
assert [int(x[0]) for x in rows] == list(range(512))
assert [int(x[0]) for x in sqs] == list(range(512))
cs = [[int(x,16) for x in row[1:]] for row in rows]
sq = [int(x[1],16) for x in sqs]
text = """`timescale 1ns/1ps
`default_nettype none
// Source-exact truth tables from ot_hdc_sk_recip_rom; generated by tools/s81_dv/gunit_controls/gen_predecode.py.
// Register the three 3-bit one-hot groups at the EXISTING T-capture edge.
// Fixed module names and SYNTH_KEEP_MODULES preserve independent equal FF.
(* keep_hierarchy = 1 *) module ot_hdc_skp_predecode24(input wire clk, input wire [23:0] d, output reg [23:0] q);
    always @(posedge clk) q <= d;
endmodule
"""
for name,width,vals in [('c0lo',17,[x[0]&((1<<17)-1) for x in cs]),('c0hi',16,[x[0]>>17 for x in cs]),('c1',23,[x[1] for x in cs]),('c2',13,[x[2] for x in cs]),('sq',14,sq)]:
    text += f'(* keep_hierarchy = 1 *) module ot_hdc_skp_decode_{name}(input wire clk, input wire [23:0] d, output wire [{width-1}:0] q);\n'
    text += '    wire [23:0] a, b;\n    (* keep = 1 *) ot_hdc_skp_predecode24 u_a (.clk(clk), .d(d), .q(a));\n    (* keep = 1 *) ot_hdc_skp_predecode24 u_b (.clk(clk), .d(d), .q(b));\n    wire [511:0] row;\n'
    for i in range(512):
        bits = [f'{"b" if rep else "a"}[{8*g+((i>>(3*g))&7)}]' for g,rep in [(0,(i>>3)&1),(1,(i>>6)&1),(2,i&1)]]
        text += f'    assign row[{i}] = ' + ' & '.join(bits) + ';\n'
    for bit in range(width):
        mask = sum(((v>>bit)&1)<<i for i,v in enumerate(vals))
        text += f"    assign q[{bit}] = |(row & 512'h{mask:0128x});\n"
    text += 'endmodule\n'
text += '`default_nettype wire\n'
(root / 'rtl/hdc/v41/ot_hdc_skp_predecode.sv').write_text(text)
