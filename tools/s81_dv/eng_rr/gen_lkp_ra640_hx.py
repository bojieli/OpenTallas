#!/usr/bin/env python3
"""CORE-S81-ENG (10-23): emit the HASH-EXTERNAL variants of the RA640 Engram lookup, ot_s81_engram_lookup_ra640_hx and
dsfd_engram_lkp_ra640_hx (rtl/dsrom_sys/engram/static_lookup_1015/dsfd_engram_lkp_ra640_hx.sv), textually from the
originals (left untouched): the only change is that the internal hash instance
    ot_s81_engram_hash_n32 u_hash (.clk(clk_seed), .clk_columns(clk_hash), .in_w(win_n), .out_res(hres));
becomes two ports, hx_w = win_n (the existing ck-negedge window register = the core -> seed hop) and hres = hx_res (into
the existing res_c posedge capture = the hash -> core hop).  The hash itself moves to its own hard cores (layer halves
ot_s81_engram_hash_n32_l0/_l1).  Same registers, same edges, 0 added cycles.
usage (repo root): python3 tools/s81_dv/eng_rr/gen_lkp_ra640_hx.py"""
from pathlib import Path

D = Path("rtl/dsrom_sys/engram/static_lookup_1015")
lk = (D / "ot_s81_engram_lookup_ra640.sv").read_text().split("\n")
wr = (D / "dsfd_engram_lkp_ra640.sv").read_text().split("\n")


def body(lines, name):
    s = next(i for i, l in enumerate(lines) if l.startswith("module %s " % name))
    e = next(i for i in range(s, len(lines)) if lines[i] == "endmodule")
    return lines[s:e + 1]


HX_PORTS = ["    // CORE-S81-ENG hash-external ports (the hash runs in its own hard cores)",
            "    output wire [67:0]              hx_w,            // = win_n (ck negedge window register)",
            "    input  wire [1151:0]            hx_res,          // hash res_n (column negedge) -> res_c"]


def once(lines, old, new):
    idx = [i for i, l in enumerate(lines) if l == old]
    assert len(idx) == 1, (old, len(idx))
    return lines[:idx[0]] + new + lines[idx[0] + 1:]


a = body(lk, "ot_s81_engram_lookup_ra640")
a[0] = a[0].replace("module ot_s81_engram_lookup_ra640 ", "module ot_s81_engram_lookup_ra640_hx ")
cr = "    input  wire [1:0]               cfg_rank,        // TP rank of this die"
a = once(a, cr, [cr] + HX_PORTS)
a = once(a, "    ot_s81_engram_hash_n32 u_hash (.clk(clk_seed), .clk_columns(clk_hash), .in_w(win_n), .out_res(hres));",
         ["    assign hx_w = win_n;                      // CORE-S81-ENG: hash in hard cores (was u_hash)",
          "    assign hres = hx_res;"])
# S81-KITS-RTLA 10-24: slang (SYNTH_HDL_FRONTEND=slang) rejects emit_done used by the FSM before its declaration;
# the hx variant declares emit_done_r / emit_done ahead of the FSM (source order only, same logic)
a = once(a, "    reg       emit_done_r;", [])
a = once(a, "    wire      emit_done = emit_done_r;", [])
wn = "    reg [4*ENG_ID_W-1:0] win_n;"
a = once(a, wn, ["    reg       emit_done_r;                   // declared before the FSM (slang source order)",
                 "    wire      emit_done = emit_done_r;", wn])
b = body(wr, "dsfd_engram_lkp_ra640")
b[0] = b[0].replace("module dsfd_engram_lkp_ra640 ", "module dsfd_engram_lkp_ra640_hx ")
cr2 = "    input  wire [1:0]            cfg_rank,"
b = once(b, cr2, [cr2, "    output wire [67:0]           hx_w,", "    input  wire [1151:0]         hx_res,"])
b = once(b, "    ot_s81_engram_lookup_ra640 #(.RETURN_AGE(RETURN_AGE), .ROWSTRIPE(ROWSTRIPE), .NR(4), .CPR(6), .NSLOT(NSLOT), .ABW(36),",
         ["    ot_s81_engram_lookup_ra640_hx #(.RETURN_AGE(RETURN_AGE), .ROWSTRIPE(ROWSTRIPE), .NR(4), .CPR(6), .NSLOT(NSLOT), .ABW(36),"])
b = once(b, "        .cfg_layer(cl_q), .cfg_rank(cr_q),", ["        .cfg_layer(cl_q), .cfg_rank(cr_q), .hx_w(hx_w), .hx_res(hx_res),"])
out = ["// GENERATED by tools/s81_dv/eng_rr/gen_lkp_ra640_hx.py from ot_s81_engram_lookup_ra640.sv + dsfd_engram_lkp_ra640.sv",
       "// -- do not edit.  Hash-external RA640 lookup (CORE-S81-ENG 10-23): identical except u_hash -> ports hx_w / hx_res.",
       "`timescale 1ns/1ps", "import ot_hdc_engram_tables_shipped_pkg::*;"] + a + [""] + b + [""]
(D / "dsfd_engram_lkp_ra640_hx.sv").write_text("\n".join(out))
print("wrote", D / "dsfd_engram_lkp_ra640_hx.sv", len(out), "lines")
