#!/usr/bin/env python3
"""Split released flat hash statements into real fixed clock ownership modules.
No registers, expressions, or edges are created/removed. Default module is untouched.
Run after gen_hash_n32_flat.py if the released arithmetic generator changes.
"""
import re,sys,json,hashlib
from pathlib import Path
root=Path(sys.argv[1] if len(sys.argv)>1 else '.')
base=root/'rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32.sv'
out=base.with_name('ot_s81_engram_hash_cohort_n32.sv')
s=base.read_text(); fn=re.search(r'    function automatic.*?    endfunction\n',s,re.S).group()
start=s.index('    // ---- product 0 '); col=s.index('    // ---- column 0 ')
end=s.index('\nendmodule',col);seed=s[start:col]
blocks={}
for c in range(48):
 a=s.index(f'    // ---- column {c} ',col)
 b=s.index(f'    // ---- column {c+1} ',a) if c<47 else end
 blocks[c]=s[a:b]
parts=['// GENERATED by gen_hash_n32_cohorts.py. Exact released flat statements, no edge changes.','`timescale 1ns/1ps','module ot_s81_engram_hash_cohort_n32(input wire clk,input wire[5:0] clk_columns,input wire[67:0] in_w,output wire[1151:0] out_res);',' wire[767:0] rolls;',' ot_s81eng_hash_seed_n32 u_seed(.clk(clk),.in_w(in_w),.rolls(rolls));']
for g in range(6):parts.append(f' ot_s81eng_hash_group{g}_n32 u_group{g}(.clk(clk_columns[{g}]),.roll0(rolls[{128*g}+:64]),.roll1(rolls[{128*g+64}+:64]),.out_res(out_res[{192*g}+:192]));')
parts+=['endmodule','(* keep_hierarchy=1 *) module ot_s81eng_hash_seed_n32(input wire clk,input wire[67:0] in_w,output wire[767:0] rolls);',fn,seed]
for g in range(6):
 l,gorder=g//3,g%3+1
 for rn in range(2):parts.append(f' assign rolls[{128*g+64*rn}+:64]=roll_n{rn}_{l}_{gorder};')
parts.append('endmodule')
audit=[]
for g in range(6):
 l,order=g//3,g%3+1;original=''.join(blocks[c] for c in range(g*8,g*8+8));body=original
 body=body.replace(f'clk_columns[{g}]','clk')
 for rn in range(2):body=body.replace(f'roll_n{rn}_{l}_{order}',f'roll{rn}')
 body=re.sub(r'out_res\[(\d+):(\d+)\]',lambda m:f'out_res[{int(m[1])-192*g}:{int(m[2])-192*g}]',body)
 # Inverse normalized statements must reproduce exactly the released arithmetic.
 inv=re.sub(r'out_res\[(\d+):(\d+)\]',lambda m:f'out_res[{int(m[1])+192*g}:{int(m[2])+192*g}]',body)
 for rn in range(2):inv=re.sub(r'\broll'+str(rn)+r'\b',f'roll_n{rn}_{l}_{order}',inv)
 inv=re.sub(r'(?<!\.)\bclk\b',f'clk_columns[{g}]',inv)
 assert inv==original,(g,'statement/edge mismatch')
 parts += [f'(* keep_hierarchy=1 *) module ot_s81eng_hash_group{g}_n32(input wire clk,input wire[63:0] roll0,roll1,output wire[191:0] out_res);',body,'endmodule']
 audit.append({'group':g,'columns':list(range(g*8,g*8+8)),'exact_inverse_statement_match':True,'released_statement_sha256':hashlib.sha256(original.encode()).hexdigest()})
out.write_text('\n'.join(parts)+'\n')
p=root/'results/arch/s81_eng_lookup_physical_1021/cohort_successor/STATEMENT_AUDIT.json'
p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps({'baseline_sha256':hashlib.sha256(s.encode()).hexdigest(),'generated_sha256':hashlib.sha256(out.read_bytes()).hexdigest(),'seed_statement_sha256':hashlib.sha256(seed.encode()).hexdigest(),'seed_statements_copied_verbatim':True,'groups':audit,'clock_ports_unchanged':True,'reset_state':'seed and column registers originally unreset; preserved','added_edges':0},indent=2)+'\n')
print('wrote',out,'six real clockgroups; all inverse statements/edges identical')
