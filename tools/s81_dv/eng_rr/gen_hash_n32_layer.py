#!/usr/bin/env python3
"""CORE-S81-ENG (10-23): emit the two Engram LAYER halves of ot_s81_engram_hash_n32 as separate modules
ot_s81_engram_hash_n32_l0 / _l1 (rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32_layer.sv), sliced
TEXTUALLY from the generated flat hash (tools/s81_dv/eng_rr/gen_hash_n32_flat.py output), so every kept leaf, register,
edge and constant is the original line.  The flat hash is layer-separable by construction: products p = 4 l + k
(k = order, input in_w[17 k +: 17] shared by both layers), rolling XOR roll_s_l_* / roll_n*_l_*, columns c = 24 l ..
24 l + 23 on clk_columns[3 l .. 3 l + 2].  Half l: in_w[67:0] (same window), clk_columns[2:0] = original [3 l + i],
out_res[575:0] = original out_res[576 l +: 576].  Nothing is shared between the layers except the input window, which
each half captures in its own kept kq17 copies (the original already keeps 16 copies per product = per layer).
Leaf modules (ot_s81engf_*) stay in ot_s81_engram_hash_n32.sv (compile both files).
usage (repo root): python3 tools/s81_dv/eng_rr/gen_hash_n32_layer.py"""
import re
from pathlib import Path

SRC = Path("rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32.sv")
OUT = Path("rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32_layer.sv")
RW, COLS = 24, 24
lines = SRC.read_text().split("\n")
m0 = lines.index("module ot_s81_engram_hash_n32 (")
end = next(i for i in range(m0, len(lines)) if lines[i] == "endmodule")
body = lines[m0:end]
hdr_end = next(i for i, l in enumerate(body) if l.startswith("    // ---- product 0 "))
hdr = body[:hdr_end]
assert hdr[1:5] == ["    input  wire          clk,          // ck_seed",
                    "    input  wire [5:0]    clk_columns,  // one per (layer, order)",
                    "    input  wire [67:0]   in_w,", "    output wire [1151:0] out_res"], hdr[1:5]
funcs = hdr[5:]                                                  # ');' then the carry-select functions
sec, cur = [], None
for l in body[hdr_end:]:
    mp = re.match(r"    // ---- product (\d+) \(layer (\d+)", l)
    mc = re.match(r"    // ---- column (\d+) \(layer (\d+)", l)
    if mp:
        cur = ["p", int(mp.group(2)), []]; sec.append(cur)
    elif mc:
        cur = ["c", int(mc.group(2)), []]; sec.append(cur)
    elif l.startswith("    reg [63:0] roll_s_0_1;"):
        cur = ["r", None, []]; sec.append(cur)
    cur[2].append(l)
out = ["// GENERATED by tools/s81_dv/eng_rr/gen_hash_n32_layer.py from ot_s81_engram_hash_n32.sv -- do not edit.",
       "// Layer halves of the flat Engram hash (CORE-S81-ENG 10-23, eng_rr split into hard cores): same lines, same",
       "// registers / edges / kept copies; only the other layer's products, rolls and columns are left out.",
       "`timescale 1ns/1ps"]
for L in (0, 1):
    out += ["module ot_s81_engram_hash_n32_l%d (" % L,
            "    input  wire          clk,          // ck_seed",
            "    input  wire [2:0]    clk_columns,  // = original clk_columns[%d +: 3] (layer %d, orders 1-3)" % (3 * L, L),
            "    input  wire [67:0]   in_w,",
            "    output wire [575:0]  out_res"] + funcs
    n = dict(p=0, c=0, r=0)
    for kind, lay, ls in sec:
        if kind == "r":
            keep = [l for l in ls if re.search(r"roll_s_%d_|roll_n\d_%d_|u_n\d_%d_" % (L, L, L), l)]
            assert len(keep) == 3 * 6, len(keep)
            out += keep; n["r"] += len(keep)
            continue
        if lay != L:
            continue
        n[kind] += 1
        for l in ls:
            l = re.sub(r"clk_columns\[(\d+)\]", lambda m: "clk_columns[%d]" % (int(m.group(1)) - 3 * L), l)
            ma = re.match(r"    assign out_res\[(\d+):(\d+)\] = (res_n_\d+);$", l)
            if ma:
                l = "    assign out_res[%d:%d] = %s;" % (int(ma.group(1)) - 576 * L, int(ma.group(2)) - 576 * L, ma.group(3))
            out.append(l)
    assert n["p"] == 4 and n["c"] == COLS, n
    out += ["endmodule", ""]
OUT.write_text("\n".join(out) + "\n")
print("wrote", OUT, len(out), "lines")
