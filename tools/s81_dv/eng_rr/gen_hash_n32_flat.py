#!/usr/bin/env python3
"""ELEM-ENG2 (10-21): emit ot_s81_engram_hash_n32 as ONE flat module (no generate, no parameters, no package reads).

Why: the 54aa19348 form (nested generate g_prod/g_sl/g_e + g_col/g_xh/g_dig/g_k over package constants) keeps Yosys
in AST::expand_genblock for > 1.5 h (doubled 4-bit slice count).  This generator folds every constant in Python and
writes plain assigns / always blocks, with the kept register copies as FIXED, non-parameterised keep_hierarchy leaves
(ot_s81engf_kq17 / ot_s81engf_kq64 / ot_s81engf_kqn64: unique names, so Yosys has no $paramod rename to lose).

Logically identical to 54aa19348 (same registers, same edges, same copies, 0 added cycles):
  * w: one kept 17-bit copy per (product p, 4-bit slice j of the 64-bit digit-table output) = 32 copies per id bit;
  * digit tables: one-hot AND-OR selects of the folded constants (an entry bit that is 0 contributes nothing);
  * pp0/pp1/pp2 4-bit slice registers, pa/pb, 2x32 carry-select adds, roll_s (posedge), 2 kept negedge roll_n
    copies per (layer, order), heads 0-3 fed by copy 0, heads 4-7 by copy 1;
  * roll_h: 6 kept copies per column on the column clock, copy t drives residue bits [4t +: 4] of every digit;
  * residue adder tree s1..s4, carry-select conditional subtractions (constants 12q/8q/4q/3q/2q/q folded), m2,
    res_n on the column clock negedge.
Usage: gen_hash_n32_flat.py <repo root>   (reads rtl/hdc/v41/ot_hdc_engram_tables_shipped_pkg.sv, rewrites
       rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32.sv)
"""
import re, sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
PKG = root / 'rtl/hdc/v41/ot_hdc_engram_tables_shipped_pkg.sv'
OUT = root / 'rtl/dsrom_sys/engram/static_lookup_1015/ot_s81_engram_hash_n32.sv'
src = PKG.read_text()

def ival(name):
    return int(re.search(r'localparam integer %s\s*=\s*(\d+)' % name, src).group(1))

def bigconst(name):
    m = re.search(r'localparam \[(\d+):0\] %s = (.*?);' % name, src, re.S)
    width = int(m.group(1)) + 1
    body = m.group(2).strip()
    if body.startswith('{'):
        parts = re.findall(r"(\d+)'h([0-9a-fA-F_]+)", body)
    else:
        parts = [re.match(r"(\d+)'h([0-9a-fA-F_]+)", body).groups()]
    v, tw = 0, 0
    for w, h in parts:               # MSB first (concatenation order)
        w = int(w); v = (v << w) | int(h.replace('_', ''), 16); tw += w
    assert tw == width, (name, tw, width)
    return v

L, N, H, COLS, IDW, DW, RW = (ival(n) for n in ('ENG_LAYERS', 'ENG_N', 'ENG_HEADS', 'ENG_COLS', 'ENG_ID_W', 'ENG_DIG_W', 'ENG_RES_W'))
assert (L, N, H, COLS, IDW, DW, RW) == (2, 4, 8, 24, 17, 6, 24), 'generator written for the shipped geometry'
NIB, RES, PRIME = bigconst('ENG_NIB'), bigconst('ENG_RES'), bigconst('ENG_PRIME')
NP, NC, ND = L * N, L * COLS, 1 << DW
M64 = (1 << 64) - 1
def field(v, lsb, w): return (v >> lsb) & ((1 << w) - 1)

o = []
e = o.append
e('// GENERATED by tools/s81_dv/eng_rr/gen_hash_n32_flat.py from rtl/hdc/v41/ot_hdc_engram_tables_shipped_pkg.sv -- do not edit.')
e('// ot_s81_engram_hash_n32, FLAT form (ELEM-ENG2 10-21): logically identical to the 54aa19348 generate form (same')
e('// registers, edges, kept copies: w 32/id bit, roll_n 2 negedge per (layer, order), roll_h 6 per column; 0 added cycles),')
e('// with every package constant folded here and no generate loop (Yosys spent > 1.5 h expanding the nested genblocks).')
e('// Kept copies are fixed non-parameterised keep_hierarchy leaves ot_s81engf_kq17 / _kq64 / _kqn64.')
e('// Stage map: w 1, pp 2, pa/pb 3, roll_s 4, roll_n 4.5 (seed negedge), roll_h 5 (column posedge), s1..m2 6-11, res_n 11.5.')
e('`timescale 1ns/1ps')
e('module ot_s81_engram_hash_n32 (')
e('    input  wire          clk,          // ck_seed')
e('    input  wire [5:0]    clk_columns,  // one per (layer, order)')
e('    input  wire [%d:0]   in_w,' % (N * IDW - 1))
e('    output wire [%d:0] out_res' % (RW * NC - 1))
e(');')
e('    function automatic [63:0] add64cs(input [63:0] a, input [63:0] b);')
e('        reg [32:0] lo;')
e('        reg [31:0] h0, h1;')
e('        begin')
e("            lo = {1'b0, a[31:0]} + {1'b0, b[31:0]};")
e('            h0 = a[63:32] + b[63:32];')
e("            h1 = a[63:32] + b[63:32] + 32'd1;")
e('            add64cs = {lo[32] ? h1 : h0, lo[31:0]};')
e('        end')
e('    endfunction')

def onehot(name, sel, width_sel, n):
    # n-entry one-hot decode of sel (explicit equalities, entry k at bit k)
    terms = ', '.join("(%s == %d'd%d)" % (sel, width_sel, k) for k in reversed(range(n)))
    e('    wire [%d:0] %s = {%s};' % (n - 1, name, terms))

def sel4(oh, n, entries, lsb):
    # 4-bit AND-OR select: bit b = OR over entries k whose constant has bit (lsb+b) set
    bits = []
    for b in reversed(range(4)):
        m = 0
        for k in range(n):
            if (entries[k] >> (lsb + b)) & 1:
                m |= 1 << k
        bits.append("1'b0" if m == 0 else "(|(%s & %d'h%x))" % (oh, n, m))
    return '{' + ', '.join(bits) + '}'

# ---- 1-4: window copies, digit tables, product adds
for p in range(NP):
    k = p % N
    TP = field(NIB, 64 * ND * p, 64 * ND)
    E0 = [field(TP, 64 * q, 64) for q in range(ND)]
    E1 = [(x << DW) & M64 for x in E0]
    E2 = [(x << (2 * DW)) & M64 for x in E0]
    e('    // ---- product %d (layer %d, order %d): in_w[%d +: %d], 16 kept window copies (one per 4-bit output slice)' % (p, p // N, p % N, IDW * k, IDW))
    e('    wire [63:0] ep0_%d, ep1_%d, ep2_%d;' % (p, p, p))
    for j in range(16):
        w = 'w_%d_%d' % (p, j)
        e('    wire [%d:0] %s;' % (IDW - 1, w))
        e('    (* keep = 1 *) ot_s81engf_kq17 u_w_%d_%d (.clk(clk), .d(in_w[%d:%d]), .q(%s));' % (p, j, IDW * k + IDW - 1, IDW * k, w))
        onehot('h0_%d_%d' % (p, j), '%s[%d:0]' % (w, DW - 1), DW, ND)
        onehot('h1_%d_%d' % (p, j), '%s[%d:%d]' % (w, 2 * DW - 1, DW), DW, ND)
        # digit 2 = {1'b0, w[16:12]} (t = {1'b0, w}): entries >= 32 never selected, decode the 6-bit zero-extended value
        onehot('h2_%d_%d' % (p, j), "{1'b0, %s[%d:%d]}" % (w, IDW - 1, 2 * DW), DW, ND)
        e('    assign ep0_%d[%d:%d] = %s;' % (p, 4 * j + 3, 4 * j, sel4('h0_%d_%d' % (p, j), ND, E0, 4 * j)))
        e('    assign ep1_%d[%d:%d] = %s;' % (p, 4 * j + 3, 4 * j, sel4('h1_%d_%d' % (p, j), ND, E1, 4 * j)))
        e('    assign ep2_%d[%d:%d] = %s;' % (p, 4 * j + 3, 4 * j, sel4('h2_%d_%d' % (p, j), ND, E2, 4 * j)))
    e('    reg [63:0] pp0_%d, pp1_%d, pp2_%d, pa_%d, pb_%d;' % ((p,) * 5))
    e('    always @(posedge clk) begin pp0_%d <= ep0_%d; pp1_%d <= ep1_%d; pp2_%d <= ep2_%d; end' % ((p,) * 6))
    e('    always @(posedge clk) begin pa_%d <= add64cs(pp0_%d, pp1_%d); pb_%d <= pp2_%d; end' % ((p,) * 5))
    e('    wire [63:0] prod_%d = add64cs(pa_%d, pb_%d);' % ((p,) * 3))

# ---- 4-5: rolling XOR roll_s (seed posedge) -> 2 kept roll_n copies (seed negedge)
for l in range(L):
    for s in range(1, N):
        x = ' ^ '.join('prod_%d' % (l * N + r) for r in range(s + 1))
        e('    reg [63:0] roll_s_%d_%d;' % (l, s))
        e('    always @(posedge clk) roll_s_%d_%d <= %s;' % (l, s, x))
        for rn in range(2):
            e('    wire [63:0] roll_n%d_%d_%d;' % (rn, l, s))
            e('    (* keep = 1 *) ot_s81engf_kqn64 u_n%d_%d_%d (.clk(clk), .d(roll_s_%d_%d), .q(roll_n%d_%d_%d));' % (rn, l, s, l, s, rn, l, s))

# ---- 6-12: per column residue
for c in range(NC):
    Lc, Sc, hd, ck = c // COLS, (c % COLS) // H + 1, c % H, c // 8
    rn = hd // 4
    Q = field(PRIME, RW * c, RW)
    e('    // ---- column %d (layer %d, order %d, head %d), clock clk_columns[%d], q = %d' % (c, Lc, Sc, hd, ck, Q))
    for t in range(6):
        e('    wire [63:0] xh_%d_%d;' % (c, t))
        e('    (* keep = 1 *) ot_s81engf_kq64 u_x_%d_%d (.clk(clk_columns[%d]), .d(roll_n%d_%d_%d), .q(xh_%d_%d));' % (c, t, ck, rn, Lc, Sc, c, t))
    for j in range(16):
        TD = field(RES, RW * 16 * (c * 16 + j), RW * 16)
        ent = [field(TD, RW * q, RW) for q in range(16)]
        e('    wire [%d:0] r_%d_%d;' % (RW - 1, c, j))
        for t in range(6):
            oh = 'g_%d_%d_%d' % (c, j, t)
            onehot(oh, 'xh_%d_%d[%d:%d]' % (c, t, 4 * j + 3, 4 * j), 4, 16)
            e('    assign r_%d_%d[%d:%d] = %s;' % (c, j, 4 * t + 3, 4 * t, sel4(oh, 16, ent, 4 * t)))
    W1, W2, W3, W4 = RW + 1, RW + 2, RW + 3, RW + 4
    e('    reg [%d:0] s1_%d_0, s1_%d_1, s1_%d_2, s1_%d_3, s1_%d_4, s1_%d_5, s1_%d_6, s1_%d_7;' % ((W1 - 1,) + (c,) * 8))
    e('    reg [%d:0] s2_%d_0, s2_%d_1, s2_%d_2, s2_%d_3;' % ((W2 - 1,) + (c,) * 4))
    e('    reg [%d:0] s3_%d_0, s3_%d_1;' % ((W3 - 1,) + (c,) * 2))
    e('    reg [%d:0] s4_%d;' % (W4 - 1, c))
    e('    reg [%d:0] m1_%d;' % (RW + 2, c))
    e('    reg [%d:0] m2_%d;' % (RW - 1, c))
    e('    reg [%d:0] res_n_%d;' % (RW - 1, c))
    e("    wire [%d:0] d12_%d = {1'b0, s4_%d} - %d'd%d;" % (RW + 4, c, c, RW + 5, 12 * Q))
    e("    wire [%d:0] d8_%d  = {1'b0, s4_%d} - %d'd%d;" % (RW + 4, c, c, RW + 5, 8 * Q))
    e("    wire [%d:0] d4_%d  = {1'b0, s4_%d} - %d'd%d;" % (RW + 4, c, c, RW + 5, 4 * Q))
    e("    wire [%d:0] e3_%d  = {1'b0, m1_%d} - %d'd%d;" % (RW + 3, c, c, RW + 4, 3 * Q))
    e("    wire [%d:0] e2_%d  = {1'b0, m1_%d} - %d'd%d;" % (RW + 3, c, c, RW + 4, 2 * Q))
    e("    wire [%d:0] e1_%d  = {1'b0, m1_%d} - %d'd%d;" % (RW + 3, c, c, RW + 4, Q))
    e('    always @(posedge clk_columns[%d]) begin' % ck)
    for i in range(8):
        e("        s1_%d_%d <= {1'b0, r_%d_%d} + {1'b0, r_%d_%d};" % (c, i, c, 2 * i, c, 2 * i + 1))
    for i in range(4):
        e("        s2_%d_%d <= {1'b0, s1_%d_%d} + {1'b0, s1_%d_%d};" % (c, i, c, 2 * i, c, 2 * i + 1))
    for i in range(2):
        e("        s3_%d_%d <= {1'b0, s2_%d_%d} + {1'b0, s2_%d_%d};" % (c, i, c, 2 * i, c, 2 * i + 1))
    e("        s4_%d <= {1'b0, s3_%d_0} + {1'b0, s3_%d_1};" % (c, c, c))
    e('        m1_%d <= !d12_%d[%d] ? d12_%d[%d:0] : !d8_%d[%d] ? d8_%d[%d:0] : !d4_%d[%d] ? d4_%d[%d:0] : s4_%d[%d:0];'
      % (c, c, RW + 4, c, RW + 2, c, RW + 4, c, RW + 2, c, RW + 4, c, RW + 2, c, RW + 2))
    e('        m2_%d <= !e3_%d[%d] ? e3_%d[%d:0] : !e2_%d[%d] ? e2_%d[%d:0] : !e1_%d[%d] ? e1_%d[%d:0] : m1_%d[%d:0];'
      % (c, c, RW + 3, c, RW - 1, c, RW + 3, c, RW - 1, c, RW + 3, c, RW - 1, c, RW - 1))
    e('    end')
    e('    always @(negedge clk_columns[%d]) res_n_%d <= m2_%d;' % (ck, c, c))
    e('    assign out_res[%d:%d] = res_n_%d;' % (RW * c + RW - 1, RW * c, c))
e('endmodule')
e('')
e('// fixed-width kept copies (keep_hierarchy, non-parameterised: no $paramod rename)')
e('(* keep_hierarchy = "yes" *) module ot_s81engf_kq17 (input wire clk, input wire [16:0] d, output reg [16:0] q);')
e('    always @(posedge clk) q <= d;')
e('endmodule')
e('(* keep_hierarchy = "yes" *) module ot_s81engf_kq64 (input wire clk, input wire [63:0] d, output reg [63:0] q);')
e('    always @(posedge clk) q <= d;')
e('endmodule')
e('(* keep_hierarchy = "yes" *) module ot_s81engf_kqn64 (input wire clk, input wire [63:0] d, output reg [63:0] q);')
e('    always @(negedge clk) q <= d;')
e('endmodule')
e('')
e('// shared kept copies used by ot_s81_engram_lookup_ra640 / dsfd_engram_lkp_ra640 (unchanged from 54aa19348)')
e('(* keep_hierarchy = "yes" *) module ot_s81eng_kq #(parameter integer W = 1) (input wire clk, input wire [W-1:0] d, output reg [W-1:0] q);')
e('    always @(posedge clk) q <= d;')
e('endmodule')
e('(* keep_hierarchy = "yes" *) module ot_s81eng_kqr #(parameter integer W = 1) (input wire clk, input wire rst_n, input wire [W-1:0] d, output reg [W-1:0] q);')
e('    always @(posedge clk or negedge rst_n)')
e("        if (!rst_n) q <= {W{1'b0}};")
e('        else        q <= d;')
e('endmodule')
e('(* keep_hierarchy = "yes" *) module ot_s81eng_kq_neg #(parameter integer W = 1) (input wire clk, input wire [W-1:0] d, output reg [W-1:0] q);')
e('    always @(negedge clk) q <= d;')
e('endmodule')
OUT.write_text('\n'.join(o) + '\n')
print('wrote', OUT, len(o), 'lines')
