#!/usr/bin/env python3
"""S81U-SVC4 2026-10-17 (S81-DV p4j): the q / host broadcast trees, the status reduce trees and the P.V return trees of
the 16 regional service slices dsdv_svc_rs (2 x 8 grid, sid = rsv_NN = 2 column + row, row 1 upper).

p4j (SPEC '#### p4j', dv_plan.py --p4j): q / P.V enter at the slice under the slice-column void of each half -- W rsv_05
(column 2), E rsv_11 (column 5) -- the ENTRY slices (host endpoint of the half: j / q / hw in, jd / hc / fault / pv out).
Each half's tree is rooted at its entry and runs neighbour-only along the upper row both ways (W: 05 -> 03 -> 01 and
05 -> 07 = tq_05_07; E: 11 -> 13 -> 15 and 11 -> 09 = tq_11_09) and down each column.  The q.k fold stays at the centre
chain roots rsv_07 / rsv_09 (score exchange, svc_rs_embed.py: the W-half partial 05 -> 07 -> 09 = tp_05_07 + fc_07_09,
the E-half partial 11 -> 09 = tp_11_09, fold node at 09; reduction order unchanged).  The status (up) tree and the P.V
return tree (`ri` in / `ro` out, 513 b + v a face) run the same edges child -> parent; the edge from the chain root to
its entry (07 -> 05, 09 -> 11) is the p4j result lane tr_07_05 / tr_09_11, the other edges are the plan's tp_* lanes.

Per slice: parent face (0 = the entry's host pins), child faces, depth, the compiled GO delay
    gd(s) = HOP * (DMAX - depth(s)) + sx_role_off(s) + G0
(every slice's engine share starts at the same absolute cycle shifted by its score-exchange leaf offset), and per die
strap ST the compiled P.V drain slot of the 4 owner slices (tiles 4 ST + k, k = 0..3, all in one half):
    pvslot(ST, s) = PVW * k + HOP * (DMAX - depth(s)) + (OFFMAX - sx_role_off(s))
so owner k's PVW = 40 words (8 beats x 5) reach the entry's pv pins in window k after the job's PVO: no two owners ever
share a return-lane cycle (a collision is a sticky fault, never arbitrated).  HOP = 5 cycles on every tree.
Output: rtl/dsrom_sys/s81_dv/svc_rs/dsdv_svc_rs_roles.svh, results/arch/s81_dv_1016/svc_rs/tree.json.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import svc_rs_embed as E

HOP, G0, PVW = 5, 1, 40
FACES = ['N', 'E', 'S', 'W']
ENTRY = {'W': (1, 2), 'E': (1, 5)}              # rsv_05, rsv_11
CROOT = {'W': (1, 3), 'E': (1, 4)}              # chain roots rsv_07, rsv_09 (fold)


def half(c): return 'W' if c < 4 else 'E'


def tree():
    par, depth = {}, {}
    for c in range(8):
        h = half(c); ec = ENTRY[h][1]; r1 = (1, c)
        if c < ec: par[r1] = ((1, c + 1), 'E')      # child's face toward its parent
        elif c > ec: par[r1] = ((1, c - 1), 'W')
        depth[r1] = abs(c - ec)
        par[(0, c)] = ((1, c), 'N'); depth[(0, c)] = abs(c - ec) + 1
    return par, depth


def main():
    root = os.path.join(os.path.dirname(__file__), '..', '..', '..')
    base = E.roles(E.balanced(0, 15), E.NODE, 1, 5)
    par, depth = tree()
    dmax = max(depth.values())
    offmax = max(base['roles'][s].get('off', 0) for s in range(16))
    ch = {E.sid(rc): 0 for rc in depth}
    for rc, (p, f) in par.items():
        ch[E.sid(p)] |= 1 << FACES.index(E.OPP[f])
    rows = {}
    for rc in depth:
        s = E.sid(rc)
        off = base['roles'][s].get('off', 0)
        tile = base['roles'][s]['head']
        entry = rc in ENTRY.values()
        pf = 0 if entry else 1 + FACES.index(par[rc][1])
        gd = HOP * (dmax - depth[rc]) + off + G0
        rows[s] = dict(tile=tile, half=half(rc[1]), entry=entry, parent=pf, children=ch[s], depth=depth[rc], gd=gd,
                       sx_off=off)
    pvslot = {}
    for st in range(4):
        own = sorted((s for s in range(16) if rows[s]['tile'] // 4 == st), key=lambda s: rows[s]['tile'])
        assert len({rows[s]['half'] for s in own}) == 1, 'a P.V quarter spans both halves'
        for s in own:
            k = rows[s]['tile'] % 4
            pvslot[(st, s)] = PVW * k + HOP * (dmax - rows[s]['depth']) + (offmax - rows[s]['sx_off'])
            assert pvslot[(st, s)] < 256
    assert E.sid(CROOT['E']) == base['root'] == 9          # the fold node sits on the E chain root
    es = {h: E.sid(rc) for h, rc in ENTRY.items()}
    L = ['// generated by tools/s81_dv/svc_rs/svc_rs_tree.py (S81U-SVC4 2026-10-17, S81-DV p4j) -- do not edit',
         '// role word: {gd 8, depth 3, parent 3 (0 entry host pins, 1 + face N/E/S/W), children 4 (face mask, bit = face), tile 4}',
         '// trees rooted at the p4j entry slices (W rsv_05, E rsv_11); the q.k fold stays at rsv_09 (chain roots 07 / 09)',
         'function automatic [21:0] rs_role(input [3:0] sid);', '    case (sid)']
    for s in range(16):
        r = rows[s]
        v = (r['gd'] << 14) | (r['depth'] << 11) | (r['parent'] << 8) | (r['children'] << 4) | r['tile']
        L.append(f"        4'd{s}: rs_role = 22'h{v:06x};   // {r['half']}{' ENTRY' if r['entry'] else ''} tile {r['tile']} "
                 f"depth {r['depth']} parent {r['parent']} children {r['children']:04b} gd {r['gd']}")
    L += ["        default: rs_role = '0;", '    endcase', 'endfunction',
          '// P.V drain slot (cycles after the job PVO) of the owner slices of quarter st; 255 = not an owner',
          'function automatic [7:0] rs_pvslot(input [1:0] st, input [3:0] sid);', '    case ({st, sid})']
    for (st, s), v in sorted(pvslot.items()):
        L.append(f"        6'd{16 * st + s}: rs_pvslot = 8'd{v};   // st {st} slice {s} tile {rows[s]['tile']}")
    L += ["        default: rs_pvslot = 8'd255;", '    endcase', 'endfunction',
          f'localparam integer RS_ENTRY_W = {es["W"]}, RS_ENTRY_E = {es["E"]}, RS_CROOT_W = {E.sid(CROOT["W"])}, '
          f'RS_CROOT_E = {E.sid(CROOT["E"])}, RS_FOLD = {base["root"]};',
          f'localparam integer RS_HOP = {HOP}, RS_DMAX = {dmax}, RS_G0 = {G0}, RS_PVW = {PVW}, RS_OFFMAX = {offmax};']
    open(os.path.join(root, 'rtl/dsrom_sys/s81_dv/svc_rs/dsdv_svc_rs_roles.svh'), 'w').write('\n'.join(L) + '\n')
    json.dump(dict(generator='tools/s81_dv/svc_rs/svc_rs_tree.py', plan='S81-DV p4j', hop=HOP, g0=G0, dmax=dmax,
                   entries=es, chain_roots={h: E.sid(rc) for h, rc in CROOT.items()}, fold=base['root'], pv_words=PVW,
                   offmax=offmax, rsv_map='rsv_NN = sid NN = 2 column + row (row 1 upper), as dv_plan.py rsv_links',
                   plan_edges=dict(tq='dn stream, parent -> child', tp='up + P.V return, child -> parent (non-root edges)',
                                   tr='up + P.V return on the chain-root -> entry edge: tr_07_05 (07 W face -> 05 E face), '
                                      'tr_09_11 (09 E face -> 11 W face) = ro on 07 / 09, ri on 05 / 11',
                                   fc='score exchange gather 07 -> 09 / scatter 09 -> 07 (fold)',
                                   tp_entry_root='score exchange gather 05 -> 07, 11 -> 09; scatter 09 -> 11, 07 -> 05'),
                   slices={s: rows[s] for s in range(16)},
                   pvslot={f'st{st}_s{s}': v for (st, s), v in sorted(pvslot.items())}),
              open(os.path.join(root, 'results/arch/s81_dv_1016/svc_rs/tree.json'), 'w'), indent=1)
    print(json.dumps({s: (rows[s]['tile'], rows[s]['half'], rows[s]['depth'], rows[s]['gd']) for s in range(16)}))
    print(json.dumps({f'{st}/{s}': v for (st, s), v in sorted(pvslot.items())}))


if __name__ == '__main__':
    main()
