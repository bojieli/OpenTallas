#!/usr/bin/env python3
"""S81U-SVC 2026-10-17: the q / host broadcast tree and the status reduce tree of the 16 regional service slices
dsdv_svc_rs (S81-DV p4h: root slice 9 = column 4 upper row, the host endpoint; the tree runs neighbour-only along the
upper row both ways and down to the lower row in every column, as p4h plans it).

Per slice: parent face (0 = the root's host pins), child faces, depth, and the compiled GO delay
    gd(s) = HOP * (DMAX - depth(s)) + sx_role_off(s) + G0
so that every slice's engine share starts at the same absolute cycle shifted by its score-exchange leaf offset
(svc_rs_embed.py), i.e. both operands of every q.k tree node meet in the same cycle.  HOP = 5 cycles (centre register,
relay, out pin flop | in pin flop, relay), the same stage plan as the score exchange.
Output: rtl/dsrom_sys/s81_dv/svc_rs/dsdv_svc_rs_roles.svh, results/arch/s81_dv_1016/svc_rs/tree.json.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import svc_rs_embed as E

HOP, G0 = 5, 1
FACES = ['N', 'E', 'S', 'W']
ROOT = (1, 4)


def tree():
    par, depth = {}, {}
    for c in range(8):
        r1 = (1, c)
        if c < 4: par[r1] = ((1, c + 1), 'E')       # child's face toward its parent
        elif c > 4: par[r1] = ((1, c - 1), 'W')
        depth[r1] = abs(c - 4)
        par[(0, c)] = ((1, c), 'N'); depth[(0, c)] = abs(c - 4) + 1
    return par, depth


def main():
    root = os.path.join(os.path.dirname(__file__), '..', '..', '..')
    base = E.roles(E.balanced(0, 15), E.NODE, 1, 5)
    par, depth = tree()
    dmax = max(depth.values())
    ch = {E.sid(rc): 0 for rc in depth}
    for rc, (p, f) in par.items():
        if rc == ROOT: continue
        opp = E.OPP[f]
        ch[E.sid(p)] |= 1 << FACES.index(opp)
    rows = {}
    for rc in depth:
        s = E.sid(rc)
        off = base['roles'][s].get('off', 0)
        tile = base['roles'][s]['head']
        pf = 0 if rc == ROOT else 1 + FACES.index(par[rc][1])
        gd = HOP * (dmax - depth[rc]) + off + G0
        rows[s] = dict(tile=tile, parent=pf, children=ch[s], depth=depth[rc], gd=gd, sx_off=off)
    assert E.sid(ROOT) == base['root'] == 9
    L = ['// generated by tools/s81_dv/svc_rs/svc_rs_tree.py (S81U-SVC 2026-10-17) -- do not edit',
         '// role word: {gd 8, depth 3, parent 3 (0 host pins, 1 + face N/E/S/W), children 4 (face mask, bit = face), tile 4}',
         'function automatic [21:0] rs_role(input [3:0] sid);', '    case (sid)']
    for s in range(16):
        r = rows[s]
        v = (r['gd'] << 14) | (r['depth'] << 11) | (r['parent'] << 8) | (r['children'] << 4) | r['tile']
        L.append(f"        4'd{s}: rs_role = 22'h{v:06x};   // tile {r['tile']} depth {r['depth']} parent {r['parent']} "
                 f"children {r['children']:04b} gd {r['gd']}")
    L += ["        default: rs_role = '0;", '    endcase', 'endfunction',
          f'localparam integer RS_ROOT = 9, RS_HOP = {HOP}, RS_DMAX = {dmax}, RS_G0 = {G0};']
    open(os.path.join(root, 'rtl/dsrom_sys/s81_dv/svc_rs/dsdv_svc_rs_roles.svh'), 'w').write('\n'.join(L) + '\n')
    json.dump(dict(generator='tools/s81_dv/svc_rs/svc_rs_tree.py', hop=HOP, g0=G0, dmax=dmax, root=9,
                   slices={s: rows[s] for s in range(16)}),
              open(os.path.join(root, 'results/arch/s81_dv_1016/svc_rs/tree.json'), 'w'), indent=1)
    print(json.dumps({s: (rows[s]['tile'], rows[s]['depth'], rows[s]['gd']) for s in range(16)}))


if __name__ == '__main__':
    main()
