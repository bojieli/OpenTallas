#!/usr/bin/env python3
"""S81-ELEM2-SVCCOLL (10-21): COLUMN-PAIR MERGE of the service72 2x8 grid (PINBOUND fix, COORD 10-20 09:28 (d)).

Pure hierarchy regroup of tools/s81_dv/svc_rs/gen_service72.py (same instances, same links, same landings, same
reset syncs, same inactive-face contract):
  * dsdv_svc_pair72 / dsdv_svc_pair72_entry = one grid column: row 0 (sid 2c) under row 1 (sid 2c+1) plus the two
    N/S face72 links between them (u_link_{2c}_{2c+1}, u_link_{2c+1}_{2c}).  The 4,545-bit partner links that made the
    1,728-um N/S faces of a single slot pin-bound (2 x 4,545 = 9,090 pins / 1,728 um = 5.26 pins/um) are now internal.
    Row 0 S and row 1 N are the existing semantic-inactive outer faces (tied 0 inside, as gen_service72.py).
  * the pair exposes only its E/W chain faces (per row tx 4,545 + rx 4,545; 18,180 pins per face over the 7,603.2-um
    pair height = 2.39 pins/um, one layer) and the per-row HBM / SM faces (~1.04 pins/um on N/S; entry pair ~2.0).
  * dsdv_svc_group72p = the same ports as dsdv_svc_group72: 16 reset syncs, 8 pairs, 28 E/W face72 landings
    (identical clocks/resets/bit order to u_link_i_j of dsdv_svc_group72), 4 inactive outer column faces tied 0.
Entry slots are sid 5 and 11 (row 1 of columns 2 and 5) -> dsdv_svc_pair72_entry for those columns (separate master,
never a renamed parameterisation).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'rtl/dsrom_sys/s81_dv/svc_rs/group72'
fields = [('dn', 805), ('ud', 13), ('uf', 3), ('pv', 514), ('g', 2133), ('s', 1077)]
W = sum(w for _, w in fields)          # 4545
HBM = [('output', 682, 'rq'), ('input', 2, 'rk'), ('input', 2, 'wd'), ('input', 2, 'rv'),
       ('input', 512, 'r_data'), ('input', 34, 'r_tag'), ('input', 8, 'r_beat'), ('input', 2, 'hs'),
       ('output', 1, 'w_v'), ('output', 14, 'w_a'), ('output', 16, 'w_m'), ('output', 512, 'w_d'), ('output', 12, 'w_st')]
ENT = [('input', 33, 'j'), ('output', 2, 'jd'), ('input', 515, 'q'), ('input', 292, 'hw'), ('output', 9, 'hc'),
       ('output', 1, 'fault'), ('output', 2, 'st_rg'), ('output', 1, 'pv_v'), ('output', 513, 'pv_d'), ('output', 48, 'pv_x')]
ENTRY_SIDS = (5, 11)
N, E, S, Wf = 0, 1, 2, 3


def face_bus(name_i_o, k, face):
    return '{' + ','.join(f'{n}_{name_i_o}_{k}[{face*w}+:{w}]' for n, w in reversed(fields)) + '}'


def svc_body(k, ck, rst, sid, entry, hbm_ix):
    """svc instance k (local row) inside a module; mirrors gen_service72.py exactly."""
    L = []
    for n, w in fields:
        L.append(f'    wire [{4*w-1}:0] {n}_i_{k}, {n}_o_{k};')
    L += [f'    wire [3:0] gv_{k}, sv_{k}, gov_{k}, sov_{k};',
          f'    wire [8527:0] gd_{k}, god_{k}; wire [4303:0] sd_{k}, sod_{k};']
    for f in range(4):
        L += [f'    assign g_o_{k}[{2133*f}+:2133] = {{god_{k}[{2132*f}+:2132],gov_{k}[{f}]}};',
              f'    assign {{gd_{k}[{2132*f}+:2132],gv_{k}[{f}]}} = g_i_{k}[{2133*f}+:2133];',
              f'    assign s_o_{k}[{1077*f}+:1077] = {{sod_{k}[{1076*f}+:1076],sov_{k}[{f}]}};',
              f'    assign {{sd_{k}[{1076*f}+:1076],sv_{k}[{f}]}} = s_i_{k}[{1077*f}+:1077];']
    L.append(f'    wire [63:0] up_i_{k}, up_o_{k};')
    for f in range(4):
        L += [f'    assign up_i_{k}[{16*f}+:16] = {{uf_i_{k}[{3*f+1}+:2],ud_i_{k}[{13*f+12}],uf_i_{k}[{3*f}],ud_i_{k}[{13*f}+:12]}};',
              f'    assign {{uf_o_{k}[{3*f+1}+:2],ud_o_{k}[{13*f+12}],uf_o_{k}[{3*f}],ud_o_{k}[{13*f}+:12]}} = up_o_{k}[{16*f}+:16];']
    c = [f'.ck({ck[0]})', f'.ck_sm({ck[1]})', f'.ck_att({ck[2]})', f'.rst({rst})', f'.sid({sid})']
    for p, a in [('dn_i', 'dn_i'), ('dn_o', 'dn_o'), ('up_i', 'up_i'), ('up_o', 'up_o'), ('ri', 'pv_i'), ('ro', 'pv_o'),
                 ('gi_v', 'gv'), ('gi_d', 'gd'), ('go_v', 'gov'), ('go_d', 'god'),
                 ('si_v', 'sv'), ('si_d', 'sd'), ('so_v', 'sov'), ('so_d', 'sod')]:
        c.append(f'.{p}({a}_{k})')
    for _, w, p in HBM:
        c.append(f'.{p}({p}[{hbm_ix*w}+:{w}])')
    if entry:
        for _, w, p in ENT:
            c.append(f'.{p}({p})')
    else:
        c += [".j(33'd0)", ".q(515'd0)", ".hw(292'd0)"]   # ENTRY=0: existing semantic absent host endpoint
    return L, c


def tie(k, face):
    return [f"    assign {n}_i_{k}[{face*w}+:{w}] = {w}'d0; // inherited semantic inactive outer face" for n, w in fields]


def pair_module(entry):
    name = 'dsdv_svc_pair72_entry' if entry else 'dsdv_svc_pair72'
    ports = [('input', 6, 'ck'), ('input', 2, 'rst'), ('input', 8, 'sid')]
    ports += [(d, 2*w, p) for d, w, p in HBM]
    if entry:
        ports += ENT
    ports += [('output', 2*W, 'e_o'), ('input', 2*W, 'e_i'), ('output', 2*W, 'w_o'), ('input', 2*W, 'w_i')]
    L = ['`timescale 1ns/1ps', '`default_nettype none',
         f'// GENERATED by tools/s81_dv/svc_rs/gen_service72_pair.py -- do not edit.  One service72 grid column:',
         '// row 0 (u_s0) under row 1 (u_s1' + (', ENTRY' if entry else '') + '); the N/S partner face72 links are internal.',
         '// e_o/e_i/w_o/w_i = row r at [r*4545 +: 4545], bit order {s,g,pv,uf,ud,dn} as dsdv_svc_group72 u_link_i_j.',
         '// ck = {row1 att, row1 sm, row1 c, row0 att, row0 sm, row0 c}; rst = synchronised per-row resets.',
         f'module {name} #(parameter integer DIE_ID=0, ST=0, SRAM_MACRO=1, parameter [1:0] PMEM_MASK=2\'b11) (']
    L += [f'    {d} wire [{w-1}:0] {p}' + (',' if k < len(ports)-1 else '') for k, (d, w, p) in enumerate(ports)]
    L.append(');')
    for k in range(2):
        body, conns = svc_body(k, (f'ck[{3*k}]', f'ck[{3*k+1}]', f'ck[{3*k+2}]'), f'rst[{k}]', f'sid[{4*k}+:4]',
                               entry and k == 1, k)
        L += body
        L += [f'    dsdv_svc_rs_c_group72 #(.ENTRY({int(entry and k == 1)}), .DIE_ID(DIE_ID), .ST(ST), .SRAM_MACRO(SRAM_MACRO), '
              f'.PMEM(PMEM_MASK[{k}])) u_s{k} (', '        ' + ', '.join(conns) + ');']
    # internal partner links: row0 N -> row1 S, row1 S -> row0 N (identical to group72 u_link_{2c}_{2c+1} / _{2c+1}_{2c})
    L += ['    dsdv_svc_face72 u_link_n (.ck_w(ck[0]), .ck_r(ck[3]),',
          f'        .rst_w(rst[0]), .rst_r(rst[1]), .i({face_bus("o", 0, N)}), .o({face_bus("i", 1, S)}));',
          '    dsdv_svc_face72 u_link_s (.ck_w(ck[3]), .ck_r(ck[0]),',
          f'        .rst_w(rst[1]), .rst_r(rst[0]), .i({face_bus("o", 1, S)}), .o({face_bus("i", 0, N)}));']
    L += tie(0, S) + tie(1, N)
    for k in range(2):
        L += [f'    assign e_o[{k*W}+:{W}] = {face_bus("o", k, E)};',
              f'    assign {face_bus("i", k, E)} = e_i[{k*W}+:{W}];',
              f'    assign w_o[{k*W}+:{W}] = {face_bus("o", k, Wf)};',
              f'    assign {face_bus("i", k, Wf)} = w_i[{k*W}+:{W}];']
    L += ['endmodule', '`default_nettype wire']
    return '\n'.join(L) + '\n'


def group_module():
    ports = [('input', 48, 'ck'), ('input', 16, 'rst'), ('input', 64, 'sid'),
             ('input', 66, 'j'), ('output', 4, 'jd'), ('input', 1030, 'q'), ('input', 584, 'hw'),
             ('output', 18, 'hc'), ('output', 2, 'fault'), ('output', 4, 'st_rg'),
             ('output', 2, 'pv_v'), ('output', 1026, 'pv_d'), ('output', 96, 'pv_x')]
    ports += [(d, 16*w, p) for d, w, p in HBM]
    L = ['`timescale 1ns/1ps', '`default_nettype none',
         '// GENERATED by tools/s81_dv/svc_rs/gen_service72_pair.py -- do not edit.  dsdv_svc_group72 regrouped into 8',
         '// column pairs (same ports, instances, links, landings, reset syncs; 16 x (C,SM,ATT) roots).',
         'module dsdv_svc_group72p #(parameter integer DIE_ID=0, ST=0, SRAM_MACRO=1,',
         "    parameter [15:0] PMEM_MASK=16'hffff) ("]
    L += [f'    {d} wire [{w-1}:0] {p}' + (',' if k < len(ports)-1 else '') for k, (d, w, p) in enumerate(ports)]
    L += [');', '    wire [15:0] rst_c;']
    for i in range(16):
        L.append(f'    ot_reset_sync #(.ASYNC_STAGES(2)) u_rst_{i} (.clk(ck[{3*i}]), .async_rst_n(rst[{i}]), .sync_rst_n(rst_c[{i}]));')
    for c in range(8):
        L.append(f'    wire [{2*W-1}:0] e_o_{c}, e_i_{c}, w_o_{c}, w_i_{c};')
    for c in range(8):
        i0 = 2*c
        entry = (i0+1) in ENTRY_SIDS
        conns = [f'.ck(ck[{3*i0}+:6])', f'.rst(rst_c[{i0}+:2])', f'.sid(sid[{4*i0}+:8])']
        for _, w, p in HBM:
            conns.append(f'.{p}({p}[{i0*w}+:{2*w}])')
        if entry:
            e = int(i0+1 == 11)
            for _, w, p in ENT:
                conns.append(f'.{p}({p}[{e*w}+:{w}])')
        conns += [f'.e_o(e_o_{c})', f'.e_i(e_i_{c})', f'.w_o(w_o_{c})', f'.w_i(w_i_{c})']
        L += [f'    {"dsdv_svc_pair72_entry" if entry else "dsdv_svc_pair72"} #(.DIE_ID(DIE_ID), .ST(ST), .SRAM_MACRO(SRAM_MACRO), '
              f'.PMEM_MASK(PMEM_MASK[{i0}+:2])) u_p{c} (', '        ' + ', '.join(conns) + ');']
    links = []
    for c in range(8):
        for r in range(2):
            i = 2*c + r
            for side, dc, src, dst in (('e', 1, 'e_o', 'w_i'), ('w', -1, 'w_o', 'e_i')):
                cc = c + dc
                if 0 <= cc < 8:
                    j = 2*cc + r
                    L += [f'    dsdv_svc_face72 u_link_{i}_{j} (.ck_w(ck[{3*i}]), .ck_r(ck[{3*j}]),',
                          f'        .rst_w(rst_c[{i}]), .rst_r(rst_c[{j}]), .i({src}_{c}[{r*W}+:{W}]), .o({dst}_{cc}[{r*W}+:{W}]));']
                    links.append(dict(source=i, destination=j, pair_from=c, pair_to=cc, width=W, banks=(W+275)//276))
    L += [f"    assign w_i_0 = {2*W}'d0; // inherited semantic inactive outer face (column 0 W)",
          f"    assign e_i_7 = {2*W}'d0; // inherited semantic inactive outer face (column 7 E)",
          'endmodule', '`default_nettype wire']
    return '\n'.join(L) + '\n', links


if __name__ == '__main__':
    (OUT / 'dsdv_svc_pair72.sv').write_text(pair_module(False))
    (OUT / 'dsdv_svc_pair72_entry.sv').write_text(pair_module(True))
    g, links = group_module()
    (OUT / 'dsdv_svc_group72p.sv').write_text(g)
    H = 3758.4
    rec = dict(scope='column-pair merge of service72 (PINBOUND fix); pure hierarchy regroup of dsdv_svc_group72',
               masters={'dsdv_svc_pair72': 6, 'dsdv_svc_pair72_entry': 2},
               pair_outline_main_um=[1728.0, 2*H+86.4], pair_outline_fb_um=[2160.0, 2*H+86.4],
               internal_links_per_pair=2, die_links_ew=len(links), link_width=W,
               face_pins=dict(ew_per_face=4*W, ew_pins_per_um_main=round(4*W/(2*H+86.4), 2),
                              single_slot_ns_before=round(2*W/1728.0, 2)),
               links=links)
    R = ROOT / 'results/arch/s81_service72_1021'
    (R / 'pair72.json').write_text(json.dumps(rec, indent=1) + '\n')
    print(json.dumps({k: v for k, v in rec.items() if k != 'links'}))
