#!/usr/bin/env python3
"""Generate the exact production service role boundaries, including hard HROW bodies.

No wrapper may feed constant faces into a generic hard HROW. Each generated HROW
owns the original arithmetic and its absent input values inside that hard body.
All generated types need fresh physical views; data pipeline depth is unchanged.
"""
import argparse
import importlib.util
import json
import re
from pathlib import Path

BT = chr(96)
FACES = "nesw"


def module_body(text, name):
    start = re.search(r"^module " + re.escape(name) + r"\b", text, re.M).start()
    body = text[start:].split(");", 1)[1].split("\nendmodule", 1)[0]
    return body


def header(name, params, ports):
    return "module " + name + (" #(" + params + ")" if params else "") + " (\n    " + ",\n    ".join(ports) + "\n);\n"


def timed_body(body):
    old = "always @(posedge ck or negedge rst) if (!rst) rs <= 2'b00; else rs <= {rs[0], 1'b1};"
    assert body.count(old) == 1
    return body.replace(old, "always @(posedge ck) rs <= {rs[0], rst};")


def generate(root):
    directory = root / "rtl/dsrom_sys/s81_dv/svc_rs"
    spec = importlib.util.spec_from_file_location("faces", root / "tools/s81_dv/svc_rs/svc_rs_faces.py")
    faces = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(faces)
    roles = faces.masks(str(root))
    hbody = module_body((directory / "dsdv_svc_sx_hrow.sv").read_text(), "dsdv_svc_sx_hrow")
    sxbody = module_body((directory / "dsdv_svc_sx.sv").read_text(), "dsdv_svc_sx")
    upbody = module_body((directory / "dsdv_svc_rs.sv").read_text(), "dsdv_svc_rs_up")
    jobbody = module_body((root / "rtl/dsrom_sys/s81_ctrl/ot_s81_svc_job.sv").read_text(), "ot_s81_svc_job")
    groups = {}
    for sid, m in roles.items():
        key = tuple(m[g] for g in ("GI", "GO", "SI", "SO"))
        groups.setdefault(key, []).append(sid)
    upgroups = {}
    for sid, m in roles.items():
        upgroups.setdefault((m["UI"], m["UO"]), []).append(sid)
    out = ["// Generated by svc_role_masters.py. NEW physical views required.\n" + BT + "default_nettype none\n"]
    # Full-port timed reference is a functional reference, never a hard-view alias.
    original = (directory / "dsdv_svc_sx_hrow.sv").read_text()
    reference = original.replace("module dsdv_svc_sx_hrow #(", "module dsdv_svc_sx_hrow_timed_ref #(", 1)
    reference = reference.replace("always @(posedge ck or negedge rst) if (!rst) rs <= 2'b00; else rs <= {rs[0], 1'b1};", "always @(posedge ck) rs <= {rs[0], rst};", 1)
    contracts = []
    dispatch = ["// Generated actual-role SX selection; no generic hard HROW fallback.\ngenerate\n"]
    for ordinal, (masks, sids) in enumerate(sorted(groups.items())):
        gm, go, sm, so = masks
        tag = "".join(format(x, "x") for x in masks)
        hname = "dsdv_svc_sx_hrow_fv_" + tag
        sname = "dsdv_svc_sx_fv_" + tag
        hp = ["input wire ck, rst", "input wire [3:0] sid", "input wire hb", "input wire [269:0] l_i"]
        aliases = []
        ports = []
        for group, mask, width, direction in (("gi", gm, 270, "input"), ("go", go, 270, "output"), ("si", sm, 138, "input"), ("so", so, 138, "output")):
            for f, face in enumerate(FACES):
                name = group + "_" + face
                if mask >> f & 1:
                    hp.append(f"{direction} wire [{width-1}:0] {name}")
                    ports.append(dict(name=name, direction=direction, width=width, face=face))
                elif direction == "input":
                    aliases.append(f"wire [{width-1}:0] {name} = {width}'d0;")
                else:
                    aliases.append(f"wire [{width-1}:0] {name};")
        hp += ["output wire [269:0] rt_o", "output wire [38:0] t_o", "output reg fault"]
        hb = timed_body(hbody)
        # Controls exercise actual wrong absent/active wiring, never checker masking.
        absent = next("gi_" + face for f, face in enumerate(FACES) if not (gm >> f & 1))
        zero = f"wire [269:0] {absent} = 270'd0;"
        aliases[aliases.index(zero)] = BT + "ifdef OT_SVC_ROLE_MUT_ABSENT\n" + f"wire [269:0] {absent} = {{1'b1, 269'd0}};\n" + BT + "else\n" + zero + "\n" + BT + "endif"
        active_group, active_mask, active_w = ("gi", gm, 270) if gm else ("si", sm, 138)
        active = active_group + "_" + next(face for f, face in enumerate(FACES) if active_mask >> f & 1)
        hb = re.sub(r"\b" + active + r"\b", "role_active_input", hb)
        aliases.append(BT + "ifdef OT_SVC_ROLE_MUT_ACTIVE\n" + f"wire [{active_w-1}:0] role_active_input = {active} ^ {active_w}'d1;\n" + BT + "else\n" + f"wire [{active_w-1}:0] role_active_input = {active};\n" + BT + "endif")
        normal = "always @(posedge ck) rs <= {rs[0], rst};"
        hb = hb.replace(normal, BT + "ifdef OT_SVC_ROLE_MUT_ASYNC\n" + "always @(posedge ck or negedge rst) if(!rst) rs<=0; else rs<={rs[0],1'b1};\n" + BT + "else\n" + normal + "\n" + BT + "endif", 1)
        out.append(header(hname, "parameter integer MUT=0, FX=5, F12=1", hp) + "\n".join(aliases) + hb + "\nendmodule\n")
        # SX is a real specialised body and instantiates only its actual hard HROW type.
        sp = ["input wire ck, rst", "input wire [3:0] sid", "input wire l_v", "input wire [2131:0] l_d"]
        sa = []
        conns = [".ck(ck)", ".rst(rst)", ".sid(sid)", ".l_v(l_v || pl_v)", ".l_d(pl_v ? pl_d : l_d)"]
        sb = sxbody
        for g, mask, width, direction in (("gi", gm, 2132, "input"), ("go", go, 2132, "output"), ("si", sm, 1076, "input"), ("so", so, 1076, "output")):
            sa += [f"wire [3:0] {g}_v;", f"wire [{4*width-1}:0] {g}_d;"]
            for f, face in enumerate(FACES):
                if mask >> f & 1:
                    sp += [f"{direction} wire {g}_v_{face}", f"{direction} wire [{width-1}:0] {g}_d_{face}"]
                    if direction == "input":
                        sa += [f"assign {g}_v[{f}]={g}_v_{face};", f"assign {g}_d[{width*f} +: {width}]={g}_d_{face};"]
                    else:
                        sa += [f"assign {g}_v_{face}={g}_v[{f}];", f"assign {g}_d_{face}={g}_d[{width*f} +: {width}];"]
                    conns += [f".{g}_v_{face}({g}_v[{f}])", f".{g}_d_{face}({g}_d[{width*f} +: {width}])"]
                elif direction == "input":
                    sa += [f"assign {g}_v[{f}]=1'b0;", f"assign {g}_d[{width*f} +: {width}]=0;"]
                else:
                    conns += [f"// absent {g}_{face}"]
        # Named hard connections are removed, rather than supplied as constant hard pins.
        for g, mask in (("gi", gm), ("go", go), ("si", sm), ("so", so)):
            for f, face in enumerate(FACES):
                if not (mask >> f & 1):
                    sb = re.sub(r"\." + g + "_" + face + r"\([^)]*\),\s*", "", sb)
        sb = sb.replace("dsdv_svc_sx_hrow", hname)
        sb = sb.replace("dsdv_sx_rly_in", "dsdv_svc_rly_276_in").replace("dsdv_sx_rly_out", "dsdv_svc_rly_276_out")
        # The production gather's six padding bits must not reach hard relay pins.
        sb = sb.replace("dsdv_svc_rly_276_in #(.F(f)) u_g", "dsdv_svc_rly_270_in #(.F(f)) u_g")
        sb = sb.replace("dsdv_svc_rly_276_out #(.F(f)) u_g", "dsdv_svc_rly_270_out #(.F(f)) u_g")
        for vector in ("gin[j]", "gin[j+1]", "gout[j]", "gout[j+1]"):
            sb = sb.replace(vector + "[275:0]", vector + "[269:0]").replace(vector + "[551:276]", vector + "[545:276]")
        lines=[]
        for line in sb.splitlines():
            lines.append(line)
            if "dsdv_svc_rly_270_" in line and "u_g1" in line:
                vec="gin" if "gin[" in line else "gout"
                lines.append(f"assign {vec}[j+1][275:270]=0; assign {vec}[j+1][551:546]=0;")
        sb="\n".join(lines)
        sp += ["output wire rt_v", "output wire [2131:0] rt_d", "output wire t_v", "output wire [19:0] t_tag", "output wire [127:0] t_y", "output wire [3:0] t_f", "output wire fault"]
        sa.append(f"localparam logic[3:0] FM_GI=4'h{gm:x},FM_GO=4'h{go:x},FM_SI=4'h{sm:x},FM_SO=4'h{so:x};")
        out.append(header(sname, "parameter integer MUT=0, NR=1, FX=5, F12=1", sp) + "\n".join(sa) + sb + "\nendmodule\n")
        conns = [c for c in conns if not c.startswith("//")]
        conns += [f".{n}({n})" for n in ("rt_v", "rt_d", "t_v", "t_tag", "t_y", "t_f")]
        conns.append(".fault(x_f)")
        test = f"FM_GI==4'h{gm:x} && FM_GO==4'h{go:x} && FM_SI==4'h{sm:x} && FM_SO==4'h{so:x}"
        dispatch.append(("if" if ordinal == 0 else "else if") + f" ({test}) begin:g_sx_{tag}\n    {sname} u_sx (" + ",".join(conns) + ");\n")
        for g, mask, width in (("go", go, 2132), ("so", so, 1076)):
            for f in range(4):
                if not (mask >> f & 1):
                    dispatch.append(f"assign {g}_v[{f}]=0; assign {g}_d[{width*f} +: {width}]=0;\n")
        dispatch.append("end\n")
        contracts.append(dict(sids=sids, hrow=hname, sx=sname, masks=dict(zip(("GI", "GO", "SI", "SO"), masks)), hrow_instances=8*len(sids), face_ports=ports, physical_view="NEEDS_REHARDEN", data_cycles_added=0, private_reset_assertion=2, private_reset_release=2))
    dispatch.append("else begin:g_bad_sx OT_SVC_ROLE_MASK_NOT_IMPLEMENTED invalid_role(); end\nendgenerate\n")
    updispatch = ["// Generated actual-role status-up selection.\ngenerate\n"]
    for ordinal, ((ui, uo), sids) in enumerate(sorted(upgroups.items())):
        name = f"dsdv_svc_rs_up_fv_{ui:x}{uo:x}"
        ports = ["input wire ck,rn", "input wire[3:0]chm", "input wire[2:0]par", "input wire done,fl", "input wire[1:0]hcr,hack,hs_s"]
        aliases = ["localparam integer UW=16;", f"localparam logic[3:0]FM_UI=4'h{ui:x},FM_UO=4'h{uo:x};", "wire[63:0]up_i,up_o;"]
        mapping=dict(ck="ck",rn="rn",chm="chm",par="par",done="done && !so_pend",fl="hs_f",hcr="hcr",hack="hack",hs_s="hs1",uc="uc")
        conns = [f".{p}({v})" for p,v in mapping.items()]
        for direction, mask, bus in (("input", ui, "up_i"), ("output", uo, "up_o")):
            for f, face in enumerate(FACES):
                if mask >> f & 1:
                    ports.append(f"{direction} wire[15:0]{bus}_{face}")
                    aliases.append(f"assign {bus}[{16*f} +: 16]={bus}_{face};" if direction == "input" else f"assign {bus}_{face}={bus}[{16*f} +: 16];")
                    conns.append(f".{bus}_{face}({bus}[{16*f} +: 16])")
                elif direction == "input":
                    aliases.append(f"assign {bus}[{16*f} +: 16]=0;")
        ports.append("output reg[15:0]uc")
        out.append(header(name, "parameter integer UPMUT=0", ports) + "\n".join(aliases) + upbody + "\nendmodule\n")
        updispatch.append(("if" if ordinal == 0 else "else if") + f" (UW==16 && FM_UI==4'h{ui:x} && FM_UO==4'h{uo:x}) begin:g_up_{ui:x}{uo:x}\n {name} u_up (" + ",".join(conns) + ");\n")
        for f in range(4):
            if not (uo >> f & 1):updispatch.append(f"assign up_o[{16*f} +: 16]=0;\n")
        updispatch.append("end\n")
    updispatch.append("else begin:g_bad_up OT_SVC_ROLE_MASK_NOT_IMPLEMENTED invalid_role(); end\nendgenerate\n")
    jp = ["input wire ck,rs_n", "input wire[32:0]j_cmd", "output reg[1:0]j_dn", "input wire[512:0]q", "output wire[512:0]core_q", "input wire[512:0]ad"]
    jobbody = re.sub(r"\bad\b", "ad_full", re.sub(r"\bcore_q\b", "core_q_full", re.sub(r"\bq\b", "q_full", jobbody)))
    jobbody = jobbody.replace("integer k, m, nend;", "integer nend;")
    jobbody = re.sub(r"for \(([km]) =", r"for (int \1 =", jobbody)
    ja = ["wire[514:0]q_full={2'd0,q}; wire[514:0]core_q_full; assign core_q=core_q_full[512:0];", BT+"ifdef OT_SVC_JOB_ENTRY_MUT_ACTIVE\nwire[1025:0]ad_full={513'd0,(ad ^ (513'd1<<496))};\n"+BT+"else\nwire[1025:0]ad_full={513'd0,ad};\n"+BT+"endif", "wire[513:0]od={512'd0,1'b0,1'b1};", BT+"ifdef OT_SVC_JOB_ENTRY_MUT_ABSENT\nwire[513:0]xd={((512'd1<<507)|(512'hff<<495)),1'b1,1'b1};\n"+BT+"else\nwire[513:0]xd={512'd0,1'b0,1'b1};\n"+BT+"endif"]
    out.append(header("ot_s81_svc_job_entry", "parameter integer JQ=8,MUT=0", jp) + "\n".join(ja) + jobbody + "\nendmodule\n")
    # New native station masters: one data edge, two private timed-reset edges.
    # Reset controls valid only. Datapath registers always capture their input.
    out.append("(* keep_hierarchy *) module dsdv_svc_role_ckinv(input wire a,output wire y); assign y=~a; endmodule\n")
    relay_contracts=[]
    for width,valids in ((270,[269]),(276,[137,275])):
        for direction in ("NS","EW","SN","WE"):
            name=f"dsdv_svc_rly{width}_{direction}"
            body=["(* keep=1, dont_touch=1 *) reg[1:0]rs_private;", "always @(posedge ck)rs_private<={rs_private[0],rs};"]
            for bit in range(width):
                body.append(f"reg q_{bit};")
                body.append(f"always @(posedge ck) q_{bit} <= " + (f"rs_private[1] ? i[{bit}] : 1'b0;" if bit in valids else f"i[{bit}];"))
                body.append(f"assign o[{bit}]=q_{bit};")
            body += ["wire ckn;", "dsdv_svc_role_ckinv u_ck0(.a(ck),.y(ckn));", "dsdv_svc_role_ckinv u_ck1(.a(ckn),.y(ck_o));"]
            out.append(header(name,"",["input wire ck,rs",f"input wire[{width-1}:0]i",f"output wire[{width-1}:0]o","output wire ck_o"])+"\n".join(body)+"\nendmodule\n")
            relay_contracts.append(dict(name=name,width=width,valid_bits=valids,data_latency=1,private_reset_assertion=2,private_reset_release=2,physical_view="NEEDS_REHARDEN"))
        for sense,dirs in (("in",("NS","EW","SN","WE")),("out",("SN","WE","NS","EW"))):
            body=["generate"]
            for f,direction in enumerate(dirs):
                body.append(("if" if f==0 else "else if")+f"(F=={f})begin:g_f{f} dsdv_svc_rly{width}_{direction} u(.ck(ck),.rs(rs),.i(i),.o(o),.ck_o()); end")
            body.append("else begin:g_bad OT_SVC_ROLE_FACE_NOT_IMPLEMENTED invalid_face();end\nendgenerate")
            out.append(header(f"dsdv_svc_rly_{width}_{sense}","parameter integer F=0",["input wire ck,rs",f"input wire[{width-1}:0]i",f"output wire[{width-1}:0]o"])+"\n".join(body)+"\nendmodule\n")
    out.append(BT + "default_nettype wire\n")
    return {directory/"dsdv_svc_role_masters.sv":"\n".join(out), directory/"dsdv_svc_hrow_timed_ref.sv":reference, directory/"dsdv_svc_sx_role_dispatch.svh":"".join(dispatch), directory/"dsdv_svc_up_role_dispatch.svh":"".join(updispatch), root/"results/arch/s81_svc_roles_1713/contracts.json":json.dumps(dict(hrow_types=contracts, up_types=[dict(name=f"dsdv_svc_rs_up_fv_{a:x}{b:x}",sids=s) for (a,b),s in sorted(upgroups.items())], relays=relay_contracts,hrow_instances=128, data_cycles_added=0, physical_view_adoption=False),indent=2)+"\n"}


if __name__ == "__main__":
    p=argparse.ArgumentParser();p.add_argument("--root",type=Path,default=Path(__file__).resolve().parents[3]);a=p.parse_args()
    for path,text in generate(a.root).items():path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
