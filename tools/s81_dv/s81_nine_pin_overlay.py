#!/usr/bin/env python3
"""Prepare the explicit nine-pin edge-centre overlay for the one S81 plan event."""
import argparse,copy,hashlib,json
from pathlib import Path
def prepare(plan,pin_root,delta_dir,out):
 out=Path(out);out.mkdir(parents=True,exist_ok=True);delta_dir=Path(delta_dir);delta=json.loads((delta_dir/"delta.json").read_text());doc=json.loads(Path(plan).read_text());rows=[]
 for core in delta["cores"]:
  mod=core["module"];source=Path(pin_root)/(mod+".json");raw=source.read_bytes()
  if hashlib.sha256(raw).hexdigest()!=core["base_pins_sha256"]:raise ValueError("source pin file changed: "+mod)
  pins=json.loads(raw);mapping={p["name"]:p for p in pins["pins"]}
  for move in core["pins"]:
   pin=mapping[move["pin"]]
   if [pin["x"],pin["y"]]!=move["old_center_um"]:raise ValueError("old centre differs: "+move["pin"])
   if pin["layer"]!=move["layer"]:raise ValueError("layer differs")
   pin["x"],pin["y"]=move["new_center_um"]
  # Full file/content hashes are generated by the current kit writer. Retain only
  # the explicitly labelled historical pinhash, never a stale current hash.
  if "pinhash" in pins:pins["historical_pinhash"]=pins.pop("pinhash")
  pins["source"]+="; explicit existing edge-PORT centre selection, S81 one-event candidate only"
  dest=out/"inputs"/"core_pins"/(mod+".json");dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(json.dumps(pins,indent=2)+"\n")
  refs=[dict(type=t,inst=h["inst"]) for t,v in doc["partition_types"].items() for h in v.get("hard_cores",[]) if h.get("module")==mod]
  rows.append(dict(module=mod,pins=len(core["pins"]),plan_declarations=refs,new_pin_file=str(dest),new_full_sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),lef_changed=False))
 doc["note"]=doc.get("note","")+"; CODEX candidate nine existing edge-PORT centres, no LEF/body/clock/latency changes; remaining input sidecars from unchanged base"
 (out/"die_plan.json").write_text(json.dumps(doc,indent=2)+"\n")
 report=dict(candidate_only=True,source_plan_sha256=hashlib.sha256(Path(plan).read_bytes()).hexdigest(),pin_moves=rows,canonical_adopted=False,all_other_inputs_require_base_sidecars=True)
 (out/"REPORT.json").write_text(json.dumps(report,indent=2)+"\n");return report
if __name__=="__main__":
 p=argparse.ArgumentParser();p.add_argument("--plan",required=True);p.add_argument("--pin-root",required=True);p.add_argument("--delta-dir",required=True);p.add_argument("--out",required=True);a=p.parse_args();print(json.dumps(prepare(a.plan,a.pin_root,a.delta_dir,a.out),indent=2))
