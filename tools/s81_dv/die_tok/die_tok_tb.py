#!/usr/bin/env python3
"""TOK-DS-2 (11-01): whole-die bench for the generated S81 bound top (tools/die_plan/bind.py elab: s81_bound_top).

V0 bench (no programme yet): every die clock input (clk_core, clk_region_*, SerDes lk_*_pma_rck) from ONE bench clock
(functional RTL; skew is a timing question), PMA rx lanes idle 0, die rst_n asserted at t=0.1 ns, released at a falling
edge after --nrst cycles.  Cycle k = k-th rising edge after release.  Monitors every clock-landing pair the top declares
(wire cland_ready_<x>, cland_fault_<x>): fault is sticky-checked from release on; ready rise cycle is recorded.  Verdict
TB_S81_DIE PASS when every landing is ready by --cycles and no fault ever rose; else FAIL with the first event.

Usage: die_tok_tb.py --top s81_bound_top.sv --out tb_s81_die.sv [--nrst 64] [--cycles 4000] [--period-ps 833]
"""
import argparse, re
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--top', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--nrst', type=int, default=64); ap.add_argument('--cycles', type=int, default=4000)
    ap.add_argument('--period-ps', type=int, default=833); ap.add_argument('--module', default='s81_bound_top')
    ap.add_argument('--hier-out', help='also write a Verilator config with one hier_block per partition master')
    ap.add_argument('--hier-skip', default='', help='comma list of masters the bench reaches into (not hier blocks)')
    ap.add_argument('--hier-extra', default='ot_s81c_attn_hcore',
                    help='comma list of leaf modules also made hier blocks (the 16 svc_rs/pvso partitions hold 64 attn hcores '
                         'each and need >32 GB per frontend without it)')
    a = ap.parse_args()
    t = Path(a.top).read_text()
    ports = []
    for m in re.finditer(r'^\s*(input|output)\s+wire\s*(\[(\d+):(\d+)\])?\s*(\w+)\s*;', t, re.M):
        d, _, hi, lo, n = m.groups()
        w = int(hi) - int(lo) + 1 if hi else 1
        ports.append((d, w, n))
    decl = set(re.findall(r'\bcland_ready_(\w+)\b', ' '.join(re.findall(r'^\s*wire\b[^;]*;', t, re.M))))
    lands = sorted(x for x in set(re.findall(r'\bcland_fault_(\w+)\b', t)) if x in decl)
    half = a.period_ps / 2000.0
    L = ['// GENERATED by die_tok_tb.py (TOK-DS-2) -- whole-die S81 bench, do not edit', '`timescale 1ns/1ps',
         'module tb_s81_die;', "  reg clk = 1'b0;", "  reg rst_n = 1'b1;",
         f'  always #{half:.4f} clk = ~clk;']
    conns = []
    for d, w, n in ports:
        if d == 'input':
            if n == 'rst_n':
                conns.append('.rst_n(rst_n)')
            elif w == 1 and (n.startswith('clk') or n.endswith('_rck')):
                conns.append(f'.{n}(clk)')
            else:
                L.append(f"  reg [{w-1}:0] {n} = '0;"); conns.append(f'.{n}({n})')
        else:
            L.append(f'  wire [{w-1}:0] {n};'); conns.append(f'.{n}({n})')
    L.append(f'  {a.module} dut (' + ', '.join(conns) + ');')
    txs = [n for d, w, n in ports if d == 'output' and n.endswith('_tx')]
    TXL, TXD = [], []
    for n in txs:
        TXD.append(f'  integer tx_n_{n} = 0; integer tx_f_{n} = -1;')
        TXL += [f"  always @(negedge clk) if (rst_n && cyc >= 0 && |{n}) begin tx_n_{n} = tx_n_{n} + 1; if (tx_f_{n} < 0) begin tx_f_{n} = cyc; $display(\"TB_S81_DIE TXFIRST {n} cycle %0d\", cyc); end end"]
    a.txs = txs
    nl = len(lands)
    L += [f'  localparam integer NL = {nl};', f'  localparam integer NRST = {a.nrst};',
          f'  integer NCYC = {a.cycles}; initial if ($value$plusargs("NCYC=%d", NCYC)) ;', '  wire [NL-1:0] lf, lr;']
    for i, x in enumerate(lands):
        L.append(f'  assign lf[{i}] = dut.cland_fault_{x}; assign lr[{i}] = dut.cland_ready_{x};')
    L.append('  string lname [0:NL-1];')
    L.append('  initial begin')
    for i, x in enumerate(lands):
        L.append(f'    lname[{i}] = "{x}";')
    L.append('  end')
    L += ['  integer cyc = -1; integer first_fault_cyc = -1; integer nfault = 0; integer nready = 0; integer i; integer mx;',
          '  integer ready_at [0:NL-1]; reg [NL-1:0] fseen;'] + TXD + [
          '  initial begin',
          "    for (i = 0; i < NL; i = i + 1) ready_at[i] = -1; fseen = '0;",
          "    #0.1 rst_n = 1'b0;",
          '    repeat (NRST) @(posedge clk);',
          "    @(negedge clk) rst_n = 1'b1;",
          '    $display("TB_S81_DIE RELEASE t=%0t", $time);',
          '  end',
          '  always @(posedge clk) if (rst_n) cyc <= cyc + 1;',
          '  // V1 host-word injection (+HOSTIN=<memh of 515-b words {type 2, x 512, v}>, +HOST_T0=<cycle>): the lep core',
          '  // f_host of s_7N_LP (where the EN0/EN1 link host frame is decoded) is driven one word per cycle.',
          '  reg [514:0] hmem [0:1048575]; integer nh = 0; integer ht0 = 300; reg [8*512-1:0] hfile; reg [514:0] hword = 515\'d0;',
          '  integer alive_at = -1; integer hfault_at = -1;',
          '  initial begin',
          '    if ($value$plusargs("HOST_T0=%d", ht0)) ;',
          '    if ($value$plusargs("HOSTN=%d", nh)) ;',
          '    if (nh > 0 && $value$plusargs("HOSTIN=%s", hfile)) begin',
          '      $readmemh(hfile, hmem, 0, nh - 1);',
          '      $display("TB_S81_DIE HOSTIN %0d words from cycle %0d", nh, ht0);',
          '      force dut.s_7N_LP.w_u_lep_f_host = hword;',
          '    end',
          '  end',
          '  // +HOST_AFTER_ALIVE: like the host, start the stream HOST_T0 cycles after the die START gate (t_host alive) rises',
          '  integer haa = 0; integer hbase = -1; initial if ($value$plusargs("HOST_AFTER_ALIVE=%d", haa)) ;',
          '  always @(negedge clk) if (rst_n && nh > 0) begin',
          "    if (hbase < 0 && (haa == 0 || dut.seqhost.w_u_seqhost_t_host[76] === 1'b1)) begin hbase = (haa == 0) ? ht0 : cyc + 1 + ht0; $display(\"TB_S81_DIE HOST_STREAM_BASE cycle %0d\", hbase); end",
          "    if (hbase >= 0 && cyc + 1 >= hbase && cyc + 1 - hbase < nh) hword <= hmem[cyc + 1 - hbase]; else hword <= 515\'d0;",
          '  end',
          '  always @(negedge clk) if (rst_n && cyc >= 0) begin',
          "    if (dut.seqhost.w_u_seqhost_t_host[76] === 1'b1 && alive_at < 0) begin alive_at = cyc; $display(\"TB_S81_DIE HOST_ALIVE cycle %0d\", cyc); end",
          "    if (dut.seqhost.w_u_seqhost_t_host[75] !== 1'b0 && hfault_at < 0) begin hfault_at = cyc; $display(\"TB_S81_DIE HOST_FAULT cycle %0d t_host[76:71] %b\", cyc, dut.seqhost.w_u_seqhost_t_host[76:71]); end",
          '  end',
          '  // +KS=1: the job start {v, user 37, tok 1000, pos 5000} on the seq_host core f_ks (dsdv_seq_host u_u, below the MU',
          '  // mux), on the same launch rule as tools/s81_dv/layer_prog/tb_dv_prog_seqhost.sv: all host words delivered, issuer',
          '  // sealed and phase_q 0 at edge c -> f_ks for edge c + 29.  PROG KS/VO/CW/SJ/KD/STATUS/END lines in that bench\'s',
          '  // format, so check_seqhost.py checks the whole-die run against the compiled calendar unchanged.',
          '  integer ksm = 0; integer nhv = 0; integer nhv_seen = 0; integer launch0 = -1; integer t_ks = -1; reg [52:0] ksw = 53\'d0;',
          '  initial begin if ($value$plusargs("KS=%d", ksm)) ; #1; for (i = 0; i < nh; i = i + 1) if (hmem[i][0] === 1\'b1) nhv = nhv + 1;',
          '    if (ksm != 0) begin $display("TB_S81_DIE KS mode: %0d valid host words", nhv); force dut.seqhost.u_u_seqhost.u.u_u.f_ks = ksw; end end',
          '  always @(negedge clk) if (rst_n && cyc >= 0 && ksm != 0) begin',
          "    ksw <= 53'd0;",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.f_host[0] === 1'b1) nhv_seen = nhv_seen + 1;",
          "    if (launch0 < 0 && nhv_seen == nhv && nhv > 0 && dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.sealed === 1'b1 && dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.phase_q == 2'd0) launch0 = cyc + 29;",
          "    if (launch0 >= 0 && t_ks < 0 && cyc + 1 == launch0) begin ksw <= {1'b1, 10'd37, 21'd1000, 21'd5000}; t_ks = cyc + 1; $display(\"PROG KS %0d\", t_ks); end",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.vo_s[0] === 1'b1) $display(\"PROG VO S %0d %h\", cyc, dut.seqhost.u_u_seqhost.u.u_u.vo_s);",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.vo_n[0] === 1'b1) $display(\"PROG VO N %0d %h\", cyc, dut.seqhost.u_u_seqhost.u.u_u.vo_n);",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.cw_v === 1'b1) $display(\"PROG CW %0d %h %h\", cyc, dut.seqhost.u_u_seqhost.u.u_u.cw_a, dut.seqhost.u_u_seqhost.u.u_u.cw_d);",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.s_j[32] === 1'b1) $display(\"PROG SJ %0d %h\", cyc, dut.seqhost.u_u_seqhost.u.u_u.s_j);",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.t_kd[53] === 1'b1) $display(\"PROG KD %0d %h\", cyc, dut.seqhost.u_u_seqhost.u.u_u.t_kd);",
          "    if (dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.fault === 1'b1 && t_ks >= 0 && cyc == t_ks + 1) $display(\"PROG FAULT %0d code %0d\", cyc, dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.fault_code);",
          '  end',
          '  // host return (t_host = {alive, fault, wf4, sseq6, t_v, t_d64}): log every status change and every t_v word',
          '  reg [12:0] th_prev = 13\'h1fff; integer ntv = 0; reg [63:0] tdx = 64\'d0;',
          '  always @(negedge clk) if (rst_n && cyc >= 0) begin',
          '    if (dut.seqhost.w_u_seqhost_t_host[76:64] !== th_prev) begin th_prev = dut.seqhost.w_u_seqhost_t_host[76:64];',
          '      $display("TB_S81_DIE THOST cycle %0d alive %b fault %b wf %b sseq %0d tv %b td %h", cyc, th_prev[12], th_prev[11], th_prev[10:7], th_prev[6:1], th_prev[0], dut.seqhost.w_u_seqhost_t_host[63:0]); end',
          "    if (dut.seqhost.w_u_seqhost_t_host[64] === 1'b1) begin ntv = ntv + 1; tdx = {tdx[62:0], tdx[63]} ^ dut.seqhost.w_u_seqhost_t_host[63:0];",
          '      if (ntv <= 64) $display("TB_S81_DIE TV cycle %0d n %0d td %h", cyc, ntv, dut.seqhost.w_u_seqhost_t_host[63:0]); end',
          '  end',
          '  always @(negedge clk) if (rst_n && cyc >= 0) begin',
          '    for (i = 0; i < NL; i = i + 1) begin',
          "      if (lr[i] === 1'b1 && ready_at[i] < 0) begin ready_at[i] = cyc; nready = nready + 1; end",
          "      if (lf[i] !== 1'b0 && !fseen[i]) begin fseen[i] = 1'b1; nfault = nfault + 1;",
          '        if (first_fault_cyc < 0) first_fault_cyc = cyc;',
          '        $display("TB_S81_DIE FAULT cycle %0d landing %s value %b", cyc, lname[i], lf[i]); end',
          '    end',
          '    if (cyc % 500 == 0) $display("TB_S81_DIE PROGRESS cycle %0d ready %0d/%0d faults %0d", cyc, nready, NL, nfault);',
          '    if (cyc == NCYC) begin',
          '      mx = -1;',
          '      for (i = 0; i < NL; i = i + 1) begin',
          '        if (ready_at[i] < 0) $display("TB_S81_DIE NOTREADY %s", lname[i]);',
          '        if (ready_at[i] > mx) mx = ready_at[i];',
          '      end',
          ] + [f'      $display("TB_S81_DIE TX {n} words %0d first %0d", tx_n_{n}, tx_f_{n});' for n in a.txs] + [
          '      if (ksm != 0) begin $display("PROG FCODE %0d fault %0d", dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.fault_code, dut.seqhost.u_u_seqhost.u.u_u.u_l1.u_iss.fault);',
          '        $display("PROG STATUS %0d t_host %h", cyc, dut.seqhost.u_u_seqhost.u.u_u.t_host); $display("PROG END"); end',
          '      $display("TB_S81_DIE SUMMARY cycles %0d landings %0d ready %0d last_ready_cycle %0d faults %0d first_fault_cycle %0d host_words %0d host_alive %0d host_fault %0d tv_words %0d tv_hash %h", cyc, NL, nready, mx, nfault, first_fault_cyc, nh, alive_at, hfault_at, ntv, tdx);',
          '      if (nfault == 0 && nready == NL && hfault_at < 0 && (nh == 0 || alive_at >= 0)) $display("TB_S81_DIE PASS"); else $display("TB_S81_DIE FAIL");',
          '      $finish;',
          '    end',
          '  end',
          ] + TXL + ['endmodule']
    Path(a.out).write_text('\n'.join(L) + '\n')
    if a.hier_out:
        skip = set(x for x in a.hier_skip.split(',') if x)
        body = t.split(');', 1)[1]
        ms = sorted(set(re.findall(r'^\s*(\w+)\s*(?:#\s*\(.*?\))?\s+\w+\s*\(', body, re.M | re.S)) - skip -
                    {'assign', 'wire', 'module', 'endmodule', 'input', 'output'})
        ms = list(ms) + [x for x in a.hier_extra.split(',') if x and x not in ms]
        Path(a.hier_out).write_text('`verilator_config\n' + ''.join(f'hier_block -module "{m}"\n' for m in ms))
        print(f'hier blocks {len(ms)} -> {a.hier_out}')
    print(f'ports {len(ports)} landings {nl} -> {a.out}')


if __name__ == '__main__':
    main()
