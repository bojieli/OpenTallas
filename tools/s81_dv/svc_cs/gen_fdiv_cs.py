"""Generate rtl/dsrom_sys/s81_svc/ot_s81_svc_fdiv_f12_cs.sv from ot_dsrom_su_fdiv_f12 (rtl/hdc/v41x, read only).

DIE-S81-85 svc census 11-10: census-safe S81 copy of the f12 divider.  Same function, same latency; the F1 cut
bits above 64 loads (f1_sh: the F2 denormalise shift + lost mask) get a kept replica feeding the lost mask.
Usage: python3 gen_fdiv_cs.py REPO_ROOT
"""
import re, sys
from pathlib import Path

root = Path(sys.argv[1])
src = (root / 'rtl/hdc/v41x/ot_dsrom_su_fdiv_f12.sv').read_text()
t = re.search(r'^module ot_dsrom_su_fdiv_f12 #\(.*?^endmodule\n', src, re.M | re.S).group(0)


def sub(old, new):
    global t
    assert t.count(old) == 1, old
    t = t.replace(old, new)


sub('module ot_dsrom_su_fdiv_f12 #(', 'module ot_s81_svc_fdiv_f12_cs #(')
sub('    reg [4:0]  f1_sh;\n', '    reg [4:0]  f1_sh;\n    (* keep = 1 *) reg [4:0] f1_sh_b;                // = f1_sh, census-safe replica (lost mask)\n')
sub("        f1_sh    <= (sh_full > 11'd25) ? 5'd25 : sh_full[4:0];\n",
    "        f1_sh    <= (sh_full > 11'd25) ? 5'd25 : sh_full[4:0];\n"
    "        f1_sh_b  <= (sh_full > 11'd25) ? 5'd25 : sh_full[4:0];\n")
sub("    wire [24:0] lost_mask = (25'd1 << f1_sh) - 25'd1;",
    "    wire [24:0] lost_mask = (25'd1 << f1_sh_b) - 25'd1;")
hdr = ('`timescale 1ns/1ps\n'
       '// GENERATED by tools/s81_dv/svc_cs/gen_fdiv_cs.py from ot_dsrom_su_fdiv_f12 (rtl/hdc/v41x/ot_dsrom_su_fdiv_f12.sv,\n'
       '// unchanged there); do not edit.  DIE-S81-85 svc census 11-10 (COORD loopgap-153x-1109, 11-10 ruling): census-safe\n'
       '// S81 copy for the S81 svc provider boxes only; same function, same latency; f1_sh has a kept replica (lost mask).\n'
       '// EQ: tools/s81_dv/svc_cs/eq_cs.sh fdiv.\n')
dst = root / 'rtl/dsrom_sys/s81_svc/ot_s81_svc_fdiv_f12_cs.sv'
dst.write_text(hdr + t)
print('wrote', dst)
