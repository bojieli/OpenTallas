#!/usr/bin/env python3
"""TOK-ALL-17: extract from die_b178.v the exact return-lane cone of selected frames:
frame ret (w_r_f_<F>_src) -> hop-0 ICG -> dsfd_dvrlyh stations -> dsfd_dvland_70 (die k strap) -> w_r_f_<F>_lnd,
plus the full die reset wavefront cone (dsfd_rly_1_* stations) feeding every rs/ENA pin in it, back to its root.
Instances are copied verbatim from the die netlist; undriven nets become module inputs: root clocks (ck_*) are tied
to the bench's one uniform clock, the reset root to the bench reset. Emits a module ret_cone_<tag> with ports
ret_<F> (in), lnd_<F> (out), land_fault (out OR), ck, rst_n."""
import re, sys, json, hashlib
from pathlib import Path
die, out, frames = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3].split(',')
land = json.loads(Path(sys.argv[4]).read_text()) if len(sys.argv) > 4 else None
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from frame_chain_reset_v2 import lane_flight
OUTP = {'o', 'ck_o', 'GCLK', 'fault', 'y', 'q', 'Q'}
inst_re = re.compile(r'^\s*(\w+)\s+(?:#\((?:[^()]|\([^()]*\))*\)\s*)?(\w+)\s*\((.*)\);')
port_re = re.compile(r'\.(\w+)\(\s*([^()]*?)\s*\)')
drv, insts, widths = {}, {}, {}
def base(n):
    return re.sub(r'\[.*\]$', '', n.strip())
for ln in die.read_text().splitlines():
    m = re.match(r'^\s*wire\s*(\[\d+:\d+\])?\s*(.*);', ln)
    if m:
        for n in m.group(2).split(','):
            widths[n.strip()] = m.group(1) or ''
        continue
    m = inst_re.match(ln)
    if not m or m.group(1) in ('module', 'assign', 'input', 'output', 'wire'):
        continue
    mod, name, body = m.groups()
    ports = port_re.findall(body)
    insts[name] = (mod, ln.split('//')[0].rstrip(), ports)
    for p, n in ports:
        if p in OUTP and re.fullmatch(r'\w+(\[\d+\])?', n):
            drv.setdefault(base(n), []).append(name)
cone, todo, prim = [], [f'w_r_f_{f}_lnd' for f in frames], set()
seen = set()
while todo:
    n = todo.pop()
    if n in seen: continue
    seen.add(n)
    ds = drv.get(n)
    if ds is None:
        prim.add(n); continue
    for d in ds:
      if d in cone: continue
      mod, ln, ports = insts[d]
      if mod.startswith('col_h'):   # the frame itself is the bench's DUT: stop, its ret is a module input
        prim.add(n); continue
      cone.append(d)
      for p, x in ports:
        if p in OUTP: continue
        if re.fullmatch(r"\d+'[bdh]\w*", x): continue
        for t in re.findall(r"[A-Za-z_]\w*", x):
            todo.append(t)
mods = sorted({insts[c][0] for c in cone})
ck = sorted(p for p in prim if p.startswith('ck_'))
rets = sorted(p for p in prim if p.startswith('w_r_f_'))
oth = sorted(p for p in prim if p not in ck and p not in rets)
L = [f'// generated by die_ret_cone.py from {die.name} sha256 {hashlib.sha256(die.read_bytes()).hexdigest()}',
     f'// frames {frames}; {len(cone)} instances copied verbatim; root clocks {ck} -> ck; other primaries {oth} -> rst_n',
     '`default_nettype none', f'module ret_cone(input wire ck, input wire rst_n, ' +
     ', '.join(f'input wire [69:0] ret_{f}, output wire [69:0] lnd_{f}' for f in frames) + ', output wire land_fault);']
decl = set()
for c in cone:
    for p, x in insts[c][2]:
        if p in OUTP and re.fullmatch(r'\w+(\[\d+\])?', x): decl.add(base(x))
for f in frames: decl.add(f'w_r_f_{f}_src')
for c in cone:
    for p, x in insts[c][2]:
        for t in re.findall(r"[A-Za-z_]\w*", x):
            if t in widths: decl.add(t)
for n in sorted(decl):
    if n in ck or n in oth: continue
    L.append(f'  wire {widths.get(n, "")} {n};')
for n in ck: L.append(f'  wire {n} = ck;')
for n in oth:
    if n != 'rst_n': L.append(f'  wire {n} = rst_n;')
for f in frames:
    L.append(f'  assign w_r_f_{f}_src = ret_{f};')
    L.append(f'  assign lnd_{f} = w_r_f_{f}_lnd;')
faults = []
FL = {}
for c in cone:
    mod, ln, ports = insts[c]
    if mod.startswith('dsfd_dvland'):
        # last-hop flight (dv_slice_cut / frame_chain_reset_v2 rule): F whole periods from the GEN land plan s1 at the
        # die K strap, delaying both the lane clock and the word into the landing (FRAME_CAL_FF = ff corner)
        f = c.removeprefix('ld_r_f_'); K = int(re.search(r"\.k\(3'd(\d)\)", ln).group(1))
        row = next((r for r in land['links'] if r.get('link') == f'r_f_{f}' and r.get('cls') == 'ret'), {}) if land else {}
        T = land['T_ps'] if land else 833.333
        F = {cn: lane_flight(K, (row.get('s1') or {}).get(cn), T) for cn in ('tt', 'ff')}
        FL[f] = dict(K=K, F=F, s1=row.get('s1'), stations=None)
        ckf = re.search(r"\.ck_f\(([^)]*)\)", ln).group(1); di = re.search(r"\.i\(([^)]*)\)", ln).group(1)
        L += [f'  wire flck_{f}; wire [69:0] fli_{f};',
              f'  `ifdef FRAME_CAL_FF dv_flight_sim #(.W(70), .F({F["ff"]})) `else dv_flight_sim #(.W(70), .F({F["tt"]})) `endif '
              f'fl_{f} (.ck_in({ckf}), .rs(1\'b1), .i_in({di}), .ck_out(flck_{f}), .i_out(fli_{f}));']
        ln = ln.replace(f'.ck_f({ckf})', f'.ck_f(flck_{f})').replace(f'.i({di})', f'.i(fli_{f})')
    if mod.startswith('dsfd_dvland') and not any(p == 'fault' for p, _ in ports):
        ln = ln.rstrip(';').rstrip()
        assert ln.endswith(')'); ln = ln[:-1] + f', .fault(lf_{c}));'
        L.append(f'  wire lf_{c};'); faults.append(f'lf_{c}')
    L.append('  ' + ln.strip())
L.append(f'  assign land_fault = ' + (' | '.join(faults) or "1'b0") + ';')
L += ['endmodule', '`default_nettype wire']
from dv_slice_cut import FLIGHT_SIM
L += ['module ICGx4_ASAP7_75t_R(input CLK, ENA, SE, output GCLK); reg en_l; /* verilator lint_off COMBDLY */ '
      'always_latch if (!CLK) en_l = ENA | SE; /* verilator lint_on COMBDLY */ assign GCLK = CLK & en_l; endmodule', FLIGHT_SIM]
out.write_text('\n'.join(L) + '\n')
info = dict(instances=len(cone), modules={m: sum(insts[c][0] == m for c in cone) for m in mods}, clocks=ck, others=oth, rets=rets,
            stations={f: sum(1 for c in cone if insts[c][0].startswith('dsfd_dvrlyh') and f'r_f_{f}_' in c) for f in frames},
            flights=FL, land_k={f: re.search(r"\.k\(([^)]*)\)", insts[f'ld_r_f_{f}'][1]).group(1) for f in frames})
print(json.dumps(info, indent=1))
