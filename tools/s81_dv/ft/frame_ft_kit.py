#!/usr/bin/env python3
"""FT-S81 10-23: in-place ft variant of a frame kit (no wrapper hierarchy).

A pushdown.py wrapper puts the kit under u_kit, which renames every instance the landed-frame contracts bind by name
(children / landings / forwarded outputs / soft clocks / place.tcl).  This tool writes the SAME kit module text renamed
to the variant, with the ft ports appended to its port list and the wrapper's ft stations appended to its body, each
insertion fenced by "// >>> FT-S81 ft" / "// <<< FT-S81 ft" lines.  Removing the fenced lines and renaming the module
back reproduces the kit file byte for byte (`check`), so the frame logic is provably unmodified.

    frame_ft_kit.py gen   --kit KIT.sv --kit-top TOP --wrapper WRAP.v --variant NAME --out OUT.sv
    frame_ft_kit.py check --kit KIT.sv --kit-top TOP --variant-sv OUT.sv --variant NAME   (prints FT_KIT_CHECK PASS|FAIL)
"""
import argparse
import hashlib
import re
import sys

BEGIN, END = "// >>> FT-S81 ft", "// <<< FT-S81 ft"


def module_span(text, name):
    m = re.search(rf"^module {re.escape(name)}\b", text, re.M)
    if not m:
        raise SystemExit(f"module {name} not found")
    e = re.compile(r"^endmodule\b", re.M).search(text, m.end())
    return m.start(), e.start()


def gen(a):
    kit = open(a.kit).read()
    wrap = open(a.wrapper).read()
    ws, we = module_span(wrap, a.variant)
    wbody = wrap[ws:we]
    hdr_end = wbody.index(");")
    ports = [l.strip().rstrip(",") for l in wbody[:hdr_end].splitlines() if re.match(r"\s*(input|output)\s", l)]
    ft_ports = [p for p in ports if re.search(r"\bft\d+_\w+$", p)]
    body = wbody[hdr_end + 2:]
    body = re.sub(rf"^\s*{re.escape(a.kit_top)}\s+u_kit\s*\(.*?\);\n", "", body, flags=re.S | re.M)
    if "u_kit" in body:
        raise SystemExit("wrapper body still references u_kit")
    extra = wrap[we:].split("\n", 1)[1] if "\n" in wrap[we:] else ""     # helper modules after the wrapper (ft_pipe_reg)
    ks, ke = module_span(kit, a.kit_top)
    mod = kit[ks:ke]
    h = mod.index("\n);")
    new_mod = (mod[:h] + ",\n" + BEGIN + " ports\n" + ",\n".join("    " + p for p in ft_ports) + "\n" + END + " ports"
               + mod[h:] + BEGIN + " stations (tools/s81_dv/ft/frame_ft_kit.py from " + a.wrapper + ")\n"
               + body.rstrip() + "\n" + END + " stations\n")
    new_mod = re.sub(rf"^module {re.escape(a.kit_top)}\b", f"module {a.variant}", new_mod, count=1, flags=re.M)
    sha = hashlib.sha256(kit.encode()).hexdigest()
    out = (f"{BEGIN} header\n// GENERATED by tools/s81_dv/ft/frame_ft_kit.py: {a.kit_top} of {a.kit} (sha256 {sha}) "
           f"renamed {a.variant} + ft ports/stations from {a.wrapper}; frame logic unmodified (frame_ft_kit.py check).\n"
           f"{END} header\n" + kit[:ks] + new_mod + kit[ke:])
    if extra.strip():
        out = out.rstrip("\n") + "\n" + BEGIN + " helpers\n" + extra.strip("\n") + "\n" + END + " helpers\n"
    open(a.out, "w").write(out)
    print(a.out, len(ft_ports), "ft ports")


def strip_ft(text):
    out, skip = [], False
    lines = text.split("\n")
    for i, l in enumerate(lines):
        if l.startswith(BEGIN):
            skip = True
            continue
        if l.startswith(END):
            skip = False
            continue
        if not skip:
            out.append(l)
    return "\n".join(out)


def check(a):
    kit = open(a.kit).read()
    v = strip_ft(open(a.variant_sv).read())
    v = re.sub(rf"^module {re.escape(a.variant)}\b", f"module {a.kit_top}", v, count=1, flags=re.M)
    # the port-list insertion added one "," after the last kit port
    ks, _ = module_span(kit, a.kit_top)
    h = kit.index("\n);", ks)
    kit_comma = kit[:h] + "," + kit[h:]
    ok = v == kit_comma
    print("FT_KIT_CHECK " + ("PASS frame logic byte-identical to " if ok else "FAIL differs from ") + a.kit)
    sys.exit(0 if ok else 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sp = ap.add_subparsers(dest="cmd", required=True)
    g = sp.add_parser("gen")
    for k in ("--kit", "--kit-top", "--wrapper", "--variant", "--out"):
        g.add_argument(k, required=True)
    c = sp.add_parser("check")
    for k in ("--kit", "--kit-top", "--variant-sv", "--variant"):
        c.add_argument(k, required=True)
    a = ap.parse_args()
    gen(a) if a.cmd == "gen" else check(a)


if __name__ == "__main__":
    main()
