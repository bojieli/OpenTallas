#!/usr/bin/env python3
"""FT-S81 10-23: PG-stripe-aware placement of the feedthrough (ft) pins of a frame variant.

pushdown.py pins puts every ft bit on a fixed 0.24-um step of the M8 track grid.  A two-level S81 frame exports its PG
as full-length M8 stripes (w 0.48, p 8.64, off 4.32): 309 of the 4,716 ft2 pins landed ON a stripe.  This writes an
ORFS POST_IO_PLACEMENT_TCL hook that, after place_pins, reads the ACTUAL M8 special-net shapes from the block and
re-places each ft bit on the first free M8 track at or after its nominal position (step = the pushdown step, a blocked
track moves the rest of the port up).  The rule is deterministic and every frame sits on the die's M8 PG phase, so an
in-face and the matching out-face of the neighbour get identical tracks.  It fails closed when a port would overrun the
next port's start or the face.

Usage: ft_pins_pg.py PINS.json --out HOOK.tcl [--margin-um 0.064]
"""
import argparse
import json
from collections import OrderedDict

TCL_HEAD = r'''# GENERATED by tools/s81_dv/ft/ft_pins_pg.py from {src} -- do not edit; regenerate.
# POST_IO_PLACEMENT hook: ft pins of {variant} on M8 tracks clear of the M8 PG stripes (read from the block).
set ft_blk [ord::get_db_block]
set ft_dbu [[ord::get_db_tech] getDbUnitsPerMicron]
set ft_layer [[ord::get_db_tech] findLayer {layer}]
set ft_blocked {{}}
foreach ft_net [$ft_blk getNets] {{
  if {{[lsearch -exact {{POWER GROUND}} [$ft_net getSigType]] < 0}} continue
  foreach ft_sw [$ft_net getSWires] {{
    foreach ft_w [$ft_sw getWires] {{
      if {{[$ft_w isVia] || [$ft_w getTechLayer] ne $ft_layer}} continue
      lappend ft_blocked [list [$ft_w yMin] [$ft_w yMax]]
    }}
  }}
}}
foreach ft_bt [$ft_blk getBTerms] {{
  if {{[lsearch -exact {{POWER GROUND}} [$ft_bt getSigType]] < 0}} continue
  foreach ft_bp [$ft_bt getBPins] {{ foreach ft_b [$ft_bp getBoxes] {{
    if {{[$ft_b getTechLayer] eq $ft_layer}} {{ lappend ft_blocked [list [$ft_b yMin] [$ft_b yMax]] }}
  }} }}
}}
set ft_blocked [lsort -integer -index 0 [lsort -unique $ft_blocked]]
if {{![llength $ft_blocked]}} {{ error "FT_PINS_PG: no {layer} PG shape found (expected the frame's M8 stripes)" }}
puts "FT_PINS_PG [llength $ft_blocked] {layer} PG intervals"
set ft_margin [expr {{round({margin} * $ft_dbu)}}]
set ft_half [expr {{round({half} * $ft_dbu)}}]
set ft_pitch [expr {{round({pitch} * $ft_dbu)}}]
set ft_off [expr {{round({offset} * $ft_dbu)}}]
proc ft_free {{y}} {{
  upvar #0 ft_blocked blk ft_margin m ft_half h
  foreach iv $blk {{
    if {{$y + $h + $m > [lindex $iv 0] && $y - $h - $m < [lindex $iv 1]}} {{ return 0 }}
  }}
  return 1
}}
proc ft_snap {{y}} {{
  upvar #0 ft_pitch p ft_off o
  return [expr {{$o + int(ceil(double($y - $o) / $p)) * $p}}]
}}
set ft_moved 0; set ft_n 0
'''

TCL_PORT = r'''# port {port}: {n} bits, face {face}, nominal {lo:.3f}..{hi:.3f} um, step {step:.3f} um, limit {limit:.3f} um
set y [ft_snap [expr {{round({lo} * $ft_dbu)}}]]
set ft_names {{{names}}}
set k 0
foreach nm $ft_names {{
  if {{$k > 0}} {{ set y [ft_snap [expr {{$y + round({step} * $ft_dbu)}}]] }}
  while {{![ft_free $y]}} {{ set y [expr {{$y + $ft_pitch}}]; incr ft_moved }}
  if {{$y > round({limit} * $ft_dbu)}} {{ error "FT_PINS_PG: port {port} overruns its band at $nm ([expr {{$y / double($ft_dbu)}}] um > {limit})" }}
  place_pin -pin_name $nm -layer {layer} -location [list {x} [expr {{$y / double($ft_dbu)}}]] -pin_size {{{size}}} -force_to_die_boundary
  incr k; incr ft_n
}}
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("pins")
    ap.add_argument("--out", required=True)
    ap.add_argument("--margin-um", type=float, default=0.064, help="M8 pin-to-stripe clearance (>= M8 min spacing)")
    ap.add_argument("--pitch-um", type=float, default=0.080, help="M8 track pitch")
    ap.add_argument("--offset-um", type=float, default=0.116, help="M8 track offset")
    a = ap.parse_args()
    d = json.load(open(a.pins))
    W, H = d["outline"]
    layers = sorted({p["layer"] for p in d["pins"]})
    if layers != ["M8"]:
        raise SystemExit(f"ft_pins_pg: only M8 ft pins are handled, got {layers}")
    ports = OrderedDict()
    for p in d["pins"]:
        ports.setdefault(p["port"], []).append(p)
    # per face, ports in order of their first pin: a port may grow up to the next port's nominal start (or the face end)
    rows = []
    for name, pins in ports.items():
        faces = {p["face"] for p in pins}
        xs = {tuple(p["location"])[0] for p in pins}
        if len(faces) != 1 or len(xs) != 1:
            raise SystemExit(f"ft_pins_pg: port {name} spans faces {faces} / x {xs}")
        ys = [p["location"][1] for p in pins]
        if ys != sorted(ys):
            raise SystemExit(f"ft_pins_pg: port {name} bits not in ascending y")
        step = (ys[-1] - ys[0]) / (len(ys) - 1) if len(ys) > 1 else 0.24
        rows.append(dict(port=name, face=faces.pop(), x=xs.pop(), lo=ys[0], hi=ys[-1], step=round(step, 4),
                         names=[p["pin"] for p in pins], size=pins[0]["size"]))
    out = [TCL_HEAD.format(src=a.pins, variant=d["variant"], layer="M8", margin=a.margin_um,
                           half=rows[0]["size"][1] / 2, pitch=a.pitch_um, offset=a.offset_um)]
    for face in sorted({r["face"] for r in rows}):
        fr = sorted((r for r in rows if r["face"] == face), key=lambda r: r["lo"])
        for i, r in enumerate(fr):
            limit = (fr[i + 1]["lo"] - 2 * a.pitch_um) if i + 1 < len(fr) else H - 1.0
            out.append(TCL_PORT.format(port=r["port"], n=len(r["names"]), face=face, lo=r["lo"], hi=r["hi"], step=r["step"],
                                       limit=limit, names=" ".join("{" + n + "}" for n in r["names"]), layer="M8",
                                       x=f"{r['x']:.4f}", size=f"{r['size'][0]:.4f} {r['size'][1]:.4f}"))
    out.append('puts "FT_PINS_PG placed $ft_n ft pins, $ft_moved track moves off PG stripes"\n')
    open(a.out, "w").write("".join(out))
    print(a.out, len(rows), "ports", sum(len(r["names"]) for r in rows), "pins")


if __name__ == "__main__":
    main()
