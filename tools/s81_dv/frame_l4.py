#!/usr/bin/env python3
"""S81-LAND2: successor frame masters col_h9_l4 / col_h10_l4 / col_h9_MX_l4 with the column FIFO dsfd_cfifo_crs4
(rtl/dsrom_sys/s81_dv/land/dsfd_cfifo_crs4.sv: every x lane lands on ITS OWN forwarded clock xk[k], read epoch = the
frame's regional reset release; LANDING-CONTRACT L1-L7) instead of dsfd_cfifo_crs (lanes 0 / 3 on the neighbour lane's
clock, marker-sampled read epoch).

Derived TEXTUALLY from the GENERATED frame_wrap.py masters (rtl/dsrom_sys/s81_dv/frame/<m>.sv, left byte-identical):
the one dsfd_cfifo_crs instance u_cf becomes dsfd_cfifo_crs4 with .xf(xk[1]) / .xf2(xk[2]) replaced by .xk(xk) and the
new strap port .lk(lk) (lk[3k +: 3] = lane k's K, tied by the die binder); the module gains input lk[11:0] and the
suffix _l4.  Nothing else changes (asserted: one instance, both clock pins found, every other line identical).
Also emits <m>_l4_b (bench wrappers: the frame_bench port list, lk = {4{LK}} from a define) for tools/s81_dv/frame_bench.sh.

  frame_l4.py [--out-rtl rtl/dsrom_sys/s81_dv/frame_l4] [--mutant xlane]
"""
import argparse, hashlib, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/dsrom_sys/s81_dv/frame'
BASE = ('col_h9', 'col_h10')
LANE = 276


def derive(m, mutant=None):
    txt = (SRC / f'{m}.sv').read_text()
    hdr = f'module {m} #(parameter string INSTANCE = "{m}") (clk, cr, cr_s, rst_n, x, xk, xo, xok, ret);'
    assert txt.count(hdr) == 1, m
    t = txt.replace(hdr, f'module {m}_l4 #(parameter string INSTANCE = "{m}") (clk, cr, cr_s, rst_n, x, xk, lk, xo, xok, ret);')
    t = t.replace('    input wire [3:0] xk;\n', '    input wire [3:0] xk;\n    input wire [11:0] lk;\n', 1)
    i = t.index('    dsfd_cfifo_crs u_cf (')
    j = t.index(');\n', i) + 3
    inst = t[i:j]
    assert t.count('dsfd_cfifo_crs ') == 1 and '.xf(xk[1])' in inst and '.xf2(xk[2])' in inst, m
    new = inst.replace('dsfd_cfifo_crs u_cf (', 'dsfd_cfifo_crs4 u_cf (').replace('.xf(xk[1]), ', '').replace(', .xf(xk[1])', '')
    new = new.replace('.xf2(xk[2])', '.xk(xk), .lk(lk)')
    assert '.xf' not in new
    # S81-DIE7/CRS4 10-18: dsfd_cfifo_crs4 takes one port per lane (xl0..xl3 = {xd2, xd}[276k +: 276]) so each lane
    # port is owned by exactly one forwarded-clock domain xk[k] in the hardened view; same bits, same order.
    bits = {}
    for p in ('xd', 'xd2'):
        mm = re.search(r'\.' + p + r'\(\{([^}]*)\}\)', new)
        assert mm, (m, p)
        bits[p] = [b.strip() for b in mm.group(1).split(',')][::-1]          # LSB first
    xin = bits['xd'] + bits['xd2']
    assert len(bits['xd']) == 566 and len(xin) == 4 * LANE, m
    lanes = ', '.join(f'.xl{k}({{{", ".join(xin[LANE * k:LANE * (k + 1)][::-1])}}})' for k in range(4))
    new = re.sub(r'\.xd\(\{[^}]*\}\), ', '', new, count=1)
    new = re.sub(r'\.xd2\(\{[^}]*\}\)', lanes, new, count=1)
    assert '.xd' not in new and new.count('.xl') == 4, m
    if mutant == 'xlane':          # bench negative control: x lanes 1 and 2 swapped at the column FIFO entry
        def sw(mm):
            k = int(mm.group(1))
            return f'x[{k + LANE}]' if LANE <= k < 2 * LANE else (f'x[{k - LANE}]' if 2 * LANE <= k < 3 * LANE else mm.group(0))
        new = re.sub(r'x\[(\d+)\]', sw, new)
    t = t[:i] + new + t[j:]
    t = t.replace('// GENERATED by tools/s81_dv/frame_wrap.py -- do not edit.',
                  '// GENERATED by tools/s81_dv/frame_l4.py from the frame_wrap.py master (cfifo -> dsfd_cfifo_crs4) -- do not edit.', 1)
    return t


def bench_wrap(m):
    return f'''// GENERATED by tools/s81_dv/frame_l4.py: frame_bench wrapper of {m}_l4 (frame_bench port list; lk = {{4{{LK}}}}).
`timescale 1ns/1ps
`default_nettype none
`ifndef LK
`define LK 2
`endif
module {m}_l4_b #(parameter string INSTANCE = "{m}") (input wire clk, input wire cr, input wire cr_s, input wire rst_n,
    input wire [1103:0] x, input wire [3:0] xk, output wire [1103:0] xo, output wire [3:0] xok, output wire [69:0] ret);
    {m}_l4 #(.INSTANCE(INSTANCE)) u_f (.clk(clk), .cr(cr), .cr_s(cr_s), .rst_n(rst_n), .x(x), .xk(xk), .lk({{4{{3'd`LK}}}}),
        .xo(xo), .xok(xok), .ret(ret));
endmodule
`default_nettype wire
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out-rtl', type=Path, default=ROOT / 'rtl/dsrom_sys/s81_dv/frame_l4')
    ap.add_argument('--mutant', choices=('xlane',))
    a = ap.parse_args()
    a.out_rtl.mkdir(parents=True, exist_ok=True)
    rec = {}
    for m in BASE:
        (a.out_rtl / f'{m}_l4.sv').write_text(derive(m, a.mutant))
        (a.out_rtl / f'{m}_l4_b.sv').write_text(bench_wrap(m))
    mx = (SRC / 'col_h9_MX.sv').read_text()
    mx = mx.replace('module col_h9_MX #(parameter string INSTANCE = "col_h9_MX") (clk, cr, cr_s, rst_n, x, xk, xo, xok, ret);',
                    'module col_h9_MX_l4 #(parameter string INSTANCE = "col_h9_MX") (clk, cr, cr_s, rst_n, x, xk, lk, xo, xok, ret);')
    mx = mx.replace('    input wire [3:0] xk;\n', '    input wire [3:0] xk;\n    input wire [11:0] lk;\n', 1)
    mx = mx.replace('col_h9 #(.INSTANCE(INSTANCE)) u_f (', 'col_h9_l4 #(.INSTANCE(INSTANCE)) u_f (').replace('.xk(xk), ', '.xk(xk), .lk(lk), ')
    assert 'col_h9_MX_l4' in mx and 'col_h9_l4 #' in mx and '.lk(lk)' in mx
    (a.out_rtl / 'col_h9_MX_l4.sv').write_text(mx)
    (a.out_rtl / 'col_h9_MX_l4_b.sv').write_text(bench_wrap('col_h9_MX'))   # LANDFIX-SQ/F: MX bench wrapper
    for f in sorted(a.out_rtl.glob('*.sv')):
        rec[f.name] = hashlib.sha256(f.read_bytes()).hexdigest()
    src = {f'{m}.sv': hashlib.sha256((SRC / f'{m}.sv').read_bytes()).hexdigest() for m in BASE + ('col_h9_MX',)}
    if not a.mutant:
        (a.out_rtl / 'frame_l4.json').write_text(json.dumps(dict(schema='opentallas.s81_land.frame_l4.v1', sources=src, emitted=rec,
                                                                 cfifo='rtl/dsrom_sys/s81_dv/land/dsfd_cfifo_crs4.sv'), indent=1) + '\n')
    print(json.dumps(rec, indent=1))


if __name__ == '__main__':
    main()
