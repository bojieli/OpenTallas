#!/usr/bin/env python3
"""Emit exact period96 option-M map, constant payload with no ECC sidecar."""
from pathlib import Path

def generate():
    rows=['// Generated by tools/gen_qwen_kvc_map_lut.py; key={stack[1:0],j_mod96[6:0]}.',
          'module ot_qwen_kvc_map_lut(input wire [8:0] key,output reg [8:0] value);',
          ' always @* begin case (key)']
    for stack in range(4):
        index=0
        for residue in range(48):
            owner=residue//8 if residue<32 else (residue-32)//4
            slots=list(range(4)) if owner==stack else []
            for phase in slots+[4]:
                word=((phase==4)<<8)|((stack if phase==4 else phase)<<6)|residue
                rows.append(f"  9'd{stack*128+index}: value=9'h{word:03x};")
                index+=1
        assert index==96
    rows+=['  default: value=0;', ' endcase end', 'endmodule', '']
    return '\n'.join(rows)
if __name__=='__main__':
    target=Path(__file__).resolve().parents[1]/'rtl/physical/ot_qwen_kvc_map_lut.sv'
    target.write_text(generate())
