#!/bin/bash
# Regenerate the swept Qwen P8191 exactness fixtures, verify them against the committed oracle digests, publish them
# durably (KEEP STATUS.md in every dir) to ot-epyc1tb and ot-epyc2, then relaunch the benches they block.
# Runs on the control host (the local GPU runs the golden).  Detached; no polling by any agent.
#
#   SRC=<pinned source export> regen_fixtures.sh [all|tp4|tp2_l3|tp2]
#
# Fixtures (F on each bench host):
#   F/gold/tp4/P8191      TP4 36-layer + head golden  -> Qwen ROM token (layer X, current KV, head) [gold_tp4/oracle.json]
#   F/history/            KV history = tp4 kv_pre as u32 (published qwen-P8191-full36-history-r1/history)
#   F/gold/tp2_l3/P8191   TP2 3-layer golden          -> HBM-Qwen L0 bench                          [gold_tp2/oracle_l3.json]
#   F/gold/tp2/P8191      TP2 36-layer + head golden  -> HBM-Qwen head bench                        [gold_tp2/oracle.json]
#   F/hbmq_runs/...       HBM-Qwen stage fixtures (stages.txt, preload.hex) from qwen_hbmacc_layer_parallel.py --plan
# Generator: tools/qwen_hbmacc_position_oracle_gpu.py (--prep on EPYC1 where the W12 images live, --run on the GPU),
# exactly the README replay of results/rtl/qwen_hbmacc_p8191_20261004.
set -u -o pipefail
SRC=${SRC:-$(cd "$(dirname "$0")/../.." && pwd)}
COMMIT=${COMMIT:-$(cat "$SRC/SOURCE_COMMIT" 2>/dev/null || echo unknown)}
L=${L:-/home/ubuntu/exactness-fixtures/qwen_p8191}
F=/srv/opentallas-scratch/claude/exactness/fixtures/qwen_p8191
FX=/srv/opentallas-scratch/claude/exactness/fixtures
W=/srv/opentallas/scratch-overflow/claude/hbm-accel-qwen-token
GEN=ot-epyc1tb
HOSTS="ot-epyc1tb ot-epyc2"
FLOG=/home/ubuntu/claude-takeover-20261007/fixtures.log
REF=$SRC/results/rtl/qwen_hbmacc_p8191_20261004
TOK=$L/inputs/prompt_tokens_8192.txt
EMB=$L/inputs/prompt_embedding.npz
PY=/usr/bin/python3
mkdir -p "$L"/{inputs,prep,gold,logs}
now() { TZ=America/Los_Angeles date '+%F %H:%M PT'; }
log() { echo "$(now) $*" >> "$L/regen.log"; }
flog() { log "$*"; echo "$(now) [regen_fixtures $COMMIT] $*" >> "$FLOG"; }
die() { flog "FAIL $*"; exit 1; }
envtp() { echo "QWEN_O4_TP=$1 QWEN_O4_GROUPS=6144 HDC_SU_WIDTH=1024 HDC_KV_FMT=fp8"; }
NOTE="Qwen3-8B P8191 exactness fixtures regenerated by tools/exactness/regen_fixtures.sh (source $COMMIT) after the
fleet sweeper deleted the originals on 2026-10-07; every file verified against the committed oracle digests
(verify*.json). Used by tools/exactness benches qwen_rom_*, hbm_qwen_* and the Qwen split/partition token benches."

stage_src() {   # generator + verifier source on the bench hosts (tools only; pinned export)
  for h in $HOSTS; do
    tar -C "$SRC" -c tools results/rtl/qwen_hbmacc_p8191_20261004 results/rtl/qwen_rom_combined_p0_20261005/linked_expected \
      | ssh "$h" "rm -rf $F/gen-src.part && mkdir -p $F/gen-src.part && tar -x -C $F/gen-src.part && rm -rf $F/gen-src && mv $F/gen-src.part $F/gen-src && echo $COMMIT > $F/gen-src/SOURCE_COMMIT" \
      || die "stage gen-src on $h"
  done
}

inputs() {
  cp -n /home/ubuntu/realmem-ctx8k/prompt_tokens_8192.txt "$TOK"
  cp -n /home/ubuntu/qwen-dspark-oracle-run/ref/realmem_gold/prompt_embedding.npz "$EMB"
  local t e
  t=$(python3 -c "import json;print(json.load(open('$REF/gold_tp4/oracle.json'))['tokens_sha256'])")
  e=$(python3 -c "import json;print(json.load(open('$REF/gold_tp4/oracle.json'))['embedding_npz_sha256'])")
  [ "$(sha256sum < "$TOK" | cut -c1-64)" = "$t" ] || die "prompt tokens sha != committed $t"
  [ "$(sha256sum < "$EMB" | cut -c1-64)" = "$e" ] || die "prompt embedding sha != committed $e"
  log "inputs pinned (tokens $t, embedding $e)"
}

prep() {   # $1 = 2|4 ; decode the pinned W12 stage images on EPYC1 (no torch), pull the npz to the GPU host
  local tp=$1 st img pins
  if [ "$tp" = 2 ]; then st=st6144_sw64; img=img6144; pins=$W/gold/oracle6144/oracle.json
  else st=st_tp4_sw64; img=img_tp4; pins=$W/w12/oracle_tp4/oracle.json; fi
  if [ ! -f "$L/prep/tp$tp/prep.json" ]; then
    ssh $GEN "mkdir -p $F/pins && cp $pins $F/pins/tp$tp.json && cd $F/gen-src && \
      /srv/opentallas-scratch/admit.sh 48 -- env $(envtp $tp) $PY tools/qwen_hbmacc_position_oracle_gpu.py --prep \
      --stages /home/ubuntu/w12/$st/stages.txt --pins $F/pins/tp$tp.json \
      --layout-manifest '/home/ubuntu/w12/$img/L0-d{die}/layer0_rom.json' \
      --head-manifest '/home/ubuntu/w12/$img/head-d{die}/head_rom.json' --out $F/prep/tp$tp --procs 32" \
      > "$L/logs/prep_tp$tp.log" 2>&1 || die "prep tp$tp (see $L/logs/prep_tp$tp.log)"
    rsync -a "$GEN:$F/prep/tp$tp/" "$L/prep/tp$tp/" || die "pull prep tp$tp"
  fi
  log "prep tp$tp ready"
}

gpu() {   # $1 name $2 tp $3 layers $4 head-flag ; ISA golden on the local GPU (retry CUDA-init exit 75 like gpurun.sh)
  local name=$1 tp=$2 nl=$3 hd=$4 out=$L/gold/$1 rc=75 i
  if [ -f "$out/gpu.done" ]; then return 0; fi
  for i in $(seq 1 20); do
    env $(envtp $tp) OMP_NUM_THREADS=4 $PY "$SRC/tools/qwen_hbmacc_position_oracle_gpu.py" --run --prep-dir "$L/prep/tp$tp" \
      --layers $nl $hd --tokens "$TOK" --positions 8191 --embedding-npz "$EMB" --out "$out" > "$L/logs/gpu_$name.log" 2>&1
    rc=$?; [ $rc = 75 ] || break; sleep 5
  done
  [ $rc = 0 ] || die "GPU golden $name rc=$rc (see $L/logs/gpu_$name.log)"
  touch "$out/gpu.done"; log "GPU golden $name done"
}

verify_local() {   # $1 name $2 committed ref
  $PY "$SRC/tools/exactness/fixtures.py" verify --gold "$L/gold/$1" --ref "$2" --out "$L/gold/$1/verify.local.json" \
    >> "$L/regen.log" 2>&1 || die "$1 does NOT match the committed digests ($2); see $L/gold/$1/verify.local.json -- NOT published"
}

publish() {   # $1 = relative path under L (gold/<name> or history) ; $2 = committed ref for remote re-verify (or "")
  local rel=$1 ref=${2:-} h
  for h in $HOSTS; do
    ssh "$h" "mkdir -p $F/$rel" && rsync -a "$L/$rel/" "$h:$F/$rel/" || die "rsync $rel -> $h"
    if [ -n "$ref" ]; then
      ssh "$h" "cd $F/gen-src && $PY tools/exactness/fixtures.py verify --gold $F/$rel --ref $F/gen-src/${ref#$SRC/} --out $F/$rel/verify.$h.json" \
        >> "$L/regen.log" 2>&1 || die "remote verify $rel on $h"
    fi
    ssh "$h" "cd $F/gen-src && $PY tools/exactness/fixtures.py keep --root $F --note '$NOTE' && \
      for d in $FX $FX/build; do [ -d \$d ] && [ ! -f \$d/STATUS.md ] && printf '# KEEP -- exactness fixtures (do not sweep)\nSee $F/STATUS.md and tools/exactness/benches.json.\n' > \$d/STATUS.md; done; \
      [ -d $FX/hbm_ds_joint ] && $PY tools/exactness/fixtures.py keep --root $FX/hbm_ds_joint --note 'HBM-DS SM PQ/XMAP P1+P6 fixtures (sha-equal to results/rtl/dshbm_hbm_opt_20261005/joint_r2/retained_layouts.json)'" \
      >> "$L/regen.log" 2>&1 || die "keep markers on $h"
  done
  log "published $rel to $HOSTS"
}

compat() {   # old absolute paths used by staged source snapshots -> the durable tree (only replace links / absent paths)
  local h
  for h in $HOSTS; do
    ssh "$h" "set -e; S=/srv/opentallas-scratch
      p=\$S/codex/qwen-P8191-full36-history-r1; if [ -L \$p ] || [ ! -e \$p ]; then ln -sfn $F \$p; fi
      mkdir -p \$S/claude/qwen-hbmacc-8k
      for n in gold:gold runs:hbmq_runs; do p=\$S/claude/qwen-hbmacc-8k/\${n%%:*}; if [ -L \$p ] || [ ! -e \$p ]; then ln -sfn $F/\${n#*:} \$p; fi; done
      ls -la \$S/codex/qwen-P8191-full36-history-r1 \$S/claude/qwen-hbmacc-8k/" >> "$L/regen.log" 2>&1 || die "compat links on $h"
  done
}

hbmq_plan() {   # $1 plan subdir $2 gold name $3 stage ; stage fixtures for the HBM-Qwen bench
  ssh $GEN "cd $F/gen-src && $PY tools/qwen_hbmacc_layer_parallel.py --plan --plan-dir $F/hbmq_runs/$1 \
    --stages /home/ubuntu/w12/st6144_sw64/stages.txt --oracle-dir $F/gold/$2/P8191 \
    --layout /home/ubuntu/w12/img6144/L0-d0/layer0_rom.json --build-dir unused --pos 8191 --token 24 --only $3" \
    >> "$L/regen.log" 2>&1 || die "plan $1/$3"
  rsync -a "$GEN:$F/hbmq_runs/" "$L/hbmq_runs/" && publish hbmq_runs ""
}

launch_bench() {   # exactness harness bench on THIS source (its tools/exactness), commit = the pinned source commit
  (cd "$SRC" && $PY tools/exactness/regress.py launch --ref "$COMMIT" --bench "$@" --label fixtures-regen) \
    >> "$L/regen.log" 2>&1 && flog "LAUNCHED exactness $* on $COMMIT (collect: tools/exactness/regress.py collect)" \
    || flog "FAIL launching exactness $*"
}

relaunch_qwen_split() {   # qwen-split-exact d58eb1634 (base/s0/s22/s13/s22neg L0, s22 full) + qwen-rtl-finish 4b111850a
  local O=/srv/opentallas-scratch/claude/qwen-split-exact/runs/d58eb1634
  ssh $GEN "cat > $O/rerun_fixtures.sh" <<EOF
#!/bin/bash
# rerun on the existing builds after the KV-history / gold regeneration (tools/exactness/regen_fixtures.sh)
set -u
S=/srv/opentallas-scratch/claude/qwen-split-exact/src-d58eb1634; O=$O
cd \$S
echo "fixtures rerun \$(date '+%F %T')" >> \$O/STATUS
run() {
  local n=\$1
  /srv/opentallas-scratch/admit.sh 25 -- python3 tools/qwen_missing/partition_token.py run --build \$O/build_\$n --work \$O/L0fx_\$n --stages L0 --threads 16 --max-cycles 40000 > \$O/L0fx_\$n.log 2>&1
  local rc=\$?; echo "\$n L0 (fixtures rerun) rc=\$rc \$(grep -o '"exact": [a-z]*' \$O/L0fx_\$n/*.json 2>/dev/null | head -1)" >> \$O/STATUS
  if [ "\$n" = s22 ] && [ \$rc = 0 ]; then
    /srv/opentallas-scratch/admit.sh 25 -- python3 tools/qwen_missing/partition_token.py run --build \$O/build_\$n --work \$O/fullfx_\$n --stages full --threads 16 > \$O/fullfx_\$n.log 2>&1
    echo "\$n full (fixtures rerun) rc=\$? \$(grep -o '"exact": [a-z]*' \$O/fullfx_\$n/*.json 2>/dev/null | head -1)" >> \$O/STATUS
  fi
}
for n in base s0 s22 s13 s22neg; do run \$n & done
wait; echo "fixtures rerun done" >> \$O/STATUS
EOF
  ssh $GEN "chmod +x $O/rerun_fixtures.sh && setsid -f nohup $O/rerun_fixtures.sh > $O/rerun_fixtures.nohup 2>&1 < /dev/null" \
    && flog "LAUNCHED qwen-split-exact rerun (EPYC1 $O/rerun_fixtures.sh: L0fx_{base,s0,s22,s13,s22neg}, fullfx_s22; STATUS)" \
    || flog "FAIL launching qwen-split-exact rerun"
  local R=/srv/opentallas-scratch/claude/qwen-rtl-finish/runs/4b111850a
  ssh $GEN "cd $R && setsid -f nohup bash $R/rerun.sh 4b111850a > $R/rerun.log 2>&1 < /dev/null" \
    && flog "LAUNCHED qwen-rtl-finish rerun (EPYC1 $R/rerun.sh 4b111850a: L0_s22ml4, L0_s0ml4; STATUS)" \
    || flog "FAIL launching qwen-rtl-finish rerun"
}

chain_tp4() {
  prep 4; gpu tp4 4 36 --head; verify_local tp4 "$REF/gold_tp4/oracle.json"
  $PY "$SRC/tools/exactness/fixtures.py" history --gold "$L/gold/tp4/P8191" --out "$L/history" >> "$L/regen.log" 2>&1 \
    || die "KV history L0 die0 != committed pin"
  publish gold/tp4 "$REF/gold_tp4/oracle.json"; publish history ""; compat
  flog "OK tp4 gold + KV history verified vs committed digests, published to $HOSTS:$F"
  relaunch_qwen_split
}
chain_tp2_l3() {
  prep 2; gpu tp2_l3 2 3 ""; verify_local tp2_l3 "$REF/gold_tp2/oracle_l3.json"
  publish gold/tp2_l3 "$REF/gold_tp2/oracle_l3.json"; compat; hbmq_plan a_p8191 tp2_l3 L0
  flog "OK tp2_l3 gold verified, published; HBM-Qwen L0 fixtures staged"
  launch_bench hbm_qwen_L0
}
chain_tp2() {
  prep 2
  while [ ! -f "$L/gold/tp2_l3/gpu.done" ]; do sleep 120; done      # one TP2 job at a time behind the short one
  while pgrep -f "prep-dir $L/prep/tp4" > /dev/null && \
        [ "$(nvidia-smi --query-gpu=memory.free --format=csv,noheader,nounits | head -1)" -lt 45000 ]; do sleep 300; done
  gpu tp2 2 36 --head; verify_local tp2 "$REF/gold_tp2/oracle.json"
  publish gold/tp2 "$REF/gold_tp2/oracle.json"; compat; hbmq_plan a_p8191_w224_head tp2 head
  flog "OK tp2 gold verified, published; HBM-Qwen head fixtures staged"
  launch_bench hbm_qwen_head
}

what=${1:-all}
flog "start ($what) local=$L remote=$F hosts=$HOSTS"
inputs; stage_src
case $what in
  tp4) chain_tp4 ;;
  tp2_l3) chain_tp2_l3 ;;
  tp2) chain_tp2 ;;
  all) prep 2 & prep 4 & wait
       chain_tp4 & sleep 60; chain_tp2_l3 & chain_tp2 & wait
       flog "DONE all chains (see $L/regen.log)" ;;
esac
