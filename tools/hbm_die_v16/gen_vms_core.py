#!/usr/bin/env python3
"""H-NETLIST 1940 (d4f / A2P TP-192: only the SM side halves; H-DIE option (a)): VM hub masters for the quadrants whose
SM side is absent (SE, NE).  hfd_hgi_vms_static_<Q>_core = hfd_hgi_vms_static_<Q> with the SM-side client slots
ABSENT: no HBM fill port dq / dq_done (vmdel lanes), read groups 1 (DMA-back) and 2 (x-load) and write group 1 (SM
write) removed from rq / rr / wq / wq_done.  The present groups keep their slice group numbers (lg = 0, coll = 3), so the
compiler calendar is unchanged and never schedules the absent slots; their slice inputs are module-internal constants
(no die port tied, no port open).  These hubs fill over the VM ring and the core engines only.  Kept local (one file) so
option (b) (cross-quadrant fill) can replace it.  Writes rtl/hbm_accel/generic/vm/static/hfd_hgi_vms_static_core.sv;
--check verifies the committed file.
"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/hbm_accel/generic/vm/static/hfd_hgi_vms_static.sv'
OUT = ROOT / 'rtl/hbm_accel/generic/vm/static/hfd_hgi_vms_static_core.sv'
RG, KEEP_R, WG, KEEP_W = 4, (0, 3), 2, (0,)


def core(q, txt):
    m = re.search(rf'module hfd_hgi_vms_static_{q} .*?\nendmodule\n', txt, re.S)
    s = m.group(0)
    assert f'.RG({RG}),.WG({WG})' in s, q
    def sub(a, b):
        nonlocal s
        assert s.count(a) == 1, (q, a); s = s.replace(a, b)
    sub(f'module hfd_hgi_vms_static_{q} #', f'module hfd_hgi_vms_static_{q}_core #')
    sub(f'    input wire [{RG*136-1}:0] rq,\n', f'    input wire [{len(KEEP_R)*136-1}:0] rq,      // read groups {KEEP_R} (lg, coll)\n')
    sub(f'    output wire [{RG*2056-1}:0] rr,\n', f'    output wire [{len(KEEP_R)*2056-1}:0] rr,\n')
    sub(f'    input wire [{WG*2248-1}:0] wq,\n', f'    input wire [{len(KEEP_W)*2248-1}:0] wq,     // write group 0 (lg)\n')
    sub(f'    output wire [{WG*8-1}:0] wq_done,\n', f'    output wire [{len(KEEP_W)*8-1}:0] wq_done,\n')
    sub('    input wire [2247:0] dq,\n', '')
    sub('    output wire [7:0] dq_done,\n', '')
    body = ['    // SM-side client slots absent (no SM side in this quadrant): internal constants, never scheduled',
            f'    wire [{RG*136-1}:0] rq_s; wire [{RG*2056-1}:0] rr_s; wire [{WG*2248-1}:0] wq_s; wire [{WG*8-1}:0] wqd_s; wire [7:0] dqd_s;']
    rq = []; rr = []
    for g in range(RG - 1, -1, -1):
        rq.append(f'rq[{KEEP_R.index(g)*136} +: 136]' if g in KEEP_R else "136'd0")
    for k, g in enumerate(KEEP_R):
        rr.append(f'    assign rr[{k*2056} +: 2056] = rr_s[{g*2056} +: 2056];')
    wq = [f'wq[{KEEP_W.index(g)*2248} +: 2248]' if g in KEEP_W else "2248'd0" for g in range(WG - 1, -1, -1)]
    body += [f'    assign rq_s = {{{", ".join(rq)}}};', *rr, f'    assign wq_s = {{{", ".join(wq)}}};']
    body += [f'    assign wq_done[{k*8} +: 8] = wqd_s[{g*8} +: 8];' for k, g in enumerate(KEEP_W)]
    sub('    ot_vms_slice_static #', '\n'.join(body) + '\n    ot_vms_slice_static #')
    sub('        .rq(rq),\n', '        .rq(rq_s),\n'); sub('        .rr(rr),\n', '        .rr(rr_s),\n')
    sub('        .wq(wq),\n', '        .wq(wq_s),\n'); sub('        .wq_done(wq_done),\n', '        .wq_done(wqd_s),\n')
    sub('        .dq(dq),\n', "        .dq(2248'd0),\n"); sub('        .dq_done(dq_done),\n', '        .dq_done(dqd_s),\n')
    return s


def main():
    txt = SRC.read_text()
    out = ('`timescale 1ns/1ps\n`default_nettype none\n// GENERATED by tools/hbm_die_v16/gen_vms_core.py (do not edit).\n'
           + '\n'.join('// ' + l if l else '//' for l in __doc__.strip().splitlines()) + '\n'
           + ''.join(core(q, txt) for q in ('SE', 'NE')) + '`default_nettype wire\n')
    if '--check' in sys.argv:
        ok = OUT.read_text() == out; print('VMS_CORE_GEN', 'CHECK_PASS' if ok else 'CHECK_FAIL'); sys.exit(0 if ok else 1)
    OUT.write_text(out); print('VMS_CORE_GEN WROTE', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
