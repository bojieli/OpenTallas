#!/usr/bin/env python3
"""SMFRAME (HANDOFF 0gd 10-18): carry the taller SM frame of the d4g plan into grants_d4g.json, gen1_bindings_plan.json
and the d4g clock region map.

The plan is regenerated by plan_d4g.py --sm-dh DH (the SM column slot grows DH in y; the S-half SM row keeps its PHY
edge, everything inward of it moves +DH, the N half moves +2DH at its PHY edge).  grants_d4g.json carries
hand-applied d4g edits after its generator (H-D4G2 SFU store re-plan, d4g.gen1), so it is TRANSFORMED, not
regenerated: every die-level slot moves with the d4g plan block under its centre in the OLD plan (smallest block
containing the centre; the slot keeps its offset to that block's moved origin); a slot inside an SM column (or under
no block) takes the piecewise die map (S SM-row lower half 0, middle +DH, N SM-row upper half +2DH).  SM column slots
(sm_<st><i>) grow DH.  Children (parent != die) are parent-relative and unchanged.  Overlaps among die slots are
checked before / after (no new overlap allowed).  The region map is rebuilt by grants_d4g.py --regions-only.

    d4g_sm_frame.py --old-plan OLD/compact.P.json --dh 276.48 [--write]
"""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NEW_PLAN = ROOT / 'results/arch/hbm_die_d4g/plan/d4g_phy/compact.P.json'
GRANTS = ROOT / 'results/arch/hbm_die_d4g/grants_d4g.json'
BIND = ROOT / 'results/arch/hbm_die_d4g/gen1_bindings_plan.json'


def inside(r, x, y):
    return r['x'] <= x <= r['x'] + r['w'] and r['y'] <= y <= r['y'] + r['h']


def mapper(P0, P1, H0, dh):
    sms = P0['sm_SW0'], P0['sm_NW0']
    s_mid, n_mid = sms[0]['y'] + sms[0]['h'] / 2, sms[1]['y'] + sms[1]['h'] / 2
    assert abs(s_mid + n_mid - H0) < 1.0, (s_mid, n_mid, H0)

    def piecewise(cy):
        return 0.0 if cy < s_mid else (2 * dh if cy > n_mid else dh)

    def dy(x, y, w, h):
        cx, cy = x + w / 2, y + h / 2
        hs = [b for b, r in P0.items() if inside(r, cx, cy)]
        if hs:
            b = min(hs, key=lambda b: P0[b]['w'] * P0[b]['h'])
            if not b.startswith('sm_'):
                assert abs(P1[b]['h'] - P0[b]['h']) < 1e-6 and abs(P1[b]['x'] - P0[b]['x']) < 1e-6, b
                return P1[b]['y'] - P0[b]['y'], b
        return piecewise(cy), 'piecewise'
    return dy


def overlaps(slots):
    rs = []
    for s in slots:
        w, h = s['outline']['w'], s['outline']['h']
        if s['origin'].get('orient', 'R0') in ('R90', 'R270'):
            w, h = h, w
        rs.append((s['name'], s['origin']['x'], s['origin']['y'], w, h))
    out = set()
    for i, a in enumerate(rs):
        for b in rs[i + 1:]:
            if a[1] < b[1] + b[3] - 1e-3 and b[1] < a[1] + a[3] - 1e-3 and a[2] < b[2] + b[4] - 1e-3 and b[2] < a[2] + a[4] - 1e-3:
                out.add(tuple(sorted((a[0], b[0]))))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--old-plan', required=True); ap.add_argument('--dh', type=float, required=True)
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    P0 = json.loads(Path(a.old_plan).read_text()); P1 = json.loads(NEW_PLAN.read_text())
    G = json.loads(GRANTS.read_text())
    die = next(s for s in G['slots'] if s['kind'] == 'die')
    H0 = die['outline']['h']
    H1 = json.loads((NEW_PLAN.parent / 'compact.metrics.json').read_text())['die_um'][1]
    assert abs(H1 - H0 - 2 * a.dh) < 0.01, (H0, H1, a.dh)
    dy = mapper(P0, P1, H0, a.dh)
    slots = [s for s in G['slots'] if s.get('parent') == 'die']
    ov0 = overlaps(slots)
    rep = dict(dh_um=a.dh, die_h_um=[H0, H1], moved={}, by_rule={})
    moves = {}
    for s in slots:
        o, wh = s['origin'], s['outline']
        if s['name'] in P0 and s['name'].startswith('sm_'):      # the SM column itself: its own plan block delta
            d, why = round(P1[s['name']]['y'] - P0[s['name']]['y'], 3), s['name']
        else:
            d, why = dy(o['x'], o['y'], wh['w'], wh['h'])
        moves[s['name']] = d
        if s['name'].startswith('sm_') and s['kind'] == 'cluster':
            wh['h'] = round(wh['h'] + a.dh, 3)
            s['notes'] = (s.get('notes', '') + f' | SMFRAME 10-18 (HANDOFF 0gd): SM column +{a.dh:g} um (4 rp4 tile rows 1529.28 -> 1598.4, 43.2 lattice)').lstrip(' |')
        if d:
            o['y'] = round(o['y'] + d, 3)
        rep['by_rule'][f'{why if why == "piecewise" else "host"} +{d:g}'] = rep['by_rule'].get(f'{why if why == "piecewise" else "host"} +{d:g}', 0) + 1
    ov1 = overlaps(slots)
    rep['overlaps_before'] = len(ov0); rep['overlaps_after'] = len(ov1); rep['new_overlaps'] = sorted(map(list, ov1 - ov0))
    outside = [s['name'] for s in slots if s['origin']['y'] < 0 or s['origin']['y'] + s['outline']['h'] > H1 + 1e-3]
    rep['outside'] = outside
    die['outline']['h'] = H1
    G['floorplan']['die_um'] = [die['outline']['w'], H1]
    G['floorplan']['smframe'] = f'SMFRAME 10-18 (HANDOFF 0gd): SM column slot +{a.dh:g} um in y, die {H0} -> {H1} um (d4g_sm_frame.py)'
    G['version'] = 'd4g.2'; G['updated'] = '2026-10-18'
    # gen1 binding plan: slot origins recorded there follow the same slots
    B = json.loads(BIND.read_text())
    nb = 0

    def walk(x):
        nonlocal nb
        if isinstance(x, dict):
            n = x.get('slot') or x.get('name') or x.get('inst')
            for k, v in x.items():
                if k in ('new', 'origin', 'new_origin') and isinstance(v, dict) and 'y' in v and n in moves and moves[n]:
                    v['y'] = round(v['y'] + moves[n], 3); nb += 1
                else:
                    walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
    walk(B)
    if isinstance(G.get('d4g', {}).get('gen1'), dict):
        walk(G['d4g']['gen1'])                     # the same plan, copied into the grants (H-D4G2)
    rep['bindings_plan_origins_moved'] = nb
    print(json.dumps({k: v for k, v in rep.items() if k != 'moved'}, indent=1))
    if rep['new_overlaps'] or outside:
        raise SystemExit('new overlaps / outside slots: not written')
    if a.write:
        GRANTS.write_text(json.dumps(G, indent=1) + '\n')
        BIND.write_text(json.dumps(B, indent=1) + '\n')
        (ROOT / 'results/arch/hbm_die_d4g/smframe_report.json').write_text(json.dumps(rep, indent=1) + '\n')


if __name__ == '__main__':
    main()
