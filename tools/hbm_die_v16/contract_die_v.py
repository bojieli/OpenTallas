#!/usr/bin/env python3
"""H-DIE-R8b 2026-10-17: write the die top netlist (die.v, top hbm_v16_die) FROM a final d4f source contract.

Same emitter rules as tools/hbm_die_v15/full_die_v16.py emit_die(): every output port gets a wire <inst>__<port>
(die pins keep their pin name), every input bit is driven by exactly one of: an edge (contract 'edges'), a domain
clock / release of hb_ckgen (contract 'clock_resets', one net replicated), a strap constant (contract 'straps',
identity and PAD), or a die pin (contract 'die_pins').  Undriven input bits are left on nc__<inst>__<port> (a listed
gap, never tied).  Post-layers that remap instances (folds, master swaps with split ports) then only have to edit the
contract: the netlist follows from it, so contract and die.v cannot drift apart.

Check mode compares the emitted text with an existing die.v (whitespace-normalised, per instance block):
    contract_die_v.py emit CONTRACT.json[.gz] OUT_die.v
    contract_die_v.py check CONTRACT.json[.gz] die.v
"""
import gzip
import json
import re
import sys

TOP = 'hbm_v16_die'
CK = 'hb_ckgen'


def ld(p):
    return json.load(gzip.open(p, 'rt') if p.endswith('.gz') else open(p))


def vparam(v):
    """contract param value -> Verilog.  A LIST is a per-element vector packed 8 bits per element, element 0 at the
    LSB (HBM-BANKLAT-XL 10-19: ot_hgi_sm_xload_cl2_ctlx RD_LAT [l0..l7] -> {8'd l7, ..., 8'd l0} = RD_LAT[8b +: 8])."""
    if isinstance(v, bool):
        return str(int(v))
    if isinstance(v, (list, tuple)):
        assert v and all(isinstance(x, int) and 0 <= x < 256 for x in v), f'list param needs 8-bit ints: {v}'
        return '{' + ', '.join(f"8'd{int(x)}" for x in reversed(v)) + '}'
    return str(v)


def drivers(c):
    I = c['instances']
    drv = {}
    bad = []

    def put(key, val, why):
        if key in drv and drv[key] != val:
            bad.append(f'{why}: {key} already driven by {drv[key]} (new {val})')
            return
        drv[key] = val
    for e in c['edges']:
        si, sp, slo, shi = e['source'][:4]
        di, dp, dlo, dhi = e['sink'][:4]
        if shi - slo != dhi - dlo:
            bad.append(f"edge {e['name']}: width {shi - slo} vs {dhi - dlo}")
            continue
        for k in range(shi - slo):
            put((di, dp, dlo + k), (si, sp, slo + k), f"edge {e['name']}")
    for x in c['clock_resets']:
        i, p = x['instance'], x['port']
        net = f"{x['source'][0]}__{x['source'][1]}"     # hb_ckgen domain net, or a reset-tree output (refcfg pc_rst_n)
        for b in range(x['bits']):
            put((i, p, b), ('CKNET', net, 0), f'clock {i}.{p}')
    for st in c.get('straps', []):
        i, p = st['inst'], st['port']
        lo, hi = st.get('lo', 0), st.get('hi', I[i]['ports'][p]['bits'])
        for b in range(lo, hi):
            put((i, p, b), ('CONST', (int(st['value']) >> (b - lo)) & 1, 0), f'strap {i}.{p}')
    for x in c.get('die_pins', []):
        if x['direction'] == 'input':
            for b in range(x['bits']):
                put((x['instance'], x['port'], b), ('PIN', x['name'], b), f"pin {x['name']}")
    return drv, bad


def emit(c):
    I = c['instances']
    pins = c.get('die_pins', [])
    pinset = {(x['instance'], x['port']) for x in pins}
    drv, bad = drivers(c)
    L = ['// generated by tools/hbm_die_v16/contract_die_v.py from the final d4f source contract (instances + wires only)',
         '`default_nettype none', f"module {TOP} ({', '.join(x['name'] for x in pins)});"]
    for x in pins:
        L.append(f"  {x['direction']} wire [{x['bits'] - 1}:0] {x['name']};")
    for i, inst in I.items():
        for p, d in inst['ports'].items():
            if d['direction'] == 'output' and (i, p) not in pinset:
                L.append(f"  wire [{d['bits'] - 1}:0] {i}__{p};")
    partial, body = [], []
    for i, inst in I.items():
        conns = []
        for p, d in inst['ports'].items():
            if d['direction'] == 'output':
                conns.append(f'.{p}({i}__{p})' if (i, p) not in pinset else f'.{p}({i}__{p})')
                continue
            bits = [drv.get((i, p, b)) for b in range(d['bits'])]
            if all(b is None for b in bits):
                continue
            parts = []
            b = d['bits'] - 1
            while b >= 0:
                s = bits[b]
                if s is None:
                    e = b
                    while e - 1 >= 0 and bits[e - 1] is None:
                        e -= 1
                    nm = f'nc__{i}__{p}'
                    partial.append((nm, d['bits']))
                    parts.append(f'{nm}[{b}:{e}]'); b = e - 1; continue
                if s[0] == 'CONST':
                    e = b
                    while e - 1 >= 0 and bits[e - 1] is not None and bits[e - 1][0] == 'CONST':
                        e -= 1
                    val = sum(bits[k][1] << (k - e) for k in range(e, b + 1))
                    parts.append(f"{b - e + 1}'d{val}"); b = e - 1; continue
                net = s[1] if s[0] in ('PIN', 'CKNET') else f'{s[0]}__{s[1]}'
                if s[0] == 'CKNET':
                    e2 = b
                    while e2 - 1 >= 0 and bits[e2 - 1] == s:
                        e2 -= 1
                    n_ = b - e2 + 1
                    parts.append(f'{{{n_}{{{net}[0]}}}}' if n_ > 1 else f'{net}[0]'); b = e2 - 1; continue
                e = b
                while (e - 1 >= 0 and bits[e - 1] is not None and bits[e - 1][:2] == s[:2]
                       and bits[e - 1][2] == bits[e][2] - 1):
                    e -= 1
                lo, hi = bits[e][2], s[2]
                parts.append(f'{net}[{hi}:{lo}]' if hi != lo else f'{net}[{lo}]'); b = e - 1
            conns.append(f".{p}({parts[0] if len(parts) == 1 else '{' + ', '.join(parts) + '}'})")
        pr = inst.get('params') or {}
        ps = (' #(' + ', '.join(f'.{k}({vparam(v)})' for k, v in pr.items()) + ')') if pr else ''
        body.append(f"  {inst['master']}{ps} {i} (\n    " + ',\n    '.join(conns) + '\n  );')
    for nm, w in sorted(set(partial)):
        L.append(f'  wire [{w - 1}:0] {nm};   // undriven bits = listed gap bits (never tied)')
    L += body + ['endmodule', '`default_nettype wire']
    return '\n'.join(L) + '\n', bad


def _bits(x):
    """'.p({a[3:1], b[0]})' -> '.p(a[3],a[2],a[1],b[0])': range spelling does not matter for the check."""
    x = re.sub(r'\s+', '', x)
    return re.sub(r'(\w+)\[(\d+):(\d+)\]', lambda m: ','.join(f'{m.group(1)}[{k}]' for k in
                  range(int(m.group(2)), int(m.group(3)) - 1, -1)), x).replace('{', '').replace('}', '')


def blocks(v):
    """instance name -> (master+params header, sorted normalised connection list)."""
    out = {}
    for m in re.finditer(r'\n  (\w+)((?: #\(.*?\))?) (\w+) \(\n(.*?)\n  \);', v, re.S):
        conns = sorted(_bits(x) for x in re.split(r',\n', m.group(4)))
        out[m.group(3)] = (m.group(1) + re.sub(r'\s+', '', m.group(2)), conns)
    return out


def main():
    mode, cp, vp = sys.argv[1:4]
    c = ld(cp)
    text, bad = emit(c)
    for b in bad[:20]:
        print('DRIVER_CONFLICT', b)
    if mode == 'emit':
        open(vp, 'w').write(text)
        print(f'die.v from contract: {len(c["instances"])} instances, {len(text)} chars, driver conflicts {len(bad)}')
        sys.exit(1 if bad else 0)
    ref = open(vp).read()
    a, b = blocks(text), blocks(ref)
    only_a, only_b = sorted(set(a) - set(b)), sorted(set(b) - set(a))
    diff = [n for n in a if n in b and a[n] != b[n]]
    print(f'CHECK instances emitted {len(a)} ref {len(b)} only_emitted {len(only_a)} only_ref {len(only_b)} differ {len(diff)}')
    for n in (only_a[:5] + only_b[:5]):
        print('  ONLY', n)
    for n in diff[:8]:
        ha, ca = a[n]; hb, cb = b[n]
        if ha != hb:
            print('  HDR', n, ha[:200], '|', hb[:200])
        sa, sb = set(ca), set(cb)
        print('  CONN', n, 'emitted-only', sorted(sa - sb)[:3], 'ref-only', sorted(sb - sa)[:3])
    sys.exit(0 if not (only_a or only_b or diff or bad) else 1)


if __name__ == '__main__':
    main()
