#!/usr/bin/env python3
"""H-NETLIST 2026-10-16 (alias reduction): derive the strap-identity service-group masters from the parameterised ones.

ot_hbm_svc_sm_group #(STACK,SM) is instantiated 32x on the HBM die with 32 distinct parameter sets (31 exact-view
aliases).  The identities are used only as compare/address constants:
  sm4pc_cdc        STACK: descriptor check (stream side) + hbm-side re-check;  SM: PC_BASE=4*SM -> reserve_pcs
  overlap_owner    PC   : lane select (pcs[j]==PC) and k_addr XOR term
This tool writes *_id copies in which those constants are module INPUTS, each captured by a flop in the clock domain
that uses it (die straps are static; the flop isolates the strap pin from the logic cone), and nothing else changes.
The originals stay byte-identical.  Only OVERLAP=1 (the die default, owner = overlap_owner) is supported by the copy.
Every edit is asserted to apply exactly once; re-running reproduces the files byte-for-byte (--check).
"""
import argparse, sys
from pathlib import Path
D = Path(__file__).resolve().parents[2] / 'rtl/hbm_accel/loader/service_native'
HDR = ('// GENERATED by tools/hbm_die_v16/gen_svc_sm_group_id.py from {src} (do not edit): strap-identity copy, the\n'
       '// per-instance identity is an input captured by a flop in its using domain instead of a module parameter.\n')


def sub(s, a, b, n=1):
    c = s.count(a)
    if c != n:
        raise SystemExit(f'gen_svc_sm_group_id: expected {n} x {a[:70]!r}, found {c}')
    return s.replace(a, b)


def owner(s):
    s = sub(s, 'module ot_hbm_svc_prefetch_overlap_owner #(\n parameter [4:0] PC=0,parameter integer OWNER_AW=5',
            'module ot_hbm_svc_prefetch_overlap_owner_id #(\n parameter integer OWNER_AW=5')
    s = sub(s, ' input wire clk,rst_n,descriptor_v,', ' input wire [4:0] pc_id,\n input wire clk,rst_n,descriptor_v,')
    s = sub(s, ' localparam integer ENTRIES=1<<OWNER_AW,GW=17-OWNER_AW;',
            ' localparam integer ENTRIES=1<<OWNER_AW,GW=17-OWNER_AW;\n'
            ' reg [4:0] pc_q;always @(posedge clk)pc_q<=pc_id; // strap identity (static), this owner\'s physical PC')
    s = sub(s, 'if(pcs[j*5+:5]==PC)', 'if(pcs[j*5+:5]==pc_q)')
    s = sub(s, 'assign k_addr={row,bhi,col,PC^col^hi5,blo};', 'assign k_addr={row,bhi,col,pc_q^col^hi5,blo};')
    return s


def cdc(s):
    s = sub(s, 'module ot_hbm_svc_sm4pc_cdc #(parameter [1:0] STACK=0, parameter integer SM=0, OWNER_AW=5,',
            'module ot_hbm_svc_sm4pc_cdc_id #(parameter integer OWNER_AW=5,')
    s = sub(s, ' input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n',
            ' input wire [1:0] id_stack,input wire [2:0] id_sm,\n input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n')
    s = sub(s, ' localparam integer PC_BASE=4*SM;\n',
            ' // strap identity (static): stream-side copies for the reserve check/PC set, hbm-side copy for the re-check\n'
            ' reg [1:0] stack_s,stack_h;reg [2:0] sm_s;\n'
            ' always @(posedge stream_clk)begin stack_s<=id_stack;sm_s<=id_sm;end\n'
            ' always @(posedge hbm_clk)stack_h<=id_stack;\n')
    s = sub(s, ' initial if(LBANKS>2&&OVERLAP==0)$fatal(1,"LBANKS>2 needs the overlap owner");\n',
            ' initial if(OVERLAP==0)$fatal(1,"sm4pc_cdc_id: only the overlap owner (OVERLAP=1, die default)");\n')
    s = sub(s, ' localparam [19:0] reserve_pcs={5\'(PC_BASE+3),5\'(PC_BASE+2),5\'(PC_BASE+1),5\'(PC_BASE)};\n',
            ' wire [19:0] reserve_pcs={sm_s,2\'d3,sm_s,2\'d2,sm_s,2\'d1,sm_s,2\'d0}; // = the four PCs 4k..4k+3 of SM k\n')
    s = sub(s, ' initial if(SM<0||SM>7)$fatal(1,"SM physical PC group must be0..7");\n', '')
    s = sub(s, '&&reserve_base[31:30]==STACK&&', '&&reserve_base[31:30]==stack_s&&')
    s = sub(s, 'if(desc_data[S0+1:S0]!=STACK||', 'if(desc_data[S0+1:S0]!=stack_h||')
    a = s.index('  ot_hbm_svc_prefetch_overlap_owner #(.PC(PC_BASE+pc),.OWNER_AW(OWNER_AW),.LB(LB)) u_owner(\n')
    s = sub(s, '  ot_hbm_svc_prefetch_overlap_owner #(.PC(PC_BASE+pc),.OWNER_AW(OWNER_AW),.LB(LB)) u_owner(\n'
               '   .clk(hbm_pc_clk[pc]),',
            '  ot_hbm_svc_prefetch_overlap_owner_id #(.OWNER_AW(OWNER_AW),.LB(LB)) u_owner(\n'
            '   .pc_id({id_sm,2\'(pc)}),.clk(hbm_pc_clk[pc]),')
    b = s.index('  end else begin:seq\n')
    e = s.index('  assign issue_done[pc]=1\'b1;\n  end\n', b)
    s = s[:b] + '  end\n' + s[e + len('  assign issue_done[pc]=1\'b1;\n  end\n'):]
    if 'mapped4_owner' in s or 'STACK' in s or 'PC_BASE' in s:
        raise SystemExit('gen_svc_sm_group_id: residual parameter identity in sm4pc_cdc_id')
    return s


def feed(s):
    s = sub(s, 'module ot_hbm_svc_sm_feed_programmed #(\n parameter [1:0] STACK=0,parameter integer SM=0,OWNER_AW=5,',
            'module ot_hbm_svc_sm_feed_programmed_id #(\n parameter integer OWNER_AW=5,')
    s = sub(s, ' input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n',
            ' input wire [1:0] id_stack,input wire [2:0] id_sm,\n input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n')
    s = sub(s, ' ot_hbm_svc_sm4pc_cdc #(.STACK(STACK),.SM(SM),.OWNER_AW(OWNER_AW)',
            ' ot_hbm_svc_sm4pc_cdc_id #(.OWNER_AW(OWNER_AW)')
    s = sub(s, '  .stream_clk(stream_clk),.stream_rst_n(stream_rst_n),.hbm_clk(hbm_clk),.hbm_rst_n(hbm_rst_n),.stream_bank_clk',
            '  .id_stack(id_stack),.id_sm(id_sm),\n'
            '  .stream_clk(stream_clk),.stream_rst_n(stream_rst_n),.hbm_clk(hbm_clk),.hbm_rst_n(hbm_rst_n),.stream_bank_clk')
    if 'STACK' in s.split('module', 1)[1] or '.SM(' in s:
        raise SystemExit('gen_svc_sm_group_id: residual parameter identity in feed_programmed_id')
    return s


def group(s):
    s = sub(s, 'module ot_hbm_svc_sm_group #(parameter[1:0]STACK=0,parameter integer SM=0,LBANKS=4,',
            'module ot_hbm_svc_sm_group_id #(parameter integer LBANKS=4,')
    s = sub(s, ' input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n',
            ' // strap identity: id_stack = HBM stack / quadrant (SW0 SE1 NW2 NE3), id_sm = SM index k (PCs 4k..4k+3)\n'
            ' input wire[1:0]id_stack,input wire[2:0]id_sm,\n'
            ' input wire stream_clk,stream_rst_n,hbm_clk,hbm_rst_n,\n')
    s = sub(s, ' ot_hbm_svc_sm_feed_programmed #(.STACK(STACK),.SM(SM),.LBANKS(LBANKS)) feed(\n',
            ' ot_hbm_svc_sm_feed_programmed_id #(.LBANKS(LBANKS)) feed(\n  .id_stack(id_stack),.id_sm(id_sm),\n')
    return s


FILES = [('ot_hbm_svc_prefetch_overlap_owner.sv', 'ot_hbm_svc_prefetch_overlap_owner_id.sv', owner),
         ('ot_hbm_svc_sm4pc_cdc.sv', 'ot_hbm_svc_sm4pc_cdc_id.sv', cdc),
         ('ot_hbm_svc_sm_feed_programmed.sv', 'ot_hbm_svc_sm_feed_programmed_id.sv', feed),
         ('ot_hbm_svc_sm_group.sv', 'ot_hbm_svc_sm_group_id.sv', group)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='fail if a committed copy differs from regeneration')
    a = ap.parse_args()
    bad = 0
    for src, dst, fn in FILES:
        txt = HDR.format(src=src) + fn((D / src).read_text())
        if a.check:
            if (D / dst).read_text() != txt:
                print('DIFFERS', dst); bad = 1
        else:
            (D / dst).write_text(txt)
    print('SVC_SM_GROUP_ID_GEN', 'CHECK_FAIL' if bad else ('CHECK_PASS' if a.check else 'WROTE'), len(FILES))
    sys.exit(bad)


if __name__ == '__main__':
    main()
