#!/usr/bin/env python3
"""HBM-WIRE 10-18: cut a SLICE module out of the generated die netlist (die.v from contract_die_v.py) for a wiring bench.

    d4g_die_slice.py --die die.v --contract pre.json[.gz] --keep REGEX --observe REGEX --top NAME --out slice.sv

The slice keeps the instance blocks whose name fully matches --keep VERBATIM (same master, parameters and connection
text as the die), so a bench on the slice simulates exactly the die's wiring between those blocks.  Ports of the slice:
  input  <net>               every die net a kept instance reads that no kept instance drives (TB drives it)
  output <net>               every net a kept instance drives (TB observes faults etc.)
  output obs__<inst>__<port> for every input pin of a NOT-kept instance matching --observe whose die connection reads a
                             kept-driven net: the die's own connection expression (bit order exactly as in die.v)
Directions come from the contract's instance port table.  Prints SLICE <top> kept=N in=I out=O obs=B.
"""
import argparse, gzip, json, re
from pathlib import Path

CONST = re.compile(r"\d*'[sS]?[bodhBODH][0-9a-fA-FxXzZ_]+")
IDENT = re.compile(r'\b([A-Za-z_][A-Za-z0-9_$]*)\b')
HEAD = re.compile(r'^  ([A-Za-z_][A-Za-z0-9_]*)\s+(#\(.*\)\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*\($')
CONN = re.compile(r'^\s*\.([A-Za-z_][A-Za-z0-9_]*)\((.*)\),?$')
DECL = re.compile(r'^\s*(input|output|wire)\s+wire\s*(\[(\d+):(\d+)\])?\s*([A-Za-z_][A-Za-z0-9_]*);|^\s*wire\s*(\[(\d+):(\d+)\])?\s*([A-Za-z_][A-Za-z0-9_]*);')


def parse(die):
    nets, blocks, cur = {}, [], None
    for ln in Path(die).read_text().splitlines():
        m = DECL.match(ln)
        if m and cur is None:
            if m.group(5):
                hi = int(m.group(3)) if m.group(3) else 0; nets[m.group(5)] = hi + 1
            else:
                hi = int(m.group(7)) if m.group(7) else 0; nets[m.group(9)] = hi + 1
            continue
        m = HEAD.match(ln)
        if m and cur is None:
            cur = dict(master=m.group(1), inst=m.group(3), text=[ln], conns=[]); continue
        if cur is not None:
            cur['text'].append(ln)
            m = CONN.match(ln)
            if m:
                cur['conns'].append((m.group(1), m.group(2)))
            if ln.strip() == ');':
                blocks.append(cur); cur = None
    return nets, blocks


def idents(expr):
    return [x for x in IDENT.findall(CONST.sub(' ', expr))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--die', required=True); ap.add_argument('--contract', required=True)
    ap.add_argument('--keep', required=True); ap.add_argument('--observe', default='$^')
    ap.add_argument('--top', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--observe-all', action='store_true', help='observe every input pin of the --observe instances '
                    '(not only pins reading kept-driven nets): a pure die-wiring transport slice')
    a = ap.parse_args()
    c = json.load(gzip.open(a.contract) if a.contract.endswith('.gz') else open(a.contract))
    I = c['instances']
    nets, blocks = parse(a.die)
    keep = [b for b in blocks if re.fullmatch(a.keep, b['inst'])]
    kn = {b['inst'] for b in keep}
    driven, read = set(), set()
    for b in keep:
        ports = I[b['inst']]['ports']
        for p, e in b['conns']:
            ids = [x for x in idents(e) if x in nets]
            (driven if ports[p]['direction'] == 'output' else read).update(ids)
    ins = sorted(read - driven)
    outs = sorted(driven)
    obs = []
    for b in blocks:
        if b['inst'] in kn or not re.fullmatch(a.observe, b['inst']):
            continue
        ports = I[b['inst']]['ports']
        for p, e in b['conns']:
            if ports.get(p, {}).get('direction') != 'input':
                continue
            ids = [x for x in idents(e) if x in nets]
            if ids and (a.observe_all or any(x in driven for x in ids)):
                obs.append((f'obs__{b["inst"]}__{p}', ports[p]['bits'], e))
                ins += [x for x in ids if x not in driven and x not in ins]
    ins = sorted(set(ins))
    L = [f'// generated by tools/hbm_die_v16/d4g_die_slice.py from {a.die} (keep {a.keep!r}, observe {a.observe!r})',
         '`default_nettype none', f'module {a.top} (']
    plist = ins + outs + [o[0] for o in obs]
    L.append('  ' + ', '.join(plist))
    L.append(');')
    for n in ins:
        L.append(f'  input wire [{nets[n] - 1}:0] {n};')
    for n in outs:
        L.append(f'  output wire [{nets[n] - 1}:0] {n};')
    for n, w, e in obs:
        L.append(f'  output wire [{w - 1}:0] {n};')
        L.append(f'  assign {n} = {e};')
    for b in keep:
        L += b['text']
    L += ['endmodule', '`default_nettype wire', '']
    Path(a.out).write_text('\n'.join(L))
    meta = dict(top=a.top, kept=sorted(kn), inputs={n: nets[n] for n in ins}, outputs={n: nets[n] for n in outs},
                observe={n: w for n, w, _ in obs}, masters=sorted({b['master'] for b in keep}))
    Path(a.out).with_suffix('.json').write_text(json.dumps(meta, indent=1))
    print(f'SLICE {a.top} kept={len(keep)} in={len(ins)} out={len(outs)} obs={len(obs)}')


if __name__ == '__main__':
    main()
