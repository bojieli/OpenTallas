#!/usr/bin/env python3
"""HBM-LANDING 10-18: generate rtl/hbm_accel/die_glue/hbfd_lane_masters.sv, the HBM d4g forwarded-clock half-cycle lane
masters (LANDING-CONTRACT sections 2, 3, 7; Qwen cores rtl/qwen_split/qfd_fwd_lane.sv + fork rtl/hbm_accel/die_glue/ot_hbm_lane.sv):
  hbfd_lh0_<W>_<DIR>        (ck, en, a -> b, eb, ck_o)                 hop-0 station on the source root (non-inverting ICG)
  hbfd_lh_<W>_<DIR>         (ckf, ea, a -> b, eb, ck_o)                half-cycle station
  hbfd_lh0_<W>_<DIR>_f<N> / hbfd_lh_<W>_<DIR>_f<N>  (same inputs -> b[N*W], eb[N], ck_o[N])   fork, N = 2..4
  hbfd_land_<W>_<DIR>       (ckf, ea, a, ck, rs, k0, k1, k2 -> b, fault)  landing, ring D = 4 (ot_qfd_land FIRST = 0)
  hbfd_land0_<W>_<DIR>      (ck_s, en, a, ck, rs, k0, k1, k2 -> b, fault) 0-station lane landing (FIRST = 1)
k0..k2 = the K strap (declared die straps).  Sources per master: this file + ot_hbm_lane.sv + rtl/qwen_split/qfd_fwd_lane.sv
+ rtl/hdc/ot_hdc_cg.sv.     gen_hbm_lane_masters.py [--out FILE]
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WIDTHS = (48, 136, 624)
DIRS = ('WE', 'EW', 'SN', 'NS')
FORKS = (2, 3, 4)
SOURCES = ['rtl/hbm_accel/die_glue/hbfd_lane_masters.sv', 'rtl/hbm_accel/die_glue/ot_hbm_lane.sv',
           'rtl/qwen_split/qfd_fwd_lane.sv', 'rtl/hdc/ot_hdc_cg.sv']


def masters():
    for W in WIDTHS:
        for d in DIRS:
            yield f'hbfd_lh0_{W}_{d}', W, 'lh0', 1
            yield f'hbfd_lh_{W}_{d}', W, 'lh', 1
            for n in FORKS:
                yield f'hbfd_lh0_{W}_{d}_f{n}', W, 'lh0', n
                yield f'hbfd_lh_{W}_{d}_f{n}', W, 'lh', n
            yield f'hbfd_land_{W}_{d}', W, 'land', 1
            yield f'hbfd_land0_{W}_{d}', W, 'land0', 1


def body(m, W, fam, n):
    if fam in ('lh0', 'lh'):
        ci, ei = ('ck', 'en') if fam == 'lh0' else ('ckf', 'ea')
        f = 1 if fam == 'lh0' else 0
        if n == 1 and fam == 'lh':
            return (f'module {m} (input wire {ci}, input wire {ei}, input wire [{W - 1}:0] a, output wire [{W - 1}:0] b, '
                    f'output wire eb, output wire ck_o);\n'
                    f'    ot_qfd_lane_st #(.W({W}), .FIRST({f})) u_st (.ck({ci}), .en({ei}), .a(a), .b(b), .eb(eb), .ck_o(ck_o));\nendmodule')
        if n == 1:   # HBM hop 0 (non-inverting ICG on the source root): the fork core with one branch, scalar ports
            return (f'module {m} (input wire {ci}, input wire {ei}, input wire [{W - 1}:0] a, output wire [{W - 1}:0] b, '
                    f'output wire eb, output wire ck_o);\n'
                    f'    ot_hbm_lane_stf #(.W({W}), .N(1), .FIRST(1)) u_st (.ck({ci}), .en({ei}), .a(a), .b(b), .eb(eb), .ck_o(ck_o));\nendmodule')
        return (f'module {m} (input wire {ci}, input wire {ei}, input wire [{W - 1}:0] a, output wire [{n * W - 1}:0] b, '
                f'output wire [{n - 1}:0] eb, output wire [{n - 1}:0] ck_o);\n'
                f'    ot_hbm_lane_stf #(.W({W}), .N({n}), .FIRST({f})) u_st (.ck({ci}), .en({ei}), .a(a), .b(b), .eb(eb), .ck_o(ck_o));\nendmodule')
    ci, ei = ('ckf', 'ea') if fam == 'land' else ('ck_s', 'en')
    f = 0 if fam == 'land' else 1
    return (f'module {m} (input wire {ci}, input wire {ei}, input wire [{W - 1}:0] a, input wire ck, input wire rs, '
            f'input wire k0, input wire k1, input wire k2, output wire [{W - 1}:0] b, output wire fault);\n'
            f'    ot_qfd_land #(.W({W}), .D(4), .FIRST({f})) u_land (.ckf({ci}), .ea({ei}), .i(a), .ck(ck), .rs(rs), '
            f'.k({{k2, k1, k0}}), .o(b), .fault(fault));\nendmodule')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=str(ROOT / SOURCES[0]))
    a = ap.parse_args()
    L = ['`timescale 1ns/1ps', '`default_nettype none',
         '// GENERATED by tools/hbm_die_v16/gen_hbm_lane_masters.py (HBM-LANDING 10-18) -- do not edit.',
         '// HBM d4g forwarded-clock half-cycle lane masters + landings; cores rtl/qwen_split/qfd_fwd_lane.sv,',
         '// rtl/hbm_accel/die_glue/ot_hbm_lane.sv (fork), rtl/hdc/ot_hdc_cg.sv.  Contract: lanes/LANDING-CONTRACT.md.']
    k = 0
    for m, W, fam, n in masters():
        L.append(body(m, W, fam, n)); k += 1
    L.append('`default_nettype wire')
    Path(a.out).write_text('\n'.join(L) + '\n')
    print(f'{k} masters -> {a.out}')


if __name__ == '__main__':
    main()
