#!/usr/bin/env python3
"""Per-bank face pin plan of the hb_quant_NW tile (ot_hgi_qdq_host_static, HBMA-QDQ 2026-10-17).

The tile's rq/rr/wq buses are eight bank slices (bank g = rq[17g+:17], wq[281g+:281], rr[257g+:257], 555 bits) whose
peers are the d4f NW bank tiles vmb_NW<g> / merges vmm_NW<g> (run6 placement, hbm_manifest.json): banks 4/5 sit at the
W face, 6/7 east, 0..3 far west on the same bank row (even banks the upper row, odd the lower row).  A base-name face
plan would put a whole 2,056-bit bus on one 244 um face (8.4 pins/um); this per-bit io_tcl gives each bank slice the
face toward its peer: W = banks 5 (south half) / 4 (north half); N = banks 0, 2 (upper row, routes west along the top);
S = banks 1, 3 (lower row) + the programme clock/reset at the S centre + cfg (host_cp_ingress lies SE) at the S east
end; E = descriptor/launch/status (host_cp_ingress / host_status SE) at the south end, banks 7 (south) / 6 (north).
The four transport/decoder clocks enter at the N centre.  Every face is spread evenly over its full length (W/E M4,
N/S M5, >= 2 tracks between pins), conventions of tools/ref_tile/spread_face_pins.py.
Usage: qdq_host_nw_pins.py OUTLINE_W OUTLINE_H OUT.tcl
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "ref_tile"))
from spread_face_pins import PITCH, OFF, SIZE, snap   # noqa: E402

MARGIN = 4.32


def bank(g):
    return ([f"rq[{17*g+i}]" for i in range(17)] + [f"wq[{281*g+i}]" for i in range(281)]
            + [f"rr[{257*g+i}]" for i in range(257)])


def vec(n, w):
    return [f"{n}[{i}]" for i in range(w)]


def plan():
    cfg = ["cfg_v"] + vec("cfg_target", 8) + vec("cfg_addr", 12) + vec("cfg_data", 256)
    desc = ["desc_v"] + vec("desc_base", 12) + vec("desc_limit", 13) + vec("desc_loops", 16) + ["launch_v"]
    status = ["program_active", "program_done", "configured", "beat_done", "record_done", "fault"]
    s_bits = bank(1) + bank(3)
    s_mid = len(s_bits + cfg) // 2
    s_face = s_bits[:s_mid] + ["clk_program", "rst_n"] + s_bits[s_mid:] + cfg
    n_bits = bank(0) + bank(2)
    n_mid = len(n_bits) // 2
    n_face = n_bits[:n_mid] + ["clk_transport", "clk_dxl", "clk_dbq", "clk_daq"] + n_bits[n_mid:]
    return {"W": bank(5) + bank(4), "E": desc + status + bank(7) + bank(6), "N": n_face, "S": s_face}


def main():
    W, H, out = float(sys.argv[1]), float(sys.argv[2]), Path(sys.argv[3])
    faces = plan()
    allbits = [b for f in faces.values() for b in f]
    assert len(allbits) == len(set(allbits)) == 4772, len(allbits)
    lines = [f"# generated by tools/hbm_die_v16/qdq_host_nw_pins.py {W:g} {H:g}: per-bank faces toward the d4f NW bank "
             "peers, every face spread evenly (W/E M4, N/S M5)"]
    summary = {}
    for face, bits in faces.items():
        horiz = face in ("N", "S")
        span = (W if horiz else H) - 2 * MARGIN
        step = span / len(bits)
        layer = "M5" if horiz else "M4"
        if step < 2 * PITCH[layer]:
            raise SystemExit(f"face {face}: {len(bits)} pins, step {step:.3f} < 2 tracks")
        used = set()
        for i, b in enumerate(bits):
            c = snap(MARGIN + step * (i + 0.5), PITCH[layer], OFF[layer])
            while c in used:
                c = round(c + PITCH[layer], 3)
            used.add(c)
            x, y = (c, 0.0 if face == "S" else H) if horiz else (0.0 if face == "W" else W, c)
            sx, sy = SIZE[layer]
            lines.append(f"place_pin -pin_name {{{b}}} -layer {layer} -location {{{x:.3f} {y:.3f}}} "
                         f"-pin_size {{{sx} {sy}}} -force_to_die_boundary")
        summary[face] = f"{len(bits)} pins {len(bits)/span:.2f}/um"
    out.write_text("\n".join(lines) + "\n")
    print("QDQ_HOST_NW_PINS", summary)


if __name__ == "__main__":
    main()
