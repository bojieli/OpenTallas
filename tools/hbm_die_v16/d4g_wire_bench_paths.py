#!/usr/bin/env python3
"""HBM-WIRE 10-18: die-wiring TRANSPORT bench of every compiled functional path (d4g_functional_bind.spec()).

    d4g_wire_bench_paths.py --die die.v --contract pre.json[.gz] --out DIR [--cls INJ,DEL,...] [--mut CLASS]

Slice = the die.v connection text of every consumer pin of the spec (d4g_die_slice.py --observe-all, plus the die relay
/ landing stations of the contract kept verbatim with their RTL), so the bench simulates the GENERATED die wiring.  The TB
drives a fresh random word on every producer output net each cycle and checks, for every path, that the consumer pin
bits equal the producer bits the compiler names (slice + bit order), delayed by the path's relay stages (from the
contract trace; 0 on the pre-relay die).  This proves the paths of HC (root <-> hubs <-> bank rings), XCMD (xcal / svg
-> SM command, x-load issuer -> SM write port), DMA write-back, SFU operand join and the INJ/DEL/RC wires in one build;
the INJ/DEL/RC slot behaviour is d4g_wire_bench_sucx.py.  Prints PATH_WIRE PASS|FAIL paths=N bits=B checks=C.
MUT CLASS (must FAIL): one consumer connection of that class rewired (two producer slices swapped) in the slice text.
"""
import argparse, collections, gzip, json, re, subprocess, sys
from pathlib import Path

H = Path(__file__).resolve().parent
sys.path.insert(0, str(H))
import d4g_functional_bind as FB  # noqa: E402

MUTS = {  # class -> (consumer obs port, old, new): swap two producer slices in the die connection text
    'XCMD': ('obs__sm_SW5__command', 'xc_SW5__cmd_ext[108:0], svg_SW5__sm_command[82:0]', 'svg_SW5__sm_command[82:0], xc_SW5__cmd_ext[108:0]'),
    'HC': ('obs__hc_eng__qps', 'hc_NW__ps[31:0], hc_SE__ps[31:0]', 'hc_SE__ps[31:0], hc_NW__ps[31:0]'),
    'DMA': ('obs__hb_dbk_NE__wa', 'wbk_NE__wa[11:0]', '{wbk_NE__wa[5:0], wbk_NE__wa[11:6]}'),
    'SFUJ': ('obs__sfucore_NW__vi_q_e', 'sfus_NW__l09_vi_q[31:0], sfus_NW__l08_vi_q[31:0]', 'sfus_NW__l08_vi_q[31:0], sfus_NW__l09_vi_q[31:0]'),
    'INJ': ('obs__cij_NE__su_inj_d_r1', 'cxij_NE__inj_d[1023:768], cxij_NE__inj_d[511:256]', 'cxij_NE__inj_d[511:256], cxij_NE__inj_d[1023:768]'),
    'DEL': ('obs__cxdl_NW3__del_obase', 'hb_coll_NW__hgi_del_obase[159:120]', 'hb_coll_NW__hgi_del_obase[119:80]'),
    'RC': ('obs__cxrc_SE__rr_d', 'hb_coll_SE__rr_d[255:0]', '{hb_coll_SE__rr_d[127:0], hb_coll_SE__rr_d[255:128]}'),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--die', required=True); ap.add_argument('--contract', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--cls', default=''); ap.add_argument('--mut', default=''); ap.add_argument('--cycles', type=int, default=400)
    a = ap.parse_args()
    O = Path(a.out); O.mkdir(parents=True, exist_ok=True)
    c = FB.load(a.contract)
    S = FB.spec()
    if a.cls:
        S = [x for x in S if x['cls'] in a.cls.split(',')]
    stages = {}
    for x, r in zip(S, FB.check(c, S)):
        if r['status'] != 'PASS':
            print('CONTRACT_PATH_FAIL', x['src'], x['dst'], r['bad']); sys.exit(2)
        stages[(tuple(x['src']), tuple(x['dst']))] = r['relay_stages'][0] if r['relay_stages'] else 0
    cons = sorted({x['dst'][0] for x in S})
    I = c['instances']
    relays = sorted(i for i, v in I.items() if FB.RELAY.match(v['master']))
    keep = '|'.join(re.escape(i) for i in relays) if any(stages.values()) else '$^'
    sl = O / 'slice_paths.sv'
    subprocess.run([sys.executable, str(H / 'd4g_die_slice.py'), '--die', a.die, '--contract', a.contract, '--keep', keep,
                    '--observe', '|'.join(re.escape(i) for i in cons), '--observe-all', '--top', 'slice_paths', '--out', str(sl)],
                   check=True)
    meta = json.loads(sl.with_suffix('.json').read_text())
    if a.mut:
        port, old, new = MUTS[a.mut]
        t = sl.read_text(); key = f'  assign {port} = '
        i = t.index(key); j = t.index('\n', i); line = t[i:j]
        assert old in line, (port, old, line)
        sl.write_text(t[:i] + line.replace(old, new, 1) + t[j:])
    ins, obs = meta['inputs'], meta['observe']
    L = ['`timescale 1ns/1ps', '`default_nettype none', '// generated by tools/hbm_die_v16/d4g_wire_bench_paths.py (HBM-WIRE 10-18)',
         'module tb_d4g_wire_paths;', ' reg clk=0; always #1 clk=~clk;']
    clk_nets = [n for n in ins if n.startswith('hb_ckgen__pll_')]
    for n, w in ins.items():
        L.append(f' reg [{w - 1}:0] {n};')
    for n, w in {**meta['outputs'], **obs}.items():
        L.append(f' wire [{w - 1}:0] {n};')
    L.append(' slice_paths dut(' + ', '.join(f'.{n}({n})' for n in list(ins) + list(meta['outputs']) + list(obs)) + ');')
    for n in clk_nets:
        L.append(f' always @* {n} = {{{ins[n]}{{clk}}}};')
    L.append(' integer i;')
    L.append(' task automatic rnd; begin')
    for n, w in ins.items():
        if n in clk_nets:
            continue
        if n.startswith('hb_ckgen__por_') or 'rst' in n:
            L.append(f'  {n} = {{{w}{{1\'b1}}}};'); continue
        for k in range(0, w, 32):
            L.append(f'  {n}[{min(k + 31, w - 1)}:{k}] = $urandom;')
    L.append(' end endtask')
    maxst = max(stages.values() or [0])
    checks = []
    for n, x in enumerate(S):
        si, sp, slo = x['src']; di, dp, dlo = x['dst']; w = x['w']
        if w == 0:
            continue
        pn, on = f'{si}__{sp}', f'obs__{di}__{dp}'
        assert pn in ins, ('producer net not a slice input', pn)
        assert on in obs, ('consumer pin not observed', on)
        st = stages[(tuple(x['src']), tuple(x['dst']))]
        src = f'{pn}[{slo + w - 1}:{slo}]'
        if st:
            L.append(f' reg [{w - 1}:0] d{n} [0:{st - 1}]; always @(posedge clk) begin d{n}[0] <= {src}; '
                     + ' '.join(f'd{n}[{k}] <= d{n}[{k - 1}];' for k in range(1, st)) + ' end')
            src = f'd{n}[{st - 1}]'
        checks.append((n, f'{on}[{dlo + w - 1}:{dlo}]', src, x['cls'], f'{si}.{sp}[{slo}+:{w}] -> {di}.{dp}[{dlo}]', w))
    L.append(' integer errors=0, checks=0, cyc=0; reg [31:0] cls_err [0:7];')
    L.append(' task automatic chk; begin')
    for n, o, s, cl, desc, w in checks:
        L.append(f'  checks=checks+1; if({o}!=={s}) begin errors=errors+1; if(errors<12) $display("PATH MISMATCH cyc=%0d {cl} {desc}", cyc); end')
    L.append(' end endtask')
    L.append(f''' initial begin
  rnd; #0.5;
  for(cyc=0; cyc<{a.cycles}; cyc=cyc+1) begin @(negedge clk); rnd; @(posedge clk); #0.5; if(cyc>{maxst + 1}) chk; end
  if(errors==0 && checks>0) $display("PATH_WIRE PASS paths={len(checks)} bits={sum(c_[5] for c_ in checks)} checks=%0d stages_max={maxst} MUT={a.mut or 0}", checks);
  else $display("PATH_WIRE FAIL paths={len(checks)} errors=%0d checks=%0d MUT={a.mut or 0}", errors, checks);
  $finish;
 end
endmodule
`default_nettype wire''')
    (O / 'tb_d4g_wire_paths.sv').write_text('\n'.join(L) + '\n')
    rtl = sorted({f for r in relays if any(stages.values()) for f in [I[r]['source']] + (I[r].get('rtl_deps') or [])})
    (O / 'files.txt').write_text(''.join(f + '\n' for f in rtl))
    (O / 'run.sh').write_text(f'''#!/bin/bash
# HBM-WIRE path transport bench MUT={a.mut or 0}: run from a source tree root SRC (relay RTL of files.txt when the die has relays).
set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd); SRC=${{SRC:?SRC}}; cd "$SRC"
vl=$HOME/.local/opentallas-tools/verilator-5.050/bin/verilator
"$vl" --version
"$vl" --binary --timing -j 8 -Wno-fatal -Wno-lint -Wno-style --top-module tb_d4g_wire_paths -Mdir "$here/obj" -o Vpaths \\
  "$here/tb_d4g_wire_paths.sv" "$here/slice_paths.sv" $(cat "$here/files.txt") > "$here/build.log" 2>&1 || {{ tail -30 "$here/build.log"; echo "PATH_WIRE BUILD_FAIL"; exit 2; }}
"$here/obj/Vpaths" > "$here/run.log" 2>&1
grep -E "PATH_WIRE|PATH MISMATCH" "$here/run.log" | head -14
rm -rf "$here/obj"
grep -q "PATH_WIRE PASS" "$here/run.log"
''')
    print('BENCH', O, 'paths', len(checks), 'relay_stages_max', maxst)


if __name__ == '__main__':
    main()
