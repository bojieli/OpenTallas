#!/usr/bin/env python3
"""Audit the actual PHY-to-service-band boundary without fabricating v15 endpoints.

Inventory generation succeeds independently of implementation qualification. The
contract explicitly rejects qualification while historical interfaces have no
actual-source binding. Use --require-bound when consuming it as a closure gate.
No generator is imported or executed; only the die-view readers are used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SPLIT = 'physical/hbm_accel_die_views/svc/split_psn/split.json'
PHY_BB = ('physical/asap7_memory_macros_v2/ot_hbm3e_phy_v41x_aw30_e8p5/'
          'ot_hbm3e_phy_v41x_aw30_e8p5_bb.v')
PHY_MODULE = 'ot_hbm3e_phy_v41x_aw30_e8p5'
DEFAULT_OUT = 'physical/hbm_accel_die_views/svc/v15/contract.json'
# Width per pseudo-channel, checked against the actual PHY declaration below.
PC_FIELDS = dict(k_v=1, k_rdy=1, k_addr=30, k_len=4, k_tag=17,
                 k_we=1, k_wdata=256, k_wstrb=32, k_wr_done=1,
                 kr_v=1, kr_rdy=1, kr_tag=17, kr_beat=4, kr_data=256)
PC_LEAF = 'rtl/hbm_accel/loader/service_native/ot_hbm_svc_static_pc.sv'
PC_MODULE = 'ot_hbm_svc_static_pc'
WRAPPER_DIR = 'physical/hbm_accel_die_views/svc/v15/rtl'
NON_PC_FIELDS = {'clk', 'rst_n', 'w_v', 'w_rdy', 'w_addr', 'w_len',
                 'w_tag', 'w_room', 'wr_v', 'wr_rdy', 'wr_tag',
                 'wr_beat', 'wr_data', 'k_oor', 'w_oor', 'refreshes', 'w_reads'}


def need(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def band_ports(pcs, ports):
    """band port table: PC fields packed per slot, rst_n shared, and the PC clock replaced by one clock entry per PC
    (clk_pc[slot], H-DIE v15 top-down grant 7aa4a2686 per_pc_root_request: the svcPC native audit failed with one band
    clock, L408.99/C508.02/spread104.7)"""
    out = {}
    for port, (direction, width) in ports.items():
        if port == 'clk':
            out['clk_pc'] = (direction, len(pcs))
        else:
            out[port] = (direction, width if port == 'rst_n' else width * len(pcs))
    return out


def wrapper_source(name, pcs, ports):
    lines = ['`default_nettype none',
             '// Generated by tools/hbm_svc_v15_contract.py. PC-local payload only.',
             '// Historical service joins and shared PHY signals remain unbound.',
             '// Local slot -> physical PC: ' + ', '.join(map(str, pcs)),
             f'module {name} (']
    declarations = []
    for port, (direction, width) in band_ports(pcs, ports).items():
        dim = f' [{width - 1}:0]' if width > 1 else ''
        declarations.append(f'    {direction} wire{dim} {port}')
    lines.append(',\n'.join(declarations))
    lines.append(');')
    for slot, pc in enumerate(pcs):
        lines.append(f'    {PC_MODULE} u_pc{pc} (')
        joins = []
        for port, (_, width) in ports.items():
            if port == 'clk':   # H-DIE grant 7aa4a2686: one clock entry per PC (own CTS root, insertion <= 300 ps)
                expr = 'clk_pc' if len(pcs) == 1 else f'clk_pc[{slot}]'
            else:
                expr = port if port == 'rst_n' or len(pcs) == 1 else (
                    f'{port}[{slot}]' if width == 1 else f'{port}[{slot * width} +: {width}]')
            joins.append(f'        .{port}({expr})')
        lines.append(',\n'.join(joins))
        lines.append('    );')
    lines.extend(['endmodule', '`default_nettype wire', ''])
    return '\n'.join(lines)


def build_contract(module_specs=(), generate_wrappers=False):
    sys.path.insert(0, str(ROOT / 'tools'))
    import hbm_die_views as V

    sources = {}

    def source(rel):
        p = ROOT / rel
        need(p.is_file(), f'missing source: {rel}')
        sources[str(p.relative_to(ROOT))] = digest(p)
        return p

    split_path = source(SPLIT)
    split = json.loads(split_path.read_text())
    need(set(split['parents']) == {f'hfd_svc_{q}' for q in ('SW', 'NW', 'SE', 'NE')},
         'unknown/missing service parent')
    phy_lef = source(V.S.PHY_LEF)
    phy = V.S.real_lef(str(phy_lef))
    need(phy['name'] == PHY_MODULE, 'unexpected PHY macro')
    phy_ports = V.L.parse_module(str(source(PHY_BB)), PHY_MODULE)['ports']
    need(set(phy_ports) == set(PC_FIELDS) | NON_PC_FIELDS,
         'unknown/missing PHY field; explicit routing classification required')
    need(sum(PC_FIELDS.values()) == 622, 'PC field width changed')
    for name, width in PC_FIELDS.items():
        need(phy_ports[name][1] == 32 * width, f'PHY PC width mismatch: {name}')
    for rel in ('tools/hbm_die_views.py', 'tools/die_top_lint.py',
                'tools/hbm_accel_die_fp.py', 'tools/dsrom_s81_fulldie.py',
                'tools/hbm_svc_v15_contract.py'):
        source(rel)
    dfi = V.H.real_ports()[PHY_MODULE]['dfi']
    need(len(dfi) == len(set(dfi)) == sum(p[1] for p in phy_ports.values()),
         'DFI mapping has duplicate or missing bits')
    parsed = []
    seen = set()
    for flat_bit, endpoint in enumerate(dfi):
        match = re.fullmatch(r'(\w+)(?:\[(\d+)\])?', endpoint)
        need(match is not None, f'unknown DFI endpoint syntax: {endpoint}')
        field, index = match.group(1), int(match.group(2) or 0)
        need(field in phy_ports and index < phy_ports[field][1],
             f'DFI endpoint outside actual source: {endpoint}')
        seen.add((field, index))
        pc = index // PC_FIELDS[field] if field in PC_FIELDS else None
        parsed.append(dict(parent_bit=flat_bit, phy_field=field, phy_bit=index,
                           phy_direction=phy_ports[field][0], pc=pc))
    need(len(seen) == len(dfi), 'DFI aliases an actual PHY bit')

    masters = {}
    instances = []
    families = {}
    rejections = []
    for family, count in (('SW', 8), ('SE', 9)):
        parent = f'hfd_svc_{family}'
        par = split['parents'][parent]
        bands = par['bands']
        need(len(bands) == count, f'{family} band count changed')
        routes = [None] * len(dfi)
        for band in bands:
            need(band in split['bands'], f'unknown band {band}')
            record_rel = str(Path(SPLIT).parent / band / 'ports.json')
            record = json.loads(source(record_rel).read_text())
            need(record['master'] == band, f'ports master mismatch: {band}')
            metadata = split['bands'][band]
            need(set(record['ports']) == set(metadata['ports']),
                 f'split/ports port-set mismatch: {band}')
            ports = {}
            for port, value in record['ports'].items():
                n = value['bits']
                need(n == metadata['ports'][port]['bits'], f'port width mismatch: {band}.{port}')
                direction = {}
                for lo, hi, dr in value['dir_segments']:
                    need(dr in ('in', 'out'), f'unknown direction: {band}.{port}')
                    for bit in range(lo, hi):
                        need(0 <= bit < n and bit not in direction,
                             f'overlapping/out-of-bounds direction: {band}.{port}')
                        direction[bit] = dr
                need(len(direction) == n, f'incomplete port directions: {band}.{port}')
                pin_bits = []
                for pin in value['pins']:
                    m = re.fullmatch(re.escape(port) + r'\[(\d+)\]', pin[0])
                    need(m is not None, f'unknown pin name: {band}.{pin[0]}')
                    pin_bits.append(int(m.group(1)))
                need(sorted(pin_bits) == list(range(n)), f'missing/duplicate physical pins: {band}.{port}')
                mapping = par['port_map'][band].get(port)
                ports[port] = dict(bits=n, direction=value['direction'],
                                   direction_segments=value['dir_segments'], face=value['face'],
                                   parent_mapping=mapping,
                                   status='historical_source_unbound',
                                   actual_module_endpoint=None)
                if mapping and mapping['parent_port'] == 'phy':
                    lo, hi = mapping['parent_bits']
                    need(hi - lo + 1 == n, f'PHY slice width mismatch: {band}')
                    for bit in range(n):
                        parent_bit = lo + bit
                        need(0 <= parent_bit < len(dfi) and routes[parent_bit] is None,
                             f'overlapping/out-of-bounds PHY mapping: {band}')
                        expected = 'out' if parsed[parent_bit]['phy_direction'] == 'input' else 'in'
                        need(direction[bit] == expected,
                             f'PHY/service direction mismatch: {band}.phy[{bit}]')
                        routes[parent_bit] = dict(master=band, port=port, bit=bit)
            masters[band] = dict(geometry={k: metadata[k] for k in ('x0_um', 'w_um', 'h_um')},
                                 physical_ports=ports, historical_forwarded_clocks=record.get('fclk', {}),
                                 historical_record_inst_names=record['inst_names'], actual_module=None,
                                 status='historical_source_unbound')
            rejections.append(dict(code='SERVICE_BAND_SOURCE_UNBOUND', master=band,
                                   detail='Historical physical ports have no v15 actual module endpoint binding.'))
        need(all(r is not None for r in routes), f'{family} PHY coverage incomplete')
        # Every range is contiguous in both the PHY field and the local band port.
        ranges = []
        for bit, route in zip(parsed, routes):
            key = (route['master'], route['port'], bit['phy_field'], bit['phy_direction'], bit['pc'])
            if (ranges and ranges[-1]['_key'] == key
                    and ranges[-1]['parent_bits'][1] + 1 == bit['parent_bit']
                    and ranges[-1]['phy_bits'][1] + 1 == bit['phy_bit']
                    and ranges[-1]['band_bits'][1] + 1 == route['bit']):
                for field, value in (('parent_bits', bit['parent_bit']),
                                     ('phy_bits', bit['phy_bit']), ('band_bits', route['bit'])):
                    ranges[-1][field][1] = value
            else:
                ranges.append(dict(_key=key, master=route['master'], band_port=route['port'],
                                   phy_field=bit['phy_field'], phy_direction=bit['phy_direction'],
                                   service_direction='output' if bit['phy_direction'] == 'input' else 'input',
                                   pc=bit['pc'], parent_bits=[bit['parent_bit']] * 2,
                                   phy_bits=[bit['phy_bit']] * 2, band_bits=[route['bit']] * 2,
                                   actual_module_endpoint=None, status='physical_route_source_unbound'))
        for r in ranges:
            del r['_key']
        pcs = []
        for pc in range(32):
            selected = [r for r in ranges if r['pc'] == pc]
            owners = sorted({r['master'] for r in selected})
            widths = {name: sum(r['phy_bits'][1] - r['phy_bits'][0] + 1
                               for r in selected if r['phy_field'] == name) for name in PC_FIELDS}
            need(widths == PC_FIELDS, f'incomplete PC fields: {family} PC{pc}')
            need(len(owners) == 1, f'PC crosses service bands: {family} PC{pc}: {owners}')
            pcs.append(dict(pc=pc, master=owners[0], bits=622,
                            field_route_indices=[i for i, r in enumerate(ranges) if r['pc'] == pc]))
        families[family] = dict(parent=parent, physical_pc_inventory=pcs,
                               phy_routing_ranges=ranges,
                               coverage=dict(parent_bits=len(dfi), routed_bits=len(routes),
                                             pc_bits=32 * 622, other_bits=len(dfi) - 32 * 622,
                                             complete=True))
    need(set(masters) == set(split['bands']), 'unknown/missing service band master')
    for quadrant, family in (('SW', 'SW'), ('NW', 'SW'), ('SE', 'SE'), ('NE', 'SE')):
        par = split['parents'][f'hfd_svc_{quadrant}']
        base = split['parents'][f'hfd_svc_{family}']
        need(par['bands'] == base['bands'],
             f'{quadrant} differs from reused {family} band mapping')
        for band in par['bands']:
            need(par['port_map'][band]['phy'] == base['port_map'][band]['phy'],
                 f'{quadrant} differs from reused {family} PHY mapping')
        for band in par['bands']:
            suffix = band.rsplit('_s', 1)[1]
            instances.append(dict(instance=f'svc_{quadrant}_s{suffix}', parent=f'hfd_svc_{quadrant}',
                                  quadrant=quadrant, family=family, master=band,
                                  orientation='MX' if quadrant in ('NW', 'NE') else 'R0',
                                  historical_parent_port_map=par['port_map'][band]))
    need(len(instances) == 34, 'expected 34 service instances')
    module_tables = {}
    leaf_path = source(PC_LEAF)
    leaf_ports = V.L.parse_module(str(leaf_path), PC_MODULE)['ports']
    need(bool(leaf_ports), 'missing PC leaf module')
    for field, width in PC_FIELDS.items():
        need(field in leaf_ports and leaf_ports[field][1] == width,
             f'leaf PHY field width mismatch: {field}')
        expected = 'output' if phy_ports[field][0] == 'input' else 'input'
        need(leaf_ports[field][0] == expected, f'leaf PHY direction mismatch: {field}')
    for family, data in families.items():
        for master in split['parents'][f'hfd_svc_{family}']['bands']:
            pcs = [p['pc'] for p in data['physical_pc_inventory'] if p['master'] == master]
            need(bool(pcs), f'zero-PC band has no qualified wrapper: {master}')
            name = master.replace('hfd_svc_', 'hfd_svc_v15_', 1)
            rel = f'{WRAPPER_DIR}/{name}.sv'
            expected_source = wrapper_source(name, pcs, leaf_ports)
            path = ROOT / rel
            if generate_wrappers:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected_source)
            need(path.is_file() and path.read_text() == expected_source,
                 f'wrapper missing or differs from source-derived PC packing: {rel}; use --generate-wrappers')
            source(rel)
            table = V.L.parse_module(str(path), name)['ports']
            expected_ports = band_ports(pcs, leaf_ports)
            need(table == expected_ports, f'wrapper source port-table mismatch: {name}')
            module_tables[name] = dict(source=rel, sha256=digest(path),
                                      ports={p: dict(direction=v[0], bits=v[1]) for p, v in table.items()},
                                      physical_pc_ids=pcs,
                                      status='actual_pc_leaf_wrapper_external_joins_unbound')
            masters[master]['actual_module'] = name
            masters[master]['physical_pc_ids'] = pcs
            masters[master]['status'] = 'actual_pc_leaf_wrapper_historical_ports_unbound'
            for r in data['phy_routing_ranges']:
                if r['master'] != master or r['pc'] is None:
                    continue
                width = PC_FIELDS[r['phy_field']]
                slot = pcs.index(r['pc'])
                local_lo = r['phy_bits'][0] % width
                local_hi = r['phy_bits'][1] % width
                r['actual_module_endpoint'] = dict(module=name, port=r['phy_field'],
                    wrapper_bits=[slot * width + local_lo, slot * width + local_hi],
                    leaf_instance=f'u_pc{r["pc"]}', leaf_module=PC_MODULE,
                    leaf_port=r['phy_field'], leaf_bits=[local_lo, local_hi])
                r['status'] = 'actual_leaf_port_bound_external_join_unbound'
        rejections.extend([
            dict(code='SHARED_PHY_ENDPOINTS_UNBOUND', family=family,
                 bits=data['coverage']['other_bits'],
                 detail='Non-PC PHY write-lane, shared command, clock/reset and status routes require actual source bindings.'),
            dict(code='STATIC_SM_WB_LOADER_JOINS_UNBOUND', family=family,
                 detail='PC-local wrapper ports do not establish the actual SM, writeback and loader schedule joins.')])
    for instance in instances:
        instance['actual_module'] = masters[instance['master']]['actual_module']
        instance['physical_pc_ids'] = masters[instance['master']]['physical_pc_ids']
        instance['status'] = 'actual_pc_leaf_wrapper_external_joins_unbound'
    for spec in [f'{PC_LEAF}:{PC_MODULE}', *module_specs]:
        rel, sep, name = spec.rpartition(':')
        need(sep and rel and name, f'--module requires PATH:MODULE, got {spec}')
        need(name not in module_tables, f'duplicate module {name}')
        path = source(rel)
        table = V.L.parse_module(str(path), name)['ports']
        need(bool(table), f'empty/unknown actual module: {name}')
        module_tables[name] = dict(source=rel, sha256=digest(path),
                                  ports={p: dict(direction=v[0], bits=v[1]) for p, v in table.items()},
                                  status='source_port_table_only_not_endpoint_binding')
    return dict(schema='opentallas.hbm_svc_v15_contract.v1',
                inventory_status='verified', qualification_status='rejected',
                qualification_rejections=rejections,
                note='Physical inventory is exact. Historical interfaces and source port tables do not prove v15 endpoint integration.',
                range_convention='All *_bits pairs are inclusive; dir_segments source pairs are half-open.',
                phy=dict(module=PHY_MODULE, dfi_bits=len(dfi), pc_count=32,
                         bits_per_pc=622, pc_fields=PC_FIELDS,
                         source_port_table={p: dict(direction=v[0], bits=v[1]) for p, v in phy_ports.items()}),
                families=families, masters=masters, instances=instances,
                actual_module_port_tables=module_tables, source_sha256=dict(sorted(sources.items())))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=DEFAULT_OUT)
    parser.add_argument('--module', action='append', default=[], metavar='PATH:MODULE',
                        help='Record an actual module port table; does not imply endpoint binding.')
    parser.add_argument('--generate-wrappers', action='store_true',
                        help='Write new PC-local actual wrappers derived from the physical inventory.')
    parser.add_argument('--require-bound', action='store_true', help='Fail when v15 qualification is rejected.')
    args = parser.parse_args()
    try:
        contract = build_contract(args.module, args.generate_wrappers)
        dest = ROOT / args.out
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps(contract, indent=2, sort_keys=True) + '\n')
        print(json.dumps(dict(output=str(dest), inventory_status=contract['inventory_status'],
                             qualification_status=contract['qualification_status'],
                             masters=len(contract['masters']), instances=len(contract['instances']),
                             rejections=len(contract['qualification_rejections']))))
        return 2 if args.require_bound else 0
    except (ValueError, KeyError, OSError) as error:
        print(f'REJECT: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
