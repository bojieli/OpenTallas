#!/usr/bin/env python3
"""Generate rm_access.hpp: typed accessors to the PRELOAD-ONLY memories of the REAL_MEM runtime
models (rtl/test/qwen_rom_runtime/qwen_rom_rt_w12_rm.cpp).

The host writes memory CONTENTS (ROM via masks, the HBM model's KV history, the vector memory's
X row) before a stage; it never serves a read.  The arrays are verilator-public (pragmas in the
REAL_MEM RTL, and a .vlt public_flat_rw rule for the unmodified ASAP7 macro models); this tool
finds their generated member names in V<model>___024root.h and emits one accessor per array:

  rm_vm / rm_prog / rm_desc / rm_crom / rm_crom_words      die arrays
  rm_scale_arr(root, port, bank)                          die scale-ROM macro via masks
  rm_hbm_mem(root)                                        die HBM model backing store
  rm_tile_rom_arr(root, pair, bank), rm_tile_kv_arr(root, half)   tile macro arrays
Fails if any expected array is missing (the build would otherwise silently serve nothing).
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path


def members(header: Path):
    text = header.read_text()
    return set(re.findall(r'\b(\w+)\s*;', text)) | set(re.findall(r'(\w+__DOT__\w+)', text))


def find(names, pattern, what):
    hits = sorted(n for n in names if re.fullmatch(pattern, n))
    if not hits:
        raise SystemExit(f'missing public array: {what} ({pattern})')
    return hits


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--die-header', type=Path, required=True)
    ap.add_argument('--tile-header', type=Path, required=True)
    ap.add_argument('--nport', type=int, required=True)
    ap.add_argument('--scale-banks', type=int, required=True)
    ap.add_argument('--code-banks', type=int, required=True)
    ap.add_argument('--crom-words', type=int, required=True)
    ap.add_argument('--hbm-layers', type=int, required=True)
    ap.add_argument('--kv-ideal', type=int, required=True)
    ap.add_argument('--embed-rom', type=int, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    dn, tn = members(a.die_header), members(a.tile_header)
    out = ['// GENERATED by tools/qwen_rom_rt_rm_access.py -- do not edit', '#pragma once', '#include <cstdint>',
           f'constexpr int RM_SCALE_BANKS = {a.scale_banks};', f'constexpr size_t RM_CROM_WORDS = {a.crom_words};',
           f'constexpr int RM_HBM_LAYERS = {a.hbm_layers};',
           'constexpr int RM_ROM_ROWS = 512, RM_ROM_ROWW = 67;   // ot_rom_4096x266_m8: 512 rows x 2,128 bits',
           'constexpr int RM_KV_ROWS = 130, RM_KV_ROWW = 9;      // ot_sram_1r1w_128x256_m1_r2c2: 130 rows x 258 bits']
    for fn, var in (('rm_vm', 'vm'), ('rm_prog', 'prog_mem'), ('rm_desc', 'desc_mem'),
                    ('rm_crom', 'crom_mem'), ('rm_crom_words', 'crom_words')):
        hit = find(dn, r'ot_qwen_rom_rt_die_w12_rm__DOT__' + var, fn)
        if len(hit) != 1:
            raise SystemExit(f'ambiguous {fn}: {hit}')
        out.append(f'static inline auto& {fn}(Vdie___024root* r) {{ return r->{hit[0]}; }}')
    if not a.kv_ideal:
        hit = find(dn, r'\w*u_hbm__DOT__mem', 'HBM mem')
        out.append(f'static inline auto& rm_hbm_mem(Vdie___024root* r) {{ return r->{hit[0]}; }}')
    out.append(f'#define RM_EMBED_ROM {a.embed_rom}')
    if a.embed_rom:
        for fn, var in (('rm_embed_codes', 'codes'), ('rm_embed_scales', 'scales')):
            hit = find(dn, r'\w*u_emb__DOT__' + var, fn)
            out.append(f'static inline auto& {fn}(Vdie___024root* r) {{ return r->{hit[0]}; }}')
    sc = {}
    for n in dn:
        m = re.fullmatch(r'\w*g_sc__BRA__(\d+)__KET____DOT__u_bank__DOT__g_m__BRA__(\d+)__KET____DOT__u_rom__DOT__arr', n)
        if m:
            sc[(int(m.group(1)), int(m.group(2)))] = n
    if len(sc) != a.nport * a.scale_banks:
        raise SystemExit(f'scale macro arrays: found {len(sc)}, expected {a.nport * a.scale_banks}')
    out.append('static inline uint32_t* rm_scale_arr(Vdie___024root* r, int g, int b) {')
    out.append('    switch (g * 1000 + b) {')
    for (g, b), n in sorted(sc.items()):
        out.append(f'    case {g * 1000 + b}: return reinterpret_cast<uint32_t*>(&r->{n}[0][0]);')
    out.append('    } return nullptr; }')
    tr, tk = {}, {}
    for n in tn:
        # (a76724a9c put the macro under a BAW generate scope g_f/g_h: allow one optional generate level)
        m = re.fullmatch(r'\w*g_colh?__BRA__(\d+)__KET____DOT__g_bank__BRA__(\d+)__KET____DOT__'
                         r'(?:g_[A-Za-z0-9]+__DOT__)?u_rom__DOT__arr', n)
        if m:
            tr[(int(m.group(1)), int(m.group(2)))] = n
        m = re.fullmatch(r'\w*g_kv__BRA__(\d+)__KET____DOT__u_kv__DOT__arr', n)
        if m:
            tk[int(m.group(1))] = n
    if len(tr) != 2 * a.code_banks or len(tk) != 2:
        raise SystemExit(f'tile macro arrays: rom {len(tr)} (expected {2 * a.code_banks}), kv {len(tk)} (expected 2)')
    out.append('static inline uint32_t* rm_tile_rom_arr(Vtile___024root* r, int p, int b) {')
    out.append('    switch (p * 1000 + b) {')
    for (p, b), n in sorted(tr.items()):
        out.append(f'    case {p * 1000 + b}: return reinterpret_cast<uint32_t*>(&r->{n}[0][0]);')
    out.append('    } return nullptr; }')
    out.append('static inline uint32_t* rm_tile_kv_arr(Vtile___024root* r, int p) {')
    out.append('    switch (p) {')
    for p, n in sorted(tk.items()):
        out.append(f'    case {p}: return reinterpret_cast<uint32_t*>(&r->{n}[0][0]);')
    out.append('    } return nullptr; }')
    a.out.write_text('\n'.join(out) + '\n')
    print(f'wrote {a.out}: {len(sc)} scale macros, {len(tr)} tile ROM macros, {len(tk)} tile KV macros')


if __name__ == '__main__':
    main()
