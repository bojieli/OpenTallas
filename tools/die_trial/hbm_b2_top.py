#!/usr/bin/env python3
"""Die top of the B2r2 trial (TRIAL-HBM step 1): adapts a `gen.py assembly` kit (mock partition abstracts) into a
placement + PDN + keep-out + GRT flow without editing tools/die_plan/*.

    python3 tools/die_plan/gen.py mockview PLAN --out VIEWS
    python3 tools/die_plan/gen.py assembly PLAN --out KIT --views VIEWS
    python3 tools/die_trial/hbm_b2_top.py PLAN --kit KIT/die          -> KIT/die/trial_flow.tcl, keepouts.json, trial_post.py
    (docker, /work = KIT/die) openroad -exit /work/trial_flow.tcl ; openroad -python /work/trial_post.py

Differences to the kit's die_flow.tcl (kept unchanged in the kit):
- place_macro with the EXACT plan origins (%.4f).  gen_phys.die_flow_tcl / macro_place_tcl print origins with %g
  (6 significant digits), which moves every partition with an origin >= 10000 um by up to 0.04 um; the flow first
  places with those %g values and reports their legality (finding), then re-places exactly.
- M1-M3 tracks coarse (0.64 um, as g2.py die_probe) so the GRT gcell grid stays die-sized; M4-M9 = plan tracks.
- keep-outs: full-stack M1-M9 obstructions over the HBM PHY content rect (the die.io window of PHY_N = the PHY_N
  outline: its content has no own outline) and over every SerDes / UCIe content rect; created AFTER pdngen so the
  die PG stays continuous over the PHYs (the PHYs are powered by the grid; the keep-out is for die signal routing).
- no detailed route (DRT skipped: abutted seams are pin-to-pin, the die nets are the clock / reset spine only).
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "die_plan"))
import schema as S  # noqa: E402
import gen_rtl  # noqa: E402
import gen_phys  # noqa: E402

KEEP_MODS = ("ot_pdie_serdes", "ot_pdie_ucie_col", "ot_hbm3e_phy_rc_e8p5")


def keepouts(P):
    ko = []
    for n, p in sorted(P.parts.items()):
        t = P.types[p["type"]]
        for c in t.get("contents", []):
            if c["module"] not in KEEP_MODS:
                continue
            if "outline_um" in c:
                (ax, ay), (bx, by) = P.to_die(n, c["origin_um"]), P.to_die(
                    n, (c["origin_um"][0] + c["outline_um"][0], c["origin_um"][1] + c["outline_um"][1]))
                r = [min(ax, bx), min(ay, by), max(ax, bx), max(ay, by)]
                src = "content outline"
            else:
                r = list(P.rect(n))
                src = "partition outline (content has no outline; = die.io window)"
            ko.append(dict(part=n, inst=c["inst"], module=c["module"], rect_um=[round(v, 4) for v in r], source=src))
    return ko


def flow(P, kd, ko):
    top = f"{gen_rtl.sv_id(P.name)}_top"
    lefs = sorted(x.name for x in kd.glob("*.lef"))
    t = ["# GENERATED by tools/die_trial/hbm_b2_top.py (TRIAL-HBM die top).",
         "set PL /OpenROAD-flow-scripts/flow/platforms/asap7",
         "set t0 [clock seconds]",
         "read_lef $PL/lef/asap7_tech_1x_201209.lef", "read_lef $PL/lef/asap7sc7p5t_28_R_1x_220121a.lef"]
    t += [f"read_lef /work/{x}" for x in lefs]
    t += ["read_liberty $PL/lib/NLDM/asap7sc7p5t_INVBUF_RVT_TT_nldm_220122.lib.gz",
          "read_verilog /work/die_top_struct.v", f"link_design {top}",
          f"initialize_floorplan -die_area {{0 0 {P.W:.4f} {P.H:.4f}}} -core_area {{0 0 {P.W:.4f} {P.H:.4f}}} -site asap7sc7p5t"]
    for n in ("M9", "M8", "M7", "M6", "M5", "M4"):
        L = P.layers[n]
        t.append(f"make_tracks {n} -x_offset {L['pitch_um'] / 2:g} -x_pitch {L['pitch_um']:g} "
                 f"-y_offset {L['pitch_um'] / 2:g} -y_pitch {L['pitch_um']:g}")
    t += [f"make_tracks {n} -x_offset 0.32 -x_pitch 0.64 -y_offset 0.32 -y_pitch 0.64" for n in ("M3", "M2", "M1")]
    for name, L, x, y in gen_phys.die_root_pins(P):
        sz = "{0.04 0.32}" if P.layers[L]["dir"] == "V" else "{0.32 0.04}"
        t.append(f"place_pin -pin_name {name} -layer {L} -location {{{x:.4f} {y:.4f}}} -pin_size {sz}")
    t.append("puts \"OT_T_READ [expr {[clock seconds]-$t0}]\"")
    # legality proc: overlaps (area > 0) and out-of-die, from the placed instance bboxes
    t += ["proc ot_legal {tag} {",
          "  set b [ord::get_db_block]; set dbu [[$b getTech] getDbUnitsPerMicron]; set die [$b getDieArea]",
          "  set bb {}; set unpl 0; foreach i [$b getInsts] { if {![$i isPlaced]} { incr unpl; continue }; set r [$i getBBox]; lappend bb [list [$i getName] [$r xMin] [$r yMin] [$r xMax] [$r yMax]] }",
          "  set ov 0; set oa 0.0; set out 0; set ex {}",
          "  for {set a 0} {$a < [llength $bb]} {incr a} { lassign [lindex $bb $a] na ax0 ay0 ax1 ay1",
          "    if {$ax0 < [$die xMin] || $ay0 < [$die yMin] || $ax1 > [$die xMax] || $ay1 > [$die yMax]} { incr out; lappend ex \"OUT:$na\" }",
          "    for {set c [expr {$a+1}]} {$c < [llength $bb]} {incr c} { lassign [lindex $bb $c] nc cx0 cy0 cx1 cy1",
          "      set w [expr {min($ax1,$cx1)-max($ax0,$cx0)}]; set h [expr {min($ay1,$cy1)-max($ay0,$cy0)}]",
          "      if {$w > 0 && $h > 0} { incr ov; set oa [expr {$oa + double($w)*$h/$dbu/$dbu}]; if {[llength $ex] < 12} { lappend ex \"$na/$nc:[expr {double($w)/$dbu}]x[expr {double($h)/$dbu}]\" } } } }",
          "  set A 0.0; foreach r $bb { lassign $r n x0 y0 x1 y1; set A [expr {$A + double($x1-$x0)*($y1-$y0)/$dbu/$dbu}] }",
          "  set D [expr {double([$die dx])*[$die dy]/$dbu/$dbu}]",
          "  puts \"OT_LEGAL $tag placed [llength $bb] unplaced $unpl overlaps $ov overlap_um2 [format %.4f $oa] out_of_die $out macro_area_um2 [format %.1f $A] die_um2 [format %.1f $D] uncovered_um2 [format %.1f [expr {$D-$A+$oa}]] ex $ex\"",
          "}"]
    # (1) the kit's %g placement (finding), (2) exact
    for tag, fmt in (("kit_g", "{:g}"), ("pm_4dp", "{:.4f}")):
        t.append("set nfail 0; foreach i [[ord::get_db_block] getInsts] { $i setPlacementStatus NONE }")
        for n, p in sorted(P.parts.items()):
            x, y = p["origin_um"]
            t.append(f"if {{[catch {{place_macro -macro_name {gen_rtl.sv_id(n)} -location {{{fmt.format(x)} {fmt.format(y)}}} "
                     f"-orientation {p.get('orient', 'R0')} -exact}} e]}} {{ incr nfail; puts \"OT_PLACE_FAIL {tag} {n} $e\" }}")
        t.append(f"puts \"OT_PLACE_FAILS {tag} $nfail\"")
        t.append(f"ot_legal {tag}")
    # (3) odb: integer dbu from the plan (round, not truncate), DEF semantics (location = oriented bbox lower-left)
    t.append("foreach i [[ord::get_db_block] getInsts] { $i setPlacementStatus NONE }")
    for n, p in sorted(P.parts.items()):
        x, y = p["origin_um"]
        t.append(f"set i [[ord::get_db_block] findInst {gen_rtl.sv_id(n)}]; $i setOrient {p.get('orient', 'R0')}; "
                 f"$i setLocation {round(x * 1000)} {round(y * 1000)}; $i setPlacementStatus FIRM")
    t.append("ot_legal odb_exact")
    # plan origin vs placed origin check (exact)
    t.append("set nb 0; foreach {n x y} {" + " ".join(f"{gen_rtl.sv_id(n)} {p['origin_um'][0]:.4f} {p['origin_um'][1]:.4f}"
                                                   for n, p in sorted(P.parts.items())) + "} {"
             " set i [[ord::get_db_block] findInst $n]; set r [$i getBBox]; set dbu 1000.0;"
             " if {abs([$r xMin]/$dbu-$x) > 0.0005 || abs([$r yMin]/$dbu-$y) > 0.0005} { incr nb; puts \"OT_ORIGIN_MISMATCH $n [$r xMin] [$r yMin] plan $x $y\" } }; puts \"OT_ORIGIN_MISMATCHES $nb\"")
    t += ["puts \"OT_T_PLACE [expr {[clock seconds]-$t0}]\"",
          "source /work/pdn.tcl",
          "pdngen -failed_via_report /work/pdn_failed_vias.rpt",
          "puts \"OT_T_PDN [expr {[clock seconds]-$t0}]\"",
          "foreach n {VDD VSS} { if {[catch {check_power_grid -net $n -error_file /work/pg_$n.rpt} e]} "
          "{ puts \"OT_PG_CHECK_FAIL $n $e\" } else { puts \"OT_PG_CHECK_OK $n\" } }",
          "puts \"OT_T_PGCHECK [expr {[clock seconds]-$t0}]\""]
    # keep-outs after pdngen; pins inside keep-outs
    t.append("set KO {" + " ".join("{%s %s %.4f %.4f %.4f %.4f}" % (gen_rtl.sv_id(k["part"]), k["inst"], *k["rect_um"]) for k in ko) + "}")
    t += ["set b [ord::get_db_block]; set tech [$b getTech]",
          "foreach k $KO { lassign $k p ci x0 y0 x1 y1; foreach L {M1 M2 M3 M4 M5 M6 M7 M8 M9} {",
          "  odb::dbObstruction_create $b [$tech findLayer $L] [expr {round($x0*1000)}] [expr {round($y0*1000)}] [expr {round($x1*1000)}] [expr {round($y1*1000)}] } }",
          "puts \"OT_KEEPOUTS [llength $KO] x 9 layers\"",
          # every partition pin (signal + clk/rst taps) whose shape intersects a keep-out
          "set tot 0; foreach k $KO { lassign $k p ci x0 y0 x1 y1; set X0 [expr {round($x0*1000)}]; set Y0 [expr {round($y0*1000)}]; set X1 [expr {round($x1*1000)}]; set Y1 [expr {round($y1*1000)}]",
          "  set n 0; set nt 0; foreach i [$b getInsts] { set r [$i getBBox]; if {[$r xMax] <= $X0 || [$r xMin] >= $X1 || [$r yMax] <= $Y0 || [$r yMin] >= $Y1} { continue }",
          "    foreach it [$i getITerms] { set mt [$it getMTerm]; if {[$mt getSigType] in {POWER GROUND}} { continue }",
          "      set g [$it getBBox]; if {[$g xMax] > $X0 && [$g xMin] < $X1 && [$g yMax] > $Y0 && [$g yMin] < $Y1} { incr n; if {[$mt getSigType] eq {CLOCK} || [$mt getName] eq {arst_n}} { incr nt } } } }",
          "  puts \"OT_KO_PINS $p $ci pins $n taps $nt\"; incr tot $n }",
          "puts \"OT_KO_PINS_TOTAL $tot\"",
          "puts \"OT_T_KO [expr {[clock seconds]-$t0}]\"",
          "write_db /work/die_pdn.odb",
          f"set_routing_layers -signal M2-M9 -clock M2-M9",
          "if {[catch {global_route -allow_congestion -verbose -congestion_report_file /work/die_grt_congestion.rpt} e]} { puts \"OT_GRT_FAIL $e\" } else { puts OT_GRT_OK }",
          "set g [[ord::get_db_block] getGCellGrid]; if {$g ne \"NULL\"} { puts \"OT_GCELL X [llength [$g getGridX]] Y [llength [$g getGridY]]\" }",
          "puts \"OT_T_GRT [expr {[clock seconds]-$t0}]\"",
          "puts \"OT_DRT NOT_RUN (skipped in the trial: die nets = clock/reset spine; abutted seams pin-to-pin)\"",
          "write_db /work/die_top.odb",
          "write_def /work/die_top.def",
          "write_verilog /work/die_top.v",
          "puts \"OT_T_END [expr {[clock seconds]-$t0}]\"",
          "puts OT_DONE"]
    return "\n".join(t) + "\n"


POST = r'''# GENERATED by tools/die_trial/hbm_b2_top.py: die PG statistics from die_pdn.odb (openroad -python)
import json, collections, odb
from openroad import Design, Tech
tech = Tech(); db = tech.getDB()
odb.read_db(db, "/work/die_pdn.odb")
b = db.getChip().getBlock()
out = {}
for n in ("VDD", "VSS"):
    net = b.findNet(n)
    vias = collections.Counter(); wires = collections.Counter()
    for sw in net.getSWires():
        for w in sw.getWires():
            if w.isVia():
                v = w.getBlockVia() or w.getTechVia()
                lay = (v.getBottomLayer().getName() + "-" + v.getTopLayer().getName()) if v else "via"
                vias[lay] += 1
            else:
                wires[w.getTechLayer().getName()] += 1
    it = [i for i in net.getITerms()]
    out[n] = dict(stripes=dict(wires), vias=dict(vias), iterms=len(it))
json.dump(out, open("/work/pg_stats.json", "w"), indent=1)
print("OT_PGSTATS", json.dumps(out))
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("plan")
    ap.add_argument("--kit", required=True)
    a = ap.parse_args()
    P = S.Plan(S.load(a.plan))
    kd = Path(a.kit)
    ko = keepouts(P)
    (kd / "keepouts.json").write_text(json.dumps(dict(keepouts=ko, die_io=P.die.get("io", [])), indent=1) + "\n")
    (kd / "trial_flow.tcl").write_text(flow(P, kd, ko))
    (kd / "trial_post.py").write_text(POST)
    print(f"{len(ko)} keep-outs -> {kd}/trial_flow.tcl")


if __name__ == "__main__":
    main()
