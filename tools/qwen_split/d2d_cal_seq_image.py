#!/usr/bin/env python3
"""Emit the constant calendar image include for ot_qwen_d2d_cal_seq (rtl/qwen_sys/d2d_static_20261015).

    d2d_cal_seq_image.py CALDIR OUT.svh

CALDIR = the output of tools/qwen_split/d2d_link_calendar.py --profile program (calendar.json + eight memh images).
The include defines the admission run (segment 2: BEGIN/AUTH S->C, admission WITNESS C->S, once per epoch),
the first-token offset and the token period, and, per link end (C = compute die qfd_d2d_static, K = KV die qkd_d2d_static), the TX / RX images,
their segment-1 bases and the shared start table: START[0] = 0 (token run: terminal RESULT + embedding + L0),
START[l] = the compiled start of layer l relative to the token cal_start (calendar.json program.layers[l].start).
The production include is committed as rtl/qwen_sys/d2d_static_20261015/d2d_cal_image.svh; the full-program bench
regenerates it from the compiler run and refuses a difference.
"""
import json
import sys
from pathlib import Path

NE, NL, TW = 32, 36, 20


def words(p):
    v = [int(x, 16) for x in Path(p).read_text().split()]
    return v


def vec(vals, w):
    return f"{len(vals) * w}'h" + ''.join(f'{x:0{w // 4}x}' for x in reversed(vals))


def emit(caldir, out):
    cd = Path(caldir)
    cal = json.loads((cd / 'calendar.json').read_text())
    prog = cal['program']
    starts = [0] + [l['start'] for l in prog['layers'][1:]]
    assert len(starts) == NL and all(a < b for a, b in zip(starts, starts[1:])) and starts[-1] < 1 << TW
    lines = ['// GENERATED by tools/qwen_split/d2d_cal_seq_image.py from the d2d_link_calendar.py --profile program '
             'images: do not edit by hand',
             f'// pinreg={int(bool(cal["pinreg"]))} txl={cal["txl"]} phy={cal["phy"]} '
             f'token_cycles_through_L35={prog["token_cycles_through_L35"]}']
    for end in ('C', 'K'):
        for d in ('tx', 'rx'):
            img = words(cd / f'cal_{end}_{d}.memh')
            assert len(img) == NE, (end, d, len(img))
            s1 = words(cd / f'cal_{end}_{d}_seg1.memh')
            lines.append(f'localparam [32*{NE}-1:0] D2D_CAL_{end}_{d.upper()}_IMG = {vec(img, 32)};')
            lines.append(f"localparam [31:0] D2D_CAL_{end}_{d.upper()}_SEG1 = 32'h{s1[0]:08x};")
            s2 = words(cd / f'cal_{end}_{d}_seg2.memh')
            lines.append(f"localparam [31:0] D2D_CAL_{end}_{d.upper()}_SEG2 = 32'h{s2[0]:08x};")
    lines.append(f'localparam [{TW}*{NL}-1:0] D2D_CAL_START = {vec(starts, TW)};')
    adm = prog['admission']
    # one value per program, shared by both dies' sequencers and the compute face (first token / token period)
    lines.append(f'localparam integer D2D_ADM_OFS = {adm["ofs"]};      // admission cal_start, edges after the epoch strobe')
    lines.append(f'localparam integer D2D_ADM_LEN = {adm["len"]};    // admission run length (all calendars idle)')
    lines.append(f'localparam integer D2D_FIRST_TOKEN = {adm["first_token_ofs"]};  // first token cal_start, edges after the epoch strobe')
    lines.append(f'localparam integer D2D_TOKEN_PERIOD = {prog["token_period"]};  // compiled token period (token path totals padded to a 768-edge multiple)')
    # QXF-LINK 2026-10-18 (F4): the die masters' producer capture latency, compiled with the same program: the die GEN sets
    # qfd_d2d_static #(.TXDP(D2D_TXDP_C)) / qkd_d2d_static #(.TXDP(D2D_TXDP_K)) from these (no default exists in the RTL)
    for end in ('C', 'K'):
        v = cal['txd'][end]
        assert len(v) == 4 and all(1 <= x < 256 for x in v), (end, v)
        word = sum(x << (8 * p) for p, x in enumerate(v))
        lines.append(f"localparam [31:0] D2D_TXDP_{end} = 32'h{word:08x};   // {'compute' if end == 'C' else 'KV'} TXDP ports 0..3 = {v}"
                     + (f"; die stages {cal['die_stages']}" if cal.get('die_stages') and end == 'C' else ''))
    Path(out).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    emit(*sys.argv[1:])
