#!/usr/bin/env python3
"""Q-ELEM-CMP (2026-10-16): die-assigned pin rectangles of one generated master -> committed JSON + ref_tile io_tcl.

  extract LEF MASTER OUT.json            signal pin rectangles of MACRO MASTER in the die's elements.lef (PG skipped)
  tcl PINS.json OUT.tcl [--spread F:lo:hi:nlo:nhi ...]
                                         place_pin lines at the exact die centres; --spread maps the die span [lo, hi]
                                         along face F linearly onto [nlo, nhi] (order kept, centres snapped to the
                                         layer's preferred track) -- a pin-density fix the die adopts from the view
"""
import hashlib, json, math, sys

TRACK = {'M4': (.012, .048), 'M5': (.012, .048), 'M3': (.009, .036), 'M6': (.016, .064)}


def extract(lef, master, out):
    pins, inm, cur, use, layer, size = [], False, None, 'SIGNAL', None, None
    for line in open(lef):
        if line.startswith('MACRO '):
            inm = line.split()[1] == master
            continue
        if not inm:
            continue
        if line.startswith('END ' + master):
            break
        s = line.split()
        if not s:
            continue
        if s[0] == 'SIZE':
            size = [float(s[1]), float(s[3])]
        elif s[0] == 'PIN':
            cur, use = s[1], 'SIGNAL'
        elif s[0] == 'USE' and cur:
            use = s[1]
        elif s[0] == 'LAYER':
            layer = s[1]
        elif s[0] == 'RECT' and cur and use == 'SIGNAL':
            pins.append([cur, layer] + [float(v) for v in s[1:5]])
        elif s[0] == 'END' and len(s) > 1 and s[1] == cur:
            cur = None
        elif s[0] == 'OBS':
            cur = None
    if not pins:
        raise SystemExit(f'{master}: no pins in {lef}')
    W, H = size
    for p in pins:
        cx, cy = (p[2] + p[4]) / 2, (p[3] + p[5]) / 2
        d = dict(W=cx, E=W - cx, S=cy, N=H - cy)
        p.append(min(d, key=d.get))
    rec = dict(schema='opentallas.qwen.die-lef-pins.v1', master=master, size=size,
               source=dict(lef=lef, sha256=hashlib.sha256(open(lef, 'rb').read()).hexdigest()),
               fields=['pin', 'layer', 'x0', 'y0', 'x1', 'y1', 'face'], pins=pins)
    json.dump(rec, open(out, 'w'), indent=0)
    print(json.dumps(dict(master=master, pins=len(pins), size=size)))


def tcl(pj, out, spreads):
    rec = json.load(open(pj))
    W, H = rec['size']
    sp = {}
    for a in spreads:
        f, lo, hi, nlo, nhi = a.split(':')
        sp[f] = tuple(map(float, (lo, hi, nlo, nhi)))
    L = [f"# GENERATED by tools/qwen_split/die_lef_pins.py from {pj} (die elements.lef sha256 {rec['source']['sha256'][:16]})",
         f"# master {rec['master']} {W} x {H}; spreads {spreads or 'none (exact die centres)'}"]
    used = {}
    nbits = {}
    for p in rec['pins']:
        nbits[p[0].partition('[')[0]] = nbits.get(p[0].partition('[')[0], 0) + 1
    for name, layer, x0, y0, x1, y1, face in rec['pins']:
        base = name.partition('[')[0]
        if nbits[base] == 1 and name == base + '[0]':
            name = base          # the die LEF writes scalar RTL ports as <name>[0]; the netlist port is scalar
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        w, h = x1 - x0, y1 - y0
        if face in sp:
            lo, hi, nlo, nhi = sp[face]
            along = cy if face in 'EW' else cx
            v = nlo + (along - lo) * (nhi - nlo) / (hi - lo) if hi > lo else nlo
            off, pitch = TRACK[layer]
            v = round(off + round((v - off) / pitch) * pitch, 4)
            key = (face, layer, v)
            while key in used:          # never stack two pins on one track
                v = round(v + pitch, 4); key = (face, layer, v)
            used[key] = name
            if face in 'EW':
                cy = v
            else:
                cx = v
        loc = {'W': (0.0, cy), 'E': (W, cy), 'S': (cx, 0.0), 'N': (cx, H)}[face]
        L.append(f"place_pin -pin_name {{{name}}} -layer {layer} -location {{{loc[0]:.6f} {loc[1]:.6f}}} "
                 f"-pin_size {{{w:.3f} {h:.3f}}} -force_to_die_boundary")
    open(out, 'w').write('\n'.join(L) + '\n')
    print(json.dumps(dict(out=out, pins=len(L) - 2)))


if __name__ == '__main__':
    if sys.argv[1] == 'extract':
        extract(*sys.argv[2:5])
    elif sys.argv[1] == 'tcl':
        a = sys.argv[2:]
        spreads = [a[i + 1] for i in range(len(a)) if a[i] == '--spread']
        tcl(a[0], a[1], spreads)
