#!/usr/bin/env python3
"""Q-LINK r4 (2026-10-15): generate the pin-registered die masters qfd_d2d_static / qkd_d2d_static around the link-end
cores (qfd_d2d_static_core / qkd_d2d_static_core in ot_qwen_d2d_dies.sv).

Why (qkd_d2d_static_r1-r1-7ab4004a2 EARLY_FAIL_SETUP, post-CTS TT WNS -434 ps / 4,510 endpoints): every failing
class was a boundary path -- fdi_rx_v (N face) through the recovery drain logic (568 ps of cells), the 548-bit RX word
from the PHY-side frame register to record_rx / rx_payload pins on the opposite face (650 ps of wire + pads) -- with
the die IO budget leaving ~280 ps inside the tile.  Structural fix: every functional input is captured by a flop at
its pin and every output is launched by a flop at its pin (io_flop_at_pins places them), so no tile path starts or ends
at a port.  Cost, all static and compiled (tools/qwen_split/d2d_link_calendar.py --pinreg): PHY hop +2 (TX pin flop +
far RX pin flop), producer codec capture +2 (slot out + payload in), consumer outputs +1, cal_start/cfg +1 on both
dies (symmetric).  Clock, power-on and reset ports are not registered here (reset is synchronised by its consumers).
"""
import re, sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / 'rtl/qwen_sys/d2d_static_20261015/ot_qwen_d2d_dies.sv'
NOREG = {'ck', 'por_n', 'rst_n'}


def ports(text, mod):
    m = re.search(r'module\s+' + mod + r'\s*#\((.*?)\)\s*\((.*?)\);', text, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(2))
    out, d, w = [], None, ''
    for tok in [t.strip() for t in body.split(',')]:
        mm = re.match(r'(input|output)\s+(?:wire|reg)?\s*(\[[^\]]+\])?\s*(\w+)$', tok)
        if mm:
            d, w, n = mm.group(1), mm.group(2) or '', mm.group(3)
        else:
            n = re.match(r'(\w+)$', tok).group(1)
        out.append((d, w, n))
    return m.group(1), out


def wrapper(mod, params, plist, core_params):
    hdr = ',\n    '.join(f"{'input ' if d == 'input' else 'output'} wire {w + ' ' if w else ''}{n}" for d, w, n in plist)
    L = [f'module {mod} #({params}, parameter integer PR = 1) (\n    {hdr}\n);']
    conn = []
    for d, w, n in plist:
        if n in NOREG:
            conn.append(f'.{n}({n})')
            continue
        L.append(f'    wire {w + " " if w else ""}c_{n};')
        conn.append(f'.{n}(c_{n})')
        if d == 'input':
            L.append(f'    reg {w + " " if w else ""}q_{n};')
            L.append(f'    always @(posedge ck) q_{n} <= {n};')
            L.append(f'    assign c_{n} = PR ? q_{n} : {n};')
        else:
            L.append(f'    reg {w + " " if w else ""}q_{n};')
            L.append(f'    always @(posedge ck) q_{n} <= c_{n};')
            L.append(f'    assign {n} = PR ? q_{n} : c_{n};')
    L.append(f'    {mod}_core #({core_params}) u_core ({", ".join(conn)});')
    L.append('endmodule')
    return '\n'.join(L)


def main():
    t = SRC.read_text()
    begin = '// ==== PINREG WRAPPERS (generated by tools/qwen_split/d2d_pinreg_gen.py; do not edit) ===='
    t = t.split(begin)[0].rstrip() + '\n'
    # cores: rename once and expose the per-port producer capture latency
    t = t.replace('module qfd_d2d_static #(parameter integer MUT = 0) (',
                  "module qfd_d2d_static_core #(parameter integer MUT = 0, parameter [31:0] TXDP = {8'd2, 8'd1, 8'd2, 8'd1}) (")
    t = t.replace(".TXD({8'd2, 8'd1, 8'd2, 8'd1})", '.TXD(TXDP)')
    t = t.replace('module qkd_d2d_static #(parameter integer MUT = 0, parameter integer NL = 2) (',
                  "module qkd_d2d_static_core #(parameter integer MUT = 0, parameter integer NL = 2, parameter [31:0] TXDP = {8'd1, 8'd1, 8'd2, 8'd1}) (")
    t = t.replace(".TXD({8'd1, 8'd1, 8'd2, 8'd1})", '.TXD(TXDP)')
    _, pc = ports(t, 'qfd_d2d_static_core')
    _, pk = ports(t, 'qkd_d2d_static_core')
    w = [begin,
         '// Pin-registered die masters: every functional port has one flop at its pin (PR = 1, production).  The core',
         '// producer capture latency is +2 per EXTERNAL port (slot out + payload in); the compute STATUS codec\n// (port 2) is inside the core and keeps 1; see the generator docstring for the cost.',
         wrapper('qfd_d2d_static', 'parameter integer MUT = 0', pc,
                 ".MUT(MUT), .TXDP(PR ? {8'd4, 8'd1, 8'd3, 8'd3} : {8'd2, 8'd1, 8'd2, 8'd1})"),
         wrapper('qkd_d2d_static', 'parameter integer MUT = 0, parameter integer NL = 2', pk,
                 ".MUT(MUT), .NL(NL), .TXDP(PR ? {8'd3, 8'd3, 8'd4, 8'd3} : {8'd1, 8'd1, 8'd2, 8'd1})")]
    SRC.write_text(t + '\n' + '\n\n'.join(w) + '\n')
    print('pinreg wrappers:', len(pc), 'compute ports,', len(pk), 'KV ports')


if __name__ == '__main__':
    main()
