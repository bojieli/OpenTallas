"""QW-G5F2 10-20 (Q.BIND.1): emit the Qwen compute die fault-observability OR tree in the GEN (opt-in OT_SPLIT_FAULT_EMIT=1).

Every runtime fault output of the die (the 417 forwarded-lane landing `fault` pins created by _relays and the declared
hard-block fault ports: io_collective fault_code / transport_*, d2d_rom transport_fault, sys_face fault, mu_* mu_fault)
reaches ONE sticky root through hard qfd_fault_or_n<N> nodes (rtl/qwen_split/qfd_fault_or.sv, N <= 16, wrapper RTL
generated by gen_relay_rtl.py).  Structure (landed-regions standard; static: observation only, never stalls):

  pre  (before _relays):  one REGION ROOT node per fault owner block (the receivers of the landed lanes, from the plan
                          OT_SPLIT_FAULT_PLAN, + the hard fault blocks), on the owner's clock (ck_follow = owner) and
                          reset; the roots form a degree-capped Manhattan MST rooted at sys_face's root.  Every tree edge
                          is a 1-bit spine_local bus: _relays relays it (<= 405 um hops) as a forwarded lane that LANDS on
                          the parent's root; a zero-stage cross-root edge gets a landing station (_relays hook).
  post (after _relays, before _reset_tree):  every source bit is captured by a LEAF on the source's own clock root
                          within LOCAL_UM; leaves chain to the region root of the same clock root with hop nodes every
                          <= REACH_UM (same root: region-local wires, no crossing).  The tree's own new landings are
                          sources like the others.  Node N is fixed last (same 21.6 um footprint for every N, so the
                          planned pins of the pre-relay edges do not move).

The root output is left open: the bound sys_face view has no obs_fault input (Q.MU.FACE.3, owed).  Fails closed on a
source without a region root on its clock root, a node over 16 inputs, or any new wire over REACH_UM + node size.
physical_qualification_eligible = false (die chain decides).
"""
import collections
import json
import math
import os
import re
from pathlib import Path

W = H = 21.6
FANIN = 16
REACH_UM = 340.0        # node centre -> node centre (pins add <= 2 x 21.6: < 405 pin to pin)
LOCAL_UM = 180.0        # source pin -> leaf centre
TREE_DEG = int(os.environ.get('OT_SPLIT_FAULT_DEG', '8'))   # children per region root in the pre-relay MST
CLS = 'spine_local'
ARRAY_MASTERS = ('qfd_c_b16', 'qfd_dv_slice2')
ROW_DY = 400.0
GROUP_UM = float(os.environ.get('OT_SPLIT_FAULT_GROUP_UM', '300'))   # QW-G5FROOT landing-group linkage / site radius
GROUP_SKIP_UM = float(os.environ.get('OT_SPLIT_FAULT_GROUP_SKIP_UM', '180'))   # no group root only when a same-clock root can capture directly (LOCAL_UM)
WIDE_BITS = int(os.environ.get('OT_SPLIT_FAULT_WIDE_BITS', '1024'))
KEEP_UM = float(os.environ.get('OT_SPLIT_FAULT_KEEP_UM', '350'))
# QW-G5FROOT 10-20 reserved-fault-site cover (OT_SPLIT_FAULT_ROOT_MODE=cover, default): every landing of an owner is
# within CAP_UM (centre to landing centre) of a region / group root of the owner's clock, so post captures it with ONE
# direct same-clock wire (pin to pin <= CAP_UM + ~31 < 405) -- no leaf, no hop chain on the crowded slice faces.  Roots go
# only on boxes the base data GEN left free (plan reserved = every rly_* box of that exact base, mkplan_rfs.py).
ROOT_MODE = os.environ.get('OT_SPLIT_FAULT_ROOT_MODE', 'cover')
CAP_UM = float(os.environ.get('OT_SPLIT_FAULT_CAP_UM', '360'))
CAP_POST_UM = CAP_UM + 10.0     # post: root centre -> actual source pin
CAP_MAXM = int(os.environ.get('OT_SPLIT_FAULT_CAP_MAXM', '6'))   # captures per group root (+ <= TREE_DEG MST inputs <= 16)
HARD = 'io_collective:fault_code,transport_cdc_fault,transport_abort,transport_fault_cause;d2d_rom:transport_fault;' \
       'sys_face:fault;mu_ctxrx:mu_fault;mu_dhobs:mu_fault'
RST_PORTS = ('rst_n', 'rs', 'rs_n', 'rst', 'por_n')
ROOT_OWNER = 'sys_face'


def enabled():
    return os.environ.get('OT_SPLIT_FAULT_EMIT', '0') == '1'


def mname(n):
    return f'qfd_fault_or_n{n}'


def make_master(v, n):
    q = v.Master(mname(n), W, H, 3, f'QW-G5F2 die fault-OR node (rtl/qwen_split/qfd_fault_or.sv N={n}): sticky OR, '
                                    f'input pin registers, 2-stage reset landing, {n + 4} flops')
    q.face('ck', 1, 'N', 'M5', W / 2 - 1.08, 1)
    q.face('rs', 1, 'N', 'M5', W / 2 + 1.08, 1)
    for j in range(n):
        q.face(f'f{j}', 1, 'W', 'M4', 1.08 + 1.08 * j, 1)
    q.face('o', 1, 'E', 'M4', H / 2, 1)
    return q


def _hard(s=None):
    out = {}
    for part in (s or os.environ.get('OT_SPLIT_FAULT_HARD', HARD)).split(';'):
        if part.strip():
            inst, ports = part.split(':')
            out[inst.strip()] = [p.strip() for p in ports.split(',') if p.strip()]
    return out


class Occ:
    """coarse-grid occupancy of every placed rect (+ keep-outs)."""
    BK = 200.0

    def __init__(self, m):
        self.g = collections.defaultdict(list)
        self.W, self.H = m['die']['w'], m['die']['h']
        for it in m['insts']:
            self.add((it.x, it.y, it.x + it.w, it.y + it.h))
        for r in m.get('relay_keepouts', ()):
            self.add(tuple(r['rect']))

    def add(self, r):
        for gx in range(int(r[0] // self.BK), int(r[2] // self.BK) + 1):
            for gy in range(int(r[1] // self.BK), int(r[3] // self.BK) + 1):
                self.g[(gx, gy)].append(r)

    def free(self, r, gap=0.432):
        if r[0] < 0 or r[1] < 0 or r[2] > self.W or r[3] > self.H:
            return False
        for gx in range(int((r[0] - gap) // self.BK), int((r[2] + gap) // self.BK) + 1):
            for gy in range(int((r[1] - gap) // self.BK), int((r[3] + gap) // self.BK) + 1):
                for q in self.g.get((gx, gy), ()):
                    if q[0] < r[2] + gap and r[0] < q[2] + gap and q[1] < r[3] + gap and r[1] < q[3] + gap:
                        return False
        return True

    def site(self, v, cx, cy, rmax=400.0, step=4.32, ok=None):
        """lower-left of the free W x H node box whose centre is nearest (cx, cy) (Manhattan rings)."""
        for ring in range(0, int(rmax / step) + 1):
            st = ring * step
            cand = [(0.0, 0.0)] if ring == 0 else \
                [(dx, dy) for dx in (-st, st) for dy in [i * step for i in range(-ring, ring + 1)]] + \
                [(dx, dy) for dy in (-st, st) for dx in [i * step for i in range(-ring + 1, ring)]]
            for dx, dy in sorted(cand, key=lambda t: abs(t[0]) + abs(t[1])):
                x0, y0 = v.dn(cx - W / 2 + dx, v.GX), v.dn(cy - H / 2 + dy, v.GY)
                r = (x0, y0, x0 + W, y0 + H)
                if (ok is None or ok(r)) and self.free(r):
                    self.add(r)
                    return x0, y0
        return None


class RasterOcc(Occ):
    """QW-G5F3 10-20: Occ on a boolean raster (CELL um), used by post: free() is one numpy slice instead of a scan of the
    bucket lists (dv2f20g5f9/10 spent > 25 min in the post A*).  Conservative: a rect marks every cell it touches
    (+ gap), a box is free only when none of its cells is marked."""
    CELL = 4.32

    def __init__(self, m, gap=0.432):
        import numpy as np
        self.np = np
        self.W, self.H = m['die']['w'], m['die']['h']
        self.gap = gap
        self.r = np.zeros((int(self.W / self.CELL) + 2, int(self.H / self.CELL) + 2), dtype=bool)
        for it in m['insts']:
            self.add((it.x, it.y, it.x + it.w, it.y + it.h))
        for r in m.get('relay_keepouts', ()):
            self.add(tuple(r['rect']))

    def _ix(self, r, g):
        c = self.CELL
        e = 1e-6                                       # FP: a cell-aligned edge belongs to the cell it starts / ends
        return (max(0, int(math.floor((r[0] - g) / c + e))), max(0, int(math.floor((r[1] - g) / c + e))),
                min(self.r.shape[0] - 1, int(math.floor((r[2] + g) / c - e))), min(self.r.shape[1] - 1, int(math.floor((r[3] + g) / c - e))))

    def add(self, r):
        a, b, c_, d = self._ix(r, self.gap)
        self.r[a:c_ + 1, b:d + 1] = True

    def free(self, r, gap=0.432):
        if r[0] < 0 or r[1] < 0 or r[2] > self.W or r[3] > self.H:
            return False
        a, b, c_, d = self._ix(r, 0.0)
        return not self.r[a:c_ + 1, b:d + 1].any()

    def near_free(self, px, py, w, h, slack):
        """lower-left (cell-aligned, on the site grid) of the free w x h box whose centre is nearest (px, py) within
        `slack` (Manhattan), or None: one cumulative-sum window instead of a ring scan."""
        np = self.np
        c = self.CELL
        nb = int(round(w / c))                     # cells a cell-aligned box covers (21.6 / 4.32 -> 5)
        k = int(slack // c) + 1
        cx0, cy0 = int((px - w / 2) // c), int((py - h / 2) // c)
        x0, y0 = max(0, cx0 - k), max(0, cy0 - k)
        x1, y1 = min(self.r.shape[0], cx0 + k + nb), min(self.r.shape[1], cy0 + k + nb)
        sub = self.r[x0:x1, y0:y1]
        if sub.shape[0] < nb or sub.shape[1] < nb:
            return None
        S = np.zeros((sub.shape[0] + 1, sub.shape[1] + 1), dtype=np.int32)
        S[1:, 1:] = sub.cumsum(0).cumsum(1)
        occn = S[nb:, nb:] - S[:-nb, nb:] - S[nb:, :-nb] + S[:-nb, :-nb]
        ii, jj = np.nonzero(occn == 0)
        if ii.size == 0:
            return None
        llx, lly = (x0 + ii) * c, (y0 + jj) * c
        ok = (llx >= 0) & (lly >= 0) & (llx + w <= self.W) & (lly + h <= self.H)
        dist = np.abs(llx + w / 2 - px) + np.abs(lly + h / 2 - py)
        ok &= dist <= slack
        if not ok.any():
            return None
        q = np.argmin(np.where(ok, dist, np.inf))
        return float(llx[q]), float(lly[q])


def _bus_index(m, cls):
    out = {}
    for j, (bid, cl, bits, eps) in enumerate(m['buses']):
        if cl == cls:
            for e in eps:
                out.setdefault((e[0], e[1].lstrip('*')), j)
    return out


def _reset_index(m):
    """(inst, reset port) -> CLASS-'reset' bus (the _reset_tree builds those against the final placement); a reset pin on
    another 1-bit bus (a forwarded reset lane hop) is not a legal tap for a new node (its wire would not be re-treed)."""
    out = {}
    for j, (bid, cl, bits, eps) in enumerate(m['buses']):
        if cl == 'reset' and bits == 1:
            for i_, p_ in eps[1:]:
                p_ = p_.lstrip('*')
                if p_ in RST_PORTS or re.fullmatch(r'rst_c\d+r\d+', p_):
                    out.setdefault((i_, p_), j)
    return out


def _clock_bus(ckx, inst, M_ports):
    for p in ('ck', 'clk'):
        if (inst, p) in ckx:
            return ckx[(inst, p)]
    cands = sorted(j for (i, p), j in ckx.items() if i == inst)
    return cands[0] if cands else None


def _reset_bus(rsx, inst):
    for p in RST_PORTS:
        if (inst, p) in rsx:
            return rsx[(inst, p)]
    cands = sorted((p, j) for (i, p), j in rsx.items() if i == inst)
    return cands[0][1] if cands else None


def _near_reset(m, rsx, by, o, cj):
    """owner without a class-'reset' bus (d2d_rom: forwarded reset lane): the class-'reset' bus of the nearest instance on
    the SAME clock root, else of the nearest instance (the reset tree reaches the node; observation-only sticky)."""
    same = {e[0] for e in m['buses'][cj][3]}
    c0 = _ctr(by[o])
    best = None
    for (i, p), j in rsx.items():
        if i not in by or i == o:
            continue
        d = (0 if i in same else 1, _man(c0, _ctr(by[i])))
        if best is None or d < best[0]:
            best = (d, j)
    return best[1] if best else None


class Zones:
    """dv die routing zones of a node box (tools/qwen_rom_fulldie_b3r2.py _poly0, dv_gap_route): a field-to-field link
    must run in ONE band row gap or in the W|E seam; a link with an end outside the tile field is routed normally."""

    def __init__(self, v, m):
        import re as _re
        from qwen_split.relay_row_gaps import row_gaps
        self.fields = [r['rect'] for r in m['regions'] if r['kind'] == 'tile_field']
        self.corr = v.CORR
        self.on = bool(m.get('dv_gap_route'))
        self.gaps = row_gaps((it.y, it.y + it.h) for it in m['insts']
                             if _re.fullmatch(r't_\d+_\d+|c16_\w+', it.name)) if self.on else []
        self.seam = m.get('dv_seam')

    def in_field(self, x, y):
        return any(a - 1 <= x <= c + self.corr + 1 and b - 1 <= y <= d + 1 for a, b, c, d in self.fields)

    def of_box(self, r):
        cx, cy = (r[0] + r[2]) / 2, (r[1] + r[3]) / 2
        if not self.on or not self.in_field(cx, cy):
            return 'out'
        if self.seam and self.seam[0] <= r[0] and r[2] <= self.seam[1]:
            return 'seam'
        for k, (a, b) in enumerate(self.gaps):
            if a <= r[1] and r[3] <= b:
                return f'gap{k}'
        return None

    def target(self, x, y, owner=None):
        """a field target (or any target of a block that sits in the field: its landings may stand outside it) moves
        to the middle of the nearest row gap, x clamped into the owner's field rectangle."""
        if self.on and owner is not None and self.gaps:
            ox, oy = owner.x + owner.w / 2, owner.y + owner.h / 2
            f = next((r for r in self.fields if r[0] - 1 <= ox <= r[2] + self.corr + 1 and r[1] - 1 <= oy <= r[3] + 1), None)
            if f is not None:
                x = min(max(x, f[0] + 2 * W), f[2] - 2 * W)
                a, b = min(self.gaps, key=lambda g: abs((g[0] + g[1]) / 2 - y))
                return x, (a + b) / 2
        if not self.on or not self.in_field(x, y) or not self.gaps:
            return x, y
        if self.seam and self.seam[0] <= x <= self.seam[1]:
            return x, y
        a, b = min(self.gaps, key=lambda g: abs((g[0] + g[1]) / 2 - y))
        return x, (a + b) / 2

    @staticmethod
    def linkable(z1, z2):
        return z1 == 'out' or z2 == 'out' or z1 == z2


def _join(m, j, ep):
    bid, cl, bits, eps = m['buses'][j]
    m['buses'][j] = (bid, cl, bits, list(eps) + [ep])


def _man(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])


def _ctr(i):
    return (i.x + i.w / 2, i.y + i.h / 2)


def pre(v, m, G):
    """region roots + their MST (before _relays)."""
    if not enabled():
        return None
    plan = json.loads(Path(os.environ['OT_SPLIT_FAULT_PLAN']).read_text())
    by = {i.name: i for i in m['insts']}
    M = v.masters(m, 1)
    hard = _hard()
    owners = dict(plan['owners'])
    pos = G._pin_pos(v, m)
    for inst, ports in hard.items():
        if inst not in by:
            raise ValueError(f'fault emit: hard fault block {inst} not on this GEN')
        mp = M[by[inst].master].ports
        for p in ports:
            if p not in mp:
                raise ValueError(f'fault emit: {inst} ({by[inst].master}) has no port {p}')
        if inst not in owners:
            pts = [pos(inst, p) for p in ports]
            owners[inst] = dict(xy=[sum(q[0] for q in pts) / len(pts), sum(q[1] for q in pts) / len(pts)], landings=0)
    if ROOT_OWNER not in owners:
        raise ValueError('fault emit: no sys_face owner (tree root)')
    missing = sorted(o for o in owners if o not in by)
    if missing:
        raise ValueError(f'fault emit: plan owners not on this GEN: {missing[:10]}')
    ckx, rsx = _bus_index(m, 'clock_trunk'), _reset_index(m)
    # rfs try 11: plan pts carry the landing's receiving clock net (n_<bid>); a c16 cluster's _clock_bus pick is NOT the
    # clock its landings land on, so cover roots go per (owner, clock)
    cknet = {}
    for j_, (bid_, cl_, bits_, eps_) in enumerate(m['buses']):
        if cl_ == 'clock_trunk':
            cknet.setdefault(bid_, j_)
            cknet.setdefault('n_' + bid_, j_)
    v._ot_fault_cknet = cknet
    occ = Occ(m)
    # QW-G5FROOT 10-20: each reserved base relay / landing box carries a RES_HALO_UM halo: _relays books a frame as
    # w + SHAVE by h + SHAVE and its spot search snaps within a tolerance, so a root touching the bare box still moved the
    # base frame (dv2f20g5rf rfs try 1: 12 q3h_col 516-b nets over 405 next to the cluster row-gap group roots)
    RH = float(os.environ.get('OT_SPLIT_FAULT_RES_HALO_UM', '4.32'))   # with the deferred roots (_relays OT_SPLIT_FAULT_DEFER) the data placement no longer sees the roots: the halo only keeps roots off the base frames' edges
    plan['reserved'] = [[r_[0] - RH, r_[1] - RH, r_[2] + RH, r_[3] + RH] for r_ in plan.get('reserved', ())]
    for r_ in plan.get('reserved', ()):
        occ.add(tuple(r_))      # the relay / landing sites the same GEN used without the tree: roots keep off them
    # g5f try 6/7: dvw_st_wi (1,088 b) lost its END frames beside dvs_W5 to three roots + their landings: the ends of
    # every very wide die bus stay clear of roots (KEEP_UM box around each endpoint pin)
    kc = 0
    for bid, cl, bits, eps in m['buses']:
        if bits >= WIDE_BITS and cl not in ('clock_trunk', 'reset', 'constant'):
            for e in eps:
                x_, y_ = pos(e[0], e[1].lstrip('*'))
                occ.add((x_ - KEEP_UM, y_ - KEEP_UM, x_ + KEEP_UM, y_ + KEEP_UM))
                kc += 1
    zn = Zones(v, m)
    q = make_master(v, FANIN)
    M[q.name] = q
    rec = m.setdefault('fault_emit', dict(schema='opentallas.qwen.fault-emit.v1', physical_qualification_eligible=False,
                                          plan=os.environ['OT_SPLIT_FAULT_PLAN'], roots={}, edges=[]))
    follow = m.setdefault('ck_follow', {})
    roots = {}
    for o, r in sorted(owners.items()):
        cj, rj = _clock_bus(ckx, o, None), _reset_bus(rsx, o)
        if rj is None and cj is not None:
            rj = _near_reset(m, rsx, by, o, cj)
            rec.setdefault('borrowed_reset', {})[o] = m['buses'][rj][0] if rj is not None else None
        if cj is None or rj is None:
            raise ValueError(f'fault emit: owner {o} without clock ({cj}) / reset ({rj}) bus')
        tx, ty = zn.target(*r['xy'], owner=by[o])
        okz = lambda b: zn.of_box(b) is not None
        s = None
        if ROOT_MODE == 'cover':
            # rfs try 2 (dv2f20g5rh 'flt_root_dvs_E2 has no input'): the primary root sits within CAP_UM of one of the
            # owner's landings (nearest the gap target), so it always captures at least one source; a hard fault owner
            # (no landing pts) within CAP_UM of its fault port median (rfs try 8: 'flt_root_mu_dhobs has no input')
            own_ = [p_ for p_ in (r.get('pts') or []) if len(p_) < 3 or cknet.get(p_[2], cj) == cj]
            pts_ = sorted((tuple(p_[:2]) for p_ in (own_ or [r['xy']])), key=lambda p_: _man(p_, (tx, ty)))
            for p_ in pts_[:8]:
                s = occ.site(v, p_[0], p_[1], rmax=CAP_UM, step=8.64,
                             ok=lambda b, p_=p_: okz(b) and _man(((b[0] + b[2]) / 2, (b[1] + b[3]) / 2), p_) <= CAP_UM)
                if s is not None:
                    break
        s = s or occ.site(v, tx, ty, ok=okz) or occ.site(v, tx, ty, rmax=2000.0, step=17.28, ok=okz)
        if s is None:
            raise ValueError(f'fault emit: no free site for the region root of {o} near {r["xy"]}')
        nm = f'flt_root_{o}'
        it = v.Inst(nm, q.name, s[0], s[1], W, H, orient='R0', kind='fault', region=by[o].region, domain='stream_1p2')
        m['insts'].append(it)
        by[nm] = it
        _join(m, cj, (nm, 'ck'))
        _join(m, rj, (nm, 'rs'))
        follow[(nm, 'ck')] = o
        roots[o] = dict(inst=nm, xy=_ctr(it), clock=m['buses'][cj][0], reset=m['buses'][rj][0], children=[],
                        zone=zn.of_box((it.x, it.y, it.x + W, it.y + H)),
                        array=by[o].master.startswith(ARRAY_MASTERS), owner=o, cj=cj, rj=rj)
    # QW-G5FROOT 10-20: ONE region root per (owner, zone) of its landings.  dv2f20g5f11: 68 leaves (the dv slices' and the
    # clusters' landings in the OTHER row gap / the W|E seam, clock clk_r0) had no free route to any node of their clock root
    # (all of them in the owner's median gap; 0.4-2.8 mm), so dvs_E0's root ended with no input.  Each landing group in a
    # field zone other than the primary root's gets its own root on the owner's clock + reset, placed in that zone at the
    # group median before _relays (sites still free); its MST edge is a relayed lane that lands on the parent (same
    # static, observation-only edge as every tree edge).  Plan field owners[o].pts = the g5 landing sites (mkplan.py).
    nz = 0
    if os.environ.get('OT_SPLIT_FAULT_ZONE_ROOTS', '1') == '1':
        # group roots sit AT their landings: the 350 um wide-bus end keep-clear boxes cover many landing faces (dv2f20g5rf
        # try 2: none free within 300 um of c16_E0_0's (19262, 5448) group), so group roots use a smaller keep-clear
        # (GROUP_KEEP_UM) over the same insts + reserved relay sites + every root already placed
        gk = float(os.environ.get('OT_SPLIT_FAULT_GROUP_KEEP_UM', '100'))
        occ_g = Occ(m)      # m['insts'] already holds the primary roots
        occ_0 = Occ(m)      # second try: insts + reserved relay sites only (no keep-clear)
        for r_ in plan.get('reserved', ()):
            occ_g.add(tuple(r_))
            occ_0.add(tuple(r_))
        unplaced = []
        tiers = collections.Counter()
        for bid, cl, bits, eps in m['buses']:
            if bits >= WIDE_BITS and cl not in ('clock_trunk', 'reset', 'constant'):
                for e in eps:
                    x_, y_ = pos(e[0], e[1].lstrip('*'))
                    occ_g.add((x_ - gk, y_ - gk, x_ + gk, y_ + gk))
        for o, r in sorted(owners.items()):
            pts = r.get('pts') or []
            if not pts or o not in roots:
                continue
            if ROOT_MODE == 'cover':
                nz += _cover_roots(v, m, o, pts, roots, by, q, occ, occ_g, occ_0, zn, follow, unplaced, tiers)
                continue
            # landing groups by proximity (single linkage GROUP_UM): Zones lumps the dv slice row (both of its faces,
            # 2.6 mm apart) into one "gap", so a zone label does not tell reachability; distance does
            grps = []
            for pt in sorted(map(tuple, pts)):
                hit = [g_ for g_ in grps if any(_man(pt, q_) <= GROUP_UM for q_ in g_)]
                grps = [g_ for g_ in grps if g_ not in hit] + [[pt] + [q_ for g_ in hit for q_ in g_]]
            for ps in sorted(grps):
                gx = sorted(q_[0] for q_ in ps)[len(ps) // 2]
                gy = sorted(q_[1] for q_ in ps)[len(ps) // 2]
                if any(rr['cj'] == roots[o]['cj'] and _man(rr['xy'], (gx, gy)) <= GROUP_SKIP_UM for rr in roots.values()):
                    continue                        # a root of the same clock already serves this group
                okz2 = lambda b: zn.of_box(b) is not None
                # tiers: full 350 um wide-end keep-clear (as the primary roots) -> GROUP_KEEP_UM -> none
                s = occ.site(v, gx, gy, rmax=GROUP_UM, ok=okz2)
                tier = 0
                if s is None:
                    s, tier = occ_g.site(v, gx, gy, rmax=GROUP_UM, ok=okz2), 1
                if s is None:
                    s, tier = occ_0.site(v, gx, gy, rmax=GROUP_UM, ok=okz2), 2
                if s is None:
                    s, tier = occ_0.site(v, gx, gy, rmax=GROUP_UM), 3    # any free box (zone None = inside the field rows)
                if s is None:
                    # recorded; post fails closed (ORPHAN default fail) if this group's leaves then have no route
                    unplaced.append((o, round(gx), round(gy), len(ps)))
                    continue
                for oc_ in (occ, occ_g, occ_0):
                    oc_.add((s[0], s[1], s[0] + W, s[1] + H))
                z = zn.of_box((s[0], s[1], s[0] + W, s[1] + H))
                k_ = 0
                while f'{o}_g{k_}' in roots:
                    k_ += 1
                key = f'{o}_g{k_}'
                nm = f'flt_root_{key}'
                it = v.Inst(nm, q.name, s[0], s[1], W, H, orient='R0', kind='fault', region=by[o].region, domain='stream_1p2')
                m['insts'].append(it)
                by[nm] = it
                cj, rj = roots[o]['cj'], roots[o]['rj']
                _join(m, cj, (nm, 'ck'))
                _join(m, rj, (nm, 'rs'))
                follow[(nm, 'ck')] = o
                roots[key] = dict(roots[o], inst=nm, xy=_ctr(it), children=[], zone=z if z is not None else 'out',
                                  landings_in_group=len(ps), site_tier=tier)
                tiers[tier] += 1
                nz += 1
        rec['group_roots_unplaced'] = unplaced
        rec['group_root_site_tiers'] = dict(tiers)
        print(f'FAULT_EMIT groups: {nz} group roots placed (site tiers keep350/keep{gk:.0f}/nokeep/anybox {dict(tiers)}), {len(unplaced)} groups without a free site within '
              f'{GROUP_UM:.0f} um: {unplaced[:20]}', flush=True)
    # rfs try 10 (rf/rh 'flt_root_mu_dhobs has no input', rfw 'flt_root_dvs_W1 has no input'): a cover-mode root with no
    # candidate source of its clock within CAP_UM (its owner's landings had no free box within CAP, so the primary root fell
    # back to the gap target) is dropped BEFORE the MST, while another root of the same clock remains (sys_face kept)
    if ROOT_MODE == 'cover':
        cand_pts = collections.defaultdict(list)
        for o_, r_ in owners.items():
            if o_ in roots:
                for p_ in (r_.get('pts') or []):
                    cand_pts[cknet.get(p_[2], roots[o_]['cj']) if len(p_) > 2 else roots[o_]['cj']].append(tuple(p_[:2]))
        dropped = []
        for key in sorted(roots):
            r_ = roots[key]
            if key == ROOT_OWNER or key in hard or any(_man(r_['xy'], p_) <= CAP_UM for p_ in cand_pts[r_['cj']]):
                continue
            if not any(k2 != key and roots[k2]['cj'] == r_['cj'] for k2 in roots):
                continue
            dropped.append(key)
            del roots[key]
            m['insts'][:] = [i_ for i_ in m['insts'] if i_.name != r_['inst']]
            by.pop(r_['inst'], None)
            follow.pop((r_['inst'], 'ck'), None)
            for j_ in (r_['cj'], r_['rj']):
                bid_, cl_, bits_, eps_ = m['buses'][j_]
                m['buses'][j_] = (bid_, cl_, bits_, [e_ for e_ in eps_ if e_[0] != r_['inst']])
        rec['roots_dropped_no_source'] = dropped
        print(f'FAULT_EMIT cover: {len(dropped)} roots without a same-clock source within {CAP_UM:.0f} um dropped: {dropped[:12]}', flush=True)
    # degree-capped Prim MST from the sys_face root
    done, parent = {ROOT_OWNER}, {}
    left = set(roots) - done
    while left:
        best = None
        for c in left:
            for p in done:
                if len(roots[p]['children']) >= TREE_DEG or not Zones.linkable(roots[c]['zone'], roots[p]['zone']):
                    continue
                if roots[c]['array'] and roots[p]['array'] and abs(roots[c]['xy'][1] - roots[p]['xy'][1]) > ROW_DY:
                    continue      # array blocks link along their row gap only (a cross-row lane has no relay sites)
                d = _man(roots[c]['xy'], roots[p]['xy'])
                if best is None or d < best[0]:
                    best = (d, c, p)
        if best is None:
            raise ValueError(f'fault emit: MST: no linkable parent for {sorted(left)[:8]} (zones '
                             f'{sorted({roots[c]["zone"] for c in left})})')
        _, c, p = best
        parent[c] = p
        roots[p]['children'].append(c)
        done.add(c)
        left.discard(c)
    for p, r in sorted(roots.items()):
        for j, c in enumerate(r['children']):
            bid = f'flt_t_{c}'
            m['buses'].append((bid, CLS, 1, [(roots[c]['inst'], 'o'), (r['inst'], f'f{j}')]))
            rec['edges'].append(dict(bid=bid, child=c, parent=p, um=round(_man(roots[c]['xy'], r['xy']), 1),
                                     src_ck=roots[c]['clock'], dst_ck=r['clock']))
    rec['roots'] = {o: dict({k_: v_ for k_, v_ in r.items() if k_ not in ('cj', 'rj')},
                            xy=[round(r['xy'][0], 3), round(r['xy'][1], 3)]) for o, r in roots.items()}
    rec['zone_roots'] = nz
    rec['root_owner'] = ROOT_OWNER
    rec['zones'] = dict(collections.Counter(r['zone'] for r in roots.values()))
    M_ = dict(M)
    v.masters = lambda model, k=1, port_bits=None: dict(M_)
    rec['wide_end_keepclear'] = dict(bits=WIDE_BITS, um=KEEP_UM, boxes=kc)
    print(f'FAULT_EMIT pre: {kc} wide-bus end keep-clear boxes; {len(roots)} region roots, {len(rec["edges"])} tree edges, '
          f'max edge {max((e["um"] for e in rec["edges"]), default=0):.0f} um; {nz} of the roots are per-zone landing-group roots',
          flush=True)
    return rec


def _cover_roots(v, m, o, pts, roots, by, q, occ, occ_g, occ_0, zn, follow, unplaced, tiers):
    """QW-G5FROOT 10-20 cover: group roots of owner o so that every landing point lies within CAP_UM of a root of o's
    clock.  Greedy: seed = first uncovered point, members = the <= CAP_MAXM uncovered points within CAP_UM of it; the root
    site must be within CAP_UM of EVERY member (tiers: 350 um wide-end keep-clear -> GROUP_KEEP_UM -> none -> any box,
    reserved base relay sites always kept); no site -> half the members -> the seed alone -> recorded unplaced."""
    cknet = getattr(v, '_ot_fault_cknet', {})
    byck = collections.defaultdict(list)
    for p_ in pts:
        byck[cknet.get(p_[2], roots[o]['cj']) if len(p_) > 2 else roots[o]['cj']].append((p_[0], p_[1]))
    n_new = 0
    for cj0, pl_ in sorted(byck.items()):
        n_new += _cover_clock(v, m, o, cj0, pl_, roots, by, q, occ, occ_g, occ_0, zn, follow, unplaced, tiers)
    return n_new


def _cover_clock(v, m, o, cj0, pts, roots, by, q, occ, occ_g, occ_0, zn, follow, unplaced, tiers):
    same = lambda: [rr['xy'] for rr in roots.values() if rr['cj'] == cj0]
    unc = sorted(tuple(p_) for p_ in pts if not any(_man(p_, c_) <= CAP_UM for c_ in same()))
    n_new = 0
    while unc:
        p0 = unc[0]
        mem = sorted((q_ for q_ in unc if _man(p0, q_) <= CAP_UM), key=lambda q_: (_man(p0, q_), q_))[:CAP_MAXM]
        got = None
        for trial in (mem, mem[:max(1, len(mem) // 2)], [p0]):
            gx = sorted(q_[0] for q_ in trial)[len(trial) // 2]
            gy = sorted(q_[1] for q_ in trial)[len(trial) // 2]

            def okc(b, trial=trial, z=True):
                c_ = ((b[0] + b[2]) / 2, (b[1] + b[3]) / 2)
                return (not z or zn.of_box(b) is not None) and all(_man(c_, q_) <= CAP_UM for q_ in trial)
            for tier, oc, z in ((0, occ, True), (1, occ_g, True), (2, occ_0, True), (3, occ_0, False)):
                s = oc.site(v, gx, gy, rmax=CAP_UM, step=8.64, ok=lambda b, z=z, f=okc: f(b, z=z))
                if s is not None:
                    got = (s, tier)
                    break
            if got:
                break
        if not got:
            unplaced.append((o, round(p0[0]), round(p0[1]), 1))
            unc.remove(p0)
            continue
        s, tier = got
        for oc_ in (occ, occ_g, occ_0):
            oc_.add((s[0], s[1], s[0] + W, s[1] + H))
        k_ = 0
        while f'{o}_g{k_}' in roots:
            k_ += 1
        key = f'{o}_g{k_}'
        nm = f'flt_root_{key}'
        it = v.Inst(nm, q.name, s[0], s[1], W, H, orient='R0', kind='fault', region=by[o].region, domain='stream_1p2')
        m['insts'].append(it)
        by[nm] = it
        _join(m, cj0, (nm, 'ck'))
        _join(m, roots[o]['rj'], (nm, 'rs'))
        follow[(nm, 'ck')] = o
        c_ = _ctr(it)
        cov = [q_ for q_ in unc if _man(c_, q_) <= CAP_UM][:CAP_MAXM]
        z = zn.of_box((it.x, it.y, it.x + W, it.y + H))
        roots[key] = dict(roots[o], inst=nm, xy=c_, children=[], zone=z if z is not None else 'out', cj=cj0,
                          clock=m['buses'][cj0][0], landings_in_group=len(cov), site_tier=tier)
        tiers[tier] += 1
        n_new += 1
        unc = [q_ for q_ in unc if q_ not in cov]
    return n_new


def land_edges(m):
    """bids of the zero-stage cross-root tree edges (_relays gives each a landing station)."""
    rec = m.get('fault_emit')
    if not rec:
        return {}
    return {e['bid']: e for e in rec['edges'] if e['src_ck'] != e['dst_ck']}


def post(v, m, G):
    """leaves + hop chains to the region roots (after _relays, before _reset_tree)."""
    rec = m.get('fault_emit')
    if not enabled() or rec is None:
        return None
    by = {i.name: i for i in m['insts']}
    M = v.masters(m, 1)
    pos = G._pin_pos(v, m)
    ckx, rsx = _bus_index(m, 'clock_trunk'), _reset_index(m)
    used = set()
    for bid, cl, bits, eps in m['buses']:
        for e in eps:
            used.add((e[0], e[1].lstrip('*')))
    # sources: (inst, die port, real port, bit, clock bus, reset bus, pin xy)
    src, bad = [], []
    for it in m['insts']:
        if it.master.startswith('qfd_landh'):
            if (it.name, 'fault') in used:
                continue
            cj, rj = ckx.get((it.name, 'ck')), rsx.get((it.name, 'rs'))
            if cj is None:
                bad.append(f'{it.name}: landing without ck bus'); continue
            src.append((it.name, 'fault', 'fault', 0, cj, rj, pos(it.name, 'fault')))
    pj = m.get('port_join')
    for inst, ports in _hard().items():
        it = by[inst]
        mp = M[it.master].ports
        cj, rj = _clock_bus(ckx, inst, None), _reset_bus(rsx, inst)
        for p in ports:
            if (inst, p) in used:
                bad.append(f'{inst}.{p}: already connected'); continue
            n = mp[p][1]
            xy = pos(inst, p)
            if n == 1:
                src.append((inst, p, p, 0, cj, rj, xy))
                continue
            if pj is None:
                raise ValueError('fault emit: multi-bit hard fault port needs the GEN port_join table (absent)')
            for b in range(n):
                al = f'flt_{p}_{b}'
                pj.setdefault(it.master, {})[al] = (p, [b])
                src.append((inst, al, p, b, cj, rj, xy))
    if bad:
        raise ValueError(f'fault emit: {len(bad)} bad sources: {bad[:8]}')
    roots = {o: by[r['inst']] for o, r in rec['roots'].items()}
    root_ck = collections.defaultdict(list)
    for o, it in roots.items():
        root_ck[ckx[(it.name, 'ck')]].append(it)
    occ = RasterOcc(m) if os.environ.get('OT_SPLIT_FAULT_RASTER', '1') == '1' else Occ(m)
    follow = m.setdefault('ck_follow', {})
    # node table: name -> dict(inst, n_in, ck, rs, owner)
    nodes = {}
    for o, it in roots.items():
        nodes[it.name] = dict(it=it, n=len(rec['roots'][o]['children']), ck=ckx[(it.name, 'ck')],
                              rs=rsx[(it.name, 'rs')], owner=rec['roots'][o].get('owner', o), root=True, up=None)
    q16 = make_master(v, FANIN)
    new_buses, nn = [], [0]
    owner_of_root = {it.name: rec['roots'][o].get('owner', o) for o, it in roots.items()}

    def new_node(kind, cx, cy, cj, rj, owner, ok=None, at=None):
        if at is not None:
            if not occ.free((at[0], at[1], at[0] + W, at[1] + H)):
                raise ValueError(f'fault emit: routed {kind} box {at} no longer free')
            occ.add((at[0], at[1], at[0] + W, at[1] + H))
            s = at
        else:
            s = occ.site(v, cx, cy, ok=ok) or occ.site(v, cx, cy, rmax=1200.0, step=8.64, ok=ok)
        if s is None:
            raise ValueError(f'fault emit: no free site for a {kind} near ({cx:.1f}, {cy:.1f})')
        nm = f'flt_{kind}{nn[0]}'
        nn[0] += 1
        it = v.Inst(nm, q16.name, s[0], s[1], W, H, orient='R0', kind='fault', region=by[owner].region,
                    domain='stream_1p2')
        m['insts'].append(it)
        by[nm] = it
        _join(m, cj, (nm, 'ck'))
        _join(m, rj, (nm, 'rs'))
        follow[(nm, 'ck')] = owner
        nodes[nm] = dict(it=it, n=0, ck=cj, rs=rj, owner=owner, root=False, up=None)
        return nm

    def take(nm):
        d = nodes[nm]
        if d['n'] >= FANIN:
            raise ValueError(f'fault emit: {nm} over {FANIN} inputs')
        d['n'] += 1
        return f'f{d["n"] - 1}'

    def connect(child, parent):
        p = take(parent)
        new_buses.append((f'flt_c_{child}', CLS, 1, [(child, 'o'), (parent, p)]))
        nodes[child]['up'] = parent

    # 1. leaves beside the sources (one clock root per leaf)
    leaves = collections.defaultdict(list)       # clock bus -> leaf names
    orphans = []
    dead = collections.defaultdict(set)   # clock bus -> grid keys of free components with no node of that root
    worst_src = 0.0
    for inst, port, real, bit, cj, rj, xy in sorted(src, key=lambda t: (t[4], t[6][0], t[6][1])):
        if cj not in root_ck:
            raise ValueError(f'fault emit: {inst}.{port} clock {m["buses"][cj][0]} has no region root (plan stale)')
        # QW-G5FROOT: a region / group root of the same clock within LOCAL_UM captures the source itself (no leaf)
        cand = [l for l in leaves[cj] + [r_.name for r_ in root_ck[cj]]
                if nodes[l]['n'] < FANIN and _man(_ctr(nodes[l]['it']), xy) <=
                (CAP_POST_UM if ROOT_MODE == 'cover' and nodes[l]['root'] else LOCAL_UM)]
        if cand:
            # rfs try 2: an input-less root within reach takes the source first (no node may end without an input)
            lf = min(cand, key=lambda l: (nodes[l]['n'] > 0, _man(_ctr(nodes[l]['it']), xy)))
        else:
            r0 = root_ck[cj][0]
            owner = owner_of_root[r0.name]
            lf = new_node('leaf', xy[0], xy[1], cj, rj if rj is not None else nodes[r0.name]['rs'], owner)
            leaves[cj].append(lf)
        worst_src = max(worst_src, _man(_ctr(nodes[lf]['it']), xy))
        new_buses.append((f'flt_s_{inst}_{port}', CLS, 1, [(inst, port), (lf, take(lf))]))
    def _free_near(px, py, slack=26.0, step=4.32):
        """lower-left of a free node box centred within `slack` (Manhattan) of (px, py), not booked."""
        if hasattr(occ, 'near_free'):
            return occ.near_free(px, py, W, H, slack)
        k = int(slack / step)
        for ring in range(0, k + 1):
            st = ring * step
            cand = [(0.0, 0.0)] if ring == 0 else \
                [(dx, dy) for dx in (-st, st) for dy in [i * step for i in range(-ring, ring + 1)]] + \
                [(dx, dy) for dy in (-st, st) for dx in [i * step for i in range(-ring + 1, ring)]]
            for dx, dy in sorted(cand, key=lambda t_: abs(t_[0]) + abs(t_[1])):
                if abs(dx) + abs(dy) > slack:
                    continue
                x0, y0 = v.dn(px - W / 2 + dx, v.GX), v.dn(py - H / 2 + dy, v.GY)
                if occ.free((x0, y0, x0 + W, y0 + H)):
                    return x0, y0
        return None

    def _hop_route(c0, tl, slack=26.0, stats=None):
        """QW-G5F3 10-20: A* over free node boxes (each hop <= REACH_UM centre to centre) from c0 until within REACH_UM
        of t; detours through row gaps / channels around hard blocks (dv2f20g5f4: the straight line from a leaf near
        (10688, 13116) crossed a cluster with no free box).  -> list of lower-lefts, or None."""
        import heapq
        # tl: [(name, centre)] = every attached node of the clock root with a free input (join the nearest reachable)
        S_ = REACH_UM - 2 * 26.0 - 4.0
        dirs = []
        stats = stats if stats is not None else {}
        for fr in (1.0, 0.7, 0.45, 0.25):
            for a_ in range(16):
                ux, uy = math.cos(a_ * math.pi / 8), math.sin(a_ * math.pi / 8)
                k_ = fr * S_ / (abs(ux) + abs(uy))
                dirs.append((ux * k_, uy * k_))
        hd = lambda p_: min(_man(p_, c_) for _, c_ in tl)
        q = 43.2
        start = (c0[0], c0[1])
        heap = [(math.ceil(hd(start) / S_), 0, 0, start, None, None)]
        back, seen = {}, set()
        n_exp, tie = 0, 0
        while heap and n_exp < 40000:
            f_, g_, _t, p_, ll, pk = heapq.heappop(heap)
            key = (round(p_[0] / q), round(p_[1] / q))
            if key in seen:
                continue
            seen.add(key)
            back[key] = (ll, pk)        # parent fixed at pop: the box chain is exactly the expanded one
            n_exp += 1
            hit = [nm_ for nm_, c_ in tl if _man(p_, c_) <= REACH_UM]
            if g_ > 0 and hit:
                out = []
                k_ = key
                while k_ is not None and back[k_][0] is not None:
                    out.append(back[k_][0])
                    k_ = back[k_][1]
                return out[::-1], min(hit, key=lambda nm_: _man(p_, _ctr(by[nm_])))
            for dx, dy in dirs:
                s_ = _free_near(p_[0] + dx, p_[1] + dy, slack=slack, step=4.32 if slack <= 30 else 8.64)
                if s_ is None:
                    continue
                cc = (s_[0] + W / 2, s_[1] + H / 2)
                if _man(p_, cc) > REACH_UM or _man(p_, cc) < 60.0:   # >= 60 um per hop: route boxes never touch
                    continue
                k2 = (round(cc[0] / q), round(cc[1] / q))
                if k2 in seen:
                    continue
                tie += 1
                heapq.heappush(heap, (g_ + 1 + 2.0 * max(0.0, hd(cc) - REACH_UM) / S_, g_ + 1, tie, cc, s_, key))   # weighted A*
        stats.update(expanded=n_exp, open_left=len(heap), slack=slack)
        if not heap:
            stats['_seen'] = seen      # whole free component exhausted: dead for this clock root (occupancy only grows)
        return None, None

    # QW-G5F3 10-20: hop-distance field per clock root on a 43.2 um cell grid (numpy BFS from the root nodes over cells that
    # hold a free node box; a hop = <= RC cells centre to centre, so the real box-to-box Manhattan stays <= REACH_UM).
    # A leaf walks the field down to its root; a leaf on no field cell is in a component without its root (ORPHAN).
    import numpy as _np
    PC = 43.2
    RC = int((REACH_UM - 2 * PC) // PC)                     # 5 cells = 216 um between cell centres
    _offs = [(di, dj) for di in range(-RC, RC + 1) for dj in range(-RC, RC + 1) if 0 < abs(di) + abs(dj) <= RC]
    fields = {}

    def _usable():
        """cells holding at least one free node box (from the live raster)."""
        r = occ.r
        c = occ.CELL
        nb = int(round(W / c))
        S = _np.zeros((r.shape[0] + 1, r.shape[1] + 1), dtype=_np.int32)
        S[1:, 1:] = r.cumsum(0, dtype=_np.int32).cumsum(1, dtype=_np.int32)
        okb = (S[nb:, nb:] - S[:-nb, nb:] - S[nb:, :-nb] + S[:-nb, :-nb]) == 0     # box lower-left at raster (i, j) free
        k = int(round(PC / c))
        nx, ny = okb.shape[0] // k, okb.shape[1] // k
        return okb[:nx * k, :ny * k].reshape(nx, k, ny, k).any(axis=(1, 3))

    def _cell(p_):
        return int(p_[0] // PC), int(p_[1] // PC)

    def _field(cj):
        if cj in fields:
            return fields[cj]
        U = _usable()
        nx, ny = U.shape
        dist = _np.full((nx, ny), -1, dtype=_np.int32)
        gx, gy = _np.meshgrid((_np.arange(nx) + 0.5) * PC, (_np.arange(ny) + 0.5) * PC, indexing='ij')
        seed = _np.zeros((nx, ny), dtype=bool)
        for rt in root_ck[cj]:
            c_ = _ctr(rt)
            seed |= (_np.abs(gx - c_[0]) + _np.abs(gy - c_[1])) <= REACH_UM - PC
        fr = seed & U
        dist[fr] = 0
        lvl = 0
        while fr.any() and lvl < 400:
            lvl += 1
            nxt = _np.zeros_like(fr)
            for di, dj in _offs:
                a0, a1 = max(0, di), nx + min(0, di)
                b0, b1 = max(0, dj), ny + min(0, dj)
                nxt[a0:a1, b0:b1] |= fr[a0 - di:a1 - di, b0 - dj:b1 - dj]
            nxt &= U & (dist < 0)
            dist[nxt] = lvl
            fr = nxt
        fields[cj] = dist
        return dist

    def _field_route(c0, cj):
        """-> (list of box lower-lefts, why).  [] + 'orphan' when the leaf sits on no field cell of its root."""
        dist = _field(cj)
        nx, ny = dist.shape
        ci, cj_ = _cell(c0)
        best = None
        for di, dj in [(0, 0)] + _offs:
            i, j = ci + di, cj_ + dj
            if 0 <= i < nx and 0 <= j < ny and dist[i, j] >= 0 and (best is None or dist[i, j] < dist[best]):
                best = (i, j)
        if best is None:
            return None, 'orphan'
        out, prev = [], c0
        cur = None
        while True:
            cands = [best] if cur is None else \
                sorted([(cur[0] + di, cur[1] + dj) for di, dj in _offs
                        if 0 <= cur[0] + di < nx and 0 <= cur[1] + dj < ny and dist[cur[0] + di, cur[1] + dj] == dist[cur] - 1],
                       key=lambda q_: abs(q_[0] - cur[0]) + abs(q_[1] - cur[1]), reverse=True)
            placed = None
            for q_ in cands:
                s_ = occ.near_free((q_[0] + 0.5) * PC, (q_[1] + 0.5) * PC, W, H, PC)
                if s_ is None:
                    continue
                cc = (s_[0] + W / 2, s_[1] + H / 2)
                if 60.0 <= _man(prev, cc) <= REACH_UM and all(abs(cc[0] - o_[0] - W / 2) > W or abs(cc[1] - o_[1] - H / 2) > H for o_ in out):
                    placed = (q_, s_, cc)
                    break
            if placed is None:
                return None, 'walk'
            cur, s_, prev = placed
            out.append(s_)
            if dist[cur] == 0:
                return out, 'ok'

    # 2. each leaf joins the nearest attached node of its clock root (roots first), hops every <= REACH_UM
    for cj, ls in sorted(leaves.items()):
        att = [r.name for r in root_ck[cj]]
        for lf in sorted(ls, key=lambda l: min(_man(_ctr(nodes[l]['it']), _ctr(by[a])) for a in att)):
            cur = lf
            while True:
                c0 = _ctr(nodes[cur]['it'])
                okp = [a for a in att if nodes[a]['n'] < FANIN]
                if not okp:
                    raise ValueError(f'fault emit: clock {m["buses"][cj][0]}: no attached node with a free input')
                tgt = min(okp, key=lambda a: _man(c0, _ctr(by[a])))
                d = _man(c0, _ctr(by[tgt]))
                if d <= REACH_UM:
                    connect(cur, tgt)
                    break
                t = _ctr(by[tgt])
                if os.environ.get('OT_SPLIT_FAULT_ASTAR', '1') == '1':
                    tl_ = [(a, _ctr(by[a])) for a in okp]
                    st1, st2 = {}, {}
                    k0 = (round(c0[0] / 43.2), round(c0[1] / 43.2))
                    route, why_ = (None, 'off')
                    if os.environ.get('OT_SPLIT_FAULT_FIELD', '1') == '1' and hasattr(occ, 'near_free') and cur == lf:
                        route, why_ = _field_route(c0, cj)
                        st1 = dict(field=why_)
                        if route is not None:
                            tgt2 = None
                    if route is not None:
                        pass
                    elif why_ == 'orphan' or k0 in dead[cj]:
                        route, st1 = None, dict(dead_component=True, field=why_)
                    else:
                        route, tgt2 = _hop_route(c0, tl_, stats=st1)
                        if route is None:   # wider snap (box still checked <= REACH_UM centre to centre)
                            route, tgt2 = _hop_route(c0, tl_, slack=150.0, stats=st2)
                        s1_, s2_ = st1.pop('_seen', None), st2.pop('_seen', None)
                        if route is None and s1_ is not None and s2_ is not None:
                            dead[cj] |= s1_ & s2_
                    if route is None and cur == lf and os.environ.get('OT_SPLIT_FAULT_ORPHAN', 'fail') == 'record':
                        # QW-G5F3: the leaf's free component holds no node of its clock root (dv2f20g5f8: flt_leaf229 in
                        # the y 18697 row gap, its clock root's nodes in the y 13409 gap; 31k boxes searched).  Recorded
                        # ORPHAN: the leaf is withdrawn, its sources stay open (as on the base g5 die); a region root per
                        # (owner, row gap) in pre is the structural fix (owed).
                        orphans.append(dict(leaf=lf, xy=[round(c0[0], 1), round(c0[1], 1)], clock=m['buses'][cj][0],
                                            nearest=tgt, nearest_um=round(d, 1), stats=st2 or st1))
                        break
                    if route is None:
                        raise ValueError(f'fault emit: no hop route from {cur} {c0} (clock {m["buses"][cj][0]}, sources '
                                         f'{[b_[3][0] for b_ in new_buses if b_[3][1][0] == lf][:6]}) to any of {len(okp)} attached nodes, nearest {tgt} {t} '
                                         f'(A* {st1} / wide {st2}; free boxes within 340 um of the leaf: '
                                         f'{sum(1 for gx in range(-8, 9) for gy in range(-8, 9) if abs(gx) + abs(gy) <= 8 and occ.free((c0[0] - W / 2 + 40 * gx, c0[1] - H / 2 + 40 * gy, c0[0] + W / 2 + 40 * gx, c0[1] + H / 2 + 40 * gy)))}/145 sampled)')
                    for k_, ll in enumerate(route):
                        if not occ.free((ll[0], ll[1], ll[0] + W, ll[1] + H)):
                            # an earlier box of this same route took it: re-snap within reach of both neighbours
                            pc = _ctr(nodes[cur]['it'])
                            nx = (route[k_ + 1][0] + W / 2, route[k_ + 1][1] + H / 2) if k_ + 1 < len(route) else \
                                (_ctr(by[tgt2]) if tgt2 else min((_ctr(by[a]) for a in okp), key=lambda c_: _man(c_, (ll[0] + W / 2, ll[1] + H / 2))))
                            ll2 = None
                            for sl in (26.0, 60.0, 120.0):
                                q_ = _free_near(ll[0] + W / 2, ll[1] + H / 2, slack=sl, step=4.32)
                                if q_ and _man(pc, (q_[0] + W / 2, q_[1] + H / 2)) <= REACH_UM and \
                                        _man(nx, (q_[0] + W / 2, q_[1] + H / 2)) <= REACH_UM:
                                    ll2 = q_
                                    break
                            if ll2 is None:
                                raise ValueError(f'fault emit: routed hop box {ll} taken, no re-snap within reach')
                            ll = ll2
                        hop = new_node('hop', 0, 0, cj, nodes[cur]['rs'], nodes[cur]['owner'], at=ll)
                        if _man(_ctr(nodes[cur]['it']), _ctr(nodes[hop]['it'])) > REACH_UM:
                            raise ValueError(f'fault emit: A* hop for {cur} too far')
                        connect(cur, hop)
                        cur = hop
                    continue
                f = REACH_UM * 0.9 / d
                hx, hy = c0[0] + (t[0] - c0[0]) * f, c0[1] + (t[1] - c0[1]) * f
                # QW-G5F3 10-20: the hop site must stay within REACH_UM of the current node AND make >= 40 um progress to the
                # target (dv2f20g5f3b: the nearest free box to the 0.9-reach point lay 523 um from flt_hop461's source)
                def _okh(r, c0=c0, t=t, d=d):
                    cc = ((r[0] + r[2]) / 2, (r[1] + r[3]) / 2)
                    return _man(c0, cc) <= REACH_UM and _man(cc, t) <= d - 40.0
                hop = new_node('hop', hx, hy, cj, nodes[cur]['rs'], nodes[cur]['owner'], ok=_okh)
                if _man(c0, _ctr(nodes[hop]['it'])) > REACH_UM:
                    raise ValueError(f'fault emit: hop site for {cur} too far ({_man(c0, _ctr(nodes[hop]["it"])):.0f} um)')
                connect(cur, hop)
                cur = hop
            if not (orphans and orphans[-1]['leaf'] == lf):
                att.append(lf)
    if orphans:
        gone = {o_['leaf'] for o_ in orphans}
        for o_ in orphans:
            o_['sources'] = [f'{e[0][0]}.{e[0][1]}' for b_, c_, n_, e in new_buses if e[1][0] == o_['leaf']]
        new_buses[:] = [b for b in new_buses if not any(e_[0] in gone for e_ in b[3])]
        m['insts'][:] = [i_ for i_ in m['insts'] if i_.name not in gone]
        for j_, (bid_, cl_, bits_, eps_) in enumerate(m['buses']):
            if any(e_[0] in gone for e_ in eps_):
                m['buses'][j_] = (bid_, cl_, bits_, [e_ for e_ in eps_ if e_[0] not in gone])
        for g_ in gone:
            nodes.pop(g_, None)
            by.pop(g_, None)
            follow.pop((g_, 'ck'), None)
        src[:] = [s_ for s_ in src if s_[:2] not in {tuple(x_.split('.', 1)) for o_ in orphans for x_ in o_['sources']}]
        print(f'FAULT_EMIT ORPHANS {len(orphans)} leaves / {sum(len(o_["sources"]) for o_ in orphans)} source bits left OPEN '
              f'(no free route to their clock root nodes): {[(o_["leaf"], o_["xy"], o_["clock"], o_["nearest_um"]) for o_ in orphans[:12]]}', flush=True)
    rec['orphans'] = orphans
    # rfs try 8/9 ('flt_root_dvs_W1 has no input'): a root none of whose sources chose it (all nearer another node of the
    # same clock) also observes its nearest same-clock source within CAP_POST_UM: that source wire gets a second sink
    # (redundant observation, never an open or tied input)
    if ROOT_MODE == 'cover':
        sb = {b[3][0][0] + '.' + b[3][0][1]: b for b in new_buses if b[0].startswith('flt_s_')}
        for nm, d in nodes.items():
            if d['n'] >= 1 or not d['root']:
                continue
            c_ = _ctr(d['it'])
            best = None
            for inst, port, real, bit, cj, rj, xy in src:
                if cj == d['ck'] and _man(c_, xy) <= CAP_POST_UM and (best is None or _man(c_, xy) < best[0]):
                    best = (_man(c_, xy), f'{inst}.{port}')
            if best is not None and best[1] in sb:
                b = sb[best[1]]
                j_ = new_buses.index(b)
                nb = (b[0], b[1], b[2], list(b[3]) + [(nm, take(nm))])
                new_buses[j_] = nb
                sb[best[1]] = nb
                rec.setdefault('second_sink', []).append([nm, best[1], round(best[0], 1)])
    # 3. masters at the final input count (same footprint, pins f0.. unchanged)
    counts = collections.Counter()
    for nm, d in nodes.items():
        if d['n'] < 1:
            raise ValueError(f'fault emit: {nm} has no input')
        d['it'].master = mname(d['n'])
        counts[d['n']] += 1
    for n in counts:
        M[mname(n)] = make_master(v, n)
    M_ = dict(M)
    v.masters = lambda model, k=1, port_bits=None: dict(M_)
    m['buses'] += new_buses
    # 4. reach audit of every new wire (pin to pin)
    pos2 = G._pin_pos(v, m)
    alias = {(s[0], s[1]): (s[0], s[2]) for s in src}
    worst, over = 0.0, []
    for bid, cl, bits, eps in new_buses:
        for e1 in eps[1:]:
            L = _man(pos2(*alias.get(tuple(eps[0]), eps[0])), pos2(*e1))
            worst = max(worst, L)
            if L > 405.0:
                over.append((bid, round(L, 1)))
    if over:
        raise ValueError(f'fault emit: {len(over)} new fault wires over 405 um: {over[:8]}')
    kinds = collections.Counter(nm.split('_')[1].rstrip('0123456789') for nm in nodes)
    rec.update(sources=len(src), source_bits_landing=sum(1 for s in src if s[2] == 'fault' and s[0].startswith('rly')),
               source_bits_hard=sum(1 for s in src if not by[s[0]].master.startswith('qfd_landh')),
               nodes=len(nodes), node_kinds=dict(kinds), node_N=dict(sorted(counts.items())),
               flops=sum(d['n'] + 4 for d in nodes.values()), new_wires=len(new_buses),
               worst_new_wire_um=round(worst, 1), worst_source_to_leaf_um=round(worst_src, 1),
               root=rec['roots'][ROOT_OWNER]['inst'], root_sink='OPEN: sys_face obs_fault absent (Q.MU.FACE.3)')
    print(f'FAULT_EMIT post: {len(src)} source bits -> {len(nodes)} nodes {dict(kinds)} N {dict(sorted(counts.items()))}, '
          f'{len(new_buses)} new wires, worst {worst:.0f} um; root {rec["root"]} o OPEN (sink owed)', flush=True)
    return rec
