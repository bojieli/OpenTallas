#!/usr/bin/env python3
"""Join compiled OVL segments with the existing epoch-admission segment; emit mask ROMs.
No link timing is inferred here: inputs must be compiled on the identical recorded seam.
Usage: d2d_ovl_release.py OVL_DIR ADMISSION_SVH OUT_DIR
"""
import hashlib, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from sys_face_image import viamap

def build(ovl, adm, out):
    out.mkdir(parents=True, exist_ok=True)
    text = adm.read_text()
    image = (ovl / 'ovl_img.svh').read_text()
    value = lambda name: int(re.search(rf'{name} = (?:\d+\'h)?([0-9a-f]+);', text).group(1), 16)
    rec = json.loads((ovl / 'ovl.json').read_text())
    for die in ('C', 'K'):
        got = value('D2D_TXDP_' + die)
        want = sum(v << (8*i) for i,v in enumerate(rec['txd'][die]))
        if got != want:
            raise ValueError(f'{die}: admission seam {got:#010x} != overlap seam {want:#010x}')
    lines = ['// Generated by d2d_ovl_release.py; admission relocated to entry 16.', f"localparam integer OVL_H = {rec['H']};", f"localparam integer OVL_FIRST_OFS = 1176;"]
    for die in ('C', 'K'):
        word = sum(v << (8*i) for i,v in enumerate(rec['txd'][die]))
        lines.append(f"localparam [31:0] OVL_TXDP_{die} = 32'h{word:08x};")
    for die in ('C','K'):
        for direction in ('TX','RX'):
            name = f'{die}_{direction}'
            original = value(f'D2D_CAL_{name}_IMG')
            base = value(f'D2D_CAL_{name}_SEG2')
            entries = []
            for i in range(base,32):
                w = (original >> (32*i)) & 0xffffffff
                entries.append(w)
                if w & (1 << 17): break
            else: raise ValueError(f'{name}: unterminated admission')
            ov = int(re.search(rf'IMG_{name} = 1024\'h([0-9a-f]+)', image).group(1),16)
            if ov >> 512: raise ValueError('OVL image extends into admission area')
            ov |= sum(w << (32*(16+i)) for i,w in enumerate(entries))
            lines.append(f"localparam [1023:0] OVL_{name}_IMG = 1024'h{ov:0256x};")
            seg = int(re.search(rf"SEG1_{name} = 32'h([0-9a-f]+)",image).group(1),16)
            lines.append(f"localparam [31:0] OVL_{name}_SEG1 = 32'd{seg};")
            words = [int(w,16) for w in (ovl/f'list_{die}_{direction.lower()}.memh').read_text().split()]
            (out/f'ovl_{die.lower()}_{direction.lower()}.viamap.hex').write_text(viamap(dict(enumerate(words))))
    (out/'ovl_release_img.svh').write_text('\n'.join(lines)+'\n')
    (out/'source.json').write_text(json.dumps(dict(admission=str(adm), admission_sha256=hashlib.sha256(adm.read_bytes()).hexdigest(), seam=rec['txd'], H=rec['H'], first_ofs=1176, admission_base=16),indent=2)+'\n')

if __name__ == '__main__': build(*map(Path,sys.argv[1:]))
