#!/usr/bin/env python3
"""Generate rtl/qwen_split/ot_qwen_me_array_xdie_w12.sv from the reference ot_qwen_me_array_w12 (rtl/hdc/ot_qwen_me_array_w12.sv).

The ONLY change: tile t no longer reads the reference's line `xl_d[(t % NXL)]` directly; it reads its slice of the die x
network ot_qwen_xdie_net (rtl/qwen_split/ot_qwen_xdie_net.sv): one 4-line (TG*32*4-bit) bundle per physical tile column,
built from the vector-memory lines by the column's position only, and a per-tile 1-of-4 select by the tile's row
inside its 4x4 block.  Everything else (spine top, tiles, tree, delays) is the reference text, so a bit-exact bench of
this array against ot_qwen_me_array_w12 proves the die delivery (compute-die contract v1, x-line fix)."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / 'rtl/hdc/ot_qwen_me_array_w12.sv').read_text().splitlines(keepends=True)
start = next(k for k, l in enumerate(src) if l.startswith('module ot_qwen_me_array_w12'))
end = next(k for k in range(start, len(src)) if src[k].startswith('endmodule'))
body = ''.join(src[start:end + 1])
body = body.replace('module ot_qwen_me_array_w12 #(', 'module ot_qwen_me_array_xdie_w12 #(\n'
                    '    parameter integer NBC  = 4,           // die x network: block columns of the tile field (4x4 blocks)\n'
                    '    parameter integer XMUT = 0,           // bench mutant: 1 = tile 1 selects the wrong line of its column bundle\n', 1)
old = '.xl(xl_d[(t % NXL)*TG*32 +: TG*32]),'
assert body.count(old) == 1, 'reference tile x connection not found'
body = body.replace(old, '.xl(xl_die[t*TG*32 +: TG*32]),')
anchor = '    wire [NT*W*32-1:0] lw [LT:TCUT];'
assert body.count(anchor) == 1
body = body.replace(anchor, '    // compute-die contract v1 x network (replaces the reference per-tile line pick)\n'
                    '    wire [NT*TG*32-1:0] xl_die;\n'
                    '    ot_qwen_xdie_net #(.NT(NT), .TG(TG), .NXL(NXL), .NBC(NBC), .XMUT(XMUT)) u_xdie (.xl(xl_d[NXL*TG*32-1:0]), .xt(xl_die));\n'
                    + anchor, 1)
hdr = ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_split/gen_xdie_array.py from rtl/hdc/ot_qwen_me_array_w12.sv -- do not edit.\n'
       '// Reference array with the compute-die x network (ot_qwen_xdie_net) in place of the per-tile line pick.\n')
out = ROOT / 'rtl/qwen_split/ot_qwen_me_array_xdie_w12.sv'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(hdr + body)
print(out)
