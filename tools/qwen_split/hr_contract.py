#!/usr/bin/env python3
"""Qwen compute die: the tt_ctlm -> slice hr bus field contract (QW-DIEFIX 10-19).

hr[452:0] runs qfd_tt_ctlm_dv.hr -> dvs_W5.hr_i -> hr_o -> ... -> dvs_E5 (12 slices, pass-through).  Layout the
consumer (qfd_dv_slice2 -> qfd_dv_heads gi / xpf -> the tiles' ot_qwen_me_array_w12 ib order) decodes:

    hr = {go [452], ib [451:73] (me_array order: nout at the MSB .. mbase at the LSB), xpf [72:1], v [0]}

The producer's ROM command (ot_qfd_tt_ctlm_head_static_rk cmd380 = {mbase .. nout, go}, go at bit 0) has the SAME
fields in the REVERSE order with go at the bottom.  As built, qfd_tt_ctlm_dv drove hr = {cmd380, xpf, v}: go landed
on hr[73] and every ib field was misplaced, so no column head ever saw a go (QW-XHEAD XT1 'asbuilt' witness).  The fix
is a zero-logic field permutation in the producer, qfd_dv_hr_pack (GENERATED by this tool from the one field table).

  hr_contract.py gen   [--root R]                   write rtl/qwen_dv/qfd_dv_hr_pack.sv
  hr_contract.py check [--root R] [--die-v die.v] [--ctlm FILE ...] [--json OUT]
      -> 'HR_CONTRACT PASS|FAIL ...': parses the producer command order (head_static_rk cmd concat), the consumer ib
         order (me_array ib concat) and its port widths (heads NW / AW), the slice gi / xpf decode, every given
         tt_ctlm variant's hr assignment, re-generates the pack module and compares it byte-for-byte, then composes
         producer pin bit -> consumer field bit for every field (go included) and reports each misplaced field.
         With --die-v: every hr bus of the die (tt_ctlm.hr -> dvs_W5.hr_i, dvs_*.hr_o -> next hr_i) is one whole
         453-b net (no slicing / reordering at die level).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NW, AW = 18, 24
# consumer order (ot_qwen_me_array_w12 ib concat, MSB first) and widths; the producer's cmd380 is go + the reverse
FIELDS = [('nout', NW), ('tiles', NW), ('k', NW), ('wsrc', 1), ('wbase', AW), ('ts', AW), ('ks', AW), ('js', AW),
          ('xbase', AW), ('xks', AW), ('xjs', AW), ('xcs', AW), ('jsh', 3), ('split', 4), ('wcs', AW), ('round', 1),
          ('obase', AW), ('ots', AW), ('ojs', AW), ('mmode', 1), ('oen', 1), ('amax', 1), ('rmax', 1), ('mbase', AW)]
IBW = sum(w for _, w in FIELDS)
assert IBW == 379
HRW, XPFW = 453, 72
PACK = 'rtl/qwen_dv/qfd_dv_hr_pack.sv'
RK = 'rtl/qwen_sys/static_schedule_20261014/ot_qfd_tt_ctlm_head_static_rk.sv'
ME = 'rtl/hdc/ot_qwen_me_array_w12.sv'
SLICE = 'rtl/qwen_dv/qfd_dv_slice2.sv'
HEADS = 'rtl/qwen_dv/qfd_dv_heads.sv'
CTLM = ['rtl/qwen_dv/qfd_tt_ctlm_dv.sv', 'rtl/qwen_dv/qfd_tt_ctlm_dv_lpf.sv', 'rtl/qwen_dv/lp/qfd_tt_ctlm_dv_lpf_lp.sv']


def producer_map():
    """cmd380 bit of each field: go at 0, then nout .. mbase from bit 1 up (concat {mbase .. nout, go}, MSB first)"""
    pos, m = 1, {'go': (0, 1)}
    for n, w in FIELDS:
        m[n] = (pos, w)
        pos += w
    assert pos == IBW + 1
    return m


def consumer_map():
    """bit of each field inside hr[452:73] (index 0 = hr[73]) as the slice decodes it: go at 379, ib below"""
    pos, m = IBW, {'go': (IBW, 1)}
    for n, w in FIELDS:
        pos -= w
        m[n] = (pos, w)
    assert pos == 0
    return m


def gen_pack() -> str:
    pm, cm = producer_map(), consumer_map()
    lines = [
        '`timescale 1ns/1ps',
        '// GENERATED by tools/qwen_split/hr_contract.py gen -- do not edit (hr_contract.py check compares it byte-for-byte).',
        '// qfd_dv_hr_pack -- the tt_ctlm ROM command (cmd380 = ot_qfd_tt_ctlm_head_static_rk cmd: {mbase .. nout, go}) laid',
        '// out as the slice reads hr[452:73] (qfd_dv_slice2 gi = {hr[451:73], hr[452]}: {go, ib 379 in ot_qwen_me_array_w12',
        '// order nout .. mbase}).  Zero logic: a field permutation (bit order inside each field kept).  QW-DIEFIX 10-19: as',
        '// built qfd_tt_ctlm_dv drove hr = {cmd380, xpf, v} (go on hr[73]) -> no column go on the die (QW-XHEAD XT1).',
        '// ASBUILT = 1 (bench mutant only): hr = cmd380 unpermuted, the as-built layout (must FAIL every matvec bench).',
        'module qfd_dv_hr_pack #(',
        '    parameter integer ASBUILT = 0',
        ') (',
        '    input  wire [379:0] cmd,',
        '    output wire [379:0] hr',
        ');',
        '    wire [379:0] p;',
    ]
    for n in ['go'] + [f for f, _ in FIELDS]:
        (cp, w), (hp, _) = pm[n], cm[n]
        lines.append(f'    assign p[{hp + w - 1}:{hp}] = cmd[{cp + w - 1}:{cp}];   // {n}')
    lines += ['    assign hr = (ASBUILT != 0) ? cmd : p;', 'endmodule', '']
    return '\n'.join(lines)


def _concat(text, lhs_re):
    m = re.search(lhs_re + r'\s*=\s*\{([^;]*)\}\s*;', text, re.S)
    if not m:
        return None
    return [t.strip() for t in re.sub(r'//[^\n]*', '', m.group(1)).split(',')]


# MU-QW-DIE 10-19: the landed re-cut qfd_tt_ctlm_dv_lpf (and its generated _lp) packs inside the wires-only child
# u_thru (a wires-only parent cannot hold a clock-less instance): hr's top field is then a child OUTPUT port whose module
# (in PARTS) drives it straight from qfd_dv_hr_pack #(ASBUILT 0).
PARTS = ['rtl/qwen_dv/qfd_tt_ctlm_dv_lpf_parts.sv']


def _child_packed(root: Path, t: str, top: str) -> bool:
    for m in re.finditer(r'\b(\w+)\s+(?:#\s*\([^;]*?\)\s*)?\w+\s*\(([^;]*?)\)\s*;', t, re.S):
        pm = re.search(r'\.(\w+)\(\s*' + re.escape(top) + r'\s*\)', m.group(2))
        if not pm:
            continue
        for f in PARTS:
            fp = root / f
            if not fp.exists():
                continue
            src = re.sub(r'//[^\n]*', '', fp.read_text())
            mm = re.search(r'\bmodule\s+' + re.escape(m.group(1)) + r'\b(.*?)\bendmodule\b', src, re.S)
            if not mm:
                continue
            inst = re.search(r'qfd_dv_hr_pack\s*#\s*\(\s*\.ASBUILT\(\s*0\s*\)\s*\)\s*\w+\s*\(([^;]*?)\)\s*;', mm.group(1), re.S)
            if inst and re.search(r'\.hr\(\s*' + re.escape(pm.group(1)) + r'\s*\)', inst.group(1)):
                return True
    return False


def check(root: Path, ctlms, die_v=None):
    errs, info = [], {}
    # producer order
    rk = (root / RK).read_text()
    pc = _concat(rk, r'assign\s+cmd')
    want_p = ['u_me_i_' + n for n, _ in reversed(FIELDS)] + ['u_me_go']
    if pc != want_p:
        errs.append(f'producer cmd concat in {RK} differs from the contract (cmd380 = {{mbase .. nout, go}}): {pc}')
    # consumer order + widths
    me = (root / ME).read_text()
    cc = _concat(me, r'wire\s*\[IBW-1:0\]\s*ib')
    if cc != ['i_' + n for n, _ in FIELDS]:
        errs.append(f'consumer ib concat in {ME} differs from the contract: {cc}')
    heads = (root / HEADS).read_text()
    m = re.search(r'parameter\s+integer\s+AW\s*=\s*(\d+)\s*,\s*NW\s*=\s*(\d+)', heads)
    if not m or (int(m.group(1)), int(m.group(2))) != (AW, NW):
        errs.append(f'{HEADS} AW/NW defaults are not {AW}/{NW}')
    # slice decode
    sl = (root / SLICE).read_text()
    if not re.search(r'\.gi\(\{\s*hr_q\[451:73\]\s*,\s*hr_q\[452\]\s*&\s*hv\s*\}\)', sl):
        errs.append(f'{SLICE}: gi decode is not {{hr_q[451:73], hr_q[452] & hv}}')
    if not re.search(r'\.xpf\(\{\s*hr_q\[72:2\]\s*,\s*hr_q\[1\]\s*&\s*hv\s*\}\)', sl):
        errs.append(f'{SLICE}: xpf decode is not {{hr_q[72:2], hr_q[1] & hv}}')
    if not re.search(r'assign\s+hr_o\s*=\s*hr_q\s*;', sl):
        errs.append(f'{SLICE}: hr_o is not the whole hr_q register (pass-through to the next slice)')
    # pack module
    pk = root / PACK
    if not pk.exists() or pk.read_text() != gen_pack():
        errs.append(f'{PACK} missing or differs from the generated permutation (run hr_contract.py gen)')
    # composition: producer pin bit -> consumer field (independent of the pack text: recomputed from the maps)
    pm, cm = producer_map(), consumer_map()
    ok_fields = all(cm[n][1] == pm[n][1] for n in pm)
    info['fields'] = {n: dict(cmd380=pm[n][0], hr=73 + cm[n][0], width=pm[n][1]) for n in pm}
    # every tt_ctlm variant's hr assignment
    info['ctlm'] = {}
    for c in ctlms:
        p = root / c
        if not p.exists():
            continue
        t = re.sub(r'//[^\n]*', '', p.read_text())
        a = re.search(r'(?:assign\s+hr\s*=|\bhr\s*<=)\s*\{\s*([A-Za-z_][\w]*)\s*,', t)
        if not a:
            errs.append(f'{c}: no hr = {{<ib>, ...}} assignment found')
            continue
        top = a.group(1)
        inst = re.search(r'qfd_dv_hr_pack\s*(#\s*\(([^;]*?)\))?\s*\w+\s*\(([^;]*?)\)\s*;', t, re.S)
        packed = bool(inst and re.search(r'\.hr\(\s*' + re.escape(top) + r'\s*\)', inst.group(3)))
        if not packed:
            packed = _child_packed(root, t, top)
        asb = inst and inst.group(2) and re.search(r'\.ASBUILT\(\s*([^)]*)\)', inst.group(2))
        if asb:
            pn = asb.group(1).strip()
            dm = re.search(r'parameter\s+integer\s+' + re.escape(pn) + r'\s*=\s*(\d+)', t) if not pn.isdigit() else None
            dflt = int(pn) if pn.isdigit() else (int(dm.group(1)) if dm else None)
            if dflt != 0:
                errs.append(f'{c}: qfd_dv_hr_pack ASBUILT default {pn} = {dflt}, not 0')
        bad = [] if packed else [n for n in pm if 73 + pm[n][0] != 73 + cm[n][0]]
        info['ctlm'][c] = dict(hr_top=top, packed=packed, misplaced=bad)
        if not packed:
            errs.append(f'{c}: hr[452:73] = {top} is the raw cmd380 (no qfd_dv_hr_pack): {len(bad)} fields misplaced '
                        f'(go at hr[73], slice reads hr[452]): {",".join(bad[:6])}...')
    if not info['ctlm']:
        errs.append('no tt_ctlm variant found')
    if not ok_fields:
        errs.append('field widths differ between producer and consumer')
    # die-level nets: tt_ctlm.hr -> (relay a -> b)* -> dvs_W5.hr_wi -> hr_eo -> ... every hop one whole 453-b net
    if die_v:
        errs += die_check(Path(die_v).read_text(), root, info)
    return errs, info


FACES = 'rtl/qwen_dv/qfd_dv_slice2_faces.sv'


def die_check(dv: str, root: Path, info: dict):
    """trace the hr bus through die.v: from the tt_ctlm .hr net over relay instances (a -> b) into slice face ports
    hr_wi / hr_ei, out of hr_eo / hr_wo into the next slice; every connection a plain whole net (no part-select or
    concat), and the slice faces pass hr_[we]i -> core hr_i and hr_o -> hr_[ew]o whole."""
    errs = []
    fc = (root / FACES).read_text() if (root / FACES).exists() else ''
    for a, b in (('hr_i', 'hr_wi'), ('hr_o', 'hr_eo'), ('hr_i', 'hr_ei'), ('hr_o', 'hr_wo')):
        if fc and not re.search(r'\.' + a + r'\(\s*' + b + r'\s*\)', fc):
            errs.append(f'{FACES}: .{a}({b}) whole connection missing')
    decl = {m.group(2): int(m.group(1)) + 1 for m in re.finditer(r'wire\s*\[(\d+):0\]\s*(\w+)\s*;', dv)}
    insts = []
    for m in re.finditer(r'^\s*(\w+)\s+(\w+)\s*\((.*?)\);\s*$', dv, re.M):
        conns = {pm.group(1): pm.group(2).strip() for pm in re.finditer(r'\.(\w+)\(([^()]*)\)', m.group(3))}
        insts.append((m.group(1), m.group(2), conns))
    by_net = {}
    for mod, inst, conns in insts:
        for port, net in conns.items():
            by_net.setdefault(net, []).append((mod, inst, port))
    w453 = {n for n, w in decl.items() if w == HRW}
    for mod, inst, conns in insts:              # no part-select / concat of any 453-b net on any port
        for port, net in conns.items():
            if re.search(r'[\[{]', net) and set(re.findall(r'\w+', net)) & w453:
                errs.append(f'die.v: {inst}.{port} connects a 453-b net through {net[:60]!r}')
    src = [c['hr'] for mod, _, c in insts if mod.startswith('qfd_tt_ctlm') and 'hr' in c]
    if len(src) != 1:
        return errs + [f'die.v: {len(src)} tt_ctlm .hr connections (want 1)']
    hops, path, net, seen = 0, [], src[0], set()
    slices = []
    while net not in seen:
        seen.add(net)
        if decl.get(net) != HRW:
            errs.append(f'die.v: hr hop net {net!r} is not a whole [452:0] wire (decl {decl.get(net)})')
            break
        sinks = [s for s in by_net.get(net, []) if not (s[2] in ('hr', 'hr_eo', 'hr_wo', 'b'))]
        if not sinks and slices:                  # the last slice's hr out is open: chain end
            break
        if len(sinks) != 1:
            errs.append(f'die.v: hr net {net} has {len(sinks)} sinks {sinks}')
            break
        mod, inst, port = sinks[0]
        conns = next(c for m_, i_, c in insts if i_ == inst)
        if port == 'a' and 'b' in conns:          # relay / landing station: a -> b
            hops += 1
            net = conns['b']
            continue
        if port in ('hr_wi', 'hr_ei'):
            slices.append(inst)
            out = 'hr_eo' if port == 'hr_wi' else 'hr_wo'
            if out not in conns:                  # chain end
                break
            net = conns[out]
            continue
        errs.append(f'die.v: hr net {net} ends on {mod} {inst}.{port} (not a relay a or slice hr_wi/hr_ei)')
        break
    info['die_hr_path'] = dict(relay_hops=hops, slices=slices)
    if not slices or not slices[0].endswith('W5'):
        errs.append(f'die.v: the tt_ctlm hr does not reach dvs_W5 first (slices {slices})')
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['gen', 'check'])
    ap.add_argument('--root', default=str(ROOT))
    ap.add_argument('--die-v')
    ap.add_argument('--ctlm', nargs='*', default=CTLM)
    ap.add_argument('--json')
    a = ap.parse_args()
    root = Path(a.root)
    if a.cmd == 'gen':
        (root / PACK).write_text(gen_pack())
        print(f'wrote {PACK}')
        return 0
    errs, info = check(root, a.ctlm, a.die_v)
    if a.json:
        Path(a.json).write_text(json.dumps(dict(errors=errs, **info), indent=1))
    variants = ' '.join(f'{Path(c).name}:{"packed" if v["packed"] else "RAW"}' for c, v in info.get('ctlm', {}).items())
    print(f'HR_CONTRACT {"PASS" if not errs else "FAIL"} fields={len(FIELDS) + 1} ctlm=[{variants}]'
          + (f' die_relay_hops={info.get("die_hr_path", {}).get("relay_hops")} die_slices='
             f'{len(info.get("die_hr_path", {}).get("slices", []))}' if a.die_v else '') + f' errors={len(errs)}')
    for e in errs:
        print('  ' + e)
    return 0 if not errs else 1


if __name__ == '__main__':
    sys.exit(main())
