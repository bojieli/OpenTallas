#!/usr/bin/env python3
"""Derive qfd_tt_ctlm_head_static_rk from qfd_tt_ctlm_head_static (Q-COMPUTE-ELEM r14, 2026-10-15).

The only change: the two program SRAMs (g_psram.g_m[m].u_pm) take their clock from a new input ck_pm[m]
instead of clk, so the hardened TT head leaf can give each raw SRAM clock pin its own explicit raw-macro
clock entry (strict multiple-CTS profile refused ck_head driving 4,831 std FF + 2 raw SRAM clocks).
The parent delivers ck_pm[0], ck_pm[1] from the same PLL phase as ck_head (same_pll_fixed_phase, 0 ps).
The shared source stays byte-unchanged (other kits keep their source binding); --check verifies the
derived file is current.  Equivalence with ck_pm tied to clk: physical/qwen_tt_static_cluster_1015/equiv.sh.
"""
import sys, hashlib
from pathlib import Path
R = Path(__file__).resolve().parents[2]
SRC = R/'rtl/qwen_sys/static_schedule_20261014/ot_qfd_tt_ctlm_split_static.sv'
DST = R/'rtl/qwen_sys/static_schedule_20261014/ot_qfd_tt_ctlm_head_static_rk.sv'

def derive():
    t = SRC.read_text()
    a = t.index('module qfd_tt_ctlm_head_static #(')
    b = t.index('endmodule', a) + len('endmodule')
    body = t[a:b]
    reps = [('module qfd_tt_ctlm_head_static #(', 'module qfd_tt_ctlm_head_static_rk #('),
            (') (\n    input wire clk,\n', ') (\n    input wire clk,\n    input wire [1:0] ck_pm,   // raw SRAM clock entries (same PLL phase as clk)\n'),
            ('ot_sram_1r1w_64x512_m1_r2c2 u_pm (.clk(clk),', 'ot_sram_1r1w_64x512_m1_r2c2 u_pm (.clk(ck_pm[m]),')]
    for old, new in reps:
        if body.count(old) != 1:
            raise SystemExit(f'derive: expected exactly one {old!r}')
        body = body.replace(old, new)
    h = hashlib.sha256(SRC.read_bytes()).hexdigest()
    return ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_split/derive_tt_head_rawck.py from\n'
            f'// rtl/qwen_sys/static_schedule_20261014/ot_qfd_tt_ctlm_split_static.sv sha256 {h}\n'
            '// Only change vs qfd_tt_ctlm_head_static: program SRAM clocks = ck_pm[m] (explicit raw macro entries).\n'
            + body + '\n')

if __name__ == '__main__':
    text = derive()
    if '--check' in sys.argv:
        sys.exit(0 if DST.exists() and DST.read_text() == text else 1)
    DST.write_text(text); print(DST)
