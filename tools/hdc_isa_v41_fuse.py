#!/usr/bin/env python3
"""OPERATOR-FUSION fields of the V4.1 ISA (W11; AGENTS.md dataflow level 1, user decision 2026-10-01).

Kept OUT of tools/hdc_isa_v41.py, whose layout committed records pin: `install()` appends these fields, in-process,
after every existing field of both profiles (reduced: after FIELDS; full shape: after FULL_EXTRA_FIELDS), so no
existing offset moves and an unfused program encodes bit for bit as before.  `python3 tools/hdc_isa_v41_fuse.py`
writes rtl/hdc/v41/ot_hdc_isa_v41_fuse.svh (the offsets the fused core, ot_hdc_core_v41x_kr.sv, decodes).

SU side (RTL: ot_hdc_v41x_vec_kr.sv / _vec_lane_kr.sv):
  kr_w (1)   also write the op's element results to lane register KR entry kr_wb + v (v: the op's vector
             index; a lane holds one element of each vector); dst may then be NONE when nothing else reads them
  kr_wb (6)
  kr_r (4)   bit 0 A, 1 B, 2 C, 3 D: those streams read KR entry kr_rb + v instead of their memory source
  kr_rb (6)
  kr_lw (1)  lay the op at the SFU lanes' width, so a light op's element e sits where an SFU op's does
PRODUCER SIDE (dataflow level 2; RESERVED, no RTL, must be 0): xkr (1) on a NON-SU op (matvec / field output,
collective, scan, the reducer's broadcast, a staging-buffer epilogue) delivers its outputs into the SU lanes' KR
at entry xkr_wb (6) + vector; VW = N, or M with xkr_lw (1); xkr_map (2) the element -> (entry, lane) mapping of
the CONSUMING chain's layout: 0 FLAT (output j at entry xkr_wb + j div VW, lane j mod VW), 1 ROWS (rows of the
producer's length r in slots S = pow2ceil(r) capped at VW, VW/S rows a vector, as the SU packs a no x r op),
2 SCALAR BROADCAST (reduced scalar k to every lane of entry xkr_wb + k), 3 reserved; xkr_epi (4) an epilogue
applied on the way in (0 none, 1-15 reserved).
"""
from pathlib import Path

import hdc_isa_v41 as I

ROOT = Path(__file__).resolve().parents[1]
SVH = ROOT / "rtl/hdc/v41/ot_hdc_isa_v41_fuse.svh"
KR_AW = 6
KR_DEPTH = 1 << KR_AW            # the widest the fields address; the unit's KR_DEPTH may be smaller
FUSE_FIELDS = [("kr_w", 1), ("kr_wb", KR_AW), ("kr_r", 4), ("kr_rb", KR_AW), ("kr_lw", 1),
               ("xkr", 1), ("xkr_wb", KR_AW), ("xkr_lw", 1), ("xkr_map", 2), ("xkr_epi", 4)]
FUSE_NAMES = {n for n, _ in FUSE_FIELDS}
_BASE = list(I.FIELDS)
_BASE_FIELDS_FOR = I.fields_for


def _base_fields_for(full_shape):
    """hdc_isa_v41.fields_for on the ORIGINAL field list (independent of install())."""
    if not full_shape:
        return list(_BASE)
    return [(n, I.FULL_XU_K if n == "xu_k" else I.FULL_A if w == I.A else I.FULL_N if w == I.N else
             I.FULL_D if w == I.D else w) for n, w in _BASE] + list(I.FULL_EXTRA_FIELDS)


assert _base_fields_for(False) == _BASE_FIELDS_FOR() and _base_fields_for(True) == _BASE_FIELDS_FOR(full_shape=True)


def fields_for(*, full_shape=False):
    return _base_fields_for(full_shape) + FUSE_FIELDS


def install():
    """Extend hdc_isa_v41 in this process: I.FIELDS (what Machine.run keeps of an op), fields_for, LAYOUT,
    FULL_LAYOUT (what encode / decode use).  Idempotent."""
    if getattr(I, "_fuse_installed", False):
        return
    I.KR_DEPTH, I.FUSE_FIELDS = KR_DEPTH, FUSE_FIELDS
    I.fields_for = fields_for
    I.FIELDS = _BASE + FUSE_FIELDS
    I.LAYOUT = I.layout_for()
    I.FULL_LAYOUT = I.layout_for(full_shape=True)
    I._fuse_installed = True


def layouts():
    """(reduced, full) offsets of the fusion fields, computed without touching hdc_isa_v41."""
    out = []
    for full in (False, True):
        off = sum(w for _, w in _base_fields_for(full))
        d = {}
        for n, w in FUSE_FIELDS:
            d[n] = (off, w)
            off += w
        assert off <= (I.FULL_INSTR_BITS if full else I.INSTR_BITS), off
        out.append(d)
    return out


def emit_svh():
    red, full = layouts()
    lines = ["// GENERATED by tools/hdc_isa_v41_fuse.py -- do not edit.",
             "// Offsets of the operator-fusion fields (appended after every field of both profiles).",
             "// Included in ot_hdc_core_v41x_kr after ot_hdc_isa_v41_profiles.svh; FULL_SHAPE selects the profile."]
    for n, _ in FUSE_FIELDS:
        lines.append(f"localparam integer O_{n.upper()} = FULL_SHAPE ? {full[n][0]} : {red[n][0]};")
        lines.append(f"localparam integer W_{n.upper()} = {red[n][1]};")
    SVH.write_text("\n".join(lines) + "\n")
    return SVH


if __name__ == "__main__":
    p = emit_svh()
    red, full = layouts()
    print(f"{p.relative_to(ROOT)}: reduced bits {min(o for o, _ in red.values())}-"
          f"{max(o + w for o, w in red.values()) - 1} of {I.INSTR_BITS}, full {min(o for o, _ in full.values())}-"
          f"{max(o + w for o, w in full.values()) - 1} of {I.FULL_INSTR_BITS}")
