#!/usr/bin/env python3
"""Emit the exhaustive, deterministic MC3c6 boundary pin plan (planning only)."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
KIT=ROOT/'physical/ref_tile/hdie_pc_ctrl_mc3c6_p540'
OUT=ROOT/'results/rtl/hbm_ds_layer_tput_1018/hbm_bw_safe_1019/mc3c/v6_lattice_plan'
WIDTHS=dict(clk=1,rst_n=1,pc_id=5,refresh_reload=8,k_v=1,k_rdy=1,k_we=1,
 k_addr=30,k_len=4,k_tag=17,k_wdata=256,k_wstrb=32,kr_v=1,kr_rdy=1,
 kr_tag=17,kr_beat=4,kr_data=256,k_wr_done=1,row_v=1,row_op=3,row_bank=5,
 row_row=19,col_v=1,col_we=1,col_bank=5,col_col=5,col_data=256,col_strb=32,
 dram_rvalid=1,dram_rdata=256,pc_fault=1,owner_fault_split=6)

def main():
    spec=json.loads((KIT/'spec.json').read_text());pins={};cols=[43.2,129.6,216,302.4]
    def add(name,side,x,y):
        assert name not in pins
        # ASAP7 M5 is vertical (N/S access), M4 horizontal (W/E).
        # Both use the actual platform track offset .012 with .048 pitch.
        if side in ('N','S'):x+=.012
        else:y+=.012
        pins[name]=dict(side=side,layer='M5' if side in ('N','S') else 'M4',at=[round(x,6),round(y,6)])
    for side,buses in spec['pins'].items():
        controls=[]
        for bus in buses:
            for b in range(WIDTHS[bus]):
                name=bus if WIDTHS[bus]==1 else f'{bus}[{b}]'
                if bus in ('k_wdata','kr_data','dram_rdata','col_data'):
                    x=cols[b//64]+4.608+.192*(2*(b%64)+(bus in ('kr_data','col_data')))
                    add(name,side,x,388.8 if side=='N' else 0)
                else:controls.append(name)
        # All positions use the actual M4 grid; the center is 189.696/208.128.
        # Keep clk exactly at the center of the full-width open central band.
        if side=='W':controls=['clk']+[p for p in controls if p!='clk']
        start=(189.696-.192*((len(controls)-1)//2)) if side in ('N','S') else 208.128
        for i,name in enumerate(controls):
            v=start+.192*i
            add(name,side,v if side in ('N','S') else (0 if side=='W' else 388.8),
                (388.8 if side=='N' else 0) if side in ('N','S') else v)
    assert len(pins)==sum(WIDTHS.values())==1229
    for side in spec['pins']:
        pts=sorted(tuple(p['at']) for p in pins.values() if p['side']==side)
        assert len(pts)==len(set(pts))
    payload=dict(schema='opentallas.mc3c6.exact-boundary-pin-plan.v1',
       scope='Deterministic intended pin coordinates; native post-IO coordinates must match before qualification',
       outline_um=[388.8,388.8],pitch_um=.192,pins=pins)
    OUT.mkdir(exist_ok=True)
    (OUT/'pin_plan.json').write_text(json.dumps(payload,indent=2)+'\n')
    lines=['# Generated by tools/hbm_layer_vehicle/mc3_pin_plan.py; all 1229 pins.',
           'set ot_mc3_block [ord::get_db_block]']
    for name,p in pins.items():
        x,y=p['at']
        lines += [f'set ot_mc3_term [$ot_mc3_block findBTerm {{{name}}}]',
          f'if {{$ot_mc3_term == "NULL"}} {{ error {{MC3c6 missing port {name}}} }}',
          'foreach ot_mc3_bpin [$ot_mc3_term getBPins] { odb::dbBPin_destroy $ot_mc3_bpin }',
          f'place_pin -pin_name {{{name}}} -layer {p["layer"]} -location {{{x} {y}}} -force_to_die_boundary']
    lines += ['orfs_write_db $::env(RESULTS_DIR)/3_2_place_iop.odb',
              'write_pin_placement $::env(RESULTS_DIR)/3_2_place_iop.tcl']
    (KIT/'post_iop_exact.tcl').write_text('\n'.join(lines)+'\n')
    print(json.dumps(dict(pins=len(pins),side_counts={s:sum(p['side']==s for p in pins.values()) for s in spec['pins']})))

if __name__=='__main__':main()
