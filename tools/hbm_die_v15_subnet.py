#!/usr/bin/env python3
"""Emit a structural Verilog subnet of the actual v15 HBM die source contract.

Every instance is the contract's real RTL master with its contract parameters.
Contract edges become bit-exact connections; every bit that the contract leaves
unbound (or whose peer lies outside the selected subset) becomes an explicitly
named top-level boundary port, so tools/die_port_bind.py can prove BIND / no STUB
/ PORTS / WIDTHS / NETS for the subset and list the open boundary honestly.
Clock inputs come from one top port per contract clock source (stream / hbm);
they are NOT a CTS claim. Logical constants are emitted as constants so the
bind check reports them as ties (they remain open contract requests).
"""
import argparse
import json
import re
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('contract', type=Path)
    ap.add_argument('--keep', required=True, help='regex of instance names to include')
    ap.add_argument('--top', default='hbm_v15_subnet')
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    c = json.loads(a.contract.read_text())
    keep = {n: r for n, r in c['instances'].items() if re.fullmatch(a.keep, n)}
    # driver map: (inst, port) -> list of (dlo, dhi, src_inst, src_port, slo)
    drive = {}
    for e in c['known_actual_edges']:
        s, d = e['source'], e['sink']
        slo = s[2] if len(s) > 2 else 0
        dlo = d[2] if len(d) > 2 else 0
        drive.setdefault((d[0], d[1]), []).append((dlo, dlo + e['bits'], s[0], s[1], slo))
    consts = {tuple(k['sink']): k for k in c['logical_constant_requests']}
    clock_src = {}
    for r in c['clock_roots']:
        clock_src[(r['instance'], r['port'])] = r['source'][1]
    ports, body, wires = [], [], []
    boundary = []
    for name, rec in keep.items():
        for port, pr in rec['ports'].items():
            if pr['direction'] == 'output':
                wires.append(f"  wire [{pr['bits']-1}:0] {name}__{port};")
    for name, rec in keep.items():
        conns = []
        for port, pr in rec['ports'].items():
            w = pr['bits']
            if pr['direction'] == 'output':
                conns.append(f".{port}({name}__{port})")
                continue
            if (name, port) in clock_src:
                src = clock_src[(name, port)]
                if f'input wire {src}' not in ports:
                    ports.append(f'input wire {src}')
                conns.append(f".{port}({{{w}{{{src}}}}})" if w > 1 else f".{port}({src})")
                continue
            # Reset is an explicit boundary unless actual contract edges drive it.
            if (name, port) in consts:
                conns.append(f".{port}({w}'d{consts[(name, port)]['value']})")
                continue
            pieces = []  # (lo, hi, expr)
            for dlo, dhi, si, sp, slo in drive.get((name, port), []):
                if si in keep:
                    expr = f"{si}__{sp}[{slo + dhi - dlo - 1}:{slo}]"
                    pieces.append((dlo, dhi, expr))
            pieces.sort()
            cur, filled = 0, []
            for lo, hi, expr in pieces:
                if lo > cur:
                    filled.append((cur, lo, None))
                filled.append((lo, hi, expr))
                cur = hi
            if cur < w:
                filled.append((cur, w, None))
            exprs = []
            for lo, hi, expr in filled:
                if expr is None:
                    pname = f"x_{name}__{port}_{lo}_{hi}"
                    ports.append(f"input wire [{hi-lo-1}:0] {pname}")
                    boundary.append(dict(instance=name, port=port, lo=lo, hi=hi, top_port=pname))
                    expr = pname
                exprs.append(expr)
            conns.append(f".{port}({{{', '.join(reversed(exprs))}}})" if len(exprs) > 1 else f".{port}({exprs[0]})")
        params = rec.get('params') or {}
        ptxt = (' #(' + ', '.join(f'.{k}({v})' for k, v in params.items()) + ')') if params else ''
        body.append(f"  {rec['master']}{ptxt} {name} (\n    " + ',\n    '.join(conns) + '\n  );')
    # Non-ANSI header (die_port_bind format). Instance outputs stay on internal
    # wires; outputs with no in-subset consumer are reported OUTPUT_OPEN.
    names = [d.split()[-1] for d in ports]
    decls = []
    for d in ports:
        parts = d.split()
        rng = parts[2] if len(parts) == 4 else ''
        decls.append(f"  input {rng} {parts[-1]};".replace('  ', ' ', 1) if rng else f"  input {parts[-1]};")
    text = (f"// Generated by tools/hbm_die_v15_subnet.py from {a.contract.name}; keep={a.keep!r}\n"
            "`default_nettype none\n"
            f"module {a.top} (" + ', '.join(names) + ');\n'
            + '\n'.join(decls) + '\n' + '\n'.join(wires) + '\n' + '\n'.join(body) + '\nendmodule\n`default_nettype wire\n')
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / f'{a.top}.v').write_text(text)
    (a.out / f'{a.top}_boundary.json').write_text(json.dumps(dict(
        keep=a.keep, instances=sorted(keep), boundary_inputs=boundary,
        boundary_input_bits=sum(b['hi'] - b['lo'] for b in boundary),
        sources={n: r['source'] for n, r in keep.items()}), indent=1) + '\n')
    print(json.dumps(dict(instances=len(keep), boundary_inputs=len(boundary),
                          boundary_input_bits=sum(b['hi'] - b['lo'] for b in boundary))))


if __name__ == '__main__':
    main()
