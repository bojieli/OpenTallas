#!/usr/bin/env python3
"""Rasterise world-atlas land-110m (TopoJSON) into the dot-matrix land mask
embedded in landmask.js. One-off generator: python3 make_landmask.py land-110m.json"""
import json, sys
STEP = 2.5; LAT0, LAT1 = 78.75, -56.25
t = json.load(open(sys.argv[1]))
sx, sy = t['transform']['scale']; tx, ty = t['transform']['translate']
arcs = []
for a in t['arcs']:
    x = y = 0; pts = []
    for dx, dy in a:
        x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)
def ring(idx):
    out = []
    for i in idx:
        p = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(p[1:] if out else p)
    return out
def unwrap(r):
    # make antimeridian-crossing rings (Eurasia/Chukotka, Fiji) continuous in longitude
    out = [r[0]]; off = 0
    for (x0, _), (x1, y1) in zip(r, r[1:]):
        if x1 - x0 > 180: off -= 360
        elif x0 - x1 > 180: off += 360
        out.append((x1 + off, y1))
    return out
rings = []
for g in t['objects']['land']['geometries']:
    polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
    for poly in polys:
        rings.extend(unwrap(ring(r)) for r in poly)
def inside(lon, lat):
    c = False
    for r in rings:
        j = len(r) - 1
        for i in range(len(r)):
            xi, yi = r[i]; xj, yj = r[j]
            if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                c = not c
            j = i
    return c
rows = []
lat = LAT0
while lat >= LAT1 - 1e-9:
    bits = ''.join('1' if any(inside(-180 + STEP / 2 + k * STEP + w, lat) for w in (0, 360, -360)) else '0' for k in range(int(360 / STEP)))
    rows.append('%0*x' % (len(bits) // 4, int(bits, 2)))
    lat -= STEP
print('// generated by make_landmask.py from world-atlas land-110m; %g deg grid, lat %g..%g' % (STEP, LAT0, LAT1))
print('window.LANDMASK={step:%g,lat0:%g,rows:%s};' % (STEP, LAT0, json.dumps(rows)))
