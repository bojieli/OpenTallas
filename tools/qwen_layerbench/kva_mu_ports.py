#!/usr/bin/env python3
"""MU-TOK-KV 10-19: netlist-specific edge facts of the attention vehicle qwk_slice_attn for drive_qwk_slice_attn_mu.svh.

The slice output names carry the die's relay suffixes (n_ks_kvs_attn__attn__tx_payload__r9__pinfix1 on kvs14p), and the
bench drives every slice input S edges before its consumer-pin event, S = the die's relay stages of that bus.  This tool
reads slice.json and the die case's relay_stages.json (+ relay_check.json, whose 'netlist walk' count wins where the two
disagree, as QW-KVATTN2 did by hand on kvs14p) and writes kva_ports.svh:
    `define KVA_TXP / KVA_TXV / KVA_KST   the d2d-face RESULT payload / valid and the seq KST output of this netlist
    localparam S_CTL, S_LP, S_SRX, S_RXP, S_TXS, S_SKW

    kva_mu_ports.py --slice slice.json --relay-stages relay_stages.json [--relay-check relay_check.json] --out kva_ports.svh
"""
import argparse
import json
import re
from pathlib import Path

BUSES = dict(S_CTL='kvs_ctl.o_attn -> kvs_attn.i_ctl', S_LP='kvs_ctl.lp -> seq.lp', S_SRX='d2d_kv.srx -> kvs_attn.d2d__srx',
             S_RXP='d2d_kv.rx_payload -> kvs_attn.d2d__rx_payload', S_TXS='d2d_kv.att_tx_slot -> kvs_attn.d2d__att_tx_slot',
             S_SKW='d2d_kv.skw -> seq.skw')
OUTS = dict(KVA_TXP='o_n_ks_kvs_attn__attn__tx_payload', KVA_TXV='o_n_ks_kvs_attn__attn__tx_valid', KVA_KST='o_n_kst')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--slice', required=True)
    ap.add_argument('--relay-stages', required=True)
    ap.add_argument('--relay-check')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    S = json.loads(Path(a.slice).read_text())
    R = json.loads(Path(a.relay_stages).read_text())
    walk = {}
    probs = list(R.get('problems', []))
    if a.relay_check and Path(a.relay_check).exists():
        C = json.loads(Path(a.relay_check).read_text())
        probs += [p if isinstance(p, str) else json.dumps(p) for p in C.get('problems', [])] if isinstance(C, dict) else []
    for p in probs:
        m = re.match(r'(\S+ -> \S+): .*= (\d+), netlist walk (\d+)', p if isinstance(p, str) else '')
        if m:
            walk[m.group(1)] = int(m.group(3))
    stages = {b['id']: b['stages'] for b in R['buses']}
    lines = ['// generated by tools/qwen_layerbench/kva_mu_ports.py (MU-TOK-KV) -- do not edit',
             f'// slice {a.slice} die {S.get("die_sha256", "?")[:12]}; relay stages {a.relay_stages}']
    facts = {}
    outs = [p['port'] for p in S['ports'] if p['dir'] == 'output']
    for k, pre in OUTS.items():
        c = [o for o in outs if o == pre or o.startswith(pre + '__')]
        if len(c) != 1:
            raise SystemExit(f'kva_mu_ports: {k}: {len(c)} slice outputs start with {pre}: {c}')
        lines.append(f'`define {k} {c[0]}')
        facts[k] = c[0]
    for k, bid in BUSES.items():
        if bid not in stages:
            raise SystemExit(f'kva_mu_ports: bus {bid} not in relay_stages')
        s = walk.get(bid, stages[bid])
        lines.append(f'    localparam integer {k} = {s};   // {bid}: relay_stages {stages[bid]}, netlist walk {walk.get(bid, "=")}')
        facts[k] = s
    Path(a.out).write_text('\n'.join(lines) + '\n')
    print('kva_mu_ports:', json.dumps(facts))


if __name__ == '__main__':
    main()
