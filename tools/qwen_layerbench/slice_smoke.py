#!/usr/bin/env python3
"""slice_smoke: emit the SMOKE bench of a cut die slice (tools/qwen_layerbench/slice_cut.py slice.json).

Smoke = the first simulation of a never-simulated die netlist slice (LAYERBENCH 10-18):
  1. RESET: every reset-role slice input (the die's reset-sequencer / reset-tree roots outside the slice) is held low
     RST_EDGES edges (longer than the deepest reset-tree tap), then released, and the trace starts RST_EDGES later; every clock-role input runs from one 1.2 GHz bench clock (all die clocks are
     regional copies of one PLL; the forwarded/landed crossings inside the slice are the die's own RTL).
  2. IDLE: data inputs at 0 (the replay model injects no neighbour traffic) for IDLE_EDGES edges.  Checks: no
     fault-named slice output rises; the output trace after reset is identical for two different random initial states
     (run twice with +verilator+rand+reset+2 and different seeds; the run script compares the printed folds) =
     reset completeness.
  MUT 1 = a 24-edge reset traced from release + 8 edges: reset completeness must FAIL (the bench's own mutant).
  3. PROGRAMME LOAD (optional, slice-specific): `define SLICE_DRIVE "file.svh" includes a task slice_programme() that
     drives the boundary with the neighbour's traffic at its scheduled cycles (drv_<port> registers) and checks the
     slice's response (smoke_err()).

Output: tb_<top>.sv.  Log lines: SMOKE_FOLD <phase> <hex>, SMOKE_ACT <port> <toggles>, SMOKE_PASS / SMOKE_FAIL.
    python3 tools/qwen_layerbench/slice_smoke.py SLICE_JSON --out TB_SV
"""
import argparse
import json
import re
from pathlib import Path

FAULT_RE = re.compile(r'fault|_abort|_err', re.I)


def chunks(w):
    return [(lo, min(w, lo + 64) - 1) for lo in range(0, w, 64)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('slice_json')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    r = json.loads(Path(a.slice_json).read_text())
    top = r['top']
    ins = [p for p in r['ports'] if p['dir'] == 'input']
    outs = [p for p in r['ports'] if p['dir'] == 'output']
    L = ['`timescale 1ns/1ps',
         f'// GENERATED by tools/qwen_layerbench/slice_smoke.py from {a.slice_json} (slice of {r["die_v"]},',
         f'// die sha256 {r["die_sha256"][:16]}).  Smoke bench: reset, idle, optional programme load (SLICE_DRIVE).',
         f'module tb_{top};',
         '    parameter integer MUT = 0;',
         '`ifndef RST_EDGES', '`define RST_EDGES 1024      // > the deepest die reset-tree tap in the slice (qfd_rst_rep chains reach ~300)', '`endif',
         '`ifndef IDLE_EDGES', '`define IDLE_EDGES 3000', '`endif',
         '`ifndef TAIL_EDGES', '`define TAIL_EDGES 2000', '`endif',
         '    reg ck = 0; always #0.4167 ck = ~ck;      // 1.2 GHz',
         '    reg rst_n = 0, trace_on = 0;',
         '    integer cyc = 0, errs = 0, rel_cyc = -1; always @(posedge ck) cyc <= cyc + 1;',
         '    task automatic smoke_err(input [8*120-1:0] msg); begin errs = errs + 1;',
         '        if (errs < 30) $display("SMOKE_ERR @%0d %0s", cyc, msg); end endtask']
    for p in ins:
        w = p['width']
        if p['role'] == 'data':
            L.append(f'    reg  [{w - 1}:0] drv_{p["port"]} = 0;')
    for p in outs:
        L.append(f'    wire [{p["width"] - 1}:0] {p["port"]};')
    conns = []
    for p in ins:
        w = p['width']
        src = {'clock': f'{{{w}{{ck}}}}', 'reset': f'{{{w}{{rst_n}}}}'}.get(p['role'], f'drv_{p["port"]}')
        conns.append(f'.{p["port"]}({src})')
    conns += [f'.{p["port"]}({p["port"]})' for p in outs]
    L.append(f'    {top} dut (' + ',\n        '.join(conns) + ');')
    # output fold (trace hash) and activity
    L.append('    reg [63:0] fold = 64\'h0; reg [63:0] fx;')
    for i, p in enumerate(outs):
        L.append(f'    integer act_{i} = 0; reg [{p["width"] - 1}:0] last_{i} = 0; reg [63:0] of_{i} = 0;')
    L.append('    always @(posedge ck) if (trace_on) begin')
    L.append('        fx = 64\'h0;')
    for i, p in enumerate(outs):
        L.append('        fx = 64\'h0;')
        for lo, hi in chunks(p['width']):
            L.append(f'        fx = {{fx[56:0], fx[63:57]}} ^ 64\'({p["port"]}[{hi}:{lo}]);')
        L.append(f'        fold = fold ^ {{fx[62 - ({i} % 61):0], fx[63:63 - ({i} % 61)]}};')
        L.append(f'        of_{i} = {{of_{i}[62:0], of_{i}[63]}} ^ fx;')
        L.append(f'        if ({p["port"]} !== last_{i}) act_{i} = act_{i} + 1; last_{i} = {p["port"]};')
        if FAULT_RE.search(p['net']):
            L.append(f'        if (|{p["port"]}) smoke_err("fault output {p["port"]} high");')
    L.append('        fold = {fold[62:0], fold[63]} ^ 64\'(cyc - rel_cyc);')
    L.append('    end')
    L.append('    task automatic report_act(); begin')
    for i, p in enumerate(outs):
        L.append(f'        $display("SMOKE_OFOLD {p["port"]} %h act %0d last %0h", of_{i}, act_{i}, last_{i});')
    L.append('    end endtask')
    L += ['`ifdef SLICE_DRIVE', '`include `SLICE_DRIVE', '`endif',
          '    initial begin',
          '        // MUT 1 (bench mutant): a 24-edge reset and the trace from release + 8 -- shorter than the die reset trees,',
          '        // so the reset-completeness check must FAIL',
          '        repeat ((MUT == 1) ? 24 : `RST_EDGES) @(negedge ck);',
          '        rst_n = 1; rel_cyc = cyc;',
          '        repeat ((MUT == 1) ? 8 : `RST_EDGES) @(negedge ck); trace_on = 1;   // release has crossed every reset-tree tap',
          '        repeat (`IDLE_EDGES) @(negedge ck);',
          '        $display("SMOKE_FOLD idle %h", fold);',
          '        report_act();',
          '`ifdef SLICE_DRIVE',
          '        slice_programme();',
          '        repeat (`TAIL_EDGES) @(negedge ck);',
          '        $display("SMOKE_FOLD programme %h", fold);',
          '        report_act();',
          '`endif',
          f'        if (errs == 0) $display("SMOKE_PASS {top} MUT=%0d edges %0d", MUT, cyc);',
          f'        else $display("SMOKE_FAIL {top} MUT=%0d errors %0d", MUT, errs);',
          '        $finish;',
          '    end',
          'endmodule']
    Path(a.out).write_text('\n'.join(L) + '\n')
    print(f'slice_smoke: {a.out}: {len(ins)} inputs ({sum(1 for p in ins if p["role"] == "clock")} clock, '
          f'{sum(1 for p in ins if p["role"] == "reset")} reset), {len(outs)} outputs')


if __name__ == '__main__':
    main()
