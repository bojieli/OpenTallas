#!/usr/bin/env python3
"""Carve a sub-netlist out of a GEN die netlist (QW-LAYERB 10-20) for an RTL bench ON the die netlist.

Keeps the SEED instances (exact die.v instance lines, parameters from die.v.params.json masters) plus every relay /
landing / forwarded-lane instance whose relay-connected component links two or more seeds (the die's own landed
paths between them, with their own tie cells).  Clock nets (n_clk_*) and reset-field nets (n_rst_field_*) are NOT
followed: they become module inputs that the bench drives (one bench clock, one bench reset: functional cycles only,
no skew).  Every other net used by a kept instance and not driven by a kept output becomes a module input (the bench
drives it, e.g. the tt_ctlm -> slice hr lane end n_dvw_hr_wi__r26, or 0); every net driven by a kept output becomes a
module output (observable).  Nothing is re-wired: the kept instance lines are copied byte-for-byte.

    die_carve.py --die die.v --dirs port_dirs.json --params die.v.params.json --seed dvs_W5 --seed c16_W5_2 ... \
                 --top xt1g_carve --out carve.v --json carve.json
"""
from __future__ import annotations
import argparse, hashlib, json, re, sys
from collections import defaultdict
from pathlib import Path

INST = re.compile(r'^\s*(\w+)\s+(\w+)\s*\((.*)\);\s*$')
CONN = re.compile(r'\.(\w+)\(([^()]*)\)')
RELAY = re.compile(r'^(qfd_rly[pf]?_|qfd_rlyh0?_|qfd_landh0?_|qfd_rlyr[0l]?_)')
GLOBAL = re.compile(r'^n_(clk_|rst_field)')
WIRE = re.compile(r'^\s*wire\s*(\[(\d+):(\d+)\])?\s*(\w+)\s*;')


def parse(die):
    widths, insts = {}, {}
    for ln in die.read_text().splitlines():
        m = WIRE.match(ln)
        if m:
            widths[m.group(4)] = (int(m.group(2)) - int(m.group(3)) + 1) if m.group(1) else 1
            continue
        m = INST.match(ln)
        if m and m.group(1) not in ('module',):
            conns = {p: n.strip() for p, n in CONN.findall(m.group(3))}
            insts[m.group(2)] = (m.group(1), conns, ln)
    return widths, insts


def is_net(s):
    return bool(re.fullmatch(r'\w+', s)) and not re.fullmatch(r"\d+'[hbd][0-9a-fA-FxXzZ_]+", s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--die', required=True, type=Path)
    ap.add_argument('--dirs', required=True, type=Path)
    ap.add_argument('--params', type=Path)
    ap.add_argument('--seed', action='append', required=True)
    ap.add_argument('--top', default='die_carve')
    ap.add_argument('--out', required=True, type=Path)
    ap.add_argument('--json', required=True, type=Path)
    a = ap.parse_args()
    widths, insts = parse(a.die)
    dirs = json.loads(a.dirs.read_text())
    masters = json.loads(a.params.read_text()).get('masters', {}) if a.params else {}
    for s in a.seed:
        if s not in insts:
            sys.exit(f'seed {s} not in {a.die}')

    def pdir(inst, port):
        m = insts[inst][0]
        d = dirs.get(m, {}).get(port)
        if d is None:
            sys.exit(f'no direction for {m}.{port} (port_dirs.json)')
        return d

    net_users = defaultdict(set)
    for i, (m, c, _) in insts.items():
        for p, n in c.items():
            if is_net(n) and not GLOBAL.match(n):
                net_users[n].add(i)
    relays = {i for i, (m, _, _) in insts.items() if RELAY.match(m)}
    # relay components (union over shared non-global nets)
    parent = {r: r for r in relays}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for n, us in net_users.items():
        rs = [u for u in us if u in relays]
        for r in rs[1:]:
            parent[find(r)] = find(rs[0])
    comp_seeds = defaultdict(set)
    comp_members = defaultdict(set)
    for r in relays:
        comp_members[find(r)].add(r)
    for n, us in net_users.items():
        seeds = us & set(a.seed)
        if not seeds:
            continue
        for u in us & relays:
            comp_seeds[find(u)] |= seeds
    kept_relays = set()
    paths = []
    for c, ss in comp_seeds.items():
        if len(ss) >= 2:
            kept_relays |= comp_members[c]
            paths.append({'seeds': sorted(ss), 'relays': sorted(comp_members[c])})
    keep = list(a.seed) + sorted(kept_relays)
    drv, used = {}, set()
    for i in keep:
        m, c, _ = insts[i]
        for p, n in c.items():
            if not is_net(n):
                continue
            used.add(n)
            if pdir(i, p) == 'output':
                drv[n] = i
    ins = sorted(n for n in used if n not in drv)
    outs = sorted(drv)
    lines = [f'// GENERATED by tools/qwen_layerbench/die_carve.py from {a.die.name} sha256 '
             f'{hashlib.sha256(a.die.read_bytes()).hexdigest()} seeds {",".join(a.seed)}',
             '`timescale 1ns/1ps', f'module {a.top} (']
    decl = []
    for n in ins:
        w = widths.get(n, 1)
        decl.append(f'    input  wire {"[%d:0] " % (w - 1) if w > 1 else ""}{n}')
    for n in outs:
        w = widths.get(n, 1)
        decl.append(f'    output wire {"[%d:0] " % (w - 1) if w > 1 else ""}{n}')
    lines.append(',\n'.join(decl))
    lines.append(');')
    # body-level wire declarations of every used net (the die.v form: gen_relay_rtl.py reads widths from them)
    lines.append('`ifdef OT_DIE_CARVE_WIDTHS')
    for n in sorted(used):
        w = widths.get(n, 1)
        lines.append(f'  wire {"[%d:0] " % (w - 1) if w > 1 else ""}{n};')
    lines.append('`endif')
    for i in keep:
        m, c, ln = insts[i]
        pm = {k: v for k, v in masters.get(m, {}).items() if not k.startswith('_')}
        if pm:
            ps = ', '.join(f'.{k}({v})' for k, v in pm.items())
            ln = re.sub(rf'^(\s*){m}\s+{i}\s*\(', rf'\g<1>{m} #({ps}) {i} (', ln, count=1)
        lines.append(ln)
    lines.append('endmodule')
    a.out.write_text('\n'.join(lines) + '\n')
    rec = {'schema': 'opentallas.qwen_layerbench.die_carve.v1', 'die_v': str(a.die),
           'die_v_sha256': hashlib.sha256(a.die.read_bytes()).hexdigest(), 'seeds': a.seed,
           'kept_relays': len(kept_relays), 'relay_masters': sorted({insts[r][0] for r in kept_relays}),
           'paths': paths, 'inputs': {n: widths.get(n, 1) for n in ins}, 'outputs': {n: widths.get(n, 1) for n in outs},
           'params': {i: masters.get(insts[i][0], {}) for i in a.seed if insts[i][0] in masters}}
    a.json.write_text(json.dumps(rec, indent=1) + '\n')
    print(json.dumps({k: rec[k] for k in ('seeds', 'kept_relays', 'relay_masters')}))
    print('inputs', len(ins), 'outputs', len(outs))


if __name__ == '__main__':
    main()
