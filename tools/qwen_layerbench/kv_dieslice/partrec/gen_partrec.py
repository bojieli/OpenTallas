#!/usr/bin/env python3
"""KV-TOK 10-24: partition record / replay for the whole-die kv_dieslice bench.

The whole-die bench runs the partitions as Verilator hierarchical (protect-lib) blocks, so their insides are opaque.
This tool makes one partition visible: the whole-die run RECORDS every input lane of the chosen partition instance on
value change (time in ps, input index, hex value), and a flat sub-bench REPLAYS that record into the same partition
module built flat (every internal signal observable), with its clocks regenerated exactly as tb_kvslice makes them.

Each recorded change is applied 1 ps after the time it happened in the whole die: every lane changes on a clock edge
(registered ot_dp_st / reset spines), so a flop of the partition clocked on that same edge still samples the old value
and anything later samples the new one -- the same order as in the whole die.

  gen_partrec.py TOP.sv PART.sv INST OUTDIR
writes OUTDIR/rec_<INST>.svh (include inside tb_kvslice, enabled by +REC_<INST>=<file>) and OUTDIR/tb_rep_<INST>.sv
(top tb_rep_<INST>: +REP=<file> +UNTIL=<ps>; a probe file OUTDIR/probe_<INST>.svh is `included if present).
"""
import re, sys, os

top, part, inst, out = sys.argv[1:5]
ts = open(top).read()
m = re.search(r'^\s*(\w+)\s*(?:#\(.*?\))?\s+' + re.escape(inst) + r'\s*\((.*?)\n\s*\);', ts, re.M | re.S)
assert m, f'instance {inst} not found'
mod, body = m.group(1), m.group(2)
conn = dict(re.findall(r'\.(\w+)\(([^()]*)\)', body))
ps = open(part).read()
hm = re.search(r'^module\s+' + re.escape(mod) + r'\b.*?\((.*?)\n\);', ps, re.M | re.S)
assert hm, f'module {mod} header not found'
ports = []
for line in hm.group(1).split('\n'):
    pm = re.match(r'\s*(input|output)\s+wire\s*(\[(\d+):0\])?\s*(\w+)', line)
    if pm:
        ports.append((pm.group(1), int(pm.group(3)) + 1 if pm.group(3) else 1, pm.group(4)))
clocks = {'clk', 'clk_clk_host', 'clk_clk_ingest', 'clk_clk_phy', 'clk_clk_hbm', 'clk_clk_fwd'}
ins = [(w, n) for d, w, n in ports if d == 'input' and n not in clocks]
outs = [(w, n) for d, w, n in ports if d == 'output']
clk_ports = [n for d, w, n in ports if d == 'input' and n in clocks]
os.makedirs(out, exist_ok=True)

# recorder (inside tb_kvslice: dut = the bound top)
r = [f'// GENERATED by partrec/gen_partrec.py: record every input lane of {inst} ({mod}), +REC_{inst}=<file>',
     f'integer rec_{inst}_fd = 0;',
     f'initial begin : rec_{inst}_open string f; if ($value$plusargs("REC_{inst}=%s", f)) begin '
     f'rec_{inst}_fd = $fopen(f, "w"); $display("PARTREC {inst} -> %s ({len(ins)} inputs)", f); end end']
for i, (w, n) in enumerate(ins):
    sig = conn[n].strip()
    sig = f'dut.{sig}' if re.match(r'^[A-Za-z_]\w*$', sig) else sig
    r.append(f'always @({sig}) if (rec_{inst}_fd != 0) $fwrite(rec_{inst}_fd, "%0d {i} %h\\n", $realtime * 1000, {sig});')
open(f'{out}/rec_{inst}.svh', 'w').write('\n'.join(r) + '\n')

# replayer (flat partition)
clkgen = {'clk': 'always #0.416667 clk = ~clk;', 'clk_clk_hbm': 'always #0.512 clk_clk_hbm = ~clk_clk_hbm;',
          'clk_clk_host': 'always #0.500 clk_clk_host = ~clk_clk_host;',
          'clk_clk_ingest': 'always #0.833334 clk_clk_ingest = ~clk_clk_ingest;',
          'clk_clk_phy': 'always #0.521500 clk_clk_phy = ~clk_clk_phy;', 'clk_clk_fwd': 'always #0.416667 clk_clk_fwd = ~clk_clk_fwd;'}
t = ['`timescale 1ns/1ps', f'// GENERATED by partrec/gen_partrec.py: replay a whole-die input record into {mod} built flat',
     f'module tb_rep_{inst};']
t += [f'    reg {c} = 0; {clkgen[c]}' for c in clk_ports]
t += [f'    reg [{w-1}:0] {n} = 0;' for w, n in ins]
t += [f'    wire [{w-1}:0] {n};' for w, n in outs]
t.append(f'    {mod} dut (' + ', '.join(f'.{n}({n})' for _, _, n in ports) + ');')
t.append('    integer core_cyc = 0; always @(posedge clk) core_cyc <= core_cyc + 1;')
t.append(f'`ifdef PROBE\n`include "probe_{inst}.svh"\n`endif')
t.append('    task automatic apply(input integer idx, input bit [8191:0] v);\n        case (idx)')
t += [f'            {i}: {n} = v[{w-1}:0];' for i, (w, n) in enumerate(ins)]
t.append('            default: $fatal(1, "bad input index %0d", idx);\n        endcase\n    endtask')
t.append('''    initial begin : replay
        string f; integer fd, idx, n = 0; longint tps, t_until = 0; bit [8191:0] v; realtime now;
        if (!$value$plusargs("REP=%s", f)) $fatal(1, "+REP=<record> required");
        void'($value$plusargs("UNTIL=%d", t_until));
        fd = $fopen(f, "r"); if (fd == 0) $fatal(1, "cannot open %s", f);
        while ($fscanf(fd, "%d %d %h", tps, idx, v) == 3) begin
            if (t_until > 0 && tps > t_until) break;
            now = tps / 1000.0 + 0.001;
            if (now > $realtime) #(now - $realtime);
            apply(idx, v); n++;
        end
        $display("PARTREP done %0d changes, t %0t core_cyc %0d", n, $realtime, core_cyc);
        #10 $finish;
    end
endmodule''')
open(f'{out}/tb_rep_{inst}.sv', 'w').write('\n'.join(t) + '\n')
print(f'{inst} ({mod}): {len(ins)} recorded inputs, {len(outs)} outputs, clocks {clk_ports}')
