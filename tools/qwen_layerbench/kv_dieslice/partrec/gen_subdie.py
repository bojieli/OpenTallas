#!/usr/bin/env python3
"""KV-TOK2 10-25: flat sub-die bench generator: a chosen set of partition instances of the bound KV die top, wired to each
other exactly as in the top; every input net not driven inside the set is a bench reg (0 unless named by a rule below).
  gen_subdie.py TOP.sv TOPS_DIR OUT.sv INST...
Rules: clocks -> clk; arst_n -> arst_n; *hbm_rst_n* -> {1, hbm_rn}; *host_rst_n* -> {1, host_rn}; die_rst_n spine -> die_rn;
       boot_go net into the chain head (i_host_boot_go) -> {1, bg}; other inputs 0."""
import re, sys
top, tops, out = sys.argv[1:4]; insts = sys.argv[4:]
ts = open(top).read()
def inst_of(i):
    m = re.search(r'^\s*(\w+)\s+' + re.escape(i) + r'\s*\((.*?)\n\s*\);', ts, re.M | re.S)
    assert m, i
    return m.group(1), dict(re.findall(r'\.(\w+)\(([^()]*)\)', m.group(2)))
def ports(mod):
    s = open(f'{tops}/{mod}.sv').read()
    hm = re.search(r'^module\s+' + mod + r'\b.*?\((.*?)\n\);', s, re.M | re.S)
    r = {}
    for l in hm.group(1).split('\n'):
        pm = re.match(r'\s*(input|output)\s+wire\s*(\[(\d+):0\])?\s*(\w+)', l)
        if pm: r[pm.group(4)] = (pm.group(1), int(pm.group(3)) + 1 if pm.group(3) else 1)
    return r
CLK = {'clk', 'clk_clk_hbm'}
I = {i: inst_of(i) for i in insts}
P = {i: ports(I[i][0]) for i in insts}
driven = {}
for i in insts:
    for p, n in I[i][1].items():
        if P[i][p][0] == 'output': driven[n.strip()] = P[i][p][1]
ins = {}
for i in insts:
    for p, n in I[i][1].items():
        n = n.strip()
        if P[i][p][0] == 'input' and p not in CLK and p != 'arst_n' and n not in driven: ins[n] = (P[i][p][1], i, p)
t = ['`timescale 1ns/1ps', '// GENERATED by gen_subdie.py (KV-TOK2): ' + ' '.join(insts), 'module tb_subdie;',
     '    reg clk = 0; always #0.416667 clk = ~clk;', '    reg arst_n = 0, hbm_rn = 0, host_rn = 0, die_rn = 0, bg = 0;',
     '    integer cyc = 0; always @(posedge clk) cyc <= cyc + 1;']
t += [f'    wire [{w-1}:0] {n};' for n, w in driven.items()]
for n, (w, i, p) in ins.items():
    if 'hbm_rst_n' in n: v = f"{{{w-1}'d1, hbm_rn}}" if w > 1 else 'hbm_rn'
    elif 'host_rst_n' in n: v = f"{{{w-1}'d1, host_rn}}" if w > 1 else 'host_rn'
    elif 'die_rst_n' in n: v = 'die_rn'
    elif p == 'i_host_boot_go': v = f"{{{w-1}'d1, bg}}"
    else: v = f"{w}'d0"
    t.append(f'    wire [{w-1}:0] {n} = {v};  // {i}.{p}')
for i in insts:
    conn = []
    for p, n in I[i][1].items():
        n = n.strip()
        conn.append(f'.{p}(' + ('clk' if p in CLK else 'arst_n' if p == 'arst_n' else n) + ')')
    t.append(f'    {I[i][0]} {i} (' + ', '.join(conn) + ');')
t.append('`include "probe_subdie.svh"')
t.append('endmodule')
open(out, 'w').write('\n'.join(t) + '\n')
print('instances', len(insts), 'internal nets', len(driven), 'boundary inputs', len(ins))
for n, (w, i, p) in ins.items(): print('  IN', w, n, i, p)
