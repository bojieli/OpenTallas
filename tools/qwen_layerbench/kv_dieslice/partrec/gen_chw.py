#!/usr/bin/env python3
"""TOK-QK/C 10-24: closed-loop hub_Wi host-link sub-bench generator (KV boot fixes C1 + C2).

The partrec replay (gen_partrec.py) drives every hub_Wi input from a whole-die record.  This bench keeps that replay for
every input EXCEPT the host SerDes link, which runs live and closed-loop on the real RTL:
  board port (real qfd_link_adp512_split + qkd_host_phy_cdc5, clk_phy; frames from +FRAMES with the host credits)
  -> bench PHY model halves (kvs_link_phy_models.sv, clk_phy, per-half skew +PHY_SKEW_W/E or +PHY_SKEW_RAND)
  -> the bound sys_SW / sys_SE partitions as staged (C-edited: ot_fdi_phy_cdc, the ONE crossing)
  -> core lanes of the bound depths (W 30 / E 36 incl. boundary flops) -> the C-edited hub_Wi (flat: ot_fdi_join2, core
     clock adapter, real HOST stack) -> o_host_fdi / link reset / tx_up lanes back to sys_SW / sys_SE -> board (deskew).
  Clocks: core 1.2 GHz, clk_phy +TP_PS (1043) with start phase +PHASE_PS; host 1.0, ingest 0.6 GHz as the vehicle.

    gen_chw.py HUBWI_EDITED.sv HUBWI_RECORDED.sv OUTDIR      -> OUTDIR/tb_chw.sv
HUBWI_RECORDED = the hub_Wi the record was made on (its input order = the record's indices).
Verdict line CHW PASS/FAIL: die HOST raw_rx words > 0, every one equal to the board's frame of that index (in order),
no adapter fault (die + board: f_seq / overrun / credit), no CDC word lost, no half-join overflow.
Mutants: +MUT_C1 (W lane valid lands 4 cycles after its data = the C1 bind bug); mutant (ii) = build with
fdicdc/mut_direct.sv instead of ot_fdi_phy_cdc.sv (direct wiring = the old unsynchronised crossing).
"""
import re
import sys


def ports_of(path, mod="kv3_hub_Wi_part"):
    s = open(path).read()
    hm = re.search(r'^module\s+' + mod + r'\b.*?\((.*?)\n\);', s, re.M | re.S)
    assert hm, path
    out = []
    for line in hm.group(1).split('\n'):
        pm = re.match(r'\s*(input|output)\s+wire\s*(\[(\d+):0\])?\s*(\w+)', line)
        if pm:
            out.append((pm.group(1), int(pm.group(3)) + 1 if pm.group(3) else 1, pm.group(4)))
    return out


CLOCKS = {'clk', 'clk_clk_host', 'clk_clk_ingest', 'clk_clk_phy', 'clk_clk_hbm', 'clk_clk_fwd'}
LIVE = {'i_serdes_W_rx_flit', 'i_serdes_E_rx_flit', 'i_serdes_W_tx_up'}      # i_dcal_dob[2] (fwd E tx_up) overridden

edited, recorded, out = sys.argv[1:4]
pe, pr = ports_of(edited), ports_of(recorded)
ins_r = [(w, n) for d, w, n in pr if d == 'input' and n not in CLOCKS]
ins_e = [(w, n) for d, w, n in pe if d == 'input' and n not in CLOCKS]
assert ins_r == ins_e, "edited hub_Wi changed its non-clock inputs: the record indices would not match"
outs = [(w, n) for d, w, n in pe if d == 'output']
clks = [n for d, w, n in pe if d == 'input' and n in CLOCKS]
assert 'clk_clk_phy' not in clks, "hub_Wi still loads clk_phy (C2 not applied?)"
for n in LIVE | {'i_dcal_dob', 'o_host_fdi', 'o_host_link_rst_n'}:
    assert any(x == n for _, _, x in pe), n

t = ['`timescale 1ns/1ps', '// GENERATED by partrec/gen_chw.py (TOK-QK/C 10-24): closed-loop hub_Wi host-link sub-bench', 'module tb_chw;']
t.append('''    real tp = 1.043, ph = 0.0;
    initial begin integer x; if ($value$plusargs("TP_PS=%d", x)) tp = x / 1000.0; if ($value$plusargs("PHASE_PS=%d", x)) ph = x / 1000.0; end
    reg clk = 0; always #0.416667 clk = ~clk;
    reg clk_clk_host = 0; always #0.500 clk_clk_host = ~clk_clk_host;
    reg clk_clk_ingest = 0; always #0.833334 clk_clk_ingest = ~clk_clk_ingest;
    reg ck_phy = 0; initial begin #(ph + 0.0005); forever #(tp / 2) ck_phy = ~ck_phy; end''')
t += [f'    reg [{w-1}:0] r_{n} = 0;' for w, n in ins_r]
t += [f'    wire [{w-1}:0] {n};' for w, n in outs]
t.append('    wire [523:0] l_i_serdes_W_rx_flit; wire [522:0] l_i_serdes_E_rx_flit; wire [1:0] l_i_serdes_W_tx_up; wire l_e_up;')
conn = []
for d, w, n in pe:
    if d == 'output' or n in CLOCKS:
        conn.append(f'.{n}({n})')
    elif n in LIVE:
        conn.append(f'.{n}(l_{n})')
    elif n == 'i_dcal_dob':
        conn.append(f'.{n}({{r_i_dcal_dob[3], l_e_up, r_i_dcal_dob[1:0]}})')
    else:
        conn.append(f'.{n}(r_{n})')
t.append('    kv3_hub_Wi_part dut (' + ', '.join(conn) + ');')
t.append('    integer core_cyc = 0; always @(posedge clk) core_cyc <= core_cyc + 1;')
t.append('    task automatic apply(input integer idx, input bit [8191:0] v);\n        case (idx)')
t += [f'            {i}: r_{n} = v[{w-1}:0];' for i, (w, n) in enumerate(ins_r)]
t.append('            default: $fatal(1, "bad input index %0d", idx);\n        endcase\n    endtask')
t.append('`include "chw_body.svh"')
t.append('endmodule')
open(f'{out}/tb_chw.sv', 'w').write('\n'.join(t) + '\n')
print(f'tb_chw: {len(ins_r)} inputs ({len(ins_r) - 3} replayed + 3 live + dcal_dob[2] live), {len(outs)} outputs, clocks {clks}')
