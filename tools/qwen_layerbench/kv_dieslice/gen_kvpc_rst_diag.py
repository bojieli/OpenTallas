#!/usr/bin/env python3
"""TOK-KV-1 10-28: generate kvpc_rst_diag.svh (tb_kvslice*.sv, +DIAG_KVPC_RST_HBM, DIAGNOSTIC only) from the bound top.

Every kvpc reset spine x_hub_Wi_rs_host_die_rst_n_<n>_pc_<Q>_<k> of the bound top is forced to follow HOST hbm_rst_n
instead of die_rst_n: the hbm_rst_n spine of the same slot (x_hub_Wi_rs_host_hbm_rst_n_<m>_pc_<Q>_<k>) when the bind has
one, else the HOST hbm_rst_n lane bit to hub_C (x_hub_Wi_o_host_hbm_rst_n_hub_C[0]).  Net numbering is the bind's, so the
list is regenerated on every build; fails (rc 2) when the top has no kvpc die_rst_n spine (the diag would be a no-op).
    gen_kvpc_rst_diag.py TOP.sv OUT.svh"""
import re, sys

top, out = sys.argv[1:3]
s = open(top).read()
die = sorted(set(re.findall(r'\b(x_hub_Wi_rs_host_die_rst_n_\d+_(pc_[A-Z]+_\d+))\b', s)), key=lambda t: t[1])
hbm = {slot: n for n, slot in re.findall(r'\b(x_hub_Wi_rs_host_hbm_rst_n_\d+_(pc_[A-Z]+_\d+))\b', s)}
lane = 'x_hub_Wi_o_host_hbm_rst_n_hub_C'
if not die:
    sys.exit('gen_kvpc_rst_diag: no kvpc die_rst_n reset spine in ' + top)
if not all(slot in hbm for _, slot in die) and not re.search(r'\b' + lane + r'\b', s):
    sys.exit('gen_kvpc_rst_diag: no hbm_rst_n source (spine or lane) in ' + top)
L = [f'// GENERATED by tools/qwen_layerbench/kv_dieslice/gen_kvpc_rst_diag.py from {top.split("/")[-1]}: '
     f'{len(die)} kvpc die_rst_n spines -> hbm_rst_n (DIAGNOSTIC, +DIAG_KVPC_RST_HBM only)']
for n, slot in die:
    src = f'dut.{hbm[slot]}' if slot in hbm else f'dut.{lane}[0]'
    L.append(f'        force dut.{n} = {src};')
L.append(f'        $display("DIAG_KVPC_RST_HBM %0d kvpc die_rst_n spines follow hbm_rst_n", {len(die)});')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'kvpc_rst_diag: {len(die)} spines, {sum(slot in hbm for _, slot in die)} same-slot hbm spines')
