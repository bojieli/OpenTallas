#!/usr/bin/env python3
"""QW-KVATTN2 10-19: the slice-edge map of the KV-die attention vehicle qwk_slice_attn (slice_cut.py of the kvs14p netlist).

The vehicle's slice edge toward the 32 static landing groups (slg_<stack>_<i>, qkd_kvs_grp / qkd_kvs_grp_h, NOT in the slice)
is the K request kreq / V request vreq (slice outputs, at the group pins) and the group's ONE response stream on its two
faces krsp (-> ECTL A issuer) and rsp (-> PV16 V port).  This tool reads the die netlist's slg_* instance lines and the
slice.json, checks every net is a slice port of the right width, and emits kva_grp_map.svh for drive_qwk_slice_attn.svh:
    wire [37:0] kva_kreq [g] / [14:0] kva_vreq [g]   <- o_<kreq net> / o_<vreq net>
    drv_i_<krsp net> / drv_i_<rsp net>              <- kva_krsp [g] / kva_rsp [g]
plus the ECTL configuration words of the four HOST roots (hroot_<stack>.o_c<e> = 4 e + stack, the sealed die-cfg values
read from the G-K1 boot run) and the per-ECTL facts the bench reports (RESPONSE_LAT bound in the netlist vs the
relay stages of case_kv/relay_stages.json).

    kv_attn_grp_map.py --die-v die_bound.v --slice slice.json --relay-stages relay_stages.json --out kva_grp_map.svh \
        --facts kva_grp_facts.json [--stacks WS[,WN,...]]

MU-TOK-KV2 10-19: --stacks maps a PER-STACK vehicle (slice_cut of one attention stack astk_<s> + its 8 ECTLs, 4 V ports,
32 head units and their relays/landings, plus the shared attention control kvs_attn/seq/ahub/pvw/pvfin): only that
stack's 8 landing groups, ECTL cfg / kgo and fault pins are emitted, with `define KVA_PARTIAL (the other stacks' partials
are not in the vehicle, so the bench reports timing, not RESULT exactness).
"""
import argparse
import json
import re
from pathlib import Path

STACKS = ('WS', 'WN', 'ES', 'EN')
LANDING_SEG_LAT = 8   # qkd_static_kv_landing_seg header: request -> response 8 edges (VREQ=1)


def conn(line, port):
    m = re.search(r'\.' + port + r'\(([^()]*)\)', line)
    if not m:
        raise SystemExit(f'kv_attn_grp_map: no .{port}( in {line[:120]}')
    net = m.group(1).strip()
    m2 = re.fullmatch(r'(\w+)\[(\d+):(\d+)\]', net)
    if not m2:
        raise SystemExit(f'kv_attn_grp_map: .{port}({net}) is not a whole net slice')
    return m2.group(1), int(m2.group(2)) - int(m2.group(3)) + 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--die-v', required=True)
    ap.add_argument('--slice', required=True)
    ap.add_argument('--relay-stages', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--facts', required=True)
    ap.add_argument('--stacks', default=','.join(STACKS), help='comma list of the stacks in the vehicle (default all 4)')
    a = ap.parse_args()
    stk = [x for x in STACKS if x in a.stacks.split(',')]
    if not stk or len(stk) != len(a.stacks.split(',')):
        raise SystemExit(f'kv_attn_grp_map: --stacks {a.stacks}: each of {STACKS}')
    V = Path(a.die_v).read_text()
    S = json.loads(Path(a.slice).read_text())
    ports = {(p['dir'], p['net']): p for p in S['ports']}
    grps = []
    for line in V.splitlines():
        m = re.match(r'\s*(qkd_kvs_grp(?:_h)?) (slg_(WS|WN|ES|EN)_(\d))\s*\(', line)
        if m:
            grps.append(dict(master=m.group(1), inst=m.group(2), stack=m.group(3), idx=int(m.group(4)),
                             kreq=conn(line, 'kreq'), vreq=conn(line, 'vreq'), krsp=conn(line, 'krsp'), rsp=conn(line, 'rsp')))
    grps.sort(key=lambda g: (STACKS.index(g['stack']), g['idx']))
    if len(grps) != 32:
        raise SystemExit(f'kv_attn_grp_map: {len(grps)} landing groups, expected 32')
    grps = [g for g in grps if g['stack'] in stk]
    NG, NV = len(grps), 4 * len(stk)
    L = ['// GENERATED by tools/qwen_layerbench/kv_attn_grp_map.py from ' + a.die_v,
         '//   slice ' + a.slice + ' (die sha256 ' + S['die_sha256'][:16] + ') stacks ' + ','.join(stk),
         f'    localparam integer KVA_NG = {NG}, KVA_NV = {NV}, KVA_NSTK = {len(stk)};',
         f'    wire [37:0] kva_kreq [0:{NG - 1}]; wire [14:0] kva_vreq [0:{NG - 1}];',
         f'    reg [1061:0] kva_krsp [0:{NG - 1}]; reg [1055:0] kva_rsp [0:{NG - 1}];']
    if len(stk) < 4:
        L.insert(2, '`define KVA_PARTIAL')
    L.append('`define KVA_STK_F {' + ', '.join(f'dut.astk_{x}.af' for x in reversed(stk)) + '}')
    L.append(f'    wire [42:0] kva_ap [0:{len(stk) - 1}];')
    for i, x in enumerate(stk):
        L.append(f'    assign kva_ap[{i}] = dut.astk_{x}.ap;')
    L.append('    function automatic string kva_sname(input integer s); case (s)')
    for i, x in enumerate(stk):
        L.append(f'        {i}: kva_sname = "{x}";')
    L.append('        default: kva_sname = "?"; endcase endfunction')
    for g, r in enumerate(grps):
        for face, d, w in (('kreq', 'output', 38), ('vreq', 'output', 15), ('krsp', 'input', 1062), ('rsp', 'input', 1056)):
            net, width = r[face]
            p = ports.get((d, net))
            if p is None or p['width'] != w or width != w:
                raise SystemExit(f'kv_attn_grp_map: {r["inst"]}.{face} net {net} is not a {w}-bit slice {d}')
        L.append(f'    assign kva_kreq[{g}] = {ports[("output", r["kreq"][0])]["port"]};   // {r["inst"]} ({r["master"]})')
        L.append(f'    assign kva_vreq[{g}] = {ports[("output", r["vreq"][0])]["port"]};')
        L.append(f'    always @* drv_{ports[("input", r["krsp"][0])]["port"]} = kva_krsp[{g}];')
        L.append(f'    always @* drv_{ports[("input", r["rsp"][0])]["port"]} = kva_rsp[{g}];')
    # ECTL cfg (5 b) from the HOST roots: 4 e + stack (G-K1 boot run: hroot_<s>.o_c<e> sealed values)
    L.append('    task automatic kva_ectl_cfg(); begin')
    for s, st in enumerate(STACKS):
        if st not in stk:
            continue
        for e in range(8):
            net = f'n_ks_kvs_hroot_{st}__o_c{e}'
            p = ports.get(('input', net))
            if p is None or p['width'] != 5:
                raise SystemExit(f'kv_attn_grp_map: {net} is not a 5-bit slice input')
            L.append(f'        drv_{p["port"]} = 5\'d{4 * e + s};')
    L.append('    end endtask')
    L.append('    task automatic kva_kg(input [22:0] w); begin')
    for st in stk:
        p = ports[('input', f'n_ks_kvs_hroot_{st}__o_kg')]
        L.append(f'        drv_{p["port"]} = w;')
    L.append('    end endtask')
    L.append('    function automatic string kva_gname(input integer g); case (g)')
    for g, r in enumerate(grps):
        L.append(f'        {g}: kva_gname = "{r["inst"]}";')
    L.append('        default: kva_gname = "?"; endcase endfunction')
    # unit fault pins (hierarchical, bench report only): 32 ECTL issuers + 16 V ports
    L.append(f'    wire [{NG - 1}:0] kva_ectl_f = {{' + ', '.join(f'dut.ectl_{r["inst"][4:]}.fault' for r in reversed(grps)) + '};')
    vps = [f'vport_{st}_{i}' for st in stk for i in range(4)]
    L.append(f'    wire [{NV - 1}:0] kva_vport_f = {{' + ', '.join(f'dut.{v}.fault' for v in reversed(vps)) + '};')
    L.append('    function automatic string kva_vname(input integer v); case (v)')
    for i, v in enumerate(vps):
        L.append(f'        {i}: kva_vname = "{v}";')
    L.append('        default: kva_vname = "?"; endcase endfunction')
    L.append(f'    wire [{NV - 1}:0] kva_vport_ov = {{' + ', '.join(f'dut.{v}.out_valid' for v in reversed(vps)) + '};')
    Path(a.out).write_text('\n'.join(L) + '\n')
    # facts: RESPONSE_LAT (netlist) vs relay stages (die table) per ECTL; V port RT vs its two round trips
    R = json.loads(Path(a.relay_stages).read_text())
    st = {(b['src']['inst'], b['src']['port'], b['dst']['inst'], b['dst']['port']): b['stages'] for b in R['buses']}
    rl = {m.group(2): int(m.group(1)) for m in re.finditer(r'qkd_ectl3_kiss_st #\(\.RESPONSE_LAT\((\d+)\).*?\) (ectl_\w+) \(', V)}
    rt = {m.group(2): int(m.group(1)) for m in re.finditer(r'qkd_pv16_vport #\(\.MUT\(\d+\), \.DQ\(\d+\), \.RT\((\d+)\)\) (vport_\w+) \(', V)}
    ectl = []
    rl = {e: v for e, v in rl.items() if e.split('_')[1] in stk}
    rt = {v: x for v, x in rt.items() if v.split('_')[1] in stk}
    for e, lat in sorted(rl.items()):
        g = 'slg_' + e[5:]
        q, r_ = st[(e, 'rq', g, 'kreq')], st[(g, 'krsp', e, 'rs')]
        ectl.append(dict(ectl=e, RESPONSE_LAT=lat, req_stages=q, rsp_stages=r_, needed=q + LANDING_SEG_LAT + r_,
                         ok=lat == q + LANDING_SEG_LAT + r_))
    vport = []
    for v, rtv in sorted(rt.items()):
        q0 = [s for k, s in st.items() if k[0] == v and k[1] == 'vq0'][0]
        q1 = [s for k, s in st.items() if k[0] == v and k[1] == 'vq1'][0]
        i0 = [s for k, s in st.items() if k[2] == v and k[3] == 'i0'][0]
        i1 = [s for k, s in st.items() if k[2] == v and k[3] == 'i1'][0]
        vport.append(dict(vport=v, RT=rtv, rt_i0=q0 + LANDING_SEG_LAT + i0, rt_i1=q1 + LANDING_SEG_LAT + i1,
                          ok=rtv == q0 + LANDING_SEG_LAT + i0 == q1 + LANDING_SEG_LAT + i1))
    facts = dict(schema='opentallas.qwk_slice_attn.grp_facts.v1', die_v=a.die_v, stacks=stk, relay_stages=a.relay_stages,
                 landing_seg_latency=LANDING_SEG_LAT, groups=[dict(g=g, inst=r['inst'], master=r['master']) for g, r in enumerate(grps)],
                 ectl=ectl, ectl_ok=sum(x['ok'] for x in ectl), vport=vport, vport_ok=sum(x['ok'] for x in vport))
    Path(a.facts).write_text(json.dumps(facts, indent=1) + '\n')
    print(f'kv_attn_grp_map: {NG} groups (stacks {",".join(stk)}) -> {a.out}; ECTL RESPONSE_LAT consistent with die stages '
          f'{facts["ectl_ok"]}/{len(ectl)}, V port RT consistent {facts["vport_ok"]}/{len(vport)}')


if __name__ == '__main__':
    main()
