def src_file(rtr, rel, roots=None):
    """FLOW-FIX-2045: path of an rt file by its repo-relative path.  In a stage job the refresher runs from an admission BUNDLE (die_plan/ + __flow__/), not from an rt tree: roots {rel dir: directory
    holding its current files} (the --src arguments) say where each repo dir lives, rt/<rel> otherwise"""
    for d in sorted((roots or {}), key=len, reverse=True):
        if rel == d or rel.startswith(d + "/"):
            return os.path.join(roots[d], rel[len(d) + 1:]) if rel != d else roots[d]
    return os.path.join(rtr, rel)


def _rt_run_kit_text(rtr, roots=None):
    import importlib.util
    dd = src_file(rtr, "tools/die_plan", roots)
    gp = os.path.join(dd, "gen_phys.py")
    if not os.path.isfile(gp):
        return None
    if dd not in sys.path:
        sys.path.insert(0, dd)
    mod = sys.modules.get("gen_phys")
    if mod is None or os.path.dirname(os.path.abspath(getattr(mod, "__file__", "") or "")) != os.path.abspath(dd):
        spec = importlib.util.spec_from_file_location("gen_phys_rt", gp)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    return getattr(mod, "RUN_KIT", None)


TAP_LINE = "uplevel #0 [list source [file join $cp_dir tap_balance.tcl]]\n"
STB_MARK = "# DIE-CORETAP-1119 (FABLE-CLOSURE lever 1, kit side)"


def patch_cts_post(kit, rtr, rec, dry=False, roots=None):
    """FLOW-FIX-2045 (COORD, DIE-CORETAP 7109ee911ef): a kit's cts_post.tcl is a PER-KIT edit of tools/die_plan/cts_post.tcl (gen inserts hook lines: clock_edge_balance, the cland_fclk_target hook ...), so it is never
    replaced whole.  A kit whose cts_post.tcl does not source subtree_balance.tcl yet gets rt's subtree-balance block (from the DIE-CORETAP comment to the line before the tap_balance source) inserted
    right before that line; every other line of the kit's file stays.  Needs exactly one tap_balance source line in the kit; idempotent.  -> True when patched"""
    p = os.path.join(kit, "cts_post.tcl")
    sp = src_file(rtr, "tools/die_plan/cts_post.tcl", roots)
    if os.path.islink(p) or not os.path.isfile(p) or not os.path.isfile(sp):
        return False
    old, new = _cur(p).decode(), open(sp).read()
    if "subtree_balance.tcl" in old or new.count(TAP_LINE) != 1 or STB_MARK not in new or old.count(TAP_LINE) != 1:
        return False
    a, b = new.index(STB_MARK), new.index(TAP_LINE)
    if a > b:
        return False
    block = new[a:b]
    rec["replaced"].append({"file": "cts_post.tcl", "src": "tools/die_plan/cts_post.tcl (subtree-balance block)", "old": blob_id(old.encode())[:12], "new": "patched", "from": "always-patch"})
    if dry:
        return True
    out = old.replace(TAP_LINE, block + TAP_LINE)
    _put(p, out.encode())
    return True


BOUND_LINE = "uplevel #0 [list source /work/repair_bound.tcl]"


def patch_grt_hook(kit, rec, dry=False):
    """FLOW-FIX-2045: the kit's PRE_GLOBAL_ROUTE_TCL file (named in config.mk; grt_pre.tcl, cons_grt_pre.tcl, grt_pre_core.tcl, macro_ff_pre_grt.tcl ...) gets one guarded line at its END that sources
    /work/repair_bound.tcl, so the bound wraps the repair_timing_helper every earlier hook has already wrapped.  Missing config line / hook file / repair_bound.tcl in the kit = nothing.  Idempotent.  -> True when patched"""
    cfg = os.path.join(kit, "config.mk")
    try:
        txt = open(cfg).read()
    except OSError:
        return False
    ms = re.findall(r"(?m)^(?:override\s+)?export\s+PRE_GLOBAL_ROUTE_TCL\s*(?::=|=)\s*(/work/\S+\.tcl)\s*$", txt)
    if not ms or not os.path.isfile(os.path.join(kit, "repair_bound.tcl")):
        return False
    p = os.path.join(kit, ms[-1][len("/work/"):])
    if os.path.islink(p) or not os.path.isfile(p):
        return False
    body = _cur(p).decode()
    if "repair_bound.tcl" in body:
        return False
    rec["replaced"].append({"file": os.path.basename(p), "src": "repair_bound hook line", "old": blob_id(body.encode())[:12], "new": "patched", "from": "always-patch"})
    if dry:
        return True
    out = body + ("" if body.endswith("\n") else "\n") + "# FLOW-FIX-2045: bound the post-GRT repair_timing_helper (chunk + stall + wall time)\nif {[file exists /work/repair_bound.tcl]} { " + BOUND_LINE + " }\n"
    _put(p, out.encode())
    return True


def always_pass(kit, rtr, rec, dry=False, roots=None):
    """replace the ALWAYS files present in the kit by rt's copy when they differ.  -> list of replaced names (also appended to rec['replaced'] with from='always')"""
    out = []
    for where, name, srcrel in ALWAYS:
        p = os.path.join(kit, name) if where in ("kit", "kit+") else os.path.join(os.path.dirname(kit.rstrip("/")), name)
        if os.path.islink(p) or (not os.path.isfile(p) and where != "kit+"):
            continue
        try:
            if srcrel == "gen_phys.RUN_KIT":
                txt = _rt_run_kit_text(rtr, roots)
                new = txt.encode() if txt else None
            else:
                sp = src_file(rtr, srcrel, roots)
                new = open(sp, "rb").read() if os.path.isfile(sp) else None
        except Exception as e:                       # noqa: BLE001 - a missing / broken rt file never stops a stage
            rec.setdefault("kept_old", []).append(f"{name}: {type(e).__name__}: {e}")
            continue
        if not new:
            continue
        data = _cur(p) if os.path.isfile(p) else b""
        if new == data and os.path.isfile(p):
            continue
        rec["replaced"].append({"file": name, "src": srcrel, "old": blob_id(data)[:12], "new": blob_id(new)[:12], "from": "always"})
        out.append(name)
        if dry:
            continue
        _put(p, new, kind="runner" if where == "runner" else "kit")
    if patch_cts_post(kit, rtr, rec, dry, roots):
        out.append("cts_post.tcl")
    if patch_grt_hook(kit, rec, dry):
        out.append("grt_hook")
    return out


def refresh(kit, stage, rt=RT, dry=False, index=None, src=None, sha=None, die_src=None):
    """all or nothing (FLOW-PROC-A): the passes stage their writes, commit() applies all of them or none (PartialRefresh)"""
    global _TXN
    outer, _TXN = _TXN, []
    try:
        rec = _plan(kit, stage, rt, dry, index, src, sha, die_src)
        txn = list(_TXN)
    finally:
        _TXN = outer
    rec["_kit"] = kit
    try:
        if not dry:
            commit(txn, rec)
    finally:
        rec.pop("_kit", None)
    tr = rec.pop("_tools_rev", None)
    if tr and not dry:
        write_tools_rev(kit, rec, *tr)
    return rec


def _plan(kit, stage, rt=RT, dry=False, index=None, src=None, sha=None, die_src=None):
    rtr = os.path.realpath(rt)
    roots = dict(src or {})                              # rel dir -> directory holding its current files (default rt/<rel dir>)
    rec = {"t": time.strftime("%Y-%m-%d %H:%M:%S %Z"), "stage": stage, "rt": rtr, "host": socket.gethostname().split(".")[0],
           "replaced": [], "kept_old": [], "note": ""}
    if sha:
        rec["sha"] = sha
    else:
        try:
            rec["sha"] = json.load(open(rtr + ".manifest.json")).get("sha", "")
        except (OSError, ValueError):
            rec["sha"] = os.path.basename(rtr)
    ip = index or os.path.join(rtr, INDEX)
    try:
        idx = json.load(open(ip))
    except (OSError, ValueError):
        rec["note"] = f"SKIPPED: no flow blob index {ip}: nothing replaced by the index pass"
        always_pass(kit, rtr, rec, dry, roots)
        if die_src:
            _die_pass(kit, rec, rtr, die_src, dry)
        return rec
    if idx.get("sha") and not sha:
        rec["sha"] = idx["sha"]
    known = idx.get("blobs") or {}                       # rel -> [blob ids on main]
    by_name = {}
    for rel in known:
        by_name.setdefault(os.path.basename(rel), []).append(rel)
    for name in sorted(os.listdir(kit)):
        p = os.path.join(kit, name)
        if name in NEVER or not name.endswith(EXT) or os.path.islink(p) or not os.path.isfile(p):
            continue
        rels = [r for r in by_name.get(name, []) if any(r == f"{d}/{name}" for d in DIRS)]
        if not rels:
            continue
        data = _cur(p)
        b = blob_id(data)
        rel = next((r for r in rels if b in known[r]), None)
        if rel is None:
            continue                                     # generated or edited at gen: not a copy of main
        d = os.path.dirname(rel)
        cur = os.path.join(roots[d], os.path.basename(rel)) if d in roots else os.path.join(rtr, rel)
        if not os.path.isfile(cur):
            rec["kept_old"].append(f"{name} ({rel} gone from main)")
            continue
        new = open(cur, "rb").read()
        if new == data:
            continue
        rec["replaced"].append({"file": name, "src": rel, "old": b[:12], "new": blob_id(new)[:12]})
        if dry:
            continue
        _put(p, new)
    always_pass(kit, rtr, rec, dry, roots)
    if die_src:
        _die_pass(kit, rec, rtr, die_src, dry)
    return rec


def _die_pass(kit, rec, rtr, die_src, dry):
    rep, rt_files, die_only = die_tree_copies(kit, rtr, os.path.realpath(die_src), dry)
    rec["replaced"].extend(rep)
    for r in rec["replaced"]:                            # index-pass replacements are rt files too
        rt_files.setdefault(r["file"], r["src"])
    rec["_tools_rev"] = (rt_files, die_only)              # written after the commit (it lists what the kit now holds)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--kit", required=True)
    ap.add_argument("--stage", default="")
    ap.add_argument("--rt", default=RT)
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--index", default="", help="flow blob index (default RT/tools/.flow_blobs.json)")
    ap.add_argument("--src", action="append", default=[], help="REL_DIR=DIR: current files of REL_DIR are in DIR (a staged copy)")
    ap.add_argument("--sha", default="")
    ap.add_argument("--die-src", default="", help="the die source tree: kit scripts that are its copies are replaced by rt's; writes K/tools_rev.json")
    a = ap.parse_args(argv)
    kit = os.path.abspath(a.kit)
    if os.environ.get("OT_FLOW_REFRESH", "1") == "0" or os.path.exists(os.path.join(kit, ".no_flow_refresh")):
        print("KIT_FLOW_REFRESH SKIPPED: off (OT_FLOW_REFRESH=0 or KIT/.no_flow_refresh)", flush=True)
        return 0
    try:
        rec = refresh(kit, a.stage, a.rt, a.dry, index=a.index or None, src=dict(x.split("=", 1) for x in a.src), sha=a.sha or None, die_src=a.die_src or None)
    except Exception as e:                               # noqa: BLE001 - all or nothing: the kit is unchanged, the caller defers the stage
        rec = {"t": time.strftime("%Y-%m-%d %H:%M:%S %Z"), "stage": a.stage, "error": f"{type(e).__name__}: {e}", "partial": True,
               "host": socket.gethostname().split(".")[0]}
    if not a.dry:
        try:
            with open(os.path.join(kit, "flow_refresh.jsonl"), "a") as f:
                f.write(json.dumps(rec, sort_keys=True) + "\n")
        except OSError:
            pass
    print(f"KIT_FLOW_REFRESH stage {a.stage} rt {str(rec.get('sha'))[:12]} replaced {len(rec.get('replaced') or [])}: "
          + " ".join(r["file"] for r in rec.get("replaced") or []) + (f" ({rec.get('note') or 'SKIPPED: ' + str(rec.get('error'))})" if rec.get("note") or rec.get("error") else "")
          + (f" runner_override {rec['runner_override']}" if rec.get("runner_override") else ""), flush=True)
    if rec.get("partial"):
        print(f"KIT_FLOW_REFRESH FAIL FLOW-REFRESH-PARTIAL: stage {a.stage} on {rec.get('host')}: {rec.get('error')}; nothing in the kit was changed "
              f"(all or nothing); the stage is deferred, not launched on stale flow files", flush=True)
        return PARTIAL_RC
    return 0


def runner_override(kit, since=0.0):
    """the refreshed runner a sealed job must run instead of its read-only input (the LAST flow_refresh.jsonl record names it), else None"""
    try:
        lines = open(os.path.join(kit, "flow_refresh.jsonl")).read().splitlines()
        rec = json.loads(lines[-1]) if lines else {}
    except (OSError, ValueError):
        return None
    alt = rec.get("runner_override")
    if alt and os.path.isfile(alt) and os.path.getmtime(alt) >= since - 5:
        return alt
    return None


