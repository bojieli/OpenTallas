#!/usr/bin/env python3
"""hbm-forks (2026-10-09): the DS-V4.1-Flash 1M-token program of the simulator (hgi_sim.ds_native --program-out, rank 0,
HGI-1 v1.0 encoding: 40 layers + head) through the RTL sequencer: CF-PROG DS.

Each layer's record stream (and the head) becomes one sequencer case at pos 2^20 - 1, rank 0, DS limits, with a closing
CTL.END (the layer programs end without one).  The reference model (tools/hgi_seq_vectors.Ref) runs every record; every
non-indexed effective base / n is checked against the simulator's addressing (hgi_sim Machine.eff); the bench files
(tag _ds) make tb_hgi_seq.sv +define+SEQ_DS compare every RTL dispatch with the reference.
  python3 tools/hgi_seq_ds.py PROGRAM.json [--layers 0,20,head]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import hgi_seq_vectors as SV  # noqa: E402

T = ROOT / 'rtl/hbm_accel/generic/tb'
POS, TOK, RANK = (1 << 20) - 1, 5, 0
END_TOKEN_VM = 0x3FFF0


def main():
    prog = json.loads(Path(sys.argv[1]).read_text())
    want = sys.argv[sys.argv.index('--layers') + 1].split(',') if '--layers' in sys.argv else None
    from hgi_sim import machine as M
    from hgi_sim import records as SR
    words, cases, exp, rows = [], [], [], []
    vm0 = {END_TOKEN_VM: 1234}
    end = SV.record(SV.header('CTL', 'END', wait=0xFFFE), descs=dict(A=SV.mdesc(space=1, fmt=5, base=END_TOKEN_VM, n=1)))
    for lay in prog['layers']:
        if want and str(lay['layer']) not in want:
            continue
        recs = [SR.decode_one(bytes.fromhex(r['hex']), 0)[0] for r in lay['records']]
        img = []
        for r in lay['records']:
            b = bytes.fromhex(r['hex'])
            img += [int.from_bytes(b[q:q + 16], 'little') for q in range(0, len(b), 16)]
        entry = len(words)
        words += img + end
        ref = SV.Ref(words, entry, TOK, POS, RANK, 129280, 1 << 20, vm0)
        tr, cpl = ref.run()
        # addressing equal to the simulator's for every non-indexed descriptor
        die = M.Die(RANK, None)
        mach = M.Machine([die])
        idx, wi = {}, entry
        for r in recs:
            idx[wi] = r
            wi += SR.rec_bytes(r) // 16
        nchk, bad = 0, []
        for d in tr:
            r = idx[d['rec']]
            die.dyn[:16] = [0, POS, POS + 1, TOK, d['L'], RANK, r.slot, POS + r.slot, d['L1'], 0, 0, 0, 0, 0, 0, POS + r.slot + 1]
            mach.cur = None
            for j, nm in enumerate(SV.OPND):
                dd = r.desc.get(nm)
                if dd is None or dd.indexed or dd.n_sel == SR.NSEL_FROM_VM:
                    continue
                base, nn, *_ = mach.eff(dd, die, d['L'])
                if (SV.field(d['eff'][j], SV.MD, 'base'), d['n'][j]) != (base & SV.M40, nn & SV.M21):
                    bad.append((r.tag, nm))
                nchk += 1
        rows.append(dict(layer=lay['layer'], records=len(recs), dispatches=len(tr), cpl=cpl, fault=getattr(ref, 'fault', None),
                         descriptors_checked=nchk, sim_mismatches=bad[:5], n_bad=len(bad)))
        first = len(exp) // 11
        for d in tr:
            mw = d['unit'] | d['L'] << 4 | d['L1'] << 20 | (d['pos1'] & SV.M21) << 36 | (d['pslot1'] & SV.M21) << 57
            exp += [mw, d['hdr'], d['sut']] + d['eff'] + [sum((n & SV.M21) << (21 * j) for j, n in enumerate(d['n']))]
        cases.append((entry, TOK, POS, RANK, 129280, 1 << 20, len(tr), cpl[0], cpl[1], 0xFFFF, first, 1 << 8))
        print(rows[-1])
    (T / 'hgi_seq_image_ds.mem').write_text('\n'.join(f'{w:032X}' for w in words) + '\n')
    (T / 'hgi_seq_expect_ds.mem').write_text('\n'.join(f'{x:064X}' for x in exp) + '\n')
    (T / 'hgi_seq_cfg_ds.mem').write_text('\n'.join(' '.join(f'{x:08X}' for x in c) for c in cases) + '\n')
    (T / 'hgi_seq_vmi_ds.mem').write_text('\n'.join(f'{c:08X}{a:08X}{v:08X}' for c in range(len(cases)) for a, v in vm0.items()) + '\n')
    (T / 'hgi_seq_toks_ds.mem').write_text('\n'.join(' '.join(['0' * 16] * 16) for _ in cases) + '\n')
    mds = []
    for c in cases:
        mds += SV.G.d_pack(dict(magic=SV.G.MAGIC, ver_minor=SV.G.D_VERSION[1], ver_major=SV.G.D_VERSION[0], n_words=SV.G.NWORDS,
                                cp_vocab=129280, cp_ctx_max=1 << 20, coll_group_size=96, entry_ar=c[0], image_base=0x10,
                                image_pages=1))
    (T / 'hgi_seq_md_ds.mem').write_text('\n'.join(f'{x:08X}' for x in mds) + '\n')
    (T / 'hgi_seq_sizes_ds.svh').write_text('// GENERATED by tools/hgi_seq_ds.py\n' + '\n'.join(
        f'localparam integer {k} = {v};' for k, v in dict(DS_NW=len(words), DS_NCASE=len(cases), DS_NEXP=max(11, len(exp)),
                                                        DS_NVMI=len(cases) * len(vm0)).items()) + '\n')
    rec = dict(schema='opentallas.hbm_forks.hgi_seq_ds.v1', program=str(sys.argv[1]), pos=POS, rank=RANK, rows=rows,
               total_dispatches=len(exp) // 11, sim_mismatches=sum(r['n_bad'] for r in rows),
               faults=[r for r in rows if r['cpl'][1] != 0])
    (T / 'hgi_seq_ds.json').write_text(json.dumps(rec, indent=1) + '\n')
    print('dispatches', rec['total_dispatches'], 'sim mismatches', rec['sim_mismatches'], 'faults', len(rec['faults']))
    return 1 if rec['sim_mismatches'] or rec['faults'] else 0


if __name__ == '__main__':
    raise SystemExit(main())
