#!/usr/bin/env python3
"""TKM root core reset form (HBM-GAPS-3 TKMRST, 11-05).

Derives ot_hgi_coll_tkm_tp192_root_core__ctlrst.sv from the committed yosys
extract ot_hgi_coll_tkm_tp192_root_core.sv (rest_extract_mem.sh, d44v part 19).

Why: the extract keeps the TKM control/config hold registers (first,
ingress_end, clear2, read2, second, finish, cells, cfg_i, cfg_*_off) and a few
slot[0..7] tag/valid bits as plain `always @(posedge clk)` flops without reset.
Kit synthesis folds the bits that only ever load a constant (or merges
duplicated sign bits), while the LEC gold keeps them as X power-up state, so the
kit LEC fails (6355 points) in states that are unreachable after reset.

Safe form: those registers get the same async active-low reset to 0 that the
core already uses (rst_n: w_v, busy, done, fault, cfg_pipe ...). Every one of
them is loaded before it is read after reset (cfg_pipe is reset and cfg_i is
loaded the cycle before cfg_pipe[2] reads it), so the visible behaviour after
reset is unchanged; it only removes the X power-up state.

Opt-in: the committed default file is untouched; a kit uses this form only when
its recipe lists the __ctlrst file instead of the default one. Module names are
unchanged (drop-in replacement; never list both files in one build).

Usage: tkm_root_ctlrst.py SRC.sv OUT.sv     (deterministic; --check compares)
"""
import re, sys

MOD = 'ot_hgi_coll_tkm_tp192_root_core_x'
RST = 'rst_n'
# whole-register reset: control/config hold registers
WHOLE = ['_60220_', '_60224_', '_60225_', '_60226_', '_60227_', '_60228_',
         '_60233_', '_60250_', '_60251_', '_60252_', '_60253_', '_60254_']
# slot[0..7] (344 bits each): only the bits the kit gate removes get a reset
SLOTS = ['_60277_', '_60278_', '_60279_', '_60280_', '_60281_', '_60282_',
         '_60283_', '_60284_']
SLOT_BITS = [1, 3, 85, 87, 89, 171, 174, 175, 257, 259, 260, 261, 343]
# (* keep *) regs: with the reset, kit synthesis (ORFS yosys) removes ingress_end[3] and second[1] although
# they are not constant (merged / sequentially folded), and lec.py cannot match the gold-only flop
# (5874 w_addr/w_data/w_mask points, LEC run 11-06 01:08).  keep on the reg wire + the kit's
# ot_keep_regs.tcl (SYNTH_CANONICALIZE_TCL) keeps every flop of these two registers.
KEEP = ['_60224_', '_60227_']

HDR = ('// GENERATED by tools/hbm_b2/tkm_l74/tkm_root_ctlrst.py from '
       'ot_hgi_coll_tkm_tp192_root_core.sv: async reset (rst_n -> 0) on the TKM '
       'control/config hold registers + slot tag/valid bits, keep on ingress_end/second (opt-in reset form, '
       'HBM-GAPS-3 TKMRST 11-05). Same module names: drop-in for the default file.\n')


def transform(lines):
    # module span of the _x module
    m0 = next(i for i, l in enumerate(lines) if l.startswith('module ' + MOD + '('))
    m1 = next(i for i in range(m0, len(lines)) if lines[i].startswith('endmodule'))
    hdr = lines[m0]
    assert re.search(r'\b%s\b' % RST, hdr), 'rst_n not a port of ' + MOD
    out = list(lines)
    done = {}
    for name in WHOLE + SLOTS:
        hits = [i for i in range(m0, m1) if name in out[i]]
        assert len(hits) == 3, (name, hits)
        ir, ia, ias = hits[0], hits[1], hits[2]
        mreg = re.match(r'^  reg \[(\d+):0\] %s;$' % re.escape(name), out[ir])
        assert mreg, out[ir][:80]
        w = int(mreg.group(1)) + 1
        assert out[ir + 1] == '  always @(posedge clk)\n', out[ir + 1]
        assert ia == ir + 2 and out[ia].startswith('    %s <= ' % name) and out[ia].endswith(';\n')
        assert ias == ir + 3 and out[ias].startswith('  assign {') and out[ias].endswith('} = %s;\n' % name)
        rhs = out[ia][len('    %s <= ' % name):-2]
        if name in KEEP:
            out[ir] = '  (* keep *)\n' + out[ir]
        if name in WHOLE:
            out[ir + 1] = '  always @(posedge clk, negedge %s)\n' % RST
            out[ia] = '    if (!%s) %s <= %d\'d0;\n    else %s <= %s;\n' % (RST, name, w, name, rhs)
            done[name] = w
        else:
            assert w == 344
            d, r, mm = name + 'd', name + 'r', name + 'm'
            nb = len(SLOT_BITS)
            out[ir] = ('  reg [%d:0] %s;\n  wire [%d:0] %s;\n  assign %s = %s;\n'
                       % (w - 1, name, w - 1, d, d, rhs))
            out[ir + 1] = '  always @(posedge clk)\n'
            out[ia] = '    %s <= %s;\n' % (name, d)
            rb = sorted(SLOT_BITS, reverse=True)
            out[ia] += ('  reg [%d:0] %s;\n  always @(posedge clk, negedge %s)\n'
                        '    if (!%s) %s <= %d\'d0;\n    else %s <= { %s };\n'
                        % (nb - 1, r, RST, RST, r, nb, r,
                           ', '.join('%s[%d]' % (d, b) for b in rb)))
            pos = {b: nb - 1 - k for k, b in enumerate(rb)}
            bits = ['%s[%d]' % (r, pos[b]) if b in pos else '%s[%d]' % (name, b)
                    for b in range(w - 1, -1, -1)]
            out[ia] += '  wire [%d:0] %s = { %s };\n' % (w - 1, mm, ', '.join(bits))
            out[ias] = out[ias][:-len('%s;\n' % name)] + '%s;\n' % mm
            done[name] = nb
    return [HDR] + out, done


def main(argv):
    check = '--check' in argv
    a = [x for x in argv if x != '--check']
    src, dst = a[0], a[1]
    lines = open(src).read().splitlines(True)
    new, done = transform(lines)
    txt = ''.join(new)
    if check:
        ok = open(dst).read() == txt
        print('CHECK', 'PASS' if ok else 'FAIL', dst)
        return 0 if ok else 1
    open(dst, 'w').write(txt)
    print('wrote', dst, 'reset flops:', sum(done.values()), done)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
