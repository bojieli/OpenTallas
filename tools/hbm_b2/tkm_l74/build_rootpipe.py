#!/usr/bin/env python3
"""Extract the opt-in static_pd CB21 root from repository RTL; tile transport is external.

Run through ot-run. The root's small slot memory must be lowered before SUBMOD;
otherwise Yosys silently skips the entire extraction and writes an empty file.
The canonical core wrapper and every cut port remain unchanged.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BASE = 'ot_hgi_coll_tkm_tp192_root_core'
FILES = [
 'rtl/hbm_accel/cores_split/ot_hgi_coll_tkm_m_tp192_face/ot_hgi_coll_tkm_m_tp192_pfd21.sv',
 'rtl/hbm_accel/generic/collective/tkm/ot_hgi_coll_tkm_static_pd.sv',
 'rtl/hbm_accel/generic/collective/tkm/ot_hgi_coll_tkm_static.sv',
 'rtl/hbm_accel/generic/collective/tkm/ot_hgi_coll_tkm.sv',
 'rtl/hbm_accel/generic/collective/tkm/ot_hgi_coll_tkm_buffer.sv',
 'rtl/lib/ot_rst_relay.sv',
]
CANON = 'rtl/hbm_accel/cores_split/ot_hgi_coll_tkm_m_tp192/ot_hgi_coll_tkm_tp192_root_core.sv'
MEMORY = 'physical/asap7_memory_macros_v2/ot_sram_1r1w_1024x256_m2_r2c2/ot_sram_1r1w_1024x256_m2_r2c2_bb.v'


def body(text, name):
    match = re.search(r'(?ms)^module\s+\\?' + re.escape(name) + r'\b.*?^endmodule\s*$', text)
    if match is None:
        raise ValueError(f'missing extracted module {name}; an empty Yosys output is not success')
    return match.group(0)


def ports(module):
    return sorted((d, w or '', n.lstrip('\\')) for d, w, n in re.findall(r'(?m)^  (input|output)\s+(?:\[(\d+:\d+)\]\s*)?(\S+)\s*;', module))


def assemble(extracted, canonical):
    new, old = body(extracted, BASE + '_x'), body(canonical, BASE + '_x')
    if ports(new) != ports(old):
        raise ValueError('root cut port set changed; update the physical interface explicitly')
    wrapper = body(canonical, BASE)
    return ('// GENERATED by tools/hbm_b2/tkm_l74/build_rootpipe.py from static_pd PIPE1 HOP2 FRT4 CB21 CLRB0 DELIVERED_RESET1; external tiles omitted.\n'
            '`timescale 1ns/1ps\n' + new + '\n\n' + wrapper + '\n').replace(BASE, BASE + '__pfd21')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', required=True, type=Path)
    ap.add_argument('--assemble-existing', type=Path, help='reuse a retained raw extraction')
    args = ap.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    raw = out / 'root_extract.v'
    if args.assemble_existing:
        raw.write_bytes(args.assemble_existing.read_bytes())
    else:
        commands = [f'read_verilog -lib {MEMORY}'] + [f'read_verilog -sv -DSYNTHESIS {p}' for p in FILES]
        commands += ['hierarchy -check -top ot_hgi_coll_tkm_m_tp192_pfd21', 'rename -top elab_top', 'proc', 'opt_clean',
                     'setattr -mod -set keep_hierarchy 1 ot_hgi_coll_tkm_tile_e86', 'flatten', 'opt_clean', 'splitnets', 'opt_clean',
                     'memory_map elab_top', 'cd elab_top', 'select -set ex c:u.g_tiles*',
                     f'submod -name {BASE}_x c:* @ex %d', 'cd ..', f'select {BASE}_x',
                     'write_verilog -selected -noattr /out/root_extract.v']
        (out / 'extract.ys').write_text('\n'.join(commands) + '\n')
        subprocess.run(['docker', 'run', '--rm', '-v', f'{ROOT}:/src:ro', '-v', f'{out}:/out', '-w', '/src',
                        'openroad/orfs:asap7lock', 'bash', '-lc',
                        'source /OpenROAD-flow-scripts/env.sh >/dev/null 2>&1; yosys -q -l /out/extract.log -s /out/extract.ys'], check=True)
    result = out / f'{BASE}__pfd21.sv'
    result.write_text(assemble(raw.read_text(), (ROOT / CANON).read_text()))
    inputs = FILES + [MEMORY, CANON, str(Path(__file__).resolve().relative_to(ROOT))]
    receipt = {'inputs': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in inputs},
               'output': result.name, 'sha256': hashlib.sha256(result.read_bytes()).hexdigest(),
               'data_cycle_delta': 0, 'private_buffer_reset_release_edges': 3,
               'physical_status': 'NOT_SIGNED; generated source only'}
    (out / 'source_receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(f'ROOTPIPE_EXTRACT_PASS {len(ports(body(raw.read_text(), BASE + "_x")))} canonical cut ports; {result}')


if __name__ == '__main__':
    main()
