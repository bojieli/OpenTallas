#!/usr/bin/env python3
"""DIE-HBM-66 11-05 (COORD ruling on the Sinkhorn ASK, option A): HBM tail on S81's row-pipelined ot_hdc_sinkhorn_fsr.
The CE form gave the Sinkhorn arithmetic 7 clk per step behind sk_en, but sdc_lint has no multicycle, so sign-off timed it at
833 ps (step0 TT -3846).  This generator derives the rest core from the committed CE rest (arithmetic and phases verbatim):
1-edge sink launch, no enable, wider age counters, calendar from the measured sink latency.  Output is committed RTL."""
from pathlib import Path
import sys
REPO=Path(__file__).resolve().parents[2]
SRC=REPO/"rtl/hbm_accel/cores_split/sk_en_q4/ot_hbm_hc_tail_rest_core_ce.sv"
OUT=REPO/"rtl/hbm_accel/cores_split/sk_fsr_1105/ot_hbm_hc_tail_rest_core_fsr.sv"
def must(t,a,b):
    if t.count(a)!=1: raise SystemExit(f"anchor x{t.count(a)}: {a[:70]}")
    return t.replace(a,b)
def gen():
    t=SRC.read_text()
    t=must(t,"// GENERATED by tools/hbm_b2/sk_ce_kit.py: QUAD5 CE remainder, Sinkhorn cut only.","// GENERATED by tools/hbm_b2/sk_fsr_kit.py from ot_hbm_hc_tail_rest_core_ce.sv: fsr sink calendar, no sink enable.")
    t=t.replace("ot_hbm_hc_tail_static_rest_ce","ot_hbm_hc_tail_static_rest_fsr")
    t=must(t,"module ot_hbm_hc_tail_rest_core_ce #(","module ot_hbm_hc_tail_rest_core_fsr #(")
    t=must(t,"    parameter integer SDIV = 7,\n","")
    t=must(t,"    parameter integer CAP  = 289 + ((SMUT == 1) ? 0 : SDIV),   // split Sinkhorn: +1 sink edge\n","    parameter integer CAP  = 769 - ((SMUT == 1) ? 1 : 0),       // sink launch -> out_valid at this core (faces + fsr LAT + FQ)\n")
    t=must(t,"    parameter integer SKL = 198 + SDIV * ((TE + 1 - 198 + SDIV - 1) / SDIV),   // sink launch age: whole SDIV periods later\n","    parameter integer SKL = TE + 1,   // sink launch age: every t word written back\n")
    t=must(t,"    parameter integer L = SKL + SDIV + CAP + 2\n","    parameter integer L = SKL + CAP + 3\n")
    i=t.index("    localparam integer CW = $clog2(SDIV);"); j=t.index("    reg active, sl, armed;")
    t=t[:i]+"    wire wrap = 1'b1;      // no sink enable: launch on the SKL edge, sl is one edge wide\n    wire sclk = 1'b1;\n    wire sk_en_o = 1'b0;   // pin kept (rest table unchanged), no load at the parent\n"+t[j:]
    t=must(t,"reg [9:0] age, sage;","reg [11:0] age, sage;")
    t=must(t,"active <= 1'b1; age <= 10'd1;","active <= 1'b1; age <= 12'd1;")
    t=must(t,"sage <= 10'd1;","sage <= 12'd1;")
    t=must(t,"age >= 10'(SKL)","age >= 12'(SKL)")
    t=must(t,"sage == 10'(CAP)","sage == 12'(CAP)")
    t=must(t,"age == 10'(L - 1)","age == 12'(L - 1)")
    return t
if __name__=="__main__":
    t=gen()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text()==t else 3)
    OUT.parent.mkdir(parents=True,exist_ok=True); OUT.write_text(t); print(OUT)
