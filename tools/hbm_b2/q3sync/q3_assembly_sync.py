#!/usr/bin/env python3
"""Adopt the q3 SYNC_INPUT reset profile in the actual five-core q3 producer assembly.

Input: the committed assembly rtl/hbm_accel/cores_split/ot_hfd_coll_q3_hard_v8x/ot_hbm_q3_producer_native.sv
(split_asm.py output: wiring only, one module, exactly five real core instances, no procedural code).
Output: module ot_hbm_q3_producer_native__q3sync, byte-identical except the module name and the five instance
types, which become the generated <core>__q3sync tops of tools/hbm_b2/q3sync/q3_sync_profile.py.

Because the assembly has no flops and no event controls of its own, the whole q3 closure is converted exactly when
the five cores are (the census covers every module below them).  The tool refuses (exit 2) unless:
  * exactly one module and it is the expected top;
  * zero always/initial blocks and zero event controls in the assembly;
  * the instance census is exactly the five expected core types, once each, and nothing else
    (no leftover legacy helper could keep an async reset);
  * each __q3sync core top named in the census file exists in --gen.
Usage: q3_assembly_sync.py --asm <asm.sv> --census <census.json> --gen <gen dir> --out <out.sv> [--report <json>]
"""
import argparse, json, os, re, sys, hashlib

CORES = ["ot_hfd_coll_q3_body_core", "ot_hfd_coll_q3_edge_core", "ot_hfd_coll_q3_vm_core",
         "ot_hfd_coll_q2_reduce_core", "ot_hfd_coll_q2_ring_ag_core"]
TOP = "ot_hbm_q3_producer_native"
SUF = "__q3sync"

ap = argparse.ArgumentParser()
ap.add_argument("--asm", required=True); ap.add_argument("--census", required=True)
ap.add_argument("--gen", required=True); ap.add_argument("--out", required=True); ap.add_argument("--report")
a = ap.parse_args()
raw = open(a.asm, "rb").read()
txt = raw.decode()
fail = []
mods = re.findall(r"^\s*module\s+(\S+?)\s*\(", txt, re.M)
if mods != [TOP]:
    fail.append("modules %r != [%s]" % (mods[:5], TOP))
n_always = len(re.findall(r"^\s*(always\w*|initial)\b", txt, re.M))
n_event = len(re.findall(r"@\s*\(", txt))
if n_always or n_event:
    fail.append("procedural code in assembly: always/initial=%d event_controls=%d" % (n_always, n_event))
# instance census: a statement starting with an identifier that is not a declaration keyword, followed by an
# instance name and '('  (escaped identifiers allowed)
inst = re.findall(r"^\s*([A-Za-z_][\w$]*)\s+(?:#\s*\(.*?\)\s*)?(\\\S+|[A-Za-z_][\w$]*)\s*\(", txt, re.M | re.S)
kinds = {}
for t, n in inst:
    if t in ("module", "assign", "wire", "input", "output", "inout", "reg", "function", "task"):
        continue
    kinds.setdefault(t, []).append(n)
if sorted(kinds) != sorted(CORES) or any(len(v) != 1 for v in kinds.values()):
    fail.append("instance census %r != five cores once each" % {k: len(v) for k, v in kinds.items()})
cen = json.load(open(a.census))
gen_tops = {}
for core, t in cen["totals_per_core"].items():
    gen_tops[t["legacy_top"]] = t["top"]
for c in CORES:
    if gen_tops.get(c) != c + SUF:
        fail.append("census has no %s%s" % (c, SUF))
    elif not os.path.exists(os.path.join(a.gen, c + SUF + ".sv")):
        fail.append("missing generated %s%s.sv" % (c, SUF))
if fail:
    print("Q3_ASM_SYNC FAIL"); [print("  " + f) for f in fail]; sys.exit(2)
out = re.sub(r"^(\s*module\s+)" + TOP + r"(\s*\()", r"\g<1>" + TOP + SUF + r"\g<2>", txt, count=1, flags=re.M)
for c in CORES:
    out, k = re.subn(r"^(\s*)" + c + r"(\s+(?:\\\S+|[A-Za-z_][\w$]*)\s*\()", r"\g<1>" + c + SUF + r"\g<2>", out, flags=re.M)
    assert k == 1, (c, k)
hdr = ("// GENERATED by tools/hbm_b2/q3sync/q3_assembly_sync.py from %s (sha256 %s): q3 SYNC_INPUT profile adopted;\n"
       "// identical to the legacy assembly except the module name and the five core instance types (-> __q3sync).\n"
       % (a.asm, hashlib.sha256(raw).hexdigest()))
open(a.out, "w").write(hdr + out)
# byte-level proof: undo the renames and compare with the input
back = out
for c in CORES:
    back = back.replace(c + SUF + " ", c + " ")
back = back.replace(TOP + SUF + "(", TOP + "(", 1).replace(TOP + SUF + " (", TOP + " (", 1)
same = back == txt
rep = {"status": "PASS" if same else "FAIL_ROUNDTRIP", "asm": a.asm, "asm_sha256": hashlib.sha256(raw).hexdigest(),
       "out": a.out, "out_sha256": hashlib.sha256((hdr + out).encode()).hexdigest(), "top": TOP + SUF,
       "instances": {c: [c + SUF, kinds[c][0]] for c in CORES}, "always_initial": n_always, "event_controls": n_event,
       "roundtrip_identical": same}
if a.report:
    json.dump(rep, open(a.report, "w"), indent=1)
print("Q3_ASM_SYNC", rep["status"], json.dumps(rep["instances"]))
sys.exit(0 if same else 3)
