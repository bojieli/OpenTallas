"""Generate rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_p.sv from the pinned parent ot_qwen_nearhbm_attn_stack.sv.

The successor is the parent with every module suffixed _p.  Only the row engine changes, and only in pipelining:
  - registered boundary inputs (start, T, cyc8, the HBM response);
  - a FIFO whose writes are pre-decoded one cycle and whose read pointer is duplicated per 32-bit slice;
  - a 4-stage lane-input distribution (central -> half -> head -> 16-lane group);
  - per-group adder control delay lines and fault OR;
  - a reset tree (central -> half -> head -> group);
  - root scores registered twice on their way to the central running max.
The lanes see every issue LANE_D = 4 cycles later.  The 8-slot V loop offset becomes (4 + LANE_D) mod 8 = 0, so a slot's
take and its next issue turn coincide; slot_ok admits that issue (see the row engine comment).  Run from the repo root:
    python3 tools/qwen_nearhbm_stack_p_gen.py [--check]
--check exits non-zero if the committed file differs from what this script generates.
"""
