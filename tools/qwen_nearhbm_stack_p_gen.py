def main():
    s = SRC.read_text()
    pat = re.compile(r"\b(" + "|".join(NAMES) + r")\b")
    s = pat.sub(lambda m: m.group(1) + "_p", s)
    # drop the parent's header comment block (first 33 lines up to the fgt comment) and use ours
    i = s.index("// FP32 a > b for finite operands")
    body = s[i:]
    a = body.index("module ot_qwen_nearhbm_row_engine_p #(")
    b = body.index("endmodule", a) + len("endmodule")
    eng = engine(body[a:b])
    # the parent's header comment for the engine is kept; add the successor note before it
    c = body.rindex("// -----", 0, a)
    c = body.rindex("// -----", 0, c)
    # the stack's engine instance connects the renamed boundary ports
    tail = body[b:]
    a2 = tail.index("ot_qwen_nearhbm_row_engine_p #(")
    b2 = tail.index(");", a2)
    inst = tail[a2:b2]
    for o, n in ((".start(start)", ".start_in(start)"), (".T(T)", ".T_in(T)"), (".cyc8(cyc8)", ".cyc8_in(cyc8)"),
                 (".rsp_valid(rsp_valid[e])", ".rsp_valid_in(rsp_valid[e])"),
                 (".rsp_data(rsp_data[HD*8*e +: HD*8])", ".rsp_data_in(rsp_data[HD*8*e +: HD*8])")):
        if inst.count(o) != 1:
            raise SystemExit(f"engine instance: {o}")
        inst = inst.replace(o, n)
    tail = tail[:a2] + inst + tail[b2:]
    out = HEADER + PRIMS + "\n" + body[:c] + ENGINE_NOTE + body[c:a] + eng + tail
    if "--check" in sys.argv:
        if DST.read_text() != out:
            raise SystemExit(f"{DST} is stale; regenerate")
        print("up to date")
        return
    DST.write_text(out)
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()
