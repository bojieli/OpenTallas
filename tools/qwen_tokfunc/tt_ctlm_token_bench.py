#!/usr/bin/env python3
"""tt_ctlm end-to-end token bench (QC-F16-PRODUCER, rebuilt 11-24 after the romw-1119 witness_f5_1515 harness was deleted).

Drives the tt_ctlm core (bound netlist or core netlist) with the real system program (rank media sys_face_cfg rows
0..1031): a fixture installs EVERY control store over its real ports before any start
  - pw rows 0..1023 (ME image, XPF dense loader 1004..1023, segment-G loader 993..1003, the F5 witness rows 400..444)
    on pw and the dh program copy (dh[118:44]), as the system face replays them,
  - dw rows 1024..1031 on dh[186:119] (C calendar),
  - f16_auth BEGIN during the replay, AUTH {all_copies, fusedcap, digest, epoch} after it,
then requires control_stores_ready=1 and cf=0 before the first start, and issues stage-0 user-0 token starts.
Per start it checks the command streams (cmd / native_cmd / table_req / emb_start) and cf / f16 fault through the run.

Modes (one binary, +MODE=n):
  0 POSITIVE      init_u0 tied 0 (the C1h strap), full fixture             -> must PASS
  1 NEG_INIT_HELD init_u0 held 1                                           -> must FAIL
  2 NEG_INIT_PULS init_u0 = 1 on each start edge                           -> must FAIL
  3 NEG_NO_XPF    XPF footer row 1023 withheld (store never sealed)        -> must FAIL
  4 NEG_BAD_AUTH  AUTH digest bit 0 flipped                                -> must FAIL
  5 NEG_NO_DW     calendar dw rows withheld                                -> must FAIL
Exit 0 iff mode 0 passes and every negative fails.

usage: tt_ctlm_token_bench.py --dut FILE[,FILE..] --top MODULE --media DIR --lib FILE[,FILE..] --out DIR
       [--ports FILE] [--params '#(...)'] [--digest HEX] [--epoch N] [--starts N] [--edges N] [--verilator PATH] [--jobs N]
--ports: file whose ANSI-less 'input wire [N:0] name;' list gives the port set (default: first --dut file).
"""
import argparse, json, os, re, subprocess, sys
from pathlib import Path

MODES = {0: 'POSITIVE', 1: 'NEG_INIT_HELD', 2: 'NEG_INIT_PULSE', 3: 'NEG_NO_XPF', 4: 'NEG_BAD_AUTH', 5: 'NEG_NO_DW'}
CLOCKS = ('ck_core', 'ck_hr', 'ck', 'clk')
NEED_IN = {'rst_n', 'pw', 'dh', 'init_u0', 'dh_user', 'f16_auth'}
NEED_OUT = {'control_stores_ready', 'cf', 'cmd', 'native_cmd', 'table_req', 'emb_start', 'f16_st', 'dc'}


def parse_ports(text):
    ports = [(d, (int(w) + 1 if w else 1), n)
             for d, w, n in re.findall(r'^\s*(input|output)\s+wire\s+(?:\[(\d+):0\]\s+)?(\w+)\s*;', text, re.M)]
    if not ports:  # ANSI header
        ports = [(d, (int(w) + 1 if w else 1), n)
                 for d, w, n in re.findall(r'^\s*(input|output)\s+(?:wire\s+)?(?:\[(\d+):0\]\s+)?(\w+)\s*[,)]', text, re.M)]
    return ports


def program_words(media):
    """sys_face_cfg mask ROM (ot_rom_4096x72_m8 viamap: addr a -> row a/8, bit b at column b*8 + a%8), rows 0..1031."""
    rows = [int(l, 16) for l in open(Path(media) / 'sys_face_cfg.viamap.hex') if l.strip()]
    word = lambda a: sum((((rows[a // 8] >> (b * 8 + a % 8)) & 1) << b) for b in range(72))
    return [word(a) & ((1 << 64) - 1) for a in range(1032)]


SEED = 0x51484f5354505247   # = sys_face_image.image_digest (emb_provider): the AUTH digest of a program image


def image_digest(words):
    d = SEED
    for i, w in enumerate(words):
        d = (((d << 7) | (d >> 57)) & (2**64 - 1)) ^ w ^ (i if i < 1024 else (1 << 10) | (i - 1024))
    return d


def xpf_records(p):
    """XPF dense records on PW1004..1015 (3 words each): (arm, first_write) per non-zero record."""
    out = []
    for r in range(4):
        rec = (p[1006 + 3 * r] << 128) | (p[1005 + 3 * r] << 64) | p[1004 + 3 * r]
        if rec:
            out.append(((rec >> 92) & 0xffffffff, (rec >> 156) & 0xffffffff))
    return out


def reprice_xpf(p, delta):
    """DIAGNOSTIC ONLY: shift every XPF record first_write (record [187:156] = word2 [59:28]) by delta edges."""
    p = list(p)
    for r in range(4):
        if p[1004 + 3 * r] & 1:
            p[1006 + 3 * r] += delta << 28
    return p


def make_tb(ports, top, params, digest, epoch, starts, edges):
    names = {n for _, _, n in ports}
    miss = (NEED_IN | NEED_OUT) - names
    if miss:
        raise SystemExit(f'TT_TOKBENCH_PORTS missing {sorted(miss)}')
    decl = '\n'.join(f'  {"reg" if d == "input" else "wire"} [{w - 1}:0] {n};' for d, w, n in ports if n not in CLOCKS)
    conn = ', '.join(f'.{n}({"ck" if n in CLOCKS else n})' for _, _, n in ports)
    zero = '\n'.join(f'    {n} = 0;' for d, _, n in ports if d == 'input' and n not in CLOCKS)
    return f'''`timescale 1ps/1fs
// GENERATED by tools/qwen_tokfunc/tt_ctlm_token_bench.py
module tb;
  reg ck = 0; always #416.5 ck = ~ck;
{decl}
  reg [63:0] prog [0:1031];
  integer mode, i, k, cyc = 0, first_cf = -1, first_f16f = -1, ready_cyc = -1, start_cyc = -1, nst = 0;
  integer ncmd = 0, nncmd = 0, ntreq = 0, nemb = 0, s_cmd, s_ncmd, s_treq, s_emb, bad_start = 0;
  reg [63:0] hcmd = 0;
  {top} {params} dut({conn});
  always @(posedge ck) begin
    cyc = cyc + 1; #5;
    if (rst_n) begin
      if (cf === 1'b1 && first_cf < 0) first_cf = cyc;
      if (f16_st[16] === 1'b1 && first_f16f < 0) first_f16f = cyc;
      if (control_stores_ready === 1'b1 && ready_cyc < 0) ready_cyc = cyc;
      if (start_cyc >= 0) begin
        if (|cmd) begin ncmd = ncmd + 1; hcmd = {{hcmd[62:0], hcmd[63]}} ^ cmd[63:0] ^ 64'(cyc - start_cyc); end
        if (|native_cmd) nncmd = nncmd + 1;
        if (|table_req) ntreq = ntreq + 1;
        if (emb_start === 1'b1) nemb = nemb + 1;
      end
    end
  end
  task automatic tick; @(negedge ck); endtask
  initial begin
    if (!$value$plusargs("MODE=%d", mode)) mode = 0;
    $readmemh("prog.hex", prog);
{zero}
    repeat (8) tick; rst_n = 1; repeat (40) tick;
    if (mode == 1) init_u0 = 1;
    f16_auth = {{1'b1, 82'd0}};
    for (i = 0; i < 1024; i = i + 1) begin
      if (!(mode == 3 && i == 1023)) begin
        pw = {{1'b1, 10'(i), prog[i]}}; dh = 0; dh[118] = 1; dh[117:108] = 10'(i); dh[107:44] = prog[i];
      end else begin pw = 0; dh = 0; end
      tick;
    end
    pw = 0; dh = 0;
    for (i = 0; i < 8; i = i + 1) begin
      dh = 0; if (mode != 5) begin dh[186] = 1; dh[185:183] = 3'(i); dh[182:119] = prog[1024 + i]; end
      tick;
    end
    dh = 0; repeat (4) tick;
    f16_auth = {{1'b0, 1'b1, 1'b1, 64'h{digest:016x} ^ 64'(mode == 4), 16'd{epoch}}};
    repeat (300) tick;
    $display("TT_TOKBENCH_IMAGE mode=%0d control_stores_ready=%0d ready_cyc=%0d cal_image_ready=%0d cf=%0d f16_st=%h dc=%h",
      mode, control_stores_ready, ready_cyc, cal_image_ready, cf, f16_st, dc);
    for (k = 0; k < {starts}; k = k + 1) begin
      s_cmd = ncmd; s_ncmd = nncmd; s_treq = ntreq; s_emb = nemb;
      dh = 0; dh[42] = 1; dh[41:36] = 6'd0; dh[35:18] = 18'(100 + k); dh[17:0] = 18'(k); dh_user = 0;
      if (mode == 2) init_u0 = 1;
      if (start_cyc < 0) start_cyc = cyc;
      tick; dh = 0; init_u0 = (mode == 1);
      repeat ({edges}) tick;
      nst = nst + 1;
      $display("TT_TOKBENCH_START k=%0d cmd=%0d native_cmd=%0d table_req=%0d emb_start=%0d cf=%0d",
        k, ncmd - s_cmd, nncmd - s_ncmd, ntreq - s_treq, nemb - s_emb, cf);
      if (ncmd == s_cmd || nncmd == s_ncmd || ntreq == s_treq || nemb - s_emb != 1) bad_start = bad_start + 1;
    end
    $display("TT_TOKBENCH_RESULT mode=%0d ready_cyc=%0d first_cf=%0d first_f16fault=%0d start=%0d starts=%0d bad_starts=%0d cmd=%0d native_cmd=%0d table_req=%0d emb_start=%0d cmdhash=%h f16_st=%h dc=%h",
      mode, ready_cyc, first_cf, first_f16f, start_cyc, nst, bad_start, ncmd, nncmd, ntreq, nemb, hcmd, f16_st, dc);
    if (ready_cyc >= 0 && ready_cyc < start_cyc && first_cf < 0 && first_f16f < 0 && bad_start == 0)
      $display("TT_TOKBENCH_PASS mode=%0d", mode);
    else
      $display("TT_TOKBENCH_FAIL mode=%0d", mode);
    $finish;
  end
endmodule
'''


def main():
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument('--dut', required=True); a.add_argument('--top', required=True); a.add_argument('--media', required=True)
    a.add_argument('--lib', default=''); a.add_argument('--out', required=True); a.add_argument('--ports')
    a.add_argument('--params', default=''); a.add_argument('--digest', default='program', help="AUTH digest: 'program' = image_digest of the replayed image, or HEX"); a.add_argument('--epoch', type=int, default=8)
    a.add_argument('--starts', type=int, default=4); a.add_argument('--edges', type=int, default=6000)
    a.add_argument('--verilator', default=os.path.expanduser('~/.local/opentallas-tools/verilator-5.050/bin/verilator'))
    a.add_argument('--jobs', type=int, default=8); a.add_argument('--modes', default=','.join(map(str, MODES)))
    a.add_argument('--gen-only', action='store_true')
    a.add_argument('--reprice-xpf', type=int, default=0, help='DIAGNOSTIC: add N edges to every XPF first_write')
    a.add_argument('--xpf-transport-edges', type=int, default=21, help='the core compiled XPF_TRANSPORT_EDGES (fw >= arm + T + 3)')
    x = a.parse_args()
    out = Path(x.out); out.mkdir(parents=True, exist_ok=True)
    duts = [p for p in x.dut.split(',') if p]; libs = [p for p in x.lib.split(',') if p]
    ports = parse_ports(Path(x.ports or duts[0]).read_text(errors='replace')[:400000])
    prog = program_words(x.media)
    media_digest = image_digest(prog)
    if x.reprice_xpf:
        prog = reprice_xpf(prog, x.reprice_xpf)
    digest = image_digest(prog) if x.digest == 'program' else int(x.digest, 16)
    recs = xpf_records(prog); tedge = x.xpf_transport_edges + 3
    pre = dict(media_digest=f'{media_digest:016x}', auth_digest=f'{digest:016x}', reprice_xpf=x.reprice_xpf,
               xpf_records=[dict(arm=a_, first_write=f_, margin=f_ - a_, need=tedge, ok=f_ - a_ >= tedge) for a_, f_ in recs])
    print('TT_TOKBENCH_PROGRAM', json.dumps(pre))
    (out / 'prog.hex').write_text(''.join(f'{w:016x}\n' for w in prog))
    (out / 'tb.sv').write_text(make_tb(ports, x.top, x.params, digest, x.epoch, x.starts, x.edges))
    if x.gen_only:
        print('TT_TOKBENCH_GEN ports', len(ports)); return 0
    cmd = [x.verilator, '--binary', '--timing', '--top-module', 'tb', '-j', str(x.jobs), '-O1', '-Wno-fatal', '-Wno-lint',
           '-Wno-style', '-Wno-PINMISSING', '-Wno-WIDTH', '-Wno-MULTIDRIVEN', '-Wno-TIMESCALEMOD', '--Mdir', 'obj', 'tb.sv',
           *map(os.path.abspath, duts), *map(os.path.abspath, libs)]
    with open(out / 'build.log', 'w') as f:
        if subprocess.run(cmd, cwd=out, stdout=f, stderr=subprocess.STDOUT).returncode:
            print('TT_TOKBENCH_BUILD_FAIL see', out / 'build.log'); return 2
    res, rc = {}, 0
    for m in map(int, x.modes.split(',')):
        log = out / f'mode{m}.log'
        with open(log, 'w') as f:
            subprocess.run(['./obj/Vtb', f'+OT_ROM_DIR={os.path.abspath(x.media)}', f'+MODE={m}'], cwd=out, stdout=f, stderr=subprocess.STDOUT)
        t = log.read_text(errors='replace')
        passed = f'TT_TOKBENCH_PASS mode={m}' in t
        want = (m == 0)
        ok = passed == want
        rc |= 0 if ok else 1
        line = next((l for l in t.splitlines() if l.startswith('TT_TOKBENCH_RESULT')), 'NO_RESULT')
        res[MODES[m]] = dict(mode=m, bench_pass=passed, expected_pass=want, ok=ok, result=line)
        print(f'{MODES[m]:15s} {"PASS" if passed else "FAIL"} ({"as required" if ok else "WRONG"}) {line}')
    (out / 'receipt.json').write_text(json.dumps(dict(schema='opentallas.tt_ctlm_token_bench.v1', top=x.top, dut=duts,
        media=os.path.abspath(x.media), params=x.params, program=pre, modes=res, verdict='PASS' if rc == 0 else 'FAIL'), indent=2) + '\n')
    print('TT_TOKBENCH_VERDICT', 'PASS' if rc == 0 else 'FAIL')
    return rc


if __name__ == '__main__':
    sys.exit(main())
