#!/usr/bin/env python3
"""TOK-FUNC-QW/xt1 (10-21): the XT1n near+far matvec vehicle as a SOURCE carve of the Qwen compute release die.

Writes the same sub-netlist the XT1g die carve (tools/qwen_layerbench/die_carve.py on out/case/die.v) yields, but from
the SOURCE assembly alone (no GEN): dvs_W5 = qfd_dv_slice2_w #(MU_NU 4) (release param, die.v.params.json of the
g5r3-rev GEN dv2f21g5r4a), near cluster c16_W5_2 (cid 2, far 0), far cluster c16_W5_3 (cid 3, far 1), and the 11
one-frame die landings between them (qfd_landh0, n = 1) with the master names / K straps of the g5r3-rev die plan:
  slice cw_n<i> -> rly_q3h_col_<i>_2_0 (516 SN) -> near bc<i>              4 x  (broadcast, slice -> near)
  near bco<i>   -> rly_q3h_far_W5_2_<i>_0 (516 SN, i=2: SE) -> far bc<i>   4 x  (broadcast, near -> far)
  far rs        -> rly_dv_rsi_W5_3_0 (514 NS) -> near rs_i                 1 x  (reduce, far -> near)
  near rs / rs_o-> rly_dv_rs_W5_2_{a,b}_0 (514 NS) -> slice rs_n0 / rs_n1  2 x  (reduce, near -> slice)
K = (E + G + 1 - R0) mod 8 with the plan's E = 2 and one bench reset (G = R0): K = 3 = {k2 lo, k1 hi, k0 hi}, exactly
the tie pattern of dv2f21g5r4a / g5r2b die.v.  Relay RTL: tools/qwen_split/gen_relay_rtl.py on the written carve.
--landings 0 replaces every landing by a wire (the XT1n topology, no die landings) for the comparison run.
Bench inputs = the die lane ends the tt_ctlm / W4 neighbour drive (cmd_wi, hr_wi, st_wi = XT1 event ports 0/1/2);
every other slice input 0 (S band-1 clusters, W4 neighbour, ring return idle) as in the XT1g carve.

    stage_xt1_carve.py --out DIR [--landings 1|0] [--nobind]   -> DIR/xt1s_carve.v DIR/tb_xt1s.sv DIR/rom_bind_xt1s.vh
"""
import argparse, json
from pathlib import Path

LAND = []   # (inst, master, a_net, b_net, width)
for i in range(4):
    LAND.append((f'rly_q3h_col_{i}_2_0', 'qfd_landh0_516_SN_90x30', f'n_q3h_col_{i}_2', f'n_q3h_col_{i}_2__r1', 516))
for i in range(4):
    LAND.append((f'rly_q3h_far_W5_2_{i}_0', 'qfd_landh0_516_%s_90x30' % ('SE' if i == 2 else 'SN'),
                 f'n_q3h_far_W5_2_{i}', f'n_q3h_far_W5_2_{i}__r1', 516))
LAND.append(('rly_dv_rsi_W5_3_0', 'qfd_landh0_514_NS_90x30', 'n_dv_rsi_W5_3', 'n_dv_rsi_W5_3__r1', 514))
LAND.append(('rly_dv_rs_W5_2_a_0', 'qfd_landh0_514_NS_90x30', 'n_dv_rs_W5_2_a', 'n_dv_rs_W5_2_a__r1', 514))
LAND.append(('rly_dv_rs_W5_2_b_0', 'qfd_landh0_514_NS_90x30', 'n_dv_rs_W5_2_b', 'n_dv_rs_W5_2_b__r1', 514))
K = 3
MU_NU = 4
# ROM binding of the die (dv2f21g5r4a out/case/rom_bind.vh, c16_W5_2 / c16_W5_3 lines): ROM_TILE = 16 cid + kslice
SLOT = {(0, 0): 0, (0, 1): 2, (0, 2): 8, (0, 3): 10, (1, 0): 1, (1, 1): 3, (1, 2): 9, (1, 3): 11,
        (2, 0): 4, (2, 1): 6, (2, 2): 12, (2, 3): 14, (3, 0): 5, (3, 1): 7, (3, 2): 13, (3, 3): 15}


def cluster(inst, cid, far, bc, bco, rs, rs_i, rs_o):
    cks = ', '.join(f'.ck_c{c}r{r}(ck)' for c in range(4) for r in range(4))
    rss = ', '.join(f'.rst_c{c}r{r}(rst_n)' for c in range(4) for r in range(4))
    b = ', '.join(f'.bc{i}({bc[i]}), .bco{i}({bco[i]})' for i in range(4))
    return (f'  qfd_c_b16_dv {inst} ({cks}, {rss}, .far(1\'b{far}), .cid(12\'d{cid}), {b}, .rs({rs}), .rs_i({rs_i}), '
            f'.rs_o({rs_o}), .tie_hi(), .tie_lo());')


def carve(landings):
    L = ['// GENERATED by tools/qwen_tokfunc/stage_xt1_carve.py (TOK-FUNC-QW/xt1, source assembly, no GEN)',
         '`timescale 1ns/1ps',
         'module xt1s_carve (input wire ck, input wire rst_n, input wire [115:0] cmd0, input wire [452:0] hr0,',
         '    input wire [1087:0] swi, output wire [515:0] cw_n0, output wire [515:0] cw_n1, output wire [515:0] cw_n2,',
         '    output wire [515:0] cw_n3, output wire [513:0] rs, output wire [513:0] rs_o, output wire [513:0] rsc,',
         '    output wire [513:0] rsoc);']
    for _, _, a, b, w in LAND:
        L += [f'  wire [{w - 1}:0] {a};', f'  wire [{w - 1}:0] {b};']
    if landings:
        for inst, *_ in LAND:
            L += [f'  wire n_ftk_{inst[4:-2]}_hi;', f'  wire n_ftk_{inst[4:-2]}_lo;']
    L.append(f'  qfd_dv_slice2_w #(.MU_NU({MU_NU})) dvs_W5 (.ck(ck), .rst_n(rst_n), .cmd_wi(cmd0), .cmd_eo(), .hr_wi(hr0), '
             '.hr_eo(), .st_wo(), .st_wi(swi), .st_eo(), .st_ei(1088\'d0), .sc_wo(), .sc_wi(48\'d0), .sc_eo(), .sc_ei(48\'d0), '
             '.arv_wo(), .arv_ei(1\'b0), .art_wo(), .art_ei(32\'d0), .arm_wo(), .arm_ei(1\'b0), .arl_wo(), .arl_ei(1\'b0), '
             '.ard_wo(), .ard_ei(512\'d0), .dd_wo(), .dd_ei(548\'d0), .rv_wi(1\'b0), .rv_eo(), .re_wi(1\'b0), .re_eo(), '
             '.rr_wi(3\'d0), .rr_eo(), .rl_wi(1\'b0), .rl_eo(), .rd_wi(512\'d0), .rd_eo(), .dr_wi(520\'d0), .dr_eo(), '
             '.ag_wo(), .ag_ei(10\'d0), .ss_wo(), .ccv_wo(), .ccm_wo(), .ccw_wo(), .cct_wo(), .l9_wi(514\'d0), .l9_eo(), '
             '.rs_n0(n_dv_rs_W5_2_a__r1), .rs_n1(n_dv_rs_W5_2_b__r1), '
             '.cw_n0(n_q3h_col_0_2), .cw_n1(n_q3h_col_1_2), .cw_n2(n_q3h_col_2_2), .cw_n3(n_q3h_col_3_2), '
             '.rs_s0(514\'d0), .rs_s1(514\'d0), .cw_s0(), .cw_s1(), .cw_s2(), .cw_s3());')
    L.append(cluster('c16_W5_2', 2, 0, [f'n_q3h_col_{i}_2__r1' for i in range(4)], [f'n_q3h_far_W5_2_{i}' for i in range(4)],
                     'n_dv_rs_W5_2_a', 'n_dv_rsi_W5_3__r1', 'n_dv_rs_W5_2_b'))
    L.append(cluster('c16_W5_3', 3, 1, [f'n_q3h_far_W5_2_{i}__r1' for i in range(4)], ['', '', '', ''],
                     'n_dv_rsi_W5_3', "514'd0", ''))
    for inst, m, a, b, w in LAND:
        if landings:
            t = inst[4:-2]
            ks = {f'k{j}': (f'n_ftk_{t}_hi' if (K >> j) & 1 else f'n_ftk_{t}_lo') for j in range(3)}
            L.append(f'  {m} {inst} (.a({a}), .b({b}), .en(rst_n), .rs(rst_n), .tie_hi(n_ftk_{t}_hi), .k0({ks["k0"]}), '
                     f'.k1({ks["k1"]}), .tie_lo(n_ftk_{t}_lo), .k2({ks["k2"]}), .ck_s(ck), .ck(ck), .fault());')
        else:
            L.append(f'  assign {b} = {a};   // --landings 0: no die landing ({inst} {m})')
    L += ['  assign {cw_n3, cw_n2, cw_n1, cw_n0} = {n_q3h_col_3_2, n_q3h_col_2_2, n_q3h_col_1_2, n_q3h_col_0_2};',
          '  assign rs = n_dv_rs_W5_2_a__r1;     // sampled at the slice pins AFTER the die landing (XT1g)',
          '  assign rs_o = n_dv_rs_W5_2_b__r1;',
          '  assign rsc = n_dv_rs_W5_2_a;        // cluster outputs before landing',
          '  assign rsoc = n_dv_rs_W5_2_b;',
          'endmodule']
    return '\n'.join(L) + '\n'


TB = '''`timescale 1ns/1ps
// GENERATED by tools/qwen_tokfunc/stage_xt1_carve.py: XT1n events / log lines (xt1n_bench.py checks them unchanged) on
// the source carve xt1s_carve (landings LANDINGS); RS / RSO at the slice pins after the landings, RSC / RSOC before.
module tb_xt1s (input wire ck);
    reg rst_n = 1'b0;
    reg  [115:0]  cmd0;
    reg  [452:0]  hr0;
    reg  [1087:0] swi;
    wire [515:0]  cw_n0, cw_n1, cw_n2, cw_n3;
    wire [513:0]  rs, rs_o, rsc, rsoc;
    xt1s_carve u_d (.ck(ck), .rst_n(rst_n), .cmd0(cmd0), .hr0(hr0), .swi(swi), .cw_n0(cw_n0), .cw_n1(cw_n1),
        .cw_n2(cw_n2), .cw_n3(cw_n3), .rs(rs), .rs_o(rs_o), .rsc(rsc), .rsoc(rsoc));
`define OT_ROM_BIND_TOP tb_xt1s.u_d
`include "rom_bind_xt1s.vh"
    integer fd, lg, cyc, ncyc, ec, ep, r, pre = 0, nrst;
    reg [1087:0] ev;
    reg have, hdf, stf, rsf, rof;
    reg [1023:0] evf, lgf;
    wire [3:0] cwgo = {cw_n3[0], cw_n2[0], cw_n1[0], cw_n0[0]};
    task automatic apply(input integer p, input [1087:0] v);
        begin
            if (p == 0) cmd0 = v[115:0];
            else if (p == 1) hr0 = v[452:0];
            else if (p == 2) swi = v;
            else $fatal(1, "bad port %0d", p);
        end
    endtask
    initial begin
        if (!$value$plusargs("EV=%s", evf)) $fatal(1, "+EV");
        if (!$value$plusargs("LOG=%s", lgf)) $fatal(1, "+LOG");
        if (!$value$plusargs("NCYC=%d", ncyc)) ncyc = 4000;
        if (!$value$plusargs("NRST=%d", nrst)) nrst = 16;
        fd = $fopen(evf, "r"); lg = $fopen(lgf, "w");
        cmd0 = 0; hr0 = 0; swi = 0; cyc = 0; hdf = 0; stf = 0; rsf = 0; rof = 0;
        r = $fscanf(fd, "%d %d %h\\n", ec, ep, ev); have = (r == 3);
    end
    always @(negedge ck) begin
        if (pre < nrst) begin pre = pre + 1; if (pre == nrst) rst_n = 1'b1; end
        else begin
            if (hr0[452]) $fdisplay(lg, "%0d HRGO", cyc);
            if (hr0[1])   $fdisplay(lg, "%0d HRXPF", cyc);
            if (|cwgo)    $fdisplay(lg, "%0d CWGO %h", cyc, cwgo);
            if (rs[512] || rs[513]) $fdisplay(lg, "%0d RS %0d %h", cyc, rs[513], rs[511:0]);
            if (rs_o[512] || rs_o[513]) $fdisplay(lg, "%0d RSO %0d %h", cyc, rs_o[513], rs_o[511:0]);
            if (rsc[512] || rsc[513]) $fdisplay(lg, "%0d RSC %0d", cyc, rsc[513]);
            if (rsoc[512] || rsoc[513]) $fdisplay(lg, "%0d RSOC %0d", cyc, rsoc[513]);
            if (u_d.dvs_W5.u_core.hd_fault && !hdf) begin $fdisplay(lg, "%0d FAULT heads", cyc); hdf = 1; end
            if (u_d.dvs_W5.u_core.stm_fault && !stf) begin $fdisplay(lg, "%0d FAULT stream", cyc); stf = 1; end
            if (rs[513] && !rsf) begin $fdisplay(lg, "%0d FAULT near_cluster", cyc); rsf = 1; end
            if (rs_o[513] && !rof) begin $fdisplay(lg, "%0d FAULT far_cluster", cyc); rof = 1; end
            cmd0 = 0; hr0 = 0; swi = 0;
            while (have && ec == cyc) begin
                apply(ep, ev);
                r = $fscanf(fd, "%d %d %h\\n", ec, ep, ev); have = (r == 3);
            end
            if (have && ec < cyc) $fatal(1, "event file not sorted at cycle %0d", ec);
            cyc = cyc + 1;
            if (cyc >= ncyc) begin
                $fdisplay(lg, "%0d END hd_fault %0d stm_fault %0d near_fault %0d far_fault %0d", cyc, u_d.dvs_W5.u_core.hd_fault, u_d.dvs_W5.u_core.stm_fault, rsf, rof);
                $fclose(lg);
                $finish;
            end
        end
    end
endmodule
'''


def rom_bind(nobind):
    if nobind:
        return '// nobind mutant: no ROM_TILE bindings\n'
    L = ['// ROM_TILE binding of c16_W5_2 / c16_W5_3 = the die rom_bind.vh lines (dv2f21g5r4a, = g5r2b, = XT1n)']
    for inst, cid in (('c16_W5_2', 2), ('c16_W5_3', 3)):
        for (r, c), s in sorted(SLOT.items()):
            L.append(f'defparam `OT_ROM_BIND_TOP.{inst}.u_t_{r}_{c}.ROM_TILE = {16 * cid + s};')
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True, type=Path)
    ap.add_argument('--landings', type=int, default=1)
    ap.add_argument('--nobind', action='store_true')
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / 'xt1s_carve.v').write_text(carve(a.landings))
    (a.out / 'tb_xt1s.sv').write_text(TB.replace('LANDINGS', 'on' if a.landings else 'off'))
    (a.out / 'rom_bind_xt1s.vh').write_text(rom_bind(a.nobind))
    (a.out / 'carve.json').write_text(json.dumps(dict(
        schema='opentallas.tokfunc_qw.xt1s_carve.v1', landings=a.landings, nobind=a.nobind, mu_nu=MU_NU, K=K,
        seeds=['dvs_W5', 'c16_W5_2', 'c16_W5_3'],
        landing_insts=[dict(inst=i, master=m, a=x, b=y, width=w) for i, m, x, y, w in LAND] if a.landings else []),
        indent=1) + '\n')
    print(f'xt1s carve: landings {a.landings} nobind {a.nobind} ({len(LAND) if a.landings else 0} landings)')


if __name__ == '__main__':
    main()
