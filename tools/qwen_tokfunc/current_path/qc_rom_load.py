#!/usr/bin/env python3
"""TOK-QW-5 11-03: sim-only (tb-only) ROM image loader for the whole-QC vehicle (qc_vehicle.py tb_qcdie).

    qc_rom_load.py --rom-bind veh0/rom_bind.vh --prog PROG.txt --out rom_load.vh

Why: rom_bind.vh gives every compute tile its ROM_TILE by defparam.  ROM_TILE is a tile-level parameter, so the 768
defparams make 768 specialisations of the whole tile subtree (ROM logic + the matvec engine); the flat build of
that vehicle was MEMCG-OOM at 360 GiB.  Verilator cannot defparam through generate-array scopes (g_rb[b]), so the
ROM identity cannot be moved down to the leaf by defparam either.  Instead every tile keeps ROM_TILE = -1 (one
shared tile body) and the bench loads each ROM macro's array by a hierarchical $readmemh, with the same file the
macro model itself would read under +OT_ROM_DIR (<dir>/<INSTANCE>.viamap.hex, INSTANCE = qtile_t<T>_b<b>_c<c>).

The bench must then NOT pass +OT_ROM_DIR (the ROM leaf $fatal's on +OT_ROM_DIR with ROM_TILE < 0), so the programme
ROMs that read +OT_ROM_DIR by INSTANCE (table_s*_m*, calendar_m*, opseg, ...) are loaded the same way (--prog: one
"<path below the die top> <INSTANCE>" per line).  The bench plusarg is +OT_TB_ROM_DIR; a missing image is fatal
(same as qc_prog_rom_guard / the ROM leaf), and the bench prints one QCDIE_ROM_LOAD line with the count.
The load runs at #0.01 ns, after the macro models' own time-0 zero fill and before the first clock edge.
"""
import argparse, re, sys
from pathlib import Path

TILE_LEAF = 'u_g.u_tile.u_tile.u_logic.g_rom_pipe.g_rph.g_rb[{b}].g_single.g_col[{c}].u_leaf.u_rom'
DEF = re.compile(r'^defparam\s+(\S+)\.ROM_TILE\s*=\s*(\d+)\s*;')
DEF_INST = re.compile(r'^defparam\s+(.+?)\s*\.INSTANCE\s*=\s*"([^"]+)"\s*;')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom-bind', required=True)
    ap.add_argument('--prog', help='programme ROMs: "<hier path from the tb> <INSTANCE>" per line')
    ap.add_argument('--banks', type=int, default=5)
    ap.add_argument('--cols', type=int, default=2)
    ap.add_argument('--expect-tiles', type=int, default=768, help='768 for the whole die (smaller only for unit tests)')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    loads, tiles, inst_defs = [], set(), 0
    for line in Path(a.rom_bind).read_text().splitlines():
        m = DEF.match(line.strip())
        if m:
            path, t = m[1], int(m[2])
            if not 0 <= t < 768 or t in tiles:
                sys.exit(f'bad or duplicate ROM_TILE {t} at {path}')
            tiles.add(t)
            for b in range(a.banks):
                for c in range(a.cols):
                    loads.append((f'{path}.{TILE_LEAF.format(b=b, c=c)}', f'qtile_t{t}_b{b}_c{c}'))
            continue
        m = DEF_INST.match(line.strip())
        if m:   # a ROM macro INSTANCE defparam (non-arrayed path): load it the same way
            loads.append((m[1].strip(), m[2])); inst_defs += 1
        elif line.strip().startswith('defparam'):
            sys.exit(f'unhandled defparam: {line}')
    if len(tiles) != a.expect_tiles:
        sys.exit(f'{len(tiles)} tiles in {a.rom_bind}, expected {a.expect_tiles}')
    nprog = 0
    if a.prog:
        for line in Path(a.prog).read_text().splitlines():
            if not line.strip() or line.startswith('#'):
                continue
            path, inst = line.rsplit(None, 1)
            loads.append((path, inst)); nprog += 1
    seen = set()
    for p, i in loads:
        if p in seen:
            sys.exit(f'duplicate ROM path {p}')
        seen.add(p)
    out = ['// GENERATED by tools/qwen_tokfunc/current_path/qc_rom_load.py (TOK-QW-5): sim-only hierarchical ROM loads',
           f'// {len(tiles)} tiles x {a.banks} banks x {a.cols} cols + {inst_defs} INSTANCE defparam ROMs + {nprog} programme ROMs',
           '    string qcrom_dir;',
           '    task automatic qcrom_need(input string n);',
           '        integer fd; begin fd = $fopen({qcrom_dir, "/", n, ".viamap.hex"}, "r");',
           '        if (fd == 0) $fatal(1, "QCDIE_ROM_MISSING %s/%s.viamap.hex", qcrom_dir, n); $fclose(fd); end',
           '    endtask',
           '    initial begin',
           '        if ($test$plusargs("OT_ROM_DIR=")) $fatal(1, "QCDIE_ROM: use +OT_TB_ROM_DIR (tile ROM_TILE is -1 in this bench)");',
           '        if (!$value$plusargs("OT_TB_ROM_DIR=%s", qcrom_dir)) $fatal(1, "QCDIE_ROM: +OT_TB_ROM_DIR required");',
           '        #0.01;']
    for p, i in loads:
        sep = ' ' if '\\' in p else ''   # an escaped identifier ends at white space
        out.append(f'        qcrom_need("{i}"); $readmemh({{qcrom_dir, "/{i}.viamap.hex"}}, {p}{sep}.arr);')
    out += [f'        $display("QCDIE_ROM_LOAD %0d images from %s", {len(loads)}, qcrom_dir);', '    end']
    Path(a.out).write_text('\n'.join(out) + '\n')
    print(f'{len(loads)} loads ({len(tiles)} tiles, {inst_defs} INSTANCE defparams, {nprog} programme) -> {a.out}')


if __name__ == '__main__':
    main()
