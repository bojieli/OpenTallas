#!/usr/bin/env python3
"""TOK-DS 10-26: event-driven Verilog bench for a bound_carve.py carve (the bound partitions, byte-for-byte), driven ONLY
through the carve's own ports.

    carve_tb.py --carve DIR/<name>.json --reset BOUND/bind_reset.json --out tb_<name>.sv [--top <carve module>]

Ports (carve json "inputs"/"outputs"):
  clk_*            one free-running clock (the die has one core clock).
  rstw_<src>_rst_o_<k>  neighbour reset wavefront inputs from partitions OUTSIDE the carve: released at the static release
                   clock the bind computed for <src> (bind_reset.json parts[<src>].release, clocks after die rst_n
                   deasserts; die rst_n deasserts at +rst_cycle=, default 4).  Nothing else drives reset.
  lane inputs      driven from event files <stim>/<port>.ev, one line per change: "<cycle> <word>" (decimal cycle,
                   hex word incl. the epoch bit, lines in cycle order); the word is applied before the rising edge of
                   <cycle> and held until the next event.  A port WITHOUT a file stays 0 for the whole run (no epoch
                   toggle = no beat) and is listed at start as CARVE_TB_IDLE: the stimulus spec must justify each one
                   (idle by schedule), this bench never invents values.
  outputs          every change is written to <trace> ("<cycle> <port> <word>"); optional checks <exp>/<port>.ev
                   ("<cycle> <word>": port must equal word at that rising edge) count CARVE_TB_MISMATCH.
Run end: +cycles=N (default 40000).  Summary line:
  CARVE_TB cycles=<N> start=<die rst_n release cycle> out_changes=<n> checks=<n> mismatches=<n> last_change=<cycle>
"""
from __future__ import annotations
import argparse, json, re
from pathlib import Path

_RSTW = re.compile(r"rstw_(\w+?)_rst_o_(\d+)$")


def sv_name(p):
    return re.sub(r"\W", "_", p)


def classify(cv):
    clk, rst, lane_in, outs = [], [], [], []
    for n, v in cv["inputs"].items():
        if n.startswith("clk"):
            clk.append(n)
        elif _RSTW.match(n):
            rst.append(n)
        else:
            lane_in.append((n, int(v["width"])))
    for n, v in cv["outputs"].items():
        outs.append((n, int(v["width"])))
    if len(clk) != 1:
        raise SystemExit(f"carve needs exactly one clock input, found {clk}")
    return clk[0], rst, lane_in, outs


def reset_release(rst_ports, reset):
    rel = {}
    for n in rst_ports:
        src = _RSTW.match(n).group(1)
        part = reset["parts"].get(src)
        if part is None or not isinstance(part.get("release"), int):
            raise SystemExit(f"{n}: no static release for source partition {src} in bind_reset.json")
        rel[n] = part["release"]
    return rel


def emit(cv, reset, top=None):
    top = top or cv["name"]
    clk, rst, lane_in, outs = classify(cv)
    rel = reset_release(rst, reset)
    L = [f"// GENERATED by tools/qwen_tokfunc/xdie_bound/carve_tb.py for carve {cv['name']} (top sha256 "
         f"{cv.get('top_sha256', '?')}).  Do not edit.",
         "`timescale 1ns/1ps", f"module tb_{top};",
         f"    reg {clk} = 1'b0;", f"    always #1 {clk} = ~{clk};",
         "    integer cyc = 0, max_cyc = 40000, rst_cyc = 4, out_changes = 0, checks = 0, mism = 0, last_change = -1;",
         "    integer ftr, rc, idle = 0;", "    reg [1023:0] stim, expd, trace;"]
    for n in rst:
        L.append(f"    wire {sv_name(n)} = (cyc >= rst_cyc + {rel[n]});   // bind_reset release of the source partition")
    for i, (n, w) in enumerate(lane_in):
        L += [f"    reg [{w-1}:0] {sv_name(n)} = {w}'d0; reg [{w-1}:0] nx_i{i}; integer fi{i}, ci{i};"]
    for i, (n, w) in enumerate(outs):
        L += [f"    wire [{w-1}:0] {sv_name(n)}; reg [{w-1}:0] pv_o{i}; reg [{w-1}:0] ex_o{i}; integer fe{i}, ce{i};"]
    conns = [f".{n}({sv_name(n)})" for n in [clk] + rst + [p for p, _ in lane_in] + [p for p, _ in outs]]
    L.append(f"    {top} dut (\n        " + ",\n        ".join(conns) + ");")
    L += ["    initial begin",
          "        if (!$value$plusargs(\"stim=%s\", stim)) stim = \"stim\";",
          "        if (!$value$plusargs(\"exp=%s\", expd)) expd = \"exp\";",
          "        if (!$value$plusargs(\"trace=%s\", trace)) trace = \"carve_trace.txt\";",
          "        if ($value$plusargs(\"cycles=%d\", max_cyc)) ;", "        if ($value$plusargs(\"rst_cycle=%d\", rst_cyc)) ;",
          "        ftr = $fopen(trace, \"w\");"]
    for i, (n, w) in enumerate(lane_in):
        L += [f"        fi{i} = $fopen({{stim, \"/{n}.ev\"}}, \"r\"); ci{i} = -1;",
              f"        if (fi{i} == 0) begin $display(\"CARVE_TB_IDLE {n}\"); idle = idle + 1; end",
              f"        else begin rc = $fscanf(fi{i}, \"%d %h\\n\", ci{i}, nx_i{i}); if (rc != 2) ci{i} = -1; end"]
    for i, (n, w) in enumerate(outs):
        L += [f"        fe{i} = $fopen({{expd, \"/{n}.ev\"}}, \"r\"); ce{i} = -1;",
              f"        if (fe{i} != 0) begin rc = $fscanf(fe{i}, \"%d %h\\n\", ce{i}, ex_o{i}); if (rc != 2) ce{i} = -1; end",
              f"        pv_o{i} = {w}'d0;"]
    L += ["        $display(\"CARVE_TB_START idle_inputs=%0d lane_inputs=" + str(len(lane_in)) + " outputs=" + str(len(outs))
          + " rst_cycle=%0d cycles=%0d\", idle, rst_cyc, max_cyc);", "    end"]
    # inputs change on the falling edge before the rising edge of their cycle
    L.append(f"    always @(negedge {clk}) begin")
    for i, (n, w) in enumerate(lane_in):
        L += [f"        while (ci{i} >= 0 && ci{i} <= cyc) begin",
              f"            {sv_name(n)} <= nx_i{i};",
              f"            rc = $fscanf(fi{i}, \"%d %h\\n\", ci{i}, nx_i{i}); if (rc != 2) ci{i} = -1;",
              "        end"]
    L.append("    end")
    L.append(f"    always @(posedge {clk}) begin")
    for i, (n, w) in enumerate(outs):
        L += [f"        if ({sv_name(n)} !== pv_o{i}) begin $fwrite(ftr, \"%0d {n} %h\\n\", cyc, {sv_name(n)}); "
              f"pv_o{i} <= {sv_name(n)}; out_changes = out_changes + 1; last_change = cyc; end",
              f"        while (ce{i} >= 0 && ce{i} <= cyc) begin",
              f"            if (ce{i} == cyc) begin checks = checks + 1; if ({sv_name(n)} !== ex_o{i}) begin mism = mism + 1; "
              f"$display(\"CARVE_TB_MISMATCH %0d {n} got %h exp %h\", cyc, {sv_name(n)}, ex_o{i}); end end",
              f"            rc = $fscanf(fe{i}, \"%d %h\\n\", ce{i}, ex_o{i}); if (rc != 2) ce{i} = -1;",
              "        end"]
    L += ["        cyc <= cyc + 1;",
          "        if (cyc + 1 >= max_cyc) begin",
          "            $display(\"CARVE_TB cycles=%0d start=%0d out_changes=%0d checks=%0d mismatches=%0d last_change=%0d\", "
          "cyc + 1, rst_cyc, out_changes, checks, mism, last_change);",
          "            $fclose(ftr); $finish;", "        end", "    end", "endmodule", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--carve", required=True, type=Path)
    ap.add_argument("--reset", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--top", default=None)
    a = ap.parse_args(argv)
    cv = json.loads(a.carve.read_text())
    a.out.write_text(emit(cv, json.loads(a.reset.read_text()), a.top))
    _, rst, li, outs = classify(cv)
    print(json.dumps(dict(tb=str(a.out), lane_inputs=len(li), reset_inputs=len(rst), outputs=len(outs))))


if __name__ == "__main__":
    main()
