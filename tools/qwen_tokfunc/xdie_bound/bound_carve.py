#!/usr/bin/env python3
"""TOK-QW xdie_bound 10-24: carve named partition instances out of a BOUND die top (tools/die_plan/bind.py output) for
the compute <-> KV D2D co-sim on bound RTL.  Generalises the CAL-AUTO bind_smoke.py QC xt1 carve (same parser, same
port-direction source = the bound partition modules), for any die / any seed set:

  * the kept instance lines are copied byte-for-byte from the bound top (bound parameters, straps, lane wiring);
  * every top wire read by a kept instance and not driven by one becomes a carve INPUT port (the bench drives it);
  * every top wire driven by a kept instance and not read by another kept instance becomes a carve OUTPUT port;
  * top-level clock / reset / pad ports used by the kept instances become carve inputs of the same name.
Nothing is re-wired, nothing is padded: what the bound top has between the kept partitions is what simulates.

    bound_carve.py --top BOUND/rtl/<die>_bound_top.sv --seeds glue,ucie_kv --name qc_d2d_carve --out DIR
writes DIR/<name>.v and DIR/<name>.json (ports with widths, lanes, readers/drivers, source sha256).
"""
from __future__ import annotations
import argparse, hashlib, json, re, sys
from pathlib import Path

INST = re.compile(r'^\s*(\w+)\s*(#\(.*\))?\s+(\w+)\s*\($')
CONN = re.compile(r'^\s*\.(\w+)\(([\w\[\]:\']*)\),?$')
WIRE = re.compile(r'^\s*wire\s*(\[(\d+):(\d+)\])?\s*(\w+)\s*;\s*(//\s*lane\s+(\S+))?')
TPORT = re.compile(r'^\s*input\s+wire\s*(\[(\d+):(\d+)\])?\s*(\w+)\s*;')
PORT = re.compile(r'^\s*(input|output)\s+wire\s*(\[(\d+):(\d+)\])?\s*(\w+)')


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def parse_top(p: Path):
    wires, tports, insts, cur = {}, {}, [], None
    for ln in p.read_text().splitlines():
        if cur is not None:
            m = CONN.match(ln)
            if m:
                cur['conns'].append((m.group(1), m.group(2)))
                cur['text'].append(ln)
                continue
            if ln.strip() == ');':
                cur['text'].append(ln)
                insts.append(cur)
                cur = None
                continue
            raise SystemExit(f'unparsed instance line: {ln}')
        m = WIRE.match(ln)
        if m:
            w = int(m.group(2)) - int(m.group(3)) + 1 if m.group(1) else 1
            wires[m.group(4)] = dict(width=w, lane=m.group(6), decl=ln)
            continue
        m = TPORT.match(ln)
        if m:
            tports[m.group(4)] = int(m.group(2)) - int(m.group(3)) + 1 if m.group(1) else 1
            continue
        m = INST.match(ln)
        if m and m.group(1) != 'module':
            cur = dict(module=m.group(1), name=m.group(3), conns=[], text=[ln])
    return wires, tports, insts


def ports_of(rtl: Path, module: str, cache={}):
    if module not in cache:
        d = {}
        for ln in (rtl / f'{module}.sv').read_text().splitlines():
            m = PORT.match(ln)
            if m:
                d[m.group(5)] = m.group(1)
            if ln.startswith(');'):
                break
        cache[module] = d
    return cache[module]


def carve(top: Path, seeds, name: str, out: Path):
    rtl = top.parent
    wires, tports, insts = parse_top(top)
    keep = [i for i in insts if i['name'] in seeds]
    if sorted(i['name'] for i in keep) != sorted(seeds):
        raise SystemExit(f'seeds not found: {sorted(set(seeds) - {i["name"] for i in keep})}')
    drv, rd = {}, {}
    for i in keep:
        pd = ports_of(rtl, i['module'])
        for p, n in i['conns']:
            base = re.sub(r'\[.*$', '', n)
            if not base or re.fullmatch(r"\d+'.*", n):
                continue
            dirn = pd.get(p)
            if not dirn:
                raise SystemExit(f'{i["name"]}.{p} not a port of {i["module"]}')
            (drv if dirn == 'output' else rd).setdefault(base, []).append(f'{i["name"]}.{p}')
    ins = sorted(n for n in rd if n not in drv)
    outs = sorted(n for n in drv if n not in rd)
    internal = sorted(n for n in drv if n in rd)
    for n in ins + outs + internal:
        if n not in wires and n not in tports:
            raise SystemExit(f'net {n} neither a top wire nor a top port')
    width = lambda n: wires[n]['width'] if n in wires else tports[n]
    rng = lambda n: f'[{width(n) - 1}:0] ' if width(n) > 1 else ''
    hdr = [f'    input  wire {rng(n)}{n}' for n in ins] + [f'    output wire {rng(n)}{n}' for n in outs]
    L = [f'// GENERATED by tools/qwen_tokfunc/xdie_bound/bound_carve.py from {top.name} (sha256 {sha256(top)}).',
         f'// seeds {",".join(seeds)}: instance text byte-for-byte; open lane ends = ports. Do not edit.',
         '`timescale 1ns/1ps', '`default_nettype none', f'module {name} (', ',\n'.join(hdr), ');']
    L += [wires[n]['decl'] for n in internal]
    for i in keep:
        L += i['text']
    L += ['endmodule', '`default_nettype wire']
    out.mkdir(parents=True, exist_ok=True)
    (out / f'{name}.v').write_text('\n'.join(L) + '\n')
    rep = dict(schema='opentallas.tok_qw.bound_carve.v1', top=str(top), top_sha256=sha256(top), name=name,
               seeds={i['name']: i['module'] for i in keep},
               inputs={n: dict(width=width(n), lane=wires.get(n, {}).get('lane'), readers=rd[n]) for n in ins},
               outputs={n: dict(width=width(n), lane=wires.get(n, {}).get('lane'), drivers=drv[n]) for n in outs},
               internal={n: dict(width=width(n), lane=wires[n]['lane']) for n in internal})
    (out / f'{name}.json').write_text(json.dumps(rep, indent=1) + '\n')
    return rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--top', required=True, type=Path)
    ap.add_argument('--seeds', required=True)
    ap.add_argument('--name', required=True)
    ap.add_argument('--out', required=True, type=Path)
    a = ap.parse_args()
    rep = carve(a.top, a.seeds.split(','), a.name, a.out)
    print(f'{a.name}: {len(rep["seeds"])} instances, {len(rep["inputs"])} inputs, {len(rep["outputs"])} outputs, '
          f'{len(rep["internal"])} internal wires')


if __name__ == '__main__':
    sys.exit(main())
