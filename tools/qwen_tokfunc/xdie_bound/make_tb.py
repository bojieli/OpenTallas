#!/usr/bin/env python3
"""TOK-QW xdie_bound: derive tb_xdie_bound.sv from main's rtl/test/qwen_split/tb_xdie_qwen_exchange.sv (golden payloads,
landing checks and measurements untouched) with ONE change: `define XB_C_OVL swaps the compute D2D master from the source
qfd_d2d_static to the module the BOUND compute die instantiates (physical/die_plan/qwen_compute/bind/bound_r8:
glue.u_d2d_rom = qfd_d2d_static_ovl_sf7_obs1, PR 1).  The overlay inputs are tied to the single-user, single-start
schedule (cal_start_rx = cal_start, cal_seg_rx = cal_seg, users 0; observer inputs 0, HEAD_CONTEXT 0 as bound).
XB_C_TXDP_ASBOUND=1 builds it with the TXDP the bound top carries (no override -> 0: must not elaborate).
    make_tb.py SRC_TB OUT_TB
"""
import sys
src, out = sys.argv[1], sys.argv[2]
t = open(src).read()
a = t.index('    qfd_d2d_static #(.MUT(0), .PR(PR), .TXDP(')
b = t.index('.fault(c_f));', a) + len('.fault(c_f));')
orig = t[a:b]
ovl = orig.replace('qfd_d2d_static #(.MUT(0), .PR(PR), .TXDP(XQ_TXDP_UNSET ? 32\'d0 : P_TXDP_C)) u_c (',
                   'qfd_d2d_static_ovl_sf7_obs1 #(.MUT(0), .PR(PR), .TXDP((XQ_TXDP_UNSET || XB_C_TXDP_ASBOUND) ? 32\'d0 : P_TXDP_C)) u_c (\n'
                   '        .obs_ctx(62\'d0), .obs_res(47\'d0), .obs_native(60\'d0), .cal_start_rx(cstart), .cal_seg_rx(1\'b0),\n'
                   '        .cal_user_tx(2\'d0), .cal_user_rx(2\'d0), .tx_user(), .rx_user(), .prog_head_context_slot(),')
assert ovl != orig, 'u_c header not found'
t = t[:a] + '`ifdef XB_C_OVL\n' + ovl + '\n`else\n' + orig + '\n`endif' + t[b:]
k = t.index('    parameter integer XQ_TXDP_UNSET = 0;')
t = t[:k] + '    parameter integer XB_C_TXDP_ASBOUND = 0;   // xdie_bound: compute master TXDP as the bound top binds it (none)\n' + t[k:]
t = ('// GENERATED by tools/qwen_tokfunc/xdie_bound/make_tb.py from rtl/test/qwen_split/tb_xdie_qwen_exchange.sv: '
     '`XB_C_OVL = the bound compute D2D master.\n') + t
c = t.index('u_k.u_core.u_end.end_fault, u_k.u_core.u_end.fault_cause);') + len('u_k.u_core.u_end.end_fault, u_k.u_core.u_end.fault_cause);')
t = t[:c] + '''
`ifdef XQ_K_SFM
            $display("XB_CAUSE KV kvn_f %0d status_f %0d end_fault %0d", u_k.u_core.kvn_f, u_k.u_core.s_f, u_k.u_core.endf);
`endif''' + t[c:]
open(out, 'w').write(t)
print(f'{out}: XB_C_OVL u_c swap applied')
