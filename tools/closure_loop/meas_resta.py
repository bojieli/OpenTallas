#!/usr/bin/env python3
"""Measured-clock re-STA of a FINISHED route (synth-resta 2026-10-08; generalises physical/common_flow/nbr_clk_measured.sdc).

A route that started on an ASSUMED block clock insertion (parallel calibrate) is re-timed at sign-off with the IO SDCs
regenerated from the MEASURED insertion, without touching the route: the job's own corner_sta Tcl (w18_sta_ss.tcl /
w18_sta_ff.tcl: same odb / spef / 6_final.sdc / post-SDCs / macros) with
  * setup at TT (the SS libraries swapped for TT, as tt_resta.sh; owner option B) and hold at FF (unchanged libraries),
  * --insert F: read_sdc F (+ set_propagated_clock again) right after the base SDC/SPEF, BEFORE the job's post-SDCs, so
    the measured IO SDC replaces the route SDC's IO model and the sign-off post-SDCs still apply on top,
  * --append F: read_sdc F LAST (after every post-SDC, before the reports) -- FLOW-IOREF: physical/common_flow/
    io_ref_routed.sdc re-derives every IO reference virtual clock from the ROUTED tree in the session's corner; its
    OT_IOREF lines (the routed insertion per corner) land in OUT json as ioref,
  * --replace SRCREL=F: the job's post-SDC /src/SRCREL read from F instead (budget sign-off SDCs regenerated by the
    loop from the measured insertion).
Writes OUT json {setup_tt, hold_ff, inserted, replaced}.  Read-only on the ORFS dir and the snapshot.

    meas_resta.py --orfs ORFS_DIR --src SRC_DIR --out OUT.json [--insert HOSTFILE]... [--replace SRCREL=HOSTFILE]... [--append HOSTFILE]...
"""
import argparse, hashlib, json, re, shutil, subprocess, sys
from pathlib import Path

IMAGE = "openroad/orfs:asap7lock"


def g(s, k):
    m = re.search(rf"^{k} (\S+)", s, re.M)
    return m.group(1) if m else None


def ps(v):
    if v in (None, "INF", "1e9", "1e+09"):
        return None
    f = float(v)
    return round(f * 1e12, 2) if abs(f) < 1e-3 else round(f, 2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--orfs", type=Path, required=True)
    ap.add_argument("--src", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--insert", action="append", default=[])
    ap.add_argument("--replace", action="append", default=[])
    ap.add_argument("--append", action="append", default=[])
    a = ap.parse_args()
    d = a.out.parent / (a.out.stem + "_meas")
    d.mkdir(parents=True, exist_ok=True)
    ins, rep = [], {}
    for i, f in enumerate(a.insert):
        n = f"ins{i}_{Path(f).name}"
        shutil.copy(f, d / n)
        ins.append(n)
    for i, r in enumerate(a.replace):
        rel, f = r.split("=", 1)
        n = f"rep{i}_{Path(f).name}"
        shutil.copy(f, d / n)
        rep[rel] = n
    app = []
    for i, f in enumerate(a.append):
        n = f"app{i}_{Path(f).name}"
        shutil.copy(f, d / n)
        app.append(n)
    res = dict(inserted=a.insert, replaced=dict(r.split("=", 1) for r in a.replace), appended=a.append)
    for corner, key in (("ss", "setup_tt"), ("ff", "hold_ff")):
        t = a.orfs / f"w18_sta_{corner}.tcl"
        if not t.is_file():
            res[key] = dict(error=f"no {t}")
            continue
        lines, out, done_ins, n_rep = t.read_text().splitlines(), [], False, 0
        for ln in lines:
            m = re.match(r"^read_sdc /src/(\S+)$", ln)
            if m and m.group(1) in rep:
                ln = f"read_sdc /meas/{rep[m.group(1)]}"
                n_rep += 1
            out.append(ln)
            if not done_ins and ln.startswith("set_propagated_clock"):
                out += [f"read_sdc /meas/{n}" for n in ins] + (["set_propagated_clock [all_clocks]"] if ins else [])
                done_ins = True
        if ins and not done_ins:
            res[key] = dict(error="no set_propagated_clock line to insert after")
            continue
        if n_rep != len(rep):
            res[key] = dict(error=f"replaced {n_rep} of {len(rep)} post-SDCs (not read by {t.name})")
            continue
        if app:
            k = next((i for i, ln in enumerate(out) if ln.startswith('puts "OT_CORNER')), None)
            if k is None:
                res[key] = dict(error="no OT_CORNER line to append before")
                continue
            out[k:k] = [f"read_sdc /meas/{n}" for n in app]
        text = "\n".join(out) + "\n"
        if corner == "ss":
            text = re.sub(r"_(R|L|SL)VT_SS_nldm", r"_\1VT_TT_nldm", text).replace("_ss.lib", "_tt.lib")
            text = text.replace('puts "OT_CORNER ss"', 'puts "OT_CORNER tt"')
        tcl = d / f"meas_{corner}.tcl"
        tcl.write_text(text)
        r = subprocess.run(["timeout", "5400", "docker", "run", "--rm", "-v", f"{a.orfs}:/work:ro", "-v", f"{a.src}:/src:ro",
                            "-v", f"{d}:/meas:ro", IMAGE, "bash", "-lc",
                            f"/OpenROAD-flow-scripts/tools/install/OpenROAD/bin/openroad -no_init -exit /meas/{tcl.name}"],
                           capture_output=True, text=True)
        s = r.stdout + r.stderr
        (d / f"meas_{corner}.log").write_text(s)
        res[key] = dict(corner="tt" if corner == "ss" else "ff", worst_slack_ps=ps(g(s, "OT_WS")), tns_ps=ps(g(s, "OT_TNS")),
                        worst_reg_to_reg_slack_ps=ps(g(s, "OT_WS_R2R")), worst_input_to_reg_slack_ps=ps(g(s, "OT_WS_I2R")),
                        worst_output_port_slack_ps=ps(g(s, "OT_WS_OUT")), violating_d_pins=g(s, "OT_VIOL_D_PINS"),
                        ioref={m[0]: dict(clock=m[1], mean=float(m[2]), min=float(m[3]), max=float(m[4]), n=int(m[5]), kind=m[6])
                               for m in re.findall(r"^OT_IOREF (\S+) (\S+) mean (\S+) min (\S+) max (\S+) n (\d+) (\S+)", s, re.M)},
                        errors=re.findall(r"\[ERROR[^\n]*|^Error[^\n]*", s, re.M)[:5], rc=r.returncode,
                        tcl_sha256=hashlib.sha256(text.encode()).hexdigest())
    a.out.write_text(json.dumps(res, indent=1))
    print(json.dumps(res))
    ok = all(res.get(k, {}).get("worst_slack_ps") is not None and not res[k].get("errors") for k in ("setup_tt", "hold_ff"))
    return 0 if ok else 3


if __name__ == "__main__":
    sys.exit(main())
