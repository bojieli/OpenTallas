"""SYNTH-RESTA 2026-10-08: measured-clock re-STA before a calibrate re-route."""
import subprocess
import unittest
from unittest.mock import patch

import closure_loop as cl


def ok(stdout=""):
    return subprocess.CompletedProcess([], 0, stdout, "")


ENV = {"CK_SS_MEAN": 900, "CK_FF_MEAN": 600, "CK_SS_MIN": 880, "CK_SS_MAX": 930, "CK_FF_MIN": 590, "CK_FF_MAX": 620}


def job(**kw):
    j = dict(name="t", host="h", run="/r", attempt=1, events=[], calibration=dict(env=ENV),
             ctrack=dict(state="done", delta_ps=120.0, sdc_cmd=None),
             spec=dict(name="t", block="b", source=dict(commit="c" * 40), stages=dict(route=dict(cmd="x"))))
    j.update(kw)
    return j


class MeasuredSdc(unittest.TestCase):
    def test_budget_job_replaces_signoff_and_guarded_ff(self):
        rc = ("cp $BUDGET_SDC_SIGNOFF physical/v/common/budget_signoff.sdc && { echo 'if {[llength [get_libs -quiet "
              "*_FF_*]]} {'; cat $BUDGET_SDC_FF; echo '}'; } > physical/v/common/budget_ff_guarded.sdc && run")
        j = job(budget=dict(check=dict(ok=True), insertion_used=dict(grade="measured")))
        j["spec"]["stages"]["route"]["cmd"] = rc
        with patch.object(cl, "ssh", return_value=ok()):
            args, why = cl.measured_sdc_args(j)
        self.assertIsNone(why)
        self.assertEqual(args, ["--replace", "physical/v/common/budget_signoff.sdc=/r/cl/budget_signoff.sdc",
                                "--replace", "physical/v/common/budget_ff_guarded.sdc=/r/cl/meas_budget_ff_guarded.sdc"])

    def test_flagged_budget_is_not_remeasured(self):
        j = job(budget=dict(check=dict(ok=False), insertion_used=dict(grade="B")))
        args, why = cl.measured_sdc_args(j)
        self.assertIsNone(args)
        self.assertIn("not regenerated", why)

    def test_sdc_cmd_out_is_redirected_to_cl(self):
        j = job()
        j["ctrack"]["sdc_cmd"] = "python3 mk.py --l-ss-max $CK_SS_MAX --out {RUN}/routes/io.sdc"
        calls = []
        with patch.object(cl, "ssh", side_effect=lambda h, c, **k: calls.append(c) or ok()):
            args, why = cl.measured_sdc_args(j)
        self.assertEqual(args, ["--insert", "/r/cl/meas_io.sdc"])
        self.assertTrue(any("--out /r/cl/meas_io.sdc" in c and "calib.measured.env" in c for c in calls))

    def test_sdc_cmd_listing_a_file(self):
        j = job()
        j["ctrack"]["sdc_cmd"] = "mk.sh $CK_SS_MEAN && ls physical/c/io_vclk_m_$CK_SS_MEAN.sdc"
        with patch.object(cl, "ssh", return_value=ok("physical/c/io_vclk_m_900.sdc\n")):
            args, _ = cl.measured_sdc_args(j)
        self.assertEqual(args, ["--insert", "/r/src/physical/c/io_vclk_m_900.sdc"])

    def test_echo_sdc_cmd_has_no_generic_resta(self):
        j = job()
        j["ctrack"]["sdc_cmd"] = 'echo "route SDC regenerated by the route script from CK_SS_MEAN"'
        with patch.object(cl, "ssh", return_value=ok("route SDC regenerated by the route script from CK_SS_MEAN\n")):
            args, why = cl.measured_sdc_args(j)
        self.assertIsNone(args)
        self.assertIn("internally", why)

    def test_small_delta_needs_no_resta(self):
        j = job()
        j["ctrack"]["delta_ps"] = 20.0
        self.assertIsNone(cl.measured_resta(j, {"orfs_dir": "/o"}))


if __name__ == "__main__":
    unittest.main()
