#!/usr/bin/env python3
"""Emit the simulation-only runtime core: ot_hdc_core_vector_weight with u_me
replaced by ot_qwen_rt_matvec_seq and every G-wide matvec port removed.

The per-group matvec state is simulated by ot_qwen_rt_matvec_slice models that a
C++ host composes (rtl/test/qwen_runtime/qwen_rt_matvec.hpp); the host serves
their memory ports directly.  Only text of the production core is copied: the
emitter refuses to run if any expected anchor is missing, so a changed core
cannot be silently mis-cut.  Production RTL is not modified.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "rtl/hdc/ot_hdc_core_vector_weight.sv"
GWIDE = ("int8_wrom_q", "scale_gre", "scale_addr", "scale_q", "kv_raddr", "kv_q", "vx_re", "vx_addr", "vx_q",
         "vw_me_we", "vw_me_addr", "vw_me_mask", "vw_me_data", "me_oaddr", "me_omask", "me_odata")
BROADCAST = [  # (direction at the core boundary, width, name)
    ("output", "", "b_active"), ("output", "[AW-1:0]", "b_cur"), ("output", "[3:0]", "b_split_r"),
    ("output", "[AW-1:0]", "b_ts_r"), ("output", "[AW-1:0]", "b_wcs_r"), ("output", "[AW-1:0]", "b_xc"),
    ("output", "[AW-1:0]", "b_xcs_r"), ("output", "", "b_wsrc_r"), ("output", "[NW-1:0]", "b_k"),
    ("output", "[NW-1:0]", "b_ktot_r"), ("output", "", "b_s1b_wsrc"), ("output", "", "b_s2_round"),
    ("output", "", "b_s3_v"), ("output", "", "b_fl_first4"), ("output", "", "b_vline5"),
    ("output", "[$clog2(G)-1:0]", "b_reduce_valid"), ("output", "[$clog2(G)-1:0]", "b_reduce_select"),
    ("output", "", "b_pre_v"), ("output", "[3*(NW+1)+AW+4+3-1:0]", "b_pre"),
    ("output", "", "b_raw_v"), ("output", "[3*(NW+1)+4+3-1:0]", "b_raw"),
    ("output", "", "b_r_v"), ("output", "[3*(NW+1)+2*AW+4+3-1:0]", "b_r"),
    ("input", "", "x_scale_any"), ("input", "", "x_group_fault_q"), ("input", "", "x_scale_fault"),
    ("input", "", "x_tfault"), ("input", "[1+32+NW-1:0]", "x_top"),
]


def emit(text: str) -> str:
    def must_sub(pattern, repl, s, count=1, flags=0):
        out, n = re.subn(pattern, repl, s, count=count, flags=flags)
        if n != count:
            raise SystemExit(f"anchor not found exactly {count}x: {pattern}")
        return out

    text = must_sub(r"module ot_hdc_core_vector_weight #\(", "module ot_qwen_rt_core #(", text)
    for name in GWIDE:
        text = must_sub(rf"\n    (input|output)\s+wire\s+\[[^\]]*G[^\]]*\]\s+{name},[^\n]*", "", text)
    ports = "".join(f"\n    {d} wire {w} {n}," for d, w, n in BROADCAST)
    text = must_sub(r"\n    input  wire              w_ok, emb_ok\n\);",
                    ports + "\n    input  wire              w_ok, emb_ok\n);", text)
    # the INT8/BF16 matrix-word select only fed u_me's G-wide wrom_q
    text = must_sub(r"\n    wire \[G\*W\*\(\(INT8_WEIGHT != 0\) \? 8 : 16\)-1:0\] me_wrom_q;\n    generate if .*?end endgenerate",
                    "", text, flags=re.S)
    start = text.index("    ot_hdc_matvec #(")
    end = text.index(");", start) + 2
    inst = text[start:end]
    inst = inst.replace("ot_hdc_matvec #(", "ot_qwen_rt_matvec_seq #(", 1)
    for port in ("wrom_q", "scale_gre", "scale_addr", "scale_q", "kv_addr", "kv_q", "x_re", "x_addr", "x_q",
                 "o_we", "o_addr", "o_mask", "o_data"):
        inst, n = re.subn(rf"\.{port}\(\w+\),\s*", "", inst)
        if n != 1:
            raise SystemExit(f"u_me port {port} not bound exactly once")
    if inst.count(".am_idx(") != 1:
        raise SystemExit("u_me am_idx anchor")
    inst = inst.replace(".am_idx(", ", ".join(f".{n}({n})" for _, _, n in BROADCAST) + ",\n        .am_idx(", 1)
    text = text[:start] + inst + text[end:]
    text = must_sub(r"\n    assign me_oaddr = vw_me_addr;\n    assign me_omask = vw_me_mask;\n    assign me_odata = vw_me_data;", "", text)
    for name in GWIDE:
        if re.search(rf"\b{name}\b", text):
            raise SystemExit(f"G-wide net {name} still referenced")
    return ("// GENERATED by tools/qwen_rt_core_emit.py from rtl/hdc/ot_hdc_core_vector_weight.sv "
            f"(sha256 {hashlib.sha256(CORE.read_bytes()).hexdigest()}). SIMULATION ONLY.\n" + text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(emit(CORE.read_text()))
    print(args.out)


if __name__ == "__main__":
    main()
