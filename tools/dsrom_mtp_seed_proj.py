#!/usr/bin/env python3
"""DS-V4.1 ROM MTP seed projection, production slice (mtp-lead 2026-10-09).  Remote only (released tensor).

  desc     regenerate rtl/dsrom_sys/mtp/ot_dsrom_mtp_seed_desc.sv (the four aligned K phases 4096/4096/4096/3072
           of one NB2 element; row pair rp = phase words + rp * WPR in cfg word 0 [41:29] and word 16 [19:6])
           and assert that form for every row pair; --check fails if the committed file differs.
  gate     fixture (released main_proj rows 0 .. 2 RP - 1, HC mean of L37/38/39 BF16, chunk8 golden), Verilator
           build of tb_dsrom_mtp_seed_proj (ctl + native element + real SRAM models), run; --mut-join runs the
           sequential-join mutant, which must FAIL.
"""
import argparse, hashlib, json, os, subprocess, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
import dsrom_1m_field as F
import v41_die_images_w17w10 as I
import rtl_v41_rom_array as A
import hdc_golden_v41 as G

ROOT = Path(__file__).resolve().parents[1]
SEG = [(0, 4096), (4096, 4096), (8192, 4096), (12288, 3072)]
DESC = ROOT / 'rtl/dsrom_sys/mtp/ot_dsrom_mtp_seed_desc.sv'
MTP = ROOT / 'rtl/dsrom_sys/mtp'
TENSOR = 'mtp.0.main_proj'


def field(ck, rp_n):
    fld = I.Field(1, 1, 0, pp=True, fast=True)
    phases = []
    for rp in range(rp_n):
        for off, k in SEG:
            part = A.Mat(ck, TENSOR, 'fp8', 2, k, r0=2 * rp, k0=off)
            part.s81_segments = [[0, k]]; part.s81_place = [(0, 0, 0)]
            phases.append(I.add_phase(fld, [part], (True, True), 0))
    nb = [p['nbeat'] for p in phases[:4]]
    assert nb == [128, 128, 128, 96], nb
    wpr = sum(nb)
    cfg = [c[0] for c in fld.cfg]
    st = fld.stream
    for rp in range(rp_n):
        for ph in range(4):
            got, ref = cfg[4 * rp + ph], list(cfg[ph])
            ref[0] = (ref[0] & ~(0x1FFF << 29)) | ((((ref[0] >> 29) & 0x1FFF) + rp * wpr) << 29)
            ref[16] = (ref[16] & ~(0x3FFF << 6)) | ((((ref[16] >> 6) & 0x3FFF) + rp * wpr) << 6)
            assert got == ref, ('row pair cfg is not phase cfg + rp * WPR', rp, ph)
        assert st[rp * wpr:(rp + 1) * wpr] == st[:wpr], ('stream differs for row pair', rp)
    assert int(fld.fill[0]) == rp_n * wpr and rp_n * wpr <= 4096, fld.fill
    return fld, phases, cfg[:4], st[:wpr], wpr


def desc_text(cfg4, st, wpr):
    L = ['`timescale 1ns/1ps',
         '// GENERATED by tools/dsrom_mtp_seed_proj.py desc -- do not edit.  Descriptor of the DS-V4.1 MTP seed',
         '// projection on one native NB2 q-element: K 15360 as four aligned phases (4096/4096/4096/3072 = 128/128/128/96',
         f'// beats, WPR {wpr} ROM words per row pair).  cfg = the 25 element config words of row pair 0; stream = the',
         '// element stream word {sv[13:12], b[11:9], p[8:1], v[0]} of beat k; kblk = first 32-element block of the phase.',
         'module ot_dsrom_mtp_seed_desc (input wire [1:0] ph, input wire [4:0] a, input wire [6:0] k,',
         '    output reg [47:0] cfg, output reg [13:0] strm, output reg [8:0] kblk, output reg [6:0] nbeat);',
         '    always @* begin', '        case ({ph, a})']
    for ph in range(4):
        for a in range(25):
            if cfg4[ph][a]:
                L.append(f"            7'd{ph * 32 + a}: cfg = 48'h{cfg4[ph][a]:012x};")
    L += ['            default: cfg = 48\'h0;', '        endcase', '    end', '    always @* begin', '        case ({ph, k})']
    base = 0
    for ph, (off, kk) in enumerate(SEG):
        n = kk // 32
        for k in range(n):
            w = st[base + k]
            assert w < (1 << 14), w
            if w:
                L.append(f"            9'd{ph * 128 + k}: strm = 14'h{w:04x};")
        base += n
    L += ['            default: strm = 14\'h0;', '        endcase', '    end', '    always @* begin', '        case (ph)']
    for ph, (off, kk) in enumerate(SEG):
        L.append(f"            2'd{ph}: begin kblk = 9'd{off // 32}; nbeat = 7'd{(kk // 32) % 128}; end")
    L += ['            default: begin kblk = 9\'d0; nbeat = 7\'d0; end', '        endcase', '    end', 'endmodule', '']
    return '\n'.join(L)


def snapshot(p):
    return A.Ckpt(p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['desc', 'gate'])
    ap.add_argument('--snapshot', type=Path, required=True)
    ap.add_argument('--ref', type=Path)
    ap.add_argument('--work', type=Path)
    ap.add_argument('--rp', type=int, default=8)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--mut-join', action='store_true')
    ap.add_argument('--jobs', type=int, default=12)
    a = ap.parse_args()
    G.set_arith('chunk8')
    ck = snapshot(a.snapshot)
    fld, phases, cfg4, st, wpr = field(ck, a.rp)
    text = desc_text(cfg4, st, wpr)
    if a.cmd == 'desc':
        if a.check:
            if DESC.read_text() != text:
                raise SystemExit('committed descriptor differs from the regenerated one')
            print(f'SEED_DESC CHECK OK rp={a.rp} wpr={wpr} sha256={hashlib.sha256(text.encode()).hexdigest()}')
        else:
            DESC.write_text(text); print('wrote', DESC)
        return
    if DESC.read_text() != text:
        raise SystemExit('committed descriptor differs from the regenerated one (run desc)')
    w = a.work; w.mkdir(parents=True, exist_ok=True)
    def mean(h):
        assert h.shape[0] == 4 and h.shape[-1] == 5120, h.shape
        return G.to_bf16(G.mul(G.seqsum([h[j] for j in range(4)]), G.F(.25)))
    x = np.concatenate([mean(np.load(a.ref / f'ctx1048576_L{l}.npz')['h_in']) for l in (37, 38, 39)])
    assert x.shape == (15360,)
    xb = G.bits(x).astype(np.uint32)
    assert not np.any(xb & 0xFFFF), 'activation is not BF16'
    m = A.Mat(ck, TENSOR, 'fp8', 2 * a.rp, 15360)
    acc, _, _, _ = A.golden_rows(m, x)
    acc = np.asarray(acc, dtype=np.uint64)
    bf = ((acc + 0x7FFF + ((acc >> 16) & 1)) >> 16) & 0xFFFF
    assert np.array_equal(bf << 16, G.bits(G.to_bf16(G.from_bits(acc.astype(np.uint32)))).astype(np.uint64))
    # phase partials, for diagnosis only (the bench checks the final roots)
    for mb in range(2):
        for parity in (0, 1):
            f = w / f'seed{"b" if mb else ""}_{parity}.viamap.hex'
            A.viamap({k // 2: v for k, v in fld.words[mb].items() if k % 2 == parity}, f)
            lines = f.read_text().splitlines(keepends=True)
            assert all(int(l, 16) == 0 for l in lines[512:]), 'ROM words beyond 4096'
            f.write_text(''.join(lines[:512]))
    def hx(n, vs, wd): (w / n).write_text(''.join(f'{int(v):0{wd}x}\n' for v in vs))
    hx('x.hex', xb, 8); hx('gold.hex', acc, 8); hx('goldbf.hex', bf, 4)
    srcs = list(dict.fromkeys(F.RTL + F.QRTL + F.ROMS + [ROOT / 'rtl/v41rom/ot_v41_elem_pq_tags.sv',
        ROOT / 'rtl/v41rom/ot_v41_fadd.sv',
        ROOT / 'physical/asap7_memory_macros/ot_sram_1r1w_128x256_m1_r2c2/ot_sram_1r1w_128x256_m1_r2c2.v',
        DESC, MTP / 'ot_dsrom_mtp_seed_ctl.sv', MTP / 'ot_dsrom_mtp_seed_proj.sv', MTP / 'tb_dsrom_mtp_seed_proj.sv']))
    srcs = [s for s in srcs if Path(s).exists()]
    obj = w / 'obj'
    cmd = [os.environ.get('OT_VERILATOR', F.VERILATOR), '--binary', '--timing', '-Wno-fatal', '--top-module',
           'tb_dsrom_mtp_seed_proj', f'-GRP={a.rp}', f'-GMUT_JOIN={int(a.mut_join)}', '--Mdir', str(obj),
           '-j', str(a.jobs)] + [str(s) for s in srcs]
    r = subprocess.run(cmd, text=True, capture_output=True); (w / 'build.log').write_text(r.stdout + r.stderr)
    if r.returncode: raise SystemExit('build failed: see build.log')
    r = subprocess.run([str(obj / 'Vtb_dsrom_mtp_seed_proj'), f'+DATA={w}', f'+OT_ROM_DIR={w}'], text=True,
                       capture_output=True)
    (w / 'sim.log').write_text(r.stdout + r.stderr); print(r.stdout[-3000:])
    passed = r.returncode == 0 and 'SEED_PROJ PASS' in r.stdout
    rec = dict(rp=a.rp, rows=2 * a.rp, wpr=wpr, mut_join=a.mut_join, passed=passed, returncode=r.returncode,
               segments=[k for _, k in SEG], phases=[p['nbeat'] for p in phases[:4]],
               desc_sha256=hashlib.sha256(text.encode()).hexdigest(),
               x_sha256=hashlib.sha256(xb.tobytes()).hexdigest(), gold=[f'{int(v):08x}' for v in acc],
               source_sha256={str(Path(s).relative_to(ROOT)): hashlib.sha256(Path(s).read_bytes()).hexdigest()
                              for s in srcs},
               tail=[l for l in r.stdout.splitlines() if l.startswith('SEED_PROJ')][-20:])
    (w / 'record.json').write_text(json.dumps(rec, indent=1) + '\n')
    if a.mut_join:
        if passed: raise SystemExit('MUTANT PASSED (sequential join must not be exact)')
        print('SEED_PROJ_MUT_JOIN FAIL_AS_REQUIRED')
    elif not passed:
        raise SystemExit('seed projection gate failed')


if __name__ == '__main__':
    main()
