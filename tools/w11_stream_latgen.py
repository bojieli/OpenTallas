#!/usr/bin/env python3
"""Generate the W11 streaming-domain (1.2 GHz) latency-parameterised RTL files from the routed source revision.

The FPL/FML/QL-parameterised V4.1 indexer and attention modules live in their own files, so the pinned as-built
sources (ot_hdc_v41x_idx.sv, ot_hdc_v41x_idx_arith.sv, ot_hdc_v41x_attn_tile.sv, ot_hdc_v41x_attn.sv, the score
slice / array) stay byte-identical to main.  Each module of a streaming file is the module text of the source
revision SRC_REV (the revision the closing routes were run from; the engine from ENGINE_REV), with every streaming
module name suffixed _l; modules that are unchanged (ot_hdc_v41x_csa, _bf16, _dly, _vdly, _attn_deq, _attn_tr*)
are not copied and come from the as-built files, which a streaming build therefore lists too.

    python3 tools/w11_stream_latgen.py            # write the files
    python3 tools/w11_stream_latgen.py --check    # verify the committed files equal the generation
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC_REV = "cd1b1061"         # sources of st_tail7*, st_chunk755k/m5, st_tile76k/m5, st_tile74k
ENGINE_REV = "cdc47f9a"      # engine (not routed) with FPL/FML/NBANKP on the ILV/REPL/NSTAGE controller
V = "rtl/hdc/v41x/"
RENAME = ["ot_hdc_v41x_q4dot", "ot_hdc_v41x_bmul", "ot_hdc_v41x_idx_chunk", "ot_hdc_v41x_idx_tail",
          "ot_hdc_v41x_idx_engine", "ot_hdc_v41x_idx_score_slice", "ot_hdc_v41x_idx_array",
          "ot_hdc_v41x_attn_bmul", "ot_hdc_v41x_attn_chunk", "ot_hdc_v41x_attn_hdp", "ot_hdc_v41x_attn_tile",
          "ot_hdc_v41x_attn_merge", "ot_hdc_v41x_attn"]
# output file: [(revision, source file, [modules])]
PLAN = {
    V + "ot_hdc_v41x_idx_arith_lat.sv": [(SRC_REV, V + "ot_hdc_v41x_idx_arith.sv",
                                          ["ot_hdc_v41x_q4dot", "ot_hdc_v41x_bmul", "ot_hdc_v41x_faddl"])],
    V + "ot_hdc_v41x_idx_lat.sv": [(SRC_REV, V + "ot_hdc_v41x_idx.sv",
                                    ["ot_hdc_v41x_idx_chunk", "ot_hdc_v41x_idx_tail", "ot_hdc_v41x_idx_engine"]),
                                   (SRC_REV, V + "ot_hdc_v41x_idx_score_slice.sv", ["ot_hdc_v41x_idx_score_slice"]),
                                   (SRC_REV, V + "ot_hdc_v41x_idx_array.sv", ["ot_hdc_v41x_idx_array"])],
    V + "ot_hdc_v41x_attn_tile_lat.sv": [(SRC_REV, V + "ot_hdc_v41x_attn_tile.sv",
                                          ["ot_hdc_v41x_attn_bmul", "ot_hdc_v41x_attn_chunk", "ot_hdc_v41x_attn_hdp",
                                           "ot_hdc_v41x_attn_tile", "ot_hdc_v41x_qaddl"])],
    V + "ot_hdc_v41x_attn_lat.sv": [(ENGINE_REV, V + "ot_hdc_v41x_attn.sv",
                                     ["ot_hdc_v41x_attn_merge", "ot_hdc_v41x_attn"])],
}
HEADER = """`timescale 1ns/1ps
// ---------------------------------------------------------------------------
// GENERATED by tools/w11_stream_latgen.py -- do not edit; edit the generator's sources.
// W11 streaming domain (1.2 GHz at SS): the latency-parameterised (FPL binary32 add, FML product, QL block dot)
// {what}.  Each module below is the text of {src} at {rev} with the streaming module names
// suffixed _l; FPL = FML = QL = 3 is the as-built unit cycle for cycle.  A streaming build lists the as-built file
// too (shared helper modules) and, for FPL > 3, rtl/hdc/ot_hdc_fp32_add_lat.sv and rtl/hdc/ot_hdc_prefix.sv.
// ---------------------------------------------------------------------------
"""
WHAT = {"ot_hdc_v41x_idx_arith_lat.sv": "indexer arithmetic (block dot, head-weight product, FP32 add wrapper)",
        "ot_hdc_v41x_idx_lat.sv": "indexer element, tail, engine, score slice and scoring array",
        "ot_hdc_v41x_attn_tile_lat.sv": "attention tile (product, chunk chain, head datapath, tile, FP32 add wrapper)",
        "ot_hdc_v41x_attn_lat.sv": "attention engine (controller, lane trees, block merge)"}


def git_show(rev, path):
    return subprocess.run(["git", "show", f"{rev}:{path}"], cwd=ROOT, capture_output=True, text=True,
                          check=True).stdout


def modules(text):
    """{name: text} of each top-level module (from its `module` line, preceded by its comment block, to endmodule)."""
    out = {}
    for m in re.finditer(r"^module (\w+)", text, flags=re.M):
        start = m.start()
        # take the comment lines directly above
        lines = text[:start].split("\n")[:-1]
        k = len(lines)
        while k > 0 and lines[k - 1].startswith("//"):
            k -= 1
        cstart = len("\n".join(lines[:k])) + (1 if k else 0)
        end = text.index("endmodule", start) + len("endmodule")
        out[m.group(1)] = text[cstart:end]
    return out


def rename(text):
    pat = re.compile(r"\b(" + "|".join(sorted(RENAME, key=len, reverse=True)) + r")\b")
    return pat.sub(lambda m: m.group(1) + "_l", text)


def generate():
    files = {}
    for out, parts in PLAN.items():
        body, srcs, revs = [], [], []
        for rev, src, mods in parts:
            ms = modules(git_show(rev, src))
            body += [rename(ms[n]) for n in mods]
            srcs.append(src)
            revs.append(rev)
        name = Path(out).name
        files[out] = HEADER.format(what=WHAT[name], src=", ".join(srcs), rev=", ".join(sorted(set(revs)))) + \
            "\n\n".join(body) + "\n"
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = generate()
    bad = []
    for p, t in files.items():
        if a.check:
            if (ROOT / p).read_text() != t:
                bad.append(p)
        else:
            (ROOT / p).write_text(t)
    if bad:
        sys.exit("differs from generation: " + ", ".join(bad))
    print("ok", len(files))


if __name__ == "__main__":
    main()
