#!/usr/bin/env python3
"""Generate a fixed R6 circuit/calendar; no floating-point computation here."""
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MODEL = json.loads((HERE / 'model_input.json').read_text())['selected']
INV = json.loads((HERE / 'mux_inventory.json').read_text())
OPS = MODEL['operations']
NAMES = [f'q{q}.station{k}' for q in range(4) for k in range(16 if q in (0,2) else 4)]
SID = {n:i for i,n in enumerate(NAMES)}
PROD = {o['result']:o for o in OPS}
def tm(o, key='start'): return o[key]+3
def ident(n): return n.replace('.', '_')
def digest(x): return hashlib.sha256(repr(x).encode()).hexdigest()
WORD = {digest(('square', i)):i for i in range(1280)}
CANON = {digest(('canonical_zero', ('square',i))):i for i in range(0,1280,8)}

# Extract all fragments: local products which leave the local station graph.
global_ops = [o for o in OPS if o['resource'].startswith('global')]
local_ops = [o for o in OPS if not o['resource'].startswith('global')]
global_operands = {d for o in global_ops for d in o['operands']}
fragment_ops = sorted([o for o in local_ops if o['result'] in global_operands], key=lambda o:(tm(o,'done'),o['name']))
assert len(fragment_ops)==26
slots = {o['result']:i for i,o in enumerate(fragment_ops)}
fragment_slots = dict(slots)
global_rows=[]
for o in global_ops:
    refs=[]
    for d in o['operands']:
        if d in slots: refs.append(slots[d])
        else:
            assert d not in PROD, 'missing live global operand'
            refs.append(26)  # the only two canonical padded-zero subtrees
    dst = next(x for x in refs if x<26)
    global_rows.append((o,refs,dst))
    for d in o['operands']: slots.pop(d,None)
    slots[o['result']]=dst
assert len(slots)==1 and len(global_rows)==27
OPID={o['result']:(i%32,int(o['name'][1])) for n in NAMES
      for i,o in enumerate([x for x in local_ops if x['resource']==n])}

out=[]
def emit(s=''): out.append(s)
emit('''`timescale 1ns/1ps
`default_nettype none
// GENERATED by tools/hbm_record6_station41/generate.py. Numerical component only.
// New standalone mechanism, disabled by default; no production compiler change.
module ot_hbm_r6_station41 #(parameter integer ENABLE=0,MUT=0)(
 input wire clk,rst_n,start,input wire [7:0] episode_epoch,
 input wire [16383:0] lane_x,input wire [511:0] lane_v,
 input wire [3:0] capture,input wire [1:0] capture_group,
 output wire root_v,output wire [31:0] root_x,output wire fault,
 output wire [9:0] cycle,output wire [10:0] capture_count,add_count
);
generate if(ENABLE==0) begin:g_off
 assign root_v=0; assign root_x=0; assign fault=0;
 assign cycle=0; assign capture_count=0; assign add_count=0;
end else begin:g_on
 reg landing_1,landing_2;
 always @(posedge clk)begin landing_1<=rst_n;landing_2<=landing_1;end
 wire run_rst_n=landing_2;
 reg active; reg [9:0] tick; reg [7:0] epoch;
 reg [10:0] ncap,nadd; reg ctl_fault;
 assign cycle=tick; assign capture_count=ncap; assign add_count=nadd;
 wire [40:0] nv,ne; wire [31:0] nx[0:40];
 wire [39:0] sf;
 integer ai; reg [6:0] adds_now;
 integer ci;reg [8:0] actual_capture_words;
 always @* begin actual_capture_words=0;
  for(ci=0;ci<512;ci=ci+1)if((ci<128)||(ci>=256&&ci<384)||(ci>=128&&ci<160)||(ci>=384&&ci<416))actual_capture_words=actual_capture_words+{8'd0,lane_v[ci]};
 end
 always @* begin adds_now=0; for(ai=0;ai<41;ai=ai+1) adds_now=adds_now+{6'd0,nv[ai]}; end
 always @(posedge clk or negedge rst_n) begin
  if(!rst_n) begin active<=0;tick<=0;epoch<=0;ncap<=0;nadd<=0;ctl_fault<=0;end
  else if(start) begin
   ctl_fault<=active;
   active<=1;tick<=1;epoch<=episode_epoch;ncap<=0;nadd<=0;
  end else if(active) begin
   tick<=tick+1'b1; nadd<=nadd+{4'd0,adds_now};
   if(tick==64||tick==176||tick==288||tick==400) begin
    ncap<=ncap+{2'd0,actual_capture_words};
    if(actual_capture_words!=320)ctl_fault<=1;
    if(capture!=4'hf||capture_group!=2'((tick-64)/112)) ctl_fault<=1;
   end else if(capture!=0) ctl_fault<=1;
   if(tick==591)begin active<=0;if(ncap!=1280||nadd+{4'd0,adds_now}!=1281||!nv[40])ctl_fault<=1;end
  end
 end
 // Result wires forward a completed real node at its held-result capture edge.
 // This permits S+9 selection; otherwise NBA ordering would require S+10.
 wire [31:0] result_x[0:39]; wire [39:0] result_v;
 wire [4:0] result_op[0:39];wire [1:0] result_group[0:39];wire [7:0] result_epoch[0:39];
''')

# All 512 face words have useful held data/valid and two 16-bit capture enables.
# 32 ancestors fan out to <=32 actual local enable D pins. Their registered
# prediction precedes capture by two edges, preserving the source age.
for a in range(32):
    emit(f' (* keep=1,dont_touch=1 *) reg cap_ancestor_{a};')
    emit(f' always @(posedge clk or negedge rst_n) if(!rst_n) cap_ancestor_{a}<=0; else cap_ancestor_{a}<=active&&(tick==62||tick==174||tick==286||tick==398);')
for w in range(512):
    a=(2*w)//32
    emit(f' (* keep=1,dont_touch=1 *) reg ce_{w}_lo,ce_{w}_hi;')
    emit(f' reg [31:0] word_{w}; reg valid_{w};')
    emit(f' always @(posedge clk or negedge rst_n) if(!rst_n) begin ce_{w}_lo<=0;ce_{w}_hi<=0;valid_{w}<=0;end else begin ce_{w}_lo<=cap_ancestor_{a};ce_{w}_hi<=cap_ancestor_{a};if(ce_{w}_lo)valid_{w}<=lane_v[{w}];end')
    emit(f' always @(posedge clk) begin if(ce_{w}_lo)word_{w}[15:0]<=lane_x[{w*32}+:16];if(ce_{w}_hi)word_{w}[31:16]<=lane_x[{w*32+16}+:16];end')

schedule=[]
for name in NAMES:
    si=SID[name]; q=int(name[1]); k=int(name.split('station')[1]); base=q*128+k*8
    peers=INV['peer_sets'].get(name,[])
    assert len(peers)<=4 and len(set(peers))==len(peers)
    rows=[o for o in local_ops if o['resource']==name]
    actual_peers={PROD[d]['resource'] for o in rows for d in o['operands']
                  if d in PROD and PROD[d]['resource']!=name}
    assert actual_peers==set(peers), ('missing/unused peer',name,actual_peers,peers)
    emit(f' begin : s{si}')
    emit(' reg [31:0] held;reg held_v;reg [1:0] group;reg [7:0] local_epoch;reg [4:0] ordinal;reg [3:0] countdown;reg busy,bad;')
    emit(' reg [4:0] pending_op,held_op;reg [1:0] pending_group,held_group;reg [7:0] pending_epoch,held_epoch;')
    emit(' reg expected_retire;reg [4:0] expected_op;reg [1:0] expected_group;')
    emit(' always @* begin expected_retire=0;expected_op=0;expected_group=0;case(tick)')
    for oi,o in enumerate(rows):
        emit(f" 10'd{tm(o,'done')}:begin expected_retire=active;expected_op=5'd{oi%32};expected_group=2'd{int(o['name'][1])};end")
    emit(' default:begin end endcase end')
    emit(' reg issue,p_issue,asel; reg [3:0] bsel; reg [4:0] next_ordinal;')
    emit(' always @* begin p_issue=0;asel=0;bsel=0;next_ordinal=0;case(tick+1)')
    for ordinal,o in enumerate(rows):
        a,b=o['operands']
        if a in CANON: aa=0
        else:
            assert PROD[a]['resource']==name
            aa=1
        if b in WORD: bb=WORD[b]%8
        else:
            pn=PROD[b]['resource']; assert pn in peers
            bb=8+peers.index(pn)
        emit(f' 10\'d{tm(o)}:begin p_issue=active;asel=1\'b{aa};bsel=4\'d{bb};next_ordinal=5\'d{ordinal%32};end')
        schedule.append(dict(**o,source_start=tm(o),source_done=tm(o,'done'),station=si,a_select=aa,b_select=bb))
    emit(' default:begin end endcase end')
    # Explicit per-segment selector controls: four bits bsel each only controls
    # one 16-bit mux segment at first stage. asel similarly duplicated.
    emit(' (* keep=1,dont_touch=1 *) reg as_lo,as_hi;')
    emit(' (* keep=1,dont_touch=1 *) reg [3:0] bs_lo,bs_hi,bs1_lo,bs1_hi,bs2_lo,bs2_hi;')
    # Controls registered a cycle before data select, independently decoded at
    # previous tick. Avoid adding latency by presenting next-edge schedule.
    emit(' always @(posedge clk or negedge rst_n)if(!rst_n)issue<=0;else begin issue<=p_issue;as_lo<=asel;as_hi<=asel;bs_lo<=bsel;bs_hi<=bsel;bs1_lo<=bsel;bs1_hi<=bsel;bs2_lo<=bsel;bs2_hi<=bsel;end')
    # Registered one-edge prediction supplies actual useful per-segment selects.
    emit(' reg [31:0] a1,a2,b10,b11,b12,b2;reg av1,av2,bv1,bv2;reg [1:0] bank1;')
    emit(' wire [31:0] src[0:11];wire [11:0] sv;')
    for j in range(8):
        emit(f' assign src[{j}]=(MUT==1)?word_{base+(3-j if j in (1,2) else j)}:word_{base+j};assign sv[{j}]=valid_{base+j};')
    for j in range(4):
        if j<len(peers):
            ps=SID[peers[j]]
            alternate=SID[peers[(j+1)%len(peers)]]
            emit(f' assign src[{8+j}]=(MUT==2)?result_x[{alternate}]:result_x[{ps}];assign sv[{8+j}]=result_v[{ps}];')
        else: emit(f' assign src[{8+j}]=0;assign sv[{8+j}]=0;')
    emit(f' assign result_x[{si}]=(nv[{si}]&&MUT!=3)?nx[{si}]:held;assign result_v[{si}]=(nv[{si}]&&pending_epoch==epoch)||(held_v&&held_epoch==epoch);assign sf[{si}]=bad;')
    emit(f' assign result_op[{si}]=nv[{si}]?pending_op:held_op;assign result_group[{si}]=nv[{si}]?pending_group:held_group;assign result_epoch[{si}]=nv[{si}]?pending_epoch:held_epoch;')
    emit(' wire [31:0] a0=(src[0][30:0]==0)?32\'d0:src[0];')
    emit(' always @(posedge clk) begin')
    emit(f' if(issue)begin a1[15:0]<=as_lo?result_x[{si}][15:0]:a0[15:0];a1[31:16]<=as_hi?result_x[{si}][31:16]:a0[31:16];')
    for bi,sel in enumerate(['bs','bs1','bs2']):
        emit(f" b1{bi}[15:0]<=src[{bi*4}+{sel}_lo[1:0]][15:0];b1{bi}[31:16]<=src[{bi*4}+{sel}_hi[1:0]][31:16];")
    emit(' bank1<=bs_lo[3:2];end')
    emit(' if(av1)begin a2<=a1;case(bank1)0:b2<=b10;1:b2<=b11;2:b2<=b12;default:b2<=0;endcase end')
    emit(f' if(nv[{si}])held<=nx[{si}];end')
    emit(' always @(posedge clk or negedge rst_n)begin')
    emit(' if(!rst_n)begin held_v<=0;av1<=0;av2<=0;bv1<=0;bv2<=0;group<=0;local_epoch<=0;ordinal<=0;countdown<=0;busy<=0;bad<=0;end')
    emit(' else begin av1<=issue;bv1<=issue&&bs_lo<12&&sv[bs_lo];av2<=av1;bv2<=bv1;')
    emit(' if(start)begin held_v<=0;group<=0;local_epoch<=episode_epoch;ordinal<=0;countdown<=0;busy<=1;bad<=0;end')
    emit(' if(countdown!=0)countdown<=countdown-1\'b1;')
    emit(f' if(issue)begin countdown<=9;ordinal<=ordinal+1\'b1;if(countdown>1||!sv[bs_lo]||(as_lo&&!result_v[{si}])||(!as_lo&&!sv[0]))bad<=1;end')
    emit(' case(tick)')
    for oi,o in enumerate(rows):
        g=int(o['name'][1])
        emit(f" 10'd{tm(o)}:begin pending_op<=5'd{oi%32};pending_group<=2'd{g};pending_epoch<=epoch;")
        for d in o['operands']:
            if d not in PROD: continue
            source=PROD[d]; ps=SID[source['resource']]; po,pg=OPID[d]
            emit(f" if(!result_v[{ps}]||result_op[{ps}]!=5'd{po}||result_group[{ps}]!=2'd{pg}||result_epoch[{ps}]!=epoch)bad<=1;")
        emit(' end')
    emit(' default:begin end endcase')
    emit(' if(av1&&(bs_lo!=bs_hi||as_lo!=as_hi||bank1==3))bad<=1;')
    emit(f' if(active&&(nv[{si}]!=expected_retire))bad<=1;')
    emit(f' if(nv[{si}]&&(pending_op!=expected_op||pending_group!=expected_group))bad<=1;')
    emit(f' if(nv[{si}])begin held_v<=1;held_epoch<=pending_epoch;held_op<=pending_op;held_group<=pending_group;if(ne[{si}]||pending_epoch!=epoch)bad<=1;end')
    emit(' if(active&&(tick==64||tick==176||tick==288||tick==400))begin group<=capture_group;local_epoch<=epoch;held_v<=0;end')
    emit(' end end')
    emit(f' wire mode_unused;ot_hbm_r6_add_node u_node(.clk(clk),.rst_n(rst_n),.v(av2&&bv2),.a(a2),.b(b2),.vy(nv[{si}]),.y(nx[{si}]),.err(ne[{si}]));')
    emit(' end')

# The 26 fixed entries carry their actual identity, with a single statically
# assigned write at each event. Global joins reuse a consumed child's entry.
for i in range(26): emit(f' reg [55:0] fragment_{i};')
emit(' reg [4:0] global_pending,global_expected;reg [7:0] global_epoch;reg global_retire;wire global_owned=nv[40]&&global_retire&&global_pending==global_expected&&global_epoch==epoch;')
emit(' always @* begin global_retire=0;global_expected=0;case(tick)')
for oi,(o,refs,dst) in enumerate(global_rows):
    emit(f" 10'd{tm(o,'done')}:begin global_retire=active;global_expected=5'd{oi};end")
emit(' default:begin end endcase end')
emit(' always @(posedge clk)begin case(tick)')
for oi,(o,refs,dst) in enumerate(global_rows):
    emit(f" 10'd{tm(o)}:begin global_pending<=5'd{oi};global_epoch<=epoch;end")
emit(' default:begin end endcase end')
emit(' reg gi;reg [4:0] ga,gb,gd;reg [55:0] expect_a,expect_b;')
emit(' always @* begin gi=0;ga=0;gb=0;gd=0;expect_a=0;expect_b=0;case(tick)')
for o,refs,dst in global_rows:
    emit(f' 10\'d{tm(o)}:begin gi=active;ga=5\'d{refs[0]};gb=5\'d{refs[1]};gd=5\'d{dst};end')
emit(' default:begin end endcase end')
emit(' wire [55:0] fs[0:27];')
def local_meta(o):
    m=re.search(r'subtree(\d+):(\d+)',o['name'])
    if m: return int(m[1]),int(m[2])-int(m[1]),int(o['name'][1])
    return int(re.search(r'chunk(\d+)',o['name'])[1]),1,int(o['name'][1])
def global_meta(o):
    m=re.search(r'global(\d+):(\d+)',o['name'])
    return int(m[1]),int(m[2])-int(m[1])
for i in range(26):
    fo=fragment_ops[i];si=SID[fo['resource']];base,size,group=local_meta(fo)
    expr=f'fragment_{i}'
    for o,refs,dst in global_rows:
        if dst==i:
            b,n=global_meta(o)
            expr=f"(active&&tick==10'd{tm(o,'done')}&&global_owned)?{{epoch,5'd{n.bit_length()-1},8'd{b},2'd0,global_owned,nx[40]}}:({expr})"
    expr=f"(active&&tick==10'd{tm(fo,'done')+1})?{{epoch,5'd{size.bit_length()-1},8'd{base},2'd{group},result_v[{si}],result_x[{si}]}}:({expr})"
    emit(f' assign fs[{i}]={expr};')
emit(" assign fs[26]={8'd0,5'd0,8'd0,2'd0,1'b1,32'd0};assign fs[27]=0;")
emit(' reg [55:0] ga1[0:3],gb1[0:3],ga2,gb2;reg gv1,gv2;reg [1:0] gabank,gbbank;reg gbad;')
emit(' always @(posedge clk)begin')
for i in range(4):
    emit(f" if(gi)begin ga1[{i}]<=fs[{i*7}+ga%7];gb1[{i}]<=fs[{i*7}+gb%7];end")
emit(' if(gi)begin gabank<=2\'(ga/7);gbbank<=2\'(gb/7);end if(gv1)begin ga2<=ga1[gabank];gb2<=gb1[gbbank];end end')
emit(' always @(posedge clk or negedge rst_n)if(!rst_n)begin gv1<=0;gv2<=0;gbad<=0;end else begin gv1<=gi;gv2<=gv1;if(start)gbad<=0;if(gv2&&(!ga2[32]||!gb2[32]))gbad<=1;if(ne[40])gbad<=1;if(active&&(nv[40]!=global_retire))gbad<=1;if(nv[40]&&!global_owned)gbad<=1;case(tick)')
for o,refs,dst in global_rows:
    b,n=global_meta(o)
    emit(f" 10'd{tm(o)}:begin")
    for ref,base in zip(refs,[b,b+n//2]):
        if ref==26:
            assert base>=160, 'live source replaced by padding'
        else:
            emit(f" if(!fs[{ref}][32]||fs[{ref}][55:48]!=epoch||fs[{ref}][47:43]!=5'd{(n//2).bit_length()-1}||fs[{ref}][42:35]!=8'd{base})gbad<=1;")
    emit(' end')
emit(' default:begin end endcase end')
emit(' ot_hbm_r6_add_node u_global(.clk(clk),.rst_n(rst_n),.v(gv2&&ga2[32]&&gb2[32]),.a(ga2[31:0]),.b(gb2[31:0]),.vy(nv[40]),.y(nx[40]),.err(ne[40]));')
for i in range(26):
    fo=fragment_ops[i]; si=SID[fo['resource']]
    # 56-bit shape {epoch8,size5,base8,group2,valid1,value32}
    base,size,group=local_meta(fo)
    emit(f' always @(posedge clk or negedge rst_n) if(!rst_n)fragment_{i}[32]<=0;else if(start)fragment_{i}[32]<=0;else begin')
    emit(f" if(active&&tick==10'd{tm(fo,'done')+1})fragment_{i}<={{epoch,5'd{size.bit_length()-1},8'd{base},2'd{group},result_v[{si}],result_x[{si}]}};")
    for o,refs,dst in global_rows:
        if dst==i:
            b,n=global_meta(o)
            emit(f" if(active&&tick==10'd{tm(o,'done')})fragment_{i}<={{epoch,5'd{n.bit_length()-1},8'd{b},2'd0,global_owned,nx[40]}};")
    emit(' end')
emit(" assign root_v=global_owned&&tick==10'd591;assign root_x=nx[40];assign fault=ctl_fault||gbad||(|sf);")
emit('end endgenerate\nendmodule')
emit('''// Actual source arithmetic, OPR1 then LAT6; no real/shortreal arithmetic.
module ot_hbm_r6_add_node(input wire clk,rst_n,v,input wire [31:0] a,b,
 output wire vy,output wire [31:0] y,output wire err);
 reg ov;reg [31:0] oa,ob;
 always @(posedge clk or negedge rst_n)if(!rst_n)ov<=0;else ov<=v;
 always @(posedge clk)begin oa<=a;ob<=b;end
 wire [1:0] ae;
 ot_hdc_fp32_add_lat #(.LAT(6),.DRST(0)) u_add(.clk(clk),.rst_n(rst_n),.valid_in(ov),.a(oa),.b(ob),.y(y),.err(ae),.valid_out(vy));
 assign err=vy&&(ae!=0);
endmodule
`default_nettype wire
''')
path=ROOT/'rtl/hbm_accel/generic/adapters/static_su/reduction/ot_hbm_r6_station41.sv'
text='\n'.join(out)+'\n'
a,b=text.split('// Actual source arithmetic',1)
a=a.replace('negedge rst_n','negedge run_rst_n').replace('if(!rst_n)','if(!run_rst_n)').replace('.rst_n(rst_n)', '.rst_n(run_rst_n)')
path.write_text((a+'// Actual source arithmetic'+b).rstrip()+'\n')
ledger=dict(scope='SOURCE ONLY; no RTL simulation or physical qualification',source_model_root=591,
 operations=1281,local_operations=1254,global_operations=27,private_stations=40,
 source_schedule=schedule,global_schedule=[dict(**o,selectors=r,slot=d) for o,r,d in global_rows],
 input_payload_valid_ff=512*33,local_result_ff=40*33,local_selector_ff=40*196,
 fragment_ff=26*56,global_selector_ff=560,arithmetic_ff=41*571,
 local_state_minimum_ff=40*30,capture_enable_ff=1024,capture_ancestors_emitted=32,
 local_selector_control_ff=40*27,local_selector_bank_ff=40*2,
 local_epoch_op_group_extra_ff=40*30,local_live_result_bypass_mux_bits=40*32,
 global_live_entry_bypass_mux_bits=26*56,global_ownership_register_ff=13,
 reset_face_sampled_stages=2,arithmetic_mode_pipeline_removed_ff=41*7,
 global_state_and_root_distribution_native_fanout='UNQUALIFIED; central schedule/reset are not physically SAFE',
 capture_ancestors_used=32,unused_ancestor_reported=False,
 limitations=['No native fanout/area/clock proof','Reset/control ancestry requires synthesis audit',
 'Static metadata checks and causal mutants must pass fleet integration',
 'MUT selector reserved; parent supplies negative benches'])
(ROOT/'results/arch/hbm_record6_station41_1019/source_ledger.json').write_text(json.dumps(ledger,indent=2)+'\n')
print(json.dumps(dict(rtl=str(path),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),ops=len(OPS))))
