#!/usr/bin/env python3
"""Emit ot_qwen_rom_core with per-position DYN tables (VPOS, default-off) for the verify layer.

Applied to the output of tools/qwen_rom_rt_core_emit_w12.emit (pinned core
rtl/hdc/ot_hdc_core_vector_weight.sv and that emitter untouched).  Adds

  parameter VPOS = 0   0: the core is unchanged in behaviour (the per-position
                         tables are not generated; every decode reads dyn[]).
                       1: an instruction's POS_OFF field (bits [902:900],
                         tools/qwen_rom_verify_program_w12.py) selects which of
                         eight DYN tables, derived in S_DYN from pos + 0 .. pos + 7,
                         its bases and counts add; DYN_TTILES rounds use
                         pos + POS_OFF.

So p back-to-back copies of an operation, one per verify position, each get
their own RoPE row, K/V write slot, context length and position-tile rounds.
The tables are registers written once per step (8 x 8 x AW bits); the decode
adds one 3-bit-indexed select level in front of the existing 3-bit DYN select.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

import qwen_rom_rt_core_emit_w12 as E

POS_OFF_LO, POS_OFF_W = 900, 3


def emit_vpos(text: str) -> str:
    def sub1(pattern, repl, s, flags=0):
        out, n = re.subn(pattern, repl, s, count=1, flags=flags)
        if n != 1:
            raise SystemExit(f"anchor not found: {pattern}")
        return out

    text = sub1(r"(    parameter integer KV_PREP = [^\n,]*)\n\) \(",
                r"\1,\n    parameter integer VPOS = 0\n) (", text)
    text = sub1(r"\n    reg \[AW-1:0\] dyn \[0:7\];\n",
                "\n    reg [AW-1:0] dyn [0:7];\n"
                "    // VPOS: per-position DYN tables (pos + 0 .. pos + 7), selected by the instruction's POS_OFF\n"
                "    reg [AW-1:0] dynp [0:63];\n"
                "    wire [2:0] vp_off;\n"
                "    wire [NW-1:0] dynp_tiles_zero [0:7];\n", text)
    # DYN_TTILES of the decoded instruction: rounds of its own position
    text = sub1(r"ot_hdc_dyn_ttiles #\(\.W\(W\),\.G\(G\),\.NW\(NW\)\) u_dyn_tiles_split \(\n        \.pos\(pos_r\),",
                "ot_hdc_dyn_ttiles #(.W(W),.G(G),.NW(NW)) u_dyn_tiles_split (\n"
                "        .pos((VPOS != 0) ? pos_r + vp_off : pos_r),", text)
    text = sub1(r"(    wire dyn_tiles_bad_instruction = [^\n]*\n)",
                r"\1"
                f"    assign vp_off = (VPOS != 0) ? ir[{POS_OFF_LO} +: {POS_OFF_W}] : 3'd0;\n"
                "    generate if (VPOS != 0) begin : g_vpos_tiles\n"
                "        genvar vpt;\n"
                "        for (vpt = 0; vpt < 8; vpt = vpt + 1) begin : g_t\n"
                "            ot_hdc_dyn_ttiles #(.W(W),.G(G),.NW(NW)) u_t (\n"
                "                .pos(pos_r + vpt),.split_log2(4'd0),.rounds(dynp_tiles_zero[vpt]),.invalid_split());\n"
                "        end\n"
                "    end endgenerate\n", text)
    text = sub1(r"(        dyn\[7\] <= 0;\n    end\n)",
                r"\1"
                "    // VPOS: the eight per-position tables, same expressions at pos + o\n"
                "    integer vpo;\n"
                "    always @(posedge clk) if (VPOS != 0 && st == S_DYN) begin\n"
                "        for (vpo = 0; vpo < 8; vpo = vpo + 1) begin\n"
                "            dynp[vpo*8+0] <= 0;\n"
                "            dynp[vpo*8+1] <= tok_r * HID;\n"
                "            dynp[vpo*8+2] <= (pos_r + vpo[NW-1:0]) * HALF;\n"
                "            dynp[vpo*8+3] <= ((pos_r + vpo[NW-1:0]) >> LW) * (HD * W) + ((pos_r + vpo[NW-1:0]) & (W - 1));\n"
                "            dynp[vpo*8+4] <= (pos_r + vpo[NW-1:0]) * HD;\n"
                "            dynp[vpo*8+5] <= pos_r + vpo[NW-1:0] + 1;\n"
                "            dynp[vpo*8+6] <= dynp_tiles_zero[vpo];\n"
                "            dynp[vpo*8+7] <= 0;\n"
                "        end\n"
                "    end\n"
                "    `define DYNS(sel) ((VPOS != 0) ? dynp[{vp_off, sel}] : dyn[sel])\n", text)
    n_before = text.count("dyn[`F(")
    text = re.sub(r"\bdyn\[(`F\([A-Z_]+\))\]", r"`DYNS(\1)", text)
    if n_before != 11 or text.count("`DYNS(`F(") != 11:
        raise SystemExit(f"expected 11 DYN decode selects, found {n_before}")
    return text


def emit(core_text: str) -> str:
    return ("// GENERATED by tools/qwen_rom_verify_core_emit_w12.py (VPOS opt-in) over tools/qwen_rom_rt_core_emit_w12.py "
            f"(sha256 {hashlib.sha256(Path(E.__file__).read_bytes()).hexdigest()}).\n" + emit_vpos(E.emit(core_text)))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(emit(E.CORE.read_text()))
    print(args.out)


if __name__ == "__main__":
    main()
