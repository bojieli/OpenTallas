#!/usr/bin/env python3
"""Check the chip implementation contract without rebuilding analytical studies."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from opentallas.chip_architecture import ArchitectureError, qwen_resource_plan, reduction_service  # noqa: E402


def physical_summary(root: Path, relative: str) -> dict:
    path = root / relative
    if not path.exists():
        return {"path": relative, "status": "missing", "source_current": False}
    record = json.loads(path.read_text())
    design = record.get("design", {})
    sources = design.get("sources", [])
    mismatches = [s["path"] for s in sources if not (root / s["path"]).is_file() or
                  hashlib.sha256((root / s["path"]).read_bytes()).hexdigest() != s["sha256"]]
    metrics = record.get("place_and_route", {}).get("metrics", {})
    return {"path": relative, "record_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "status": record.get("status"), "closed": design.get("closed", False),
            "closed_reason": design.get("closed_reason"),
            "signal_integrity_violations": design.get("signal_integrity_violations", {}),
            "source_current": bool(sources) and not mismatches, "mismatched_sources": mismatches,
            "source_digests": sources, "clock_period_ns": design.get("clock_period_ns"),
            "standard_cell_area_um2": metrics.get("standard_cell_area_um2"),
            "core_area_um2": metrics.get("core_area_um2"), "macro_count": metrics.get("macro_count"),
            "setup_wns_ns": metrics.get("setup_wns_ns"), "hold_wns_ns": metrics.get("hold_wns_ns"),
            "drc_errors": metrics.get("drc_errors"), "antenna_violating_nets": metrics.get("antenna_violating_nets"),
            "max_slew_violations": metrics.get("max_slew_violations"),
            "standard_cell_count": metrics.get("standard_cell_count")}


def build_report(root: Path, config_path: Path) -> dict:
    config = json.loads(config_path.read_text())
    if config.get("schema") != "opentallas.chip-design.v2":
        raise ArchitectureError("unsupported chip-design schema")
    model_path = root / config["qwen"]["model"]
    report = qwen_resource_plan(config, json.loads(model_path.read_text()))
    report["reduction_service"] = {name: reduction_service(config, bits_per_weight=bits, group=group)
                                   for name, bits, group in (("bf16", 16, 1), ("fp8", 8, 2), ("mxfp4", 4, 4))}
    report["execution_contract"] = {key: config[key] for key in ("dependence", "numeric")}
    report["physical"] = [physical_summary(root, p) for p in config["physical_records"]]
    report["sources"] = [{"path": str(p.relative_to(root)), "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                         for p in (config_path, model_path, root / "src/opentallas/chip_architecture.py",
                                   root / "tools/check_chip_architecture.py")]
    return report


