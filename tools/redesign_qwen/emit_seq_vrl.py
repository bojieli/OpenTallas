#!/usr/bin/env python3
"""qwen-1010/a 2026-10-10: VM-read-latency successors of the stationed TP-sequencer masters (opt-in; released files unchanged).

The TP sequencer (rtl/rom/ot_qwen_tp_seq_w12.sv) captures the all-reduce word one edge after vm_re.  A die master that
stations vm_re (OS) and vm_rq (IS) -- ot_qfd_sp_constants_sequencer_sys, the CLOSED r22kcs ICUT master -- therefore
sends the word of an earlier read (rtl/test/qwen_1010/run_tp_seq_vrl.sh).  This emits

    rtl/qwen_sys/redesign_qwen/ot_qfd_sp_constants_sequencer_sys_v.sv
        ot_qwen_tp_seq_w12_vrl                (split_ctrl.tp_seq_vrl: VRL-edge read, queue sized to the round trip)
        ot_qwen_tp_seq_w12_fs_v               (ot_qwen_tp_seq_w12_fs over the VRL base)
        ot_qfd_sp_constants_sequencer_sys_v   (+ parameter RLY: die relays each way to the VM; VRL = IS + OS + 1 + 2 RLY)

    python3 tools/redesign_qwen/emit_seq_vrl.py [--check]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/redesign_qwen"))
import split_ctrl as S  # noqa: E402

FS = ROOT / "rtl/rom/ot_qwen_tp_seq_w12_fs.sv"
SYS = ROOT / "rtl/qwen_sys/system_20261008/ot_qfd_sp_constants_sequencer_sys.sv"
OUT = ROOT / "rtl/qwen_sys/redesign_qwen/ot_qfd_sp_constants_sequencer_sys_v.sv"


def emit() -> str:
    fs = FS.read_text()
    fs = S.one(fs, "module ot_qwen_tp_seq_w12_fs #(", "module ot_qwen_tp_seq_w12_fs_v #(\n    parameter integer VRL = 1,")
    fs = S.one(fs, "    ot_qwen_tp_seq_w12 #(.ENABLE_AR256", "    ot_qwen_tp_seq_w12_vrl #(.VRL(VRL), .ENABLE_AR256")
    sy = SYS.read_text()
    sy = S.one(sy, "module ot_qfd_sp_constants_sequencer_sys #(",
               "module ot_qfd_sp_constants_sequencer_sys_v #(\n    parameter integer RLY = 0,   // qwen-1010/a: die relays each way to the VM")
    sy = S.one(sy, "    ot_qwen_tp_seq_w12_fs #(.N(D),", "    ot_qwen_tp_seq_w12_fs_v #(.VRL(IS + OS + 1 + 2 * RLY), .N(D),")
    head = ("// GENERATED by tools/redesign_qwen/emit_seq_vrl.py (qwen-1010/a): VM-read-latency successor of the closed\n"
            "// ot_qfd_sp_constants_sequencer_sys (the released files are unchanged).\n")
    return head + S.tp_seq_vrl() + "\n" + fs + "\n" + sy


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = emit()
    if a.check:
        sys.exit(0 if OUT.read_text() == t else 1)
    OUT.write_text(t)
    print(OUT)


if __name__ == "__main__":
    main()
