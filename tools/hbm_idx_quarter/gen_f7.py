#!/usr/bin/env python3
"""HBM-IDXSQ8 10-20: write the wires-only flat IDX quarter ot_hbm_idx_score_quarter_f7 (input of tools/landed_parent/lp.py)."""
import sys
out = sys.argv[1]
L = []
w = L.append
w("`default_nettype none")
w("// HBM d4g IDX QUARTER SCORER, wires-only flat parent f7 (HBM-IDXSQ8 2026-10-20; generated by gen_f7.py, do not edit).")
w("// The input of tools/landed_parent/lp.py for the SAFE PHYSICAL PARENT (owner clock rule 10-20 08:50: every region crossing")
w("// lands in a fixed-latency mesochronous ring). Children: W glue ot_hbm_idx_score_qw_r4s (qw4n RTL, one root), 8 leaves")
w("// ot_hbm_idx_score_leaf_c7 (glue + 4 hard key columns, one root each), E glue ot_hbm_idx_score_qe_r4s (one root).")
w("// Same data path as ot_hbm_idx_score_quarter_wo2 with leaf_c1 -> leaf_c7 and ONE clock / ONE reset port: lp.py gives every")
w("// child its own region clock ck_<r> and reset run. Leaf resets: the parent reset (the regional reset runs replace the")
w("// W glue's relay outputs rst_c0/rst_c1, left open here and in the landed parent: diagnostic copies only).")
w("module ot_hbm_idx_score_quarter_f7(  // die TP = 192 (rank 8 b), non-parameterised")
w(" input wire clk,input wire rst_n,input wire half,")
w(" input wire[7:0]rank,input wire[10:0]first_ord,input wire[11:0]nkeys,")
w(" input wire keep_en,input wire[170:0]keep_bitmap,")
w(" input wire ql_v,input wire[7:0]ql_head,input wire[511:0]ql_codes,input wire[31:0]ql_sc,input wire[15:0]ql_w,")
w(" input wire beat_v,input wire[7:0]beat_index,input wire[4395:0]key_lines,")
w(" output wire[305:0]score,output wire fault")
w(");")
w(" wire rst_c0,rst_c1;")
for e in range(2):
    for c in range(5):
        n = f"{e}{c}"
        w(f" wire qv_{n},kv_{n};wire[567:0]q_{n};wire[3:0]kkv_{n};wire[2175:0]key_{n};wire[29:0]aux_{n};wire[551:0]bus_{n};")
w(" ot_hbm_idx_score_qw_tp192 u_w(.clk(clk),.rst_n(rst_n),.half(half),.rank(rank),.first_ord(first_ord),.nkeys(nkeys),")
w("  .keep_en(keep_en),.keep_bitmap(keep_bitmap),.ql_v(ql_v),.ql_head(ql_head),.ql_codes(ql_codes),.ql_sc(ql_sc),.ql_w(ql_w),")
w("  .beat_v(beat_v),.beat_index(beat_index),.key_lines0(key_lines[2197:0]),.key_lines1(key_lines[4395:2198]),")
w("  .rst_c0(rst_c0),.rst_c1(rst_c1),")
w("  .o_qv0(qv_00),.o_q0(q_00),.o_kv0(kv_00),.o_kkv0(kkv_00),.o_key0(key_00),.o_aux0(aux_00),.o_bus0(bus_00),")
w("  .o_qv1(qv_10),.o_q1(q_10),.o_kv1(kv_10),.o_kkv1(kkv_10),.o_key1(key_10),.o_aux1(aux_10),.o_bus1(bus_10));")
for e in range(2):
    for c in range(4):
        a, b = f"{e}{c}", f"{e}{c+1}"
        w(f" ot_hbm_idx_score_leaf_c7 u_l{e}{c}(.clk(clk),.rst_n(rst_n),.hb(8'd{8*c}),")
        w(f"  .w_qv(qv_{a}),.w_q(q_{a}),.w_kv(kv_{a}),.w_kkv(kkv_{a}),.w_key(key_{a}),.w_aux(aux_{a}),.w_bus(bus_{a}),")
        if c < 3:
            w(f"  .e_qv(qv_{b}),.e_q(q_{b}),.e_kv(kv_{b}),.e_kkv(kkv_{b}),.e_key(key_{b}),.e_aux(aux_{b}),.e_bus(bus_{b}));")
        else:  # last leaf of the row: query / key / keep-valid pass-through ends here (E glue reads valid, aux, sum bus)
            w(f"  .e_qv(qv_{b}),.e_q(),.e_kv(kv_{b}),.e_kkv(),.e_key(),.e_aux(aux_{b}),.e_bus(bus_{b}));")
w(" wire[153:0]s0;wire[151:0]s1;")
w(" ot_hbm_idx_score_qe_r4s u_e(.clk(clk),.rst_n(rst_n),")
w("  .r0_qv(qv_04),.r0_kv(kv_04),.r0_aux(aux_04),.r0_bus(bus_04),")
w("  .r1_qv(qv_14),.r1_kv(kv_14),.r1_aux(aux_14),.r1_bus(bus_14),.score0(s0),.score1(s1),.fault(fault));")
w(" // flat score bus {idx[159:0], val[127:0], kv[7:0], fl[7:0], last0, ev0} (as ot_hbm_idx_score_quarter_wo2)")
w(" assign score={s1[151:72],s0[153:74],s1[71:8],s0[73:10],s1[7:4],s0[9:6],s1[3:0],s0[5:2],s0[1],s0[0]};")
w("endmodule")
w("`default_nettype wire")
open(out, "w").write("\n".join(L) + "\n")
