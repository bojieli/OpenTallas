#!/usr/bin/env python3
"""Pin plans for the S81 HC crootr_f / _r / _w tiles (s81hc-1013): physical/s81_hc_pinplan/crr{f,r,w}_{e,w}.tcl.

v1 of these tiles left every bus as one ordered PPL group at the slot pitch: 20 b/um on one layer (limit 12, target 6;
FLOORPLAN_MARGIN pin_density on all six).  This plan spreads each face's buses over the whole face in proportion to
their bit counts, on-track, alternating M5 / M3 on N / S (M4 only on W / E), and where the 200.88 um W|E face of the
_r / _w tiles cannot hold its 2,164 / 2,173 bits at the target on its one layer, the upper half of the bus turns the
corner onto the adjacent N (r) or S (w) face, next to that corner.  Outlines (= contract slots) are unchanged.
The parent reaches every pin from M6 above the tile, so the face only sets where the endpoint flop sits.

Tracks (ASAP7 make_tracks): M5 x 0.012 + 0.048 k, M3 x 0.009 + 0.036 k, M4 y 0.012 + 0.048 k.  N / S pins keep clear of
the M5 PG stripes of the kit (pdn.tcl: 0.12 wide at 0.300 and 0.492, pitch 5.4) and of their M2-M5 via stacks; every
pin stays >= 2.16 um off the tile corners."""
import sys
from pathlib import Path

W = 276.48
MARGIN = 2.16
NG, NCOL, GS, S_RD, S_RT = 256, 3, 8, 2, 4
NS = NG // GS
NP = (NS + NCOL - 1) // NCOL
FVW, RVW = S_RD + 5, S_RT + 4
YW = NP * GS * 32
O_D = 5 + S_RD * 16 + 20 + 6 + 8 + 32 + 1
FSW, FDW = O_D + S_RD * 512, O_D + max(S_RD * 512, YW)
RDW = S_RT + 24 * S_RT + 8 + 512 * S_RT
WSL = 1 + 14 + 16 + 512
YS = NP * GS * 32          # C = 0 and C = 2 both own NP lanes
PKW = NP * 128


def bits(name, n):
    return [name] if n == 0 else [f"{name}[{i}]" for i in range(n)]


def stripe_free(x):
    r = x % 5.4
    return not (0.18 <= r <= 0.74)


def tracks(layer, lo, hi):
    off, pitch = {"M5": (0.012, 0.048), "M3": (0.009, 0.036), "M4": (0.012, 0.048)}[layer]
    k0 = int((lo - off) / pitch) + 1
    out = []
    k = k0
    while off + pitch * k <= hi:
        x = round(off + pitch * k, 3)
        if layer == "M4" or stripe_free(x):
            out.append(x)
        k += 1
    return out


def spread(names, layers, lo, hi):
    """names in order along [lo, hi], alternating layers, each on its own free track nearest the uniform position"""
    n = len(names)
    per = {L: tracks(L, lo, hi) for L in layers}
    nxt = {L: 0 for L in layers}
    out = []
    for i, nm in enumerate(names):
        L = layers[i % len(layers)]
        t = per[L]
        want = lo + (hi - lo) * (i + 0.5) / n
        j = nxt[L]
        while j + 1 < len(t) and abs(t[j + 1] - want) <= abs(t[j] - want):
            j += 1
        left = (n - i + len(layers) - 1) // len(layers)        # pins of this layer still to place, this one included
        j = min(j, len(t) - left)                              # a PG stripe at the band end: keep a track for each
        if j < nxt[L]:
            raise SystemExit(f"out of {L} tracks in [{lo}, {hi}] at {nm}")
        out.append((nm, L, t[j]))
        nxt[L] = j + 1
    return out


def face_plan(face, groups, H, layers, lo=None, hi=None, mirror=False):
    """groups: [names] in order along the face (e-variant frame); ranges by bit count over [lo, hi].  mirror: the
    w variant = the x mirror, planned in its own frame so every pin is on-track and clear of the (unmirrored) stripes"""
    L = H if face in "WE" else W
    lo = MARGIN if lo is None else lo
    hi = L - MARGIN if hi is None else hi
    if mirror and face in "NS":
        groups, lo, hi = [g[::-1] for g in groups[::-1]], round(W - hi, 3), round(W - lo, 3)
    if mirror and face in "WE":
        face = "E" if face == "W" else "W"
    tot = sum(len(g) for g in groups)
    out, a = [], lo
    for g in groups:
        b = a + (hi - lo) * len(g) / tot
        out += [(face, *p) for p in spread(g, layers, a, b)]
        a = b
    return out


def emit(pins, H, title):
    lines = [f"# {title}", "# generated by tools/s81_suhc/crr_pinplan.py -- do not edit"]
    for face, nm, layer, pos in pins:
        if face in "NS":
            size = " -pin_size {.024 .192}" if layer == "M5" else ""
            lines.append(f"place_pin -pin_name {{{nm}}} -layer {layer} -location {{{pos:.3f} {H if face == 'N' else 0.0:.3f}}}{size} -force_to_die_boundary")
        else:
            lines.append(f"place_pin -pin_name {{{nm}}} -layer M4 -location {{{0.0 if face == 'W' else W:.3f} {pos:.3f}}} -pin_size {{.192 .024}} -force_to_die_boundary")
    return "\n".join(lines) + "\n"


def check(pins, H, name):
    """no two pins on one track of one face / layer; density per face / layer over any 100 um window"""
    seen = set()
    worst = {}
    by = {}
    for face, nm, layer, pos in pins:
        key = (face, layer, pos)
        assert key not in seen, (name, key)
        seen.add(key)
        by.setdefault((face, layer), []).append(pos)
    for k, v in by.items():
        v.sort()
        L = (H if k[0] in "WE" else W)
        win = min(100.0, L)
        j, m = 0, 0
        for i, p in enumerate(v):
            while p - v[j] > win:
                j += 1
            m = max(m, i - j + 1)
        worst[f"{k[0]}/{k[1]}"] = (len(v), round(m / win, 2))
    return worst


def plans(m):
    V = ["M5", "M3"]
    fp = lambda *a, **k: face_plan(*a, mirror=m, **k)
    ck = lambda H: [("W" if m else "E", "sk", "M4", round(0.012 + 0.048 * round((H / 2 - 0.78) / 0.048), 3)),
                    ("W" if m else "E", "srs", "M4", round(0.012 + 0.048 * round((H / 2 + 0.78) / 0.048), 3))]
    # the e variant (C = 2): data on W, clock on E; the w variant (C = 0) is its x mirror
    H = 598.32
    f = (fp("N", [bits("p_req", 0) + bits("p_y", YS)], H, V)
         + fp("S", [bits("ch_rst", 0) + bits("ch_fv", FVW) + bits("ch_fd", FDW)], H, V)
         + fp("W", [bits("f_fv", FVW) + bits("f_fd", FSW)], H, ["M4"], lo=180.0, hi=368.4) + ck(H))
    H = 200.88
    srd = bits("s_rv", RVW) + bits("s_rd", RDW)
    k = len(srd) // 2
    # W: lower half bottom -> top; the upper half continues from the NW corner along N; t_* take the rest of N
    r = (fp("W", [srd[:k]], H, ["M4"])
         + fp("N", [srd[k:], bits("t_v", 0) + bits("t_flt", 0) + bits("t_pk", PKW)], H, V)
         + fp("S", [bits("ch_rv", RVW) + bits("ch_rd", RDW)], H, V) + ck(H))
    sw = bits("s_flt", 0) + bits("s_w", 4 * WSL)
    k = len(sw) // 2
    # W: upper half bottom -> top; the lower half sits on the W half of S, running into the SW corner
    w = (fp("W", [sw[k:]], H, ["M4"])
         + fp("S", [sw[:k][::-1]], H, V, lo=MARGIN, hi=W / 2)
         + fp("N", [bits("p_flt", 0) + bits("p_w", 4 * WSL)], H, V) + ck(H))
    return {"crrf": (f, 598.32), "crrr": (r, 200.88), "crrw": (w, 200.88)}


def ctrn_plan():
    """ot_s81_hc_ctrn (576.72 x 12.96 return-out sliver, one flop per bit): rvm/rdm[i] on S exactly below rv_out/rd_out[i]
    on N, same layer and track, uniform over the full width.  v1-v3 left both faces to PPL 32-pin groups, which landed
    anywhere on the face (reach 107 um): 7,300 horizontally overflowed gcells and no vertical one at 5_1_grt (v3
    GRT-0116).  Bit-aligned, every bit is a vertical feed-through and the tile has no horizontal bus demand."""
    global W
    keep, W = W, 576.72
    H = 12.96
    n = [f"rv_out[{i}]" for i in range(S_RT + 4)] + bits("rd_out", RDW)
    s_ = [f"rvm[{i}]" for i in range(S_RT + 4)] + bits("rdm", RDW)
    top = face_plan("N", [n], H, ["M5", "M3"])
    pins = top + [("S", b, L, x) for b, (_, _, L, x) in zip(s_, top)]
    pins += [("W", "clk", "M4", 6.012), ("W", "rst_in", "M4", 7.02)]
    txt = emit(pins, H, "S81 HC ctrn: bit-aligned N/S feed-through pin plan (S pin of bit i under its N pin), M5+M3")
    chk = check(pins, H, "ctrn")
    W = keep
    return txt, chk, len(pins)


def ccf_plan(lef="physical/asap7_memory_macros_v2/ot_sram_1r1w_64x512_m1_r2c2/ot_sram_1r1w_64x512_m1_r2c2.lef"):
    """ot_s81_hc_ccf (410.4 x 542.16, five 64x512 y-FIFO macros in one column at x 118.8 .. 290.1): v1-v3 left N / S to
    PPL over the full faces on M5, also above the macro column; every one of the 10.5k-13.2k GRT markers of v3 lay over
    or at the edges of the column (x 100-300) and none in the two ~115 um channels, because ~3,700 signals cross every
    horizontal cut and only M5 passes over the macros (M1-M4 OBS).  All macro pins are on the macro W / E edges (M4):
    rd_out[511:0] and wd_in[265:0] on one edge, wd_in[511:266] on the other.  v4: macros 1 and 3 are mirrored (MY), so
    the read buses leave 3 west / 2 east, and NO pin sits over the column: each bit's N / S pin is over the channel on
    the side of its macro pin, in slice bands of one order on both faces (a slice's n_y bits, the fd_i bits its ch_fd
    flops mux with, and its ch_fd bits share a band), M5 + M3."""
    import re
    global W
    keep, W = W, 410.4
    H = 542.16
    t = Path(lef).read_text()
    west = set()                                  # wd_in bits on the R0 west edge (with rd_out)
    for nm, body in re.findall(r"PIN wd_in\[(\d+)\]\n(.*?)END wd_in", t, re.S):
        if float(re.search(r"RECT ([\d.]+)", body)[1]) < 1.0:
            west.add(int(nm))
    assert len(west) == 266, len(west)
    YS1, NF = 2560, 5
    rd_side = lambda f: "W" if f % 2 == 0 else "E"      # R0: read bus west; MY (slices 1, 3): east
    oth = lambda c: "E" if c == "W" else "W"
    def n_group(f, c):
        """N pins of slice f that belong over channel c, in bit order"""
        g = []
        for i in range(512):
            if c == rd_side(f) and f < 2:
                g.append(f"fd_i[{O_D + 512 * f + i}]")
            if (c == rd_side(f)) == (i in west):
                g.append(f"n_y[{512 * f + i}]")
        return g
    s_group = lambda f: [f"ch_fd[{O_D + 512 * f + i}]" for i in range(512)]
    ctl_n = ["n_yacc", "yfl"] + bits("fv_i", FVW) + [f"fd_i[{i}]" for i in range(O_D)]
    ctl_s = ["ch_rst"] + bits("ch_fv", FVW) + [f"ch_fd[{i}]" for i in range(O_D)] + [f"ch_fd[{i}]" for i in range(O_D + YS1, FDW)]
    # bands from the tile edge towards the column; the W-channel order is mirrored into the E channel
    order = {"W": [0, 2, 4, 1, 3], "E": [1, 3, 0, 2, 4]}
    chan = {"W": (MARGIN, 113.2), "E": (295.7, W - MARGIN)}   # clear of the 5.4 um macro halo
    # v5 (v4 GRT-0116: all 1,040 markers at the S face, y 2-8, x 0-120 = the W channel, V capacity 21 / usage 22-24 per
    # gcell: 3 x 512 ch_fd pins at 13.8 /um with their out-hold chains behind them; the E channel at 12.4 /um and the N
    # face at 16 /um of plain inputs had none).  The S pins of each side now also use 47 um of the 30 um band under the
    # macro column: W side 9.7 /um, E side 8.8 /um; ~450 nets a side run laterally under the column edge (H band ~1,000
    # derated tracks).  The N face is unchanged.
    schan = {"W": (MARGIN, 160.0), "E": (250.4, W - MARGIN)}
    pins = []
    for c in "WE":
        ng = [n_group(f, c) for f in order[c]]
        sg = [s_group(f) for f in order[c] if rd_side(f) == c]
        if c == "E":
            ng, sg = [ctl_n] + ng[::-1], [ctl_s] + sg[::-1]
            ng, sg = ng[::-1], sg[::-1]           # E channel: column side first in x, control at the tile edge
        lo, hi = chan[c]
        pins += face_plan("N", ng, H, ["M5", "M3"], lo=lo, hi=hi) + face_plan("S", sg, H, ["M5", "M3"], lo=schan[c][0], hi=schan[c][1])
    pins += [("W", "sk", "M4", round(0.012 + 0.048 * round((H / 2 - 0.78) / 0.048), 3)),
             ("W", "srs", "M4", round(0.012 + 0.048 * round((H / 2 + 0.78) / 0.048), 3))]
    names = [p[1] for p in pins]
    want = (set(ctl_n) | set(ctl_s) | {f"n_y[{i}]" for i in range(YS1)} | {f"fd_i[{i}]" for i in range(FSW)}
            | {f"ch_fd[{i}]" for i in range(FDW)} | {"sk", "srs"})
    assert len(names) == len(set(names)) and set(names) == want, (len(names), len(want), sorted(want ^ set(names))[:6])
    txt = emit(pins, H, "S81 HC ccf: N pins channel-only, S pins over the channels + 47 um under the macro column (v5), slice bands, M5+M3")
    chk = check(pins, H, "ccf")
    W = keep
    return txt, chk, len(pins)


def cryys_plan():
    """ot_s81_hc_cryys (32.4 x 300.24 y slice leaf, r8): y_s[i] on N exactly above p_y[i] on S, same layer and track,
    M5 + M3 alternating over x 2.16 .. 27.9 (256 b, 5.0 b/um/layer); sk / srs / yacc / p_req / p_flt on S at the E end
    (M5).  Every bit is a vertical feed-through through its own pipeline (yp -> yp2 -> store -> rq -> b -> p_y): the leaf
    has no horizontal bus."""
    global W
    keep, W = W, 32.4
    H = 300.24
    top = face_plan("N", [bits("y_s", 256)], H, ["M5", "M3"], lo=MARGIN, hi=27.9)
    pins = top + [("S", f"p_y[{i}]", L, x) for i, (_, _, L, x) in enumerate(top)]
    ctl = tracks("M5", 28.2, W - MARGIN)
    pins += [("S", nm, "M5", ctl[4 * i]) for i, nm in enumerate(["sk", "srs", "yacc", "p_req", "p_flt"])]
    names = [p[1] for p in pins]
    assert len(names) == len(set(names)) == 2 * 256 + 5
    txt = emit(pins, H, "S81 HC cryys: bit-aligned N/S feed-through pin plan (p_y[i] under y_s[i]), M5+M3; control on S at the E end")
    chk = check(pins, H, "cryys")
    W = keep
    return txt, chk, len(pins)


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "physical/s81_hc_pinplan")
    for side, mirror in (("e", False), ("w", True)):
        for nm, (pins, H) in plans(mirror).items():
            print(nm, side, len(pins), check(pins, H, nm))
            (out / f"{nm}_{side}.tcl").write_text(emit(pins, H, f"S81 HC {nm}_{side}: full-face, by-bit-count, two-layer pin plan (b/um/layer <= 6)"))


    txt, chk, n = ctrn_plan()
    print("ctrn", n, chk)
    (out / "ctrn.tcl").write_text(txt)
    txt, chk, n = cryys_plan()
    print("cryys", n, chk)
    (out / "cryys.tcl").write_text(txt)
    txt, chk, n = ccf_plan()
    print("ccf", n, chk)
    (out / "ccf.tcl").write_text(txt)


if __name__ == "__main__":
    main()
