#!/usr/bin/env python3
"""Generate the current CAL7/NARROW=1 collective candidate with real clock pins.

The old ABI remains the reference. Six additional parent inputs independently
deliver the actual three ROM and three output clocks; none is tied inside the
candidate. Normal datapath edges and the current compiler image are unchanged.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError("source anchor changed: " + old)
    return text.replace(old, new)


def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    source = ROOT / "rtl/dsrom_sys/s81_static_collective"
    sources = {}
    for old, new in [("s81_static_collective_slab", "s81_static_collective_slab7"),
                     ("dsfd_sp_collective_static_c", "dsfd_sp_collective_static_c7")]:
        src = source / (old + ".sv")
        text = src.read_text()
        sources[str(src.relative_to(ROOT))] = hashlib.sha256(src.read_bytes()).hexdigest()
        text = once(text, "module " + old + " #(", "module " + new + " #(")
        text = once(text, "parameter integer CYCLES=1", "parameter integer CYCLES=4096")
        text = once(text, " input wire[4:0]ck_control,", " input wire[2:0]ck_calendar_rom,ck_calendar_outputs,\n input wire[4:0]ck_control,")
        if old == "s81_static_collective_slab":
            text = once(text, "parameter integer VMB_NARROW=0", "parameter integer VMB_NARROW=1")
            text = once(text, " wire[2:0]ck_cal_out={3{ck_control[0]}};", " wire[2:0]ck_cal_out=ck_calendar_outputs;")
            text = once(text, ".clk_rom({3{ck_control[0]}})", ".clk_rom(ck_calendar_rom)")
        else:
            text = once(text, " s81_static_collective_slab #(.ROM_FILE(ROM_FILE),.CYCLES(CYCLES)) slab(",
                        " s81_static_collective_slab7 #(.ROM_FILE(ROM_FILE),.CYCLES(CYCLES),.VMB_PINCAP(1),.VMB_NARROW(1)) slab(\n .ck_calendar_rom(ck_calendar_rom),.ck_calendar_outputs(ck_calendar_outputs),")
        (out / (new + ".sv")).write_text("// Candidate generated by build_slab7.py; source SHA256 " + sources[str(src.relative_to(ROOT))] + "\n" + text)
    tb = ROOT / "tools/s81_static_collective/tb_s81_static_collective_slab.sv"
    text = tb.read_text()
    sources[str(tb.relative_to(ROOT))] = hashlib.sha256(tb.read_bytes()).hexdigest()
    text = once(text, " parameter integer MUT=0;", " parameter integer MUT=0;\n parameter integer CALENDAR_CLOCK_MUT=0;")
    text = once(text, " s81_static_collective_slab #(", " s81_static_collective_slab7 #(")
    text = once(text, ".CYCLES(2141)", ".CYCLES(4096)")
    text = once(text, " .ck_control({5{clk}}),", ''' .ck_calendar_rom({3{clk}} & ((CALENDAR_CLOCK_MUT==1 && $time>400000) ? 3'b110:3'b111)),
 .ck_calendar_outputs({3{clk}} & ((CALENDAR_CLOCK_MUT==2 && $time>400000) ? 3'b110:3'b111)),
 .ck_control({5{clk}}),''')
    (out / tb.name).write_text(text)
    (out / "source_manifest.json").write_text(json.dumps(dict(source_sha256=sources,
        additional_parent_clock_pins=["ck_calendar_rom[2:0]", "ck_calendar_outputs[2:0]"],
        delivered_clock_entry_bits=35, calendar_params=dict(CYCLES=4096), vm_boundary_params=dict(MUT=0, PINCAP=1, NARROW=1),
        normal_edges_added=0, adopted=False, physical_qualified=False,
        note="Actual CAL7 and VMB b9 shapes. Other collective leaves, physical clock delivery, placement, production FIELD/calendar and native die proof remain required."), indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    generate(parser.parse_args().out)
