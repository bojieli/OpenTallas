#!/usr/bin/env python3
"""Emit the explicit seven-entry calendar composition, preserving the old ABI.

Six extra delivered clock pins are real parent inputs. The source graph and die
must bind them; the component bench supplies ideal coincident related clocks.
Generated bodies preserve the actual datapath and its compiler calendar.
"""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]

def replace_once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new, 1)

def generate(out, read_pipe=0):
    out.mkdir(parents=True, exist_ok=True)
    source = ROOT / 'rtl/dsrom_sys/s81_static_collective'
    paths = {}
    for old, new in [('s81_static_collective_slab', 's81_static_collective_slab7'),
                     ('dsfd_sp_collective_static_c', 'dsfd_sp_collective_static_c7')]:
        src = source / (old + '.sv'); text = src.read_text()
        text = replace_once(text, 'module ' + old + ' #(', 'module ' + new + ' #(')
        text = replace_once(text, ' input wire[4:0]ck_control,',
                            ' input wire[2:0]ck_calendar_rom,ck_calendar_outputs,\n input wire[4:0]ck_control,')
        if old == 's81_static_collective_slab':
            text = replace_once(text, ' s81_static_calendar_controller #(', ' s81_static_calendar_controller7 #(')
            text = replace_once(text, ' .clk(ck_control[0]),.rst_n(rn_control[0]),',
                                ' .clk_rom(ck_calendar_rom),.clk_outputs(ck_calendar_outputs),\n .clk(ck_control[0]),.rst_n(rn_control[0]),')
        else:
            text = replace_once(text, ' s81_static_collective_slab #(', ' s81_static_collective_slab7 #(')
            text = replace_once(text, ' .ck_control(ck_control),',
                                ' .ck_calendar_rom(ck_calendar_rom),.ck_calendar_outputs(ck_calendar_outputs),\n .ck_control(ck_control),')
        dst = out / (new + '.sv')
        dst.write_text('// Generated by build_slab7.py; base SHA256 ' + hashlib.sha256(src.read_bytes()).hexdigest() + '\n' + text)
        paths[str(src.relative_to(ROOT))] = hashlib.sha256(src.read_bytes()).hexdigest()
    tb = ROOT / 'tools/s81_static_collective/tb_s81_static_collective_slab.sv'
    text = tb.read_text()
    text = replace_once(text, ' parameter integer MUT=0;', ' parameter integer MUT=0;\n parameter integer CALENDAR_CLOCK_MUT=0;')
    text = replace_once(text, ' s81_static_collective_slab #(', ' s81_static_collective_slab7 #(')
    text = replace_once(text, ' .ck_control({5{clk}}),',
                        ' .ck_calendar_rom({3{clk}} & ((CALENDAR_CLOCK_MUT==1 && $time>400000) ? 3\'b110:3\'b111)),\n .ck_calendar_outputs({3{clk}} & ((CALENDAR_CLOCK_MUT==2 && $time>400000) ? 3\'b110:3\'b111)),\n .ck_control({5{clk}}),')
    if read_pipe==4:
        text=replace_once(text,' dsfd_sp_vm vm(', ' dsfd_sp_vm #(.READ_PIPE(4),.CAP_PIPE(2)) vm(')
        text=replace_once(text,'e<498+14','e<498+18')
        text=replace_once(text,'e>=12&&e<510','e>=16&&e<514')
        text=replace_once(text,'j=e-12','j=e-16')
    (out / 'tb_s81_static_collective_slab.sv').write_text(text)
    paths[str(tb.relative_to(ROOT))] = hashlib.sha256(tb.read_bytes()).hexdigest()
    (out / 'source_manifest.json').write_text(json.dumps(dict(source_sha256=paths,
        added_delivered_clock_pins=['ck_calendar_rom[0..2]', 'ck_calendar_outputs[0..2]'],
        normal_edges_added=0, initialization_extra_rom_edges=1,vm_parameters=dict(READ_PIPE=read_pipe,CAP_PIPE=2 if read_pipe==4 else 0),
        qualification='component candidate; die ABI, phi-R, placement and native route remain open'), indent=2)+'\n')

if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);p.add_argument('--read-pipe',type=int,choices=[0,4],default=0);a=p.parse_args();generate(a.out,a.read_pipe)
