#!/usr/bin/env python3
"""Split existing calendar registers onto seven real clock inputs, without new data stages.

The production base is authoritative; regenerate this structural candidate after
any base change. Related clocks must be delivered at each native phi-R entry.
This source generator does not qualify the clocks, die ABI, or production image.
"""
from pathlib import Path
import hashlib,json,re
from controller_image import FIELDS
ROOT=Path(__file__).resolve().parents[2]
def generate():
    base=ROOT/'rtl/dsrom_sys/s81_static_collective/s81_static_calendar_controller.sv'
    text=base.read_text();digest=hashlib.sha256(base.read_bytes()).hexdigest()
    text=text.replace('module s81_static_calendar_controller #(', 'module s81_static_calendar_controller7 #(',1)
    text=text.replace('input wire clk,rst_n,input wire [84:0] c_cmd,',
                      'input wire clk,rst_n,input wire [2:0] clk_rom,clk_outputs, input wire [84:0] c_cmd,',1)
    assert text.count('u_rom(.clk(clk),')==1
    text=text.replace('u_rom(.clk(clk),','u_rom(.clk(clk_rom[bank]),',1)
    groups=[[],[],[]];offset=0
    for name,width in FIELDS:
        group=min(2,offset//156);offset+=width
        matches=re.findall(r'^   '+name+r'<=enabled[^\n]*$',text,re.M)
        assert len(matches)==1,(name,matches)
        groups[group].append((name,width,matches[0].strip()))
        text=text.replace(matches[0]+'\n','',1)
        pattern=r'(?<![A-Za-z0-9_])'+name+r'<=0;'
        assert len(re.findall(pattern,text))==1,name
        text=re.sub(pattern,'',text,count=1)
    blocks=[]
    for group,fields in enumerate(groups):
        blocks.append(' always @(posedge clk_outputs['+str(group)+'] or negedge rst_n)begin\n'+
                      '  if(!rst_n)begin '+''.join(name+'<=0;' for name,_,_ in fields)+'end\n'+
                      '  else begin\n'+''.join('   '+line+'\n' for _,_,line in fields)+'  end\n end\n')
    assert text.count('endmodule')==1
    text=text.replace('endmodule',''.join(blocks)+'endmodule')
    text='// Generated by tools/s81_static_collective/build_calendar7.py; base SHA256 '+digest+'\n'+text
    out=ROOT/'rtl/dsrom_sys/s81_static_collective/s81_static_calendar_controller7.sv'
    out.write_text(text)
    census=dict(base_sha256=digest,source=str(out.relative_to(ROOT)),source_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),
                clocks=['clk']+['clk_rom['+str(i)+']' for i in range(3)]+['clk_outputs['+str(i)+']' for i in range(3)],
                output_groups=[dict(clock='clk_outputs['+str(i)+']',bits=sum(w for _,w,_ in fields),ports=[n for n,_,_ in fields]) for i,fields in enumerate(groups)],
                added_data_edges=0,added_data_registers=0,rom_macros=3,qualification=False)
    return census
if __name__=='__main__':print(json.dumps(generate(),indent=2))
