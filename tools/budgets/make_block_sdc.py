#!/usr/bin/env python3
"""Block IO SDC from the master's BUDGET SHEET (CLAUDE BUDGETS, 2026-10-06).  Replaces assumed / copied insertions.

  make_block_sdc.py sdc   <master> [--sheets DIR] [--clock core_clk] [--mode route|signoff] --out block_io.sdc
  make_block_sdc.py ff    <master> [--sheets DIR] [--clock core_clk] --out block_io_ff.sdc      FF hold post-SDC
  make_block_sdc.py check <master> [--sheets DIR] --calib calib.json                            closure-loop CHECK

sdc (read after the block's base SDC that creates the clock on its clock port):
  * vclk: the die-side launch / capture clock.  The die clock plan aligns the flops of every block of a region to one
    instant (each block's clock pin gets its own entry target = region flop target - its internal insertion), so vclk
    carries the block's OWN sheet insertion (internal_insertion.ss) -- not the measured one: a measured value that
    deviates from the sheet is a CHECK failure, never a silent re-calibration.
  * per port, the sheet's SS budgets: input delay = clk->Q + driver + 1.135 ps/um x L + skew term, output delay =
    1.135 ps/um x L + receiver + setup + skew term (skew term: region-measured intra, 150 ps inter-region / meso, 0 on
    forwarded-clock hops); min delays = the FF hold model (clk->Q FF 32.2 + 0.112 ps/um x L; outputs -(15 - 0.112 L)).
  * ports of another frequency domain (block-internal CDC; the sheet's period_ps / clock_domain) are timed against
    vclk unless --domain-clock PERIOD=CLOCK names the block's real clock of that domain.
  * route mode: setup uncertainty 60 + 63 (route over-constrained to ~770 ps, MARGIN-FIRST); signoff: 60.  Hold 25.
  * route mode puts the sheet latency on the real clock too (ideal until CTS); signoff mode puts it on vclk only and
    re-asserts set_propagated_clock on the real clock (a post-SDC latency on it made sign-off ideal-clock: fixed 2026-10-07).
  * CDC ports (another frequency domain): max delay = faster period - 123 ps, datapath only; hold false.
  * async reset pins: false path (synchronised in the block); the reset-release multicycle of make_io_vclk.sh.
ff:  the corner-true FF hold post-SDC (make_io_vclk_ff.sh convention, RULE H1): outputs held against vclk at the sheet FF
     insertion + the hold IO uncertainty (latest capture); inputs launch at vclki at the sheet FF insertion, 25 ps.
check: |CK_SS_MEAN - sheet ss| and CK_SS_MEAN - target_ss against the sheet tolerance; prints one BUDGET_CHECK line
     and exits 0 (within) / 5 (deviation: the die plan must be re-planned for this block, or the block's tree fixed).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHEETS = ROOT / 'results/rtl/budgets_20261006/sheets'
RESET_NAMES = {'rst', 'rst_n', 'rs', 'rss', 'rsv', 'por', 'por_n'}
ROUTE_EXTRA_PS = 63.0


def load(master, sheets):
    p = Path(sheets) / f'{master}.json'
    if not p.exists():
        raise SystemExit(f'no budget sheet for {master} ({p})')
    return json.loads(p.read_text())


def ports_of(name):
    return f'[get_ports -quiet {{{name} {name}[*]}}]'


def sdc(sh, clock, mode, domain_clocks=None):
    ins = sh['clock']['internal_insertion']
    L = ins['ss']
    unc = sh['skew']['setup_uncertainty_ps'] + (ROUTE_EXTRA_PS if mode == 'route' else 0.0)
    clkports = set(sh['clock']['ports'])
    out = [f"# generated by tools/budgets/make_block_sdc.py sdc {sh['master']} --mode {mode} from its budget sheet",
           f"# vclk at the sheet insertion {L} ps ({ins['grade']}: {ins['source']}); target {ins['target_ss']} ps; "
           f"die entry target SS {sh['clock'].get('entry_target_ss_ps')}",
           f'create_clock -name vclk -period [get_property [get_clocks {clock}] period]',
           f'set_clock_uncertainty -setup {unc:g} [get_clocks {{{clock} vclk}}]',
           f'set_clock_uncertainty -hold {sh["skew"]["hold_uncertainty_ps"]:g} [get_clocks {{{clock} vclk}}]',
           # route: the real clock carries the same ideal latency until CTS propagates it (pre-CTS IO parity).
           # signoff: vclk ONLY.  This file is a post-SDC read after set_propagated_clock (corner_sta.py): a
           # set_clock_latency on the real clock turns it back to IDEAL, so sign-off timed every flop at the sheet SS
           # insertion in both corners (hfd_svc_SE_s6 41d574827: FF -135.15 = core_clk ideal 558 vs the FF IO model
           # launched at the FF max insertion 408; the clock tree's own skew was not timed at all).
           (f'set_clock_latency {L:g} [get_clocks {{{clock} vclk}}]' if mode == 'route'
            else f'set_clock_latency {L:g} [get_clocks vclk]'),
           'set ot_in [all_inputs -no_clocks]',
           f'unset_input_delay -clock {clock} $ot_in',
           f'unset_output_delay -clock {clock} [all_outputs]']
    extra_clocks = {}
    for p in sh['interfaces']:
        name = p['port']
        if name in clkports:
            continue
        if name in RESET_NAMES:
            out.append(f'set_false_path -from {ports_of(name)}')
            continue
        tgt = ports_of(name)
        if p['timing'] == 'cdc':
            out.append(f"# {name}: CDC ({p.get('note', '')})")
            if p['dir'] == 'input':
                out += [f"set_max_delay -ignore_clock_latency {p['cdc_max_delay_ps']:g} -from {tgt}",
                        f"set_false_path -hold -from {tgt}"]
            else:
                out += [f"set_max_delay -ignore_clock_latency {p['cdc_max_delay_ps']:g} -to {tgt}",
                        f"set_false_path -hold -to {tgt}"]
            continue
        if p['timing'] != 'sync':
            out.append(f"# {name}: {p['timing']} -- default 0.2 T budget")
            cmd = 'set_input_delay' if p['dir'] == 'input' else 'set_output_delay'
            out += [f'{cmd} [expr {{[get_property [get_clocks {clock}] period] * 0.2 + 150}}] -clock vclk {tgt}',
                    f'{cmd} -min 0 -clock vclk {tgt}']
            continue
        vc = 'vclk'
        dom = next((v for k, v in (domain_clocks or {}).items() if abs(float(k) - p['period_ps']) < 1.0), None)
        if dom:
            vc = extra_clocks.setdefault(dom, f'vclk_{dom}')
        note = f"# {name} {p['dir']} {p['bits']}b: L {p['length_um']} um ({p['length_basis']}), {p['skew_class']} skew {p['skew_ps']:g}"
        if p.get('feasible') is False:
            note += (f" -- INFEASIBLE AS PLANNED: budget assumes {p['stages_needed']} stages "
                     f"({p['segment_after_stages_um']} um segments); the floorplan must add them")
        if p['dir'] == 'input':
            out += [note, f"set_input_delay {p['input_delay_ss_ps']:g} -clock {vc} {tgt}",
                    f"set_input_delay -min {p['input_min_delay_ff_ps']:g} -clock {vc} {tgt}"]
        else:
            out += [note, f"set_output_delay {p['output_delay_ss_ps']:g} -clock {vc} {tgt}",
                    f"set_output_delay -min {-p['output_min_delay_ff_ps']:g} -clock {vc} {tgt}"]
    hdr = []
    for dom, vc in extra_clocks.items():
        hdr += [f'create_clock -name {vc} -period [get_property [get_clocks {dom}] period]',
                f'set_clock_uncertainty -setup {unc:g} [get_clocks {vc}]',
                f'set_clock_uncertainty -hold {sh["skew"]["hold_uncertainty_ps"]:g} [get_clocks {vc}]',
                f'set_clock_latency {L:g} [get_clocks {vc}]']
    out = out[:9] + hdr + out[9:]
    out += ['# reset release (rst_mcp2, as make_io_vclk.sh)', 'set ot_rst {}',
            'foreach ot_c [get_cells *] { if {[string match {rst_s\\[1\\]*} [get_full_name $ot_c]]} { lappend ot_rst $ot_c } }',
            'if {[llength $ot_rst]} { set_multicycle_path -setup 2 -from $ot_rst; set_multicycle_path -hold 1 -from $ot_rst }']
    if mode == 'signoff':
        out += ['# sign-off times the routed clock tree: keep the real clock propagated after this post-SDC',
                f'set_propagated_clock [get_clocks {{{clock}}}]']
    return '\n'.join(out) + '\n'


def sdc_ff(sh, clock):
    ins = sh['clock']['internal_insertion']
    lmin, lmax = ins.get('ff_min') or ins['ff'], ins.get('ff_max') or ins['ff']
    h = sh['skew']['hold_io_ps']
    h0 = sh['skew'].get('hold_uncertainty_ps', 25)
    # RULE H1 (h1-verify 2026-10-08): the sender carries the link hold term once, at the latest capture (vclk at the sheet
    # FF insertion + h); the receiver launches at the nominal FF insertion with the plain hold uncertainty h0.  (Was vclk at the
    # FF min / vclki at the FF max, h on both: both optimistic extremes and h counted twice.)
    out = [f"# generated by tools/budgets/make_block_sdc.py ff {sh['master']}: FF hold sign-off post-SDC (sheet insertion "
           f"FF min {lmin} / max {lmax}, {h:g} ps hold IO uncertainty)",
           f'set_clock_latency {ins["ff"]:g} [get_clocks vclk]',
           f'create_clock -name vclki -period [get_property [get_clocks {clock}] period]',
           f'set_clock_latency {ins["ff"]:g} [get_clocks vclki]']
    for p in sh['interfaces']:
        if p['timing'] != 'sync' or p['dir'] != 'input' or p['port'] in RESET_NAMES:
            continue
        t = ports_of(p['port'])
        out += [f'unset_input_delay -clock vclk {t}', f"set_input_delay {p['input_delay_ss_ps']:g} -clock vclki {t}",
                f"set_input_delay -min {p['input_min_delay_ff_ps']:g} -clock vclki {t}"]
    out += [f'set_clock_uncertainty -hold {h0:g} -from [get_clocks vclki] -to [get_clocks {clock}]',
            f'set_clock_uncertainty -hold {h:g} -from [get_clocks {clock}] -to [get_clocks vclk]']
    return '\n'.join(out) + '\n'


def check(sh, calib):
    c = json.loads(Path(calib).read_text())
    env = c.get('env', c)
    m = float(env['CK_SS_MEAN'])
    ins = sh['clock']['internal_insertion']
    tol = ins['tolerance_ps']
    dev_sheet = m - ins['ss']
    dev_target = m - ins['target_ss']
    ok = abs(dev_sheet) <= tol and dev_target <= tol
    why = []
    if abs(dev_sheet) > tol:
        why.append(f'measured {m:g} vs sheet {ins["ss"]:g} ({ins["grade"]}) differs by {dev_sheet:+.0f} > {tol:g}: the die '
                   'entry target of this block must be re-planned (or the block tree fixed)')
    if dev_target > tol:
        why.append(f'measured {m:g} exceeds the insertion TARGET {ins["target_ss"]:g} by {dev_target:+.0f} > {tol:g}: '
                   'cap the block clock depth (smaller block / pin-near clock entry)')
    line = dict(master=sh['master'], measured_ss=m, sheet_ss=ins['ss'], target_ss=ins['target_ss'], tolerance_ps=tol,
                ok=ok, reasons=why)
    print('BUDGET_CHECK ' + json.dumps(line))
    return 0 if ok else 5


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('mode', choices=['sdc', 'ff', 'check'])
    ap.add_argument('master')
    ap.add_argument('--sheets', default=str(SHEETS))
    ap.add_argument('--clock', default='core_clk')
    ap.add_argument('--route-mode', dest='rmode', default='route', choices=['route', 'signoff'])
    ap.add_argument('--domain-clock', action='append', default=[],
                    help='PERIOD_PS=CLOCK: time the ports of that period against a virtual copy of the block clock '
                         'CLOCK (defined by the base SDC); without it every port is timed against vclk at the main '
                         'clock period (the budgets are period-independent delays, so this is the stricter choice)')
    ap.add_argument('--calib')
    ap.add_argument('--out')
    a = ap.parse_args()
    sh = load(a.master, a.sheets)
    if a.mode == 'check':
        sys.exit(check(sh, a.calib))
    text = sdc(sh, a.clock, a.rmode, dict(x.split('=', 1) for x in a.domain_clock)) if a.mode == 'sdc' else sdc_ff(sh, a.clock)
    if a.out:
        Path(a.out).write_text(text)
        print(a.out)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
