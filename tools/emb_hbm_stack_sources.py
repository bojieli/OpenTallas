#!/usr/bin/env python3
"""Compose actual qualified leaf interfaces; no sector/descriptor aliases."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate():
    ports=['input wire clk,rst_n,hclk,hrst_n,hub_ck',
           'input wire [527:0] hub_i, output wire [527:0] hub_o',
           'input wire [524:0] kv_class_i, output wire [524:0] kv_class_o',
           'input wire [31:0] native_cmd_v, input wire [1023:0] native_cmd',
           'input wire [95:0] native_read_credit, output wire [31:0] native_cmd_credit',
           'input wire [31:0] phy_r_v, input wire [9215:0] phy_r_d',
           'output wire [9215:0] phy_wd',
           'output wire [31:0] row_v, output wire [95:0] row_op',
           'output wire [159:0] row_bank, output wire [607:0] row_row',
           'output wire [31:0] col_v,col_we,col_sr,busy',
           'output wire [159:0] col_bank,col_col',
           'output wire [31:0] kv_v, output wire [9215:0] kv_d',
           'output wire [31:0] fault_core,fault_hbm',
           'output wire fault_engine,fault_link, output wire [7:0] fault_code',
           'output wire [31:0] ce_cnt,ue_info']
    s='''// Generated by tools/emb_hbm_stack_sources.py.
// Qualified external native cmd32/readcredit3 and protected PHY288 providers.
// KV class525 is an independent qualified transport, never an alias of raw KV288.
// Source composition only: physical PC stations/row arbitration/PHY provider are
// still open. Direct interleaf wires are not a routed die or a latency claim.
module ot_qfd_emb_stack_bus #(parameter integer ENABLE=0, STK=0, PHASE=0,
 SQD=4,PFD=4,TXQ=4,OCR=4,S_STARVE=8,ROW0=24427,TWIN=0,TWIN_ROFF=0)(
 '''+',\n '.join(ports)+'\n);\n'
    s+=' wire [524:0] emb_to_far,far_to_emb;\n wire [9215:0] emb_cmd; wire [8319:0] emb_ret;\n'
    s+=' ot_qfd_emb_strip_bus #(.ENABLE(ENABLE),.STK(STK),.SQD(SQD),.PFD(PFD),.TXQ(TXQ),.OCR(OCR),.ROW0(ROW0),.TWIN(TWIN),.TWIN_ROFF(TWIN_ROFF)) engine(\n .clk(clk),.rst_n(rst_n),.link_i(far_to_emb),.link_o(emb_to_far),\n'
    s+=',\n'.join(f' .cmd{p}(emb_cmd[{p}*288+:288]),.ret{p}(emb_ret[{p}*260+:260])' for p in range(32))
    s+=',\n .fault(fault_engine),.fault_code(fault_code),.ce_cnt(ce_cnt),.ue_info(ue_info));\n'
    s+=' ot_qfd_link_far_bus #(.ENABLE(ENABLE),.ECR(OCR),.TQ(TXQ)) link_endpoint(.ck(hub_ck),.lclk(clk),.rst_n(rst_n),.hub_i(hub_i),.hub_o(hub_o),.emb_i(emb_to_far),.emb_o(far_to_emb),.kv_i(kv_class_i),.kv_o(kv_class_o),.fault(fault_link));\n'
    s+=' genvar p; generate for(p=0;p<32;p=p+1) begin: pcs\n ot_qfd_emb_pc_bus #(.ENABLE(ENABLE),.PC(p),.PHASE(PHASE),.SQD(SQD),.S_STARVE(S_STARVE),.TWIN(TWIN),.TWIN_ROFF(TWIN_ROFF)) pc(\n'
    mappings={'clk':'clk','rst_n':'rst_n','hclk':'hclk','hrst_n':'hrst_n',
              'cmd_v':'native_cmd_v[p]','cmd':'native_cmd[p*32+:32]',
              'read_credit':'native_read_credit[p*3+:3]','cmd_credit':'native_cmd_credit[p]',
              'emb_cmd':'emb_cmd[p*288+:288]','emb_ret':'emb_ret[p*260+:260]',
              'r_v':'phy_r_v[p]','r_d':'phy_r_d[p*288+:288]','wd':'phy_wd[p*288+:288]'}
    for n,w in [('row_v',1),('row_op',3),('row_bank',5),('row_row',19),('col_v',1),('col_we',1),('col_sr',1),('col_bank',5),('col_col',5),('busy',1),('kv_v',1),('kv_d',288),('fault_core',1),('fault_hbm',1)]:
        mappings[n]=f'{n}[p]' if w==1 else f'{n}[p*{w}+:{w}]'
    s+=',\n'.join(f' .{n}({v})' for n,v in mappings.items())+'\n );\n end endgenerate\nendmodule\n'
    (ROOT/'rtl/qwen_sys/emb_hbm_20261008/ot_qfd_emb_stack_bus.sv').write_text(s)
if __name__=='__main__':generate()
