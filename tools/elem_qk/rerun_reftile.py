#!/usr/bin/env python3
"""ELEM-QK 10-24: re-run a closed ref_tile kit whose routed DB was lost with the old fleet (results/signoff_1024
NEEDS RE-RUN), without the closure-loop daemon: the job's own route stage, from the SAME source commit as its CLOSED
record, then tools/die_plan/signoff.py (main) at the owner sign-off corners (TT setup / FF hold, 2026-10-24 08:10).

    rerun_reftile.py prep KIT JOB_NAME COMMIT --out LOCAL_RUN_TGZ_DIR     # job spec + source tar + run.sh
    (copy the dir to the host, then)  ot-run --mem M --threads T --hosts H --dir RUN -- bash RUN/run.sh

prep reads physical/ref_tile/<KIT>/job.json AT <COMMIT> (the spec that closed; `COMMIT` placeholders -> the sha),
the host git-archives <COMMIT> and this checkout's HEAD from its own clone (fetching origin when missing):
source.paths + extra_paths / tools/die_plan itself), and writes run.sh: untar, route cmd (placeholders substituted, cwd SRC), ok
check, signoff.py run --corners tt,ff on routes/<LABEL>/work/orfs with the kit's signoff.sdc.  Benches are not re-run
(the CLOSED record's benches passed on the same commit; nothing in the source changes).
"""
import argparse
import json
import re
import shlex
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def git(*a, **k):
    return subprocess.run(["git", "-C", str(REPO), *a], check=True, capture_output=True, **k).stdout


def prep(kit, name, commit, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    sha = git("rev-parse", commit + "^{commit}").decode().strip()
    spec = json.loads(git("show", f"{sha}:physical/ref_tile/{kit}/job.json").decode().replace("COMMIT", sha[:9]))
    src = spec.get("source", {})
    paths = src.get("paths") or ["tools", "rtl", "physical", "Makefile"]
    paths = paths + [p for p in src.get("extra_paths", []) if p not in paths]
    have = [p for p in paths if subprocess.run(["git", "-C", str(REPO), "cat-file", "-e", f"{sha}:{p}"],
                                               capture_output=True).returncode == 0]
    # physical/ref_tile holds every kit's views (~22 GB): take only this kit + the ref_tile kits its kit.env/spec name
    kt = "".join(git("show", f"{sha}:physical/ref_tile/{kit}/{f}").decode(errors="replace")
                 for f in ("kit.env", "spec.json", "job.json")
                 if subprocess.run(["git", "-C", str(REPO), "cat-file", "-e", f"{sha}:physical/ref_tile/{kit}/{f}"],
                                   capture_output=True).returncode == 0)
    refs = sorted({kit} | set(re.findall(r"physical/ref_tile/([A-Za-z0-9_.-]+)/", kt)))
    for r in list(refs):
        if r in ("common",):
            continue
    have = [h for h in have if h != "physical"] + [":(exclude)physical/ref_tile"] * ("physical" in have) + (
        ["physical"] if "physical" in have else []) + [f"physical/ref_tile/{r}" for r in refs
        if subprocess.run(["git", "-C", str(REPO), "cat-file", "-e", f"{sha}:physical/ref_tile/{r}"],
                          capture_output=True).returncode == 0]
    # the host git-archives the source from its own clone (fetching origin if the commit is missing)
    main = git("rev-parse", "HEAD").decode().strip()
    label = re.sub(r"[^A-Za-z0-9_]", "_", name)
    st = spec["stages"]["route"]
    th = st.get("threads", spec.get("threads", 8))

    def sub(c):
        return (c.replace("{RUN}", "$RUN").replace("{SRC}", "$RUN/src").replace("{CL}", "$RUN/cl")
                .replace("{LABEL}", label).replace("{NAME}", name).replace("{BLOCK}", spec["block"])
                .replace("{COMMIT}", sha[:9]).replace("{THREADS}", str(th)).replace("{HOST}", "$(hostname)"))
    sdc = f"$RUN/src/physical/ref_tile/{kit}/signoff.sdc"
    run = f"""#!/bin/bash
# GENERATED by tools/elem_qk/rerun_reftile.py: re-run of {kit} (job {name}, source {sha})
set -uo pipefail
RUN=$(cd "$(dirname "$0")" && pwd); export RUN
export PATH=$HOME/.local/opentallas-tools/bin:$PATH
mkdir -p $RUN/src $RUN/cl $RUN/so_tools $RUN/routes
G=$HOME/OpenTallas
for c in {sha} {main}; do git -C $G cat-file -e $c^{{commit}} 2>/dev/null || git -C $G fetch -q origin || exit 3; done
[ -f $RUN/src/.untarred ] || {{ git -C $G archive {sha} {' '.join(shlex.quote(h) for h in have)} | tar -x -C $RUN/src && touch $RUN/src/.untarred; }} || exit 3
git -C $G archive {main} tools/die_plan | tar -x -C $RUN/so_tools || exit 3
cd $RUN/src
export CL_PHASE=route CL_LABEL_SUFFIX= CL_STOP_AFTER=
( {sub(st['cmd'])} ) > $RUN/cl/route.log 2>&1
echo "route_rc=$?" > $RUN/cl/route_rc
( {sub(st['ok']) if st.get('ok') else 'true'} ) && echo route_ok=1 >> $RUN/cl/route_rc || echo route_ok=0 >> $RUN/cl/route_rc
cat $RUN/cl/route_rc
OR=$RUN/routes/{label}/work/orfs
SDC={sdc}; [ -f $SDC ] || SDC=$(ls $OR/results/asap7/*/base/6_final.sdc 2>/dev/null | tail -1)
python3 $RUN/so_tools/tools/die_plan/signoff.py run --run-dir $OR --sdc $SDC --name {kit} --corners tt,ff \\
  --out $RUN/signoff > $RUN/cl/signoff.log 2>&1
echo "signoff_rc=$?" >> $RUN/cl/route_rc
tail -5 $RUN/cl/signoff.log
"""
    (out / "run.sh").write_text(run)
    (out / "job_spec.json").write_text(json.dumps(spec, indent=1))
    print(json.dumps(dict(kit=kit, name=name, sha=sha, label=label, threads=th,
                          ram=st.get("peak_ram_gb", spec.get("peak_ram_gb", 32)), paths=have)))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("prep",))
    ap.add_argument("kit")
    ap.add_argument("name")
    ap.add_argument("commit")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    prep(a.kit, a.name, a.commit, a.out)


if __name__ == "__main__":
    sys.exit(main())
