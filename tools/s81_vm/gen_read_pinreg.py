#!/usr/bin/env python3
"""READ_PIPE 2 (pin-registered) read egress: derive the hard-master wrappers and the router from the READ_PIPE 1
sources so the two can never diverge.  claude S81 VM F5, 2026-10-15.
  dsfd_vm_static_read_q{g}_p / _v{g}_p = the same wrappers with the leaf at IN_REG=1 (distinct hard-master names:
  no #() override on a hard child, no alias with the READ_PIPE 1 views);
  dsfd_vm_static_read_router_p = the same wires-only composition over the _p masters.
Writes rtl/dsrom_sys/s81_ph/vm/dsfd_vm_static_read_{quartets,valid_quartets,router}_p.sv; --check verifies only."""
import pathlib,re,sys
R=pathlib.Path(__file__).resolve().parents[2]/'rtl/dsrom_sys/s81_ph/vm'
HDR='// GENERATED by tools/s81_vm/gen_read_pinreg.py from {src} -- do not edit (READ_PIPE 2, leaf IN_REG=1)\n'
def derive(src):
    s=(R/src).read_text()
    s=re.sub(r'\bmodule (dsfd_vm_static_read_[qv]\d)\(',r'module \1_p(',s)
    s=re.sub(r'\b(dsfd_vm_static_read_(?:leaf|valid)) #\(\.G\((\d)\)\)',r'\1 #(.G(\2),.IN_REG(1))',s)
    s=re.sub(r'\bmodule dsfd_vm_static_read_router\(','module dsfd_vm_static_read_router_p(',s)
    s=re.sub(r'^( dsfd_vm_static_read_[qv]\d) ',r'\1_p ',s,flags=re.M)
    # r2: valid leaves recompute completeness from the memory group's slot-valid bits (stripe pair k = 32k + slot)
    def sv(g):return (0,8) if g<=1 else (4*g,4)
    if src=='dsfd_vm_static_read_valid_quartets.sv':
        for g in range(8):
            sb,n=sv(g)
            s=s.replace(f'module dsfd_vm_static_read_v{g}_p(input wire ck,rst_n,\n',f'module dsfd_vm_static_read_v{g}_p(input wire ck,rst_n,\n input wire[{4*n-1}:0] i_slot_valid,\n',1)
            s=s.replace(f'dsfd_vm_static_read_valid #(.G({g}),.IN_REG(1)) leaf(.ck(ck),.rst_n(rst_n),',f'dsfd_vm_static_read_valid #(.G({g}),.IN_REG(1)) leaf(.ck(ck),.rst_n(rst_n),.i_slot_valid(i_slot_valid),',1)
    if src=='dsfd_vm_static_read_router.sv':
        for g in range(8):
            sb,n=sv(g);bits=','.join(f'slot_valid[{32*k+sb}+:{n}]' for k in (3,2,1,0))
            a=f' dsfd_vm_static_read_v{g}_p v{g}(.ck(ck_valid[{g}]),.rst_n(rst_valid_n[{g}]),'
            assert s.count(a)==1,a
            s=s.replace(a,a+f'.i_slot_valid({{{bits}}}),')
    return HDR.format(src=src)+s
def main():
    bad=0
    for src in ['dsfd_vm_static_read_quartets.sv','dsfd_vm_static_read_valid_quartets.sv','dsfd_vm_static_read_router.sv']:
        out=R/src.replace('.sv','_p.sv');txt=derive(src)
        if '--check' in sys.argv:
            if not out.exists() or out.read_text()!=txt:print('STALE',out.name);bad=1
        else:out.write_text(txt)
    n=sum(len(re.findall(r'IN_REG\(1\)',(R/f).read_text())) for f in ['dsfd_vm_static_read_quartets_p.sv','dsfd_vm_static_read_valid_quartets_p.sv'])
    m=len(re.findall(r'^ dsfd_vm_static_read_[qv]\d_p ',(R/'dsfd_vm_static_read_router_p.sv').read_text(),flags=re.M))
    assert n==16 and m==72,(n,m)
    print('GEN_READ_PINREG',('STALE' if bad else 'OK'),'wrappers',n,'router instances',m);return bad
if __name__=='__main__':sys.exit(main())
