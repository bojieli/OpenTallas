#!/usr/bin/env python3
"""Regenerate the two DERIVED files of the A2-F / hop-1 VM parent from their unchanged legacy sources (S-VM-RTL 2026-10-16).

  rtl/dsrom_sys/s81_ph/vm/dsfd_vm_a2f_rsched.sv   <- dsfd_vm_static_rsched.sv with the release tap as parameter REL
  rtl/dsrom_sys/s81_ph/test/tb_dsfd_sp_vm_a2f.sv  <- tb_dsfd_sp_vm_static.sv (S-FUNC master bench) on dsfd_sp_vm_a2f
Every substitution is asserted to match exactly once (or the stated count), so a changed legacy source fails loudly.
  python3 tools/s81_vm/gen_dsfd_vm_a2f_derived.py [--check]     (--check: compare with the committed files, exit 1 on drift)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
V = ROOT / 'rtl/dsrom_sys/s81_ph/vm'
T = ROOT / 'rtl/dsrom_sys/s81_ph/test'
RS_HDR = '`timescale 1ns/1ps\n`default_nettype none\n// ---------------------------------------------------------------------------------------------------------------\n// dsfd_vm_a2f_rsched (S-VM-RTL, 2026-10-16): the fixed-rule READ schedule of the A2-F / hop-1 VM parent.  A verbatim\n// copy of dsfd_vm_static_rsched (rtl/dsrom_sys/s81_ph/vm/dsfd_vm_static_rsched.sv, kept byte-identical for its closed\n// view) whose ONLY change is the release tap: the fixed release edge E0 + REL (legacy REL = 10) becomes a parameter.\n// Hop-1 storage removes the two b4 quarter relays (one request + one response register), so every row reaches the\n// return store two edges earlier: E9 -> E7, release E10 -> E8 (REL = 8).  prepare = REL - 1, expected / slot taps\n// = REL + 1, exactly the legacy offsets; REL = 10 is cycle-identical to dsfd_vm_static_rsched.  The unused chain tail\n// (stages REL+2..11) has no load and is removed by synthesis.\n// ---------------------------------------------------------------------------------------------------------------\n'
TB_HDR = "// tb_dsfd_sp_vm_a2f (S-VM-RTL, 2026-10-16): the S-FUNC die-name VM master bench (tb_dsfd_sp_vm_static.sv, unchanged\n// program, checks, fault witnesses 1..8 and mutants) run on the A2-F / hop-1 parent dsfd_sp_vm_a2f.  Generated by\n// tools/s81_vm/gen_dsfd_vm_a2f_derived.py; the ONLY edits are the parent's clock / reset category ports and the read\n// expectations' read pipe: every stream read is RPE = READ_PIPE - 2*HOP1 (SU / t_crs L 12 + RPE, the Q / G stream\n// phase and the WFC serial return use RPE; with HOP1 these equal the legacy READ_PIPE 2 calendar).\n"


def sub(s, pairs):
    for a, b, *n in pairs:
        n = n[0] if n else 1
        assert s.count(a) == n, (a, s.count(a))
        s = s.replace(a, b)
    return s


def rsched():
    src = (V / 'dsfd_vm_static_rsched.sv').read_text()
    body = src[src.index('module dsfd_vm_static_rsched #(parameter integer PINREG=0)'):]
    return RS_HDR + sub(body, [
        ('module dsfd_vm_static_rsched #(parameter integer PINREG=0) (',
         'module dsfd_vm_a2f_rsched #(parameter integer PINREG=0, parameter integer REL=8) ('),
        ("rel_v_q <= |dv[9] | |da[9];                  // = |dv[10] | |da[10] at the same edge",
         "rel_v_q <= |dv[REL-1] | |da[REL-1];          // = |dv[REL] | |da[REL] at the same edge"),
        ("pre_v_q <= |dv[8] | |da[8];                  // = |dv[9]  | |da[9]",
         "pre_v_q <= |dv[REL-2] | |da[REL-2];          // = |dv[REL-1] | |da[REL-1]"),
        ("ev_q <= dv[11] & ~dm[11][17:0]; ea_q <= da[11] & ~dm[11][29:18]; mxe_q <= dxv[11];",
         "ev_q <= dv[REL+1] & ~dm[REL+1][17:0]; ea_q <= da[REL+1] & ~dm[REL+1][29:18]; mxe_q <= dxv[REL+1];"),
        ("es_q <= ds[11]; mxs_q <= dxs[11];", "es_q <= ds[REL+1]; mxs_q <= dxs[REL+1];"),
        ("assign release_v = |dv[10] | |da[10];", "assign release_v = |dv[REL] | |da[REL];"),
        ("assign prepare_v = |dv[9] | |da[9];", "assign prepare_v = |dv[REL-1] | |da[REL-1];"),
        ("assign expected_v = dv[11] & ~dm[11][17:0];", "assign expected_v = dv[REL+1] & ~dm[REL+1][17:0];"),
        ("assign release_slot = ds[11];", "assign release_slot = ds[REL+1];"),
        ("assign aux_expected = da[11] & ~dm[11][29:18];", "assign aux_expected = da[REL+1] & ~dm[REL+1][29:18];"),
        ("assign mx_expected = dxv[11];", "assign mx_expected = dxv[REL+1];"),
        ("assign mx_rslot = dxs[11];", "assign mx_rslot = dxs[REL+1];"),
        ("assign release_group = dg[10];", "assign release_group = dg[REL];"),
        ("assign release_mask = masks[10];", "assign release_mask = masks[REL];"),
        ("assign prepare_group = dg[9];", "assign prepare_group = dg[REL-1];"),
        ("assign prepare_mask = masks[8]; // DUT mutant: stale completion descriptor.",
         "assign prepare_mask = masks[REL-2]; // DUT mutant: stale completion descriptor."),
        ("assign prepare_mask = masks[9];", "assign prepare_mask = masks[REL-1];"),
        ('module dsfd_vm_static_rsched_p (', 'module dsfd_vm_a2f_rsched_p #(parameter integer REL=8) ('),
        ('dsfd_vm_static_rsched #(.PINREG(1)) u (', 'dsfd_vm_a2f_rsched #(.PINREG(1), .REL(REL)) u (')])


def bench():
    s = (T / 'tb_dsfd_sp_vm_static.sv').read_text()
    return TB_HDR + sub(s, [
        ('module tb_dsfd_sp_vm_static;', 'module tb_dsfd_sp_vm_a2f;\n`ifndef A2F_HOP1\n`define A2F_HOP1 1\n`endif\n'
         '    localparam integer HOP1 = `A2F_HOP1;\n    localparam integer NRL = HOP1 ? 16 : 48;'),
        ('    reg s_ck = 1, t_ck = 1, rst = 0, rss = 0;',
         '    // every stream read service is 2 edges shorter with HOP1: the expectations use the effective read pipe RPE\n'
         '    localparam integer RPE = READ_PIPE - 2*HOP1;\n    reg s_ck = 1, t_ck = 1, rst = 0, rss = 0;'),
        ('dsfd_sp_vm #(.CAP_PIPE(CAP_PIPE), .READ_PIPE(READ_PIPE), .WSCATTER_PIPE(WSCATTER_PIPE)) dut (',
         'dsfd_sp_vm_a2f #(.CAP_PIPE(CAP_PIPE), .READ_PIPE(READ_PIPE), .HOP1(HOP1)) dut ('),
        ("""        .ck_mem_wcapture_t({128{t_ck}}), .ck_mem_wscatter_t({16{t_ck}}),
        .ck_mem_relay_req_t({48{t_ck}}), .ck_mem_relay_rsp_t({48{t_ck}}),
        .ck_write_control_t(t_ck), .ck_write_header_t(t_ck), .ck_write_payload_t({4{t_ck}}),
        .ck_write_dispatch_t({16{t_ck}}), .ck_write_stage_t({128{t_ck}}),""",
         """        .ck_mem_wscatter_t({16{t_ck}}),
        .ck_mem_relay_req_t({NRL{t_ck}}), .ck_mem_relay_rsp_t({NRL{t_ck}}),
        .ck_write_header_t(t_ck), .ck_write_payload_t({16{t_ck}}), .ck_write_control_t({4{t_ck}}), .ck_write_fault_t({4{t_ck}}),
        .ck_write_meta_t({28{t_ck}}), .ck_write_data_t({128{t_ck}}),"""),
        ("""        .rss_mem_wcapture_t({128{rss}}), .rss_mem_wscatter_t({16{rss}}), .rss_mem_relay_t({48{rss}}),
        .rss_write_control_t(rss), .rss_write_header_t(rss), .rss_write_payload_t({4{rss}}),
        .rss_write_dispatch_t({16{rss}}), .rss_write_stage_t({128{rss}}),""",
         """        .rss_mem_wscatter_t({16{rss}}), .rss_mem_relay_t({NRL{rss}}),
        .rss_write_header_t(rss), .rss_write_payload_t({16{rss}}), .rss_write_control_t({4{rss}}), .rss_write_fault_t({4{rss}}),
        .rss_write_meta_t({28{rss}}), .rss_write_data_t({128{rss}}),"""),
        ('while (I % 4 == ((2-READ_PIPE)%4+4)%4) I = I + 1;', 'while (I % 4 == ((2-RPE)%4+4)%4) I = I + 1;'),
        ('x43_serial(I + 19+READ_PIPE)', 'x43_serial(I + 19+RPE)', 2),
        ('12+READ_PIPE]', '12+RPE]', 4),
        ('e_tc[tk + 1 + 16+READ_PIPE]', 'e_tc[tk + 1 + 16+RPE]'),
        ('e_w[sk + 1 + 18+3*((READ_PIPE+3)/4)]', 'e_w[sk + 1 + 18+3*((RPE+3)/4)]'),
        ('.ck_cap_control_s(s_ck)', '.ck_cap_fault_s(s_ck), .rst_cap_fault_s(rst), .ck_cap_fault_t(t_ck), .rss_cap_fault_t(rss), .ck_cap_control_s(s_ck)'),
        ('.ck_landing_t(t_ck)', '.ck_landing_t({5{t_ck}})'),
        ('.ck_mem_fsr_t({16{t_ck}})', '.ck_write_summary_t(t_ck), .rss_write_summary_t(rss), .ck_mem_native_diag_t({4{t_ck}}), .rss_mem_native_diag_t({4{rss}}), .ck_mem_fsr_t({16{t_ck}})'),
        ('stream(1, (READ_PIPE == 2) ? 1100 : 1101, 2);', 'stream(1, (RPE == 2) ? 1100 : 1101, 2);')])


def main():
    out = {V / 'dsfd_vm_a2f_rsched.sv': rsched(), T / 'tb_dsfd_sp_vm_a2f.sv': bench()}
    bad = 0
    for p, text in out.items():
        if '--check' in sys.argv:
            ok = p.read_text() == text
            print(('OK    ' if ok else 'DRIFT ') + str(p.relative_to(ROOT)))
            bad |= not ok
        else:
            p.write_text(text)
            print('wrote', p.relative_to(ROOT))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
