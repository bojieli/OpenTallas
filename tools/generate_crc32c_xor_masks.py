#!/usr/bin/env python3
"""Emit CRC32C as XOR masks, so the RTL can compute it in a tree instead of a chain.

``rtl/lib/ot_crc_pkg.sv``'s ``crc32c`` is the reflected Castagnoli algorithm written
the way the standard states it: one bit at a time, ``c = (c >> 1) ^ poly`` when the
feedback bit is set.  That is the right way to STATE it and the wrong way to
synthesise it.  Unrolled over a 1,536-bit record it is a 1,536-step chain, and the
routed ``ot_a3_communication_decoder`` showed the cost -- 1,162 XOR and XNOR cells on
one path from ``descriptor_record[1]`` to ``trap_class[1]``, 661 cell arcs, 39.9 MHz
at a 4 ns target, the slowest block in the ABI 3.0 inventory.

A CRC is LINEAR over GF(2), so each of the 32 output bits is the XOR of a fixed
subset of the input bits, plus a constant:

    crc(data) = crc(0)  XOR  XOR over set bits i of ( crc(e_i) XOR crc(0) )

which this derives by calling the reference algorithm once per input bit.  Written as
``^(data & mask[j])`` the same function becomes a balanced XOR reduction: for 1,536
bits each output bit depends on about 768 inputs, so TEN levels rather than 1,536.

The masks are emitted rather than computed in SystemVerilog on purpose.  A constant
function that calls the serial CRC 1,536 times would ask every tool in the flow to
fold two million iterations at elaboration, and the two that matter disagree about
how much of that they will do.  Emitting them makes the table auditable, identical in
every tool, and regenerable from one command.

``rtl/test/tb_crc32c_tree_equiv.sv`` is the gate: it drives both forms from one
stimulus and compares all 32 bits, so a table that does not reproduce the reference
algorithm fails rather than ships.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
POLY = 0x82F63B78
#: Every width ``crc32c`` is called at in the synthesisable RTL.  A CRC depends on
#: the message LENGTH, so each width needs its own table.
WIDTHS = (64, 1024, 1536, 2048)


def crc32c(width: int, data: int) -> int:
    """The reference algorithm, transcribed from rtl/lib/ot_crc_pkg.sv."""
    c = 0xFFFFFFFF
    for byte_i in range(width // 8):
        for bit_i in range(8):
            feedback = (c & 1) ^ ((data >> (byte_i * 8 + bit_i)) & 1)
            c >>= 1
            if feedback:
                c ^= POLY
    return c ^ 0xFFFFFFFF


def masks_for(width: int) -> tuple[int, list[int]]:
    """``(base, mask_per_output_bit)`` for one message width."""
    base = crc32c(width, 0)
    columns = [crc32c(width, 1 << bit) ^ base for bit in range(width)]
    masks = []
    for out_bit in range(32):
        mask = 0
        for in_bit, column in enumerate(columns):
            if (column >> out_bit) & 1:
                mask |= 1 << in_bit
        masks.append(mask)
    return base, masks


def verify(width: int, base: int, masks: list[int], rounds: int = 64) -> None:
    """The table must reproduce the reference on edge cases and random data."""
    rng = random.Random(0x5EED ^ width)
    probes = [0, (1 << width) - 1, 1, 1 << (width - 1)]
    probes += [rng.getrandbits(width) for _ in range(rounds)]
    for data in probes:
        expect = crc32c(width, data)
        got = base
        for out_bit in range(32):
            if bin(data & masks[out_bit]).count("1") & 1:
                got ^= 1 << out_bit
        if got != expect:
            raise SystemExit(
                f"width {width}: table gives {got:#010x}, reference {expect:#010x}"
            )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=REPO / "rtl/lib/ot_crc32c_tree_pkg.sv"
    )
    args = parser.parse_args()

    lines = [
        "// GENERATED by tools/generate_crc32c_xor_masks.py -- do not edit by hand.",
        "//",
        "// CRC32C as XOR masks.  ot_crc_pkg::crc32c states the reflected Castagnoli",
        "// algorithm one bit at a time, which unrolls into a chain as long as the",
        "// message: 1,536 steps for a descriptor record, and 39.9 MHz routed.  A CRC is",
        "// linear over GF(2), so each output bit is the XOR of a fixed subset of the",
        "// input bits plus a constant, and `^(data & MASK)` is a balanced reduction --",
        "// ten levels for 1,536 bits instead of 1,536.",
        "//",
        "// The tables are derived by calling the reference algorithm once per input bit",
        "// and are verified against it, on edge cases and random data, at generation",
        "// time; rtl/test/tb_crc32c_tree_equiv.sv is the standing gate.",
        "package ot_crc32c_tree_pkg;",
    ]
    for width in WIDTHS:
        base, masks = masks_for(width)
        verify(width, base, masks)
        hexdigits = (width + 3) // 4
        lines.append("")
        lines.append(f"    // ---- {width}-bit message ----")
        lines.append(f"    localparam [31:0] BASE_{width} = 32'h{base:08x};")
        for out_bit, mask in enumerate(masks):
            lines.append(
                f"    localparam [{width - 1}:0] M{width}_{out_bit:02d} = "
                f"{width}'h{mask:0{hexdigits}x};"
            )
        lines.append(f"    function automatic [31:0] crc32c_{width};")
        lines.append(f"        input [{width - 1}:0] data;")
        lines.append("        begin")
        lines.append(f"            crc32c_{width} = BASE_{width} ^ {{")
        terms = [f"^(data & M{width}_{bit:02d})" for bit in reversed(range(32))]
        for index in range(0, 32, 4):
            chunk = ", ".join(terms[index : index + 4])
            comma = "," if index + 4 < 32 else ""
            lines.append(f"                {chunk}{comma}")
        lines.append("            };")
        lines.append("        end")
        lines.append("    endfunction")
    lines.append("endpackage")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"{len(WIDTHS)} widths verified against the reference algorithm")
    print(f"-> {args.output} ({args.output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
