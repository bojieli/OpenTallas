#!/usr/bin/env python3
"""Generate positive, source-measured terminal-load envelopes, not child timing credit."""
import json
import hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'results/uarch/dsrom_v9_parent_context_20261005'
rows=[]
for corner in ('SS','FF'):
 p=BASE/'inputs'/f'{corner}_terminal_loads.tsv'
 for line in p.read_text().splitlines():
  r=line.split('\t')
  if r[0]=='positive': rows.append(dict(corner=corner,source=r[1],cap=float(r[3]),raw=line))
  elif r[0]=='cut': rows.append(dict(corner=corner,source=r[1]+'/'+r[2],cap=float(r[5]),raw=line))
  elif r[0]=='port' and r[2]=='INPUT': rows.append(dict(corner=corner,source='port/'+r[1],cap=float(r[3]),raw=line))
def envelope(prefixes):
 candidates=[r for r in rows if any(p in r['source'] for p in prefixes) and r['cap']>0]
 if not candidates: raise ValueError('no source load: '+str(prefixes))
 return max(candidates,key=lambda r:r['cap'])
profiles={
 'engine_cfg*':envelope(['g_qb.b_cfg']),
 'engine_cdec*':envelope(['g_qb.b_cdec']),
 'engine_xs*':envelope(['g_qb.g_bx.b_xs']),
 'engine_go*':envelope(['g_ir.g_gok']),
 'engine_reset_n*':envelope(['g_mz.u_rs']),
 'engine_clk':envelope(['g_cg.u_cg.u_icg/GCLK']),
}
# Non-engine observation terminals use a positive measured input-pin envelope.
# Their actual downstream enclosing consumer is still outside this cut.
observation=envelope(['port/cfg_','port/xs_','port/go'])
profiles['f_bus* node_v node_e node_t* node_d* busy fault captured_root*']=observation
record=dict(schema='dsrom.v9.parent.terminal-load-envelopes.v1',
 source_QX10='0032b7355',ODB_stage='existing Z18a 4_cts',
 profiles=profiles,exact_per_bit_child_loading=False,
 note='Worst measured family load across SS/FF, including positive net after first QN inverter where uniquely traceable. Conservative one-element mapping envelopes. Observation terminals use measured QX input-pin envelope, not qualified downstream return-network loads. No full-field or child closure.',
 hashes={f'{c}_terminal_loads.tsv':hashlib.sha256((BASE/'inputs'/f'{c}_terminal_loads.tsv').read_bytes()).hexdigest() for c in ('SS','FF')})
(BASE/'terminal_profiles.json').write_text(json.dumps(record,indent=2)+'\n')
p=ROOT/'physical/dsrom_v9_parent_context/loaded_ports.sdc'
p.write_text('# Generated by tools/dsrom_v9_parent_loads.py; actual measured family envelopes in fF.\n'+''.join(f'set_load {r["cap"]:.9g} [get_ports {{{name}}}]\n' for name,r in profiles.items()))
