#!/usr/bin/env python3
"""Generate the MBIST successor of the DS-V4.1 ROM S81 element (default-off; the pinned element is untouched).

Reads rtl/v41rom/ot_v41_rom_elem_qp_w10.sv and writes rtl/dft/v41/ot_v41_rom_elem_qp_mb_w10.sv with three
mechanical edits, each asserted to match exactly once:

1. module name -> ot_v41_rom_elem_qp_mb_w10, plus a ROM test bus (mb_*) before `clk`;
2. the element ICG opens while any of its ROMs is under test (en = cg_en_q | mb_on), so the macros and the
   collars are clocked during BIST; with mb_on = 0 the gate is the original;
3. each ot_rom_4096x274_m8 of the PP (ping-pong) path sits behind an ot_mbist_rom_collar_par (matrix-form CRC): the collar muxes the
   macro's ce/address to the test bus while its rom_sel bit is set and is a combinational pass-through
   otherwise; the read word goes straight back to the element (f_rd = m_rd).

Macro index inside the element: 2*mb + {0,1} (u_rom0, u_rom1 of g_mac[mb]).  Only PP != 0 is collared (the S81
q element's routed configuration); the single-macro g_one path is unchanged.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "rtl/v41rom/ot_v41_rom_elem_qp_w10.sv"
DST = ROOT / "rtl/dft/v41/ot_v41_rom_elem_qp_mb_w10.sv"


def sub1(text: str, old: str, new: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"anchor found {n} times: {old[:80]!r}")
    return text.replace(old, new)


def generate(src: str) -> str:
    t = src
    t = sub1(t, "module ot_v41_rom_elem_qp_w10 #(", "module ot_v41_rom_elem_qp_mb_w10 #(")
    t = sub1(t, "    input  wire         clk,\n",
             "    // ---- MBIST ROM test bus (ot_mbist_ctrl ROM side), macro m = 2*mb + {0,1} ----\n"
             "    input  wire                 mb_on,      // any ROM of this element under test: gate open\n"
             "    input  wire [2*NB-1:0]      mb_sel,     // rom_sel slice of this element\n"
             "    input  wire                 mb_clear,\n"
             "    input  wire                 mb_req,\n"
             "    input  wire [11:0]          mb_addr,\n"
             "    input  wire [64*NB-1:0]     mb_exp,     // expected signature per macro (fuse / CSR)\n"
             "    output wire [2*NB-1:0]      mb_match,\n"
             "    output wire [64*NB-1:0]     mb_sig,\n"
             "    input  wire                 mb_rst_n,   // collar reset\n"
             "    input  wire         clk,\n")
    t = sub1(t, "        ot_hdc_cg u_cg (.clk(clk), .en(cg_en_q), .gclk(gclk));",
             "        ot_hdc_cg u_cg (.clk(clk), .en(cg_en_q | mb_on), .gclk(gclk));")
    t = sub1(t, "    end else begin : g_nocg\n        assign gclk = clk;",
             "    end else begin : g_nocg\n        assign gclk = clk;   // MBIST: no gate to open")
    for k, ce in ((0, "issue && !a_ctr[0]"), (1, "issue && a_ctr[0]")):
        old = (f"            u_rom{k} (.clk(gclk), .ce_in({ce}), .addr_in(a_ctr[12:1]), .rd_out(rd{k}));")
        new = (f"            u_rom{k} (.clk(gclk), .ce_in(mb_m_ce{k}), .addr_in(mb_m_a{k}), .rd_out(rd{k}));\n"
               f"        ot_mbist_rom_collar_par #(.WORDS(4096), .DW(274), .AMAX(12)) u_rc{k} (\n"
               f"            .clk(gclk), .rst_n(mb_rst_n), .f_ce({ce}), .f_addr(a_ctr[12:1]), .f_rd(),\n"
               f"            .m_ce(mb_m_ce{k}), .m_addr(mb_m_a{k}), .m_rd(rd{k}),\n"
               f"            .t_en(mb_sel[2*mb+{k}]), .t_clear(mb_clear), .t_req(mb_req), .t_addr(mb_addr),\n"
               f"            .exp_sig(mb_exp[32*(2*mb+{k}) +: 32]), .sig(mb_sig[32*(2*mb+{k}) +: 32]),\n"
               f"            .sig_match(mb_match[2*mb+{k}]), .sig_busy());")
        t = sub1(t, old, new)
    t = sub1(t, "        reg  [273:0] cap0, cap1;\n",
             "        reg  [273:0] cap0, cap1;\n        wire mb_m_ce0, mb_m_ce1;\n        wire [11:0] mb_m_a0, mb_m_a1;\n")
    t = sub1(t, "        u_rom (.clk(gclk), .ce_in(issue), .addr_in(rom_addr), .rd_out(rd));",
             "        u_rom (.clk(gclk), .ce_in(issue), .addr_in(rom_addr), .rd_out(rd));\n"
             "        assign mb_match[2*mb +: 2] = 2'b00; assign mb_sig[64*mb +: 64] = 64'd0;   // not collared")
    hdr = ("// GENERATED by tools/dft/gen_elem_mbist.py from rtl/v41rom/ot_v41_rom_elem_qp_w10.sv\n"
           f"// source sha256 {hashlib.sha256(src.encode()).hexdigest()}\n"
           "// MBIST successor: ROM collars on the PP macros + ICG open under test.  With mb_on = 0 and mb_sel = 0\n"
           "// every functional path equals the source module (collars are combinational pass-throughs).\n")
    return hdr + t


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if the committed output is stale")
    a = ap.parse_args()
    out = generate(SRC.read_text())
    if a.check:
        if DST.read_text() != out:
            raise SystemExit(f"{DST} is stale")
        return 0
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(out)
    print(DST)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
