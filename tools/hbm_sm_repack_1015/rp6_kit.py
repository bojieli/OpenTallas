BASE = {"n": "physical/ref_tile/smh_rp5n_m/spec.json", "s": "physical/ref_tile/smh_rp5s_m/spec.json"}
# band clock pins: (face, coordinate along the face) -- each root enters its own band
CKPIN = {
    ("n", "m"): {"u": ("W", 918.0), "t": ("N", 345.6), "c": ("W", 560.0), "m": ("W", 160.0)},
    ("n", "f"): {"u": ("W", 918.0), "t": ("N", 345.6), "c": ("W", 240.0)},
    ("s", "m"): {"c": ("W", 560.0), "u": ("W", 960.0), "m": ("W", 160.0)},
    ("s", "f"): {"u": ("W", 918.0), "t": ("W", 1188.0), "c": ("W", 240.0)},
}
SPLIT = "rtl/hbm_accel/sm/repack/h2a5/ot_rp5_land_reset_split.sv"
FENCE_DIR = "physical/hbm_smh_r6"


def inst_regions(sv: str, regions):
    """top-level instance -> band, from the clock port each instance of the landed top is clocked by (one per line)"""
    out = {}
    for line in sv.split("\n"):
        m = re.match(r"\s*[A-Za-z_]\w*\s(?:.*?\s)?(u_\w+)\s*\((\..*)$", line)
        if not m or line.lstrip().startswith(("//", "module", "input", "output", "wire", "assign", "localparam")):
            continue
        name, conns = m.group(1), m.group(2)
        cks = set(re.findall(r"\.(?:ck|clk)\s*\(\s*(?:\{\s*\d+\s*\{\s*)?ck_(\w+?)\s*(?:\}\s*\}\s*)?\)", conns))
        cks &= set(regions)
        if len(cks) == 1:
            out[name] = cks.pop()
        elif len(cks) > 1:
            raise SystemExit(f"instance {name} on several band clocks {cks}")
    return out


def fence_tcl(h, v, kit, imap, core):
    bands = G.BANDS[(h, v)]
    lines = [f"# GENERATED by tools/hbm_sm_repack_1015/rp6_kit.py (HBM-ELEM13/SMH-R6 {kit}): band placement fences.",
             "# PRE_GLOBAL_PLACE (pin_hook_before_flops): one INCLUSIVE region + group per band; EVERY movable standard cell joins",
             "# its band (named cells by top-level instance = the instance's band clock; anonymous cells by neighbour vote).",
             "# Dissolved before detailed placement by physical/hbm_smh_r6/fence_dissolve.tcl.  Placement only, 0 cycles.",
             "set ot_r6_bands {" + " ".join(f"{{{b} {x0} {y0} {x1} {y1}}}" for b, (x0, y0, x1, y1) in bands.items()) + "}",
             f"set ot_r6_default {core}",
             "set ot_r6_map [dict create " + " ".join(f"{k} {imap[k]}" for k in sorted(imap)) + "]",
             FENCE_BODY]
    return "\n".join(lines) + "\n"


FENCE_BODY = r'''set ot_r6_blk [ord::get_db_block]
set ot_r6_dbu [$ot_r6_blk getDbUnitsPerMicron]
set ot_r6_core [$ot_r6_blk getCoreArea]
set ot_r6_reg [dict create]
set ot_r6_un {}
set ot_r6_named 0
foreach i [$ot_r6_blk getInsts] {
  set m [$i getMaster]
  if {[$m isBlock]} continue
  set ty [$m getType]
  if {![string match CORE* $ty] || $ty in {CORE_WELLTAP CORE_SPACER CORE_ANTENNACELL}} continue
  if {[$i getPlacementStatus] in {FIRM LOCKED COVER}} continue
  regsub -all {\\} [$i getName] {} n
  set top [lindex [split $n "./"] 0]
  if {[dict exists $ot_r6_map $top]} {
    dict set ot_r6_reg $i [dict get $ot_r6_map $top]; incr ot_r6_named
  } else { lappend ot_r6_un $i }
}
set ot_r6_vote 0
for {set pass 0} {$pass < 60 && [llength $ot_r6_un]} {incr pass} {
  set next {}
  foreach i $ot_r6_un {
    set votes [dict create]
    foreach it [$i getITerms] {
      set net [$it getNet]
      if {$net eq "NULL" || [$net getSigType] in {POWER GROUND CLOCK}} continue
      set its [$net getITerms]
      if {[llength $its] > 48} continue
      foreach jt $its {
        set j [$jt getInst]
        if {[dict exists $ot_r6_reg $j]} { dict incr votes [dict get $ot_r6_reg $j] }
      }
    }
    if {[dict size $votes]} {
      set best ""; set bn -1
      dict for {b c} $votes { if {$c > $bn} { set best $b; set bn $c } }
      dict set ot_r6_reg $i $best; incr ot_r6_vote
    } else { lappend next $i }
  }
  if {[llength $next] == [llength $ot_r6_un]} break
  set ot_r6_un $next
}
set ot_r6_left [llength $ot_r6_un]
foreach i $ot_r6_un { dict set ot_r6_reg $i $ot_r6_default }
puts "R6_FENCE_ASSIGN named=$ot_r6_named voted=$ot_r6_vote default=$ot_r6_left (band $ot_r6_default)"
set ot_r6_grp [dict create]
set ot_r6_box [dict create]
foreach b $ot_r6_bands {
  lassign $b name x0 y0 x1 y1
  # snap to the row / site grid of the core and clip to the core
  set cx0 [$ot_r6_core xMin]; set cy0 [$ot_r6_core yMin]; set cx1 [$ot_r6_core xMax]; set cy1 [$ot_r6_core yMax]
  set X0 [expr {max($cx0, round($x0 * $ot_r6_dbu))}]; set X1 [expr {min($cx1, round($x1 * $ot_r6_dbu))}]
  set Y0 [expr {max($cy0, round($y0 * $ot_r6_dbu))}]; set Y1 [expr {min($cy1, round($y1 * $ot_r6_dbu))}]
  set X0 [expr {$cx0 + 54 * (($X0 - $cx0) / 54)}]; set X1 [expr {$cx0 + 54 * (($X1 - $cx0) / 54)}]
  set Y0 [expr {$cy0 + 270 * (($Y0 - $cy0) / 270)}]; set Y1 [expr {$cy0 + 270 * (($Y1 - $cy0) / 270)}]
  if {$X1 > $cx1} { set X1 $cx1 }; if {$Y1 > $cy1} { set Y1 $cy1 }
  set r [odb::dbRegion_create $ot_r6_blk r6_$name]
  odb::dbBox_create $r $X0 $Y0 $X1 $Y1
  dict set ot_r6_grp $name [odb::dbGroup_create $r r6_$name]
  dict set ot_r6_box $name [list $X0 $Y0 $X1 $Y1]
}
set ot_r6_area [dict create]
set ot_r6_cnt [dict create]
dict for {i b} $ot_r6_reg {
  if {![dict exists $ot_r6_grp $b]} { error "R6_FENCE: unknown band $b" }
  [dict get $ot_r6_grp $b] addInst $i
  set m [$i getMaster]
  dict set ot_r6_area $b [expr {([dict exists $ot_r6_area $b] ? [dict get $ot_r6_area $b] : 0.0) + double([$m getWidth]) * [$m getHeight]}]
  dict incr ot_r6_cnt $b
}
foreach b [dict keys $ot_r6_box] {
  lassign [dict get $ot_r6_box $b] X0 Y0 X1 Y1
  set free [expr {double($X1 - $X0) * ($Y1 - $Y0)}]
  foreach i [$ot_r6_blk getInsts] {
    if {![[$i getMaster] isBlock]} continue
    set bb [$i getBBox]
    set ox [expr {min($X1, [$bb xMax]) - max($X0, [$bb xMin])}]; set oy [expr {min($Y1, [$bb yMax]) - max($Y0, [$bb yMin])}]
    if {$ox > 0 && $oy > 0} { set free [expr {$free - double($ox) * $oy}] }
  }
  set a [expr {[dict exists $ot_r6_area $b] ? [dict get $ot_r6_area $b] : 0.0}]
  set n [expr {[dict exists $ot_r6_cnt $b] ? [dict get $ot_r6_cnt $b] : 0}]
  puts [format "R6_FENCE band=%s cells=%d cell_area_um2=%.0f free_um2=%.0f util=%.3f box=%s" $b $n \
      [expr {$a / $ot_r6_dbu / $ot_r6_dbu}] [expr {$free / $ot_r6_dbu / $ot_r6_dbu}] [expr {$free > 0 ? $a / $free : 99}] \
      [list [expr {$X0 / double($ot_r6_dbu)}] [expr {$Y0 / double($ot_r6_dbu)}] [expr {$X1 / double($ot_r6_dbu)}] [expr {$Y1 / double($ot_r6_dbu)}]]]
  if {$n == 0} { error "R6_FENCE: band $b got no cells" }
  if {$free <= 0 || $a / $free > 0.85} { error "R6_FENCE: band $b over-full ([expr {$free > 0 ? $a / $free : 99}])" }
}'''


def spec(h, v):
    base = json.loads((ROOT / BASE[h]).read_text())
    lps = lp.load(str(ROOT / REC / f"lp_spec_{h}_{v}.json"))
    rec_path = f"{REC}/ot_hbm_smh_rp6{h}_{v}_record.json"
    rec = json.loads((ROOT / rec_path).read_text())
    Pm = lp.Parent(lps)
    P = Pm.plan()
    regions = list(rec["regions"])
    core = regions[0]
    cps = [rec["regions"][r]["clock_port"] for r in regions]
    ports = [p for p in Pm.mod["ports"] if p["name"] != "clk"]
    dom = {}
    for r in regions:
        name = "core" if r == core else r
        dom[name] = dict(ratio=[1, 1], ports=[f"ck_{r}"],
                         inputs=[p["name"] for p in ports if p["dir"] == "in" and P["nreg"].get(f"port:{p['name']}") == r],
                         outputs=[p["name"] for p in ports if p["dir"] == "out" and P["nreg"].get(f"port:{p['name']}") == r])
    covered = {x for d in dom.values() for x in d["inputs"] + d["outputs"]}
    missing = [p["name"] for p in ports if p["name"] not in covered]
    if missing:
        raise SystemExit(f"{h}{v}: ports without a band domain {missing}")
    pins = {f: [p for p in ps if not p.startswith("ck_")] for f, ps in base["pins"].items()}
    pr = {k: v_ for k, v_ in base["pin_ranges"].items() if not k.startswith("ck_")}
    for r in regions:
        face, c = CKPIN[(h, v)][r]
        pins[face] = pins[face] + [f"ck_{r}"]
        pr[f"ck_{r}"] = [round(c - 0.54, 2), round(c + 0.54, 2)]
    lsrc = f"{RTL}/lp_{h}_{v}/ot_hbm_smh_rp6{h}_{v}.sv"
    bb = [s.replace(".v", "_bb.v") if s.startswith("physical/") and s.endswith(".v") else s for s in lps["child_sources"]]
    srcs = bb + ["rtl/common/landed_parent/ot_pl_land.sv", "rtl/common/landed_parent/ot_pl_land_field_copies.sv", SPLIT, lsrc]
    kit = f"smh_rp6{h}_{v}"
    sv = (ROOT / lsrc).read_text()
    imap = inst_regions(sv, regions)
    for r in regions:
        if r not in imap.values():
            raise SystemExit(f"{kit}: band {r} has no clocked instance")
    for ch in base["children"]:
        top = ch["inst"].split(".")[0]
        if top not in imap:
            raise SystemExit(f"{kit}: hard child {ch['inst']} not in the band map")
    (ROOT / FENCE_DIR).mkdir(parents=True, exist_ok=True)
    ftcl = f"{FENCE_DIR}/fence_{kit}.tcl"
    (ROOT / ftcl).write_text(fence_tcl(h, v, kit, imap, core))
    ow = base["outline"]
    form = "MAIN" if v == "m" else "FALLBACK"
    bands = G.BANDS[(h, v)]
    bdesc = ", ".join(f"{r} y{y0:g}-{y1:g}" for r, (x0, y0, x1, y1) in bands.items())
    nland = len(rec["landings"])
    dg = G.DG[v]
    checklist = {
        "1_pins": "PASS: every data pin registered in RTL on the root of the band at its face (W rin / E rout glue on c; "
                  "bin / bout / gin / straps / attn on t (n); xi_* entry on " + ("u" if (h, v) == ("s", "m") else "t")
                  + " (s); S-face xo_* / gout / straps on " + ("m" if v == "m" else "c") + "); rout = new glue pin register "
                  "(+1) instead of the hard row_e flop (internal insertion 104-119 TT); reset captured beside its pin on that "
                  "band root (u_lpr_pin, uniform +1); band clock pins enter their own band.",
        "2_reach": "every registered hop inside one band (<= ~410 um tall bands); every seam a landing (E=2 multicycle ring -> "
                   "read, <= ~750 um over 2 cycles): t->c xb / gin / strap landings span the x-store band (411-600 um); the "
                   "reset pin stage -> lp root hop is 1 bit (<= ~710 um, repeated); actual route timing decides.",
        "3_fanout": "r3 / r5 kept copies unchanged; landings chunked 24 b with the r5 per-slot reset copies "
                    "(ot_rp5_land_reset_split.sv); every scalar reset pad on its own forest leaf; pre-gate native census decides.",
        "4_depth": "PASS: cut only at existing register stages / landings (registered slot mux); no new combinational path.",
        "5_storage": "PASS: unchanged hard SRAM children (x store, PV merge, columns); landing rings D=4 slots of flops.",
        "6_floorplan": f"r5 outline {ow['w']} x {ow['h']} and child placement unchanged; bands {bdesc}; "
                       f"+{rec['flops']['landing']} landing flops; per-band utilisation printed by the fence hook "
                       "(R6_FENCE ... util, error > 0.85).",
        "7_clock": f"{len(regions)} GEOMETRIC band roots ({', '.join(cps)}), each a fenced band <= 691 x 412 um "
                   "(x-store band root without IO = all-internal scope); every band seam landed (lp audit PASS, "
                   f"{nland} landings), 1-bit reset runs only; judged per root at the pin flops TT+FF <= 80.",
        "8_schedule": f"static; every landed net +3 absorbed in removed relays / pads where possible; vs r3: gout +{dg} "
                      f"(r5 {'8' if v == 'm' else '5'}), rout +1 (glue), bout 0, half reset +1 uniform; consumer reset depths "
                      f"shifted with their data. PRICED: rp4a gout G 10 -> {10 + dg} per SM tile hop, rout +1 per half.",
    }
    s = dict(base)
    s.update(
        name=kit, top=f"ot_hbm_smh_rp6{h}_{v}", sources=srcs, params={},
        defines=lps["defines"] + ["OT_RP4A_HARD"], hard_define="OT_RP4A_HARD",
        clock="multiple_cts_roots", clock_port=f"ck_{core}", clock_ports=cps, clock_data_paths="related_same_frequency",
        clock_relationship=dict(kind="same_pll_fixed_phase", ratio=[1, 1], phase_ps=0),
        clock_entry_domains=dom, landed_record=rec_path, pins=pins, pin_ranges=pr,
        orfs_vars={"OT_IO_REF_CLASS": "1", "GPL_TIMING_DRIVEN": "0", "DONT_BUFFER_PORTS": "1"},
        pin_hook_before_flops=[ftcl], pre_dpl_extra=[f"{FENCE_DIR}/fence_dissolve.tcl"],
        reset_landing=dict(enable=False, reason=f"the lp RTL lands rst_n (pin stage u_lpr_pin on its face band, regional run "
                           f"rooted in {lps['reset_region']}, same-depth reset forest, depth {rec['reset']['depth']} + 1) and "
                           "ot_rp5_rst kept copies per consumer; priced in the landed record"),
        safe_design_checklist=checklist,
        landed=dict(record=rec_path, landings=nland, landing_flops=rec["flops"]["landing"], reset_depth=rec["reset"]["depth"],
                    lp_spec=f"{REC}/lp_spec_{h}_{v}.json"),
        structural_change=(f"r6 {form}: GEOMETRIC band roots ({', '.join(cps)}) with placement fences (every cell in its "
                           "band), every band seam a 4-slot landing, relay chains split at the seams, rout glue pin register, "
                           "reset captured at its face band; replaces r5 register-mass DOMAINS (TT spread 242 / 415 / 267)."),
    )
    for k in ("pin_regs",):
        if k in s:
            s[k] = dict(s[k], reason=s[k]["reason"].replace("rout / bout launched by the hard row_e / beat_e flops",
                                                            "rout launched by the r6 glue pin register u_ro, bout by u_be2"))
    j = dict(base["job"])
    j.update(owner="Claude:HBM-ELEM13/SMH-R6", branch="claude/hbm-elem13-smh-r6-1021", tag=f"smh_rp6{h}_{v}",
             purpose=f"H.STA.BLK.14.6 smh_attn {h} half r6 {form}: geometric band roots + fences + landed seams",
             structural_change=s["structural_change"],
             extra_paths=["tools/hbm_sm_repack_1015", "tools/landed_parent", "rtl/common/landed_parent", RTL,
                          "rtl/hbm_accel/sm/repack/h2a5", "rtl/hbm_accel/sm/repack/h2", "rtl/hbm_accel/sm/repack/h2a",
                          REC, FENCE_DIR, "physical/ref_tile/smh_xs_p192d_bay/views"])
    lpb = f"{RTL}/lp_{h}_{v}/ot_hbm_smh_rp6{h}_{v}_bench.sh"
    vv = 0 if v == "m" else 1
    W6 = f"{REC}/bench"
    benches = [dict(name="r6_lockstep", cmd=f"bash {RTL}/run_rp6_2_one.sh {{RUN}}/r6 {vv} 0", expect="pass",
                    pass_regex=f"^R6_LOCKSTEP PASS VAR={vv} HMUT=0 compared=", pass_witness=f"{W6}/r6_v{vv}_m0.log",
                    threads=4, peak_ram_gb=32)]
    for m in (1, 2, 3, 5, 6):
        benches.append(dict(name=f"r6_mut{m}", cmd=f"bash {RTL}/run_rp6_2_one.sh {{RUN}}/r6m{m} {vv} {m}", expect="fail",
                            fail_regex=f"^R6_LOCKSTEP FAIL VAR={vv} HMUT={m} mismatches=[1-9]",
                            fail_witness=f"{W6}/r6_v{vv}_m{m}.log", threads=4, peak_ram_gb=32))
    for m in (0, 1, 2, 4):
        b = dict(name=f"lp_{h}{v}_mut{m}", cmd=f"MUTS={m} SIM=verilator VERILATOR=$HOME/.local/opentallas-tools/verilator-5.050/bin/verilator bash {lpb} {{RUN}}/lp{m}",
                 expect="pass" if m == 0 else "fail", threads=8, peak_ram_gb=32)
        if m == 0:
            b.update(pass_regex="MUT 0: LP_LOCKSTEP PASS", pass_witness=f"{W6}/lp_{h}_{v}.log")
        else:
            b.update(fail_regex=f"MUT {m}: LP_LOCKSTEP FAIL", fail_witness=f"{W6}/lp_{h}_{v}.log")
        benches.append(b)
    j["benches"] = benches
    s["job"] = j
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen", action="store_true")
    a = ap.parse_args()
    out = ROOT / "physical/ref_tile_specs/smh"
    for h in ("n", "s"):
        for v in ("m", "f"):
            s = spec(h, v)
            p = out / f"smh_rp6{h}_{v}.json"
            p.write_text(json.dumps(s, indent=1) + "\n")
            print(f"wrote {p.relative_to(ROOT)}: {len(s['clock_ports'])} roots, domains "
                  + ", ".join(f"{d}:{len(x['inputs'])}in/{len(x['outputs'])}out" for d, x in s["clock_entry_domains"].items()))
            if a.gen:
                subprocess.run([sys.executable, str(ROOT / "tools/ref_tile/ref_tile.py"), "gen", str(p)], check=True)


if __name__ == "__main__":
    main()
