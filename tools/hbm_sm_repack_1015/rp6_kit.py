#!/usr/bin/env python3
"""HBM-ELEM13/SMH-R6 r6 (10-21): ref_tile kit specs + band placement fences for the GEOMETRIC regional smh_attn halves.

Inputs: rp6_gen.py lp specs / records (results/arch/hbm_smh_r6_1021) and the lp + rp6_post.py landed tops
(rtl/hbm_accel/sm/repack/h2a6/lp_<h>_<v>/ot_hbm_smh_rp6<h>_<v>.sv).  Geometry, hard children, data pins and outline are the
r5 kits' (physical/ref_tile/smh_rp5<h>_m: same 8 hard children on the 43.2 lattice, 691.2 x 1512.0 / 1252.8); the
changes are the CTS roots (one per band, ck_<band>), the band clock pins, and the PLACEMENT FENCES:

  physical/hbm_smh_r6/fence_smh_rp6<h>_<v>.tcl  (pin_hook_before_flops, PRE_GLOBAL_PLACE, before the pin flops are fixed)
      one INCLUSIVE dbRegion + dbGroup per band (box = the band); every movable standard cell joins the group of its band:
      named cells by their top-level instance (the instance's clock port ck_<band> in the landed RTL), ABC-anonymous cells
      by a majority vote of their already-assigned neighbours (signal nets <= 48 pins), repeated to convergence.
      GPL places each group inside its box (verified on the ORFS image, fencetest 10-21: an ungrouped movable cell with
      full-core regions is GPL-0301, so EVERY cell is grouped and the kit runs GPL_TIMING_DRIVEN=0 / DONT_BUFFER_PORTS=1:
      no cell is born between the hook and global placement).
  physical/hbm_smh_r6/fence_dissolve.tcl       (pre_dpl_extra) reports inside / outside per band, dissolves the fences.

    python3 tools/hbm_sm_repack_1015/rp6_kit.py [--gen]      -> physical/ref_tile_specs/smh/smh_rp6{n,s}_{m,f}.json (+ kits)
"""
