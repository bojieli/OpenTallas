"""L2H-SMATT/RP4A (LEAD3-HBM, 10-19; RELEASE_TREE H.STA.BLK.14.6 + H.STA.BLK.9.1): ref_tile specs for the HBM SM ATTENTION
tile rp4a (the die binds smh_attn x16) as two hardened halves, from the L2H-SM9 rp4 halves generator (rp4h_kit.spec()).

RTL rtl/hbm_accel/sm/repack/h2a/ot_hbm_smh_rp4ah.sv: ot_hbm_smh_rp4ah_n / _s (rp4h halves + the attention leaf
ot_rp4a_leaf: x store, block-dot, 2 tcl_gu, tct, PV merge s3 as hard children; GN/GS/XB relays, see the RTL header).

FRAME (H.STA.BLK.9.1).  The safe x-store successor smh_xs_ring_p192c_1019 is 475.2 x 302.4 and its x-store band spans the
whole leaf width, so the frame width W fixes the x store's W / E channels (xs at x = W - 518.4):
  W 475.2 : xs flush with BOTH tile edges (x 0): its rl1 W-face pins on the tile edge, no channel for rl1 / the bin pin
            registers / the gather relays in the 302-um xs band (no relay site: every N->S lane crosses >= 400 um of
            macro) -> NOT a safe floorplan; option kept (--frame 475.2) for the re-plan record, not generated by default.
  W 561.6 : xs at x 43.2, 43.2-um W and E channels (818 rl1 wires up the W channel ~19/um: tight)   <- gated (diag)
  W 604.8 : xs at x 86.4, 86.4-um W channel / 43.2 E                                               <- gated (diag)
Leaf stack, every half (bottom-up; orientations = the track-legal ones of the closed children: tct R0 only, tcl R0, xs/bdc
MX): PV merge R0 y 43.2 (all pins N, facing the sums) | tct R0 y 388.8 (sum_i up) + row_w / row_e MX y 388.8 | bdc MX +
tcl_gu x2 R0 y 518.4 (sum_o down, operands up) | xs MX y 734.4 (operands down, bk1 up).  The stack order is forced by the
closed children's pin faces.  n: 1,425.6 tall (bin / bout faces need >= 345 um at <= 6 pins/um ABOVE the xs, beside its
bk1 face; soft beat in that band); s: 1,123.2 (86.4-um N band for the 2,069 landing registers).
Children: xs = DIAGNOSTIC STAND-IN smh_xs_p192c_standin (p192c not closed); bdc p50, tcl_gu, tct p45, rows (L2H-SM9 views)
CLOSED; PV merge = CLOSED smh_pvm_ref_s4a (record cf9c5a54b, ROOT merge to main pending).  With a stand-in these kits are
diagnostic only: gate, never submit.
    python3 tools/hbm_sm_repack_1015/rp4a_kit.py [--frame 561.6 --frame 604.8 ...]
"""
