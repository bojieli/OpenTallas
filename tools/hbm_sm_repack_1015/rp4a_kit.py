from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import rp4h_kit as H  # noqa: E402

ROOT = H.ROOT
RTL = "rtl/hbm_accel/sm/repack/h2a/ot_hbm_smh_rp4ah.sv"
BENCH_ONE = "rtl/hbm_accel/sm/repack/h2a/run_rp4ah2_one.sh"
WIT = "results/arch/l2h_rp4a_1019/bench/g211"
V = dict(H.V)
V.update({"xs": "physical/ref_tile/smh_xs_p192c_standin/views/ot_hbm_accel_smh_xs",
          "tcl": "physical/ref_tile/smh_tcl_gu_ref/views/ot_hbm_accel_smh_tcl_gu",
          "pvm": "physical/ref_tile/smh_pvm_ref_s4a/views/ot_hbm_sm_pv_merge_s3"})
STANDIN = {"xs": "smh_xs_ring_p192c_1019 (475.2 x 302.4, gate WARN clean, COORD review) not closed"}
EXTRA_SRC = ["rtl/hbm_accel/sm/ot_hbm_accel_smh_gu.sv",
             "physical/asap7_memory_macros/ot_sram_1r1w_64x512_m1_r2c2_p192_mir/ot_sram_1r1w_64x512_m1_r2c2_p192_mir_bb.v",
             "rtl/hbm_accel/sm/attn/ot_hbm_sm_pv_merge_s3.sv", "rtl/hbm_accel/sm/repack/h2/ot_hbm_smh_rp4h.sv", RTL]
HN, HS = 1425.6, 1123.2
K = 32


def leaf(j, dx):
    p = f"u_lf{j}"
    return [("pvm", f"{p}.u_merge", 43.2 + dx, 43.2, "R0"),
            ("tct", f"{p}.u_qk", 216.0 + dx, 388.8, "R0"),
            ("bdc", f"{p}.u_bdc", 43.2 + dx, 518.4, "MX"),
            ("tcl", f"{p}.u_h0", 216.0 + dx, 518.4, "R0"),
            ("tcl", f"{p}.u_h1", 345.6 + dx, 518.4, "R0"),
            ("xs", f"{p}.u_xs", 43.2 + dx, 734.4, "MX")]


def kits(W):
    dx = round(W - 561.6, 2)
    t = f"w{int(round(W))}"
    rows = lambda j: [("roww", f"u_row{j}", 86.4 + dx, 388.8, "MX"), ("rowe", f"u_rowe{j}", 475.2 + dx, 388.8, "MX")]
    return {
        f"smh_rp4ahn_{t}_standin": dict(half="n", w=W, h=HN, dx=dx, kids=leaf(0, dx) + rows(0)),
        f"smh_rp4ahs_{t}_standin": dict(half="s", w=W, h=HS, dx=dx, kids=leaf(1, dx) + rows(1)),
    }


# abutment face (n S / s N): same x ranges so bit i meets bit i
XR = {"b": (4.32, 410.4), "rst_n": (412.56, 413.64), "g0": (415.8, 428.76), "gp": (430.92, 461.16)}


def pins(half, h):
    c = H.CROSS[half]
    cy = round(h / 2, 2)
    rng = {"clk": (cy - 0.54, cy + 0.54)}
    if half == "n":
        p = {"W": ["rin_n", "clk", "bin"], "E": ["rout_n", "bout"],
             "N": ["gin", "xs_a1", "xs_g1", "xs_a2", "xs_g2", "attn"], "S": [c["b"], "rst_n", c["g0"], c["gp"]]}
        rng.update({"rin_n": (302.4, 475.2), "bin": (1041.12, 1420.56), "rout_n": (302.4, 475.2), "bout": (1041.12, 1420.56),
                    "gin": (216.0, 248.4), "xs_a1": (250.56, 254.88), "xs_g1": (257.04, 259.2), "xs_a2": (261.36, 264.6),
                    "xs_g2": (266.76, 268.92), "attn": (271.08, 273.24)})
    else:
        p = {"W": ["rin_s", "clk"], "E": ["rout_s"], "S": ["gout", "xss_a1", "xss_g1", "xss_a2", "xss_g2", "attn"],
             "N": [c["b"], "rst_n", c["g0"], c["gp"]]}
        rng.update({"rin_s": (302.4, 475.2), "rout_s": (302.4, 475.2), "gout": (216.0, 280.8), "xss_a1": (285.12, 289.44),
                    "xss_g1": (291.6, 293.76), "xss_a2": (295.92, 299.16), "xss_g2": (301.32, 303.48), "attn": (305.64, 307.8)})
    rng.update({c["b"]: XR["b"], "rst_n": XR["rst_n"], c["g0"]: XR["g0"], c["gp"]: XR["gp"]})
    return p, {k: [lo, hi] for k, (lo, hi) in rng.items()}


def stations(name, half, h, dx):
    src = (H.SPECS / "smh_tile_rp4lp_stations.tcl").read_text()
    head = src[:src.index("st_group gl0_mid")]
    body = head[head.index("set ::sr_blk"):]
    hdr = (f"# L2H-SMATT/RP4A {name}: generated by tools/hbm_sm_repack_1015/rp4a_kit.py (procs from smh_tile_rp4lp_stations.tcl).\n"
           "# Gather relay stages FIRM at fixed stations in the free corridors (E of the columns / E channel of the x store):\n"
           "# every N->S gather hop <= ~375 um.\n")
    if half == "n":
        y3, y2, y1 = round(h * 0.75, 1), 712.8, 367.2
        g = (f"st_group gl0_mid {{u_gn.g_gl[0].u_v2/ u_gn.g_gl[0].u_d2/ u_gn.g_gl\\[0\\].u_v2/ u_gn.g_gl\\[0\\].u_d2/}} {300 + dx} {y3} 50\n"
             f"st_group gl1_mid {{u_gn.g_gl[1].u_v2/ u_gn.g_gl[1].u_d2/ u_gn.g_gl\\[1\\].u_v2/ u_gn.g_gl\\[1\\].u_d2/}} {330 + dx} {y3} 50\n"
             f"st_group xpr0 {{u_xpr.g_s[0]. u_xpr.g_s\\[0\\].}} {490 + dx} {y2} 100\n"
             f"st_group xgr0 {{u_xgr.g_s[0]. u_xgr.g_s\\[0\\].}} {530 + dx} {y2} 50\n"
             f"st_group xpr1 {{u_xpr.g_s[1]. u_xpr.g_s\\[1\\].}} {490 + dx} {y1} 100\n"
             f"st_group xgr1 {{u_xgr.g_s[1]. u_xgr.g_s\\[1\\].}} {530 + dx} {y1} 50\n")
    else:
        g = (f"st_group xg2_mid {{u_xg2.}} {530 + dx} 748.8 50\n"
             f"st_group xp2_mid {{u_xp2.}} {540 + dx} 790.0 100\n"
             f"st_group xg3 {{u_xg3.g_s[0]. u_xg3.g_s\\[0\\].}} {500 + dx} 367.2 50\n"
             f"st_group xp3 {{u_xp3.g_s[0]. u_xp3.g_s\\[0\\].}} {530 + dx} 367.2 100\n")
    return hdr + body + g + 'puts "RP4_STATION fixed $::sr_fixed"\n'


def benches():
    out = [{"name": "h2a_lockstep", "cmd": f"bash {BENCH_ONE} {{RUN}}/h2a 0 1 13 2 1 1", "expect": "pass",
            "pass_regex": "^H2A_LOCKSTEP PASS MUT=0 compared=", "pass_witness": f"{WIT}/mut0.log", "threads": 4,
            "peak_ram_gb": 24}]
    for m in (1, 2, 3, 5):
        out.append({"name": f"h2a_mut{m}", "cmd": f"bash {BENCH_ONE} {{RUN}}/h2am{m} {m} 1 13 2 1 1", "expect": "fail",
                    "fail_regex": f"^H2A_LOCKSTEP FAIL MUT={m} mismatches=[1-9]", "fail_witness": f"{WIT}/mut{m}.log",
                    "threads": 4, "peak_ram_gb": 24})
    return out


def spec(name, k, base):
    hk = dict(half=k["half"], h=k["h"], params={}, kids=[], desc="", ranges={"W": {}, "E": {}})
    s = H.spec(name, hk, base)                      # the rp4h half spec (defines, route, reset / pin-reg reasons)
    half, h, W, dx = k["half"], k["h"], k["w"], k["dx"]
    s["name"] = name
    s["diagnostic"] = True
    s["top"] = f"ot_hbm_smh_rp4ah_{half}"
    s["params"] = {"SOFTBEAT": 1, "GN": 2, "XB": 1} if half == "n" else {"GN": 2, "GS": 1, "XB": 1}
    s["sources"] = [f for f in s["sources"] if f not in EXTRA_SRC] + EXTRA_SRC
    s["outline"] = {"w": W, "h": h}
    s["children"] = [{"view": V[v], "count": 1, "at": [x, y], "orient": o, "inst": i} for v, i, x, y, o in k["kids"]]
    s["pins"], s["pin_ranges"] = pins(half, h)
    st = f"physical/ref_tile_specs/smh/{name}_stations.tcl"
    (ROOT / st).write_text(stations(name, half, h, dx))
    s["orfs_vars"] = {"OT_IO_REF_CLASS": "1", "POST_TAPCELL_TCL": st, "OT_CKKM_K": str(K), "OT_CKKM_PORT": "clk"}
    s["clock"] = "cts"
    s["pre_cts_extra"] = ["physical/common_flow/clock_split_km.tcl"]
    s["route"] = dict(s["route"], io_hold_margin_ns=0.03, hold_margin_ns=0.03)
    s["pin_regs"]["reason"] += "  rp4a: the static attn strap lands in 2 kept stages (u_as_n / u_as_s)."
    s["standins"] = {v: STANDIN[v] for v in STANDIN}
    s["job"] = {
        "owner": "Claude LEAD3-HBM/L2H-SMATT/RP4A", "branch": "claude/l2h-rp4a-1019", "tag": name.replace("smh_", ""),
        "purpose": (f"DIAGNOSTIC (x store = stand-in; never submit): HBM SM attention tile rp4a ({half} half, frame {W} x "
                    f"{h}) as two hardened halves from the L2H-SM9 rp4 halves; geometry / clock / congestion evidence for "
                    "the 475.2+ SM frame re-plan (H.STA.BLK.9.1) and the rp4a parent (H.STA.BLK.14.6)."),
        "structural_change": (
            "rp4h halves (L2H-SM9) with the attention leaf (ot_hbm_sm_attn_leafh native column inlined: x store, block-dot, "
            "2 tcl_gu, tct, PV merge s3 SAFE2 hard; sync glue resets; static attn straps registered); leaf stack forced by "
            "the closed children's pin faces (PVM R0 bottom, tct R0, tcl/bdc, xs MX, all on 43.2); regional k-means clock "
            f"roots K={K} (clock_split_km.tcl, clk on the W face at half height); GN/GS kept gather relays (+3 uniform on "
            "gout, priced) and XB beat-crossing relay keep every hop <= ~375 um; io_hold_margin 0.03."),
        "extra_paths": ["tools/hbm_sm_repack_1015", "rtl/hbm_accel/sm/repack/h2", "rtl/hbm_accel/sm/repack/h2a",
                        "results/arch/l2h_rp4a_1019/bench"],
        "benches": benches()}
    return s


