def write_readme(name, k, s):
    rows = []
    for c in s["children"]:
        st = "STAND-IN (diagnostic)" if "standin" in c["view"] else ("CLOSED record cf9c5a54b (ROOT merge pending)" if "pvm" in c["view"] else "CLOSED")
        rows.append(f"| {c['inst']} | `{c['view']}` {c['orient']} @ {c['at']} | {st} |")
    asp = k["h"] / k["w"]
    note = "<= 2:1 PASS" if asp <= 2.0 + 1e-6 else ("WAIVED-diag: the leaf stack order is forced by the closed children's pin faces and "
            "the 2,069-pin bin / bout faces must sit above the xs bk1 face; side-by-side PVM | columns form (~691 wide, aspect ~1.75) is the re-plan alternative")
    gl = 3
    (ROOT / "physical/ref_tile" / name / "README.md").write_text(README.format(
        name=name, half=k["half"], w=k["w"], h=k["h"], asp=asp, kids="\n".join(rows), gn=2, k=K, aspnote=note, gl=gl, gt=3 + gl))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--frame", type=float, action="append", help="frame width(s), default 561.6 and 604.8")
    a = ap.parse_args()
    base = json.loads(H.BASE.read_text())
    for W in (a.frame or [561.6, 604.8]):
        for name, k in kits(W).items():
            s = spec(name, k, base)
            kd = ROOT / "physical/ref_tile" / name
            kd.mkdir(parents=True, exist_ok=True)
            (kd / "spec.json").write_text(json.dumps(s, indent=1) + "\n")
            write_readme(name, k, s)
            print(f"{kd / 'spec.json'}: {len(s['children'])} children, outline {W} x {k['h']} (aspect {k['h'] / W:.2f})")


if __name__ == "__main__":
    main()
