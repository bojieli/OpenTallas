#!/usr/bin/env python3
"""Produce additive production-shape SM clock-entry RTL from the actual tile.
No arithmetic/storage/control stage is changed. Closed source stays byte-identical.
Generated RTL is a candidate until full lockstep, area, pin/cut and native gates.
"""
import argparse,hashlib,json,pathlib,re,subprocess,tempfile
ROOT=pathlib.Path(__file__).resolve().parents[2]
SOURCE='rtl/hbm_accel/sm/ot_hbm_accel_smh.sv'
OUT='rtl/hbm_accel/sm/repack/ot_hbm_smh_rp4_clocks.sv'
def swap(s,a,b,n=1):
 if s.count(a)!=n:raise ValueError(f'expected {n} exact occurrences of {a!r}, got{s.count(a)}')
 return s.replace(a,b)
def main():
 spec=json.loads((ROOT/'physical/ref_tile/smh_tile_rp3/spec.json').read_text())
 with tempfile.TemporaryDirectory() as td:
  dest=pathlib.Path(td)/'production.sv'
  subprocess.run(['iverilog','-E','-g2012','-DSYNTHESIS',*['-D'+x for x in spec['defines']],'-o',str(dest),SOURCE],cwd=ROOT,check=True)
  alltext=dest.read_text()
 def mod(name):
  m=re.search(r'^module '+re.escape(name)+r'\b.*?^endmodule',alltext,re.M|re.S)
  if not m:raise ValueError(name)
  return m[0]
 tcc=mod('ot_hbm_accel_smh_tcc').replace('module ot_hbm_accel_smh_tcc','module ot_hbm_smh_rp4_tcc',1)
 tcc=swap(tcc,'input  wire clk, input wire rst_a,','input wire [2:0] clk_hard, input wire rst_a,')
 for i,inst in enumerate(['u_h0','u_h1','u_tr']):
  tcc=swap(tcc,inst+' (.clk(clk)',inst+f' (.clk(clk_hard[{i}])')
 leaf=mod('ot_hbm_accel_smh_leafh').replace('module ot_hbm_accel_smh_leafh','module ot_hbm_smh_rp4_leafh',1)
 leaf=swap(leaf,'input  wire clk, input wire rst_n,','input wire clk, clk_xb, clk_xf, input wire [4:0] clk_hard, input wire rst_n,')
 leaf=swap(leaf,'u_xs (.clk(clk)','u_xs (.clk(clk_hard[0])')
 leaf=swap(leaf,'u_bdc (.clk(clk)','u_bdc (.clk(clk_hard[1])')
 leaf=swap(leaf,'ot_hbm_accel_smh_tcc','ot_hbm_smh_rp4_tcc')
 leaf=swap(leaf,'u_tcc (.clk(clk)','u_tcc (.clk_hard(clk_hard[4:2])')
 old='''always @(posedge clk or negedge r_x)
        if (!r_x) begin xb_v <= 1'b0; xf_v <= 1'b0; end
        else begin xb_v <= iv_b; xf_v <= iv_f; end'''
 new='''always @(posedge clk_xb or negedge r_x) if (!r_x) xb_v<=0; else xb_v<=iv_b;
    always @(posedge clk_xf or negedge r_x) if (!r_x) xf_v<=0; else xf_v<=iv_f;'''
 leaf=swap(leaf,old,new)
 leaf=swap(leaf,'always @(posedge clk) begin\n        xb_first','always @(posedge clk_xb) begin\n        xb_first')
 leaf=swap(leaf,'        xf_first <= ifirst_e;', '    end\n    always @(posedge clk_xf) begin\n        xf_first <= ifirst_e;')
 core=mod('ot_hbm_accel_smh_tile').replace('module ot_hbm_accel_smh_tile','module ot_hbm_smh_rp4_core',1)
 core=swap(core,'input  wire                     clk,','input wire [17:0] clk_hard, input wire [2:0] clk_pin, input wire [3:0] clk_oper, input wire [2:0] clk_region,')
 core=core.replace('ot_hbm_accel_smh_rst_tree u_rt (.clk(clk)','ot_hbm_smh_rp4_rst u_rt (.clk_region(clk_region)')
 core=swap(core,'u_r (.clk(clk)','u_r (.clk(clk_pin[pj])')
 for inst in ['u_pbv','u_pbd']:core=swap(core,inst+' (.clk(clk)',inst+' (.clk(clk_pin[2])')
 core=core.replace('ot_hbm_smh_compact_pt_w','ot_hbm_smh_rp4_ptw').replace('ot_hbm_smh_compact_pt_e','ot_hbm_smh_rp4_pte')
 core=swap(core,'u_ptw (.clk(clk)','u_ptw (.clk_hard({clk_hard[16:14],clk_hard[11:10]})')
 core=swap(core,'u_pte (.clk(clk)','u_pte (.clk_hard({clk_hard[17],clk_hard[13:12]})')
 core=swap(core,'ot_hbm_accel_smh_leafh','ot_hbm_smh_rp4_leafh')
 core=swap(core,'.clk(clk), .rst_n(r_lh[j])','.clk(clk_region[j==0?0:2]), .clk_xb(clk_oper[2*j]), .clk_xf(clk_oper[2*j+1]), .clk_hard(clk_hard[j*5+:5]), .rst_n(r_lh[j])')
 for inst in ['u_grv1','u_grd1']:core=swap(core,inst+' (.clk(clk)',inst+' (.clk(clk_region[j==0?0:2])')
 for inst in ['u_grv2','u_grd2']:core=swap(core,inst+' (.clk(clk)',inst+' (.clk(clk_region[j==0?1:2])')
 for inst in ['u_gov','u_god']:core=swap(core,inst+' (.clk(clk)',inst+' (.clk(clk_region[2])')
 for suffix,index in [('',0),('2',1),('3',2)]:
  for inst in ['u_v'+suffix,'u_d'+suffix]:core=swap(core,inst+' (.clk(clk)',inst+f' (.clk(clk_region[{index}])')
 if re.search(r'\(clk\)|posedge\s+clk\b',core):raise ValueError('unassigned core clock')
 support=(ROOT/'tools/hbm_sm_repack_1015/local_clock_support.sv').read_text()
 text='// Generated by tools/hbm_sm_repack_1015/local_clock_source.py; production shape only.\n'+tcc+'\n'+leaf+'\n'+core+'\n'+support
 out=ROOT/OUT;out.parent.mkdir(parents=True,exist_ok=True);out.write_text(text)
 manifest={'schema':'opentallas.sm_rp4_clock_source.v1','source':SOURCE,'source_sha256':hashlib.sha256((ROOT/SOURCE).read_bytes()).hexdigest(),'defines':['SYNTHESIS']+spec['defines'],'generated':OUT,'generated_sha256':hashlib.sha256(out.read_bytes()).hexdigest(),'scope':'candidate clock partition, no physical or fullSM qualification','hard_entries':18,'soft_entries':10,'normal_edges_added':0}
 (out.parent/'source_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
