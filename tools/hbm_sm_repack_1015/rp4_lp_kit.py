#!/usr/bin/env python3
"""PL-SMT (PARENTS-LANDED 10-18): ref_tile spec for the LANDED HBM SM tile rp4 (kit smh_tile_rp4lp, top ot_hbm_smh_rp4_lpt).

Derived from the rp4m kit (physical/ref_tile/smh_tile_rp4m/spec.json): same 18 CLOSED child views, same relative child
placement, same data pin plan; changes:
  * top = ot_hbm_smh_rp4_flat_lp (the lp.py output itself; rin / rout are split per region: rin_n / rout_n = old
    bits 817:0 on the N half of the W / E faces, rin_s / rout_s = old bits 1635:818 on the S half; the die binder slices);
  * clock = PL-KIT LANDED CLUSTER (10-18, origin/main 112f518d5): clock "multiple_cts_roots", one TritonCTS root per lp
    region (ck_n = core_clk on the N face where the old clk pin was, ck_s on the S face beside the gout / xss pins),
    landed_record = the lp record (landing multicycles + per-root IO domains generated by ref_tile; no sdc_extra, no spine).
    Gate 1 (spine form, 10-18 06:41) showed why: the spine-form S-root IO was timed against a virtual clock whose latency
    did not match the ck_s tree (FF hold -957 ps on 1,282 rin_s / xss_* -> u_pr_s / u_sr_s endpoints, 33k hold buffers,
    setup -220 on u_pr_s.u_r.g_p.u_v), which then stalled GRT/repair past the 4 h guard;
  * outline 457.92 x 1598.4 (H-D4G5/SMFRAME GEN2 rp4 row height, +69.12): the S half (leaf 1, land_s, row 1) keeps its
    place, the N half (beat_t / pte beat, row 0, land_n, leaf 0) and the N face pins move up 69.12, which opens a
    ~91 um W-column band between row 1 and beat_t for the bin landing (ring 8,276 + read 2,069 flops) and the leaf-1 pads;
  * gather mid stations re-targeted to the new instance names (N-region u_gn stages).
Children stay on the 4.32 um lattice as in rp4m (43.2 is infeasible for the 11-high stack even at 1598.4: 1676 um
with >= 21.6 um channels and land->xs >= 43.2; see lanes/PL-SMT.md).

  python3 tools/hbm_sm_repack_1015/rp4_lp_kit.py      -> physical/ref_tile/smh_tile_rp4lp/spec.json (+ pins / stations / sdc)
then: python3 tools/ref_tile/ref_tile.py gen physical/ref_tile/smh_tile_rp4lp/spec.json
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "physical/ref_tile/smh_tile_rp4m/spec.json"
NAME = "smh_tile_rp4lp"
KIT = ROOT / "physical/ref_tile" / NAME
SPECS = ROOT / "physical/ref_tile_specs/smh"
H0, H = 1529.28, 1598.4
DH = round(H - H0, 3)
Y_SPLIT = 650.0             # children at y >= this (beat_t, pte beat, row 0, land_n, leaf 0) move up DH
SPLIT = 818                 # rin / rout bits >= SPLIT belong to region s (lp ports rin_s / rout_s)
RECORD = "results/arch/landed_parent_1018/pl_smt/ot_hbm_smh_rp4_flat_lp_record.json"
INST = {   # rp4m instance pattern -> landed-parent hierarchy (kit top ot_hbm_smh_rp4_lpt, lp module instance u)
    "u.g_lf?0?.u_lh.u_xs": "u_lf0.u_lh.u_xs", "u.g_lf?0?.u_lh.u_bdc": "u_lf0.u_lh.u_bdc",
    "u.g_lf?0?.u_lh.u_tcc.u_h0": "u_lf0.u_lh.u_tcc.u_h0", "u.g_lf?0?.u_lh.u_tcc.u_h1": "u_lf0.u_lh.u_tcc.u_h1",
    "u.g_lf?0?.u_lh.u_tcc.u_tr": "u_lf0.u_lh.u_tcc.u_tr",
    "u.g_lf?1?.u_lh.u_xs": "u_lf1.u_lh.u_xs", "u.g_lf?1?.u_lh.u_bdc": "u_lf1.u_lh.u_bdc",
    "u.g_lf?1?.u_lh.u_tcc.u_h0": "u_lf1.u_lh.u_tcc.u_h0", "u.g_lf?1?.u_lh.u_tcc.u_h1": "u_lf1.u_lh.u_tcc.u_h1",
    "u.g_lf?1?.u_lh.u_tcc.u_tr": "u_lf1.u_lh.u_tcc.u_tr",
    "u.u_ptw.u_land_s": "u_land_s", "u.u_ptw.u_row1": "u_row1", "u.u_ptw.u_beat_t": "u_beat_t",
    "u.u_ptw.u_row0": "u_row0", "u.u_ptw.u_land_n": "u_land_n",
    "u.u_pte.u_row1": "u_rowe1", "u.u_pte.u_beat": "u_beate", "u.u_pte.u_row0": "u_rowe0"}
REGION = {"n": ["u_lf0.", "u_row0", "u_land_n", "u_beat_t", "u_rowe0", "u_beate"],
          "s": ["u_lf1.", "u_row1", "u_land_s", "u_rowe1"]}


def pins_tcl():
    src = (SPECS / "smh_tile_rp4h_pins.tcl").read_text().splitlines()
    out = [f"# generated by tools/hbm_sm_repack_1015/rp4_lp_kit.py from smh_tile_rp4h_pins.tcl: outline 457.92 x {H}; N face "
           f"pins y {H0} -> {H}; clk -> ck_n (N face, same site); ck_s added on the S face (x 299.98 M5, E of the gout pins)"]
    n = 0
    for ln in src:
        if not ln.startswith("place_pin"):
            continue
        ln = ln.replace(f" {H0:.3f}}}", f" {H:.3f}}}")
        ln = ln.replace("-pin_name {clk}", "-pin_name {ck_n}")
        ln = re.sub(r"-pin_name \{(rin|rout)\[(\d+)\]\}",
                    lambda m: f"-pin_name {{{m.group(1)}_n[{m.group(2)}]}}" if int(m.group(2)) < SPLIT
                    else f"-pin_name {{{m.group(1)}_s[{int(m.group(2)) - SPLIT}]}}", ln)
        out.append(ln)
        n += 1
    out.append("place_pin -pin_name {ck_s} -layer M5 -location {299.980 0.000} -pin_size {0.024 0.192} -force_to_die_boundary")
    return "\n".join(out) + "\n", n + 1


def stations_tcl():
    src = (SPECS / "smh_tile_rp4_stations.tcl").read_text()
    head = src[:src.index("st_group gl2_mid")]
    head = head.replace('if {$n == 0} {error "RP4_STATION $name: no DFFs"}',
                        'if {$n == 0} {puts "RP4_STATION WARNING $name: no DFFs matched ($pats)"; odb::dbGroup_destroy $gr; return}')
    y = 765 + DH / 2
    return ("# PL-SMT rp4lp: generated by tools/hbm_sm_repack_1015/rp4_lp_kit.py from smh_tile_rp4_stations.tcl (procs unchanged;\n"
            "# a group that matches no DFF warns instead of failing).  The N-region mid stages of the N->S gather lanes\n"
            "# (u_gn: pass lanes u_v2/u_d2, leaf-0 u_grv2/u_grd2) FIRM at mid-tile; their outputs enter the n->s landings.\n"
            + head +
            f"st_group gl0_mid {{u_gn.g_gl[0].u_v2/ u_gn.g_gl[0].u_d2/ u_gn.g_gl\\[0\\].u_v2/ u_gn.g_gl\\[0\\].u_d2/}} 205 {y:.1f} 50\n"
            f"st_group gl1_mid {{u_gn.g_gl[1].u_v2/ u_gn.g_gl[1].u_d2/ u_gn.g_gl\\[1\\].u_v2/ u_gn.g_gl\\[1\\].u_d2/}} 265 {y:.1f} 50\n"
            f"st_group lf0_mid {{u_gn.u_grv2/ u_gn.u_grd2/}} 325 {y - 65:.1f} 50\n"
            'puts "RP4_STATION fixed $::sr_fixed"\n')


def main():
    s = json.loads(SRC.read_text())
    s["name"] = NAME
    s["top"] = "ot_hbm_smh_rp4_flat_lp"
    src = [f for f in s["sources"] if not f.endswith("ot_hbm_smh_rp4_one.sv")]
    src += ["rtl/hbm_accel/sm/repack/ot_rp4l_children.sv", "rtl/common/landed_parent/ot_pl_land.sv",
            "rtl/hbm_accel/sm/repack/lp/ot_hbm_smh_rp4_flat_lp.sv"]
    s["sources"] = src
    s["clock_port"] = "ck_n"
    s["clock_ports"] = ["ck_n", "ck_s"]
    # PL-KIT landed cluster: one CTS root per lp region, related same-frequency roots, IO per region root
    s["clock"] = "multiple_cts_roots"
    s["clock_data_paths"] = "related_same_frequency"
    s["clock_relationship"] = {"kind": "same_pll_fixed_phase", "ratio": [1, 1], "phase_ps": 0}
    s["clock_entry_domains"] = {
        "core": {"ratio": [1, 1], "ports": ["ck_n"],
                 "inputs": ["rst_n", "xs_a1", "xs_g1", "xs_a2", "xs_g2", "rin_n", "bin", "gin"], "outputs": ["rout_n", "bout"]},
        "s": {"ratio": [1, 1], "ports": ["ck_s"],
              "inputs": ["xss_a1", "xss_g1", "xss_a2", "xss_g2", "rin_s"], "outputs": ["rout_s", "gout"]}}
    s["landed_record"] = RECORD
    s["outline"] = {"w": 457.92, "h": H}
    for c in s["children"]:
        c["inst"] = INST[c["inst"]]
        if c["at"][1] >= Y_SPLIT:
            c["at"] = [c["at"][0], round(c["at"][1] + DH, 3)]
        c["region"] = "n" if any(c["inst"].startswith(p) for p in REGION["n"]) else "s"
    s["pins"]["N"] = [p if p != "clk" else "ck_n" for p in s["pins"]["N"]]
    s["pins"]["W"] = [q for p in s["pins"]["W"] for q in ((p + "_n", p + "_s") if p == "rin" else (p,))]
    s["pins"]["E"] = [q for p in s["pins"]["E"] for q in ((p + "_n", p + "_s") if p == "rout" else (p,))]
    s["pins"]["S"] = s["pins"]["S"] + ["ck_s"]
    pt, npins = pins_tcl()
    (SPECS / f"{NAME}_pins.tcl").write_text(pt)
    (SPECS / f"{NAME}_stations.tcl").write_text(stations_tcl())
    old_sdc = SPECS / f"{NAME}_regions.sdc"
    if old_sdc.exists():
        old_sdc.unlink()   # spine-form sdc_extra; PL-KIT generates the landing multicycles and per-root IO
    s["io_tcl"] = f"physical/ref_tile_specs/smh/{NAME}_pins.tcl"
    s["orfs_vars"] = dict(s.get("orfs_vars", {}), POST_TAPCELL_TCL=f"physical/ref_tile_specs/smh/{NAME}_stations.tcl")
    s["orfs_vars"].pop("OT_SPINE_PORTS", None)
    s.pop("sdc_extra", None)
    s["pin_regs"] = dict(s["pin_regs"], reason=(
        "Actual RTL pin capture and launch registers retained from rp4 (rin / bin pin flops in ot_rp4l_pinrow / pinbeat, "
        "rout / bout launched by the hard row_e / beat_e cells, gin / gout by the gather registers, xs_* through the five-stage "
        "straps); TWO regional roots (ck_n, ck_s, lp.py landed regions), every n->s data net landed (bin_l 2,069 b, leaf-0 "
        "gather 50 b, pass-through gather 100 b), 1-bit reset runs only. External gating companion separate as rp4m."))
    s["job"] = {
        "owner": "Claude PL-SMT (PARENTS-LANDED)", "branch": "claude/pl-smt-1018", "tag": "rp4lp",
        "purpose": "MATVEC body clock-structure closure as LANDED REGIONS (landed-regions-standard-1018); not attention/fullSM/native chip qualification.",
        "structural_change": (
            "rp4lp (PL-SMT 10-18, landed-regions-standard-1018): rp4m ran ONE balanced spine over 457.92 x 1529.28 um (TT insertion "
            "1.53 ns, child-flop boundary ~91 ps). Now 2 clock regions from tools/landed_parent/lp.py (spec "
            "results/arch/landed_parent_1018/pl_smt/rp4_lp_spec.json): n = leaf 0 + row 0 + the whole bin beat path (pin flops, beat_t, "
            "pte beat, land_n) + N gather relays; s = leaf 1 + row 1 + land_s + S-edge gather outputs. Minimum-crossing cut (bin is "
            "broadcast to land_n, beat_t and land_s): 3 landings (bin_l->land_s 2,069 b, leaf-0 gather 50 b, pass gather 100 b; ring "
            "D4/E=K=2, +3 edges), pads 3 x (818 + 26) b in front of leaf 1, reset runs depth 3 replace the 5-stage u_rt tree. "
            "Ports: kit top = lp output ot_hbm_smh_rp4_flat_lp (rin / rout split per region: rin_n / rout_n = old 817:0, rin_s / rout_s = old 1635:818), clk -> ck_n + ck_s; offsets gout +3, all others 0. PL-KIT landed-cluster clock (multiple_cts_roots per region, landed_record) replaces the gate-1 spine form, whose S-root IO latency mismatch gave FF hold -957 ps on 1,282 S-region input endpoints. "
            f"Outline h 1529.28 -> {H} (GEN2 SM frame row): N half +{DH}. Same 18 CLOSED child views."),
        "extra_paths": ["physical/common_flow/anchor_row_packing.tcl", "tools/hbm_sm_repack_1015", "tools/landed_parent",
                        "results/arch/landed_parent_1018/pl_smt", "rtl/hbm_accel/sm/repack/lp"],
        "benches": [
            {"name": "lp_lockstep", "expect": "pass", "pass_regex": "BENCH_EXIT 0", "threads": 8, "peak_ram_gb": 40,
             "cmd": "LP_ROOT=$PWD SIM=verilator bash rtl/hbm_accel/sm/repack/lp/ot_hbm_smh_rp4_flat_lp_bench.sh {RUN}/lp"}]}
    s.pop("child_clock_ref", None)
    s["child_clock_ref"] = "boundary"
    KIT.mkdir(parents=True, exist_ok=True)
    (KIT / "spec.json").write_text(json.dumps(s, indent=1) + "\n")
    print(f"{KIT / 'spec.json'}: {len(s['children'])} children, pins {npins}, sources {len(src)}")


if __name__ == "__main__":
    main()
