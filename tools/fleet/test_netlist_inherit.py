import json
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import netlist_inherit as N  # noqa: E402

A = r"""/* Generated by Yosys */
(* keep_hierarchy =  1  *)
module \$paramod$aa\sub (a, y);
  input [1:0] a;
  wire [1:0] a;
  output y;
  wire y;
  AND2x2_ASAP7_75t_R \g1  ( .A(a[0]), .B(a[1]), .Y(y) );
endmodule
module typeA (clk, d, q, r);
  input clk; input [1:0] d; output q; output [3:0] r;
  wire _0_; wire n1; wire n2;
  \$paramod$aa\sub u_s ( .a(d), .y(_0_) );
  DFFHQNx1_ASAP7_75t_R q_reg ( .CLK(clk), .D(_0_), .QN(n1) );
  INVx1_ASAP7_75t_R i0 ( .A(n1), .Y(q) );
  BUFx2_ASAP7_75t_R b0 ( .A(n1), .Y() );
  BUFx2_ASAP7_75t_R b1 ( .A(n1), .Y() );
  ot_rom_4096x72_m8 #(.INSTANCE("img_a")) u_rom ( .CLK(clk), .A({ d, 1'b0 }), .Q(r[2:0]) );
  assign r[3] = 1'b1;
endmodule
"""


def rename(text):
    return (text.replace("typeA", "typeB").replace("q_reg", "zz_reg").replace("img_a", "img_b").replace("u_s ", "u_t ")
            .replace("_0_", "_9_").replace("$aa", "$bb").replace(" b0 ", " c7 ").replace(" b1 ", " c3 "))


def g(text, lefs=None):
    return N.build(N.parse(text), lef_sigs=lefs or {})


def test_names_and_rom_image_do_not_matter():
    r = N.isomorphism(g(A), g(rename(A)))
    assert r["isomorphic"], r["why"]
    assert N.structural_hash(g(A))[0] == N.structural_hash(g(rename(A)))[0] == r["structural_hash"]


def test_symmetric_cells_are_individualised_and_checked():
    r = N.isomorphism(g(A), g(rename(A)))
    assert r["isomorphic"] and r["cmap"] is not None


@pytest.mark.parametrize("mut", [
    lambda t: t.replace("INVx1_ASAP7_75t_R", "BUFx4_ASAP7_75t_R"),             # different master
    lambda t: t.replace(".A(n1), .Y(q)", ".A(_0_), .Y(q)"),                     # different connection
    lambda t: t.replace("assign r[3] = 1'b1;", "assign r[3] = 1'b0;"),         # different constant
    lambda t: t.replace("(clk, d, q, r)", "(clk, d, qq, r)").replace("output q;", "output qq;").replace(".Y(q)", ".Y(qq)"),  # port name
])
def test_real_differences_are_not_isomorphic(mut):
    assert not N.isomorphism(g(A), g(mut(A)))["isomorphic"]


def test_rom_of_another_size_is_not_masked(tmp_path):
    lef = tmp_path / "rom.lef"
    lef.write_text("MACRO ot_rom_4096x72_m8\n SIZE 10 BY 20 ;\n PIN CLK\n  DIRECTION INPUT ;\n END CLK\nEND ot_rom_4096x72_m8\n"
                   "MACRO ot_rom_2048x72_m8\n SIZE 10 BY 12 ;\n PIN CLK\n  DIRECTION INPUT ;\n END CLK\nEND ot_rom_2048x72_m8\n"
                   "MACRO ot_rom_4096x72_m8_b\n SIZE 10 BY 20 ;\n PIN CLK\n  DIRECTION INPUT ;\n END CLK\nEND ot_rom_4096x72_m8_b\n")
    sigs = N.lef_signatures([tmp_path])
    assert not N.isomorphism(g(A, sigs), g(A.replace("ot_rom_4096x72_m8", "ot_rom_2048x72_m8"), sigs))["isomorphic"]
    assert N.isomorphism(g(A, sigs), g(A.replace("ot_rom_4096x72_m8", "ot_rom_4096x72_m8_b"), sigs))["isomorphic"]


def kit(root, name, text, pins=None, sdc="create_clock -name clk -period 833\n"):
    k = root / name
    b = k / "run/results/asap7" / ("dp_" + name) / "base"
    b.mkdir(parents=True)
    (b / "1_2_yosys.v").write_text(text)
    (k / "pins.json").write_text(json.dumps(pins or [{"bus": "d", "bit": 0, "layer": "M5", "x": 1.0, "y": 0.0, "face": "S"}]))
    (k / "constraint.sdc").write_text(sdc.replace("NAME", name))
    (k / "config.mk").write_text("export DESIGN_NAME = %s\nexport DIE_AREA = 0 0 10 10\nexport CORE_AREA = 1 1 9 9\n" % name)
    return k


def signed(root):
    p = root / "rep_signoff.json"
    p.write_text(json.dumps(dict(checks=dict(drc=dict(count=0), setup_tt=dict(wns_ps=5.0), hold_ff=dict(wns_ps=1.0)),
                                 internal_hold=dict(schema="opentallas.internal_ff_hold.v1", complete=True, wns_ps=1.0, violators=0))))
    return p


def run_prove(tmp_path, member_text, pins=None, sdc_m=None):
    km = kit(tmp_path, "typeB", member_text, pins=pins, sdc=sdc_m or "create_clock -name clk -period 833\n# NAME\n")
    kr = kit(tmp_path, "typeA", A, sdc="create_clock -name clk -period 833\n# NAME\n")
    out = tmp_path / "rec.json"
    rc = N.main(["prove", "--die", "s81", "--member", "typeB", "--rep", "typeA", "--member-kit", str(km), "--rep-kit", str(kr),
                 "--rep-signoff", str(signed(tmp_path)), "--out", str(out)])
    return rc, json.loads(out.read_text())


def test_prove_credits_a_rom_and_name_sibling(tmp_path):
    rc, r = run_prove(tmp_path, rename(A))
    assert rc == 0 and r["credit"] and r["schema"] == N.SCHEMA and r["proof"]["isomorphic"]
    assert r["sibling"] == "typeB" and r["representative"] == "typeA"
    assert r["rom_views"]["status"] == "TO-GENERATE" and r["rom_views"]["instances"] == ["u_rom"]
    assert r["physical"]["checks"]["pins"] == "PASS" and r["physical"]["checks"]["sdc"] == "PASS"


def test_prove_blocks_on_pins(tmp_path):
    rc, r = run_prove(tmp_path, rename(A), pins=[{"bus": "d", "bit": 0, "layer": "M5", "x": 2.0, "y": 0.0, "face": "S"}])
    assert rc == 1 and not r["credit"] and any("physical" in b for b in r["credit_blockers"])


def test_prove_blocks_on_netlist(tmp_path):
    rc, r = run_prove(tmp_path, rename(A).replace("INVx1_ASAP7_75t_R", "BUFx4_ASAP7_75t_R"))
    assert rc == 1 and not r["credit"] and not r["proof"]["isomorphic"]
