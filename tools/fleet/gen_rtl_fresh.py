#!/usr/bin/env python3
"""gen_rtl_fresh.py -- GEN-FRESH (PRECHECK-R3 11-24, COORD on HEAD-EAST-REPLAN hub 6245e3a3; report only, never a gate).

A generated RTL file on main that no longer matches a fresh run of its generator is drift inside main itself: the next lane
that regenerates it (or a split generator that pattern-matches it) silently changes the netlist or fails.  Known positive:
rtl/dsrom_sys/s81_head/generated/ot_s81hd_lep_nr.sv predates the portfix178 ot_s81sl_slice_lep.sv WREP/RIP/ROS/CRP edits, so
`head_lep_nr_sources.py --check` says STALE and head_lep_split_sources.py (which derives from that file) fails on main.

Pairs: every rtl/ file whose first 8 lines say "generated by|from <generator>.py|.tcl" (and optionally "from <source>").
Per generator:
  FRESH        `python3 -I <gen> --check` exits 0 (generators that offer --check; required --record/--report/--json
               options get a throw-away path)
  STALE        --check exits non-zero with STALE / differ / mismatch in its message, or exits non-zero silently
               (no traceback, no message: the `sys.exit(0 if same else 1)` form)
  PINNED       --check exits 0 and says GEN-PINNED: the committed file was hand-evolved past the generator and is kept
               as the source of truth (GEN-FRESH-FIX 11-24); the generator refuses to overwrite it without --unpin
  GEN-FAIL     --check raises (traceback): the generator no longer runs on main
  NEEDS-ARGS   --check needs other required arguments (not run)
  NEEDS-FILES  --check hit a missing input file (a sparse lane clone lacks it: widen the cone and rerun)
  NO-CHECK     no --check mode; dated only: SOURCE-NEWER when the generator or the named source was committed after the
               generated file (a regeneration may be due), else DATED-OK
  MISSING-GEN  the named generator is not on main
Usage: gen_rtl_fresh.py [--repo DIR] [--only SUBSTR] [--timeout S] [--tsv OUT] [--no-run]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HDR = re.compile(r"(?i)generated\s+(?:by|from)\s+([A-Za-z0-9_./-]+?\.(?:py|tcl))\b")
SRC = re.compile(r"(?i)\bfrom\s+((?:rtl|physical|tools|results)/[A-Za-z0-9_./-]+?\.(?:sv|v|svh|json))\b")
EXT = (".sv", ".v", ".svh", ".vh")
STALE_RE = re.compile(r"(?i)stale|differ|mismatch|out of date|not up to date|would change")


def pairs(repo):
    """{generator: {"files": [rel], "sources": set(rel)}} from the rtl/ headers (generator paths resolved against the repo)"""
    out = {}
    base = Path(repo)
    for root, _d, files in os.walk(base / "rtl"):
        for fn in files:
            if not fn.endswith(EXT):
                continue
            p = Path(root) / fn
            try:
                with open(p, errors="replace") as f:
                    head = "".join(next(f, "") for _ in range(8))
            except OSError:
                continue
            m = HDR.search(head)
            if not m:
                continue
            g = m.group(1).rstrip(":")
            if not (base / g).is_file():                        # bare name ("face_shell.py"): look it up under tools/
                hits = [str(q.relative_to(base)) for q in (base / "tools").rglob(os.path.basename(g))][:1]
                g = hits[0] if hits else g
            e = out.setdefault(g, {"files": [], "sources": set()})
            e["files"].append(str(p.relative_to(base)))
            for s in SRC.findall(head):
                e["sources"].add(s)
    return out


def last_ct(repo, path, memo):
    if path not in memo:
        r = subprocess.run(["git", "-C", repo, "log", "-1", "--format=%ct %h", "--", path], capture_output=True, text=True, timeout=120)
        v = r.stdout.split()
        memo[path] = (int(v[0]), v[1]) if len(v) == 2 else (0, "")
    return memo[path]


def run_check(repo, gen, timeout):
    """-> (status, message)"""
    gp = Path(repo) / gen
    if gen.endswith(".tcl"):
        return "NO-CHECK", "tcl generator"
    txt = gp.read_text(errors="replace")
    if not re.search(r'[\'"]--check[\'"]', txt):      # a quoted --check argument, not a docstring mention
        return "NO-CHECK", ""
    with tempfile.TemporaryDirectory(prefix="genfresh_") as td:
        args = ["--check"]
        for opt in ("--record", "--report", "--json", "--manifest"):
            if re.search(r"add_argument\(\s*['\"]" + re.escape(opt) + r"['\"][^)]*required\s*=\s*True", txt):
                args += [opt, os.path.join(td, opt.strip("-") + ".json")]
        env = dict(os.environ, HOME=td, TMPDIR=td, PYTHONDONTWRITEBYTECODE="1")
        try:
            r = subprocess.run([sys.executable, "-I", str(gp)] + args, cwd=repo, capture_output=True, text=True, timeout=timeout, env=env)
        except subprocess.TimeoutExpired:
            return "TIMEOUT", f"--check over {timeout} s"
    msg = (r.stderr.strip().splitlines() or r.stdout.strip().splitlines() or [""])[-1][:240]
    if r.returncode == 0:
        pin = [ln for ln in (r.stdout + r.stderr).splitlines() if "GEN-PINNED" in ln]
        return ("PINNED", "; ".join(pin)[:240]) if pin else ("FRESH", msg)
    if "the following arguments are required" in r.stderr or "unrecognized arguments" in r.stderr:
        return "NEEDS-ARGS", msg
    if "FileNotFoundError" in r.stderr or "No such file" in r.stderr:
        return "NEEDS-FILES", msg                     # an input outside this checkout (sparse cone): widen it and rerun
    if "Traceback" in r.stderr and not STALE_RE.search(msg):
        return "GEN-FAIL", msg
    if STALE_RE.search(r.stderr + r.stdout):
        return "STALE", msg
    if "Traceback" not in r.stderr and not (r.stdout + r.stderr).strip():
        return "STALE", f"--check exit {r.returncode}, no message (silent compare)"
    return "GEN-FAIL", msg


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--only", default="")
    ap.add_argument("--timeout", type=float, default=180)
    ap.add_argument("--tsv")
    ap.add_argument("--no-run", action="store_true", help="dates only, run no generator")
    a = ap.parse_args(argv)
    repo = os.path.realpath(a.repo)
    P = pairs(repo)
    memo, rows = {}, []
    for gen in sorted(P):
        if a.only and a.only not in gen:
            continue
        e = P[gen]
        if not (Path(repo) / gen).is_file():
            rows.append(("MISSING-GEN", gen, e["files"], "generator not on main"))
            continue
        st, msg = ("NO-CHECK", "") if a.no_run else run_check(repo, gen, a.timeout)
        if st == "NO-CHECK":
            gct = max(last_ct(repo, x, memo)[0] for x in [gen] + sorted(e["sources"]))
            old = [f for f in e["files"] if last_ct(repo, f, memo)[0] and last_ct(repo, f, memo)[0] < gct]
            st, msg = ("SOURCE-NEWER", f"{len(old)} file(s) older than the generator/source commit; " + msg) if old else ("DATED-OK", msg)
        rows.append((st, gen, e["files"], msg))
    order = {"GEN-FAIL": 0, "STALE": 1, "TIMEOUT": 2, "MISSING-GEN": 3, "SOURCE-NEWER": 4, "NEEDS-ARGS": 5, "NEEDS-FILES": 5, "PINNED": 6, "FRESH": 6, "DATED-OK": 7}
    rows.sort(key=lambda r: (order.get(r[0], 9), r[1]))
    cnt = {}
    for st, gen, files, msg in rows:
        cnt[st] = cnt.get(st, 0) + 1
        if st in ("FRESH", "DATED-OK"):
            continue
        print(f"GEN-FRESH {st} {gen} -> {len(files)} file(s) [{', '.join(files[:3])}{' ...' if len(files) > 3 else ''}] {msg}")
    print("GEN-FRESH summary " + ", ".join(f"{k} {v}" for k, v in sorted(cnt.items(), key=lambda kv: order.get(kv[0], 9)))
          + f"; {sum(len(e['files']) for e in P.values())} generated rtl file(s) from {len(P)} generator(s); repo {repo}")
    if a.tsv:
        with open(a.tsv, "w") as f:
            f.write("status\tgenerator\tn_files\tfiles\tmessage\n")
            for st, gen, files, msg in rows:
                f.write(f"{st}\t{gen}\t{len(files)}\t{','.join(files)}\t{msg}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
