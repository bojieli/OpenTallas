"""pytest: GEN-FRESH on a throw-away repo (fresh / stale / failing / no-check generators)."""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_rtl_fresh as G  # noqa: E402

GEN = '''import argparse, pathlib, sys
ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
R = pathlib.Path(__file__).resolve().parents[1]
src = (R / "rtl/src.sv").read_text()
text = "// Generated by tools/{name}.py from rtl/src.sv; do not edit.\\n" + src
out = R / "rtl/{name}_out.sv"
if a.check:
    if out.read_text() != text: raise SystemExit("STALE {name}")
else: out.write_text(text)
'''


def _git(d, *a):
    env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t", GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@t")
    subprocess.run(["git", "-C", str(d), *a], check=True, capture_output=True, env=env)


def test_fresh_stale_fail(tmp_path, capsys):
    r = tmp_path
    (r / "tools").mkdir()
    (r / "rtl").mkdir()
    (r / "rtl/src.sv").write_text("module m; endmodule\n")
    for n in ("g_ok", "g_old"):
        (r / f"tools/{n}.py").write_text(GEN.replace("{name}", n))
        subprocess.run([sys.executable, str(r / f"tools/{n}.py")], check=True)
    (r / "tools/g_bad.py").write_text("import argparse\nargparse.ArgumentParser().add_argument('--check')\nraise ValueError('source pattern changed')\n")
    (r / "rtl/g_bad_out.sv").write_text("// Generated by tools/g_bad.py; do not edit.\nmodule b; endmodule\n")
    (r / "rtl/g_none_out.sv").write_text("// GENERATED by tools/g_none.py\nmodule n; endmodule\n")
    (r / "tools/g_none.py").write_text("print('no check mode')\n")
    _git(r, "init", "-q", "-b", "main")
    _git(r, "add", "-A")
    _git(r, "commit", "-qm", "base")
    # g_old's output goes stale: edit the old one's generator text (same source, new header) -> --check differs
    (r / "tools/g_old.py").write_text(GEN.replace("{name}", "g_old").replace("do not edit", "do not edit (v2)"))
    tsv = tmp_path / "o.tsv"
    G.main(["--repo", str(r), "--tsv", str(tsv)])
    out = capsys.readouterr().out
    assert "GEN-FRESH STALE tools/g_old.py -> 1 file(s) [rtl/g_old_out.sv]" in out
    assert "GEN-FRESH GEN-FAIL tools/g_bad.py" in out and "source pattern changed" in out
    assert "g_ok" not in out.split("summary")[0]
    assert "FRESH 1" in out and "DATED-OK 1" in out
    assert len(tsv.read_text().splitlines()) == 5
