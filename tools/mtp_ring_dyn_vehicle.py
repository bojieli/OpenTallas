#!/usr/bin/env python3
"""Ring-DYN physical vehicle (mtp-lead 2026-10-09).

The DS ROM ring-8 DYN25/26 repair (ROLLBACK_RING_DYN, V36) lives in the v41x core sequencer's DYN table, which is now
the module ot_hdc_v41x_dyn_unit (rtl/hdc/v41x/ot_hdc_v41x_dyn_unit.sv, instantiated by ot_hdc_core_v41x as u_dyn).
No routed block contains that sequencer, so this tool builds the smallest honest route source for it:

  ot_dsrom_ring_dyn_vehicle = registered pins + the core's own b_pos = pos_r + ds adder + ot_hdc_v41x_dyn_unit,
  i.e. pin flop -> capture arithmetic -> dyn[] table flops, and pin flop -> 17 read selectors -> pin flop
  (in the core the read-selector outputs feed the S_DEC decode registers through one `F + `DY adder).

run_abi3_physical has no include path, so the route source is one flat file: the vehicle, then the unit with its
`include "ot_hdc_isa_v41_profiles.svh" replaced by that header's text.  The unit text is copied unchanged otherwise.

  mtp_ring_dyn_vehicle.py write   -> physical/mtp_ring_dyn/ot_dsrom_ring_dyn_vehicle.sv
  mtp_ring_dyn_vehicle.py --check -> exit 1 if the committed flat file is stale against the unit / header
  mtp_ring_dyn_vehicle.py bench --out DIR -> Verilator: the vehicle's 64 DYN rows at 32 positions (ring phases, window
      / scan-cap edges, 2^20 range) == tools/v41_fullshape_isa.full_dyn on every row the core writes (NEWBLK, the
      rank-aware model row, is not written by the core: excluded); mutant ROLLBACK_RING_DYN=0 must FAIL.
      Prints RING_DYN_VEHICLE_GATE PASS|FAIL and writes DIR/bench.json.
  mtp_ring_dyn_vehicle.py bench --negative --out DIR -> the ROLLBACK_RING_DYN=0 mutant alone: prints
      RING_DYN_VEHICLE_NEGATIVE FAIL_AS_REQUIRED (mismatches only on DYN25/26) and exits 1, the closure-loop
      expect=fail bench; an undetected mutant prints RING_DYN_VEHICLE_NEGATIVE UNDETECTED and exits 0.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNIT = ROOT / "rtl/hdc/v41x/ot_hdc_v41x_dyn_unit.sv"
SVH = ROOT / "rtl/hdc/v41/ot_hdc_isa_v41_profiles.svh"
OUT = ROOT / "physical/mtp_ring_dyn/ot_dsrom_ring_dyn_vehicle.sv"
INC = '`include "ot_hdc_isa_v41_profiles.svh"'

VEHICLE = """// GENERATED by tools/mtp_ring_dyn_vehicle.py -- do not edit.
// Route vehicle of the ring-8 DYN table (ot_hdc_v41x_dyn_unit) at the DS ROM full shape: every input and output is a
// pin flop (registered boundary); b_pos = pos_r + ds is the core's own adder.  Read ports in DYI_* order (core).
module ot_dsrom_ring_dyn_vehicle #(
    parameter integer FULL_SHAPE = 1,
    parameter integer NSLOT = 1,
    parameter integer ROLLBACK_RING_DYN = 1,
    parameter integer AW = FULL_SHAPE ? 30 : 24,
    parameter integer NW = FULL_SHAPE ? 21 : 16,
    parameter integer NRD = 17,
    parameter integer RIW = 8
) (
    input  wire              clk,
    input  wire              rst_n,
    input  wire              i_cap,
    input  wire [2:0]        i_ds,
    input  wire [NW-1:0]     i_tok,
    input  wire [NW-1:0]     i_pos,
    input  wire [NRD*3-1:0]  i_rd_slot,
    input  wire [NRD*RIW-1:0] i_rd_idx,
    output reg  [NRD*AW-1:0] o_rd_val
);
    reg              cap_q;
    reg [2:0]        ds_q;
    reg [NW-1:0]     tok_q, pos_q;
    reg [NRD*3-1:0]  slot_q;
    reg [NRD*RIW-1:0] idx_q;
    wire [NRD*AW-1:0] val;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) cap_q <= 1'b0;
        else cap_q <= i_cap;
    end
    always @(posedge clk) begin
        ds_q <= i_ds; tok_q <= i_tok; pos_q <= i_pos; slot_q <= i_rd_slot; idx_q <= i_rd_idx;
        o_rd_val <= val;
    end
    wire [NW-1:0] b_pos = pos_q + ds_q;
    ot_hdc_v41x_dyn_unit #(.FULL_SHAPE(FULL_SHAPE), .AW(AW), .NW(NW), .NSLOT(NSLOT),
                           .ROLLBACK_RING_DYN(ROLLBACK_RING_DYN), .NRD(NRD), .RIW(RIW)) u_dyn (
        .clk(clk), .cap(cap_q), .ds(ds_q), .b_tok(tok_q), .b_pos(b_pos),
        .rd_slot(slot_q), .rd_idx(idx_q), .rd_val(val));
endmodule

"""


def build() -> str:
    unit = UNIT.read_text()
    if unit.count(INC) != 1:
        raise SystemExit(f"{UNIT}: expected exactly one {INC}")
    svh = SVH.read_text().rstrip("\n")
    return VEHICLE + unit.replace(INC, "// --- inlined rtl/hdc/v41/ot_hdc_isa_v41_profiles.svh ---\n" + svh
                                  + "\n// --- end inline ---")


TB = ROOT / "rtl/test/tb_ot_dsrom_ring_dyn_vehicle.sv"
VERILATOR = os.environ.get("VERILATOR", str(Path.home() / ".local/opentallas-tools/verilator-5.050/bin/verilator"))
DYNV = re.compile(r"DYNV pos=(\d+) tok=(\d+) idx=(\d+) val=(\d+)")


def sim(out: Path, ring: int) -> list:
    obj = out / f"obj_ring{ring}"
    cmd = [VERILATOR, "--binary", "-O1", "-Wno-fatal", "-Wno-WIDTH", "-Wno-UNUSED", "--top-module",
           "tb_ot_dsrom_ring_dyn_vehicle", f"-GRING={ring}", "-Mdir", str(obj), str(OUT), str(TB)]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
    log = subprocess.run([str(obj / "Vtb_ot_dsrom_ring_dyn_vehicle")], check=True, capture_output=True, text=True).stdout
    (out / f"sim_ring{ring}.log").write_text(log)
    if "DYNV_END" not in log:
        raise SystemExit(f"ring{ring}: bench did not finish")
    return [tuple(map(int, m.groups())) for m in DYNV.finditer(log)]


def compare(rows) -> dict:
    sys.path.insert(0, str(ROOT / "tools"))
    import v41_fullshape_isa as F
    import hdc_isa_v41 as I
    skip = {I.FULL_DYN["NEWBLK"]}
    bad, n, models = [], 0, {}
    for pos, tok, idx, val in rows:
        if idx in skip:
            continue
        if (pos, tok) not in models:
            models[(pos, tok)] = F.full_dyn(pos, tok)
        want = models[(pos, tok)][idx] % (1 << 30)
        n += 1
        if val != want:
            bad.append(dict(pos=pos, idx=idx, rtl=val, model=want))
    return dict(rows_compared=n, positions=len(models), mismatches=len(bad), first=bad[:8],
                mismatch_rows=sorted({b["idx"] for b in bad}))


def bench(out: Path, negative: bool = False) -> int:
    out.mkdir(parents=True, exist_ok=True)
    if build() != OUT.read_text():
        raise SystemExit("flat vehicle source is stale: run tools/mtp_ring_dyn_vehicle.py write")
    if negative:
        neg = compare(sim(out, 0))
        (out / "negative.json").write_text(json.dumps(neg, indent=1) + "\n")
        caught = neg["mismatches"] > 0 and set(neg["mismatch_rows"]) <= {25, 26}
        print(f"RING_DYN_VEHICLE_NEGATIVE {'FAIL_AS_REQUIRED' if caught else 'UNDETECTED'} "
              f"mut_bad={neg['mismatches']} mut_rows={neg['mismatch_rows']}")
        return 1 if caught else 0
    pos = compare(sim(out, 1))
    neg = compare(sim(out, 0))
    ok = (pos["mismatches"] == 0 and pos["rows_compared"] > 0 and neg["mismatches"] > 0
          and set(neg["mismatch_rows"]) <= {25, 26})
    rec = dict(schema="opentallas.mtp_ring_dyn.vehicle_bench.v1", vehicle=str(OUT.relative_to(ROOT)),
               model="tools/v41_fullshape_isa.full_dyn", positive=pos, mutant_ring0=neg, passed=ok)
    (out / "bench.json").write_text(json.dumps(rec, indent=1) + "\n")
    print(f"RING_DYN_VEHICLE_GATE {'PASS' if ok else 'FAIL'} pos_rows={pos['rows_compared']} "
          f"pos_bad={pos['mismatches']} mut_bad={neg['mismatches']} mut_rows={neg['mismatch_rows']}")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", default="write", choices=["write", "bench"])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", type=Path, default=Path("/tmp/ring_dyn_vehicle_bench"))
    ap.add_argument("--negative", action="store_true")
    a = ap.parse_args()
    if a.cmd == "bench":
        return bench(a.out, a.negative)
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print(f"RING_DYN_VEHICLE {'FRESH' if ok else 'STALE'} {OUT.relative_to(ROOT)}")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
