#!/usr/bin/env python3
"""Generate rtl/hdc/ot_hdc_core_vsu.sv: ot_hdc_core at the vector-stream-unit
configuration of the reduced vehicle (SU_VEC 1, SW 8, LV 4) as a parameterless
top for place and route (the physical flow elaborates a top's defaults).

    python3 tools/gen_hdc_core_top.py [--check]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "rtl/hdc/ot_hdc_core.sv"
OUT = ROOT / "rtl/hdc/ot_hdc_core_vsu.sv"
PARAMS = dict(SU_VEC=1, SW=8, LV=4)


def generate():
    src = SRC.read_text()
    head = src[src.index("module ot_hdc_core #("):]
    head = head[:head.index("\n);") + 3]
    ports = []
    for line in head.splitlines():
        m = re.match(r"\s*(input|output)\s+(wire|reg)?\s*(\[[^\]]*\])?\s*([\w\s,]+?)\s*,?\s*(//.*)?$", line)
        if m and m.group(4):
            for name in [n.strip() for n in m.group(4).split(",") if n.strip()]:
                ports.append((m.group(1), m.group(3) or "", name))
    decl = ",\n".join(f"    {d} wire {w} {n}".replace("  ", " ") for d, w, n in ports)
    conn = ",\n".join(f"        .{n}({n})" for _, _, n in ports)
    ptxt = ", ".join(f".{k}({v})" for k, v in PARAMS.items())
    pblock = head[head.index("#(") + 2:head.index(") (")]
    plist = []
    for m in re.finditer(r"parameter\s+integer\s+(\w+)\s*=\s*([^,\n/]+)", pblock):
        if m.group(1) not in PARAMS:
            plist.append((m.group(1), m.group(2).strip()))
    pdecl = ",\n".join(f"    parameter integer {n} = {v}" for n, v in plist)
    ppass = ", ".join(f".{n}({n})" for n, _ in plist)
    # the port widths use SW: substitute the configuration
    for k, v in PARAMS.items():
        decl = re.sub(rf"\b{k}\b", str(v), decl)
    return (f"`timescale 1ns/1ps\n// GENERATED by tools/gen_hdc_core_top.py from rtl/hdc/ot_hdc_core.sv -- do not edit.\n"
            f"// ot_hdc_core with the vector stream unit ({ptxt}) as a parameterless top.\n"
            f"module ot_hdc_core_vsu #(\n{pdecl}\n) (\n{decl}\n);\n"
            f"    ot_hdc_core #({ppass}, {ptxt}) u_core (\n{conn}\n    );\nendmodule\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    t = generate()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == t
        print("current" if ok else "STALE")
        return 0 if ok else 1
    OUT.write_text(t)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
