#!/usr/bin/env python3
"""Derive ot_qwen_tp8_attention_native_service_w16 (16 V rows/cycle P.V) from the committed static native service by
exact edits: QK stacks, AHUB, finalize, calendar control and result path are unchanged; the V boundary is 16 ports
(4 per HBM stack), each stack's e-read is 4 wide, and the two 1-row/cycle pairs become ot_qwen_tp8_pv_wide_pair.
  mk_service_w16.py [--check]"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service.sv'
OUT = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16.sv'

def edit(s, a, b):
    assert s.count(a) == 1, (a[:100], s.count(a))
    return s.replace(a, b)

def derive():
    s = SRC.read_text()
    s = edit(s, '// Q-ATTN 2026-10-15: Qwen TP8 native attention service on a compiler-fixed cycle calendar.\n',
             '// GENERATED by tools/qwen_attention_native/rate_1015/mk_service_w16.py from ot_qwen_tp8_attention_native_service.sv.\n'
             '// Q-ATTN-RATE 2026-10-15: the same static service with P.V at 16 V rows/cycle (2 x ot_qwen_tp8_pv_wide_pair,\n'
             '// 8 banks each), 16 V boundary ports (4 per HBM stack) and a 4-wide e read per stack. Original header follows.\n'
             '// Q-ATTN 2026-10-15: Qwen TP8 native attention service on a compiler-fixed cycle calendar.\n')
    s = edit(s, 'module ot_qwen_tp8_attention_native_service #(', 'module ot_qwen_tp8_attention_native_service_w16 #(')
    s = edit(s, ' // diagnostic mutant: 1 = flip LSB of head0 reciprocal inside the DUT\n parameter integer DMUT=0\n',
             ' // diagnostic mutants: 1 = flip LSB of head0 reciprocal inside the DUT; 2 = P.V join order swapped in pair 0\n parameter integer DMUT=0\n')
    s = edit(s, ''' output wire [3:0] v_req_valid,input wire [3:0] v_req_ready,
 output wire [55:0] v_req_t,output wire [11:0] v_req_slot,
 input wire [3:0] v_rsp_valid,output wire [3:0] v_rsp_ready,
 input wire [55:0] v_rsp_t,input wire [11:0] v_rsp_slot,
 input wire [63:0] v_rsp_epoch,input wire [23:0] v_rsp_layer,input wire [4095:0] v_rsp_data,''',
             ''' // V boundary: port 4*s+j = HBM stack s, lane j (request visible in cycle i -> row presented in cycle i+V_EXT)
 output wire [15:0] v_req_valid,input wire [15:0] v_req_ready,
 output wire [223:0] v_req_t,
 input wire [15:0] v_rsp_valid,output wire [15:0] v_rsp_ready,
 input wire [223:0] v_rsp_t,
 input wire [255:0] v_rsp_epoch,input wire [95:0] v_rsp_layer,input wire [16383:0] v_rsp_data,''')
    s = edit(s, ''' localparam integer V_RL=V_EXT+3;                 // external + actual EP ER3 capture
 localparam integer FIRST_INPUT_AGE=129+V_RL;      // pair-local age of the first V row slot''',
             ''' localparam integer V_RL=V_EXT+3;                 // external + actual EP ER3 capture
 localparam integer FIRST_INPUT_AGE=1+V_RL;        // pair cycle of the q = 0 arrival (requests from the cycle after start_pv)''')
    s = edit(s, ''' wire [3:0] er_v;wire [43:0] er_addr;
 wire [3:0] er_rsp_v;wire [43:0] er_rsp_addr;wire [255:0] er_data;''',
             ''' wire [15:0] er_v;wire [175:0] er_addr;
 wire [15:0] er_rsp_v;wire [175:0] er_rsp_addr;wire [1023:0] er_data;''')
    s = edit(s, '  ot_qwen_tp8_attention_native_stack_cp #(.QK_ISSUE_AGE(QK_ISSUE_AGE)',
             '  ot_qwen_tp8_attention_native_stack_w4_cp #(.QK_ISSUE_AGE(QK_ISSUE_AGE)')
    s = edit(s, '''   .er_v(er_v[s]),.er_addr(er_addr[11*s+:11]),.er_rsp_v(er_rsp_v[s]),.er_rsp_addr(er_rsp_addr[11*s+:11]),
   .er_data(er_data[64*s+:64]),''',
             '''   .er_v(er_v[4*s+:4]),.er_addr(er_addr[44*s+:44]),.er_rsp_v(er_rsp_v[4*s+:4]),.er_rsp_addr(er_rsp_addr[44*s+:44]),
   .er_data(er_data[256*s+:256]),''')
    a = s.index(' // ---------------- V rows, actual EP e read, static PV pairs ----------------')
    b = s.index(' // ---------------- final join (fixed capture slots) and fixed result emission ----------------')
    s = s[:a] + PV + s[b:]
    s = edit(s, 'module ot_qwen_tp8_attention_native_stack_cp #(', 'module ot_qwen_tp8_attention_native_stack_w4_cp #(')
    s = edit(s, ' input wire er_v,input wire[10:0] er_addr,output wire er_rsp_v,output wire[10:0] er_rsp_addr,output wire[63:0] er_data,',
             ' input wire[3:0] er_v,input wire[43:0] er_addr,output wire[3:0] er_rsp_v,output wire[43:0] er_rsp_addr,output wire[255:0] er_data,')
    s = edit(s, ' ot_qwen_tp8_attention_native_stack_cal #(.RL(1)', ' ot_qwen_tp8_attention_native_stack_w4_cal #(.RL(1)')
    return s

PV = r''' // ---------------- V rows (16 ports), actual EP e read (4 per stack), static 8-bank PV pairs ----------------
 // port k = 4 s + j: the e-quad read of the returned row is issued on its V return edge on stack s, e-read lane j
 // (the calendar puts the 4 rows of a stack-cycle on 4 distinct EP owners); V payload delayed 3 edges to the ER3 data.
 wire [1:0] vf,pf;wire [1:0] pvalid;wire [32767:0] partial;wire [31:0] pep;wire [31:0] pv_out_age;
 wire [15:0] cv;wire [223:0] ct;wire [255:0] cep;wire [16383:0] crow;
 reg [31:0] vcount[0:1];
 assign v_rsp_ready=16'hffff;   // static: the slot is reserved; an unexpected return is a fault inside the pair
 genvar k;
 generate for(k=0;k<16;k=k+1)begin:gk
  assign er_v[k]=v_rsp_valid[k];
  assign er_addr[11*k+:11]={v_rsp_t[14*k+9+:4],v_rsp_t[14*k+:7]};
 end
 for(k=0;k<8;k=k+1)begin:gcap
  ot_qwen_tp8_vrow_capture #(.LATENCY(3)) u_capture(
   .clk(clk),.rst_n(rst_n),.in_valid(v_rsp_valid[2*k+:2]),.in_slot(6'd0),.in_t(v_rsp_t[28*k+:28]),
   .in_epoch(v_rsp_epoch[32*k+:32]),.in_rows(v_rsp_data[2048*k+:2048]),
   .out_valid(cv[2*k+:2]),.out_slot(),.out_t(ct[28*k+:28]),.out_epoch(cep[32*k+:32]),.out_rows(crow[2048*k+:2048]));
 end endgenerate
 // e-read identity: the ER3 response of every port must carry the address of the row it is aligned with
 reg er_bad;
 integer ea;
 always @(posedge clk or negedge rst_n)if(!rst_n)er_bad<=0;
  else for(ea=0;ea<16;ea=ea+1)begin
   if(er_rsp_v[ea]!=cv[ea])er_bad<=1;
   if(cv[ea]&&er_rsp_addr[11*ea+:11]!={ct[14*ea+9+:4],ct[14*ea+:7]})er_bad<=1;
   if(er_rsp_v[ea]&&!running)er_bad<=1;
  end
 generate for(s=0;s<2;s=s+1)begin:gp
  // the pair takes its 8 V ports as captured: {stack s lanes 0-3, stack s+2 lanes 0-3}; the columns map port -> bank
  wire [7:0] bv;wire [8191:0] bvrow;wire [511:0] bexp;wire [111:0] bt;wire [127:0] bep;
  genvar k2;
  for(k2=0;k2<8;k2=k2+1)begin:gport
   localparam integer K=(k2<4)?4*s+k2:4*(s+2)+k2-4;
   assign bv[k2]=cv[K];assign bvrow[1024*k2+:1024]=crow[1024*K+:1024];assign bexp[64*k2+:64]=er_data[64*K+:64];
   assign bt[14*k2+:14]=ct[14*K+:14];assign bep[16*k2+:16]=cep[16*K+:16];
  end
  wire [7:0] rq;wire [111:0] rqt;
  assign v_req_valid[4*s+:4]=rq[3:0];assign v_req_valid[4*(s+2)+:4]=rq[7:4];
  assign v_req_t[56*s+:56]=rqt[55:0];assign v_req_t[56*(s+2)+:56]=rqt[111:56];
  reg rqbad;
  always @(posedge clk or negedge rst_n)if(!rst_n)rqbad<=0;
   else if(((rq[3:0]&~v_req_ready[4*s+:4])!=0)||((rq[7:4]&~v_req_ready[4*(s+2)+:4])!=0))rqbad<=1;
  assign vf[s]=rqbad;
  ot_qwen_tp8_pv_wide_pair #(.PAIR(s),.FIRST_INPUT_AGE(FIRST_INPUT_AGE),.MUT((DMUT==2&&s==0)?1:0)) u_pv(.clk(clk),.rst_n(rst_n),
   .start(start_pv),.col_clk({33{clk}}),.context_len(ctx),.epoch(ep),
   .in_valid(bv),.in_v(bvrow),.in_e(bexp),.in_t(bt),.in_epoch(bep),.req_valid(rq),.req_t(rqt),
   .out_valid(pvalid[s]),.out_leaf(partial[16384*s+:16384]),.out_epoch(pep[16*s+:16]),.fault(pf[s]),
   .busy(),.out_age(pv_out_age[16*s+:16]));
  always @(posedge clk or negedge rst_n)if(!rst_n)vcount[s]<=0;else if(start_pv)vcount[s]<=0;else vcount[s]<=vcount[s]+32'($countones(bv));
 end endgenerate
 assign v_words=vcount[0]+vcount[1];

'''

if __name__ == '__main__':
    text = derive()
    if '--check' in sys.argv:
        if OUT.read_text() != text: sys.exit(f'{OUT.name} stale')
        print(f'{OUT.name} current')
    else:
        OUT.write_text(text); print(OUT)
