#!/usr/bin/env python3
"""Q-ATTN-RATE (2026-10-15): derive the 4-port e-read stack wrappers from the committed calendar stack wrappers.

The 16-row/cycle P.V pair (rtl/hdc/nearhbm/ot_qwen_tp8_pv_wide_pair.sv) reads 4 e rows per edge from each stack's
actual EP SRAMs (4 distinct EP owners per edge, one per EP read port). The only change against the committed
qkd_astk_native_stack_cal / ot_qwen_tp8_attention_native_stack_cal is that the e-read port is 4 wide and served by
qkd_astk_native_er_service_w (N=4); the EP/EX/ZN/CTL/ECTL/head instances are byte-identical.

  gen_pv_rate.py            write rtl/qwen_sys/split_20261014/qkd_astk_native_stack_w4_gen.sv
  gen_pv_rate.py --check    fail if the committed output is stale
  gen_pv_rate.py --cp IN OUT apply the same edits to a source-minimal cp wrapper file (build recipe; lib names kept)
"""
import argparse, hashlib, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/qwen_sys/split_20261014/qkd_astk_cal_gen.sv'
OUT = ROOT / 'rtl/qwen_sys/split_20261014/qkd_astk_native_stack_w4_gen.sv'
SLICE = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_pv256_slice.sv'
SLICE_OUT = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_pv16_slice_gen.sv'


def derive_slice():
    """ot_qwen_tp8_pv16_slice: the pv256 slice with its 16 used chain addresses in 4 x ot_sram_1r1w_32x128_m1 (512 b
    word = 4 x 128 b, address 5 b) instead of 2 x ot_sram_1r1w_128x256 (16 of 128 rows used); datapath byte-identical"""
    s = SLICE.read_text()
    s = edit(s, 'module ot_qwen_tp8_pv256_slice(', 'module ot_qwen_tp8_pv16_slice(')
    s = edit(s, 'for(m=0;m<2;m=m+1)begin:g_mem\n  ot_sram_1r1w_128x256_m1_r2c2 u_mem(.clk(clk),',
             'for(m=0;m<4;m=m+1)begin:g_mem\n  ot_sram_1r1w_32x128_m1 u_mem(.clk(clk),')
    s = edit(s, '.r_addr_in(read_leaf?leaf_c:c),.rd_out(rd[256*m+:256]),', '.r_addr_in(5\'(read_leaf?leaf_c:c)),.rd_out(rd[128*m+:128]),')
    s = edit(s, '.w_addr_in(init_zero?init_c:commit_c),.wd_in(init_zero?256\'b0:sum[256*m+:256]),.w_mask_in({256{1\'b1}}),\n'
                '   .rr_en(2\'b0),.rr_addr(12\'b0),.cr_en(2\'b0),.cr_sel(16\'b0));',
             '.w_addr_in(5\'(init_zero?init_c:commit_c)),.wd_in(init_zero?128\'b0:sum[128*m+:128]),.w_mask_in({128{1\'b1}}));')
    # data registers without reset (every consumer is valid-qualified): adder DRST 0, tree_sum written before its read
    s = edit(s, 'ot_hdc_fp32_add_lat #(.LAT(7)) u_add(', 'ot_hdc_fp32_add_lat #(.LAT(7),.DRST(0)) u_add(')
    s = edit(s, 'if(!rst_n)begin vp<=0;fp<=0;lastp<=0;tree_sum<=0;end', 'if(!rst_n)begin vp<=0;fp<=0;lastp<=0;end')
    s = edit(s, 'if(commit&&lastp[6])tree_sum<=sum;end\n end', 'end\n end\n always @(posedge clk)if(commit&&lastp[6])tree_sum<=sum;')
    h = hashlib.sha256(SLICE.read_bytes()).hexdigest()
    return (f'// GENERATED by tools/qwen_attention_native/gen_pv_rate.py from {SLICE.relative_to(ROOT)} sha256 {h}.\n'
            '// Do not edit. 16-chain slice on 4 x 32x128 SRAM macros (Q-ATTN-RATE physical kit, 2026-10-15).\n' + s)


def edit(s, a, b, n=1):
    assert s.count(a) == n, (a[:90], s.count(a))
    return s.replace(a, b)


def module(text, name):
    m = re.search(r'^module %s #\(.*?^endmodule\n' % re.escape(name), text, re.S | re.M)
    assert m, name
    return m.group(0)


def widen(text, er_service):
    """the exact edits; er_service = the instance master name in this text (source or protected-lib name)"""
    s = edit(text, 'module qkd_astk_native_stack_cal #(', 'module qkd_astk_native_stack_w4_cal #(')
    s = edit(s, '  input wire er_v,\n  input wire [10:0] er_addr,\n  output wire er_rsp_v,\n'
                '  output wire [10:0] er_rsp_addr,\n  output wire [63:0] er_data,',
             '  input wire [3:0] er_v,\n  input wire [43:0] er_addr,\n  output wire [3:0] er_rsp_v,\n'
             '  output wire [43:0] er_rsp_addr,\n  output wire [255:0] er_data,')
    s = edit(s, f' {er_service} u_er(', ' qkd_astk_native_er_service_w #(.N(4)) u_er(')
    s = edit(s, 'else if(er_v&&!visibility[er_addr[6:3]])visibility_fault<=1;',
             'else for(integer vr=0;vr<4;vr=vr+1)if(er_v[vr]&&!visibility[er_addr[11*vr+3+:4]])visibility_fault<=1;')
    s = edit(s, 'module ot_qwen_tp8_attention_native_stack_cal #(', 'module ot_qwen_tp8_attention_native_stack_w4_cal #(')
    s = edit(s, ' input wire er_v,input wire[10:0] er_addr,\n output wire er_rsp_v,output wire[10:0] er_rsp_addr,'
                'output wire[63:0] er_data,',
             ' input wire[3:0] er_v,input wire[43:0] er_addr,\n output wire[3:0] er_rsp_v,output wire[43:0] er_rsp_addr,'
             'output wire[255:0] er_data,')
    s = edit(s, ' qkd_astk_native_stack_cal #(', ' qkd_astk_native_stack_w4_cal #(')
    return s


def derive():
    src = SRC.read_text()
    body = module(src, 'qkd_astk_native_stack_cal') + '\n' + module(src, 'ot_qwen_tp8_attention_native_stack_cal')
    h = hashlib.sha256(SRC.read_bytes()).hexdigest()
    return ('`timescale 1ns/1ps\n`ifndef KVD_HEADS\n`define KVD_HEADS 2\n`endif\n'
            f'// GENERATED by tools/qwen_attention_native/gen_pv_rate.py from {SRC.relative_to(ROOT)} sha256 {h}.\n'
            '// Do not edit. 4-port e-read variants of the calendar stack wrappers (Q-ATTN-RATE 2026-10-15).\n'
            + widen(body, 'qkd_astk_native_er_service'))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--cp', nargs=2, metavar=('IN', 'OUT'))
    a = ap.parse_args()
    if a.cp:
        text = Path(a.cp[0]).read_text()
        out = widen(text, 'qkd_astk_native_er_service_2')
        # the cp entry of the wide service (one common-phase clock, the stack_cal of this file)
        out = edit(out, 'module ot_qwen_tp8_attention_native_stack_cp #(', 'module ot_qwen_tp8_attention_native_stack_w4_cp #(')
        out = edit(out, ' input wire er_v,input wire[10:0] er_addr,output wire er_rsp_v,output wire[10:0] er_rsp_addr,'
                        'output wire[63:0] er_data,',
                   ' input wire[3:0] er_v,input wire[43:0] er_addr,output wire[3:0] er_rsp_v,output wire[43:0] er_rsp_addr,'
                   'output wire[255:0] er_data,')
        out = edit(out, ' ot_qwen_tp8_attention_native_stack_cal #(.RL(1)', ' ot_qwen_tp8_attention_native_stack_w4_cal #(.RL(1)')
        Path(a.cp[1]).write_text(out)
        print(a.cp[1])
        return
    for out, text in ((OUT, derive()), (SLICE_OUT, derive_slice())):
        if a.check:
            if out.read_text() != text:
                sys.exit(f'{out.name} is stale')
            print(f'{out.name} current')
        else:
            out.write_text(text)
            print(out)


if __name__ == '__main__':
    main()
