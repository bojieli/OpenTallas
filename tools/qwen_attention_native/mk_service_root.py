#!/usr/bin/env python3
"""KVJ-B 2026-10-17: hierarchy move of the w16 attention service's fixed calendar control into qkd_attn_service_root.

Reads the canonical rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16.sv (unchanged) and writes
  rtl/test/qwen_split/qkd_attn_service_root_ref.sv      the moved text VERBATIM (calendar decode + fixed calendar
                                                         control) as a module: the lockstep reference
  rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16_sr.sv
                                                         the same service with that block replaced by a
                                                         qkd_attn_service_root instance and the PV start word
                                                         (start_pv / context_len / epoch) on a PV_LEAD-edge relay
Every edit is a single exact-match replacement (asserted), so the _sr service differs from the canonical one ONLY in
the moved block, the cal/cycles declarations, the pair's context_len/epoch pins and the dropped stack_cp entry (the
build recipes drop it too, rate_1015/build_w16.sh).  The block is byte-identical in the g3s2 copy
(qkd_native_attention_service_g3s2_gen.sv), which --check also asserts.
Usage: mk_service_root.py [--check]
"""
import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SERVICE = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16.sv'
G3S2 = ROOT / 'rtl/qwen_sys/split_20261014/qkd_native_attention_service_g3s2_gen.sv'
REF = ROOT / 'rtl/test/qwen_split/qkd_attn_service_root_ref.sv'
SR = ROOT / 'rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16_sr.sv'

A_START = ' reg [175:0] cal;\n'
A_END = ' wire [15:0] END_AGE=RESULT_AGE+16\'d33;\n'
B_START = ' // ---------------- fixed calendar control ----------------\n'
B_END = ' // ---------------- per stack: native QK stack, K boundary, held command context ----------------\n'

NEW_B = ''' // ---------------- fixed calendar control: qkd_attn_service_root (KVJ-B hierarchy move) ----------------
 wire running,start_qk,start_pv_root;
 wire [15:0] age;           // age 0 = the cycle in which start_qk is high
 wire [15:0] ep;wire [5:0] layer;wire [13:0] ctx;
 wire local_fault,io_fault;reg result_fault;
 qkd_attn_service_root #(.PV_LEAD(PV_LEAD)) u_root(.ck(clk),.rst_n(rst_n),
  .request_valid(request_valid),.request_ready(request_ready),.request_epoch(request_epoch),.request_layer(request_layer),
  .request_position(request_position),.fused_program_capability(fused_program_capability),.request_calendar(request_calendar),
  .q_valid(q_valid),.q_beat(q_beat),.q_ready(q_ready),
  .running(running),.start_qk(start_qk),.start_pv(start_pv_root),.age(age),.ep(ep),.layer(layer),.ctx(ctx),.cal(cal),
  .cycles(cycles),.local_fault(local_fault),.io_fault(io_fault));
 assign busy=running;
 assign active_epoch=ep;assign active_layer=layer;
 wire q_window=q_ready;
 // PV start word {start_pv, context_len, epoch} on its PV_LEAD registered relay edges (the die's relay chain to pvw_0/1);
 // the root issues start_pv PV_LEAD edges early, so every PV-side consumer sees it on the service's edge.
 wire start_pv;wire [13:0] pv_ctx;wire [15:0] pv_ep;
 generate if(PV_LEAD==0)begin:gpv0
  assign start_pv=start_pv_root;assign pv_ctx=ctx;assign pv_ep=ep;
 end else begin:gpvr
  reg [PV_LEAD-1:0] rs;reg [13:0] rc[0:PV_LEAD-1];reg [15:0] re[0:PV_LEAD-1];
  always @(posedge clk or negedge rst_n)if(!rst_n)rs<=0;else rs<={rs,start_pv_root};
  always @(posedge clk)begin rc[0]<=ctx;re[0]<=ep;for(integer j=1;j<PV_LEAD;j=j+1)begin rc[j]<=rc[j-1];re[j]<=re[j-1];end end
  assign start_pv=rs[PV_LEAD-1];assign pv_ctx=rc[PV_LEAD-1];assign pv_ep=re[PV_LEAD-1];
 end endgenerate

'''


def once(s, a, b):
    if s.count(a) != 1:
        raise ValueError(f'source binding mismatch {a[:70]!r}: {s.count(a)}')
    return s.replace(a, b)


def span(s, a, b, incl_end):
    i = s.index(a)
    j = s.index(b, i)
    if s.count(a) != 1 or s.count(b) != 1:
        raise ValueError('span markers not unique')
    return s[i:j + len(b)] if incl_end else s[i:j]


def generate():
    s = SERVICE.read_text()
    sha = hashlib.sha256(s.encode()).hexdigest()
    a = span(s, A_START, A_END, True)
    b = span(s, B_START, B_END, False)
    g = G3S2.read_text()
    if g.count(a) != 1 or g.count(b) != 1:
        raise ValueError('the g3s2 copy no longer carries the identical block')
    hdr = (f'// GENERATED by tools/qwen_attention_native/mk_service_root.py from\n'
           f'// rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16.sv sha256 {sha}\n')
    ref = (hdr + '`timescale 1ns/1ps\n'
           '// Lockstep reference: the calendar decode and the fixed calendar control block of the w16 service, VERBATIM.\n'
           'module qkd_attn_service_root_ref (\n'
           ' input wire clk,rst_n,\n'
           ' input wire request_valid,output wire request_ready,\n'
           ' input wire [15:0] request_epoch,input wire [5:0] request_layer,\n'
           ' input wire [17:0] request_position,input wire fused_program_capability,\n'
           ' input wire [175:0] request_calendar,\n'
           ' input wire q_valid,output wire q_ready,input wire [4:0] q_beat,\n'
           ' output wire [15:0] active_epoch,output wire [5:0] active_layer,\n'
           ' output wire busy,output reg [31:0] cycles\n'
           ');\n' + a + '\n' + b + 'endmodule\n')
    t = s.replace('module ot_qwen_tp8_attention_native_service_w16 #(', 'module ot_qwen_tp8_attention_native_service_w16_sr #(')
    if t == s:
        raise ValueError('module header')
    t = once(t, ' parameter integer DMUT=0\n', ' parameter integer DMUT=0,\n'
             ' // KVJ-B: registered relay edges between qkd_attn_service_root and the PV pairs (0 = the canonical service)\n'
             ' parameter integer PV_LEAD=0\n')
    t = once(t, ' output reg [31:0] cycles,output wire [31:0] k_words,v_words,',
             ' output wire [31:0] cycles,output wire [31:0] k_words,v_words,')
    t = once(t, A_START, ' wire [175:0] cal;\n')
    t = once(t, b, NEW_B)
    t = once(t, '.start(start_pv),.col_clk({33{clk}}),.context_len(ctx),.epoch(ep),',
             '.start(start_pv),.col_clk({33{clk}}),.context_len(pv_ctx),.epoch(pv_ep),')
    t = t[:t.index('// Common-phase stack entry')]
    t = once(t, '`timescale 1ns/1ps\n', hdr + '`timescale 1ns/1ps\n')
    return {REF: ref, SR: t}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    out = generate()
    bad = 0
    for p, txt in out.items():
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print('STALE', p.relative_to(ROOT))
                bad = 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(txt)
            print('wrote', p.relative_to(ROOT))
    return bad


if __name__ == '__main__':
    sys.exit(main())
