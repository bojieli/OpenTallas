#!/usr/bin/env python3
"""Generate the A0 bound-vs-kit port equivalence bench.

usage: gen_tb.py TILE(nk|nl) BOUND_PP.sv BOUND_TOP KIT_PP.sv KIT_TOP ROM_TILE OUT_TB.sv

BOUND side: BOUND_TOP (e.g. qfd_tile_nk_rp2_romleaf_rr), every ck* port tied to the one bench clock (as in the bound die).
KIT side:   KIT_TOP (prefixed copy of qfd_tile_nk_a0c, REGROOT_MODE=9), ck + unloaded ck_t* taps tied to the clock; its
            rst_n goes through KRL plain registers on ck (the kit's OT_RST_LAND_STAGES=2 landing,
            physical/common_flow/ot_pin_regs.tcl) -- KRL=0 benches the bare RTL.
Plusargs: +MUT=n (0 none; 1 kit-only tap xl bit 400 flipped all run; 2 kit-only n_a bit 5 flipped all run (NK);
          3 kit-only go of the 3rd command dropped), +KRL=n (kit reset landing stages, default 2), +KSKEW=n (kit rst_n
          source released n cycles after the bound one, default 0), +NCYC=n (cycles after release, default 6500).
"""
import re
import sys

tile, bpp, btop, kpp, ktop, romt, out = sys.argv[1:8]
nk = tile == "nk"


def ports(path, top):
    txt = open(path).read()
    m = re.search(r"^\s*module\s+" + re.escape(top) + r"\b(.*?)\);", txt, re.S | re.M)
    if not m:
        sys.exit(f"gen_tb.py: module {top} not in {path}")
    return re.findall(r"input\s+wire\s+(?:\[[^\]]*\]\s*)?(\w+)", m.group(1))


bck = [p for p in ports(bpp, btop) if p.startswith("ck")]
kck = [p for p in ports(kpp, ktop) if p.startswith("ck")]
bconn = ", ".join(f".{p}(ck)" for p in bck)
kconn = ", ".join(f".{p}(ck)" for p in kck)
nports_b = ".n_a(na), .n_b(nb), .n_y(bn)," if nk else ""
nports_k = ".n_a(na_k), .n_b(nb), .n_y(kn)," if nk else ""

tb = f"""`timescale 1ns/1ps
// GENERATED by tools/qwen_romleaf/a0core/equiv/gen_tb.py ({tile.upper()}): bound {btop} vs kit {ktop}.
// bound clock ports tied to ck: {len(bck)}; kit clock ports tied to ck: {len(kck)}
module tb_a0_equiv;
integer MUT=0, KRL=2, KSKEW=0, NCYC=6500;
localparam integer RB = 8;                 // bound rst_n released at negedge count RB
initial begin
  if ($value$plusargs("MUT=%d", MUT)) begin end
  if ($value$plusargs("KRL=%d", KRL)) begin end
  if ($value$plusargs("KSKEW=%d", KSKEW)) begin end
  if ($value$plusargs("NCYC=%d", NCYC)) begin end
  if (KRL < 0 || KRL > 4 || RB + KSKEW < 1) $fatal(1, "bad KRL/KSKEW");
end
reg ck = 0; always #0.5 ck = ~ck;
integer tc = 0;                            // negedge count since time 0
always @(negedge ck) tc <= tc + 1;
wire rs_b = (tc >= RB);
wire rs_k_src = (tc >= RB + KSKEW);
reg [3:0] rl = 4'd0;                       // kit reset landing (plain flops on ck)
always @(posedge ck) rl <= {{rl[2:0], rs_k_src}};
wire rs_k = (KRL == 0) ? rs_k_src : rl[KRL-1];
reg [507:0] tap = 0;
reg [513:0] na = 0, nb = 0;
reg drop3 = 0;
wire [507:0] tap_k = tap ^ ((MUT == 1) ? (508'd1 << 400) : 508'd0) ^ ((MUT == 3 && drop3) ? 508'd1 : 508'd0);
wire [513:0] na_k = na ^ ((MUT == 2) ? (514'd1 << 5) : 514'd0);
wire [513:0] bt, kt;
wire [513:0] bn, kn;
wire bhi, blo, khi, klo;
{btop} #(.ROM_TILE({romt})) ub ({bconn},
  .rst_n(rs_b), .tile_id(16'd{romt}), .tie_hi(bhi), .tie_lo(blo), .tap(tap), .t_out(bt){', ' + nports_b.rstrip(',') if nk else ''});
{ktop} #(.REGROOT_MODE(9), .ROM_TILE({romt})) uk ({kconn},
  .rst_n(rs_k), .tile_id(16'd{romt}), .tie_hi(khi), .tie_lo(klo), .tap(tap_k), .t_out(kt){', ' + nports_k.rstrip(',') if nk else ''});
{"" if nk else "assign bn = 514'd0; assign kn = 514'd0;"}
// internal reset release (the face reset_q each side's core sees), measured exactly
integer rel_b = -1, rel_k = -1;
always @(negedge ck) begin
  if (rel_b < 0 && ub.u_g.reset_q === 1'b1) rel_b = tc;
  if (rel_k < 0 && uk.u_g.reset_q === 1'b1) rel_k = tc;
end
function automatic [378:0] command(input integer bank);
 command={{18'd4096,18'd2,18'd32,1'b0,24'(bank*4096),24'd64,24'd8,24'd1,
          24'd0,24'd1,24'd1,24'd1,3'd0,4'd7,24'd1,1'b0,24'd0,24'd1,24'd1,
          1'b0,1'b1,1'b0,1'b0,24'd0}};
endfunction
localparam integer MAXC = 20000;
reg [513:0] tr_bt [0:MAXC-1], tr_kt [0:MAXC-1], tr_bn [0:MAXC-1], tr_kn [0:MAXC-1];
function automatic integer popc(input [513:0] v);
  integer i; popc = 0; for (i = 0; i < 514; i = i + 1) popc = popc + v[i];
endfunction
function automatic integer lowbit(input [513:0] v);
  integer i; lowbit = -1; for (i = 513; i >= 0; i = i - 1) if (v[i]) lowbit = i;
endfunction
integer cyc, errors = 0, checks = 0, tvalid = 0, tnz = 0, nvalid = 0, nnz = 0, ktvalid = 0, knvalid = 0, cmds = 0;
integer et = 0, en = 0, eh = 0, first_err = -1;
initial begin
  @(negedge ck);
  while (tc < RB) @(negedge ck);
  if (NCYC > MAXC) $fatal(1, "NCYC > %0d", MAXC);
  for (cyc = 0; cyc < NCYC; cyc = cyc + 1) begin
    tap[0] = 0; drop3 = 0;
    if (cyc >= 200 && (cyc - 200) % 1200 == 0 && cyc < NCYC - 300) begin
      tap[379:1] = command(((cyc - 200) / 1200) % 5); tap[0] = 1; cmds = cmds + 1;
      if (cmds == 3) drop3 = 1;
    end
    for (integer g = 0; g < 4; g = g + 1) tap[380 + g*32 +: 32] = 32'h3f800000 + ((cyc % 8 + g) << 18);
    for (integer lane = 0; lane < 16; lane = lane + 1) begin
      na[lane*32 +: 32] = 32'h3f000000 + ((cyc % 16 + lane) << 17);
      nb[lane*32 +: 32] = 32'h3f800000 + ((cyc % 8 + lane) << 17);
    end
    na[513:512] = {{1'b0, (cyc % 11 == 0)}}; nb[513:512] = na[513:512];
    @(negedge ck);
    tr_bt[cyc] = bt; tr_kt[cyc] = kt; tr_bn[cyc] = bn; tr_kn[cyc] = kn;
    checks = checks + 1;
    if (bt !== kt || bn !== kn || bhi !== khi || blo !== klo) begin
      errors = errors + 1;
      if (first_err < 0) first_err = cyc;
      if (bt !== kt) et = et + 1;
      if (bn !== kn) en = en + 1;
      if (bhi !== khi || blo !== klo) eh = eh + 1;
      if (errors <= 5)
        $display("A0EQ_MISMATCH cyc%0d t_out:%0d bits (low %0d, [513:512] b%b k%b) n_y:%0d bits (low %0d) tie b%b%b k%b%b",
          cyc, popc(bt ^ kt), lowbit(bt ^ kt), bt[513:512], kt[513:512], popc(bn ^ kn), lowbit(bn ^ kn), bhi, blo, khi, klo);
      if (errors <= 2) $display("A0EQ_MISMATCH_WORDS cyc%0d bt=%h kt=%h bn=%h kn=%h", cyc, bt, kt, bn, kn);
    end
    if (bt[512]) begin tvalid = tvalid + 1; if (|bt[511:0]) tnz = tnz + 1; end
    if (kt[512]) ktvalid = ktvalid + 1;
    if (bn[512]) begin nvalid = nvalid + 1; if (|bn[511:0]) nnz = nnz + 1; end
    if (kn[512]) knvalid = knvalid + 1;
  end
  // offset analysis: mismatching cycles of kit[c+d] vs bound[c] (c in [100, NCYC-100))
  for (integer d = -3; d <= 3; d = d + 1) begin
    integer mm; mm = 0;
    for (integer c = 100; c < NCYC - 100; c = c + 1)
      if (tr_bt[c] !== tr_kt[c+d] || tr_bn[c] !== tr_kn[c+d]) mm = mm + 1;
    $display("A0EQ_SHIFT d=%0d mismatching_cycles=%0d of %0d", d, mm, NCYC - 200);
  end
  $display("A0EQ_RESET bound_reset_q_rise_tc=%0d kit_reset_q_rise_tc=%0d kit_minus_bound=%0d (KRL=%0d KSKEW=%0d)",
    rel_b, rel_k, rel_k - rel_b, KRL, KSKEW);
  $display("A0EQ_COUNTS tile={tile} MUT=%0d checks=%0d cmds=%0d t_valid=%0d t_nonzero=%0d n_valid=%0d n_nonzero=%0d kit_t_valid=%0d kit_n_valid=%0d",
    MUT, checks, cmds, tvalid, tnz, nvalid, nnz, ktvalid, knvalid);
  if (tvalid == 0 || tnz == 0) $display("A0EQ_ACTIVITY_MISSING t_valid=%0d t_nonzero=%0d", tvalid, tnz);
  if (errors)
    $display("A0EQ_FAIL tile={tile} MUT=%0d KRL=%0d KSKEW=%0d errors=%0d (t_out %0d, n_y %0d, tie %0d) first_cycle=%0d checks=%0d",
      MUT, KRL, KSKEW, errors, et, en, eh, first_err, checks);
  else if (tvalid > 0 && tnz > 0)
    $display("A0EQ_PASS tile={tile} MUT=%0d KRL=%0d KSKEW=%0d checks=%0d t_valid=%0d t_nonzero=%0d n_valid=%0d n_nonzero=%0d",
      MUT, KRL, KSKEW, checks, tvalid, tnz, nvalid, nnz);
  $finish;
end
endmodule
"""
open(out, "w").write(tb)
print(f"gen_tb.py: {out} ({len(bck)} bound clock ports, {len(kck)} kit clock ports)")
