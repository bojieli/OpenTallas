#!/usr/bin/env python3
"""QW-CLUSTER3/A0 (10-19) rc1 floorplan for the A0 ROM-leaf parents qfd_tile_n{k,l}_romleaf.

Safe-design rebuild after NK c1r9f (DPL-0033 / GATE_GRT_RC2) and NL c1r9f (spec FAIL: reset_landing.clock):
  * outline 820.8 x 907.2 um (19 x 21 lattice cells of 43.2 um), aspect 1.105, fill ~45 % (40-60 %)
  * every hard-child origin on the 43.2 um lattice; channels >= 20 um; ROM rows 172.8 um pitch (62.6 um std rows)
  * layout W->E: ROM column 0 (MY, pins E) | ROM pin channel (rsw/dw/rnw) | LSL 0..3 (R0, pins E) | TX strip |
    hub (issue engine, bottom) + node (top, NK) | TX strip | LSL 4..7 (MY, pins W) | ROM pin channel (rse/de/rne) |
    ROM column 1 (R0, pins W).  Full-width std rows: the 41 um bottom band, the 60 um top band and the 62.6 um ROM-row
    channels run the whole width between the ROM stacks; no std island.
  * pins on full W/E faces at 0.192 um (5.2 pins/um <= 6); buses beside their consumers (n_a/n_b/n_y at the node rows,
    tap at the hub rows, ROM-leaf and LSL entries at their rows).
Writes: tools/ref_tile/specs_qw_cluster3_1019/<kit>.json, tools/qwen_romleaf/rc1/<kit>_pins.tcl, <kit>_regions.tcl.
"""
import json, copy, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[3]
W, H = 820.8, 907.2
LAT = 43.2
ROM_W, ROM_H, LSL_W, LSL_H, NODE_W, NODE_H = 172.8, 110.16, 99.792, 140.4, 47.52, 432.0
ROM0_X, ROM1_X, LSLA_X, NODE_X, LSLB_X = 43.2, 604.8, 259.2, 388.8, 475.2
ROM_Y = [43.2 + 172.8 * b for b in range(5)]
LSL_Y = [129.6 + 172.8 * i for i in range(4)]
NODE_Y = 432.0
for v in [ROM0_X, ROM1_X, LSLA_X, NODE_X, LSLB_X, NODE_Y] + ROM_Y + LSL_Y:
    assert abs(v / LAT - round(v / LAT)) < 1e-9, v
assert abs(W / LAT - round(W / LAT)) < 1e-9 and abs(H / LAT - round(H / LAT)) < 1e-9

def snap(y):        # M4 track grid of the old kits: y = 0.012 + 0.096 k
    return round(0.012 + 0.096 * round((y - 0.012) / 0.096), 3)

def children(nk):
    me = "u_g.u_tile.u_tile.u_logic"
    out = []
    if nk:
        out.append(dict(view="physical/ref_tile/ot_qwen_tile_node/views/ot_qwen_tile_node", count=1,
                        inst=f"{me}.genblk5.g_ndh.u_node", at=[NODE_X, NODE_Y], orient="R0", at_exact=True))
    for g in range(8):
        x, o = (LSLA_X, "R0") if g < 4 else (LSLB_X, "MY")
        out.append(dict(view="physical/ref_tile/qfd_tile_lsl_fp1/views/ot_qwen_tile_lsl_fp1", count=1,
                        inst=f"{me}.u_me.g_hier.g_sl[{g}].g_hd.u_lh", at=[x, LSL_Y[g % 4]], orient=o, at_exact=True))
    for p in range(2):
        for b in range(5):
            x, o = (ROM0_X, "MY") if p == 0 else (ROM1_X, "R0")
            out.append(dict(view="physical/ref_tile/ot_qwen_tile_romleaf/views/ot_qwen_tile_romleaf", count=1,
                            inst=f"{me}.g_rom_pipe.g_rph.g_rb[{b}].g_single.g_col[{p}].u_leaf", at=[x, ROM_Y[b]],
                            orient=o, at_exact=True))
    return out

def pin_plan(nk):
    """face -> list of (pin, y); buses at 0.192 pitch, singles snapped and kept clear of the bus spans"""
    W_bus = ([("n_a", 514, 455.0), ("n_b", 514, 560.0), ("n_y", 514, 665.0)] if nk else []) + [("t_out", 514, 770.0)]
    E_bus = [("tap", 508, 120.0), ("tile_id", 16, 222.0)]
    rc = [ROM_Y[b] + ROM_H / 2 for b in range(5)]
    lc = [LSL_Y[i] + LSL_H / 2 for i in range(4)]
    W_single = {**({"ck_fa0": 440.0, "ck_fa1": 444.0, "ck_fa3": 448.0, "ck_node": 452.0} if nk else {}),
                "ck_fa2": 874.0, "ck_rsw": 170.0, "ck_dw": 430.0, "ck_rnw": 700.0 if not nk else 436.0,
                **{f"ck_rp{b}": rc[b] for b in range(5)},
                **{f"ck_lsl{i}": lc[i] - 6 for i in range(4)}, **{f"ck_tx{i}": lc[i] + 6 for i in range(4)}}
    E_single = {"ck": 240.0, "ck_fa4": 116.0, "rst_n": 228.0, "tie_hi": 232.0, "tie_lo": 236.0,
                "ck_rs": 170.0, "ck_de": 430.0, "ck_rn": 700.0,
                **{f"ck_rp{b+5}": rc[b] for b in range(5)},
                **{f"ck_lsl{i+4}": lc[i] - 6 for i in range(4)}, **{f"ck_tx{i+4}": lc[i] + 6 for i in range(4)}}
    plan = {}
    for face, buses, singles in (("W", W_bus, W_single), ("E", E_bus, E_single)):
        spans, rows = [], []
        for name, n, y0 in buses:
            y = snap(y0)
            ys = [round(y + 0.192 * i, 3) for i in range(n)]
            spans.append((ys[0] - 0.5, ys[-1] + 0.5))
            rows += [(f"{name}[{i}]", ys[i]) for i in range(n)]
        used = []
        for name, y0 in sorted(singles.items(), key=lambda kv: kv[1]):
            y = snap(y0)
            while any(a <= y <= b for a, b in spans) or any(abs(y - u) < 0.95 for u in used):
                y = snap(y + 0.96)
            assert 3.0 < y < H - 3.0, (name, y)
            used.append(y); rows.append((name, y))
        plan[face] = rows
    return plan

def pins_tcl(kit, nk):
    plan = pin_plan(nk)
    out = [f"# {kit}: generated by tools/qwen_romleaf/rc1/gen_rc1.py (QW-CLUSTER3/A0 10-19 rc1 floorplan {W} x {H} um);",
           "# W/E faces, M4, 0.192 um bus pitch (5.2 pins/um); buses at their consumer rows (see the generator docstring)."]
    for face, rows in plan.items():
        x = 0.096 if face == "W" else round(W - 0.096, 3)
        for name, y in sorted(rows, key=lambda r: r[1]):
            out.append(f"place_pin -pin_name {{{name}}} -layer M4 -location {{{x:.3f} {y:.3f}}}")
    return "\n".join(out) + "\n", {f: sorted({re.sub(r"\[.*", "", n) for n, _ in rows}) for f, rows in plan.items()}

def regions_tcl(kit, nk):
    tx = []
    for g in range(8):
        y0 = LSL_Y[g % 4]
        x0, x1 = ((LSLA_X + LSL_W + 0.5, NODE_X - 0.5) if g < 4 else (NODE_X + NODE_W + 0.3, LSLB_X - 0.3))
        tx.append(f"  [dict create name tx{g} type EXCLUSIVE regex {{g_sl\\[{g}\\]\\.g_hd\\.(g_tx\\.g_r\\[1\\]\\.u_tx/|g_lrr\\.rq|g_outland\\.q)}} "
                  f"boxes {{{{{x0:.3f} {y0:.3f} {x1:.3f} {y0 + LSL_H:.3f}}}}} min 1 max 100000] \\")
    cw0, cw1 = ROM0_X + ROM_W + 0.4, LSLA_X - 0.4          # ROM 0 pin channel
    ce0, ce1 = LSLB_X + LSL_W + 0.4, ROM1_X - 0.4          # ROM 1 pin channel
    hub = (NODE_X + 0.5, 8.0, NODE_X + NODE_W - 0.5, (NODE_Y if nk else H - 48.0) - 6.0)
    lo = "([0-9]|[1-9][0-9]|[1-4][0-9][0-9]|50[0-9]|51[01])"
    g = [
      "  [dict create name land_tx type FREE regex {g_hd\\.g_tx\\.g_r\\[0\\]\\.u_tx/} boxes {} min 1 max 100000] \\",
      "  [dict create name land_rq type FREE regex {g_rom_pipe\\.rq_(ce|ad)_[sn]\\[1\\]\\[} boxes {} min 1 max 100000] \\",
      "  [dict create name land_fault type FREE regex {u_me\\.fault_q\\[} boxes {} min 0 max 100] \\",
      *tx,
      f"  [dict create name rsw type EXCLUSIVE regex {{(g_rqr\\.(genblk[0-9]+\\.g_col_roots\\.gs|gs_q)\\[{lo}\\]|g_rph\\.g_rb\\[[0-2]\\]\\.g_single\\.g_col\\[0\\]\\.g_lrr\\.rq)}} boxes {{{{{cw0:.3f} 40.0 {cw1:.3f} 300.0}}}} min 1 max 100000] \\",
      f"  [dict create name rnw type EXCLUSIVE regex {{(g_rqr\\.(genblk[0-9]+\\.g_col_roots\\.gn|gn_q)\\[{lo}\\]|g_rph\\.g_rb\\[[34]\\]\\.g_single\\.g_col\\[0\\]\\.g_lrr\\.rq)}} boxes {{{{{cw0:.3f} 560.0 {cw1:.3f} 860.0}}}} min 1 max 100000] \\",
      f"  [dict create name rse type EXCLUSIVE regex {{(g_rqr\\.(genblk[0-9]+\\.g_col_roots\\.gs|gs_q)\\[|g_rph\\.g_rb\\[[0-2]\\]\\.g_single\\.g_col\\[1\\]\\.g_lrr\\.rq)}} boxes {{{{{ce0:.3f} 40.0 {ce1:.3f} 300.0}}}} min 1 max 100000] \\",
      f"  [dict create name rne type EXCLUSIVE regex {{(g_rqr\\.(genblk[0-9]+\\.g_col_roots\\.gn|gn_q)\\[|g_rph\\.g_rb\\[[34]\\]\\.g_single\\.g_col\\[1\\]\\.g_lrr\\.rq)}} boxes {{{{{ce0:.3f} 560.0 {ce1:.3f} 860.0}}}} min 1 max 100000] \\",
      f"  [dict create name dw type EXCLUSIVE regex {{(u_me\\.g_operand_rr\\.g_lsel\\.s1b_(wsrc_w|gm_w\\[)|u_me\\.g_operand_rr\\.g_csel\\.(wsrc_q|gm_q)\\[([0-9]|1[0-5])\\]|u_me\\.mq_wrom\\[{lo}\\]|g_hd\\.g_tx\\.tc\\[(12[89]|1[3-9][0-9]|2[0-4][0-9]|25[0-5])\\])}} boxes {{{{{cw0:.3f} 300.0 {cw1:.3f} 560.0}}}} min 1 max 100000] \\",
      f"  [dict create name de type EXCLUSIVE regex {{(u_me\\.g_operand_rr\\.g_lsel\\.s1b_(wsrc_e|gm_e\\[)|u_me\\.g_operand_rr\\.g_csel\\.(wsrc_q|gm_q)\\[|u_me\\.mq_wrom\\[|g_hd\\.g_tx\\.tc\\[(25[6-9]|2[6-9][0-9]|3[0-7][0-9]|38[0-3])\\])}} boxes {{{{{ce0:.3f} 300.0 {ce1:.3f} 560.0}}}} min 1 max 100000] \\",
      f"  [dict create name hub type EXCLUSIVE regex {{^u_g\\.u_tile\\.}} boxes {{{{{hub[0]:.3f} {hub[1]:.3f} {hub[2]:.3f} {hub[3]:.3f}}}}} min 1 max 100000] \\",
    ]
    hdr = [f"# {kit}: generated by tools/qwen_romleaf/rc1/gen_rc1.py (QW-CLUSTER3/A0 10-19).  Regional soft roots, one compact",
           "# EXCLUSIVE box beside each consumer: TX rungs + output landings in the strip at each LSL's pin face, ROM RQR S/N halves",
           "# and the ROM-word / s2_w operand halves (dw/de) in the ROM pin channels, the issue engine (hub, every other ck flop",
           "# incl. the REGROOT 6 copies) in the middle column.  Counts are bounded below/above only (REGROOT 4/5/6 add copies).",
           "set qrl_groups [list \\"]
    return "\n".join(hdr + g + ["]", "source /src/tools/qwen_romleaf/parent_regions.tcl", ""])

def spec(nk, fallback):
    k = "nk" if nk else "nl"
    base = json.load(open(ROOT / f"physical/ref_tile/qfd_tile_{k}_romleaf_c1/spec.json"))
    kit = f"qfd_tile_{k}_romleaf_rc1" + ("f" if fallback else "")
    s = copy.deepcopy(base)
    s["name"] = kit
    s["outline"] = {"w": W, "h": H, "exact": True}
    s["children"] = children(nk)
    ptcl, faces = pins_tcl(kit, nk)
    s["pins"] = {"W": faces["W"], "E": faces["E"]}
    s["io_tcl"] = f"tools/qwen_romleaf/rc1/{kit}_pins.tcl"
    s["params"] = {"REGROOT_MODE": 6}
    s["pin_hook_before_flops"] = [] if fallback else [f"tools/qwen_romleaf/rc1/{kit}_regions.tcl"]
    s["reset_landing"] = {"enable": True, "stages": 2, "clock": "ck_fa4", "copies": {"rst_n": 8}}
    s["reset_relay_split"] = {"max_loads": 32}
    s["structural_change"] = ("QW-CLUSTER3/A0 rc1 (10-19, safe-design rebuild after c1r9f): REGROOT 6 RTL (per-destination kept "
        "copies of split_r/wsrc_r/active/k_last/pend/j_last/t_last, 0 cycles), kit reset landing 2 stages on ck_fa4 with 8 "
        "kept last-stage copies <=32 loads (replaces the 1-stage native reset_q: +1 boot edge), new 820.8 x 907.2 outline "
        "(aspect 1.11, 43.2-lattice origins, full-width std rows, pins <=5.2/um)" + ("; FALLBACK: no soft-root regions "
        "(placer-free)" if fallback else "; soft-root regions beside each consumer") + ".")
    s["slot_change_request"] = ("QW-CLUSTER3/A0 rc1: die slot changes 457.92 x 1166.4 -> 820.8 x 907.2 (+210.5k um2 per tile); "
        "die re-plan required before adoption; pin faces W/E kept.")
    j = s["job"]
    j["owner"] = "Claude:QW-CLUSTER3/A0"; j["branch"] = "claude/qw-cluster3-a0-1019"; j["tag"] = "rc1f" if fallback else "rc1"
    j["purpose"] = s["structural_change"]
    j["views_to"] = f"physical/ref_tile/{kit}/views"; j["record_to"] = f"results/rtl/ref_tile/{kit}"
    j["hold_merge"] = s["hold_merge"] = ("CRITICAL A0 (critical_tiles.txt): gate PNG + checklist review only; no REVIEW.json / "
                                         "submit by the lane agent.")
    j["cycles_added"] = 0
    ep = set(j.get("extra_paths", [])) | {"tools/qwen_romleaf", "rtl/test/tb_qwen_a0_rr6.sv", "tools/qwen_a0_safe"}
    j["extra_paths"] = sorted(ep)
    return kit, s, ptcl, (None if fallback else regions_tcl(kit, nk))

if __name__ == "__main__":
    for nk in (True, False):
        for fb in (False, True):
            kit, s, ptcl, rtcl = spec(nk, fb)
            (ROOT / f"tools/ref_tile/specs_qw_cluster3_1019/{kit}.json").write_text(json.dumps(s, indent=1) + "\n")
            (ROOT / f"tools/qwen_romleaf/rc1/{kit}_pins.tcl").write_text(ptcl)
            if rtcl:
                (ROOT / f"tools/qwen_romleaf/rc1/{kit}_regions.tcl").write_text(rtcl)
            print("RC1", kit, len(ptcl.splitlines()) - 2, "pins")
