#!/usr/bin/env python3
"""Q-KVSYS-STRIP 2026-10-16 (VIS-ROM audit D-QK-02, sev 2): the KV/system die's attention-stack aggregator strip
qkd_astk / qkd_astk_n (220 x 9,675 um, 44:1, every lane fanning to the strip centre, astk -> ectl_c links up to 9.06 mm)
is cut into ONE replicated hardened segment master per engine row: qkd_astk_seg.

  segment (row r of a stack) = the row's two engine columns of CLOSED leaves, exactly as the benched die wiring
  ot_qkd_astk_strip (rtl/test/qwen_kv_die/ot_qwen_nearhbm_attn_stack_k.sv) places them:
      column c (c = 0: engine 2 r, the W engine; c = 1: engine 2 r + 1), bottom to top:
      head 0 A, B | head 1 A, B | ex, ex | ep | ex, ex | head 2 A, B | head 3 A, B      (13 leaves, 13 lane stations)
  = 16 x qkd_astk_pv_tp8 + 8 x qkd_astk_ex + 2 x qkd_astk_ep, plus the relay stations of every chain hop that ENTERS
  the row (command qi, e-row ri, return xi, chunk zi) and the two intra-row hops, as registered input stages.

  The strip's static spine between segments is therefore register to register: every segment output is a leaf output
  flop (lanes, xo, zo) or a relay flop (qi / ro), every segment input lands on a relay flop or a leaf pin flop.  The hub
  end (qkd_astk_ctl_tp8, 4 x qkd_astk_zn, the hub-end relay stations u_rq8 / u_rx8 / u_rc / u_rpx / u_rpy / u_rf) stays
  as die leaves / die relay stations above row 3, unchanged.

  Cycle accounting: the relay stations are the SAME stations as the benched composition (D = RL on qi / ri / xi each
  engine, zi on the even engine, the odd engine's zi direct), only moved inside the segment that consumes them; the
  lanes stay leaf to leaf.  The segmented strip ot_qkd_astk_strip_seg is cycle-identical to ot_qkd_astk_strip (bench:
  physical/qkd_astk_strip/bench.sh with ASTK_SEG=1 compares both against the golden and reports the same dut cycles).

  Row-dependent straps (wires only, tied at the die): st[1:0] (stack), r[1:0] (row), rcfg[21:0] (the row's tree-cell
  configuration, rcfg_word(r) below; the hp / far bits are hard-wired per cell).

    python3 tools/qwen_kv_die/astk_segments.py --out rtl/qwen_sys/split_20261014/qkd_astk_seg.sv [--check]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = 'rtl/qwen_sys/split_20261014/qkd_astk_seg.sv'

# per-row tree-cell straps of the benched composition (ot_qkd_astk_strip, g_r / g_c / g_h)
def row_cfg(r):
    ym_a = 2 if r in (1, 3) else 0
    ath_a, bth_a = 2 * r, 2 * r + 1
    lvl_b = 1 if r in (0, 2) else (2 if r == 1 else 3)
    am_b = 0 if r in (0, 2) else 1
    bm_b = 0 if r == 3 else 2
    ym_b = 1 if r in (0, 1) else (2 if r == 2 else 0)
    ath_b = 4 if r == 2 else 0
    bth_b = {0: 2, 1: 4, 2: 6, 3: 0}[r]
    return dict(ym_a=ym_a, ath_a=ath_a, bth_a=bth_a, lvl_b=lvl_b, am_b=am_b, bm_b=bm_b, ym_b=ym_b, ath_b=ath_b, bth_b=bth_b)


RCFG = (('ym_a', 2), ('ath_a', 3), ('bth_a', 3), ('lvl_b', 2), ('am_b', 2), ('bm_b', 2), ('ym_b', 2), ('ath_b', 3), ('bth_b', 3))


def rcfg_word(r):
    """the rcfg strap of row r (LSB first, RCFG order): the die ties it at the segment's pins"""
    c, w, o = row_cfg(r), 0, 0
    for k, n in RCFG:
        w |= c[k] << o
        o += n
    return w


def rcfg_slices():
    o, out = 0, {}
    for k, n in RCFG:
        out[k] = f'rcfg[{o + n - 1}:{o}]' if n > 1 else f'rcfg[{o}]'
        o += n
    return out, o


# lanes of one column: (name, width, direction 'up' = enters at the bottom)
LANES = (('u', 536, 'up'), ('d', 536, 'dn'), ('p', 263, 'up'), ('c', 6, 'dn'), ('tu', 1, 'up'), ('td', 1, 'dn'),
         ('f', 1, 'up'), ('ku', 4, 'dn'), ('kd', 4, 'up'))


def lane_ports():
    """segment lane ports: <lane><c>_b (bottom face) / <lane><c>_t (top face); up lanes in at b / out at t"""
    out = []
    for c in range(2):
        for n, w, d in LANES:
            out.append((f'{n}{c}_b', w, 'input' if d == 'up' else 'output'))
            out.append((f'{n}{c}_t', w, 'output' if d == 'up' else 'input'))
    return out


def vec(w):
    return f'[{w - 1}:0]' if w > 1 else ''


def emit_seg():
    rs, nr = rcfg_slices()
    assert nr == 22
    P = [('ck_v', 16, 'input'), ('ck_x', 8, 'input'), ('ck_e', 2, 'input'), ('ck_r', 1, 'input'), ('rst_n', 1, 'input'),
         ('st', 2, 'input'), ('r', 2, 'input'), ('rcfg', 22, 'input'),
         ('so_a', 425, 'input'), ('si_a', 634, 'output'), ('nb_a', 4096, 'input'),
         ('so_b', 425, 'input'), ('si_b', 634, 'output'), ('nb_b', 4096, 'input'),
         ('qi_i', 572, 'input'), ('qi_o', 572, 'output'), ('ro_i', 522, 'input'), ('ro_o', 522, 'output'),
         ('xi_i', 267, 'input'), ('xo_o', 267, 'output'), ('zi_i', 651, 'input'), ('zo_o', 651, 'output')] + lane_ports()
    L = ['// ---- generated by tools/qwen_kv_die/astk_segments.py -- do not edit ---------------------------------------------',
         '// qkd_astk_seg: ONE engine row of the attention-stack aggregator strip (16 tree cells, 8 exp heads, 2 engine',
         '// slices = 26 CLOSED leaves) + the relay stations of the chain hops entering the row.  Wires and relay flops only.',
         'module qkd_astk_seg #(', '    parameter integer RL = 1', ') (']
    L += [f'    {d:6s} wire {vec(w):12s} {n},' for n, w, d in P]
    L[-1] = L[-1].rstrip(',')
    L += [');']
    a = L.append
    a('    // ---- lane stations of each column: 0 (bottom face) .. 13 (top face) ----------------------------------------')
    for n, w, d in LANES:
        a(f'    wire {vec(w)} {n.upper()}0 [0:13];')
        a(f'    wire {vec(w)} {n.upper()}1 [0:13];')
    for c in range(2):
        for n, w, d in LANES:
            N = f'{n.upper()}{c}'
            if d == 'up':
                a(f'    assign {N}[0] = {n}{c}_b; assign {n}{c}_t = {N}[13];')
            else:
                a(f'    assign {N}[13] = {n}{c}_t; assign {n}{c}_b = {N}[0];')
    a('    // ---- chain hops (the benched composition\'s relay stations, D = RL; the odd engine\'s zi is direct) ----------')
    a('    wire [571:0] qi_b, qi_a;  wire [521:0] ri_b, ri_a;  wire [266:0] xi_a, xi_b, xo_a;  wire [650:0] zi_a, zo_a;')
    a('    ot_hdc_delay #(.W(572), .D(RL), .RESET(1)) u_rqb (.clk(ck_r), .rst_n(rst_n), .d(qi_i), .q(qi_b));   // engine 2r+1')
    a('    ot_hdc_delay #(.W(572), .D(RL), .RESET(1)) u_rqa (.clk(ck_r), .rst_n(rst_n), .d(qi_b), .q(qi_a));   // engine 2r')
    a('    assign qi_o = qi_a;')
    a('    ot_hdc_delay #(.W(522), .D(RL), .RESET(1)) u_rrb (.clk(ck_r), .rst_n(rst_n), .d(ro_i), .q(ri_b));')
    a('    ot_hdc_delay #(.W(522), .D(RL), .RESET(1)) u_rra (.clk(ck_r), .rst_n(rst_n), .d(ri_b), .q(ri_a));')
    a('    assign ro_o = ri_a;')
    a('    ot_hdc_delay #(.W(267), .D(RL), .RESET(1)) u_rxa (.clk(ck_r), .rst_n(rst_n), .d(xi_i), .q(xi_a));')
    a('    ot_hdc_delay #(.W(267), .D(RL), .RESET(1)) u_rxb (.clk(ck_r), .rst_n(rst_n), .d(xo_a), .q(xi_b));')
    a('    ot_hdc_delay #(.W(651), .D(RL), .RESET(1)) u_rza (.clk(ck_r), .rst_n(rst_n), .d(zi_i), .q(zi_a));')
    a('    // ---- the two engine slices (ep at lane station 6 of its column) -----------------------------------------------')
    a('    wire [263:0] xa_a, xa_b;  wire [135:0] xe_a, xe_b;  wire cr_a, cr_b;')
    for c, e in ((0, 'a'), (1, 'b')):
        qi, ri, xi, zi = f'qi_{e}', f'ri_{e}', f'xi_{e}', ('zi_a' if e == 'a' else 'zo_a')
        xo, zo = ('xo_a' if e == 'a' else 'xo_o'), ('zo_a' if e == 'a' else 'zo_o')
        a(f'    qkd_astk_ep u_ep{e} (.ck(ck_e[{c}]), .rst_n(rst_n), .sq({{st, r, 1\'b{c}}}), .so(so_{e}), .si(si_{e}), .qi({qi}), '
          f'.xi({xi}), .xo({xo}), .zi({zi}), .zo({zo}), .ri({ri}), .xa(xa_{e}), .xe(xe_{e}), .cr(cr_{e}),')
        a('        ' + lane_conn(c, 6) + ');')
        for xh in range(4):
            xs = 4 + xh if xh < 2 else 5 + xh
            a(f'    qkd_astk_ex u_ex{e}{xh} (.ck(ck_x[{4 * c + xh}]), .rst_n(rst_n), .xa(xa_{e}[{66 * xh + 65}:{66 * xh}]), '
              f'.xe(xe_{e}[{34 * xh + 33}:{34 * xh}]),')
            a('        ' + lane_conn(c, xs) + ');')
    a('    // ---- the tree cells (level-4 cell A, the row\'s second-level cell B; head hp of column c) ----------------------')
    for c in range(2):
        a(f'    wire [9:0] nco{c} [0:3];  wire [9:0] ndo{c} [0:3];  wire [3:0] cra{c}, crb{c};')
        for hp in range(4):
            st_ = 2 * hp if hp < 2 else 9 + 2 * (hp - 2)
            far = 1 if hp in (0, 3) else 0
            near = 1 if hp == 0 else 2
            g = f'{c}{hp}'
            a(f'    wire [511:0] wa{g}, wb{g};  wire [133:0] lo{g};  wire lc{g};')
            for m in range(16):
                kk = 4 * (m // 2) + 2 * c + (m % 2)
                lo_, hi_ = 1024 * hp + 32 * kk, 1024 * hp + 32 * kk + 31
                a(f'    assign wa{g}[{32 * m + 31}:{32 * m}] = nb_a[{hi_}:{lo_}]; '
                  f'assign wb{g}[{32 * m + 31}:{32 * m}] = nb_b[{hi_}:{lo_}];')
            nc = f'nco{c}[{near}]' if far else 'so_a[421:412]'
            nd = f'ndo{c}[{near}]' if far else 'so_b[421:412]'
            cfg_a = (f"{{1'b0, 1'b{far}, {rs['bth_a']}, {rs['ath_a']}, {rs['ym_a']}, 2'd0, 2'd0, 2'd0, 2'd{hp}}}")
            cfg_b = (f"{{1'b0, 1'b0, {rs['bth_b']}, {rs['ath_b']}, {rs['ym_b']}, {rs['bm_b']}, {rs['am_b']}, {rs['lvl_b']}, "
                     f"2'd{hp}}}")
            a(f'    qkd_astk_pv_tp8 u_a{g} (.ck(ck_v[{8 * c + 2 * hp}]), .rst_n(rst_n), .cfg({cfg_a}),')
            a(f'        .wa(wa{g}), .wb(wb{g}), .nc({nc}), .nd({nd}), .nco(nco{c}[{hp}]), .ndo(ndo{c}[{hp}]), '
              f'.cra(cra{c}[{hp}]), .crb(crb{c}[{hp}]), .li(134\'d0), .lo(lo{g}), .lci(lc{g}), .lco(),')
            a('        ' + lane_conn(c, st_) + ');')
            a(f'    qkd_astk_pv_tp8 u_b{g} (.ck(ck_v[{8 * c + 2 * hp + 1}]), .rst_n(rst_n), .cfg({cfg_b}),')
            a(f'        .wa(512\'d0), .wb(512\'d0), .nc(10\'d0), .nd(10\'d0), .nco(), .ndo(), .cra(), .crb(), .li(lo{g}), .lo(), '
              f'.lci(1\'b0), .lco(lc{g}),')
            a('        ' + lane_conn(c, st_ + 1) + ');')
    a('    assign cr_a = cra0[1]; assign cr_b = crb0[1];')
    a('endmodule')
    return '\n'.join(L)


def lane_conn(c, s):
    """leaf lane pins at lane station s of column c (the benched composition's U/D/P/C/T/K/F index pattern)"""
    t = s + 1
    return (f'.ui(U{c}[{s}]), .uo(U{c}[{t}]), .di(D{c}[{t}]), .do_(D{c}[{s}]), .pi(P{c}[{s}]), .po(P{c}[{t}]), '
            f'.ci(C{c}[{t}]), .co(C{c}[{s}]), .tui(TU{c}[{s}]), .tuo(TU{c}[{t}]), .tdi(TD{c}[{t}]), .tdo(TD{c}[{s}]), '
            f'.kui(KU{c}[{t}]), .kuo(KU{c}[{s}]), .kdi(KD{c}[{s}]), .kdo(KD{c}[{t}]), .fi(F{c}[{s}]), .fo(F{c}[{t}])')


def emit_strip():
    """ot_qkd_astk_strip_seg: the strip as 4 segments + the unchanged hub end, ports = ot_qkd_astk_strip's (bench)"""
    L = ['// ot_qkd_astk_strip_seg: ot_qkd_astk_strip rebuilt from 4 x qkd_astk_seg (one clock: the bench reference)',
         'module ot_qkd_astk_strip_seg #(', '    parameter integer S = 0', ') (',
         '    input  wire              clk,', '    input  wire              rst_n,', '    input  wire              start,',
         '    input  wire [13:0]       T,', '    input  wire              q_valid,', '    input  wire [5:0]        q_beat,',
         '    input  wire [511:0]      q_data,', '    input  wire              mi_valid,', '    input  wire              mi_g,',
         '    input  wire [1:0]        mi_hh,', '    input  wire [31:0]       mi_data,', '    output wire              so_valid,',
         '    output wire [1:0]        so_type,', '    output wire              so_g,', '    output wire [1:0]        so_hh,',
         '    output wire [3:0]        so_k,', '    output wire              so_any,', '    output wire [31:0]       so_data,',
         '    output wire              pv_valid,', '    output wire              pv_g,', '    output wire [5:0]        pv_beat,',
         '    output wire [511:0]      pv_data,', '    output wire [1:0]        pv_done,', '    output wire              fault,',
         '    input  wire [425*8-1:0]  so_f,', '    output wire [634*8-1:0]  si_f,', '    input  wire [4096*8-1:0] nb_f', ');']
    a = L.append
    a('    localparam integer RL = `KVD_AKRL;')
    a('    wire [1:0] SS = S;')
    a('    wire [564:0] ap;  wire [571:0] cq_o;  wire [266:0] cx_i;  wire [5:0] cco;  wire [262:0] px, py;  wire [137:0] czi;')
    a('    wire cfx, cfy, cfz, af;')
    a('`ifdef KVD_ASTK_TP8')
    a('    qkd_astk_ctl_tp8 u_ctl (.ck(clk),')
    a('`else')
    a('    qkd_astk_ctl u_ctl (.ck(clk),')
    a('`endif .rst_n(rst_n), .st(SS), .aq({q_data, q_beat, q_valid, 6\'d0, T, start}), .lt(),')
    a('        .am({mi_data, mi_hh, mi_g, mi_valid}), .ap(ap), .af(af), .qo(cq_o), .xi(cx_i), .co(cco), .px(px), .py(py),')
    a('        .zi(czi), .fx(cfx), .fy(cfy), .fz(cfz));')
    a('    assign so_valid = ap[0]; assign so_type = ap[2:1]; assign so_g = ap[3]; assign so_hh = ap[5:4]; assign so_k = ap[9:6];')
    a('    assign so_any = ap[10]; assign so_data = ap[42:11]; assign pv_done = ap[44:43]; assign pv_valid = ap[45];')
    a('    assign pv_g = ap[46]; assign pv_beat = ap[52:47]; assign pv_data = ap[564:53];')
    a('    assign fault = af;')
    a('    // segment chains: index k = the boundary below row k (k = 4: the hub end)')
    a('    wire [571:0] qc [0:4];  wire [521:0] rc [0:4];  wire [266:0] xc [0:4];  wire [650:0] zc [0:4];')
    a('    assign xc[0] = 267\'d0; assign zc[0] = 651\'d0;')
    a('    ot_hdc_delay #(.W(572), .D(RL), .RESET(1)) u_rq8 (.clk(clk), .rst_n(rst_n), .d(cq_o), .q(qc[4]));')
    a('    ot_hdc_delay #(.W(267), .D(RL), .RESET(1)) u_rx8 (.clk(clk), .rst_n(rst_n), .d(xc[4]), .q(cx_i));')
    a('    assign rc[4] = {zc[4][650:139], zc[4][10:7], zc[4][6:3], zc[4][2], zc[4][0]};')
    for n, w, d in LANES:
        a(f'    wire {vec(w)} {n.upper()}B0 [0:4];  wire {vec(w)} {n.upper()}B1 [0:4];   // column lane at row boundary k')
    for c in range(2):
        a(f'    assign UB{c}[0] = 536\'d0; assign PB{c}[0] = 263\'d0; assign TUB{c}[0] = 1\'b0; assign FB{c}[0] = 1\'b0; '
          f'assign KDB{c}[0] = 4\'d0;')
        a(f'    assign DB{c}[4] = 536\'d0; assign TDB{c}[4] = 1\'b0; assign KUB{c}[4] = 4\'d0;')
        a(f'    ot_hdc_delay #(.W(6), .D(RL), .RESET(1)) u_rc{c} (.clk(clk), .rst_n(rst_n), .d(cco), .q(CB{c}[4]));')
    a('    ot_hdc_delay #(.W(263), .D(RL), .RESET(1)) u_rpx (.clk(clk), .rst_n(rst_n), .d(PB0[4]), .q(px));')
    a('    ot_hdc_delay #(.W(263), .D(RL), .RESET(1)) u_rpy (.clk(clk), .rst_n(rst_n), .d(PB1[4]), .q(py));')
    a('    ot_hdc_delay #(.W(2), .D(RL), .RESET(1)) u_rf (.clk(clk), .rst_n(rst_n), .d({FB1[4], FB0[4]}), .q({cfy, cfx}));')
    rs = {0: 'rcfg0', 1: 'rcfg1', 2: 'rcfg2', 3: 'rcfg3'}
    for r in range(4):
        a(f"    localparam [21:0] RCFG{r} = 22'd{rcfg_word(r)};")
    for r in range(4):
        ea, eb = 2 * r, 2 * r + 1
        conn = [f'.ck_v({{16{{clk}}}})', '.ck_x({8{clk}})', '.ck_e({2{clk}})', '.ck_r(clk)', '.rst_n(rst_n)', '.st(SS)',
                f".r(2'd{r})", f'.rcfg(RCFG{r})',
                f'.so_a(so_f[{425 * ea + 424}:{425 * ea}])', f'.si_a(si_f[{634 * ea + 633}:{634 * ea}])',
                f'.nb_a(nb_f[{4096 * ea + 4095}:{4096 * ea}])',
                f'.so_b(so_f[{425 * eb + 424}:{425 * eb}])', f'.si_b(si_f[{634 * eb + 633}:{634 * eb}])',
                f'.nb_b(nb_f[{4096 * eb + 4095}:{4096 * eb}])',
                f'.qi_i(qc[{r + 1}])', f'.qi_o(qc[{r}])', f'.ro_i(rc[{r + 1}])', f'.ro_o(rc[{r}])',
                f'.xi_i(xc[{r}])', f'.xo_o(xc[{r + 1}])', f'.zi_i(zc[{r}])', f'.zo_o(zc[{r + 1}])']
        for c in range(2):
            for n, w, d in LANES:
                N = f'{n.upper()}B{c}'
                conn += [f'.{n}{c}_b({N}[{r}])', f'.{n}{c}_t({N}[{r + 1}])']
        a(f'    qkd_astk_seg #(.RL(RL)) u_seg{r} (' + ', '.join(conn) + ');')
    a('    // ---- the Z tree behind slice 7 (unchanged) -----------------------------------------------------------------')
    a('    wire [137:0] zn_w [0:4];  wire [4:0] zf_w;')
    a('    assign zn_w[0] = {zc[4][138:11], zc[4][10:7], zc[4][6:3], zc[4][2], zc[4][0]};')
    a('    assign zf_w[0] = 1\'b0;')
    a('    genvar z;')
    a('    generate for (z = 0; z < 4; z = z + 1) begin : g_z')
    a('        qkd_astk_zn u_zn (.ck(clk), .rst_n(rst_n), .zc({2\'(z), SS}), .tc(cq_o[14:0]), .zi(zn_w[z]), .zo(zn_w[z+1]),')
    a('                          .fi(zf_w[z]), .fo(zf_w[z+1]));')
    a('    end endgenerate')
    a('    assign czi = zn_w[4]; assign cfz = zf_w[4];')
    a('endmodule')
    return '\n'.join(L)





def emit():
    return '`timescale 1ns/1ps\n' + emit_seg() + '\n\n' + '`ifndef SYNTHESIS\n' + emit_strip() + '\n`endif\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    t = emit()
    p = ROOT / a.out
    if a.check:
        ok = p.exists() and p.read_text() == t
        print('astk_segments: ' + ('up to date' if ok else 'STALE'))
        return 0 if ok else 1
    p.write_text(t)
    print(f'astk_segments: wrote {a.out} ({len(t.splitlines())} lines); rcfg ' +
          ', '.join(f'r{r}=0x{rcfg_word(r):06x}' for r in range(4)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
