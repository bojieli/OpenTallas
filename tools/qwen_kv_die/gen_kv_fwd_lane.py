#!/usr/bin/env python3
"""KV-CLOCK/LANEKITS 10-18 (LANDING-CONTRACT sections 2, 3, 7; landed-regions standard 10-18): the KV/system die's
forwarded-clock HALF-CYCLE lane masters at the four KV relay standards S in {1, 36, 296, 528}
(tools/qwen_kv_die/kv_rly_std.py).  A KV die relay chain that crosses clock regions (core c <-> stack WS/WN/ES/EN) binds
each replica of its stages to one of these, in the frame of the qkd_rlys_<S> standard it replaces:

    qkd_rlysh0_<S>   ck en a b eb ck_o                                    hop-0 station (ICG on the source root)
    qkd_rlysh_<S>    ckf ea a b eb ck_o                                   half-cycle station (ck_o = ~ckf)
    qkd_landsh_<S>   ckf ea a ck rs k0 k1 k2 tie_hi tie_lo b fault        landing (ring D 4 on ckf, read on the block root)
    qkd_landsh0_<S>  ck_s en a ck rs k0 k1 k2 tie_hi tie_lo b fault       n = 1 lane: landing with the hop-0 gate

The bodies are EXACTLY the wrappers tools/qwen_split/gen_relay_rtl.py emits for qfd_rlyh0_/qfd_rlyh_/qfd_landh_/
qfd_landh0_ (claude/q-die11b-1018), over the shared cores rtl/qwen_split/qfd_fwd_lane.sv (ot_qfd_lane_st, ot_qfd_land)
+ rtl/hdc/ot_hdc_cg.sv.  Port order = gen_relay_rtl.FWD.

    gen_kv_fwd_lane.py rtl                 -> rtl/qwen_sys/kv_fwd_lane_20261018/qkd_rlysh.sv
    gen_kv_fwd_lane.py specs [--owner O --branch B --tag T]
                                           -> tools/ref_tile/specs_kvfwd/qkd_<fam>_<S>.json (ref_tile.py gen inputs)
Frames: the qkd_rlys_<S> outlines exactly (1 / 36: 12.96 x 12.96, 296: 21.6 x 47.52, 528: 21.6 x 82.08), a on W, b on E
(M4, the standards' pin ranges), the 1-bit lane / strap pins on S (inputs) and N (outputs).
"""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STD = {1: (12.96, 12.96), 36: (12.96, 12.96), 296: (21.6, 47.52), 528: (21.6, 82.08)}
# KV-LANEKITS 10-18 gate f1: a landing (5S + 14 flops + read mux) does not fit its station frame: GPL utilisation 181 % (36),
# 128 % (296 / landsh0_296), 126 % (528); landsh0_1 fits (WARN 0 fail).  Landing frames, same height (W/E faces kept),
# ~2.3-3.3x the station area for ~55 % util: the die plan must reserve these at a crossing chain's last stage
LAND = {1: (12.96, 12.96), 36: (25.92, 21.6), 296: (51.84, 47.52), 528: (51.84, 82.08)}
FWD = {'qkd_rlysh0_': ('ck', 'en', 'a', 'b', 'eb', 'ck_o'), 'qkd_rlysh_': ('ckf', 'ea', 'a', 'b', 'eb', 'ck_o'),
       'qkd_landsh_': ('ckf', 'ea', 'a', 'ck', 'rs', 'k0', 'k1', 'k2', 'tie_hi', 'tie_lo', 'b', 'fault'),
       'qkd_landsh0_': ('ck_s', 'en', 'a', 'ck', 'rs', 'k0', 'k1', 'k2', 'tie_hi', 'tie_lo', 'b', 'fault')}
FWD_OUT = ('b', 'eb', 'ck_o', 'tie_hi', 'tie_lo', 'fault')
RTL = 'rtl/qwen_sys/kv_fwd_lane_20261018/qkd_rlysh.sv'
LANE_RTL = ['rtl/qwen_split/qfd_fwd_lane.sv', 'rtl/hdc/ot_hdc_cg.sv', RTL]
CLK_TCL = 'physical/qwen_kv_fwd_lane/kv_fwd_lane_clocks.tcl'
WIT = 'results/arch/qwen_kv_die/kv_clock_1018/bench'
MUTANTS = {'qkd_rlysh0_': ('full',), 'qkd_rlysh_': ('full',), 'qkd_landsh_': ('sel', 'naive'), 'qkd_landsh0_': ('sel', 'naive')}
CLOCK = {'qkd_rlysh0_': 'ck', 'qkd_rlysh_': 'ckf', 'qkd_landsh_': 'ck', 'qkd_landsh0_': 'ck'}
KIND = {'qkd_rlysh0_': 'hop-0 station (ICG on the source root, rising capture, inverted ck_o)',
        'qkd_rlysh_': 'half-cycle station', 'qkd_landsh_': 'landing (ring D 4, read on the block root)',
        'qkd_landsh0_': 'landing with the hop-0 gate'}


def module(fam, W):
    mn = f'{fam}{W}'
    decl = ', '.join(f'{"output" if p in FWD_OUT else "input"} wire {f"[{W - 1}:0] " if p in ("a", "b") else ""}{p}'
                     for p in FWD[fam])
    L = [f'module {mn} ({decl});']
    if fam in ('qkd_rlysh0_', 'qkd_rlysh_'):
        ck_, en_ = ('ck', 'en') if fam == 'qkd_rlysh0_' else ('ckf', 'ea')
        L += [f'    ot_qfd_lane_st #(.W({W}), .FIRST({1 if fam == "qkd_rlysh0_" else 0})) u_st (.ck({ck_}), .en({en_}), '
              '.a(a), .b(b), .eb(eb), .ck_o(ck_o));']
    else:
        first = fam == 'qkd_landsh0_'
        L += ['    (* keep = "true" *) wire tie_hi_w = 1\'b1;', '    (* keep = "true" *) wire tie_lo_w = 1\'b0;',
              '    assign tie_hi = tie_hi_w;', '    assign tie_lo = tie_lo_w;',
              f'    ot_qfd_land #(.W({W}), .D(4), .FIRST({int(first)})) u_land (.ckf({"ck_s" if first else "ckf"}), '
              f'.ea({"en" if first else "ea"}), .i(a), .ck(ck), .rs(rs), .k({{k2, k1, k0}}), .o(b), .fault(fault));']
    return L + ['endmodule']


def rtl():
    L = ['`timescale 1ns/1ps', '`default_nettype none',
         '// KV-CLOCK/LANEKITS 10-18: KV forwarded half-cycle lane masters at the KV relay standards (generated by',
         '// tools/qwen_kv_die/gen_kv_fwd_lane.py; bodies = tools/qwen_split/gen_relay_rtl.py qfd_rlyh*/qfd_landh* wrappers',
         '// over rtl/qwen_split/qfd_fwd_lane.sv).  Do not edit by hand.']
    for fam in FWD:
        for W in STD:
            L += module(fam, W)
    L += ['`default_nettype wire']
    p = ROOT / RTL
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text('\n'.join(L) + '\n')
    print(p)


def spec(fam, S, a):
    land = fam.startswith('qkd_landsh')
    w, h = (LAND if land else STD)[S]
    std = json.loads((ROOT / f'physical/ref_tile/qkd_rlys_{S}/spec.json').read_text())
    name = f'{fam}{S}'
    ins = [p for p in FWD[fam] if p not in ('a', 'b') and p not in FWD_OUT]
    outs = [p for p in FWD[fam] if p not in ('a', 'b') and p in FWD_OUT]
    pins = {'W': ['a'], 'E': ['b'], 'S': ins, 'N': outs}
    rng = {k: v for k, v in std.get('pin_ranges', {}).items() if k in ('a', 'b') and (w, h) == STD[S]}
    benches = [dict(name='lint', cmd=(f"mkdir -p {{RUN}} && printf '%s\\n' 'module ot_lint_top; {name} u_top (); endmodule' > "
                                      f"{{RUN}}/ot_lint_top.sv && verilator --lint-only -Wno-fatal -Wno-lint -Wno-style "
                                      f"-Wno-TIMESCALEMOD -Wno-MULTIDRIVEN -Wno-MODMISSING -DSYNTHESIS --top-module ot_lint_top "
                                      f"{{RUN}}/ot_lint_top.sv {' '.join(LANE_RTL)} && echo lint-ok"),
                    expect='pass', threads=1, peak_ram_gb=4, needs=['verilator']),
               dict(name='fwd_lane_exact', cmd=f'bash tools/qwen_kv_die/bench_kv_fwd_lane.sh pass {{RUN}}/bench_p {S}',
                    expect='pass', pass_regex='FWD_BENCH PASS 0 errors in [0-9]+ checks', threads=2, peak_ram_gb=4,
                    needs=['verilator'])]
    for mu in MUTANTS[fam]:
        benches.append(dict(name=f'{mu}_mutant', cmd=f'bash tools/qwen_kv_die/bench_kv_fwd_lane.sh {mu} {{RUN}}/bench_{mu} {S}',
                            expect='fail', fail_regex='FWD_BENCH FAIL', fail_witness=f'{WIT}/w{S}_{mu}.log',
                            threads=2, peak_ram_gb=4, needs=['verilator']))
    return dict(
        name=name, top=name, kind='tile', sources=LANE_RTL, params={}, clock_port=CLOCK[fam],
        reset_ports=['rs'] if land else [],
        outline=dict(w=w, h=h, exact=True), layer_cap='M5',
        pins=pins, pin_ranges=rng, macros=[], children=[], inter=['*'],
        refglob='*u_land.rc*' if land else '*', io_budget={'in': 0.2, 'out': 0.2},
        recipe=4, hold_budget='die', inhold=False, outhold=False, io_flop_at_pins={'cols': 4, 'allow_none': True},
        keep_pin_regs=True, forwarded_clock=not land,
        pin_regs=dict(enable=False, reason='OWNER RULE 19:50 opt-out (as the coordinator-approved S81 relays): a lane frame is '
                      'one flip-flop per bit between its pins (station) or the ring + its registered output (landing); a '
                      'flow pin register would add a stage the die calendar does not price'),
        sdc_extra=[CLK_TCL], boundary_tcl=[CLK_TCL],
        route=dict(pd=0.45, threads=2, peak_ram_gb=6, pin_h='M4', pin_v='M3 M5', m5_pg_pitch=2.7, pin_min_tracks=3,
                   hold_margin_ns=0.03, io_hold_margin_ns=0.0, macro_halo_um=5.4),
        structural_change=(f'KV-CLOCK/LANEKITS 10-18 (landed-regions standard, LANDING-CONTRACT): {S}-b forwarded-clock lane '
                           f'frame {name} ({w} x {h}): {KIND[fam]} (rtl/qwen_split/qfd_fwd_lane.sv via {RTL}); replaces the qkd_rlys_{S} '
                           'replica of the same frame on KV die relay chains that cross clock regions. Recipe 4 flop-first, '
                           'hold_budget die, M5 cap.'),
        job=dict(owner=a.owner, branch=a.branch, tag=a.tag,
                 purpose=f'Qwen KV die forwarded half-cycle lane frame {name} ({KIND[fam]}, {S} b, qkd_rlys_{S} outline)',
                 benches=benches, views_to=f'physical/ref_tile/{name}/views', record_to=f'results/rtl/ref_tile/{name}',
                 extra_paths=['physical/qwen_kv_fwd_lane', 'rtl/qwen_split/qfd_fwd_lane.sv', 'rtl/hdc',
                              'rtl/qwen_sys/kv_fwd_lane_20261018', 'tools/qwen_kv_die/bench_kv_fwd_lane.sh',
                              'tools/qwen_split/bench_fwd_lane.sh', WIT]))


def specs(a):
    out = ROOT / 'tools/ref_tile/specs_kvfwd'
    out.mkdir(parents=True, exist_ok=True)
    for fam in FWD:
        for S in STD:
            s = spec(fam, S, a)
            (out / f"{s['name']}.json").write_text(json.dumps(s, indent=1) + '\n')
            print(s['name'], s['outline'], s['pins'])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('what', choices=('rtl', 'specs'))
    ap.add_argument('--owner', default='Claude:KV-CLOCK/LANEKITS')
    ap.add_argument('--branch', default='claude/kv-lanekits-1018')
    ap.add_argument('--tag', default='f1')
    a = ap.parse_args()
    rtl() if a.what == 'rtl' else specs(a)


if __name__ == '__main__':
    main()
