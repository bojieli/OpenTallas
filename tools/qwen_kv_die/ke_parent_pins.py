#!/usr/bin/env python3
"""q13-kvleaves 2026-10-13: pin plan (ref_tile "io_tcl") of the thin-cluster KV end (kit qkd_d2d_p2_ref, top
ot_qkvd_kv_end SPL=1).  Every S / N port is wired to ONE pin of a face tile (the W ports reach the cluster's own ten flops), so each cluster pin
sits on the SAME track as its child pin, straight below / above / beside it (S and N: M5, W: M4): the port wire is the
~22-um stub between the die edge and the tile, and the tile's pin flop is the port's register.

Reads the kit's spec (child origins) and the child views' LEFs.  clk enters on W, mid-height.

    python3 tools/qwen_kv_die/ke_parent_pins.py        (re)writes physical/ref_tile_specs/qkd_ke/qkd_d2d_p2_pins.tcl
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "tools/ref_tile/specs/qkd_d2d_p2_ref.json"
OUT = ROOT / "physical/ref_tile_specs/qkd_ke/qkd_d2d_p2_pins.tcl"
W_UM, H_UM = 777.6, 518.4


def lef_pins(view):
    name = Path(view).name
    t = (ROOT / view / f"{name}.lef").read_text()
    out = {}
    for m in re.finditer(r"PIN (\S+)\n(.*?)\n  END ", t, re.S):
        r = re.search(r"LAYER (\S+) ;\s*RECT\s+(\S+) (\S+) (\S+) (\S+)", m.group(2))
        if r:
            out[m.group(1)] = (r.group(1), (float(r.group(2)) + float(r.group(4))) / 2, (float(r.group(3)) + float(r.group(5))) / 2)
    return out


def main():
    s = json.loads(SPEC.read_text())
    at = {c["inst"].lstrip("*"): (c["view"], c["at"][0], c["at"][1]) for c in s["children"]}
    lines = ["# GENERATED by tools/qwen_kv_die/ke_parent_pins.py (qkd_d2d_p2_ref, 777.6 x 518.4): do not edit by hand",
             "# every cluster pin on the track of the face-tile pin it is wired to"]
    n = 0

    def put(port, inst, cpin, face):
        nonlocal n
        view, x0, y0 = at[inst]
        lay, x, y = lef_pins(view)[cpin]
        if face in "SN":
            assert lay == "M5", (inst, cpin, lay)
            loc, size = f"{x0 + x:.3f} {0.0 if face == 'S' else H_UM:.3f}", "{0.024 0.192}"
        else:
            assert lay == "M4", (inst, cpin, lay)
            loc, size = f"0.000 {y0 + y:.3f}", "{0.192 0.024}"
        lines.append(f"place_pin -pin_name {{{port}}} -layer {lay} -location {{{loc}}} -pin_size {size} -force_to_die_boundary")
        n += 1

    for i in range(3):                                   # die TX face lanes (S)
        put(f"t_v[{i}]", f"u_ti{i}", "t_v", "S")
        put(f"t_cr[{i}]", f"u_ti{i}", "t_cr", "S")
        for b in range(528):
            put(f"t_d[{528 * i + b}]", f"u_ti{i}", f"t_d[{b}]", "S")
    for j in range(4):                                   # die RX face lanes (S)
        put(f"r_v[{j}]", f"u_ro{j}", "r_v", "S")
        put(f"r_cr[{j}]", f"u_ro{j}", "r_cr", "S")
        for b in range(528):
            put(f"r_d[{528 * j + b}]", f"u_ro{j}", f"r_d[{b}]", "S")
    put("tx_up", "u_tf", "tx_up", "N")                    # FDI (N)
    put("tx_v", "u_tf", "tx_v", "N")
    for b in range(548):
        put(f"tx_flit[{b}]", "u_tf", f"tx_flit[{b}]", "N")
        put(f"rx_flit[{b}]", "u_rq", f"rx_flit[{b}]", "N")
    put("rx_v", "u_rq", "rx_v", "N")
    # W face: the cluster's own ten flops (reset synchroniser + fault face flops) sit behind these pins; M4 tracks
    # (0.012 + k x 0.048), 0.96 um apart, next to the clock pin
    for k, port in enumerate(["rst_n", "fault"] + [f"fault_cause[{b}]" for b in range(5)]):
        lines.append(f"place_pin -pin_name {{{port}}} -layer M4 -location {{0.000 {260.172 + 0.96 * k:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary")
        n += 1
    lines.append("place_pin -pin_name {clk} -layer M4 -location {0.000 259.212} -pin_size {0.192 0.024} -force_to_die_boundary")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, n + 1, "pins")


if __name__ == "__main__":
    main()
