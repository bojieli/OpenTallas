#!/usr/bin/env python3
"""RTL-BUILD-KV/ASTK 2026-10-18: generate the static-die heads WITHOUT the node beat (nb_d) -- ot_qkh_head_native_r4_s and
ot_qkh_head_native_r4_ft_s -- from ot_qkh_head_native_r4 / _ft (exact text otherwise: same leaf cells and cell names).

On the static timeline the ECTL finishes at its K pass (STATIC_QK: no V phase, P.V in the pvw pairs), so the decision word
lt is 0 and the lanes' node slices are never written; the static ASTK strip (qkd_astk_strip_st / _er_st) has no nb input.
Removed: the output nb_d (1,024 b), its two relay stages a lane (u_nb1 / u_nb2: 32 ot_qkh_head_nb_native children) and their
clock entries ck_nb1 / ck_nb2 (32).  ot_qkh_lane8's nb output stays a child-internal net with no load (the lane8 leaf is the
closed master; its local P.V tree executes lt = 0 and is a no-op on this timeline).

    python3 tools/qwen_kv_die/head_st_rtl.py [--check]

KV-DCAL2 10-19 (K.STA.ECTL KPV_LOCKSTEP; ROOT: no blanket lockstep admission): the same run also writes
ot_qkh_head_native_r4_s_lk.sv (modules ot_qkh_head_native_r4_s_lk / _r4_ft_s_lk) = the _s heads with u_kt bound to
ot_qkh_ktree_lk, which reads every lane's kpv (lane mismatch -> lane fault into the existing gf_r -> g_f path, +0 cycles).
Selected by the die generator with OT_KV_KPV_LK=1 once the ot_qkh_ktree_lk kit is CLOSED.

KV-KT-E0 11-18 (FABLE-FIX-KV-HG fix #2, KV event D25): the same run also writes ot_qkh_head_native_r4_kst.sv = every head
above (+ the node-beat head ot_qkh_head_native_r4 itself) as a <name>_kst module with the kt input stations: parameter
KT_ST (0, 1, 2; default 0 = the head it is generated from, cell for cell) puts KT_ST register stages on EVERY lane between
u_stk and u_kt, as two named leaves a lane (g_t[t].u_kst0, g_t[t].u_kst1: ot_qkh_head_kst_native, D 1 or 0).  The score
(sc_d / sc_f / g_f) leaves KT_ST edges later: the control tile's HXK and the attention calendar D_QK take them
(tools/qwen_kv_die/kv_head_kst.py).  KT_MUT 1 (bench only) leaves lanes 0, 1 without stations (the 14-lane parent-only form).
The existing heads are not touched (their text and every pinned sha256 stay).
"""
import argparse, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
D = ROOT / 'rtl/qwen_sys/split_20261014'
OUT = D / 'ot_qkh_head_native_r4_s.sv'
OUT_LK = D / 'ot_qkh_head_native_r4_s_lk.sv'
KT_OLD = '  ot_qkh_ktree u_kt (.clk(ck_kt),.rst_n(kt_rst_n),.kp_in(kp_k),.kpv_in(kpv_k[0]),.gf_in(gf_k),'
KT_LK = '  ot_qkh_ktree_lk u_kt (.clk(ck_kt),.rst_n(kt_rst_n),.kp_in(kp_k),.kpv_in(kpv_k),.gf_in(gf_k),'
OUT_KST = D / 'ot_qkh_head_native_r4_kst.sv'
KST_PAR = '  parameter integer Q_FP32=1,parameter integer MUT=0\n)('
KST_WIRE = '  wire [511:0] kp_t,kp_k;wire [15:0] kpv_t,kpv_k,gf_t,gf_k;\n'
KST_STK = '       .kp_o(kp_k[32*t +:32]),.kpv_o(kpv_k[t]),.gf_o(gf_k[t]));\n'
KST_NEW = ("       .kp_o(kp_s[32*t +:32]),.kpv_o(kpv_s[t]),.gf_o(gf_s[t]));\n"
           "    // kt input stations: KT_ST stages on every lane, one named leaf a stage (u_kst0 by the stk, u_kst1 by the K-tree)\n"
           "    localparam integer KT_L=(KT_MUT==1 && t<2) ? 0 : KT_ST;\n"
           "    wire [31:0] kp_m;wire kpv_m,gf_m;\n"
           "    ot_qkh_head_kst_native #(.D(KT_L>=1 ? 1 : 0)) u_kst0\n"
           "      (.clk(ck_stk[t]),.kp_i(kp_s[32*t +:32]),.kpv_i(kpv_s[t]),.gf_i(gf_s[t]),.kp_o(kp_m),.kpv_o(kpv_m),.gf_o(gf_m));\n"
           "    ot_qkh_head_kst_native #(.D(KT_L>=2 ? 1 : 0)) u_kst1\n"
           "      (.clk(ck_kt),.kp_i(kp_m),.kpv_i(kpv_m),.gf_i(gf_m),.kp_o(kp_k[32*t +:32]),.kpv_o(kpv_k[t]),.gf_o(gf_k[t]));\n")
NB = re.compile(r'\n    wire \[63:0\] nb_mid;\n    ot_qkh_head_nb_native #\(\.MUT\(MUT\)\) u_nb1\n.*?\.nb_o\(nb_d\[64\*t \+:64\]\)\);', re.S)


def one(src, name, new):
    t = (D / src).read_text()
    m = re.search(rf'^module {name} #\(.*?^endmodule\s*$', t, re.M | re.S)
    if not m:
        raise SystemExit(f'{name} not found in {src}')
    b = m.group(0)
    for old, rep in ((f'module {name} #(', f'module {new} #('),
                     ('input wire [15:0] ck_stin,ck_stk,ck_nb1,ck_nb2,ck_lane,', 'input wire [15:0] ck_stin,ck_stk,ck_lane,'),
                     ('output wire [31:0] sc_d,output wire sc_f,g_f,output wire [1023:0] nb_d', 'output wire [31:0] sc_d,output wire sc_f,g_f')):
        assert b.count(old) == 1, f'{name}: {old!r} changed: regenerate by hand'
        b = b.replace(old, rep)
    b, n = NB.subn('', b)
    assert n == 1 and 'nb_d' not in b and 'ck_nb' not in b, f'{name}: nb relay block changed'
    return b


def generate():
    return ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/head_st_rtl.py from ot_qkh_head_native_r4 / _r4_ft (do not edit; regenerate).\n'
            '// Static-die heads without the node beat: no nb_d, no u_nb1 / u_nb2 relays, no ck_nb1 / ck_nb2 (see the generator).\n'
            + one('ot_qkh_head_native_r4.sv', 'ot_qkh_head_native_r4', 'ot_qkh_head_native_r4_s') + '\n\n'
            + one('ot_qkh_head_native_r4_ft.sv', 'ot_qkh_head_native_r4_ft', 'ot_qkh_head_native_r4_ft_s') + '\n')


def generate_lk(txt=None):
    txt = generate() if txt is None else txt
    assert txt.count(KT_OLD) == 2, 'u_kt instance text changed: regenerate the _lk heads by hand'
    lk = txt.replace(KT_OLD, KT_LK)
    for m in ('ot_qkh_head_native_r4_s', 'ot_qkh_head_native_r4_ft_s'):
        assert lk.count(f'module {m} #(') == 1
        lk = lk.replace(f'module {m} #(', f'module {m}_lk #(')
    return lk.replace('// GENERATED by tools/qwen_kv_die/head_st_rtl.py from',
                      '// GENERATED by tools/qwen_kv_die/head_st_rtl.py (KPV lockstep _lk: u_kt = ot_qkh_ktree_lk) from', 1)


def kst_one(b, name):
    """one head module text -> its <name>_kst twin with the KT_ST stations (every edit must hit exactly once)"""
    for o, r in ((f'module {name} #(', f'module {name}_kst #('),
                 (KST_PAR, '  parameter integer Q_FP32=1,parameter integer MUT=0,\n'
                           '  parameter integer KT_ST=0,parameter integer KT_MUT=0\n)('),
                 (KST_WIRE, KST_WIRE + '  wire [511:0] kp_s;wire [15:0] kpv_s,gf_s;\n'
                            '  generate if(KT_ST<0 || KT_ST>2) begin:g_kt_bad ot_qkh_head_kst__KT_ST_is_0_1_2 u_bad(); end endgenerate\n'),
                 (KST_STK, KST_NEW)):
        assert b.count(o) == 1, f'{name}: {o!r} changed: regenerate the _kst heads by hand'
        b = b.replace(o, r)
    return b


def generate_kst(txt=None, lk=None):
    txt = generate() if txt is None else txt
    lk = generate_lk(txt) if lk is None else lk
    mods = [(one_raw('ot_qkh_head_native_r4.sv', 'ot_qkh_head_native_r4'), 'ot_qkh_head_native_r4')]
    for t, names in ((txt, ('ot_qkh_head_native_r4_s', 'ot_qkh_head_native_r4_ft_s')),
                     (lk, ('ot_qkh_head_native_r4_s_lk', 'ot_qkh_head_native_r4_ft_s_lk'))):
        for n in names:
            m = re.search(rf'^module {n} #\(.*?^endmodule\s*$', t, re.M | re.S)
            assert m, n
            mods.append((m.group(0).rstrip('\n'), n))
    return ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/head_st_rtl.py (kt input stations, parameter KT_ST) from ot_qkh_head_native_r4 '
            'and the _s / _s_lk heads (do not edit; regenerate).\n'
            '// KT_ST 0 = the source head cell for cell; KT_ST 1 / 2 = that many ot_qkh_head_kst_native stages on every lane '
            'between u_stk and u_kt (score +KT_ST edges).\n'
            + '\n\n'.join(kst_one(b, n) for b, n in mods) + '\n')


def one_raw(src, name):
    t = (D / src).read_text()
    m = re.search(rf'^module {name} #\(.*?^endmodule\s*$', t, re.M | re.S)
    if not m:
        raise SystemExit(f'{name} not found in {src}')
    return m.group(0).rstrip('\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    txt = generate()
    lk = generate_lk(txt)
    kst = generate_kst(txt, lk)
    if a.check:
        sys.exit(0 if OUT.exists() and OUT.read_text() == txt and OUT_LK.exists() and OUT_LK.read_text() == lk
                 and OUT_KST.exists() and OUT_KST.read_text() == kst else 1)
    OUT.write_text(txt)
    OUT_LK.write_text(lk)
    OUT_KST.write_text(kst)
    print(OUT)
    print(OUT_LK)
    print(OUT_KST)
