"""KV-PC 10-19 (OT_KV_PC_RLAND=1): the PC kit tiles land rst_n on ck and hrst_n on hck in 2 registered stages before any
child reset pin.  pc_rland_text is a pure rewrite of module_text output; the committed _ds_rl tile file equals the
rewrite of the committed _ds file (both generated by kv_static_die.rtl_text at the same design point)."""
import re
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import kv_static_die as KSD  # noqa: E402

TOY = """// qkd_kvs_pc: GENERATED by tools/qwen_kv_die/kv_static_die.py (wires-only parent of the static join; do not edit)
module qkd_kvs_pc (
    input wire ck,
    input wire hck,
    input wire rst_n,
    input wire hrst_n,
    input wire [3:0] i_x,
    output wire [3:0] o_x
);
    wire [3:0] w_a__q;
    child_a u_a (.ck(ck), .rst_n(rst_n), .d(i_x), .q(w_a__q));
    child_b u_b (.hck(hck), .hrst(hrst_n), .cal_rst_n(hrst_n), .ck(ck), .rsi(rst_n));
    assign o_x = w_a__q;
endmodule
"""


def test_rewrite_lands_every_reset_pin():
    t = KSD.pc_rland_text(TOY)
    assert 'u_rland_ck (.clk(ck), .async_rst_n(rst_n), .sync_rst_n(w_rland__rst_n))' in t
    assert 'u_rland_hck (.clk(hck), .async_rst_n(hrst_n), .sync_rst_n(w_rland__hrst_n))' in t
    body = t.split('u_rland_hck', 1)[1]
    assert not re.search(r'(?<![.\w])h?rst_n\b', re.sub(r'w_rland__h?rst_n', '', body.split('\n', 1)[1]))
    assert body.count('(w_rland__hrst_n)') == 3 and body.count('(w_rland__rst_n)') == 2


def test_mutant_reset_in_expression_refused():
    bad = TOY.replace('.rsi(rst_n)', '.rsi(rst_n & i_x[0])')
    with pytest.raises(ValueError, match='outside a plain child pin'):
        KSD.pc_rland_text(bad)


def test_mutant_double_landing_refused():
    with pytest.raises(ValueError, match='already landed'):
        KSD.pc_rland_text(KSD.pc_rland_text(TOY))


def test_mutant_missing_hck_refused():
    with pytest.raises(ValueError, match='no scalar input hck'):
        KSD.pc_rland_text(TOY.replace('    input wire hck,\n', ''))


def test_committed_rl_file_is_the_rewrite_of_ds():
    d = ROOT / 'rtl/qwen_sys/static_kv_die_20261017'
    ds, rl = d / 'qkd_kvs_tiles_hroot_ff_k_mu_ds.sv', d / 'qkd_kvs_tiles_hroot_ff_k_mu_ds_rl.sv'
    if not (ds.exists() and rl.exists()):
        pytest.skip('tile files not checked out')
    t = ds.read_text()
    for m in ('qkd_kvs_pc', 'qkd_kvs_pc_h'):
        a = re.search(rf'^module {m} \(', t, re.M).start()
        a = t.rfind('\n', 0, a - 1) + 1
        b = t.index('endmodule\n', a) + len('endmodule\n')
        t = t[:a] + KSD.pc_rland_text(t[a:b]) + t[b:]
    assert t == rl.read_text()
