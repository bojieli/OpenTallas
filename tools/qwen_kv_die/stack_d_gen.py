#!/usr/bin/env python3
"""kv-die 2026-10-09 (review-0528 KV1(b), CRITICAL PATH): generate rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_d.sv, the
near-HBM stack RE-CUT D at the row engine <-> stack aggregator boundary, from the timing successor
rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_p.sv (every module suffixed _d; the _p file is untouched).

Why D and not C.  Re-cut C (stack_c_gen.py) kept the tree at the aggregator and serialised every P.V leaf (16,384 b) over
the boundary in LFB beats.  The tree takes a stack's 128 leaves in residue order (engine 0's 8 slots, then engine 1's,
...), so an engine's leaves wait for the other engines' and its slots stay blocked: measured +735 cycles a layer (LFB 4,
LBD 4) to +1,239 (LFB 4, LBD 2) -- rejected (run8, results/arch/qwen_kv_die_20261009/recut.json).

Re-cut D moves the P.V tree's levels 1-3 into the engine.  Residue group gam (residues 8 gam .. 8 gam + 7) is one
engine's slots 0..7, so the pairwise tree's levels 1-3 never mix engines: node (level 3, gam) = the group's 8 leaves
summed in the golden pairwise order.  The leaf count is always 8 gmax, so levels 1-3 are always complete and the
aggregator's flush sees exactly the pending set it saw before.  Same arithmetic, same order:
  engine     a local streaming pairwise tree (levels 1-3, one LN-wide adder bank beside the lanes): leaves are taken
             in slot order straight from the loop (fb) at their offer turn, as the stack's tree took them; a leaf that
             would collide with a completing pair waits in the loop (offered again 8 cycles later), as before.
             The level-3 node is registered and sent to the aggregator in LFB beats {beat, g, gam, data}
             (16,384 / LFB data bits) under a credit (ND nodes staged at the aggregator).  A new group starts only
             when the previous node has left the local tree.
  q          as re-cut C: the engine holds its own q registers, written from the aggregator's registered 519-bit
             q beat broadcast.
  aggregator an ND-node staging FIFO per engine; the P.V tree keeps levels 4-7 (NL = 4) over the 16 group nodes in
             residue-group order (group gam is engine gam mod R's), with the same streaming / flush / root logic.
Engine boundary: q 519 b in, nodes 16,384 / LFB + 7 b out (16,385 + 16,392 before).
Every added register is priced by the bench (cycles per layer), not assumed.

    python3 tools/qwen_kv_die/stack_d_gen.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_p.sv'
DST = ROOT / 'rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_d.sv'


def rep(s, a, b, n=1):
    if a not in s:
        raise SystemExit(f'stack_d_gen: anchor not found: {a[:80]!r}')
    return s.replace(a, b, n)


def generate():
    s = SRC.read_text()
    head = ('`timescale 1ns/1ps\n'
            '// ---------------------------------------------------------------------------------------------------------------------\n'
            '// GENERATED by tools/qwen_kv_die/stack_d_gen.py from rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_p.sv (do not edit by\n'
            '// hand).  RE-CUT D of the near-HBM stack at the row engine <-> aggregator boundary (kv-die 2026-10-09, review-0528\n'
            '// KV1(b)): P.V levels 1-3 inside each engine (its residue group of 8 slots), level-3 nodes sent to the aggregator in\n'
            '// LFB beats under ND credits; the aggregator tree keeps levels 4-7.  q held in each engine (519-bit beat broadcast).\n'
            '// Same arithmetic, same order.  NEW, DEFAULT-OFF: only the KV-die elements (qkd_reng / qkd_astk) and benches use it.\n'
            '// ---------------------------------------------------------------------------------------------------------------------\n')
    s = s.split('\n', 1)[1]
    mods = re.findall(r'(?m)^module\s+(\w+)_p\b', s)
    s = re.sub(r'\b(' + '|'.join(map(re.escape, mods)) + r')_p\b', r'\1_d', s)
    # ================= row engine =================
    s = rep(s, """    input  wire                 q_ready,      // q registers loaded
    input  wire [8*HD*16-1:0]   q_bf16,       // q[h][d] at [(h*HD+d)*16 +: 16]
""", """    input  wire                 q_valid_in,   // re-cut: the aggregator's registered q beat broadcast
    input  wire [5:0]           q_beat_in,
    input  wire [511:0]         q_data_in,
""")
    s = rep(s, """    output wire                 lf_valid,
    output wire                 lf_g,
    output wire [3:0]           lf_gam,
    output wire [2:0]           lf_slot,
    output wire [4*HD*32-1:0]   lf_data,
    input  wire                 lf_take,
""", """    output reg                  nb_valid,     // re-cut D: a level-3 node beat {beat, g, gam, data} to the staging FIFO
    output reg  [3:0]           nb_beat,
    output reg                  nb_g,
    output reg  [3:0]           nb_gam,
    output reg  [4*HD*32/LFB-1:0] nb_data,
    input  wire                 nb_cr,        // one staging credit returned (the aggregator tree took a node)
""")
    s = rep(s, """    parameter integer DQ = 32,           // row / e FIFO depth = outstanding-request credit
    parameter [31:0]  SCALE = 32'h3DB504F3
) (
    input  wire                 clk,
    input  wire                 rst_n,
    input  wire                 start_in,""", """    parameter integer DQ = 32,           // row / e FIFO depth = outstanding-request credit
    parameter [31:0]  SCALE = 32'h3DB504F3,
    parameter integer LFB = 4,           // re-cut D: node beats
    parameter integer ND = 1             // re-cut D: staged nodes a engine at the aggregator (= the engine's credits)
) (
    input  wire                 clk,
    input  wire                 rst_n,
    input  wire                 start_in,""")
    s = rep(s, """    always @(posedge clk) begin T <= T_in; cyc8_r <= cyc8_in; rsp_data <= rsp_data_in; end
""", """    always @(posedge clk) begin T <= T_in; cyc8_r <= cyc8_in; rsp_data <= rsp_data_in; end
    // re-cut: this engine's q registers, written from the registered beat broadcast (q_ready = all 32 beats in)
    localparam integer NQB = 8 * HD * 16 / 512;
    reg               qv_r;
    reg  [5:0]        qb_r;
    reg  [511:0]      qd_r;
    reg  [8*HD*16-1:0] q_bf16;
    reg  [6:0]        qcnt;
    always @(posedge clk or negedge rst_n) if (!rst_n) qv_r <= 1'b0; else qv_r <= q_valid_in;
    always @(posedge clk) begin qb_r <= q_beat_in; qd_r <= q_data_in; if (qv_r) q_bf16[512*qb_r +: 512] <= qd_r; end
    always @(posedge clk or negedge rst_n)
        if (!rst_n) qcnt <= 7'd0;
        else if (start) qcnt <= 7'd0;
        else if (qv_r) qcnt <= qcnt + 7'd1;
    wire q_ready = (qcnt == NQB);
""")
    # the take now comes from the engine's own tree (declared before the consumption logic uses it)
    s = rep(s, """    wire        take = offer && lf_take;
""", """    wire        take;                                   // re-cut D: the local tree takes the leaf (below)
""")
    s = rep(s, """    assign lf_valid = offer;
    assign lf_g = pend_g[os];
    assign lf_gam = pend_gam[os];
    assign lf_slot = os;
    assign lf_data = fb;
""", """    // ---- re-cut D: the P.V tree's levels 1-3 over this engine's residue group (slots 0..7 in order) -------------------
    // Leaves are taken in slot order (lt_rho) at their offer turn, straight from the loop.  The streaming pairwise tree:
    // a pending left node per level; an arriving result that completes a pair always issues, a leaf with a pending
    // left node waits in its loop when it would collide.  The level-3 arrival is the group's node.  A group's first
    // leaf is taken only when the previous node has left the tree and the output register.
    localparam integer NLL = 3;
    reg  [2:0]       lt_rho;
    reg  [LN*32-1:0] LP [0:NLL-1];
    reg  [NLL-1:0]   LPv;
    reg  [3:0]       lt_infl;
    reg              lt_g;
    reg  [3:0]       lt_gam;
    reg              lt_fault;
    wire [2:0]       lt_tag;                            // {valid, level issued}
    wire [LN*32-1:0] lt_y;
    wire [LN-1:0]    lt_yvo, lt_yerr;
    wire             lt_arr_v = lt_tag[2];
    wire [1:0]       lt_arr_l = lt_tag[1:0] + 2'd1;
    wire             lt_arr_issue = lt_arr_v && (lt_arr_l < NLL) && LPv[lt_arr_l];
    reg  [LN*32-1:0] ob;                                // the node being sent
    reg              ob_busy;
    reg              ob_g;
    reg  [3:0]       ob_gam;
    reg  [3:0]       ob_b;
    reg  [$clog2(ND+1)-1:0] ocred;
    reg              ocr_q;
    wire             lt_room = (lt_rho != 3'd0) || (!ob_busy && (LPv == 0) && (lt_infl == 0) && !lt_arr_v);
    assign take = offer && (os == lt_rho) && lt_room && (!LPv[0] || !lt_arr_issue);
    wire             lt_leaf_issue = take && LPv[0];
    wire             lt_issue = lt_arr_issue || lt_leaf_issue;
    wire [LN*32-1:0] lt_a = lt_arr_issue ? LP[lt_arr_l] : LP[0];
    wire [LN*32-1:0] lt_b = lt_arr_issue ? lt_y : fb;
    wire [1:0]       lt_l = lt_arr_issue ? lt_arr_l : 2'd0;
    ot_hdc_delay #(.W(3), .D(ADD_LAT), .RESET(1)) u_lttag (.clk(clk), .rst_n(rc), .d({lt_issue, lt_l}), .q(lt_tag));
    generate for (h = 0; h < LN; h = h + 1) begin : g_ltb
        wire [1:0] err;
        ot_hdc_fp32_add_lat #(.LAT(ADD_LAT)) u_add (
            .clk(clk), .rst_n(rc), .valid_in(lt_issue), .a(lt_a[32*h +: 32]), .b(lt_b[32*h +: 32]),
            .y(lt_y[32*h +: 32]), .err(err), .valid_out(lt_yvo[h]));
        assign lt_yerr[h] = lt_yvo[h] && (err != 2'd0);
    end endgenerate
    wire ob_send = ob_busy && ((ob_b != 4'd0) || (ocred != 0));
    always @(posedge clk or negedge rc) begin
        if (!rc) begin
            lt_rho <= 3'd0; LPv <= 0; lt_infl <= 0; lt_fault <= 1'b0; ob_busy <= 1'b0; ob_b <= 4'd0; ocred <= ND;
            ocr_q <= 1'b0; nb_valid <= 1'b0;
        end else begin
            ocr_q <= nb_cr;
            nb_valid <= 1'b0;
            lt_infl <= lt_infl + (lt_issue ? 4'd1 : 4'd0) - (lt_arr_v ? 4'd1 : 4'd0);
            if (|lt_yerr) lt_fault <= 1'b1;
            if (start) lt_rho <= 3'd0;
            // arriving results
            if (lt_arr_v) begin
                if (lt_arr_l == NLL) begin
                    ob <= lt_y; ob_busy <= 1'b1; ob_b <= 4'd0; ob_g <= lt_g; ob_gam <= lt_gam;
                    if (ob_busy) lt_fault <= 1'b1;                       // cannot happen: lt_room
                end else if (LPv[lt_arr_l]) LPv[lt_arr_l] <= 1'b0;
                else begin LP[lt_arr_l] <= lt_y; LPv[lt_arr_l] <= 1'b1; end
            end
            // leaves
            if (take) begin
                if (LPv[0]) LPv[0] <= 1'b0;
                else begin LP[0] <= fb; LPv[0] <= 1'b1; end
                lt_rho <= lt_rho + 3'd1;
                if (lt_rho == 3'd0) begin lt_g <= pend_g[os]; lt_gam <= pend_gam[os]; end
                else if ((pend_g[os] != lt_g) || (pend_gam[os] != lt_gam)) lt_fault <= 1'b1;
            end
            // node beats
            if (ob_send) begin
                nb_valid <= 1'b1; nb_beat <= ob_b; nb_g <= ob_g; nb_gam <= ob_gam;
                nb_data <= ob[(LN*32/LFB)*ob_b +: LN*32/LFB];
                if (ob_b == 4'(LFB - 1)) begin ob_busy <= 1'b0; ob_b <= 4'd0; end
                else ob_b <= ob_b + 4'd1;
            end
            ocred <= ocred - ((ob_send && ob_b == 4'd0) ? 1'b1 : 1'b0) + (ocr_q ? 1'b1 : 1'b0);
        end
    end
""")
    # the engine fault includes the local tree's
    s = rep(s, """                if ((|tf) || (|tree_fault) || mac_fault) fault <= 1'b1;""",
            """                if ((|tf) || (|tree_fault) || mac_fault || lt_fault) fault <= 1'b1;""")
    # ================= P.V tree: levels 4-7 over the group nodes =================
    i = s.index('module ot_qwen_nearhbm_pvtree_d #(')
    j = s.index('endmodule', i)
    t = s[i:j]
    t = rep(t, """    parameter integer ADD_LAT = 7
) (""", """    parameter integer ADD_LAT = 7
) (   // re-cut D: the leaves are the engines' level-3 group nodes (group gam from engine gam mod R)""")
    t = rep(t, """    input  wire [3*R-1:0]    lf_slot,
""", "")
    t = rep(t, """    localparam integer NL = 7;                         // levels: 128 residues""",
            """    localparam integer NL = 4;                         // re-cut D: levels 4-7 over 16 group nodes""")
    t = rep(t, """    wire [7:0]  nlv = {gmax, 3'b000};""", """    wire [7:0]  nlv = {3'b000, gmax};                  // re-cut D: one node a nonempty group""")
    t = rep(t, """(rho < nlv) && (lf_slot[3*ep +: 3] == rho[2:0]) && lf_valid[ep] &&
                              (lf_g[ep] == tg) && (lf_gam[4*ep +: 4] == rho[6:3]);""",
            """(rho < nlv) && lf_valid[ep] &&
                              (lf_g[ep] == tg) && (lf_gam[4*ep +: 4] == rho[3:0]);""")
    t = rep(t, """                    if (rho[2:0] == 3'd7) ep <= (ep == R - 1) ? 0 : ep + 1;""",
            """                    ep <= (ep == R - 1) ? 0 : ep + 1;""")
    s = s[:i] + t + s[j:]
    # ================= stack =================
    i = s.index('module ot_qwen_nearhbm_attn_stack_d #(')
    j = s.index('    parameter integer ZW = 4,\n', i)
    s = s[:j] + ('    parameter integer ZW = 4,\n    parameter integer LFB = 4,           // re-cut D: node beats\n'
                 '    parameter integer ND = 1,            // re-cut D: staged nodes a engine\n') + s[j + len('    parameter integer ZW = 4,\n'):]
    s = rep(s, """    // q registers
    reg [8*HD*16-1:0] qr;
    reg [6:0] qcnt;
    wire q_ready = (qcnt == NQB);
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) qcnt <= 0;
        else if (start) qcnt <= 0;
        else if (q_valid) qcnt <= qcnt + 7'd1;
    end
    always @(posedge clk) if (q_valid) qr[512*q_beat +: 512] <= q_data;
""", """    // re-cut: no stack q registers; the q beats are registered once and broadcast to the engines (q_ready: the bench
    // marker only -- every engine counts its own beats)
    reg [6:0] qcnt;
    wire q_ready = (qcnt == NQB);
    reg        qv_b;
    reg [5:0]  qb_b;
    reg [511:0] qd_b;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin qcnt <= 0; qv_b <= 1'b0; end
        else begin
            qv_b <= q_valid;
            if (start) qcnt <= 0;
            else if (q_valid) qcnt <= qcnt + 7'd1;
        end
    end
    always @(posedge clk) begin qb_b <= q_beat; qd_b <= q_data; end
""")
    s = rep(s, """    wire [3*R-1:0] lf_slot;
    wire [LN*32*R-1:0] lf_data;
    reg  [31:0] exp_done;""", """    wire [LN*32*R-1:0] lf_data;
    wire [R-1:0] nb_valid, nb_g;
    wire [4*R-1:0] nb_beat, nb_gam;
    wire [LN*32/LFB*R-1:0] nb_data;
    reg  [R-1:0] nb_cr;
    reg  [31:0] exp_done;""")
    s = rep(s, """                                     .MUL_LAT(MUL_LAT), .DQ(DQ), .SCALE(SCALE)) u_eng (
            .clk(clk), .rst_n(rst_n), .start_in(start), .T_in(T), .cyc8_in(cyc8), .q_ready(q_ready), .q_bf16(qr),""",
            """                                     .MUL_LAT(MUL_LAT), .DQ(DQ), .SCALE(SCALE), .LFB(LFB), .ND(ND)) u_eng (
            .clk(clk), .rst_n(rst_n), .start_in(start), .T_in(T), .cyc8_in(cyc8), .q_valid_in(qv_b), .q_beat_in(qb_b),
            .q_data_in(qd_b),""")
    s = rep(s, """            .lf_valid(lf_valid[e]), .lf_g(lf_g[e]), .lf_gam(lf_gam[4*e +: 4]), .lf_slot(lf_slot[3*e +: 3]),
            .lf_data(lf_data[LN*32*e +: LN*32]),
            .lf_take(take[e]), .k_done(k_done[e]),""", """            .nb_valid(nb_valid[e]), .nb_beat(nb_beat[4*e +: 4]), .nb_g(nb_g[e]), .nb_gam(nb_gam[4*e +: 4]),
            .nb_data(nb_data[LN*32/LFB*e +: LN*32/LFB]), .nb_cr(nb_cr[e]),
            .k_done(k_done[e]),""")
    s = rep(s, """        assign req_valid[e] = rv; assign req_v[e] = rvv; assign req_g[e] = rg; assign req_t[13*e +: 13] = rt;
    end endgenerate""", """        assign req_valid[e] = rv; assign req_v[e] = rvv; assign req_g[e] = rg; assign req_t[13*e +: 13] = rt;
        // re-cut D: this engine's node staging FIFO (ND nodes), assembled from the registered beats
        reg            bv;
        reg  [3:0]     bb;
        reg            bg;
        reg  [3:0]     bgam;
        reg  [LN*32/LFB-1:0] bd;
        always @(posedge clk or negedge rst_n) if (!rst_n) bv <= 1'b0; else bv <= nb_valid[e];
        always @(posedge clk) begin bb <= nb_beat[4*e +: 4]; bg <= nb_g[e]; bgam <= nb_gam[4*e +: 4];
                                     bd <= nb_data[LN*32/LFB*e +: LN*32/LFB]; end
        localparam integer SA = (ND > 1) ? $clog2(ND) : 1;
        reg  [LN*32-1:0] stg [0:ND-1];
        reg  [4:0]       smeta [0:ND-1];
        reg  [SA-1:0]    swp, srp;
        reg  [$clog2(ND+1)-1:0] scnt;
        wire             last_beat = bv && (bb == 4'(LFB - 1));
        always @(posedge clk) if (bv) begin
            stg[swp][(LN*32/LFB)*bb +: LN*32/LFB] <= bd;
            smeta[swp] <= {bg, bgam};
        end
        always @(posedge clk or negedge rst_n) begin
            if (!rst_n) begin swp <= 0; srp <= 0; scnt <= 0; nb_cr[e] <= 1'b0; end
            else begin
                if (last_beat) swp <= (swp == SA'(ND - 1)) ? {SA{1'b0}} : swp + 1'b1;
                if (take[e]) srp <= (srp == SA'(ND - 1)) ? {SA{1'b0}} : srp + 1'b1;
                scnt <= scnt + (last_beat ? 1'b1 : 1'b0) - (take[e] ? 1'b1 : 1'b0);
                nb_cr[e] <= take[e];
            end
        end
        assign lf_valid[e] = (scnt != 0);
        assign lf_g[e] = smeta[srp][4];
        assign lf_gam[4*e +: 4] = smeta[srp][3:0];
        assign lf_data[LN*32*e +: LN*32] = stg[srp];
    end endgenerate""")
    s = rep(s, """.lf_valid(lf_valid), .lf_g(lf_g),
        .lf_gam(lf_gam), .lf_slot(lf_slot), .lf_data(lf_data),""", """.lf_valid(lf_valid), .lf_g(lf_g),
        .lf_gam(lf_gam), .lf_data(lf_data),""")
    return head + s


def main():
    txt = generate()
    if '--check' in sys.argv:
        sys.exit(0 if DST.exists() and DST.read_text() == txt else 1)
    DST.write_text(txt)
    print(DST)


if __name__ == '__main__':
    main()
