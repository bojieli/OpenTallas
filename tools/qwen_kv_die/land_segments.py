OUT = 'rtl/qwen_sys/split_20261014/qkd_land_seg.sv'
NSEG = KS.NGRP
W_GW, W_DN, W_UP, W_CR = 273, 298, 262, 32


def emit_seg():
    L = ['// ---- generated by tools/qwen_kv_die/land_segments.py -- do not edit ------------------------------------------',
         '// qkd_land_seg: one row-engine group of the KV landing strip = 4 x qkd_land_pc (slots q = 0..3, S to N) +',
         '// qkd_land_grp_epoch.  Wires only (every block a CLOSED leaf on its own clock entry).',
         'module qkd_land_seg (', '    input  wire          ck_p0,', '    input  wire          ck_p1,',
         '    input  wire          ck_p2,', '    input  wire          ck_p3,', '    input  wire          ck_g,', '    input  wire          rst_n,',
         '    input  wire [1:0]    st,', '    input  wire [2:0]    g,']
    for q in range(4):
        L += [f'    input  wire [{KS.W_LI - 1}:0]  li{q},', f'    output wire          lp{q},', f'    input  wire          cf{q},',
              f'    output wire [{KS.W_ES - 1}:0]  es{q},', f'    input  wire [{KS.W_ER - 1}:0]  er{q},']
    L += [f'    input  wire [{KS.W_RQ - 1}:0]   rq,', f'    output wire [{KS.W_RS - 1}:0] rs,', f'    input  wire [{KS.W_LT - 1}:0]   lt,',
          f'    input  wire [{KS.W_KN - 1}:0] kn,',
          f'    input  wire [{W_DN - 1}:0]  dn_i,      // N face: from the segment above (or the embedding engine)',
          f'    output wire [{W_DN - 1}:0]  dn_o,      // S face',
          f'    input  wire [{W_UP - 1}:0]  up_i,      // S face', f'    output wire [{W_UP - 1}:0]  up_o,      // N face',
          f'    input  wire [{W_CR - 1}:0]   cr_i,', f'    output wire [{W_CR - 1}:0]   cr_o,',
          '    input  wire          pf_i,', '    output wire          pf_o,', '    input  wire          gf_i,', '    output wire          gf_o',
          ');']
    a = L.append
    a(f'    wire [{W_GW - 1}:0] gw [0:3];  wire gc [0:3];')
    a(f'    wire [{W_DN - 1}:0] dn [0:4];  wire [{W_UP - 1}:0] up [0:4];  wire [{W_CR - 1}:0] cr [0:4];  wire pf [0:4];')
    a('    assign dn[4] = dn_i; assign dn_o = dn[0]; assign up[0] = up_i; assign up_o = up[4]; assign cr[0] = cr_i;')
    a('    assign cr_o = cr[4]; assign pf[0] = pf_i; assign pf_o = pf[4];')
    for q in range(4):
        a(f"    qkd_land_pc u_pc{q} (.ck(ck_p{q}), .rst_n(rst_n), .lpc({{2'd{q}, g}}), .li(li{q}), .lp(lp{q}), .cf(cf{q}), "
          f".gw(gw[{q}]), .gc(gc[{q}]), .es(es{q}), .er(er{q}), .dni(dn[{q + 1}]), .dno(dn[{q}]), .upi(up[{q}]), "
          f".upo(up[{q + 1}]), .cri(cr[{q}]), .cro(cr[{q + 1}]), .fi(pf[{q}]), .fo(pf[{q + 1}]));")
    a('    qkd_land_grp_epoch u_g (.ck(ck_g), .rst_n(rst_n), .g(g), .s(st), '
      + ' '.join(f'.gw{q}(gw[{q}]), .gc{q}(gc[{q}]),' for q in range(4))
      + ' .rq(rq), .rs(rs), .lt(lt), .kn(kn), .fi(gf_i), .fo(gf_o));')
    a('endmodule')
    return '\n'.join(L)


def emit_strip():
    """qkd_land_strip_seg: ports = qkd_land_strip_s; 8 segments + the die relay spine (kvn station, kn / lt chains) + emb"""
    s = KS.emit_land()
    hdr = s[s.index('module qkd_land_strip_s ('):s.index(');') + 2].replace('qkd_land_strip_s', 'qkd_land_strip_seg')
    d = KS.land_depths()
    W = KS.W_KN + KS.W_LT
    L = ['// qkd_land_strip_seg: qkd_land_strip_s rebuilt from 8 x qkd_land_seg (the equivalence reference for the die)', hdr]
    a = L.append
    a(f'    wire [{KS.W_KN - 1}:0] kn_m;')
    a(f'    ot_hdc_delay #(.W({KS.W_KN}), .D(1), .RESET(1)) u_kvd (.clk(ck_r), .rst_n(rst_n), .d(kvi), .q(kn_m));')
    a('    assign kvo = kn_m;')
    a('    ot_hdc_delay #(.W(1), .D(1), .RESET(1)) u_kvc (.clk(ck_r), .rst_n(rst_n), .d(kvo_cr), .q(kvi_cr));')
    a(f'    wire [{W - 1}:0] tap [0:{NSEG - 1}];')
    for half, grps in (('s', (3, 2, 1, 0)), ('n', (4, 5, 6, 7))):
        prev, at = '{lt, kn_m}', 0
        for i in grps:
            n = d[i] - at
            a(f'    wire [{W - 1}:0] ch_{half}{i};')
            a(f'    ot_hdc_delay #(.W({W}), .D({n}), .RESET(1)) u_{half}{i} (.clk(ck_r), .rst_n(rst_n), .d({prev}), .q(ch_{half}{i}));')
            a(f'    assign tap[{i}] = ch_{half}{i};')
            prev, at = f'ch_{half}{i}', d[i]
    a(f'    wire [{W_DN - 1}:0] dn [0:{NSEG}];  wire [{W_UP - 1}:0] up [0:{NSEG}];  wire [{W_CR - 1}:0] cr [0:{NSEG}];')
    a(f'    wire pf [0:{NSEG}];  wire gf [0:{NSEG}];')
    a(f"    assign up[0] = {W_UP}'d0; assign cr[0] = {W_CR}'d0; assign pf[0] = kf; assign gf[0] = wf;")
    for i in range(NSEG):
        g = KS.LAND_GROUP_ORDER[i]
        b = 4 * i
        conn = [*(f'.ck_p{q}(ck_p[{b + q}])' for q in range(4)), f'.ck_g(ck_g[{i}])', '.rst_n(rst_n)', '.st(st)', f".g(3'd{g})"]
        for q in range(4):
            conn += [f'.li{q}(li{b + q})', f'.lp{q}(lp{b + q})', f'.cf{q}(cf{b + q})', f'.es{q}(es{b + q})', f'.er{q}(er{b + q})']
        conn += [f'.rq(rq{g})', f'.rs(rs{g})', f'.lt(tap[{i}][{W - 1}:{KS.W_KN}])', f'.kn(tap[{i}][{KS.W_KN - 1}:0])',
                 f'.dn_i(dn[{i + 1}])', f'.dn_o(dn[{i}])', f'.up_i(up[{i}])', f'.up_o(up[{i + 1}])', f'.cr_i(cr[{i}])',
                 f'.cr_o(cr[{i + 1}])', f'.pf_i(pf[{i}])', f'.pf_o(pf[{i + 1}])', f'.gf_i(gf[{i}])', f'.gf_o(gf[{i + 1}])']
        a(f'    qkd_land_seg u_seg{i} (' + ', '.join(conn) + ');')
    a(f'    qkd_land_emb_ifw u_emb (.ck(ck_e), .rst_n(rst_n), .st(st), .emf(emf), .emf_cr(emf_cr), .emr(emr), .emr_cr(emr_cr), '
      f'.dno(dn[{NSEG}]), .upi(up[{NSEG}]), .cri(cr[{NSEG}]), .fi(pf[{NSEG}]), .gfi(gf[{NSEG}]), .mf(mf));')
    a('endmodule')
    return '\n'.join(L)


def emit():
    return '`timescale 1ns/1ps\n' + emit_seg() + '\n\n' + emit_strip() + '\n'


LEAF_LIB = ('rtl/qwen_sys/kv_die_20261009/qkd_land_strip.sv', 'rtl/qwen_sys/split_20261014/qkd_land_grp_epoch.sv',
            'rtl/qwen_sys/split_20261014/qkd_land_emb_ifw.sv')


def leaf_blackboxes():
    """(* blackbox *) copies of the leaf module headers (ANSI port lists; the bodies are not needed for the proof)"""
    import re
    out = []
    for f in LEAF_LIB:
        src = (ROOT / f).read_text()
        for name in ('qkd_land_pc', 'qkd_land_grp_epoch', 'qkd_land_emb_ifw'):
            m = re.search(r'^module\s+' + name + r'\b.*?\);', src, re.S | re.M)
            if m:
                hdr = re.sub(r'//[^\n]*', '', m.group(0))
                hdr = re.sub(r'\boutput\s+reg\b', 'output wire', hdr)
                out.append('(* blackbox *)\n' + hdr + '\nendmodule')
    return '\n'.join(out) + '\n'


def _netlist(t, files, top, keep_seg):
    """yosys JSON of TOP: leaves and ot_hdc_delay black boxes, qkd_land_seg flattened into TOP"""
    ys = t / f'{top}.ys'
    js = t / f'{top}.json'
    ys.write_text('\n'.join([f'read_verilog -sv {f}' for f in files] +
                            [f'hierarchy -check -top {top}', 'proc', 'flatten', 'opt_clean -purge' if False else 'opt_clean',
                             f'write_json {js}']) + '\n')
    p = subprocess.run(['yosys', '-q', str(ys)], capture_output=True, text=True)
    if p.returncode:
        raise SystemExit('land_segments: yosys failed: ' + (p.stdout + p.stderr)[-2000:])
    import json
    return json.loads(js.read_text())['modules'][top]


def _canon(mod, rename):
    """{(instance, port, bit): driver} for every black-box input bit and every top output bit; driver = ('port', name,
    bit) | ('cell', instance, port, bit) | ('const', v); instance names mapped by RENAME (segment -> strip names)"""
    drv = {}
    for pn, pd in mod['ports'].items():
        if pd['direction'] == 'input':
            for k, b in enumerate(pd['bits']):
                drv[b] = ('port', pn, k)
    cells = {}
    for cn, c in mod['cells'].items():
        n = rename(cn.replace('\\', ''))
        cells[n] = c
        for pn, bits in c['connections'].items():
            if c['port_directions'][pn] == 'output':
                for k, b in enumerate(bits):
                    drv[b] = ('cell', n, pn, k)
    out = {}
    def d(b):
        return ('const', b) if isinstance(b, str) else drv.get(b, ('undriven',))
    for n, c in cells.items():
        out[('type', n)] = (c['type'], tuple(sorted((k, str(v)) for k, v in c.get('parameters', {}).items())))
        for pn, bits in c['connections'].items():
            if c['port_directions'][pn] == 'input':
                for k, b in enumerate(bits):
                    out[(n, pn, k)] = d(b)
    for pn, pd in mod['ports'].items():
        if pd['direction'] == 'output':
            for k, b in enumerate(pd['bits']):
                out[('port', pn, k)] = d(b)
    return out


def equiv(seg_file, keep=None, mutate=None):
    """structural netlist equivalence qkd_land_strip_seg == qkd_land_strip_s: every leaf / relay-station input bit and
    every strip output bit has the same driver (leaf output bit, strip input bit or constant), leaves and relay stations
    matched by name (segment i pc q = strip pc 4 i + q, segment i group = strip group i), same master and parameters.
    Returns (ok, report).  mutate: a text substitution applied to the segment file first (the failing-mutant check)."""
    import re
    with tempfile.TemporaryDirectory() as t:
        t = Path(keep) if keep else Path(t)
        t.mkdir(parents=True, exist_ok=True)
        (t / 'bb.v').write_text(leaf_blackboxes() + '(* blackbox *)\nmodule ot_hdc_delay #(parameter integer W = 32, parameter integer D = 1, '
                                 'parameter integer RESET = 0) (input wire clk, input wire rst_n, input wire [W-1:0] d, '
                                 'output wire [W-1:0] q);\nendmodule\n')
        src = (ROOT / 'rtl/qwen_sys/split_20261014/qkd_strips_s.sv').read_text()
        s = src.index('module qkd_land_strip_s (')
        (t / 'ref.sv').write_text(src[s:src.index('endmodule', s) + len('endmodule')] + '\n')
        seg = Path(seg_file).read_text()
        if mutate:
            seg = seg.replace(*mutate, 1)
        (t / 'seg.sv').write_text(seg)
        gold = _canon(_netlist(t, [t / 'bb.v', t / 'ref.sv'], 'qkd_land_strip_s', False), lambda n: n)

        def ren(n):
            m = re.fullmatch(r'u_seg(\d+)\.u_pc(\d)', n)
            if m:
                return f'u_pc{4 * int(m.group(1)) + int(m.group(2))}'
            m = re.fullmatch(r'u_seg(\d+)\.u_g', n)
            return f'u_g{m.group(1)}' if m else n
        gate = _canon(_netlist(t, [t / 'bb.v', t / 'seg.sv'], 'qkd_land_strip_seg', True), ren)
        diff = [k for k in sorted(set(gold) | set(gate), key=str) if gold.get(k) != gate.get(k)]
        rep = (f'{sum(1 for k in gold if k[0] == "type")} instances, {len(gold)} checked items; {len(diff)} differ'
               + ''.join(f'\n  {k}: strip {gold.get(k)} seg {gate.get(k)}' for k in diff[:8]))
        return not diff, rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--equiv', action='store_true')
    ap.add_argument('--mutant', action='store_true', help='the swapped-slot mutant alone: exit 1 (FAIL) when it is detected')
    a = ap.parse_args()
    t = emit()
    p = ROOT / a.out
    if a.check:
        ok = p.exists() and p.read_text() == t
        print('land_segments: ' + ('up to date' if ok else 'STALE'))
        return 0 if ok else 1
    if a.mutant:
        mok, mrep = equiv(p, mutate=("lpc({2'd0, g})", "lpc({2'd1, g})"))
        print(mrep.splitlines()[0])
        if not mok:
            print('FAIL land_seg mutant detected (pc0 lpc strap = slot 1)')
            return 1
        print('mutant NOT detected')
        return 0
    if a.equiv:
        ok, rep = equiv(p)
        print(rep)
        # failing mutant: two PC slots of one group swapped in the segment (lpc straps 0 <-> 1) must be seen
        mok, mrep = equiv(p, mutate=("lpc({2'd0, g})", "lpc({2'd1, g})"))
        print('mutant (pc0 lpc strap = slot 1): ' + ('NOT DETECTED' if mok else 'detected: ' + mrep.splitlines()[0]))
        ok = ok and not mok
        print('EQUIV ' + ('PASS qkd_land_strip_seg == qkd_land_strip_s (mutant detected)' if ok else 'FAIL'))
        return 0 if ok else 1
    p.write_text(t)
    print(f'land_segments: wrote {a.out} ({len(t.splitlines())} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
