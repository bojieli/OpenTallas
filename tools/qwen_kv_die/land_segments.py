#!/usr/bin/env python3
"""Q-KVSYS-STRIP 2026-10-16 (VIS-ROM audit D-QK-02, sev 2): the KV landing strip qkd_land / qkd_land_n (172.8 x 12,141 um,
70:1) is cut into ONE replicated hardened segment master per row-engine group: qkd_land_seg.

  segment i (i = 0..7 from the S end; group g = LAND_GROUP_ORDER[i]) = the four landing PC slots 4 i .. 4 i + 3
  (qkd_land_pc, E column, one a 378-um HBM PC pitch) + the group leaf (qkd_land_grp_epoch, W column) and their chains,
  exactly as qkd_land_strip_s (tools/qwen_kv_die/kv_strips.py emit_land) wires them.  WIRES ONLY: every hop inside is
  leaf to leaf (one flop a leaf: the dn / up / credit / PC-fault chains, the group-fault chain), every segment pin is a
  leaf pin, so the segment is a "clock": "entries" cluster (5 child clock ports, no parent flop, no parent tree).
  Straps: g[2:0] (group id: logical PC lpc = 8 q + g at slot q) and st[1:0] (stack), tied at the die.

  Registered static spine between segments: the chains are leaf-to-leaf (abutting segments: the same 378-um hops as
  today); the KV write words kn / lt keep the die relay stations of qkd_land_strip_s (kvn middle station + the S / N
  chains with depth ceil(|y_grp - y_mid| / 450 um) = 12 9 6 2 | 2 6 9 12), now between segments in the strip channel.
  => cycle-identical to qkd_land_strip_s (proved structurally: tools/qwen_kv_die/land_segments.py --equiv: yosys netlists of qkd_land_strip_seg and
  qkd_land_strip_s with every leaf and relay station a black box, every input bit of every instance and every output bit
  driven identically; a swapped-slot mutant is detected).

    python3 tools/qwen_kv_die/land_segments.py [--out rtl/qwen_sys/split_20261014/qkd_land_seg.sv] [--check] [--equiv]
"""
