#!/usr/bin/env python3
"""Create a default-off, exact-source PC fault-export family; never mutate originals."""
import argparse,hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
INPUTS={
'rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_tiles_hroot_ff_k_mu_ba.sv':('df66545140a103b45170c9132cf19e521945c61c8fc649e836df4bb9c49e6e97',['qkd_kvs_pc','qkd_kvs_pc_h']),
'rtl/qwen_sys/static_embedding_20261014/qkd_static_kv_pc_path_fan_nc_b.sv':('90f9a4ec6dbb0ee2e1d644ac0878566c709ba5a1ec68601a4d250a50fa4f98fe',['qkd_static_kv_pc_path_fan_nc_b','qkd_static_kv_pc_path_emb_nc_b']),
'rtl/qwen_sys/static_kv_20261014/qkd_static_kv_pc_path_nc.sv':('16ac2306ab9b5e707c276042080c03225ab04773f43169d376905c05b0508f0f',['qkd_static_kv_pc_path_nc','qkd_static_kv_return_slots_mc_nc'])}
NAMES={n:n+'_fault_export' for _,ns in INPUTS.values() for n in ns}
def once(s,a,b):
 if s.count(a)!=1:raise ValueError(f'exact source equation count {s.count(a)}: {a}')
 return s.replace(a,b)
def generate():
 out=['`timescale 1ns/1ps\n// Generated by pc_fault_export_family.py. Original modules stay byte-identical.\n']
 for path,(sha,names) in INPUTS.items():
  raw=(ROOT/path).read_bytes()
  if hashlib.sha256(raw).hexdigest()!=sha:raise ValueError('source fingerprint changed: '+path)
  text=raw.decode()
  for name in names:
   matches=re.findall(r'\bmodule\s+'+name+r'\b[\s\S]*?\bendmodule\b',text)
   if len(matches)!=1:raise ValueError('module identity: '+name)
   s=matches[0]
   if name in ('qkd_kvs_pc','qkd_kvs_pc_h'):
    s=once(s,'module '+name+' (','module '+name+' #(parameter integer FAULT_EXPORT=0) (')
    s=once(s,'#(.MU(1)) u_pc','#(.MU(1), .FAULT_EXPORT(FAULT_EXPORT)) u_pc')
   elif name=='qkd_static_kv_pc_path_fan_nc_b':
    s=once(s,'parameter integer MU = 0','parameter integer MU = 0, parameter integer FAULT_EXPORT=0')
    s=once(s,'#(.MU(MU)) u_pce','#(.MU(MU), .FAULT_EXPORT(FAULT_EXPORT)) u_pce')
    s=once(s,'.pc(pc),\n        .wes(s_wes),','.pc(pc),\n        .wes(s_wes), .chain_fault_core(chain_fault),')
   elif name=='qkd_static_kv_pc_path_emb_nc_b':
    s=once(s,'parameter integer MU = 0','parameter integer MU = 0, parameter integer FAULT_EXPORT=0')
    s=once(s,'input wire pll_hbm,','input wire chain_fault_core,\n    input wire pll_hbm,')
    s=once(s,'#(.MU(MU)) u_path','#(.MU(MU), .FAULT_EXPORT(FAULT_EXPORT)) u_path')
    s=once(s,'        .es(es_merged),','        .es(es_merged), .extra_core_fault(chain_fault_core | es_merge_fault),')
   elif name=='qkd_static_kv_pc_path_nc':
    s=once(s,'parameter integer MU = 0','parameter integer MU = 0, parameter integer FAULT_EXPORT=0')
    s=once(s,'input wire pll_hbm,','input wire extra_core_fault,\n    input wire pll_hbm,')
    s=once(s,'#(.DEPTH(8)) u_return','#(.DEPTH(8), .FAULT_EXPORT(FAULT_EXPORT)) u_return')
    s=once(s,'.fault_core(return_fault_core),','.fault_core(return_fault_core), .extra_core_fault(extra_core_fault),')
   elif name=='qkd_static_kv_return_slots_mc_nc':
    s=once(s,'parameter integer DEPTH=8','parameter integer DEPTH=8, parameter integer FAULT_EXPORT=0')
    s=once(s,'input wire pll_hbm,hrst,ck,rsi,','input wire extra_core_fault,\n input wire pll_hbm,hrst,ck,rsi,')
    s=once(s,'fault_core<=rs_a && (fault_core_s || fault_core_set);','fault_core<=rs_a && (fault_core_s || fault_core_set || (FAULT_EXPORT != 0 && extra_core_fault));')
   s=re.sub(r'\b('+'|'.join(sorted(NAMES,key=len,reverse=True))+r')\b',lambda m:NAMES[m[0]],s)
   out.append('// Exact whole-module source: '+path+' SHA256 '+sha+'\n'+s+'\n')
 return '\n'.join(out)
def main():
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);a=p.parse_args();a.out.parent.mkdir(parents=True,exist_ok=True);a.out.write_text(generate())
 print(json.dumps(dict(output=str(a.out),sha256=hashlib.sha256(a.out.read_bytes()).hexdigest(),default_export=0,selected_abi_bits=305,selected_fault_bit=301)))
if __name__=='__main__':main()
