#!/usr/bin/env python3
"""KDIE5-TV 10-22: kits qkd_kvs_grp_r1 / qkd_kvs_grp_h_r1 for the RELEASE KV die (kvs14r-f9b69ebb3-relm).
Base = the k1 kits (same module text: qkd_kvs_tiles_hroot_ff_k.sv == ..._n32_pj.sv for qkd_kvs_grp / _h), retargeted to
the release tile file, the release frame outline and the release frame's pin faces / order / spans."""
import json, re, subprocess, sys, collections
from pathlib import Path

WT = Path(sys.argv[1]); LEF = Path(sys.argv[2])
TILE = 'rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_tiles_hroot_ff_k_hl_mu_ba_n32_pj.sv'
PITCH = 0.096          # 2 M4 / M5 tracks (PIN_MIN_TRACKS=2); the frame stand-in packs every track (0.048)


def git_show(rev, p):
    return subprocess.run(['git', '-C', str(WT), 'show', f'{rev}:{p}'], capture_output=True, text=True, check=True).stdout


def frame(m):
    t = LEF.read_text()
    b = re.search(r'^MACRO ' + m + r'\n(.*?)^END ' + m + r'\n', t, re.S | re.M).group(1)
    W, H = map(float, re.search(r'SIZE ([\d.]+) BY ([\d.]+)', b).groups())
    pins = []
    for blk in re.split(r'\n  PIN ', b)[1:]:
        name = blk.split('\n', 1)[0].strip()
        r = re.search(r'LAYER (\S+) ;\s+RECT ([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+)', blk)
        L = r.group(1); x0, y0, x1, y1 = map(float, r.groups()[1:])
        f = 'W' if x0 < 0.5 else 'E' if x1 > W - 0.5 else 'S' if y0 < 0.5 else 'N' if y1 > H - 0.5 else 'I'
        t_ = (y0 + y1) / 2 if f in 'WE' else (x0 + x1) / 2
        pins.append((name, f, L, t_))
    return W, H, pins


def io_tcl(kit, W, H, pins):
    """same face, same layer, same bit order along the face, each port group re-spread at PITCH about its frame centre"""
    by = collections.defaultdict(list)
    for n, f, L, t in pins:
        by[(f, re.sub(r'\[\d+\]$', '', n))].append((t, n, L))
    lines = [f'# {kit}: GENERATED by KDIE5-TV mk_r1.py from the release KV die frame (kvs14r-f9b69ebb3-relm case_kv/elements.lef '
             f'MACRO {kit.rsplit("_r1", 1)[0]})', '# face / layer / bit order / port-group centre = the frame; pitch 2 tracks '
             f'({PITCH} um) instead of the stand-in 1 track (every die frame packs 0.048).']
    out = {}
    for f in 'NSEW':
        groups = sorted([(sum(t for t, _, _ in v) / len(v), k[1], sorted(v)) for k, v in by.items() if k[0] == f])
        edge = W if f in 'NS' else H
        prev_hi = 2.0
        for c, port, v in groups:
            n = len(v); span = (n - 1) * PITCH
            lo = max(c - span / 2, prev_hi + PITCH)
            lo = round(round((lo - 0.012) / 0.048) * 0.048 + 0.012, 3)   # M4 / M5 track grid 0.048 k + 0.012 (frame pins)
            for i, (t, name, L) in enumerate(v):
                p = round(lo + i * PITCH, 3)
                out[name] = (f, L, p)
            prev_hi = lo + span
            assert prev_hi < edge - 2.0, (kit, f, port, prev_hi, edge)
    nbits = collections.Counter(n.split('[')[0] for n in out)
    for name, (f, L, p) in sorted(out.items()):
        # a width-1 port is a scalar BTerm: the recipe-3 wrapper (ot_pin_regs.tcl e3919f90e) declares it scalar
        # (route 7dc9135b2 failed PPL-0061 'Pins {af__fault[0]} ... not found')
        pn = re.sub(r'\[0\]$', '', name) if nbits[name.split('[')[0]] == 1 else name
        x, y = {'W': (0.042, p), 'E': (round(W - 0.042, 3), p), 'S': (p, 0.042), 'N': (p, round(H - 0.042, 3))}[f]
        lines.append(f'place_pin -pin_name {pn} -layer {L} -location {{{x} {y}}}')
    return '\n'.join(lines) + '\n', out


SCALARS = {'ck', 'hck', 'rst_n', 'hrst_n'}


def main():
    base = 'HEAD'
    for k in ('grp', 'grp_h'):
        m = f'qkd_kvs_{k}'; kit = f'{m}_r1'; k1 = f'{m}_k1'
        W, H, pins = frame(m)
        # ports the die leaves unread have no frame pin (port_bind rtl_outputs_unread): y__tok / y__tep = x__tok / x__tep
        # pass words -> W beside x__tok; grp_h o_dn (= i_ctl permuted) -> N between i_ctl and o_ctl (short feed-through)
        have = {re.sub(r'\[\d+\]$', '', n) for n, *_ in pins}
        xt = max(t for n, f, L, t in pins if n.startswith('x__tok['))
        extra = [('y__tok', 18, 'W', 'M4', xt + 12.0), ('y__tep', 16, 'W', 'M4', xt + 14.0),
                 ('o_dn', 271, 'N', 'M5', 128.0)]
        for port, w, f, L, c in extra:
            if port in have:
                continue
            pins += [(f'{port}[{i}]', f, L, c + (i - w / 2) * 0.001) for i in range(w)]
        s = json.loads(git_show(base, f'physical/ref_tile/{k1}/spec.json'))
        s['name'] = kit
        s['sources'] = [TILE if x.endswith('qkd_kvs_tiles_hroot_ff_k.sv') else x for x in s['sources']]
        s['outline'] = {'w': W, 'h': H, 'exact': True}
        txt, placed = io_tcl(kit, W, H, pins)
        io = f'physical/qkd_kvs_kits/{kit}_io.tcl'
        (WT / io).write_text(txt)
        s['io_tcl'] = io
        s.pop('pin_ranges', None)
        faces = collections.defaultdict(list)
        for n, (f, L, p) in placed.items():
            b = n.split('[')[0]
            if b not in faces[f]:
                faces[f].append(b)
        s['pins'] = {f: faces[f] for f in 'NSEW' if faces[f]}
        # landing SRAM of branch q level with its i_pc<q> pins (g_pc[q] <- i_pc<q>: slg actual_*__<3-q>, concatenated {__0..__3})
        ys = {}
        for n, (f, L, p) in placed.items():
            mm = re.match(r'i_pc(\d)\[', n)
            if mm:
                ys.setdefault(int(mm.group(1)), []).append(p)
        mh = 41.064
        for mac in s['macros']:
            q = int(re.search(r'g_pc\?(\d)\?', mac['inst']).group(1))
            c = sum(ys[q]) / len(ys[q])
            mac['at'] = [85.5, round(c - mh / 2, 3)]
            mac['orient'] = 'R0'
        # hck: per-bit domains of the mixed o_pc / o_ctl ports (TW2-KVGRP 9bfa7f470, measured on this module text)
        sdc = f'physical/qkd_kvs_kits/{kit}_hck.sdc'
        (WT / sdc).write_text(git_show('129b40f0a', f'physical/qkd_kvs_kits/{k1}_hck.sdc').replace(k1, kit))
        bnd = f'physical/qkd_kvs_kits/{kit}_hck_boundary.tcl'
        (WT / bnd).write_text(git_show('129b40f0a', f'physical/qkd_kvs_kits/{k1}_hck_boundary.tcl').replace(k1, kit))
        s['sdc_extra'] = [sdc]
        s['boundary_tcl'] = [bnd]
        s['clock'] = 'spine'
        s['orfs_vars'] = {'OT_SPINE_PORTS': 'ck,hck'}
        s['reset_ports'] = ['rst_n']
        s['reset_landing'] = {'enable': True, 'stages': 2, 'clock': 'ck'}
        s['route'] = dict(s['route'], io_hold_margin_ns=0.03)
        s['structural_change'] = (
            'KDIE5-TV 10-22: release-die kit of qkd_kvs_tiles_hroot_ff_k_hl_mu_ba_n32_pj.sv module ' + m +
            ' (module text identical to the k1 kit\'s qkd_kvs_tiles_hroot_ff_k.sv). Structural changes vs k1 (no RTL change): '
            '(1) outline = the release frame 222.576 x 1187.976; (2) pins = the release frame faces / bit order / port '
            'centres at a 2-track pitch (io_tcl); (3) landing SRAM g_pc[q] level with i_pc<q> (k1 had the branch order '
            'inverted: g_pc[0] at the top while i_pc0 enters at the bottom); (4) per-bit hck domains of o_pc / o_ctl '
            '(9bfa7f470) + hclk boundary re-read after every io_ref switch; (5) spine ck,hck; (6) rst_n landed on ck in 2 '
            'stages (+2 reset release, startup only), hrst_n stays an hclk input (a one-clock flow landing would land it on ck).')
        s['purpose'] = f'KDIE5-TV 10-22: die-bindable view of {m} for the release KV die (relm f9b69ebb3, x{28 if k == "grp" else 4})'
        j = s['job']
        j.update(owner='Claude:KDIE5-TV', branch='claude/kdie5-tv-1022', tag='r1', purpose=s['purpose'],
                 views_to=f'physical/ref_tile/{kit}/views', record_to=f'results/rtl/ref_tile/{kit}')
        j['extra_paths'] = ['rtl', 'tools/qwen_kv_die', 'results/arch', 'results/rtl/qwen_kv_die/kvs_kits_1018',
                            'physical/asap7_memory_macros_v2/ot_sram_1r1w_128x256_m1_r2c2', 'physical/qkd_kvs_kits']
        # benches: lockstep vs the die-bound tile (bench tile text == the release module, checked), Verilator 5.050
        for b in j['benches']:
            b['cmd'] = b['cmd'].replace('bash tools/qwen_kv_die/kvs_tile_bench.sh', 'KVS_SIM=verilator bash tools/qwen_kv_die/kvs_tile_bench.sh')
            b['needs'] = ['verilator']
            for w in ('pass_witness', 'fail_witness'):
                if w in b:
                    b[w] = b[w].replace('results/rtl/qwen_kv_die/kvs_kits_1018/', 'results/rtl/qwen_kv_die/kdie5_tv_1022/')
        j['extra_paths'] = [x.replace('results/rtl/qwen_kv_die/kvs_kits_1018', 'results/rtl/qwen_kv_die/kdie5_tv_1022') for x in j['extra_paths']]
        d = WT / 'physical/ref_tile' / kit
        d.mkdir(parents=True, exist_ok=True)
        (d / 'spec.json').write_text(json.dumps(s, indent=1) + '\n')
        print(kit, W, H, 'pins', len(placed), {f: len(v) for f, v in s['pins'].items()},
              [m_['at'] for m_ in s['macros']])


main()
