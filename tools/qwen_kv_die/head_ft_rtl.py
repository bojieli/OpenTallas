#!/usr/bin/env python3
"""kvsys v1.4.3 (G3S2, KV die lead 2026-10-15): generate the NEAR-head frame RTL ot_qkh_head_native_r4_ft.

The near head of each pair carries its FAR neighbour's mid-way stages in a feed-through channel (head_ft_plan.json):
one qkh_head_gather_stage (the far head's T1: the 1559-bit ti word + 16-bit e word, one registered edge) and one
qkh_head_sstage (the far head's S2: the 34-bit score word, one registered edge).  The frame is a wires-only parent
(kv_expand elaborates ONE module text with every leaf a black box), so the body is the exact text of
ot_qkh_head_native_r4 (same leaf cells, same yosys cell names -> the r4 plan's child names) plus the two leaves on
their own ports and clock entries.  Static schedule: pure pipeline registers, no valid/ready/credit, no reset.

    python3 tools/qwen_kv_die/head_ft_rtl.py [--check]
"""
import argparse, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/qwen_sys/split_20261014/ot_qkh_head_native_r4.sv'
OUT = ROOT / 'rtl/qwen_sys/split_20261014/ot_qkh_head_native_r4_ft.sv'


def r4_text():
    t = SRC.read_text()
    m = re.search(r'^module ot_qkh_head_native_r4 #\(.*?^endmodule\s*$', t, re.M | re.S)
    if not m:
        raise SystemExit('ot_qkh_head_native_r4 not found')
    return m.group(0)


def generate():
    body = r4_text()
    head, rest = body.split(');', 1)                      # parameter/port header | body
    assert head.count('output wire [1023:0] nb_d') == 1, 'r4 header changed: regenerate by hand'
    head = head.replace('module ot_qkh_head_native_r4 #(', 'module ot_qkh_head_native_r4_ft #(')
    head = head.replace('output wire [1023:0] nb_d', 'output wire [1023:0] nb_d,\n'
                        '  // v1.4.3 feed-through for the far neighbour head: its T1 (ti 1559 + e 16) and its S2 (score 34)\n'
                        '  input wire ck_ft_t,ck_ft_s,input wire [1558:0] ft_ti_a,input wire [15:0] ft_e_a,\n'
                        '  output wire [1558:0] ft_ti_b,output wire [15:0] ft_e_b,input wire [33:0] ft_s_a,output wire [33:0] ft_s_b')
    rest = rest.replace('endmodule', '  qkh_head_gather_stage u_ftg (.ck(ck_ft_t),.ti_a(ft_ti_a),.e_a(ft_e_a),.ti_b(ft_ti_b),.e_b(ft_e_b));\n'
                        '  qkh_head_sstage u_fts (.ck(ck_ft_s),.s_a(ft_s_a),.s_b(ft_s_b));\nendmodule')
    return ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/head_ft_rtl.py from ot_qkh_head_native_r4 (do not edit; regenerate).\n'
            '// kvsys v1.4.3 near head = r4 head (identical leaf cells) + the far neighbour\'s T1 gather stage + S2 score stage.\n'
            + head + ');' + rest + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    txt = generate()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == txt
        print('head_ft_rtl', 'CURRENT' if ok else 'STALE'); return 0 if ok else 1
    OUT.write_text(txt); print(OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
