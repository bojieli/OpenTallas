#!/usr/bin/env python3
"""Source-only G3S2/HXK13 native service binding; no protected-lib or reference aliases.

Canonical w16 remains unchanged. The new composition reuses its actual arithmetic,
ASTK memory service and exact closed head stages. No physical master is introduced:
these are wires/clock-root composition modules over the existing hardware leaves.
"""
import argparse
import hashlib
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SERVICE=ROOT/'rtl/hdc/nearhbm/ot_qwen_tp8_attention_native_service_w16.sv'
STACK=ROOT/'rtl/qwen_sys/split_20261014/qkd_astk_native_stack_w4_gen.sv'
OUT=ROOT/'rtl/qwen_sys/split_20261014/qkd_native_attention_service_g3s2_gen.sv'

def once(s,a,b):
    if s.count(a)!=1:raise ValueError(f'source binding mismatch {a!r}: {s.count(a)}')
    return s.replace(a,b)

def generate():
    s=SERVICE.read_text().replace('ot_qwen_tp8_attention_native_service_w16','ot_qwen_tp8_attention_native_service_w16_g3s2')
    s=s.replace('ot_qwen_tp8_attention_native_stack_w4_cp','ot_qwen_tp8_attention_native_stack_w4_g3s2_cp')
    s=s.replace('ot_qwen_tp8_attention_native_stack_w4_cal','ot_qwen_tp8_attention_native_stack_w4_g3s2_cal')
    t=re.search(r'^module ot_qwen_tp8_attention_native_stack_w4_cal #\(.*?^endmodule\n',STACK.read_text(),re.M|re.S).group()
    t=t.replace('module ot_qwen_tp8_attention_native_stack_w4_cal','module ot_qwen_tp8_attention_native_stack_w4_g3s2_cal')
    t=once(t,'localparam integer HEAD_SCORE_HXK=8;','localparam integer HEAD_SCORE_HXK=13;')
    t=once(t,'ot_qkh_head_native_r4 #(.Q_FP32(1)) u_head(', 'qkd_head_g3s2_native u_head(')
    h='''
// Same G3S2 port/stage topology as the measured rate_1015/head_g3s2_wrap,
// with the actual source master ot_qkh_head_native_r4 (Q_FP32=1).
module qkd_head_g3s2_native (
 input wire [3:0] ck_front,input wire ck_score,ck_kt,
 input wire [15:0] ck_stin,ck_stk,ck_nb1,ck_nb2,ck_lane,
 input wire rst_n,input wire [3:0] c_in,input wire [1023:0] row_in,
 input wire [15:0] e_in,input wire [11:0] lt_in,input wire [1:0] hid,
 input wire q_valid_in,input wire [5:0] q_beat_in,input wire [511:0] q_data_in,
 output wire [31:0] sc_d,output wire sc_f,g_f,output wire [1023:0] nb_d
);
 wire [1558:0] t0={c_in,row_in,lt_in,q_valid_in,q_beat_in,q_data_in},t1,t2,t3;
 wire [15:0] e1,e2,e3;wire [31:0] hs;wire hf,hg;wire [33:0] s1;
 qkh_head_gather_stage u_g(.ck(ck_kt),.ti_a(t0),.e_a(e_in),.ti_b(t1),.e_b(e1));
 qkh_head_tstage u_t1(.ck(ck_kt),.ti_a(t1),.e_a(e1),.ti_b(t2),.e_b(e2));
 qkh_head_tstage u_t2(.ck(ck_kt),.ti_a(t2),.e_a(e2),.ti_b(t3),.e_b(e3));
 ot_qkh_head_native_r4 #(.Q_FP32(1)) u_r4(.ck_front(ck_front),.ck_score(ck_score),.ck_kt(ck_kt),
  .ck_stin(ck_stin),.ck_stk(ck_stk),.ck_nb1(ck_nb1),.ck_nb2(ck_nb2),.ck_lane(ck_lane),
  .rst_n(rst_n),.c_in(t3[1558:1555]),.row_in(t3[1554:531]),.e_in(e3),
  .lt_in(t3[530:519]),.hid(hid),.q_valid_in(t3[518]),.q_beat_in(t3[517:512]),.q_data_in(t3[511:0]),
  .sc_d(hs),.sc_f(hf),.g_f(hg),.nb_d(nb_d));
 qkh_head_sstage u_s1(.ck(ck_score),.s_a({hs,hf,hg}),.s_b(s1));
 qkh_head_sstage u_s2(.ck(ck_score),.s_a(s1),.s_b({sc_d,sc_f,g_f}));
endmodule
'''
    hashes='\n'.join('// '+str(p.relative_to(ROOT))+' sha256 '+hashlib.sha256(p.read_bytes()).hexdigest() for p in (SERVICE,STACK))
    return '// GENERATED by tools/qwen_kv_die/gen_native_endpoint_service.py; canonical sources unchanged.\n'+hashes+'\n'+s+'\n'+t+h

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();s=generate()
    if a.check:
        if OUT.read_text()!=s:raise SystemExit('source binding stale')
    else:OUT.write_text(s)
if __name__=='__main__':main()
