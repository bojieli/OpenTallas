#!/usr/bin/env python3
"""Inline the exact86-child r4 head with one real internal T2 stage (87 roots).

No raw head or closed stage source is edited. --check proves byte-exact inverse
aliasing of the inherited body and reproduces the standalone composition bench.
"""
import argparse,hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
RAW=Path('rtl/qwen_sys/split_20261014/ot_qkh_head_native_r4.sv')
STAGE=Path('rtl/qwen_sys/split_20261014/qkh_head_stages.sv')
OLDTB=Path('rtl/test/qwen_split/tb_qkh_head_native.sv')
OUT=Path('rtl/qwen_sys/split_20261014/ot_qkh_head_native_r4_s2.sv')
TB=Path('rtl/test/qwen_split/tb_qkh_head_inner_t2.sv')
MAP=Path('results/rtl/qkh_head_inner_t2_1103/source_composition.json')
ALIASES={'c_in':'c_t2','row_in':'row_t2','e_in':'e_t2','lt_in':'lt_t2','q_valid_in':'qv_t2','q_beat_in':'qb_t2','q_data_in':'qd_t2'}

def module(text,name):
 match=re.search(r'\bmodule\s+'+name+r'\b',text)
 if match is None:raise ValueError('actual module absent: '+name)
 end=text.index('endmodule',match.end())+len('endmodule')
 return text[match.start():end]

def generate():
 raw=(ROOT/RAW).read_text();stages=(ROOT/STAGE).read_text();oldtb=(ROOT/OLDTB).read_text()
 source=module(raw,'ot_qkh_head_native_r4');header,body=source.split(');',1)
 found=re.findall(r"\b(ot_qkh_\w+)\s*(?:#\s*\((?:[^()]|\([^()]*\))*\)\s*)?(u_\w+)\s*\(",body)
 expected=[('ot_qkh_head_frontq_native','u_front'),('ot_qkh_head_stin_native','u_stin'),('ot_qkh_head_stk_native','u_stk'),('ot_qkh_head_nb_native','u_nb1'),('ot_qkh_head_nb_native','u_nb2'),('ot_qkh_lane8','u_l8'),('ot_qkh_ktree','u_kt'),('ot_qkh_head_score4_native','u_score')]
 if found!=expected or 'g<4' not in body or 't<16' not in body:raise ValueError('actual inherited child/loop grammar differs')
 if body.count('endmodule')!=1:raise ValueError('unexpected raw body')
 header=header.replace('module ot_qkh_head_native_r4','module ot_qkh_head_native_r4_s2',1)
 needle='input wire [15:0] ck_stin,ck_stk,ck_nb1,ck_nb2,ck_lane,'
 if header.count(needle)!=1:raise ValueError('raw clock face changed')
 header=header.replace(needle,needle+'input wire ck_t2,')
 transformed=body
 for old,new in ALIASES.items():transformed=re.sub(r'(?<!\.)\b'+old+r'\b',new,transformed)
 restored=transformed
 for old,new in ALIASES.items():restored=re.sub(r'\b'+new+r'\b',old,restored)
 if restored!=body:raise ValueError('inherited86-child body is not exactly recoverable')
 prefix="""
  // T2 is the sole added child. T1 and S1 remain outside this parent.
  wire [1558:0] ti_t2;
  wire [15:0] e_t2;
  qkh_head_tstage u_t2 (.ck(ck_t2),
    .ti_a({c_in,row_in,lt_in,q_valid_in,q_beat_in,q_data_in}),.e_a(e_in),
    .ti_b(ti_t2),.e_b(e_t2));
  wire [3:0] c_t2=ti_t2[1558:1555];
  wire [1023:0] row_t2=ti_t2[1554:531];
  wire [11:0] lt_t2=ti_t2[530:519];
  wire qv_t2=ti_t2[518];
  wire [5:0] qb_t2=ti_t2[517:512];
  wire [511:0] qd_t2=ti_t2[511:0];
  // Inherited raw86-child body follows; inverse aliases reproduce its exact bytes.
"""
 product='`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/head_inner_t2.py; raw86 clocks and child names retained.\n'+header+');'+prefix+transformed+'\n'
 if re.findall(r'\bmodule\s+(\w+)',product)!=['ot_qkh_head_native_r4_s2']:raise ValueError('product must contain sole target module')
 # Directly compare the new inner+external T1/S1 against the real existing staged composition.
 bench=oldtb.replace('module tb_qkh_head_native;','module tb_qkh_head_inner_t2;',1)
 start=bench.index('  ot_qwen_nearhbm_head_hs u_ref')
 stop=bench.index('  integer cycles=',start)
 instances="""
  ot_qkh_head_native_r4_staged #(.Q_FP32(1),.MUT(0)) u_ref
    (.ck_front({4{clk}}),.ck_score(clk),.ck_kt(clk),.ck_stin({16{clk}}),.ck_stk({16{clk}}),
     .ck_nb1({16{clk}}),.ck_nb2({16{clk}}),.ck_lane({16{clk}}),.ck_t1(clk),.ck_t2(clk),.ck_s1(clk),
     .rst_n(rst_n),.c_in(c),.row_in(row),.e_in(e),.lt_in(lt),.hid(hid),
     .q_valid_in(qv),.q_beat_in(qb),.q_data_in(qd),.sc_d(rsc),.sc_f(rsf),.g_f(rgf),.nb_d(rnb));
  qkh_head_inner_t2_bench_view #(.Q_FP32(1),.MUT(MUT)) u_dut
    (.ck_front({4{clk}}),.ck_score(clk),.ck_kt(clk),.ck_stin({16{clk}}),.ck_stk({16{clk}}),
     .ck_nb1({16{clk}}),.ck_nb2({16{clk}}),.ck_lane({16{clk}}),.ck_t1(clk),.ck_t2(clk),.ck_s1(clk),
     .rst_n(rst_n),.c_in(c),.row_in(row),.e_in(e),.lt_in(lt),.hid(hid),
     .q_valid_in(qv),.q_beat_in(qb),.q_data_in(qd),.sc_d(dsc),.sc_f(dsf),.g_f(dgf),.nb_d(dnb));
  wire [31:0] csc=rsc; wire csf=rsf,cgf=rgf; wire [1023:0] cnb=rnb;
"""
 bench=bench[:start]+instances+bench[stop:]
 # The bench-only external composition retains the exact staged port order.
 wrapper=module(stages,'ot_qkh_head_native_r4_staged').split(');',1)[0]
 wrapper=wrapper.replace('module ot_qkh_head_native_r4_staged','module qkh_head_inner_t2_bench_view',1)+');'
 wrapper+="""
  integer mode=0;
  initial begin if($value$plusargs("negative=%d",mode))begin end end
  wire [1558:0] ti0={c_in,row_in,lt_in,q_valid_in,q_beat_in,q_data_in};
  wire [1558:0] ti1;wire [15:0] e1;
  qkh_head_tstage u_t1(.ck(ck_t1),.ti_a(ti0),.e_a(e_in),.ti_b(ti1),.e_b(e1));
  wire [1558:0] ti=(mode==1)?ti0:ti1;
  wire [15:0] ee=(mode==1)?e_in:e1;
  wire [33:0] sh,so;
  ot_qkh_head_native_r4_s2 #(.Q_FP32(Q_FP32),.MUT(MUT)) u_head
    (.ck_front(ck_front),.ck_score(ck_score),.ck_kt(ck_kt),.ck_stin(ck_stin),.ck_stk(ck_stk),
     .ck_nb1(ck_nb1),.ck_nb2(ck_nb2),.ck_lane(ck_lane),.ck_t2(ck_t2),.rst_n(rst_n),
     .c_in(ti[1558:1555]),.row_in(ti[1554:531]),.e_in(ee),.lt_in(ti[530:519]),.hid(hid),
     .q_valid_in(ti[518]),.q_beat_in(ti[517:512]),.q_data_in(ti[511:0]),
     .sc_d(sh[33:2]),.sc_f(sh[1]),.g_f(sh[0]),.nb_d(nb_d));
  qkh_head_sstage u_s1(.ck(ck_s1),.s_a(sh),.s_b(so));
  assign {sc_d,sc_f,g_f}=(mode==2)?sh:so;
endmodule
"""
 bench+='\n'+wrapper+'\n'
 clocks={f'g_front[{g}].u_front':f'ck_front[{g}]' for g in range(4)}
 kinds={'u_stin':'ck_stin','u_stk':'ck_stk','u_nb1':'ck_nb1','u_nb2':'ck_nb2','u_l8':'ck_lane'}
 for t in range(16):clocks.update({f'g_t[{t}].{u}':f'{ck}[{t}]' for u,ck in kinds.items()})
 clocks.update(u_kt='ck_kt',u_score='ck_score',u_t2='ck_t2')
 if len(clocks)!=87 or len(set(clocks.values()))!=87:raise ValueError('actual87 independent entry mapping differs')
 report=dict(schema='opentallas.qkh-head-inner-t2-source.v1',status='EXACT_INVERSE_ALIAS_BODY_SOURCE_ONLY',
   original_child_count=86,child_count=87,clock_entries=clocks,source_sha256={str(p):hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in (RAW,STAGE,OLDTB,Path(__file__).relative_to(ROOT))},
   inherited_body_sha256=hashlib.sha256(body.encode()).hexdigest(),inverse_alias_body_sha256=hashlib.sha256(restored.encode()).hexdigest(),
   generated_source_sha256=hashlib.sha256(product.encode()).hexdigest(),composition_bench_sha256=hashlib.sha256(bench.encode()).hexdigest(),aliases=ALIASES,
   external_children=['qkh_head_tstage T1','qkh_head_sstage S1'],semantic_edges=dict(input=2,score=1,nb=2),
   physical_qualified=False,numerical_execution=False,note='Original86 child body, parameters, names, resets and separate clocks preserved exactly after input alias inversion. T2 is the actual existing closed stage source; no old gate/view is relabelled.')
 return {OUT:product,TB:bench,MAP:json.dumps(report,indent=2)+'\n'}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 for path,text in generate().items():
  if a.check:
   if (ROOT/path).read_text()!=text:raise ValueError('generated bytes differ: '+str(path))
  else:(ROOT/path).parent.mkdir(parents=True,exist_ok=True);(ROOT/path).write_text(text)
 print('HEAD_INNER_T2_SOURCE_PASS exact86 inherited bindings plus actual T2;87clock entries')
if __name__=='__main__':main()
