#!/usr/bin/env python3
"""kv-die 2026-10-09 (review-0528 KV1(b), CRITICAL PATH): generate rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_e.sv, the
near-HBM stack RE-CUT E: re-cut D (tools/qwen_kv_die/stack_d_gen.py: P.V levels 1-3 inside the engine, level-3 nodes
to the aggregator in LFB beats under ND credits, aggregator levels 4-7, q beat broadcast) WITHOUT D's extra 512-lane
adder bank.  Levels 1-3 run on the engine's own lane loop adders.

Why it is exact and free of a bank.  A finished slot's value recirculates in its lane loop as add(acc, +0) every turn
(the parent's pending-leaf rule).  A pair (left slot l, right slot r) of the residue group's pairwise tree --
level 1: (2i, 2i+1); level 2: (1, 3), (5, 7); level 3: (3, 7) -- is formed in two control bits on that loop:
  xl  at l's turn every lane loads its loop value into a one-word register X (and slot l is freed, as by the tree's take);
  pr  at r's turn the lane adder adds X instead of +0: r's loop now holds add(r, l) = add(l, r) (the finite RNE sum is
      symmetric; non-finite operands fault as before).
The window l..r of one pair never overlaps another (x_open blocks a new pair until the open one issues), so one X a lane
suffices.  A pair fires only when both slots are final at the same level and carry the same (g, gam).  The level-3
node is loaded (ol) into a one-word output register a lane at slot 7's turn and sent in LFB beats as in D.
Lane cost: two 32-bit registers (X, the output word) and a 3:1 operand select a lane, no adders.  Every cycle the
pairs cost (each level is one loop pass) is measured by the bench, not assumed.

    python3 tools/qwen_kv_die/stack_e_gen.py [--check]
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stack_d_gen as D               # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DST = ROOT / 'rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_e.sv'
rep = D.rep


def generate():
    s = D.generate()
    mods = re.findall(r'(?m)^module\s+(\w+)_d\b', s)
    s = re.sub(r'\b(' + '|'.join(map(re.escape, mods)) + r')_d\b', r'\1_e', s)
    s = rep(s, """// GENERATED by tools/qwen_kv_die/stack_d_gen.py from rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_p.sv (do not edit by
// hand).  RE-CUT D of the near-HBM stack""", """// GENERATED by tools/qwen_kv_die/stack_e_gen.py (re-cut D of stack_d_gen.py with levels 1-3 on the lane loop adders:
// no extra adder bank; do not edit by hand).  RE-CUT E of the near-HBM stack""")
    # ---- central: the pair / output decisions replace D's local tree ----
    i = s.index("    // ---- re-cut D: the P.V tree's levels 1-3 over this engine's residue group")
    j = s.index("    // ---- K pass: the root (level LV)", i)
    s = s[:i] + """    // ---- re-cut E: the node word leaves in LFB beats (the lanes' output registers, loaded by ol) -----------------------
    reg              ob_g;
    reg  [3:0]       ob_gam;
    reg  [3:0]       ob_b;
    reg  [3:0]       ob_wait;                           // ol reaches the lanes LANE_D + PLAT cycles after the decision
    reg  [$clog2(ND+1)-1:0] ocred;
    reg              ocr_q;
    wire ob_send = ob_busy && (ob_wait == 4'd0) && ((ob_b != 4'd0) || (ocred != 0));
    always @(posedge clk or negedge rc) begin
        if (!rc) begin ob_b <= 4'd0; ob_wait <= 4'd0; ocred <= ND; ocr_q <= 1'b0; nb_valid <= 1'b0; end
        else begin
            ocr_q <= nb_cr;
            nb_valid <= 1'b0;
            if (ofire) begin ob_g <= pend_g[os]; ob_gam <= pend_gam[os]; ob_wait <= 4'(LANE_D + PLAT + 1); ob_b <= 4'd0; end
            else if (ob_wait != 4'd0) ob_wait <= ob_wait - 4'd1;
            if (ob_send) begin
                nb_valid <= 1'b1; nb_beat <= ob_b; nb_g <= ob_g; nb_gam <= ob_gam;
                nb_data <= ob_l[(LN*32/LFB)*ob_b +: LN*32/LFB];
                ob_b <= (ob_b == 4'(LFB - 1)) ? 4'd0 : ob_b + 4'd1;
            end
            ocred <= ocred - ((ob_send && ob_b == 4'd0) ? 1'b1 : 1'b0) + (ocr_q ? 1'b1 : 1'b0);
        end
    end

""" + s[j:]
    s = rep(s, """    wire        take;                                   // re-cut D: the local tree takes the leaf (below)
""", """    // re-cut E: the residue group's pairwise tree (levels 1-3) on the lane loops.  lvl[s]: the level of slot s's value.
    // A left slot l (level 0 even slots; level 1 slots 1, 5; level 2 slot 3) pairs with r = l + 1 / l + 2 / 7 when both
    // are final at the same level with the same (g, gam) and no pair window is open: xl at l's turn (l is freed), pr at
    // r's turn.  ol loads slot 7's level-3 value (the node) into the lanes' output words.
    reg  [1:0]  lvl [0:7];
    reg         x_open, ob_busy;
    reg  [2:0]  x_r;
    wire [1:0]  lv_os = lvl[os];
    wire        is_left = ((lv_os == 2'd0) && !os[0]) || ((lv_os == 2'd1) && (os[1:0] == 2'b01)) ||
                          ((lv_os == 2'd2) && (os == 3'd3));
    wire [2:0]  pr_s = (lv_os == 2'd0) ? os + 3'd1 : ((lv_os == 2'd1) ? os + 3'd2 : 3'd7);
    wire        xfire = is_left && pend[os] && arm[os] && pend[pr_s] && arm[pr_s] && (lvl[pr_s] == lv_os) &&
                        (pend_g[pr_s] == pend_g[os]) && (pend_gam[pr_s] == pend_gam[os]) && !x_open;
    wire        pfire = x_open && (os == x_r);
    wire        ofire = (os == 3'd7) && pend[os] && arm[os] && (lv_os == 2'd3) && !ob_busy;
    wire        take = xfire || ofire;
    wire [4*HD*32-1:0] ob_l;                            // the lanes' output words
""")
    s = rep(s, """ || mac_fault || lt_fault) fault <= 1'b1;""", """ || mac_fault) fault <= 1'b1;""")
    s = rep(s, """            if (v_issue && v_last_k) begin
                pend[cyc8] <= 1'b1; arm[cyc8] <= 1'b0; pend_g[cyc8] <= c_g; pend_gam[cyc8] <= c_gam[3:0];
            end
        end
    end
""", """            if (v_issue && v_last_k) begin
                pend[cyc8] <= 1'b1; arm[cyc8] <= 1'b0; pend_g[cyc8] <= c_g; pend_gam[cyc8] <= c_gam[3:0];
            end
            // re-cut E: pairs on the loops, the node's output load
            if (v_issue && v_last_k) lvl[cyc8] <= 2'd0;
            if (xfire) begin x_open <= 1'b1; x_r <= pr_s; end
            if (pfire) begin x_open <= 1'b0; lvl[x_r] <= lvl[x_r] + 2'd1; arm[x_r] <= 1'b0; end
            if (ofire) ob_busy <= 1'b1;
            if (ob_send && ob_b == 4'(LFB - 1)) ob_busy <= 1'b0;
        end
    end
""")
    s = rep(s, """            pend <= 8'd0; arm <= 8'd0; pend_g <= 8'd0; k_done <= 1'b0; v_done <= 1'b0; ev_k_first <= 1'b0; ev_v_first <= 1'b0;
""", """            pend <= 8'd0; arm <= 8'd0; pend_g <= 8'd0; k_done <= 1'b0; v_done <= 1'b0; ev_k_first <= 1'b0; ev_v_first <= 1'b0;
            x_open <= 1'b0; ob_busy <= 1'b0;
""")
    # ---- the pair / load controls to the lanes: their own S1 / S1b / S2 / S3 copies + the adder-control delay ----
    s = rep(s, """    always @(posedge clk) begin c1[0] <= c_g; row1 <= row; e1 <= e_word; end
""", """    always @(posedge clk) begin c1[0] <= c_g; row1 <= row; e1 <= e_word; end
    reg  [2:0]          x1;                           // re-cut E: {pr, xl, ol}
    always @(posedge clk or negedge rc) if (!rc) x1 <= 3'd0; else x1 <= {pfire, xfire, ofire};
    wire [3*2-1:0]      x1b;
    wire [3*4-1:0]      x2;
    wire [3*NG-1:0]     x3, xz_d;
""")
    s = rep(s, """    function automatic integer tbase(input integer lev);""", """    generate
        for (gg = 0; gg < 2; gg = gg + 1) begin : g_xs1b
            (* keep_hierarchy *) ot_nhb_repr_e #(.W(3)) u_x (.clk(clk), .rst_n(rhalf[gg]), .d(x1), .q(x1b[3*gg +: 3]));
        end
        for (gg = 0; gg < 4; gg = gg + 1) begin : g_xs2
            (* keep_hierarchy *) ot_nhb_repr_e #(.W(3)) u_x (.clk(clk), .rst_n(rhead[gg]), .d(x1b[3*(gg/2) +: 3]),
                                                           .q(x2[3*gg +: 3]));
        end
        for (gg = 0; gg < NG; gg = gg + 1) begin : g_xs3
            (* keep_hierarchy *) ot_nhb_repr_e #(.W(3)) u_x (.clk(clk), .rst_n(rgrp[gg]), .d(x2[3*(gg/GPH) +: 3]),
                                                           .q(x3[3*gg +: 3]));
            ot_hdc_delay #(.W(3), .D(PLAT), .RESET(1)) u_xctl (.clk(clk), .rst_n(rgrp[gg]), .d(x3[3*gg +: 3]),
                                                              .q(xz_d[3*gg +: 3]));
        end
    endgenerate
    function automatic integer tbase(input integer lev);""")
    s = rep(s, """                wire [31:0] vb = vd ? p_y[32*L +: 32] : 32'd0;""", """                wire [2:0]  xz = xz_d[3*G +: 3];               // re-cut E: {pr, xl, ol} at this lane
                reg  [31:0] xw, ow;
                always @(posedge clk) begin
                    if (xz[1]) xw <= fb[32*L +: 32];
                    if (xz[0]) ow <= fb[32*L +: 32];
                end
                assign ob_l[32*L +: 32] = ow;
                wire [31:0] vb = xz[2] ? xw : (vd ? p_y[32*L +: 32] : 32'd0);""")
    s = rep(s, """.valid_in(kt || vd),""", """.valid_in(kt || vd || xz[2]),""")
    return s


def main():
    txt = generate()
    if '--check' in sys.argv:
        sys.exit(0 if DST.exists() and DST.read_text() == txt else 1)
    DST.write_text(txt)
    print(DST)


if __name__ == '__main__':
    main()
