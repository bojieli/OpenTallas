#!/usr/bin/env python3
"""q13-kvleaves 2026-10-13: explicit pin plans (ref_tile "io_tcl") of the two KV-end tiles whose buses fan in / out
bit-wise: ot_qkvd_ke_tm (three TX buffer heads -> one tf0 word) and ot_qkvd_ke_rq (one FDI word -> four RX buffer copies).

Rule: all pins of word bit i sit in ONE narrow column (the bit's S pins two M5 tracks apart, its N pin straight above),
so nothing crosses the thin core sideways; the convergence / fan-out of the buses is the parent's (channel + M6 over
the buffers).  q16 gave each bus its own range: 528 bits x 75-300 um of horizontal wire in a 10-17 um core (cut 0.6-1.0;
tm q16b GRT-0116, rq q16 stuck in incremental global route).

The columns are ordered by the x of the bit's pin on the ot_qkvd_sbufp view (dout for tm, din for rq), so the buses
between a tile and the sbufp buffers are parallel (no crossing); the fbuf8p buses cross within their own span.
M5 tracks x = 0.012 + 0.048 k; the tile's own M5 power stripes (pairs at 2.40 / 2.592 + 5.4 n, 0.12 wide) are skipped.

    python3 tools/qwen_kv_die/ke_pins.py            (re)writes physical/ref_tile_specs/qkd_ke/qkd_ke_{tm,rq}_pins.tcl
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SBUFP = ROOT / "physical/ref_tile/qkd_sbufp_ref/views/ot_qkvd_sbufp/ot_qkvd_sbufp.lef"
OUT = ROOT / "physical/ref_tile_specs/qkd_ke"


def lef_x(bus):
    t = SBUFP.read_text()
    xs = {}
    for m in re.finditer(r"PIN " + bus + r"\[(\d+)\]\n(.*?)\n  END ", t, re.S):
        r = re.search(r"RECT\s+(\S+) (\S+) (\S+) (\S+)", m.group(2))
        xs[int(m.group(1))] = (float(r.group(1)) + float(r.group(3))) / 2
    assert len(xs) == 528, (bus, len(xs))
    return [i for i in sorted(xs, key=lambda i: xs[i])]


def blocked(k):
    x = 0.012 + 0.048 * k
    r = (x - 2.34) % 5.4
    return r <= 0.432 + 1e-9            # 2.34 .. 2.772: the stripe pair +- 0.06


def columns(width, n, span, gap):
    """n columns of `span` tracks (all clear of the power stripes), `gap` free tracks between columns"""
    k, last = int((3.0 - 0.012) / 0.048) + 1, int((width - 3.0 - 0.012) / 0.048)
    cols = []
    while len(cols) < n:
        if any(blocked(k + d) for d in range(span)):
            k += 1
            continue
        cols.append(k)
        k += span + gap
    assert cols[-1] + span <= last, f"pins do not fit: last track {cols[-1] + span} > {last}"
    return cols


def pin(name, layer, x, y):
    size = "{0.024 0.192}" if layer == "M5" else "{0.192 0.024}"
    return f"place_pin -pin_name {{{name}}} -layer {layer} -location {{{x:.3f} {y:.3f}}} -pin_size {size} -force_to_die_boundary"


def tx(k):
    return 0.012 + 0.048 * k


def tm():
    W, H = 237.6, 15.12
    order, cols = lef_x("dout"), columns(W, 528, 5, 3)
    out = ["# GENERATED by tools/qwen_kv_die/ke_pins.py (ot_qkvd_ke_tm 237.6 x 15.12): do not edit by hand",
           "# column c = word bit order[c] (sbufp dout x order): h0, h2, h1 on S two tracks apart, tw above the middle one"]
    for c, b in enumerate(order):
        k = cols[c]
        out += [pin(f"h0[{b}]", "M5", tx(k), 0.0), pin(f"h2[{b}]", "M5", tx(k + 2), 0.0), pin(f"h1[{b}]", "M5", tx(k + 4), 0.0),
                pin(f"tw[{b}]", "M5", tx(k + 2), H)]
    cm = next(c for c in range(264, 528) if cols[c] - cols[c - 1] == 8)    # a mid-tile column pair with no stripe between
    out.append(pin("clk", "M5", tx(cols[cm] - 2), H))           # N face, between two columns (4 tracks from either tw)
    for j, n in enumerate(["rst_n", "gq_i[0]", "gq_i[1]", "gq_i[2]"]):
        out.append(pin(n, "M4", 0.0, 0.012 + 0.048 * (70 + 40 * j)))
    return "\n".join(out) + "\n"


def rq():
    W, H = 280.8, 21.6
    order, cols = lef_x("din"), columns(W, 528, 7, 2)
    out = ["# GENERATED by tools/qwen_kv_die/ke_pins.py (ot_qkvd_ke_rq 280.8 x 21.6): do not edit by hand",
           "# column c = word bit order[c] (sbufp din x order): w1, w3, w0, w2 on S two tracks apart, rx_flit above"]
    for c, b in enumerate(order):
        k = cols[c]
        out += [pin(f"w1[{b}]", "M5", tx(k), 0.0), pin(f"w3[{b}]", "M5", tx(k + 2), 0.0), pin(f"w0[{b}]", "M5", tx(k + 4), 0.0),
                pin(f"w2[{b}]", "M5", tx(k + 6), 0.0), pin(f"rx_flit[{b}]", "M5", tx(k + 2), H)]
    # N face: header bits, rx_v, clock and reset between the word pins (4 tracks from the column's own N pin)
    hdr = [f"rx_flit[{528 + j}]" for j in range(20)] + ["rx_v"]
    for j, n in enumerate(hdr):
        out.append(pin(n, "M5", tx(cols[12 + 24 * j] + 6), H))
    out.append(pin("clk", "M5", tx(cols[264] + 6), H))          # mid-tile; the column's 4th S pin is on this track, the N face is free
    out.append(pin("rst_n", "M5", tx(cols[270] + 6), H))
    side = ["rqv"] + [f"rqh[{j}]" for j in range(20)] + [f"psh[{j}]" for j in range(4)]
    for j, n in enumerate(side):
        out.append(pin(n, "M4", 0.0, 0.012 + 0.048 * (64 + 14 * j)))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "qkd_ke_tm_pins.tcl").write_text(tm())
    (OUT / "qkd_ke_rq_pins.tcl").write_text(rq())
    print("wrote", OUT / "qkd_ke_tm_pins.tcl", OUT / "qkd_ke_rq_pins.tcl")
