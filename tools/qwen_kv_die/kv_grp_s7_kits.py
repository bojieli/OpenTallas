#!/usr/bin/env python3
"""KV-GRP7 10-20: s7 branch-slice kits for qkd_kvs_grp_s6c / qkd_kvs_grp_h_s6c (same RTL, +0 cycles).

s6 gates (all four) failed trial GRT at the NE ring stack: two 8-macro ring columns, the E one 31 um from a
99%-occupied E pin face, every W ring's 256-b read word crossing it to reach its E exit pins.  s7 replans the tile
as four horizontal BRANCH SLICES (data flow W -> E, one per PC branch b, matching the W i_pc<b> bands):
  W pins i_pc<b>  ->  row macro b (MY: rd_out on its E face)  ->  out_data flops  ->  ring b as two staggered
  4-macro stacks A (k0..3, low) / B (k4..7, high), MY  ->  exit flops at the E face  ->  E pins of branch b.
The E face pins are regrouped per branch (exact io_tcl): branch b's krsp and rsp data copies of macro k sit
together (bit-interleaved), slices bottom -> top b0..b3, the metadata/kreq/vreq block between b1 and b2.  So no
ring word crosses another ring column: ring A's read word passes ring B's column in B's low corridor, ring B's
write word passes ring A in A's high corridor.  The E strip right of the rings is macro-free (~149 um).
Branch map (netlist traced): results/rtl/qwen_kv_die/kvs_grp_s7_1020/branch_map.json.
Base pin coordinates: the s6a gates' 3_2_place_iop.tcl (legal tracks); E coordinates are re-used in sorted order,
W/E y scaled (and N moved) for a taller outline, snapped to the M4 track phase 0.012 + 0.048k.
usage: kv_grp_s7_kits.py <kit> <grp|grp_h> <height_um>
"""
import json, re, sys, copy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = "results/rtl/qwen_kv_die/kvs_grp_s7_1020"
ROW_W, ROW_H = 94.824, 80.472
RING_W, RING_H, RING_P = 19.656, 14.328, 14.352
G = 0.048


def snap(v, ph=0.0):
    return round(round((v - ph) / G) * G + ph, 3)


def io_tcl(tile, H):
    base = (ROOT / RES / f"base_iop_qkd_kvs_{tile}_s6a.tcl").read_text().splitlines()
    pins = []
    for l in base:
        m = re.search(r"-pin_name (\S+) -layer (\S+) -location \{(\S+) (\S+)\}", l)
        if m.group(1) in ("VDD", "VSS"):
            continue  # PG pins: made by the kit PDN (PPL-0061 at floorplan if placed here)
        pins.append([m.group(1), m.group(2), float(m.group(3)), float(m.group(4))])
    s = (H - 4.32) / (388.8 - 4.32)
    ys = lambda y: snap(2.16 + (y - 2.16) * s, 0.012) if H != 388.8 else y
    face = lambda p: "W" if p[2] < 1 else "E" if p[2] > 388 else "S" if p[3] < 1 else "N"
    E = [p for p in pins if face(p) == "E"]
    names = {p[0] for p in E}
    order = []
    def data(b):
        for k in range(8):
            for i in range(32):
                order.extend([f"krsp[{1 + 256 * b + 32 * k + i}]", f"rsp[{32 + 256 * b + 32 * k + i}]"])
    data(0); data(1)
    order += [n for n in sorted(names, key=lambda n: (n.split("[")[0], int(n.split("[")[1][:-1]) if "[" in n else 0))
              if n.startswith("kreq")]
    order += ["krsp[0]"] + [f"krsp[{i}]" for i in range(1025, 1062)] + [f"rsp[{i}]" for i in range(32)]
    order += [n for n in sorted(names, key=lambda n: int(n.split("[")[1][:-1]) if "[" in n else 0) if n.startswith("vreq")]
    data(2); data(3)
    assert len(order) == len(set(order)) == len(names) and set(order) == names, (len(order), len(names))
    ey = sorted(p[3] for p in E)
    out = []
    for p in pins:
        f = face(p)
        if f == "W":
            out.append((p[0], p[1], p[2], ys(p[3])))
        elif f == "N":
            out.append((p[0], p[1], p[2], round(H - 0.042, 3)))
        elif f == "S":
            out.append(tuple(p))
    ex = round(388.8 - 0.042, 3)
    for n, y in zip(order, ey):
        out.append((n, "M4", ex, ys(y)))
    hdr = (f"# KV-GRP7 s7 branch-slice pins for qkd_kvs_{tile} ({388.8} x {H}): generated by tools/qwen_kv_die/kv_grp_s7_kits.py\n"
           f"# from {RES}/base_iop_qkd_kvs_{tile}_s6a.tcl; E face regrouped per branch (krsp/rsp copies interleaved).\n")
    return hdr + "".join(f"place_pin -pin_name {n} -layer {l} -location {{{x:g} {y:g}}}\n" for n, l, x, y in out)


def macros(tile, H, view_row, view_ring):
    bm = json.loads((ROOT / RES / "branch_map.json").read_text())[tile]
    # >= 20 um macro edge to the N/S pin faces and >= 20 um channels (ref_tile rules).  388.8: rows abut N-S in two
    # pairs (b0+b1, b2+b3; row macros have no N/S pins: abutted_stack) with one ~22.5 um middle corridor; 432: four
    # separate rows with ~21.9 um corridors.
    lo, hi = 2.16 + 20.0, H - 2.16 - 20.0
    if H < 400:
        y0 = -(-lo // G) * G
        y3 = (hi - ROW_H) // G * G
        ys = [y0, y0 + 0.024 + ROW_H, y3 - 0.024 - ROW_H, y3]
        g = ys[2] - (ys[1] + ROW_H)
    else:
        g = (hi - 0.1 - lo - 4 * ROW_H) / 3
        ys = [-(-(lo + b * (ROW_H + g)) // G) * G for b in range(4)]
    out = []
    for b in range(4):
        ry = round(ys[b], 3)
        out.append({"view": view_row, "count": 1, "inst": f"*{bm['rows'][str(b)]}?u_cell", "at": [43.2, ry],
                    "orient": "MY", "at_exact": True})
        for k, inst in enumerate(bm["rings"][str(b)]):
            if k < 4:
                x, y = 168.048, ry + k * RING_P
            else:
                x, y = 217.728, ry + 23.04 + (k - 4) * RING_P
            out.append({"view": view_ring, "count": 1, "inst": f"*{inst}?u_cell", "at": [x, round(y, 3)],
                        "orient": "MY", "at_exact": True})
    return out, g


def main():
    kit, tile, H = sys.argv[1], sys.argv[2], float(sys.argv[3])
    src = json.loads((ROOT / f"physical/ref_tile/qkd_kvs_{tile}_s6a/spec.json").read_text())
    s = copy.deepcopy(src)
    vr = [m["view"] for m in src["macros"] if "128x256" in m["view"]][0]
    vg = [m["view"] for m in src["macros"] if "4x32" in m["view"]][0]
    s["name"] = kit
    s["outline"] = {"w": 388.8, "h": H, "exact": True}
    s["macros"], g = macros(tile, H, vr, vg)
    s.pop("pin_ranges", None)
    s.pop("pin_order_desc", None)
    s["route"].pop("pin_balance", None)
    io = f"physical/qkd_kvs_kits/{kit}_io.tcl"
    (ROOT / io).write_text(io_tcl(tile, H))
    s["io_tcl"] = io
    if "kits_b" in s:
        s["kits_b"]["frame"] = [388.8, H]
        s["kits_b"]["kit_outline"] = [388.8, H]
    s["job"]["owner"] = "Claude:KV-GRP7"
    s["job"]["branch"] = "claude/kv-grp7-1020"
    s["job"]["tag"] = kit.replace("qkd_kvs_", "")
    why = (f"KV-GRP7 s7 branch slices ({388.8} x {H}): four W->E PC-branch slices (row macro MY rd_out E -> two staggered "
           f"4-macro ring stacks A/B MY -> exit flops at E pins), E pins regrouped per branch by exact io_tcl; "
           f"no ring column in front of the E face, no ring word crosses another ring column; row gap {g:.1f} um.")
    s["purpose"] = f"KV-GRP7 10-20: {why} Same RTL/netlist as s6 ({src['top']}), +0 cycles."
    s["structural_change"] = why + " s6 (all four gates) failed trial GRT at the NE ring stack in front of the 99%-pinned E face."
    s["reroute_reason"] = {"kind": "floorplan_change", "reason": "s6 gates FAIL trial GRT 323/280/128/111 (NE ring stack 31 um "
                           "from the 99%-pinned E face; W ring words crossing it). " + why}
    s["fill_reason"] = {"pin_bound": f"4.6k signal pins on 388.8 x {H}; E face pins regrouped per branch; outline = die slot"
                        + (" grown to 388.8 x 432 (ROOT model)" if H > 400 else " (unchanged)")}
    kd = ROOT / f"physical/ref_tile/{kit}"
    kd.mkdir(parents=True, exist_ok=True)
    (kd / "spec.json").write_text(json.dumps(s, indent=1) + "\n")
    print(f"{kit}: {tile} H={H} row gap {g:.2f}; io {io}")


if __name__ == "__main__":
    main()
