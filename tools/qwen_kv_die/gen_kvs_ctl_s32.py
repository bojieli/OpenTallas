#!/usr/bin/env python3
"""KV-CTL3 10-20: generate qkd_kvs_ctl_s32 (the native-census form of the KV control tile) from the generated wires-only
parent qkd_kvs_ctl in rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_tiles_hroot_ff_k_mu.sv (kv_static_die.py --rtl output).

Same ports, same wiring; only the member instances change to their S32 successors (new modules, the shared originals stay
byte-identical):
  u_fanr  qkd_kv_es_fan_root2_b            -> qkd_kv_es_fan_root2_b_s32 (S32 1, RCOPIES 32, PH1C 1)     qkd_kv_ctl_s32_misc.sv
  u_lprg  qkd_static_kv_layer_programme_mus -> qkd_static_kv_layer_programme_s32 (RCOPIES 32)          (mu_qwen_20261018)
  u_wprg  qkd_kv_native_programme          -> qkd_kv_native_programme_s32 (NC 4, RCOPIES 20)            qkd_kv_ctl_s32_writer.sv
  u_wrn   qkd_kv_static_writer_native_mu   -> qkd_kv_static_writer_native_mu_s32 (NC 4, RST_COPIES 12)  qkd_kv_ctl_s32_writer.sv
          + the programme's kept word slot / index copies (w_wprg__compiled_word_slot_c / _index_c, tile-internal)
  u_dcfg  qkd_kv_die_cfg                   -> qkd_kv_die_cfg_s32 (S32 1, PCOPIES 1)                     qkd_kv_ctl_s32_misc.sv
  u_own   qkd_static_kv_ownership_calendar_mu -> _s32 (S32 1)                                            qkd_kv_ctl_s32_misc.sv
  u_boot  qkd_static_kv_boot_dispatch_mu   -> qkd_static_kv_boot_dispatch_mu_s32                          qkd_kv_ctl_s32_boot.sv
Every substitution must apply exactly once (refuses otherwise).  --boot-orig keeps the original dispatcher (interim).
  python3 tools/qwen_kv_die/gen_kvs_ctl_s32.py [--root .] [--boot-orig] [--out rtl/.../qkd_kvs_ctl_s32.sv]
"""
import argparse, hashlib, re, sys
from pathlib import Path

SRC = "rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_tiles_hroot_ff_k_mu.sv"
OUT = "rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_ctl_s32.sv"
SUBS = [
    ("module qkd_kvs_ctl #(parameter integer CTLSRAM = 1) (", "module qkd_kvs_ctl_s32 #(parameter integer CTLSRAM = 1) ("),
    ("qkd_kv_es_fan_root2_b #(.MUT(0), .RCOPIES(28), .PH1C(1)) u_fanr",
     "qkd_kv_es_fan_root2_b_s32 #(.MUT(0), .RCOPIES(32), .PH1C(1), .S32(1)) u_fanr"),
    ("qkd_static_kv_layer_programme_mus #(.MUT(0), .MU(1), .CTLSRAM(CTLSRAM), .RCOPIES(32)) u_lprg",
     "qkd_static_kv_layer_programme_s32 #(.MUT(0), .MU(1), .CTLSRAM(CTLSRAM), .RCOPIES(32)) u_lprg"),
    ("qkd_kv_native_programme #(.MUT(0), .VMAP(1), .RCOPIES(16), .SRAM(1), .CTLSRAM(CTLSRAM)) u_wprg (",
     "qkd_kv_native_programme_s32 #(.MUT(0), .VMAP(1), .RCOPIES(20), .SRAM(1), .CTLSRAM(CTLSRAM), .NC(4)) u_wprg "
     "(.compiled_word_slot_c(w_wprg__compiled_word_slot_c), .compiled_word_index_c(w_wprg__compiled_word_index_c), "),
    ("qkd_kv_static_writer_native_mu #(.MUT(0), .VMAP(1), .MU(1), .RST_COPIES(10)) u_wrn (",
     "qkd_kv_static_writer_native_mu_s32 #(.MUT(0), .VMAP(1), .MU(1), .NC(4), .RST_COPIES(12)) u_wrn "
     "(.compiled_word_slot_c(w_wprg__compiled_word_slot_c), .compiled_word_index_c(w_wprg__compiled_word_index_c), "),
    ("    wire [0:0] w_wprg__compiled_word_slot;\n",
     "    wire [0:0] w_wprg__compiled_word_slot;\n    wire [3:0] w_wprg__compiled_word_slot_c;\n    wire [7:0] w_wprg__compiled_word_index_c;\n"),
    ("qkd_kv_die_cfg #(.NRST(43), .CAP(1), .MUT(0), .PCOPIES(8)) u_dcfg",
     "qkd_kv_die_cfg_s32 #(.NRST(43), .CAP(1), .MUT(0), .PCOPIES(1), .S32(1)) u_dcfg"),
    ("qkd_static_kv_ownership_calendar_mu #(.MUT(0), .MU(1), .PIPE(1), .SAFE(1), .RCOPIES(12)) u_own",
     "qkd_static_kv_ownership_calendar_mu_s32 #(.MUT(0), .MU(1), .PIPE(1), .SAFE(1), .RCOPIES(12), .S32(1)) u_own"),
]
BOOT = ("qkd_static_kv_boot_dispatch_mu #(", "qkd_static_kv_boot_dispatch_mu_s32 #(")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--boot-orig", action="store_true")
    a = ap.parse_args()
    root = Path(a.root)
    text = (root / SRC).read_text()
    m = re.search(r"^module qkd_kvs_ctl #.*?^endmodule\n", text, re.S | re.M)
    if not m:
        sys.exit("gen_kvs_ctl_s32: module qkd_kvs_ctl not found in " + SRC)
    body = m.group(0)
    subs = SUBS + ([] if a.boot_orig else [BOOT])
    for old, new in subs:
        n = body.count(old)
        if n != 1:
            sys.exit(f"gen_kvs_ctl_s32: substitution applies {n} times (need 1): {old[:80]}")
        body = body.replace(old, new)
    sha = hashlib.sha256(text.encode()).hexdigest()
    hdr = ("`timescale 1ns/1ps\n"
           "// GENERATED by tools/qwen_kv_die/gen_kvs_ctl_s32.py from " + SRC + " (sha256 " + sha[:16] + ")" +
           (" --boot-orig" if a.boot_orig else "") + "; do not edit.\n"
           "// qkd_kvs_ctl_s32 = qkd_kvs_ctl (same ports and wiring) with the native-census S32 member successors\n"
           "// (no driver > 32 mapped loads; 0 added edges; lockstep benches rtl/test/mu_qwen_1018/run_kv_ctl_s32_*.sh).\n")
    (root / a.out).write_text(hdr + body)
    print("GEN_KVS_CTL_S32 wrote", a.out, "boot", "orig" if a.boot_orig else "s32")


if __name__ == "__main__":
    main()
