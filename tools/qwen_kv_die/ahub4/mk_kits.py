def tcl_table(kit, v, pfx):
    rows = []
    for reg, boxes in v["fences"].items():
        b = " ".join("{" + " ".join(f"{x:g}" for x in bx) + "}" for bx in boxes)
        rows.append(f"  {reg} {{{b}}} {{{' '.join(pfx[reg])}}}")
    return FENCE_TCL.format(kit=kit, rec=REC, table="\n".join(rows))


