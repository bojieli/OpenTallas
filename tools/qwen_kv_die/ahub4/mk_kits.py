def main():
    pfx = prefixes()
    for kit, v in VARIANTS.items():
        d = ROOT / "physical/ref_tile" / kit
        d.mkdir(parents=True, exist_ok=True)
        (d / "spec.json").write_text(json.dumps(spec(kit, v), indent=1) + "\n")
        (d / "lp_fences.tcl").write_text(tcl_table(kit, v, pfx))
        (d / "lp_fences_release.tcl").write_text(RELEASE_TCL.format(kit=kit))
        print("wrote", d)


