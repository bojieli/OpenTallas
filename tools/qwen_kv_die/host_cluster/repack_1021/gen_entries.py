#!/usr/bin/env python3
"""KV-HROOT10 10-20: qkd_hr_cluster_e = qkd_hr_cluster with ONE clock entry port per hard-child clock pin (the ref_tile
'entries' cluster contract: the die / region tree drives every child clock pin directly; the parent has no clock cells).
Pure text transform of the generated cluster: each child connection .<pin>(ck_<fam>) becomes .<pin>(ck_<fam>__<inst>),
a new input; the family ports ck_core / ck_host / ck_ingest / ck_phy_fam disappear (ck_phy[7:0] were already per adp).
Tying every ck_<fam>__* of a family to ck_<fam> (wrapper qkd_hr_cluster_e_tied in the same file) is the original."""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
t = open(src).read()
start = t.index('module qkd_hr_cluster(')
body = t[start:]
fams = ('ck_core', 'ck_host', 'ck_ingest', 'ck_phy_fam')
new_ports = []
out_lines = []
cur = None
for line in body.split('\n'):
    m = re.match(r'\s*(\w+)\s*(#\(.*\))?\s+(\w+)\s*\($', line)
    if m and m.group(1) not in ('module',):
        cur = m.group(3)
    m2 = re.match(r'(\s*\.\w+\()(ck_core|ck_host|ck_ingest|ck_phy_fam)(\),?)$', line)
    if m2 and cur:
        short = cur.replace('u_rank__u_', '').replace('u_', '', 1).replace('__', '_')
        n = f'{m2.group(2)}__{short}'
        new_ports.append((m2.group(2), n))
        line = m2.group(1) + n + m2.group(3)
    out_lines.append(line)
b = '\n'.join(out_lines)
hdr_end = b.index(');')
hdr = b[:hdr_end]
for f in fams:
    hdr = re.sub(rf'\b{f}\b,\s*', '', hdr, count=1)
hdr = hdr.replace('module qkd_hr_cluster(', 'module qkd_hr_cluster_e(' + ', '.join(n for _, n in new_ports) + ', ')
rest = b[hdr_end:]
for f in fams:
    rest = re.sub(rf'\n\s*input {f};\n\s*wire {f};', '', rest, count=1)
decl = ''.join(f'\n  input {n};\n  wire {n};' for _, n in new_ports)
rest = rest.replace(');', ');' + decl, 1)
e = t[:start] + hdr + rest
# tied wrapper (reference / equivalence): same ports as qkd_hr_cluster
orig_hdr = t[start:t.index(');', start) + 2]
ports = re.findall(r'\b(\w+)\b', orig_hdr[len('module qkd_hr_cluster('):-2])
conns = [f'.{p}({p})' for p in ports if p not in fams] + [f'.{n}({f})' for f, n in new_ports]
w = ('\n// tie-back reference: every per-child entry of a family driven by the family port == the original qkd_hr_cluster\n'
     + orig_hdr.replace('module qkd_hr_cluster(', 'module qkd_hr_cluster_e_tied(') + '\n')
decls = re.findall(r'^  (input|output)\s*(\[[^\]]*\])?\s*(\w+);', t[start:], re.M)
for d, wd, n in decls:
    w += f'  {d} {wd + " " if wd else ""}{n};\n'
w += '  qkd_hr_cluster_e u_e (\n    ' + ',\n    '.join(conns) + '\n  );\nendmodule\n'
open(dst, 'w').write('// GENERATED by KV-HROOT10 tools/qwen_kv_die/host_cluster/repack_1020/gen_entries.py from\n// rtl/qwen_sys/host_cluster_20261017/qkd_hr_cluster.v; do not edit.\n' + e.rstrip() + '\n' + w)
print(len(new_ports), 'per-child entries:', [n for _, n in new_ports])
# hard-child parameter overrides only outside the hard build (the views ARE the hardened configs: rx_rr kit params
# MUT 0 / STRAPPED 1 / IR_REPL 1, adp128 / pad5 MUT 0 = defaults)
t = open(dst).read()
t = re.sub(r'^  (\w+) (#\(.*?\))\s+(\w+)\s+\($', r'`ifdef OT_HR_CLUSTER_HARD\n  \1 \3 (\n`else\n  \1 \2 \3 (\n`endif', t, flags=re.M)
open(dst, 'w').write(t)
