#!/usr/bin/env python3
"""HKV-PROMPT6 (10-19): timing forks for the HOST cluster child qkd_hr_core_prompt (routed p5-0a8742a18 NEEDS_RTL).

Routed p5 sign-off STA (TT setup / FF hold, signoff.sdc) classified: no reset-pin path among the violators; TT
 (a) u_prompt.u_m.u_core.lane_capture -> 8:1 slot mux -> SECDED decode -> u_prompt.u_m.q (18 endpoints, -131.7 ps;
     fault -49.9): lane select sat IN FRONT of the 24-bit syndrome/correction tree;
 (b) u_host.u_m.u_core.inflight -> 64-bit c_busy ripple increment (16 OR levels) -> c_busy[63] (-34.9 ps).
Both are fixed bit- and cycle-exactly (no latency change):
 (a) ot_qfd_prompt_sram_capture_pd: the eight 24-bit slots of rd_capture are decoded in parallel and the lane selects the
     decoded {ue, data}; decode(sel(x)) == sel(decode(x)) for every x and lane.
 (b) ot_host_if_pb2_observed_pd: c_cycles / c_busy are ot_hkv_cnt_la (64-bit, low 32 with a registered all-ones flag).
Renamed copies whose ONLY edits are listed above / the instance types; the original files are untouched (other closed
tiles bind them).  The rr wrappers of gen_prompt_rr.py instantiate the _pd members (INNER map there).

QKD_HR_PD_MUTANT (bench only): the parallel decode selects slot lane^1.

usage: gen_prompt_pd.py [--check]      (writes rtl/qwen_sys/host_cluster_20261017/prompt_pd/*_pd.sv)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'rtl/qwen_sys/host_cluster_20261017/prompt_pd'
HDR = '// GENERATED by tools/qwen_kv_die/host_cluster/gen_prompt_pd.py (HKV-PROMPT6 10-19) -- do not edit.\n'


def sub1(t, old, new, what):
    n = t.count(old)
    assert n == 1, (what, n)
    return t.replace(old, new)


def rename(t, mod):
    u, n = re.subn(r'(\bmodule\s+)' + mod + r'\b', r'\g<1>' + mod + '_pd', t, count=1)
    assert n == 1, mod
    return u


def sram_capture():
    src = 'rtl/physical/ot_qfd_prompt_sram_capture.sv'
    t = rename((ROOT / src).read_text(), 'ot_qfd_prompt_sram_capture')
    t = sub1(t, ' wire [18:0] dec=decode(rd_capture[lane_capture*32+:24]);\n',
             ' // HKV-PROMPT6: decode the eight slots in parallel, then select the decoded word (same function, the lane\n'
             ' // select no longer precedes the syndrome/correction tree).\n'
             ' wire [18:0] dec_s [0:7];\n'
             ' generate for(g=0;g<8;g=g+1) begin:g_dec\n'
             '  assign dec_s[g]=decode(rd_capture[g*32+:24]);\n'
             ' end endgenerate\n'
             '`ifdef QKD_HR_PD_MUTANT\n'
             ' wire [18:0] dec=dec_s[lane_capture^3\'d1];\n'
             '`else\n'
             ' wire [18:0] dec=dec_s[lane_capture];\n'
             '`endif\n', 'dec')
    return HDR + f'// {src} renamed _pd; only edit: parallel per-slot SECDED decode before the lane select.\n' + t


def capture_pins():
    src = 'rtl/physical/ot_qkd_host_prompt_capture_pins.sv'
    t = rename((ROOT / src).read_text(), 'qkd_host_prompt_capture_pins')
    t = sub1(t, ' ot_qfd_prompt_sram_capture #(', ' ot_qfd_prompt_sram_capture_pd #(', 'core type')
    return HDR + f'// {src} renamed _pd; only edit: u_core type ot_qfd_prompt_sram_capture_pd.\n' + t


def if_pins():
    src = 'rtl/qwen_sys/host_integrated_20261014/qkd_host_if_pins_observed.sv'
    t = rename((ROOT / src).read_text(), 'qkd_host_if_pins_observed')
    t = sub1(t, '\not_host_if_pb2_observed #(', '\not_host_if_pb2_observed_pd #(', 'core type')
    return HDR + f'// {src} renamed _pd; only edit: u_core type ot_host_if_pb2_observed_pd.\n' + t


def pb2():
    src = 'rtl/qwen_sys/host_integrated_20261014/ot_host_if_pb2_observed.sv'
    t = rename((ROOT / src).read_text(), 'ot_host_if_pb2_observed')
    t = sub1(t, '    reg [63:0]   c_cycles, c_busy;\n', '    wire [63:0]  c_cycles, c_busy;   // HKV-PROMPT6: ot_hkv_cnt_la below\n', 'decl')
    t = sub1(t, '            c_cycles <= 0; c_busy <= 0; c_tokens <= 0;', '            c_tokens <= 0;', 'reset')
    t = sub1(t, '            if (enable) c_cycles <= c_cycles + 1\'b1;\n'
                '            if (inflight || b_st == B_RUN) c_busy <= c_busy + 1\'b1;\n', '', 'incr')
    t = sub1(t, '    integer j;\n    always @(posedge clk or negedge rst_n) begin\n',
             '    // HKV-PROMPT6: the two 64-bit counters with a registered low-half carry lookahead (same values every edge)\n'
             '    ot_hkv_cnt_la #(.W(64),.LO(32)) u_c_cycles(.clk(clk),.rst_n(rst_n),.en(enable),.q(c_cycles));\n'
             '    ot_hkv_cnt_la #(.W(64),.LO(32)) u_c_busy(.clk(clk),.rst_n(rst_n),.en(inflight || b_st == B_RUN),.q(c_busy));\n'
             '    integer j;\n    always @(posedge clk or negedge rst_n) begin\n', 'inst')
    return HDR + f'// {src} renamed _pd; only edits: c_cycles / c_busy are ot_hkv_cnt_la instances (were 64-bit ripple\n' \
                 '// increments in the main always block); reset/increment lines moved into the counter.\n' + t


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    files = {OUT / 'ot_qfd_prompt_sram_capture_pd.sv': sram_capture(),
             OUT / 'qkd_host_prompt_capture_pins_pd.sv': capture_pins(),
             OUT / 'qkd_host_if_pins_observed_pd.sv': if_pins(),
             OUT / 'ot_host_if_pb2_observed_pd.sv': pb2()}
    bad = 0
    for f, txt in files.items():
        if '--check' in sys.argv:
            if not f.exists() or f.read_text() != txt:
                print(f'STALE {f.relative_to(ROOT)}')
                bad += 1
        else:
            f.write_text(txt)
            print(f'wrote {f.relative_to(ROOT)}')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
