#!/usr/bin/env python3
"""HKV-PROMPT6 (10-19): timing fork for the HOST cluster child qkd_hr_core_peer (routed r3-40d82161e NEEDS_RTL TT -174.78).

Routed r3 sign-off STA (TT setup, signoff.sdc): every violating endpoint (400 listed, worst -174.8) starts at the RX
queue read pointer u_rank__u_control__packet__u_ctrl.u_m.rp of qkd_host_ctrl_token_service_packet_collected and ends in
tk8 / kst8: rp -> 512-bit 4:1 head mux h=q[rp] (rp buffer tree ~135 ps) -> wide zero tests h[511:K]==0 (6 OR5 levels,
~245 ps) -> accept conditions -> one write enable fanned out to 744 tk8 flops.  No reset-pin path.

Fix (bit- and cycle-exact, 0 cycles): the queue head is a REGISTER.  h <= the entry rp addresses AFTER the edge
(rp_n = take ? rp+1 : rp), forwarding a same-edge write into that entry; the six wide zero tests are computed when an
entry is written (from rd) and carried with the head (hz).  h == q[rp] whenever count != 0, and every use of h / src /
rs / hdr / sequence_ok is gated by take (count != 0), so every output is unchanged on every edge.

QKD_HR_PEPD_MUTANT (bench only): the same-edge write forwarding is dropped (head stale after a write into an empty queue).

KV-PEER5 (10-19, SAFE-AUDIT-KV r5, gate rtl WARN runtime_partselect tk8[role*93+:93]): every runtime-indexed part-select
WRITE X[role*W+:W] / X[src*W+:W] (tk8, kst8, boot8, service_epoch8, seq_rx) becomes a constant-index decode
`for(k=0..7) if(idx==k) X[k*W+:W]<=E;` (one-hot compare + per-slice enable, no $shift / $shiftx); statement order and
therefore the last-assignment-wins priority are unchanged.  Bit- and cycle-exact (same bench, peer_pd_equiv.sh).

usage: gen_peer_pd.py [--check]      (writes rtl/qwen_sys/host_cluster_20261017/peer_pd/*_pd.sv)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'rtl/qwen_sys/host_cluster_20261017/peer_pd'
SRC = 'rtl/qwen_sys/host_integrated_20261014/qkd_host_ctrl_token_service_packet_collected.sv'
MOD = 'qkd_host_ctrl_token_service_packet_collected'
ZK = [64, 65, 153, 170, 230, 263]   # hz[i] == (h[511:ZK[i]] == 0)


def sub1(t, old, new, what, n=1):
    k = t.count(old)
    assert k == n, (what, k)
    return t.replace(old, new)


def fork():
    t = (ROOT / SRC).read_text()
    t = sub1(t, f'module {MOD} #(', f'module {MOD}_pd #(', 'module')
    rz = ','.join(f'rd[511:{k}]==0' for k in reversed(ZK))
    t = sub1(t, ' wire[511:0]h=q[rp];',
             ' // HKV-PROMPT6: registered queue head (== q[rp] whenever count != 0) + its wide zero tests (hz)\n'
             ' reg[511:0]h;reg[5:0]hz;reg[5:0]qz[0:3];\n'
             ' wire[1:0]rp_n=take?rp+2\'d1:rp;wire q_wr=rv&&count<4;\n'
             f' wire[5:0]rz={{{rz}}};\n'
             '`ifdef QKD_HR_PEPD_MUTANT\n'
             ' wire h_fwd=1\'b0;\n'
             '`else\n'
             ' wire h_fwd=q_wr&&wp==rp_n;\n'
             '`endif\n'
             ' always @(posedge ck)begin if(q_wr)qz[wp]<=rz;h<=h_fwd?rd:q[rp_n];hz<=h_fwd?rz:qz[rp_n];end\n', 'head')
    for i, k in enumerate(ZK):
        n = t.count(f'h[511:{k}]==0')
        assert n >= 1, k
        t = t.replace(f'h[511:{k}]==0', f'hz[{i}]')
    assert 'rd[511:' in t
    # KV-PEER5: constant-index slice writes (one-hot decode) in place of runtime part-select writes
    n0 = len(re.findall(r'\b\w+\[(?:role|src)\*\d+\+:\d+\]<=', t))
    t, n = re.subn(r'\b(\w+)\[(role|src)\*(\d+)\+:(\d+)\]<=([^;]+);',
                   lambda m: (f"begin for(integer kq_{m.group(1)}=0;kq_{m.group(1)}<8;kq_{m.group(1)}=kq_{m.group(1)}+1)"
                              f"if({m.group(2)}==3'(kq_{m.group(1)})){m.group(1)}[kq_{m.group(1)}*{m.group(3)}+:{m.group(4)}]<={m.group(5)}; end "),
                   t)
    assert n == n0 == 13, (n, n0)
    hdr = ('// GENERATED by tools/qwen_kv_die/host_cluster/gen_peer_pd.py (HKV-PROMPT6 10-19) -- do not edit.\n'
           f'// {SRC} renamed {MOD}_pd; only edits: registered queue head h (+ same-edge write forwarding) and the\n'
           '// h[511:K]==0 tests read from flags computed at queue write (hz); KV-PEER5: runtime part-select writes\n'
           '// X[role|src*W+:W] as constant-index one-hot slice writes.  Same outputs every edge.\n')
    return hdr + t


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    f, txt = OUT / f'{MOD}_pd.sv', fork()
    if '--check' in sys.argv:
        ok = f.exists() and f.read_text() == txt
        print('OK' if ok else f'STALE {f.relative_to(ROOT)}')
        sys.exit(0 if ok else 1)
    f.write_text(txt)
    print(f'wrote {f.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
