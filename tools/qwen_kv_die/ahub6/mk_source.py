#!/usr/bin/env python3
"""AHUB6 private structural source: narrow landing writers, preserve D/K/edges.
Not gate-admitted: complete native census/control fixes are mandatory.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[3]
src=ROOT/'rtl/hdc/nearhbm/lp/qkd_ahub_static_dw_g3_lp.sv'
dst=src.with_name('qkd_ahub_static_dw_g6_lp.sv')
s=src.read_text()
assert s.count('module qkd_ahub_static_dw_g3_lp #(')==1
assert s.count('.CHUNK_BITS(8)')==30
s=s.replace('module qkd_ahub_static_dw_g3_lp #(', 'module qkd_ahub_static_dw_g6_lp #(')
s=s.replace('.CHUNK_BITS(8)', '.CHUNK_BITS(2)').replace('+8-1)/8', '+2-1)/2')
# Seven same-edge root copies avoid one root driving the sum of all regional
# branch counts. The primary reset pin sees seven D pins, each copy <=32.
old="wire lpr_root;  ot_pl_pad #(.W(1), .N(1)) u_lpr_root (.ck(ck_c), .d(rst_n), .q(lpr_root));"
new="wire [6:0] lpr_root_region;\n    for(genvar r=0;r<7;r=r+1) begin:g_lpr_root\n        (* keep_hierarchy=\"yes\" *) ot_pl_land_field_copy_bit #(.ID(8192+r)) u_ff (.ck(ck_c),.d(rst_n),.q(lpr_root_region[r]));\n    end"
assert s.count(old)==1
s=s.replace(old,new)
regions=('c','w','e','z0','z1','z2','z3')
for i,r in enumerate(regions):
 pattern=r'ot_pl_land_reset_forest #\(\.DEPTH\(2\), \.LEAVES\(LPR_LEAVES_'+r+r'\), \.ROOT_LOADS\(.*?\)\) u_lpr_'+r+r' \([^;]+;'
 m=re.search(pattern,s)
 assert m, r
 oldline=m.group(0)
 newline=oldline[:oldline.index('.ROOT_LOADS(')]+'.ROOT_LOADS((LPR_LEAVES_'+r+'+31)/32)) u_lpr_'+r+' (.ck(ck_'+r+'), .d(lpr_root_region['+str(i)+']), .q(lpr_'+r+'_leaves));'
 s=s[:m.start()]+newline+s[m.end():]

assert '.CHUNK_BITS(8)' not in s and '+8-1)/8' not in s
s='// AHUB6 private derivative generated by tools/qwen_kv_die/ahub6/mk_source.py.\n// CHUNK2; reset leaf dimensions and slices change together. D4/K2 and all edges unchanged.\n// NOT GATE ADMITTED until full native control/reset/comb census passes.\n'+s
dst.write_text(s)
print(dst)
