#!/usr/bin/env python3
"""KV-AHUB7 10-20 (tree K.STA.AHUB): re-point the AHUB6 g6a/g6b kits at the CANONICAL lp.py parent.

The landed parent rtl/hdc/nearhbm/lp/qkd_ahub_static_dw_g6_lp.sv is generated by tools/landed_parent/lp.py from
tools/qwen_kv_die/ahub7/lp_spec.json (flat rtl/hdc/nearhbm/qkd_ahub_static_dw_g6.sv): CHUNK2 landings,
landing_reset_root_copies (one kept same-edge root copy per region), child_reset_copies (u_io reset group = one run
whose last stage is 4 kept copies).  Its record says generator tools/landed_parent/lp.py, so the gate's normal
landed-record check applies; the codex derived-record helper (Gate-Rule relaxing) is NOT used.
Run: python3 tools/landed_parent/lp.py gen tools/qwen_kv_die/ahub7/lp_spec.json; python3 tools/qwen_kv_die/ahub7/mk_kits.py;
then python3 tools/ref_tile/ref_tile.py gen physical/ref_tile/qkd_ahub_g6{a,b}/spec.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RECORD = 'results/arch/kv_ahub7_1020/lp/qkd_ahub_static_dw_g6_lp_record.json'
REGIONS = ('c', 'w', 'e', 'z0', 'z1', 'z2', 'z3')


def main():
    rec = json.loads((ROOT / RECORD).read_text())
    assert rec['generator'] == 'tools/landed_parent/lp.py' and rec['top'] == 'qkd_ahub_static_dw_g6_lp'
    assert rec['reset']['same_depth_forest']['regional_root_copies'] == 7
    for suffix in ('a', 'b'):
        name = 'qkd_ahub_g6' + suffix
        d = ROOT / 'physical/ref_tile' / name
        s = json.loads((d / 'spec.json').read_text())
        s['landed_record'] = RECORD
        s['reset_landing']['reason'] = (
            'the lp.py RTL lands it: rst_n -> u_lpr_root_<region> (7 kept same-edge copies, 1 stage, ck_c; rst_n has '
            '7 D loads) -> u_lpr_<region> reset forests (depth 2, per-chunk leaves <= 32 loads) -> per-child u_lprc_* '
            'pads (reference schedule +7; u_io: 6 shared stages + 4 kept last-stage copies). Reset age unchanged.')
        j = s['job']
        j.update(owner='Claude:KV-AHUB7', branch='claude/kv-ahub7-1020', tag='g6c',
                 purpose='AHUB6 native-32 hub, canonical lp.py parent (no derived-record helper); u_rx/u_ry/root '
                         'copies fenced in c; no added cycles vs g3.')
        for b in j['benches']:
            b['cmd'] = b['cmd'].replace('tools/qwen_kv_die/ahub6/bench.sh', 'tools/qwen_kv_die/ahub7/bench.sh')
            for k in ('pass_witness', 'fail_witness'):
                if k in b:
                    b[k] = b[k].replace('qwen_kv_ahub6_1020', 'qwen_kv_ahub7_1020')
        j['extra_paths'] = [p for p in j['extra_paths'] if p != 'tools/ref_tile/derived_landed_record.py'] + [
            'tools/qwen_kv_die/ahub7', 'results/arch/kv_ahub7_1020', 'results/rtl/qwen_kv_ahub7_1020']
        s['structural_change'] = ('AHUB6 native-32 source (CHUNK2 landings, kept same-edge command/metadata/decoder/'
                                  'capture copies) generated canonically by lp.py (KV-AHUB7); u_rx/u_ry, the 7 root '
                                  'copies and the u_io reset-copy flops fenced in c.')
        (d / 'spec.json').write_text(json.dumps(s, indent=1) + '\n')
        f = (d / 'lp_fences.tcl').read_text()
        old = ' '.join('u_lpr_root_r%d' % i for i in range(7))
        assert f.count(old) == 1, name
        f = f.replace(old, ' '.join('u_lpr_root_' + r for r in REGIONS) + ' ' +
                      ' '.join('u_lprc_u_io_k%d' % c for c in range(4)))
        (d / 'lp_fences.tcl').write_text(f)
        print(d)


if __name__ == '__main__':
    main()
