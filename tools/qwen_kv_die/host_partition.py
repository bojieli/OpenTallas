"""qwen-split/kvsys die lead r6 2026-10-15: physical partition of the actual HOST root for the KV/system die.

The actual HOST root qkd_host_root_integrated (owner q_control_host / q_host_bind; source on main) carries the 128-PC static
ingest/return words land_es / land_er / ctrl_es / ctrl_er (2 x 36,864 + 2 x 33,408 b) through ONE block: that violates the
die cut rule.  This generator moves, per PC, the three source children that touch those words out of the root into one
die-placed slice (rtl/qwen_sys/split_20261014/qkd_host_pc_slice.sv: ingest station + static arbiter + boot/normal
completion demux), placed beside its controller/landing pair, and emits the root core:

  qkd_host_ingest_chain_pt      = qkd_host_ingest_chain_splitboot without its g_pc instances (map / sum / order stay);
                                  stack chain ends (f0 291 b out, c0 / a0 32 b in, fault0 in) and all_acks become ports
  qkd_host_rank_services_pt     = qkd_host_rank_services without g_boot; boot_done/ok/fault per PC become inputs
  qkd_host_root_pt              = qkd_host_root_integrated with u_rank -> the _pt service, the per-PC buses removed
  qkd_host_root_composed        = (bench only) root_pt + 128 slices wired exactly as the source parents: SAME ports as
                                  qkd_host_root_integrated, so the co-simulation bench compares the two bit for bit

The transformation is textual with exact-match assertions: a source change in a touched region fails loudly here
instead of silently diverging.  Every other line of the source modules is carried verbatim.

    python3 tools/qwen_kv_die/host_partition.py --out rtl/qwen_sys/split_20261014/qkd_host_root_pt.sv \
        --composed rtl/test/qwen_split/qkd_host_root_composed.sv --manifest results/.../host_partition.json
"""
