def sub1(text, pattern, repl, what, flags=re.S):
    out, n = re.subn(pattern, lambda _: repl, text, flags=flags)
    if n != 1:
        raise SystemExit(f'host_partition: {what}: expected exactly 1 match of {pattern!r}, got {n}')
    return out


def module_text(text, name):
    m = re.search(r'^module\s+' + name + r'\b.*?^endmodule\b', text, re.M | re.S)
    if not m:
        raise SystemExit(f'host_partition: module {name} not found')
    return m.group(0)


