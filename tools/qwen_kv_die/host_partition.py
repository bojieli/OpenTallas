def root_pt(text):
    t = module_text(text, 'qkd_host_root_integrated')
    t = sub1(t, r'module qkd_host_root_integrated\b', 'module qkd_host_root_pt', 'root name')
    t = sub1(t, r'\n input wire\[127:0\] ck_boot,\n input wire\[127:0\] ck_boot_test,', '', 'root ck_boot ports')
    t = sub1(t, r'\n input wire\[127:0\] ck_station,\n input wire\[127:0\] ck_static,', '', 'root ck_station ports')
    t = sub1(t, r' input wire\[36863:0\] land_es,\n output wire\[33407:0\] land_er,\n output wire\[36863:0\] ctrl_es,\n'
                r' input wire\[33407:0\] ctrl_er,\n input wire\[127:0\] ctrl_completion_v,\n input wire\[127:0\] ctrl_completion_we,\n',
             ' ' + NEW_PORTS + '\n', 'root per-PC ports')
    t = sub1(t, r'qkd_host_rank_services #\(', 'qkd_host_rank_services_pt #(', 'root u_rank master')
    for p in ('ck_boot', 'ck_boot_test', 'ck_station', 'ck_static'):
        t = sub1(t, r'\n \.' + p + r'\(' + p + r'\),', '', f'root .{p}')
    t = sub1(t, r' \.land_es\(land_es\),\n \.land_er\(land_er\),\n \.ctrl_es\(ctrl_es\),\n \.ctrl_er\(ctrl_er\),\n'
                r' \.ctrl_completion_v\(ctrl_completion_v\),\n \.ctrl_completion_we\(ctrl_completion_we\),\n',
             ' ' + NEW_CONN + '\n', 'root u_rank per-PC connections')
    for name in ('ck_boot', 'ck_boot_test', 'ck_station', 'ck_static', 'land_es', 'land_er', 'ctrl_es', 'ctrl_er',
                 'ctrl_completion_v', 'ctrl_completion_we'):
        if re.search(r'\b' + name + r'\b', t):
            raise SystemExit(f'host_partition: root_pt still references {name}')
    return t


def composed(root_text):
    """bench wrapper: SAME header as qkd_host_root_integrated; root_pt + 128 slices wired as the source parents"""
    t = module_text(root_text, 'qkd_host_root_integrated')
    m = re.match(r'(module qkd_host_root_integrated\s*#\(.*?\)\s*\((.*?)\n\);)', t, re.S)
    head, ports = m.group(1), m.group(2)
    names = []
    for item in re.sub(r'//[^\n]*', '', ports).split(','):
        w = re.findall(r'[A-Za-z_][A-Za-z_0-9]*', item.strip())
        if w:
            names.append(w[-1])
    params = re.findall(r'(\w+)=', re.search(r'#\((.*?)\)\s*\(', head, re.S).group(1))
    moved = {'ck_boot', 'ck_boot_test', 'ck_station', 'ck_static', 'land_es', 'land_er', 'ctrl_es', 'ctrl_er',
             'ctrl_completion_v', 'ctrl_completion_we'}
    conn = ',\n  '.join(f'.{n}({n})' for n in names if n not in moved)
    out = [head.replace('module qkd_host_root_integrated', 'module qkd_host_root_composed', 1), '',
           ' wire[1163:0]chain_f;wire[127:0]chain_c,chain_a,slice_ack,slice_boot_done,slice_boot_ok,slice_boot_fault;wire[3:0]chain_fault_i;',
           ' qkd_host_root_pt #(' + ','.join(f'.{p}({p})' for p in params) + ') u_core(',
           '  ' + conn + ',', '  ' + NEW_CONN.rstrip(',').replace(',.', ',\n  .') + ');',
           ' for(genvar st=0;st<4;st=st+1)begin:g_stack',
           '  wire[290:0]f[0:32];wire[31:0]c[0:32],a[0:32];wire[32:0]fault;',
           '  assign f[0]=chain_f[st*291+:291];assign c[32]=0;assign a[32]=0;assign fault[32]=0;',
           '  assign chain_c[st*32+:32]=c[0];assign chain_a[st*32+:32]=a[0];assign chain_fault_i[st]=fault[0];',
           '  for(genvar pc=0;pc<32;pc=pc+1)begin:g_pc',
           '   localparam integer ID=st*32+pc;',
           '   qkd_host_pc_slice u_slice(.ck_station(ck_station[ID]),.ck_static(ck_static[ID]),.ck_boot(ck_boot[ID]),.ck_boot_test(ck_boot_test[ID]),',
           '    .host_rst_n(host_rst_n),.hbm_rst_n(hbm_rst_n),.boot_go(boot_go),.lpc(5\'(pc)),',
           '    .fi(f[pc]),.fo(f[pc+1]),.ci(c[pc+1]),.co(c[pc]),.ai(a[pc+1]),.ao(a[pc]),.fault_i(fault[pc+1]),.fault_o(fault[pc]),',
           '`ifdef OT_PARTITION_MUT',
           '    // bench mutant: PCs 0 and 1 of stack 0 take each other\'s landing word (a crossed die wire)',
           '    .land_es(land_es[(ID<2?ID^1:ID)*288+:288]),',
           '`else',
           '    .land_es(land_es[ID*288+:288]),',
           '`endif',
           '    .land_er(land_er[ID*261+:261]),.ctrl_es(ctrl_es[ID*288+:288]),.ctrl_er(ctrl_er[ID*261+:261]),',
           '    .ctrl_completion_v(ctrl_completion_v[ID]),.ctrl_completion_we(ctrl_completion_we[ID]),',
           '    .all_ack(slice_ack[ID]),.boot_done(slice_boot_done[ID]),.boot_ok(slice_boot_ok[ID]),.boot_fault(slice_boot_fault[ID]));',
           '  end', ' end', 'endmodule', '']
    return '\n'.join(out)


def sha(p):
    return hashlib.sha256((ROOT / p).read_bytes()).hexdigest()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--composed', type=Path)
    ap.add_argument('--manifest', type=Path)
    a = ap.parse_args(argv)
    chain_src = (ROOT / SRC['chain']).read_text()
    flat = re.sub(r'\s+', '', chain_src)
    for pat in CHAIN_SOURCE_BODY:
        if not re.search(re.sub(r'(?<!\\)\s+', '', pat.replace(' ', '')), flat):
            raise SystemExit(f'host_partition: chain source changed near {pat!r}; re-derive CHAIN_PT')
    root_src = (ROOT / SRC['root']).read_text()
    hdr = ('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/host_partition.py (kvsys die lead r6): HOST root core for the KV/system die.\n'
           '// Sources: ' + ', '.join(f'{k}={SRC[k]}@{sha(SRC[k])[:12]}' for k in ('root', 'rank', 'chain')) + '\n'
           '// Do not edit: regenerate.  The per-PC station / static arbiter / boot completion live in qkd_host_pc_slice.\n')
    a.out.write_text(hdr + CHAIN_PT + '\n' + rank_pt((ROOT / SRC['rank']).read_text()) + '\n\n' + root_pt(root_src) + '\n')
    if a.composed:
        a.composed.write_text('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/host_partition.py: bench-only composition '
                              '(root_pt + 128 die slices) with the exact port list of qkd_host_root_integrated.\n' + composed(root_src))
    if a.manifest:
        a.manifest.parent.mkdir(parents=True, exist_ok=True)
        rec = dict(schema='opentallas.qwen_kv_host_partition.v1', sources={k: dict(path=v, sha256=sha(v)) for k, v in SRC.items()},
                   generated=dict(root_pt=str(a.out), root_pt_sha256=hashlib.sha256(a.out.read_bytes()).hexdigest()),
                   moved_per_pc=['qkd_host_ingest_station', 'qkd_host_static_pc_emback', 'qkd_hbm_boot_static_completion'],
                   root_core_ports_removed=['ck_boot[128]', 'ck_boot_test[128]', 'ck_station[128]', 'ck_static[128]',
                                            'land_es[36864]', 'land_er[33408]', 'ctrl_es[36864]', 'ctrl_er[33408]',
                                            'ctrl_completion_v[128]', 'ctrl_completion_we[128]'],
                   root_core_ports_added=dict(chain_f=1164, chain_c=128, chain_a=128, chain_fault_i=4, slice_ack=128,
                                              slice_boot_done=128, slice_boot_ok=128, slice_boot_fault=128),
                   slice_ports=dict(fi=291, fo=291, ci=32, co=32, ai=32, ao=32, fault_i=1, fault_o=1, land_es=288, land_er=261,
                                    ctrl_es=288, ctrl_er=261, ctrl_completion_v=1, ctrl_completion_we=1, lpc=5,
                                    clocks=['ck_station', 'ck_static', 'ck_boot', 'ck_boot_test'],
                                    resets=['host_rst_n', 'hbm_rst_n'], status=['all_ack', 'boot_done', 'boot_ok', 'boot_fault']))
        if a.composed:
            rec['generated'].update(composed=str(a.composed), composed_sha256=hashlib.sha256(a.composed.read_bytes()).hexdigest())
        a.manifest.write_text(json.dumps(rec, indent=1) + '\n')
    print(f'host_partition: wrote {a.out}' + (f' and {a.composed}' if a.composed else ''))


if __name__ == '__main__':
    main()
