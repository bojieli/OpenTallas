#!/usr/bin/env python3
"""KDIE5-RTL 10-22: kits of the pin-registered KV group successors qkd_kvs_grp_r2 / qkd_kvs_grp_h_r2 (rtl/qwen_sys/
static_kv_die_20261017/qkd_kvs_grp_r2.sv) for the RELEASE KV die frame, derived from the KDIE5-TV r1 kits (same ports,
same frame outline / faces / bit order / pin plan / macros / spine / reset landing):
  <m>_r2a  MAIN: the relays / pass flops placed by GPL (pin flops fixed at their pins by io_flop_at_pins)
  <m>_r2b  FB:   the same RTL with every pass-word relay stage FIRM at its 1/3 / 2/3 point of the N <-> S span
                 (relay_place.tcl, OT_RELAY_PLACE: GPL collapses mm-long relay chains), released for DPL
Changes vs r1: top = the r2 successor (+ its file); hck boundary without o_ctl (every o_ctl bit now leaves a core-clock
exit flop); benches = kvs_grp_r2_bench.sh (lockstep vs the release module on the documented delays, mutants 1-4 FAIL).
    python3 tools/qwen_kv_die/kvs_grp_r2_kits.py && python3 tools/ref_tile/ref_tile.py gen physical/ref_tile/<kit>/spec.json
"""
import json, re, sys
from pathlib import Path

WT = Path(__file__).resolve().parents[2]
R2 = 'rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_grp_r2.sv'
WIT = 'results/rtl/qwen_kv_die/kdie5_rtl_1022'
# FB relay plan (um, kit frame 222.576 x 1187.976): macros x 85.5..180.3 at y 82 / 368 / 694 / 980 (h 41.064, halo 5.4);
# i_ctl N x 60..86, o_dn S x 136..162, i_up S x 33..47, o_ctl N x 176..190.  Bands free of macros: y 129..362, 415..688,
# 741..974.  Legs (Manhattan, pin -> r1 -> r2 -> pin): fan 445 / 440 / 379, gather 450 / 430 / 451.
# Note: the plan regexes name flops of the r2 TOP module (u_core flops are u_core.*, never matched).
PLAN = {
    # yosys opt_merge shares fan relays r1 / r2 bits 0..193 with the equal-D delay-line stages dl[0] / dl[1]
    'grp': [(r'^(?:r1|dl\[0\])\[(\d+)\]\$_DFF', 271, (110.0, 780.0)), (r'^(?:r2|dl\[1\])\[(\d+)\]\$_DFF', 271, (130.0, 360.0)),
            (r'^u1\[(\d+)\]\$_DFF', 126, (60.0, 430.0)), (r'^u2\[(\d+)\]\$_DFF', 126, (120.0, 800.0))],
    # grp_h FB: the cf1 fault / own-status path pinned (the r1 failure class: u_cf1.fault >= 631 um from its pins):
    # f1 (cf1 fault relays) at the W mid-height, own status o1 / o2 on the way to the o_ctl N pins (legs <= ~390)
    'grp_h': [(r'^f1\[(\d+)\]\$_DFF', 4, (40.0, 560.0)), (r'^o1\[(\d+)\]\$_DFF', 18, (60.0, 820.0)),
              (r'^o2\[(\d+)\]\$_DFF', 18, (130.0, 1060.0))],
}
SPREAD = 0.3
R2C = {'grp': 'rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_grp_r2c.sv',
       'grp_h': 'rtl/qwen_sys/static_kv_die_20261017/qkd_kvs_grp_h_r2c.sv'}
MAPPED = {k: f'{WIT}/inputs/qkd_kvs_{k}_r2.input.mapped.v.gz' for k in ('grp', 'grp_h')}
MACRO_BB = 'physical/asap7_memory_macros_v2/ot_sram_1r1w_128x256_m1_r2c2/ot_sram_1r1w_128x256_m1_r2c2_bb.v'


def mapped_cells(k):
    """cell index -> original name of the archived mapped input (the SAME parse kv_grp_safe5.py numbers its u<ci>_c<r>)"""
    import gzip, importlib.util
    spec = importlib.util.spec_from_file_location('kv_r2_textbook', WT / 'tools/textbook_lint.py')
    m = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = m
    spec.loader.exec_module(m)
    raw = gzip.decompress((WT / MAPPED[k]).read_bytes()).decode()
    g, _ = m.flatten(m.parse_verilog(raw), None)
    return [c[1] for c in g.cells]


def relay_tcl(kit, k, plan):
    names = mapped_cells(k)
    pts, rows = {}, []
    for re_, w, (x, y) in plan:
        n = 0
        for ci, nm in enumerate(names):
            mm = re.match(re_, nm)
            if not mm:
                continue
            b = int(mm.group(1)) % w
            pts[ci] = (round(x + (b - (w - 1) / 2.0) * SPREAD, 3), y)
            n += 1
        if not n:
            raise SystemExit(f'{kit}: relay plan row {re_} matches no mapped flop')
        rows.append(f'# {re_}: {n} flops at ({x}, {y})')
    table = ' '.join(f'{ci} {{{x} {y}}}' for ci, (x, y) in sorted(pts.items()))
    return f'''# {kit}: GENERATED by tools/qwen_kv_die/kvs_grp_r2_kits.py (KDIE5-RTL 10-22) -- do not edit.
# PRE_GLOBAL_PLACE hook (spec pin_hook_before_flops): every pass-word relay stage of the structural copy FIRM at its 1/3 / 2/3
# point of the N <-> S span, packed legally by anchor_row_packing.tcl, released for DPL by the kit's relay_release.tcl.
# The structural copy names cell <ci> of the mapped r2 netlist u<ci>_c<replica>/u_cell (kv_grp_safe5.py); the table maps
# ci -> point for the mapped relay flops ({MAPPED[k]}):
{chr(10).join(rows)}
# Placement only.
set ot_rl_blk [ord::get_db_block]
set ot_rl_dbu [[ord::get_db_tech] getDbUnitsPerMicron]
array set ot_rl_pt {{{table}}}
set ot_rl_list {{}}
foreach i [$ot_rl_blk getInsts] {{
  if {{[[$i getMaster] isBlock]}} continue
  set name [string map {{\\ {{}}}} [$i getName]]
  if {{![regexp {{^u(\d+)_c\d+[/.]u_cell$}} $name -> ci]}} continue
  if {{![info exists ot_rl_pt($ci)]}} continue
  if {{[$i isFixed]}} continue
  lassign $ot_rl_pt($ci) x y
  $i setLocation [expr {{round($x * $ot_rl_dbu)}}] [expr {{round($y * $ot_rl_dbu)}}]
  $i setPlacementStatus FIRM
  lappend ot_rl_list [$i getName]
}}
puts "OT_RELAY_PLACE placed [llength $ot_rl_list] relay flops ([array size ot_rl_pt] mapped cells planned)"
if {{[llength $ot_rl_list] < [array size ot_rl_pt]}} {{ error "OT_RELAY_PLACE: [llength $ot_rl_list] of [array size ot_rl_pt] planned relay flops found (naming changed?)" }}
if {{[llength $ot_rl_list]}} {{
  source /src/physical/common_flow/anchor_row_packing.tcl
  ot_anchor_pack::repair $ot_rl_blk $ot_rl_list
}}
set fh [open $::env(RESULTS_DIR)/ot_relay_place.txt w]
foreach n $ot_rl_list {{ puts $fh $n }}
close $fh
'''


RELEASE = '''# {kit}: GENERATED by tools/qwen_kv_die/kvs_grp_r2_kits.py -- PRE_DETAIL_PLACE: relay flops fixed by relay_place.tcl -> PLACED
set ot_rl_blk [ord::get_db_block]
set ot_rl_f $::env(RESULTS_DIR)/ot_relay_place.txt
set ot_rl_n 0
if {{[file exists $ot_rl_f]}} {{
  set fh [open $ot_rl_f r]
  foreach n [split [read $fh] "\\n"] {{
    if {{$n eq ""}} continue
    set i [$ot_rl_blk findInst $n]
    if {{$i eq "NULL" || $i eq ""}} continue
    $i setPlacementStatus PLACED
    incr ot_rl_n
  }}
  close $fh
}}
puts "OT_RELAY_PLACE released $ot_rl_n relay flops for DPL"
'''


def bench(k, kit, m):
    b = dict(name=f'{k}_r2_' + ('eq' if m == 0 else f'mut{m}'),
             cmd=f'bash tools/qwen_kv_die/kvs_grp_r2_bench.sh {{RUN}}/bench/{k}_m{m} {k} {m} all 4000',
             expect='pass' if m == 0 else 'fail', threads=2, peak_ram_gb=8, needs=['verilator'],
             pass_regex=f'^GRP_R2 PASS tile={k}_r2 .* failing=0 .* mut={m}$' if m == 0 else f'^GRP_R2 PASS tile={k}_r2 ')
    b['cmd'] += ' struct'
    b.update(threads=2, peak_ram_gb=16)
    b['pass_regex'] = b['pass_regex'].replace('_r2 ', '_r2c ')
    if m == 0:
        b.update(min_count_regex=r'checks=(\d+)', pass_witness=f'{WIT}/{k}_r2c_m0.log')
    else:
        b.update(fail_regex=f'^GRP_R2 FAIL tile={k}_r2c .* mut={m}$', fail_witness=f'{WIT}/{k}_r2c_m{m}.log')
    return b


def main():
    for k in ('grp', 'grp_h'):
        m = f'qkd_kvs_{k}'; r1 = f'{m}_r1'
        base = json.loads((WT / f'physical/ref_tile/{r1}/spec.json').read_text())
        for var in ('a', 'b'):
            kit = f'{m}_r2{var}'
            s = json.loads(json.dumps(base))
            s['name'] = kit
            # the bounded-driver structural copy of the r2 RTL (native census <= 32 by replication); only the macro
            # black box beside it (the copy is flat mapped cells + keep_hierarchy cell wrappers)
            s['top'] = f'{m}_r2c'
            assert MACRO_BB in s['sources'], s['sources']
            s['sources'] = [R2C[k], MACRO_BB]
            # hclk boundary: every o_ctl bit is now a core-clock exit flop (own status re-registered on ck)
            for kind_, ext in (('sdc', '_hck.sdc'), ('tcl', '_hck_boundary.tcl')):
                src = (WT / f'physical/qkd_kvs_kits/{r1}{ext}').read_text().replace(r1, kit)
                if kind_ == 'sdc':
                    src = re.sub(r' o_ctl\[\d+\]', '', src)
                    src = src.replace('# ---- ', '# ---- ', 1)
                    src = ('# KDIE5-RTL: o_ctl removed from the hclk outputs (qkd_kvs_grp_r2 exit flops are on ck); '
                           'otherwise = ' + r1 + '\n' + src)
                (WT / f'physical/qkd_kvs_kits/{kit}{ext}').write_text(src)
            s['sdc_extra'] = [f'physical/qkd_kvs_kits/{kit}_hck.sdc']
            s['boundary_tcl'] = [f'physical/qkd_kvs_kits/{kit}_hck_boundary.tcl']
            io = (WT / s['io_tcl']).read_text().replace(r1, kit)
            (WT / f'physical/qkd_kvs_kits/{kit}_io.tcl').write_text(io)
            s['io_tcl'] = f'physical/qkd_kvs_kits/{kit}_io.tcl'
            s['pin_regs'] = dict(enable=False, reason='KDIE5-RTL: the r2 RTL registers every pass word at both pins '
                                 '(entry / exit face flops + mid-span relays); a flow pin stage would add an uncounted edge')
            s['reset_landing'] = dict(enable=False, reason='KDIE5-RTL: the r2 RTL lands both resets (rst_n: cr0 -> cr1 on ck, '
                                      'hrst_n: hr0 -> hr1 on hck; async assert, release +2 own-clock edges) and the mapped '
                                      'structural copy preserves them (replicated landing copies, <= 32 loads each); '
                                      'benched in lockstep; a flow landing would add 2 more unbenched edges')
            s['reset_ports'] = ['rst_n', 'hrst_n']
            kd = WT / 'physical/ref_tile' / kit
            kd.mkdir(parents=True, exist_ok=True)
            if var == 'b':
                (kd / 'relay_place.tcl').write_text(relay_tcl(kit, k, PLAN[k]))
                (kd / 'relay_release.tcl').write_text(RELEASE.format(kit=kit))
                s['pin_hook_before_flops'] = s.get('pin_hook_before_flops', []) + [f'physical/ref_tile/{kit}/relay_place.tcl']
                s['pre_dpl_extra'] = s.get('pre_dpl_extra', []) + [f'physical/ref_tile/{kit}/relay_release.tcl']
            s['structural_change'] = (
                f'KDIE5-RTL 10-22: top {m}_r2c = bounded-driver structural copy (kv_grp_safe5.py, max 32 loads) of '
                f'the ORFS mapped netlist of {m}_r2 = the UNCHANGED release module {m} (n32_pj) as u_core + face registers: no '
                'combinational in -> out path (o_dn 4 edges a hop, in-tile equalising delay so every group sees the fan '
                'word +29, gather own +3 / +4 a hop, cf1 fault inputs +2, EST / tok / tep +2). Frame, pins, macros, spine, '
                'reset landing = ' + r1 + '. ' + ('MAIN: relays placed by GPL.' if var == 'a' else
                ('FB: fan / gather relay stages FIRM at their 1/3 / 2/3 span points (relay_place.tcl).' if k == 'grp' else
                 'FB: cf1 fault relays f1 + own-status relays o1 / o2 FIRM on the W-mid -> N path (relay_place.tcl).')))
            s['purpose'] = f'KDIE5-RTL 10-22: pin-registered successor of {m} for the release KV die ({"MAIN" if var == "a" else "FB"})'
            j = s['job']
            j.update(owner='Claude:KDIE5-RTL', branch='claude/kdie5-rtl-1022', tag=f'r2{var}', purpose=s['purpose'],
                     views_to=f'physical/ref_tile/{kit}/views', record_to=f'results/rtl/ref_tile/{kit}')
            j['benches'] = [bench(k, kit, mm) for mm in range(5)]
            j['extra_paths'] = sorted(set([x for x in j['extra_paths'] if 'kdie5_tv_1022' not in x] + [WIT]))
            (kd / 'spec.json').write_text(json.dumps(s, indent=1) + '\n')
            print(kit, s['top'], len(s['sources']), 'relays' if var == 'b' else 'gpl')


main()
