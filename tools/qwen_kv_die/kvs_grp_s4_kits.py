#!/usr/bin/env python3
"""KV-GRP5 2026-10-19: ref_tile specs qkd_kvs_grp_h_s4{a,b} of the s4 H group tile qkd_kvs_grp_h_s4 (kv_grp_safe4.py).

Same floorplan / pins / clock variants / SDC as the s3 kits (kvs_grp_s2_kits.spec, GEN s4); differences: top
qkd_kvs_grp_h_s4 (rsp / krsp leave separate kept exit copies, +0 cycles), sources + qkd_kvs_grp_s4.sv, benches
kvs_grp_s4_bench.py m0..m10 with witnesses results/rtl/qwen_kv_die/kvs_grp_s4_1019/b1, synth_keep_modules
qkd_kvs_rsp_exit_s4 (unparameterised, keep_hierarchy) so the two copies cannot be merged back.

    python3 tools/qwen_kv_die/kvs_grp_s4_kits.py a b      # writes physical/ref_tile/qkd_kvs_grp_h_s4<v>/spec.json + hck SDC/TCL
    then: python3 tools/ref_tile/ref_tile.py gen physical/ref_tile/<kit>/spec.json
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import kv_grp_safe4 as S4  # noqa: E402
import kvs_grp_s2_kits as K  # noqa: E402
import kvs_grp_s4_bench as B4  # noqa: E402

WIT = 'results/rtl/qwen_kv_die/kvs_grp_s4_1019/b1'
NOTE = (' KV-GRP5 s4 (s3 gate review): both grp_h s3 gates had reg->out -345 / -350 ps on rsp[527]: one row-control '
        'output register set fed rsp[32+i] AND krsp[1+i], E-face pins ~196 um apart.  s4: two KEPT exit copies '
        '(qkd_kvs_rsp_exit_s4, keep_hierarchy + SYNTH_KEEP_MODULES), one per pin group, same D and edge (+0 cycles).')


def spec(v):
    K.GEN = 's4'
    K.GEN_NOTE['s4'] = K.GEN_NOTE['s3']
    s = K.spec('grp_h', v)
    assert s['name'] == f'qkd_kvs_grp_h_s4{v}', s['name']
    s['top'] = S4.TOP
    s['sources'] = [s['sources'][0], S4.OUT] + s['sources'][1:]
    s['purpose'] = s['purpose'].replace('qkd_kvs_grp_h_s2', S4.TOP).replace(
        'generated by tools/qwen_kv_die/kv_grp_safe2.py', f'+ {S4.OUT}, generated by kv_grp_safe2.py + kv_grp_safe4.py')
    s['route']['synth_keep_modules'] = [S4.KEEP]
    benches = []
    for m in [0] + sorted(B4.MUTANTS):
        b = dict(name=f's4_m{m}', cmd=f'python3 tools/qwen_kv_die/kvs_grp_s4_bench.py --out {{RUN}}/bench/s4_m{m} --cases m{m} --raw',
                 threads=8, peak_ram_gb=16, needs=['verilator'])
        if m == 0:
            b.update(expect='pass', pass_regex=r'^S2_PASS checks=\d+ edges=6000 mut=0', min_count_regex=r'checks=(\d+)',
                     pass_witness=f'{WIT}/m0.log')
        else:
            b.update(expect='fail', pass_regex=r'^S2_PASS ', fail_regex=rf'^S2_FAIL tile=\w+ output=\w+ edge=\d+ side=\d mut={m} ',
                     fail_witness=f'{WIT}/m{m}.log')
        benches.append(b)
    j = s['job']
    j.update(owner='Claude:KV-GRP5', branch='claude/kv-grp5-s4-1019', benches=benches)
    j['extra_paths'] = ['rtl', 'tools/qwen_kv_die', WIT.rsplit('/', 1)[0]] + j['extra_paths'][3:]
    j['reroute_reason']['reason'] += NOTE
    s['structural_change'] += NOTE
    s['kits_b']['rtl'] = S4.OUT
    s['reset_landing']['reason'] = s['reset_landing']['reason'].replace('s3:', 's3/s4:')
    return s


def main():
    k = ROOT / 'physical/qkd_kvs_kits'
    for v in sys.argv[1:] or ['a', 'b']:
        s = spec(v)
        d = ROOT / 'physical/ref_tile' / s['name']
        d.mkdir(parents=True, exist_ok=True)
        (d / 'spec.json').write_text(json.dumps(s, indent=1) + '\n')
        old = f'qkd_kvs_grp_h_s3{v}'
        for suf in ('_hck.sdc', '_hck_boundary.tcl'):
            (k / f'{s["name"]}{suf}').write_text((k / f'{old}{suf}').read_text().replace(old, s['name']))
        print(s['name'], {f: len(n) for f, n in s['pins'].items()})


if __name__ == '__main__':
    main()
