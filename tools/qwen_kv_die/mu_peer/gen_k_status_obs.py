#!/usr/bin/env python3
"""Derive the opt-in K STATUS v1 chain; preserve all original sfm3 modules."""
import hashlib
import json
import re
import sys
from pathlib import Path

SOURCE = 'rtl/qwen_sys/d2d_static_20261015/ot_qwen_d2d_sfm3.sv'
CODEC = 'rtl/qwen_sys/d2d_static_20261015/ot_qwen_status_observers_v1.sv'
OUTPUT = 'rtl/qwen_sys/d2d_static_20261015/ot_qwen_k_status_obs1.sv'
NAMES = ('ot_qwen_static_slot_ctl_sfm3', 'ot_qwen_static_slot_link_sfm3',
         'ot_qwen_d2d_static_end_sfm3', 'qkd_d2d_static_core_sfm3', 'qkd_d2d_static_ovl_sfm3')


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f'K STATUS source anchor changed ({text.count(old)}): {old[:80]}')
    return text.replace(old, new)


def ports(text):
    return once(text, '\n);', '\n,\n output wire status_obs_v,\n output wire[15:0] status_obs_epoch16,\n'
                ' output wire[207:0] status_obs_payload\n);')


def generate(root):
    source = (root / SOURCE).read_text()
    modules = dict(re.findall(r'^module\s+(\w+)\b(.*?\nendmodule)', source, re.M | re.S))
    out = []
    for name in NAMES:
        text = 'module ' + name + modules[name]
        if name == NAMES[0]:
            text = once(text, "rf[511:156] == 356'd0", "rf[303:156] == 148'd0 && obs_rf_good")
            text = once(text, '    wire hk_d =',
                        '    wire obs_rf_good;\n'
                        '    ot_qwen_status_obs_v1_valid u_obs_rf(.x(rf[511:304]),.good(obs_rf_good));\n'
                        '    wire hk_d =')
            text = once(text, '`ifdef OT_FO_CHECK\n    reg fo_armed',
                        '`ifdef OT_FO_CHECK\n    wire obs_rx_good;\n'
                        '    ot_qwen_status_obs_v1_valid u_obs_rx(.x(rx_flit[511:304]),.good(obs_rx_good));\n'
                        '    reg fo_armed')
            text = once(text, "rx_flit[511:156] == 356'd0", "rx_flit[303:156] == 148'd0 && obs_rx_good")
        if name == NAMES[3]:
            text = ports(text)
            text = once(text, '    wire [NEB-1:0] ebc;',
                        '    wire [NG2+1:0] status_rst_k;\n'
                        '    ot_qwen_status_cold_reset_forest_v1 #(.REGIONS(NG2+2)) u_status_reset\n'
                        '      (.ck(ck),.rst_n_in(rst_n),.rst_n(status_rst_k));\n'
                        '    wire [NEB-1:0] ebc;')
            text = once(text, 'ot_qwen_d2d_status_rx_sfm3 #', 'ot_qwen_d2d_status_rx_sfm3_obs1 #')
            text = once(text, 'u_st (.ck(ck), .rst_n(local_rst_n[2]),',
                        'u_st (.ck(ck), .rst_n(local_rst_n[2]), .rst_k(status_rst_k),')
            text = once(text, '.epoch_begin(ebc[17]), .fault(s_f)',
                        '.epoch_begin(ebc[17]), .fault(s_f), .status_obs_v(status_obs_v), '
                        '.status_obs_epoch16(status_obs_epoch16), .status_obs_payload(status_obs_payload)')
        if name == NAMES[4]:
            text = ports(text)
            regs = ''
            for signal, width in (('status_obs_v', 1), ('status_obs_epoch16', 16), ('status_obs_payload', 208)):
                rng = '' if width == 1 else f'[{width-1}:0] '
                regs += (f' wire {rng}c_{signal};\n reg {rng}q_{signal};\n'
                         f' always @(posedge ck)q_{signal}<=c_{signal};\n'
                         f' assign {signal}=PR?q_{signal}:c_{signal};\n')
            # The new output pin stage has the same PR edge as the old svc outputs.
            text = once(text, '\n);', '\n);\n' + regs)
            text = once(text, '.sf_start(q_sf_start)',
                        '.status_obs_v(c_status_obs_v), .status_obs_epoch16(c_status_obs_epoch16), '
                        '.status_obs_payload(c_status_obs_payload), .sf_start(q_sf_start)')
        text = re.sub(r'\bNG\s*=\s*13\b', 'NG=24', text)
        text = re.sub(r'\bNG2\s*=\s*13\b', 'NG2=24', text)
        for old in NAMES:
            text = re.sub(r'\b' + old + r'\b', old + '_obs1', text)
        out.append(text)
    text = ('`timescale 1ns/1ps\n// GENERATED by gen_k_status_obs.py; explicit opt-in source, no closed-view alias.\n'
            '// STATUS v1: 24 real capture groups, full schema predicate on the actual rf -> hk copies.\n'
            '// Normal calendar unchanged. New 225-bit observation pin bundle carries the existing PR edge.\n' + '\n\n'.join(out) + '''

// Exact old reset release: two asynchronous-assert synchronizer stages followed
// by two plain distribution stages. The root drives26 real first-stage FFs;
// retained hierarchy prevents equivalent leaf registers collapsing together.
(* keep_hierarchy=1 *)module ot_qwen_status_reset_region_v1(
 input wire ck,d,output wire q
);
 reg a,b;
 always @(posedge ck)begin a<=d;b<=a;end
 assign q=b;
endmodule
module ot_qwen_status_cold_reset_forest_v1 #(parameter integer REGIONS=26)(
 input wire ck,rst_n_in,output wire[REGIONS-1:0]rst_n
);
 reg s0,s1;
 always @(posedge ck or negedge rst_n_in)
   if(!rst_n_in)begin s0<=0;s1<=0;end else begin s0<=1;s1<=s0;end
 genvar r;
 for(r=0;r<REGIONS;r=r+1)begin:g_region
   ot_qwen_status_reset_region_v1 u_region(.ck(ck),.d(s1),.q(rst_n[r]));
 end
endmodule
''')
    receipt = dict(source=SOURCE, source_sha256=hashlib.sha256((root/SOURCE).read_bytes()).hexdigest(),
                   codec=CODEC, codec_sha256=hashlib.sha256((root/CODEC).read_bytes()).hexdigest(),
                   top=NAMES[-1]+'_obs1', output=OUTPUT, output_sha256=hashlib.sha256(text.encode()).hexdigest(),
                   capture_groups=24, capture_bits=364, observation_bits=225,
                   reset_regions=26, reset_release='2sync+2distribution, equal to existing cold reset; root26 sinks',
                   calendar_delta=0, physical_qualification='NOTRUN; new exact source/view required')
    return text, receipt


if __name__ == '__main__':
    root = Path(sys.argv[1]) if len(sys.argv)>1 else Path(__file__).resolve().parents[3]
    text, receipt = generate(root)
    (root/OUTPUT).write_text(text)
    p = root/'results/rtl/codex_kv_die_1021/status_obs_k_source.json'
    p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(receipt,indent=2)+'\n')
    print(receipt['top'], receipt['output_sha256'])
