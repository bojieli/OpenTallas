# {143'd0,cmd_hc}.  HCW (default 182 = the original logic, behaviour-identical) sets the width of the command / hc
# field; HCW 39 = START only: cmd_hc / hc / cd / cq / active are 39 bits and the PW113 / DW181 command-event logic is
# absent (its event mask is empty), not fed constants.  The 512-bit link frame keeps its layout; in HCW 39 its PW/DW
# field (frame bits 229:87) is reserved and a peer fails closed (fault) on a frame that sets it.  Applied to the main
# transport only (the --pd fork keeps TS_EDITS alone).
