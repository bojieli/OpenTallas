def main():
    if '--pd' in sys.argv:
        # HKV-PROMPT6 fork (registered RX queue head, claude/hkv-peer6-1019): qkd_host_ctrl_token_service_packet_collected_pd
        # -> qkd_host_ctrl_token_service_packet_collected_pd_mu (same MU edits; MU 0 = the _pd fork).  usage:
        # gen_peer_mu.py ROOT --pd <..._pd.sv> <out_dir>   (written only where the _pd fork exists, i.e. after that merge)
        i = sys.argv.index('--pd'); pd, od = Path(sys.argv[i + 1]), Path(sys.argv[i + 2])
        mod = 'qkd_host_ctrl_token_service_packet_collected_pd'
        out = build(pd.read_text(), mod, TS_HEAD.replace('packet_collected.sv', 'packet_collected_pd.sv (HKV-PROMPT6 fork)'),
                    TS_EDITS, body_prefix=TS_PREFIX)
        (od / f'{mod}_mu.sv').write_text(out); print('wrote', od / f'{mod}_mu.sv'); return
    jobs = [
     ('qkd_host_peer_coordinator_codec', CODEC_HEAD, CODEC_EDITS, CODEC_PREFIX),
     ('qkd_host_ctrl_token_service_packet_collected', TS_HEAD, TS_EDITS, TS_PREFIX),
     ('qkd_host_tp8_coordinator', CO_HEAD, CO_EDITS, ''),
    ]
    extra = dict(qkd_host_tp8_coordinator=CO_EXTRA)
    extra['qkd_host_ctrl_token_service_packet_collected'] = 'parameter integer MU=1,parameter integer HCW=182'
    for mod, head, edits, prefix in jobs:
        src = (HI / f'{mod}.sv').read_text()
        hcw = mod == 'qkd_host_ctrl_token_service_packet_collected'
        if hcw:
            head, edits, prefix = head + TS_HCW_HEAD, edits + TS_HCW_EDITS, prefix + TS_HCW_PREFIX
        out = build(src, mod, head, edits, body_prefix=prefix, extra_param=extra.get(mod, 'parameter integer MU=1'))
        for a, b in (TS_HCW_PORTS if hcw else []):
            assert out.count(a) == 1, (mod, a, out.count(a))
            out = out.replace(a, b)
        (OUT / f'{mod}_mu.sv').write_text(out)
        print('wrote', OUT / f'{mod}_mu.sv')

if __name__ == '__main__':
    main()
