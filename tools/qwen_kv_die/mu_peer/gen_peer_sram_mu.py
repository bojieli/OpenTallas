#!/usr/bin/env python3
"""KV-PEER12 10-20: MU 1 (Qwen ROM 4 users) successor of the RR/PD/RX-SRAM PEER composition (qkd_hr_core_peer_sram, the
source of the native32 qkd_hr_core_peer_n32 kits p32a..f, which is MU 0).  Applies the UNCHANGED MU-KV-PEER edit lists of
gen_peer_mu.py to the _pd forks (each edit must apply exactly once) and swaps the _rr wrappers' inner members:
  qkd_host_peer_coordinator_codec_pd      -> _pd_mu   (CODEC_EDITS)
  qkd_host_ctrl_token_service_packet_collected_pd2 -> _pd2_mu (TS_EDITS)
  qkd_host_tp8_coordinator_pd             -> _pd_mu   (CO_EDITS with codec _pd; POST_UID_SLOT passed through)
  qkd_host_tp8_coordinator_rr / ctrl_rr   -> _rr_mu   (inner member _mu #(MU 1[, POST_UID_SLOT 1]))
  qkd_hr_core_peer_sram                   -> qkd_hr_core_peer_sram_mu (the two _rr members -> _rr_mu)
POST_UID_SLOT 1 = the KV die HOST root's real-observer POST decode (qkd_host_root_admission_mu u_coordinator).
The coordinator services are qkd_host_coordinator_services_mu (post_collector_mu with the KV-MU7 next-issue hold, a92df84c4).
usage: gen_peer_sram_mu.py ROOT OUT_DIR
"""
import re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from mkmu import build
import gen_peer_mu as G

R = Path(sys.argv[1]); OD = Path(sys.argv[2]); OD.mkdir(parents=True, exist_ok=True)
H = R / 'rtl/test/host_peer_main_fixture_1020/historical/rtl/qwen_sys/host_cluster_20261017'
TAG = '// KV-PEER12 10-20: generated by tools/qwen_kv_die/mu_peer/gen_peer_sram_mu.py -- do not edit.\n'

def once(s, a, b, n=1):
    assert s.count(a) == n, (a, s.count(a), n)
    return s.replace(a, b)

def w(name, text):
    (OD / name).write_text(text); print('wrote', OD / name)

# prefix wires that read body registers before their declaration (Verilator accepts the forward reference; Yosys
# refuses it): declared in the prefix, assigned after the body (same expressions, no logic change).
def split_prefix(prefix):
    pre, post = [], []
    for ln in prefix.splitlines(True):
        m = re.match(r'\s*wire(\[[^\]]*\])?\s*(\w+)=(.*);(.*)$', ln.rstrip('\n'))
        if m:
            pre.append(' wire%s %s;%s\n' % (m.group(1) or '', m.group(2), m.group(4)))
            post.append(' assign %s=%s;\n' % (m.group(2), m.group(3)))
        else:
            pre.append(ln)
    return pre, post
# codec _pd -> _pd_mu
src = (H / 'peer_pd/qkd_host_peer_coordinator_codec_pd.sv').read_text()
cpre, cpost = split_prefix(G.CODEC_PREFIX)
out = build(src, 'qkd_host_peer_coordinator_codec_pd',
  TAG + G.CODEC_HEAD.replace('qkd_host_peer_coordinator_codec.sv', 'qkd_host_peer_coordinator_codec_pd.sv (KV-HOST/PEER r6 fork)'),
  G.CODEC_EDITS, body_prefix=''.join(cpre))
out = once(out, 'end endgenerate\nendmodule\n', ''.join(cpost) + 'end endgenerate\nendmodule\n')
w('qkd_host_peer_coordinator_codec_pd_mu.sv', out)
# token service _pd2 -> _pd2_mu.  The pd2 fork computes the token-frame test once at queue write (rf[15] = f_tok22, used by
# both peer_token_frame and the class-22 decode) and names the command head cmd_head: same MU edits on those spellings.
TS_PD2 = []
for e in G.TS_EDITS:
    a, b = e[0], e[1]
    if a == "h[65:61]==0&&h[83:66]<18'd151936":
        e = ("rd[65:61]==0&&rd[83:66]<18'd151936", "rd[63:61]==0&&rd[231:230]==rd[65:64]&&rd[83:66]<18'd151936", 1)
    elif a == "if(cq[cr][17:13]!=0||cq[cr][35:18]>=18'd151936)fault<=1;":
        e = ("if(cmd_head[17:13]!=0||cmd_head[35:18]>=18'd151936)fault<=1;", "if(cmd_head[15:13]!=0||cmd_head[35:18]>=18'd151936)fault<=1;")
    TS_PD2.append(e)
# TS_PREFIX's cu_latest / cu_epoch read allocated_*_q before the body declares them (Verilator accepts the forward
# reference; Yosys refuses it: "Failed to detect width of signal access g_mu.allocated_token_q").  Same expressions,
# declared in the prefix and assigned after the body (no logic change).
pre, post = split_prefix(G.TS_PREFIX)
assert len(post) == 4, post
src = (H / 'peer_pd/qkd_host_ctrl_token_service_packet_collected_pd2.sv').read_text()
out = build(src, 'qkd_host_ctrl_token_service_packet_collected_pd2',
  TAG + G.TS_HEAD.replace('packet_collected.sv', 'packet_collected_pd2.sv (KV-HOST/PEER r6 fork)'),
  TS_PD2, body_prefix=''.join(pre))
out = once(out, 'end endgenerate\nendmodule\n', ''.join(post) + 'end endgenerate\nendmodule\n')
w('qkd_host_ctrl_token_service_packet_collected_pd2_mu.sv', out)
# coordinator _pd -> _pd_mu
src = (H / 'peer_pd/qkd_host_tp8_coordinator_pd.sv').read_text()
ed = [(a.replace('qkd_host_peer_coordinator_codec u_peer(', 'qkd_host_peer_coordinator_codec_pd u_peer('),
       b.replace('qkd_host_peer_coordinator_codec_mu #(.MU(1)) u_peer(', 'qkd_host_peer_coordinator_codec_pd_mu #(.MU(1)) u_peer('))
      for a, b in G.CO_EDITS]
w('qkd_host_tp8_coordinator_pd_mu.sv', build(src, 'qkd_host_tp8_coordinator_pd',
  TAG + G.CO_HEAD.replace('qkd_host_tp8_coordinator.sv', 'qkd_host_tp8_coordinator_pd.sv (KV-HOST/PEER r6 fork)'),
  ed, extra_param=G.CO_EXTRA))
# _rr wrappers: rename module, inner member -> _mu with MU 1 (plain rename, same ports)
s = (H / 'peer_rr/qkd_host_tp8_coordinator_rr.sv').read_text()
s = once(s, 'module qkd_host_tp8_coordinator_rr(', 'module qkd_host_tp8_coordinator_rr_mu #(parameter integer POST_UID_SLOT=1)(')
s = re.sub(r'\bqkd_host_tp8_coordinator_pd(\s+u_)', r'qkd_host_tp8_coordinator_pd_mu #(.MU(1),.POST_UID_SLOT(POST_UID_SLOT))\1', s, count=1)
assert 'qkd_host_tp8_coordinator_pd_mu' in s
w('qkd_host_tp8_coordinator_rr_mu.sv', TAG + s)
s = (H / 'peer_rr/qkd_host_ctrl_token_service_packet_collected_rr.sv').read_text()
s = once(s, 'module qkd_host_ctrl_token_service_packet_collected_rr #(', 'module qkd_host_ctrl_token_service_packet_collected_rr_mu #(')
n0 = s.count('qkd_host_ctrl_token_service_packet_collected_pd2 #(')
assert n0 == 1, n0
s = s.replace('qkd_host_ctrl_token_service_packet_collected_pd2 #(', 'qkd_host_ctrl_token_service_packet_collected_pd2_mu #(.MU(1),')
w('qkd_host_ctrl_token_service_packet_collected_rr_mu.sv', TAG + s)
# PEER top
s = (H / 'qkd_hr_core_peer_sram.v').read_text()
s = once(s, 'module qkd_hr_core_peer_sram(', 'module qkd_hr_core_peer_sram_mu(')
for m in ('qkd_host_tp8_coordinator_rr', 'qkd_host_ctrl_token_service_packet_collected_rr'):
    k = len(re.findall(r'\b' + m + r'\b(?!_)', s)); assert k == 1, (m, k)
    s = re.sub(r'\b' + m + r'\b(?!_)', m + '_mu', s)
w('qkd_hr_core_peer_sram_mu.v', TAG + s)

# ---------------------------------------------------------------- MU 1-only flat copies (synthesis)
# Yosys resolves a name used before its declaration at module scope (the _pd forks do this, e.g. pd2 load_cmd) but NOT
# inside a named generate block ("Failed to detect width of signal access g_mu.load_cmd").  The PEER tile is MU 1 only,
# so every MU member it uses is written MU 1-only: the g_mu body at module scope, the g_plain branch dropped (MU kept as
# a parameter; any other value is an elaboration error).  Same logic; hierarchical names lose the g_mu level.
GEN = re.compile(r'generate\s+if\s*\(\s*MU\s*==\s*0\s*\)\s*begin\s*:\s*g_plain\b(.*?)\bend\s+else\s+begin\s*:\s*g_mu\b', re.S)
def flat(text, mod):
    m = GEN.search(text); assert m, mod
    k = text.rindex('endgenerate'); e = text.rindex('end', 0, k)
    assert text[e:k].strip() == 'end', mod
    body = text[m.end():e]
    chk = ("`ifndef SYNTHESIS\n initial if(MU!=1)$error(\"%s: MU 1-only copy (KV-PEER12 flat)\");\n`endif\n" % mod)
    return text[:m.start()] + '// KV-PEER12: MU 1-only flat copy (g_plain dropped, g_mu body at module scope)\n' + chk + body + text[k + len('endgenerate'):]
M = R / 'rtl/qwen_sys/mu_qwen_20261018'
for name in ('qkd_host_coordinator_services_mu', 'qkd_host_lifecycle_collected_mu', 'qkd_host_post_collector_mu',
             'ot_qwen_tp8_token_cohort_mu', 'ot_qwen_tp8_token_epoch_allocator_mu'):
    w(name + '.sv', TAG + flat((M / (name + '.sv')).read_text(), name))
for name in ('qkd_host_peer_coordinator_codec_pd_mu', 'qkd_host_ctrl_token_service_packet_collected_pd2_mu',
             'qkd_host_tp8_coordinator_pd_mu'):
    w(name + '.sv', flat((OD / (name + '.sv')).read_text(), name))
