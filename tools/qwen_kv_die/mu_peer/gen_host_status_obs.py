#!/usr/bin/env python3
"""Opt-in STATUS-only MU root, with a real HOST AXI CSR reader.

Keep all original root producers/ports. Thread the accepted225-bit STATUS
observation bundle to the packet-master/control-slave AXI boundary. The reader
owns its atomic snapshot and delta checks; it never changes token scheduling.
"""
import hashlib
import json
import sys
from pathlib import Path
from gen_host_root_obs import module_text, once, AXI_M2S, AXI_S2M, AXI_W

SRC='rtl/qwen_sys/mu_qwen_20261018/qkd_host_root_admission_mu.sv'
OUT='rtl/qwen_sys/kv_status_obs_20261021/qkd_host_root_admission_status_obs1.sv'
NAMES=('qkd_host_root_admission_mu','qkd_host_rank_services_admission_mu','qkd_host_control_packet_admission_mu')
NEW=tuple(n.removesuffix('_mu')+'_status_obs1' for n in NAMES)
PORTS='\n,\n input wire status_obs_v,\n input wire[15:0]status_obs_epoch16,\n input wire[207:0]status_obs_payload\n);'
CONN='.status_obs_v(status_obs_v),.status_obs_epoch16(status_obs_epoch16),.status_obs_payload(status_obs_payload),'


def generate(root):
    source=(root/SRC).read_text()
    modules=[]
    for i,name in enumerate(NAMES):
        text=module_text(source,name)
        text=once(text,'module '+name+' #(','module '+NEW[i]+' #(')
        text=once(text,'\n);',PORTS+'\n initial if(MU!=1)$fatal(1,"STATUS observation root requires MU1");')
        if i<2:
            old=NAMES[i+1]
            text=once(text,old+' #(.MU(1),',NEW[i+1]+' #(.MU(1),')
            start=text.index(NEW[i+1]+' #(')
            instance=')u_rank(' if i==0 else ')u_control('
            pos=text.index(instance,start)+len(instance)
            text=text[:pos]+CONN+text[pos:]
        else:
            begin=text.index('begin:g_mu')
            start=text.index('qkd_host_packet_bundle_admission_mu #(',begin)
            k=text.index(')u_packet(',start)
            end=text.index('end endgenerate',k)
            instance=text[k:end]
            for signal in AXI_M2S+AXI_S2M:
                instance=once(instance,f'.{signal}({signal})',f'.{signal}(u_{signal})')
            wires=''.join(f'wire [{AXI_W[s]-1}:0] u_{s};\n' if s in AXI_W else f'wire u_{s};\n' for s in AXI_M2S+AXI_S2M)
            conn=','.join([f'.u_{s[2:]}(u_{s})' for s in AXI_M2S+AXI_S2M]+[f'.d_{s[2:]}({s})' for s in AXI_M2S+AXI_S2M])
            reader=('qkd_host_status_obs u_status_reader(.clk(ck_csr),.rst_n(host_rst_n),'+CONN+conn+');\n')
            text=text[:start]+wires+text[start:k]+instance+reader+text[end:]
        modules.append(text)
    text='`timescale 1ns/1ps\n// GENERATED by gen_host_status_obs.py; explicit opt-in STATUS reader, original MU root unchanged.\n'+'\n\n'.join(modules)+'\n'
    receipt=dict(source=SRC,source_sha256=hashlib.sha256((root/SRC).read_bytes()).hexdigest(),
        output=OUT,output_sha256=hashlib.sha256(text.encode()).hexdigest(),top=NEW[0],
        status_input_bits=225,window='0x1800-0x19FF',snapshot_bits=293,
        snapshot_fields={'payload208':[0,207],'receipt_epoch16':[208,223],'record_seq32':[224,255],
                         'completion_delta32':[256,287],'errors4':[288,291],'seen':[292,292]},
        semantics='operation epoch/owner are carried inside raw schema208 and independent from receipt epoch; same-epoch completion count must be monotonic; changed receipt epoch starts new delta window',
        latency='accepted STATUS commit2samples; CAPTURE commit2samples; CSR read3samples after AR; off token schedule',
        physical_qualification='NOTRUN; new exact wrapper/frame/native source proof required')
    return text,receipt


if __name__=='__main__':
    root=Path(sys.argv[1]) if len(sys.argv)>1 else Path(__file__).resolve().parents[3]
    text,receipt=generate(root);p=root/OUT;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text)
    p=root/'results/rtl/codex_kv_die_1021/status_host_source.json';p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(receipt,indent=2)+'\n')
    print(receipt['top'],receipt['output_sha256'])
