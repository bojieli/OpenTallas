#!/usr/bin/env python3
"""el1013-qwen-kvstrips: bench-only golden aggregator for the qkd_astk leaves.

Writes module ot_qkd_astk_gold = ot_qwen_nearhbm_attn_stack_h (rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv) with its
row engines replaced by so / si / nb port vectors (the qkd_ectl bus layout), text otherwise untouched: the stack's
memories, exp quads, Z tree, P.V tree, node staging and sideband.  rtl/test/qwen_kv_die/tb_qkd_astk.sv drives it and the
die-master strip (ot_qkd_astk_strip) with the same engine model and compares every output.

    python3 tools/qwen_kv_die/astk_gold_gen.py OUT.sv
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / 'rtl/hdc/nearhbm/ot_qwen_nearhbm_attn_stack_h.sv').read_text()
i = src.index('module ot_qwen_nearhbm_attn_stack_h #(')
m = src[i:src.index('endmodule', i) + len('endmodule')]
m = m.replace('module ot_qwen_nearhbm_attn_stack_h #(', 'module ot_qkd_astk_gold #(', 1)
# ports: the engines' vectors in place of the row requests
a = m.index('    output wire [R-1:0]      req_valid,')
b = m.index('    input  wire              mi_valid,')
m = m[:a] + ('    input  wire [425*R-1:0]  so_f,\n    output wire [634*R-1:0]  si_f,\n'
             '    input  wire [4096*R-1:0] nb_f,\n') + m[b:]
# the engine instance -> taps
a = m.index('        wire rv, rvv, rg;')
b = m.index("        // re-cut D: this engine's node staging FIFO")
taps = '''        wire [424:0] so_e = so_f[425*e +: 425];
        assign er_valid[e] = so_e[0]; assign er_addr[12*e +: 12] = so_e[12:1]; assign sc_valid[e] = so_e[13];
        assign sc_addr[12*e +: 12] = so_e[25:14]; assign sc_data[128*e +: 128] = so_e[153:26];
        assign lmax[256*e +: 256] = so_e[409:154]; assign lmax_any[2*e +: 2] = so_e[411:410];
        assign nb_valid[e] = so_e[412]; assign nb_beat[4*e +: 4] = so_e[416:413]; assign nb_g[e] = so_e[417];
        assign nb_gam[4*e +: 4] = so_e[421:418]; assign k_done[e] = so_e[422]; assign v_done[e] = so_e[423];
        assign e_fault[e] = so_e[424]; assign ev_kf[e] = 1'b0; assign ev_vf[e] = 1'b0;
        assign nb_data[LN*32/LFB*e +: LN*32/LFB] = nb_f[4096*e +: 4096];
        assign si_f[634*e +: 634] = {nb_cr[e], er_data[64*e +: 64], exp_done, qd_b, qb_b, qv_b, cyc8, T, start};
'''
m = m[:a] + taps + m[b:]
assert 'u_eng' not in m and 'req_valid' not in m, 'engine text left'
Path(sys.argv[1]).write_text('`timescale 1ns/1ps\n// GENERATED by tools/qwen_kv_die/astk_gold_gen.py (bench only)\n' + m + '\n')
