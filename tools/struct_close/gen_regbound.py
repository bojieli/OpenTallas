#!/usr/bin/env python3
"""struct-close 2026-10-09: registered-boundary wrapper generator (template D, owner rule "register every block boundary").

    gen_regbound.py SPEC.json OUT.sv

SPEC: {"src": file, "module": name, "core": renamed core module, "clk": "clk", "reset": "por_n", "params": "ENABLE=1,...",
       "in_hs":  [{"v": "flit_v", "r": "flit_r", "data": ["flit", "flit_owner"]}],      # valid/ready INTO the block
       "out_hs": [{"v": "tuple_v", "r": "tuple_r", "data": [...]}],                     # valid/ready OUT of the block
       "pass": [ports passed through unregistered: clocks / async reset]}
Every other input gets one pin flop (no logic before it); every other output one flop at the pin.  Each valid/ready
pair crosses an ot_sc_pfifo (2 entries: in_ready / out_valid from flops, data stored without a handshake-gated enable,
out_data one AND-OR level from flop copies), i.e. +1 cycle per crossing, protocol unchanged.  The core is the ORIGINAL
module text, renamed (copied verbatim into OUT.sv).  Cycle cost: +1 on every input and every output (+2 round trip).
"""
import json, re, sys
spec = json.load(open(sys.argv[1])); out = sys.argv[2]
src = open(spec["src"]).read()
m = re.search(r"module\s+%s\s*(#\s*\((?:[^()]|\([^()]*\))*\))?\s*\((.*?)\);" % re.escape(spec["module"]), src, re.S)
phdr, hdr = (m.group(1) or ""), m.group(2)
pnames = re.findall(r"(?:parameter\s+(?:integer\s+)?|,)\s*([A-Za-z_]\w*)\s*=", phdr)
# ports: direction, width, names
ports = []
for d, w, names in re.findall(r"(input|output)\s+(?:wire|reg)?\s*(\[[^\]]+\])?\s*([A-Za-z_][\w\s,]*?)(?=,\s*(?:input|output)|\s*$|\s*//)", hdr.replace("\n", " ") + " "):
    for n in names.split(","):
        n = n.strip()
        if n: ports.append((d, w or "", n))
P = {n: (d, w) for d, w, n in ports}
mod_body = src[m.start():]
mod_body = mod_body[:mod_body.index("endmodule") + len("endmodule")]
core = mod_body.replace("module " + spec["module"], "module " + spec["core"], 1)
hs_ports = set(); 
for g in spec.get("in_hs", []) + spec.get("out_hs", []): hs_ports |= {g["v"].split("[")[0], g["r"], *g["data"]}
# vector channels ("in_vec"/"out_vec": {"v": vport, "r": rport, "data": dport, "n": N}): N independent valid/ready lanes,
# lane k = v[k] / r[k] / data[k*W/N +: W/N], each through its own pin FIFO
for g in spec.get("in_vec", []) + spec.get("out_vec", []): hs_ports |= {g["v"], g["r"], g["data"]}
# a valid carried as bit 0 of a data vector ("v": "emit[0]", data ["emit"]): the FIFO valid is that bit; the core sees
# {data[MSB:1], fifo valid} (an empty FIFO presents valid 0)
passp = set(spec.get("pass", [])) | {spec["clk"], spec["reset"]}
if spec.get("outputs_registered"):   # the core already drives every output from a flop: no second output stage
    passp |= {n for d, w, n in ports if d == "output"}
L = []
L.append("`timescale 1ps/1fs\n`default_nettype none")
L.append("// GENERATED by tools/struct_close/gen_regbound.py from %s (%s): registered-boundary wrapper.  DO NOT EDIT." % (spec["src"], spec["module"]))
L.append("// " + spec.get("why", ""))
plist = ", ".join(f"{d} wire {w} {n}".replace("  ", " ") for d, w, n in ports)
params = phdr
L.append(f"module {spec['module']} {params}({plist});")
ck, rs = spec["clk"], spec["reset"]
L.append(f" // reset for the boundary FIFOs: synchronous use of the block's reset (held for several edges at POR)")
conn = {}
# a completion PULSE input (no ready) that must stay behind an input stream: held until that stream's pin FIFO is empty
for k, o in enumerate(spec.get("in_after", [])):
    hs_ports |= {o["pulse"], *o.get("data", [])}
order_after = spec.get("in_after", [])
for d, w, n in ports:
    if n in passp: conn[n] = n; continue
    if n in hs_ports: continue
    if d == "input":
        if not w:   # 1-bit controls (valids, credits, owner flags) clear with the block's active-low reset
            L.append(f" reg q_{n}; always @(posedge {ck} or negedge {rs}) if (!{rs}) q_{n} <= 1'b0; else q_{n} <= {n};")
        else:
            L.append(f" reg {w} q_{n}; always @(posedge {ck}) q_{n} <= {n};")
        conn[n] = f"q_{n}"
    else:
        L.append(f" wire {w} c_{n}; reg {w} q_{n}; always @(posedge {ck}) q_{n} <= c_{n}; assign {n} = q_{n};"); conn[n] = f"c_{n}"
def width(n):
    w = P[n][1]
    if not w: return "1"
    a, b = w[1:-1].split(":"); return f"(({a})-({b})+1)"
for i, g in enumerate(spec.get("in_hs", [])):
    W = "+".join(width(n) for n in g["data"]) or "1"
    L.append(f" localparam integer WI{i} = {W};")
    L.append(f" wire ci{i}_v, ci{i}_r; wire [WI{i}-1:0] ci{i}_d;")
    L.append(f" ot_sc_pfifo #(.W(WI{i}), .S(2), .G(64)) u_in{i} (.clk({ck}), .rst_n({rs}), .in_valid({g['v']}), .in_ready({g['r']}),")
    L.append(f"   .in_data({{{', '.join(g['data'])}}}), .out_valid(ci{i}_v), .out_ready(ci{i}_r), .out_data(ci{i}_d));")
    if "[" not in g["v"]: conn[g["v"]] = f"ci{i}_v"
    conn[g["r"]] = f"ci{i}_r"
    off = []
    for n in g["data"]:
        L.append(f" wire {P[n][1]} ci{i}_{n};"); off.append(n)
    L.append(f" assign {{{', '.join(f'ci{i}_{n}' for n in off)}}} = ci{i}_d;")
    for n in off: conn[n] = f"ci{i}_{n}"
    if "[" in g["v"]:
        b = g["v"].split("[")[0]; hi = P[b][1][1:-1].split(":")[0]
        conn[b] = f"{{ci{i}_{b}[{hi}:1], ci{i}_v}}"
for i, g in enumerate(spec.get("out_hs", [])):
    W = "+".join(width(n) for n in g["data"]) or "1"
    L.append(f" localparam integer WO{i} = {W};")
    L.append(f" wire co{i}_v, co{i}_r;")
    for n in g["data"]:
        L.append(f" wire {P[n][1]} co{i}_{n};"); conn[n] = f"co{i}_{n}"
    ind = "{" + ", ".join(f"co{i}_{n}" for n in g["data"]) + "}" if g["data"] else "1'b0"
    outd = "{" + ", ".join(g["data"]) + "}" if g["data"] else ""
    ov, orr = g["v"], g["r"]
    if "after" in g:   # cross-stream order: this stream (e.g. a done marker) leaves only once stream g["after"] is empty
        prev = spec["out_hs"][g["after"]]["v"]
        L.append(f" wire co{i}_ov; assign {g['v']} = co{i}_ov && !{prev};")
        ov, orr = f"co{i}_ov", f"({g['r']} && !{prev})"
    L.append(f" ot_sc_pfifo #(.W(WO{i}), .S(2), .G(64)) u_out{i} (.clk({ck}), .rst_n({rs}), .in_valid(co{i}_v), .in_ready(co{i}_r),")
    L.append(f"   .in_data({ind}), .out_valid({ov}), .out_ready({orr}), .out_data({outd}));")
    conn[g["v"]] = f"co{i}_v"; conn[g["r"]] = f"co{i}_r"
for k, o in enumerate(order_after):
    pu, fifo = o["pulse"], o["after"]
    L.append(f" // {pu}: held until the in-stream {fifo} pin FIFO is empty (keeps the pulse behind the beats sent before it)")
    L.append(f" reg ia{k}_p; always @(posedge {ck} or negedge {rs}) if (!{rs}) ia{k}_p <= 1'b0; else if ({pu}) ia{k}_p <= 1'b1; else if (!ci{fifo}_v) ia{k}_p <= 1'b0;")
    for dn in o.get("data", []):
        L.append(f" reg {P[dn][1]} ia{k}_{dn}; always @(posedge {ck}) if ({pu}) ia{k}_{dn} <= {dn};"); conn[dn] = f"ia{k}_{dn}"
    conn[pu] = f"(ia{k}_p && !ci{fifo}_v)"
def pw(n):
    w = P[n][1]
    if not w: return 1
    a, b = w[1:-1].split(":"); return eval(a) - eval(b) + 1
for i, g in enumerate(spec.get("in_vec", [])):
    N = g["n"]; DW = pw(g["data"]) // N
    L.append(f" wire [{N-1}:0] iv{i}_v, iv{i}_r; wire [{N*DW-1}:0] iv{i}_d;")
    for k in range(N):
        L.append(f" ot_sc_pfifo #(.W({DW}), .S(2), .G(64)) u_iv{i}_{k} (.clk({ck}), .rst_n({rs}), .in_valid({g['v']}[{k}]), .in_ready({g['r']}[{k}]),")
        L.append(f"   .in_data({g['data']}[{k*DW} +: {DW}]), .out_valid(iv{i}_v[{k}]), .out_ready(iv{i}_r[{k}]), .out_data(iv{i}_d[{k*DW} +: {DW}]));")
    conn[g["v"]] = f"iv{i}_v"; conn[g["r"]] = f"iv{i}_r"; conn[g["data"]] = f"iv{i}_d"
for i, g in enumerate(spec.get("out_vec", [])):
    N = g["n"]; DW = pw(g["data"]) // N
    L.append(f" wire [{N-1}:0] ov{i}_v, ov{i}_r; wire [{N*DW-1}:0] ov{i}_d;")
    for k in range(N):
        L.append(f" ot_sc_pfifo #(.W({DW}), .S(2), .G(64)) u_ov{i}_{k} (.clk({ck}), .rst_n({rs}), .in_valid(ov{i}_v[{k}]), .in_ready(ov{i}_r[{k}]),")
        L.append(f"   .in_data(ov{i}_d[{k*DW} +: {DW}]), .out_valid({g['v']}[{k}]), .out_ready({g['r']}[{k}]), .out_data({g['data']}[{k*DW} +: {DW}]));")
    conn[g["v"]] = f"ov{i}_v"; conn[g["r"]] = f"ov{i}_r"; conn[g["data"]] = f"ov{i}_d"
inst = ", ".join(f".{n}({conn[n]})" for _, _, n in ports)
pp = ", ".join(f".{n}({n})" for n in pnames)
L.append(f" {spec['core']} #({pp}) u_core ({inst});")
L.append("endmodule\n")
L.append(core)
L.append("`default_nettype wire")
open(out, "w").write("\n".join(L) + "\n")
print("wrote", out, "ports", len(ports))
