#!/usr/bin/env python3
"""Emit the die's hb_idx.key_lines wiring for one IDX stack as SystemVerilog assigns, FROM the generated v16 contract
(H-NETLIST idxcoll 2026-10-15), so the key-service bench exercises exactly the netlist's bit mapping.

    idx_key_wiring_2210.py CONTRACT.json STACK OUT.svh      (STACK 0..3 = scorer j = key_lines[j*8792 +: 8792])

OUT.svh: `assign key_lines[k] = <inst>__<port>[b];` for the 8,792 bits of the stack, every bit from a contract edge.
"""
import json, sys
c = json.load(open(sys.argv[1])); j = int(sys.argv[2]); lo, hi = j * 8792, j * 8792 + 8792
bit = {}
for e in c['edges']:
    si, sp, slo, shi = e['source']; di, dp, dlo, dhi = e['sink']
    if (di, dp) != ('hb_idx', 'key_lines'):
        continue
    for k in range(dhi - dlo):
        if lo <= dlo + k < hi:
            assert dlo + k not in bit
            bit[dlo + k] = (si, sp, slo + k)
missing = [k for k in range(lo, hi) if k not in bit]
assert not missing, f'{len(missing)} key_lines bits of stack {j} have no contract edge'
srcs = sorted({(s, p) for s, p, _ in bit.values()})
L = [f'// generated by tools/hbm_die_v15/idx_key_wiring_2210.py from {sys.argv[1]} (stack {j}): {len(srcs)} sources']
for k in range(lo, hi):
    s, p, b = bit[k]
    L.append(f'assign key_lines[{k - lo}] = {s}__{p}[{b}];')
open(sys.argv[3], 'w').write('\n'.join(L) + '\n')
print(sys.argv[3], len(bit), 'bits from', [f'{s}.{p}' for s, p in srcs])
