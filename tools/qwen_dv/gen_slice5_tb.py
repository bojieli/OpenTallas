#!/usr/bin/env python3
"""gen_slice5_tb.py -- QW-SLICE6 10-19: lockstep bench qfd_dv_slice2 #(SU_TLS 1, SU_LT 1, HD_W130 1, MU_NU 4,
PRIVATE_CALR 1) vs the wires-only re-cut qfd_dv_s5_flat0 (tools/qwen_dv/gen_slice5_flat.py) at offset 0.

Stimulus modes (plusargs): default = random words on every input every edge (treq valid 1/64); +quiet = no commands,
chains or rs words (the heads / hr paths and the fault joins are visible); +hronly = only the head-row control.
+legal = commands restricted to SETID + kinds 1..6 for slice 0 (sid 0) and the other inputs random (the decode,
config and VM write merge paths fire without saturating the port fault first).  Every output is compared every edge
after reset release (+ a 20-edge warm-up), two resets (the second at CYC/2).
Prints S5_EQ PASS / S5_EQ FAIL (and S5_MISMATCH lines).  Mutants (must FAIL): -GDMUT=10 (SETID forwards the id
unincremented, qfd_dv_s5_fup), +define+OT_S5_LOFF_MUT (lane offset applied twice, suvm), +define+OT_S5_LRLY_MUT
(lane memory answers skip their relay stage, lrly).

    python3 tools/qwen_dv/gen_slice5_tb.py   -> rtl/test/qwen_dv/s5/tb_qfd_dv_s5_flat0.sv
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/qwen_dv/gen_slice5_flat.py"


def ports():
    txt = SRC.read_text()
    blk = txt[txt.index('PORTS = """') + 11: txt.index('"""', txt.index('PORTS = """') + 11)]
    out = []
    for line in blk.splitlines():
        m = re.match(r"\s*(input|output)\s+wire\s+(\[(\d+):0\])?\s*(.*?),?\s*$", line)
        if not m:
            continue
        w = int(m.group(3)) + 1 if m.group(3) else 1
        for n in m.group(4).split(","):
            n = n.strip()
            if n:
                out.append((m.group(1), n, w))
    return out


def rnd(w):
    return "{" + ",".join(["$urandom"] * ((w + 31) // 32)) + "}"


def main():
    P = ports()
    ins = [(n, w) for d, n, w in P if d == "input" and n not in ("ck", "rst_n")]
    outs = [(n, w) for d, n, w in P if d == "output"]
    L = []
    w = L.append
    w("`timescale 1ns/1ps")
    w("// GENERATED by tools/qwen_dv/gen_slice5_tb.py (QW-SLICE6 10-19) -- do not edit.")
    w("// Lockstep qfd_dv_slice2 (SU_TLS 1, SU_LT 1, HD_W130 1, MU_NU 4, PRIVATE_CALR 1) vs qfd_dv_s5_flat0 at offset 0.")
    w("module tb_qfd_dv_s5_flat0;")
    w("    parameter integer CYC = 6000;")
    w("    parameter integer DMUT = 0;")
    w("    reg ck = 1'b0;  always #0.5 ck = ~ck;")
    w("    reg rst_n = 1'b0;")
    for n, b in ins:
        w(f"    reg [{b-1}:0] {n};")
    for n, b in outs:
        w(f"    wire [{b-1}:0] a_{n}, b_{n};")
    conn = lambda pre: ", ".join([".ck(ck)", ".rst_n(rst_n)"] + [f".{n}({n})" for n, b in ins] + [f".{n}({pre}_{n})" for n, b in outs])
    w("    qfd_dv_slice2 #(.SU_TLS(1), .SU_LT(1), .HD_W130(1), .MU_NU(4), .PRIVATE_CALR(1)) u_ref (" + conn("a") + ");")
    w("    qfd_dv_s5_flat0 #(.MUT(DMUT)) u_dut (" + conn("b") + ");")
    w(f"    integer pnz [0:{len(outs)-1}];")
    w("    integer cyc, bad, nc, nz, k, naf, nhf, rel; reg quiet, hronly, legal;")
    w("    always @(posedge ck) if (rst_n) begin naf = naf + (u_ref.any_fault ? 1 : 0); nhf = nhf + (u_ref.hd_fault ? 1 : 0); end")
    w("    initial begin")
    w("        bad = 0; nc = 0; nz = 0; naf = 0; nhf = 0; rel = 16;")
    w("        quiet = $test$plusargs(\"quiet\"); hronly = $test$plusargs(\"hronly\"); legal = $test$plusargs(\"legal\");")
    w(f"        for (k = 0; k < {len(outs)}; k = k + 1) pnz[k] = 0;")
    for n, b in ins:
        w(f"        {n} = '0;")
    w("        for (cyc = 0; cyc < CYC; cyc = cyc + 1) begin")
    w("            @(negedge ck);")
    w("            if (cyc == 16) rst_n = 1'b1;")
    w("            if (cyc == CYC / 2) begin rst_n = 1'b0; rel = CYC / 2 + 8; end")
    w("            if (cyc == CYC / 2 + 8) rst_n = 1'b1;")
    for n, b in ins:
        r = rnd(b)
        if n == "hr_i":
            w(f"            {n} = {r};")
        elif n == "cmd_i":
            w(f"            {n} = (quiet || hronly) ? '0 : {r};")
            w("            if (legal) begin")
            w("                // SETID (kind 7, id 0) for the first edges after a release, then slice-0 / broadcast commands")
            w("                if (cyc < rel + 24) cmd_i = {108'd0, 4'd0, 3'd7, 1'b1};")
            w("                else begin cmd_i[115:112] = ($urandom % 4 == 0) ? 4'hF : 4'h0; cmd_i[3:1] = 3'($urandom % 7);")
            w("                           cmd_i[0] = ($urandom % 3 == 0); end")
            w("            end")
        elif n == "treq_i":
            w(f"            {n} = (quiet || hronly) ? '0 : ($urandom % 64 == 0) ? {{1'b1, 8'($urandom)}} : {{1'b0, 8'($urandom)}};")
        elif n in ("st_up_i", "st_dn_i", "sc_up_i", "sc_dn_i"):
            w(f"            {n} = hronly ? '0 : {r};")
        else:
            w(f"            {n} = (quiet || hronly) ? '0 : {r};")
    w("            if (rst_n && cyc > rel + 20) begin")
    for i, (n, b) in enumerate(outs):
        w(f"                nc = nc + 1; if (|a_{n}) begin nz = nz + 1; pnz[{i}] = pnz[{i}] + 1; end"
          f" if (a_{n} !== b_{n}) begin bad = bad + 1; if (bad <= 12) $display(\"S5_MISMATCH port={n} cycle=%0d ref=%h dut=%h\", cyc, a_{n}, b_{n}); end")
    w("            end")
    w("        end")
    for i, (n, b) in enumerate(outs):
        w(f"        $display(\"S5_NZ {n} %0d\", pnz[{i}]);")
    w("        $display(\"S5_FAULT_CYCLES any=%0d heads=%0d\", naf, nhf);")
    w("        if (bad == 0 && nc > 0) $display(\"S5_EQ PASS quiet=%0d hronly=%0d legal=%0d compared=%0d nonzero=%0d cycles=%0d\", quiet, hronly, legal, nc, nz, CYC);")
    w("        else $display(\"S5_EQ FAIL quiet=%0d hronly=%0d legal=%0d mismatches=%0d of %0d\", quiet, hronly, legal, bad, nc);")
    w("        $finish;")
    w("    end")
    w("endmodule")
    out = ROOT / "rtl/test/qwen_dv/s5/tb_qfd_dv_s5_flat0.sv"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
