#!/usr/bin/env python3
"""Generate an opt-in exact static-slot packer; original stream stays unchanged."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def generate():
    source=(ROOT/'rtl/qwen_dv/qfd_dv_stream.sv').read_text()
    start=source.index('    integer l;')
    stop=source.index('    always @(posedge ck or negedge rst_n) begin',start)
    legacy=source[start:stop]
    rows=['    wire [63:0] nm;','    wire [1023:0] nb;','    wire pbad;',
          '    generate if (!STATIC_PACKER) begin: g_legacy',
          legacy.replace('nm','legacy_nm').replace('nb','legacy_nb').replace('pbad','legacy_pbad'),
          '    assign nm=legacy_nm; assign nb=legacy_nb; assign pbad=legacy_pbad;',
          '    end else begin: g_static',
          '    wire [127:0] lane_data;',
          '    for(genvar l=0;l<8;l=l+1) begin: g_bf',
          '        assign lane_data[16*l+:16]=bf16(xw_data[32*l+:32]);',
          '    end',
          '    wire [63:0] slot_bad;',
          '    for(genvar s=0;s<64;s=s+1) begin: g_slot',
          '        wire [7:0] hit, select_lane;',
          '        wire [127:0] contribution;',
          '        for(genvar l=0;l<8;l=l+1) begin: g_lane',
          "            assign hit[l]=xw_we[l] && xw_addr[24*l+:6]==6'(s);",
          '            if(l==7) assign select_lane[l]=hit[l];',
          '            else assign select_lane[l]=hit[l] && ((MUT==21) || !(|hit[7:l+1]));',
          '            assign contribution[16*l+:16]=lane_data[16*l+:16] & {16{select_lane[l]}};',
          '        end',
          '        wire [15:0] packed_slot;',
          '        for(genvar b=0;b<16;b=b+1) begin: g_bit',
          '            wire [7:0] terms;',
          '            for(genvar l=0;l<8;l=l+1) begin: g_term',
          '                assign terms[l]=contribution[16*l+b];',
          '            end',
          '            assign packed_slot[b]=|terms;',
          '        end',
          '        assign nb[16*s+:16]=(|hit)?packed_slot:xb[16*s+:16];',
          '        assign nm[s]=(xopen && xm[s]) || (|hit);',
          '        wire [7:0] duplicate;',
          '        for(genvar l=0;l<8;l=l+1) begin: g_dup',
          "            if(l==0) assign duplicate[l]=1'b0;",
          '            else assign duplicate[l]=hit[l] && (|hit[l-1:0]);',
          '        end',
          '        assign slot_bad[s]=(MUT==22)?1\'b0:((xopen && xm[s] && (|hit)) || (|duplicate));',
          '    end',
          '    wire [7:0] beat_bad;',
          '    for(genvar l=0;l<8;l=l+1) begin: g_beat',
          '        assign beat_bad[l]=xw_we[l] && (!xw_we[0] || xw_addr[24*l+6+:16]!=xw_addr[6+:16]);',
          '    end',
          '    assign pbad=(|slot_bad) || (|beat_bad) || (xw_we[0] && xopen && xw_addr[6+:16]!=xbeat);',
          '    end endgenerate']
    source=source[:start]+'\n'.join(rows)+'\n'+source[stop:]
    source=source.replace('module qfd_dv_stream #(','module qfd_dv_stream_packer #(',1)
    source=source.replace('parameter integer MUT = 0','parameter integer MUT = 0,\n    parameter integer STATIC_PACKER = 0',1)
    return '// GENERATED by tools/qwen_dv/static_stream_packer.py; legacy default unchanged.\n'+source
if __name__=='__main__':
    (ROOT/'rtl/qwen_dv/qfd_dv_stream_packer.sv').write_text(generate())
