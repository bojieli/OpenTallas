#!/usr/bin/env python3
"""QW-SLICE3 10-19: generate the 8-region station leaf wrapper + the two kit specs.

  rtl/qwen_dv/qfd_dv_redstn2_rg8.sv            flat leaf top: per-region SCALAR clock ck_r<r>, reset rst_n_r<r> and
                                                 per-region port groups (*_r<r>), so every IO belongs to exactly one
                                                 clock_entry_domain (multiple_cts_roots, related_same_frequency).
  physical/ref_tile/specs/qfd_dv_slice2_stn8.json   station leaf, 8 CTS roots (one per SU-lane region), 2x4 regions
  physical/ref_tile/specs/qfd_dv_slice2_stnrg.json  one region as its own hardened tile (single root) = parallel variant

Region placement (2x4, folded fault ring 0,2,4,6,7,5,3,1 = physical neighbours): top row r=0,2,4,6 (N face),
bottom row r=1,3,5,7 (S face); region r's pins sit on its own face segment so its cells and its tree stay local.
Usage: gen_station_rg8.py [--rw RW] [--rh RH]   (region cell size, um; multiples of 43.2)
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IN_W = [("cfg", 29), ("rs_s_lo", 64), ("rs_s_hi", 64), ("rs_n_lo", 64), ("rs_n_hi", 64), ("rs_s_c", 4), ("rs_n_c", 4),
        ("nb_d", 64), ("nb_c", 2), ("bt_q", 32)]
OUT_W = [("nb_od", 64), ("r_d", 64)]
R0_OUT = [("nb_oc", 2), ("bt_re", 1), ("bt_word", 9), ("r_v", 1), ("r_idx", 8), ("r_last", 1), ("fault", 1)]
SRCS = ["rtl/qwen_dv/qfd_dv_redstn2_rg8.sv", "rtl/qwen_dv/qfd_dv_redstn2_regional.sv", "rtl/qwen_dv/qfd_dv_redstn2_gsafe.sv",
        "rtl/qwen_dv/qfd_dv_station_math_g.sv", "rtl/qwen_dv/qfd_dv_ring_delay.sv", "rtl/qwen_dv/qfd_dv_reset_tree.sv",
        "rtl/common/landed_parent/ot_pl_land.sv", "rtl/common/landed_parent/ot_pl_land_physical.sv",
        "rtl/hdc/ot_hdc_fastfp.sv", "rtl/hdc/ot_hdc_fp32_add_lat.sv", "rtl/hdc/ot_hdc_fp32_mul_lat.sv", "rtl/hdc/ot_hdc_prefix.sv",
        "physical/asap7_memory_macros_v2/ot_sram_1r1w_32x64_m1/ot_sram_1r1w_32x64_m1_bb.v"]
SRAM = "physical/asap7_memory_macros_v2/ot_sram_1r1w_32x64_m1"


def rng(w):
    return f"[{w-1}:0] " if w > 1 else ""


def wrapper():
    p = [f"input wire ck_r{r}, rst_n_r{r}" for r in range(8)]
    for r in range(8):
        p += [f"input wire {rng(w)}{n}_r{r}" for n, w in IN_W]
        p += [f"output wire {rng(w)}{n}_r{r}" for n, w in OUT_W]
    p += [f"output wire {rng(w)}{n}" for n, w in R0_OUT]
    cat = lambda n: "{" + ",".join(f"{n}_r{r}" for r in reversed(range(8))) + "}"
    s = ["`timescale 1ns/1ps",
         "// GENERATED by tools/qwen_dv/gen_station_rg8.py (QW-SLICE3 10-19): the 8-region station as one leaf with eight",
         "// independent CTS roots ck_r0..ck_r7 (one per SU-lane region, related same-frequency clocks).  Every port group",
         "// *_r<r> is owned by region r's clock; region-0 control outputs (bt_re/bt_word/r_v/r_idx/r_last/nb_oc/fault) by ck_r0.",
         "// The only region-to-region path is the landed sticky-fault ring inside qfd_dv_redstn2_rg.",
         "module qfd_dv_redstn2_rg8 #(parameter integer PIN_IN = 1, BT_LAT = 1) (", "    " + ",\n    ".join(p), ");"]
    s.append("wire [511:0] nb_od_all, r_d_all;")
    s.append("qfd_dv_redstn2_rg #(.MUT(0),.PIN_IN(PIN_IN),.BT_LAT(BT_LAT)) u_rg (")
    s.append(f"    .ck_r({cat('ck')}), .rst_n_r({cat('rst_n')}), .cfg_r({cat('cfg')}),")
    s.append(f"    .rs_s_lo({cat('rs_s_lo')}), .rs_s_hi({cat('rs_s_hi')}), .rs_n_lo({cat('rs_n_lo')}), .rs_n_hi({cat('rs_n_hi')}),")
    s.append(f"    .rs_s_c({cat('rs_s_c')}), .rs_n_c({cat('rs_n_c')}), .nb_d({cat('nb_d')}), .nb_c({cat('nb_c')}),")
    s.append("    .nb_od(nb_od_all), .nb_oc(nb_oc), .bt_re(bt_re), .bt_word(bt_word),")
    s.append(f"    .bt_q({cat('bt_q')}), .r_v(r_v), .r_idx(r_idx), .r_last(r_last), .r_d(r_d_all), .fault(fault));")
    for r in range(8):
        s.append(f"assign nb_od_r{r} = nb_od_all[64*{r} +: 64]; assign r_d_r{r} = r_d_all[64*{r} +: 64];")
    s.append("endmodule\n")
    return "\n".join(s)


CHECKLIST = {
    "1_pins": "PASS: PIN_IN=1 one pin register on every data/control input; outputs are flop Q; rst_n lands in 2 registered stages (rst_l0/rst_l1) then kept 32-ary trees",
    "2_reach": "PASS by construction: no region-to-region data; the only crossing (fault ring) is a landed hop (4-slot writer at source clock, K=2 reader at destination) between physical neighbours (folded 0,2,4,6,7,5,3,1)",
    "3_fanout": "PASS by construction: control replicated per region from per-region input copies; cfg_v 1->24 kept copies, mode/valid copies <=16; reset kept copies <=32 (qfd_dv_reset_tree); gate textbook_lint high_fanout confirms",
    "4_depth": "inherited R8 bounded math (ADD7/SCALE6 kernels); gate logic_depth WARN/--cts path classes confirm",
    "5_storage": "PASS: skew/hb/h9/scale-wait in 32x64 SRAM macros (5 per region, 40 total); valid/bad bits in finite 4-slot rings",
    "6_floorplan": "macros placed by gen on the asap7 lattice; outline from gate synthesis area; 2x4 region grid (stn8), square region (stnrg)",
    "7_clock": "8 regional CTS roots (stn8: multiple_cts_roots related_same_frequency) / one root per hardened region (stnrg); crossings landed; io_hold_margin 0.03",
    "8_schedule": "static: PIN_IN +1 edge on every input, BT_LAT +1 on the bt round trip, reset release +2, fault visibility <= 28 edges (sticky diagnostic) -> compiler schedule",
}


OPTOUT = {"pin_regs": {"enable": False, "reason": "the RTL registers every data/control input at its pin (PIN_IN=1, in the region's own clock) and every output is flop Q; the flow wrapper would add a second +1 register (single clock)"},
          "reset_landing": {"enable": False, "reason": "the RTL lands rst_n in 2 registered stages (rst_l0/rst_l1) in each region's own clock, then kept 32-ary trees (qfd_dv_reset_tree)"}}


def job(name, purpose, mem):
    return {"owner": "Claude:QW-SLICE3", "branch": "claude/qw-slice3-1019", "tag": "g2", "purpose": purpose,
            "extra_paths": ["rtl/qwen_dv", "rtl/hdc", "rtl/common/landed_parent", "physical/asap7_memory_macros_v2/ot_sram_1r1w_32x64_m1"],
            "benches": [
                {"name": "station_regional_eq", "cmd": "PIN=1 bash rtl/test/qwen_dv/safe_storage/run_station_regional.sh {RUN}/bench/rg 0 0",
                 "expect": "pass", "threads": 8, "peak_ram_gb": 16, "needs": ["verilator"]},
                {"name": "station_regional_rmut1", "cmd": "PIN=1 bash rtl/test/qwen_dv/safe_storage/run_station_regional.sh {RUN}/bench/rg 0 1",
                 "expect": "fail", "fail_regex": "REGIONAL_STATION_MISMATCH", "threads": 8, "peak_ram_gb": 16, "needs": ["verilator"]}],
            "views_to": f"physical/ref_tile/{name}/views", "record_to": f"results/rtl/ref_tile/{name}"}


def specs(rw, rh):
    region_pins = {"W": ["ck", "rst_n", "cfg_v_p", "cfg_mode_p", "cfg_wsrc_p", "cfg_nwords_p", "cfg_sbase_p", "cfg_kcm1_p",
                         "rs_s_lo_p", "rs_s_hi_p", "rs_s_c_p", "flt_bank_i", "flt_vld_i"],
                   "N": ["rs_n_lo_p", "rs_n_hi_p", "rs_n_c_p", "nb_d_p", "nb_c_p"],
                   "S": ["bt_re", "bt_word", "bt_q_p", "r_v", "r_idx", "r_last", "r_d"],
                   "E": ["nb_od", "nb_oc", "flt_bank_o", "flt_vld_o", "fault"]}
    route = {"pd": 0.5, "threads": 16, "peak_ram_gb": 64, "hold_margin_ns": 0.03, "macro_halo_um": 5.4, "io_hold_margin_ns": 0.03}
    a = {"name": "qfd_dv_slice2_stnrg", "top": "qfd_dv_redstn2_region", "kind": "tile", "diagnostic": True,
         "sources": [s for s in SRCS if not s.endswith("_rg8.sv")], "params": {"PIN_IN": 1, "BT_LAT": 1, "MUT": 0},
         "clock_port": "ck", "reset_ports": ["rst_n"], "outline": {"w": rw, "h": rh},
         "macros": [{"view": SRAM, "count": 5}], "pins": region_pins, "route": dict(route),
         "safe_design_checklist": CHECKLIST, **OPTOUT,
         "job": job("qfd_dv_slice2_stnrg", "QW-SLICE3: one SU-lane region of the slice2 station (8 per station, own clock root)", 64)}
    # stn8: 2x4 regions; region r column c = r//2, row top (N) for even r, bottom (S) for odd r
    W8, H8 = 4 * rw, 2 * rh
    pins = {"N": [], "S": [], "W": [], "E": []}
    ranges = {}
    for r in range(8):
        face = "N" if r % 2 == 0 else "S"
        c = r // 2
        names = [f"ck_r{r}", f"rst_n_r{r}"] + [f"{n}_r{r}" for n, _ in IN_W] + [f"{n}_r{r}" for n, _ in OUT_W]
        if r == 0:
            names += [n for n, _ in R0_OUT]
        pins[face] += names
        lo, hi = c * rw + 4.32, (c + 1) * rw - 4.32
        step = (hi - lo) / len(names)
        for k, n in enumerate(names):
            ranges[n] = [round(lo + k * step, 3), round(lo + (k + 1) * step - 0.25, 3)]
    pins = {k: v for k, v in pins.items() if v}
    doms = {}
    for r in range(8):
        d = {"ratio": [1, 1], "ports": [f"ck_r{r}"], "inputs": [f"rst_n_r{r}"] + [f"{n}_r{r}" for n, _ in IN_W],
             "outputs": [f"{n}_r{r}" for n, _ in OUT_W] + ([n for n, _ in R0_OUT] if r == 0 else [])}
        doms["core" if r == 0 else f"region{r}"] = d
    b = {"name": "qfd_dv_slice2_stn8", "top": "qfd_dv_redstn2_rg8", "kind": "tile", "diagnostic": True,
         "sources": SRCS, "params": {"PIN_IN": 1, "BT_LAT": 1},
         "clock": "multiple_cts_roots", "clock_port": "ck_r0", "clock_ports": [f"ck_r{r}" for r in range(8)],
         "clock_entry_domains": doms, "clock_data_paths": "related_same_frequency",
         "clock_relationship": {"kind": "same_pll_fixed_phase", "ratio": [1, 1], "phase_ps": 0},
         "reset_ports": [f"rst_n_r{r}" for r in range(8)], "outline": {"w": W8, "h": H8},
         "macros": [{"view": SRAM, "count": 40}], "pins": pins, "pin_ranges": ranges,
         "route": dict(route, threads=32, peak_ram_gb=192, pin_balance={"group_max": 1, "h": "M4", "v": "M5"}),
         "safe_design_checklist": CHECKLIST, **OPTOUT,
         "job": job("qfd_dv_slice2_stn8", "QW-SLICE3: slice2 station, 8 regional CTS roots (one per SU-lane region), landed fault ring", 192)}
    return a, b


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rw", type=float, default=151.2)
    ap.add_argument("--rh", type=float, default=151.2)
    a = ap.parse_args()
    (ROOT / "rtl/qwen_dv/qfd_dv_redstn2_rg8.sv").write_text(wrapper())
    d = ROOT / "physical/ref_tile/specs"
    d.mkdir(parents=True, exist_ok=True)
    for s in specs(a.rw, a.rh):
        (d / f"{s['name']}.json").write_text(json.dumps(s, indent=1) + "\n")
        print("wrote", d / f"{s['name']}.json")


if __name__ == "__main__":
    main()
