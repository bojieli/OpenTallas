#!/usr/bin/env python3
"""Q-SLICE 10-17 (coordinator 0de): generate the two hardened face variants of the Q-DV slice2 core.

  qfd_dv_slice2_w  DIR 0: dn face (toward W5 / the W column) = master W face.  Die W row, placed R0.
  qfd_dv_slice2_e  DIR 1: dn face = master E face.  Die E row, placed MY, so the dn face lands on the die W side.

Both are thin port maps of qfd_dv_slice2 (no logic, no direction mux).  Port names are <kind>_<face><dir> in MASTER
coordinates; the AR words are split into exactly the io_collective port set (in_* / out_* / cmd_*) so W5 binds the
collective whole-port, and the D2D words stay whole (native59 dd_i / dr_o).  Also writes the face map JSON the die
writer (tools/qwen_split/dv_case.py) reads.

    python3 tools/qwen_dv/gen_slice_faces.py            # writes rtl/qwen_dv/qfd_dv_slice2_faces.{sv,json}
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# (port suffix kind, dir on the dn face, bits, core expression); the up face carries the opposite direction
# kinds that exist on one face only have face 'd' (dn) or 'u' (up)
AR = [('arv', 1, 546, 546), ('art', 32, 545, 514), ('arm', 1, 513, 513), ('arl', 1, 512, 512), ('ard', 512, 511, 0)]
RT = [('rv', 1, 517, 517), ('re', 1, 516, 516), ('rr', 3, 515, 513), ('rl', 1, 512, 512), ('rd', 512, 511, 0)]
CC = [('ccv', 1, 49, 49), ('ccm', 1, 48, 48), ('ccw', 16, 47, 32), ('cct', 32, 31, 0)]


def ports(dn):
    up = 'e' if dn == 'w' else 'w'
    P = []          # (name, dir, bits, face, core_port, slice_expr or None)
    add = lambda n, d, b, f, cp, sl=None: P.append((n, d, b, f, cp, sl))
    add('ck', 'input', 1, 'N', 'ck'); add('rst_n', 'input', 1, 'N', 'rst_n')
    add(f'cmd_{dn}i', 'input', 116, dn, 'cmd_i'); add(f'cmd_{up}o', 'output', 116, up, 'cmd_o')
    add(f'hr_{dn}i', 'input', 453, dn, 'hr_i'); add(f'hr_{up}o', 'output', 453, up, 'hr_o')
    add(f'st_{dn}o', 'output', 1088, dn, 'st_dn_o'); add(f'st_{dn}i', 'input', 1088, dn, 'st_up_i')
    add(f'st_{up}o', 'output', 1088, up, 'st_up_o'); add(f'st_{up}i', 'input', 1088, up, 'st_dn_i')
    add(f'sc_{dn}o', 'output', 48, dn, 'sc_dn_o'); add(f'sc_{dn}i', 'input', 48, dn, 'sc_up_i')
    add(f'sc_{up}o', 'output', 48, up, 'sc_up_o'); add(f'sc_{up}i', 'input', 48, up, 'sc_dn_i')
    for k, b, hi, lo in AR:                          # outbound AR word = ch[1094:548]
        add(f'{k}_{dn}o', 'output', b, dn, 'ch_dn_o', (548 + hi, 548 + lo))
        add(f'{k}_{up}i', 'input', b, up, 'ch_up_i', (548 + hi, 548 + lo))
    add(f'dd_{dn}o', 'output', 548, dn, 'ch_dn_o', (547, 0)); add(f'dd_{up}i', 'input', 548, up, 'ch_up_i', (547, 0))
    for k, b, hi, lo in RT:                          # AR return = ch_dn_i / ch_up_o [1037:520]
        add(f'{k}_{dn}i', 'input', b, dn, 'ch_dn_i', (520 + hi, 520 + lo))
        add(f'{k}_{up}o', 'output', b, up, 'ch_up_o', (520 + hi, 520 + lo))
    add(f'dr_{dn}i', 'input', 520, dn, 'ch_dn_i', (519, 0)); add(f'dr_{up}o', 'output', 520, up, 'ch_up_o', (519, 0))
    add(f'ag_{dn}o', 'output', 10, dn, 'ag_dn_o'); add(f'ag_{up}i', 'input', 10, up, 'ag_up_i')
    add(f'ss_{dn}o', 'output', 107, dn, 'st')
    for k, b, hi, lo in CC:
        add(f'{k}_{dn}o', 'output', b, dn, 'cc_o', (hi, lo))
    add('l9_wi', 'input', 514, 'w', 'l9_i'); add('l9_eo', 'output', 514, 'e', 'l9_o')
    for f in ('n', 's'):
        add(f'rs_{f}0', 'input', 514, f.upper(), f'rs_{f}', (513, 0))
        add(f'rs_{f}1', 'input', 514, f.upper(), f'rs_{f}', (1027, 514))
        for k in range(4):
            add(f'cw_{f}{k}', 'output', 516, f.upper(), f'cw_{f}{k}')
    return P


CORE_W = dict(ch_dn_o=1095, ch_up_i=1095, ch_dn_i=1038, ch_up_o=1038, cc_o=50, rs_n=1028, rs_s=1028)


def emit(dn, dirv):
    name = f'qfd_dv_slice2_{dn}'
    P = ports(dn)
    L = [f'// {name}: GENERATED by tools/qwen_dv/gen_slice_faces.py -- DIR {dirv} face variant of qfd_dv_slice2 '
         f'(dn face = master {dn.upper()}).',
         f'module {name} #(parameter integer MUT = 0, parameter integer SU_TLS = 1, parameter integer MU_NU = 1) (']
    L.append(',\n'.join(f'    {d:<6} wire [{b - 1}:0] {n}' if b > 1 else f'    {d:<6} wire {n}' for n, d, b, f, cp, sl in P))
    L.append(');')
    split = {}
    for n, d, b, f, cp, sl in P:
        if sl is not None:
            split.setdefault(cp, []).append((sl, n, d))
    for cp, parts in split.items():
        L.append(f'    wire [{CORE_W[cp] - 1}:0] w_{cp};')
        d = parts[0][2]
        if d == 'input':
            parts = sorted(parts, key=lambda t: -t[0][0])
            assert sum(h - l + 1 for (h, l), _, _ in parts) == CORE_W[cp], cp
            L.append(f'    assign w_{cp} = {{{", ".join(n for _, n, _ in parts)}}};')
        else:
            for (h, l), n, _ in parts:
                L.append(f'    assign {n} = w_{cp}[{h}:{l}];')
    conn = {}
    for n, d, b, f, cp, sl in P:
        conn[cp] = f'w_{cp}' if sl is not None else n
    L.append(f'    qfd_dv_slice2 #(.MUT(MUT), .SU_TLS(SU_TLS), .MU_NU(MU_NU), .DIR({dirv})) u_core (')
    L.append(',\n'.join(f'        .{cp}({e})' for cp, e in conn.items()))
    L.append('    );')
    L.append('endmodule')
    pm = [dict(port=n, dir=d, bits=b, face=f.upper()) for n, d, b, f, cp, sl in P]
    return '\n'.join(L) + '\n', pm


def main():
    sv = ['`timescale 1ns/1ps']
    js = {}
    for dn, dirv in (('w', 0), ('e', 1)):
        t, pm = emit(dn, dirv)
        sv.append(t)
        js[f'qfd_dv_slice2_{dn}'] = dict(dir=dirv, dn_face=dn.upper(), placement='R0' if dn == 'w' else 'MY', ports=pm)
    (ROOT / 'rtl/qwen_dv/qfd_dv_slice2_faces.sv').write_text('\n'.join(sv))
    (ROOT / 'rtl/qwen_dv/qfd_dv_slice2_faces.json').write_text(json.dumps(js, indent=1) + '\n')


if __name__ == '__main__':
    main()
