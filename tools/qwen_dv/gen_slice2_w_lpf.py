#!/usr/bin/env python3
"""Generate the W-facing wires-only slice partition from the maintained E partition.

The core implementation is shared with gen_slice2_lpf.py. L9 always travels W to E,
so unlike the other east/west ports it does not mirror with the command direction.
This generator does not turn the unresolved SU/VM clock loop into a landed seam.
"""
import copy
import json
import re
from pathlib import Path

import gen_slice2_lpf as east

ROOT = Path(__file__).resolve().parents[2]


def mirror_ports(text):
    def swap(match):
        name, face, direction = match.groups()
        return match.group(0) if name == 'l9' else f'{name}_{"w" if face == "e" else "e"}{direction}'
    return re.sub(r'\b([a-z][a-z0-9]*)_([ew])([io])\b', swap, text)


def top():
    text = mirror_ports(east.top())
    text = text.replace('qfd_dv_slice2_e_lpf', 'qfd_dv_slice2_w_lpf')
    text = re.sub(r'qfd_dv_slice2_e_t(\w+)', r'qfd_dv_slice2_w_t\1', text)
    text = text.replace('.DIR(1)', '.DIR(0)')
    # L9 stays on E while the down-facing command/status through-cell moves to W.
    text = text.replace(', .l9_o(c_l9_o)', '').replace(', .l9_eo(l9_eo)', '')
    anchor = '.rd_eo(rd_eo), .dr_eo(dr_eo));'
    if text.count(anchor) != 1:
        raise ValueError('W up-face through-cell changed; review fixed-direction L9 routing')
    text = text.replace(anchor, '.rd_eo(rd_eo), .dr_eo(dr_eo), .l9_o(c_l9_o), .l9_eo(l9_eo));')
    return text.replace('GENERATED by tools/qwen_dv/gen_slice2_lpf.py',
                        'GENERATED by tools/qwen_dv/gen_slice2_w_lpf.py')


def through_parts():
    original = east.THRU
    thru = {}
    for module, (comment, ports) in copy.deepcopy(original).items():
        module = module.replace('qfd_dv_slice2_e_t', 'qfd_dv_slice2_w_t')
        ports = [(pin, width, [(mirror_ports(out), hi, lo) for out, hi, lo in outputs])
                 for pin, width, outputs in ports]
        thru[module] = (comment, ports)
    l9 = next(p for p in thru['qfd_dv_slice2_w_te'][1] if p[0] == 'l9_o')
    thru['qfd_dv_slice2_w_te'][1].remove(l9)
    thru['qfd_dv_slice2_w_tw'][1].append(l9)
    try:
        east.THRU = thru
        return '`timescale 1ns/1ps\n' + east.thru_modules()
    finally:
        east.THRU = original


def landed_spec():
    spec = json.loads((ROOT / 'tools/landed_parent/specs/qfd_dv_slice2_e_lpf.json').read_text())
    spec['top'] = 'qfd_dv_slice2_w_lpf'
    spec['sources'] = ['rtl/qwen_dv/qfd_dv_slice2_w_lpf.sv']
    spec['child_sources'].append('rtl/qwen_dv/qfd_dv_slice2_w_lpf_thru.sv')
    spec['record_dir'] = 'results/arch/safe_qw_slice_w_1019/landed'
    spec['port_regions'] = {mirror_ports(port): ('ef' if region == 'wf' else 'wf' if region == 'ef' else region)
                            for port, region in spec['port_regions'].items()}
    spec['port_regions']['l9_wi'] = 'wf'
    for region in spec['regions']:
        if region['name'] == 'ef':
            region['insts'] = ['u_tw']
        elif region['name'] == 'wf':
            region['insts'] = ['u_te', 'u_tes']
    spec['why'] = ('W mirror of E landed partition; command direction DIR0, fixed W-to-E L9. '
                   'NOT READY TO GATE: core SU/VM loop still needs per-lane landed cuts; '
                   'the safe W kit must not claim this ten-region shell solves the core clock tree.')
    return spec


def main():
    outputs = {
        'rtl/qwen_dv/qfd_dv_slice2_w_lpf.sv': top(),
        'rtl/qwen_dv/qfd_dv_slice2_w_lpf_thru.sv': through_parts(),
        'tools/landed_parent/specs/qfd_dv_slice2_w_lpf.json': json.dumps(landed_spec(), indent=1) + '\n',
    }
    for path, value in outputs.items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(value)
        print(path)


if __name__ == '__main__':
    main()
