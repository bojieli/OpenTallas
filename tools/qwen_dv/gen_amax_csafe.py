#!/usr/bin/env python3
"""Fleet-only: specialize original arithmetic, partition reset, bound native cones.

Source construction is generic, before ABC. Existing arithmetic edges are
unchanged; every original async reset is served by a two-edge reset tree.
Actual technology mapping and independent equivalence remain required.
"""
import copy,json,re,subprocess,sys,inspect
import bound_math_netlist as BM
from pathlib import Path
from bound_math_netlist import build
root=Path(__file__).resolve().parents[2]
out=Path(sys.argv[1]).resolve();out.mkdir(parents=True,exist_ok=True)
cap=16 if '--internal-cap16' in sys.argv[2:] else 32
if cap==16:
    code=inspect.getsource(BM.build)
    assert 'sum(v[0] for v in x)>32]' in code and 'cost+sink[0]>32:' in code
    code=code.replace('sum(v[0] for v in x)>32]', 'sum(v[0] for v in x)>(16 if b in drivers else 32)]').replace('cost+sink[0]>32:', 'cost+sink[0]>16:')
    exec(code,BM.__dict__)
    build=BM.build

seed=root/'rtl/qwen_dv/mu/qfd_dv_amax_mu.sv'
helpers={};bodies=[];records=[];special_ports={}
for nu,mut in [(1,0)]+[(4,m) for m in range(6)]:
    tag=f'n{nu}m{mut}'; p=out/(tag+'.json')
    cmd=f'read_verilog -sv -D SYNTHESIS {seed}; chparam -set NU {nu} -set MUT {mut} qfd_dv_amax_mu; synth -top qfd_dv_amax_mu -flatten -noabc -nofsm -noshare; write_json {p}'
    with (out/(tag+'.log')).open('w') as log:subprocess.run(['yosys','-Q','-p',cmd],stdout=log,stderr=subprocess.STDOUT,check=True)
    design=json.loads(p.read_text());mod=design['modules']['qfd_dv_amax_mu'];cells=mod['cells']
    rst=mod['ports']['rst']['bits'][0];clk=mod['ports']['ck']['bits'][0]
    nxt=max(b for c in cells.values() for bs in c['connections'].values() for b in bs if isinstance(b,int))+1
    for cname,c in list(cells.items()):
        if c['type']=='$_DFFE_PN0P_':
            old=c['connections']['D'];en=c['connections'].pop('E');c['port_directions'].pop('E')
            c['connections']['D']=[nxt];c['type']='$_DFF_PN0_'
            cells[cname+'_enable']={'type':'$_MUX_','connections':{'A':c['connections']['Q'],'B':old,'S':en,'Y':[nxt]},'port_directions':{'A':'input','B':'input','S':'input','Y':'output'}}
            nxt+=1
    targets=[c for c in cells.values() if c['connections'].get('R')==[rst]]
    assert targets and all(c['type'].startswith('$_DFF_') for c in targets)
    nxt=max(b for c in cells.values() for bs in c['connections'].values() for b in bs if isinstance(b,int))+1
    branches=[]
    def ff(name,d):
        global nxt
        q=nxt;nxt+=1
        cells[name]={'type':'$_DFF_P_','connections':{'C':[clk],'D':[d],'Q':[q]},'port_directions':{'C':'input','D':'input','Q':'output'}}
        return q
    for k in range((len(targets)+1023)//1024):branches.append(ff(f'$reset_branch{k}',rst))
    for k in range(0,len(targets),32):
        q=ff(f'$reset_leaf{k//32}',branches[k//1024])
        for c in targets[k:k+32]:c['connections']['R']=[q]
    raw=json.dumps(design).encode();(out/(tag+'_reset.json')).write_bytes(raw)
    name='qfd_dv_amax_csafe_'+tag
    source,hs,record=build(raw,'qfd_dv_amax_mu',name)
    special_ports[tag]=re.search(r'module '+name+r'\(([^)]+)\)',source)[1].split(',')
    for h in hs:
        n=re.search(r'module (\w+)',h)[1]
        if n in helpers:assert helpers[n]==h
        helpers[n]=h
    bodies.append(source);record.update(NU=nu,MUT=mut,reset_root_loads=source.count(f'.D(n_{rst})'),original_reset_flops=len(targets),reset_release_extra_edges=2,internal_generic_load_cap=cap,input_generic_load_cap=32)
    records.append(record)
port='ck,rst,c_stn,stn_amax_bit,stn_user,stn_pend,r_v,r_addr,r_d,c_am,am_clr,am_emit_cmd,am_user,am_v,am_idx,am_val,am_u,emit_empty,mu_fault'
decl='''input wire ck,rst,c_stn,stn_amax_bit,stn_pend,r_v,c_am,am_clr,am_emit_cmd;
input wire[1:0] stn_user,am_user;input wire[23:0] r_addr;input wire[511:0] r_d;
output wire am_v,emit_empty,mu_fault;output wire[23:0] am_idx;output wire[31:0] am_val;output wire[1:0] am_u;
'''
con=','.join('.'+p+'('+p+')' for p in port.split(','))
wrap='module qfd_dv_amax_mu_csafe #(parameter integer NU=1,MUT=0,SAFE=1)('+port+');\n'+decl
wrap+='generate if(!SAFE) begin:g_legacy qfd_dv_amax_mu #(.NU(NU),.MUT(MUT)) u('+con+'); end\n'
for nu,mut in [(1,0)]+[(4,m) for m in range(6)]:
    cond='NU==1' if nu==1 else f'NU==4 && MUT=={mut}'
    sc=','.join('.'+p+'('+p+')' for p in special_ports[f'n{nu}m{mut}'])
    wrap+=f'else if({cond}) begin:g_n{nu}m{mut} qfd_dv_amax_csafe_n{nu}m{mut} u({sc}); end\n'
wrap+='else begin:g_unsupported initial $fatal(1,"csafe requires NU1/4 MUT0..5"); end endgenerate\nendmodule\n'
(out/'qfd_dv_amax_mu_csafe.sv').write_text('// Generated by gen_amax_csafe.py; +2 reset release, +0 data edges.\n'+wrap+'\n'.join(bodies)+'\n'.join(helpers.values())+'\n')
(out/'construction.json').write_text(json.dumps(records,indent=2)+'\n')
print(json.dumps(records,indent=2))
