def make_flat():
    t = FLAT5.read_text()
    t = t.replace("module qfd_dv_s5_flat (", "module qfd_dv_s7_flat (", 1)
    for inst, (old, new) in REBIND.items():
        pat = re.compile(r"^(\s+)" + re.escape(old) + r"(\s+" + re.escape(inst) + r"\s*\()", re.M)
        t, n = pat.subn(r"\1" + new + r"\2", t)
        if n != 1:
            raise SystemExit(f"rebind {inst}: {old} found {n} times")
    hdr = ("// GENERATED by tools/qwen_dv/gen_slice7_lp_spec.py (QW-S5-LP 10-21) from rtl/qwen_dv/s5/qfd_dv_s5_flat.sv -- do not edit.\n"
           "// Re-bound children (wires only, same instance names / port maps): "
           + ", ".join(f"{i} {o} -> {n}" for i, (o, n) in REBIND.items()) + ".\n")
    lines = t.split("\n")
    lines.insert(1, hdr.rstrip("\n"))
    FLAT6.parent.mkdir(parents=True, exist_ok=True)
    FLAT6.write_text("\n".join(lines))


def base_spec(name, D, E):
    S = g5.base_spec(name, D, E)
    S.update({
        "why": f"QW-S5-LP 10-21 Q.STA.SLICE.3/.4: slice2 W/E master with CLOSED children bound (su8_rst3, stream c3r, tload ns4, "
               f"ctl5, btab_s4, lrly; VM8 group vm8q), D {D} / E {E}; landing_chunk_bits 24 + regional_reset_copies (e5 census); "
               "every cross-region reader pin lagged E + 1 (cross-region loops: compiler re-schedule)",
        "top": "qfd_dv_s7_flat",
        "sources": ["rtl/qwen_dv/s5/s7/qfd_dv_s7_flat.sv"],
        "child_sources": CHILD_SOURCES,
        "defines": ["OT_S5_HARD"],
        "out_dir": OUT_DIR,
        "record_dir": REC_DIR,
        "landing_chunk_bits": 24,
        "regional_reset_copies": True,
        "landing_writer": "n32",
    })
    return S


def main():
    make_flat()
    out = ROOT / "tools/landed_parent/specs"
    for name, D, E in (("qfd_dv_s7b", 8, 4), ("qfd_dv_s7", 4, 2)):      # main last: its lagref keeps the shared name
        S = base_spec(name, D, E)
        lg, P = g5.lag_pins(S)
        S["lag_pins"] = lg
        (out / f"{name}.json").write_text(json.dumps(S, indent=1) + "\n")
        bits = sum(L["width"] for L in P["lands"])
        print(f"{name}: {len(P['lands'])} landings ({bits} bits), {sum(len(x['pins']) for x in lg)} lag pins on {len(lg)} instances")
        if "--gen" in sys.argv:
            lp.gen(lp.load(str(out / f"{name}.json")))
            if name != "qfd_dv_s7":
                d = ROOT / OUT_DIR
                src = (d / "qfd_dv_s7_flat_lagref.sv").read_text().replace("module qfd_dv_s7_flat_lagref", f"module {name}_flat_lagref")
                (d / f"{name}_flat_lagref.sv").write_text(src)
                for f in (d / f"tb_{name}_lp.sv", d / f"{name}_lp_bench.sh"):
                    f.write_text(f.read_text().replace("qfd_dv_s7_flat_lagref", f"{name}_flat_lagref"))


if __name__ == "__main__":
    main()
