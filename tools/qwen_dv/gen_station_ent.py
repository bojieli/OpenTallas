#!/usr/bin/env python3
"""QW-SLICE4 10-19 (Q.STA.SLICE.1): the slice2 reduction station as an ENTRIES cluster of 8 hardened region children
(qfd_dv_redstn2_region = closed kit qfd_dv_slice2_stnrgc, 151.2 x 151.2, one clock entry each).

Writes the WIRES-ONLY flat parent that tools/landed_parent/lp.py lands:

  rtl/qwen_dv/qfd_dv_redstn2_ef.sv                 qfd_dv_redstn2_ef: one clock ck, eight explicit region instances u_r0..u_r7,
                                                   ONE copy of the control inputs (cfg / rs_s_c / rs_n_c / nb_c: lp lands a
                                                   per-region copy into every other region), per-region data ports (each
                                                   region's 64-bit lane slices and its bt_q[32r +: 32] slice enter at the
                                                   region's own face), region-0 control outputs, and the fault ring as
                                                   child -> child wires flt_b<r> / flt_v<r> (lp lands each hop: loose
                                                   sticky-status nets).
  rtl/test/qwen_dv/safe_storage/stn_ef_inst.svh   tb_station_regional STN_EF mode: the flat parent in place of
                                                   qfd_dv_redstn2_rg (proves ef == monolith, PIN 1, + RMUT witnesses)
  rtl/test/qwen_dv/safe_storage/stn_ent_stim.svh  lp tb_stimulus: protocol-legal phase + random phase (as tb_station_regional)

Ring order (folded, every hop to a physical neighbour of the 2x4 array): 0,2,4,6 on row 0 (W -> E), 7,5,3,1 on row 1;
region r reads the writer of UP[r] (0<-2<-4<-6<-7<-5<-3<-1<-0).

    python3 tools/qwen_dv/gen_station_ent.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UP = {0: 2, 2: 4, 4: 6, 6: 7, 7: 5, 5: 3, 3: 1, 1: 0}
DATA_IN = [("rs_s_lo", 64), ("rs_s_hi", 64), ("rs_n_lo", 64), ("rs_n_hi", 64), ("nb_d", 64), ("bt_q", 32)]
DATA_OUT = [("nb_od", 64), ("r_d", 64)]


def flat_parent() -> str:
    L = ["`timescale 1ns/1ps",
         "// GENERATED by tools/qwen_dv/gen_station_ent.py (QW-SLICE4 10-19) -- do not edit.",
         "// Flat (single-clock, wires-only) parent of the 8-region station: input of tools/landed_parent/lp.py",
         "// (spec tools/landed_parent/specs/qfd_dv_stn_ent.json -> rtl/qwen_dv/lp/qfd_dv_redstn2_ef_lp.sv).",
         "// Same function as qfd_dv_redstn2_rg with every region's control copy fed from ONE port copy and the",
         "// region data slices as per-region ports; region-0 copies drive the control outputs.",
         "module qfd_dv_redstn2_ef (",
         "    input  wire         ck,",
         "    input  wire         rst_n,",
         "    input  wire [28:0]  cfg,           // {v, mode[1:0], wsrc, nwords[7:0], sbase[8:0], kcm1[7:0]}",
         "    input  wire [3:0]   rs_s_c,        // {rs_s[1027], rs_s[1026], rs_s[513], rs_s[512]}",
         "    input  wire [3:0]   rs_n_c,",
         "    input  wire [1:0]   nb_c,          // nb_i[513:512]"]
    for r in range(8):
        for n, w in DATA_IN:
            L.append(f"    input  wire [{w - 1}:0]  {n}_r{r},")
        for n, w in DATA_OUT:
            L.append(f"    output wire [{w - 1}:0]  {n}_r{r},")
    L += ["    output wire [1:0]   nb_oc,",
          "    output wire         bt_re,",
          "    output wire [8:0]   bt_word,",
          "    output wire         r_v,",
          "    output wire [7:0]   r_idx,",
          "    output wire         r_last,",
          "    output wire         fault",
          ");"]
    for r in range(8):
        L.append(f"    wire [3:0] flt_b{r}, flt_v{r};")
    for r in range(1, 8):
        L.append(f"    wire [1:0] nb_oc_x{r}; wire bt_re_x{r}; wire [8:0] bt_word_x{r}; wire r_v_x{r}; wire [7:0] r_idx_x{r};"
                 f" wire r_last_x{r}; wire fault_x{r};")
    for r in range(8):
        u = UP[r]
        sfx = "" if r == 0 else f"_x{r}"
        L.append(f"    qfd_dv_redstn2_region #(.PIN_IN(1), .BT_LAT(1)) u_r{r} (.ck(ck), .rst_n(rst_n),")
        L.append(f"        .cfg_v_p(cfg[28]), .cfg_mode_p(cfg[27:26]), .cfg_wsrc_p(cfg[25]), .cfg_nwords_p(cfg[24:17]),"
                 f" .cfg_sbase_p(cfg[16:8]), .cfg_kcm1_p(cfg[7:0]),")
        L.append(f"        .rs_s_lo_p(rs_s_lo_r{r}), .rs_s_hi_p(rs_s_hi_r{r}), .rs_n_lo_p(rs_n_lo_r{r}), .rs_n_hi_p(rs_n_hi_r{r}),"
                 f" .rs_s_c_p(rs_s_c), .rs_n_c_p(rs_n_c),")
        L.append(f"        .nb_d_p(nb_d_r{r}), .nb_c_p(nb_c), .nb_od(nb_od_r{r}), .nb_oc(nb_oc{sfx}), .bt_re(bt_re{sfx}),"
                 f" .bt_word(bt_word{sfx}), .bt_q_p(bt_q_r{r}),")
        L.append(f"        .r_v(r_v{sfx}), .r_idx(r_idx{sfx}), .r_last(r_last{sfx}), .r_d(r_d_r{r}),")
        L.append(f"        .flt_bank_i(flt_b{u}), .flt_vld_i(flt_v{u}), .flt_bank_o(flt_b{r}), .flt_vld_o(flt_v{r}),"
                 f" .fault(fault{sfx}));")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def tb_inst() -> str:
    """tb_station_regional STN_EF: u_g = the flat parent (same g_* nets as the qfd_dv_redstn2_rg instance)"""
    L = ["// GENERATED by tools/qwen_dv/gen_station_ent.py: tb_station_regional STN_EF mode (flat entries parent as u_g).",
         "wire [255:0] bt_q_e = (RMUT == 1) ? {bt_q_g[255:192], bt_q_g[159:128], bt_q_g[159:0]} : bt_q_g;",
         "qfd_dv_redstn2_ef u_g (.ck(ck), .rst_n(rst_n), .cfg({cfg_v, cfg_mode, cfg_wsrc, cfg_nwords, cfg_sbase, cfg_kcm1}),",
         "    .rs_s_c({rs_s[1027:1026], rs_s[513:512]}), .rs_n_c({rs_n[1027:1026], rs_n[513:512]}), .nb_c(nb_i[513:512]),"]
    for r in range(8):
        L.append(f"    .rs_s_lo_r{r}(rs_s[{64 * r + 63}:{64 * r}]), .rs_s_hi_r{r}(rs_s[{514 + 64 * r + 63}:{514 + 64 * r}]),"
                 f" .rs_n_lo_r{r}(rs_n[{64 * r + 63}:{64 * r}]), .rs_n_hi_r{r}(rs_n[{514 + 64 * r + 63}:{514 + 64 * r}]),"
                 f" .nb_d_r{r}(nb_i[{64 * r + 63}:{64 * r}]), .bt_q_r{r}(bt_q_e[{32 * r + 31}:{32 * r}]),"
                 f" .nb_od_r{r}(g_nb_o[{64 * r + 63}:{64 * r}]), .r_d_r{r}(g_r_d[{64 * r + 63}:{64 * r}]),")
    L.append("    .nb_oc(g_nb_o[513:512]), .bt_re(g_bt_re), .bt_word(g_bt_word), .r_v(g_r_v), .r_idx(g_r_idx), .r_last(g_r_last),"
             " .fault(g_fault));")
    L.append("generate if (RMUT == 2) begin : g_cut")
    L.append("    initial begin #1; force u_g.flt_b3 = 4'd0; force u_g.flt_v3 = 4'd0; end")
    L.append("end endgenerate")
    return "\n".join(L) + "\n"


def stim() -> str:
    """lp tb_stimulus (module-level include inside tb_qfd_dv_redstn2_ef_lp): drives fi_<port> and rst, then lp_finish.
    Phase 1 (first reset): protocol-legal mode-0 traffic (valid pattern of period SKEW = 14, cfg only in a valid-free
    window, clean data) with one NaN injected into lane 6 (region 3) so the fault must travel the landed ring to region 0;
    phase 2 (second reset): unconstrained random traffic, all modes, specials, colliding configuration (as
    tb_station_regional).  bt_q_r<k> is the bt table read of the flat parent's bt_word one edge late, delayed by the
    landed offset of bt_q_r<k> (the slice presents every region's bt slice at that region's schedule)."""
    S = ["// GENERATED by tools/qwen_dv/gen_station_ent.py: lp tb_stimulus of qfd_dv_redstn2_ef (QW-SLICE4 10-19).",
         "localparam integer SN = 16000;",
         "integer scy = 0, sph = 0; reg sact = 0, sinj = 0, squiet = 1; reg [14:0] slo = 0;",
         "function automatic [31:0] sfp(input integer clean);",
         "    reg [31:0] x; begin x = $random; x[30:23] = 8'd100 + (x[30:23] & 8'h3f);",
         "    if (!clean && (($random & 63) == 0)) x[30:23] = 8'hff; sfp = x; end",
         "endfunction",
         "function automatic [255:0] sbt(input [8:0] w);",
         "    reg [255:0] x; reg [31:0] h; begin",
         "        for (integer l = 0; l < 16; l = l + 1) begin",
         "            h = (w * 32'h9e3779b1) ^ (l * 32'h85ebca6b); h = h ^ (h >> 13); h = h * 32'hc2b2ae35;",
         "            x[16*l +: 16] = {h[15], 8'd120 + {4'd0, h[3:0]}, h[10:4]};",
         "        end",
         "        sbt = x; end",
         "endfunction",
         "reg [255:0] sbtq = 0;",
         "always @(posedge clk) sbtq <= sbt(fo_bt_word);   // the bt table: one-edge read of the FLAT parent's bt_word",
         "initial begin",
         "    rst = 1'b0;",
         "    fi_cfg = 0; fi_rs_s_c = 0; fi_rs_n_c = 0; fi_nb_c = 0;"]
    for r in range(8):
        S.append("    " + " ".join(f"fi_{n}_r{r} = 0;" for n, _ in DATA_IN))
    S += ["    while (scy < SN) begin",
          "        @(negedge clk); scy = scy + 1;",
          "        rst = !((scy < 6) || (scy >= SN/2 && scy < SN/2 + 6));",
          "        squiet = (scy < 60) || (scy >= SN/2 - 40 && scy < SN/2 + 60);"]
    for r in range(8):
        S.append(f"        fi_rs_s_lo_r{r} = {{sfp(scy < SN/2), sfp(scy < SN/2)}}; fi_rs_s_hi_r{r} = {{sfp(scy < SN/2), sfp(scy < SN/2)}};"
                 f" fi_rs_n_lo_r{r} = {{sfp(scy < SN/2), sfp(scy < SN/2)}}; fi_rs_n_hi_r{r} = {{sfp(scy < SN/2), sfp(scy < SN/2)}};"
                 f" fi_nb_d_r{r} = {{sfp(scy < SN/2), sfp(scy < SN/2)}};")
    S += ["        if (scy < SN/2) begin",
          "            sph = scy % 14; sact = (scy >= 60 && scy < SN/2 - 80);",
          "            fi_cfg = {(scy == 40) || (sact && sph == 1 && (scy % 224) < 14), 2'd0, 1'((scy/8)%2), 8'd255, 9'((scy/16)%512), 8'd0};",
          "            slo = {slo[13:0], sact && ((14'b10110110100000 >> sph) & 1'b1)};",
          "            fi_rs_s_c = {1'b0, slo[14], 1'b0, slo[0]}; fi_rs_n_c = {1'b0, slo[14], 1'b0, slo[0]}; fi_nb_c = 2'd0;",
          "            if (scy >= SN/4 && slo[14] && !sinj) begin fi_rs_s_hi_r3[63:32] = 32'h7fc00000; sinj = 1; end",
          "        end else if (squiet) begin",
          "            fi_cfg[28] = 1'b0; fi_rs_s_c = 0; fi_rs_n_c = 0; fi_nb_c = 0;"]
    for r in range(8):
        S.append("            " + " ".join(f"fi_{n}_r{r} = 0;" for n, _ in DATA_IN if n != "bt_q"))
    S += ["        end else begin",
          "            if (($random & 255) == 0) fi_cfg = {1'b1, 2'($random), 1'($random), 8'(1 + ($random & 63)), 9'($random), 8'($random & 3)};",
          "            else fi_cfg[28] = 1'b0;",
          "            begin : vb reg v; v = (($random & 3) != 0);",
          "                fi_rs_s_c = {1'b0, v, 1'(($random & 4095) == 0), v}; fi_rs_n_c = {1'b0, v, 1'b0, v};",
          "                fi_nb_c = {1'b0, 1'(($random & 7) == 0)}; end",
          "        end"]
    for r in range(8):
        S.append(f"        fi_bt_q_r{r} = sbtq[{32 * r + 31}:{32 * r}];")
    S += ["    end",
          "    lp_finish(\"stn_ent legal+inject / random, two resets\");",
          "end"]
    return "\n".join(S) + "\n"


def main():
    (ROOT / "rtl/qwen_dv/qfd_dv_redstn2_ef.sv").write_text(flat_parent())
    (ROOT / "rtl/test/qwen_dv/safe_storage/stn_ef_inst.svh").write_text(tb_inst())
    (ROOT / "rtl/test/qwen_dv/safe_storage/stn_ent_stim.svh").write_text(stim())
    print("wrote rtl/qwen_dv/qfd_dv_redstn2_ef.sv, rtl/test/qwen_dv/safe_storage/stn_ef_inst.svh, stn_ent_stim.svh")


if __name__ == "__main__":
    main()
