#!/usr/bin/env python3
"""Derive MU argmax reset banks; no data/comparator pipeline edge changes."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
s=(ROOT/'rtl/qwen_dv/mu/qfd_dv_amax_mu.sv').read_text()
a=s.index('    reg [16*57-1:0] al0;')
b=s.index('    reg am_emit;',a)
s=s[:a]+'''    wire [16*57-1:0] al0;
    wire [8*57-1:0] al1;
    wire [4*57-1:0] al2;
    wire [2*57-1:0] al3;
    wire [56:0] al4;
    wire [16*57-1:0] al0_d;
    wire [8*57-1:0] al1_d;
    wire [4*57-1:0] al2_d;
    wire [2*57-1:0] al3_d;
    genvar q;
    generate
      for(q=0;q<16;q=q+1) begin:g_a0
        assign al0_d[57*q+:57]={r_v&&stn_amax,r_addr+24'(q),r_d[32*q+:32]};
      end
      for(q=0;q<8;q=q+1) begin:g_a1
        assign al1_d[57*q+:57]=amb(al0[114*q+:57],al0[114*q+57+:57]);
      end
      for(q=0;q<4;q=q+1) begin:g_a2
        assign al2_d[57*q+:57]=amb(al1[114*q+:57],al1[114*q+57+:57]);
      end
      for(q=0;q<2;q=q+1) begin:g_a3
        assign al3_d[57*q+:57]=amb(al2[114*q+:57],al2[114*q+57+:57]);
      end
    endgenerate
    qfd_dv_reset_bank #(.W(16*57)) u_a0(.ck(ck),.rst_n(rst),.d(al0_d),.q(al0));
    qfd_dv_reset_bank #(.W(8*57)) u_a1(.ck(ck),.rst_n(rst),.d(al1_d),.q(al1));
    qfd_dv_reset_bank #(.W(4*57)) u_a2(.ck(ck),.rst_n(rst),.d(al2_d),.q(al2));
    qfd_dv_reset_bank #(.W(2*57)) u_a3(.ck(ck),.rst_n(rst),.d(al3_d),.q(al3));
    qfd_dv_reset_bank #(.W(57)) u_a4(.ck(ck),.rst_n(rst),.d(amb(al3[56:0],al3[113:57])),.q(al4));
''' + s[b:]
a=s.index('        reg [56:0] am_run;');b=s.index('        assign am_v',a)
s=s[:a]+'''        wire [56:0] am_run;
        qfd_dv_reset_bank #(.W(57)) u_run(.ck(ck),.rst_n(rst),
          .d((c_am&&am_clr)?57'd0:amb(am_run,al4)),.q(am_run));
'''+s[b:]
s=s.replace('reg [56:0] run [0:NU-1];','wire [56:0] run [0:NU-1];')
s=s.replace("                for (u = 0; u < NU; u = u + 1) run[u] <= 57'd0;\n",'')
a=s.index('                for (u = 0; u < NU; u = u + 1) begin')
b=s.index('                if (clr) open',a)
s=s[:a]+s[b:]
a=s.index('        wire [56:0] sel = run[am_eu];')
s=s[:a]+'''        for(genvar ur=0;ur<NU;ur=ur+1) begin:g_run
          wire [56:0] merged=(MUT==1)?((!run[ur][56]||okey(al4[31:0])>=okey(run[ur][31:0]))?al4:run[ur]):amb(run[ur],al4);
          wire [56:0] next_run=(clr&&(am_user==ur||MUT==3))?57'd0:
            (al4[56]&&mu==ur)?merged:run[ur];
          qfd_dv_reset_bank #(.W(57)) u_r(.ck(ck),.rst_n(rst),.d(next_run),.q(run[ur]));
        end
'''+s[a:]
assert 'run[u] <=' not in s and 'al0 <=' not in s
s='// Generated by tools/qwen_dv/gen_amax_rsafe.py; production safe-reset variant.\n'+s
(ROOT/'rtl/qwen_dv/mu/qfd_dv_amax_mu_rsafe.sv').write_text(s)
