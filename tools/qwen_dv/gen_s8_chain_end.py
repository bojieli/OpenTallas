#!/usr/bin/env python3
"""Chain-end variants of the Qwen compute DV slice (QC-P4 10-23, COORD R7: a chain-end input needs a real producer or
an RTL variant that removes the port, never a tie).

As built, the die ties 5,927 slice input bits to literals at the ends of the slice chains (BINDER2 qc3 bind_report
tied_by_port).  This generator writes rtl/qwen_dv/s5/s8/qfd_dv_s8_ce.sv: PORT-LESS variants of the slice and of the
leaves behind those ports, made by text transformation of the unchanged sources (so they track the as-built RTL):

  qfd_dv_s8_ce_l9h  l9 pair HEAD slice (E1/E3/E5-less-end, W1/W3/W5): no l9_i port (514 b).  u_fdn -> fdn_l9h (no
                    l9_i / l9_r* / l9_c), u_r0..u_r7 -> station_tail1_nb0 (no nb_d_p / nb_c_p: the mode-2 neighbour add
                    has no neighbour; its inputs fold to the as-built 0 inside the leaf and synthesis removes the stage).
  qfd_dv_s8_ce_e5   far-east chain END slice (dvs_E5): l9h + no st_dn_i (1,088 b), ch_up_i (1,095 b), ag_up_i (10 b).
                    u_fup -> fup_e5 (no st_dn_i / ch_up_i / ag_up_i, no se_q / chu_q / agu_q stage), u_fdn -> fdn_e5
                    (no chu_q / agu_q: the up-chain select falls to own_ch, ag_dn_o = ag_own), u_stm -> stm_se0
                    (stream tile without the east face se_lo / se_hi / se_v).
  qfd_dv_s8_ce_w5   W5 (QC-P5-TIE 10-23): l9h + no sc_up_i (48 b): u_fdn -> fdn_w5 (no sc_up_i / scu_q stage), u_sc ->
                    qfd_dv_s5_sc2_leaf_up0 (the k79 netlist regenerated without up_i, tools/qwen_dv/gen_sc2_chain_end.py).
  qfd_dv_s8_ce_e5   also no sc_dn_i (48 b, QC-P5-TIE): fup_e5 has no sc_dn_i / scd_q stage, u_sc -> qfd_dv_s5_sc2_leaf_dn0.
treq_i (9 b x 12 slices) is not a chain end: it is the CTLM table_req lane (planned beside cmd; QC-P5-TIE).

CE_MUT (bench negative control): 1 = every removed face folds to all-ones instead of the as-built zero.
Usage: python3 tools/qwen_dv/gen_s8_chain_end.py   (writes the .sv; --check exits 1 if the file is stale)
"""
import re, sys, hashlib
from pathlib import Path

R = Path(__file__).resolve().parents[2]
SRC = {
    'flat': 'rtl/qwen_dv/s5/s8/qfd_dv_s8_flat.sv',
    'fdn': 'rtl/qwen_dv/s5/s8/qfd_dv_s8_fdn_arf1.sv',
    'stn': 'rtl/qwen_dv/s5/s8/qfd_dv_s8_station_tail1.sv',
    'leaves6': 'rtl/qwen_dv/s5/s6/qfd_dv_s6_leaves.sv',
    'stream': 'rtl/qwen_dv/qfd_dv_stream_tile.sv',
}
OUT = R / 'rtl/qwen_dv/s5/s8/qfd_dv_s8_ce.sv'


def module(text, name):
    m = re.search(r'^module\s+' + name + r'\b.*?^endmodule\b', text, re.S | re.M)
    assert m, name
    return m.group(0)


def sub1(t, old, new, count=1):
    n = t.count(old)
    assert n == count, (old[:80], n, count)
    return t.replace(old, new)


def rsub(t, pat, new, count=1, flags=0):
    t2, n = re.subn(pat, new, t, flags=flags)
    assert n == count, (pat, n, count)
    return t2


def cst(w):
    return "(CE_MUT == 1 ? {%d{1'b1}} : %d'd0)" % (w, w)


def fdn_variant(src, end, w5=False):
    name = 'qfd_dv_s8_fdn_arf1_' + ('e5' if end else 'w5' if w5 else 'l9h')
    t = module(src, 'qfd_dv_s8_fdn_arf1')
    t = sub1(t, 'module qfd_dv_s8_fdn_arf1 #(parameter integer USE_SEL_COPIES=0)',
             'module %s #(parameter integer USE_SEL_COPIES=0, parameter integer CE_MUT=0)' % name)
    t = rsub(t, r'\n\s*input\s+wire\s+\[513:0\]\s+l9_i,', '')
    t = rsub(t, r'\n\s*output wire \[63:0\]\s+l9_r0, l9_r1, l9_r2, l9_r3, l9_r4, l9_r5, l9_r6, l9_r7,', '')
    t = rsub(t, r'\n\s*output wire \[1:0\]\s+l9_c,', '')
    t = rsub(t, r'\n\s*assign l9_c = l9_i\[513:512\];', '')
    t = rsub(t, r'\n\s*assign l9_r[0-7] = \{l9_i\[\d+:\d+\]\};', '', count=8)
    assert 'l9_' not in t, 'l9 left in fdn variant'
    hdr = '// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s: l9 pair head (no l9_i / l9_r* / l9_c)' % SRC['fdn']
    if end:
        t = rsub(t, r'\n\s*input\s+wire \[1094:0\]\s+chu_q,', '')
        t = rsub(t, r'\n\s*input\s+wire \[9:0\]\s+agu_q,', '')
        t = sub1(t, '\n    wire p_ar = chu_q[1094]',
                 '\n    wire [1094:0] chu_q = %s;  // chain END: no up-chain neighbour (as-built literal 0)\n'
                 '    wire [9:0] agu_q = %s;\n    wire p_ar = chu_q[1094]' % (cst(1095), cst(10)))
        hdr += '; far chain END (no chu_q / agu_q: up-chain select = own_ch, ag_dn_o = ag_own)'
    if w5:
        t = rsub(t, r'\n\s*input\s+wire \[47:0\]\s+sc_up_i,', '')
        t = rsub(t, r'\n\s*output reg\s+\[47:0\]\s+scu_q,', '')
        t = sub1(t, '\n    wire [3:0] rst;',
                 '\n    wire [47:0] sc_up_i = %s;  // W5 scalar chain END: no up-chain neighbour (as-built literal 0)\n'
                 '    reg [47:0] scu_q;  // end stage: no load (removed)\n    wire [3:0] rst;' % cst(48))
        hdr += '; W5 scalar chain END (no sc_up_i / scu_q)'
    return hdr + '\n' + t + '\n'


def fup_e5(src):
    t = module(src, 'qfd_dv_s6_fup')
    t = sub1(t, 'module qfd_dv_s6_fup (', 'module qfd_dv_s6_fup_e5 #(parameter integer CE_MUT = 0) (')
    for pat in (r'\n\s*input\s+wire \[1087:0\]\s+st_dn_i,', r'\n\s*input\s+wire \[1094:0\]\s+ch_up_i,',
                r'\n\s*input\s+wire \[9:0\]\s+ag_up_i,', r'\n\s*output reg\s+\[1087:0\]\s+se_q,',
                r'\n\s*output reg\s+\[1094:0\]\s+chu_q,', r'\n\s*output reg\s+\[9:0\]\s+agu_q,',
                r'\n\s*input\s+wire \[47:0\]\s+sc_dn_i,', r'\n\s*output reg\s+\[47:0\]\s+scd_q,'):
        t = rsub(t, pat, '')
    # the end stage: its D inputs fold to the as-built constant and its Q has no load -> removed by synthesis
    t = sub1(t, '\n    wire [3:0] rst;',
             '\n    wire [1087:0] st_dn_i = %s;  // chain END: no down-chain neighbour (as-built literal 0)\n'
             '    wire [1094:0] ch_up_i = %s;\n    wire [9:0] ag_up_i = %s;\n    wire [47:0] sc_dn_i = %s;\n'
             '    reg [1087:0] se_q; reg [1094:0] chu_q; reg [9:0] agu_q; reg [47:0] scd_q;  // end stage: no load (removed)\n'
             '    wire [3:0] rst;' % (cst(1088), cst(1095), cst(10), cst(48)))
    return ('// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s: far chain END (no st_dn_i / ch_up_i / ag_up_i / '
            'sc_dn_i ports, no se_q / chu_q / agu_q / scd_q stage)\n' % SRC['leaves6']) + t + '\n'


def stm_se0(src):
    t = module(src, 'qfd_dv_s6_stm')
    t = sub1(t, 'module qfd_dv_s6_stm #(parameter integer HARD = 1,',
             'module qfd_dv_s6_stm_se0 #(parameter integer CE_MUT = 0, parameter integer HARD = 1,')
    t = rsub(t, r'\n\s*input\s+wire \[1087:0\]\s+se_i,', '')
    t = sub1(t, 'qfd_dv_stream_tile u_stream(', 'qfd_dv_stream_tile_se0 #(.CE_MUT(CE_MUT)) u_stream(')
    t = sub1(t, '\n        .se_lo(se_i[543:0]),.se_hi(se_i[1086:544]),.se_v(se_i[1087]),', '')
    assert 'se_i' not in t
    return ('// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s: far chain END stream (no se_i)\n'
            % SRC['leaves6']) + t + '\n'


def stream_se0(src):
    t = module(src, 'qfd_dv_stream_tile')
    t = sub1(t, 'module qfd_dv_stream_tile #(\n    parameter integer MUT = 0\n)',
             'module qfd_dv_stream_tile_se0 #(\n    parameter integer MUT = 0,\n    parameter integer CE_MUT = 0\n)')
    for pat in (r'\n\s*input\s+wire \[543:0\]\s+se_lo,', r'\n\s*input\s+wire\s+se_v,',
                r'\n\s*input\s+wire \[542:0\]\s+se_hi,'):
        t = rsub(t, pat, '')
    t = sub1(t, '    wire [1087:0] se_i = {se_v, se_hi, se_lo};',
             '    wire [1087:0] se_i = %s;  // chain END: no east face (as-built literal 0); its roots/relays fold away'
             % cst(1088))
    return ('// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s: stream tile without the east face\n'
            % SRC['stream']) + t + '\n'


def station_nb0(src):
    t = module(src, 'qfd_dv_s8_station_tail1')
    t = sub1(t, 'module qfd_dv_s8_station_tail1 #(\n', 'module qfd_dv_s8_station_tail1_nb0 #(\n    parameter integer CE_MUT    = 0,\n')
    t = rsub(t, r'\n\s*input\s+wire \[63:0\]\s+nb_d_p,[^\n]*', '')
    t = rsub(t, r'\n\s*input\s+wire \[1:0\]\s+nb_c_p,[^\n]*', '')
    t = sub1(t, 'localparam integer PW = 1+2+1+8+9+8 + 5*64 + 4+4+2 + 32;',
             'localparam integer PW = 1+2+1+8+9+8 + 4*64 + 4+4 + 32;   // neighbour word + valid pins removed (l9 pair head)')
    t = sub1(t, 'rs_n_hi_p, nb_d_p, rs_s_c_p, rs_n_c_p, nb_c_p, bt_q_p};', 'rs_n_hi_p, rs_s_c_p, rs_n_c_p, bt_q_p};')
    t = sub1(t, 'assign {cfg_v, cfg_mode, cfg_wsrc, cfg_nwords, cfg_sbase, cfg_kcm1, rs_s_lo, rs_s_hi, rs_n_lo, rs_n_hi, nb_d, rs_s_c, rs_n_c, nb_c, bt_q} = pin_q;',
             'assign {cfg_v, cfg_mode, cfg_wsrc, cfg_nwords, cfg_sbase, cfg_kcm1, rs_s_lo, rs_s_hi, rs_n_lo, rs_n_hi, rs_s_c, rs_n_c, bt_q} = pin_q;\n'
             '// l9 pair HEAD: no neighbour word.  nb_d / nb_c fold to the as-built literal 0, so nbv = 0: the mode-2\n'
             '// neighbour add (h9 buffer, g_l9 adders, c9 / lead) never fires and synthesis removes it.\n'
             'assign nb_d = %s; assign nb_c = %s;' % (cst(64), cst(2)))
    assert 'nb_d_p' not in t and 'nb_c_p' not in t
    return ('// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s: l9 pair head station (no nb_d_p / nb_c_p)\n'
            % SRC['stn']) + t + '\n'


def inst(t, mod, name):
    m = re.search(r'\n    ' + mod + r' ' + name + r' \(.*?\);', t, re.S)
    assert m, (mod, name)
    return m


def slice_variant(src, end, w5=False):
    name = 'qfd_dv_s8_ce_' + ('e5' if end else 'w5' if w5 else 'l9h')
    t = module(src, 'qfd_dv_s8_flat')
    t = sub1(t, 'module qfd_dv_s8_flat (', 'module %s #(parameter integer CE_MUT = 0) (' % name)
    t = rsub(t, r'\n\s*input\s+wire \[513:0\]\s+l9_i,', '')
    # fdn
    m = inst(t, 'qfd_dv_s8_fdn_arf1', 'u_fdn'); s = m.group(0)
    s2 = sub1(s, 'qfd_dv_s8_fdn_arf1 u_fdn (', 'qfd_dv_s8_fdn_arf1_%s #(.CE_MUT(CE_MUT)) u_fdn (' %
              ('e5' if end else 'w5' if w5 else 'l9h'))
    if w5:
        s2 = sub1(s2, ' .sc_up_i(sc_up_i),', '')
        s2 = sub1(s2, ' .scu_q(scu_q),', '')
    s2 = rsub(s2, r', \.l9_i\(l9_i\), \.l9_c\(nb_c\)(, \.l9_r[0-7]\(nb_r[0-7]\)){8}', '')
    if end:
        s2 = sub1(s2, ' .chu_q(chu_q),', '')
        s2 = sub1(s2, ' .agu_q(agu_q),', '')
    t = t.replace(s, s2)
    # stations
    for k in range(8):
        m = inst(t, 'qfd_dv_s8_station_tail1', 'u_r%d' % k); s = m.group(0)
        s2 = sub1(s, 'qfd_dv_s8_station_tail1 u_r%d (' % k, 'qfd_dv_s8_station_tail1_nb0 #(.CE_MUT(CE_MUT)) u_r%d (' % k)
        s2 = sub1(s2, '.nb_d_p(nb_r%d[63:0]), .nb_c_p(nb_c), ' % k, '')
        t = t.replace(s, s2)
    # nb_r / nb_c wires now have neither driver nor load
    t = sub1(t, ' wire [8*64-1:0] nb_r;', '')
    t = rsub(t, r' wire \[63:0\] nb_r0, nb_r1, nb_r2, nb_r3, nb_r4, nb_r5, nb_r6, nb_r7;', '')
    t = sub1(t, ' wire [1:0] nb_c;', '')
    t = sub1(t, ' assign nb_r = {nb_r7, nb_r6, nb_r5, nb_r4, nb_r3, nb_r2, nb_r1, nb_r0};', '')
    assert not re.search(r'\bnb_r\d?\b|\bnb_c\b|\bl9_i\b', t), 'nb/l9_i left'
    hdr = ('// GENERATED by tools/qwen_dv/gen_s8_chain_end.py from %s (sha256 %s): ' %
           (SRC['flat'], hashlib.sha256((R / SRC['flat']).read_bytes()).hexdigest()[:16]))
    if end:
        for pat in (r'\n\s*input\s+wire \[1087:0\]\s+st_dn_i,', r'\n\s*input\s+wire \[1094:0\]\s+ch_up_i,',
                    r'\n\s*input\s+wire \[9:0\]\s+ag_up_i,'):
            t = rsub(t, pat, '')
        m = inst(t, 'qfd_dv_s6_fup', 'u_fup'); s = m.group(0)
        s2 = sub1(s, 'qfd_dv_s6_fup u_fup (', 'qfd_dv_s6_fup_e5 #(.CE_MUT(CE_MUT)) u_fup (')
        for c in (' .st_dn_i(st_dn_i),', ' .ch_up_i(ch_up_i),', ' .ag_up_i(ag_up_i),', ' .se_q(se_q),',
                  ' .chu_q(chu_q),', ' .agu_q(agu_q),'):
            s2 = sub1(s2, c, '')
        t = t.replace(s, s2)
        m = inst(t, 'qfd_dv_s6_stm', 'u_stm'); s = m.group(0)
        s2 = sub1(s, 'qfd_dv_s6_stm u_stm (', 'qfd_dv_s6_stm_se0 #(.CE_MUT(CE_MUT)) u_stm (')
        s2 = sub1(s2, ' .se_i(se_q),', '')
        t = t.replace(s, s2)
        t = sub1(t, 'wire [1087:0] sw_q, se_q;', 'wire [1087:0] sw_q;')
        t = sub1(t, 'wire [1094:0] chu_q, own_ch;', 'wire [1094:0] own_ch;')
        t = sub1(t, 'wire [9:0] agu_q, ag_own;', 'wire [9:0] ag_own;')
        # scalar chain END (QC-P5-TIE): no sc_dn_i; the sc2 leaf is the k79 netlist regenerated without dn_i
        t = rsub(t, r'\n\s*input\s+wire \[47:0\]\s+sc_dn_i,', '')
        m = inst(t, 'qfd_dv_s6_fup_e5 #\\(\\.CE_MUT\\(CE_MUT\\)\\)', 'u_fup'); s = m.group(0)
        s2 = sub1(s, ' .sc_dn_i(sc_dn_i),', '')
        s2 = sub1(s2, ' .scd_q(scd_q),', '')
        t = t.replace(s, s2)
        t = sub1(t, 'qfd_dv_s5_sc2_leaf u_sc (', 'qfd_dv_s5_sc2_leaf_dn0 u_sc (')
        t = sub1(t, ' .dn_i(scd_q),', '')
        t = sub1(t, 'wire [47:0] scu_q, scd_q;', 'wire [47:0] scu_q;')
        assert not re.search(r'\b(st_dn_i|ch_up_i|ag_up_i|se_q|chu_q|agu_q|sc_dn_i|scd_q)\b', t), 'end signal left'
        hdr += 'far chain END slice (dvs_E5): no l9_i, st_dn_i, ch_up_i, ag_up_i, sc_dn_i'
    elif w5:
        t = rsub(t, r'\n\s*input\s+wire \[47:0\]\s+sc_up_i,', '')
        t = sub1(t, 'qfd_dv_s5_sc2_leaf u_sc (', 'qfd_dv_s5_sc2_leaf_up0 u_sc (')
        t = sub1(t, ' .up_i(scu_q),', '')
        t = sub1(t, 'wire [47:0] scu_q, scd_q;', 'wire [47:0] scd_q;')
        assert not re.search(r'\b(sc_up_i|scu_q)\b', t), 'w5 signal left'
        hdr += 'W5 slice (l9 pair head + scalar chain END): no l9_i, sc_up_i'
    else:
        hdr += 'l9 pair HEAD slice (dvs_E1/E3, W1/W3/W5): no l9_i'
    return hdr + '\n' + t + '\n'


def build():
    s = {k: (R / v).read_text() for k, v in SRC.items()}
    parts = ['// GENERATED by tools/qwen_dv/gen_s8_chain_end.py -- do not edit.  Chain-end slice variants (COORD R7):\n'
             '// the chain-end inputs that the as-built die tied to literals are REMOVED (ports and end stages), not tied.\n'
             '`timescale 1ns/1ps\n',
             fdn_variant(s['fdn'], False), fdn_variant(s['fdn'], True), fdn_variant(s['fdn'], False, w5=True),
             fup_e5(s['leaves6']), stm_se0(s['leaves6']), stream_se0(s['stream']), station_nb0(s['stn']),
             slice_variant(s['flat'], False), slice_variant(s['flat'], True), slice_variant(s['flat'], False, w5=True)]
    return '\n'.join(parts)


if __name__ == '__main__':
    txt = build()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print('gen_s8_chain_end:', 'CURRENT' if ok else 'STALE'); sys.exit(0 if ok else 1)
    OUT.write_text(txt)
    print('wrote', OUT.relative_to(R), hashlib.sha256(txt.encode()).hexdigest()[:16], len(txt.splitlines()), 'lines')
