#!/usr/bin/env python3
"""Chain-end variants of the slice scalar face leaf sc2 (QC-P5-TIE 10-23, COORD R7: a chain-end input needs a real
producer or an RTL variant that removes the port, never a tie).

The bound Qwen compute top tied 96 b at the two ends of the slice scalar chain (BINDER2 15:19): dvs_E5 sc_dn_i (48 b,
qfd_dv_s6_fup_e5) and dvs_W5 sc_up_i (48 b, qfd_dv_s8_fdn_arf1_l9h).  Both feed the face registers f_dn / f_up of the
bounded k79 NETLIST leaf qfd_dv_s5_sc2_leaf, so the variant is made where the netlist comes from:

  qfd_dv_s5_sc2_dn0  = qfd_dv_s5_sc2 without the dn_i port (E5: no down-chain neighbour; f_dn folds to the as-built 0)
  qfd_dv_s5_sc2_up0  = qfd_dv_s5_sc2 without the up_i port (W5: no up-chain neighbour; f_up folds to the as-built 0)

written to rtl/qwen_dv/s5/qfd_dv_s5_sc2_ce.sv (RTL of record), plus the scalar-port kit tops qfd_dv_s5_sc2_leaf_dn0 /
_up0 (rtl/qwen_dv/s5/qfd_dv_s5_sc2_ce_leaf.sv) around the bounded netlists qfd_dv_s5_sc2_k79_dn0 / _up0.  The netlists
are built with EXACTLY the k79 recipe (rtl/test/qwen_dv/s5_scred2/native_k.sh @840685653: yosys 0.67 generic synth,
tools/qwen_dv/bound_math_netlist.py @840685653 --load-cap 8 --transparent-inverters --retain-mux --shared-helpers
--retain-keep --reuse-copies, chparam LA 7 LM 9, helper prefix qfd_s2_bmath_); the same run reproduces the committed
qfd_dv_s5_sc2_k79.sv byte for byte (recipe proof, see rtl/test/qwen_dv/s8/sc2ce/).

CE_MUT (bench negative controls, constructed into separate mutant netlists): 1 = the removed face folds to all-ones
(kind 7: only the sticky fault sees it), 2 = it folds to a valid RB broadcast word (1.0f): passed on / written to VM.
Usage: python3 tools/qwen_dv/gen_sc2_chain_end.py [--check]
"""
import re
import sys
import hashlib
from pathlib import Path

R = Path(__file__).resolve().parents[2]
SRC = 'rtl/qwen_dv/s5/qfd_dv_s5_sc2.sv'
OUT = R / 'rtl/qwen_dv/s5/qfd_dv_s5_sc2_ce.sv'
OUT_LEAF = R / 'rtl/qwen_dv/s5/qfd_dv_s5_sc2_ce_leaf.sv'
LEAF_PORTS = [('input', '', 'ck'), ('input', '', 'rst_n'), ('input', '[100:0]', 'sc_cfg'), ('input', '[47:0]', 'dn_i'),
              ('output', '[47:0]', 'dn_o'), ('input', '[47:0]', 'up_i'), ('output', '[47:0]', 'up_o'),
              ('input', '', 'red_we'), ('input', '[23:0]', 'red_addr'), ('input', '[31:0]', 'red_data'),
              ('input', '[7:0]', 'vm_we'), ('input', '[1:0]', 'vm_win0'), ('input', '[31:0]', 'vm_wdata0'),
              ('input', '', 'am_v'), ('input', '[23:0]', 'am_idx'), ('input', '[31:0]', 'am_val'),
              ('input', '[1:0]', 'am_u'), ('output', '', 'w1_we'), ('output', '[23:0]', 'w1_addr'),
              ('output', '[31:0]', 'w1_data'), ('output', '', 'tok_v'), ('output', '[23:0]', 'tok_idx'),
              ('output', '', 'tok_own'), ('output', '[31:0]', 'tok_val'), ('output', '[1:0]', 'tok_user'),
              ('output', '', 'busy'), ('output', '', 'fault')]


def module(text, name):
    m = re.search(r'^module\s+' + name + r'\b.*?^endmodule\b', text, re.S | re.M)
    assert m, name
    return m.group(0)


def sub1(t, old, new):
    assert t.count(old) == 1, (old[:80], t.count(old))
    return t.replace(old, new)


def variant(src, face):
    """face 'dn' (E5 chain end) or 'up' (W5 chain end)"""
    name = 'qfd_dv_s5_sc2_%s0' % face
    t = module(src, 'qfd_dv_s5_sc2')
    t = sub1(t, 'module qfd_dv_s5_sc2 #(parameter integer MU_NU = 4, parameter integer LA = 4, parameter integer LM = 4) (',
             'module %s #(parameter integer MU_NU = 4, parameter integer LA = 4, parameter integer LM = 4,\n'
             '    parameter integer CE_MUT = 0) (' % name)
    t = sub1(t, '\n    input  wire [47:0]    %s_i,' % face, '')
    t = sub1(t, '\n    wire rst_f;',
             '\n    // chain END: no %s-chain neighbour.  The face input folds to the as-built literal 0 (idle word, valid 0);\n'
             '    // its face register f_%s then has a constant D and synthesis removes it and the chain-word cones.\n'
             "    wire [47:0] %s_i = (CE_MUT == 1) ? {48{1'b1}} : (CE_MUT == 2) ? {1'b1, 3'd2, 12'd0, 32'h3f800000} : 48'd0;\n"
             "    wire rst_f;" % (face, face, face))
    assert re.search(r'input\s+wire \[47:0\]\s+%s_i' % face, t) is None
    return ('// GENERATED by tools/qwen_dv/gen_sc2_chain_end.py from %s (sha256 %s): chain-end sc2 without %s_i\n'
            % (SRC, hashlib.sha256((R / SRC).read_bytes()).hexdigest()[:16], face)) + t + '\n'


def leaf(face):
    n = 'qfd_dv_s5_sc2_k79_%s0' % face
    P = [p for p in LEAF_PORTS if p[2] != '%s_i' % face]
    L = ['// chain-end kit top: scalar-port wrapper of the bounded netlist %s = qfd_dv_s5_sc2_%s0 #(LA 7, LM 9)' % (n, face),
         '// (k79 recipe, see tools/qwen_dv/gen_sc2_chain_end.py).  Ports = qfd_dv_s5_sc2_leaf without %s_i.' % face,
         '// OT_S5_SC2CE_MUT_NETLIST (bench only): the constructed CE_MUT=1 mutant netlist instead.',
         'module qfd_dv_s5_sc2_leaf_%s0 (' % face]
    L += ['    %-6s wire %-10s %s%s' % (d, w, p, ',' if i < len(P) - 1 else '') for i, (d, w, p) in enumerate(P)]
    L += [');', '`ifdef OT_S5_SC2CE_MUT_NETLIST', '    %s_mut u (' % n, '`else', '    %s u (' % n, '`endif',
          '        ' + ', '.join('.%s(%s)' % (p, p) for _, _, p in P) + ');', 'endmodule', '']
    return '\n'.join(L)


def build():
    s = (R / SRC).read_text()
    rtl = ('// GENERATED by tools/qwen_dv/gen_sc2_chain_end.py -- do not edit.  Chain-end sc2 variants (COORD R7): the\n'
           '// chain-end scalar inputs the as-built die tied to literals are REMOVED (port), never tied.\n'
           '`timescale 1ns/1ps\n' + variant(s, 'dn') + '\n' + variant(s, 'up'))
    lf = ('// GENERATED by tools/qwen_dv/gen_sc2_chain_end.py -- do not edit.\n`timescale 1ns/1ps\n' + leaf('dn') + '\n' +
          leaf('up'))
    return rtl, lf


if __name__ == '__main__':
    rtl, lf = build()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == rtl and OUT_LEAF.exists() and OUT_LEAF.read_text() == lf
        print('gen_sc2_chain_end:', 'CURRENT' if ok else 'STALE')
        sys.exit(0 if ok else 1)
    OUT.write_text(rtl)
    OUT_LEAF.write_text(lf)
    for p in (OUT, OUT_LEAF):
        print('wrote', p.relative_to(R), hashlib.sha256(p.read_bytes()).hexdigest()[:16])
