#!/usr/bin/env python3
"""Relay masters of the S81 die as real hard tiles (tools/ref_tile): RTL masters file + one ref_tile spec per master.

The die generator (tools/dsrom_s81_fulldie.py) places dsfd_rly_<W>_<fi><fo> as a generated outline with an interim
timing model (29,184 instances / 27 masters in c5).  This writes the same masters as RTL (scalar ck / rs; W = 1 has
scalar i / o) and a ref_tile spec each: outline = the generator's slot, data in on face fi, out on face fo, ck / rs on
the generator's third face, M5 cap, minimum output delay built at the output pins (outhold).

Usage: rly_kits.py [--census results/physical/die_iter_1012/s81/real_view_census_20261013/c5_census.json] [--gen]
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RTL = "rtl/dsrom_sys/s81_glue"


def outline(w: int, fi: str, fo: str) -> dict:
    """Outline from the content, not from the generator's 17.256 placeholder slot (pre-route gate 2026-10-13: W = 63
    is 18.6% utilised at 17.28 sq; W = 266 / 283 do not fit at all -- PPL-0111, 283 pins at 2 tracks need 27.2 um of
    face against 17.28, and 128 um2 of flops + 113 um2 of output delay cells exceed the 196 um2 core).
    Pins take 2 tracks (0.096 um) a bit on the data faces; std = flops + BUF-HB4-BUF per output at ~0.52; every
    dimension is a multiple of 2.16 um (row 0.27, site 0.054, M4/M5 track 0.048)."""
    # W <= 15 also take 15.12: at 8.64 / 10.8 (v2 routes, timing closed) the M5 PG stripes inside the 2.16-um margins span
    # 31% / 50% of the tile and the exported view fails child_lint (b) (>= 2 stripes a net over > 50%); 15.12 is the
    # smallest outline of this margin / 2.7-um pitch that passes (54%), proven on the W 54-68 masters
    if w <= 68:
        return {"w": 15.12, "h": 15.12}
    # wide column relays: the data face must hold w pins at 0.096 um
    if fi in "NS" and fo in "NS":
        return {"w": 34.56, "h": 19.44}
    return {"w": 21.6, "h": 30.24}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--census", default="results/physical/die_iter_1012/s81/real_view_census_20261013/c5_census.json")
    ap.add_argument("--gen", action="store_true", help="also run ref_tile.py gen on every spec")
    ap.add_argument("--owner", default="Claude:s81-die")
    ap.add_argument("--branch", default="claude/el1011-s81dieit")
    ap.add_argument("--only", help="MASTER:INSTANCES[,MASTER:INSTANCES...]: write ONLY these masters (new masters of a later die "
                    "case), into --rtl-file; the census, the other specs and dsfd_rly_masters.sv (a source of the closed "
                    "kits) are left untouched")
    ap.add_argument("--rtl-file", default="dsfd_rly_masters.sv", help="masters file under rtl/dsrom_sys/s81_glue")
    ap.add_argument("--case", default="c5", help="die case named in the job purpose")
    ap.add_argument("--outline", help="W,H (um) for the --only masters instead of the class outline (2026-10-13: the E/W wide "
                    "class 21.6 x 30.24 is 62-66 % utilised with the hold cells = refused at floorplan; 23.76 x 30.24 = 55-59 %)")
    ap.add_argument("--tag", help="job tag for the --only masters")
    a = ap.parse_args()
    if a.only:
        assert a.rtl_file != "dsfd_rly_masters.sv", "--only needs its own --rtl-file"
        ms = [(x.split(":")[0], int(x.split(":")[1])) for x in a.only.split(",")]
        assert all(re.fullmatch(r"dsfd_rly_\d+_[NSEW]{2}", m_) for m_, _ in ms), ms
    else:
        cen = json.loads((ROOT / a.census).read_text())
        ms = sorted(((m["master"], m["instances"]) for m in cen["masters"] if re.fullmatch(r"dsfd_rly_\d+_[NSEW]{2}", m["master"])),
                    key=lambda x: (-x[1], x[0]))
    v = ["// GENERATED by tools/s81/rly_kits.py from the S81 die census: one module per placed relay master.",
         "`default_nettype none"]
    specs = []
    for mst, n in ms:
        _, _, w, ff = mst.split("_")
        w = int(w)
        fi, fo = ff
        cf = [f for f in "NSEW" if f not in (fi, fo)][0]
        rng = "" if w == 1 else f"[{w - 1}:0] "
        v.append(f"module {mst} (input wire ck, input wire rs, input wire {rng}i, output wire {rng}o);")
        v.append(f"    ot_s81_rly #(.W({w})) u (.ck(ck), .rs(rs), .i(i), .o(o));")
        v.append("endmodule")
        name = f"s81_rly_{w}_{ff.lower()}"
        small = outline(w, fi, fo)["w"] <= 15.12
        pins = {f: [] for f in "NSEW"}
        pins[fi].append("i"); pins[fo].append("o"); pins[cf] += ["ck", "rs"]
        spec = {
            'pin_regs': {'enable': False, 'reason': 'OWNER RULE 19:50 opt-out (coordinator APPROVED 2026-10-15): this relay IS one flip-flop per bit between its input and output pins (ot_s81_rly: i -> r -> o, no logic); a flow pin register would add a second stage per bit and a cycle the die calendar does not price'},
            "name": name, "top": mst, "kind": "tile",
            "sources": [f"{RTL}/ot_s81_rly.sv", f"{RTL}/{a.rtl_file}"],
            "params": {}, "clock_port": "ck", "reset_ports": ["rs"],
            "outline": ({"w": float(a.outline.split(",")[0]), "h": float(a.outline.split(",")[1])} if a.only and a.outline
                        else outline(w, fi, fo)), "macros": [],
            "pins": {f: p for f, p in pins.items() if p},
            "outhold": True,
            # small tiles (<= 15.12 um): M5 PG at 2.7 um so each net has >= 2 full-length stripes spanning > 50% of the tile
            # (v1 export child_lint (b): 1 stripe a net at 8.64, 36% span at 15.12; the 21.6 / 34.56 um masters closed at 5.4)
            "route": {"pd": 0.45, "threads": 4, "peak_ram_gb": 8, **({"m5_pg_pitch": 2.7} if small else {})},
            "job": {
                "owner": a.owner, "branch": a.branch, "tag": a.tag or (("v3" if w <= 15 else "v2") if small else "v1"),
                "purpose": f"S81 die relay master {mst} ({n} instances in the {a.case} placement, generated outline + interim "
                           f"timing there): real hard tile, {w} b in {fi} / out {fo}, ck+rs {cf}, scalar ck/rs, M5 cap, one "
                           "register stage, minimum output delay at the pin (outhold BUF-HB4-BUF) for the >= 65 ps "
                           "abutted-seam budget",
                "benches": [
                    {"name": "exact_words", "cmd": f"bash {RTL}/test/bench_rly.sh pass {mst} {w} {{RUN}}/bench_p",
                     "expect": "pass", "pass_regex": "RLY_BENCH PASS 0 errors in 20000 words", "threads": 2, "peak_ram_gb": 4},
                    {"name": "neg_bit0_mutant", "cmd": f"bash {RTL}/test/bench_rly.sh mut {mst} {w} {{RUN}}/bench_m",
                     "expect": "fail", "fail_regex": "RLY_BENCH FAIL", "threads": 2, "peak_ram_gb": 4},
                ],
                "views_to": f"physical/ref_tile/{name}/views",
                "record_to": f"results/rtl/ref_tile/{name}",
            },
        }
        p = ROOT / "tools/ref_tile/specs" / f"{name}.json"
        p.write_text(json.dumps(spec, indent=1) + "\n")
        specs.append((p, mst, n))
    v.append("`default_nettype wire")
    (ROOT / RTL / a.rtl_file).write_text("\n".join(v) + "\n")
    print(f"{len(specs)} relay masters, {sum(n for _, _, n in specs)} instances")
    if a.gen:
        for p, mst, n in specs:
            r = subprocess.run([sys.executable, str(ROOT / "tools/ref_tile/ref_tile.py"), "gen", str(p)],
                               capture_output=True, text=True, cwd=ROOT)
            print(mst, n, "gen rc", r.returncode, (r.stdout + r.stderr).strip().splitlines()[-1:][0][:200] if (r.stdout + r.stderr).strip() else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
