#!/usr/bin/env python3
"""Extract the production control leaf with explicit family/advance read enables.

No control state or broadcast cycle changes. Speculative head inspection is
separate from an operand read that the streamer will consume; memory protection
guards the latter. The early-consume mutant deliberately removes that boundary.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    source = ROOT / "physical/s81_pq_hier/pinned/rtl/v41die/ot_v41_spine_pqc_w17w10.sv"
    s = source.read_text()
    first = s.index("module ot_v41_pqc_ctl #(")
    last = s.index("\nendmodule", first) + len("\nendmodule")
    s = s[first:last].replace("module ot_v41_pqc_ctl", "module ot_s81_pq_ctl_native", 1)
    for name, old, new in [("PHW",6,9),("SAW",14,11),("R",2,128),("PQ",0,1),("RG",8,11),("XRV",0,1)]:
        s = s.replace(f"parameter integer {name} = {old},",f"parameter integer {name} = {new},",1)
    s = s.replace("output wire              aq_vin,", "output wire              q_consume, b_consume,\n    output wire              aq_vin,", 1)
    s = s.replace("assign hw_o = hw;", """`ifdef OT_S81_PQ_CTL_MUT_EARLY_CONSUME
    assign q_consume = hw[0] && !h_fam;
`else
    assign q_consume = s_adv_h && hw[0] && !h_fam;
`endif
    assign b_consume = s_adv_h && hw[0] && h_fam;
    assign hw_o = hw;""", 1)
    s = s.replace("    assign aq_vin = rq_v && !rq_fam;", """`ifdef OT_PQ_AQ_PIN_LAUNCH
    // Move AQ's first validity flop into the controller's launch pin owner.
    // AQ removes exactly that validity stage locally, keeping every data epoch.
    // Distinct async-reset owner avoids synthesis merging this pin launch
    // with u_aqi's first metadata flop (that flop resets from rst_c).
    reg aq_v_pin;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) aq_v_pin <= 0;
        else aq_v_pin <= rst_c && rq_v && !rq_fam;
    assign aq_vin = aq_v_pin;
`else
    assign aq_vin = rq_v && !rq_fam;
`endif""", 1)
    # d7f2edbd3 (Codex, 10-14): the return leaves expose NGR count groups (RG 11 -> 12), not (R + 7) / 8.
    s = s.replace("    localparam integer NCA = (R + 7) / 8;", """    // The return leaves expose NGR counters, regardless of their region
    // partition. A fixed 8-region assumption reads beyond ga_i for RG=11.
    localparam integer NCA = NGR;""", 1)
    # B6 s81-elemB (10-14): per-parity stage A write enables registered here (no IX tile compares a parity constant;
    # owner NO-STUBS rule: the ix_rb 'par' input was a per-instance tie).  Same edge and value as ba_v && ba_blk[0] == p.
    s = s.replace("    output wire              ba_v_o,          // T_IX: BF16 write stage A\n",
                  "    output wire              ba_v_o,          // T_IX: BF16 write stage A\n"
                  "    output reg  [1:0]        ba_wv_o,         // T_IX: stage A write enable per block parity (ba_v && ba_blk[0] == p), same edge\n", 1)
    s = s.replace("            a_v <= 1'b0; a_v2 <= 1'b0; bw_v <= 1'b0; ba_v <= 1'b0;",
                  "            a_v <= 1'b0; a_v2 <= 1'b0; bw_v <= 1'b0; ba_v <= 1'b0; ba_wv_o <= 2'b00;", 1)
    s = s.replace("            ba_v <= rq_v && rq_fam; ba_par <= rq_par; ba_k <= rq_k;\n",
                  "            ba_v <= rq_v && rq_fam; ba_par <= rq_par; ba_k <= rq_k;\n"
                  "`ifdef OT_S81_PQ_WV_MUT_ROW\n"
                  "            ba_wv_o <= {2{rq_v && rq_fam}} & {~bw_blk_n[0], bw_blk_n[0]};   // negative control: parities swapped\n"
                  "`else\n"
                  "            ba_wv_o <= {2{rq_v && rq_fam}} & {bw_blk_n[0], ~bw_blk_n[0]};\n"
                  "`endif\n", 1)
    for need in ("NCA = NGR;", "ba_wv_o <= {2{rq_v"):
        assert need in s, need
    out = ROOT / "rtl/dsrom_sys/s81_ph/pq/ot_s81_pq_ctl_native.sv"
    out.write_text("`timescale 1ns/1ps\n// Generated by tools/s81/pq_native_ctl.py from pinned v15 controller.\n"+s+"\n")
    print(out.relative_to(ROOT))


if __name__ == "__main__":
    main()
