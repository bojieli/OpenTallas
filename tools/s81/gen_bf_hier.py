#!/usr/bin/env python3
"""bf-arch hierarchical BF (2026-10-09): generate the hardened-column split of the S81 BF pair from the q-element.

Writes (all derived mechanically from rtl/v41rom/ot_v41_rom_elem_qx_w10.sv and rtl/s81/ot_s81_bf_native.sv, so the
arithmetic, sequencing and per-column logic are the q-element's own text):
  rtl/v41rom/ot_v41_bf_col.sv          one macro column (2 PP ROMs, capture, FP / BF lanes, chains, pair, segment tree,
                                       outputs) as its own hardened block.  EVERY input is registered at the block
                                       boundary on the free clock (registered abutted boundary, Tensix / Cerebras-style
                                       tile), the column's gate enable and reset release are delayed by the same one cycle:
                                       the column is the original column shifted by exactly one cycle (exact by
                                       construction; partials +1 cycle).
  rtl/v41rom/ot_v41_bf_front_core.sv   the q-element without its columns: the column interface leaves on ports.
  rtl/s81/ot_s81_bf_front.sv           the BF pair's front block (pin registers + front core) for the die: column ports
                                       exported.
The flat wrapper ot_s81_bf_native HCOL=1 instantiates ot_s81_bf_front + 2 x ot_v41_bf_col (bench vehicle).
Supported configuration only: RECUT q-element path (FAST QPIPE QZ QY QX=10 PP BF16 QBF>=2 BP=0 QP_CAP=0) with TCG=1, QZE=1.
"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
QX = (ROOT / 'rtl/v41rom/ot_v41_rom_elem_qx_w10.sv').read_text()
WR = (ROOT / 'rtl/s81/ot_s81_bf_native.sv').read_text()

def between(t, a, b, start=0):
    i = t.index(a, start); j = t.index(b, i)
    return i, j

# ---- pieces of the q-element
mi = QX.index('module ot_v41_rom_elem_qx_w10 #(')
pstart = mi + len('module ot_v41_rom_elem_qx_w10 #(')
pend = QX.index('\n) (\n', pstart)
params = QX[pstart:pend]                       # parameter list text
gs = QX.index('    generate for (mb = 0; mb < NB; mb = mb + 1) begin : g_mac')
ge = QX.index('    end endgenerate\n    assign busy_c', gs)
gmac = QX[gs:ge]
loc = []
for name in ('QK', 'SW', 'TRW', 'HW', 'LAT', 'XD', 'BPH', 'BPN', 'KW', 'TW', 'TG'):
    m = re.search(r'^\s*localparam integer ' + name + r' = [^\n]*', QX, re.M)
    loc.append(m.group(0).strip())
for name in ('HOLDM1', 'KLAST'):
    m = re.search(r'^\s*localparam \[[^\]]*\] ' + name + r' = [^\n]*', QX, re.M)
    loc.append(m.group(0).strip())
fi = QX.index('    function automatic [255:0] nib(')
fe = QX.index('    endfunction', fi) + len('    endfunction')
nib = QX[fi:fe]

# ---------------------------------------------------------------- column block
body = gmac
body = body.replace('    generate for (mb = 0; mb < NB; mb = mb + 1) begin : g_mac\n', '', 1)
body = body.replace('.x(i2_q0)', '.x(mz_q0)')          # BF x slice: the column's own copy (u_x q == i2_q0 every cycle)
body = re.sub(r'(\w+)\[mb \* NSEG \+ t_seg\]', r'\1_c[t_seg]', body)
for a, b in [('pv[mb]', 'pv'), ('pval[32*mb +: 32]', 'pval'), ('prow[16*mb +: 16]', 'prow'), ('pseg[5*mb +: 5]', 'pseg'),
             ('pnseg[5*mb +: 5]', 'pnseg'), ('perr[mb]', 'perr'), ('ppos[3*mb +: 3]', 'ppos'), ('bk_fault[mb]', 'bk_fault'),
             ('qy_bkf[mb]', 'qy_bkf')]:
    assert a in body, a
    body = body.replace(a, b)
body = re.sub(r'\bmb\b', 'MB', body)
ren = {'issue': 'b_issue', 'a_ctr': 'b_a_ctr', 'i1_v': 'b_i1_v', 'i1_bk': 'b_i1_bk', 'i1_bf': 'b_i1_bf', 'i1_t': 'b_i1_t',
       'i2x_q0': 'b_i2x_q0', 'i2x_e0': 'b_i2x_e0', 'i2x_q1': 'b_i2x_q1', 'i2x_e1': 'b_i2x_e1', 'rst_n_pin': 'b_rst',
       'tcg_ze_d': 'b_ze', 'so_idx': 'b_so_idx', 'so_n': 'b_so_n'}
for a, b in ren.items():
    body = re.sub(r'(?<![\w.])' + a + r'(?![\w])', b, body)
tie = ['i2_q0', 'i2_q1', 'i2_e0', 'i2_e1', 'i2_v', 'i2_bk', 'i2_bf', 'i2_t', 'i2x_v', 'i2x_bk', 'c3_q0', 'c3_q1', 'c3_e0',
       'c3_e1', 'hx_sh', 'fam', 'rom_addr', 'rst_n', 'rst_q', 'gclk', 's_idx', 's_n']
assert 'end endgenerate' not in body[-40:]
col = f'''`timescale 1ns/1ps
// GENERATED by tools/s81/gen_bf_hier.py from rtl/v41rom/ot_v41_rom_elem_qx_w10.sv (g_mac) -- do not edit.
// ot_v41_bf_col (bf-arch 2026-10-09): ONE macro column of the S81 BF pair as a hardened tile with a registered
// boundary.  Every input is captured at the block boundary on the free clock (g_pin.r_*), including the gate-enable
// (one more register after the element's ze) and the reset synchroniser (one more stage), so the column is the
// q-element's column shifted by exactly one cycle: same values, same order, partials +1 cycle.  Outputs leave from the
// column's own output registers.  The BF x slice is the column's u_x copy (equal to the element's i2_q0 every cycle).
module ot_v41_bf_col #({params},
    parameter integer MB = 0          // which column (simulation ROM image name only)
) (
    input  wire          clk,
    input  wire          rst_n_pin,
    input  wire          ze_d,          // element gate-enable next state (qx tcg_ze_d)
    input  wire          issue,
    input  wire [13:0]   a_ctr,
    input  wire          i1_v,
    input  wire          i1_bk,
    input  wire          i1_bf,
    input  wire [$clog2(NCH)+3+$clog2(NSEG)+(MTP != 0 ? 1 : 0)+6-1:0] i1_t,
    input  wire [255:0]  i2x_q0,
    input  wire [9:0]    i2x_e0,
    input  wire [255:0]  i2x_q1,
    input  wire [9:0]    i2x_e1,
    input  wire [16*NSEG-1:0] so_row,   // this column's NSEG output rows
    input  wire [5*NSEG-1:0]  so_idx,
    input  wire [5*NSEG-1:0]  so_n,
    output wire          pv,
    output wire [31:0]   pval,
    output wire [15:0]   prow,
    output wire [4:0]    pseg,
    output wire [4:0]    pnseg,
    output wire          perr,
    output wire [2:0]    ppos,
    output wire          qy_bkf
);
    {chr(10).join("    " + l for l in loc)}
{nib}
    wire bk_fault;
    // ---- registered boundary (free clock): the column runs one cycle behind the front end
    wire b_rst;                                     // reset synchroniser copy: the column's reset pin (+1 release)
    wire b_ze;                                      // = the element's ze, so the column tiles' enables are ze delayed
    wire b_issue, b_i1_v, b_i1_bk, b_i1_bf;
    wire [13:0] b_a_ctr;
    wire [TW-1:0] b_i1_t;
    wire [255:0] b_i2x_q0, b_i2x_q1;
    wire [9:0]   b_i2x_e0, b_i2x_e1;
    wire [15:0]  so_row_c [0:NSEG-1];
    wire [4:0]   b_so_idx [0:NSEG-1];
    wire [4:0]   b_so_n [0:NSEG-1];
    if (1) begin : g_pin
        ot_v41_kreg #(.W(1), .AR(1), .RV(1'b0)) r_rst (.clk(clk), .arst_n(rst_n_pin), .d(1'b1), .q(b_rst));
        ot_v41_kreg #(.W(1), .AR(1), .RV(1'b1)) r_ze (.clk(clk), .arst_n(rst_n_pin), .d(ze_d), .q(b_ze));
        reg r_issue, r_i1_v, r_i1_bk, r_i1_bf;
        reg [13:0] r_a_ctr;
        reg [TW-1:0] r_i1_t;
        reg [255:0] r_i2x_q0, r_i2x_q1;
        reg [9:0] r_i2x_e0, r_i2x_e1;
        reg [16*NSEG-1:0] r_so_row;
        reg [5*NSEG-1:0] r_so_idx, r_so_n;
        always @(posedge clk) begin
            r_issue <= issue; r_i1_v <= i1_v; r_i1_bk <= i1_bk; r_i1_bf <= i1_bf; r_a_ctr <= a_ctr; r_i1_t <= i1_t;
            r_i2x_q0 <= i2x_q0; r_i2x_e0 <= i2x_e0; r_i2x_q1 <= i2x_q1; r_i2x_e1 <= i2x_e1;
            r_so_row <= so_row; r_so_idx <= so_idx; r_so_n <= so_n;
        end
        assign b_issue = r_issue; assign b_i1_v = r_i1_v; assign b_i1_bk = r_i1_bk; assign b_i1_bf = r_i1_bf;
        assign b_a_ctr = r_a_ctr; assign b_i1_t = r_i1_t;
        assign b_i2x_q0 = r_i2x_q0; assign b_i2x_e0 = r_i2x_e0; assign b_i2x_q1 = r_i2x_q1; assign b_i2x_e1 = r_i2x_e1;
        genvar s;
        for (s = 0; s < NSEG; s = s + 1) begin : g_s
            assign so_row_c[s] = r_so_row[16*s +: 16]; assign b_so_idx[s] = r_so_idx[5*s +: 5]; assign b_so_n[s] = r_so_n[5*s +: 5];
        end
    end
    // unused branches of the shared column text (other q-element configurations)
    wire [255:0] i2_q0 = '0, i2_q1 = '0, c3_q0 = '0, c3_q1 = '0, hx_sh = '0;
    wire [9:0] i2_e0 = '0, i2_e1 = '0, c3_e0 = '0, c3_e1 = '0;
    wire i2_v = 1'b0, i2_bk = 1'b0, i2_bf = 1'b0, i2x_v = 1'b0, i2x_bk = 1'b0, fam = 1'b0, rst_n = 1'b0, rst_q = 1'b0, gclk = 1'b0;
    wire [TW-1:0] i2_t = '0;
    wire [12:0] rom_addr = '0;
    wire [15:0] s_row_c [0:NSEG-1];
    wire [4:0] s_idx [0:NSEG-1];
    wire [4:0] s_n [0:NSEG-1];
`ifndef SYNTHESIS
    initial if (!(FAST != 0 && QPIPE != 0 && QZ != 0 && QY != 0 && PP != 0 && BF16 != 0 && QBF >= 2 && BP == 0 && QP_CAP == 0 && TCG != 0 && QZE != 0))
        $fatal(1, "ot_v41_bf_col: unsupported configuration");
`endif
{body}endmodule
'''
(ROOT / 'rtl/v41rom/ot_v41_bf_col.sv').write_text(col)

# ---------------------------------------------------------------- front core
fc = QX[:gs] + '''    // bf-arch: the columns are hardened blocks (ot_v41_bf_col); their interface leaves on the c_* ports
    assign c_issue = issue; assign c_a_ctr = a_ctr; assign c_i1_v = i1_v; assign c_i1_bk = i1_bk; assign c_i1_bf = i1_bf;
    assign c_i1_t = i1_t; assign c_i2x_q0 = i2x_q0; assign c_i2x_e0 = i2x_e0; assign c_i2x_q1 = i2x_q1; assign c_i2x_e1 = i2x_e1;
    assign c_ze_d = tcg_ze_d;
    genvar cs;
    for (cs = 0; cs < NB * NSEG; cs = cs + 1) begin : g_cxso
        assign c_so_row[16*cs +: 16] = so_row[cs];
    end
    for (cs = 0; cs < NSEG; cs = cs + 1) begin : g_csi
        assign c_so_idx[5*cs +: 5] = so_idx[cs]; assign c_so_n[5*cs +: 5] = so_n[cs];
    end
    assign bk_fault = c_qy_bkf; assign qy_bkf = c_qy_bkf;
    assign pv = '0; assign pval = '0; assign prow = '0; assign pseg = '0; assign pnseg = '0; assign perr = '0; assign ppos = '0;
''' + QX[ge + len('    end endgenerate\n'):]
fc = fc.replace('module ot_v41_rom_elem_qx_w10 #(', 'module ot_v41_bf_front_core #(', 1)
hdr_end = fc.index('\n);\n', fc.index('module ot_v41_bf_front_core #('))
fc = fc[:hdr_end] + ''',
    // bf-arch column interface (to / from the two ot_v41_bf_col blocks)
    output wire          c_issue,
    output wire [13:0]   c_a_ctr,
    output wire          c_i1_v,
    output wire          c_i1_bk,
    output wire          c_i1_bf,
    output wire [$clog2(NCH)+3+$clog2(NSEG)+(MTP != 0 ? 1 : 0)+6-1:0] c_i1_t,
    output wire [255:0]  c_i2x_q0,
    output wire [9:0]    c_i2x_e0,
    output wire [255:0]  c_i2x_q1,
    output wire [9:0]    c_i2x_e1,
    output wire          c_ze_d,
    output wire [16*NB*NSEG-1:0] c_so_row,
    output wire [5*NSEG-1:0] c_so_idx,
    output wire [5*NSEG-1:0] c_so_n,
    input  wire [NB-1:0] c_qy_bkf''' + fc[hdr_end:]
fc = '// GENERATED by tools/s81/gen_bf_hier.py from rtl/v41rom/ot_v41_rom_elem_qx_w10.sv -- do not edit.\n' + fc
(ROOT / 'rtl/v41rom/ot_v41_bf_front_core.sv').write_text(fc)
print('ok')

# ---------------------------------------------------------------- front block wrapper (die element)
W = (ROOT / 'rtl/s81/ot_s81_bf_native.sv').read_text()
W = W.replace('module ot_s81_bf_native #(', 'module ot_s81_bf_front #(', 1)
outs = ['    output wire [NB-1:0]    pv,\n', '    output wire [32*NB-1:0] pval,\n', '    output wire [16*NB-1:0] prow,\n',
        '    output wire [5*NB-1:0]  pseg,\n', '    output wire [5*NB-1:0]  pnseg,\n', '    output wire [NB-1:0]    perr,\n',
        '    output wire [3*NB-1:0]  ppos,\n']
for o in outs:
    assert o in W, o
    W = W.replace(o, '', 1)
CT = '$clog2(NCH)+3+$clog2(NSEG)+(MTP != 0 ? 1 : 0)+6'
ports = ''
for c in (0, 1):
    ports += f'''    output wire          c{c}_issue,
    output wire [13:0]   c{c}_a_ctr,
    output wire          c{c}_i1_v,
    output wire          c{c}_i1_bk,
    output wire          c{c}_i1_bf,
    output wire [{CT}-1:0] c{c}_i1_t,
    output wire [255:0]  c{c}_i2x_q0,
    output wire [9:0]    c{c}_i2x_e0,
    output wire [255:0]  c{c}_i2x_q1,
    output wire [9:0]    c{c}_i2x_e1,
    output wire          c{c}_ze_d,
    output wire [16*NSEG-1:0] c{c}_so_row,
    output wire [5*NSEG-1:0] c{c}_so_idx,
    output wire [5*NSEG-1:0] c{c}_so_n,
'''
ports += '    input  wire [1:0]    c_qy_bkf_in,     // the two columns\' registered fault ORs\n'
anchor = '    output wire         busy,\n'
assert anchor in W
W = W.replace(anchor, ports + anchor, 1)
hdr_end = W.index('\n);\n', W.index('module ot_s81_bf_front #('))
W = W[:hdr_end + 4] + '''    // bf-arch: the partial outputs leave from the hardened columns, not from this block
    wire [NB-1:0] pv; wire [32*NB-1:0] pval; wire [16*NB-1:0] prow; wire [5*NB-1:0] pseg, pnseg; wire [NB-1:0] perr;
    wire [3*NB-1:0] ppos;
''' + W[hdr_end + 4:]
i = W.index('        genvar cm;\n        for (cm = 0; cm < NB; cm = cm + 1) begin : g_col')
j = W.index('        end\n', W.index('.qy_bkf(c_qy_bkf[cm]));', i)) + len('        end\n')
rep = '        // replicated column interface: one pin set per column face (west: column 0, east: column 1)\n'
for c in (0, 1):
    for s in ('issue', 'a_ctr', 'i1_v', 'i1_bk', 'i1_bf', 'i1_t', 'i2x_q0', 'i2x_e0', 'i2x_q1', 'i2x_e1', 'ze_d', 'so_idx', 'so_n'):
        rep += f'        assign c{c}_{s} = c_{s};\n'
    rep += f'        assign c{c}_so_row = c_so_row[16*NSEG*{c} +: 16*NSEG];\n'
rep += '        assign c_qy_bkf = c_qy_bkf_in;\n'
rep += "        assign pv_e = '0; assign pval_e = '0; assign prow_e = '0; assign pseg_e = '0; assign pnseg_e = '0; assign perr_e = '0; assign ppos_e = '0;\n"
W = W[:i] + rep + W[j:]
W = '// GENERATED by tools/s81/gen_bf_hier.py from rtl/s81/ot_s81_bf_native.sv -- do not edit.\n' + W
(ROOT / 'rtl/s81/ot_s81_bf_front.sv').write_text(W)
print('front ok')
