#!/usr/bin/env python3
"""ctrl_lane_bench (S-BIND r6 2026-10-15): exact die-extract bench of one engine's forwarded ctrl lanes.

The sequencer <-> slab command plane of an S81 layer die (engine e: sseq c<e> {v, descriptor 84} -> slab c_cmd, slab
c_done {v, tag 8} -> sseq d<e>, slab c_st {avail, fault} -> sseq s<e>) travels as forwarded lanes (start block, stations,
end block, fault folds).  This tool cuts those lanes out of a GENERATED die netlist (die.v + its glue RTL) verbatim --
every lane instance, net and the sequencer / slab connection expressions exactly as the die has them -- and drives the
cut with the sequencer and slab behaviour at the die nets:

  * c lane: N commands {1, descriptor} with random descriptors (both LSB values) at random static spacing; the slab
    side must see exactly the same words in order, each at ONE constant latency (static schedule: no word lost, no
    word retimed);
  * d lane: N completions {1, tag} the same way, slab -> sequencer;
  * s lane: status levels avail (10), idle (00), fault (01) held for 64 edges each; the sequencer side must settle to the
    same level after a constant latency and the fault must also stay visible (sticky in the meso FIFO fold).

PASS line CTRL_LANE_BENCH ... PASS.  Run it on a die from the generator BEFORE the r6 fix (vbit 0 lanes) as the observed
failing mutant: commands / dones whose descriptor / tag LSB is 0 never arrive.

    python3 tools/s81/ctrl_lane_bench.py --die DIE_V --glue GLUE_SV --engine 5 --slab bk_selector --out DIR [--run]
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRIM = ['rtl/common/ot_meso_fifo.sv', 'rtl/common/ot_ratio_cdc_fifo.sv', 'rtl/common/ot_fwd_link_stage.sv']
INST = re.compile(r'^\s+(\\?\S+)\s+(\\?\S+)\s+\((.*)\);\s*$')
CONN = re.compile(r'\.(\w+)\(([^()]*)\)')
WIRE = re.compile(r'^\s+wire\s+(\[[^\]]+\]\s+)?(\S+);')


def nets_of(expr):
    return re.findall(r'\b(n_\w+)\b', expr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--die', required=True)
    ap.add_argument('--glue', required=True)
    ap.add_argument('--engine', type=int, required=True)
    ap.add_argument('--slab', required=True, help='slab instance name the lanes are tagged with (bk_selector, svcj, ...)')
    ap.add_argument('--sseq', default='sp_sseq')
    ap.add_argument('--out', required=True)
    ap.add_argument('--n', type=int, default=200)
    ap.add_argument('--run', action='store_true')
    a = ap.parse_args()
    e, sl = a.engine, a.slab
    tags = [f'{k}{e}_{sl}' for k in 'cds']
    lane_re = re.compile(r'^(?:(?:hs|he)_(?:%s)|f_(?:%s)_\d+)$' % ('|'.join(tags), '|'.join(tags)))
    wires, insts, sseq, slab = {}, [], None, None
    slab_inst = sl
    for line in open(a.die):
        mw = WIRE.match(line)
        if mw:
            wires[mw.group(2)] = line.strip()
            continue
        mi = INST.match(line)
        if not mi:
            continue
        mst, nm, body = mi.groups()
        if lane_re.match(nm):
            insts.append(line.rstrip())
        elif nm == a.sseq:
            sseq = dict(CONN.findall(body))
        elif body and any(f'.c_cmd(' in body for _ in [0]) and (f'n_he_c{e}_{sl}_o' in body):
            slab = dict(CONN.findall(body)); slab_inst = nm
    assert insts and sseq and slab, (len(insts), sseq is not None, slab is not None)
    used = set()
    for l_ in insts:
        used.update(nets_of(l_))
    ext = {'c': sseq[f'c{e}'], 'd': sseq[f'd{e}'], 's': sseq[f's{e}'],
           'cmd': slab['c_cmd'], 'done': slab['c_done'], 'st': slab['c_st']}
    for v in ext.values():
        used.update(nets_of(v))
    clocks = sorted(n for n in used if n.startswith(('n_clk_', 'n_rst_')))
    decl = [wires[n] for n in sorted(used) if n in wires and n not in clocks]
    missing = [n for n in sorted(used) if n not in wires and n not in clocks]
    assert not missing, missing
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    tb = f"""`timescale 1ns/1ps
// GENERATED by tools/s81/ctrl_lane_bench.py from {a.die} (engine {e}, slab {slab_inst}): {len(insts)} lane instances
module tb_ctrl_lane;
    parameter integer N = {a.n};
    reg n_clk_stream = 0, n_clk_serial = 0, n_rst_stream = 0, n_rst_serial = 0;
    always #0.41667 n_clk_stream = ~n_clk_stream;   // 1.2 GHz stream
    always #0.55556 n_clk_serial = ~n_clk_serial;   // 0.9 GHz serial (related 3:4)
{chr(10).join('    ' + d for d in decl)}
    reg [84:0] c_drv = 0; reg [8:0] d_drv = 0; reg [1:0] s_drv = 0;
    assign {ext['c']} = c_drv;          // sequencer c{e} face
    assign {ext['done']} = d_drv;       // slab c_done face
    assign {ext['st']} = s_drv;         // slab c_st face
    wire [84:0] cmd_obs = {ext['cmd']};  // slab c_cmd face
    wire [8:0] d_obs = {ext['d']};        // sequencer d{e} face
    wire [1:0] s_obs = {ext['s']};        // sequencer s{e} face
{chr(10).join(insts)}
    reg [83:0] cq [0:N-1]; reg [7:0] dq [0:N-1]; integer ct [0:N-1]; integer dt [0:N-1];
    integer cyc = 0, cs = 0, cr = 0, ds = 0, dr = 0, bad = 0, clat = -1, dlat = -1, i, gap;
    integer s_bad = 0, s_lat = -1, s_t0 = 0; reg [1:0] s_want = 0;
    always @(posedge n_clk_stream) cyc <= cyc + 1;
    initial begin
        for (i = 0; i < N; i = i + 1) begin cq[i] = {{$urandom, $urandom, $urandom}}; dq[i] = $urandom; end
        repeat (8) @(posedge n_clk_serial); n_rst_stream = 1; n_rst_serial = 1;
        repeat (400) @(posedge n_clk_stream);
        fork
            begin : csend
                while (cs < N) begin
                    @(negedge n_clk_stream); c_drv = {{1'b1, cq[cs]}}; ct[cs] = cyc; cs = cs + 1;
                    @(negedge n_clk_stream); c_drv = 0; gap = $urandom % 4; repeat (gap) @(negedge n_clk_stream);
                end
            end
            begin : dsend
                while (ds < N) begin
                    @(negedge n_clk_stream); d_drv = {{1'b1, dq[ds]}}; dt[ds] = cyc; ds = ds + 1;
                    @(negedge n_clk_stream); d_drv = 0; gap = $urandom % 3; repeat (gap) @(negedge n_clk_stream);
                end
            end
        join
        // status levels after the pulse traffic: avail, idle, fault (64 edges each)
        @(negedge n_clk_stream); s_drv = 2'b10; s_want = 2'b10; s_t0 = cyc; repeat (64) @(negedge n_clk_stream);
        s_drv = 2'b00; s_want = 2'b00; s_t0 = cyc; repeat (64) @(negedge n_clk_stream);
        s_drv = 2'b01; s_want = 2'b01; s_t0 = cyc; repeat (64) @(negedge n_clk_stream);
        $display("CTRL_LANE_BENCH engine=%0d slab={slab_inst} c_sent=%0d c_recv=%0d c_latency=%0d d_sent=%0d d_recv=%0d d_latency=%0d bad=%0d s_latency=%0d s_bad=%0d %s",
            {e}, cs, cr, clat, ds, dr, dlat, bad, s_lat, s_bad,
            (cr == N && dr == N && bad == 0 && s_bad == 0 && clat > 0 && dlat > 0 && s_lat > 0) ? "PASS" : "FAIL");
        $finish;
    end
    always @(posedge n_clk_stream) if (n_rst_stream) begin
        if (cmd_obs[84]) begin
            if (cr >= N || cmd_obs[83:0] !== cq[cr]) begin bad = bad + 1; if (bad < 5) $display("ERR c word %0d got %h", cr, cmd_obs); end
            else if (clat < 0) clat = cyc - ct[cr];
            else if (cyc - ct[cr] != clat) begin bad = bad + 1; if (bad < 5) $display("ERR c latency %0d vs %0d", cyc - ct[cr], clat); end
            cr = cr + 1;
        end
        if (d_obs[8]) begin
            if (dr >= N || d_obs[7:0] !== dq[dr]) begin bad = bad + 1; if (bad < 5) $display("ERR d word %0d got %h", dr, d_obs); end
            else if (dlat < 0) dlat = cyc - dt[dr];
            else if (cyc - dt[dr] != dlat) begin bad = bad + 1; if (bad < 5) $display("ERR d latency %0d vs %0d", cyc - dt[dr], dlat); end
            dr = dr + 1;
        end
        if (s_t0 != 0) begin
            if (s_obs === s_want) begin if (s_lat < 0 && s_want == 2'b10) s_lat = cyc - s_t0; end
            else if (cyc - s_t0 > 40) begin s_bad = s_bad + 1; if (s_bad < 5) $display("ERR s level %b want %b", s_obs, s_want); end
        end
    end
endmodule
"""
    (out / 'tb_ctrl_lane.sv').write_text(tb)
    files = [str(ROOT / p) for p in PRIM] + [str(Path(a.glue).resolve()), str(out / 'tb_ctrl_lane.sv')]
    (out / 'files.f').write_text('\n'.join(files) + '\n')
    print(f'CTRL_LANE_EXTRACT engine={e} slab={slab_inst} instances={len(insts)} nets={len(decl)} -> {out}')
    if not a.run:
        return 0
    V = Path.home() / '.local/opentallas-tools/verilator-5.050/bin/verilator'
    r = subprocess.run([str(V), '--binary', '--timing', '-j', '8', '-Wno-fatal', '-Wno-lint', '-Wno-style', '-Wno-UNOPTFLAT',
                        '--top-module', 'tb_ctrl_lane', '--Mdir', str(out / 'obj'), '-o', 'tb', *files],
                       capture_output=True, text=True)
    (out / 'build.log').write_text(r.stdout + r.stderr)
    if r.returncode:
        print('CTRL_LANE_BENCH BUILD_FAIL'); return 2
    r = subprocess.run([str(out / 'obj' / 'tb')], capture_output=True, text=True, timeout=3600)
    (out / 'run.log').write_text(r.stdout + r.stderr)
    line = [l for l in r.stdout.splitlines() if l.startswith(('CTRL_LANE_BENCH', 'ERR'))]
    print('\n'.join(line[-6:]))
    return 0 if line and line[-1].endswith(' PASS') else 1


if __name__ == '__main__':
    sys.exit(main())
