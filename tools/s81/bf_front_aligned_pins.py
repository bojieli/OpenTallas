#!/usr/bin/env python3
"""ot_s81_bf_front pin plan aligned to the CLOSED BF column (s81-bf 2026-10-13).

The compact199 pair is col R0 | front | col MY inside the dsfd_bf frame.  The closed routes placed each block's pins by
face region only, so the 776 column interface pins of the front (c0_* on W, c1_* on E, M4) sit 0.096 / 0.192 um off the
column's E-face pins (issue 116.364 vs 116.556 / 116.268) and every seam needs an M5 jog channel.  This writes the
front's place_pin file with
  * c0_<p>[i] (W, M4) and c1_<p>[i] (E, M4) at exactly the y of the column pin <p>[i] (col MY mirrors x only), so both
    seams are straight M4 abutment wires; the column's rst_n_pin track (y 116.46) stays empty on both faces;
  * c_qy_bkf_in[0] / [1] on the S face (M5) at the W / E end: the column's qy_bkf leaves on ITS S face, 53 um from the
    seam, so the die wire runs in the channel under the frame (~60 um) instead of around the front (190 / 290 um);
  * every other pin where the closed front has it (S control + FP8 stream, N BF16 stream; M5).

    bf_front_aligned_pins.py --col-pins COL.json --front-pins FRONT.json --out physical/s81_bf_hier/front_pins_aligned.tcl

COL.json / FRONT.json: {pin: [direction, layer, x, y]} read from the PINS section of the routed 6_final.def of
bfh_compact199_col_kreg_a1200_05a8d46ee-cl and bfh_compact199_front_a1200_332bffbb6-cl (closed archive; --from-def
extracts them)."""
import argparse, json, re, sys, subprocess
from pathlib import Path

W, H = 100.224, 198.72


def from_def(path):
    t = subprocess.check_output(['zstd', '-dc', path], text=True) if str(path).endswith('.zst') else Path(path).read_text()
    t = t[t.index('\nPINS '):t.index('END PINS')]
    out = {}
    for m in re.finditer(r"- (\S+) \+ NET \S+ \+ DIRECTION (\w+) \+ USE SIGNAL\s+\+ PORT\s+\+ LAYER (\w+) \( -?\d+ -?\d+ \) "
                         r"\( -?\d+ -?\d+ \)\s+\+ (?:PLACED|FIXED) \( (-?\d+) (-?\d+) \) \w+", t):
        out[m[1].replace('\\', '')] = [m[2], m[3], int(m[4]) / 1000, int(m[5]) / 1000]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--col-pins'); ap.add_argument('--front-pins'); ap.add_argument('--col-def'); ap.add_argument('--front-def')
    ap.add_argument('--out', type=Path, required=True); ap.add_argument('--json', type=Path)
    a = ap.parse_args()
    col = from_def(a.col_def) if a.col_def else json.loads(Path(a.col_pins).read_text())
    fr = from_def(a.front_def) if a.front_def else json.loads(Path(a.front_pins).read_text())
    lines = ["# generated by tools/s81/bf_front_aligned_pins.py: ot_s81_bf_front pins; c0_* (W) / c1_* (E) at the y of the closed",
             "# column's E-face pins (bfh_compact199_col_kreg_a1200_05a8d46ee-cl), c_qy_bkf_in on S, the rest as the closed front"]
    used, n_seam, moved = set(), 0, 0
    for name in sorted(fr):
        d, lay, x, y = fr[name]
        m = re.match(r'c([01])_(.*)$', name)
        if m and m[2] in col:
            cy = col[m[2]][3]
            assert col[m[2]][1] == 'M4' and abs((cy - 0.012) / 0.048 - round((cy - 0.012) / 0.048)) < 1e-6, (name, cy)
            face_x = 0.0 if m[1] == '0' else W
            key = (m[1], round(cy, 3)); assert key not in used, key
            used.add(key); n_seam += 1; moved += abs(cy - y) > 1e-6
            lines.append(f"place_pin -pin_name {{{name}}} -layer M4 -location {{{face_x} {cy:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary")
        elif name.startswith('c_qy_bkf_in'):
            bit = int(re.search(r'\[(\d+)\]', name)[1])
            px = 4.332 if bit == 0 else 95.916          # M5 tracks 4.332 / 95.916 um: W end faces col R0, E end col MY
            lines.append(f"place_pin -pin_name {{{name}}} -layer M5 -location {{{px:.3f} 0.0}} -pin_size {{0.024 0.192}} -force_to_die_boundary")
        elif lay == 'M5' and (y < 0.5 or y > H - 0.5):
            lines.append(f"place_pin -pin_name {{{name}}} -layer M5 -location {{{x:.3f} {0.0 if y < 0.5 else H}}} -pin_size {{0.024 0.192}} -force_to_die_boundary")
        else:
            sys.exit(f"unplanned pin {name} {fr[name]}")
    missing = [p for p in col if col[p][1] == 'M4' and p != 'rst_n_pin' and ('0', round(col[p][3], 3)) not in used]
    assert not missing, missing[:5]
    assert ('0', round(col['rst_n_pin'][3], 3)) not in used
    a.out.write_text("\n".join(lines) + "\n")
    rec = dict(schema="opentallas.s81.bf_front_aligned_pins.v1", front=[W, H], pins=len(lines) - 2, seam_pins=n_seam,
               seam_pins_moved=moved, col_rst_n_pin_y=col['rst_n_pin'][3], qy_bkf_col_s_x=col['qy_bkf'][2],
               c_qy_bkf_in_s_x=[4.332, 95.916])
    print(json.dumps(rec))
    if a.json:
        a.json.write_text(json.dumps(rec, indent=1) + "\n")


if __name__ == '__main__':
    main()
