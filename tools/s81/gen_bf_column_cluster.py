#!/usr/bin/env python3
"""Hardened-cluster BF column (S-ELEM 2026-10-16, opt-in, unqualified).

Derived from the generated ten-root column (tools/s81/gen_bf_column_roots.py output) after the hybrid12 E/W CTS
failure (root insertion 710 ps, intra-root spread 100-390 ps, FF hold -314 ps: each root's sinks spread over the
whole 450 x 199 tile).  The column becomes a cluster of hardened single-root children, each placed under its own
clock pin, with registered child inputs:

  child            top                 root        input stage                         cycles
  BFL4 (x4)        ot_v41_bf_lane4_cl  leaf_ck[2..5] relocated BXST boundary in; NEW output reg  +1 BF16
  BFFP             ot_v41_bf_fp_cl     leaf_ck[0]  one FXST stage relocated (+0); output reg +1  +1 FP4
                   (fp0 pair + fp1 chain on ONE root: the fp1->fp0 'other' hop stays internal)
  BFRED            ot_v41_bf_red_cl    leaf_ck[6]  new input register (values/errors/tag/v)  +1 BF16
                   (reduction low + high on ONE root: the low->high hop stays internal)
  BFSEG            ot_v41_bf_seg_cl    leaf_ck[1]  new input register (data/rows/indices/v)  +1 both paths

ck (ROM read/capture pipeline, lanes tree tile, parent XST/FXST stages) and the two raw ROM clock entries stay in
the parent.  Column latency: BF16 path +3 (lane out, red in, seg in), FP4 path +2 (fp out, seg in) (transaction-level exact: every input of a registered child
is delayed by the same edge, valid with reset, so values, order and tree are unchanged).  Same-PLL zero-phase roots.
Die clock entries per column: 7 std (fp, seg, lane0..3, red) + ck + 2 raw ROM.  Existing files stay byte-identical.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
V = ROOT / 'rtl/v41rom'
D = ROOT / 'rtl/dsrom_sys/s81_die_bind'


def once(s, a, b):
    assert s.count(a) == 1, (a[:80], s.count(a))
    return s.replace(a, b)


LEAVES = """`timescale 1ns/1ps
// GENERATED by tools/s81/gen_bf_column_cluster.py -- do not edit.
// Hardened single-root children of the cluster BF column.  Each registers its inputs at its pins on its own gated
// clock (valid reset, data plain), so a child boundary never carries logic in front of its first flop.
// BF_CL_MUTANT_SKEW (negative control): the valid bypasses the new input register while the data is registered.

// BFRED: golden-order pairwise reduction 16 -> 8 (low) -> 1 (high) on one root.  +1 input edge.
module ot_v41_bf_red_cl #(parameter integer TRW=7, parameter [8:0] CUT=9'b1_1111_1111)(
 input wire fclk,rst_pin,ze_d,iv,
 input wire [511:0] values_in,input wire [15:0] errors_in,input wire [TRW:0] tag_in,
 output wire ov,output wire [31:0] oval,output wire oerr,output wire [TRW:0] tag_out);
 // r2 reset frontier (routed r1 native: rst_pin capture 235.3 > 190 into three tile-clock synchronisers spread over
 // the 198.7-tall strip): one pin-side async-assert / sync-release flop; +1 boot-release edge, 0 payload edges.
 reg rp_q;
 always @(posedge fclk or negedge rst_pin) if(!rst_pin) rp_q<=1'b0; else rp_q<=1'b1;
 wire rst_l=rp_q;
 wire clk,rst_n;
 ot_v41_tile_clk u_tc(.fclk(fclk),.rst_pin(rst_l),.ze_d(ze_d),.gclk(clk),.rst_n(rst_n));
 reg iv_q;reg [511:0] v_q;reg [15:0] e_q;reg [TRW:0] t_q;
 always @(posedge clk or negedge rst_n) if(!rst_n) iv_q<=1'b0; else iv_q<=iv;
 always @(posedge clk) begin v_q<=values_in;e_q<=errors_in;t_q<=tag_in; end
`ifdef BF_CL_MUTANT_SKEW
 wire iv_d=iv;
`else
 wire iv_d=iv_q;
`endif
 wire v_low;wire [255:0] low_values;wire [7:0] low_errors;wire [TRW:0] low_tag;
 ot_v41_bf_reduce #(.NIN(16),.LEVELS(1),.TRW(TRW),.CUT(CUT)) u_reduce_low
   (.fclk(fclk),.rst_pin(rst_l),.ze_d(ze_d),.iv(iv_d),
    .values_in(v_q),.errors_in(e_q),.tag_in(t_q),
    .ov(v_low),.values_out(low_values),.errors_out(low_errors),.tag_out(low_tag));
 ot_v41_bf_reduce #(.NIN(8),.LEVELS(3),.TRW(TRW),.CUT(CUT)) u_reduce_high
   (.fclk(fclk),.rst_pin(rst_l),.ze_d(ze_d),.iv(v_low),
    .values_in(low_values),.errors_in(low_errors),.tag_in(low_tag),
    .ov(ov),.values_out(oval),.errors_out(oerr),.tag_out(tag_out));
endmodule

// BFSEG: segment tree + registered partial outputs.  +1 input edge (rows/indices/counts ride with the data).
module ot_v41_bf_seg_cl #(parameter integer NSEG=8,LV=5,MTP=1,EARLY=1,
 parameter [8:0] CUT=9'b1_0111_1011,
 parameter integer SW=$clog2(NSEG),TRW=SW+(MTP!=0?1:0))(
 input wire fclk,rst_pin,ze_d,in_v,
 input wire [TRW-1:0] in_tree,input wire [2:0] in_pos,
 input wire [31:0] in_val,input wire in_final,in_err,
 input wire [16*NSEG-1:0] rows,input wire [5*NSEG-1:0] indices,counts,
 output wire pv,output wire [31:0] pval,output wire [15:0] prow,
 output wire [4:0] pseg,pnseg,output wire [2:0] ppos,output wire perr,
 output wire fault);
 wire clk,rst_n;
 ot_v41_tile_clk u_tc(.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.gclk(clk),.rst_n(rst_n));
 reg v_q;reg [TRW-1:0] tr_q;reg [2:0] po_q;reg [31:0] va_q;reg fi_q,er_q;
 reg [16*NSEG-1:0] ro_q;reg [5*NSEG-1:0] ix_q,cn_q;
 always @(posedge clk or negedge rst_n) if(!rst_n) v_q<=1'b0; else v_q<=in_v;
 always @(posedge clk) begin tr_q<=in_tree;po_q<=in_pos;va_q<=in_val;fi_q<=in_final;er_q<=in_err;
  ro_q<=rows;ix_q<=indices;cn_q<=counts; end
`ifdef BF_CL_MUTANT_SKEW
 wire v_d=in_v;
`else
 wire v_d=v_q;
`endif
 ot_v41_bf_segment_leaf #(.NSEG(NSEG),.LV(LV),.MTP(MTP),.EARLY(EARLY),.CUT(CUT)) u_segment_leaf
  (.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.in_v(v_d),.in_tree(tr_q),.in_pos(po_q),.in_val(va_q),
   .in_final(fi_q),.in_err(er_q),.rows(ro_q),.indices(ix_q),.counts(cn_q),
   .pv(pv),.pval(pval),.prow(prow),.pseg(pseg),.pnseg(pnseg),.ppos(ppos),.perr(perr),.fault(fault));
endmodule

// BFFP: FP4 chunk pair (fp0 pair leaf + fp1 chain) on one root.  The input register is the LAST of the parent's
// FXST relay stages moved to the child pins: +0 edges.
module ot_v41_bf_fp_cl #(parameter integer NCH=16,TG=7,TW=$clog2(NCH)+TG+6,
 parameter [8:0] CUT=9'b1_0111_1011)(
 input wire fclk,rst_pin,ze_d,v0,v1,input wire [TW-1:0] tag,
 input wire [255:0] xq0,wq0,xq1,wq1,input wire [9:0] xe0,we0,xe1,we1,
 output wire q_v,output wire [31:0] q_val,output wire q_err,output wire [TG:0] q_tag,output wire fault0,fault1);
 wire qv_i,qe_i,f0_i,f1_i;wire [31:0] qval_i;wire [TG:0] qt_i;
 wire clk,rst_n;
 ot_v41_tile_clk u_tc(.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.gclk(clk),.rst_n(rst_n));
 reg [1:0] v_q;reg [TW-1:0] t_q;reg [255:0] xq0_q,wq0_q,xq1_q,wq1_q;reg [9:0] xe0_q,we0_q,xe1_q,we1_q;
 always @(posedge clk or negedge rst_n) if(!rst_n) v_q<=2'b00; else v_q<={v0,v1};
 always @(posedge clk) begin t_q<=tag;xq0_q<=xq0;wq0_q<=wq0;xq1_q<=xq1;wq1_q<=wq1;
  xe0_q<=xe0;we0_q<=we0;xe1_q<=xe1;we1_q<=we1; end
`ifdef BF_CL_MUTANT_SKEW
 wire [1:0] v_d={v0,v1};
`else
 wire [1:0] v_d=v_q;
`endif
 wire c1_v,c1_f;wire [31:0] c1_s;wire [TG:0] c1_t;
 ot_v41_bf_fp4_pair_leaf #(.NCH(NCH),.TG(TG),.TW(TW),.CUT(CUT)) u_fp0_leaf
   (.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.v(v_d[1]),.fp4(t_q[0]),
    .xq(xq0_q),.xe(xe0_q),.wq(wq0_q),.we(we0_q),.tag(t_q),
    .other_v(c1_v),.other_sum(c1_s),.other_f(c1_f),.other_tag(c1_t),
    .q_v(qv_i),.q_val(qval_i),.q_err(qe_i),.q_tag(qt_i),.fault(f0_i));
 ot_v41_bf_fp4_chain #(.NCH(NCH),.TG(TG),.TW(TW),.CUT(CUT)) u_fp1_leaf
   (.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.v(v_d[0]),.fp4(1'b1),
    .xq(xq1_q),.xe(xe1_q),.wq(wq1_q),.we(we1_q),.tag(t_q),
    .cv(c1_v),.cs(c1_s),.cf(c1_f),.ct(c1_t),.fault(f1_i));
 // Pin-side output stage on a local gated clock (+1 FP4 edge): q_val is a registered-select mux and the chain
 // registers sit deep in the tile (gate s81_bf_cl_fp native launch 308.5 on q_val).
 wire oclk,orst;
 ot_v41_tile_clk u_oc(.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.gclk(oclk),.rst_n(orst));
 reg qv_q,qe_q,f0_q,f1_q;reg [31:0] qval_q;reg [TG:0] qt_q;
 always @(posedge oclk or negedge orst) if(!orst) begin qv_q<=1'b0;f0_q<=1'b0;f1_q<=1'b0; end
  else begin qv_q<=qv_i;f0_q<=f0_i;f1_q<=f1_i; end
 always @(posedge oclk) begin qval_q<=qval_i;qe_q<=qe_i;qt_q<=qt_i; end
 assign q_v=qv_q;assign q_val=qval_q;assign q_err=qe_q;assign q_tag=qt_q;assign fault0=f0_q;assign fault1=f1_q;
endmodule
"""


LANE4_CL = """`timescale 1ns/1ps
// GENERATED by tools/s81/gen_bf_column_cluster.py -- do not edit.
// BFL4: lane4 master with registered outputs on its own local gated clock (+1 edge on every lane output, BF16 path).
// The lane chain registers sit behind per-lane ICGs deep in the tile; native launch (routed r2 gate: cs_p of lane 3
// 238 ps > 220) needs a dedicated pin-side output stage.
module ot_v41_bf_lane4_cl #(
    parameter integer NCHB=8,TRW=7,GRADUAL_RNE=1,RC=1,GROUP=0,BOUNDARY_STAGE=1,
    parameter [8:0] CUT=9'b1_0111_1011
)(input wire fclk,rst_pin,ze_d,v_s,
  input wire [63:0] w_s,x_s,
  input wire [$clog2(NCHB)+2+TRW:0] t_p,
  output wire [3:0] cv,cf,cfault,
  output wire [127:0] cs_p,
  output wire [4*(TRW+1)-1:0] ct_p);
 wire [3:0] cv_i,cf_i,fa_i;wire [127:0] cs_i;wire [4*(TRW+1)-1:0] ct_i;
 ot_v41_bf_lane4 #(.NCHB(NCHB),.TRW(TRW),.GRADUAL_RNE(GRADUAL_RNE),.RC(RC),.GROUP(GROUP),
   .BOUNDARY_STAGE(BOUNDARY_STAGE),.CUT(CUT)) u_lane4
  (.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.v_s(v_s),.w_s(w_s),.x_s(x_s),.t_p(t_p),
   .cv(cv_i),.cf(cf_i),.cfault(fa_i),.cs_p(cs_i),.ct_p(ct_i));
 wire oclk,orst;
 ot_v41_tile_clk u_oc(.fclk(fclk),.rst_pin(rst_pin),.ze_d(ze_d),.gclk(oclk),.rst_n(orst));
 reg [3:0] cv_q,cf_q,fa_q;reg [127:0] cs_q;reg [4*(TRW+1)-1:0] ct_q;
 always @(posedge oclk or negedge orst) if(!orst) begin cv_q<=4'd0;fa_q<=4'd0; end else begin cv_q<=cv_i;fa_q<=fa_i; end
 always @(posedge oclk) begin cf_q<=cf_i;cs_q<=cs_i;ct_q<=ct_i; end
`ifdef BF_CL_MUTANT_SKEW
 assign cv=cv_i;
`else
 assign cv=cv_q;
`endif
 assign cf=cf_q;assign cfault=fa_q;assign cs_p=cs_q;assign ct_p=ct_q;
endmodule
"""


def lanes3():
    s = (V / 'ot_v41_bf16_lanes3_roots.sv').read_text()
    s = once(s, 'module ot_v41_bf16_lanes3_roots #(', 'module ot_v41_bf16_lanes3_cl #(')
    s = once(s, '    input wire [5:0] leaf_clk, // lane groups0..3, reduction level0, reduction levels1..3',
             '    input wire [4:0] leaf_clk, // cl: lane groups0..3, reduction (one hardened root)')
    s = once(s, '        ot_v41_bf_lane4 #(', '        ot_v41_bf_lane4_cl #(')
    a = s.index('    wire v_low;wire [255:0] low_values;')
    b = s.index('    assign otree=final_tag[TRW:1];')
    s = s[:a] + """    wire [TRW:0] final_tag;
    ot_v41_bf_red_cl #(.TRW(TRW),.CUT(CUTT)) u_red
      (.fclk(leaf_clk[4]),.rst_pin(rst_pin),.ze_d(ze_d),.iv(cv[0]),
       .values_in(lane_values),.errors_in(cf),.tag_in(ct[0]),
       .ov(ov),.oval(oval),.oerr(oerr),.tag_out(final_tag));
""" + s[b:]
    return '// GENERATED by tools/s81/gen_bf_column_cluster.py from ot_v41_bf16_lanes3_roots.sv -- do not edit.\n' + s


def column():
    s = (V / 'ot_v41_bf_col_roots.sv').read_text()
    s = once(s, 'module ot_v41_bf_col_roots #(', 'module ot_v41_bf_col_cl #(')
    s = once(s, '    input wire [8:0] leaf_clk, // fp0, fp1, segment, four lane groups, two reduction roots',
             '    input wire [6:0] leaf_clk, // cl: fp, segment, four lane groups, reduction')
    # the three local roots drive only non-production profiles (g_l2/g_nfast); keep them on the fp/segment roots
    s = once(s, '.fclk(leaf_clk[root])', '.fclk(leaf_clk[root==2?1:0])')
    # FXST: the parent keeps FXST-1 relay stages; the last one is the BFFP child's pin register (+0 edges)
    a = s.index('        if (TCG != 0 && FXST != 0) begin : g_fx')
    b = s.index('        end else begin : g_nfx', a)
    blk = s[a:b].replace('FXST', 'PFXST')
    s = s[:a] + '        localparam integer PFXST = FXST > 0 ? FXST - 1 : 0;\n' + blk + s[b:]
    s = once(s, '        if (TCG != 0 && PFXST != 0) begin : g_fx', '        if (TCG != 0 && PFXST != 0) begin : g_fx')
    a = s.index('        ot_v41_bf_fp4_pair_leaf #(.NCH(NCH),.TG(TG),.TW(TW),.CUT(CUT)) u_fp0_leaf')
    b = s.index('    end else if (FAST != 0) begin : g_l2', a)
    s = s[:a] + """        ot_v41_bf_fp_cl #(.NCH(NCH),.TG(TG),.TW(TW),.CUT(CUT)) u_fp
          (.fclk(leaf_clk[0]),.rst_pin(b_rst),.ze_d(b_ze),.v0(f_v0),.v1(f_v1),.tag(f_t),
           .xq0(f_xq0),.xe0(f_xe0),.wq0(f_w0q),.we0(f_we0),.xq1(f_xq1),.xe1(f_xe1),.wq1(f_w1q),.we1(f_we1),
           .q_v(q_v),.q_val(q_val),.q_err(q_err),.q_tag(q_tag_native),.fault0(c0_fault),.fault1(c1_fault));
""" + s[b:]
    s = once(s, '.leaf_clk(leaf_clk[8:3]), .fclk(clk)', '.leaf_clk({leaf_clk[6], leaf_clk[5:2]}), .fclk(clk)')
    s = once(s, 'ot_v41_bf16_lanes3_roots #(', 'ot_v41_bf16_lanes3_cl #(')
    s = once(s, '    ot_v41_bf_segment_leaf #(.NSEG(NSEG),.LV(LV),.MTP(MTP),.EARLY(EARLY),.CUT(CUT)) u_segment_leaf\n      (.fclk(leaf_clk[2])',
             '    ot_v41_bf_seg_cl #(.NSEG(NSEG),.LV(LV),.MTP(MTP),.EARLY(EARLY),.CUT(CUT)) u_seg\n      (.fclk(leaf_clk[1])')
    return '// GENERATED by tools/s81/gen_bf_column_cluster.py from ot_v41_bf_col_roots.sv -- do not edit.\n' + s


def wrapper():
    s = (D / 'dsfd_bf_col_roots.sv').read_text()
    s = once(s, 'module dsfd_bf_col_roots #(', 'module dsfd_bf_col_cl #(')
    s = once(s, '    input wire [8:0] leaf_ck,', '    input wire [6:0] leaf_ck, // cl: fp, seg, lane0..3, red')
    s = once(s, '    ot_v41_bf_col_roots #(', '    ot_v41_bf_col_cl #(')
    return '// GENERATED by tools/s81/gen_bf_column_cluster.py from dsfd_bf_col_roots.sv -- do not edit.\n' + s


def generate():
    out = {V / 'ot_v41_bf_cl_leaves.sv': LEAVES, V / 'ot_v41_bf_lane4_cl.sv': LANE4_CL, V / 'ot_v41_bf16_lanes3_cl.sv': lanes3(),
           V / 'ot_v41_bf_col_cl.sv': column(), D / 'dsfd_bf_col_cl.sv': wrapper()}
    for p, t in out.items():
        p.write_text(t)
        print('wrote', p.relative_to(ROOT))


if __name__ == '__main__':
    generate()
