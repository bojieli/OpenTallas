#!/usr/bin/env python3
"""Build the production BF16 operand tile with eight real 128x256 SRAMs.

Four instances replace the production spine's four flop-buffer IX tiles. Each
tile has four independent read groups, with two macros per group; all four
copies receive the same two complete 256-bit writes. No read latency is added.
The reference is the unchanged parameterized, pinned hierarchical IX tile.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def main():
    source = ROOT / "physical/s81_pq_hier/pinned/rtl/v41die/ot_v41_pqc_tiles.sv"
    text = source.read_text()
    text = text[text.index("module ot_v41_pqc_ix #("):text.index("\n// T_QB:")]
    text = text.replace("module ot_v41_pqc_ix", "module ot_s81_pq_ix_sram", 1)
    text = text.replace("output wire [255:0]    bt_d", "output wire           fault,\n    output wire [255:0]    bt_d", 1)
    text = text.replace("input  wire            par,", "input  wire            consume,\n    input  wire            par,", 1)
    start = text.index("    // the buffer: one array per lane index")
    text = text[:start] + r'''
    // KMAX=6144 uses 96 of 128 rows. A row contains eight BF16 words
    // from each of two adjacent lane indices. Each independent byte group
    // owns a read-port replica; each load writes all four copies together.
    localparam integer ROWS_USED = KMAX / 64;
    initial begin
        if (KMAX != 6144 || VRD != 64)
            $fatal(1, "production IX SRAM requires KMAX6144/VRD64");
    end
    reg [WBW-1:0] write_blk;
    reg write_valid;
    always @(posedge clk or negedge rst_l[0]) begin
        if (!rst_l[0]) begin write_blk <= '0; write_valid <= 1'b0; end
        else begin write_blk <= ba_blk; write_valid <= ba_v; end
    end
    wire we = write_valid && (write_blk[0] == par);
    wire [6:0] wa = write_blk[WBW-1:1];
    wire [7:0] bank_fault;
    reg consume_1, consume_2;
    always @(posedge clk or negedge rst_l[0])
        if (!rst_l[0]) begin consume_1 <= 0; consume_2 <= 0; end
        else begin consume_1 <= consume; consume_2 <= consume_1; end
    // The diagnostic leaves from its own pin register, like the data lanes.
    reg fault_pin;
    always @(posedge clk or negedge rst_l[0])
        if (!rst_l[0]) fault_pin <= 0; else fault_pin <= |bank_fault;
    assign fault = fault_pin;
    genvar gu, gp, gl;
    generate for (gu = 0; gu < 4; gu = gu + 1) begin : g_read_group
        for (gp = 0; gp < 2; gp = gp + 1) begin : g_bank
            wire [8:0] row = p1_hi[9*(2*gu + gp) +: 9];
`ifdef OT_S81_PQ_IX_MUT_ROW
            wire [6:0] ra = (gu == 1) ? 7'd0 : row[6:0];
`else
            wire [6:0] ra = row[6:0];
`endif
            wire re = p1_bg[2*gu + gp] && consume_1;
            wire [255:0] rd;
            wire [255:0] wd = bw_d[256*gp +: 256];
            ot_sram_1r1w_128x256_m1_r2c2 u_mem (
                .clk(clk), .r_ce_in(re), .r_addr_in(ra), .rd_out(rd),
                .w_ce_in(we), .w_addr_in(wa), .wd_in(wd), .w_mask_in({256{1'b1}}),
                .rr_en(2'b0), .rr_addr(14'b0), .cr_en(2'b0), .cr_sel(16'b0));
            // Side parity protects every 64-bit slice before byte selection.
            reg [3:0] parity [0:ROWS_USED-1];
            reg [ROWS_USED-1:0] written;
            reg [3:0] expected;
            reg checked;
            reg sticky;
            wire [3:0] wp = {^wd[255:192], ^wd[191:128], ^wd[127:64], ^wd[63:0]};
            wire [3:0] rp = {^rd[255:192], ^rd[191:128], ^rd[127:64], ^rd[63:0]};
            always @(posedge clk or negedge rst_l[0]) begin
                if (!rst_l[0]) begin written <= '0; checked <= 0; sticky <= 0; end
                else begin
                    if (we && wa < ROWS_USED) begin parity[wa] <= wp; written[wa] <= 1'b1; end
                    checked <= re && row < ROWS_USED && written[ra];
                    if (re && row < ROWS_USED) expected <= parity[ra];
                    if (checked && expected != rp) sticky <= 1'b1;
                    if (re && (row >= ROWS_USED || !written[ra])) sticky <= 1'b1;
                end
            end
            assign bank_fault[2*gu + gp] = sticky;
`ifndef SYNTHESIS
            always @(posedge clk) if (rst_l[0]) begin
                if (we && wa >= ROWS_USED) $fatal(1, "IX write beyond production storage");
                if (re && (row >= ROWS_USED || !written[ra])) $fatal(1, "IX read before loaded");
                if (we && re && wa == ra) $fatal(1, "IX read during write violates have protocol");
            end
`endif
            for (gl = 0; gl < 2; gl = gl + 1) begin : g_lane
                reg [15:0] selected;
                always @(posedge clk)
                    selected <= p2_bg[4*gu + 2*gp + gl] && consume_2
                        ? rd[128*gl + 16*p2_bb[3*(4*gu + 2*gp + gl) +: 3] +: 16] : 16'd0;
                assign bt_d[64*gu + 32*gp + 16*gl +: 16] = selected;
            end
        end
    end endgenerate
endmodule
'''
    header = "`timescale 1ns/1ps\n// Generated by tools/s81/pq_ix_sram.py; production KMAX6144 SRAM tile.\n"
    out = ROOT / "rtl/dsrom_sys/s81_ph/pq/ot_s81_pq_ix_sram.sv"
    out.write_text(header + text)
    print(out.relative_to(ROOT))


if __name__ == "__main__":
    main()
