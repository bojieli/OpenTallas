#!/usr/bin/env python3
"""Hub end / start block die views for an S81 die variant (CLAUDE S81-DIE, 2026-10-07).

Every 'hend' instance of the die is its own generator master (dsfd_{m2l,r2l,l2r}_<fmt>_<lanes>__<inst>: the same
logic, its pins on the faces toward its own peers).  This writes, for one die variant:
  physical/s81_die_views/ports/<label>/<master>/{ports.json, io_place.tcl}   (tools/s81_die_view_ports.py records)
  physical/s81_die_views/hend/<label>/dsfd_glue.sv                            (the die's glue RTL, current generator)
  physical/s81_die_views/hend/<label>/masters.json                            (master -> kind, lanes, outline, ports)
  <jobs>/s81-hend-<label>-<master>-<commit>.json                              (closure-loop jobs, --jobs DIR)
  hend_views.py emit --s81-opts "<die options incl. --die>" --label m221pq [--jobs DIR --commit C --branch B]
"""
import argparse
import json
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
import dsrom_s81_fulldie as S  # noqa: E402
import s81_die_view_ports as V  # noqa: E402


def job(label, mst, kind, commit, branch, glue):
    lab = '{LABEL}'
    env = (f'SRC={{SRC}} OUT={{RUN}}/routes CORES=8 DIE={label} GLUE={glue} SDCGEN=make_sdc_hend.sh HEND_KIND={kind} '
           f'POSTCTS=physical/s81_die_views/glue/post_cts_hend.tcl CLK=ck PD=0.45 '
           f'SRCS="rtl/common/ot_ratio_cdc_fifo.sv"')
    name = f's81-hend-{label}-{mst.split("__")[1].replace("_", "-")}-{commit}'
    return name, dict(
        name=name, block=mst, owner='Claude:s81-die',
        purpose=f'S81 {label} die hub end/start block {mst} ({kind}; registered FIFO crossing, pins at the generator '
                'positions): die view (LEF + SS/FF lib) for die-level STA; no per-master bench (structural wrapper of '
                'the benched ot_meso_fifo d8g1 / ot_ratio_cdc_fifo primitives)',
        hosts=['ot-agidock128', 'ot-pve1', 'ot-epyc1tb', 'ot-epyc2'], threads=8, peak_ram_gb=16,
        source=dict(branch=branch, commit=commit),
        stages=dict(
            bench=[],
            calibrate=dict(cmd=f'{env} physical/s81_die_views/glue/route.sh {lab}${{CL_LABEL_SUFFIX}} {mst} $CL_STOP_AFTER',
                           base='{RUN}/routes/{LABEL}_cal/work/orfs/results/asap7/*/base', clock='core_clk',
                           sdc_cmd='echo "route SDC regenerated by the route script from CK_SS_MEAN=$CK_SS_MEAN"',
                           threads=8, peak_ram_gb=12),
            route=dict(cmd=f'{env} physical/s81_die_views/glue/route.sh {lab} {mst}',
                       ok="grep -q '^rc=0' {RUN}/routes/{LABEL}/exit && grep -q '^corner_rc=0' {RUN}/routes/{LABEL}/exit",
                       logs=['{RUN}/routes/{LABEL}/run.log']),
            collect=dict(cmd=f'mkdir -p {{RUN}}/record && cd {{SRC}} && python3 tools/hbm_fmax_attn_abstract.py --orfs-dir '
                             f'{{RUN}}/routes/{lab}/work/orfs --name {mst} --out {{RUN}}/record --tmp-dir {{RUN}}/abs_tmp > '
                             f'{{RUN}}/record/export.log 2>&1; python3 tools/s81_die_view_ports.py check --die {label} '
                             f'--master {mst} --lef {{RUN}}/record/{mst}.lef > {{RUN}}/record/check.json; cp '
                             f'{{RUN}}/routes/{lab}/corner_sta.json {{RUN}}/routes/{lab}/args {{RUN}}/record/ && cp '
                             '{CL}/calib.json {RUN}/record/calib.json')),
        verdict=dict(corner_sta='{RUN}/routes/{LABEL}/corner_sta.json',
                     drc_metrics='{RUN}/routes/{LABEL}/work/orfs/logs/asap7/*/base/5_2_route.json', checks=[],
                     post_sdc=['physical/s81_die_views/common/signoff_unc60.sdc']),
        record=[{'from': '{RUN}/record', 'to': f'physical/s81_die_views/views/{label}/{mst}'}],
        cycles_added=0, merge_target=branch,
        budget=dict(enabled=False, reason='registered-at-pin FIFO crossing view: IO at 0.2 T (+150 ps die term on the '
                    'local side) against the measured insertion, as the cfifo / station views'))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('mode', choices=['emit'])
    ap.add_argument('--s81-opts', required=True)
    ap.add_argument('--label', required=True)
    ap.add_argument('--jobs', type=Path)
    ap.add_argument('--commit', default='HEAD')
    ap.add_argument('--branch', default='claude/s81-die-20261007')
    a = ap.parse_args()
    args = S.die_options(argparse.ArgumentParser()).parse_args(shlex.split(a.s81_opts))
    S.apply_options(args)
    m = S.build()
    S.finalize_r8(m)
    hend = sorted({it.master for it in m['insts'] if it.kind == 'hend'})
    recs = V.records(m, args.die, a.s81_opts, hend)
    pdir = ROOT / 'physical/s81_die_views/ports' / a.label
    for n, rec in recs.items():
        d = pdir / n
        d.mkdir(parents=True, exist_ok=True)
        (d / 'ports.json').write_text(json.dumps(rec, indent=0) + '\n')
        (d / 'io_place.tcl').write_text(V.io_tcl(rec))
    hd = ROOT / 'physical/s81_die_views/hend' / a.label
    hd.mkdir(parents=True, exist_ok=True)
    (hd / 'dsfd_glue.sv').write_text(S.glue_rtl(m))
    info = {n: dict(kind=m['glue'][n]['kind'], fmt=m['glue'][n]['fmt'], lanes=m['glue'][n]['lanes'],
                    w_um=recs[n]['w_um'], h_um=recs[n]['h_um'],
                    ports={p: (q['direction'], q['bits'], q['face']) for p, q in recs[n]['ports'].items()})
            for n in hend}
    (hd / 'masters.json').write_text(json.dumps(dict(options=a.s81_opts, masters=info), indent=1) + '\n')
    if a.jobs:
        a.jobs.mkdir(parents=True, exist_ok=True)
        glue = f'physical/s81_die_views/hend/{a.label}/dsfd_glue.sv'
        for n in hend:
            name, j = job(a.label, n, info[n]['kind'], a.commit, a.branch, glue)
            (a.jobs / f'{name}.json').write_text(json.dumps(j, indent=1) + '\n')
    print(json.dumps({n: (v['kind'], v['lanes'], v['w_um'], v['h_um']) for n, v in info.items()}, indent=0))


if __name__ == '__main__':
    main()
