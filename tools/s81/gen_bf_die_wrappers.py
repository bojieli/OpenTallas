#!/usr/bin/env python3
"""s81-die-rtl-bind 2026-10-14: die-name RTL of the S81 BF pair masters (dsfd_bf_col x1024, dsfd_bf_front x512).

The die generator (--bf-hier-compact, tools/s81/bf_direct_pins.py) binds every die-port bit of dsfd_bf_col /
dsfd_bf_front to ONE pin of the CLOSED compact199 views (ot_v41_bf_col bfh_compact199_col_kreg_a1200_05a8d46ee-cl,
ot_s81_bf_front el1013-bf-front-align-f003d825f-cl): die bit i of port p = groups()[p][i].  This tool writes the RTL
those die masters ARE: a wires-only module under the die name that instantiates the closed view's RTL module with the
closed route's elaboration parameters and maps die bit i to the same pin -- so the RTL binding and the physical
binding are one table (no second hand-written map).

The closed front's RTL has inputs the die does not drive yet: go_bf and the native BF16 x stream xb_* (1,067 b).
They are NOT tied: dsfd_bf_front gets one more die port, xb[1067:0] = {xb_d 1024, xb_u 32, xb_sv 4, xb_b 3, xb_v,
xb_pos 3, go_bf} (bit 0 = go_bf), which tools/die_port_bind.py reports unconnected until the BF transport exists.
hph (constant 1 at HALF 0) is left open inside the wrapper (an output nothing reads).

  python3 tools/s81/gen_bf_die_wrappers.py [--check]     (--check: fail if the committed files differ)
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/s81'))
import bf_direct_pins as B   # noqa: E402

OUT = ROOT / 'rtl/dsrom_sys/s81_die_bind'
# run_bf_hier_physical.py QP (column) + the closed routes' --bxst 2 --fxst 2 (HDLY 0); the front: --block front
# parameters + --pinlat 1 (route commands in results/closure_loop/<job>/verdict.json job_spec)
COL_PARAMS = dict(NSEG=8, NCH=16, XF=8, LV=5, BF16=1, NCHB=8, NB=2, MTP=1, EARLY=1, CG=1, DRAIN=200, FAST=1, PP=1, BP=0,
                  QTIMING_FIX=1, QPIPE=1, QP_XS=1, QP_CAP=0, QP_P1=1, QP_CSAM=10, QZ=1, QZ_NS=8, QZ_NE=4, QY=1, QX=10,
                  QBF=2, QZE=1, TCG=1, GRADUAL_RNE=1, BXST=2, FXST=2)
FRONT_PARAMS = dict(PINREG=1, HITFIX=1, RECUT=2, QZE=1, TCG=1, HCOL=1, BXST=2, FXST=2, PINLAT=1)
COL_DIR = dict(ck='in', rs='in', ci='in', qy='out', r='out')
FRONT_DIR = dict(cfg='in', go='in', st='out', x0='in', x1='in', ck='in', rs='in', c0='out', qy0='in', c1='out',
                 qy1='in', xb='in')
XB = ['go_bf'] + [f'xb_pos[{i}]' for i in range(3)] + ['xb_v'] + [f'xb_b[{i}]' for i in range(3)] + \
     [f'xb_sv[{i}]' for i in range(4)] + [f'xb_u[{i}]' for i in range(32)] + [f'xb_d[{i}]' for i in range(1024)]
OPEN_OUT = {'ot_s81_bf_front': ['hph']}


def _split(pin):
    m = re.match(r'^(\w+)\[(\d+)\]$', pin)
    return (m.group(1), int(m.group(2))) if m else (pin, None)


def render(die, rtl, groups, dirs, params, extra_params, note):
    widths = {}
    for pins in groups.values():
        for p in pins:
            b, i = _split(p)
            widths[b] = max(widths.get(b, 0), (i + 1) if i is not None else 0)
    L = ['`timescale 1ns/1ps', '// GENERATED by tools/s81/gen_bf_die_wrappers.py -- do not edit.']
    L += ['// ' + x for x in note]
    pl = ', '.join(f'parameter {k} = {v}' for k, v in extra_params)
    pnames = [k.split()[-1] for k, _ in extra_params]
    L.append(f'module {die} #({pl}) (')
    decl = []
    for port, pins in groups.items():
        w = len(pins)
        decl.append(f'    {"input " if dirs[port] == "in" else "output"} wire [{w - 1}:0] {port}')
    if die == 'dsfd_bf_front_static':
        decl.append('    input wire [37:0] f_prog')
        decl.append('    input wire io_clk')
    L.append(',\n'.join(decl))
    L.append(');')
    for b in sorted(widths):
        w = widths[b]
        L.append(f'    wire {"[%d:0] " % (w - 1) if w else ""}w_{b};')
    mut = {}
    if die == 'dsfd_bf_col':       # negative control: two seam bits of the die map swapped (tools/s81/bf_txn_bench.py --die-pair)
        ia, ib = groups['ci'].index('a_ctr[0]'), groups['ci'].index('a_ctr[1]')
        mut = {('ci', ia): ib, ('ci', ib): ia}
    for port, pins in groups.items():
        for i, p in enumerate(pins):
            b, j = _split(p)
            sig = f'w_{b}' + (f'[{j}]' if j is not None else '')
            if dirs[port] == 'in':
                if (port, i) in mut:
                    L.append('`ifdef DSFD_BF_DIE_MUT_SWAP')
                    L.append(f'    assign {sig} = {port}[{mut[(port, i)]}];')
                    L.append('`else')
                    L.append(f'    assign {sig} = {port}[{i}];')
                    L.append('`endif')
                else:
                    L.append(f'    assign {sig} = {port}[{i}];')
            else:
                L.append(f'    assign {port}[{i}] = {sig};')
    ps = ', '.join(f'.{k}({v})' for k, v in list(params.items()) + [(n, n) for n in pnames])
    conns = [f'.{b}(w_{b})' for b in sorted(widths)] + [f'.{o}()' for o in OPEN_OUT.get(rtl, [])]
    if die == 'dsfd_bf_front_static':
        conns.extend(['.f_prog(f_prog)', '.io_clk(io_clk)'])
    L.append('    /* verilator lint_off PINCONNECTEMPTY */')
    L.append(f'    {rtl} #({ps}) u_view (')
    L.append('        ' + ',\n        '.join(conns) + ');')
    L.append('    /* verilator lint_on PINCONNECTEMPTY */')
    L.append('endmodule')
    return '\n'.join(L) + '\n'


def build():
    col = B.groups(column=True)
    front = B.groups(column=False)
    assert 'xb' not in front
    front = dict(front, xb=XB)
    files = {
        'dsfd_bf_col.sv': render(
            'dsfd_bf_col', 'ot_v41_bf_col', col, COL_DIR, COL_PARAMS,
            [('INSTANCE', '""'), ('integer MB', '0')],
            ['dsfd_bf_col (die master x1024, both columns of a BF pair; the E one is placed MY) = the CLOSED view',
             'ot_v41_bf_col (bfh_compact199_col_kreg_a1200_05a8d46ee-cl, TT +33.00 / FF +15.37, DRC 0) at its route',
             'parameters.  Die bit i of ci / r / qy = the view pin tools/s81/bf_direct_pins.groups(column=True) names.',
             'INSTANCE / MB: simulation ROM image names only (ot_v41_bf_col MB), never hardware.']),
        'dsfd_bf_front.sv': render(
            'dsfd_bf_front', 'ot_s81_bf_front', front, FRONT_DIR, FRONT_PARAMS, [('INSTANCE', '""')],
            ['dsfd_bf_front (die master x512, the pair front) = the CLOSED view ot_s81_bf_front',
             '(el1013-bf-front-align-f003d825f-cl, TT +99.69 / FF +18.73, DRC 0) at its route parameters.  Die bit i of',
             'every port = the view pin tools/s81/bf_direct_pins.groups() names; xb = {xb_d, xb_u, xb_sv, xb_b, xb_v,',
             'xb_pos, go_bf} (bit 0 go_bf): the native BF16 x stream, a die port with NO die driver until the BF transport',
             'is built (die_port_bind reports it; never tied).  hph (1 at HALF 0) has no reader.']),
    }
    files['dsfd_bf_front_static.sv'] = render(
        'dsfd_bf_front_static', 'ot_s81_bf_front', front, FRONT_DIR,
        dict(FRONT_PARAMS, STATIC_PROGRAM=1, CPIN=1), [('INSTANCE', '""')],
        ['Actual compiler-programmed BF front: all legacy payload pins retained;',
         'f_prog[37:0] captured at pins, core consumes +1 edge, CPIN adds +1 column edge.',
         'Requires its own static physical view; historical CLOSED view is not substituted.'])
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    bad = []
    for name, text in build().items():
        p = OUT / name
        if a.check:
            if not p.exists() or p.read_text() != text:
                bad.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            print('wrote', p.relative_to(ROOT))
    if bad:
        raise SystemExit('stale: ' + ', '.join(bad))


if __name__ == '__main__':
    main()
