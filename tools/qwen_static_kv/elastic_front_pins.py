#!/usr/bin/env python3
"""0az elastic front pin plan (kvsys lead r8 2026-10-15): qkd_kv_hbm_elastic_front 64.8 x 216 abuts the W face of the static
return ring qkd_static_kv_return_slots (129.6 x 216, v1.3 static_io pins).  Its E face carries co_out / epoch_out /
compiled_hbm_put at EXACTLY the y of the ring's controller_co / controller_epoch / compiled_hbm_put (zero-length abutted
hops); its W face carries co_in / epoch_in / blk_go straight across at the same y (controller / CDC side).  Status
outputs on the N face, pll_hbm / hrst on the S face, all on the ASAP7 M5 track lattice (.060 + .192 k um).

    python3 tools/qwen_static_kv/elastic_front_pins.py   # writes results/.../kvsys_v1_4_candidate/static_io/qkd_kv_hbm_elastic_front.tcl
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RING = ROOT / 'results/arch/qwen_split_1014/kvsys_v1_3_candidate/static_io/qkd_static_kv_return_slots.tcl'
OUT = ROOT / 'results/arch/qwen_split_1014/kvsys_v1_4_candidate/static_io/qkd_kv_hbm_elastic_front.tcl'
W, H = 64.8, 216.0
M5 = lambda k: round(0.060 + 0.192 * k, 3)  # noqa: E731
STATUS = ['blk_freed', 'hold', 'idle', 'fault_overflow', 'fault_go'] + [f'stall_edges[{i}]' for i in range(16)] + \
         [f'occupancy[{i}]' for i in range(6)]


def main():
    ring = {}
    for ln in RING.read_text().splitlines():
        m = re.match(r'place_pin -pin_name \{(\S+)\} -layer (M\d) -location \{([\d.]+) ([\d.]+)\}', ln)
        if m and m.group(3) == '0.000' and m.group(2) == 'M4':
            ring[m.group(1)] = float(m.group(4))
    pairs = [(f'co_out[{i}]', f'co_in[{i}]', f'controller_co[{i}]') for i in range(294)] + \
            [(f'epoch_out[{i}]', f'epoch_in[{i}]', f'controller_epoch[{i}]') for i in range(16)] + \
            [('compiled_hbm_put', 'blk_go', 'compiled_hbm_put')]
    L = ['# GENERATED by tools/qwen_static_kv/elastic_front_pins.py: qkd_kv_hbm_elastic_front 64.8 x 216, E face abuts the',
         '# static return ring W face pin for pin; W face straight-through; N status; S clock/reset (M5 lattice).']
    for e, w_, r in pairs:
        y = ring[r]
        L.append(f'place_pin -pin_name {{{e}}} -layer M4 -location {{{W:.3f} {y:.3f}}} -pin_size {{.144 .024}}')
        L.append(f'place_pin -pin_name {{{w_}}} -layer M4 -location {{0.000 {y:.3f}}} -pin_size {{.144 .024}}')
    for j, p in enumerate(STATUS):
        L.append(f'place_pin -pin_name {{{p}}} -layer M5 -location {{{M5(40 + 4 * j):.3f} {H:.3f}}} -pin_size {{.024 .144}}')
    for p, k in (('pll_hbm', 135), ('hrst', 200)):
        L.append(f'place_pin -pin_name {{{p}}} -layer M5 -location {{{M5(k):.3f} 0.000}} -pin_size {{.024 .144}}')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L) + '\n')
    print(OUT, len(L) - 2, 'pins')


if __name__ == '__main__':
    main()
