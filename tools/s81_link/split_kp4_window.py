#!/usr/bin/env python3
"""S81-TYPES-9-RCK 11-08: split the KP4 WINDOW matrices into four partial products (one register stage).

The generated window matrices (tools/s81_link/gen_kp4_linear.py) compute
    <p0>[o] = ^(<in>[H-1:0]   & MASK0[o])        <p1>[o] = ^(<in>[2H-1:H] & MASK1[o])
This tool writes, from those exact masks, the GF(2)-linear split
    <q0>[o] = ^(<in>[A-1:0]  & MASK0[o][A-1:0])     <q1>[o] = ^(<in>[H-1:A]    & MASK0[o][H-1:A])
    <q2>[o] = ^(<in>[H+B-1:H] & MASK1[o][B-1:0])    <q3>[o] = ^(<in>[2H-1:H+B] & MASK1[o][H-1:B])
so that p0 = q0 ^ q1 and p1 = q2 ^ q3 for every input (XOR is linear; the self-check below recombines every mask).
Cut points follow the RTL select copies: encoder ch_q 4 x 130 (A = B = 130); syndrome sc_q copies of 138 bits
(A = 138, B = 138).  Usage:
    split_kp4_window.py enc  <ot_s81_kp4_enc_mat.svh>  <out.svh>
    split_kp4_window.py syn  <ot_s81_kp4_syn_mat.svh>  <out.svh>
"""
import re
import sys

KIND = {
    #       in    H    A    B    p0      p1      q names
    'enc': ('ch_q', 260, 130, 130, 'e_p0', 'e_p1', ('e_q0', 'e_q1', 'e_q2', 'e_q3')),
    'syn': ('sc_q', 275, 138, 138, 's_p0', 's_p1', ('s_q0', 's_q1', 's_q2', 's_q3')),
}


def masks(text, name, width):
    out = {}
    pat = re.compile(r'^assign %s\[(\d+)\] = \^\((\w+)(\[\d+:\d+\])? & %d\'h([0-9a-fA-F]+)\);$' % (name, width), re.M)
    for m in pat.finditer(text):
        out[int(m.group(1))] = int(m.group(4), 16)
    assert sorted(out) == list(range(300)), (name, len(out))
    return out


def term(sig, lo, hi, mask):
    w = hi - lo + 1
    if mask == 0:
        return "1'b0"
    return "^(%s[%d:%d] & %d'h%x)" % (sig, hi, lo, w, mask)


def main():
    kind, src, dst = sys.argv[1:4]
    sig, H, A, B, p0, p1, q = KIND[kind]
    text = open(src).read()
    m0, m1 = masks(text, p0, H), masks(text, p1, H)
    lines = ['// GENERATED by split_kp4_window.py (S81-TYPES-9-RCK 11-08) from %s -- do not edit.' % src.split('/')[-1],
             '// Four-way split of the %s window matrices: %s = %s ^ %s, %s = %s ^ %s (exact GF(2) mask split, one'
             % (kind, p0, q[0], q[1], p1, q[2], q[3]),
             '// register stage between the partials and their pair XOR).  Include inside the generate branch that uses it.']
    for o in range(300):
        a, b = m0[o] & ((1 << A) - 1), m0[o] >> A
        c, d = m1[o] & ((1 << B) - 1), m1[o] >> B
        assert a | (b << A) == m0[o] and c | (d << B) == m1[o]
        lines.append('assign %s[%d] = %s;' % (q[0], o, term(sig, 0, A - 1, a)))
        lines.append('assign %s[%d] = %s;' % (q[1], o, term(sig, A, H - 1, b)))
        lines.append('assign %s[%d] = %s;' % (q[2], o, term(sig, H, H + B - 1, c)))
        lines.append('assign %s[%d] = %s;' % (q[3], o, term(sig, H + B, 2 * H - 1, d)))
    open(dst, 'w').write('\n'.join(lines) + '\n')
    print('%s: %d outputs x 4 partials written to %s' % (kind, 300, dst))


if __name__ == '__main__':
    main()
