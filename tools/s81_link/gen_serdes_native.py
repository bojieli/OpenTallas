#!/usr/bin/env python3
"""Generate a no-parameter physical flat decoder from the real four-child RTL.

This is source preparation, not a timing abstraction. Leaves retain their real
published views; no modeled decoder or rate-matcher view is produced here.
"""
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('lp', ROOT / 'tools/landed_parent/lp.py')
lp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lp)
source = ROOT / 'rtl/dsrom_sys/s81_link/ot_s81_kp4_dec.sv'
mod = lp.parse_module(lp.preprocess(source.read_text(), ['OT_KP4_DEC_HARD']), 'ot_s81_kp4_dec')
ports = []
for p in mod['ports']:
    direction = {'in': 'input', 'out': 'output', 'inout': 'inout'}[p['dir']]
    ports.append(f"{direction} wire {p['range'] + ' ' if p['range'] else ''}{p['name']}")
body = mod['body']
# Explicit face registers clocked in the owning region: a single global
# pin_regs clock would create new unlanded crossings on multi-root outputs.
inputs = [p for p in mod['ports'] if p['name'] in ('p_v', 'p_d')]
outputs = [p for p in mod['ports'] if p['dir'] == 'out']
for p in inputs + outputs:
    body = re.sub(r'(?<!\.)\b' + p['name'] + r'\b', 'face_' + p['name'], body)
face = []
for p in inputs + outputs:
    name, rng = p['name'], p['range'] or ''
    width = lp.width_text(rng)
    face.append(f"wire {rng} face_{name};")
    clock = 'clk'  # lp.py assigns each pad to its owning region below.
    d, q = (name, 'face_' + name) if p in inputs else ('face_' + name, name)
    face.append(f"ot_pl_pad #(.W({width}), .N(1)) u_face_{name} (.ck({clock}), .d({d}), .q({q}));")
body += '\n' + '\n'.join(face) + '\n' 
assert all(not i['params'] for i in lp.parse_body(mod['body'])[2]), 'hard children must have fixed accepted parameters'
out = ROOT / 'rtl/dsrom_sys/s81_link/native'
out.mkdir(parents=True, exist_ok=True)
(out / 'ot_s81_kp4_dec_native_flat.sv').write_text(
    '`timescale 1ns/1ps\n// GENERATED by tools/s81_link/gen_serdes_native.py; hard child structure, no abstract digital logic.\n'
    + '// Source SHA256 ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    + 'module ot_s81_kp4_dec_native_flat (\n    ' + ',\n    '.join(ports) + '\n);\n' + body + '\nendmodule\n')

# Optional simulation composition of exactly the accepted leaf pin registers.
# Run again after lp.py gen; production uses the actual accepted hard views.
landed = ROOT / 'rtl/dsrom_sys/s81_link/lp/ot_s81_kp4_dec_native_flat_lp.sv'
if landed.exists():
    hw = landed.read_text().replace('module ot_s81_kp4_dec_native_flat_lp #', 'module ot_s81_kp4_dec_native_flat_lp_hw #')
    wrappers = []
    for leaf in ('dsyn', 'ddly', 'dchn', 'dout'):
        name = 'ot_s81_kp4_' + leaf
        cm = lp.parse_module(lp.preprocess((ROOT / f'rtl/dsrom_sys/s81_link/{name}.sv').read_text(), []), name)
        hw = re.sub(r'\b' + name + r'\b', name + '_pinmodel', hw)
        pp, lines, connections = [], [], []
        for p in cm['ports']:
            n, rng = p['name'], p['range'] or ''
            direction = {'in': 'input', 'out': 'output'}[p['dir']]
            pp.append(f"{direction} wire {rng} {n}")
            if n in ('clk', 'rst_n'):
                connections.append(f'.{n}({n})')
                continue
            lines.append(f"wire {rng} pin_{n};")
            d, q = (n, 'pin_' + n) if p['dir'] == 'in' else ('pin_' + n, n)
            lines.append(f"ot_pl_pad #(.W({lp.width_text(p['range'])}), .N(1)) u_pin_{n} (.ck(clk), .d({d}), .q({q}));")
            connections.append(f'.{n}(pin_{n})')
        lines.append(name + ' u_real (' + ', '.join(connections) + ');')
        wrappers.append('module ' + name + '_pinmodel (\n' + ',\n'.join(pp) + '\n);\n' + '\n'.join(lines) + '\nendmodule\n')
    (out / 'ot_s81_kp4_dec_native_pinmodel.sv').write_text('// GENERATED simulation-only composition of accepted input/output pin flops; no timing model.\n' + hw + '\n'.join(wrappers))
