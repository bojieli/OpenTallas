#!/usr/bin/env python3
"""FABLE-FIX-HEAD-SD9F 11-18: N-way split of the KP4 WINDOW matrices into registered partials (ZERO added cycles).

hd_serdes sd9f / sd9g3 routed sign-off: the only failing setup family is the window rank ch_q -> pp0/pp1 (encoder) and
sc_q -> sp0/sp1 (syndrome): two 260/275-input GF(2) rows per output = an 8-level XOR tree (7.7 levels measured, 507-590 ps
of routed logic delay) in one 833 ps stage, while the stage that consumes the partials (wb <= pp0 ^ pp1) has one level.
This tool cuts every row into N contiguous input segments:
    <w>[k*300 + o] = ^(<in>[lo_k +: seg] & MASK[o] segment k)        k = 0..N-1
so that (p0 ^ p1)[o] = XOR_k <w>[k*300 + o] for every input (XOR is linear; the self-check recombines every mask).  The
partials are registered in the SAME stage pp0/pp1 were, and the N-input XOR moves into the next stage: no pin cycle.
Depth of the first stage (worst row): N=2 (today) 8 levels, N=8 6, N=16 5.
Usage:  split_kp4_window_n.py enc|syn N <ot_s81_kp4_{enc,enc_la,syn}_mat.svh> <out.svh>
"""
import math
import re
import sys

KIND = {  # in, H (bits per window half), p0, p1, partial vector
    'enc': ('ch_q', 260, 'e_p0', 'e_p1', 'e_w'),
    'syn': ('sc_q', 275, 's_p0', 's_p1', 's_w'),
}


def masks(text, name, width):
    out = {}
    pat = re.compile(r'^assign %s\[(\d+)\] = \^\((\w+)(\[\d+:\d+\])? & %d\'h([0-9a-fA-F]+)\);$' % (name, width), re.M)
    for m in pat.finditer(text):
        out[int(m.group(1))] = int(m.group(4), 16)
    assert sorted(out) == list(range(300)), (name, len(out))
    return out


def split(kind, n, text):
    sig, H, p0, p1, w = KIND[kind]
    m0, m1 = masks(text, p0, H), masks(text, p1, H)
    W = 2 * H
    seg = math.ceil(W / n)
    lines, worst = [], 0
    for o in range(300):
        full = m0[o] | (m1[o] << H)
        back = 0
        for k in range(n):
            lo, hi = k * seg, min(W, (k + 1) * seg) - 1
            part = (full >> lo) & ((1 << (hi - lo + 1)) - 1)
            back |= part << lo
            worst = max(worst, bin(part).count('1'))
            rhs = "1'b0" if part == 0 else "^(%s[%d:%d] & %d'h%x)" % (sig, hi, lo, hi - lo + 1, part)
            lines.append('assign %s[%d] = %s;' % (w, k * 300 + o, rhs))
        assert back == full, o
    return seg, worst, lines


def main():
    kind, n, src, dst = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    seg, worst, lines = split(kind, n, open(src).read())
    sig, H, p0, p1, w = KIND[kind]
    head = ['// GENERATED by split_kp4_window_n.py (FABLE-FIX-HEAD-SD9F 11-18) from %s -- do not edit.' % src.split('/')[-1],
            '// %d-way split of the %s window matrices: (%s ^ %s)[o] = XOR over k of %s[k*300 + o]; partial k reads %s[k*%d +: %d]'
            % (n, kind, p0, p1, w, sig, seg, seg),
            '// (exact GF(2) mask split; widest partial %d inputs).  The partials are registered where %s/%s were: 0 cycles.'
            % (worst, p0.replace('e_p', 'pp').replace('s_p', 'sp'), p1.replace('e_p', 'pp').replace('s_p', 'sp'))]
    open(dst, 'w').write('\n'.join(head + lines) + '\n')
    print('%s: 300 outputs x %d partials (segment %d bits, widest %d inputs) written to %s' % (kind, n, seg, worst, dst))


if __name__ == '__main__':
    main()
