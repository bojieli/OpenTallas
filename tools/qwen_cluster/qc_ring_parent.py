#!/usr/bin/env python3
"""QW-CB16REG 10-20 (main line a): CB16 parent with HARDENED landing-ring crossings.

rtl/physical/qcluster/qfd_c_b16_fullm.sv (fulln/fullnb RTL) -> rtl/physical/qcluster/qfd_c_b16_rgx.sv:
every soft crossing pair
    qfd_c_land_w1k #(.W(W), .D(4))        u_land_<n>_w (.ck(CKW), .rsi(RSW), .i(I), .bank(..), .epo(..), .vld(..));
    qfd_c_land_r1k #(.W(W), .D(4), .K(2)) u_land_<n>_r (.ck(CKR), .rsi(RSR), .bank(..), .epo(..), .vld(..), .o(O));
becomes
    qfd_c_ring<W> u_land_<n> (.ck_w(CKW), .rsi_w(RSW), .i(I), .ck_r(CKR), .rsi_r(RSR), .o(O));   // hard
(tile == writer + reader exactly: bench tools/qwen_cluster/bench_ring_t.sh).  The MUT 6 crossing (bench-only read slot
K = 3) keeps the parameterised qfd_c_ring_t under MUT == 6.  Module names *_fullm* -> *_rgx*.  Nothing else
changes: same ports, stations, A0, xstn, reset trees, scalar FFs, edges.
    qc_ring_parent.py            (writes the RTL, prints the crossing table)
"""
import re, pathlib, json, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'rtl/physical/qcluster/qfd_c_b16_fullm.sv'
DST = ROOT / 'rtl/physical/qcluster/qfd_c_b16_rgx.sv'
L = SRC.read_text().split('\n')
start = next(i for i, l in enumerate(L) if l.startswith('module qfd_c_b16_fullm_fabric'))
end = next(i for i, l in enumerate(L) if l.startswith('module qfd_c_b16_fullmb_fabric'))
# keep the header comment block of the fullm variant + both fullm modules
hdr_start = next(i for i in range(start, -1, -1) if L[i].startswith('`timescale') or i == 0)
body = L[start:end]
while body and not body[-1].startswith('endmodule'):
    body.pop()
WR = re.compile(r'^(\s*)qfd_c_land_w1k #\(\.W\((\d+)\), \.D\(4\)\) u_land_(\w+)_w \(\.ck\((\w+)\), \.rsi\((\w+)\), \.i\(([^()]+)\), \.bank\(\w+\), \.epo\(\w+\), \.vld\(\w+\)\);(.*)$')
RD = re.compile(r'^(\s*)qfd_c_land_r1k #\(\.W\((\d+)\), \.D\(4\), \.K\(([^()]+(?:\([^()]*\))?[^()]*)\)\) u_land_(\w+)_r \(\.ck\((\w+)\), \.rsi\((\w+)\), \.bank\(\w+\), \.epo\(\w+\), \.vld\(\w+\), \.o\((\w+)\)\);(.*)$')
w = {}; out = []; table = []
for l in body:
    m = WR.match(l)
    if m:
        ind, W, n, ckw, rsw, i, cmt = m.groups(); w[n] = (W, ckw, rsw, i, cmt); continue
    m = RD.match(l)
    if m:
        ind, W, K, n, ckr, rsr, o, cmt = m.groups()
        Ww, ckw, rsw, i, wcmt = w.pop(n)
        assert Ww == W, n
        sel = o
        if K.strip() == '2':
            out.append(f'{ind}qfd_c_ring{W} u_land_{n} (.ck_w({ckw}), .rsi_w({rsw}), .i({i}), .ck_r({ckr}), .rsi_r({rsr}), .o({sel}));   // HARD crossing {ckw} -> {ckr}')
        else:
            out.append(f'{ind}if (1) begin : g_land_{n}   // bench-only K mutant keeps the parameterised tile')
            out.append(f'{ind}    if ({K.strip()} == 2) begin : g_hard qfd_c_ring{W} u_land_{n} (.ck_w({ckw}), .rsi_w({rsw}), .i({i}), .ck_r({ckr}), .rsi_r({rsr}), .o({sel})); end')
            out.append(f'{ind}    else begin : g_mut qfd_c_ring_t #(.W({W}), .D(4), .K({K.strip()})) u_land_{n} (.ck_w({ckw}), .rsi_w({rsw}), .i({i}), .ck_r({ckr}), .rsi_r({rsr}), .o({sel})); end')
            out.append(f'{ind}end')
        table.append(dict(name=n, W=int(W), ck_w=ckw, ck_r=ckr, i=i, o=o, mut_K=K.strip() != '2'))
        continue
    assert 'qfd_c_land_w1k' not in l and 'qfd_c_land_r1k' not in l or l.lstrip().startswith('//'), l[:200]
    out.append(l)
assert not w, w
txt = '\n'.join(out)
txt = txt.replace('qfd_c_b16_fullm_fabric', 'qfd_c_b16_rgx_fabric').replace('module qfd_c_b16_fullm (', 'module qfd_c_b16_rgx (')
head = ('`timescale 1ns/1ps\n'
        '// GENERATED by tools/qwen_cluster/qc_ring_parent.py from rtl/physical/qcluster/qfd_c_b16_fullm.sv -- do not edit.\n'
        '// QW-CB16REG 10-20 (main line a): every landing-ring crossing hardened = qfd_c_ring<W> (writer ring on the source\n'
        '// region clock + reader incl. its output register on the destination clock); hard tile per crossing;\n'
        f'// {len(table)} crossings.  Same ports / stations / A0 / xstn / reset trees / scalar FFs / edges.\n')
DST.write_text(head + txt + '\n')
json.dump(table, sys.stdout, indent=0); print()
print(f'QC_RING_PARENT {len(table)} crossings ({sum(t["W"] == 516 for t in table)} x 516, {sum(t["W"] == 514 for t in table)} x 514) -> {DST.relative_to(ROOT)}', file=sys.stderr)
