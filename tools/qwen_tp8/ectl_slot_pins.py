#!/usr/bin/env python3
"""q13-ectl 2026-10-13: exact pin plan of the TP8 control tile (cell qkd_ectl) from its contract slot.

Reads the slot (results/arch/hier_contract_1012/qwen_rom_tp8.json, first slot of cell qkd_ectl) and writes one
place_pin per bit: bit i of a bus at span lo + i x 0.096 um (2-track pitch, the slot's own spans), M5 on N / S and M4
on W / E.  The slot's nominal clock entry (N, 323.988) and reset (S, 316.188) fall on a half track / on a t0 pin: they
take the nearest free M5 track between two bus pins (the buses use every other track).

    python3 tools/qwen_tp8/ectl_slot_pins.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CON = ROOT / 'results/arch/hier_contract_1012/qwen_rom_tp8.json'
DST = ROOT / 'physical/ref_tile_specs/qwen_tp8/qkd_ectl_slot_pins.tcl'
W, H, STEP, T0, P = 648.0, 129.6, 0.096, 0.012, 0.048


def main():
    slot = next(s for s in json.loads(CON.read_text())['slots'] if s.get('cell') == 'qkd_ectl')
    out = [f"# GENERATED by tools/qwen_tp8/ectl_slot_pins.py from {CON.relative_to(ROOT)} slot {slot['name']} "
           f"(contract pin spans, bit i at lo + i x {STEP}); do not edit by hand"]
    used = {f: set() for f in 'NSEW'}

    def pin(name, face, c):
        k = round((c - T0) / P)
        assert abs(T0 + k * P - c) < 1e-6, (name, c)
        assert k not in used[face], (name, c)
        used[face].add(k)
        if face in 'NS':
            out.append(f"place_pin -pin_name {{{name}}} -layer M5 -location {{{c:.3f} {H if face == 'N' else 0.0}}} "
                       "-pin_size {0.024 0.192} -force_to_die_boundary")
        else:
            out.append(f"place_pin -pin_name {{{name}}} -layer M4 -location {{{W if face == 'E' else 0.0} {c:.3f}}} "
                       "-pin_size {0.192 0.024} -force_to_die_boundary")
    for p in slot['pins']:
        base, _, rng = p['name'].partition('[')
        if base == 'rst_n':
            continue
        n = int(rng.split(':')[0]) + 1
        lo, hi = p['span_um']
        assert abs(lo + (n - 1) * STEP - hi) < 1e-6, p
        for i in range(n):
            pin(f'{base}[{i}]', p['face'], lo + i * STEP)

    def free(face, want):
        k = round((want - T0) / P)
        for d in range(0, 8):
            for kk in (k + d, k - d):
                if kk not in used[face]:
                    return T0 + kk * P
        raise SystemExit('no free track')
    pin('ck', 'N', free('N', slot['clock_entry']['offset']))
    pin('rst_n', 'S', free('S', 316.188))
    txt = '\n'.join(out) + '\n'
    if '--check' in sys.argv:
        sys.exit(0 if DST.exists() and DST.read_text() == txt else 1)
    DST.write_text(txt)
    print(DST, len(out) - 1, 'pins')


if __name__ == '__main__':
    main()
