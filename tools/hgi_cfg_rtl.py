#!/usr/bin/env python3
"""hbm-forks (2026-10-09): HGI-1 config path constants and CF-0 bench vectors, generated from the frozen v0.9 encoder.

Every bit the RTL checks (magic, version word, reserved-bit masks of the hardware-read words, section-C reset values,
legal sets) is taken from tools/hbm_generic_iface.py, so the RTL binds to the spec exactly (docs/HBM_GENERIC_INTERFACE.md
sections 1.2-1.4, 2).  Writes:
  rtl/hbm_accel/generic/ot_hgi_cfg_consts.svh      SV localparams + the legal-range function (included by the master)
  rtl/hbm_accel/generic/tb/hgi_cfg_cases.mem        CF-0 cases for tb_hgi_cfg (one case = 64 MD words + ctl + expect)
  rtl/hbm_accel/generic/tb/hgi_cfg_cases.json       the same, readable
  python3 tools/hgi_cfg_rtl.py [--check]            --check: fail if the written files drift from the encoder
"""
import json
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import hbm_generic_iface as G  # noqa: E402

OUT = ROOT / 'rtl/hbm_accel/generic'
C_WORDS = list(range(40, 49))       # section C: the 9 block-mode words


def md_words(name):
    return [int(x, 16) for x in (ROOT / f'results/arch/hbm_generic_iface_20261009/md_{name}.hex').read_text().split()]


def recrc(w):
    w = list(w)
    w[G.CRC_WORD] = zlib.crc32(struct.pack('<63I', *w[:63])) & 0xFFFFFFFF
    return w


def reset_words():
    w = [0] * G.NWORDS
    for name, word, lsb, width, *_ in G.D_MD_FIELDS:
        if name in G.D_RESET:
            w[word] |= G.D_RESET[name] << lsb
    return w


def fields_c():
    return [(n, w, l, wd) for n, w, l, wd, *_ in G.D_MD_FIELDS if 40 <= w <= 48]


def used_mask():
    used = [0] * G.NWORDS
    for name, w, lsb, width, *_ in G.D_MD_FIELDS:
        for k in range(max(1, width // 32)):
            used[w + k] |= 0xFFFFFFFF if width >= 32 else ((1 << width) - 1) << lsb
    return used


def legal_sv():
    """one SV function: legal(word, data) for section C, from D_LEGAL (ranges or sets)."""
    L = ['function automatic hgi_c_legal(input [5:0] w, input [31:0] d);', '    reg ok;', '    begin', "        ok = 1'b1;",
         '        case (w)']
    byw = {}
    for n, w, l, wd in fields_c():
        if n in G.D_LEGAL:
            byw.setdefault(w, []).append((n, l, wd))
    for w in sorted(byw):
        conds = []
        for n, l, wd in byw[w]:
            f = f"d[{l + wd - 1}:{l}]" if wd > 1 else f"d[{l}]"
            lim = G.D_LEGAL[n]
            if isinstance(lim, set):
                conds.append('(' + ' || '.join(f"{f} == {wd}'d{v}" for v in sorted(lim)) + ')')
            else:
                lo, hi = lim
                c = []
                if lo > 0:
                    c.append(f"{{1'b0, {f}}} >= {wd + 1}'d{lo}")
                if hi < (1 << wd) - 1:
                    c.append(f"{{1'b0, {f}}} <= {wd + 1}'d{hi}")
                if c:
                    conds.append('(' + ' && '.join(c) + ')')
        if conds:
            L.append(f"            6'd{w}: ok = " + ' && '.join(conds) + ';')
    L += ["            default: ok = 1'b1;", '        endcase', '        hgi_c_legal = ok;', '    end', 'endfunction']
    return L


def consts():
    used = used_mask()
    rw = reset_words()
    w1 = (G.NWORDS << 16) | (G.D_VERSION[0] << 8) | G.D_VERSION[1]
    L = ['// GENERATED by tools/hgi_cfg_rtl.py from tools/hbm_generic_iface.py (HGI-1 v%d.%d, owner-approved normative).'
         '  Do not edit.' % G.D_VERSION,
         f'localparam [31:0] HGI_MAGIC = 32\'h{G.MAGIC:08X};',
         f'localparam [23:0] HGI_W1    = 24\'h{w1:06X};         // n_words 64, major {G.D_VERSION[0]}, minor {G.D_VERSION[1]}',
         'function automatic [31:0] hgi_used(input [5:0] w);   // used bits of a word (reserved = ~used)',
         '    case (w)']
    for w in range(G.NWORDS):
        if used[w] != 0:
            L.append(f"        6'd{w}: hgi_used = 32'h{used[w]:08X};")
    L += ["        default: hgi_used = 32'h00000000;", '    endcase', 'endfunction',
          '// section-C reset words (= DS-V4.1-Flash = the DS descriptor\'s section C)']
    for w in C_WORDS:
        L.append(f"localparam [31:0] HGI_RST_W{w} = 32'h{rw[w]:08X};")
    L.append('localparam [9*32-1:0] HGI_RST_C = {' + ', '.join(f'HGI_RST_W{w}' for w in reversed(C_WORDS)) + '};')
    L.append('// field positions (word, lsb, width)')
    for n, w, l, wd in fields_c():
        L.append(f'localparam integer HGI_{n.upper()}_W = {w}, HGI_{n.upper()}_L = {l}, HGI_{n.upper()}_N = {wd};')
    L += legal_sv()
    return '\n'.join(L) + '\n'


def cases():
    """the hbm-sim CF-0 conformance vectors (results/arch/hgi_sim_20261009/conformance/cf-0__*) in order, then reloads;
    err = tools/hbm_generic_iface.d_hw_check (the normative check, case for case)"""
    conf = sorted((ROOT / 'results/arch/hgi_sim_20261009/conformance').glob('cf-0__*.json'))
    code = dict(OK=0, E_MAGIC=1, E_VERSION=2, E_CRC=3, E_BUSY=4, E_RANGE=5, E_RESERVED=6)
    out = []
    for f in conf:
        v = json.loads(f.read_text())
        busy = int(v['expect'].get('busy', 'busy' in v['id']))
        words = [int(x) if isinstance(x, int) else int(x, 16) for x in v['words']]
        e = G.d_hw_check(words, busy=bool(busy))
        want = code[v['expect']['err']] if isinstance(v['expect'].get('err'), str) else v['expect'].get('err')
        assert e == want, (v['id'], e, want)
        out.append(dict(name=v['id'], words=words, busy=busy, err=e))
    first = [c for c in out if c['name'].endswith('ds_v41_flash_ok')] + [c for c in out if c['name'].endswith('qwen3_8b_ok')]
    out = first + [c for c in out if c not in first] + [dict(first[1], name=first[1]['name'] + '_reload')]
    act = [reset_words()[w] for w in C_WORDS]
    for c in out:
        if c['err'] == 0:
            act = [c['words'][w] for w in C_WORDS]
        c['act'] = list(act)
    return out


def mem(cs):
    L = []
    for c in cs:
        L += [f'{x:08X}' for x in c['words']]
        L.append(f"{(c['busy'] << 4) | c['err']:08X}")
        L += [f'{x:08X}' for x in c['act']]
    return '\n'.join(L) + '\n'


def main():
    files = {OUT / 'ot_hgi_cfg_consts.svh': consts()}
    cs = cases()
    files[OUT / 'tb/hgi_cfg_cases.mem'] = mem(cs)
    files[OUT / 'tb/hgi_cfg_cases.json'] = json.dumps(dict(
        schema='opentallas.hgi_cfg_cases.v1', spec='results/arch/hbm_generic_iface_20261009/spec.json',
        record_words=64 + 1 + 9, hw_rule='HGI-1 v1.0 normative 5.7: d_hw_check case for case (busy, magic, version, CRC, reserved, range)',
        cases=[dict(name=c['name'], err=c['err'], busy=c['busy'],
                                             act=[f'{x:08X}' for x in c['act']]) for c in cs]), indent=1) + '\n'
    if '--check' in sys.argv:
        bad = [str(p) for p, t in files.items() if not p.exists() or p.read_text() != t]
        print('DRIFT' if bad else 'OK', bad)
        return 1 if bad else 0
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
    print(len(cs), 'cases;', ', '.join(f"{c['name']}={c['err']}" for c in cs))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
