#!/usr/bin/env python3
"""S81-CTRL 10-17: write rtl/dsrom_sys/s81_ph/test/dsfd_ctrl_rg2x16.sv, a BENCH-ONLY composition of 16 regional
controllers dsfd_ctrl_rg2 with exactly the ports of the S81-PH dsfd_ctrl (22238-b phy bundle, rd 8896, rq 10912, rk,
wd, st), so tb_dsfd_ctrl runs unchanged against it (define S81CTRL_RG2) and the regional controller is compared with
the benched strip controller on the same PHY model, the same stimulus and the same checks.

Die-equivalent wiring: region k drives PHY PCs 2k, 2k+1 (the PHY's 32-PC buses sliced [2k +: 2]); the PHY rst_n is a
ckh-synchronised copy of the die reset (the PHY region's own reset leaf on the die); st merges the 16 regional
{fault, live} words plus the PHY out-of-range flags (the die fault tree's job; bench-side only)."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NPC = 32
PHY_IN = {'clk', 'rst_n', 'k_v', 'k_addr', 'k_len', 'k_tag', 'k_we', 'k_wdata', 'k_wstrb', 'kr_rdy', 'w_v', 'w_addr',
          'w_len', 'w_tag', 'wr_rdy'}
WID = dict(k_v=1, k_rdy=1, k_addr=30, k_len=4, k_tag=17, k_we=1, k_wdata=256, k_wstrb=32, k_wr_done=1, kr_v=1, kr_rdy=1,
           kr_tag=17, kr_beat=4, kr_data=256)


def main():
    dfi = json.loads((ROOT / 'results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json').read_text())
    assert len(dfi) == 22238
    L = ['`timescale 1ns/1ps',
         '// GENERATED by tools/s81_ctrl/gen_rg2_bench.py (S81-CTRL): bench-only 16 x dsfd_ctrl_rg2 composition with the',
         '// dsfd_ctrl ports (see the generator docstring).  NOT a die master.',
         '`default_nettype none',
         'module dsfd_ctrl_rg2x16 (',
         '    input  wire [0:0] ckh, input wire [0:0] cks, input wire [0:0] rst,',
         '    inout  wire [22237:0] phy,',
         '    output wire [8895:0] rd,', '    input  wire [10911:0] rq,',
         '    output wire [31:0] rk, output wire [31:0] wd, output reg [1:0] st', ');']
    for n, w in WID.items():
        L.append(f'    wire [{NPC * w - 1}:0] p_{n};')
    L += ['    wire p_k_oor, p_w_oor;', '    wire phy_rst_q;']
    for i, nm in enumerate(dfi):
        base, idx = re.match(r'^(\w+)(?:\[(\d+)\])?$', nm).groups()
        b = f'[{idx}]' if idx is not None else ''
        if base == 'clk':
            L.append(f'    assign phy[{i}] = ckh;')
        elif base == 'rst_n':
            L.append(f'    assign phy[{i}] = phy_rst_q;')
        elif base in PHY_IN:
            src = f'p_{base}{b}' if base in WID else "1'b0"
            L.append(f'    assign phy[{i}] = {src};')
        elif base in WID:
            L.append(f'    assign p_{base}{b} = phy[{i}];')
        elif base in ('k_oor', 'w_oor'):
            L.append(f'    assign p_{base} = phy[{i}];')
    L += ['    ot_s81ph_sync u_prs (.clk(ckh), .rst_n(rst), .d(1\'b1), .q(phy_rst_q));',
          '    wire [1:0] rst_g [0:15];', '    genvar g;',
          '    generate for (g = 0; g < 16; g = g + 1) begin : g_rg', '        wire [561:0] rdk;',
          '        dsfd_ctrl_rg2 u_rg (.clk(cks), .ckh(ckh), .rst_n(rst), .rq(rq[g*682 +: 682]), .rd(rdk), .ck_o(),']
    L.append('            ' + ', '.join(f'.{n}(p_{n}[g*{2 * w} +: {2 * w}])' for n, w in WID.items()) + ');')
    L += ['        genvar p;',
          '        for (p = 0; p < 2; p = p + 1) begin : g_p',
          '            localparam integer c = 2 * g + p;',
          '            assign rd[c*256 +: 256] = rdk[p*280 +: 256];',
          '            assign rd[8192 + c*17 +: 17] = rdk[p*280 + 256 +: 17];',
          '            assign rd[8736 + c*4 +: 4] = rdk[p*280 + 273 +: 4];',
          '            assign rd[8864 + c] = rdk[p*280 + 277];',
          '            assign rk[c] = rdk[p*280 + 278];',
          '            assign wd[c] = rdk[p*280 + 279];',
          '        end',
          '        assign rst_g[g] = rdk[561:560];',
          '    end endgenerate',
          '    // bench-side status merge (the die fault tree): sticky PHY out-of-range crossed into cks',
          '    wire srst_n; ot_s81ph_sync u_srs (.clk(cks), .rst_n(rst), .d(1\'b1), .q(srst_n));',
          '    reg oor_h; always @(posedge ckh or negedge phy_rst_q) if (!phy_rst_q) oor_h <= 1\'b0; else oor_h <= oor_h | p_k_oor | p_w_oor;',
          '    wire oor_s; ot_s81ph_sync u_os (.clk(cks), .rst_n(srst_n), .d(oor_h), .q(oor_s));',
          '    reg f_all, l_all; integer j;',
          '    always @* begin f_all = oor_s; l_all = 1\'b1; for (j = 0; j < 16; j = j + 1) begin f_all = f_all | rst_g[j][1]; l_all = l_all & rst_g[j][0]; end end',
          '    always @(posedge cks or negedge srst_n) if (!srst_n) st <= 2\'b00; else st <= {st[1] | f_all, l_all};',
          'endmodule', '`default_nettype wire', '']
    (ROOT / 'rtl/dsrom_sys/s81_ph/test/dsfd_ctrl_rg2x16.sv').write_text('\n'.join(L))



def pin_plan(tcl='physical/s81_ctrl_rg2/dsfd_ctrl_rg2_pins.tcl'):
    """Reorder the S (PHY) face of the spread pin plan (tools/ref_tile/spread_face_pins.py output) so that it abuts the
    PHY: PC 0 of the region on the W half, PC 1 on the E half, each PC's bits in the PHY's own x order
    (results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json, PHY abstract pins sorted by x).  Positions/layers unchanged."""
    dfi = json.loads((ROOT / 'results/rtl/s81_ph_20261006/ctrl/phy_dfi_order.json').read_text())
    pc0 = []
    for nm in dfi:
        m = re.match(r'^(\w+)\[(\d+)\]$', nm)
        if m and m.group(1) in WID and int(m.group(2)) // WID[m.group(1)] == 0:
            pc0.append((m.group(1), int(m.group(2))))
    assert len(pc0) == sum(WID.values()) == 622, len(pc0)
    want = [f'{b}[{i}]' for b, i in pc0] + ['ckh'] + [f'{b}[{i + WID[b]}]' for b, i in pc0]
    path = ROOT / tcl
    lines = path.read_text().splitlines()
    pat = re.compile(r'-pin_name \{([^}]*)\}.*-location \{([\d.]+) ([\d.]+)\}')
    s_idx = [(float(pat.search(l).group(2)), k) for k, l in enumerate(lines)
             if pat.search(l) and float(pat.search(l).group(3)) == 0.0 and pat.search(l).group(1) in set(want)]
    assert len(s_idx) == len(want), (len(s_idx), len(want))
    for (x, k), nm in zip(sorted(s_idx), want):
        lines[k] = re.sub(r'-pin_name \{[^}]*\}', '-pin_name {' + nm + '}', lines[k])
    # N face (svc slice): PC 0's rq + rd over the W half, PC 1's over the E half, the forwarded clock at the centre, status at the E end
    wn = ([f'rq[{i}]' for i in range(341)] + [f'rd[{i}]' for i in range(280)] + ['clk', 'ck_o'] +
          [f'rq[{i}]' for i in range(341, 682)] + [f'rd[{i}]' for i in range(280, 562)])
    n_idx = [(float(pat.search(l).group(2)), k) for k, l in enumerate(lines)
             if pat.search(l) and pat.search(l).group(1) in set(wn)]
    assert len(n_idx) == len(wn), (len(n_idx), len(wn))
    for (x, k), nm in zip(sorted(n_idx), wn):
        lines[k] = re.sub(r'-pin_name \{[^}]*\}', '-pin_name {' + nm + '}', lines[k])
    lines.insert(1, '# N face reordered: PC 0 rq+rd W half, clk + ck_o centre, PC 1 rq+rd E half, {fault, live}')
    lines.insert(1, '# S face reordered by tools/s81_ctrl/gen_rg2_bench.py pin_plan(): PC 0 W half, PC 1 E half, PHY x order, ckh at the centre')
    path.write_text('\n'.join(lines) + '\n')
    print(f'PIN_PLAN S face: {len(want)} pins in PHY order')


if __name__ == '__main__':
    import sys
    pin_plan() if sys.argv[1:] == ['pins'] else main()
