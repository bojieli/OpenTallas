#!/usr/bin/env python3
"""Emit the semantic-record collector's field extraction from the ABI itself.

The collector assembles the 128-word record the HC_PRE engines consume, and it has
to reach every field by byte offset in a 192-byte raw descriptor: a 64-byte header
then the payload.  There are six descriptor types and about sixty fields, and a
hand-written slice per field is sixty chances to transpose an offset -- the kind of
error that elaborates cleanly and produces a plausible wrong record.

So the slices are GENERATED from ``runtime/abi3/descriptors.py``'s own field
tables, the same tables ``runtime/abi3/semantic_record.py`` reads and
``tests/abi3/test_semantic_record.py`` proves equal to the decoded assembly.  One
source, three consumers: the ABI defines the offsets, Python reads them, the RTL
slices them, and the test ties the two readings together.  A field that moves in
the ABI moves in the generated RTL on the next run rather than becoming a silent
disagreement.

The generated file is committed, because a build that regenerates RTL is a build
that can differ from what was verified.  ``--check`` fails when the committed file
is not what the current ABI produces, which is the same discipline
``tools/publish_abi3_capabilities.py`` applies to the capability records.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from runtime.abi3 import semantic_record as spec  # noqa: E402
from runtime.abi3.descriptors import (  # noqa: E402
    DESCRIPTOR_HEADER,
    PAYLOAD_LAYOUTS,
    ExtendedDescriptorType,
)

OUTPUT = ROOT / "rtl/abi3/ot_a3_semantic_record_slices.svh"
HEADER_BYTES = spec.HEADER_BYTES

BLOCKS = (
    ("operator", ExtendedDescriptorType.OPERATOR, spec.OPERATOR_FIELDS),
    ("counter", ExtendedDescriptorType.COUNTER_CLASS, spec.COUNTER_FIELDS),
    ("numeric", ExtendedDescriptorType.NUMERIC, spec.NUMERIC_FIELDS),
    ("schedule", ExtendedDescriptorType.SCHEDULE, spec.SCHEDULE_FIELDS),
)


def slice_expression(bit_offset: int, size_bytes: int) -> str:
    """A 32-bit zero-extended little-endian read of ``size_bytes`` at a bit offset."""
    bits = size_bytes * 8
    if bits > 32:
        raise SystemExit(f"a record word cannot hold {bits} bits")
    read = f"raw[{bit_offset} +: {bits}]"
    if bits == 32:
        return read
    return f"{{{32 - bits}'d0, {read}}}"


def payload_slice(kind: ExtendedDescriptorType, name: str) -> str:
    field = PAYLOAD_LAYOUTS[kind].field(name)
    return slice_expression((HEADER_BYTES + field.offset) * 8, field.size)


def header_slice(name: str) -> str:
    field = DESCRIPTOR_HEADER.field(name)
    return slice_expression(field.offset * 8, field.size)


def emit() -> str:
    lines: list[str] = []
    add = lines.append
    add("// GENERATED by tools/generate_a3_semantic_record_collector.py.")
    add("// Do not edit: regenerate, and `--check` fails if this drifts from the ABI.")
    add("//")
    add("// One function per record block, each reading a 192-byte raw descriptor")
    add("// (64-byte header then payload) at the byte offsets")
    add("// runtime/abi3/descriptors.py declares. The word order is the record's")
    add("// contract with the engines and comes from runtime/abi3/semantic_record.py,")
    add("// which tests/abi3/test_semantic_record.py proves equal to the decoded")
    add("// assembly on both shipped stores.")
    add("")
    for block, kind, fields in BLOCKS:
        width = len(fields)
        add(f"// {kind.name}: {width} words")
        add(f"function automatic [{width}*32-1:0] a3_record_{block}_words;")
        add("    input [1535:0] raw;")
        add("    begin")
        for index, name in enumerate(fields):
            add(
                f"        a3_record_{block}_words[{index}*32 +: 32] = "
                f"{payload_slice(kind, name)}; // {name}"
            )
        add("    end")
        add("endfunction")
        add("")

    digest = PAYLOAD_LAYOUTS[ExtendedDescriptorType.NUMERIC].field("contract_digest")
    add("// NUMERIC contract digest: 256 bits as eight little-endian words")
    add("function automatic [8*32-1:0] a3_record_digest_words;")
    add("    input [1535:0] raw;")
    add("    begin")
    for index in range(8):
        bit = (HEADER_BYTES + digest.offset + index * 4) * 8
        add(
            f"        a3_record_digest_words[{index}*32 +: 32] = "
            f"raw[{bit} +: 32];"
        )
    add("    end")
    add("endfunction")
    add("")

    view_fields = spec.VIEW_PAYLOAD_FIELDS
    add(f"// TENSOR_VIEW: 2 header words then {len(view_fields)} payload words")
    add(f"function automatic [{2 + len(view_fields)}*32-1:0] a3_record_view_words;")
    add("    input [1535:0] raw;")
    add("    begin")
    add(
        f"        a3_record_view_words[0*32 +: 32] = "
        f"{header_slice('primary_object_id')}; // primary_object_id"
    )
    add(
        f"        a3_record_view_words[1*32 +: 32] = "
        f"{header_slice('permissions')}; // permissions"
    )
    for index, name in enumerate(view_fields):
        add(
            f"        a3_record_view_words[{index + 2}*32 +: 32] = "
            f"{payload_slice(ExtendedDescriptorType.TENSOR_VIEW, name)}; // {name}"
        )
    add("    end")
    add("endfunction")
    add("")
    add("// EVENT_WAIT_SET: the sole producer the record carries at word 6.")
    add("function automatic [31:0] a3_record_wait_producer_0;")
    add("    input [1535:0] raw;")
    add("    begin a3_record_wait_producer_0 = "
        f"{payload_slice(ExtendedDescriptorType.EVENT_WAIT_SET, 'producer_0')}; end")
    add("endfunction")
    add("")
    add("// The header fields a collector matches descriptors by.")
    add("function automatic [31:0] a3_record_descriptor_type;")
    add("    input [1535:0] raw;")
    add(f"    begin a3_record_descriptor_type = {header_slice('descriptor_type')}; end")
    add("endfunction")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument(
        "--check", action="store_true",
        help="do not write; fail if the committed file is not what the ABI produces",
    )
    args = parser.parse_args()
    body = emit()
    if args.check:
        if not args.output.exists():
            print(f"{args.output} does not exist", file=sys.stderr)
            return 1
        if args.output.read_text(encoding="utf-8") != body:
            print(f"{args.output} has drifted from the ABI", file=sys.stderr)
            return 1
        print(f"{args.output}: current")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(body, encoding="utf-8")
    print(f"wrote {args.output} ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
