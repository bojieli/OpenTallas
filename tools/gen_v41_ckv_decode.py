"""Generate the exact finite E2M1 x E4M3FN -> E4M3FN CKV decoder.

The table is a combinational ROM.  Generation uses the exact-rational reference,
including RNE, finite saturation and canonical positive zero.  It does not
infer the forward quantizer from reconstructed values.
"""
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from runtime.reference.formats import decode_e4m3fn
from runtime.reference.fp4_kv import dequantize_element_to_fp8, scale_code_is_nonfinite


OUTPUT = ROOT / "rtl/chip/ot_chip_v41x_ckv_fp4_decode.sv"


def generate() -> str:
    lines = [
        "`timescale 1ns/1ps",
        "// Generated by tools/gen_v41_ckv_decode.py from exact-rational fp4_kv.",
        "// Input scale is one E4M3FN byte for 16 low-nibble-first E2M1 codes.",
        "module ot_chip_v41x_ckv_fp4_decode (",
        "    input wire [3:0] code,",
        "    input wire [7:0] scale,",
        "    output reg [7:0] fp8,",
        "    output reg [31:0] fp32,",
        "    output wire poison",
        ");",
        "assign poison = (scale[6:0] == 7'h7f);",
        "always @(*) begin",
        "    fp8 = 8'h00;",
        "    case ({scale, code})",
    ]
    for scale in range(256):
        if scale_code_is_nonfinite(scale):
            continue
        for code in range(16):
            value, _ = dequantize_element_to_fp8(code, scale)
            if value:
                lines.append(f"        12'h{scale:02x}{code:x}: fp8 = 8'h{value:02x};")
    lines += ["        default: fp8 = 8'h00;", "    endcase", "    fp32 = 32'h00000000;", "    case (fp8)"]
    for code in range(256):
        decoded = decode_e4m3fn(code)
        if not decoded.finite or decoded.value is None:
            continue
        bits = struct.unpack("<I", struct.pack("<f", float(decoded.value)))[0]
        # The architectural decoder canonicalizes both signed zero codes.
        if bits and code:
            lines.append(f"        8'h{code:02x}: fp32 = 32'h{bits:08x};")
    lines += [
        "        default: fp32 = 32'h00000000;",
        "    endcase",
        "    if (poison) begin fp8 = 0; fp32 = 0; end",
        "end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(generate())
