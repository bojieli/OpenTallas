#!/usr/bin/env python3
"""S81-SLICE/ENDP 10-21: wires-only FLAT parents of the four selected72 MU end tops, for tools/landed_parent/lp.py.

Input  rtl/dsrom_sys/s81_dv/slice/mu72/ot_s81sl_slice_<f>_72.sv (G8 die-bound source: u_sl = c1x_k8_cap5r_lp with its 10
       real roots, lanes safe8_ntf, lep_mu_a / lep_mu_h / lep_mu_ab #(RX_SRAM 1, IN_PIPE 1, NATIVE32 1), dsdv_mu_land SRAM 1).
Output rtl/dsrom_sys/s81_dv/slice/mu72/lr/ot_s81sl_slice_<f>_x.sv = the same children / nets / straps with every landing,
       reset run and out_reg removed (one clk, one rst_n), so lp.py re-lands it as LANDED REGIONS (regional reset ports).
Exact text transform (no new logic): ck_S/ck_K/ck_ML -> clk; lpr_c_u_* -> rst_n; *__l_S / *__l_K / *_ml -> flat net;
fault__o -> fault.  u_sl's nine non-C roots (ck_L0..ck_CAP_RS) stay independent parent clock inputs straight to u_sl.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "rtl/dsrom_sys/s81_dv/slice/mu72"
FLAVORS = ("lepw_mab_mu", "lepw_mu", "lepe_mu", "lepe_nh_mu")


def xtop(f):
    t = (SRC / f"ot_s81sl_slice_{f}_72.sv").read_text()
    m = re.search(r"module\s+(\w+)\s*#\(\s*parameter integer MUT = 0\s*\)\s*\(", t)
    assert m, f
    e = t.index(");", m.end())
    ports, body = t[m.end():e], t[e + 2:]
    ports = ports.replace("input wire ck_S,\n    input wire ck_K, ck_ML,", "input wire clk,")
    assert "ck_S" not in ports and "ck_K" not in ports, f
    keep = []
    lines = body.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()
        if re.match(r"(ot_s81sl_slice_c1x_k8_cap5r_lp|dsfd_coll_lane_\w+|ot_s81sl_lep_mu_\w+|dsdv_mu_land)\b", s):
            blk = [ln]
            while not blk[-1].rstrip().split("//")[0].rstrip().endswith(";"):
                i += 1
                blk.append(lines[i])
            keep.append("\n".join(blk))
        elif s.startswith("wire") and not re.search(r"lpl_|lpr_|LPR_|fault__o|_ml\b|_ml,|__l_", s):
            keep.append(ln)
        elif s.startswith("assign lrx") or s.startswith("assign st"):
            keep.append(ln)
        i += 1
    b = "\n".join(keep)
    b = re.sub(r"\((ck_S|ck_K|ck_ML)\)", "(clk)", b)
    b = re.sub(r"\(lpr_c_u_\w+\)", "(rst_n)", b)
    b = re.sub(r"\b(\w+)__l_[SK]\b", r"\1", b)
    b = re.sub(r"\b(mwv|mwd|mrv|mrd|mf|mu_rc)_ml\b", r"\1", b)
    b = b.replace("(fault__o)", "(fault)")
    b = re.sub(r"\s*//[^\n]*", "", b)
    assert not re.search(r"lpl_|lpr_|ck_S\b|ck_K\b|ck_ML\b|__o\b|MUT", b), (f, re.findall(r"lpl_\w+|lpr_\w+|ck_[SKM]L?\b|MUT", b)[:5])
    top = f"ot_s81sl_slice_{f}_x"
    o = ["`timescale 1ns/1ps",
         f"// GENERATED by tools/s81_slice/mk_mu72_xtop.py from mu72/ot_s81sl_slice_{f}_72.sv (S81-SLICE/ENDP 10-21): WIRES-ONLY flat",
         "// parent (no landings / reset runs / out_regs) for tools/landed_parent/lp.py -> landed regions S (u_sl) / K (u_lep + lanes,",
         "// abutting) / ML (u_land).  u_sl keeps its 10 real roots: ck_C = clk (region S), ck_L0..ck_CAP_RS straight parent inputs.",
         f"module {top} (" + ports.rstrip() + "\n);", b, "endmodule", ""]
    out = SRC / "lr" / f"{top}.sv"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(o))
    return out


if __name__ == "__main__":
    for f in sys.argv[1:] or FLAVORS:
        print(xtop(f).relative_to(ROOT))
