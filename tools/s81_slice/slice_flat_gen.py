#!/usr/bin/env python3
"""PL-SLICE (PARENTS-LANDED sub-lane, 10-18): write the WIRES-ONLY flat slice parent for tools/landed_parent/lp.py.

ot_s81sl_slice (rtl/dsrom_sys/s81_dv/slice/ot_s81sl_slice.sv) has generate loops (5 leaves, 4 x chains, the HB variant)
and two always blocks (x-chain epoch marker mkq, the slice fault register).  lp.py needs plain named instances, so this
writes ot_s81sl_slice_c1x (HB = 0, xr1) and ot_s81sl_slice_c3x (HB = 1, xr3), same ports as ot_s81sl_slice, with:
  * the 5 leaves and every relay as explicit instances; ONE bundle net per leaf and direction
      dn_x<k> (centre side, 594 b) -> u_dn<k> (D = DLK<k>) -> dn_l<k> -> leaf k
      leaf k -> up_l<k> (668 b = the 667-b up word + the leaf fault) -> u_up<k> (D = DLK<k>) -> up_x<k>
    so a region seam lands one bundle per leaf and direction (not the 5-leaf buses);
  * the leaf fault taken from up_l<k> through u_ft<k> (D = DLF<k>; 0 = the original direct OR);
  * the glue flops moved into children (ot_s81sl_slice_glue.sv): ot_s81sl_ckf (forwarded clock branches),
    ot_s81sl_mk (x-chain epoch marker = the original mkq), ot_s81sl_sflt (registered slice fault OR).
With DLK<k> = DL and DLF<k> = 0 the module is the original slice cycle for cycle (tb_s81sl_slice_x checks it).
The landed build (lp spec) uses DLK<k> = DL - (E + 1) on the landed leaves: the landing's E + 1 edges replace relay stages,
so the landed slice keeps the original leaf <-> centre latency DL (the compiler sees no change there); DLF<k> = 0 makes the
leaf fault visible E + 1 edges later (the only latency change; checked at phase end, like the cap_rt fault copy flop).

  python3 tools/s81_slice/slice_flat_gen.py     (writes rtl/dsrom_sys/s81_dv/slice/ot_s81sl_slice_c{1,3}x.sv)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "rtl/dsrom_sys/s81_dv/slice"

DN = [("c_v", 1), ("c_d", 160), ("sw_v", 1), ("sw_a", 10), ("sw_m", 8), ("sw_d", 256), ("cw_v", 2), ("cw_a", 24),
      ("cw_d", 64), ("rb_v", 1), ("rb_d", 32), ("g_v", 1), ("g_c", 2), ("g_d", 32)]
UP = [("lo_v", 1), ("lo_d", 256), ("p_v", 1), ("p_d", 32), ("xf_v", 1), ("xf_s", 1), ("xf", 276), ("e_v", 1),
      ("e_c", 2), ("e_d", 96), ("fault", 1)]
# centre-side bus per field: (bus net, slice of leaf k) -- None = one shared copy (XR3: c_d / rb_* / g_* single copies)
DN_X = {"c_v": "c_v_x", "c_d": None, "sw_v": "sw_v_x", "sw_a": "sw_a_x", "sw_m": "sw_m_x", "sw_d": "sw_d_x",
        "cw_v": "cw_v_x", "cw_a": "cw_a_x", "cw_d": "cw_d_x", "rb_v": None, "rb_d": None, "g_v": None, "g_c": None,
        "g_d": None}
SHARED = {"c_d": "c_d_x", "rb_v": "rb_v_x", "rb_d": "rb_d_x", "g_v": "gv_x", "g_c": "gc_x", "g_d": "gd_x"}
UP_X = {"lo_v": "lo_v_x", "lo_d": "lo_d_x", "p_v": "p_v_x", "p_d": "p_d_x", "xf_v": "xfv_x", "xf_s": "xfs_x",
        "xf": "xf_x", "e_v": "ev_x", "e_c": "ec_x", "e_d": "ed_x"}
WDN = sum(w for _, w in DN)
WUP = sum(w for _, w in UP)


def fields(lst):
    """field -> (lo, hi) inside the bundle, first field at the MSB end (as the original {a, b, ...} concatenation)"""
    pos, out = sum(w for _, w in lst), {}
    for n, w in lst:
        pos -= w
        out[n] = (pos, pos + w - 1)
    return out


def sel(n, lo, hi):
    return f"{n}[{hi}:{lo}]" if hi > lo else f"{n}[{lo}]"


def gen(hb: int) -> str:
    top = f"ot_s81sl_slice_c{3 if hb else 1}x"
    fd, fu = fields(DN), fields(UP)
    L = []
    w = L.append
    w("`timescale 1ns/1ps")
    w(f"// GENERATED by tools/slice_flat_gen.py (PL-SLICE 10-18) -- do not edit.  {top} = ot_s81sl_slice #(.HB({hb})) as a")
    w("// WIRES-ONLY flat parent (explicit leaves / relays / glue children, one bundle net per leaf and direction) for")
    w("// tools/landed_parent/lp.py.  DLK<k> = DL and DLF<k> = 0: cycle-identical to ot_s81sl_slice (tb_s81sl_slice_x).")
    w(f"module {top} #(")
    w("    parameter integer DLK0 = 4, parameter integer DLK1 = 4, parameter integer DLK2 = 4, parameter integer DLK3 = 4,")
    w("    parameter integer DLK4 = 4,")
    w("    parameter integer DLF0 = 0, parameter integer DLF1 = 0, parameter integer DLF2 = 0, parameter integer DLF3 = 0,")
    w("    parameter integer DLF4 = 0,")
    w("    parameter integer DR = 6, parameter integer DX = 6, parameter integer VQ_XMEM = 2, parameter integer VS_MUT = 0")
    w(") (")
    w("    input  wire            clk,")
    w("    input  wire            rst_n,")
    w("    input  wire [3:0]      sid,")
    w("    input  wire [1103:0]   ri_w, input wire [1103:0] ri_e, output wire [1103:0] ro_e, output wire [1103:0] ro_w,")
    w("    input  wire [275:0]    vi,   output wire [275:0] vo,")
    w("    input  wire [1103:0]   bi,   output wire [512:0] bo,")
    w("    output wire [4415:0]   xc,")
    w("    input  wire [559:0]    rt,")
    w("    output wire [15:0]     ck_line,")
    w("    output wire [1:0]      ck_v,")
    w("    output wire [15:0]     ck_xc,")
    w("    output wire [7:0]      ck_rt,")
    w("    output wire            fault")
    w(");")
    w("    wire [4:0] c_v_x, sw_v_x, lo_v_x, p_v_x; wire [159:0] c_d_x; wire rb_v_x; wire [31:0] rb_d_x;")
    w("    wire gv_x; wire [1:0] gc_x; wire [31:0] gd_x;")
    w("    wire [49:0] sw_a_x; wire [39:0] sw_m_x; wire [1279:0] sw_d_x, lo_d_x; wire [159:0] p_d_x;")
    w("    wire [9:0] cw_v_x; wire [119:0] cw_a_x; wire [319:0] cw_d_x;")
    w("    wire [4:0] xfv_x, xfs_x; wire [1379:0] xf_x; wire [4:0] ev_x; wire [9:0] ec_x; wire [479:0] ed_x;")
    for k in range(5):
        w(f"    wire [{WDN - 1}:0] dn_x{k}, dn_l{k};  wire [{WUP - 1}:0] up_l{k};  wire [{WUP - 2}:0] up_x{k};  wire f_l{k};")
    # centre-side bundle assembly / disassembly (pure wiring)
    for k in range(5):
        parts = []
        for n, wd in DN:
            if DN_X[n] is None:
                parts.append(SHARED[n])
            else:
                parts.append(f"{DN_X[n]}[{wd * k + wd - 1}:{wd * k}]" if wd > 1 else f"{DN_X[n]}[{k}]")
        w(f"    assign dn_x{k} = {{{', '.join(parts)}}};")
    for n, wd in UP:
        if n == "fault":
            continue
        lo, hi = fu[n]
        lo, hi = lo - 1, hi - 1            # up_x drops the fault bit (bundle LSB)
        w(f"    assign {UP_X[n]} = {{{', '.join(sel(f'up_x{k}', lo, hi) for k in reversed(range(5)))}}};")
    # leaves
    for k in range(5):
        cs = ["clk(clk)", "rst_n(rst_n)", "sid(sid)", f"k(3'd{k})"]
        for n, _ in DN:
            lo, hi = fd[n]
            cs.append(f"{n}({sel(f'dn_l{k}', lo, hi)})")
        for n, _ in UP:
            lo, hi = fu[n]
            cs.append(f"{n}({sel(f'up_l{k}', lo, hi)})")
        w(f"    ot_s81sl_leaf #(.AQ_XMEM(VQ_XMEM), .VS_MUT(VS_MUT)) u_lf{k} (" + ", ".join("." + c for c in cs) + ");")
        w(f"    ot_s81sl_rly #(.W({WDN}), .D(DLK{k})) u_dn{k} (.clk(clk), .d(dn_x{k}), .q(dn_l{k}));")
        w(f"    ot_s81sl_rly #(.W({WUP - 1}), .D(DLK{k})) u_up{k} (.clk(clk), .d(up_l{k}[{WUP - 1}:1]), .q(up_x{k}));")
        w(f"    ot_s81sl_rly #(.W(1), .D(DLF{k})) u_ft{k} (.clk(clk), .d(up_l{k}[0]), .q(f_l{k}));")
    # centre
    w("    wire dl_ev, dl_wv, dl_vv, is_v, cfg_v, x_go, x_sv, x_rbv, f_xg, f_xr, f_cap, f_xf;")
    w("    wire [1103:0] dl_e, dl_w, ci_b; wire [275:0] dl_vb; wire [2:0] ci_dir; wire [159:0] is_d, cfg_d;")
    w("    wire [31:0] x_eps, x_s, x_rbd, x_scale; wire x_mode;")
    w("    wire xe_v, eg_v, f_eg; wire [1:0] xe_c, eg_c; wire [31:0] xe_hh, xe_kk, xe_dd, eg_d; wire [7:0] x_si;")
    w("    wire [172:0] nx_wi, nx_ei, nx_eo, nx_wo; wire [1100:0] xw_d;")
    w("    ot_s81sl_xg u_xg (.clk(clk), .rst_n(rst_n), .sid(sid), .ri_w(ri_w), .ri_e(ri_e), .ro_e(ro_e), .ro_w(ro_w),")
    w("        .vi(vi), .vo(vo), .xf_v(xfv_x), .xf_s(xfs_x), .xf(xf_x), .nx_wi(nx_wi), .nx_ei(nx_ei), .nx_eo(nx_eo), .nx_wo(nx_wo),")
    w("        .dl_ev(dl_ev), .dl_e(dl_e), .dl_wv(dl_wv), .dl_w(dl_w), .dl_vv(dl_vv), .dl_vb(dl_vb), .ci_dir(ci_dir), .ci_b(ci_b),")
    w("        .is_v(is_v), .is_d(is_d), .xw_d(xw_d), .fault(f_xg));")
    band = ".bi(bi), .bo(bo), " if hb else ""
    w(f"    ot_s81sl_xr{3 if hb else 1} u_xr (.clk(clk), .rst_n(rst_n), .sid(sid), .dl_ev(dl_ev), .dl_e(dl_e), .dl_wv(dl_wv), .dl_w(dl_w),")
    w(f"        .dl_vv(dl_vv), .dl_vb(dl_vb), .ci_dir(ci_dir), .ci_b(ci_b), {band}")
    w("        .c_v(c_v_x), .c_d(c_d_x), .sw_v(sw_v_x), .sw_a(sw_a_x), .sw_m(sw_m_x), .sw_d(sw_d_x), .lo_v(lo_v_x), .lo_d(lo_d_x),")
    w("        .p_v(p_v_x), .p_d(p_d_x), .rb_v(rb_v_x), .rb_d(rb_d_x),")
    w("        .e_v(ev_x), .e_c(ec_x), .e_d(ed_x), .eg_v(eg_v), .eg_c(eg_c), .eg_d(eg_d), .g_v(gv_x), .g_c(gc_x), .g_d(gd_x),")
    w("        .x_go(x_go), .x_mode(x_mode), .x_eps(x_eps), .x_scale(x_scale), .x_sv(x_sv), .x_si(x_si),")
    w("        .x_s(x_s), .x_rbv(x_rbv), .x_rbd(x_rbd), .is_v(is_v), .is_d(is_d), .cfg_v(cfg_v), .cfg_d(cfg_d), .fault(f_xr));")
    if not hb:
        w("    assign bo = 513'd0;      // C1 has no band port")
    w("    ot_s81dv_xfin u_xf (.clk(clk), .rst_n(rst_n), .go(x_go), .mode(x_mode), .sid(sid), .eps(x_eps), .s_v(x_sv),")
    w("        .s_i(x_si), .s(x_s),")
    w("        .wi_v(nx_wi[172]), .wi_h(nx_wi[171:168]), .wi_b(nx_wi[167:160]), .wi_d(nx_wi[159:0]),")
    w("        .ei_v(nx_ei[172]), .ei_h(nx_ei[171:168]), .ei_b(nx_ei[167:160]), .ei_d(nx_ei[159:0]),")
    w("        .eo_v(nx_eo[172]), .eo_h(nx_eo[171:168]), .eo_b(nx_eo[167:160]), .eo_d(nx_eo[159:0]),")
    w("        .wo_v(nx_wo[172]), .wo_h(nx_wo[171:168]), .wo_b(nx_wo[167:160]), .wo_d(nx_wo[159:0]),")
    w("        .rb_v(x_rbv), .rb_d(x_rbd), .e_v(xe_v), .e_c(xe_c), .e_hh(xe_hh), .e_kk(xe_kk), .e_dd(xe_dd), .fault(f_xf));")
    w("    ot_s81sl_eg u_eg (.clk(clk), .rst_n(rst_n), .eps(x_eps), .scale(x_scale), .i_v(xe_v), .i_c(xe_c), .i_hh(xe_hh),")
    w("        .i_kk(xe_kk), .i_dd(xe_dd), .g_v(eg_v), .g_c(eg_c), .g(eg_d), .fault(f_eg));")
    w("    wire [559:0] rt_q;")
    w("    ot_s81sl_rly #(.W(560), .D(DR)) u_rt (.clk(clk), .d(rt), .q(rt_q));")
    w("    ot_s81sl_capc2 u_cap (.clk(clk), .rst_n(rst_n), .rt_w(rt_q[279:0]), .rt_e(rt_q[559:280]), .cfg_v(cfg_v), .cfg_d(cfg_d),")
    w("        .cw_s_v(cw_v_x[5:0]), .cw_s_a(cw_a_x[71:0]), .cw_s_d(cw_d_x[191:0]),")
    w("        .cw_n_v(cw_v_x[9:6]), .cw_n_a(cw_a_x[119:72]), .cw_n_d(cw_d_x[319:192]), .fault(f_cap));")
    w("    wire [1:0] mkq; wire [1103:0] xw4;")
    w("    ot_s81sl_mk u_mk (.clk(clk), .rst_n(rst_n), .mk(mkq));")
    w("    assign xw4 = {xw_d[1100:565], xw_d[0], mkq[1], xw_d[564:0], mkq[1]};")
    for c in range(4):
        w(f"    ot_s81sl_rly #(.W(1104), .D(DX)) u_x{c} (.clk(clk), .d(xw4), .q(xc[{1104 * c + 1103}:{1104 * c}]));")
    w("    ot_s81sl_ckf u_ckf (.clk(clk), .ck_line(ck_line), .ck_v(ck_v), .ck_xc(ck_xc), .ck_rt(ck_rt));")
    w("    ot_s81sl_sflt u_flt (.clk(clk), .f({f_l4, f_l3, f_l2, f_l1, f_l0, f_xg, f_xr, f_cap, f_xf, f_eg}), .q(fault));")
    w("endmodule")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    for hb in (0, 1):
        p = OUT / f"ot_s81sl_slice_c{3 if hb else 1}x.sv"
        p.write_text(gen(hb))
        print("wrote", p.relative_to(ROOT), f"(dn {WDN} b, up {WUP} b per leaf)")
