#!/usr/bin/env python3
"""S81-SLICE/PARENT 10-21: derive the HB=1 (C3) landed slice parent ot_s81sl_slice_c3x_k8_cap5r_lp from the C1 one, plus
parameter-free die-bind wrappers for both, plus the lp.py records (top renamed) for the kit SDC.

lp.py output for c1x vs c3x differs ONLY where the flat sources differ (ot_s81sl_slice_c1x.sv vs _c3x.sv, generated by
tools/slice_flat_gen.py from ot_s81sl_slice #(.HB)): u_xr master xr1 -> xr3 with .bi(bi), .bo(bo), and no 'assign bo = 0'
(compare landed/c1x vs landed/c3x on main).  The same three edits are applied to the CURRENT C1 parent
(c1x_k8_cap5r: CAPC5r + CAP reset forests + u_xg ot_s81sl_xgt_xo + u_xr ot_s81sl_xrt1) -> u_xr ot_s81sl_xrt3.
Landings, regions, reset forests, schedule: identical to the C1 parent (bi / bo are region-C ports of u_xr, unlanded,
exactly as in landed/c3x).  Cycle delta vs C1: none (xr3 band latency is the xr3 child's own, unchanged).
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
L = ROOT / "rtl/dsrom_sys/s81_dv/slice/landed"
REC = ROOT / "results/rtl/drive_s81_slicep_1020"
PARAMS = "#(.DLK0(1), .DLK1(1), .DLK2(4), .DLK3(1), .DLK4(1), .DLF0(0), .DLF1(0), .DLF2(0), .DLF3(0), .DLF4(0))"


def c3x():
    src = (L / "c1x_k8_cap5r/ot_s81sl_slice_c1x_k8_cap5r_lp.sv").read_text()
    t = src.replace("module ot_s81sl_slice_c1x_k8_cap5r_lp #(", "module ot_s81sl_slice_c3x_k8_cap5r_lp #(", 1)
    n0 = t.count("    assign bo = 513'd0;\n")
    assert n0 == 1, n0
    t = t.replace("    assign bo = 513'd0;\n", "", 1)
    pat = "    ot_s81sl_xrt1 u_xr (.clk(ck_C), .rst_n(lpr_c_u_xr), .sid(sid), .dl_ev(dl_ev), .dl_e(dl_e), .dl_wv(dl_wv), .dl_w(dl_w), .dl_vv(dl_vv), .dl_vb(dl_vb), .ci_dir(ci_dir), .ci_b(ci_b), "
    assert t.count(pat) == 1
    t = t.replace(pat, pat.replace("ot_s81sl_xrt1", "ot_s81sl_xrt3") + ".bi(bi), .bo(bo), ", 1)
    hdr = ("// S81-SLICE/PARENT 10-21: HB=1 (C3) successor = c1x_k8_cap5r_lp with u_xr ot_s81sl_xrt3 (.bi/.bo) and no bo tie --\n"
           "// the exact lp.py c1x->c3x difference (tools/s81_slice/pl_slice/mk_k8_cap5r_c3x.py).  Die masters s_3S (iq) / s_4S.\n")
    out = L / "c3x_k8_cap5r/ot_s81sl_slice_c3x_k8_cap5r_lp.sv"
    out.parent.mkdir(exist_ok=True)
    out.write_text(hdr + t)
    return out


def ports(text, mod):
    m = re.search(r"module\s+%s\s*#\(.*?\)\s*\((.*?)\);" % mod, text, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    names = []
    for item in body.split(","):
        toks = re.sub(r"\[[^\]]*\]", " ", item).split()
        if toks:
            names.append(toks[-1])
    return body, names


def wrapper(variant):
    lp = f"ot_s81sl_slice_{variant}_k8_cap5r_lp"
    text = (L / f"{variant}_k8_cap5r/{lp}.sv").read_text()
    body, names = ports(text, lp)
    body = "\n".join(l.rstrip() for l in body.strip("\n").splitlines())
    conn = ", ".join(f".{n}({n})" for n in names)
    w = f"""`timescale 1ns/1ps
// S81-SLICE/PARENT 10-21: PARAMETER-FREE die-bind wrapper of {lp} (the hardened kit top s81dv_slice_lp_k8*):
// the kit parameters (DLK 1/1/4/1/1, DLF 0, DR 6, DX 6, VQ_XMEM 2, VS_MUT 0, MUT 0) fixed here, so the die binds one
// name with no paramod renaming.  Region clocks stay separate inputs (C, L0, L1, L3, L4, CAP_RT/CW/CE/RN/RS): the die
// feeds each from its own regional root (landed-regions standard); never tie them together in a die.
module ot_s81sl_slice_{variant}_k8_cap5r_w (
{body}
);
    {lp} {PARAMS} u_lp ({conn});
endmodule
"""
    out = L / f"{variant}_k8_cap5r/ot_s81sl_slice_{variant}_k8_cap5r_w.sv"
    out.write_text(w)
    return out


def record(variant):
    r = json.loads((REC / "c1x_k8_cap5/ot_s81sl_slice_c1x_k8_cap5_lp_record.json").read_text())
    top = f"ot_s81sl_slice_{variant}_k8_cap5r_lp"
    r["top"] = top
    if variant == "c3x":
        r["flat"] = "ot_s81sl_slice_c3x"
    r["derived_by"] = {"tool": "tools/s81_slice/pl_slice/mk_k8_cap5r_c3x.py", "base_record_top": "ot_s81sl_slice_c1x_k8_cap5_lp",
                       "rtl": f"rtl/dsrom_sys/s81_dv/slice/landed/{variant}_k8_cap5r/{top}.sv",
                       "note": "cap5 record with the top renamed: cap5r keeps every landing / region / port (CAP resets become "
                               "fixed-depth forests from lpr_root, no new crossing); u_xg xgt_xo / u_xr xrt1|xrt3 same ports"}
    d = REC / f"{variant}_k8_cap5r"
    d.mkdir(exist_ok=True)
    p = d / f"{top}_record.json"
    p.write_text(json.dumps(r, indent=1) + "\n")
    return p


if __name__ == "__main__":
    print(c3x())
    for v in ("c1x", "c3x"):
        print(wrapper(v), record(v))
