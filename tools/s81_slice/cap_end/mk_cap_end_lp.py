#!/usr/bin/env python3
"""S81/PORTFIX-DEAD D-CAPEND (2026-10-25): row-end variants of the landed slice ot_s81sl_slice_c1x_k8_cap5r_lp.

The as-built die drives the slice's 8-lane capture input with the missing lanes tied 0 (die_asb.v: .rt({350'd0, 3 lanes}),
.rt({140'd0, 6 lanes})).  OWNER DECISION 8: dead ports dropped on both ends -> module VARIANTS (same instance paths as the
base, so floorplans / binder names are unchanged):
  ot_s81sl_slice_c1x_k8_cap5r_lp_e6  rt 420 b (6 frames), u_cap = ot_s81sl_capc5r_e6, the E landing 140 b
  ot_s81sl_slice_c1x_k8_cap5r_lp_w3  rt 210 b (3 frames), u_cap = ot_s81sl_capc5r_w3, the W landing 210 b, no E landing,
                                      no CAP CE region: no ck_CAP_CE port, no CE reset forest
The same transform applies to the HB=1 sibling ot_s81sl_slice_c3x_k8_cap5r_lp and to the thin die wrappers
ot_s81sl_slice_c{1,3}x_k8_cap5r_w (u_lp -> the lp variant, rt narrowed, no ck_CAP_CE at w3).  Those bases are not on main
(binder rtl_extra 6ff783251ab2 = origin/claude/s81-slicep-k8c-1021); their variants are generated from that commit's files
(--extra DIR = a checkout / rtl_extra root holding them) and committed here.  An lp base that still connects the dropped
xg output xw_v (PORTFIX-DEAD D-XWV) has that connection removed too.
Usage (repo root): mk_cap_end_lp.py [--check] [--extra DIR]   (--check: exit 1 when a committed variant differs)
"""
import re, sys
from pathlib import Path
D = Path("rtl/dsrom_sys/s81_dv/slice/landed/c1x_k8_cap5r")
BASE = D / "ot_s81sl_slice_c1x_k8_cap5r_lp.sv"
HDR = ("// S81/PORTFIX-DEAD D-CAPEND (10-25): GENERATED by tools/s81_slice/cap_end/mk_cap_end_lp.py from {base} -- do not edit.\n"
       "// Row-end variant {v}: {why}\n")


def rep(s, a, b, n=1):
    c = s.count(a)
    if c != n:
        raise SystemExit(f"mk_cap_end_lp: expected {n} x {a[:90]!r}, found {c}")
    return s.replace(a, b)


def variant(src, v, top="ot_s81sl_slice_c1x_k8_cap5r_lp", base=BASE):
    s = src
    s = rep(s, f"module {top} #(", f"module {top}_{v} #(")
    if ".xw_v(xw_v), " in s:                                   # D-XWV: the xg masters have no xw_v output
        s = rep(s, ".xw_v(xw_v), ", "")
        s = rep(s, ", f_xf, xw_v;", ", f_xf;")
    if v == "e6":
        why = "6 frames: rt 420 b (lanes 0..5), u_cap = ot_s81sl_capc5r_e6 (rt_e 140 b, u_te = cap_tr2)."
        s = rep(s, "    input wire [559:0] rt,", "    input wire [419:0] rt,")
        s = rep(s, "    wire [559:0] rt_q;", "    wire [419:0] rt_q;")
        s = rep(s, "ot_s81sl_rly #(.W(560), .D(DR)) u_rt", "ot_s81sl_rly #(.W(420), .D(DR)) u_rt")
        s = rep(s, "    wire [279:0] cap5_w_in, cap5_e_in;", "    wire [279:0] cap5_w_in; wire [139:0] cap5_e_in;")
        s = rep(s, "    ot_s81sl_capc5r u_cap (", "    ot_s81sl_capc5r_e6 u_cap (")
        s = rep(s, "    wire [4*280-1:0] cap5_east_in_bank;", "    wire [4*140-1:0] cap5_east_in_bank;")
        s = rep(s, "    wire [4*((280+23)/24)-1:0] cap5_east_in_vld;", "    wire [4*((140+23)/24)-1:0] cap5_east_in_vld;")
        s = rep(s, "ot_pl_land_n32_chunk_w #(.W(280), .D(4), .CHUNK_BITS(24)) u_lpl_cap5_east_in_w",
                "ot_pl_land_n32_chunk_w #(.W(140), .D(4), .CHUNK_BITS(24)) u_lpl_cap5_east_in_w")
        s = rep(s, ".i(rt_q[559:280]), .bank(cap5_east_in_bank)", ".i(rt_q[419:280]), .bank(cap5_east_in_bank)")
        s = rep(s, "ot_pl_land_chunk_r #(.W(280), .D(4), .K(2), .CHUNK_BITS(24)) u_lpl_cap5_east_in_r",
                "ot_pl_land_chunk_r #(.W(140), .D(4), .K(2), .CHUNK_BITS(24)) u_lpl_cap5_east_in_r")
    else:
        why = "3 frames: rt 210 b (lanes 0..2), u_cap = ot_s81sl_capc5r_w3 (no E column, no W lane 3), no CAP CE region."
        s = rep(s, "    input wire [559:0] rt,", "    input wire [209:0] rt,")
        s = rep(s, "    wire [559:0] rt_q;", "    wire [209:0] rt_q;")
        s = rep(s, "ot_s81sl_rly #(.W(560), .D(DR)) u_rt", "ot_s81sl_rly #(.W(210), .D(DR)) u_rt")
        s = rep(s, "    input wire ck_CAP_RT, ck_CAP_CW, ck_CAP_CE, ck_CAP_RN, ck_CAP_RS,",
                "    input wire ck_CAP_RT, ck_CAP_CW, ck_CAP_RN, ck_CAP_RS,")
        s = rep(s, "    wire [279:0] cap5_w_in, cap5_e_in;", "    wire [209:0] cap5_w_in;")
        s = rep(s, "cap5_rst_CW, cap5_rst_CE, cap5_rst_RT", "cap5_rst_CW, cap5_rst_RT")
        a = s.index("    wire [1:0] lpr_CAPCE_leaves;")
        b = s.index("    assign cap5_rst_CE = lpr_CAPCE_leaves[1];\n") + len("    assign cap5_rst_CE = lpr_CAPCE_leaves[1];\n")
        s = s[:a] + s[b:]
        s = rep(s, "    ot_s81sl_capc5r u_cap (", "    ot_s81sl_capc5r_w3 u_cap (")
        s = rep(s, ".ck_ce(ck_CAP_CE), ", "")
        s = rep(s, ".rst_n_ce(lpr_CAPCE_leaves[0]), ", "")
        s = rep(s, ".rt_w(cap5_w_in), .rt_e(cap5_e_in),", ".rt_w(cap5_w_in),")
        s = rep(s, "    wire [4*280-1:0] cap5_west_in_bank;", "    wire [4*210-1:0] cap5_west_in_bank;")
        s = rep(s, "    wire [4*((280+23)/24)-1:0] cap5_west_in_vld;", "    wire [4*((210+23)/24)-1:0] cap5_west_in_vld;")
        s = rep(s, "ot_pl_land_n32_chunk_w #(.W(280), .D(4), .CHUNK_BITS(24)) u_lpl_cap5_west_in_w",
                "ot_pl_land_n32_chunk_w #(.W(210), .D(4), .CHUNK_BITS(24)) u_lpl_cap5_west_in_w")
        s = rep(s, ".i(rt_q[279:0]), .bank(cap5_west_in_bank)", ".i(rt_q[209:0]), .bank(cap5_west_in_bank)")
        s = rep(s, "ot_pl_land_chunk_r #(.W(280), .D(4), .K(2), .CHUNK_BITS(24)) u_lpl_cap5_west_in_r",
                "ot_pl_land_chunk_r #(.W(210), .D(4), .K(2), .CHUNK_BITS(24)) u_lpl_cap5_west_in_r")
        a = s.index("    wire [4*280-1:0] cap5_east_in_bank;")
        b = s.index(".o(cap5_e_in));\n") + len(".o(cap5_e_in));\n")
        s = s[:a] + s[b:]
        left = [l for l in s.split("\n") if re.search(r"\b(ck_CAP_CE|cap5_e_in|cap5_rst_CE|lpr_CAPCE_leaves|rt_q\[559)", l.split("//")[0])]
        if left:
            raise SystemExit("mk_cap_end_lp: w3 still references the E column:\n" + "\n".join(left))
    return HDR.format(base=base, v=v, why=why) + s


def wrapper(src, v, top, base):
    s = rep(src, f"module {top} (", f"module {top}_{v} (")
    lp = top[:-2] + "_lp"
    s = rep(s, f"    {lp} #(", f"    {lp}_{v} #(")
    n = {"e6": 420, "w3": 210}[v]
    s = rep(s, "    input wire [559:0] rt,", f"    input wire [{n - 1}:0] rt,")
    why = f"{n // 70} frames: rt {n} b, u_lp = {lp}_{v}" + (" (no ck_CAP_CE)." if v == "w3" else ".")
    if v == "w3":
        s = rep(s, "    input wire ck_CAP_RT, ck_CAP_CW, ck_CAP_CE, ck_CAP_RN, ck_CAP_RS,",
                "    input wire ck_CAP_RT, ck_CAP_CW, ck_CAP_RN, ck_CAP_RS,")
        s = rep(s, ".ck_CAP_CE(ck_CAP_CE), ", "")
    return HDR.format(base=base, v=v, why=why) + s


EXTRA = [  # (kind, top, path relative to the --extra root, variants the die uses)
    ("lp", "ot_s81sl_slice_c3x_k8_cap5r_lp", "rtl/dsrom_sys/s81_dv/slice/landed/c3x_k8_cap5r/ot_s81sl_slice_c3x_k8_cap5r_lp.sv", ("w3",)),
    ("w", "ot_s81sl_slice_c3x_k8_cap5r_w", "rtl/dsrom_sys/s81_dv/slice/landed/c3x_k8_cap5r/ot_s81sl_slice_c3x_k8_cap5r_w.sv", ("w3",)),
    ("w", "ot_s81sl_slice_c1x_k8_cap5r_w", "rtl/dsrom_sys/s81_dv/slice/landed/c1x_k8_cap5r/ot_s81sl_slice_c1x_k8_cap5r_w.sv", ("e6", "w3")),
]


def emit(out, txt, bad):
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != txt:
            print(f"STALE {out}"); return 1
        return bad
    out.parent.mkdir(parents=True, exist_ok=True); out.write_text(txt); print(f"wrote {out}")
    return bad


def main():
    src = BASE.read_text()
    bad = 0
    for v in ("e6", "w3"):
        bad = emit(D / f"ot_s81sl_slice_c1x_k8_cap5r_lp_{v}.sv", variant(src, v), bad)
    if "--extra" in sys.argv:
        root = Path(sys.argv[sys.argv.index("--extra") + 1])
        for kind, top, rel, vs in EXTRA:
            b = root / rel
            for v in vs:
                txt = variant(b.read_text(), v, top, f"{rel} @6ff783251ab2") if kind == "lp" else wrapper(b.read_text(), v, top, f"{rel} @6ff783251ab2")
                bad = emit(Path(rel).parent / f"{top}_{v}.sv", txt, bad)
    sys.exit(bad)


if __name__ == "__main__":
    main()
