#!/usr/bin/env python3
"""S81/PORTFIX-DEAD D-CAPEND (2026-10-25): 3-frame variants of the ot_s81sl_slice family (capture root capc2).

Die s_3N (ot_s81sl_slice_sukv_raw512 -> ot_s81sl_slice) and s_3S (ot_s81sl_slice_iq -> ot_s81sl_slice) are 3-frame row-end
slices: the as-built die drives .rt({350'd0, 3 lanes}).  Variants (same instance paths as the bases):
  ot_s81sl_slice_w3            rt 210 b, u_rt relay 210 b, u_cap = ot_s81sl_capc2_w3       (from ot_s81sl_slice.sv)
  ot_s81sl_slice_iq_w3         rt 210 b, u_sl = ot_s81sl_slice_w3                          (from dsdv_idx_bsplit.sv)
  ot_s81sl_slice_sukv_raw512_w3 rt 210 b, u_slice = ot_s81sl_slice_w3   (from binder rtl_extra 07abeb43f, --extra DIR)
Usage (repo root): mk_cap_end_slice.py [--check] [--extra DIR]
"""
import sys
from pathlib import Path
SL = Path("rtl/dsrom_sys/s81_dv/slice")
OUT = SL / "cap_end" / "ot_s81sl_slice_w3.sv"
HDR = ("// S81/PORTFIX-DEAD D-CAPEND (10-25): GENERATED by tools/s81_slice/cap_end/mk_cap_end_slice.py -- do not edit.\n"
       "// 3-frame row-end variants (rt 210 b, capture root ot_s81sl_capc2_w3); bases named per module below.\n")


def rep(s, a, b, n=1):
    if s.count(a) != n:
        raise SystemExit(f"mk_cap_end_slice: expected {n} x {a[:90]!r}, found {s.count(a)}")
    return s.replace(a, b)


def module(text, name):
    i = text.index(f"module {name} ")
    j = text.index("endmodule", i) + len("endmodule")
    return text[i:j]


def slice_w3(src):
    m = module(src, "ot_s81sl_slice")
    m = rep(m, "module ot_s81sl_slice ", "module ot_s81sl_slice_w3 ")
    m = rep(m, "    input  wire [8*70-1:0] rt,", "    input  wire [3*70-1:0] rt,     // PORTFIX-DEAD D-CAPEND: lanes 0..2 (3 frames)")
    m = rep(m, "    wire [8*70-1:0] rt_q;", "    wire [3*70-1:0] rt_q;")
    m = rep(m, "ot_s81sl_rly #(.W(8 * 70), .D(DR)) u_rt", "ot_s81sl_rly #(.W(3 * 70), .D(DR)) u_rt")
    m = rep(m, "    ot_s81sl_capc2 u_cap (.clk(clk), .rst_n(rst_n), .rt_w(rt_q[279:0]), .rt_e(rt_q[559:280]),",
            "    ot_s81sl_capc2_w3 u_cap (.clk(clk), .rst_n(rst_n), .rt_w(rt_q),")
    return "// base: rtl/dsrom_sys/s81_dv/slice/ot_s81sl_slice.sv module ot_s81sl_slice\n" + m


def iq_w3(src):
    m = module(src, "ot_s81sl_slice_iq")
    m = rep(m, "module ot_s81sl_slice_iq ", "module ot_s81sl_slice_iq_w3 ")
    m = rep(m, "    input  wire [8*70-1:0] rt,", "    input  wire [3*70-1:0] rt,")
    m = rep(m, "    ot_s81sl_slice #(", "    ot_s81sl_slice_w3 #(")
    return "// base: rtl/dsrom_sys/s81_dv/idx/dsdv_idx_bsplit.sv module ot_s81sl_slice_iq\n" + m


def sukv_w3(src):
    m = module(src, "ot_s81sl_slice_sukv_raw512")
    m = rep(m, "module ot_s81sl_slice_sukv_raw512 ", "module ot_s81sl_slice_sukv_raw512_w3 ")
    m = rep(m, "    input  wire [8*70-1:0] rt,", "    input  wire [3*70-1:0] rt,")
    m = rep(m, "    ot_s81sl_slice #(", "    ot_s81sl_slice_w3 #(")
    return "// base: rtl/dsrom_sys/s81_dv/slice/ot_s81sl_slice_sukv_raw512.sv @07abeb43f (binder rtl_extra)\n" + m


def main():
    parts = [slice_w3((SL / "ot_s81sl_slice.sv").read_text()),
             iq_w3(Path("rtl/dsrom_sys/s81_dv/idx/dsdv_idx_bsplit.sv").read_text())]
    if "--extra" in sys.argv:
        root = Path(sys.argv[sys.argv.index("--extra") + 1])
        parts.append(sukv_w3((root / "rtl/dsrom_sys/s81_dv/slice/ot_s81sl_slice_sukv_raw512.sv").read_text()))
    txt = "`timescale 1ns/1ps\n" + HDR + "\n\n".join(parts) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print("OK" if ok else f"STALE {OUT}"); sys.exit(0 if ok else 1)
    OUT.write_text(txt); print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
