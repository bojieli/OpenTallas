#!/usr/bin/env python3
"""Locked pin plan for the landscape D8 elastic station (410.4 x 138.24 um, M5 cap).

f_in[i] (S face) and f_out[i] (N face) share one M5 track, so the corresponding-bit X displacement
between chained stations is 0 um by construction (budget <= 5.28 um for a 494.72 um face gap under
the 500 um reach). Bits are ordered monotonically so each 16-bit subslice has contiguous pins.
Pins use every second M5 track (0.096 um) at most and skip the M5 PG stripe windows.
"""
import json, sys
W, H, CORE = 410.4, 138.24, 2.16
PITCH, OFF = 0.048, 0.012
PG_PITCH, PG_OFF, PG_W, PG_SP = 5.4, 0.300, 0.12, 0.072
GUARD = 0.12
def pg_blocked(x):
    for org in (0.0, CORE):          # guard both stripe-origin conventions
        r = (x - org) % PG_PITCH
        if PG_OFF - PG_W/2 - GUARD <= r <= PG_OFF + PG_W + PG_SP + PG_W/2 + GUARD: return True
    return False
slots = []
n = 0
while True:
    x = round(OFF + PITCH*2*n, 3); n += 1
    if x > W - 3.0: break
    if x < 3.0 or pg_blocked(x): continue
    slots.append(x)
order = []                                 # S-face signal order, left to right
for c in range(9):
    lo, w = c*276, (15 if c == 8 else 276)
    bits = [f"f_in[{b}]" for b in range(lo, lo+w)]
    bits.insert(len(bits)//2, f"data_clk[{c}]")
    order += bits
mid = len(order)//2
order[mid:mid] = ["clk", "f_in[2223]", "cr_out[0]", "cr_out[1]"]   # valid + credits sit with the control root
assert len(order) <= len(slots), (len(order), len(slots))
lines = ["# generated by physical/hbm_ring_transport_1013/gen_station_pins.py -- do not edit",
         "# f_in[i] (S) and f_out[i] (N) share one M5 track: matching-bit X displacement 0 um."]
pinmap = {}
def pin(name, layer, x, y, size):
    lines.append(f"place_pin -pin_name {{{name}}} -layer {layer} -location {{{x:.3f} {y:g}}} -pin_size {{{size}}} -force_to_die_boundary")
    pinmap[name] = [layer, x, y]
for k, name in enumerate(order):
    x = slots[(k*len(slots))//len(order)]
    pin(name, "M5", x, 0.0, "0.024 0.192")
    if name.startswith("f_in["): pin(name.replace("f_in", "f_out"), "M5", x, H, "0.024 0.192")
    elif name.startswith("cr_out["): pin(name.replace("cr_out", "cr_in"), "M5", x, H, "0.024 0.192")
ymid = round(0.012 + 0.048*round((H/2 - 0.012)/0.048), 3)
pin("rst_n", "M4", 0.0, ymid, "0.192 0.024")
xs = [pinmap[f"f_in[{b}]"][1] for b in range(2223)]
assert xs == sorted(xs) and len(set(xs)) == 2223 and "f_out[2223]" in pinmap
summary = {"schema": "opentallas.hbm.ring_station_pin_lock.v1", "outline_um": [W, H], "pins": len(pinmap),
           "legal_slots": len(slots), "min_pin_pitch_um": round(min(b-a for a, b in zip(xs, xs[1:])), 3),
           "f_span_um": [xs[0], xs[-1]],
           "matching_bit_dx_um_max": max(abs(pinmap[f"f_in[{b}]"][1]-pinmap[f"f_out[{b}]"][1]) for b in range(2224)),
           "matching_bit_dx_budget_um": 5.28, "face_gap_um": 494.72, "pinmap": pinmap}
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
open(sys.argv[2], "w").write(json.dumps(summary, indent=1) + "\n")
print({k: v for k, v in summary.items() if k != "pinmap"})
