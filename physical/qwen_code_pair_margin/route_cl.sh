#!/bin/bash
# CODE-pair margin route for the closure loop (MARGIN2 variant given by M2, default 2). IO from the MEASURED insertion
# (CK_SS_MEAN / CK_FF_MEAN; defaults = the previous route's 726 / 394 ps): route (corner-neutral): in max = ss+120+150,
# in min = ss+50, out max = 120-(ss-150), out min = (ss-ff)-60; sign-off (833.333, per corner): in min = ff-50, out min = -(ff+50).
# usage: OUT=<dir> SRC=<src root> route_cl.sh <label> [extra args]
set -o pipefail
L=${1:?label}; shift; S=${SRC:-.}; O=${OUT:?out}/$L; mkdir -p $O $O/tmp; cd $S
SS=${CK_SS_MEAN:-726}; FF=${CK_FF_MEAN:-394}; M2=${M2:-2}; HM=${HM:-0.035}
r(){ python3 -c "print(round(($1)/1000.0,4))"; }
IMAX=$(r "$SS+270"); IMIN=$(r "$SS+50"); OMAX=$(r "120-($SS-150)"); OMIN=$(r "($SS-$FF)-60")
export OT_SYNTH_TIMEOUT_SECONDS=unlimited OT_FLOW_TIMEOUT_SECONDS=unlimited TMPDIR=$O/tmp
export OT_ORFS_NUM_CORES=${CORES:-16}
export OPENTALLAS_ORFS_IMAGE=${OPENTALLAS_ORFS_IMAGE:-sha256:16470cea1d346bfa245e402108995a4f04a1e54fe7c7bb7441774d7f6a2ece29}
P=physical/qwen_code_pair_margin
SIGN=$P/signoff_cl_$L.sdc
cat > $S/$SIGN <<SDC
# generated by route_cl.sh: sign-off at 833.333 ps with the IO at the measured insertion (SS $SS / FF $FF ps)
create_clock -name core_clk -period 833.333 [get_ports clk]
set_clock_uncertainty -setup 60 [get_clocks core_clk]
set_clock_uncertainty -hold 25 [get_clocks core_clk]
set_propagated_clock [get_clocks core_clk]
set code_inputs {}
foreach p [all_inputs] {if {[get_full_name \$p] ni {clk por_n}} {lappend code_inputs \$p}}
set_input_delay -clock core_clk -max $(python3 -c "print(round($SS+270))") \$code_inputs
set_input_delay -clock core_clk -min $(python3 -c "print(round($FF-50))") \$code_inputs
set_output_delay -clock core_clk -max $(python3 -c "print(round(120-($SS-150)))") [all_outputs]
set_output_delay -clock core_clk -min $(python3 -c "print(round(-($FF+50)))") [all_outputs]
set_false_path -from [get_ports por_n]
SDC
echo "$(date -Is) START $(hostname) io $IMIN $IMAX $OMIN $OMAX M2=$M2" >> $O/MANIFEST
python3 tools/run_abi3_physical.py --view asap7 --top ot_qwen_hbm_code_pair_margin --param ENABLE=1 --param COLUMN_BASE=0 --param ROWS=4496 --param MARGIN2=$M2 \
  --source rtl/gpu/w6/ot_gpu_w6_secded_pkg.sv --source rtl/model_ready_hbm_r14/ot_hbm_r14_pkg.sv --source rtl/hbm_accel/qwen/payload/ot_qwen_hbm_code_pair_margin.sv \
  --clock-period-ns 0.730 --clock-uncertainty-ns 0.060 --clock-uncertainty-hold-ns 0.025 \
  --core-input-delay-min-ns $IMIN --core-input-delay-max-ns $IMAX --output-delay-min-ns $OMIN --output-delay-max-ns $OMAX \
  --false-path-from por_n --sdc-append $P/boundary_append.sdc \
  --orfs-corner WC --hold-corners WC,BC --stages pnr --hold-margin-ns $HM --max-fanout 32 \
  --die-area 0 0 864 673.92 --core-area 8.64 8.64 855.36 665.28 --place-density 0.55 \
  --macro-view ot_sram_1r1w_1024x256_m2_r2c2=physical/asap7_memory_macros/ot_sram_1r1w_1024x256_m2_r2c2 \
  --macro-view ot_sram_1r1w_128x256_m1_r2c2=physical/asap7_memory_macros/ot_sram_1r1w_128x256_m1_r2c2 \
  --macro-place-halo 2.16 2.16 --routing-layers M2 M9 \
  --orfs-var SYNTH_HDL_FRONTEND=slang --orfs-var SYNTH_HIERARCHICAL=1 --orfs-var SYNTH_MINIMUM_KEEP_SIZE=0 \
  --orfs-var MACRO_PLACEMENT_TCL=/src/$P/macros.tcl --orfs-var FOOTPRINT_TCL=/src/$P/pins.tcl \
  --orfs-var ADDER_MAP_FILE= --orfs-var GPL_ROUTABILITY_DRIVEN=0 --orfs-var MIN_CLK_ROUTING_LAYER=M4 --orfs-var MAX_CLK_ROUTING_LAYER=M9 \
  --synth-timeout-seconds unlimited --flow-timeout-seconds unlimited --purpose characterization --nickname-tag $L \
  --keep-workdir $O/work --output $O/physical.json --force "$@" > $O/run.log 2>&1
rc=$?; echo "rc=$rc" > $O/exit
if [ $rc -eq 0 ] && [[ " $* " != *"--pnr-stop-after"* ]]; then
  python3 tools/w18/corner_sta.py --orfs-dir $O/work/orfs --macro physical/asap7_memory_macros/ot_sram_1r1w_1024x256_m2_r2c2 --macro physical/asap7_memory_macros/ot_sram_1r1w_128x256_m1_r2c2 --post-sdc $SIGN --output $O/corner_sta.json > $O/sta.log 2>&1
  echo "corner_rc=$?" >> $O/exit
fi
