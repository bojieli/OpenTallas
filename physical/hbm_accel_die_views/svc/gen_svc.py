#!/usr/bin/env python3
"""CLAUDE HBM-ABSTRACTS (svcidx): generate the four r16g stream-service die tops hfd_svc_{SW,SE,NW,NE} around
rtl/ot_hbm_svc_core.sv, with wire-stage counts from the generator's pin geometry, plus the PHY-bundle binding and the
forwarded-clock SDC of each top.

    python3 physical/hbm_accel_die_views/svc/gen_svc.py      (writes rtl/hfd_svc_*.sv, rtl/ot_hbm_svc_phybind.sv,
                                                              sdc/hfd_svc_*_fwd.sdc, svc_geometry.json)
"""
import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
import hbm_die_views as V  # noqa: E402

S, H, L = V.S, V.H, V.L
STAGE_UM = 430.56            # corridor-gate closing pitch (wire stage every <= 504 um at SS)
UNUSED = ('k_wr_done', 'k_oor', 'w_oor', 'refreshes', 'w_reads')   # PHY status: no die consumer
PHY_BB = 'physical/asap7_memory_macros_v2/ot_hbm3e_phy_v41x_aw30_e8p5/ot_hbm3e_phy_v41x_aw30_e8p5_bb.v'


def st(dx):
    return min(15, max(0, math.ceil(dx / STAGE_UM) - 1))     # stages beyond the ingress/egress registers


def cx(port):
    xs = [(p[2] + p[4]) / 2 for p in port['pins']]
    return sum(xs) / len(xs)


def main():
    phy = S.real_lef(S.PHY_LEF)
    pins = phy['pins']
    pcx = [sum((pins[f'kr_data[{p*256+i}]'][1][0] + pins[f'k_addr[{p*30 + min(i, 29)}]'][1][0]) / 2
               for i in range(0, 256, 32)) / 8 for p in range(32)]
    lanex = [sum(pins[f'wr_data[{l*256+i}]'][1][0] for i in range(0, 256, 16)) / 16 for l in range(8)]
    wportx = pins['w_v'][1][0]
    dfi = H.real_ports()[phy['name']]['dfi']
    bb = L.parse_module(PHY_BB, 'ot_hbm3e_phy_v41x_aw30_e8p5')['ports']        # name -> (dir, width)
    geo = {}
    for st_ in ('SW', 'SE', 'NW', 'NE'):
        mst = f'hfd_svc_{st_}'
        rec = V.master_record(mst)
        P = rec['ports']
        lsm = sorted((p for p in P if p.startswith('lsm')), key=lambda p: int(p[3:]))
        assert len(lsm) == 8
        smx = {p: cx(P[p]) for p in lsm}
        order = sorted(lsm, key=lambda p: smx[p])        # core SM index = rank by x
        sm_pc0 = [4 * k for k in range(8)]
        fwd = [P[p]['bits'] == 1102 for p in order]
        req_st, rsp_st, w_st = [], [0] * 32, []
        for k, p in enumerate(order):
            q = 'q' + p[1:]
            qx = cx(P[q])
            req_st.append(st(max(abs(pcx[4 * k + j] - qx) for j in range(4)) + 259.2))
            for j in range(4):
                rsp_st[4 * k + j] = st(abs(pcx[4 * k + j] - smx[p]) + 259.2)
            w_st.append(st(abs(lanex[k] - smx[p]) + 259.2))
        kvx, ikx, ex = cx(P['kv']), cx(P['ik']), cx(P['e'])
        kv_pc = min(range(32), key=lambda q: abs(pcx[q] - kvx))
        ik_pc = min((q for q in range(32) if q != kv_pc), key=lambda q: abs(pcx[q] - ikx))
        kv_st, ik_st = st(abs(pcx[kv_pc] - kvx) + 259.2), st(abs(pcx[ik_pc] - ikx) + 259.2)
        e_st = st(max(abs(ex - wportx), abs(ex - pcx[kv_pc]), abs(ex - pcx[ik_pc])) + 259.2)
        g = dict(order=order, sm_x=[round(smx[p], 1) for p in order], pc_x=[round(x, 1) for x in pcx],
                 lane_x=[round(x, 1) for x in lanex], fwd=fwd, req_st=req_st, rsp_st=rsp_st, w_st=w_st,
                 kv_pc=kv_pc, ik_pc=ik_pc, kv_st=kv_st, ik_st=ik_st, e_st=e_st,
                 added_cycles=dict(sm_line_k=[2 + req_st[k] + max(rsp_st[4*k:4*k+4]) for k in range(8)],
                                   w_line=[w_st[k] for k in range(8)]))
        geo[mst] = g

        def vec(vals, w):
            return f"{len(vals)*w}'h" + ''.join(f'{v:x}' for v in reversed(vals)).rjust(math.ceil(len(vals) * w / 4), '0') \
                if w == 4 else "{" + ', '.join(f"{w}'d{v}" for v in reversed(vals)) + "}"
        decl = V.svh(rec).rstrip()
        L_ = [f'// CLAUDE HBM-ABSTRACTS (svcidx): r16g die view top {mst} (generated by gen_svc.py; ports = the generator',
              f"// master's, directions = die_top_lint's DIRECTION MODEL).  Core SM index k = SM ports by x: {order}.",
              '`default_nettype none', f'module {mst} (', decl, ');']
        L_ += ['  wire [8*42-1:0] q_d; wire [7:0] q_v, q_fclk, q_rdy; wire [8*1099-1:0] line; wire fclk;',
               '  wire phy_clk, phy_rst_n;']
        L_ += [f'  wire {"" if w == 1 else f"[{w-1}:0] "}{n};' for n, (d, w) in bb.items() if n not in ('clk', 'rst_n')]
        for k, p in enumerate(order):
            q = 'q' + p[1:]
            L_.append(f'  assign q_v[{k}] = {q}[0]; assign q_d[{k*42+41}:{k*42}] = {q}[42:1];')
            if fwd[k]:
                L_.append(f'  assign q_fclk[{k}] = {q}[44];')
                L_.append(f'  assign {p} = {{fclk, fclk, fclk, line[{k*1099+1098}:{k*1099}]}};')
            else:
                L_.append(f"  assign q_fclk[{k}] = 1'b0; assign {q}[43] = q_rdy[{k}];")
                L_.append(f'  assign {p} = line[{k*1099+1098}:{k*1099}];')
        L_ += ['  wire [1037:0] kv_d; wire [1023:0] ik_d;',
               '  assign kv = {fclk, fclk, fclk, kv_d}; assign ik = {fclk, fclk, ik_d};']
        cp = ', '.join(f'.{n}({n})' for n in bb if n not in ('clk', 'rst_n') + UNUSED)
        cpb = ', '.join(f'.{n}({n})' for n in bb if n not in ('clk', 'rst_n'))
        L_ += [f'  ot_hbm_svc_core #(.SM_PC0({vec(sm_pc0, 5)}), .RSP_ST({vec(rsp_st, 4)}), .REQ_ST({vec(req_st, 4)}),',
               f"    .W_ST({vec(w_st, 4)}), .FWD(8'b{''.join('1' if f else '0' for f in reversed(fwd))}),",
               f'    .KV_PC({kv_pc}), .IK_PC({ik_pc}), .KV_ST({kv_st}), .IK_ST({ik_st}), .E_ST({e_st})) u_core (',
               '    .ck(ck[0]), .rst(rst[0]), .q_d(q_d), .q_v(q_v), .q_fclk(q_fclk), .q_rdy(q_rdy), .line(line), .fclk(fclk),',
               '    .e_d(e[127:0]), .e_fclk(e[128]), .kv(kv_d), .ik(ik_d), .phy_clk(phy_clk), .phy_rst_n(phy_rst_n),',
               f'    {cp});',
               f'  ot_hbm_svc_phybind u_pb (.phy(phy), .clk(phy_clk), .rst_n(phy_rst_n), {cpb});',
               'endmodule', '`default_nettype wire', '']
        (HERE / 'rtl' / f'{mst}.sv').write_text('\n'.join(L_))
        # bench top for this master (uniform nets of tb_svc_body.svh in core order)
        T = [f'// bench (gen_svc.py) for {mst}', '`timescale 1ps/1ps', f'module tb_{mst};',
             f"  localparam [7:0] FWDV = 8'b{''.join('1' if f else '0' for f in reversed(fwd))};",
             '`include "tb_svc_body.svh"']
        conns = []
        for k, p in enumerate(order):
            q = 'q' + p[1:]
            if fwd[k]:
                T.append(f"  wire [44:0] tq{k} = {{fck, 1'b0, qd[{k}], qv[{k}]}}; assign qrdy[{k}] = 1'b0;")
                T.append(f'  wire [1101:0] tl{k}; assign ln[{k}] = tl{k}[1098:0];')
            else:
                T.append(f'  wire [43:0] tq{k}; assign tq{k}[42:0] = {{qd[{k}], qv[{k}]}}; assign qrdy[{k}] = tq{k}[43];')
                T.append(f'  wire [1098:0] tl{k}; assign ln[{k}] = tl{k};')
            conns += [f'.{q}(tq{k})', f'.{p}(tl{k})']
        T += ['  wire [1040:0] tkv; wire [1025:0] tik; assign kvo = tkv[1037:0]; assign iko = tik[1023:0];',
              f"  {mst} dut (.ck(ck), .rst(rst), .e({{fck, ed, ev}}), .kv(tkv), .ik(tik), .phy(phy),",
              '    ' + ', '.join(conns) + ');', 'endmodule', '']
        (HERE / 'tb').mkdir(exist_ok=True)
        (HERE / 'tb' / f'tb_{mst}.sv').write_text('\n'.join(T))
        sdc = [f'# {mst}: forwarded input clocks (row-1 SM requests, e) at the stream clock period; they only write',
               '# two-clock FIFOs (ot_hbm_accel_cdc_fifo), asynchronous to ck (clk_hbm)']
        names = []
        for k, p in enumerate(order):
            if fwd[k]:
                q = 'q' + p[1:]
                sdc.append(f'create_clock -name fq{k} -period 0.833 [get_ports {{{q}[44]}}]')
                names.append(f'fq{k}')
        sdc.append('create_clock -name fe -period 0.833 [get_ports {e[128]}]')
        names.append('fe')
        sdc.append('set_clock_uncertainty -setup 0.060 [get_clocks {' + ' '.join(names) + '}]')
        sdc.append('set_clock_uncertainty -hold 0.025 [get_clocks {' + ' '.join(names) + '}]')
        sdc.append('set_clock_groups -asynchronous -group [get_clocks core_clk] ' +
                   ' '.join(f'-group [get_clocks {n}]' for n in names))
        (HERE / 'sdc').mkdir(exist_ok=True)
        (HERE / 'sdc' / f'{mst}_fwd.sdc').write_text('\n'.join(sdc) + '\n')
    # PHY bundle binding (identical for the four services): phy[i] = PHY pin dfi[i]
    runs = []
    for i, n in enumerate(dfi):
        m = re.match(r'(\w+)\[(\d+)\]$', n)
        b, ix = (m.group(1), int(m.group(2))) if m else (n, None)
        if runs and runs[-1][0] == b and ix is not None and runs[-1][2] is not None \
                and ix == runs[-1][2] + runs[-1][3] and i == runs[-1][1] + runs[-1][3]:
            runs[-1][3] += 1
        else:
            runs.append([b, i, ix, 1])
    B = ['// CLAUDE HBM-ABSTRACTS (svcidx): the service side of the r16g PHY bundle (generated by gen_svc.py).',
         '// phy[i] is the PHY abstract pin dfi[i] (tools/hbm_accel_die_fp.py real_ports: PHY pins sorted by x);',
         '// a PHY input is driven here, a PHY output is read here.', '`default_nettype none',
         'module ot_hbm_svc_phybind (', f'  inout wire [{len(dfi)-1}:0] phy,']
    pl = []
    for n, (d, w) in bb.items():
        sd = 'input' if d == 'input' else 'output'        # PHY input = driven by the service
        pl.append(f'  {sd} wire {"" if w == 1 else f"[{w-1}:0] "}{n}')
    B.append(',\n'.join(pl) + ');')
    for b, i0, ix, n in runs:
        d = bb[b][0]
        w = bb[b][1]
        sig = b if w == 1 else (f'{b}[{ix}]' if n == 1 else f'{b}[{ix+n-1}:{ix}]')
        ph = f'phy[{i0}]' if n == 1 else f'phy[{i0+n-1}:{i0}]'
        B.append(f'  assign {ph} = {sig};' if d == 'input' else f'  assign {sig} = {ph};')
    B += ['endmodule', '`default_nettype wire', '']
    (HERE / 'rtl' / 'ot_hbm_svc_phybind.sv').write_text('\n'.join(B))
    # bench-only complement: the PHY side of the bundle (PHY outputs drive phy[], PHY inputs are read from it)
    T = ['// bench only (gen_svc.py): the PHY side of the r16g PHY bundle', 'module tb_svc_physide (',
         f'  inout wire [{len(dfi)-1}:0] phy,']
    pl = []
    for n, (d, w) in bb.items():
        sd = 'output' if d == 'input' else 'input'
        pl.append(f'  {sd} wire {"" if w == 1 else f"[{w-1}:0] "}{n}')
    T.append(',\n'.join(pl) + ');')
    for b, i0, ix, n in runs:
        d, w = bb[b]
        sig = b if w == 1 else (f'{b}[{ix}]' if n == 1 else f'{b}[{ix+n-1}:{ix}]')
        ph = f'phy[{i0}]' if n == 1 else f'phy[{i0+n-1}:{i0}]'
        T.append(f'  assign {sig} = {ph};' if d == 'input' else f'  assign {ph} = {sig};')
    T += ['endmodule', '']
    (HERE / 'tb').mkdir(exist_ok=True)
    (HERE / 'tb' / 'tb_svc_physide.sv').write_text('\n'.join(T))
    (HERE / 'svc_geometry.json').write_text(json.dumps(geo, indent=1) + '\n')
    print(json.dumps({k: dict(order=v['order'], req=v['req_st'], w=v['w_st'], kv=(v['kv_pc'], v['kv_st']),
                              ik=(v['ik_pc'], v['ik_st']), e=v['e_st'], rsp_max=max(v['rsp_st'])) for k, v in geo.items()}))


if __name__ == '__main__':
    main()
