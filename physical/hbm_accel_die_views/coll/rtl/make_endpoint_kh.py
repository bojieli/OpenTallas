#!/usr/bin/env python3
"""hfd_coll synthesis hierarchy (views agent, 2026-10-06): co13 spent 6.5 h and hbm_coll_f29a13cb3 > 1 h in ONE flat ABC
run (the TU endpoint flattened into hfd_coll: 112 fp32 adders, 8 port FIFOs + CDC FIFOs, 35 / 14-stage delays).
SYNTH_KEEP_MODULES cannot select the parametrized derived modules ($paramod...), and a module attribute on the shared
primitives would change every other block's synthesis.  This writes a coll-local copy of the UNCHANGED endpoint with
(* keep_hierarchy *) on its primitive INSTANCES only (same module name, same logic): yosys keeps those cells as
hierarchy, so ABC maps each unique derived module once (one fp32 adder instead of 112) and the endpoint glue alone.

    python3 make_endpoint_kh.py write | check      (check: exit 1 unless the copy == source + the attributes)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SRC = ROOT / 'rtl/hbm_accel/tu/ot_hbm_accel_tu_endpoint.sv'
DST = Path(__file__).resolve().parent / 'ot_hbm_accel_tu_endpoint_kh.sv'
PRIMS = ('ot_ha2_delay', 'ot_ha2_fifo', 'ot_link_afifo', 'ot_hdc_fp32_add_lat')
ATTR = '(* keep_hierarchy *) '
HDR = '// GENERATED by physical/hbm_accel_die_views/coll/rtl/make_endpoint_kh.py from rtl/hbm_accel/tu/ot_hbm_accel_tu_endpoint.sv: identical but for (* keep_hierarchy *) on primitive instances\n'


def kh(text):
    out = []
    for ln in text.splitlines(keepends=True):
        m = re.match(r'^(\s*)(' + '|'.join(PRIMS) + r')\b', ln)
        out.append(m.group(1) + ATTR + ln[len(m.group(1)):] if m else ln)
    return HDR + ''.join(out)


def main():
    want = kh(SRC.read_text())
    if sys.argv[1:] == ['write']:
        DST.write_text(want)
        n = want.count(ATTR)
        print(f'wrote {DST.name}: {n} kept primitive instance sites')
        return 0
    got = DST.read_text()
    ok = got == want and got.replace(HDR, '', 1).replace(ATTR, '') == SRC.read_text()
    print('ENDPOINT_KH MATCH' if ok else 'ENDPOINT_KH MISMATCH')
    return 0 if ok else 1


if __name__ == '__main__':
    raise SystemExit(main())
