#!/usr/bin/env python3
"""ot_hfd_cmdproc20_m: margin-first cmdproc (CLAUDE HBM-ABSTRACTS spine, owner rule 2026-10-06) = rtl/gpu_sys/
ds_hbm_full20/ot_ds_hbm_cmdproc20.sv (unchanged) with its 256 x 64 flop command memory moved into an ASAP7 SRAM
macro (ot_sram_2rw_512x64_m4_r2c2, port A writes, port B reads, lower 256 words).

Failing classes on cp7_pd55 (3_place, ideal clocks, 29,569 endpoints under +40 ps): cmem write 13,311 + 13,291
endpoints (-383 / -361 ps: cmd_we / addr / wdata broadcast to 16 Ki flops per instance), cmd -802 / -684 ps (the
256:1 x 64 read mux), the output face hops (now face_stages 5).  With the macro the write is one macro pin set and the
read is the macro's own sense path.  Cycle-exact: the original reads cmem[cp] into cmd at the FETCH edge; the macro
reads at the same edge and its output register holds until the next read (b_ce only in S_FETCH), with the same
read-before-write order on a same-cycle write (the macro model: reads see the array before either write).  cmd's
reset value (0) is never observed: cmd is used only in S_EXEC / S_WAIT, which follow a FETCH."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
t = (ROOT / 'rtl/gpu_sys/ds_hbm_full20/ot_ds_hbm_cmdproc20.sv').read_text()


def rep(a, b):
    global t
    assert t.count(a) == 1, a
    t = t.replace(a, b)


rep('module ot_ds_hbm_cmdproc20 #(', 'module ot_hfd_cmdproc20_m #(')
rep("""    reg [63:0]   cmem [0:NCMD-1];
    always @(posedge clk) if (cmd_we) cmem[cmd_addr] <= cmd_wdata;
""", """    // command memory: SRAM macro (port A write, port B read at FETCH; NCMD <= 512)
    wire [63:0]  cmd;
    reg  [2:0]   st;
    reg  [CB-1:0] cp;
    ot_sram_2rw_512x64_m4_r2c2 u_cmem (.clk(clk),
        .a_ce_in(cmd_we), .a_we_in(1'b1), .a_addr_in(9'(cmd_addr)), .a_wd_in(cmd_wdata), .a_w_mask_in({64{1'b1}}),
        .a_rd_out(),
        .b_ce_in(st == S_FETCH), .b_we_in(1'b0), .b_addr_in(9'(cp)), .b_wd_in(64'd0), .b_w_mask_in(64'd0),
        .b_rd_out(cmd),
        .rr_en(2'b0), .rr_addr(14'b0), .cr_en(2'b0), .cr_sel(12'b0));
""")
rep("""    reg [2:0]    st;
    reg [CB-1:0] cp;
    reg [63:0]   cmd;
""", "")
rep("st <= S_IDLE; cp <= 0; cmd <= 64'd0; waiting <= 0;", "st <= S_IDLE; cp <= 0; waiting <= 0;")
rep("S_FETCH: begin cmd <= cmem[cp]; cp <= cp + 1'b1; st <= S_EXEC; end",
    "S_FETCH: begin cp <= cp + 1'b1; st <= S_EXEC; end           // u_cmem reads cmem[cp] at this edge")
rep("generate if (ENABLE == 0) begin : g_off", "initial if (ENABLE && NCMD > 512) $fatal(1, \"cmdproc_m: NCMD <= 512\");\ngenerate if (ENABLE == 0) begin : g_off")
# RDREG (margin-first, owner rule "stage every macro output", 2026-10-06): cpss3/cpsn3 (route 770, sign-off 833) failed
# SS -123 / -106 ps on u_cmem b_rd_out -> c_op / c_mask decode -> launch_pc / waiting / st (SRAM clk->Q 495 ps at SS).
# RDREG 1 registers the macro read word (cmd_q, captured in the new state S_RD between FETCH and EXEC): +1 cycle per
# executed command, every launch / completion value unchanged (tb_cmdproc_rd_equiv.sv, transaction-level vs the
# unchanged cmdproc).  RDREG 0 is the cycle-exact SRAM version (tb_cmdproc_m_equiv.sv).
rep("    parameter integer NCMD   = 256", "    parameter integer NCMD   = 256,\n    parameter integer RDREG  = 1")
rep("localparam [2:0] S_IDLE = 3'd0, S_FETCH = 3'd1, S_EXEC = 3'd2, S_WAIT = 3'd3, S_CPL = 3'd4;",
    "localparam [2:0] S_IDLE = 3'd0, S_FETCH = 3'd1, S_EXEC = 3'd2, S_WAIT = 3'd3, S_CPL = 3'd4, S_RD = 3'd5;")
rep("""    wire [63:0]  cmd;
    reg  [2:0]   st;""", """    wire [63:0]  cmd_m;             // macro read word (valid from the cycle after FETCH until the next read)
    reg  [63:0]  cmd_q;             // RDREG: registered read word (S_RD)
    wire [63:0]  cmd = (RDREG != 0) ? cmd_q : cmd_m;
    reg  [2:0]   st;
    always @(posedge clk) if (st == S_RD) cmd_q <= cmd_m;""")
rep("        .b_rd_out(cmd),", "        .b_rd_out(cmd_m),")
rep("S_FETCH: begin cp <= cp + 1'b1; st <= S_EXEC; end           // u_cmem reads cmem[cp] at this edge",
    "S_FETCH: begin cp <= cp + 1'b1; st <= (RDREG != 0) ? S_RD : S_EXEC; end   // u_cmem reads cmem[cp] at this edge\n"
    "                S_RD: st <= S_EXEC;                                          // RDREG: cmd_q <= read word")
Path(__file__).with_name('ot_hfd_cmdproc20_m.sv').write_text(
    '// GENERATED by make_cmdproc_m.py from rtl/gpu_sys/ds_hbm_full20/ot_ds_hbm_cmdproc20.sv (command memory in an SRAM '
    'macro; see there)\n' + t)
print('ok')
