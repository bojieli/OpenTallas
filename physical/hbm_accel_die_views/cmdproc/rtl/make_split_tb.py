#!/usr/bin/env python3
"""Exact bench of the cmdproc split (CLAUDE HBM-ABSTRACTS spine, 2026-10-06): hfd_cmdproc_s + hfd_cmdproc_n joined by
their cross buses (xl, xb, xt) against the unsplit hfd_cmdproc wrapper (face_stages 5, 4eda1e273, renamed
hfd_cmdproc_ref), both driven with the same die-input stream.

The split changes latencies (per-face stages), so every die output bit is checked at its own offset: the split's
output at cycle t must equal the reference's at cycle t + D(bit), D = (reference path cycles) - (split path cycles):
  cpS outputs (cSE/cSW/t_su_SE/t_su_SW): 10 - (3 + 3) = 4      cpN outputs (cNE/cNW/t_su_NE/t_su_NW): 10 - (4 + 3) = 3
  release f_barrier[0:16] -> S faces: 10 - 9 = 1              f_barrier[16:32] -> N faces: 10 - 5 = 5
  arrive t_barrier[0:16]: 10 - 9 = 1                          t_barrier[16:32]: 10 - 7 = 3
Equal input latency into each cmdproc (cpS 3/3, cpN 4/4) keeps every cmdproc's input stream aligned, so the states
are identical once the inputs start after an idle reset period (inputs 0 through reset and 24 cycles after release;
the configuration-chain inputs cNE[42] / cSE[42] are held 0 in both).  Spare die outputs are constant in both.
    python3 make_split_tb.py <out.sv> [cycles]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / 'tools'))
import hbm_die_views as V  # noqa: E402
import hbm_die_wrap as W  # noqa: E402

out = Path(sys.argv[1]); cycles = int(sys.argv[2]) if len(sys.argv) > 2 else 3000
rec = V.master_record('hfd_cmdproc')
ports = rec['ports']
spec = json.loads((Path(__file__).parent / 'spec.json').read_text())
dirs = {}
for p, v in ports.items():
    arr = ['in'] * v['bits']
    for a, b, d in v['dir_segments']:
        for i in range(a, b):
            arr[i] = 'out' if d == 'out' else 'in'
    dirs[p] = arr
S_PORTS = {'cSE', 'cSW', 't_su_SE', 't_su_SW', 'f_loader', 'f_router'}
# offsets per output bit
rel = {}   # (port, bit) -> D for the release/arrive pass-through bits
for port, lo, hi, e in spec['extra_out']:
    if e.startswith('i_f_barrier['):
        k = int(e[12:-1])
        rel[(port, lo)] = 1 if k < 16 else 5
    else:
        rel[(port, lo)] = 1 if lo < 16 else 3


def D(p, b):
    if (p, b) in rel:
        return rel[(p, b)]
    if p in ('t_barrier', 't_coll'):
        return 3   # constant spare bits (any offset)
    return 4 if p in S_PORTS else 3


T = ['`timescale 1ns/1ps', '// generated by make_split_tb.py: hfd_cmdproc_s + hfd_cmdproc_n vs hfd_cmdproc_ref', 'module tb_cmdproc_split;',
     '    reg clk = 0; always #0.4165 clk = ~clk;', '    reg rst;']
inn, outb = [], []
for p, v in sorted(ports.items()):
    n = v['bits']
    if p in ('ck', 'rst'):
        continue
    T.append(f'    wire [{n - 1}:0] r_{p}, s_{p};')
    T.append(f'    reg [{n - 1}:0] drv_{p};')
    for i, d in enumerate(dirs[p]):
        if d == 'in':
            T.append(f'    assign r_{p}[{i}] = drv_{p}[{i}]; assign s_{p}[{i}] = drv_{p}[{i}];')
            inn.append((p, i))
        elif W.fclk_bits('hfd_cmdproc').get(p, {}).get(i) != 'out':   # forwarded clocks: ~clk in both, not data
            outb.append((p, i))
conn_r = ', '.join([f'.{p}(r_{p})' for p in sorted(ports) if p not in ('ck', 'rst')] + ['.ck(clk)', '.rst(rst)'])
T.append(f'    hfd_cmdproc_ref u_ref({conn_r});')
T.append('    wire [146:0] xl; wire [15:0] xb, xt;')
for nm, pl in (('s', sorted(S_PORTS)), ('n', sorted(set(ports) - S_PORTS - {'ck', 'rst'}))):
    c = ', '.join([f'.{p}(s_{p})' for p in pl] + ['.ck(clk)', '.rst(rst)', '.xl(xl)', '.xb(xb)', '.xt(xt)'])
    T.append(f'    hfd_cmdproc_{nm} u_{nm}({c});')
# split output history (split is earlier): compare s_hist[D] with ref now
maxd = 6
for p, v in sorted(ports.items()):
    if p in ('ck', 'rst') or not any(d == 'out' for d in dirs[p]):
        continue
    n = v['bits']
    T.append(f'    reg [{n - 1}:0] h_{p} [0:{maxd}];')
    T.append(f'    integer i_{p}; always @(posedge clk) begin h_{p}[0] <= s_{p}; for (i_{p} = 1; i_{p} <= {maxd}; i_{p} = i_{p} + 1) h_{p}[i_{p}] <= h_{p}[i_{p} - 1]; end')
T += ['    integer err = 0, nchk = 0, cyc, seed = 20261006;', '    task automatic rnd; begin']
for p, v in sorted(ports.items()):
    if p in ('ck', 'rst') or not any(d == 'in' for d in dirs[p]):
        continue
    for k in range(0, v['bits'], 32):
        hi = min(v['bits'], k + 32)
        T.append(f'        drv_{p}[{hi - 1}:{k}] = $urandom(seed); seed = seed + 1;')
T += ['        drv_cNE[42] = 0; drv_cSE[42] = 0;', '    end endtask', '    task automatic idle; begin']
for p, v in sorted(ports.items()):
    if p in ('ck', 'rst') or not any(d == 'in' for d in dirs[p]):
        continue
    T.append(f"        drv_{p} = 0;")
T += ['    end endtask', '    initial begin', '        rst = 1; idle;', '        repeat (12) @(posedge clk);', '        #0.05 rst = 0;',
      '        repeat (24) @(posedge clk);', f'        for (cyc = 0; cyc < {cycles}; cyc = cyc + 1) begin', '            @(negedge clk);',
      '            if (cyc >= 12) begin']
# group checks by (port, D) contiguous runs
for p in sorted({p for p, _ in outb}):
    bits = [b for q, b in outb if q == p]
    run = []
    for b in bits + [None]:
        if run and (b is None or b != run[-1] + 1 or D(p, b) != D(p, run[0])):
            lo, hi, d = run[0], run[-1], D(p, run[0])
            T.append(f'                nchk = nchk + 1; if (h_{p}[{d - 1}][{hi}:{lo}] !== r_{p}[{hi}:{lo}]) begin err = err + 1; '
                     f'if (err < 12) $display("MISMATCH {p}[{hi}:{lo}] D={d} split %h ref %h cyc %0d", h_{p}[{d - 1}][{hi}:{lo}], r_{p}[{hi}:{lo}], cyc); end')
            run = []
        if b is not None:
            run.append(b)
T += ['            end', '            rnd;', '        end',
      '        $display("TB_cmdproc_split checks=%0d mismatches=%0d", nchk, err);',
      '        if (err != 0 || nchk == 0) $fatal(1, "FAIL");', '        $finish;', '    end', 'endmodule']
out.write_text('\n'.join(T) + '\n')
print(out, len(inn), len(outb))
