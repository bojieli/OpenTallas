#!/usr/bin/env python3
"""Writes ot_hfd_loader_half.sv: the unchanged ot_hfd_loader_host_m at half rate with handshake gating (see the header
of the generated file).  views agent, fail-fast 2026-10-06.   python3 make_loader_half.py"""
import re
from pathlib import Path
D = Path(__file__).resolve().parent
src = (D / 'ot_hfd_loader_host_m.sv').read_text()
i = src.index('module ot_hfd_loader_host_m')
body = src[src.index('(\n', i) + 2:src.index(');', i)]
ports = []
for d, rg, names in re.findall(r'(input|output)\s+wire\s*(\[[^\]]+\])?\s*([A-Za-z_]\w*(?:\s*,\s*(?!input|output)[A-Za-z_]\w*)*)', body):
    ports += [(d, rg or '', n.strip()) for n in names.split(',') if n.strip()]
dirs = {n: d for d, _, n in ports}
HOST = ['s_awready', 's_wready', 's_bvalid', 's_arready', 's_rvalid', 'h_awvalid', 'h_wvalid', 'h_bready', 'h_arvalid',
        'h_rready', 'h_dma_arready', 'h_dma_rvalid', 'h_dma_awready', 'h_dma_wready', 'h_dma_bvalid',
        'm_arvalid', 'm_rready', 'm_awvalid', 'm_wvalid', 'm_bready']          # m_*: the host-side DMA master (clk_host)
MEM = ['req_v', 'rsp_rdy']                                                      # MREQ (clk_mem)
for g in HOST + MEM:
    assert dirs.get(g) == 'output', g
import sys
# CFGREP (drive-2125 2026-10-08, REVIEW_20261008 DQ1): --rep adds parameter RG and replica-valid inputs for the two
# input channels whose storage is wide and whose valid comes from the die view's cfg chain (rsp: 273 b per lane, m_r:
# 67 b).  RG > 0: the slice's storage is split into RG groups, each loading on its own replica of the valid (the
# wrapper drives the replicas from kept registered copies of the cfg chain, equal to the valid every cycle), so the
# face -> slice single-cycle path no longer fans one flop out to every storage enable.  RG = 0: the replica ports are
# unused and the module is the plain SKID slice set (the transaction bench run_ldm_half.sh runs it that way).
REP = '--rep' in sys.argv
REP_PORTS = [' input wire [ND*(RG>0?RG:1)-1:0] rsp_v_r', ' input wire [(RG>0?RG:1)-1:0] m_rvalid_r'] if REP else []
L = ['// GENERATED by make_loader_half.py (views agent, fail-fast 2026-10-06): hfd_loader 30c5fa080 SS -863 over >= 9 internal',
     '// classes of the store and load engines in BOTH clock domains (counters, slot decode, tag / ROB arrays, 19-33 levels):',
     '// the unchanged ot_hfd_loader_host_m runs at HALF RATE: its clock is the domain clock gated every other cycle (en flop',
     '// toggling, latched while the clock is low, ANDed with it: the gated edge IS a fast edge, no divided tree and no RTL',
     '// race; SHARED=1: one gate for both domains, the die ties clk_host = clk_mem), and every valid / ready the core drives is gated to the fast cycle that',
     '// ends on a slow edge (ph), so a fast-side partner completes each handshake exactly once, at the edge where the core',
     '// samples it; data and levels pass straight through (stable for the whole slow cycle).  Bandwidth: 256 b per slow mem',
     '// cycle = 19.2 GB/s per die, still 2x the 9.6 GB/s host link that bounds the loader; off the per-token path.',
     '// SDC (loader/sdc/hfd_loader_half.sdc): core-to-core paths multicycle setup 2 / hold 1 (every core flop is clocked',
     '// only on gated edges); core <-> face paths stay single cycle.',
     '`timescale 1ns/1ps',
     'module ot_hfd_loader_half #(parameter integer ENABLE=0,ND=2,SHARED=0' + (',RG=0' if REP else '') + ')(',
     ',\n'.join([f' {d} wire{(" " + rg) if rg else ""} {n}' for d, rg, n in ports] + REP_PORTS), ');',
     ' reg hen_h_q, hen_m_q, hen_h_l, hen_m_l;',
     " always @(posedge clk_host or negedge rst_host_n) if(!rst_host_n) hen_h_q<=1'b0; else hen_h_q<=~hen_h_q;",
     ' always @(*) if (!clk_host) hen_h_l = hen_h_q;   // clock-gate latch: transparent while the clock is low',
     ' wire ck_hs = clk_host & hen_h_l;        // host-side core clock: the fast edges that end a ph_h cycle',
     ' wire ph_h = hen_h_q;', ' wire ck_ms, ph_m;',
     ' generate if (SHARED) begin : g_sh assign ck_ms = ck_hs; assign ph_m = ph_h; end', ' else begin : g_sep',
     "  always @(posedge clk_mem or negedge rst_mem_n) if(!rst_mem_n) hen_m_q<=1'b0; else hen_m_q<=~hen_m_q;",
     '  always @(*) if (!clk_mem) hen_m_l = hen_m_q;',
     '  assign ck_ms = clk_mem & hen_m_l; assign ph_m = hen_m_q;', ' end endgenerate']
SKID = '--skid' in sys.argv
if not SKID:
    L += [f' wire{(" " + rg) if rg else ""} c_{n};' for d, rg, n in ports if n in HOST + MEM]
    conn = []
    for d, rg, n in ports:
        conn.append('.clk_host(ck_hs)' if n == 'clk_host' else '.clk_mem(ck_ms)' if n == 'clk_mem' else
                    f'.{n}(c_{n})' if n in HOST + MEM else f'.{n}({n})')
    L.append(' ot_hfd_loader_host_m #(.ENABLE(ENABLE),.ND(ND)) u_core(' + ','.join(conn) + ');')
    L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_h}}}};' for n in HOST]
    L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_m}}}};' for n in MEM]
    L.append('endmodule')
else:
    # SKID (hbm-blocks 2026-10-07): a 2-entry register slice on the GATED clock at every channel boundary, so every
    # core port is a gated-domain register (core <-> slice paths: multicycle 2 / 1 like core <-> core) and the face <->
    # slice paths carry no core logic (4d30522ee: face i_h -> store/load engines -504 ps, 24 levels, single cycle).
    # The partner-facing valid / ready stay gated to ph exactly as before (one handshake per slow cycle, at the edge
    # where the slice samples it).  +1 slow cycle each way per channel; the loader is off the per-token path.
    rg_of = {n: rg for d, rg, n in ports}
    def width(n):
        return f'$bits({n})'
    chans = []                     # (name, dir 'in'|'out', valid, ready, [data], dom, lanes)
    for P in ('s', 'h', 'h_dma', 'm'):
        for ch in ('aw', 'w', 'b', 'ar', 'r'):
            v, r = f'{P}_{ch}valid', f'{P}_{ch}ready'
            if v not in dirs:
                continue
            data = [n for d, rg, n in ports if n.startswith(f'{P}_{ch}') and n not in (v, r)
                    and not (P == 'h' and n.startswith('h_dma'))]
            chans.append((f'{P}_{ch}', 'in' if dirs[v] == 'input' else 'out', v, r, data, 'h', 0))
    chans.append(('req', 'out', 'req_v', 'req_rdy', ['req_we', 'req_addr', 'req_wdata', 'req_wstrb', 'req_tag'], 'm', 1))
    chans.append(('rsp', 'in', 'rsp_v', 'rsp_rdy', ['rsp_we', 'rsp_tag', 'rsp_data'], 'm', 1))
    covered = {x for c in chans for x in [c[2], c[3]] + c[4]}
    L += [f' wire{(" " + rg) if rg else ""} k_{n};' for d, rg, n in ports if n in covered]
    L += [f' wire{(" " + rg_of[n]) if rg_of[n] else ""} c_{n};' for n in HOST + MEM]
    conn = []
    for d, rg, n in ports:
        conn.append('.clk_host(ck_hs)' if n == 'clk_host' else '.clk_mem(ck_ms)' if n == 'clk_mem' else
                    f'.{n}(k_{n})' if n in covered else f'.{n}({n})')
    L.append(' ot_hfd_loader_host_m #(.ENABLE(ENABLE),.ND(ND)) u_core(' + ','.join(conn) + ');')
    for name, dr, v, r, data, dom, lanes in chans:
        ck, rn = ('ck_hs', 'rst_host_n') if dom == 'h' else ('ck_ms', 'rst_mem_n')
        nl = 'ND' if lanes else '1'
        L.append(f' genvar g_{name};')
        L.append(f' for (g_{name} = 0; g_{name} < {nl}; g_{name} = g_{name} + 1) begin : u_sk_{name}')
        if lanes:
            def sl(n, w):
                return f'{n}[g_{name}*{w} +: {w}]'
            ws = {'req_we': 1, 'req_addr': 32, 'req_wdata': 256, 'req_wstrb': 32, 'req_tag': 16,
                  'rsp_we': 1, 'rsp_tag': 16, 'rsp_data': 256}
            dv = [(n, ws[n]) for n in data]
            vsl = lambda n: f'{n}[g_{name}]'
        else:
            dv = [(n, None) for n in data]
            vsl = lambda n: n
            sl = lambda n, w: n
        if dv:
            W = ' + '.join((str(w) if w else f'$bits({n})') for n, w in dv)
            cat = lambda pre: '{' + ', '.join(sl(pre + n, w) for n, w in dv) + '}'
        else:
            W = '1'
            cat = None
        if dr == 'in':      # partner -> slice -> core
            din = cat('') if dv else "1'b0"
            dout = cat('k_') if dv else None
            L.append(f'  wire ov; wire [{W}-1:0] od;')
            if REP and name in ('rsp', 'm_r'):
                rep = f'rsp_v_r[g_{name}*RG +: RG]' if lanes else 'm_rvalid_r'
                L.append(f'  if (RG > 0) begin : g_rep')
                L.append(f'   ot_ldh_slice_g #(.W({W}), .G(RG)) u (.clk({ck}), .rst_n({rn}), .ivg({rep}), .id({din}), .ir({vsl("c_" + r)}),'
                         f' .ov({vsl("k_" + v)}), .od(od), .orr({vsl("k_" + r)}));')
                L.append(f'  end else begin : g_one')
            L.append(f'  ot_ldh_slice #(.W({W})) u (.clk({ck}), .rst_n({rn}), .iv({vsl(v)}), .id({din}), .ir({vsl("c_" + r)}),'
                     f' .ov({vsl("k_" + v)}), .od(od), .orr({vsl("k_" + r)}));')
            if REP and name in ('rsp', 'm_r'):
                L.append(f'  end')
            if dout:
                L.append(f'  assign {dout} = od;')
        else:               # core -> slice -> partner
            din = cat('k_') if dv else "1'b0"
            dout = cat('') if dv else None
            L.append(f'  wire [{W}-1:0] od;')
            L.append(f'  ot_ldh_slice #(.W({W})) u (.clk({ck}), .rst_n({rn}), .iv({vsl("k_" + v)}), .id({din}), .ir({vsl("k_" + r)}),'
                     f' .ov({vsl("c_" + v)}), .od(od), .orr({vsl(r)}));')
            if dout:
                L.append(f'  assign {dout} = od;')
        L.append(' end')
    L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_h}}}};' for n in HOST]
    L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_m}}}};' for n in MEM]
    L.append('endmodule')
    L += ['', '// 2-entry register slice: ir and ov / od are registers (or a 1-level function of them); one transfer a cycle.',
          'module ot_ldh_slice #(parameter integer W = 1) (input wire clk, input wire rst_n, input wire iv, input wire [W-1:0] id,',
          '    output wire ir, output wire ov, output wire [W-1:0] od, input wire orr);',
          ' reg [W-1:0] m0, m1; reg wp, rp; reg [1:0] cnt;',
          ' assign ir = (cnt != 2\'d2); assign ov = (cnt != 2\'d0); assign od = rp ? m1 : m0;',
          ' wire push = iv && ir, pop = ov && orr;',
          ' always @(posedge clk or negedge rst_n)',
          "  if (!rst_n) begin wp <= 1'b0; rp <= 1'b0; cnt <= 2'd0; end",
          '  else begin if (push) wp <= ~wp; if (pop) rp <= ~rp; cnt <= cnt + {1\'b0, push} - {1\'b0, pop}; end',
          ' always @(posedge clk) if (push) begin if (wp) m1 <= id; else m0 <= id; end',
          'endmodule']
    if REP:
        L += ['', '// ot_ldh_slice with the storage split into G groups (CFGREP): group k loads on ivg[k]; every ivg[k] must equal the',
              '// single valid of ot_ldh_slice each cycle (registered copies of one source), then the two are cycle-identical.',
              '// Control (wp / rp / cnt) uses ivg[0].',
              'module ot_ldh_slice_g #(parameter integer W = 1, G = 2) (input wire clk, input wire rst_n, input wire [G-1:0] ivg,',
              '    input wire [W-1:0] id, output wire ir, output wire ov, output wire [W-1:0] od, input wire orr);',
              ' reg [W-1:0] m0, m1; reg wp, rp; reg [1:0] cnt;',
              " assign ir = (cnt != 2'd2); assign ov = (cnt != 2'd0); assign od = rp ? m1 : m0;",
              ' wire push = ivg[0] && ir, pop = ov && orr;',
              ' always @(posedge clk or negedge rst_n)',
              "  if (!rst_n) begin wp <= 1'b0; rp <= 1'b0; cnt <= 2'd0; end",
              "  else begin if (push) wp <= ~wp; if (pop) rp <= ~rp; cnt <= cnt + {1'b0, push} - {1'b0, pop}; end",
              ' genvar b;',
              ' for (b = 0; b < W; b = b + 1) begin : g_b',
              '  wire pg = ivg[(b * G) / W] && ir;',
              '  always @(posedge clk) if (pg) begin if (wp) m1[b] <= id[b]; else m0[b] <= id[b]; end',
              ' end',
              'endmodule']
(D / 'ot_hfd_loader_half.sv').write_text('\n'.join(L) + '\n')
print(len(ports), 'ports', 'REP' if REP else '')
