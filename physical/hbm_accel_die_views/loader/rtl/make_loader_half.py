#!/usr/bin/env python3
"""Writes ot_hfd_loader_half.sv: the unchanged ot_hfd_loader_host_m at half rate with handshake gating (see the header
of the generated file).  views agent, fail-fast 2026-10-06.   python3 make_loader_half.py"""
import re
from pathlib import Path
D = Path(__file__).resolve().parent
src = (D / 'ot_hfd_loader_host_m.sv').read_text()
i = src.index('module ot_hfd_loader_host_m')
body = src[src.index('(\n', i) + 2:src.index(');', i)]
ports = []
for d, rg, names in re.findall(r'(input|output)\s+wire\s*(\[[^\]]+\])?\s*([A-Za-z_]\w*(?:\s*,\s*(?!input|output)[A-Za-z_]\w*)*)', body):
    ports += [(d, rg or '', n.strip()) for n in names.split(',') if n.strip()]
dirs = {n: d for d, _, n in ports}
HOST = ['s_awready', 's_wready', 's_bvalid', 's_arready', 's_rvalid', 'h_awvalid', 'h_wvalid', 'h_bready', 'h_arvalid',
        'h_rready', 'h_dma_arready', 'h_dma_rvalid', 'h_dma_awready', 'h_dma_wready', 'h_dma_bvalid']
MEM = ['m_arvalid', 'm_rready', 'm_awvalid', 'm_wvalid', 'm_bready', 'req_v', 'rsp_rdy']
for g in HOST + MEM:
    assert dirs.get(g) == 'output', g
L = ['// GENERATED by make_loader_half.py (views agent, fail-fast 2026-10-06): hfd_loader 30c5fa080 SS -863 over >= 9 internal',
     '// classes of the store and load engines in BOTH clock domains (counters, slot decode, tag / ROB arrays, 19-33 levels):',
     '// the unchanged ot_hfd_loader_host_m runs at HALF RATE.  Each domain clock is divided by 2 here (SHARED=1: one divider',
     '// for both, the die ties clk_host = clk_mem), and every valid / ready the core drives is gated to the fast cycle that',
     '// ends on a slow edge (ph), so a fast-side partner completes each handshake exactly once, at the edge where the core',
     '// samples it; data and levels pass straight through (stable for the whole slow cycle).  Bandwidth: 256 b per slow mem',
     '// cycle = 19.2 GB/s per die, still 2x the 9.6 GB/s host link that bounds the loader; off the per-token path.',
     '// SDC: create_generated_clock -divide_by 2 on the divider flops (*hdiv_h_q* / *hdiv_m_q*, QN pin).',
     '`timescale 1ns/1ps',
     'module ot_hfd_loader_half #(parameter integer ENABLE=0,ND=2,SHARED=0)(',
     ',\n'.join(f' {d} wire{(" " + rg) if rg else ""} {n}' for d, rg, n in ports), ');',
     ' reg hdiv_h_q, hdiv_m_q;',
     " always @(posedge clk_host or negedge rst_host_n) if(!rst_host_n) hdiv_h_q<=1'b0; else hdiv_h_q<=~hdiv_h_q;",
     ' wire ck_hs = hdiv_h_q;                 // host-side core clock (rises on the fast edge that ends a ph_h cycle)',
     ' wire ph_h = ~hdiv_h_q;', ' wire ck_ms, ph_m;',
     ' generate if (SHARED) begin : g_sh assign ck_ms = ck_hs; assign ph_m = ph_h; end', ' else begin : g_sep',
     "  always @(posedge clk_mem or negedge rst_mem_n) if(!rst_mem_n) hdiv_m_q<=1'b0; else hdiv_m_q<=~hdiv_m_q;",
     '  assign ck_ms = hdiv_m_q; assign ph_m = ~hdiv_m_q;', ' end endgenerate']
L += [f' wire{(" " + rg) if rg else ""} c_{n};' for d, rg, n in ports if n in HOST + MEM]
conn = []
for d, rg, n in ports:
    conn.append('.clk_host(ck_hs)' if n == 'clk_host' else '.clk_mem(ck_ms)' if n == 'clk_mem' else
                f'.{n}(c_{n})' if n in HOST + MEM else f'.{n}({n})')
L.append(' ot_hfd_loader_host_m #(.ENABLE(ENABLE),.ND(ND)) u_core(' + ','.join(conn) + ');')
L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_h}}}};' for n in HOST]
L += [f' assign {n} = c_{n} & {{$bits(c_{n}){{ph_m}}}};' for n in MEM]
L.append('endmodule')
(D / 'ot_hfd_loader_half.sv').write_text('\n'.join(L) + '\n')
print(len(ports), 'ports')
