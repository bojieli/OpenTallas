#!/usr/bin/env python3
"""Per-PORT minimum IO arrival credit for a spine die view's FF hold sign-off: the stations' FF hold model
(stations/bench/stn_io_min.py, coordinator decision 2026-10-06) applied per die port instead of per view.

Credit of a ck-domain IO port = the connected die path's minimum arrival: launching flop clk->Q at FF (inputs only:
the upstream view's pin-launch flop) + 0.1118 ps/um (50 % of the measured FF wire delay) x the minimum Manhattan gap
between this port's pin box (route_view ports.json) and the connected port's pin box (instance outline when that
master has no ports record here: never larger than the real gap) over every r16g die bus on the port.
Split bands (cmdproc/split/split.json) take their parent's die ports from the parent master; their new cross-band
ports abut the other band (gap 0: clk->Q only).
Outputs per master an SDC read after vclk_corner_true.sdc in the FF session only:
  inputs:  set_input_delay -min (FF max - FF min insertion) + credit_in(port)   (the corner-true term + the die path)
  outputs: set_output_delay -min +credit_out(port)                              (the die path delays our data)

  spine_io_min.py --ports DIR --master hfd_cmdproc_s [--master ...] --out-dir DIR
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(ROOT / 'physical/hbm_accel_die_views/stations/bench'))
import hbm_die_views as V  # noqa: E402
from stn_io_min import PS_PER_UM, CLKQ_FF_PS, xf, gap  # noqa: E402

SPLIT = ROOT / 'physical/hbm_accel_die_views/cmdproc/split/split.json'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ports', required=True, help='dir of <master>/ports.json (tools/hbm_die_views.py ports)')
    ap.add_argument('--master', action='append', required=True)
    ap.add_argument('--out-dir', required=True)
    a = ap.parse_args()
    m, pw, M, real = V.model()
    by = {it.name: it for it in m['insts']}
    split = json.loads(SPLIT.read_text())
    band_parent = {b: split['parent'] for b in split['bands']}
    pr = {}

    def rec(mst):
        if mst not in pr:
            f = Path(a.ports) / mst / 'ports.json'
            pr[mst] = json.loads(f.read_text()) if f.exists() else None
        return pr[mst]

    def port_box(mst, port, it):
        r = rec(mst)
        if not r or port not in r['ports']:
            return (it.x, it.y, it.x + it.w, it.y + it.h)
        ps = r['ports'][port]['pins']
        bb = (min(p[2] for p in ps), min(p[3] for p in ps), max(p[4] for p in ps), max(p[5] for p in ps))
        return xf(bb, it, r['w_um'], r['h_um'])

    out_dir = Path(a.out_dir); out_dir.mkdir(parents=True, exist_ok=True)
    summary = dict(method=__doc__.split('\n\n')[0], ps_per_um=PS_PER_UM, clkq_ff_ps=CLKQ_FF_PS, views={})
    for mst in a.master:
        die_mst = band_parent.get(mst, mst)
        own = set()
        if mst in split['bands']:
            own = set(split['bands'][mst]['parent_ports'])
            cross = {p for p, v in split['bands'][mst]['new_ports'].items() if p not in ('ck', 'rst')}
        else:
            cross = set()
        best = {}
        for bid, cls, bits, eps in m['buses']:
            for inst, port in eps:
                if inst == 'TOP' or by[inst].master != die_mst or (own and port not in own):
                    continue
                if port in ('ck', 'rst', 'refclk'):     # die clock / reset (rst: false path in vclk_corner_true)
                    continue
                it = by[inst]
                mine = port_box(die_mst, port, it)
                for inst2, port2 in eps:
                    if inst2 in ('TOP', inst):
                        continue
                    it2 = by[inst2]
                    g = gap(mine, port_box(it2.master, port2, it2))
                    if port not in best or g < best[port][0]:
                        best[port] = (round(g, 3), inst2, port2)
        for p in cross:
            best[p] = (0.0, 'abutting band', p)
        ports = {p: dict(min_wire_um=v[0], credit_in_ps=round(v[0] * PS_PER_UM + CLKQ_FF_PS, 2),
                         credit_out_ps=round(v[0] * PS_PER_UM, 2), via=f'{v[1]}.{v[2]}') for p, v in sorted(best.items())}
        summary['views'][mst] = ports
        lines = [f'# generated by physical/hbm_accel_die_views/common/spine_io_min.py for {mst} (die master {die_mst}):',
                 '# FF hold credit of the connected die path per port (read after vclk_corner_true.sdc; FF session only)',
                 'if {[llength [get_libs -quiet *_FF_*]] && [llength [get_clocks -quiet vclk]]} {',
                 '  sta::redirect_string_begin', '  report_clock_latency -clocks core_clk',
                 '  set ot_s [sta::redirect_string_end]',
                 '  if {[regexp {rise -> rise.*?([0-9.]+)\\s+([0-9.]+)\\s+latency} $ot_s -> ot_lo ot_hi]} {']
        for p, r in ports.items():
            # inout die ports (the retyped cSE/cSW/h buses) are 'bidirect' to STA: both roles get their credit
            lines.append(f'    foreach ot_q [get_ports -quiet {{{p} {p}[*]}}] {{ set ot_d [get_property $ot_q direction]; '
                         f'if {{$ot_d in {{input bidirect}}}} '
                         f'{{ set_input_delay -min [expr {{$ot_hi - $ot_lo + {r["credit_in_ps"]}}}] -clock vclk $ot_q }}; '
                         f'if {{$ot_d in {{output bidirect}}}} '
                         f'{{ set_output_delay -min {r["credit_out_ps"]} -clock vclk $ot_q }} }}')
        lines += ['    puts "OT_IOMIN: per-port die-path hold credit applied"', '  }', '}', '']
        (out_dir / f'io_min_{mst}.sdc').write_text('\n'.join(lines))
    print(json.dumps(summary, indent=1))


if __name__ == '__main__':
    main()
