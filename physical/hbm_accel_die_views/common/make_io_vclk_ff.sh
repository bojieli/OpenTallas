#!/bin/bash
# make_io_vclk_ff.sh <Lmin_ps> <Lmax_ps> [clock]: io_vclk_ff_<Lmin>_<Lmax>.sdc, the corner-true FF HOLD sign-off post-SDC
# for a view timed with io_vclk[_m]_<L>.sdc (L = SS insertion; read it with corner_sta --post-sdc on the FF run only).
# One SS insertion on the hold side over-constrains IO hold: an output must then out-wait an SS-late die clock that at
# FF arrives ~130 ps earlier (stations M2_hfd_meso_r32: 7 hold buffers per output, still -7.75 ps).  At FF: outputs
# are held against vclk at the block's FF MEAN insertion (the die clock plan aligns every block's nominal insertion) plus
# the 50 ps die-clock skew allowance (inter-clock hold uncertainty): the latest capture; inputs launch at vclki at the FF
# mean with the plain 25 ps (RULE H1, h1-verify 2026-10-08: the sender carries the link hold term once; it was FF min for
# outputs / FF max + 50 for inputs: both earlier/later than nominal in the optimistic direction, the 50 counted twice).  The 150 ps die clock-arrival term stays on the setup (SS) side.
# Measure Lmin/Lmax on the routed view at FF (stations/bench/stn_ckff.sh is a station-clock example).
# Origin: CLAUDE HBM-ABSTRACTS stations (bench/stn_margin_sdc.py, stn_resignoff.sh); approved by the coordinator 2026-10-06.
cd "$(dirname "$0")"
LMIN=$1; LMAX=$2; C=${3:-core_clk}
cat > io_vclk_ff_${LMIN}_${LMAX}.sdc <<EOT
# generated by make_io_vclk_ff.sh $LMIN $LMAX $C (see there): FF hold sign-off post-SDC
# RULE H1 (h1-verify 2026-10-08): outputs vs vclk at the FF mean + 50 (sender: latest capture); inputs launched at the mean, 25
set_clock_latency $(echo "($LMIN + $LMAX) / 2" | bc -l | sed 's/0*$//;s/\.$//') [get_clocks vclk]
create_clock -name vclki -period [get_property [get_clocks $C] period]
set_clock_latency $(echo "($LMIN + $LMAX) / 2" | bc -l | sed 's/0*$//;s/\.$//') [get_clocks vclki]
set ot_in [all_inputs -no_clocks]
unset_input_delay -clock vclk \$ot_in
set_input_delay [expr {[get_property [get_clocks $C] period] * 0.2}] -clock vclki \$ot_in
set_input_delay -min 0 -clock vclki \$ot_in
set_clock_uncertainty -hold 25 -from [get_clocks vclki] -to [get_clocks $C]
set_clock_uncertainty -hold 50 -from [get_clocks $C] -to [get_clocks vclk]
EOT
echo io_vclk_ff_${LMIN}_${LMAX}.sdc
