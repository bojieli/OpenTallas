#!/bin/bash
# make_io_vclk.sh <L_ps>...: write io_vclk_<L>.sdc, the spine die-view IO budget against a virtual clock vclk at the
# block's own measured clock insertion delay L (same convention as the attn fork's io_vclk_c1000.sdc, b7c8441f8).
# A 1.4 mm wide spine view with its ck pin mid-edge has 0.7-1.1 ns SS insertion (measured on hfd_quant qt2 709-829 ps,
# hfd_router rt2 952-1132 ps, report_clock_latency after CTS); against an ideal clock that delay lands entirely on the
# output paths (-1.3 to -1.6 ns) and on input hold (-0.42 ns).  The die clock tree balances every block's flops to one
# instant (its ck pin is a CTS sink with insertion L, padded by the die), so the 0.2 T IO budgets are taken against
# vclk at latency L: an IO path sees only its register's skew from L.  Period, 60/25 ps uncertainty and the 0.2 T
# budgets are unchanged; L is reported per view (view.json note) for the die-level clock-tree balance, plus
# the reset-release multicycle (rst_mcp2).
cd "$(dirname "$0")"
for L in "$@"; do cat > io_vclk_$L.sdc <<EOT
# generated by make_io_vclk.sh $L (see there): IO budget 0.2 T against vclk at the view's measured insertion $L ps
create_clock -name vclk -period [get_property [get_clocks core_clk] period]
set_clock_uncertainty -setup 60 [get_clocks vclk]
set_clock_uncertainty -hold 25 [get_clocks vclk]
set_clock_latency $L [get_clocks {core_clk vclk}]
set ot_in [all_inputs -no_clocks]
unset_input_delay -clock core_clk \$ot_in
unset_output_delay -clock core_clk [all_outputs]
set_input_delay [expr {[get_property [get_clocks core_clk] period] * 0.2}] -clock vclk \$ot_in
set_output_delay [expr {[get_property [get_clocks core_clk] period] * 0.2}] -clock vclk [all_outputs]
set_input_delay -min 0 -clock vclk \$ot_in
set_output_delay -min 0 -clock vclk [all_outputs]
# reset release (design intent, rst_mcp2): the wrapper's synchronised reset rst_s[1] fans out to every RTL flop of a
# 1.4 mm view in one net; release is allowed 2 cycles to reach every flop (the die holds rst >= 3 cycles and sends no
# input valid within 2 cycles of release; every bound block idles until its first input).  Steady-state timing unchanged.
set ot_rst {}
foreach ot_c [get_cells *] { if {[string match {rst_s\\[1\\]*} [get_full_name \$ot_c]]} { lappend ot_rst \$ot_c } }
if {[llength \$ot_rst]} { set_multicycle_path -setup 2 -from \$ot_rst; set_multicycle_path -hold 1 -from \$ot_rst }
EOT
done
