#!/usr/bin/env python3
"""hgi_seq FE s4 pin plan (el1013-hbm-seq-split, 2026-10-13): every FE seam pin on the track of the CLOSED neighbour's pin.

The three sequencer leaves are die-placed tiles of hb_cmdproc (contract r25gq v12: u_fe (43.2, 561.6), u_be (302.4, 561.6),
u_au (43.2, 777.6): FE | BE gap 10.8 um, FE | AU gap 4.32 um).  s1-s3 left the pins to the placer inside each face, so a
seam bit ran 58-183 um sideways between two tiles 4-11 um apart (fe_s1_dmul: FE N x 27-85, AU S x 160-208).  Under the die
clock rule (o_A + 0.76 ps/um x L + s_B <= 623.3 ps with FE on the R > 300 tap) 4 of the 74 seam buses miss by 2-49 ps.
Here: FE N-face pin of a bus AU takes = AU's S-face x (same origin x); FE E-face pin of a bus BE takes or drives = BE's
W-face y (same origin y), or the highest free track when BE's pin sits above FE's top edge.  Every other FE pin keeps its
closed position, moved to the nearest free track only if a seam pin now owns its track.
    mk_hgi_seq_fe_pins.py  ->  hgi_seq_fe_pins.tcl + hgi_seq_fe_pins.json (seam lengths before / after)"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
V = "physical/ref_tile/hgi_seq_{0}/views/ot_hgi_seq_{0}/ot_hgi_seq_{0}.lef"
ORG = {"fe": (43.2, 561.6), "be": (302.4, 561.6), "au": (43.2, 777.6)}


def lef(k):
    W = H = None; pins = {}; pin = None; lay = None
    for ln in (ROOT / V.format(k)).read_text().splitlines():
        s = ln.split()
        if not s: continue
        if s[0] == "SIZE": W, H = float(s[1]), float(s[3])
        elif s[0] == "PIN": pin = s[1]
        elif s[0] == "USE" and s[1] != "SIGNAL": pin = None
        elif s[0] == "OBS": pin = None
        elif s[0] == "LAYER": lay = s[1]
        elif s[0] == "RECT" and pin and pin not in pins:
            x = (float(s[1]) + float(s[3])) / 2; y = (float(s[2]) + float(s[4])) / 2
            d = {"W": x, "E": W - x, "S": y, "N": H - y}; f = min(d, key=d.get)
            pins[pin] = (f, lay, round(x if f in "SN" else y, 3))
    return W, H, pins


def main():
    (W, H, fe), (_, _, au), (_, _, be) = lef("fe"), lef("au"), lef("be")
    new = {}; used = {}; rep = []
    def take(pin, face, layer, c):
        k = (face, layer, round(c, 3)); assert k not in used, (pin, k, used[k]); used[k] = pin; new[pin] = (face, layer, round(c, 3))
    seam = {}
    for p, (f, l, c) in fe.items():
        if f == "N" and p in au and au[p][0] == "S": seam[p] = ("N", au[p][1], au[p][2], "au")
        elif f == "E" and p in be and be[p][0] == "W": seam[p] = ("E", be[p][1], be[p][2], "be")
    top = H - 2.0
    late = []
    for p, (f, l, c, o) in sorted(seam.items(), key=lambda kv: kv[1][2]):
        if f == "E" and c > top: late.append((c, p, l)); continue
        assert (f == "N" and 1.0 < c < W - 1.0) or f == "E", (p, c)
        take(p, f, l, c)
    def free(face, layer, c0, step, lo, hi):
        k = 0
        while True:
            for sg in ((1, -1) if k else (1,)):
                c = round(c0 + sg * k * step, 3)
                if lo <= c <= hi and (face, layer, c) not in used: return c
            k += 1; assert k < 20000
    pitch = {"M4": 0.048, "M5": 0.048, "M3": 0.036}
    for c, p, l in sorted(late, reverse=True):          # BE pins above FE's top edge: highest free FE tracks, order kept
        base = round(0.012 + 0.048 * round((top - 0.012) / 0.048), 3) if l == "M4" else top
        take(p, "E", l, free("E", l, base, pitch[l], 2.0, top))
    for p, (f, l, c) in sorted(fe.items()):
        if p in new: continue
        lim = (2.0, (W if f in "SN" else H) - 2.0)
        take(p, f, l, free(f, l, c, pitch[l], *lim))
    out = ["# generated by physical/hbm_accel_die_views/seq/mk_hgi_seq_fe_pins.py: FE seam pins on the tracks of the closed",
           "# AU (S face) / BE (W face) pins; other pins at their closed positions"]
    for p, (f, l, c) in sorted(new.items()):
        x, y = {"N": (c, H), "S": (c, 0.0), "E": (W, c), "W": (0.0, c)}[f]
        sz = "0.192 0.024" if f in "EW" else "0.024 0.192"
        out.append(f"place_pin -pin_name {{{p}}} -layer {l} -location {{{x} {y}}} -pin_size {{{sz}}} -force_to_die_boundary")
    (OUT / "hgi_seq_fe_pins.tcl").write_text("\n".join(out) + "\n")
    gap = {"au": ORG["au"][1] - ORG["fe"][1] - H, "be": ORG["be"][0] - ORG["fe"][0] - W}
    b = {}
    for p, (f, l, c, o) in seam.items():
        bus = re.sub(r"\[\d+\]", "", p); old = abs(fe[p][2] - c) + gap[o]; nw = abs(new[p][2] - c) + gap[o]
        e = b.setdefault(bus, dict(to=o, bits=0, L_before_um=0.0, L_after_um=0.0)); e["bits"] += 1
        e["L_before_um"] = round(max(e["L_before_um"], old), 1); e["L_after_um"] = round(max(e["L_after_um"], nw), 1)
    moved = sum(1 for p in fe if p not in seam and fe[p] != new[p])
    rec = dict(schema="opentallas.seq.fe_pin_align.v1", fe_outline=[W, H], gaps_um=gap, seam_pins=len(seam), buses=len(b),
               worst_L_before_um=max(e["L_before_um"] for e in b.values()), worst_L_after_um=max(e["L_after_um"] for e in b.values()),
               other_pins_moved=moved, pins=len(new), per_bus=dict(sorted(b.items())))
    (OUT / "hgi_seq_fe_pins.json").write_text(json.dumps(rec, indent=1) + "\n")
    print(f"FE pins {len(new)}: {len(seam)} seam pins on neighbour tracks ({len(late)} at the top of the E face), worst seam "
          f"{rec['worst_L_before_um']} -> {rec['worst_L_after_um']} um; {moved} other pins moved")


if __name__ == "__main__":
    main()
