def join(q):
    s2n, n2s = SEAM[q]
    decl = ',\n'.join(f'    {d} wire [{w-1}:0] {n}' for d, w, n in qports(q))
    mut = ''
    if q == 'se':
        mut = ('`ifdef MUT_SEAM\n    wire [%d:0] n2s_x = {n2s[%d:12], n2s[10], n2s[11], n2s[9:0]};   // seam tap bits 10/11 swapped\n'
               '`else\n    wire [%d:0] n2s_x = n2s;\n`endif\n') % (n2s - 1, n2s - 1, n2s - 1)
    else:
        mut = f'    wire [{n2s-1}:0] n2s_x = n2s;\n'
    return (f'// GENERATED by vm/split8/make_vm_split8.py: hfd_vm_{q} as its two 8-way sub-tiles (bench join; quadrant port list)\n'
            f'module hfd_vm_{q}_j8 (\n{decl}\n);\n    wire [{s2n-1}:0] s2n; wire [{n2s-1}:0] n2s;\n{mut}'
            f'    hfd_vm_{q}_s u_s (.*, .n2s(n2s_x));\n    hfd_vm_{q}_n u_n (.*);\nendmodule\n')

def tb():
    t = (TD / 'tb_vm_tiles.sv').read_text()
    t = t.replace('// r19 VM quadrant tiles joined vs the monolithic hfd_vm',
                  '// GENERATED by vm/split8/make_vm_split8.py from tiles/tb_vm_tiles.sv: `SPLIT8 = the 8 sub-tiles (via hfd_vm_<q>_j8)\n'
                  '// joined; MUT_SEAM (split8 only) swaps two SE seam tap bits.  Original header:\n// r19 VM quadrant tiles joined vs the monolithic hfd_vm')
    for q in ('sw', 'nw', 'se', 'ne'):
        t = t.replace(f'    hfd_vm_{q} u_{q} (', f'    `VMQ({q}) u_{q} (')
    t = t.replace('module vm_joined', '`ifdef SPLIT8\n`define VMQ(q) hfd_vm_``q``_j8\n`define SWH .u_n\n`else\n`define VMQ(q) hfd_vm_``q\n'
                  '`define SWH\n`endif\nmodule vm_joined', 1)
    t = t.replace('`define VM_CFG u.u_sw.cfg', '`define VM_CFG u.u_sw`SWH.cfg')
    t = t.replace('`define VM_ROOT u.u_sw.u_mr.on', '`define VM_ROOT u.u_sw`SWH.u_mr.on')
    t = t.replace('`define VM_RT u.u_sw.u_mr', '`define VM_RT u.u_sw`SWH.u_mr')
    assert t.count('`VMQ(') == 4 and 'u.u_sw`SWH.u_mr' in t
    return t

def respread(pins):
    """VM8_PIN2 (hbm-blocks 2026-10-07): every external E / W face of a half re-placed at 2 tracks (0.096 um) a bit when
    the face's bits fit the half's edge, port order kept, centred on the original centroid; N / S faces likewise along
    the width.  The quadrant generator packs these faces at 1 track a bit (vm8 nws: qNW + iNW = 1,094 pins in 53 um on M4
    -> GRT overflow 72,652, 6,386 gcells at that corner; nwn / sen the same at their W faces)."""
    def face(x, y, sz):
        vert = float(sz.split()[0]) < float(sz.split()[1])          # N / S pins are taller than wide
        if vert:
            return 'S' if y < 1.0 else 'N' if y > HH - 1.0 else None
        return 'W' if x < 1.0 else 'E' if x > QW - 1.0 else None
    byf = {}
    for i, (p, b, ly, x, y, sz) in enumerate(pins):
        f = face(x, y, sz)
        if f:
            byf.setdefault(f, []).append(i)
    out = list(pins)
    for f, idx in byf.items():
        along = (lambda t: t[4]) if f in 'EW' else (lambda t: t[3])
        idx.sort(key=lambda i: along(pins[i]))
        L = HH if f in 'EW' else QW
        step = 2 * PITCH
        ports = []                                  # (port, [indices]) in face order
        for i in idx:
            if not ports or ports[-1][0] != pins[i][0]:
                ports.append((pins[i][0], []))
            ports[-1][1].append(i)
        gap = 4 * PITCH
        span = len(idx) * step + gap * (len(ports) - 1)
        if span > L - 4.0:
            continue                                # does not fit at 2 tracks: keep the generator's packing
        c = sum(along(pins[i]) for i in idx) / len(idx)
        start = min(max(c - span / 2, 2.0), L - 2.0 - span)
        ph = along(pins[idx[0]]) % PITCH
        pos = round((start - ph) / PITCH) * PITCH + ph
        for pn, ii in ports:
            for i in ii:
                p, b, ly, x, y, sz = pins[i]
                if f in 'EW':
                    out[i] = (p, b, ly, x, round(pos, 4), sz)
                else:
                    out[i] = (p, b, ly, round(pos, 4), y, sz)
                pos += step
            pos += gap - step + step
    return out

def rst_free(pins):
    """move rst to the nearest free 0.096 um slot of its face when a re-spread pin covers it"""
    r = [i for i, t in enumerate(pins) if t[0] == 'rst']
    if not r:
        return pins
    i = r[0]; p, b, ly, x, y, sz = pins[i]
    ew = x < 1.0 or x > QW - 1.0
    taken = sorted((t[4] if ew else t[3]) for j, t in enumerate(pins) if j != i and abs((t[3] if ew else t[4]) - (x if ew else y)) < 1.0)
    v = y if ew else x
    L = HH if ew else QW
    def free(u):
        return 1.0 <= u <= L - 1.0 and all(abs(u - w) > 0.3 for w in taken)
    k = 0
    while not free(v + k * 2 * PITCH) and not free(v - k * 2 * PITCH):
        k += 1
        assert k < 20000, 'no free rst slot'
    v = v + k * 2 * PITCH if free(v + k * 2 * PITCH) else v - k * 2 * PITCH
    pins = list(pins)
    pins[i] = (p, b, ly, x, round(v, 4), sz) if ew else (p, b, ly, round(v, 4), y, sz)
    return pins

def pin_lines(q, h, tmp):
    """io_place.tcl lines of one half from the quadrant's generator pins"""
    src = Path(tmp) / f'hfd_vm_{q}' / 'io_place.tcl'
    names = {n for _, _, n in half_ports(q, h)}
    out, used = [], {}
    for l in src.read_text().splitlines():
        m = re.match(r'place_pin -pin_name \{(\w+)\[(\d+)\]\} -layer (\w+) -location \{([\d.]+) ([\d.]+)\} -pin_size \{(.*)\}', l)
        if not m:
            continue
        p, b, ly, x, y, sz = m.group(1), int(m.group(2)), m.group(3), float(m.group(4)), float(m.group(5)), m.group(6)
        if p not in names or p in ('ck', 'rst'):
            continue
        if h == 'n':
            y -= DY
        elif 493.0 < y < 506.5:                     # E/W ctl input group: into the south half
            y -= 6.24
        assert 0.0 <= y <= HH, (q, h, p, y)
        out.append((p, b, ly, x, y, sz))
    if os.environ.get('VM8_PIN2', '') == '1':
        out = respread(out)
    # (VM8_PIN2) rst keeps its spot unless a re-spread face pin sits on it: then the nearest free track on its face
    # ck (area, centre M7), rst (quadrant pin in the south half; inner face y=480 in the north half)
    out.append(('ck', 0, 'M7', 349.648, round(HH / 2, 4), '0.0640 0.2880'))
    orig_rst = [l for l in src.read_text().splitlines() if '{rst[0]}' in l][0]
    m = re.search(r'-layer (\w+) -location \{([\d.]+) ([\d.]+)\} -pin_size \{(.*)\}', orig_rst)
    if h == 's' and q == 'nw':     # r23v k16 bundled view: the quadrant S-face rst (698.94) collides with the t_s_wr run
        out.append(('rst', 0, 'M4', 0.096, 480.0, '0.1920 0.0240'))   # free W-face spot (iNW / qNW end at y 53.3)
    elif h == 's':
        out.append(('rst', 0, m.group(1), float(m.group(2)), float(m.group(3)), m.group(4)))
    else:
        out.append(('rst', 0, 'M4', 699.72 if q in ('sw', 'nw') else 0.096, 480.0, '0.1920 0.0240'))
    # seam: top edge of the south half / bottom edge of the north half, same x per bit (abutted straight wires), M5
    if os.environ.get('VM8_PIN2', '') == '1':
        out = rst_free(out)
    s2n, n2s = SEAM[q]
    x0 = round(QW / 2 - (s2n + n2s) * PITCH / 2, 3)
    x0 = round(round(x0 / PITCH) * PITCH, 3)
    ys = HH - 0.096 if h == 's' else 0.096
    k = 0
    for p, w in (('s2n', s2n), ('n2s', n2s)):
        for b in range(w):
            out.append((p, b, 'M5', round(x0 + k * PITCH, 4), ys, '0.0240 0.1920')); k += 1
    return out

def write_ports(q, h, tmp):
    m = f'hfd_vm_{q}_{h}'
    pins = pin_lines(q, h, tmp)
    od = D / 'ports' / m; od.mkdir(parents=True, exist_ok=True)
    (od / 'io_place.tcl').write_text(f'# {m}: 8-way VM sub-tile pins (make_vm_split8.py; external pins from the r22 quadrant hfd_vm_{q})\n' +
        ''.join(f'place_pin -pin_name {{{p}[{b}]}} -layer {ly} -location {{{x:.4f} {y:.4f}}} -pin_size {{{sz}}}\n'
                for p, b, ly, x, y, sz in pins))
    ports = {}
    for d, w, n in half_ports(q, h):
        pp = [(p, b, ly, x, y) for p, b, ly, x, y, _ in pins if p == n]
        assert len(pp) == w, (m, n, len(pp), w)
        xs, ys = [t[3] for t in pp], [t[4] for t in pp]
        ports[n] = {'bits': w, 'direction': d, 'layer': pp[0][2], 'x': [min(xs), max(xs)], 'y': [min(ys), max(ys)]}
    (od / 'ports.json').write_text(json.dumps({'master': m, 'kind': 'vm8', 'w_um': QW, 'h_um': HH, 'obs_top': 7,
        'parent': f'hfd_vm_{q}', 'half': h, 'generator': 'physical/hbm_accel_die_views/vm/split8/make_vm_split8.py',
        'ports': ports}, indent=1) + '\n')

