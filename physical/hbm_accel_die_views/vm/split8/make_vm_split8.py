def qports(q):
    """quadrant port declarations, in order: [(dir, width, name)]"""
    out = []
    for l in (TD.parent / f'split_r19/hfd_vm_{q}/ports.svh').read_text().splitlines():
        m = re.match(r'\s*(input|output) wire \[(\d+):0\] (\w+),?', l)
        if m:
            out.append((m.group(1), int(m.group(2)) + 1, m.group(3)))
    return out

