SEAM = {'sw': (2817, 5401), 'nw': (2881, 285), 'se': (1078, 3855), 'ne': (2063, 1399)}     # (s2n, n2s) widths

def half_ports(q, h):
    s2n, n2s = SEAM[q]
    ps = [('input', 1, 'ck'), ('input', 1, 'rst')]
    ps += [p for p in qports(q) if p[2] not in ('ck', 'rst') and ((p[2] in NORTH[q]) == (h == 'n'))]
    ps += [('output', s2n, 's2n'), ('input', n2s, 'n2s')] if h == 's' else [('input', s2n, 's2n'), ('output', n2s, 'n2s')]
    return ps

class H(mt.T):
    def __init__(s, q, h):
        s.t, s.L, s.n = f'{q}_{h}', [], 0
        s.ports = half_ports(q, h)
        decl = ',\n'.join(f'    {d} wire [{w-1}:0] {n}' for d, w, n in s.ports)
        s.L.append(f'// GENERATED by vm/split8/make_vm_split8.py (see there): 8-way VM sub-tile hfd_vm_{q}_{h}')
        s.L.append(f'module hfd_vm_{q}_{h} (\n{decl}\n);')
        s.L += ['    wire clk = ck[0];', '    reg [1:0] rst_s; always @(posedge clk) rst_s <= {rst_s[0], rst[0]};',
                '    wire rst_n = ~rst_s[1];']
    def zero(s, *ps):
        for p in ps:
            w = dict((n, w) for _, w, n in s.ports)[p]
            s.a(f"assign {p} = {w}'d0;")

def qf(s, q, hi68, i):   # q face: {2'd0, f_su[2047:1980], i[511:0]}, q[581:580] forwarded clocks
    s.out(f'q{q}', 582, NF, f"{{2'd0, {hi68}, {i}}}", fclk=(580, 581))

