"""VM 8-way FALLBACK (OWNER 2026-10-07; CLAUDE hbm-vm-split8): each r22 VM quadrant tile hfd_vm_<q> (700 x 1,000 um) is cut at
y = 500 into a south and a north sub-tile hfd_vm_<q>_s / hfd_vm_<q>_n (699.816 x 500.04 um each, centre M7 clock pin), joined by
one registered SEAM bus pair (s2n / n2s: launched from a kept pin register ot_hfd_oreg1 at the sender's seam pin, captured in a
register at the receiver's seam pin = +2 cycles per seam crossing, like every r19 cross bus).  The VM logic is the quadrant's
(make_vm_tiles.py), only partitioned: every external die port keeps its quadrant pin (north half: y - 500.016; the E/W ctl
input groups at y 493.9-506.1 shift 6.24 um south into the south half); each half gets its own rst pin (2-flop sync).

Partition (zero-cost placement of the slices: the root's read waits for its slowest slice, NE via SE = 8 cycles):
  SW_s  die face W (f_su_SW, iSW -> qSW, xSW, t_su_SW, t_router) + the SW slice (6 macros; cmd/return over the seam: 4 < 8)
  SW_n  multicast root, cfg chain, read assembly, N + E cross buses
  NW_s  S cross buses + NW slice (6 macros) + iNW / qNW;   NW_n  f_su_NW, xNW, t_su_NW, t_quant, E cross buses
  SE_s  die face E (f_su_SE, iSE, qSE, xSE, t_su_SE) + f_w_ctl;   SE_n  W + N cross buses + SE slice (6 macros)
  NE_s  S cross buses + NE slice (4 macros) + iNE / qNE;   NE_n  f_su_NE, xNE, t_su_NE, W cross buses
Root port depth (vm_wr_skew_finding.md): wr_v / bank / addr / owner / data_hi cross the NW seam once (+2), wr_data[2047:0]
crosses the SW seam once (+2): the write port stays ONE depth (7); the read port (f_su_SE[200:0]) crosses the SE seam (+2).
Cost (bench mode 2, 8-way vs 4-tile per output bit, run_vm_split8.sh): +2 on every path that crosses one seam.
    python3 make_vm_split8.py      (writes hfd_vm_<q>_{s,n}.sv, hfd_vm_<q>_j8.sv, tb_vm_split8.sv, ports/<master>/*, *_face_stages.tcl)"""
