#!/usr/bin/env python3
"""r19 VM quadrant tiles (views agent, 2026-10-07) on the coordinator's split ports (../split_r19/<tile>/ports.svh).

Function = the monolithic hfd_vm (rtl/hfd_vm.sv): the multicast root runs in hfd_vm_sw as ot_hfd_vm_root_x (make_root_x.py:
its 22 SRAMs moved out), the row store is split by macro column, 3 / 3 / 3 / 2 columns x 2 banks per tile (SW 0-2,
NW 3-5, SE 6-8, NE 9-10: 6 / 6 / 6 / 4 macros); the root's per-op memory command travels on the *_wr buses, slices
return on the *_row buses, the published row (tap data) streams on the *_row buses to every x face.  Placeholder paths
of the monolithic wrapper (no VM function: f_su_* -> t_su_* / t_quant / t_router, q faces) keep their exact bit maps,
carried on spare bus capacity (f_su_SW -> t_su_SE: 1,230 b direct SW->SE, 818 b via NW -> NE -> SE).
Stages: die faces 3 in / 3 out (tiles <= 1 mm), every cross bus registered at both pins (1 + 1), slice command and
read data registered at the macros.  Every logical root port has ONE stage depth from its die pins (wr 5, rd 5; tb MODE 3).  Cycle cost vs monolithic: priced per path by the bench (tb_vm_tiles.sv).
    python3 make_vm_tiles.py            (writes hfd_vm_<t>.sv, <t>_face_stages.tcl, ot_hfd_vm_slice.sv here)"""
from pathlib import Path
D = Path(__file__).resolve().parent
NF = 3          # die face stages in / out
TAPW = 2063
SL = dict(sw=(0, 3), nw=(3, 3), se=(6, 3), ne=(9, 2))      # (first column, columns)

def ports(t):
    return (D.parent / f'split_r19/hfd_vm_{t}/ports.svh').read_text()

class T:
    def __init__(s, t):
        s.t, s.L, s.n = t, [], 0
        s.L.append(f'// GENERATED by make_vm_tiles.py (see there): r19 VM quadrant tile hfd_vm_{t}')
        s.L.append(f'module hfd_vm_{t} (\n' + ports(t).rstrip().rstrip(',') + '\n);')
        s.L += ['    wire clk = ck[0];', '    reg [1:0] rst_s; always @(posedge clk) rst_s <= {rst_s[0], rst[0]};',
                '    wire rst_n = ~rst_s[1];']
    def a(s, x): s.L.append('    ' + x)
    def inp(s, p, w, n):           # input chain of n stages -> i_<p>
        prev = p
        for k in range(n - 1):
            s.a(f'reg [{w-1}:0] i{k}_{p}; always @(posedge clk) i{k}_{p} <= {prev};'); prev = f'i{k}_{p}'
        s.a(f'reg [{w-1}:0] i_{p}; always @(posedge clk) i_{p} <= {prev};')
    def out(s, p, w, n, expr, fclk=()):   # output through per-bit ot_hfd_oreg<n>; fclk bits driven by kept inverters
        s.a(f'wire [{w-1}:0] od_{p} = {expr};'); s.a(f'wire [{w-1}:0] o_{p};')
        s.a(f'for (genvar k = 0; k < {w}; k = k + 1) begin : g_o_{p}')
        s.a(f'    ot_hfd_oreg{n} u (.clk(clk), .d(od_{p}[k]), .q(o_{p}[k]));'); s.a('end')
        for k in range(w):
            if k in fclk:
                s.n += 1; s.a(f'wire fclk_{s.n}; ot_fwd_clk_inv u_fclk_{s.n} (.a(clk), .y(fclk_{s.n})); assign {p}[{k}] = fclk_{s.n};')
        if fclk:
            s.a(f'for (genvar k = 0; k < {min(fclk)}; k = k + 1) begin : g_a_{p} assign {p}[k] = o_{p}[k]; end')
        else:
            s.a(f'assign {p} = o_{p};')
    def text(s): return '\n'.join(s.L + ['endmodule']) + '\n'

def cat(parts, w):            # parts: list of (lsb, width, expr) -> {..} of width w, zero filled
    parts = sorted(parts); bits, pos = [], 0
    for lsb, wd, e in parts:
        assert lsb >= pos, (lsb, pos)
        if lsb > pos: bits.append(f"{lsb-pos}'d0")
        bits.append(e); pos = lsb + wd
    assert pos <= w, (pos, w)
    if pos < w: bits.append(f"{w-pos}'d0")
    return '{' + ', '.join(reversed(bits)) + '}'

def slice_inst(s, t, cmd_v, we, bank, addr, wd, rv, rd):
    c0, nc = SL[t]
    s.a(f'wire {rv}; wire [{nc*256-1}:0] {rd};')
    s.a(f'ot_hfd_vm_slice #(.NM({nc})) u_slice (.clk(clk), .rst_n(rst_n), .cmd_v({cmd_v}), .we({we}), .bank({bank}), .addr({addr}), .wd({wd}), .rv({rv}), .rd({rd}));')

def cross_in(s, p, w): s.a(f'reg [{w-1}:0] x_{p}; always @(posedge clk) x_{p} <= {p};')
def cross_out(s, p, w, expr): s.out(p, w, 1, expr)

W, R, C = 2264, 2256, 256
CMD = lambda src: [(0, 1, f'{src}_v'), (1, 1, f'{src}_we'), (2, 1, f'{src}_bank'), (3, 7, f'{src}_addr')]

def q_face(s, q):   # monolithic: od_q = {2'd0, i_f_su_X[2047:1980], i_iX[511:0]}, q[580:581] forwarded clocks
    s.out(f'q{q}', 582, NF, f"{{2'd0, i_f_su_{q}[2047:1980], i_i{q}[511:0]}}", fclk=(580, 581))
def x_face(s, q, tap):
    s.out(f'x{q}', 2068, NF, f"{{5'd0, {tap}}}", fclk=(2063, 2064, 2065, 2066, 2067))

def sw():
    s = T('sw')
    s.inp('f_su_SW', 2048, NF); s.inp('iSW', 512, NF)
    for p, w in (('f_n_wr', W), ('f_n_row', R), ('f_e_wr', W), ('f_e_row', R)): cross_in(s, p, w)
    s.a('// configuration chain (monolithic: 772 bits from f_su_NE[0]; here relayed NE -> SE -> SW on the wr buses)')
    s.a('reg [771:0] cfg; always @(posedge clk) cfg <= {cfg[770:0], x_f_e_wr[1791]};')
    s.a('// write port depth (coordinator vm_wr_skew_finding.md): wr_v / bank / addr / owner / data[2062:2048] reach the root over')
    s.a('// f_su_NW (3 face stages in NW) + the NW -> SW wr bus (1 + 1) = 5; wr_data[2047:0] arrives on f_su_SW (3 face stages):')
    s.a('// two more registers so every field of the logical write port has ONE depth (5) at the root (0 cycles: wr_v is at 5)')
    s.a('reg [2047:0] wd0_f_su_SW, wd_f_su_SW; always @(posedge clk) begin wd0_f_su_SW <= i_f_su_SW; wd_f_su_SW <= wd0_f_su_SW; end')
    s.a('wire m_v, m_we, m_bank; wire [6:0] m_addr; wire [2815:0] m_wd; wire m_rd_v; wire [2815:0] m_rd;')
    s.a('wire wr_ready, wr_ACK_v, rd_ready, native_release, drained, fault; wire [3:0] tap_v; wire [191:0] wr_ACK_owner;')
    s.a('wire [767:0] tap_owner; wire [4*2063-1:0] tap_data;')
    s.a('ot_hfd_vm_root_x #(.ENABLE(1)) u_mr (.clk(clk), .por_n(rst_n), .mem_cmd_v(m_v), .mem_cmd_we(m_we), .mem_cmd_bank(m_bank), '
        '.mem_cmd_addr(m_addr), .mem_wd(m_wd), .mem_rd_v(m_rd_v), .mem_rd(m_rd), '
        '.wr_v(x_f_n_wr[15]), .wr_ready(wr_ready), .wr_bank(x_f_n_wr[16]), .wr_addr(x_f_n_wr[23:17]), '
        '.wr_data({x_f_n_wr[14:0], wd_f_su_SW[2047:0]}), .wr_owner(x_f_n_wr[215:24]), .wr_ACK_v(wr_ACK_v), '
        '.wr_ACK_ready(x_f_n_wr[216]), .wr_ACK_owner(wr_ACK_owner), .rd_v(x_f_e_wr[0]), .rd_ready(rd_ready), '
        '.rd_bank(x_f_e_wr[1]), .rd_addr(x_f_e_wr[8:2]), .rd_owner(x_f_e_wr[200:9]), .tap_v(tap_v), .tap_ready(4\'d15), '
        '.tap_data(tap_data), .tap_owner(tap_owner), .tap_ACK_v(cfg[3:0]), .tap_ACK_owner(cfg[771:4]), '
        '.native_release(native_release), .drained(drained), .fault(fault));')
    s.a('// root memory command: local slice (columns 0-2) at the root, the others on the wr buses')
    s.a('reg c_v, c_we, c_bank; reg [6:0] c_addr; reg [767:0] c_wd;')
    s.a('always @(posedge clk) begin c_v <= m_v && rst_n; c_we <= m_we; c_bank <= m_bank; c_addr <= m_addr; c_wd <= m_wd[767:0]; end')
    slice_inst(s, 'sw', 'c_v', 'c_we', 'c_bank', 'c_addr', 'c_wd', 's0_v', 's0_d')
    s.a('// read row assembly: one op outstanding; every slice returns once per read')
    s.a('reg [3:0] got; reg [2815:0] hold;')
    s.a('wire [3:0] arr = {x_f_e_row[769], x_f_e_row[0], x_f_n_row[0], s0_v};')
    s.a('wire [3:0] got_nx = got | arr;')
    s.a('assign m_rd_v = &got_nx;')
    s.a('assign m_rd = {arr[3] ? x_f_e_row[1281:770] : hold[2815:2304], arr[2] ? x_f_e_row[768:1] : hold[2303:1536], '
        'arr[1] ? x_f_n_row[768:1] : hold[1535:768], arr[0] ? s0_d : hold[767:0]};')
    s.a('always @(posedge clk or negedge rst_n) if (!rst_n) got <= 0; else got <= m_rd_v ? 4\'d0 : got_nx;')
    s.a('always @(posedge clk) hold <= m_rd;')
    cmd = CMD('m')
    cross_out(s, 't_n_wr', W, cat(cmd + [(10, 768, 'm_wd[1535:768]'), (778, 818, 'i_f_su_SW[2047:1230]')], W))
    cross_out(s, 't_e_wr', W, cat(cmd + [(10, 768, 'm_wd[2303:1536]'), (778, 512, 'm_wd[2815:2304]'),
                                         (1290, 974, 'i_f_su_SW[973:0]')], W))
    cross_out(s, 't_e_ctl', C, 'i_f_su_SW[1229:974]')
    cross_out(s, 't_n_row', R, cat([(0, TAPW, 'tap_data[2062:0]')], R))
    cross_out(s, 't_e_row', R, cat([(0, TAPW, 'tap_data[2062:0]')], R))
    s.a("assign t_n_ctl = 256'd0;")
    x_face(s, 'SW', 'tap_data[2062:0]'); q_face(s, 'SW')
    s.out('t_su_SW', 2048, NF, '{x_f_e_wr[1278:201], tap_owner[767:0], wr_ACK_owner[191:0], tap_v[3:0], fault, drained, '
          'native_release, rd_ready, wr_ACK_v, wr_ready}')
    s.out('t_router', 512, NF, 'x_f_e_wr[1790:1279]')
    return s

def nw():
    s = T('nw')
    s.inp('f_su_NW', 2048, NF); s.inp('iNW', 512, NF)
    for p, w in (('f_s_wr', W), ('f_s_row', R), ('f_e_row', R)): cross_in(s, p, w)
    slice_inst(s, 'nw', 'x_f_s_wr[0]', 'x_f_s_wr[1]', 'x_f_s_wr[2]', 'x_f_s_wr[9:3]', 'x_f_s_wr[777:10]', 'sv', 'sd')
    cross_out(s, 't_s_wr', W, cat([(0, 217, 'i_f_su_NW[216:0]')], W))
    cross_out(s, 't_s_row', R, cat([(0, 1, 'sv'), (1, 768, 'sd')], R))
    cross_out(s, 't_e_wr', W, cat([(0, 818, 'x_f_s_wr[1595:778]')], W))
    cross_out(s, 't_e_row', R, cat([(0, 2048, 'i_f_su_NW[2047:0]')], R))
    s.a("assign t_s_ctl = 256'd0; assign t_e_ctl = 256'd0;")
    x_face(s, 'NW', 'x_f_s_row[2062:0]'); q_face(s, 'NW')
    s.out('t_su_NW', 2048, NF, 'x_f_e_row[2047:0]')
    s.out('t_quant', 1024, NF, 'x_f_e_row[1023:0]')
    return s

def se():
    s = T('se')
    s.inp('f_su_SE', 2048, NF); s.inp('iSE', 512, NF)
    for p, w in (('f_w_wr', W), ('f_w_row', R), ('f_w_ctl', C), ('f_n_wr', W), ('f_n_row', R)): cross_in(s, p, w)
    slice_inst(s, 'se', 'x_f_w_wr[0]', 'x_f_w_wr[1]', 'x_f_w_wr[2]', 'x_f_w_wr[9:3]', 'x_f_w_wr[777:10]', 'sv', 'sd')
    cross_out(s, 't_n_wr', W, cat([(0, 10, 'x_f_w_wr[9:0]'), (10, 512, 'x_f_w_wr[1289:778]')], W))
    cross_out(s, 't_n_row', R, cat([(0, TAPW, 'x_f_w_row[2062:0]')], R))
    cross_out(s, 't_w_wr', W, cat([(0, 201, 'i_f_su_SE[200:0]'), (201, 1078, 'i_f_su_SE[1077:0]'),
                                    (1279, 512, 'x_f_n_wr[511:0]'), (1791, 1, 'x_f_n_wr[512]')], W))
    cross_out(s, 't_w_row', R, cat([(0, 1, 'sv'), (1, 768, 'sd'), (769, 1, 'x_f_n_row[0]'), (770, 512, 'x_f_n_row[512:1]')], R))
    s.a("assign t_n_ctl = 256'd0; assign t_w_ctl = 256'd0;")
    x_face(s, 'SE', 'x_f_w_row[2062:0]'); q_face(s, 'SE')
    s.out('t_su_SE', 2048, NF, '{x_f_n_wr[1330:513], x_f_w_ctl[255:0], x_f_w_wr[2263:1290]}')
    return s

def ne():
    s = T('ne')
    s.inp('f_su_NE', 2048, NF); s.inp('iNE', 512, NF)
    for p, w in (('f_s_wr', W), ('f_s_row', R), ('f_w_wr', W), ('f_w_row', R)): cross_in(s, p, w)
    slice_inst(s, 'ne', 'x_f_s_wr[0]', 'x_f_s_wr[1]', 'x_f_s_wr[2]', 'x_f_s_wr[9:3]', 'x_f_s_wr[521:10]', 'sv', 'sd')
    cross_out(s, 't_s_row', R, cat([(0, 1, 'sv'), (1, 512, 'sd')], R))
    cross_out(s, 't_s_wr', W, cat([(0, 512, 'i_f_su_NE[1535:1024]'), (512, 1, 'i_f_su_NE[0]'), (513, 818, 'x_f_w_wr[817:0]')], W))
    cross_out(s, 't_w_row', R, cat([(0, 2048, 'i_f_su_NE[2047:0]')], R))
    s.a("assign t_s_ctl = 256'd0; assign t_w_ctl = 256'd0; assign t_w_wr = 2264'd0;")
    x_face(s, 'NE', 'x_f_s_row[2062:0]'); q_face(s, 'NE')
    s.out('t_su_NE', 2048, NF, 'x_f_w_row[2047:0]')
    return s

SLICE = '''// GENERATED by make_vm_tiles.py: one tile's column slice of the VM row store (NM macro columns x 2 banks of
// ot_sram_1r1w_128x256_m1_r2c2, the monolithic root's macros); command registered at the macros, read data registered at
// the macro outputs (rv one cycle after the macro read cycle).
module ot_hfd_vm_slice #(parameter integer NM = 3) (
    input wire clk, input wire rst_n, input wire cmd_v, input wire we, input wire bank, input wire [6:0] addr,
    input wire [NM*256-1:0] wd, output wire rv, output wire [NM*256-1:0] rd);
    reg c_v, c_we, c_b; reg [6:0] c_a; reg [NM*256-1:0] c_wd;
    always @(posedge clk or negedge rst_n) if (!rst_n) c_v <= 1'b0; else c_v <= cmd_v;
    always @(posedge clk) begin c_we <= we; c_b <= bank; c_a <= addr; c_wd <= wd; end
    wire [NM*256-1:0] q [0:1];
    for (genvar b = 0; b < 2; b = b + 1) begin : banks
        for (genvar m = 0; m < NM; m = m + 1) begin : macros
            ot_sram_1r1w_128x256_m1_r2c2 u_sram (.clk(clk), .r_ce_in(c_v && !c_we && c_b == 1'(b)), .r_addr_in(c_a),
                .rd_out(q[b][m*256 +: 256]), .w_ce_in(c_v && c_we && c_b == 1'(b)), .w_addr_in(c_a), .wd_in(c_wd[m*256 +: 256]),
                .w_mask_in({256{1'b1}}), .rr_en(2'b0), .rr_addr(14'b0), .cr_en(2'b0), .cr_sel(16'b0));
        end
    end
    reg r1_v, r1_b, rv_q; reg [NM*256-1:0] rd_q;
    always @(posedge clk or negedge rst_n) if (!rst_n) begin r1_v <= 1'b0; rv_q <= 1'b0; end
                                           else begin r1_v <= c_v && !c_we; rv_q <= r1_v; end
    always @(posedge clk) begin r1_b <= c_b; rd_q <= r1_b ? q[1] : q[0]; end
    assign rv = rv_q; assign rd = rd_q;
endmodule
'''

if __name__ == '__main__':
    (D / 'ot_hfd_vm_slice.sv').write_text(SLICE)
    for f in (sw, nw, se, ne):
        s = f(); (D / f'hfd_vm_{s.t}.sv').write_text(s.text())
        (D / f'hfd_vm_{s.t}_face_stages.tcl').write_text('# generated by make_vm_tiles.py: die port -> face chain depth\n' +
            ''.join(f'set fc_ps({p}) {1 if p.startswith(("f_n_", "f_s_", "f_e_", "f_w_", "t_n_", "t_s_", "t_e_", "t_w_")) else NF}\n'
                    for p in [l.split()[-1].rstrip(',') for l in ports(s.t).splitlines() if 'wire' in l]
                    if p not in ('ck', 'rst')))
    print('ok')
