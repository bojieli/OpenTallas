#!/usr/bin/env python3
"""[vm8 FACE3 2026-10-13] make_root_p.py: writes ot_hfd_vm_root_p.sv, the PIPELINED VM multicast root.

The W6 SECDED functions are taken verbatim from ot_hfd_vm_root_x.sv (encode64; decode64 split into its syndrome and its
correction so a register can sit between them).  Everything else is the template below.
    python3 make_root_p.py
"""
import re
from pathlib import Path

D = Path(__file__).resolve().parent
x = (D / 'ot_hfd_vm_root_x.sv').read_text()
enc = re.search(r' function \[71:0\] encode64.*?endfunction', x, re.S).group(0)
dec = re.search(r' function \[65:0\] decode64.*?endfunction', x, re.S).group(0)
s_expr = re.search(r'\n   s=(\{.*?\}); ov=\^code;', dec, re.S).group(1)
dmap = re.search(r'decode64=\{ue,cor,(\{.*?\})\};', dec, re.S).group(1)
assert s_expr.count('^{') == 7 and dmap.count('c[') == 64

T = r'''// GENERATED by make_root_p.py ([vm8 FACE3 2026-10-13] pipelined VM multicast root; SECDED functions from ot_hfd_vm_root_x.sv)
`timescale 1ns/1ps
`default_nettype none
// Same function as ot_hfd_vm_root_x (SEATP=1, FREG=1): two-bank 128-row activation store in the slice SRAMs, W6 SECDED on
// the seat / sampled row / validity / control, write ACKed only after SRAM read-back, read published to the taps after the
// owner check, sticky fault on any mismatch.  Re-timed for 833 ps (vm_cp_root-cp1-2370c0876: post-CTS TT -609 ps, 9,373
// failing endpoints = the classes below, not one path):
//   class (cp1)                                         here
//   in -> control_code, 18 levels (rd_v / wr_v pins)    request pins registered in the tile wrapper; the FSM reads flops
//   in -> seat enable, 2,592 loads from a pin           accept is a registered state (S_ACC); per-word replicated enables
//   seat -> decode -> compare -> chk_err_q (23 lv)      syndrome registers (sy_q / ssyn_q), per-word verdict registers
//                                                       (weq_q / sue_q), then the reduction: three stages
//   seat -> decode -> owner compare -> control_code     owner register own_q; tap ACK compare registered (av_q / aeq_q)
//   sample -> decode -> encode -> smp_enc_q -> seat     the read row is loaded into the seat AS READ (a valid or
//                                                       single-error code word; every use of the seat decodes it)
//   validity -> decode -> set bit -> encode             registered valid-bit lookup (vbit_q); the update XORs the code
//                                                       word of the one new bit (SECDED is linear)
//   state -> mem_cmd pins (unregistered)                four command registers at the four slice faces
//   seat -> decode -> tap_q -> two faces                one tap register rank per face, fed with RAW seat data bits
//                                                       (wire only, <= ~460 um); the seat scrubs itself in place
//   reset: 5,504 async loads on one flop                replicated synchronous resets, only where the value matters
// Pin registers: mem_wd = seat (each bit drives exactly one slice pin), mem_rd -> sampled (capture enable replicated per
// word), mem_cmd_o, tap_w / tap_e, st_o.  Request inputs are registered by the wrapper.
// CONTRACTS (checked): the slices return read data RDLAT = 3 cycles after the command is at their pins (command register,
// SRAM, output register); the capture cycle is fixed and S_SYN faults if the four rv pins were not all 1 in it.
// A request (valid + payload) must be held until it is served (ACK / tap_v): the root loads the seat from the request
// registers one cycle after it accepts.  The status path already forces this (ready returns over >= 6 registered hops).
// Cycles per operation: see the stage list at the FSM; the bench (run_vm_cp.sh) is transaction-level and latency-free.
module ot_hfd_vm_root_p #(parameter integer RSTN=11)(
 input wire clk, input wire [RSTN-1:0] rst_r,
 output wire [39:0] mem_cmd_o, output wire [2815:0] mem_wd, input wire [3:0] mem_rv_q, input wire [2815:0] mem_rd,
 input wire wr_v, input wire wr_bank, input wire [6:0] wr_addr, input wire [2062:0] wr_data, input wire [191:0] wr_owner,
 input wire wr_ACK_ready,
 input wire rd_v, input wire rd_bank, input wire [6:0] rd_addr, input wire [191:0] rd_owner,
 output wire [2062:0] tap_w, output wire [2062:0] tap_e,
 input wire [3:0] tap_ACK_v, input wire [4*192-1:0] tap_ACK_owner,
 output wire [201:0] st_o, output wire fault
);
@ENC@
 // syndrome {overall parity, s[6:0]} of a 72-bit code word (first half of decode64)
 function [7:0] syn64(input [71:0] code);
  begin syn64={^code,@SEXPR@}; end
 endfunction
 // uncorrectable: non-zero syndrome that is not a single-bit position with odd overall parity
 function ue64(input [7:0] sy);
  begin ue64=(sy[6:0]!=7'd0)&&!(sy[7]&&sy[6:0]<=7'd71); end
 endfunction
 // corrected 64 data bits (second half of decode64), from the code word and its REGISTERED syndrome
 function [63:0] fix64(input [71:0] code,input [7:0] sy);
  reg [71:0] c;
  begin
   c=code;
   if(sy[6:0]!=7'd0)begin if(sy[7]&&sy[6:0]<=7'd71)c=code^(72'd1<<(sy[6:0]-7'd1)); end
   else if(sy[7])c[71]=~c[71];
   fix64=@DMAP@;
  end
 endfunction
 localparam [71:0] PARITY_POS=72'h80_8000_0000_8000_808B;   // code bits 0,1,3,7,15,31,63,71
 generate if(1)begin:on
  localparam [4:0] S_IDLE=0,S_ACC=1,S_ENC=2,S_WR=3,S_RD=4,S_W0=5,S_W1=6,S_W2=7,S_CAP=8,S_SYN=9,S_CHK1=10,S_CHK2=11,
                   S_LOAD=12,S_LD2=13,S_P0=14,S_P1=15,S_PUB=16,S_WACK=17,S_P2=18;
  // ---- control (SECDED-checked through a two-stage registered decode) ------------------------------------------
  reg [4:0] state,ns; reg bank,nbank,is_write,nisw,sticky; reg [6:0] addr,naddr; reg [3:0] sent,nsent,acked,nacked;
  reg [71:0] control_code,cc_q; reg [7:0] csyn_q; reg [63:0] ctl_q;
  reg bad_cv_q,seat_bad_q,chk_err_q,vbit_q; reg [2:0] arm;
  wire armed=arm[2];
  wire [63:0] control={41'b0,sticky,is_write,bank,addr,sent,acked,state};
  reg err;
  assign fault=sticky||bad_cv_q||(state!=S_IDLE&&seat_bad_q);
  wire nsticky=sticky||fault||err;
  wire hold=fault||err;
  wire [63:0] next_control=hold?{41'b0,nsticky,is_write,bank,addr,sent,acked,state}:{41'b0,nsticky,nisw,nbank,naddr,nsent,nacked,ns};
  // ---- registered predicates -----------------------------------------------------------------------------------
  reg [3:0] av_q,aeq_q; reg [191:0] own_q;
  reg [35:0] weq_q,sue_q; reg o32_q,o35_q,z_q;
  // ---- big registers: seat (= mem_wd pin registers), sampled (= mem_rd pin registers) -------------------------------
  reg [36*72-1:0] seat; reg [36*72-1:0] sampled; reg [36*8-1:0] sy_q,ssyn_q;
  (* keep = "true", dont_touch = "true" *) reg [35:0] ldd_r,isw_r,ldp_r,lds_r,cap_r;
  reg [35:0] sv_q;   // sy_q[k] was computed from the PRESENT seat word (no write to it at the previous edge)
  wire [2303:0] raw_w={49'b0,wr_owner,wr_data},raw_r={49'b0,rd_owner,2063'b0};
  wire [2303:0] seat_data; wire [35:0] seat_ue;
  always @(posedge clk)begin
   ldd_r<={36{state==S_IDLE&&!fault&&(wr_v^rd_v)}}; isw_r<={36{wr_v&&!rd_v}};
   ldp_r<={36{state==S_ACC}}; lds_r<={36{state==S_LOAD&&!fault&&!chk_err_q&&!is_write}};
   cap_r<={36{state==S_W2&&!fault}};
  end
  for(genvar k=0;k<36;k=k+1)begin:w
   wire [71:0] sw=seat[k*72+:72],mw=sampled[k*72+:72];
   wire [63:0] rawk=isw_r[k]?raw_w[k*64+:64]:raw_r[k*64+:64];
   // self-scrub: a correctable seat word is rewritten in place (local to the word), so the tap / owner / status
   // registers on the far faces take the RAW seat data bits over a wire-only path; a read row with a single-bit
   // SRAM error is scrubbed in P1, before the taps are loaded (P2) and tap_v is raised (PUB)
   wire [7:0] sy=sv_q[k]?sy_q[k*8+:8]:8'd0;
   wire cor=(sy[6:0]!=7'd0)?(sy[7]&&sy[6:0]<=7'd71):sy[7];
   wire [71:0] flip=(sy[6:0]!=7'd0)?(72'd1<<(sy[6:0]-7'd1)):72'h80_0000_0000_0000_0000;
   always @(posedge clk)begin
    if(rst_r[2+k/4])seat[k*72+:72]<=72'd0;
    else if(ldd_r[k])seat[k*72+:72]<=encode64(rawk)&~PARITY_POS;        // data bits from the request registers
    else if(ldp_r[k])seat[k*72+:72]<=encode64(fix64(sw,8'd0));           // parity one cycle later, from the seat itself
    else if(lds_r[k])seat[k*72+:72]<=mw;                                 // read row, as read
    else if(cor)seat[k*72+:72]<=sw^flip;
    sv_q[k]<=!(rst_r[2+k/4]||ldd_r[k]||ldp_r[k]||lds_r[k]||cor);
    if(cap_r[k])sampled[k*72+:72]<=mem_rd[k*72+:72];
    sy_q[k*8+:8]<=ldp_r[k]?8'd0:syn64(sw);                               // the word is completed by this same edge
    ssyn_q[k*8+:8]<=syn64(mw);
   end
   wire [63:0] td=fix64(sw,sy),sd=fix64(mw,ssyn_q[k*8+:8]);
   assign seat_data[k*64+:64]=fix64(sw,8'd0); assign seat_ue[k]=ue64(sy_q[k*8+:8]);
   always @(posedge clk)begin weq_q[k]<=sd==td; sue_q[k]<=ue64(ssyn_q[k*8+:8]); end
   if(k==32)begin:o32 always @(posedge clk)o32_q<=sd[63:15]==td[63:15]; end
   if(k==35)begin:o35 always @(posedge clk)begin o35_q<=sd[14:0]==td[14:0]; z_q<=sd[63:15]==49'd0; end end
  end
  assign mem_wd={224'b0,seat};
  // ---- validity (authoritative coded valid bits, cold reset) -----------------------------------------------------
  reg [4*72-1:0] validity; reg [4*8-1:0] vsyn_q; wire [255:0] valid_bits; wire [3:0] valid_ue;
  for(genvar k=0;k<4;k=k+1)begin:v
   always @(posedge clk)vsyn_q[k*8+:8]<=syn64(validity[k*72+:72]);
   assign valid_bits[k*64+:64]=fix64(validity[k*72+:72],vsyn_q[k*8+:8]); assign valid_ue[k]=ue64(vsyn_q[k*8+:8]);
  end
  wire [7:0] row={bank,addr};
  wire vset=state==S_LOAD&&!fault&&!chk_err_q&&is_write&&!vbit_q;
  wire [71:0] vdelta=encode64(64'd1<<row[5:0]);
  always @(posedge clk)vbit_q<=valid_bits[row];
  for(genvar k=0;k<4;k=k+1)begin:vw
   always @(posedge clk)
    if(rst_r[1])validity[k*72+:72]<=72'd0;
    else if(vset&&row[7:6]==k)validity[k*72+:72]<=validity[k*72+:72]^vdelta;
  end
  // ---- pin registers: slice commands (one per slice face), taps (one rank per face), status -------------------------
  (* keep = "true", dont_touch = "true" *) reg [39:0] cmd_q;
  (* keep = "true", dont_touch = "true" *) reg [2062:0] tap_w_q,tap_e_q;
  reg [201:0] st_q;
  wire cmd_v=(state==S_WR||state==S_RD)&&!fault;
  wire wr_ready=state==S_IDLE&&!fault&&!rd_v,rd_ready=state==S_IDLE&&!fault&&!wr_v;
  wire wr_ACK_v=state==S_WACK&&!fault,drained=state==S_IDLE&&!fault,native_release=state==S_PUB&&(&acked)&&!fault;
  wire [3:0] tap_v={4{state==S_PUB&&!fault}}&~sent;
  always @(posedge clk)begin
   cmd_q<={4{addr,bank,state==S_WR,cmd_v}};
   tap_w_q<=seat_data[2062:0]; tap_e_q<=seat_data[2062:0]; own_q<=seat_data[2063+:192];
   st_q<={own_q,tap_v,fault,drained,native_release,rd_ready,wr_ACK_v,wr_ready};
   av_q<=tap_ACK_v;
   for(integer t=0;t<4;t=t+1)aeq_q[t]<=tap_ACK_owner[t*192+:192]==own_q;
  end
  assign mem_cmd_o=cmd_q; assign tap_w=tap_w_q; assign tap_e=tap_e_q; assign st_o=st_q;
  // ---- FSM: every input of the next-state function is a register -------------------------------------------------
  // write: IDLE ACC ENC WR RD W0 W1 W2 CAP SYN CHK1 CHK2 LOAD WACK      read: IDLE ACC ENC RD W0 W1 W2 CAP SYN CHK1 CHK2 LOAD LD2 P0 P1 P2 PUB
  //   ACC  seat data <- request registers          ENC  seat parity; read: the row must be valid (vbit_q)
  //   WR / RD  command register loaded (at the slice pins one cycle later: W0 for the read)
  //   CAP  read data at the pins, captured         SYN  syndromes; rv pin registers must be 1111
  //   CHK1 per-word verdicts   CHK2 reduction      LOAD write: validity + ACK; read: seat <- sampled (LD2)
  //   P0 P1  seat syndromes, scrub   P2  tap registers loaded          PUB  tap_v (tap data already at the pins)
  always @*begin
   ns=state;nbank=bank;naddr=addr;nisw=is_write;nsent=sent;nacked=acked;err=1'b0;
   if((|av_q)&&state!=S_PUB)err=1'b1;
   case(state)
    S_IDLE:begin
     nsent=4'd0;nacked=4'd0;
     if(wr_v&&!rd_v)begin nbank=wr_bank;naddr=wr_addr;nisw=1'b1;ns=S_ACC;end
     else if(rd_v&&!wr_v)begin nbank=rd_bank;naddr=rd_addr;nisw=1'b0;ns=S_ACC;end
    end
    S_ACC:ns=S_ENC;
    S_ENC:if(!is_write&&!vbit_q)err=1'b1;else ns=is_write?S_WR:S_RD;
    S_WR:ns=S_RD;
    S_RD:ns=S_W0;
    S_W0:ns=S_W1;
    S_W1:ns=S_W2;
    S_W2:ns=S_CAP;
    S_CAP:ns=S_SYN;
    S_SYN:if(!(&mem_rv_q))err=1'b1;else ns=S_CHK1;
    S_CHK1:ns=S_CHK2;
    S_CHK2:ns=S_LOAD;
    S_LOAD:if(chk_err_q)err=1'b1;else ns=is_write?S_WACK:S_LD2;
    S_LD2:ns=S_P0;
    S_P0:ns=S_P1;
    S_P1:ns=S_P2;
    S_P2:ns=S_PUB;
    S_WACK:if(wr_ACK_ready)ns=S_IDLE;
    S_PUB:begin
     nsent=4'hF;
     for(integer t=0;t<4;t=t+1)if(av_q[t])begin
      if(!sent[t]||acked[t]||!aeq_q[t])err=1'b1;else nacked[t]=1'b1;
     end
     if(&acked)ns=S_IDLE;
    end
    default:err=1'b1;
   endcase
  end
  wire [65:0] cdec={ue64(csyn_q),1'b0,fix64(cc_q,csyn_q)};
  always @(posedge clk)begin
   if(rst_r[0])begin
    state<=S_IDLE;bank<=1'b0;addr<=7'd0;is_write<=1'b0;sticky<=1'b0;sent<=4'd0;acked<=4'd0;control_code<=72'd0;
    bad_cv_q<=1'b0;seat_bad_q<=1'b0;chk_err_q<=1'b0;arm<=3'd0;
   end else begin
    sticky<=nsticky;control_code<=encode64(next_control);
    if(!hold)begin state<=ns;bank<=nbank;addr<=naddr;is_write<=nisw;sent<=nsent;acked<=nacked;end
    arm<={arm[1:0],1'b1};
    bad_cv_q<=armed&&(cdec[65]||cdec[63:0]!=ctl_q||(|valid_ue));
    seat_bad_q<=armed&&(|seat_ue);
    if(state==S_CHK2)chk_err_q<=(|sue_q)||!z_q||(is_write?!(&weq_q):!(o32_q&&weq_q[33]&&weq_q[34]&&o35_q));
   end
   cc_q<=control_code;csyn_q<=syn64(control_code);ctl_q<=control;
  end
 end endgenerate
endmodule
`default_nettype wire
'''
out = T.replace('@ENC@', enc).replace('@SEXPR@', s_expr).replace('@DMAP@', dmap)
(D / 'ot_hfd_vm_root_p.sv').write_text(out)
print('wrote ot_hfd_vm_root_p.sv', len(out.splitlines()), 'lines')
