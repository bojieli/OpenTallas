#!/usr/bin/env python3
"""Yosys copy of Codex's ot_hbm_die_vm_multicast_root (CLAUDE HBM-ABSTRACTS spine): ORFS yosys 0.68 asserts
(simplify.cc:4320) on any call of the ot_gpu_w6_secded_pkg loop-bodied functions, and on cell outputs driving an
unpacked-array slice.  This writes ot_hbm_die_vm_multicast_root.sv beside it with (1) the package import replaced by
module-local static (fully unrolled, constant-mask) encode64/decode64 that compute the same Hsiao/Hamming SECDED code,
(2) ram_q[0:1] flattened to ram_q_flat, (3) unnamed-block locals hoisted.  No other change; equivalence is a
Verilator lockstep bench of the original against this copy (tb_mroot_equiv.sv)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SRC = ROOT / 'physical/hbm_die_abstracts_20261006/memory_control/ot_hbm_die_vm_multicast_root.sv'
OUT = Path(__file__).with_name('ot_hbm_die_vm_multicast_root.sv')

# encode64 (package): data bits fill the non-power-of-two positions p=1..71 in order; parity bit (1<<k)-1 is the XOR
# of positions p with bit k set (p != 1<<k), computed on the data-filled word; c[71] = ^c[70:0].
pos = [p for p in range(1, 72) if p & (p - 1)]          # data position for data[j]
assert len(pos) == 64
enc = {}                                                 # code bit -> list of data bits
for j, p in enumerate(pos):
    enc[p - 1] = [j]
for k in range(7):
    enc[(1 << k) - 1] = [j for j, p in enumerate(pos) if p & (1 << k)]
# overall parity = XOR of all c[70:0] = XOR over data bits with odd multiplicity
cnt = {}
for b in range(71):
    for j in enc[b]:
        cnt[j] = cnt.get(j, 0) ^ 1
enc[71] = [j for j in range(64) if cnt.get(j)]


def x(bits, v):
    return '^{' + ','.join(f'{v}[{b}]' for b in bits) + '}' if bits else "1'b0"


E = '{' + ','.join(x(enc[b], 'data') if len(enc[b]) > 1 else f'data[{enc[b][0]}]' for b in range(71, -1, -1)) + '}'
syn = [x([p - 1 for p in range(1, 72) if p & (1 << k)], 'code') for k in range(6, -1, -1)]
D = '{' + ','.join(f'c[{p - 1}]' for p in reversed(pos)) + '}'
FUN = f""" // static ot_gpu_w6_secded_pkg::encode64 / decode64 (make_mroot_yosys.py)
 function [71:0] encode64(input [63:0] data);
  begin encode64={E}; end
 endfunction
 function [65:0] decode64(input [71:0] code);
  reg [71:0] c; reg [6:0] s; reg ov,ue,cor;
  begin
   s={{{','.join(syn)}}}; ov=^code; ue=1'b0; cor=1'b0; c=code;
   if(s!=7'd0)begin
    if(ov&&s<=7'd71)begin c=code^(72'd1<<(s-7'd1)); cor=1'b1; end else ue=1'b1;
   end else if(ov)begin c[71]=~c[71]; cor=1'b1; end
   decode64={{ue,cor,{D}}};
  end
 endfunction
"""
s = SRC.read_text()
hdr = ('// GENERATED by make_mroot_yosys.py from physical/hbm_die_abstracts_20261006/memory_control/'
       'ot_hbm_die_vm_multicast_root.sv (CLAUDE HBM-ABSTRACTS spine): yosys-only rewrites, see the script; '
       'lockstep-equivalent to the original (tb_mroot_equiv.sv).\n')
rep = [(' import ot_gpu_w6_secded_pkg::*;\n', FUN),
       ('  wire [2815:0] ram_q[0:1];\n', '  wire [2*2816-1:0] ram_q_flat;\n  reg [2303:0] raw;\n  reg [255:0] next_valid;\n'),
       ('.rd_out(ram_q[b][m*256+:256])', '.rd_out(ram_q_flat[b*2816+m*256+:256])'),
       ('sampled<=ram_q[bank];', 'sampled<=bank?ram_q_flat[2816+:2816]:ram_q_flat[0+:2816];'),
       ('     reg [2303:0] raw;\n', ''),
       ('     reg [255:0] next_valid;next_valid=valid_bits;', '     next_valid=valid_bits;')]
for a, b in rep:
    assert s.count(a) == 1, a
    s = s.replace(a, b)
OUT.write_text(hdr + s)
print('wrote', OUT)
