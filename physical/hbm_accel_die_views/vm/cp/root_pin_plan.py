#!/usr/bin/env python3
"""[vm8 FACE3 2026-10-13] vm_cp_root locked per-bit pin plan (root_plan() of make_vm_cp.py) -> codex_specs/pins/
vm_cp_root_cx_pins.tcl, the in-tile register-to-register path lengths and the per-bit die hops to every neighbour
(RWa, RWb, RWT, RE from face_pin_plan.py; the slices from slice3_pin_plan.py / the slice2 kit's balanced ranges).
    python3 root_pin_plan.py        exit 1 if a die hop exceeds 500 um
"""
import json
import re
import sys
from pathlib import Path

CP = Path(__file__).resolve().parent
sys.path.insert(0, str(CP))
import make_vm_cp as plan       # noqa: E402
import face_pin_plan as fpp     # noqa: E402
import slice3_pin_plan as s3    # noqa: E402


def main():
    pl = plan.root_plan()
    pins, xy = pl['pins'], pl['xy']
    L = ["# generated by physical/hbm_accel_die_views/vm/cp/root_pin_plan.py (vm_cp_root_cx) -- do not edit",
         "# locked per-bit pin plan: W / E on M4, S / N on M3, 2 tracks per pin; every pin has its register beside it"]
    for n, (f, t) in sorted(pins.items(), key=lambda kv: (kv[1][0], kv[1][1])):
        x, y = xy(n)
        L.append(f"place_pin -pin_name {{{n}}} -layer {'M4' if f in 'WE' else 'M3'} -location {{{x:.4f} {y:.4f}}} -force_to_die_boundary")
    (CP / "codex_specs" / "pins" / "vm_cp_root_cx_pins.tcl").write_text("\n".join(L) + "\n")
    inst = {n: (m, x, y, o) for n, m, x, y, o, _c in plan.INST}
    def root_abs(port, w):
        _m, X, Y, _o = inst['u_root']
        return [(X + xy(f'{port}[{i}]' if w > 1 else port)[0], Y + xy(f'{port}[{i}]' if w > 1 else port)[1]) for i in range(w)]
    def other_abs(iname, port):
        m, X, Y, o = inst[iname]
        if m == 'vm_cp_slice3':
            p = s3.pins(); n = plan.ports_of(m)[port][1]
            loc = [(p[f'{port}[{i}]' if n > 1 else port] * s3.T3 + s3.T3O, s3.H) for i in range(n)]
            h = s3.H
        else:
            mp, (w, h) = fpp.master_pins(m)
            loc = mp[port]
        Y = fpp.INST_Y.get(iname, Y)
        return [(X + px, Y + ((h - py) if o == 'MX' else py)) for px, py in loc]
    rows = []
    nets = {}
    for n, m, x, y, o, conn in plan.INST:
        for port, net in conn.items():
            nets.setdefault(net, []).append((n, port))
    for port, net in dict(next(c for n, *_r, c in plan.INST if n == 'u_root')).items():
        if not net.startswith('n_'):
            continue
        w = plan.ports_of('vm_cp_root')[port][1]
        a = root_abs(port, w)
        for (n2, p2) in nets[net]:
            if n2 == 'u_root':
                continue
            b = other_abs(n2, p2)
            d = [abs(p[0] - q[0]) + abs(p[1] - q[1]) for p, q in zip(a, b)]
            rows.append(dict(net=net, root=port, to=f'{n2}.{p2}', bits=len(d), max_um=round(max(d), 1),
                             mean_um=round(sum(d) / len(d), 1)))
    rng = {}
    for n, (f, t) in pins.items():
        b = n.split('[')[0]; x, y = xy(n); v = round(y if f in 'WE' else x, 3)
        lo, hi = rng.get(b, (v, v)); rng[b] = (min(lo, v), max(hi, v))
    faces = {}
    for n, (f, t) in sorted(pins.items(), key=lambda kv: kv[1][1]):
        b = n.split('[')[0]
        if b not in faces.setdefault(f, []): faces[f].append(b)
    res = dict(in_tile_paths_um=pl['paths'], s_words=pl['s_at'], n_words=pl['n_at'], die_hops=rows,
               pins=faces, pin_ranges={k: list(v) for k, v in sorted(rng.items())})
    print(json.dumps(res, indent=1))
    return 1 if any(r['max_um'] > 500 for r in rows) else 0


if __name__ == "__main__":
    sys.exit(main())
