#!/bin/bash
# S81 head-die element (dsfd_nvx successor, recovery lever head.json): ot_dsrom_head_elem IOREG=1 (every input at a
# pin flop, outputs from flops). Redesign pass 2026-10-06: routed at 770 ps, signed off at 833.333 ps (60/25 ps),
# IO at the MEASURED insertion (owner model: in max = insSS + 250, in min = insFF - 50, out max = 250 - insSS,
# out min = -(insFF + 50)). Accept SS >= +15 / FF >= +15, DRC 0.
# r1 (2026-10-06 20:05): hold margin 35 ps hit RSZ-0060 at CTS (16,642 hold endpoints, 21,390 buffers at the default
# 20% buffer budget): flow margin 20 ps (accept FF >= +15) and the repair buffer budget hook.
# Usage: route.sh <src> <out> <A|B> <cal|route> [insSS_ps insFF_ps]
#   cal  : CTS-only calibration run (assumed insertion 150/100) -> tools/w18/clock_insertion.py
#   route: one full route with the measured insertion; writes $O/signoff_833.sdc and runs corner_sta
set -o pipefail
S=${1:?src}; O=${2:?out}; E=${3:?A|B}; MODE=${4:?cal|route}; ISS=${5:-150}; IFF=${6:-100}
mkdir -p $O; cd $S
export OT_ORFS_NUM_CORES=16 NUM_CORES=16 OT_SYNTH_TIMEOUT_SECONDS=unlimited OT_FLOW_TIMEOUT_SECONDS=unlimited
export OPENTALLAS_ORFS_IMAGE=${OPENTALLAS_ORFS_IMAGE:-sha256:16470cea1d346bfa245e402108995a4f04a1e54fe7c7bb7441774d7f6a2ece29}
M=ot_rom_4096x274_m8
if [ $E = A ]; then P=(--param LV=8 --param PAD=0 --param JOIN=1 --param ROWS=32); else P=(--param LV=6 --param PAD=2 --param JOIN=0 --param ROWS=128); fi
IMAX=$(echo "($ISS+250)/1000" | bc -l); IMIN=$(echo "($IFF-${IN_HOLD_SKEW:-0})/1000" | bc -l)
OMAX=$(echo "(250-$ISS)/1000" | bc -l); OMIN=$(echo "-($IFF+50)/1000" | bc -l)
H=physical/dsrom_head_elem_ioreg
STOP=(); [ $MODE = cal ] && STOP=(--pnr-stop-after cts --orfs-var SKIP_CTS_REPAIR_TIMING=1)   # calibration: clock tree only
cat > $O/signoff_833.sdc <<S2
# generated by $H/route.sh: insertion SS $ISS / FF $IFF ps
create_clock -name core_clk -period 833.333 [get_ports clk]
set_propagated_clock [all_clocks]
set_clock_uncertainty -setup 60 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay -max $(echo "$ISS+250" | bc) -clock core_clk [all_inputs -no_clocks]
set_input_delay -min $(echo "$IFF-${IN_HOLD_SKEW:-0}" | bc) -clock core_clk [all_inputs -no_clocks]
set_output_delay -max $(echo "250-$ISS" | bc) -clock core_clk [all_outputs]
set_output_delay -min $(echo "-($IFF+50)" | bc) -clock core_clk [all_outputs]
set_load 3.898 [all_outputs]
set_false_path -from [get_ports rst_n]
set_multicycle_path -setup 2 -from [get_cells -hierarchical *u_rom?]
set_multicycle_path -hold 1 -from [get_cells -hierarchical *u_rom?]
S2
echo "$(date -Is) START $(hostname) $E $MODE ins $ISS/$IFF" >> $O/MANIFEST
python3 tools/run_abi3_physical.py --view asap7 --top ot_dsrom_head_elem --source rtl/v41rom/ot_dsrom_head_elem.sv \
 --source rtl/v41rom/ot_v41_fadd.sv --source rtl/common/ot_prefix.sv --source rtl/v41rom/ot_v41_bmul2.sv \
 --source rtl/v41rom/ot_dsrom_bmul3.sv --source physical/asap7_memory_macros/$M/${M}_bb.v "${P[@]}" --param IOREG=1 \
 --clock-period-ns 0.770 --clock-uncertainty-ns 0.060 --clock-uncertainty-hold-ns 0.025 \
 --orfs-corner WC --hold-corners WC,BC --orfs-var ADDER_MAP_FILE= --max-fanout 32 --stages pnr "${STOP[@]}" \
 --false-path-from rst_n --core-input-delay-min-ns $IMIN --core-input-delay-max-ns $IMAX \
 --output-delay-min-ns $OMIN --output-delay-max-ns $OMAX \
 --core-utilization 40 --macro-place-halo 3 3 --hold-margin-ns 0.020 --slew-margin-percent 30 \
 --step-tcl PRE_CTS=physical/abi3/v41x_karb_repair_buffer_cap.tcl --step-tcl PRE_GLOBAL_ROUTE=physical/abi3/v41x_karb_repair_buffer_cap.tcl \
 --sdc-append physical/abi3/v41_w10_elem_pp_multicycle.sdc --macro-view $M=physical/asap7_memory_macros/$M \
 --nickname-tag hio$E$MODE --keep-workdir $O/work --keep-heavy-artifacts --output $O/physical.json > $O/route.log 2>&1
echo $? > $O/route.exit
if [ $MODE = route ]; then
 cp $O/signoff_833.sdc $S/$H/signoff_$E.gen.sdc
 python3 tools/w18/corner_sta.py --orfs-dir $O/work/orfs --macro physical/asap7_memory_macros/$M --post-sdc $H/signoff_$E.gen.sdc \
  --output $O/corner_sta.json > $O/sta.log 2>&1; echo $? > $O/sta.exit
else
 python3 tools/w18/clock_insertion.py --orfs-dir $O/work/orfs --stage 4_cts --macro physical/asap7_memory_macros/$M --output $O/insertion.json > $O/ins.log 2>&1; echo $? > $O/ins.exit
fi
echo "$(date -Is) END route=$(cat $O/route.exit)" >> $O/MANIFEST
touch $O/DONE
