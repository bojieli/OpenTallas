#!/usr/bin/env python3
"""Q-TTH15 h15 controller lockstep bench generator: the TT head's ot_qwen_rom_core_ctrl_static instance (its exact parameter
and connection text from qfd_tt_ctlm_head_static_rk) wrapped twice -- H15 = 0 (FQWE/OINC/DTIL/AMWC/RRH off = the h14 controller)
and H15 = 1 -- driven by the same random stimulus (random start / token / pos / calendar pulses / engine status / argmax
returns / other-unit counts, random programme words with a DYN_TTILES / split / unit bias) and compared on every connected
output every cycle.  Writes tb_h15_ctrl.sv next to this script."""
import re
from pathlib import Path
R = Path(__file__).resolve().parents[2]
D = R / 'rtl/qwen_sys/static_schedule_20261014'
head = (D / 'ot_qfd_tt_ctlm_head_static_rk.sv').read_text()
ctrl = (D / 'ot_qwen_rom_core_ctrl_static.sv').read_text()
a = head.index('ot_qwen_rom_core_ctrl_static #(')
b = head.index('));', head.index('.rst_hfc_n(', a)) + 3
inst = head[a:b]
# port directions / widths from the controller header (the XPF monitor block is not elaborated)
hdr = ctrl[ctrl.index(') (\n    input  wire              clk'):ctrl.index('\n);', ctrl.index(') (\n    input  wire              clk'))]
hdr = re.sub(r'`ifdef OT_QFD_XPF_MONITOR.*?`endif', '', hdr, flags=re.S)
ports = {}
toks = re.findall(r"\[[^\]]+\]|[A-Za-z_]\w*|[,]", re.sub(r"//[^\n]*", "", hdr))
d = w = None
for k in toks:
    if k in ("input", "output"): d, w = k, ""
    elif k in ("wire", "reg", ","): continue
    elif k.startswith("["): w = k
    elif d: ports[k] = (d, w)
conns = re.findall(r'\.(\w+)\(((?:[^()]|\([^()]*\))*)\)', inst[inst.index('u_ctrl_me ('):])
wp, body = [], []
for p, e in conns:
    e = e.strip()
    if p == 'rst_hfc_n':
        body.append(f'.{p}({{4{{rst_n}}}})'); continue
    if p in ('clk', 'rst_n'):
        body.append(f'.{p}({p})'); continue
    if e == '' or re.fullmatch(r"'0|\d+'[bdh][0-9a-fA-F]+", e):
        body.append(f'.{p}({e})'); continue
    d, w = ports[p]
    wp.append((d, w, p)); body.append(f'.{p}({p})')
params = inst[len('ot_qwen_rom_core_ctrl_static '):inst.index(' u_ctrl_me (')]
L = ['`timescale 1ns/1ps', '// GENERATED by physical/qwen_tt_static_cluster_1015/gen_h15_ctrl_tb.py -- do not edit',
     'module tbc_h15_ctrl #(parameter integer H15 = 0, parameter integer NW = 18, parameter integer AW = 24, parameter integer PAW = 12,',
     '    parameter integer XW = 24) (',
     '    input wire clk, input wire rst_n, input wire [31:0] seed,']
L += [f'    {"input" if d == "input" else "output"} wire {w} {p},' for d, w, p in wp if p != 'prog_q']
L[-1] = L[-1].rstrip(',')
L += [');',
      '    localparam integer G = 3072, TPMUT = 0, AUD = 33975, MEREG = 3, PCUT = 1, HQ2 = 1, DPRE = 1, DSEL = 1;',
      '    localparam integer FQWE = H15, OINC = H15, DTIL = H15, AMWC = H15, RRH = H15;',
      '    // the head store model: read issued at the prog_re edge, captured in prog_q one edge later (PRL 2)',
      '    reg prog_re_r; reg [11:0] prog_a_r; reg [1023:0] prog_q;',
      '    function automatic [31:0] hsh(input [31:0] x); reg [31:0] v; begin v = x * 32\'h9E3779B1; v = v ^ (v >> 15); v = v * 32\'h85EBCA77;',
      '        hsh = v ^ (v >> 13); end endfunction',
      '    function automatic [1023:0] word(input [11:0] a, input [31:0] s); reg [1023:0] w; integer i; reg [31:0] h; begin',
      '        for (i = 0; i < 32; i = i + 1) w[32*i +: 32] = hsh({a, i[4:0], 15\'d0} ^ s);',
      '        h = hsh({20\'d0, a} ^ s ^ 32\'h5bd1e995);',
      '        w[0 +: 2] = h[1:0] | 2\'d1;                          // mostly ME / SU (unit 0 = END rarely)',
      '        if (h[4:2] < 3) w[O_ME_D_TILES +: 3] = 3\'d6;           // DYN_TTILES often',
      '        if (h[7:5] == 0) w[0 +: 2] = 2\'d0;',
      '        word = w; end endfunction',
      '    always @(posedge clk) begin prog_re_r <= prog_re; prog_a_r <= prog_addr; if (prog_re_r) prog_q <= word(prog_a_r, seed); end',
      '    `include "ot_hdc_isa.svh"',
      f'    ot_qwen_rom_core_ctrl_static {params} u_ctrl_me (',
      '        ' + ',\n        '.join(body) + ');',
      'endmodule', '']
ins = [(d, w, p) for d, w, p in wp if d == 'input' and p != 'prog_q']
outs = [(d, w, p) for d, w, p in wp if d == 'output']
T = ['module tb_h15_ctrl;', '  localparam integer NW = 18, AW = 24, PAW = 12, XW = 24;', '  reg clk = 0; always #0.5 clk = ~clk;', '  reg rst_n; reg [31:0] seed; integer cyc = 0, errs = 0, i;']
T += [f'  reg {w} {p};' for d, w, p in ins]
T += [f'  wire {w} r_{p}, d_{p};' for d, w, p in outs]
def hook(pref):
    return ', '.join(['.clk(clk)', '.rst_n(rst_n)', '.seed(seed)'] + [f'.{p}({p})' for _, _, p in ins] + [f'.{p}({pref}_{p})' for _, _, p in outs])
T += [f'  tbc_h15_ctrl #(.H15(0)) u_ref ({hook("r")});', f'  tbc_h15_ctrl #(.H15(1)) u_dut ({hook("d")});']
rnd = {'start': '($urandom % 40) == 0', 'fixed_issue': '($urandom % 4) == 0', 'fixed_end': '($urandom % 60) == 0',
       'fixed_fault': '($urandom % 5000) == 0', 'me_mem_ok': '($urandom % 8) != 0', 'kv_ok': '($urandom % 3) != 0',
       'kv_write_drained': '($urandom % 3) != 0', 'pi_me_am_any': '($urandom % 2)', 'pi_me_ready': '($urandom % 4) != 0',
       'pi_me_idle': '($urandom % 3) != 0', 'x_oidle': '($urandom % 2)'}
T += ['  task rnd; begin']
for d, w, p in ins:
    T.append(f'    {p} = {rnd[p]};' if p in rnd else f'    {p} = {{$urandom, $urandom}};')
T += ['    if (($urandom % 3) == 0) pi_me_am_val = {pi_me_am_val[31], 31\'h7f000000 | pi_me_am_val[23:0]};',
      '    if (($urandom % 2) == 0) x_oacc = u_dut.u_ctrl_me.o_cnt + ($urandom % 3);',
      '  end endtask']
cmp = ' || '.join(f'(r_{p} !== d_{p})' for _, _, p in outs)
T += ['  integer dt6 = 0, amw = 0, skp = 0, ld = 0;',
      '  always @(posedge clk) if (rst_n) begin',
      '    if (u_ref.u_ctrl_me.load && u_ref.u_ctrl_me.ir[O_ME_D_TILES +: 3] == 3\'d6) dt6 = dt6 + 1;',
      '    if (u_ref.u_ctrl_me.load) ld = ld + 1;',
      '    if (u_ref.u_ctrl_me.skip) skp = skp + 1;',
      '    if (u_ref.u_ctrl_me.me_go && u_ref.u_ctrl_me.me_amax && u_ref.u_ctrl_me.me_amc && u_ref.u_ctrl_me.am_wins) amw = amw + 1;',
      '  end',
      '  `include "ot_hdc_isa.svh"',
      '  initial begin',
      '    seed = 32\'h1234; rst_n = 0; rnd; repeat (3) @(negedge clk); rst_n = 1;',
      '    repeat (`NCYC) begin',
      '      @(negedge clk); rnd; cyc = cyc + 1;',
      '      if (cyc % 25000 == 0) begin seed = $urandom; rst_n = 0; @(negedge clk); rst_n = 1; end',
      '      @(posedge clk); #0.1;',
      f'      if ({cmp}) begin errs = errs + 1; if (errs < 6) $display("H15CTRL_MISMATCH cyc=%0d", cyc); end',
      '    end',
      '    $display("H15CTRL cycles=%0d loads=%0d dyn_ttiles_loads=%0d skips=%0d am_wins=%0d outputs=%0d errs=%0d", cyc, ld, dt6, skp, amw, ' + str(len(outs)) + ', errs);',
      '    if (errs == 0 && dt6 > 0 && amw > 0 && skp > 0) $display("H15CTRL_PASS"); else if (errs != 0) $display("H15CTRL_FAIL errs=%0d", errs);',
      '    else $display("H15CTRL_UNSENSITIZED");',
      '    $finish;',
      '  end', 'endmodule', '']
(Path(__file__).parent / 'tb_h15_ctrl.sv').write_text('\n'.join(L + T))
print(len(ins), 'inputs', len(outs), 'outputs')
