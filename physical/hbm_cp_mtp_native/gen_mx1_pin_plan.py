#!/usr/bin/env python3
"""Render every MX1 pin from its committed physical contract, including clocks."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
P=ROOT/'physical/hbm_cp_mtp_native/collar_mx1/hfd_cmdproc_s_mtp_native_mx1'
def generate():
    ports=json.loads((P/'ports.json').read_text())['ports'];seen=set();lines=['# GENERATED by physical/hbm_cp_mtp_native/gen_mx1_pin_plan.py; every contract pin.']
    for port,record in ports.items():
        for pin in record['pins']:
            name,layer,x0,y0,x1,y1=pin
            assert name not in seen,(port,name);seen.add(name)
            assert x1>x0 and y1>y0,(port,pin)
            lines.append(f'place_pin -pin_name {{{name}}} -layer {layer} -location {{{(x0+x1)/2:.6f} {(y0+y1)/2:.6f}}} -pin_size {{{x1-x0:.6f} {y1-y0:.6f}}}')
    return '\n'.join(lines)+'\n',len(seen)
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args();text,n=generate();out=P/'io_place.tcl'
    if a.check:
        assert out.read_text()==text,'MX1 IO pin plan does not match full committed pin contract'
    else:out.write_text(text)
    print(f'MX1_PIN_PLAN PASS {n} unique pins')
if __name__=='__main__':main()
