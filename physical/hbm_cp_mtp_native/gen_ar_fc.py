#!/usr/bin/env python3
"""mtp-lead 2026-10-10: MX1's AR band with FACE CLOCK TAPS + LOCKUPS (design standard ~20:30 PT 2026-10-09, REVIEW_20261009).

    python3 physical/hbm_cp_mtp_native/gen_ar_fc.py        (writes rtl/hfd_cmdproc_s_fc.sv; --check: fail if stale)

Derives hfd_cmdproc_s_fc from the generated AR view source physical/hbm_accel_die_views/cmdproc/rtl/hfd_cmdproc_s.sv
(tools/hbm_die_wrap.py) WITHOUT changing the adopted AR view: MX1 instantiates the derived module, every other user keeps
hfd_cmdproc_s.  Why: on MX1 (AR + native MTP, 7,043 clock sinks) AR's boundary flops sit 844..1149 ps around a 658 ps
routed reference (post-CTS skew 424 ps vs AR-south closed 352): the same buses fail setup on some pin flops and hold on
others (arcts-hm10-e705d6a01: f_loader -> i0 -238.9 TT, t_su output stations -265..-301, cSE stations FF -44).

Standard applied (same patterns as svc/gen_svc_seg.py --fc and tools/hbm_hub_quarter_gen.py --xroot lockup):
  (1) face clock taps: every pin flop is clocked by its face's die clock leaf -- cks (S: f_loader, f_router), ckn
      (N: xb, xl, xt), cke (E: cSE, t_su_SE), ckw (W: cSW, t_su_SW); the core keeps ck.
  (2) lockups: every zero-logic hop between a tap root and the core root goes through a falling-edge copy on the SOURCE
      root -- input: i0_<p> (posedge tap) -> lk_<p> (negedge tap) -> its reader on ck; output: last core stage (posedge ck)
      -> lockup (negedge ck) -> pin flop (posedge tap).  0 added cycles (each hop keeps one cycle: half on each root).
  (3) the forwarded-clock inverters of cSE / cSW leave from their face tap (aligned with that face's pin flops).
Cycle behaviour is identical to hfd_cmdproc_s when all taps are the same clock (bench: tb_hfd_cmdproc_s_fc_lockstep).
Fails loudly when the source no longer has the expected structure.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'physical/hbm_accel_die_views/cmdproc/rtl/hfd_cmdproc_s.sv'
OUT = ROOT / 'physical/hbm_cp_mtp_native/rtl/hfd_cmdproc_s_fc.sv'
FACE = dict(f_loader='s', f_router='s', xb='n', xl='n', xt='n', cSE='e', t_su_SE='e', cSW='w', t_su_SW='w')
FCLK = {0: 'e', 1: 'e', 2: 'w', 3: 'w'}       # u_fclk_k -> face (cSE[824/825] / cSW[824/825])


def gen():
    s = SRC.read_text()
    n0 = s.count('\n')
    hdr = (f'// GENERATED by physical/hbm_cp_mtp_native/gen_ar_fc.py from {SRC.relative_to(ROOT)}: face clock taps + lockups.\n'
           '// DO NOT EDIT.  See the generator docstring (design standard 2026-10-09 ~20:30 PT).\n')
    assert s.count('module hfd_cmdproc_s (') == 1
    s = s.replace('module hfd_cmdproc_s (', 'module hfd_cmdproc_s_fc (\n    input wire [0:0] cks, ckn, cke, ckw,', 1)
    assert s.count('    wire clk = ck[0];\n') == 1
    s = s.replace('    wire clk = ck[0];\n', '    wire clk = ck[0];\n    wire c_s = cks[0], c_n = ckn[0], c_e = cke[0], c_w = ckw[0];   // face clock taps\n', 1)
    # (1)+(2) inputs: pin flop on the face tap, lockup on the same tap, readers through the lockup
    nin = 0
    for p, f in FACE.items():
        m = re.search(rf'    reg \[(\d+):0\] i0_{p}; always @\(posedge clk\) i0_{p} <= {p};\n', s)
        if not m:
            continue
        w = m.group(1)
        new = (f'    reg [{w}:0] i0_{p}; always @(posedge c_{f}) i0_{p} <= {p};   // pin flop on the {f.upper()} tap\n'
               f'    (* keep *) reg [{w}:0] lk_{p}; always @(negedge c_{f}) lk_{p} <= i0_{p};   // lockup ({f.upper()} -> core)\n')
        s = s[:m.start()] + new + s[m.end():]
        body_start = s.index(new) + len(new)
        rest, k = re.subn(rf'\bi0_{p}\b', f'lk_{p}', s[body_start:])
        assert k >= 1, (p, 'no reader')
        s = s[:body_start] + rest
        nin += 1
    assert nin == 5, nin          # cSE, cSW, f_loader, f_router, xb
    # (1)+(2) outputs: oreg stations driving o_<p> -> *_fc (lockup on ck, pin flop on the tap)
    nout = 0
    def sub1(mm):
        nonlocal nout
        kind, inst, d, q = mm.group(1), mm.group(2), mm.group(3), mm.group(4)
        p = re.sub(r'\[.*', '', q)[2:]
        if not q.startswith('o_') or p not in FACE:
            return mm.group(0)
        if kind == 'ot_hfd_oreg1':
            assert re.fullmatch(r'n_st\d+', d), (inst, d, 'oreg1 output station fed by logic: a lockup would halve its budget')
        nout += 1
        return f'{kind}_fc {inst} (.clk(clk), .fclk(c_{FACE[p]}), .d({d}), .q({q}))'
    s = re.sub(r'(ot_hfd_oreg[123])\s+(\w+)\s*\(\.clk\(clk\),\s*\.d\(([^)]*)\),\s*\.q\(([^)]*)\)\)', sub1, s)
    assert nout == 672 * 2 + 17 * 2 + 4, nout
    # (3) forwarded clocks from the face taps
    for k, f in FCLK.items():
        a = f'ot_fwd_clk_inv u_fclk_{k} (.a(clk), .y(fclk_{k}));'
        assert s.count(a) == 1, a
        s = s.replace(a, f'ot_fwd_clk_inv u_fclk_{k} (.a(c_{f}), .y(fclk_{k}));')
    assert s.count("\n") == n0 + 2 + nin, (s.count("\n"), n0)   # + tap port line + tap wire line + one lockup per input
    return hdr + s


def main():
    txt = gen()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print('UP TO DATE' if ok else 'STALE'); raise SystemExit(0 if ok else 1)
    OUT.write_text(txt)
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
