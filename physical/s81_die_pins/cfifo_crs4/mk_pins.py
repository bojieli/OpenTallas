#!/usr/bin/env python3
"""S81-DIE7/CRS4 10-18: dsfd_cfifo_crs4 pin plan, derived from the CLOSED dsfd_cfifo_crs plan
physical/s81_die_pins/cfifo_crs/dsfd_cfifo_crs_nspread.tcl (same 280.8 x 69.12 frame slot, same N face, same S data order):
  * xd[i] -> xl<i // 276>[i % 276], xd2[j] -> lane bit 566 + j: every lane bit keeps its S x position;
  * xf / xf2 removed; xk[k] (lane k forwarded clock) on S M5 at the centre of lane k's own pin span, snapped to the M5
    grid (0.012 + n * 0.048) with >= 0.096 clearance to every other pin (the crs clock-pin rule);
  * lk[11:0] (identity straps) on W M4 above rst, 0.24 pitch on the M4 grid; cr / cr_s / rd / rst / N face unchanged.
  mk_pins.py  (writes dsfd_cfifo_crs4.tcl next to itself)"""
import re
from pathlib import Path
HERE = Path(__file__).resolve().parent
SRC = HERE.parents[0] / 'cfifo_crs' / 'dsfd_cfifo_crs_nspread.tcl'
LANE = 276
PP = re.compile(r'place_pin -pin_name \{([^}]+)\} -layer (\S+) -location \{([0-9.]+) ([0-9.]+)\} -force_to_die_boundary')
out, pins, lane_x = [], [], {k: [] for k in range(4)}
for ln in SRC.read_text().splitlines():
    m = PP.fullmatch(ln.strip())
    if not m:
        continue
    n, lay, x, y = m.group(1), m.group(2), float(m.group(3)), float(m.group(4))
    if n in ('xf', 'xf2'):
        continue
    b = re.fullmatch(r'(xd2?)\[(\d+)\]', n)
    if b:
        i = int(b.group(2)) + (566 if b.group(1) == 'xd2' else 0)
        n = f'xl{i // LANE}[{i % LANE}]'
        lane_x[i // LANE].append(x)
    pins.append((n, lay, x, y))
S_Y = 0.042
s_x = [x for n, l, x, y in pins if y == S_Y]
for k in range(4):
    c = (min(lane_x[k]) + max(lane_x[k])) / 2
    best = None
    for d in range(0, 200):
        for sgn in (1, -1):
            g = round(0.012 + (round((c - 0.012) / 0.048) + sgn * d) * 0.048, 3)
            if all(abs(g - x) >= 0.096 - 1e-9 for x in s_x):
                best = g
                break
        if best is not None:
            break
    pins.append((f'xk[{k}]', 'M5', best, S_Y)); s_x.append(best)
rst = [p for p in pins if p[0] == 'rst'][0]
for i in range(12):
    pins.append((f'lk[{i}]', 'M4', rst[2], round(rst[3] + 0.48 + 0.24 * i, 3)))
hdr = ['# GENERATED by physical/s81_die_pins/cfifo_crs4/mk_pins.py (S81-DIE7/CRS4 10-18) -- do not edit.',
       '# dsfd_cfifo_crs4 = dsfd_cfifo_crs_nspread.tcl with xd/xd2 -> xl0..xl3 (same x), xf/xf2 -> xk[0..3] at the centre of',
       '# each lane span (S M5), lk[11:0] straps on W M4 above rst.']
body = [f'place_pin -pin_name {{{n}}} -layer {l} -location {{{x:.3f} {y:.3f}}} -force_to_die_boundary' for n, l, x, y in pins]
(HERE / 'dsfd_cfifo_crs4.tcl').write_text('\n'.join(hdr + body) + '\n')
print('pins', len(pins), 'xk', [p for p in pins if p[0].startswith('xk')])
