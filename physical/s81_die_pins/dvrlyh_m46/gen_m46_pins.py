#!/usr/bin/env python3
"""STW-S81c-DIE4-BLK 10-22 (owner: two-layer pin spread at the die H hot channels): io_tcl for the H half-cycle lane
relays dsfd_dvrlyh_<W>_{EW,WE}: data bits on BOTH data faces at IDENTICAL y and layer (bit b even -> M4 track, odd ->
M6 track), pairs on a 0.192-um slot (= 4 M4 / 3 M6 tracks, so each layer keeps >= 2 own tracks between its pins),
centred on the face; one empty slot at the centre of the bit range carries ck_o (M4) on the o face and stays empty on
the i face, so i[b] of station k+1 sits exactly opposite o[b] of station k (bundles run straight, no jog, same layer).
ck / rs stay where the closed kit had them (N face, M3 / M5).  Same RTL, ports, registers, outline.
usage: gen_m46_pins.py BITS H_UM IFACE OFACE OUT.tcl"""
import sys
bits, H, fi, fo, out = int(sys.argv[1]), float(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
W = 17.28
STEP = 0.192
CEN = {"M4": 0.012, "M6": 0.016}; PIT = {"M4": 0.048, "M6": 0.064}
SIZE = {"M4": "0.192 0.024", "M6": "0.192 0.032"}
def snap(y, L):
    return round(round((y - CEN[L]) / PIT[L]) * PIT[L] + CEN[L], 3)
pairs = (bits + 1) // 2
slots = pairs + 1                       # + the ck_o slot
y0 = (H - slots * STEP) / 2
gap = pairs // 2                        # ck_o slot index
x = {"E": W, "W": 0.0}
L = ["# generated by physical/s81_die_pins/dvrlyh_m46/gen_m46_pins.py %d %.2f %s %s (STW-S81c-DIE4-BLK 10-22)" % (bits, H, fi, fo),
     "place_pin -pin_name {ck} -layer M3 -location {5.409 %.3f} -pin_size {0.018 0.144} -force_to_die_boundary" % H,
     "place_pin -pin_name {rs} -layer M5 -location {11.868 %.3f} -pin_size {0.024 0.192} -force_to_die_boundary" % H]
ys = []
for b in range(bits):
    p = b // 2; s = p + (1 if p >= gap else 0)
    lay = "M4" if b % 2 == 0 else "M6"
    y = snap(y0 + s * STEP + (0.048 if lay == "M4" else 0.144), lay)
    ys.append((b, lay, y))
for port, face in (("i", fi), ("o", fo)):
    for b, lay, y in ys:
        L.append("place_pin -pin_name {%s[%d]} -layer %s -location {%.3f %.3f} -pin_size {%s} -force_to_die_boundary"
                 % (port, b, lay, x[face], y, SIZE[lay]))
yck = snap(y0 + gap * STEP + 0.096, "M4")
L.append("place_pin -pin_name {ck_o} -layer M4 -location {%.3f %.3f} -pin_size {0.192 0.024} -force_to_die_boundary" % (x[fo], yck))
# self-check: per layer per face min spacing >= 2 own tracks
for lay in ("M4", "M6"):
    v = sorted([y for _, l, y in ys if l == lay] + ([yck] if lay == "M4" else []))
    d = min(b - a for a, b in zip(v, v[1:]))
    assert d >= 2 * PIT[lay] - 1e-6, (lay, d)
assert ys[0][2] > 0.5 and ys[-1][2] < H - 0.5
open(out, "w").write("\n".join(L) + "\n")
print(out, "bits", bits, "y range %.3f..%.3f" % (ys[0][2], ys[-1][2]), "ck_o y", yck)
