#!/usr/bin/env python3
"""Print the 833.333 ps sign-off SDC of one Qwen die master (cfg/<CFG>.env): clock re-created at the real period,
propagated, 60 / 25 ps uncertainty, then the die-context boundary io_ref_skew.sdc with the master's REFGLOB / INTER
bound.  Also the closure-loop verdict.post_sdc of the master (physical/qwen_die_masters/signoff/<CFG>.sdc)."""
import re
import sys
from pathlib import Path

D = Path(__file__).resolve().parents[1]
cfg = sys.argv[1]
env = (D / "cfg" / f"{cfg}.env").read_text()
get = lambda k, d="": (re.search(rf"^{k}='?([^'\n]*)'?$", env, re.M) or [None, d])[1]
print(f"# Qwen die master {cfg}: sign-off at 833.333 ps (generated by jobs/signoff_sdc.py)")
print("create_clock -name core_clk -period 833.333 [get_ports clk]")
print("set_propagated_clock [all_clocks]")
print("set_clock_uncertainty -setup 60 [all_clocks]")
print("set_clock_uncertainty -hold 25 [all_clocks]")
print("set ::env(OT_IO_SKEW) 90")
print("set ::env(OT_IO_HOLD_SKEW) 50")
print(f"set ::env(OT_REF_GLOB) {{{get('REFGLOB', '*_q*')}}}")
print(f"set ::env(OT_IO_INTER) {{{get('INTER')}}}")
print("set ::env(OT_IO_SKEW_INTER) 150")
print((D / "io_ref_skew.sdc").read_text())
for line in env.splitlines():
    if line.startswith("FALSE_FROM="):
        for g in line.split("=", 1)[1].strip("'\"").split(","):
            print(f"set_false_path -from [get_ports -quiet {{{g}}}]")
