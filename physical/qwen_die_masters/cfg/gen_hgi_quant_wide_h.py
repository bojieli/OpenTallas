#!/usr/bin/env python3
"""Generate the ot_hgi_quant_wide_h top route cfg + macro placement (el1011-hbm-fq, 2026-10-11).

Physical spec (el1011-hbm-fq.log 09:25): 8 read quads (left column) and 8 write quads (right column) in R0, one per lane
quad q at y = Y0 + q * pitch; the decode tile and the 64x512 result SRAM in the centre; the lane pins of quad q on the
face beside tile q; command + status pins on the bottom face near the centre.  Routing M2-M7 (tiles own M2-M6).
usage: gen_hgi_quant_wide_h.py <name> <dec_view_dir> <dec_size> <rq_view_dir> <wq_view_dir>
"""
import sys
from pathlib import Path


def rng(a, b):
    """regex alternation matching the decimal integers a..b inclusive"""
    out = []
    def go(lo, hi):
        if lo > hi:
            return
        sl, sh = str(lo), str(hi)
        if len(sl) != len(sh):
            go(lo, 10 ** len(sl) - 1); go(10 ** len(sl), hi); return
        if lo == hi:
            out.append(sl); return
        # common prefix
        i = 0
        while i < len(sl) and sl[i] == sh[i]:
            i += 1
        p = sl[:i]
        if i == len(sl) - 1:
            out.append(f"{p}[{sl[i]}-{sh[i]}]"); return
        rest = len(sl) - i - 1
        lo_full = sl[i + 1:] == "0" * rest
        hi_full = sh[i + 1:] == "9" * rest
        if lo_full and hi_full:
            out.append(f"{p}[{sl[i]}-{sh[i]}]" + "[0-9]" * rest); return
        if not lo_full:
            go(lo, int(p + sl[i] + "9" * rest)); lo = int(p + str(int(sl[i]) + 1) + "0" * rest)
        if not hi_full:
            top = int(p + str(int(sh[i]) - 1) + "9" * rest)
            if lo <= top:
                go(lo, top)
            go(int(p + sh[i] + "0" * rest), hi); return
        go(lo, hi)
    go(a, b)
    return "(" + "|".join(out) + ")"


def main():
    name, decv, decs, rqv, wqv = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4], sys.argv[5]
    FH = 1000.0
    RQW, WQW, TH = 85.0, 38.0, 100.0
    E, CH = 20.0, 30.0
    FW = round(E + RQW + CH + max(decs, 172.0) + CH + WQW + E, 1)
    pitch = (FH - 2 * E - TH) / 7
    ys = [round(E + q * pitch, 2) for q in range(8)]
    xr, xw = E, round(FW - E - WQW, 2)
    xc = E + RQW + CH
    dec_y = round(FH / 2 - decs / 2 + 60, 2)
    sram_y = round(dec_y - 22 - 77.76, 2)
    snap = lambda v: round(round(v / 0.054) * 0.054, 3)
    tcl = [f"# generated by gen_hgi_quant_wide_h.py ({name})"]
    tcl += [r"# instance names: match the ODB name with escapes stripped (ODB keeps g_q\[0\].u_rq; the verilog name is g_q[0].u_rq)",
            "proc ot_inst {n} {",
            r'  foreach i [[ord::get_db_block] getInsts] { if {[string map {\\ ""} [$i getName]] eq $n} { return [$i getName] } }',
            '  error "ot_inst: no instance $n"', "}"]
    for q in range(8):
        tcl.append(f"place_macro -macro_name [ot_inst {{g_q[{q}].u_rq}}] -location {{{snap(xr)} {snap(ys[q])}}} -orientation R0")
        tcl.append(f"place_macro -macro_name [ot_inst {{g_q[{q}].u_wq}}] -location {{{snap(xw)} {snap(ys[q])}}} -orientation R0")
    tcl.append(f"place_macro -macro_name [ot_inst {{u_dec}}] -location {{{snap(xc)} {snap(dec_y)}}} -orientation R0")
    tcl.append(f"place_macro -macro_name [ot_inst {{u_od}}] -location {{{snap(xc + max(decs, 172.0) - 171.288)} {snap(sram_y)}}} -orientation R0")
    root = Path(__file__).resolve().parents[3]
    tp = root / f"physical/qwen_die_masters/cfg/{name}_macro_place.tcl"
    tp.write_text("\n".join(tcl) + "\n")
    pins = []
    for q in range(8):
        y0, y1 = round(ys[q] + 2, 1), round(ys[q] + TH - 2, 1)
        pins.append(f"--pin-region '^wrr\\[{rng(q*1028, q*1028+1027)}\\]$=left:{y0}-{y1}'")
        pins.append(f"--pin-region '^wrq\\[{rng(q*64, q*64+63)}\\]$=left:{y0}-{y1}'")
        pins.append(f"--pin-region '^wrq_cr\\[{rng(q*4, q*4+3)}\\]$=left:{y0}-{y1}'")
        pins.append(f"--pin-region '^wwq\\[{rng(q*1120, q*1120+1119)}\\]$=right:{y0}-{y1}'")
        pins.append(f"--pin-region '^(wwq_cr|wwq_done)\\[{rng(q*4, q*4+3)}\\]$=right:{y0}-{y1}'")
    pins.append(f"--pin-region '^cmd\\[=bottom:{round(xc,1)}-{round(xc + max(decs,172.0),1)}'")
    pins.append(f"--pin-region '^(clk|rst_n|go|idle|done|fault|rg_req|rg_gnt|wg_req|wg_gnt)$=bottom:{round(xc,1)}-{round(xc+60,1)}'")
    hdc = ("rtl/hdc/ot_hdc_delay.sv rtl/hdc/ot_hdc_fpu.sv rtl/hdc/ot_hdc_fp32_mul_pipe.sv rtl/hdc/ot_hdc_sfu.sv")
    env = f"""# el1011-hbm-fq (2026-10-11): ot_hgi_quant_wide_h hierarchical top ({FW} x {FH}); generated by gen_hgi_quant_wide_h.py.
# Tiles: rq {rqv}, wq {wqv}, dec {decv} (hardened views, R0, fixed by {name}_macro_place.tcl); SRAM 64x512 result FIFO.
TOP=ot_hgi_quant_wide_h
SRCS='rtl/lib/ot_rst_relay.sv rtl/hbm_accel/generic/qw/ot_hgi_quant_wide_h.sv'
PARAMS=()
FW={FW}
FH={FH}
PINS=({' '.join(pins)})
PIN_H='M4 M6'
PIN_V='M5 M7'
PIN_MIN_TRACKS=2
INTER='*'
REFGLOB='*p_go*'
CLKPORT=clk
PD=0.55
NC=16
MACROS=(physical/asap7_memory_macros/ot_sram_1r1w_64x512_m1_r2c2)
EXTRA=(--macro-view ot_hgi_qw_rq={rqv} --macro-view ot_hgi_qw_wq={wqv} --macro-view ot_hgi_qw_dec={decv} --macro-view ot_sram_1r1w_64x512_m1_r2c2=physical/asap7_memory_macros/ot_sram_1r1w_64x512_m1_r2c2 --macro-place-halo 6 6 --orfs-var MACRO_PLACEMENT_TCL=/src/physical/qwen_die_masters/cfg/{name}_macro_place.tcl)
STAGES=pnr
export OT_PIN_GROUP_MAX=32
export OT_PIN_BALANCE_H='M4 M6'
export OT_PIN_BALANCE_V='M5 M7'
"""
    (root / f"physical/qwen_die_masters/cfg/{name}.env").write_text(env)
    print(name, FW, FH, "pitch", round(pitch, 2), "dec_y", dec_y, "sram_y", sram_y)


if __name__ == "__main__":
    main()
