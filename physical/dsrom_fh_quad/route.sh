#!/bin/bash
# Quadrant-structured DS fused head (redesign pass 2026-10-06): hardened views ot_hdc_v41_fh_quad (16 hardened SRAM lane
# leaves + the group datapath; one element, replicated 4x) and ot_hdc_v41_fh_head_top (registered top: tag/index-write
# control, request decode, FPIPE checked endpoint, five-deep retirement). Every pin is a flop. Routed at 770 ps, signed
# off at 833.333 ps (60/25), IO at the MEASURED insertion (owner model: in max = insSS + 250, in min = insFF - 50,
# out max = 250 - insSS, out min = -(insFF + 50)). Accept SS >= +15 / FF >= +15, DRC 0.
# Usage: route.sh <src> <out> <quad|top> <cal|route> [insSS_ps insFF_ps]
set -o pipefail
S=${1:?src}; O=${2:?out}; V=${3:?quad|top}; MODE=${4:?cal|route}; ISS=${5:-200}; IFF=${6:-120}
mkdir -p $O; cd $S
export OT_ORFS_NUM_CORES=16 NUM_CORES=16 OT_SYNTH_TIMEOUT_SECONDS=unlimited OT_FLOW_TIMEOUT_SECONDS=unlimited
export OPENTALLAS_ORFS_IMAGE=${OPENTALLAS_ORFS_IMAGE:-sha256:16470cea1d346bfa245e402108995a4f04a1e54fe7c7bb7441774d7f6a2ece29}
D=rtl/hdc/v41/dspark_fused_head; H=physical/dsrom_fh_quad
L=ot_hdc_v41_fh_sram_lane_hardened
args=(--source rtl/dsrom_sys/protected_vm/ot_dsrom_vm_pkg.sv --orfs-var SYNTH_HDL_FRONTEND=slang)
for f in rtl/proto/ot_fp32_add_rne_pipe.sv rtl/hdc/ot_hdc_delay.sv rtl/hdc/ot_hdc_fpu.sv rtl/proto/ot_fp32_mul_rne_pipe.sv \
  rtl/hdc/ot_hdc_fp32_mul_pipe.sv rtl/hdc/ot_hdc_sfu.sv rtl/hdc/ot_hdc_fastfp.sv rtl/hdc/ot_hdc_prefix.sv rtl/hdc/ot_hdc_fp32_add_lat.sv \
  $D/capture_candidate/ot_hdc_v41_matvec.sv $D/capture_candidate/ot_hdc_v41_fh_ctx.sv; do args+=(--source $f); done
if [ $V = quad ]; then
 TOP=ot_hdc_v41_fh_quad
 args+=(--source $D/quad/ot_hdc_v41_fh_quad.sv)   # the lane leaf comes from its liberty/LEF (--macro-view)
 args+=(--macro-view $L=$H/leaf --macro-place-halo 2 2 --orfs-var MACRO_PLACEMENT_TCL=/src/$H/macro_place_quad.tcl
   --die-area 0 0 610 560 --core-area 2 2 608 558 --false-path-from gid --core-utilization 30)
 MAC=(--macro $H/leaf)
else
 TOP=ot_hdc_v41_fh_head_top
 for f in $D/capture_candidate/ot_hdc_v41_fh_fault_retire.sv $D/capture_candidate/ot_hdc_v41_fh_retire_parent.sv \
   $D/capture_candidate/ot_hdc_v41_fh_vm_endpoint_ctx.sv $D/capture_candidate/ot_hdc_v41_fh_checked_permission.sv \
   $D/quad/ot_hdc_v41_fh_head_top.sv; do args+=(--source $f); done
 args+=(--param FPIPE=1 --die-area 0 0 700 700 --core-area 2 2 698 698 --core-utilization 25)
 MAC=()
fi
IMAX=$(echo "($ISS+250)/1000" | bc -l); IMIN=$(echo "($IFF-50)/1000" | bc -l)
OMAX=$(echo "(250-$ISS)/1000" | bc -l); OMIN=$(echo "-($IFF+50)/1000" | bc -l)
STOP=(); [ $MODE = cal ] && STOP=(--pnr-stop-after cts)
FP="set_false_path -from [get_ports rst_n]"; [ $V = quad ] && FP="$FP
set_false_path -from [get_ports gid*]"
cat > $O/signoff_833.sdc <<S2
# generated by $H/route.sh ($V): insertion SS $ISS / FF $IFF ps
create_clock -name core_clk -period 833.333 [get_ports clk]
set_propagated_clock [all_clocks]
set_clock_uncertainty -setup 60 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay -max $(echo "$ISS+250" | bc) -clock core_clk [all_inputs -no_clocks]
set_input_delay -min $(echo "$IFF-50" | bc) -clock core_clk [all_inputs -no_clocks]
set_output_delay -max $(echo "250-$ISS" | bc) -clock core_clk [all_outputs]
set_output_delay -min $(echo "-($IFF+50)" | bc) -clock core_clk [all_outputs]
set_load 3.898 [all_outputs]
$FP
S2
echo "$(date -Is) START $(hostname) $V $MODE ins $ISS/$IFF" >> $O/MANIFEST
python3 tools/run_abi3_physical.py --source-root "$S" --view asap7 --top $TOP "${args[@]}" \
 --clock-period-ns 0.770 --clock-uncertainty-ns 0.060 --clock-uncertainty-hold-ns 0.025 \
 --orfs-corner WC --hold-corners BC --stages pnr "${STOP[@]}" \
 --false-path-from rst_n --core-input-delay-min-ns $IMIN --core-input-delay-max-ns $IMAX \
 --output-delay-min-ns $OMIN --output-delay-max-ns $OMAX \
 --orfs-var ADDER_MAP_FILE= --place-density 0.55 --orfs-var PLACE_DENSITY_LB_ADDON= \
 --max-transition-ns 0.25 --max-fanout 16 --slew-margin-percent 20 --hold-margin-ns 0.035 \
 --step-tcl PRE_CTS=physical/abi3/v41x_karb_repair_buffer_cap.tcl --step-tcl PRE_GLOBAL_ROUTE=physical/abi3/v41x_karb_repair_buffer_cap.tcl \
 --keep-workdir "$O/work" --nickname-tag fhq_${V}_$MODE --keep-heavy-artifacts --output "$O/physical.json" > $O/route.log 2>&1
echo $? > $O/route.exit
if [ $MODE = route ]; then
 cp $O/signoff_833.sdc $S/$H/signoff_$V.gen.sdc
 python3 tools/w18/corner_sta.py --orfs-dir $O/work/orfs "${MAC[@]}" --post-sdc $H/signoff_$V.gen.sdc --output $O/corner_sta.json > $O/sta.log 2>&1
 echo $? > $O/sta.exit
else
 python3 tools/w18/clock_insertion.py --orfs-dir $O/work/orfs --stage 4_cts "${MAC[@]}" --output $O/insertion.json > $O/ins.log 2>&1; echo $? > $O/ins.exit
fi
echo "$(date -Is) END route=$(cat $O/route.exit)" >> $O/MANIFEST
touch $O/DONE
