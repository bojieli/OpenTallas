#!/bin/bash
# S81-TAIL 2026-10-08: route SDC of a COMMON-CLOCK hub station die view (dsfd_hstnh_* / dsfd_hstnv_*, m221pq glue:
# one ot_fwd_link_stage per slice on fck = ~ck, i.e. every di bit captured on posedge ck at the pin, dq straight from
# the flop).  usage: make_sdc_hstn.sh <L_ps> <out.sdc>.  L = the calibrated insertion (closure loop CK_SS_MEAN);
# POST_CTS (common/post_cts_vclk.tcl) re-sets vclk to the measured midpoint, output min delay from the BC tree.
# A full-cycle common-clock hop on each face, split as the consistent die-link budget (link_budget_consistent.sdc:
# S = R = 254.7 ps of each link): input delay = T - 254.7 (the receiver gets 254.7 ps from pin to flop incl. setup),
# output delay = T - 254.7 (the sender gets 254.7 ps from clock to pin).  Registered at both faces, so either is
# ~10x what the view needs; the die link STA / rebudget re-derive the split from the routed view.  Routed at 123 ps
# setup uncertainty (770 ps effective), signed off at 60 ps (common/signoff_unc60.sdc).
L=${1:?L}; O=${2:?out}
cat > $O <<EOT
# generated by physical/s81_die_views/glue/make_sdc_hstn.sh $L
create_clock -name core_clk -period 833.333 [get_ports {ck[0]}]
create_clock -name vclk -period 833.333
set_clock_latency $L [get_clocks vclk]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay 578.6 -clock vclk [get_ports {di*}]
set_input_delay -min 0 -clock vclk [get_ports {di*}]
set_output_delay 578.6 -clock vclk [get_ports {dq*}]
set_output_delay -min 0 -clock vclk [get_ports {dq*}]
set_max_fanout 32 [current_design]
EOT
