#!/bin/bash
# CLAUDE S81-DIE: route SDC of a hub end / start block die view (generator kind 'hend', dsfd_{m2l,r2l,l2r}_*__<inst>).
# usage: make_sdc_hend.sh <L_ps> <out.sdc>   (kind from $HEND_KIND: m2l | r2l | l2r)
#   m2l  lane(s) -> local stream: per lane an ot_meso_fifo d8g1 written by the lane's forwarded clock fi<j> (wclk<j>),
#        read by ck (core_clk, stream 833.333).  Meso crossing arcs at 1.5 T - 60 = 1,190 ps (as make_sdc_cfifo.sh).
#        di<j> forwarded with fi<j>: 0.2 T against vw; o (registered FIFO read side): 0.2 T + 150 ps against vclk.
#   r2l  lane -> serial: ot_ratio_cdc_fifo written by fi0 (stream, 833.331), read by ck (serial, 1111.108); one PLL
#        3:4 related clocks (physical/two_clock/ratio_cdc_fifo_f2s.sdc: no exceptions); o 0.2 T + 150 vs vser.
#   l2r  serial -> lane: ot_ratio_cdc_fifo written by ck (serial, 1111.108), read by cks (stream, 833.331); i 0.2 T
#        against vser; od 0.2 T + 150 ps against vclk (stream); st (write-side status) against vser; fo = cks (clock).
# Resets asynchronous assert, synchronised release inside the view.  Routed at 123 ps setup uncertainty, signed off at
# 60 ps (common/signoff_unc60.sdc).  POST_CTS: glue/post_cts_hend.tcl re-sets the virtual clocks to measured insertion.
L=${1:?L}; O=${2:?out}; K=${HEND_KIND:?HEND_KIND}
{
echo "# generated by physical/s81_die_views/glue/make_sdc_hend.sh $L ($K)"
case $K in
m2l)
cat <<EOT
create_clock -name core_clk -period 833.333 [get_ports {ck[0]}]
set ot_w {}
foreach p [get_ports {fi*}] { set n [get_property \$p name]; regsub {\[0\]} \$n {} b; create_clock -name w_\$b -period 833.333 \$p; lappend ot_w w_\$b }
create_clock -name vclk -period 833.333
create_clock -name vw -period 833.333
set_clock_latency $L [get_clocks {vclk vw}]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
foreach w \$ot_w {
  set_max_delay -ignore_clock_latency 1190.0 -from [get_clocks \$w] -to [get_clocks core_clk]
  set_max_delay -ignore_clock_latency 1190.0 -from [get_clocks core_clk] -to [get_clocks \$w]
  set_min_delay -ignore_clock_latency 0 -from [get_clocks \$w] -to [get_clocks core_clk]
  set_min_delay -ignore_clock_latency 0 -from [get_clocks core_clk] -to [get_clocks \$w]
  set_false_path -from [get_clocks vw] -to [get_clocks core_clk]
  set_false_path -from [get_clocks core_clk] -to [get_clocks vw]
  set_false_path -from [get_clocks \$w] -to [get_clocks vclk]
  set_false_path -from [get_clocks vclk] -to [get_clocks \$w]
  foreach w2 \$ot_w { if {\$w2 ne \$w} { set_false_path -from [get_clocks \$w] -to [get_clocks \$w2] } }
}
set_false_path -from [get_clocks vw] -to [get_clocks vclk]
set_input_delay 166.667 -clock vw [get_ports {di*}]
set_input_delay -min 0 -clock vw [get_ports {di*}]
set_output_delay 316.667 -clock vclk [get_ports {o*}]
set_output_delay -min 0 -clock vclk [get_ports {o*}]
set_false_path -from [get_ports {rs*}]
EOT
;;
r2l)
cat <<EOT
create_clock -name w_fi0 -period 833.331 [get_ports {fi0[0]}]
create_clock -name core_clk -period 1111.108 [get_ports {ck[0]}]
create_clock -name vw -period 833.331
create_clock -name vclk -period 1111.108
set_clock_latency $L [get_clocks {vclk vw}]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay 166.666 -clock vw [get_ports {di*}]
set_input_delay -min 0 -clock vw [get_ports {di*}]
set_output_delay 372.222 -clock vclk [get_ports {o*}]
set_output_delay -min 0 -clock vclk [get_ports {o*}]
set_false_path -from [get_ports {rs*}]
EOT
;;
l2r)
cat <<EOT
create_clock -name core_clk -period 1111.108 [get_ports {ck[0]}]
create_clock -name w_cks -period 833.331 [get_ports {cks[0]}]
create_clock -name vclk -period 1111.108
create_clock -name vw -period 833.331
set_clock_latency $L [get_clocks {vclk vw}]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay 222.222 -clock vclk [get_ports {i*}]
set_input_delay -min 0 -clock vclk [get_ports {i*}]
set_output_delay 222.222 -clock vclk [get_ports {st*}]
set_output_delay -min 0 -clock vclk [get_ports {st*}]
set_output_delay 316.666 -clock vw [get_ports {od*}]
set_output_delay -min 0 -clock vw [get_ports {od*}]
set_false_path -to [get_ports {fo*}]
set_false_path -from [get_ports {rs*}]
EOT
;;
*) echo "unknown kind $K" >&2; exit 2;;
esac
echo "set_max_fanout 32 [current_design]"
} > $O
