#!/bin/bash
# d8g1 meso (DEPTH 8 / OFFSET 4 / GUARD_LO 1 / GUARD_HI 7): the low guard trips at a lag below 1.5 T, so every crossing
# arc must settle within 1.5 T - 60 ps = 1,190 ps (was T/2 - 60 = 356.7 with GUARD_LO 0; +1 cycle a crossing).
# CLAUDE S81-RERUN: route SDC of the column FIFO die view dsfd_cfifo.  usage: make_sdc_cfifo.sh <L_ps> <out.sdc>
# Clocks: ck (column clock, core_clk) and xf (the forwarded x-stream clock, wclk), equal period, unknown static phase:
# the meso crossing arcs carry the T/2 - 60 ps phase-window budget (physical/rom_clock/meso_ring_w512_d4.sdc).
# IO against virtual clocks at the measured insertion (glue/post_cts_cfifo.tcl re-measures each tree per corner):
#   xd (forwarded with xf, same clock as its data)            0.2 T against vw
#   st / ri (column, die wire)  and  xa / xb / cc / rs         0.2 T + 150 ps against vclk
#   rd (to the return chain's first station, which captures on the FALLING edge of rf = ck): 0.2 T against vclk fall
#   co / rf are the column clock itself (clock outputs, not data); rst is the asynchronous reset (synchronised inside).
# Routed at 123 ps setup uncertainty (770 ps effective), signed off at 60 ps (common/signoff_unc60.sdc).
# s81-die-2 2026-10-08: CFIFO_COLCK=1 (generator --cfifo-colck) -- the column side is clocked from cr (a sink of the
# cfifo's own column tree), so core_clk is defined on cr; ck only passes to co (clock ckp, no sinks in the block).
L=${1:?L}; O=${2:?out}
if [ "${CFIFO_COLCK:-0}" = 1 ]; then CKPORT='cr[0]'; CKP="create_clock -name ckp -period 833.333 [get_ports {ck[0]}]"; else CKPORT='ck[0]'; CKP=''; fi
cat > $O <<EOT
# generated by physical/s81_die_views/glue/make_sdc_cfifo.sh $L
create_clock -name core_clk -period 833.333 [get_ports {$CKPORT}]
$CKP
create_clock -name wclk -period 833.333 [get_ports {xf[0]}]
create_clock -name vclk -period 833.333
create_clock -name vw -period 833.333
set_clock_latency $L [get_clocks {vclk vw}]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_max_delay -ignore_clock_latency 1190.0 -from [get_clocks wclk] -to [get_clocks core_clk]
set_max_delay -ignore_clock_latency 1190.0 -from [get_clocks core_clk] -to [get_clocks wclk]
set_min_delay -ignore_clock_latency 0 -from [get_clocks wclk] -to [get_clocks core_clk]
set_min_delay -ignore_clock_latency 0 -from [get_clocks core_clk] -to [get_clocks wclk]
set_false_path -from [get_clocks vw] -to [get_clocks {core_clk vclk}]
set_false_path -from [get_clocks vclk] -to [get_clocks {wclk vw}]
set_false_path -from [get_clocks wclk] -to [get_clocks vclk]
set_false_path -from [get_clocks core_clk] -to [get_clocks vw]
set_input_delay 166.667 -clock vw [get_ports {xd*}]
set_input_delay -min 0 -clock vw [get_ports {xd*}]
set_input_delay 316.667 -clock vclk [get_ports {st* ri*}]
set_input_delay -min 0 -clock vclk [get_ports {st* ri*}]
set_output_delay 316.667 -clock vclk [get_ports {xa* xb* cc* rs*}]
set_output_delay -min 0 -clock vclk [get_ports {xa* xb* cc* rs*}]
set_output_delay 166.667 -clock vclk -clock_fall [get_ports {rd*}]
set_output_delay -min 0 -clock vclk -clock_fall [get_ports {rd*}]
set_false_path -to [get_ports {co* rf*}]
set_false_path -from [get_ports {rst*}]
set_max_fanout 32 [current_design]
EOT
