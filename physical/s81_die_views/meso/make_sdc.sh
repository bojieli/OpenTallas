#!/bin/bash
# CLAUDE S81-RERUN: route SDC of the ot_meso_fifo die view (calibrated flow).  usage: make_sdc.sh <L_ps> <out.sdc>
# L = the CTS-only calibration's measured SS insertion (closure loop CK_SS_MEAN); post_cts_vclk.tcl re-measures each
# clock tree per corner after CTS.  Routed over-constrained (setup uncertainty 123 ps = 770 ps effective), signed off
# at 833.333 / 60 ps (signoff_unc60.sdc via corner_sta --post-sdc).  Crossing arcs as physical/rom_clock/
# meso_ring_w512_d4.sdc (T/2 - 60 ps phase window).  IO: 0.2 T + 150 ps die clock-arrival allowance against a virtual
# clock per side at the measured insertion; hold 0 (input) and BC-tree output min delay (post_cts_vclk.tcl).
L=${1:?L}; O=${2:?out}
cat > $O <<EOT
# generated by physical/s81_die_views/meso/make_sdc.sh $L
create_clock -name wclk -period 833.333 [get_ports wclk]
create_clock -name rclk -period 833.333 [get_ports rclk]
create_clock -name vw -period 833.333
create_clock -name vr -period 833.333
set_clock_latency $L [get_clocks {vw vr}]
set_clock_uncertainty -setup 123 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_max_delay -ignore_clock_latency 356.667 -from [get_clocks wclk] -to [get_clocks rclk]
set_max_delay -ignore_clock_latency 356.667 -from [get_clocks rclk] -to [get_clocks wclk]
set_min_delay -ignore_clock_latency 0 -from [get_clocks wclk] -to [get_clocks rclk]
set_min_delay -ignore_clock_latency 0 -from [get_clocks rclk] -to [get_clocks wclk]
set_false_path -from [get_clocks vw] -to [get_clocks {rclk vr}]
set_false_path -from [get_clocks vr] -to [get_clocks {wclk vw}]
set_false_path -from [get_clocks wclk] -to [get_clocks vr]
set_false_path -from [get_clocks rclk] -to [get_clocks vw]
set_input_delay 316.667 -clock vw [get_ports {wrst_n w_v w_d*}]
set_input_delay 316.667 -clock vr [get_ports {rrst_n r_rdy}]
set_input_delay -min 0 -clock vw [get_ports {wrst_n w_v w_d*}]
set_input_delay -min 0 -clock vr [get_ports {rrst_n r_rdy}]
set_output_delay 316.667 -clock vw [get_ports {w_rdy w_live w_fault}]
set_output_delay 316.667 -clock vr [get_ports {r_v r_d* r_live r_fault}]
set_output_delay -min 0 -clock vw [get_ports {w_rdy w_live w_fault}]
set_output_delay -min 0 -clock vr [get_ports {r_v r_d* r_live r_fault}]
set_max_fanout 32 [current_design]
EOT
