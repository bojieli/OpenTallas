#!/bin/bash
# Closure-loop route of ot_dsrom_markov_bundle_glue (mtp-head-1010 fork MB, 2026-10-10): the hardened Markov bundle
# glue of dsrom_mtp_head_full340_A (85 per head die, one per bundle: beside the bundle's B element, under its 4 A
# elements, with the bundle's 4 Markov drivers on its east face). Same IO / sign-off model as
# physical/dsrom_markov_head_driver/route.sh: routed at 770 ps, signed off at 833.333 ps (60/25), IO from the loop's
# calibrated insertion (in max = CK_SS_MEAN + 250, in min = CK_FF_MEAN - IN_HOLD_SKEW, out max = 250 - CK_SS_MEAN,
# out min = -(CK_FF_MEAN + 50)). No macros. DESIGN STANDARD: every port has its own flop (RTL); PINANCHOR=1 (default)
# places those flops beside their pins (physical/qwen_die_masters/io_flop_at_pins.tcl) and puts the clock pin at the
# middle of the die-side (south) face.
# Faces: south = die trees (go/x, start, embed_valid, row0, status out), west = B element, north = 4 A elements,
# east = 4 Markov drivers.  Slot 600 x 200 um fits the head-bundle frame row beside B (840 x 216 um free).
# Usage (from the source root): route.sh <label> <out dir> [extra run_abi3_physical args, e.g. $CL_STOP_AFTER].
set -o pipefail
LBL=${1:?label}; O=${2:?out}; shift 2
S=$(pwd); mkdir -p "$O"
if [ -e "$O/physical.json" ]; then
 echo "existing result preserved: $O/physical.json; use a new attempt directory" >&2
 exit 2
fi
export OT_ORFS_NUM_CORES=${CORES:-16} NUM_CORES=${CORES:-16} OT_SYNTH_TIMEOUT_SECONDS=unlimited OT_FLOW_TIMEOUT_SECONDS=unlimited
export OPENTALLAS_ORFS_IMAGE=${OPENTALLAS_ORFS_IMAGE:-sha256:16470cea1d346bfa245e402108995a4f04a1e54fe7c7bb7441774d7f6a2ece29}
ISS=${CK_SS_MEAN:-500}; IFF=${CK_FF_MEAN:-300}; HMS=${HM:-0.035}
SLOT_W=${SLOT_W:-600}; SLOT_H=${SLOT_H:-200}; CORE_X=$((SLOT_W-2)); CORE_Y=$((SLOT_H-2)); PX=$((SLOT_W-20)); PY=$((SLOT_H-20))
TOP=ot_dsrom_markov_bundle_glue
CLK_MID=$((SLOT_W/2)); CLK_LO=$((CLK_MID-1)); CLK_HI=$((CLK_MID+1))
# fill-8 2026-10-10: the south signal group used to span 20-$PX THROUGH the clock window; the IO placer packed that
# 588-pin group (fallback mode) over every slot of 299-301 first, leaving 0 positions for clk (PPL-0093 at
# 3_2_place_iop, mkglue-a/s-75ccbb9b3 calibrate). The south face is now two groups (go/xa/start/row0/embed/rst 277
# west of the clock, xb + status outputs 311 east) with a CLK_KEEP um keep-out on each side of the face-mid clock pin.
CLK_KEEP=${CLK_KEEP:-5}
anchor_args=()
if [ "${PINANCHOR:-1}" = 1 ]; then
 anchor_args=(--orfs-var PRE_GLOBAL_PLACE_TCL=/src/physical/qwen_die_masters/io_flop_at_pins.tcl
  --orfs-var PRE_DETAIL_PLACE_TCL=/src/physical/qwen_die_masters/out_flop_release.tcl)
fi
args=(--source rtl/hdc/ot_hdc_delay_ring.sv --source rtl/dsrom_sys/mtp/ot_dsrom_markov_bundle_glue.sv
 --param ENABLE=1 --param A_INPUT_STAGES=4 --param CUT=511 --param SPLIT9=1 --param RING=${RING:-1}
 --orfs-var SYNTH_HDL_FRONTEND=slang --orfs-var "SYNTH_SLANG_ARGS=--unroll-limit 8192" --die-area 0 0 $SLOT_W $SLOT_H --core-area 2 2 $CORE_X $CORE_Y
 --core-utilization 40 --max-fanout 16 --routing-layers M2 M6
 --pin-region "^clk\$=bottom:$CLK_LO-$CLK_HI"
 --pin-region "^(go|xa.*|start|row0.*|embed_valid|rst_n)\$=bottom:20-$((CLK_LO-CLK_KEEP))"
 --pin-region "^(xb.*|start_ready|mg_all|mg_any|done|best_valid|best_row.*|best_bits.*|fault)\$=bottom:$((CLK_HI+CLK_KEEP))-$PX"
 --pin-region "^(b_go|b_x.*|b_o_v|b_o_d.*|b_fault)\$=left:20-$PY"
 --pin-region "^(a_go.*|a_row.*|a_x.*|a_bv.*|a_bd.*|a_fault.*)\$=top:20-$PX"
 --pin-region "^(d_.*)\$=right:20-$PY"
 --pin-regions-exhaustive "${anchor_args[@]}")
FP="set_false_path -from [get_ports rst_n]"
IMAX=$(echo "($ISS+250)/1000" | bc -l); IMIN=$(echo "($IFF-${IN_HOLD_SKEW:-0})/1000" | bc -l)
OMAX=$(echo "(250-$ISS)/1000" | bc -l); OMIN=$(echo "-($IFF+50)/1000" | bc -l)
if [ "${ROUTE_HOLD_IO:-ff}" = ss ]; then
 IMIN=$(echo "($ISS-${IN_HOLD_SKEW:-0})/1000" | bc -l); OMIN=$(echo "-($ISS+50)/1000" | bc -l)
fi
G=physical/dsrom_markov_bundle_glue/gen; mkdir -p $G
PSIGN=833.333; PROUTE=0.770
cat > $G/signoff_glue.sdc <<S2
# generated by physical/dsrom_markov_bundle_glue/route.sh: insertion SS $ISS / FF $IFF ps
create_clock -name core_clk -period $PSIGN [get_ports clk]
set_propagated_clock [all_clocks]
set_clock_uncertainty -setup 60 [all_clocks]
set_clock_uncertainty -hold 25 [all_clocks]
set_input_delay -max $(echo "$ISS+250" | bc) -clock core_clk [all_inputs -no_clocks]
set_input_delay -min $(echo "$IFF-${IN_HOLD_SKEW:-0}" | bc) -clock core_clk [all_inputs -no_clocks]
set_output_delay -max $(echo "250-$ISS" | bc) -clock core_clk [all_outputs]
set_output_delay -min $(echo "-($IFF+50)" | bc) -clock core_clk [all_outputs]
set_load 3.898 [all_outputs]
$FP
S2
echo "$(date -Is) START $(hostname) glue $LBL ins $ISS/$IFF HM $HMS holdio ${ROUTE_HOLD_IO:-ff} slot ${SLOT_W}x${SLOT_H} anchor ${PINANCHOR:-1} period $PSIGN/$PROUTE $*" >> $O/MANIFEST
python3 tools/run_abi3_physical.py --source-root "$S" --view asap7 --top $TOP "${args[@]}" \
 --clock-period-ns $PROUTE --clock-uncertainty-ns 0.060 --clock-uncertainty-hold-ns 0.025 \
 --orfs-corner WC --hold-corners WC,BC --stages pnr --false-path-from rst_n \
 --core-input-delay-min-ns $IMIN --core-input-delay-max-ns $IMAX --output-delay-min-ns $OMIN --output-delay-max-ns $OMAX \
 --orfs-var ADDER_MAP_FILE= --place-density 0.45 --orfs-var PLACE_DENSITY_LB_ADDON= --max-transition-ns 0.25 \
 --hold-margin-ns $HMS --step-tcl PRE_CTS=physical/abi3/v41x_karb_repair_buffer_cap.tcl \
 --step-tcl PRE_GLOBAL_ROUTE=physical/abi3/v41x_karb_repair_buffer_cap.tcl \
 --keep-workdir "$O/work" --nickname-tag $LBL --keep-heavy-artifacts --output "$O/physical.json" "$@" > $O/run.log 2>&1
rc=$?; result_rc=$rc; echo "rc=$rc" > $O/exit
if [ $rc = 0 ] && ! echo "$*" | grep -q -- --pnr-stop-after; then
 python3 tools/w18/corner_sta.py --orfs-dir $O/work/orfs --post-sdc $G/signoff_glue.sdc --output $O/corner_sta.json > $O/sta.log 2>&1
 corner_rc=$?; echo "corner_rc=$corner_rc" >> $O/exit
 if [ "$corner_rc" -ne 0 ]; then result_rc=$corner_rc; fi
 python3 tools/w18/export_view.py --orfs-dir $O/work/orfs --name $TOP --post-sdc $G/signoff_glue.sdc --out $O/view > $O/export.log 2>&1
 export_rc=$?; echo "export_rc=$export_rc" >> $O/exit
 if [ "$export_rc" -ne 0 ]; then result_rc=$export_rc; fi
fi
echo "$(date -Is) END $(cat $O/exit | tr '\n' ' ')" >> $O/MANIFEST
exit "$result_rc"
