#!/usr/bin/env python3
"""BUF column-mux pin file (A3 HBM group A 2026-10-14): N face ob_d interleaved ob_d[r], ob_d[1024+r] so both column
outputs of image column r sit together (cut arithmetic in ot_hbm_xp_buf_rptr.sv); M5 at 2 tracks, M4 W/E."""
W, H = 220.32, 108.0
P5 = 0.048; OFF = 0.012
def snap(x): return round(OFF + P5 * round((x - OFF) / P5), 3)
out = ["# hbm_xp_buf_rptr_1014 column-mux pin file: generated by physical/hbm_xp_buf_rptr_1014/mk_io.py; do not edit"]
def pg_m5(x):           # pdn.tcl M5 VDD/VSS pair: offset 0.300, width 0.12, spacing 0.072, pitch 5.4 (+ 0.1 clearance)
    return 0.20 <= (x % 5.4) <= 0.712
def row(names, y, pitch):
    """pins at `pitch`, M5 where the PG stripe pair leaves room, else M3 (M3 carries no PG)"""
    span = pitch * (len(names) - 1); x0 = snap((W - span) / 2)
    for i, n in enumerate(names):
        x = snap(x0 + i * pitch)
        lay, sz = ("M3", "{0.018 0.192}") if (i % 2 == 0 or pg_m5(x)) else ("M5", "{0.024 0.192}")
        out.append(f"place_pin -pin_name {{{n}}} -layer {lay} -location {{{x:.3f} {y:.3f}}} -pin_size {sz} -force_to_die_boundary")
def col(names, x, pitch):
    span = pitch * (len(names) - 1); y0 = snap((H - span) / 2)
    for i, n in enumerate(names):
        out.append(f"place_pin -pin_name {{{n}}} -layer M4 -location {{{x:.3f} {snap(y0 + i * pitch):.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary")
n = ["ob_v", "ob_eop"] + [f"ob_addr[{i}]" for i in range(7)] + [f"ob_grp[{i}]" for i in range(7)]
for r in range(1024):
    n += [f"ob_d[{r}]", f"ob_d[{1024 + r}]"]
row(n, H - 0.096, 0.096)
row(["w_v_i"] + [f"w_t_i[{i}]" for i in range(25)] + [f"w_d_i[{i}]" for i in range(1024)], 0.096, 0.192)
col(["clk", "rst_n", "tok0", "tok_i"], 0.096, 0.96)
col(["tok_o", "fault"], W - 0.096, 0.96)
open(__file__.replace("mk_io.py", "buf_col_io.tcl"), "w").write("\n".join(out) + "\n")
print(len(out) - 1, "pins")
