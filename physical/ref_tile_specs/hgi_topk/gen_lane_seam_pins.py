#!/usr/bin/env python3
"""Lane-tile io_tcl with an ABUTMENT-ALIGNED heap seam (el1011-hbm-idx 2026-10-12, w8c GRT-0116 fix).

w8c rt_b failed GRT on M6 in the heap<->lane channel of every column: the heap's 179 seam pins sit in a 25.2-um window
(x 105.66..130.91, M5 every 2nd track) but the lane's t_* pins were spread over 112 um (x 109..221), so all 179 nets
fanned out horizontally right at the heap face (M6 usage 10-12 / capacity 9 per gcell, 3,336 overflow).  This places
every lane S-face pin t_X[b] at EXACTLY the heap view's X[b] x / layer / size (heap and lane share the 43.2-um column
lattice in R0 and MX, so each seam net is one straight M5 drop) and keeps the lane's N-face (glue side) pins where the
closed lane_rt_a view had them, so the cluster glue sees no change.
usage: gen_lane_seam_pins.py HEAP.lef LANE_OLD.lef OUT.tcl
"""
import re
import sys


def pins(path):
    txt = open(path).read()
    W, H = map(float, re.search(r"SIZE ([\d.]+) BY ([\d.]+)", txt).groups())
    out, pin, lay = {}, None, None
    for line in txt.split("\n"):
        s = line.split()
        if not s:
            continue
        if s[0] == "PIN":
            pin, lay = s[1], None
        elif s[0] == "OBS":
            pin = None
        elif pin and s[0] == "LAYER":
            lay = s[1]
        elif pin and s[0] == "RECT" and pin not in ("VDD", "VSS"):
            n = [float(x) for x in s[1:] if re.fullmatch(r"-?[\d.]+", x)]
            out[pin] = dict(x=(n[0] + n[2]) / 2, y=(n[1] + n[3]) / 2, w=n[2] - n[0], h=n[3] - n[1], layer=lay)
            pin = None
    return out, W, H


def main():
    heap, _, _ = pins(sys.argv[1])
    lane, LW, LH = pins(sys.argv[2])
    lines = ["# generated by physical/ref_tile_specs/hgi_topk/gen_lane_seam_pins.py -- do not edit",
             "# S face: t_X[b] at the heap view's X[b] (straight M5 seam drops); N face: as closed lane_rt_a"]
    nS = nN = 0
    for name, p in sorted(lane.items()):
        if p["y"] < 1.0:  # S face: seam
            hn = name[2:] if name.startswith("t_") else None
            if hn not in heap:
                sys.exit(f"seam pin {name}: no heap pin {hn}")
            q = heap[hn]
            x, w, h, lay, y = q["x"], q["w"], q["h"], q["layer"], 0.0
            nS += 1
        else:
            x, w, h, lay, y = p["x"], p["w"], p["h"], p["layer"], LH
            nN += 1
        lines.append(f"place_pin -pin_name {{{name}}} -layer {lay} -location {{{x:.4f} {y}}} "
                     f"-pin_size {{{w:.4f} {h:.4f}}} -force_to_die_boundary")
    open(sys.argv[3], "w").write("\n".join(lines) + "\n")
    print(f"S seam {nS} (aligned to heap), N {nN} (kept), lane {LW}x{LH}")


if __name__ == "__main__":
    main()
