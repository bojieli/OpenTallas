#!/usr/bin/env python3
"""dsfd_vm_bgr28 N/S pin plan v4c (el1011-ds-vm/bgq28, 2026-10-12): re-spread the 4,144 request pins (i_* N / f_* S, shared x
and layer for chain abutment) so no face layer exceeds ~10 b/um in any 100-um window (v4b: A-region M3 13.2 b/um,
FLOORPLAN_MARGIN), keeping every region's horizontal-cut ratio <= 0.57.

Regions (macro column centred, x [85.536, 259.656]; macros block M1-M4 there):
  A x[2.4, 85.536]   M3 + M5   cut capacity 3,911 tracks
  B x[85.536, 259.656] M5 only cut capacity 3,351 tracks
  C x[259.656, 343.2] M3 + M5  cut capacity 3,940 tracks; holds the return r_*/o_* pins (contract v11 positions, kept verbatim)
Max-window density D: every 100-um window <= 100*D pins per layer.  A and C are ~83 um wide, so a window over A (or C)
also covers ~16.9 um of B's M5:  A_M3 <= 100D, A_M5 + 16.9*b <= 100D, B = 174.12*b, b <= D.  Solve with b = D for the
4,144 request bits; the request bits are assigned in their existing (bit) order A -> B -> C (monotone in x), each region's
per-layer pins spread uniformly over that layer's free tracks (M5 tracks overlapping the M5 PG stripe pair are excluded;
C excludes the tracks the return pins snap to).
Usage: gen_bgr28_pins.py IN.tcl OUT.tcl  (IN = the v4b plan: supplies port order, return and W-face lines)."""
import re
import sys

H = 501.12
XA0, XB0, XB1, XC1 = 2.4, 85.536, 259.656, 343.2
WIN = 100.0
CAP = {"A": 3911, "B": 3351, "C": 3940}
TR = {"M3": (0.009, 0.036, "{0.018 0.144}"), "M5": (0.012, 0.048, "{0.024 0.192}")}
PG = [(0.300, 0.420), (0.492, 0.612)]  # pdn.tcl: M5 width 0.12 spacing 0.072 pitch 5.4 offset 0.3
PG_KEEP = 0.012 + 0.024  # pin half-width + spacing


def tracks(layer, lo, hi):
    off, p, _ = TR[layer]
    k0, k1 = int((lo - off) / p) + 1, int((hi - off) / p)
    out = []
    for k in range(k0, k1 + 1):
        x = round(off + k * p, 4)
        if layer == "M5":
            m = x % 5.4
            if any(a - PG_KEEP < m < b + PG_KEEP for a, b in PG):
                continue
        out.append(x)
    return out


def spread(cands, n):
    if n > len(cands):
        raise SystemExit(f"need {n} tracks, have {len(cands)}")
    if n <= 0:
        return []
    step = len(cands) / n
    return [cands[int((i + 0.5) * step)] for i in range(n)]


def main(src, dst):
    pin = re.compile(r"-pin_name \{(\S+)\} -layer (\S+) -location \{(\S+) (\S+)\}")
    keep, req = [], []  # verbatim lines; request ports (N name) in x order
    for line in open(src):
        m = pin.search(line)
        if not m:
            continue
        n, layer, x, y = m.group(1), m.group(2), float(m.group(3)), float(m.group(4))
        if n.startswith(("i_", "f_")):
            if n.startswith("i_"):
                req.append((x, n))
            continue
        keep.append((n, layer, x, y, line.rstrip("\n")))
    req = [n for _, n in sorted(req)]
    nreq = len(req)
    # return-pin occupancy in C (snapped track per layer)
    occ = {"M3": set(), "M5": set()}
    ret = {"M3": 0, "M5": 0}
    for n, layer, x, y, _ in keep:
        if y > 1 and layer in occ:
            off, p, _ = TR[layer]
            occ[layer].add(round(off + round((x - off) / p) * p, 4))  # the track place_pin snaps it to
            occ[layer].update(t for t in tracks(layer, x - 2 * p, x + 2 * p) if abs(t - x) < p - 1e-6)  # or, unsnapped, <= spacing
            ret[layer] += 1
    wa, wc, wb = XB0 - XA0, XC1 - XB1, XB1 - XB0
    # per-unit-D capacities: A_M3 = C_M3 = 100D (C minus its return M3), A_M5 = 100D - (WIN - wa)*D, C_M5 likewise minus return
    def quota(D):
        a3, a5 = WIN * D, WIN * D - (WIN - wa) * D
        c3, c5 = WIN * D - ret["M3"], WIN * D - (WIN - wc) * D - ret["M5"]
        b = wb * D
        return a3, a5, b, max(c3, 0), max(c5, 0)
    lo, hi = 1.0, 30.0
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if sum(quota(mid)) < nreq else (lo, mid)
    D = hi
    q = [int(v) for v in quota(D)]
    for i in range(nreq - sum(q)):  # rounding remainder, cycle over regions
        q[i % 5] += 1
    a3, a5, b5, c3, c5 = q
    pos = {
        "A": sorted([(x, "M3") for x in spread(tracks("M3", XA0, XB0), a3)] +
                    [(x, "M5") for x in spread(tracks("M5", XA0, XB0), a5)]),
        "B": [(x, "M5") for x in spread(tracks("M5", XB0, XB1), b5)],
        "C": sorted([(x, "M3") for x in spread([t for t in tracks("M3", XB1, XC1) if t not in occ["M3"]], c3)] +
                    [(x, "M5") for x in spread([t for t in tracks("M5", XB1, XC1) if t not in occ["M5"]], c5)]),
    }
    slots = pos["A"] + pos["B"] + pos["C"]
    assert len(slots) == nreq and len({s for s in slots}) == nreq
    cut = {"A": (a3 + a5) / CAP["A"], "B": b5 / CAP["B"], "C": (c3 + c5 + ret["M3"] + ret["M5"]) / CAP["C"]}
    with open(dst, "w") as f:
        f.write("# dsfd_vm_bgr28 v4c N/S pin plan, generated by physical/ref_tile_specs/ds_vm/gen_bgr28_pins.py (el1011-ds-vm/bgq28\n"
                f"# 2026-10-12): request pins spread at max {D:.2f} b/um/layer per 100-um window (v4b: A-region M3 13.2, FLOORPLAN_MARGIN).\n"
                f"# req A M3 {a3} M5 {a5} | B M5 {b5} | C M3 {c3} M5 {c5} (C also holds the return r_*/o_* pins, kept verbatim).\n"
                f"# cut ratios: A {cut['A']:.3f} B {cut['B']:.3f} C {cut['C']:.3f} (<= 0.57). i_X[b] (N) and f_X[b] (S) share x/layer.\n")
        for n, (x, layer) in zip(req, slots):
            size = TR[layer][2]
            for nm, y in ((n, H), ("f_" + n[2:], 0.0)):
                f.write(f"place_pin -pin_name {{{nm}}} -layer {layer} -location {{{x:.3f} {y}}} -pin_size {size} "
                        "-force_to_die_boundary\n")
        for *_, line in keep:
            f.write(line + "\n")
    print(f"D {D:.2f} quotas A3 {a3} A5 {a5} B5 {b5} C3 {c3} C5 {c5}; cut {cut}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
