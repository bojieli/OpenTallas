#!/usr/bin/env python3
"""s81coll_vm_boundary b8 pin plan (S-ELEM-PQ/COLL 10-16, VIS-ROM S81H-04): dataflow-aligned faces, NARROW ports.

W (VM seam) is kept byte-identical to b7 (t_crq / t_vm / read_* at the b7 M4 tracks).  Every E input lands at the y of
the t_vm bit it feeds (gather_data[j*512+b] -> t_vm[j*551+31+b], gather_rows[j*15+i] -> t_vm[j*551+1+i], gather_we[j]
-> t_vm[j*551] valid; tag / pack-check / mode bits on free t_vm-constant rows), so the E->W path is a straight row.
N and S are spread evenly over the face (M3/M5 alternating), source buses ordered from the W end (their destination
face): S raw_sources[k] (-> t_vm[k]) first, N reduced_data[b] (-> t_vm[31+b]) first; clock at the N-face centre.
b9 (--read-at-crq): read_slot / read_row move from the W top (y 231.8-233.2) to the W bottom right under t_crq
(t_crq = {read_row, read_slot} one register later): b8 routed with those registers beside read_row at y ~232 and
228 um of output wire to t_crq at y 4.4-5.8 (native launch t_crq[0] 253.4 ps > 220).
Usage: gen_vmb_aligned_pins.py B7_PINS.tcl OUT.tcl [--read-at-crq]
"""
import re, sys
W, H, MARGIN = 151.2, 237.6, 4.32
PITCH = {"M3": 0.036, "M5": 0.048}; OFF = {"M3": 0.009, "M5": 0.012}
SIZE = {"M3": (0.018, 0.144), "M5": (0.024, 0.192), "M4": (0.192, 0.024)}
b7, out = sys.argv[1], sys.argv[2]; READ_AT_CRQ = "--read-at-crq" in sys.argv[3:]
wy = {}
lines = ["# generated by physical/ref_tile_specs/s81coll_static/gen_vmb_aligned_pins.py (b8, NARROW=1): W = b7, E aligned "
         "to the t_vm destination row, N/S spread from the W end"]
for l in open(b7):
    m = re.search(r"-pin_name \{(\S+)\} -layer (\w+) -location \{([\d.]+) ([\d.]+)\}", l)
    if m and float(m.group(3)) == 0.0:                       # W face: keep as is
        if READ_AT_CRQ and m.group(1).startswith("read_"):
            continue
        wy[m.group(1)] = float(m.group(4)); lines.append(l.rstrip())
if READ_AT_CRQ:                                              # mirror t_crq = {read_row, read_slot} below t_crq[0]
    y0 = wy["t_crq[0]"]
    for i, p in enumerate(["read_slot"] + [f"read_row[{k}]" for k in range(14)]):
        y = round(y0 - 0.096 * (i + 1), 3); assert y > 2.0, y
        wy[p] = y
        lines.append(f"place_pin -pin_name {{{p}}} -layer M4 -location {{0.000 {y:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary")
def tv(i): return wy[f"t_vm[{i}]"]
E = {}
for j in range(4):
    E[f"gather_we[{j}]"] = tv(j * 551)
    for i in range(15):
        E[f"gather_rows[{j*15+i}]"] = tv(j * 551 + 1 + i)       # i = 14 (pack check) -> the first constant row bit
    for b in range(512):
        E[f"gather_data[{j*512+b}]"] = tv(j * 551 + 31 + b)
for k in range(8):
    E[f"gather_tag[{k}]"] = tv(1 * 551 + 543 + k)               # tag feeds all 4 words: centre it (word 1 tag rows)
E["commit_gather"] = tv(2 * 551 + 16); E["hc_reduce_slot"] = tv(2 * 551 + 17)   # mode bits, mid-face constant rows
assert len(set(E.values())) == len(E), "E collision"
for p, y in E.items():
    lines.append(f"place_pin -pin_name {{{p}}} -layer M4 -location {{{W:.3f} {y:.3f}}} -pin_size {{0.192 0.024}} -force_to_die_boundary")
def vec(n, w): return [f"{n}[{i}]" for i in range(w)]
faces = {
 "S": vec("raw_sources", 1102) + vec("phy_rx_fault", 8) + vec("phy_rx_valid", 8) + vec("phy_rx_live", 8) +
      ["issue_slot", "raw_capture", "raw_capture_payload_slot", "raw_capture_meta_slot"] + vec("raw_tx_count", 3) +
      vec("host_rx", 2) + ["pack_bad_out", "fault"],
 "N": vec("reduced_data", 512) + vec("reduced_tag", 8) + ["hc_write_slot", "reduced_valid", "reduced_error", "reduced_last"] +
      vec("reduced_seq", 16) + vec("hc_expect_seq", 16) + ["hc_expect_last", "rst_n"],
}
faces["N"].insert(len(faces["N"]) // 2, "clk")
for face, bits in faces.items():
    step = (W - 2 * MARGIN) / len(bits); assert step >= 0.072, (face, step)
    used = set(); y = 0.0 if face == "S" else H
    for i, b in enumerate(bits):
        L = "M3" if i % 2 == 0 else "M5"
        c = MARGIN + step * (i + 0.5)
        x = round(round((c - OFF[L]) / PITCH[L]) * PITCH[L] + OFF[L], 3)
        while (L, x) in used: x = round(x + PITCH[L], 3)
        used.add((L, x)); sx, sy = SIZE[L]
        lines.append(f"place_pin -pin_name {{{b}}} -layer {L} -location {{{x:.3f} {y:.3f}}} -pin_size {{{sx} {sy}}} -force_to_die_boundary")
    print(face, len(bits), f"{len(bits)/(W-2*MARGIN):.2f} pins/um")
print("W", len(wy), "E", len(E))
open(out, "w").write("\n".join(lines) + "\n")
print("pins", len(lines) - 1, "->", out)
