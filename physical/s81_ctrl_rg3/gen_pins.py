# DRIVE-S81-IDX4-KITS 10-20: s81ctrl_rg3 pin plans from the n32s plan (dsfd_ctrl_rg2_n32s_pins.tcl).
#  mode n: N face re-pinned per PC half: PC0 rq[0:340] rd[0:279] rrq[0:45] rrd[0:271] | clk ck_o | PC1 rq[341:681] rd[280:561]
#          rrq[46:91] rrd[272:543]; alternating M3/M5 on their tracks; S / W faces = n32s exactly.
#  mode s: every n32s pin unchanged; rrq (92) on the W face, rrd (544) on the E face (M4 tracks, rst_n kept at W y 162).
import re, sys
src, mode, out = sys.argv[1], sys.argv[2], sys.argv[3]
W, H = 388.8, 324.0
lines = open(src).read().splitlines()
hdr = [l for l in lines if l.startswith('#')]
pins = [l for l in lines if l.startswith('place_pin')]
def nm(l): return re.search(r'-pin_name \{([^}]*)\}', l).group(1)
def ycoord(l): return float(re.search(r'-location \{[\d.]+ ([\d.]+)\}', l).group(1))
M3 = ('M3', 0.009, 0.036, '{0.018 0.144}'); M5 = ('M5', 0.012, 0.048, '{0.024 0.192}'); M4 = ('M4', 0.012, 0.048, '{0.192 0.024}')
def snap(L, v, lo):
    k = max(0, round((v - L[1]) / L[2]))
    x = L[1] + k * L[2]
    while x < lo: k += 1; x = L[1] + k * L[2]
    return round(x, 3)
res = ['# DRIVE-S81-IDX4-KITS 10-20: dsfd_ctrl_rg3 pin plan mode %s, generated by gen_pins.py from dsfd_ctrl_rg2_n32s_pins.tcl' % mode]
if mode == 'n':
    keep = [l for l in pins if ycoord(l) != H]
    seq = ([f'rq[{i}]' for i in range(341)] + [f'rd[{i}]' for i in range(280)] + [f'rrq[{i}]' for i in range(46)] + [f'rrd[{i}]' for i in range(272)]
           + ['clk', 'ck_o'] + [f'rq[{i}]' for i in range(341, 682)] + [f'rd[{i}]' for i in range(280, 562)]
           + [f'rrq[{i}]' for i in range(46, 92)] + [f'rrd[{i}]' for i in range(272, 544)])
    x0, x1 = 4.545, 384.27
    st = (x1 - x0) / (len(seq) - 1)
    last = {'M3': -1.0, 'M5': -1.0}
    for i, p in enumerate(seq):
        L = M3 if i % 2 == 0 else M5
        x = snap(L, x0 + i * st, last[L[0]] + 0.3)
        last[L[0]] = x
        res.append(f'place_pin -pin_name {{{p}}} -layer {L[0]} -location {{{x:.3f} {H:.3f}}} -pin_size {L[3]} -force_to_die_boundary')
    assert max(last.values()) < W - 1, last
    res += keep
else:
    res += pins
    for face, xx, seq in (('W', 0.0, [f'rrq[{i}]' for i in range(92)]), ('E', W, [f'rrd[{i}]' for i in range(544)])):
        y0, y1 = 6.0, H - 6.0
        st = (y1 - y0) / (len(seq) - 1)
        prev = -1.0
        for i, p in enumerate(seq):
            y = snap(M4, y0 + i * st, prev + 0.3)
            if face == 'W' and abs(y - 162.0) < 0.5: y = snap(M4, 162.6, prev + 0.3)
            prev = y
            res.append(f'place_pin -pin_name {{{p}}} -layer M4 -location {{{xx:.3f} {y:.3f}}} -pin_size {M4[3]} -force_to_die_boundary')
open(out, 'w').write('\n'.join(res) + '\n')
print(mode, len(res) - 1, 'pins')
