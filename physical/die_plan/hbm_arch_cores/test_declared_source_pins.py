"""Native source pin contracts must survive emission and canonical checking."""
from pathlib import Path
import json
import sys
import tempfile
import unittest
import importlib.util

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[2] / "tools/die_plan"))
import gen_core_kit_hbm as G
import kit_contract as K


class DeclaredSourcePins(unittest.TestCase):
    def setUp(self):
        self.pins = [dict(name="d[0]", layer="M4", x=.096, y=5),
                     dict(name="clk", layer="M5", x=30.012, y=50),
                     dict(name="clk_e", layer="M5", x=35.016, y=.24, w=.048, h=.48),
                     dict(name="rst_n", layer="M5", x=96.712, y=73.181)]
        self.io, self.rows = G.declared_source_io_tcl(
            self.pins, 100, 100, "native", {"clk", "clk_e"}, {"rst_n"})
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.kit = Path(self.tmp.name)
        (self.kit / "io.tcl").write_text(self.io)
        (self.kit / "pins.json").write_text(json.dumps(self.rows))

    def test_exact_declared_points_and_shapes_match_canonical_contract(self):
        self.assertEqual(K._canon(K.placed_pins(self.kit), [100, 100]),
                         K._canon(self.pins, [100, 100]))
        self.assertIn("-location {96.7120 73.1810}", self.io)
        self.assertIn("-location {30.0120 50.0000}", self.io)

    def test_actual_emitted_shape_is_checked_not_metadata_claim(self):
        (self.kit / "io.tcl").write_text(
            self.io.replace("-pin_size {0.0480 0.4800}", "-pin_size {0.0960 0.4800}"))
        pins = {p["name"]: p for p in K.placed_pins(self.kit)}
        self.assertEqual(pins["clk_e"]["w"], .096)
        self.assertNotEqual(K._canon(list(pins.values()), [100, 100]),
                            K._canon(self.pins, [100, 100]))

    def test_missing_emitted_shape_fails_closed(self):
        (self.kit / "io.tcl").write_text(
            self.io.replace("-pin_size {0.0480 0.4800}", ""))
        with self.assertRaisesRegex(ValueError, "no emitted pin_size"):
            K.placed_pins(self.kit)

    def test_legacy_io_and_parser_are_unchanged_without_optin(self):
        io, rows = G.io_tcl([self.pins[0]], 100, 100, "legacy")
        self.assertEqual(io,
            "# GENERATED by gen_core_kit_hbm.py: exact plan pins of legacy (1 pins, core frame um).\n"
            "place_pin -pin_name {d[0]} -layer M4 -location {0.0960 5.0000} "
            "-pin_size {0.1920 0.0240}\n")
        (self.kit / "io.tcl").write_text(io)
        (self.kit / "pins.json").write_text(json.dumps(rows))
        self.assertEqual(K.placed_pins(self.kit), [self.pins[0]])

    def test_staged_audit_consumes_native_interior_and_scalar_pins(self):
        G.stage_pin_audit(self.kit)
        spec = importlib.util.spec_from_file_location("staged_native_pin_audit", self.kit / "pin_audit_core.py")
        audit = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(audit)
        p = dict(bus="clk", bit=None, layer="M5", x=30.012, y=50, face="I")
        self.assertEqual(audit.pin_key(p), "clk")
        self.assertTrue(audit.box_ok(p, (29.988, 49.76, 30.036, 50.24), 100, 100))
        self.assertFalse(audit.box_ok(p, (30.036, 49.76, 30.084, 50.24), 100, 100))


if __name__ == "__main__":
    unittest.main()
