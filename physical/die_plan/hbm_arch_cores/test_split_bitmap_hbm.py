#!/usr/bin/env python3
"""HBM-CORES-KITS-5 split3: bit-level cut map for remainder split cores.
gen_core_kit_hbm.build_wrapper accepts slice lists [[top port, port lsb, plan lsb, n], ...] (opt-in,
canonical_bitmap_split.json); whole-bus maps give byte-identical text (golden from main 8b172e6b98);
split_bitmap.build maps plan bits to RTL bits by net identity.
  python3 -m pytest physical/die_plan/hbm_arch_cores/test_split_bitmap_hbm.py"""
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "hbm" / "cores" / "harden"))
import gen_core_kit_hbm as GK  # noqa: E402
import split_bitmap as SB  # noqa: E402

PB = {"a": (8, False), "b": (1, True), "y": (4, False)}
TP = [("ta", "input", 8), ("tb", "input", 1), ("ty", "output", 4), ("tz", "output", 2), ("ts", "input", 3)]
# text of build_wrapper on origin/main 8b172e6b98 (before slice support) for the same call
GOLDEN = ("// GENERATED by gen_core_kit_hbm.py (ELEM-HBM): pass-through wrapper, plan pins -> RTL top; wires only.\n"
          "`default_nettype none\nmodule m (\n    input wire [7:0] a,\n    input wire b,\n    output wire [3:0] y\n);\n"
          "    top #(.P(2)) u_core (\n        .ta(a),\n        .tb(b),\n        .ty(y),\n        .ts(3'b101));\n"
          "endmodule\n`default_nettype wire\n")


def test_whole_bus_byte_identical():
    txt, rep = GK.build_wrapper("m", PB, "top", {"P": 2}, TP, cmap={"a": {"ta": 8}, "b": {"tb": 1}, "y": {"ty": 4}},
                                straps={"ts": "101"})
    assert txt == GOLDEN
    assert rep == dict(open_outputs=["tz[2]"], tied_inputs=[], straps={"ts": "101"}, mapped=13)


def test_one_full_slice_is_a_rename():
    cm = {"a": [["ta", 0, 0, 8]], "b": [["tb", 0, 0, 1]], "y": [["ty", 0, 0, 4]]}
    txt, _ = GK.build_wrapper("m", PB, "top", {"P": 2}, TP, cmap=cm, straps={"ts": "101"})
    assert txt == GOLDEN


SPB = {"xa": (4, False), "xb": (4, False), "ya": (2, False), "yb": (2, False), "s": (1, True)}
STP = [("tx", "input", 8), ("ty", "output", 4), ("ts", "input", 1)]


def test_slices_regroup_both_directions():
    cm = {"xa": [["tx", 4, 0, 4]], "xb": [["tx", 0, 0, 4]],
          "ya": [["ty", 2, 0, 2]], "yb": [["ty", 0, 1, 1], ["ty", 1, 0, 1]], "s": {"ts": 1}}
    txt, rep = GK.build_wrapper("m", SPB, "top", {}, STP, cmap=cm)
    assert "    wire [7:0] __s_tx;" in txt and "    wire [3:0] __s_ty;" in txt
    assert "    assign __s_tx[3:0] = xb[3:0];" in txt and "    assign __s_tx[7:4] = xa[3:0];" in txt
    assert "    assign ya[1:0] = __s_ty[3:2];" in txt
    assert "    assign yb[1] = __s_ty[0];" in txt and "    assign yb[0] = __s_ty[1];" in txt
    assert "    top u_core (\n        .ts(s),\n        .tx(__s_tx),\n        .ty(__s_ty));" in txt
    assert "    output wire [1:0] ya" in txt and "    input wire [3:0] xa" in txt
    assert rep["mapped"] == 13 and rep["open_outputs"] == []


@pytest.mark.parametrize("cm,msg", [
    ({"xa": [["tx", 4, 0, 4]], "xb": [["tx", 3, 0, 4]]}, "not driven exactly once"),           # tx[3] twice, tx[7]? no
    ({"xa": [["tx", 4, 0, 4]], "xb": [["tx", 0, 0, 3]]}, "not driven exactly once"),           # tx[3] undriven
    ({"xa": [["tx", 4, 0, 4]], "xb": [["tx", 0, 0, 4]], "ya": [["ty", 2, 0, 1]]}, "not driven exactly once"),
    ({"xa": [["tx", 6, 0, 4]], "xb": [["tx", 0, 0, 4]]}, "out of range"),
    ({"xa": [["tx", 4, 0, 4]], "xb": [["nope", 0, 0, 4]]}, "not a port"),
])
def test_slices_fail_closed(cm, msg):
    base = {"xa": None, "xb": None, "ya": [["ty", 2, 0, 2]], "yb": [["ty", 0, 0, 2]], "s": {"ts": 1}}
    base.update(cm)
    with pytest.raises(SystemExit, match=msg):
        GK.build_wrapper("m", SPB, "top", {}, STP, cmap=base)


def test_slice_and_whole_on_one_port_refused():
    cm = {"xa": [["tx", 4, 0, 4]], "xb": [["tx", 0, 0, 4]], "ya": [["ty", 2, 0, 2]], "yb": [["ty", 0, 0, 2]],
          "s": {"ts": 1}}
    pb = dict(SPB, z=(8, False))
    with pytest.raises(SystemExit, match="reached twice"):
        GK.build_wrapper("m", pb, "top", {}, STP, cmap=dict(cm, z={"tx": 8}))


# split_bitmap: master {ro_x_n, ro_x_w} = a_ro_x (face re-slicing alias); the rest top regroups a_ro_x as one port
MASTER = {"modules": {"mtop": {"netnames": {
    "u_core.a_ro_x": {"bits": list(range(2, 10))},
    "ro_x_n": {"bits": [2, 3, 4, 5]}, "ro_x_w": {"bits": [6, 7, 8, 9]},
    "u_core.q": {"bits": [10, 11]}, "k": {"bits": ["1", "1"]}}, "cells": {}}}}
REST = """module rtop (
    input wire [7:0] u_core_a_ro_x,
    output wire [1:0] u_core_q,
    input wire [1:0] k
);
    rtop_x u_x (
""" + "".join(f"        .\\u_core.a_ro_x[{i}] (u_core_a_ro_x[{7 - i}]),\n" for i in range(8)) + """        .\\u_core.q[0] (u_core_q[0]),
        .\\u_core.q[1] (u_core_q[1])
    );
endmodule
"""


def test_bitmap_by_net_identity():
    cut = [["ro_x_n", "input", 4, 0], ["ro_x_w", "input", 4, 0], ["x_u_core_q", "output", 2, 0],
           ["k", "input", 2, 0]]
    r = SB.build(MASTER, "mtop", REST, "rtop", cut, dict(cut_pins={"k": {"k": 2}}))
    s = r["slices"]
    assert s["ro_x_n"] == [["u_core_a_ro_x", 7, 0, 1], ["u_core_a_ro_x", 6, 1, 1], ["u_core_a_ro_x", 5, 2, 1],
                           ["u_core_a_ro_x", 4, 3, 1]]
    assert s["ro_x_w"][0] == ["u_core_a_ro_x", 3, 0, 1]
    assert s["x_u_core_q"] == [["u_core_q", 0, 0, 2]]
    assert s["k"] == [["k", 0, 0, 2]] and "CONST_NET" in r["check"]["notes"]["k"]
    assert r["check"]["verdict"] == "PASS" and r["check"]["n_rtl_inputs_uncovered"] == 0
    # the result drives build_wrapper
    pb = {c: (w, False) for c, _, w, _ in cut}
    txt, _ = GK.build_wrapper("m", pb, "rtop", {}, [("u_core_a_ro_x", "input", 8), ("u_core_q", "output", 2),
                                                     ("k", "input", 2)], cmap=s)
    assert "    assign __s_u_core_a_ro_x[7] = ro_x_n[0];" in txt


def test_bitmap_unknown_bus_fails():
    r = SB.build(MASTER, "mtop", REST, "rtop", [["ro_x_n", "input", 4, 0], ["nobody", "input", 3, 0]])
    assert r["check"]["verdict"] == "FAIL" and any("nobody" in p for p in r["check"]["problems"])
