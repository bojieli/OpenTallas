#!/usr/bin/env python3
"""dcap_hot_boxes.py (DIE-HBM-97-PS10): local std-cell density cap for the hot routing channels of a macro-field core.

Input : the kit macro_placement.tcl (place_macro table), the macro LEF size, a GRT congestion report (congestion*.rpt).
Method: the free channels of the macro grid (row gaps and column channels, split per macro) are the only places
        std cells can sit.  A channel rectangle is hot when >= --min-markers GRT markers lie within --halo um of it
        (most markers of a macro-field core sit on M5/M6 over the macro bodies, driven by the cells in the channel next to them).
Output: JSON {boxes:[[x0,y0,x1,y1,n_markers]], cap_pct} and, with --tcl, a PRE_GLOBAL_PLACE hook
        (--pre-gpl-extra) that creates one partial placement blockage per box with -max_density cap_pct
        (global placement caps the bin density; detail placement does not treat a partial blockage as a keep-out).
"""
import argparse, json, re, sys

def macros(tcl, w, h):
    out = []
    for m in re.finditer(r'\{(\S+)\}\s+(\S+)\s+([\d.]+)\s+([\d.]+)\s+(R0|MY|MX|R180|R90|R270)', open(tcl).read()):
        o = m.group(5); ww, hh = (h, w) if o in ("R90", "R270") else (w, h)
        x, y = float(m.group(3)), float(m.group(4)); out.append((x, y, x + ww, y + hh))
    return out

def markers(rpt):
    mk = []
    for l in open(rpt, errors="replace"):
        if "bbox" in l:
            v = re.findall(r"[\d.]+", l); mk.append(((float(v[0]) + float(v[2])) / 2, (float(v[1]) + float(v[3])) / 2))
    return mk

def channels(ms, die, min_w=3.0):
    xs = sorted({round(m[0], 3) for m in ms} | {round(m[2], 3) for m in ms})
    ys = sorted({round(m[1], 3) for m in ms} | {round(m[3], 3) for m in ms})
    xs = [die[0]] + xs + [die[2]]; ys = [die[1]] + ys + [die[3]]
    # elementary grid cells that no macro covers, merged along the long direction
    cells = []
    for i in range(len(xs) - 1):
        for j in range(len(ys) - 1):
            x0, x1, y0, y1 = xs[i], xs[i + 1], ys[j], ys[j + 1]
            if x1 - x0 < 0.5 or y1 - y0 < 0.5: continue
            cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
            if any(m[0] < cx < m[2] and m[1] < cy < m[3] for m in ms): continue
            cells.append([x0, y0, x1, y1])
    return cells

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--placement", required=True); ap.add_argument("--report", required=True)
    ap.add_argument("--macro-w", type=float, default=96.552); ap.add_argument("--macro-h", type=float, default=69.66)
    ap.add_argument("--die", type=float, nargs=4, default=[4.32, 4.32, 570.24, 734.4])
    ap.add_argument("--min-markers", type=int, default=400); ap.add_argument("--halo", type=float, default=30.0); ap.add_argument("--cap-pct", type=float, default=15.0)
    ap.add_argument("--json"); ap.add_argument("--tcl"); ap.add_argument("--release-tcl", help="POST_GLOBAL_PLACE hook: destroys the partial blockages after global placement (DPL treats them as keep-outs)")
    a = ap.parse_args()
    ms = macros(a.placement, a.macro_w, a.macro_h); mk = markers(a.report)
    cells = channels(ms, a.die)
    boxes = []
    for c in cells:
        h = a.halo; n = sum(1 for x, y in mk if c[0] - h <= x <= c[2] + h and c[1] - h <= y <= c[3] + h)
        if n >= a.min_markers: boxes.append([round(v, 3) for v in c] + [n])
    boxes.sort(key=lambda b: -b[4])
    tot = len(mk)
    print(f"{len(ms)} macros, {len(cells)} free grid cells, {tot} markers, {len(boxes)} hot boxes, {sum((b[2]-b[0])*(b[3]-b[1]) for b in boxes):.0f} um2", file=sys.stderr)
    if a.json: json.dump({"cap_pct": a.cap_pct, "min_markers": a.min_markers, "halo_um": a.halo, "boxes": boxes}, open(a.json, "w"), indent=1)
    if a.tcl:
        L = ["# GENERATED by dcap_hot_boxes.py (DIE-HBM-97-PS10): partial placement density cap in the hot routing channels",
             "# (--pre-gpl-extra hook; max_density blockage = global placement density cap).",
             "# ORFS sources hooks inside a proc: run at global scope. Idempotent: the 3_1 odb already carries the blockages.",
             "uplevel #0 {",
             "set ot_dc_blk [ord::get_db_block]",
             "set ot_dc_have 0",
             "foreach b [$ot_dc_blk getBlockages] { if {[$b getMaxDensity] > 0} { incr ot_dc_have } }",
             "if {$ot_dc_have == 0} {"]
        for b in boxes:
            L.append(f"  create_blockage -region {{{b[0]} {b[1]} {b[2]} {b[3]}}} -max_density {a.cap_pct:g}")
        L += [f'  puts "OT-DCAP: {len(boxes)} partial blockages, max_density {a.cap_pct:g} %"', "} else { puts \"OT-DCAP: $ot_dc_have partial blockages already present\" }", "}"]
        if a.release_tcl:
            open(a.release_tcl, "w").write("# GENERATED by dcap_hot_boxes.py: POST_GLOBAL_PLACE, remove the density-cap blockages before resize / detail placement\n"
                "uplevel #0 {\nset ot_dc_blk [ord::get_db_block]; set ot_dc_n 0\n"
                "foreach b [$ot_dc_blk getBlockages] { if {[$b getMaxDensity] > 0} { odb::dbBlockage_destroy $b; incr ot_dc_n } }\n"
                "puts \"OT-DCAP: released $ot_dc_n partial blockages\"\n}\n")
        open(a.tcl, "w").write("\n".join(L) + "\n")
if __name__ == "__main__": main()
