#!/usr/bin/env python3
"""HBM-FACE 10-25: equivalence bench of a face-register shell (face_shell.py) against its core, modulo the added latency.

    face_shell_bench.py KITDIR [--cycles 30000] [--seed 1] [--out DIR]       (Verilator 5.050; heavy: through ot-run)

Reference = the unshelled core <module>__fcore fed with every input delayed by one clock (TB register) and its outputs
delayed by one clock (TB register): Z o core o Z.  DUT = the generated shell <module> (plan pins minus dropped bits).
Both cores get the same clock and the same (undelayed) reset, so their internal state is cycle-identical and every
signal output must match exactly on every cycle (2-state Verilator, --x-initial fast: both zero-initialised).
Dropped (unread) input bits get RANDOM values at the reference and nothing at the DUT (the shell drives 0), so the bench
also checks the 'unread' claim.  Stimulus phases: dense random, sparse random (p=1/16 per bit), held buses with rare
changes; reset asserted at start and once mid-run.

Pass 1: shell vs reference -> 0 mismatches required; records output bits that toggled.
Pass 2: three MUTANT shells (generated by face_shell.emit_shell) vs the same reference, each must be caught:
  in_bypass  = the highest-fanout input bit skips its face flop (dropped input flop),
  out_bypass = a toggling output bit skips its face flop (dropped output flop),
  out_delay2 = that output bus gets two flops (wrong delay).
Writes OUT/bench.json (verdict PASS = pass 1 clean AND every mutant caught).
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(HERE))
import face_shell as FS  # noqa: E402

VERILATOR = str(Path.home() / ".local/opentallas-tools/bin/verilator")


def rst_active_low(n):
    return bool(re.search(r"(_n|n)$", n))


def tb_text(J, dut_mods, cycles, seed):
    """dut_mods: [(module_name, instance_tag)] shells to compare against one reference core."""
    W, D, K = J["widths"], J["dirs"], J["keep"]
    pas = set(J["passthrough"])
    core, params = J["core"], J["params"]
    clks = [n for n in W if n in pas and D[n] == "input" and not re.search(r"rst|reset", n)]
    rsts = [n for n in W if n in pas and D[n] == "input" and n not in clks]
    ins = [n for n in W if D[n] == "input" and n not in pas]
    outs = [n for n in W if D[n] == "output"]
    sig_outs = [n for n in outs if n not in pas]
    pas_outs = [n for n in outs if n in pas]
    L = ["`timescale 1ns/1ps", "module tb;", "  reg clk = 1'b0;", "  always #5 clk = ~clk;",
         "  reg rst_a;  // active reset (1 = in reset)", "  integer cyc = 0, phase = 0;"]
    for n in ins:
        L.append(f"  reg [{W[n] - 1}:0] i_{n}, d_{n};")
    for n in outs:
        L.append(f"  wire [{W[n] - 1}:0] r_{n};")
        L.append(f"  reg  [{W[n] - 1}:0] rd_{n};")
        L.append(f"  reg  [{W[n] - 1}:0] tg_{n};  // toggled bits (reference, after reset)")
        for _, t in dut_mods:
            L.append(f"  wire [{W[n] - 1}:0] {t}_{n};")
    for _, t in dut_mods:
        L.append(f"  integer mis_{t} = 0, first_{t} = -1;")
    prm = (" #(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ")") if params else ""

    def pconn(n, src_in, out_pfx, dut):
        if n in clks:
            return f".{n}(clk)"
        if n in rsts:
            return f".{n}({'~rst_a' if rst_active_low(n) else 'rst_a'})"
        if D[n] == "input":
            if dut:
                k = K[n]
                return None if k == 0 else (f".{n}({src_in}{n})" if k == W[n] else f".{n}({src_in}{n}[{k - 1}:0])")
            return f".{n}({src_in}{n})"
        return f".{n}({out_pfx}_{n})"

    L.append(f"  {core}{prm} u_ref (" + ", ".join(c for c in (pconn(n, 'd_', 'r', False) for n in W) if c) + ");")
    for m, t in dut_mods:
        L.append(f"  {m} u_{t} (" + ", ".join(c for c in (pconn(n, 'i_', t, True) for n in W) if c) + ");")
    # stimulus at negedge
    L.append("  task automatic stim;")
    L.append("    begin")
    for n in ins:
        w = W[n]
        ch = (w + 31) // 32
        rnd = "{" + ", ".join(["$urandom"] * ch) + "}"
        L.append(f"      if (phase == 0) i_{n} = {w}'({rnd});")
        L.append(f"      else if (phase == 1) i_{n} = {w}'({rnd}) & {w}'({rnd}) & {w}'({rnd}) & {w}'({rnd});")
        L.append(f"      else if (($urandom % 8) == 0) i_{n} = {w}'({rnd});")
    L.append("    end")
    L.append("  endtask")
    L.append("  always @(posedge clk) begin")
    for n in ins:
        L.append(f"    d_{n} <= i_{n};")
    for n in sig_outs:
        L.append(f"    rd_{n} <= r_{n};")
    L.append("  end")
    L.append("  initial begin")
    L.append(f"    void'($urandom({seed}));")
    for n in ins:
        L.append(f"    i_{n} = '0; d_{n} = '0;")
    for n in outs:
        L.append(f"    tg_{n} = '0;")
    L.append("    rst_a = 1'b1;")
    L.append(f"    for (cyc = 0; cyc < {cycles}; cyc = cyc + 1) begin")
    L.append("      @(negedge clk);")
    mid = cycles // 2
    L.append(f"      rst_a = (cyc < 8) || (cyc >= {mid} && cyc < {mid + 3});")
    L.append("      phase = (cyc / 997) % 3;")
    # compare (outputs settled after the posedge): skip the first 4 cycles (TB delay registers start at zero)
    L.append("      if (cyc > 4) begin")
    for n in sig_outs:
        L.append(f"        tg_{n} = tg_{n} | (rd_{n} ^ r_{n});")
        for _, t in dut_mods:
            L.append(f"        if ({t}_{n} !== rd_{n}) begin mis_{t} = mis_{t} + 1; if (first_{t} < 0) begin "
                     f"first_{t} = cyc; $display(\"MISMATCH {t} {n} cyc %0d dut %h exp %h\", cyc, {t}_{n}, rd_{n}); end end")
    for n in pas_outs:
        for _, t in dut_mods:
            L.append(f"        if ({t}_{n} !== r_{n}) begin mis_{t} = mis_{t} + 1; if (first_{t} < 0) first_{t} = cyc; end")
    L.append("      end")
    L.append("      stim();")
    L.append("    end")
    for _, t in dut_mods:
        L.append(f"    $display(\"RESULT {t} mismatches %0d first %0d\", mis_{t}, first_{t});")
    for n in sig_outs:
        L.append(f"    $display(\"TOGGLE {n} %0d %b\", $countones(tg_{n}), tg_{n});")
    L.append("    $finish;")
    L.append("  end")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def macro_models(fz):
    out = []
    for m in fz.get("macros", []):
        for d in REPO.glob(f"physical/asap7_memory_macros*/{m}"):
            if (d / f"{m}.v").is_file():
                out.append(str(d / f"{m}.v"))
                break
        else:
            raise SystemExit(f"no behavioural model for macro {m}")
    return out


def build_run(bd, kd, J, fz, dut_mods, shells, cycles, seed, jobs, tag):
    wd = bd / tag
    if wd.exists():
        shutil.rmtree(wd)
    wd.mkdir(parents=True)
    (wd / "tb.sv").write_text(tb_text(J, dut_mods, cycles, seed))
    cfg = (kd / "config.mk").read_text()
    files = [str(kd / "rtl" / Path(f).name) for f in re.search(r"VERILOG_FILES = (.*)", cfg).group(1).split()]
    defs = re.search(r"VERILOG_DEFINES = (.*)", cfg).group(1).split()
    for i, (name, txt) in enumerate(shells):
        p = wd / f"{name}.sv"
        p.write_text(txt)
        files.append(str(p))
    files += macro_models(fz)
    cmd = [VERILATOR, "--binary", "--timing", "-Wno-fatal", "-Wno-lint", "-Wno-style", "-Wno-MULTIDRIVEN",
           "--x-assign", "fast", "--x-initial", "fast", "--top-module", "tb", "-O1", "--build-jobs", str(jobs),
           "-CFLAGS", "-O1", f"-I{kd / 'rtl'}", "--Mdir", str(wd / "obj"), *defs, str(wd / "tb.sv"), *files]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=wd)
    (wd / "build.log").write_text(r.stdout[-50000:] + r.stderr[-50000:])
    if r.returncode:
        raise SystemExit(f"verilator build {tag} failed (see {wd}/build.log):\n{r.stderr[-2000:]}")
    r = subprocess.run([str(wd / "obj" / "Vtb")], capture_output=True, text=True, cwd=wd)
    (wd / "sim.log").write_text(r.stdout[-200000:] + r.stderr[-20000:])
    res, tog = {}, {}
    for ln in r.stdout.splitlines():
        m = re.match(r"RESULT (\S+) mismatches (\d+) first (-?\d+)", ln)
        if m:
            res[m[1]] = dict(mismatches=int(m[2]), first_cycle=int(m[3]))
        m = re.match(r"TOGGLE (\S+) (\d+) ([01]+)", ln)
        if m:
            tog[m[1]] = (int(m[2]), m[3])
    if r.returncode or not res:
        raise SystemExit(f"sim {tag} failed rc {r.returncode}: {r.stdout[-1500:]} {r.stderr[-1500:]}")
    first = [ln for ln in r.stdout.splitlines() if ln.startswith("MISMATCH")][:6]
    return res, tog, first


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kit")
    ap.add_argument("--cycles", type=int, default=30000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    kd = Path(a.kit).resolve()
    J = json.loads((kd / "face_shell.json").read_text())
    fz = json.loads((kd / "freeze.json").read_text())
    bd = Path(a.out or (kd / "face_shell_bench")).resolve()
    bd.mkdir(parents=True, exist_ok=True)
    module = J["module"]
    # pass 1: the generated shell (as in the kit) vs reference
    res1, tog, first1 = build_run(bd, kd, J, fz, [(module, "dut")], [], a.cycles, a.seed, a.jobs, "pass1")
    W, D, K = J["widths"], J["dirs"], J["keep"]
    pas = set(J["passthrough"])
    tog_out = {n: v for n, v in tog.items()}
    toggled_bits = sum(v[0] for v in tog_out.values())
    total_out = sum(W[n] for n in W if D[n] == "output" and n not in pas)
    # mutant targets
    best = max(tog_out.items(), key=lambda kv: kv[1][0]) if tog_out else None
    mut = []
    if J["top_fanout_in"]:
        b = J["top_fanout_in"][0][1]
        bus, bit = re.match(r"^(.*)\[(\d+)\]$", b).groups()
        mut.append(dict(kind="in_bypass", bus=bus, bit=int(bit)))
    if best and best[1][0] > 0:
        bus, (cnt, bits) = best
        bit = len(bits) - 1 - bits.index("1")       # lowest... any toggled bit: take the first '1' from msb -> index
        mut.append(dict(kind="out_bypass", bus=bus, bit=bit))
        mut.append(dict(kind="out_delay2", bus=bus, bit=0))
    shells, mods = [], []
    for i, m in enumerate(mut):
        name = f"{module}__mut{i}"
        txt = FS.emit_shell(name, J["core"], J["params"], W, D, K, pas, J["clock"], m, set(J["scalars"]))
        shells.append((name, txt))
        mods.append((name, f"m{i}"))
    res2, _, first2 = build_run(bd, kd, J, fz, mods, shells, a.cycles, a.seed, a.jobs, "pass2") if mods else ({}, {}, [])
    mutants = []
    for i, m in enumerate(mut):
        r = res2.get(f"m{i}", {})
        mutants.append(dict(m, mismatches=r.get("mismatches"), first_cycle=r.get("first_cycle"),
                            caught=bool(r.get("mismatches"))))
    ok1 = res1.get("dut", {}).get("mismatches") == 0
    verdict = "PASS" if ok1 and len(mutants) == 3 and all(m["caught"] for m in mutants) else "FAIL"
    rep = dict(schema="opentallas.hbm_arch.face_shell_bench.v1", kit=str(kd), view=fz["view"], module=module,
               simulator="verilator 5.050 (2-state, x-initial fast)", cycles=a.cycles, seed=a.seed,
               reference="Z o core o Z (inputs and outputs delayed one clock in the TB; reset undelayed)",
               shell=res1.get("dut"), shell_first_mismatches=first1,
               dropped_in_bits=len(J["dropped"]), dropped_driven_random_at_reference=True,
               out_bits=total_out, out_bits_toggled=toggled_bits,
               mutants=mutants, mutant_first_mismatches=first2, verdict=verdict,
               kit_hash=fz.get("kit_hash"))
    (bd / "bench.json").write_text(json.dumps(rep, indent=1) + "\n")
    print(f"FACE_SHELL_BENCH {verdict} {module}: shell mismatches {res1.get('dut')} toggled {toggled_bits}/{total_out}; "
          f"mutants " + ", ".join(f"{m['kind']}:{m['bus']}[{m['bit']}] caught={m['caught']} ({m['mismatches']})" for m in mutants))
    return 0 if verdict == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
