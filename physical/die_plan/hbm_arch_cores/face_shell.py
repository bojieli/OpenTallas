#!/usr/bin/env python3
"""HBM-FACE 10-25: per-core FACE-REGISTER SHELL for HBM hard-core kits (owner rule "register every tile pin by default";
face_guard R2: every core pin bit has its OWN flop at the face).

Why: 348/370 synthesised HBM core kits failed face_guard (HBM-CORES 10-24) because the core RTL was cut out of die logic
at unregistered module ports: inputs fanning out to several loads ('shared'), inputs straight into logic
('unregistered'), outputs that are copies of one register ('merged', e.g. argmax vm_rq), port-to-port wires
('feedthrough') and input bits nothing reads ('dropped').  The shell fixes all of them structurally, without touching
the core RTL:

    <module>  (plan pins - dropped unread input bits)
      in  bus  -> u_bin_<bus>  (ot_hbm_face_reg, W flops, kept)  -> <module>__fcore
      out bus  <- u_bout_<bus> (ot_hbm_face_reg, W flops, kept)  <- <module>__fcore
      clock / reset pins pass straight through (face_guard skips them; reset taps follow the plan reset rule)

  * one flop per input pin bit at the face; the fan-out happens after the flop;
  * one flop per output pin bit: an output that is a copy of another output (same core net) still gets its OWN flop
    (= the source register duplicated at each face pin, ot_hbm_face_reg is keep_hierarchy, so opt_merge never folds them);
  * input bits the core never reads (yosys: no load after proc/flatten/opt) are DROPPED from the shell port list when
    the drop keeps the pin names (the unread bits are the top bits of a bus, or the whole bus); the core port bit is
    driven 0 inside the shell (never a used input).  Unread bits inside a bus (a hole) stay pins and stay registered
    (kept flop, reported as unread_kept) - the plan may re-pack them.
  * static schedule: exactly +1 cycle on every input crossing and +1 cycle on every output crossing (+2 for a path
    that enters and leaves the core in the same crossing pair).  The core's reset pin is NOT delayed: relative to its
    data the core sees reset release one cycle earlier; schedules start on the start broadcast (owner dec. 13c), which is
    data and is delayed like all data.
  * data face flops carry no reset (owner dec. 13d): they are flushed by the reset-held producers (reset is held for
    >= 2 cycles with the clock running, dec. 2).

Usage (the kit generator calls apply(); the CLI is for analysis / tables / mutants):
    face_shell.py analyze KITDIR                 -> unread / constant / duplicate report of the kit's core (no edit)
    face_shell.py latency OUT.json REPORT...     -> merge kit face_shell.json reports into the latency/drop table
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

YOSYS = str(Path.home() / ".local/opentallas-tools/bin/yosys")
CELL = "ot_hbm_face_reg"
CELL_SV = f"""// GENERATED by face_shell.py (HBM-FACE): one face register stage, W bits, no reset (owner dec. 13d: datapath flops
// carry no reset; flushed by the reset-held producer).  keep_hierarchy + keep: every face bit keeps its OWN flop through
// Yosys (opt_merge / opt_clean / opt_dff never fold or drop a face register: face_guard R2).
(* keep_hierarchy, keep *)
module {CELL} #(parameter integer W = 1) (
    input  wire         clk,
    input  wire [W-1:0] d,
    output reg  [W-1:0] q
);
    always @(posedge clk) q <= d;
endmodule
"""
# DIE-HBM-61/CLOCK 11-03 (OWNER 11-03 RE-FORM "hold safe by construction: registered faces + lockup latch on
# crossings"): opt-in HALF-CYCLE LOCKUP stage on the OUTPUT face.  A negative-EDGE flop (ASAP7 DFFLQN) after the face
# flop drives the port: the crossing launches on the falling edge, so the receiver's hold race gains T/2 (the same
# hold window a negative-level lockup latch gives) while the port stays driven by a flop (face_guard 'registered';
# a DLL latch driving the port is 'unregistered', SAFE-STATION-1 t30 06:12).  Cycle count unchanged (the receiver
# still captures on the next rising edge); the crossing setup budget becomes T/2 - clk->q - wire.
NCELL = "ot_hbm_face_nreg"
NCELL_SV = f"""// GENERATED by face_shell.py (DIE-HBM-61/CLOCK): half-cycle lockup stage of an OUTPUT face, W bits, negative-edge
// flops (ASAP7 DFFLQN), no reset.  Drives the port: the crossing launches on the falling edge (hold +T/2, latency +0).
(* keep_hierarchy, keep *)
module {NCELL} #(parameter integer W = 1) (
    input  wire         clk,
    input  wire [W-1:0] d,
    output reg  [W-1:0] q
);
    always @(negedge clk) q <= d;
endmodule
"""
# DIE-HBM-61/RTL 11-03 (OWNER 11-03 RE-FORM: registered reset relay at the face): opt-in RESET RELAY on active-low
# reset inputs.  Asynchronous assert, synchronous de-assert through N flops: the port lands on N flop pins only (no raw
# async fan-out from the pin, so the recovery/removal fan-out tree is a timed register-to-register path inside the core)
# and the core sees reset release N edges after the pin.  Schedules start on the start broadcast (owner dec. 13c), so
# the release delay is a reset_delay_cycles entry of the latency table, not a data crossing change.
RCELL = "ot_hbm_face_rst_relay"
RCELL_SV = f"""// GENERATED by face_shell.py (DIE-HBM-61/RTL): face reset relay, W active-low reset bits, async assert,
// synchronous release after N clock edges (N >= 2).  keep_hierarchy + keep (the relay flops stay at the face).
(* keep_hierarchy, keep *)
module {RCELL} #(parameter integer W = 1, parameter integer N = 2) (
    input  wire         clk,
    input  wire [W-1:0] rst_ni,
    output wire [W-1:0] rst_no
);
    genvar g;
    generate for (g = 0; g < W; g = g + 1) begin : g_b
        reg [N-1:0] s;
        always @(posedge clk or negedge rst_ni[g])
            if (!rst_ni[g]) s <= {{N{{1'b0}}}};
            else            s <= {{s[N-2:0], 1'b1}};
        assign rst_no[g] = s[N-1];
    end endgenerate
endmodule
"""
SHELL_SCHEMA = "opentallas.hbm_arch.core_face_shell.v1"


def sv_id(n):
    return re.sub(r"[^A-Za-z0-9_]", "_", n)


