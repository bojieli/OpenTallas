#!/usr/bin/env python3
"""HBM-FACE 10-25: per-core FACE-REGISTER SHELL for HBM hard-core kits (owner rule "register every tile pin by default";
face_guard R2: every core pin bit has its OWN flop at the face).

Why: 348/370 synthesised HBM core kits failed face_guard (HBM-CORES 10-24) because the core RTL was cut out of die logic
at unregistered module ports: inputs fanning out to several loads ('shared'), inputs straight into logic
('unregistered'), outputs that are copies of one register ('merged', e.g. argmax vm_rq), port-to-port wires
('feedthrough') and input bits nothing reads ('dropped').  The shell fixes all of them structurally, without touching
the core RTL:

    <module>  (plan pins - dropped unread input bits)
      in  bus  -> u_bin_<bus>  (ot_hbm_face_reg, W flops, kept)  -> <module>__fcore
      out bus  <- u_bout_<bus> (ot_hbm_face_reg, W flops, kept)  <- <module>__fcore
      clock / reset pins pass straight through (face_guard skips them; reset taps follow the plan reset rule)

  * one flop per input pin bit at the face; the fan-out happens after the flop;
  * one flop per output pin bit: an output that is a copy of another output (same core net) still gets its OWN flop
    (= the source register duplicated at each face pin, ot_hbm_face_reg is keep_hierarchy, so opt_merge never folds them);
  * input bits the core never reads (yosys: no load after proc/flatten/opt) are DROPPED from the shell port list when
    the drop keeps the pin names (the unread bits are the top bits of a bus, or the whole bus); the core port bit is
    driven 0 inside the shell (never a used input).  Unread bits inside a bus (a hole) stay pins and stay registered
    (kept flop, reported as unread_kept) - the plan may re-pack them.
  * static schedule: exactly +1 cycle on every input crossing and +1 cycle on every output crossing (+2 for a path
    that enters and leaves the core in the same crossing pair).  The core's reset pin is NOT delayed: relative to its
    data the core sees reset release one cycle earlier; schedules start on the start broadcast (owner dec. 13c), which is
    data and is delayed like all data.
  * data face flops carry no reset (owner dec. 13d): they are flushed by the reset-held producers (reset is held for
    >= 2 cycles with the clock running, dec. 2).

Usage (the kit generator calls apply(); the CLI is for analysis / tables / mutants):
    face_shell.py analyze KITDIR                 -> unread / constant / duplicate report of the kit's core (no edit)
    face_shell.py latency OUT.json REPORT...     -> merge kit face_shell.json reports into the latency/drop table
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

YOSYS = str(Path.home() / ".local/opentallas-tools/bin/yosys")
CELL = "ot_hbm_face_reg"
CELL_SV = f"""// GENERATED by face_shell.py (HBM-FACE): one face register stage, W bits, no reset (owner dec. 13d: datapath flops
// carry no reset; flushed by the reset-held producer).  keep_hierarchy + keep: every face bit keeps its OWN flop through
// Yosys (opt_merge / opt_clean / opt_dff never fold or drop a face register: face_guard R2).
(* keep_hierarchy, keep *)
module {CELL} #(parameter integer W = 1) (
    input  wire         clk,
    input  wire [W-1:0] d,
    output reg  [W-1:0] q
);
    always @(posedge clk) q <= d;
endmodule
"""
SHELL_SCHEMA = "opentallas.hbm_arch.core_face_shell.v1"


def sv_id(n):
    return re.sub(r"[^A-Za-z0-9_]", "_", n)


# ---------------------------------------------------------------------------------------------------------------------
# Conservative def-use analysis of elaborated processes. Do not run opt_dff / opt -full here:
# they may replace an uninitialised enabled register with its constant D value, removing
# the command that initializes it. Tying that command low in emitted RTL would leave the
# original register uninitialised. Keep state and its enable cone while cleaning dead logic.
def analyze(files, top, params=None, defines=(), incdir=None, libs=(), workdir=None, log=None):
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    js = workdir / "face_shell_core.json"
    # cache (views of one module share the RTL): key = yosys binary + every input file's bytes + top + params + libs
    h = hashlib.sha256(f"v2-init-safe {YOSYS} {top} {sorted((params or {}).items())} {list(defines)}".encode())
    for f in list(files) + list(libs):
        h.update(str(Path(f).name).encode() + b"\0" + Path(f).read_bytes())
    cache = Path(os.environ.get("FACE_SHELL_CACHE", Path.home() / ".cache" / "face_shell")) / (h.hexdigest()[:32] + ".json")
    if cache.is_file():
        return json.loads(cache.read_text())
    ch = " ".join(f"-chparam {k} {v}" for k, v in (params or {}).items())
    d = " ".join(f"-D{x}" for x in ["SYNTHESIS"] + list(defines))
    sv = [f for f in files if not str(f).endswith((".svh", ".vh"))]
    inc = f"-I{incdir}" if incdir else ""
    rl = "".join(f"read_liberty -lib -ignore_miss_func {l}; " for l in libs)
    script = (f"{rl}read_verilog -sv {d} {inc} " + " ".join(map(str, sv)) + f"; hierarchy -top {top} {ch}; "
              "proc; flatten; opt_expr -keepdc; opt_clean; wreduce; opt_clean; memory -nomap; "
              f"opt_clean -purge; write_json {js}")
    r = subprocess.run([YOSYS, "-q", "-p", script], capture_output=True, text=True)
    if r.returncode and params:     # yosys 0.68 hierarchy -chparam can assert: chparam -set (as ORFS / the generator)
        cs = f"chparam {' '.join(f'-set {k} {v}' for k, v in params.items())} {top}; "
        r = subprocess.run([YOSYS, "-q", "-p", script.replace(f"hierarchy -top {top} {ch}",
                                                                cs + f"hierarchy -top {top}")],
                           capture_output=True, text=True)
    if log:
        Path(log).write_text(r.stdout[-20000:] + r.stderr[-20000:])
    if r.returncode:
        raise RuntimeError(f"face_shell: yosys analysis of {top} failed:\n{r.stderr[-3000:]}")
    J = json.loads(js.read_text())
    js.unlink()            # can be tens of MB; the kit keeps only the report
    mods = J["modules"]
    M = mods.get(top) or next(v for k, v in mods.items() if v.get("attributes", {}).get("top"))
    ports = {n: p for n, p in M["ports"].items()}
    loaded = set()
    fanout = defaultdict(int)
    for c in M["cells"].values():
        pdir = c.get("port_directions", {})
        for pn, bits in c["connections"].items():
            if pdir.get(pn, "input") != "output":     # unknown direction: count as a load (conservative: fewer drops)
                for b in bits:
                    if isinstance(b, int):
                        loaded.add(b)
                        fanout[b] += 1
    out_bits = defaultdict(list)
    for n, p in ports.items():
        if p["direction"] == "output":
            for i, b in enumerate(p["bits"]):
                out_bits[b].append(f"{n}[{i}]")
    rep = dict(top=top, unread_in={}, const_out={}, dup_out=[], feedthrough=[], in_fanout={})
    in_bit = {}
    for n, p in ports.items():
        if p["direction"] != "input":
            continue
        un = []
        for i, b in enumerate(p["bits"]):
            if not isinstance(b, int):
                continue
            in_bit[b] = f"{n}[{i}]"
            if b not in loaded and b not in out_bits:
                un.append(i)
            rep["in_fanout"][f"{n}[{i}]"] = fanout.get(b, 0)
        if un:
            rep["unread_in"][n] = un
    for n, p in ports.items():
        if p["direction"] != "output":
            continue
        cs = {i: b for i, b in enumerate(p["bits"]) if not isinstance(b, int)}
        if cs:
            rep["const_out"][n] = cs
    for b, names in out_bits.items():
        if isinstance(b, int) and len(names) > 1:
            rep["dup_out"].append(names)
        if b in in_bit:
            rep["feedthrough"] += [f"{in_bit[b]}->{x}" for x in names]
    rep["port_dirs"] = {n: p["direction"] for n, p in ports.items()}
    rep["port_width"] = {n: len(p["bits"]) for n, p in ports.items()}
    try:
        cache.parent.mkdir(parents=True, exist_ok=True)
        tmp = cache.with_suffix(f".tmp{os.getpid()}")
        tmp.write_text(json.dumps(rep))
        os.replace(tmp, cache)
    except OSError:
        pass
    return rep


# ---------------------------------------------------------------------------------------------------------------------
def drop_plan(widths, dirs, unread, passthru, scalars=()):
    """-> (keep_width {bus: w}, dropped [bit names], unread_kept [bit names]).  A drop keeps pin names: only the top bits
    of a bus (contiguous run ending at W-1) or the whole bus.  Clock / reset (passthru) buses are never dropped."""
    keep, dropped, kept = {}, [], []
    for n, w in widths.items():
        keep[n] = w
        if dirs[n] != "input" or n in passthru or n not in unread:
            continue
        un = set(unread[n])
        k = w
        while k > 0 and (k - 1) in un:
            k -= 1
        keep[n] = k
        nm = lambda i: n if n in scalars else f"{n}[{i}]"       # plan pin names: scalars have no index
        dropped += [nm(i) for i in range(k, w)]
        kept += [nm(i) for i in sorted(un) if i < k]
    return keep, dropped, kept


def _bitexpr(name, w, override):
    """concat expression msb..lsb of `name` bits, with bit overrides {i: expr}."""
    if not override:
        return name
    parts = []
    for i in range(w - 1, -1, -1):
        parts.append(override[i] if i in override else f"{name}[{i}]")
    return "{" + ", ".join(parts) + "}"


def emit_shell(module, core, params, widths, dirs, keep, passthru, clk, mutant=None, scalars=None):
    """shell SV text.  mutant (bench only): {'kind': 'in_bypass'|'out_bypass'|'out_delay2', 'bus': n, 'bit': i}."""
    mutant = mutant or {}
    decl, body, conns = [], [], []
    if scalars is None:                       # plan scalars (pin 'x', not 'x[0]'); default: every 1-bit port
        scalars = {n for n, w in widths.items() if w == 1}
    sbit = lambda n, b: n if n in scalars else f"{n}[{b}]"
    for n in widths:
        w, d = widths[n], dirs[n]
        k = keep[n]
        if k == 0:
            # whole bus dropped (unread input): core port driven 0 inside the shell
            conns.append(f".{n}({w}'d0)")
            continue
        rng = "" if n in scalars else f"[{k - 1}:0] "
        decl.append(f"    {d} wire {rng}{n}")
        if n in passthru:
            conns.append(f".{n}({n})")
            continue
        i_ = sv_id(n)
        if d == "input":
            body.append(f"    wire [{k - 1}:0] {i_}__fq;")
            body.append(f"    (* keep *) {CELL} #(.W({k})) u_bin_{i_} (.clk({clk}), .d({n}), .q({i_}__fq));")
            src = f"{i_}__fq"
            if mutant.get("kind") == "in_bypass" and mutant.get("bus") == n:
                src = _bitexpr(f"{i_}__fq", k, {mutant["bit"]: sbit(n, mutant["bit"])})
            conns.append(f".{n}({src})" if k == w else f".{n}({{{w - k}'d0, {src}}})")
        else:
            body.append(f"    wire [{w - 1}:0] {i_}__fc;")
            q = n
            if mutant.get("kind") == "out_delay2" and mutant.get("bus") == n:
                body.append(f"    wire [{w - 1}:0] {i_}__fm;")
                body.append(f"    {CELL} #(.W({w})) u_mut_{i_} (.clk({clk}), .d({i_}__fm), .q({n}));")
                q = f"{i_}__fm"
            if mutant.get("kind") == "out_bypass" and mutant.get("bus") == n:
                b = mutant["bit"]
                body.append(f"    wire [{w - 1}:0] {i_}__fm;")
                body.append(f"    (* keep *) {CELL} #(.W({w})) u_bout_{i_} (.clk({clk}), .d({i_}__fc), .q({i_}__fm));")
                body.append(f"    assign {n} = {_bitexpr(f'{i_}__fm', w, {b: f'{i_}__fc[{b}]'})};")
            else:
                body.append(f"    (* keep *) {CELL} #(.W({w})) u_bout_{i_} (.clk({clk}), .d({i_}__fc), .q({q}));")
            conns.append(f".{n}({i_}__fc)")
    prm = (" #(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ")") if params else ""
    tag = f" MUTANT {mutant}" if mutant else ""
    return "\n".join([
        f"// GENERATED by face_shell.py (HBM-FACE): face-register shell of {core}{tag}.  Every signal pin bit has its own",
        "// flop at the face (+1 cycle in, +1 cycle out); clock / reset pins pass through; dropped unread input bits are",
        "// driven 0 at the core port (never read by the core: yosys analysis, bench-verified).  Do not edit.",
        "`default_nettype none",
        f"module {module} (", ",\n".join(decl), ");", *body,
        f"    {core}{prm} u_fcore (", ",\n".join(f"        {c}" for c in conns), "    );",
        "endmodule", "`default_nettype wire", ""])


def rename_module(files, module, new):
    """rename the (single) definition of `module` in the kit RTL copies to `new`."""
    rx = re.compile(r"(?m)^(\s*module\s+)" + re.escape(module) + r"(?=[\s#(;])")
    hits = []
    for f in files:
        p = Path(f)
        if p.suffix not in (".sv", ".v"):
            continue
        t = p.read_text()
        t2, n = rx.subn(lambda m: m[1] + new, t)
        if n:
            p.write_text(t2)
            hits.append((str(p), n))
    if sum(n for _, n in hits) != 1:
        raise RuntimeError(f"face_shell: expected one definition of {module}, found {hits}")
    return hits[0][0]


def apply(kd, module, local, srcs, params, defines, macro_libs, clk_re, rst_re, drop=True, mutant=None, scalars=None):
    """turn kit `kd` (generated, top = `module` with exactly the plan pins) into a shelled kit.
    local: kit RTL paths (host), srcs: /work paths (config.mk), params: top params of `module` (moved onto the core
    instance).  Returns the report (also written to kd/face_shell.json); caller removes report['dropped'] pins from the
    pin table and adds report['files'] to the sources."""
    kd = Path(kd)
    core = module + "__fcore"
    deffile = rename_module(local, module, core)
    rep = analyze(local, core, params, defines, kd / "rtl", macro_libs, kd / "face_shell_work",
                  log=kd / "face_shell_work" / "yosys.log")
    widths, dirs = rep.pop("port_width"), rep.pop("port_dirs")
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    passthru = {n for n in widths if re.match(clk_re, n) or (dirs[n] == "input" and re.match(rst_re, n))}
    clks = sorted(n for n in passthru if re.match(clk_re, n) and dirs[n] == "input")
    if not clks:
        raise RuntimeError(f"face_shell: {module}: no input clock port")
    if scalars is None:
        scalars = {n for n, w in widths.items() if w == 1}
    scalars = sorted(set(scalars) & set(widths))
    clk = "clk" if "clk" in clks else clks[0]          # all clock ports carry the one core clock (tap-balanced)
    clk = clk if clk in scalars else f"{clk}[0]"
    if drop:
        keep, dropped, kept = drop_plan(widths, dirs, rep["unread_in"], passthru, set(scalars))
    else:
        keep, dropped = dict(widths), []
        kept = [n if n in scalars else f"{n}[{i}]" for n, ix in rep["unread_in"].items() for i in ix]
    txt = emit_shell(module, core, params, widths, dirs, keep, passthru, clk, mutant, set(scalars))
    (kd / "rtl" / f"{module}__fshell.sv").write_text(txt)
    (kd / "rtl" / f"{CELL}.sv").write_text(CELL_SV)
    sig_in = [n for n in widths if dirs[n] == "input" and n not in passthru]
    sig_out = [n for n in widths if dirs[n] == "output" and n not in passthru]
    out = dict(schema=SHELL_SCHEMA, module=module, core=core, core_def_file=Path(deffile).name, clock=clk,
               passthrough=sorted(passthru), scalars=scalars, params=params, mutant=mutant or None,
               latency=dict(in_cycles=1, out_cycles=1, in_to_out_extra_cycles=2, reset_delay_cycles=0,
                            note="every signal input +1, every signal output +1; clock/reset pins pass through"),
               in_buses=len(sig_in), out_buses=len(sig_out),
               in_bits=sum(keep[n] for n in sig_in), out_bits=sum(widths[n] for n in sig_out),
               face_flops=sum(keep[n] for n in sig_in) + sum(widths[n] for n in sig_out),
               dropped=dropped, unread_kept=kept,
               const_out={n: {str(i): v for i, v in c.items()} for n, c in rep["const_out"].items()},
               const_out_bits=sum(len(c) for c in rep["const_out"].values()),
               dup_out_groups=len(rep["dup_out"]), dup_out_bits=sum(len(g) for g in rep["dup_out"]),
               dup_out=rep["dup_out"][:200], feedthrough=rep["feedthrough"][:200], feedthrough_bits=len(rep["feedthrough"]),
               widths=widths, dirs=dirs, keep=keep,
               top_fanout_in=sorted(((v, k) for k, v in rep["in_fanout"].items() if base(k) in sig_in), reverse=True)[:16],
               files=[f"{module}__fshell.sv", f"{CELL}.sv"])
    (kd / "face_shell.json").write_text(json.dumps(out, indent=1) + "\n")
    return out


def latency_table(out, reports):
    rows = {}
    for r in reports:
        J = json.loads(Path(r).read_text())
        m = J["module"]
        row = dict(in_cycles=J["latency"]["in_cycles"], out_cycles=J["latency"]["out_cycles"],
                   in_to_out_extra_cycles=J["latency"]["in_to_out_extra_cycles"],
                   reset_delay_cycles=J["latency"]["reset_delay_cycles"],
                   in_bits=J["in_bits"], out_bits=J["out_bits"], face_flops=J["face_flops"],
                   dropped_in_bits=J["dropped"], unread_kept_bits=J["unread_kept"],
                   const_out_bits=J["const_out_bits"], dup_out_bits=J["dup_out_bits"])
        prev = rows.get(m)
        if prev and (prev["dropped_in_bits"] != row["dropped_in_bits"]):
            row["note"] = "views of this module disagree on dropped bits"
        rows[m] = row
    T = dict(schema="opentallas.hbm_arch.core_face_shell_latency.v1",
             rule=("HBM-FACE shell: +1 cycle on every signal input pin, +1 cycle on every signal output pin of every "
                   "shelled hard core (static schedule / bind add these to every core crossing); clock and reset pins "
                   "unchanged; dropped_in_bits are removed from the core pin table (plan change for the lane owner)"),
             modules=dict(sorted(rows.items())))
    Path(out).write_text(json.dumps(T, indent=1) + "\n")
    return T


def main(argv):
    if len(argv) >= 2 and argv[0] == "latency":
        T = latency_table(argv[1], argv[2:])
        print(f"{len(T['modules'])} modules -> {argv[1]}")
        return 0
    if len(argv) == 2 and argv[0] == "analyze":
        kd = Path(argv[1])
        fz = json.loads((kd / "freeze.json").read_text())
        cfg = (kd / "config.mk").read_text()
        files = [str(kd / "rtl" / Path(f).name) for f in re.search(r"VERILOG_FILES = (.*)", cfg).group(1).split()]
        prm = re.search(r"VERILOG_TOP_PARAMS = (.*)", cfg)
        params = dict(zip(*[iter(prm.group(1).split())] * 2)) if prm else {}
        libs = sorted(str(p) for p in (kd / "macros").glob("*_tt.lib")) if (kd / "macros").is_dir() else []
        top = fz.get("design")
        r = analyze(files, top, params, (), kd / "rtl", libs, kd / "face_shell_work")
        r.pop("in_fanout")
        print(json.dumps({k: (v if k not in ("dup_out", "feedthrough") else v[:5]) for k, v in r.items()
                          if k not in ("port_dirs", "port_width")}, indent=1)[:6000])
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
