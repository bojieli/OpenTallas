def drop_plan(widths, dirs, unread, passthru, scalars=()):
    """-> (keep_width {bus: w}, dropped [bit names], unread_kept [bit names]).  A drop keeps pin names: only the top bits
    of a bus (contiguous run ending at W-1) or the whole bus.  Clock / reset (passthru) buses are never dropped."""
    keep, dropped, kept = {}, [], []
    for n, w in widths.items():
        keep[n] = w
        if dirs[n] != "input" or n in passthru or n not in unread:
            continue
        un = set(unread[n])
        k = w
        while k > 0 and (k - 1) in un:
            k -= 1
        keep[n] = k
        nm = lambda i: n if n in scalars else f"{n}[{i}]"       # plan pin names: scalars have no index
        dropped += [nm(i) for i in range(k, w)]
        kept += [nm(i) for i in sorted(un) if i < k]
    return keep, dropped, kept


def _bitexpr(name, w, override):
    """concat expression msb..lsb of `name` bits, with bit overrides {i: expr}."""
    if not override:
        return name
    parts = []
    for i in range(w - 1, -1, -1):
        parts.append(override[i] if i in override else f"{name}[{i}]")
    return "{" + ", ".join(parts) + "}"


def emit_shell(module, core, params, widths, dirs, keep, passthru, clk, mutant=None, scalars=None, stages=None,
               lockup=None, rst_relay=None, in_stages=None):
    """shell SV text.  mutant (bench only): {'kind': 'in_bypass'|'out_bypass'|'out_delay2', 'bus': n, 'bit': i}.
    stages (opt-in, HBM-CORES-KITS-36/opstore, COORD 10-31 15:05): {bus: k} -> k extra pipeline register stages
    u_bmid<j>_<bus> between the core port and the face flop of an OUTPUT bus (k-cycle read pipeline before the
    face; the stage flops are free-placed, the face flop stays at the face).  Latency +k on that bus only.
    lockup (opt-in, DIE-HBM-61/CLOCK): set of OUTPUT bus names whose face flop u_bout_<bus> feeds a negative-edge
    lockup stage u_bout_<bus>__nl (ot_hbm_face_nreg) that drives the port (hold +T/2, cycle count unchanged).
    mutant kind 'out_latch' (bench only): the lockup stage of that bus is a negative-LEVEL latch instead.
    rst_relay (opt-in, DIE-HBM-61/RTL): {active-low reset INPUT name: N} -> u_brst_<name> (ot_hbm_face_rst_relay,
    async assert, release after N edges) between the pin and the core reset port.
    in_stages (opt-in, DIE-HBM-61/CUTS 11-03): {INPUT bus: k} -> k extra free-placed pipeline register stages
    u_bimid<j>_<bus> between the face flop u_bin_<bus> (stays at the face) and the core port (input relay: a far
    capture inside the core gets a mid-way register).  Latency +k on that input bus only; default none = unchanged.
    mutant kind 'in_short' (bench only): bit `bit` of that bus skips its last input stage (one cycle early)."""
    mutant = mutant or {}
    stages = stages or {}
    in_stages = in_stages or {}
    lockup = set(lockup or ())
    rst_relay = dict(rst_relay or {})
    if mutant.get("bus") in lockup and mutant.get("kind") != "out_latch":
        raise ValueError(f"emit_shell: mutant {mutant.get('kind')} on lockup bus {mutant.get('bus')}")
    decl, body, conns = [], [], []
    if scalars is None:                       # plan scalars (pin 'x', not 'x[0]'); default: every 1-bit port
        scalars = {n for n, w in widths.items() if w == 1}
    sbit = lambda n, b: n if n in scalars else f"{n}[{b}]"
    for n in widths:
        w, d = widths[n], dirs[n]
        k = keep[n]
        if k == 0:
            # whole bus dropped (unread input): core port driven 0 inside the shell
            conns.append(f".{n}({w}'d0)")
            continue
        rng = "" if n in scalars else f"[{k - 1}:0] "
        decl.append(f"    {d} wire {rng}{n}")
        if n in passthru and n in rst_relay:
            i_ = sv_id(n)
            body.append(f"    wire [{w - 1}:0] {i_}__rr;")
            body.append(f"    (* keep *) {RCELL} #(.W({w}), .N({int(rst_relay[n])})) u_brst_{i_} (.clk({clk}), .rst_ni({n}), "
                        f".rst_no({i_}__rr));")
            conns.append(f".{n}({i_}__rr)")
            continue
        if n in passthru:
            conns.append(f".{n}({n})")
            continue
        i_ = sv_id(n)
        if d == "input":
            body.append(f"    wire [{k - 1}:0] {i_}__fq;")
            body.append(f"    (* keep *) {CELL} #(.W({k})) u_bin_{i_} (.clk({clk}), .d({n}), .q({i_}__fq));")
            src = f"{i_}__fq"
            if mutant.get("kind") == "in_bypass" and mutant.get("bus") == n:
                src = _bitexpr(f"{i_}__fq", k, {mutant["bit"]: sbit(n, mutant["bit"])})
            if in_stages.get(n):
                prev_ = src
                for j_ in range(int(in_stages[n])):
                    body.append(f"    wire [{k - 1}:0] {i_}__i{j_};")
                    body.append(f"    (* keep *) {CELL} #(.W({k})) u_bimid{j_}_{i_} (.clk({clk}), .d({src}), .q({i_}__i{j_}));")
                    prev_, src = src, f"{i_}__i{j_}"
                if mutant.get("kind") == "in_short" and mutant.get("bus") == n:
                    src = _bitexpr(src, k, {mutant["bit"]: f"{prev_}[{mutant['bit']}]"})
            conns.append(f".{n}({src})" if k == w else f".{n}({{{w - k}'d0, {src}}})")
        else:
            body.append(f"    wire [{w - 1}:0] {i_}__fc;")
            q = n
            if n in lockup:
                body.append(f"    wire [{w - 1}:0] {i_}__fl;")
                if mutant.get("kind") == "out_latch" and mutant.get("bus") == n:
                    body.append(f"    reg [{w - 1}:0] {i_}__lq;")
                    body.append(f"    always @* if (!{clk}) {i_}__lq = {i_}__fl;   // MUTANT: level latch drives the port")
                    body.append(f"    assign {n} = {i_}__lq;")
                else:
                    body.append(f"    (* keep *) {NCELL} #(.W({w})) u_bout_{i_}__nl (.clk({clk}), .d({i_}__fl), .q({n}));")
                q = f"{i_}__fl"
            if mutant.get("kind") == "out_delay2" and mutant.get("bus") == n:
                body.append(f"    wire [{w - 1}:0] {i_}__fm;")
                body.append(f"    {CELL} #(.W({w})) u_mut_{i_} (.clk({clk}), .d({i_}__fm), .q({n}));")
                q = f"{i_}__fm"
            if stages.get(n):
                src_ = f"{i_}__fc"
                for j_ in range(int(stages[n])):
                    body.append(f"    wire [{w - 1}:0] {i_}__s{j_};")
                    body.append(f"    (* keep *) {CELL} #(.W({w})) u_bmid{j_}_{i_} (.clk({clk}), .d({src_}), .q({i_}__s{j_}));")
                    src_ = f"{i_}__s{j_}"
                body.append(f"    (* keep *) {CELL} #(.W({w})) u_bout_{i_} (.clk({clk}), .d({src_}), .q({q}));")
            elif mutant.get("kind") == "out_bypass" and mutant.get("bus") == n:
                b = mutant["bit"]
                body.append(f"    wire [{w - 1}:0] {i_}__fm;")
                body.append(f"    (* keep *) {CELL} #(.W({w})) u_bout_{i_} (.clk({clk}), .d({i_}__fc), .q({i_}__fm));")
                body.append(f"    assign {n} = {_bitexpr(f'{i_}__fm', w, {b: f'{i_}__fc[{b}]'})};")
            else:
                body.append(f"    (* keep *) {CELL} #(.W({w})) u_bout_{i_} (.clk({clk}), .d({i_}__fc), .q({q}));")
            conns.append(f".{n}({i_}__fc)")
    prm = (" #(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ")") if params else ""
    tag = f" MUTANT {mutant}" if mutant else ""
    return "\n".join([
        f"// GENERATED by face_shell.py (HBM-FACE): face-register shell of {core}{tag}.  Every signal pin bit has its own",
        "// flop at the face (+1 cycle in, +1 cycle out); clock / reset pins pass through; dropped unread input bits are",
        "// driven 0 at the core port (never read by the core: yosys analysis, bench-verified).  Do not edit.",
        "`default_nettype none",
        f"module {module} (", ",\n".join(decl), ");", *body,
        f"    {core}{prm} u_fcore (", ",\n".join(f"        {c}" for c in conns), "    );",
        "endmodule", "`default_nettype wire", ""])


def _active_lines(text, defines):
    """per line: True when the line is compiled with `defines` (`ifdef / `ifndef / `elsif / `else / `endif, nested)."""
    dset, stack, out = set(defines), [], []
    for ln in text.split("\n"):
        s = ln.strip()
        m = re.match(r"`(ifdef|ifndef|elsif)\s+(\w+)", s)
        if m and m[1] in ("ifdef", "ifndef"):
            on = (m[2] in dset) == (m[1] == "ifdef")
            stack.append([on, on])           # [this branch active, some branch taken]
            out.append(False)
            continue
        if m and m[1] == "elsif" and stack:
            on = (not stack[-1][1]) and m[2] in dset
            stack[-1] = [on, stack[-1][1] or on]
            out.append(False)
            continue
        if s.startswith("`else") and stack:
            stack[-1] = [not stack[-1][1], True]
            out.append(False)
            continue
        if s.startswith("`endif") and stack:
            stack.pop()
            out.append(False)
            continue
        out.append(all(b[0] for b in stack))
    return out


def rename_module(files, module, new, defines=None):
    """rename the (single) definition of `module` in the kit RTL copies to `new`.
    DIE-HBM-57/PSLICE 11-01: when the plain text holds more than one definition and `defines` is given, only the
    definitions in compiled `ifdef regions (SYNTHESIS + defines) count (a recipe define selecting one of two forms of
    the top in one file); a file set with exactly one textual definition is renamed exactly as before."""
    # HBM-CORES-KITS-32 10-31: a definition may carry a leading attribute (ot_hbm_idx_owned_native.sv
    # "(* keep_hierarchy=\"yes\" *) module ot_hbm_idx_tail_native": was 'found []' -> FACE_SHELL failure)
    rx = re.compile(r"(?m)^(\s*(?:\(\*[^\n]*?\*\)\s*)?module\s+)" + re.escape(module) + r"(?=[\s#(;])")
    texts = {}
    for f in files:
        p = Path(f)
        if p.suffix in (".sv", ".v"):
            texts[str(p)] = p.read_text()
    plain = [(f, len(rx.findall(t))) for f, t in texts.items() if rx.search(t)]
    if sum(n for _, n in plain) != 1 and defines is not None:
        hits = []
        for f, t in texts.items():
            lines, act, n = t.split("\n"), _active_lines(t, ["SYNTHESIS"] + list(defines)), 0
            for i, ln in enumerate(lines):
                if rx.match(ln):
                    # inactive copies -> <module>__off so a textual duplicate-module scan (kit_preflight) stays clean
                    lines[i] = rx.sub(lambda m: m[1] + (new if act[i] else module + "__off"), ln, count=1)
                    n += act[i]
            hits.append((f, n, "\n".join(lines)))
        if sum(n for _, n, _ in hits) != 1:
            raise RuntimeError(f"face_shell: expected one compiled definition of {module}, found "
                               f"{[(f, n) for f, n, _ in hits if n]} (textual {plain})")
        for f, n, t in hits:
            if t != texts[f]:
                Path(f).write_text(t)
        return next(f for f, n, _ in hits if n)
    if sum(n for _, n in plain) != 1:
        raise RuntimeError(f"face_shell: expected one definition of {module}, found {plain}")
    f = plain[0][0]
    Path(f).write_text(rx.sub(lambda m: m[1] + new, texts[f]))
    return f


def apply(kd, module, local, srcs, params, defines, macro_libs, clk_re, rst_re, drop=True, mutant=None, scalars=None,
          stages=None, lockup=None, reset_relay=0, in_stages=None, pass_buses=None, native_context=None):
    """turn kit `kd` (generated, top = `module` with exactly the plan pins) into a shelled kit.
    local: kit RTL paths (host), srcs: /work paths (config.mk), params: top params of `module` (moved onto the core
    instance).  reset_relay (opt-in, DIE-HBM-61/RTL): N >= 2 -> every active-low reset input (rst_re, name ending
    '_n') gets the face reset relay (release +N edges); an active-high reset input fails.  Returns the report (also written to kd/face_shell.json); caller removes report['dropped'] pins from the
    pin table and adds report['files'] to the sources."""
    kd = Path(kd)
    core = module + "__fcore"
    deffile = rename_module(local, module, core, defines)
    rep = analyze(local, core, params, defines, kd / "rtl", macro_libs, kd / "face_shell_work",
                  log=kd / "face_shell_work" / "yosys.log")
    widths, dirs = rep.pop("port_width"), rep.pop("port_dirs")
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    from static_id_contracts import static_inputs
    straps = static_inputs(module, widths, dirs)
    passthru = {n for n in widths if re.match(clk_re, n) or (dirs[n] == "input" and re.match(rst_re, n))} | set(straps)
    # Explicit native-register seams keep their existing source/capture flops.  This changes wrapper structure,
    # not timing constraints or sign-off: callers must use the native registered boundary and price its cycles.
    native_pass = set()
    for rx_ in (pass_buses or ()):
        hit_ = [n for n in widths if n not in passthru and re.search(rx_, n)]
        if not hit_:
            raise RuntimeError(f"face_shell: pass {rx_!r} matches no signal bus")
        native_pass.update(hit_)
    if native_pass:
        if (not native_context or native_context.get("schema") != "opentallas.native_hard_child_seam.v1"
            or native_context.get("module") != module or set(native_context.get("scope_buses", ())) != native_pass
            or native_context.get("bus_widths") != {n: widths[n] for n in native_pass}
            or not native_context.get("parent_contexts")):
            raise RuntimeError("face_shell: native pass needs validated same-parent hard-child peer context")
    passthru.update(native_pass)
    clks = sorted(n for n in passthru if re.match(clk_re, n) and dirs[n] == "input")
    if not clks:
        raise RuntimeError(f"face_shell: {module}: no input clock port")
    if scalars is None:
        scalars = {n for n, w in widths.items() if w == 1}
    scalars = sorted(set(scalars) & set(widths))
    clk = "clk" if "clk" in clks else clks[0]          # all clock ports carry the one core clock (tap-balanced)
    clk = clk if clk in scalars else f"{clk}[0]"
    if drop:
        keep, dropped, kept = drop_plan(widths, dirs, rep["unread_in"], passthru, set(scalars))
    else:
        keep, dropped = dict(widths), []
        kept = [n if n in scalars else f"{n}[{i}]" for n, ix in rep["unread_in"].items() for i in ix]
    # opt-in output read stages: {regex: k} matched against the shell's signal OUTPUT buses (an unmatched regex fails)
    st_ = {}
    for rx_, k_ in (stages or {}).items():
        hit_ = [n for n in widths if dirs[n] == "output" and n not in passthru and re.search(rx_, n)]
        if not hit_ or int(k_) < 1:
            raise RuntimeError(f"face_shell: stage {rx_!r}={k_} matches no signal output bus (or k < 1)")
        for n in hit_:
            st_[n] = max(st_.get(n, 0), int(k_))
    # opt-in input relay stages (DIE-HBM-61/CUTS): {regex: k} matched against the shell's kept signal INPUT buses
    ist_ = {}
    for rx_, k_ in (in_stages or {}).items():
        hit_ = [n for n in widths if dirs[n] == "input" and n not in passthru and keep[n] > 0 and re.search(rx_, n)]
        if not hit_ or int(k_) < 1:
            raise RuntimeError(f"face_shell: in-stage {rx_!r}={k_} matches no signal input bus (or k < 1)")
        for n in hit_:
            ist_[n] = max(ist_.get(n, 0), int(k_))
    # opt-in output lockup stage: regexes over the signal OUTPUT buses ('.*' = every output); an unmatched regex fails
    lk_ = set()
    for rx_ in (lockup or ()):
        hit_ = [n for n in widths if dirs[n] == "output" and n not in passthru and re.search(rx_, n)]
        if not hit_:
            raise RuntimeError(f"face_shell: lockup {rx_!r} matches no signal output bus")
        lk_.update(hit_)
    rr_ = {}
    if reset_relay:
        if int(reset_relay) < 2:
            raise RuntimeError(f"face_shell: reset_relay {reset_relay} < 2")
        for n in sorted(widths):
            if dirs[n] == "input" and n in passthru and n not in straps and not re.match(clk_re, n) and re.match(rst_re, n):
                if not n.endswith("_n"):
                    raise RuntimeError(f"face_shell: reset_relay: {n} is not an active-low reset (name *_n)")
                rr_[n] = int(reset_relay)
        if not rr_:
            raise RuntimeError(f"face_shell: reset_relay: {module} has no reset input")
    txt = emit_shell(module, core, params, widths, dirs, keep, passthru, clk, mutant, set(scalars), st_, lk_, rr_,
                     ist_ or None)
    if native_pass:
        txt = "// Native registered passthrough (zero wrapper cycles): " + ", ".join(sorted(native_pass)) + "\n" + txt
        txt = txt.replace("Every signal pin bit has its own", "Every non-passthrough signal pin bit has its own", 1)
    (kd / "rtl" / f"{module}__fshell.sv").write_text(txt)
    (kd / "rtl" / f"{CELL}.sv").write_text(CELL_SV)
    if lk_:
        (kd / "rtl" / f"{NCELL}.sv").write_text(NCELL_SV)
    if rr_:
        (kd / "rtl" / f"{RCELL}.sv").write_text(RCELL_SV)
    sig_in = [n for n in widths if dirs[n] == "input" and n not in passthru]
    sig_out = [n for n in widths if dirs[n] == "output" and n not in passthru]
    out = dict(schema=SHELL_SCHEMA, module=module, core=core, core_def_file=Path(deffile).name, clock=clk,
               passthrough=sorted(passthru), scalars=scalars, params=params, mutant=mutant or None,
               latency=dict(in_cycles=1, out_cycles=1, in_to_out_extra_cycles=2,
                            reset_delay_cycles=max(rr_.values()) if rr_ else 0,
                            note="every signal input +1, every signal output +1; clock pins pass through; reset pins "
                                 + ("through the face reset relay (release +N)" if rr_ else "pass through")),
               out_extra_stages={n: k for n, k in sorted(st_.items())},
               out_extra_stage_flops=sum(widths[n] * k for n, k in st_.items()),
               in_buses=len(sig_in), out_buses=len(sig_out),
               in_bits=sum(keep[n] for n in sig_in), out_bits=sum(widths[n] for n in sig_out),
               face_flops=sum(keep[n] for n in sig_in) + sum(widths[n] for n in sig_out),
               dropped=dropped, unread_kept=kept,
               const_out={n: {str(i): v for i, v in c.items()} for n, c in rep["const_out"].items()},
               const_out_bits=sum(len(c) for c in rep["const_out"].values()),
               dup_out_groups=len(rep["dup_out"]), dup_out_bits=sum(len(g) for g in rep["dup_out"]),
               dup_out=rep["dup_out"][:200], feedthrough=rep["feedthrough"][:200], feedthrough_bits=len(rep["feedthrough"]),
               widths=widths, dirs=dirs, keep=keep,
               top_fanout_in=sorted(((v, k) for k, v in rep["in_fanout"].items() if base(k) in sig_in), reverse=True)[:16],
               files=[f"{module}__fshell.sv", f"{CELL}.sv"] + ([f"{NCELL}.sv"] if lk_ else []) + ([f"{RCELL}.sv"] if rr_ else []))
    if native_pass:
        out["native_registered_passthrough"] = sorted(native_pass)
        out["face_cycle_overrides"] = {n: 0 for n in sorted(native_pass)}
        out["native_endpoint_contract"] = dict(kind="INTERNAL_CORE",
            partition_rule="R2_INTERNAL_TIMED_IN_PARTITION", scope_buses=sorted(native_pass),
            port_roles={n: dirs[n] for n in sorted(native_pass)}, hard_child_context=native_context,
            parent_timing="all native data/valid/ready paths remain timed in the parent")
        out["latency"]["note"] += "; native registered buses in face_cycle_overrides retain zero wrapper cycles"
    if ist_:
        out["in_extra_stages"] = {n: k for n, k in sorted(ist_.items())}
        out["in_extra_stage_flops"] = sum(keep[n] * k for n, k in ist_.items())
        out["face_flops_in_relay_note"] = "u_bimid<j>_<bus> relay flops are free-placed (face flop u_bin_<bus> stays at the face)"
    if lk_:
        out["out_lockup"] = dict(form="negedge_face_stage", cell=NCELL, buses=sorted(lk_),
                                 bits=sum(widths[n] for n in lk_), latency_cycles=0,
                                 note="output launches on the falling edge: receiver hold +T/2, crossing setup T/2")
    if rr_:
        out["reset_relay"] = dict(form="async_assert_sync_release", cell=RCELL, resets=rr_, landing_pins_per_bit=1,
                                  note="pin lands on the relay's first flop; core reset released N edges after the pin")
    if straps:
        out["straps"] = straps
    (kd / "face_shell.json").write_text(json.dumps(out, indent=1) + "\n")
    return out


def latency_table(out, reports):
    rows = {}
    for r in reports:
        J = json.loads(Path(r).read_text())
        m = J["module"]
        row = dict(in_cycles=J["latency"]["in_cycles"], out_cycles=J["latency"]["out_cycles"],
                   in_to_out_extra_cycles=J["latency"]["in_to_out_extra_cycles"],
                   reset_delay_cycles=J["latency"]["reset_delay_cycles"],
                   in_bits=J["in_bits"], out_bits=J["out_bits"], face_flops=J["face_flops"],
                   dropped_in_bits=J["dropped"], unread_kept_bits=J["unread_kept"],
                   const_out_bits=J["const_out_bits"], dup_out_bits=J["dup_out_bits"])
        if J.get("face_cycle_overrides"):
            row["face_cycle_overrides"] = J["face_cycle_overrides"]
        if J.get("out_extra_stages"):
            row["out_extra_cycles"] = J["out_extra_stages"]     # {output bus: +k} on top of out_cycles
        if J.get("in_extra_stages"):
            row["in_extra_cycles"] = J["in_extra_stages"]       # {input bus: +k} on top of in_cycles
        prev = rows.get(m)
        if prev and (prev["dropped_in_bits"] != row["dropped_in_bits"]):
            row["note"] = "views of this module disagree on dropped bits"
        rows[m] = row
    T = dict(schema="opentallas.hbm_arch.core_face_shell_latency.v1",
             rule=("HBM-FACE shell: +1 cycle on every signal input pin, +1 cycle on every signal output pin of every "
                   "shelled hard core (static schedule / bind add these to every core crossing); clock and reset pins "
                   "unchanged; dropped_in_bits are removed from the core pin table (plan change for the lane owner)"),
             modules=dict(sorted(rows.items())))
    Path(out).write_text(json.dumps(T, indent=1) + "\n")
    return T


def main(argv):
    if len(argv) >= 2 and argv[0] == "latency":
        T = latency_table(argv[1], argv[2:])
        print(f"{len(T['modules'])} modules -> {argv[1]}")
        return 0
    if len(argv) == 2 and argv[0] == "analyze":
        kd = Path(argv[1])
        fz = json.loads((kd / "freeze.json").read_text())
        cfg = (kd / "config.mk").read_text()
        files = [str(kd / "rtl" / Path(f).name) for f in re.search(r"VERILOG_FILES = (.*)", cfg).group(1).split()]
        prm = re.search(r"VERILOG_TOP_PARAMS = (.*)", cfg)
        params = dict(zip(*[iter(prm.group(1).split())] * 2)) if prm else {}
        libs = sorted(str(p) for p in (kd / "macros").glob("*_tt.lib")) if (kd / "macros").is_dir() else []
        top = fz.get("design")
        r = analyze(files, top, params, (), kd / "rtl", libs, kd / "face_shell_work")
        r.pop("in_fanout")
        print(json.dumps({k: (v if k not in ("dup_out", "feedthrough") else v[:5]) for k, v in r.items()
                          if k not in ("port_dirs", "port_width")}, indent=1)[:6000])
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
