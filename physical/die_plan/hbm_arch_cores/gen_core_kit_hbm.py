def pre_gpl_extra_stage(kd, src):
    """--pre-gpl-extra FILE (HBM-CORES-B 11-11, for KW-FIX-45 wave items): a kit-local PRE_GLOBAL_PLACE hook sourced
    AFTER the kit's own face_flops.tcl (e.g. hnx_fused_lane_c flc_wd_split.tcl: one private driver per macro data input).
    The file is copied into the kit as pre_gpl_extra.tcl, pre_gpl_chain.tcl sources face_flops.tcl then it, and the
    kit's PRE_GLOBAL_PLACE_TCL points at the chain; freeze.json records source path + sha256.  Absent (default): returns
    the unchanged hook and writes nothing, so the kit is byte-identical to a kit generated without the flag."""
    if not src:
        return "/work/face_flops.tcl", None
    p = Path(src)
    if not p.is_file():
        raise SystemExit(f"--pre-gpl-extra {src}: not a file")
