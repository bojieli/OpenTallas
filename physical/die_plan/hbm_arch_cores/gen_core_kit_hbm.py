def _nm(v):
    return int(round(float(v) * 1000))


def kit_track_offsets(tracks_tcl):
    """{layer: [offset nm...]} preferred-direction track offsets with the tech pitch: per layer from the kit
    make_tracks file, else the platform offsets (the same rule as kit_contract macro_pin_grid)."""
    out = {}
    for m in re.finditer(r"(?m)^\s*make_tracks\s+(M\d)\s+(.*)$", tracks_tcl):
        L = m.group(1)
        if L not in TECH_TRACK_LAYERS:
            continue
        a = "y" if TECH_TRACK_LAYERS[L][0] == "H" else "x"
        o = re.search(rf"-{a}_offset\s+([-0-9.eE]+)", m.group(2))
        p = re.search(rf"-{a}_pitch\s+([-0-9.eE]+)", m.group(2))
        if o and p and _nm(p.group(1)) == TECH_TRACK_LAYERS[L][1]:
            out.setdefault(L, []).append(_nm(o.group(1)))
    return dict({k: list(v) for k, v in PLATFORM_TRACK_OFFSETS.items()}, **out)


def lef_signal_pins(lef_text, master):
    """(w nm, h nm, [(layer, x0, y0, x1, y1) nm]) signal pin rects of one LEF MACRO in its own frame."""
    m = re.search(rf"(?ms)^MACRO\s+{re.escape(master)}\b(.*?)^END\s+{re.escape(master)}\b", lef_text)
    if not m:
        raise SystemExit(f"macro grid snap: MACRO {master} not in its LEF")
    s = re.search(r"SIZE\s+([0-9.]+)\s+BY\s+([0-9.]+)", m.group(1))
    rects = []
    for pm in re.finditer(r"(?ms)^\s*PIN\s+(\S+)(.*?)^\s*END\s+\1\b", m.group(1)):
        if re.search(r"\bUSE\s+(POWER|GROUND)\b", pm.group(2)):
            continue
        layer = None
        for tok in re.finditer(r"LAYER\s+(\S+)\s*;|RECT\s+([-0-9.]+)\s+([-0-9.]+)\s+([-0-9.]+)\s+([-0-9.]+)", pm.group(2)):
            if tok.group(1):
                layer = tok.group(1)
            elif layer:
                x0, y0, x1, y1 = (_nm(tok.group(i)) for i in range(2, 6))
                rects.append((layer, min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)))
    return _nm(s.group(1)), _nm(s.group(2)), rects


def _oriented(r, o, w, h):
    x0, y0, x1, y1 = r
    f = {"R0": lambda a, b: (a, b), "MX": lambda a, b: (a, h - b), "MY": lambda a, b: (w - a, b),
         "R180": lambda a, b: (w - a, h - b)}.get(o)
    if f is None:
        raise SystemExit(f"macro grid snap: orientation {o} not supported (R0/MX/MY/R180)")
    (ax, ay), (bx, by) = f(x0, y0), f(x1, y1)
    return min(ax, bx), min(ay, by), max(ax, bx), max(ay, by)


def _on_track(lo, hi, width, pitch, offsets):
    for of in offsets:
        k = -((lo + width // 2 - of) // -pitch)               # first track >= lo + width/2
        if of + k * pitch <= hi - width // 2:
            return True
    return False


def _um(v):
    """HBM-CORES-KITS-2: geometry (um) for config.mk / Tcl.  '{v:g}' keeps only 6 significant digits, so the C24 plan
    outline 1635.552 um became DIE_AREA 1635.55 (kit_preflight master_slice FAIL, hfd_hgi_vms_glue_nw_t) and every
    coordinate >= 1000 um lost its last decimal.  10 significant digits keep the plan's 1-nm values and still drop
    float noise (177.98399999999992 -> 177.984); values < 1000 um with <= 3 decimals print as before."""
    return f"{float(v):.10g}"


def snap_macro_placement(placements, tracks_tcl, lef_text_of, outline_um):
    """Move every placement origin by the smallest (dx, dy) on the 1-nm grid that puts ALL its signal pins on a
    preferred-direction track (V-layer pins fix x, H-layer pins fix y; |d| <= one pitch).  Fail closed if none exists,
    if a moved macro leaves the outline or overlaps another.  Returns (placements, moves); on-grid input is unchanged."""
    offs = kit_track_offsets(tracks_tcl)
    out, moves, boxes = [], [], []
    for p_ in placements:
        o = p_.get("orient", "R0")
        w, h, rects = lef_signal_pins(lef_text_of(p_["macro"]), p_["macro"])
        x, y = (_nm(c) for c in p_["xy_um"])
        d = {}
        for axis, dirn in (("x", "V"), ("y", "H")):
            pins = []
            for L, *r in rects:
                if L in offs and TECH_TRACK_LAYERS[L][0] == dirn:
                    X0, Y0, X1, Y1 = _oriented(r, o, w, h)
                    pins.append(((X0, X1) if dirn == "V" else (Y0, Y1), TECH_TRACK_LAYERS[L], offs[L]))
            base = x if axis == "x" else y
            span = max([pt[1][1] for pt in pins], default=0)
            d[axis] = next((s for s in sorted(range(-span, span + 1), key=lambda v: (abs(v), v))
                            if all(_on_track(base + lo + s, base + hi + s, wd, pt, of) for (lo, hi), (_, pt, wd), of in pins)),
                           None)
            if d[axis] is None:
                raise SystemExit(f"macro grid snap: {p_['inst']} {o}: no {axis} origin within one pitch puts all "
                                 f"{len(pins)} {dirn} signal pins on the kit track grid")
        nx, ny = x + d["x"], y + d["y"]
        if nx < 0 or ny < 0 or nx + (h if o.endswith("90") else w) > _nm(outline_um[0]) or ny + h > _nm(outline_um[1]):
            raise SystemExit(f"macro grid snap: {p_['inst']} leaves the outline after the snap")
        box = (nx, ny, nx + w, ny + h)
        for q in boxes:
            if box[0] < q[2] and q[0] < box[2] and box[1] < q[3] and q[1] < box[3]:
                raise SystemExit(f"macro grid snap: {p_['inst']} overlaps another macro after the snap")
        boxes.append(box)
        if d["x"] or d["y"]:
            moves.append(dict(inst=p_["inst"], orient=o, from_um=list(p_["xy_um"]), dx_nm=d["x"], dy_nm=d["y"]))
            p_ = dict(p_, xy_um=[round(nx / 1000.0, 3), round(ny / 1000.0, 3)])
        out.append(p_)
    return out, moves


def macro_reg_guide_spec(placements, lef_size_of, scope, grow_um, core_box):
    """HBM-CORES-REBAL-10 (opt-in --macro-reg-guide SCOPE): one GPL guide box per static macro <P>.<leaf>: the macro's
    placed bbox grown by grow_um on every side, clipped to core_box (x0, y0, x1, y1 um); members = the instances under
    the sibling scope <P>.<SCOPE>. (registers that drive only that macro, e.g. the WCOPY write copies g_wcopy).
    lef_size_of(master) -> (w nm, h nm).  Orientations R0/MX/MY/R180 keep the bbox; others are refused."""
    out = []
    for i, p_ in enumerate(placements):
        o = p_.get("orient", "R0")
        if o not in ("R0", "MX", "MY", "R180"):
            raise SystemExit(f"macro reg guide: orientation {o} of {p_['inst']} not supported")
        inst = p_["inst"].replace("\\", "")
        if "." not in inst:
            raise SystemExit(f"macro reg guide: {inst} has no parent scope")
        w, h = lef_size_of(p_["macro"])
        x, y = (float(c) for c in p_["xy_um"])
        box = [max(core_box[0], x - grow_um), max(core_box[1], y - grow_um),
               min(core_box[2], x + w / 1000.0 + grow_um), min(core_box[3], y + h / 1000.0 + grow_um)]
        out.append(dict(name=f"m{i}", macro=inst, prefix=inst.rsplit(".", 1)[0] + f".{scope}.",
                        macro_um=[x, y, x + w / 1000.0, y + h / 1000.0], box_um=box))
    # disjoint guides by construction: two grown boxes that overlap are cut at the middle of the gap between their
    # macros, on the axis where the macros are apart (the wider gap if both); cuts only shrink boxes, so one pass
    # over all pairs leaves every pair disjoint.
    for i, a_ in enumerate(out):
        for b_ in out[i + 1:]:
            A, B = a_["box_um"], b_["box_um"]
            if not (A[0] < B[2] and B[0] < A[2] and A[1] < B[3] and B[1] < A[3]):
                continue
            ma, mb = a_["macro_um"], b_["macro_um"]
            gaps = []
            for ax in (0, 1):
                lo_, hi_ = (a_, b_) if ma[ax] <= mb[ax] else (b_, a_)
                gap = hi_["macro_um"][ax] - lo_["macro_um"][ax + 2]
                if gap >= 0:
                    gaps.append((gap, ax, lo_, hi_))
            if not gaps:
                raise SystemExit(f"macro reg guide: macros {a_['macro']} and {b_['macro']} overlap")
            gap, ax, lo_, hi_ = max(gaps, key=lambda g_: g_[0])
            mid = lo_["macro_um"][ax + 2] + gap / 2.0
            lo_["box_um"][ax + 2] = min(lo_["box_um"][ax + 2], mid)
            hi_["box_um"][ax] = max(hi_["box_um"][ax], mid)
    for g_ in out:
        g_["box_um"] = [round(v, 3) for v in g_["box_um"]]
        g_["macro_um"] = [round(v, 3) for v in g_["macro_um"]]
    return out


def relay_reg_guide_spec(relays, pins, mguides, core_box, step_um=5.0):
    """HBM-CORES-REBAL-10 (opt-in --relay-reg-guide FILE, with --macro-reg-guide): a register stage between boundary
    pins and a set of macro-side registers (e.g. the pinned bank write regs wd_pin/wa_pin/w_pin between the write pins
    and the per-column WCOPY copies) gets a GPL guide box centred on the plan point that MINIMISES THE LONGER HOP:
    P = argmin max(max_i L1(pin_i, P), max_j L1(P, macro_j centre)), searched on a step_um grid over the core, P such
    that the box (P +- half_um) stays clear of every macro guide box (all guides stay disjoint).
    relays = [{name, members: [literal instance-name prefixes], pins: regex on plan pin names,
               sinks: macro instance prefix, half_um}]; pins = [(name, x, y)]; mguides = macro_reg_guide_spec output."""
    out = []
    for r in relays:
        pp = [(x, y) for n, x, y in pins if re.search(r["pins"], n)]
        sk = [((g["macro_um"][0] + g["macro_um"][2]) / 2, (g["macro_um"][1] + g["macro_um"][3]) / 2)
              for g in mguides if g["macro"].startswith(r["sinks"])]
        if not pp or not sk:
            raise SystemExit(f"relay reg guide {r['name']}: {len(pp)} pins / {len(sk)} sink macros")
        hf = float(r.get("half_um", 12.0))
        taken = [g["box_um"] for g in mguides] + [g["box_um"] for g in out]
        best = None
        nx, ny = int((core_box[2] - core_box[0]) / step_um), int((core_box[3] - core_box[1]) / step_um)
        for i in range(nx + 1):
            for j in range(ny + 1):
                x, y = core_box[0] + i * step_um, core_box[1] + j * step_um
                b = [max(core_box[0], x - hf), max(core_box[1], y - hf), min(core_box[2], x + hf), min(core_box[3], y + hf)]
                if any(b[0] < q[2] and q[0] < b[2] and b[1] < q[3] and q[1] < b[3] for q in taken):
                    continue
                h1 = max(abs(px - x) + abs(py - y) for px, py in pp)
                h2 = max(abs(sx - x) + abs(sy - y) for sx, sy in sk)
                key = (max(h1, h2), h1 + h2, x, y)
                if best is None or key < best[0]:
                    best = (key, b, h1, h2)
        if best is None:
            raise SystemExit(f"relay reg guide {r['name']}: no free grid point")
        (_, _, x, y), b, h1, h2 = best
        out.append(dict(name=r["name"], prefixes=list(r["members"]), point_um=[round(x, 3), round(y, 3)],
                        box_um=[round(v, 3) for v in b], hop_pins_um=round(h1, 1), hop_sinks_um=round(h2, 1),
                        pins=len(pp), sink_macros=len(sk)))
    return out


