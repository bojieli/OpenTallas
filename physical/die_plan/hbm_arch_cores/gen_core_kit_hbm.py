def fetch(f, commit, dst, at_commit=False):
    """file f from the tree, else at `commit`; at_commit (recipe read_at_commit: true) always reads it at `commit`
    (as-built source pin: the tree copy may be another version of the file)."""
    src = REPO / f
    if src.is_file() and not at_commit:
        data = src.read_bytes()
    else:
        r = subprocess.run(["git", "-C", str(REPO), "show", f"{commit}:{f}"], capture_output=True)
        if r.returncode:
            raise SystemExit(f"rtl file {f} missing in tree and at {commit}")
        data = r.stdout
    if dst.exists() and dst.read_bytes() != data:
        raise SystemExit(f"rtl name clash {dst.name}")
    dst.write_bytes(data)


def yosys_ports(files, top, params, defines, incdir):
    """elaborated port list of `top` [(name, dir, width)] (yosys portlist after hierarchy -chparam)."""
    ch = " ".join(f"-chparam {k} {v}" for k, v in params.items())
    d = " ".join(f"-D{x}" for x in ["SYNTHESIS"] + list(defines))
    sv = [f for f in files if not f.endswith((".svh", ".vh"))]
    script = (f"read_verilog -sv -defer {d} -I{incdir} " + " ".join(sv) + f"; hierarchy -top {top} {ch}; "
              f"tee -q -o {incdir}/portlist.txt portlist {top}")
    r = subprocess.run([YOSYS, "-q", "-p", script], capture_output=True, text=True)
    if r.returncode:   # yosys 0.68 -defer can assert on re-elaborated parametric modules: plain read
        r = subprocess.run([YOSYS, "-q", "-p", script.replace("read_verilog -sv -defer", "read_verilog -sv")],
                           capture_output=True, text=True)
    if r.returncode and params:   # yosys 0.68 hierarchy -chparam can assert (qcore_r13): chparam -set as ORFS does
        cs = f"chparam {' '.join(f'-set {k} {v}' for k, v in params.items())} {top}; "
        r = subprocess.run([YOSYS, "-q", "-p", script.replace("read_verilog -sv -defer", "read_verilog -sv")
                            .replace(f"hierarchy -top {top} {ch}", cs + f"hierarchy -top {top}")
                            .replace(f"portlist {top}", "portlist A:top")],
                           capture_output=True, text=True)
    plist = Path(f"{incdir}/portlist.txt").read_text() if Path(f"{incdir}/portlist.txt").is_file() else ""
    if r.returncode:
        raise SystemExit(f"yosys elaboration of {top} failed:\n{r.stderr[-3000:]}")
    ports = []
    for ln in plist.splitlines():
        m = re.match(r"^\s*(input|output|inout)\s+\[(\d+):(\d+)\]\s+(\S+)", ln)
        if m:
            ports.append((m.group(4), m.group(1), abs(int(m.group(2)) - int(m.group(3))) + 1))
            continue
        m = re.match(r"^\s*(input|output|inout)\s+(\S+)\s*$", ln)
        if m:
            ports.append((m.group(2), m.group(1), 1))
    if not ports:
        raise SystemExit(f"yosys portlist of {top}: no ports parsed\n{r.stdout[-2000:]}")
    return ports


def retain_unused_inputs(files, top, retained, kd):
    """Keep declared reserved input bits physically registered without changing outputs."""
    if not retained:
        return None
    body = []
    for port, bits in retained.items():
        width = len(bits)
        expr = "{" + ", ".join(f"{port}[{int(b)}]" for b in bits) + "}"
        body += [f"    (* keep = 1 *) wire [{width-1}:0] keep_unused_{port};",
                 f"    (* keep = 1, keep_hierarchy = 1 *) ot_hbm_face_input_sink #(.W({width})) u_bin_unused_{port} "
                 f"(.clk(clk), .d({expr}), .q(keep_unused_{port}));"]
    rx = re.compile(r"(?ms)(^module\s+" + re.escape(top) + r"\b.*?)(^endmodule)")
    matches = 0
    for f in files:
        p = Path(f)
        if p.suffix not in (".sv", ".v"):
            continue
        text = p.read_text()
        text, n = rx.subn(lambda m: m[1] + "\n" + "\n".join(body) + "\n" + m[2], text)
        if n:
            p.write_text(text); matches += n
    if matches != 1:
        raise ValueError(f"reserved-input retention expected one {top}, found {matches}")
    helper = Path(kd) / "rtl" / "ot_hbm_face_input_sink.sv"
    helper.write_text("(* keep_hierarchy = 1 *) module ot_hbm_face_input_sink #(parameter W=1)(input clk,input [W-1:0] d,output [W-1:0] q);\n"
                      "(* keep = 1 *) reg [W-1:0] state_q;always @(posedge clk) state_q <= d;assign q=state_q;\nendmodule\n")
    return helper


def clone_output_state(files, top, clone, kd):
    """Duplicate an existing state DFF at each output face, preserving its edge/reset."""
    if not clone:
        return None
    state, nxt, width, reset = (clone[k] for k in ("state", "next", "width", "reset"))
    wire = "face_clone_" + state
    extra = (f"\n    wire [{width-1}:0] {wire};\n"
             f"    generate for (genvar cp=0;cp<{width};cp=cp+1) begin:g_face_clone_{state}\n"
             f"        (* keep = 1, keep_hierarchy = 1 *) ot_hbm_face_state_bit u_bout_copy "
             f"(.clk(clk),.rst_n({reset}),.d({nxt}[cp]),.q({wire}[cp]));\n    end endgenerate\n")
    rx = re.compile(r"(?ms)(^module\s+" + re.escape(top) + r"\b.*?)(^endmodule)")
    matches = 0
    def patch(m):
        text = m[1]
        for port in clone["ports"]:
            pattern = r"(assign\s+" + re.escape(port) + r"\s*=\s*)" + re.escape(state) + r"(?=\[)"
            text, n = re.subn(pattern, lambda q: q[1] + wire, text)
            if n != 1:
                raise ValueError(f"expected one output state assignment for {port}")
        return text + extra + m[2]
    for f in files:
        p=Path(f)
        if p.suffix not in (".v", ".sv"):
            continue
        text,n=rx.subn(patch,p.read_text())
        if n:
            p.write_text(text); matches += n
    if matches != 1:
        raise ValueError(f"output clone expected one {top}, found {matches}")
    helper=Path(kd)/"rtl"/"ot_hbm_face_state_bit.sv"
    helper.write_text("(* keep_hierarchy = 1 *) module ot_hbm_face_state_bit(input clk,rst_n,d,output reg q);\n"
                      "always @(posedge clk or negedge rst_n) if(!rst_n) q<=1'b0;else q<=d;\nendmodule\n")
    return helper


def build_wrapper(module, pb, top, params, tports, cmap=None, straps=None, ties=None):
    """pass-through wrapper `module` (plan pins pb {bus: (w, scalar)}) around `top` (tports).  cmap = {plan bus:
    {top port: bits}} (split cut map) else names must match.  Returns (text, report)."""
    tp = {n: (d, w) for n, d, w in tports}
    conns, rep = {}, dict(open_outputs=[], tied_inputs=[], straps={}, mapped=0)
    decl = []
    for b, (w, scalar) in sorted(pb.items()):
        if cmap is not None:
            mp = cmap.get(b)
            if mp is None:
                raise SystemExit(f"MAP_AMBIGUOUS {module}: plan bus {b} not in the cut map")
            if len(mp) != 1:
                raise SystemExit(f"MAP_AMBIGUOUS {module}: plan bus {b} -> {mp} (several canonical ports)")
            tname, bits = next(iter(mp.items()))
        else:
            tname, bits = b, w
        if tname not in tp:
            raise SystemExit(f"PORT_MISMATCH {module}: plan bus {b} -> {tname} not a port of {top}")
        d, tw = tp[tname]
        if not (bits == w == tw):
            raise SystemExit(f"PORT_MISMATCH {module}: plan bus {b} width {w} -> {tname}[{tw}] (map bits {bits})")
        if tname in conns:
            raise SystemExit(f"PORT_MISMATCH {module}: {tname} reached twice")
        conns[tname] = b
        decl.append(f"    {d} wire {'' if scalar else f'[{w - 1}:0] '}{b}")
        rep["mapped"] += w
    body = []
    for n, (d, w) in tp.items():
        if n in conns:
            continue
        if d == "output":
            rep["open_outputs"].append(f"{n}[{w}]")
            continue
        val = None
        if straps and n in straps:
            val = straps[n]
            rep["straps"][n] = val
        elif ties and n in ties:
            val = ties[n]
            rep["tied_inputs"].append(f"{n}={val}")
        if val is None:
            raise SystemExit(f"PORT_MISMATCH {module}: input {n}[{w}] of {top} has no plan pin, strap or tie")
        v = str(val)
        if re.fullmatch(r"[01]+", v) and len(v) > 1:
            if len(v) != w:
                raise SystemExit(f"PORT_MISMATCH {module}: strap {n}={v} width {len(v)} != {w}")
            conns[n] = f"{w}'b{v}"
        elif re.fullmatch(r"\d+|0x[0-9a-fA-F]+", v):
            conns[n] = f"{w}'d{int(v, 0)}"
        else:
            conns[n] = v
    prm = (" #(" + ", ".join(f".{k}({v})" for k, v in params.items()) + ")") if params else ""
    txt = ["// GENERATED by gen_core_kit_hbm.py (ELEM-HBM): pass-through wrapper, plan pins -> RTL top; wires only.",
           "`default_nettype none", f"module {module} (", ",\n".join(decl), ");",
           f"    {top}{prm} u_core (", ",\n".join(f"        .{n}({c})" for n, c in conns.items()) + ");",
           "endmodule", "`default_nettype wire", ""]
    return "\n".join(txt), rep


