def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def face_of(x, y, w, h):
    return min([(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")])[1]


def split_name(n):
    m = re.match(r"^(.*)\[(\d+)\]$", n)
    return (m.group(1), int(m.group(2))) if m else (n, None)


def buses_of(names):
    """plan pin names -> {bus: width} (scalar = width 1, None index); refuses holes."""
    b = {}
    for n in names:
        base, i = split_name(n)
        b.setdefault(base, set()).add(i)
    out = {}
    for base, ix in b.items():
        if ix == {None}:
            out[base] = (1, True)
        else:
            if None in ix or sorted(ix) != list(range(max(ix) + 1)):
                raise SystemExit(f"pin bus {base}: non-contiguous bits {sorted(x for x in ix if x is not None)[:8]}..")
            out[base] = (max(ix) + 1, False)
    return out


def plan_pin_records(prow):
    """kit plan_pins.json records {name: {name, layer, x, y}} from io_tcl rows: the plan edge point moved inward by half
    the placed pin depth = the io.tcl pin centre.  HBM-CORES-KITS-4 10-28: a sized row (C25a w/h, io_tcl places it
    h/2 inward) moves by its own h/2, so pins_canonical matches io.tcl; unsized rows keep PIN_LEN_UM/2 (byte-identical)."""
    pp_recs = {}
    for r in prow:
        n = r["bus"] if r["bit"] is None else f"{r['bus']}[{r['bit']}]"
        x, y = r["x"], r["y"]
        half = float(r["h"]) / 2 if r.get("h") is not None else PIN_LEN_UM / 2
        if r.get("entry") is not None:
            # AUTOBUILD-PIPE-2 --clock-pin-entry: the row carries its io.tcl centre (interior entries have no face)
            x, y = r["entry"]
            pp_recs[n] = dict(name=n, layer=r["layer"], x=round(float(x), 4), y=round(float(y), 4))
            continue
        if r["face"] in "EW":
            x = x - half if r["face"] == "E" else x + half
        else:
            y = y - half if r["face"] == "N" else y + half
        pp_recs[n] = dict(name=n, layer=r["layer"], x=round(float(x), 4), y=round(float(y), 4))
    return pp_recs


CLOCK_ENTRY_SIZE = (0.048, 0.48)   # GEOM-21 / kit_contract CLOCK_PIN_MIN (x extent, y extent)


def clock_entry_pin(p, w, h, m5):
    """AUTOBUILD-PIPE-2 10-31 (DIE-HBM-47 00:10 rule, KIT-WAVE-3 00:46: every d44f core_kit kit failed preflight
    clock_pin_geometry): a clock-class M5 plan pin is placed as the core clock entry, not projected to its nearest face.
    Interior plan point (> PIN_LEN_UM from every face, METHODOLOGY 12.8a centre entries) -> that point; face point -> on
    that face.  Size 0.048 x 0.48 (x, y), centre x on the M5 track (offset, pitch) = m5; an E/W face entry widens so it
    still touches its face.  -> (cx, cy, (sx, sy), face or None)."""
    off, pitch = m5
    snap = lambda v: off + math.floor((v - off) / pitch + 0.5) * pitch
    f = face_of(p["x"], p["y"], w, h)
    d = min(p["x"], w - p["x"], p["y"], h - p["y"])
    sx, sy = CLOCK_ENTRY_SIZE
    if d > PIN_LEN_UM:
        return round(snap(p["x"]), 4), round(float(p["y"]), 4), (sx, sy), None
    if f in "NS":
        cy = h - sy / 2 if f == "N" else sy / 2
        return round(snap(p["x"]), 4), round(cy, 4), (sx, sy), f
    if f == "W":
        cx = off + math.ceil((sx / 2 - off) / pitch - 1e-9) * pitch          # first track with the pin inside the core
        return round(cx, 4), round(float(p["y"]), 4), (round(max(sx, 2 * cx), 4), sy), f
    cx = off + math.floor((w - sx / 2 - off) / pitch + 1e-9) * pitch           # E: last such track
    return round(cx, 4), round(float(p["y"]), 4), (round(max(sx, 2 * (w - cx)), 4), sy), f


def io_tcl(pins, w, h, tag, clock_entry=None):
    """clock_entry (opt-in, --clock-pin-entry on): {"names": clock pin names, "m5": (offset, pitch)} -> those M5 pins
    take clock_entry_pin; None = every pin as before (byte-identical)."""
    out = [f"# GENERATED by gen_core_kit_hbm.py: exact plan pins of {tag} ({len(pins)} pins, core frame um)."]
    rows = []
    for p in pins:
        if clock_entry and p["name"] in clock_entry["names"] and p["layer"] == "M5":
            cx, cy, (sx, sy), f = clock_entry_pin(p, w, h, clock_entry["m5"])
            out.append(f"place_pin -pin_name {{{p['name']}}} -layer M5 -location {{{cx:.4f} {cy:.4f}}} "
                       f"-pin_size {{{sx:.4f} {sy:.4f}}}")
            b, i = split_name(p["name"])
            # row x/y = the face point as for every pin (interior: the entry point, face "I"); entry = io.tcl centre
            rx = {"E": w, "W": 0.0}.get(f, cx)
            ry = {"N": h, "S": 0.0}.get(f, cy)
            rows.append(dict(bus=b, bit=i, layer="M5", x=round(rx, 4), y=round(ry, 4), face=f or "I", w=sx, h=sy,
                             entry=[cx, cy]))
            continue
        f = face_of(p["x"], p["y"], w, h)
        lw = LAYER_W.get(p["layer"], 0.04)
        # DIE-HBM-10 C25a (opt-in): a plan pin record with explicit w (across the face) and h (into the core) keeps that
        # size, e.g. the clock-class pins at M5 0.048 x 0.48 (GEOM-21 / KIT_PREFLIGHT clock_pin_geometry); records
        # without w/h (every pin before C25a) are placed exactly as before.
        sized = p.get("w") is not None and p.get("h") is not None
        lw, ln = (float(p["w"]), float(p["h"])) if sized else (lw, PIN_LEN_UM)
        x, y = p["x"], p["y"]
        if f in "EW":
            x = w if f == "E" else 0.0
            size, cx, cy = (ln, lw), (x - ln / 2 if f == "E" else x + ln / 2), y
        else:
            y = h if f == "N" else 0.0
            size, cx, cy = (lw, ln), x, (y - ln / 2 if f == "N" else y + ln / 2)
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{cx:.4f} {cy:.4f}}} "
                   f"-pin_size {{{size[0]:.4f} {size[1]:.4f}}}")
        b, i = split_name(p["name"])
        rows.append(dict(bus=b, bit=i, layer=p["layer"], x=round(x if f in "EW" else p["x"], 4),
                         y=round(y if f in "NS" else p["y"], 4), face=f))
        if sized:
            rows[-1].update(w=lw, h=ln)
    return "\n".join(out) + "\n", rows


def core_macros_placement(cm_path, module, macros):
    """AUTOBUILD-PIPE-2 --core-macros auto: the plan core_macros.json KNOWN rects of MODULE -> (rec macro_placement
    rows {inst, xy_um, orient, macro}, macro_placement_src), the HBM-CORES-KITS-12 cm2mp form (inst = the entry name
    without u_fcore., which the face shell adds back; origin = rect lower-left; master = the entry's, else the kit's
    only macro).  None when the kit has no macros.  A macro kit without KNOWN rects fails PLAN_CORE_MACROS."""
    if not macros:
        return None
    e = (json.load(open(cm_path)).get("cores") or {}).get(module) if Path(cm_path).is_file() else None
    if not e or e.get("status") != "KNOWN" or not e.get("macros"):
        raise SystemExit(f"PLAN_CORE_MACROS {module}: {len(macros)} macro master(s) {sorted(macros)} but plan "
                         f"{Path(cm_path).name} has no KNOWN macro rects (status {(e or {}).get('status', 'absent')}) "
                         "-> no static MACRO_PLACEMENT_TCL; die owner adds the rects")
    rows = []
    for q in e["macros"]:
        ms = q.get("master") or (macros[0] if len(set(macros)) == 1 else None)
        if ms not in macros:
            raise SystemExit(f"PLAN_CORE_MACROS {module}: {q['name']} master {ms!r} not a kit macro {sorted(macros)}")
        k = q["name"][len("u_fcore."):] if q["name"].startswith("u_fcore.") else q["name"]
        x0, y0 = q["rect_um"][:2]
        rows.append(dict(inst=k, xy_um=[round(float(x0), 3), round(float(y0), 3)], orient=q.get("orient", "R0"), macro=ms))
    return rows, dict(file=str(cm_path), sha256=sha(cm_path), module=module, status=e["status"], basis=e.get("basis"))


