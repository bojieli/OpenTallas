def face_of(x, y, w, h):
    return min([(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")])[1]


def split_name(n):
    m = re.match(r"^(.*)\[(\d+)\]$", n)
    return (m.group(1), int(m.group(2))) if m else (n, None)


def direct_port_check(pb, tports, shell_drop):
    """top == module port check of the plan pin table against the RTL top.

    With the face shell dropping unread input bits (drop_face_shell_pins plan events, e.g. HBM i8w8 1109 drops
    command[191:184]), the plan table may already lack the unread top bits / whole bus of an INPUT: those buses are
    deferred, not failed, and returned as {bus: plan width} for the post-shell check (shell keep == plan width).
    Returns (bad, deferred)."""
    tp = {n: (d, wd) for n, d, wd in tports}
    bad, deferred = [], {}
    for b, (wd, _) in pb.items():
        d, twd = tp.get(b, (None, None))
        if twd == wd:
            continue
        if shell_drop and d == "input" and twd is not None and wd < twd:
            deferred[b] = wd
        else:
            bad.append(b)
    for n, (d, _) in tp.items():
        if n in pb:
            continue
        if shell_drop and d == "input":
            deferred[n] = 0
        else:
            bad.append(n)
    return bad, deferred


def buses_of(names):
    """plan pin names -> {bus: width} (scalar = width 1, None index); refuses holes."""
    b = {}
    for n in names:
        base, i = split_name(n)
        b.setdefault(base, set()).add(i)
    out = {}
    for base, ix in b.items():
        if ix == {None}:
            out[base] = (1, True)
        else:
            if None in ix or sorted(ix) != list(range(max(ix) + 1)):
                raise SystemExit(f"pin bus {base}: non-contiguous bits {sorted(x for x in ix if x is not None)[:8]}..")
            out[base] = (max(ix) + 1, False)
    return out


def plan_pin_records(prow):
    """kit plan_pins.json records {name: {name, layer, x, y}} from io_tcl rows: the plan edge point moved inward by half
    the placed pin depth = the io.tcl pin centre.  HBM-CORES-KITS-4 10-28: a sized row (C25a w/h, io_tcl places it
    h/2 inward) moves by its own h/2, so pins_canonical matches io.tcl; unsized rows keep PIN_LEN_UM/2 (byte-identical)."""
    pp_recs = {}
    for r in prow:
        n = r["bus"] if r["bit"] is None else f"{r['bus']}[{r['bit']}]"
        x, y = r["x"], r["y"]
        half = float(r["h"]) / 2 if r.get("h") is not None else PIN_LEN_UM / 2
        if r.get("entry") is not None:
            # AUTOBUILD-PIPE-2 --clock-pin-entry: the row carries its io.tcl centre (interior entries have no face)
            x, y = r["entry"]
            pp_recs[n] = dict(name=n, layer=r["layer"], x=round(float(x), 4), y=round(float(y), 4))
            continue
        if r["face"] in "EW":
            x = x - half if r["face"] == "E" else x + half
        else:
            y = y - half if r["face"] == "N" else y + half
        pp_recs[n] = dict(name=n, layer=r["layer"], x=round(float(x), 4), y=round(float(y), 4))
    return pp_recs


CLOCK_ENTRY_SIZE = (0.048, 0.48)   # GEOM-21 / kit_contract CLOCK_PIN_MIN (x extent, y extent)


def clock_entry_pin(p, w, h, m5):
    """AUTOBUILD-PIPE-2 10-31 (DIE-HBM-47 00:10 rule, KIT-WAVE-3 00:46: every d44f core_kit kit failed preflight
    clock_pin_geometry): a clock-class M5 plan pin is placed as the core clock entry, not projected to its nearest face.
    Interior plan point (> PIN_LEN_UM from every face, METHODOLOGY 12.8a centre entries) -> that point; face point -> on
    that face.  Size 0.048 x 0.48 (x, y), centre x on the M5 track (offset, pitch) = m5; an E/W face entry widens so it
    still touches its face.  -> (cx, cy, (sx, sy), face or None)."""
    off, pitch = m5
    snap = lambda v: off + math.floor((v - off) / pitch + 0.5) * pitch
    f = face_of(p["x"], p["y"], w, h)
    d = min(p["x"], w - p["x"], p["y"], h - p["y"])
    sx, sy = CLOCK_ENTRY_SIZE
    if d > PIN_LEN_UM:
        return round(snap(p["x"]), 4), round(float(p["y"]), 4), (sx, sy), None
    if f in "NS":
        cy = h - sy / 2 if f == "N" else sy / 2
        return round(snap(p["x"]), 4), round(cy, 4), (sx, sy), f
    if f == "W":
        cx = off + math.ceil((sx / 2 - off) / pitch - 1e-9) * pitch          # first track with the pin inside the core
        return round(cx, 4), round(float(p["y"]), 4), (round(max(sx, 2 * cx), 4), sy), f
    cx = off + math.floor((w - sx / 2 - off) / pitch + 1e-9) * pitch           # E: last such track
    return round(cx, 4), round(float(p["y"]), 4), (round(max(sx, 2 * (w - cx)), 4), sy), f


def entry_clock_pins(pins, clks):
    """DIE-HBM-82 11-06 (FLOW class, DIE-HBM-82 ruling (A)): the clock pins the plan clock entry may move = the clock pins
    whose pin-table row is on M5.  The entry form (clock_entry_pin, clock_pin_sites_um) is an M5 track form; a non-M5
    clock pin (sm_vm_wr_q_t_lanes4: 6 M4 E-face clocks) was moved to the M5 spread around the entry and then placed as an
    M4 face pin on the face nearest that point (W, (0.24, 108)), matching neither the table nor the entry.  Non-M5 clock
    pins keep their table position (placed as every other face pin); M5-only modules are unchanged."""
    lay = {p["name"]: p.get("layer") for p in pins}
    return [n for n in clks if lay.get(n) == "M5"]


def plan_clock_entries(entries_path, module, clks, w, h, m5):
    """DIE-HBM-48 10-31 (METHODOLOGY 12.8a "kits must place the clock pin exactly there"; KIT-WAVE d44f qw_dec /
    q2n2_vm clock_reach FAIL): the plan's per-module clock entry (PLANDIR/clock_entries.json, core frame; port +
    merged_clock_ports) is the clock pin location.  27 d44f views kept their clock pins at a face/corner in the pin
    table while the plan entry is the core centre, so --clock-pin-entry on placed the clock on the face.
    -> ({pin name: (x, y)}, record) for every clock pin whose bus is named by the module's entry; several pins (merged
    ports, clock buses) sit on every 2nd M5 track centred on the entry x (0.096 apart, same pitch as face clock
    pins).  ({}, None) when the file or the module's entry is absent (pin table kept).  Instances of one module with
    different entries -> SystemExit CLOCK_ENTRY_CONFLICT (one kit serves every instance)."""
    p = Path(entries_path)
    if not p.is_file():
        return {}, None
    ents = set()
    for blk in json.load(open(p)).values():
        for e in (blk.values() if isinstance(blk, dict) else []):
            if isinstance(e, dict) and e.get("module") == module and e.get("xy_um"):
                sites = e.get("clock_pin_sites_um")
                if sites is not None:
                    if not isinstance(sites, dict) or any(not isinstance(v, list) or len(v) != 2 for v in sites.values()):
                        raise SystemExit(f"CLOCK_ENTRY_SITES {module}: expected named [x, y] clock pin sites")
                    sites = tuple(sorted((n, float(v[0]), float(v[1])) for n, v in sites.items()))
                ents.add((round(float(e["xy_um"][0]), 4), round(float(e["xy_um"][1]), 4), e.get("port"),
                          tuple(sorted(e.get("merged_clock_ports") or [])), sites))
    if not ents:
        return {}, None
    if len(ents) > 1:
        raise SystemExit(f"CLOCK_ENTRY_CONFLICT {module}: {len(ents)} different plan clock entries {sorted(ents, key=repr)[:3]}")
    ex, ey, port, merged, sites = next(iter(ents))
    if not (0 < ex < w and 0 < ey < h):
        raise SystemExit(f"CLOCK_ENTRY_OUTSIDE {module}: plan entry ({ex}, {ey}) outside the {w} x {h} outline")
    named = set(merged) | ({port} if port else set())
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    sel = [n for n in clks if base(n) in named]
    if not sel:
        return {}, None
    off, pitch = m5
    cx = off + math.floor((ex - off) / pitch + 0.5) * pitch
    step = 2 * pitch
    k0 = -((len(sel) - 1) // 2)
    out = {n: (round(cx + (k0 + i) * step, 4), ey) for i, n in enumerate(sorted(sel, key=lambda n: (base(n), n)))}
    # Explicit sites keep reviewed per-port access geometry while retaining the
    # common source/merged-port contract. Absent sites preserve legacy spreading.
    if sites is not None:
        if {n for n, _, _ in sites} != set(sel):
            raise SystemExit(f"CLOCK_ENTRY_SITES {module}: sites must name exactly {sorted(sel)}")
        out = {n: (x, y) for n, x, y in sites}
        for n, (x, y) in out.items():
            if (not math.isfinite(x) or not math.isfinite(y) or not 0 < x < w or not 0 < y < h or
                    abs((x - off) / pitch - round((x - off) / pitch)) > 1e-5):
                raise SystemExit(f"CLOCK_ENTRY_SITES {module}: invalid/off-track M5 site for {n}: {(x, y)}")
        if len(set(out.values())) != len(out):
            raise SystemExit(f"CLOCK_ENTRY_SITES {module}: coincident explicit clock pins")
    xs = [x for x, _ in out.values()]
    if min(xs) <= PIN_LEN_UM or max(xs) >= w - PIN_LEN_UM:
        raise SystemExit(f"CLOCK_ENTRY_SPREAD {module}: {len(sel)} clock pins around x {cx} leave the core")
    rec = dict(file=str(p), sha256=sha(p), module=module, xy_um=[ex, ey], ports=sorted(named), pins=len(sel),
               rule="METHODOLOGY 12.8a plan clock entry (DIE-HBM-48)")
    if sites is not None:
        rec["clock_pin_sites_um"] = {n: list(xy) for n, xy in out.items()}
    return out, rec


def io_tcl(pins, w, h, tag, clock_entry=None):
    """clock_entry (opt-in, --clock-pin-entry on): {"names": clock pin names, "m5": (offset, pitch)} -> those M5 pins
    take clock_entry_pin; None = every pin as before (byte-identical)."""
    out = [f"# GENERATED by gen_core_kit_hbm.py: exact plan pins of {tag} ({len(pins)} pins, core frame um)."]
    rows = []
    for p in pins:
        if clock_entry and p["name"] in clock_entry["names"] and p["layer"] == "M5":
            cx, cy, (sx, sy), f = clock_entry_pin(p, w, h, clock_entry["m5"])
            out.append(f"place_pin -pin_name {{{p['name']}}} -layer M5 -location {{{cx:.4f} {cy:.4f}}} "
                       f"-pin_size {{{sx:.4f} {sy:.4f}}}")
            b, i = split_name(p["name"])
            # row x/y = the face point as for every pin (interior: the entry point, face "I"); entry = io.tcl centre
            rx = {"E": w, "W": 0.0}.get(f, cx)
            ry = {"N": h, "S": 0.0}.get(f, cy)
            rows.append(dict(bus=b, bit=i, layer="M5", x=round(rx, 4), y=round(ry, 4), face=f or "I", w=sx, h=sy,
                             entry=[cx, cy]))
            continue
        f = face_of(p["x"], p["y"], w, h)
        if clock_entry and p["layer"] == "M5" and f in "EW" and p.get("w") is None:
            # DIE-HBM-62/FLOW class M5-EW-PIN (hnx_vms_bank_q0_faces v796f rst_n: DRT-0422/DRT-0074 no access point): M5
            # tracks are vertical, so a face stub along x on an E/W face has no track through it.  Same y and face as the
            # plan, in the proven on-track entry form that clock pins already use on those faces.  A plan point a few um
            # inside the face still means that face (as the stub form below projects it), so it goes in on the face.
            on_face = dict(p, x=w if f == "E" else 0.0)
            cx, cy, (sx, sy), f2 = clock_entry_pin(on_face, w, h, clock_entry["m5"])
            out.append(f"place_pin -pin_name {{{p['name']}}} -layer M5 -location {{{cx:.4f} {cy:.4f}}} "
                       f"-pin_size {{{sx:.4f} {sy:.4f}}}")
            b, i = split_name(p["name"])
            rows.append(dict(bus=b, bit=i, layer="M5", x=round(w if f == "E" else 0.0, 4), y=round(cy, 4), face=f, w=sx,
                             h=sy, entry=[cx, cy]))
            continue
        lw = LAYER_W.get(p["layer"], 0.04)
        # DIE-HBM-10 C25a (opt-in): a plan pin record with explicit w (across the face) and h (into the core) keeps that
        # size, e.g. the clock-class pins at M5 0.048 x 0.48 (GEOM-21 / KIT_PREFLIGHT clock_pin_geometry); records
        # without w/h (every pin before C25a) are placed exactly as before.
        sized = p.get("w") is not None and p.get("h") is not None
        lw, ln = (float(p["w"]), float(p["h"])) if sized else (lw, PIN_LEN_UM)
        x, y = p["x"], p["y"]
        if f in "EW":
            x = w if f == "E" else 0.0
            size, cx, cy = (ln, lw), (x - ln / 2 if f == "E" else x + ln / 2), y
        else:
            y = h if f == "N" else 0.0
            size, cx, cy = (lw, ln), x, (y - ln / 2 if f == "N" else y + ln / 2)
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{cx:.4f} {cy:.4f}}} "
                   f"-pin_size {{{size[0]:.4f} {size[1]:.4f}}}")
        b, i = split_name(p["name"])
        rows.append(dict(bus=b, bit=i, layer=p["layer"], x=round(x if f in "EW" else p["x"], 4),
                         y=round(y if f in "NS" else p["y"], 4), face=f))
        if sized:
            rows[-1].update(w=lw, h=ln)
    return "\n".join(out) + "\n", rows


def declared_source_io_tcl(pins, w, h, tag, clocks, resets, vertical_resets=False):
    """Opt-in native source contracts: consume named clock/reset centres, never project or merge them."""
    out = [f"# GENERATED declared native clock/reset points of {tag} ({len(pins)} pins)."]
    rows = []
    named = set(clocks) | set(resets)
    for p in pins:
        if p["name"] not in named:
            text, one = io_tcl([p], w, h, tag)
            out.extend(text.splitlines()[1:])
            rows.extend(one)
            continue
        if p["layer"] != "M5":
            raise ValueError("DECLARED_NATIVE_PIN: named clock/reset must declare M5: " + p["name"])
        x, y = float(p["x"]), float(p["y"])
        sized = p.get("w") is not None or p.get("h") is not None
        if sized and (p.get("w") is None or p.get("h") is None):
            raise ValueError("DECLARED_NATIVE_PIN: both shape dimensions required")
        if sized:
            sx, sy = float(p["w"]), float(p["h"])
        elif p["name"] in clocks:
            sx, sy = CLOCK_ENTRY_SIZE
        elif vertical_resets and p["name"] in resets:
            # Explicit owned native form: M5 reset pads follow vertical metal.
            # A nearest-edge horizontal pad forms T-shaped RECTONLY unions
            # with default VIA45/VIA56 enclosures at an interior point.
            sx, sy = LAYER_W["M5"], PIN_LEN_UM
        elif face_of(x, y, w, h) in "EW":
            sx, sy = PIN_LEN_UM, LAYER_W["M5"]
        else:
            sx, sy = LAYER_W["M5"], PIN_LEN_UM
        if not all(math.isfinite(v) for v in (x, y, sx, sy)) or min(sx, sy) <= 0:
            raise ValueError("DECLARED_NATIVE_PIN: invalid point/shape")
        # The existing geometry/track gates judge the declared rectangle. A
        # legal track may intersect it without passing through its centre.
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer M5 -location {{{x:.4f} {y:.4f}}} "
                   f"-pin_size {{{sx:.4f} {sy:.4f}}}")
        b, i = split_name(p["name"])
        row = dict(bus=b, bit=i, layer="M5", x=x, y=y, face="I", entry=[x, y])
        if sized:
            row.update(w=sx, h=sy, declared_native_shape=True)
        rows.append(row)
    return "\n".join(out) + "\n", rows


