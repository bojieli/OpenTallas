"""DIE-HBM-97/KSHARE-PC: make the pin-cycle form RTL of one kshare kit from its vR rtl/ dir.
   mk_pc_rtl.py SRC_RTL DST_RTL CORE_PC_SV VIEW
 - face shell: the generator's in_stages form (face_shell.py emit_shell, DIE-HBM-61/CUTS): one relay
   u_bimid0_<bus> (ot_hbm_face_reg, free-placed) after the face flop u_bin_<bus> of every IN_STAGE bus;
 - wrapper: u_core gets .PCF(1);
 - core: CORE_PC_SV (kshare core with the PCF parameter)."""
import re, shutil, sys
from pathlib import Path
IN_STAGES = ["w_k_v", "w_k_addr", "w_k_wdata", "c_kr_v", "c_kr_tag", "c_kr_beat", "c_kr_data"]
src, dst, core, view = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4]
dst.mkdir(parents=True, exist_ok=True)
for f in src.iterdir():
    shutil.copy2(f, dst / f.name)
shutil.copy2(core, dst / "ot_hbm_svc_vm_kshare_splitstrap.sv")
m = f"ot_hbm_svc_vm_kshare_splitstrap__{view}"
fs = dst / f"{m}__fshell.sv"; t = fs.read_text()
for n in IN_STAGES:
    pat = re.compile(r"(    \(\* keep \*\) ot_hbm_face_reg #\(\.W\((\d+)\)\) u_bin_%s \(\.clk\((\w+)\), \.d\(%s\), \.q\(%s__fq\)\);\n)" % (n, n, n))
    mm = pat.findall(t); assert len(mm) == 1, (n, len(mm))
    line, k, clk = mm[0]
    t = t.replace(line, line + f"    wire [{int(k) - 1}:0] {n}__i0;\n"
                  f"    (* keep *) ot_hbm_face_reg #(.W({k})) u_bimid0_{n} (.clk({clk}), .d({n}__fq), .q({n}__i0));\n")
    c = len(re.findall(r"\.%s\(\{?[^)]*\b%s__fq\}?\)" % (n, n), t)); assert c == 1, (n, c)
    t = re.sub(r"(\.%s\(\{?[^)]*?)\b%s__fq(\}?\))" % (n, n), r"\g<1>%s__i0\g<2>" % n, t)
t = t.replace("// GENERATED by face_shell.py (HBM-FACE)", "// GENERATED by face_shell.py (HBM-FACE), in_stages %s=1 (DIE-HBM-97/KSHARE-PC)" % ",".join(IN_STAGES), 1)
fs.write_text(t)
wr = dst / f"{m}__wrap.sv"; w = wr.read_text()
assert w.count("ot_hbm_svc_vm_kshare_splitstrap #(.MUT(0), .KRL1(1)) u_core") == 1
wr.write_text(w.replace("ot_hbm_svc_vm_kshare_splitstrap #(.MUT(0), .KRL1(1)) u_core", "ot_hbm_svc_vm_kshare_splitstrap #(.MUT(0), .KRL1(1), .PCF(1)) u_core"))
print("OK", m)
