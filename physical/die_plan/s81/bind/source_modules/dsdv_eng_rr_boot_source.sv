// =====================================================================================================================
// S81-RTLGAP/RG-ENG (10-21, RELEASE_TREE TOK.DS.BENCH.4.5 / TOK.DS.LAYER.3): the Engram ROW-READ path of the S81 72-frame
// MU die and its JOIN into the die's x all-gather (the engram.wkv input), built around the CLOSED lookup element
// dsfd_engram_lkp_static14 (closure-loop 84352a2c7, source 428af274c, byte-identical copy in
// rtl/dsrom_sys/engram/static_lookup_1015/).  Golden: tools/s81_dv/dv_layer_fixtures.engram
//   eng.lead_flit -> eng.hash -> eng.hbm_read (decode_engram_rows) -> eng.rows_allgather -> eng.wkv (linear_q).
//
// Why this shape (die facts, plan_unrouted_g3): the Engram tables of a home die are ~26 GB a layer and rank, i.e. they
// span all 32 pseudo-channels; the 16 dsfd_ctrl_rg3 main faces belong to svc_rs and their 16 reader faces to the 8
// dsdv_idx_rg3 readers.  So the row reads ride the READER faces through one small inline TAP a controller (static reader
// slots, a reader-unproducible tag code, owner FIFO for the pops) and two neighbour chains along the controller row;
// nothing in svc_rs, the readers or the controllers changes.  The rows join the die where every matvec input joins it:
// as XQ x beats (FP8 codes + UE8M0 exponent, ot_s81sl_vq ring format) on a slice V rung, which the receiving ring stops
// assemble, deliver to their x streamers and inject on both tier lines (ot_s81sl_rstop "V rung").
//
//   f_ks (start tap: {start, user 10, tok 21, pos 21}) --> ot_s81eng_win: raw id -> compressed id (released map ROM,
//        ot_dsrom_engram_token_map), per-user 3-deep history in ONE 512x128 SRAM row a user, NgramHashState window with
//        the pos < k blocking (w_k = PAD), compiler slot counter
//   --> dsfd_engram_lkp_static14 (CLOSED: hash, 6 row addresses, fixed-age return, CRC, 48 row beats {scale, 32 codes})
//   --> ot_s81eng_head: each 9-atom row request -> 9 one-atom requests, atom a -> PC a[4:0], sector PCBASE + a >> 5,
//        tag7 {col 3, atom 4}: request chain word {v, pc 5, sec 30, tag 7} one a cycle (54 a window)
//   --> dsdv_eng_tap x16 (one inline on every irg -> ctrl reader link): injects its PCs' words into the reader lane in
//        the Engram window (sl = 1), demuxes the Engram response beats (tag10 g = 0, sc = 1, cell != 0: never produced by
//        dsdv_idx_rg3, whose g = 0 words carry sc = 1 only with cell 0), steers the pops by an owner FIFO, holds the beats
//        in a 6-deep ring a PC and sends them on the RESPONSE chain in its OWN chain slots (owner ids generated by the
//        west-end tap: TDM ownership, no arbitration)
//   --> ot_s81eng_head -> lookup hr (slot = the active window's slot)
//   --> ot_s81eng_xq: decode (ot_hdc_engram_e4m3_bf16, = decode_engram_rows) -> the closed act-quant ot_s81sl_aq12x
//        (= quant_fp8, the linear_q input quantiser; wait line in one 64x512 SRAM ring) -> XQ beat {e1, q1, e0, q0} of
//        global x beat idx = 4 col + beat / 2 (0..95; this rank's 24) in a 2 x 64x512 SRAM beat ring -> 4-fragment V
//        trains on BOTH rung directions of the column it sits on (pass-through of the column's rung, +2 edges)
// Static schedule: every stage is a fixed latency from the f_ks start edge except the HBM service (elastic off-die
// boundary, owner 10-14/15), which is covered by the lookup's fixed RETURN_AGE (missing / late atom = poison + fault).
// No ready / credit / backpressure anywhere; collisions are compiler errors and raise sticky faults (st).
// =====================================================================================================================

// ---------------------------------------------------------------------------------------------------------------------
// ot_s81eng_win: f_ks start -> Engram window (4 compressed ids, w0 = this token) in the compiler slot.
// Edges: f_ks pin flop (cluster) | token map 2 | window 1 -> win_v 3 edges after the pin flop.
// Per-user row (SRAM 512 x 128, row = user): [16:0] id t-1, [33:17] id t-2, [50:34] id t-3.  Rows are never reset: a new
// sequence (pos 0) blocks every look-back (b1 = pos < 1), so a stale row of a reused user slot is never read as history.
// Faults: user >= NUSER, two starts of one user within 3 edges (row read-modify-write overlap), token map fault (illegal
// raw id / compressed id >= 99,092: the window is NOT issued, the lookup then misses it -> the layer's st fault).
// ---------------------------------------------------------------------------------------------------------------------
module ot_s81eng_win #(
    parameter integer NUSER = 64,
    parameter [16:0] PAD = 17'd2
) (
    input  wire        ck,
    input  wire        rst_n,       // landed regional leaf
    input  wire        en,          // strap: Engram home die
    input  wire        ks_v,
    input  wire [9:0]  ks_user,
    input  wire [20:0] ks_tok,
    input  wire [20:0] ks_pos,
    output reg         win_v,
    output reg  [2:0]  win_slot,
    output reg  [67:0] win_ids,
    output reg         fault
);
    wire        t_v = ks_v && en;
    wire        m_v; wire [16:0] m_cid; wire m_f;
    ot_dsrom_engram_token_map u_map (.clk(ck), .rst_n(rst_n), .in_v(t_v), .in_tok(ks_tok), .out_v(m_v), .out_cid(m_cid),
                                     .fault(m_f));
    // user / pos ride the map latency (2 edges); the user row is read on the start edge, captured one edge later
    reg  [9:0]  u1, u2; reg [20:0] p1, p2; reg v1, v2;
    wire [127:0] rd;
    reg  [50:0] h2;
    always @(posedge ck) begin u1 <= ks_user; u2 <= u1; p1 <= ks_pos; p2 <= p1; h2 <= rd[50:0]; end
    always @(posedge ck or negedge rst_n)
        if (!rst_n) begin v1 <= 1'b0; v2 <= 1'b0; end else begin v1 <= t_v; v2 <= v1; end
    wire         b1 = (p2 < 21'd1), b2 = b1 | (p2 < 21'd2), b3 = b2 | (p2 < 21'd3);
    wire         wr = m_v && v2;
    ot_sram_1r1w_512x128_m4_r2c2 u_h (.clk(ck), .r_ce_in(t_v), .r_addr_in({3'd0, ks_user[5:0]}), .rd_out(rd),
        .w_ce_in(wr), .w_addr_in({3'd0, u2[5:0]}), .wd_in({77'd0, h2[33:0], m_cid}), .w_mask_in({128{1'b1}}),
        .rr_en(2'b00), .rr_addr(14'd0), .cr_en(2'b00), .cr_sel(14'd0));
    always @(posedge ck) if (wr) win_ids <= {b3 ? PAD : h2[50:34], b2 ? PAD : h2[33:17], b1 ? PAD : h2[16:0], m_cid};
    always @(posedge ck or negedge rst_n)
        if (!rst_n) begin win_v <= 1'b0; win_slot <= 3'd7; fault <= 1'b0; end
        else begin
            win_v <= wr;
            if (wr) win_slot <= win_slot + 3'd1;
            if ((t_v && ks_user >= 10'(NUSER)) || m_f || (v2 && !m_v) ||
                (t_v && ((v1 && ks_user == u1) || (v2 && ks_user == u2))))
                fault <= 1'b1;
        end
endmodule

// ---------------------------------------------------------------------------------------------------------------------
// ot_s81eng_head: lookup HBM port <-> the two chains.  The lookup issues its 6 row requests on 6 consecutive edges
// (hq_tag = column j); each becomes 9 one-atom requests, issued one a cycle in row order (54 edges, first one edge after
// the first request).  Response chain beats {v, own 4, tag 7, d 256} go to the lookup as {hr_tag = tag[6:4], hr_idx =
// tag[3:0]} with hr_slot = the window's slot (one window is active at a time: lookup II = RETURN_AGE + 64).
// ---------------------------------------------------------------------------------------------------------------------
module ot_s81eng_head #(
    parameter [29:0] PCBASE = 30'd0   // Engram region base sector inside every PC (compiler image placement)
) (
    input  wire         ck,
    input  wire         rst_n,
    input  wire         win_v,
    input  wire [2:0]   win_slot,
    input  wire         hq_v,
    input  wire [30:0]  hq_atom,
    input  wire [2:0]   hq_tag,
    output reg  [42:0]  rco,         // request chain {tag 7, sec 30, pc 5, v}
    input  wire [267:0] pci,         // response chain {d 256, tag 7, own 4, v}
    output reg          hr_v,
    output reg  [2:0]   hr_slot,
    output reg  [2:0]   hr_tag,
    output reg  [3:0]   hr_idx,
    output reg  [255:0] hr_d,
    output reg          fault
);
    reg [30:0] ra [0:5]; reg [2:0] rt [0:5];
    reg [2:0]  nw;                    // rows written (this window)
    reg [2:0]  rr;                    // row being expanded
    reg [3:0]  ai;                    // atom of that row
    reg        run;
    reg [2:0]  slot;
    always @(posedge ck) if (hq_v && nw < 3'd6) begin ra[nw] <= hq_atom; rt[nw] <= hq_tag; end
    always @(posedge ck) if (win_v) slot <= win_slot;
    // row j arrives at t0 + j and is expanded from t0 + 1 + 9 j: always present, no wait, no check needed
    always @(posedge ck or negedge rst_n)
        if (!rst_n) begin nw <= 3'd0; rr <= 3'd0; ai <= 4'd0; run <= 1'b0; rco[0] <= 1'b0; fault <= 1'b0; end
        else begin
            if (hq_v && nw == 3'd6) fault <= 1'b1;                    // a 7th request in a window
            if (!run && nw != 3'd0) begin run <= 1'b1; rr <= 3'd0; ai <= 4'd0; end
            else if (run) begin
                if (ai == 4'd8) begin
                    ai <= 4'd0; rr <= rr + 3'd1;
                    if (rr == 3'd5) run <= 1'b0;
                end else ai <= ai + 4'd1;
            end
            if (run && ai == 4'd8 && rr == 3'd5) nw <= 3'd0;
            else if (hq_v && nw != 3'd6) nw <= nw + 3'd1;
            rco[0] <= run;
        end
    // atom = row base + ai (one 31-b add, registered into the chain word)
    wire [30:0] at = ra[rr] + {27'd0, ai};
    always @(posedge ck) begin
        rco[5:1]   <= at[4:0];
        rco[35:6]  <= PCBASE + {4'd0, at[30:5]};
        rco[42:36] <= {rt[rr], ai};
    end
    // response chain -> lookup
    always @(posedge ck or negedge rst_n)
        if (!rst_n) hr_v <= 1'b0; else hr_v <= pci[0];
    always @(posedge ck) begin hr_slot <= slot; hr_tag <= pci[11:9]; hr_idx <= pci[8:5]; hr_d <= pci[267:12]; end
endmodule

// ---------------------------------------------------------------------------------------------------------------------
// dsdv_eng_tap_c: one controller's tap, inline on the dsdv_idx_rg3 -> dsfd_ctrl_rg3 reader link of that controller
// (both PCs: rrq 2 x 46 b / rrd 2 x 272 b, dsfd_ctrl_rg3 header) and a node of the two Engram chains.
//   request chain (east -> west): rci {tag 7, sec 30, pc 5, v} registered and forwarded (rco); a word with pc[4:1] = sid
//     is injected on lane pc[0] as {tag10, len 1, sec, sl 1, v 1}, tag10 = {g 0, slot3 = atom[2:0], cell = col + 1,
//     sc 1, s3 = atom[3]}.
//   window: the lane's sl = reader sl | (Engram requests not yet popped on that lane) | inject, so the controller moves
//     the landed Engram request in a reader slot; the svc calendar keeps the Engram window free (as a reader window).
//   pops: an owner FIFO a lane (1 bit a request leaving on the lane, in lane order = the controller's landing order)
//     sends each pop to the reader or absorbs it.  Response beats with the Engram code never reach the reader.
//   occupancy: the controller's RFD landing FIFO is shared; an Engram request with lane occupancy >= RFD is a fault.
//   response chain (west -> east): pci {d 256, tag 7, own 4, v}; this tap injects one held beat when the passing slot is
//     empty and own == sid (west end: generates own = 0..15 cyclically and starts the chain).
// Edges: lane +1 each way (one register on the link, in front of the controller's own pin flops); chains 1 a tap
// (+ the die's relay stations between the 531-um controller slots).
// Faults (st, sticky): reader word and Engram word on one lane edge; Engram request at occupancy >= RFD; owner FIFO
// overflow / pop with empty FIFO; Engram hold ring overflow; an Engram code response with no Engram request out.
// ---------------------------------------------------------------------------------------------------------------------
// SAFE successor (TOK-FUNC2-ENG_TAP 10-21, safe checklist 3/8): the same tap, cycle for cycle, built from kept-hierarchy
// leaves so that NO native driver exceeds 32 loads (mapped native census) and every reset leaf has <= 32 sinks:
//   * the 2 x 6 x 263-b hold rings are 12 bit slices (dsdv_eng_tap_hs, 22 b a slice); each slice keeps its own copies
//     of the ring pointers / occupancy, its own Engram decode, own slot / take decode and its share of the pco mux
//     (write enable 22 loads, read select 24, take select 22);
//   * the 44-b request data mux of a lane is 2 x 22-b kept leaves (dsdv_eng_tap_rqd) with their own hit decode;
//   * the 32-entry owner FIFO of a lane is 4 x 8-entry kept banks (dsdv_eng_tap_ofb) with their own write-pointer copy;
//   * lane request control (dsdv_eng_tap_rqc) and response control (dsdv_eng_tap_rsc) are kept leaves;
//   * reset: ot_rst_relay_bounded32 (same 3-edge release as SYNC2 / TREE1), 30 leaves of <= 25 sinks;
//   * the strap sid is registered in every leaf (port sid -> <= 27 flop D pins).
// occ (== on_ by construction: both + out - pop from 0) is folded into on_.  Same ports, same edges, same faults.
(* keep_hierarchy = 1 *) module dsdv_eng_tap_slot (
    input wire pv_in, input wire [3:0] own, input wire [3:0] sq, output wire myslot
);
    assign myslot = !pv_in && own == sq;
endmodule

(* keep_hierarchy = 1 *) module dsdv_eng_tap_take (
    input wire myslot, input wire nz0, input wire nz1, output wire [1:0] take
);
    assign take = {myslot && nz1 && !nz0, myslot && nz0};
endmodule

(* keep_hierarchy = 1 *) module dsdv_eng_tap_we (
    input wire eng, input wire [5:0] hw, output wire [5:0] we
);
    assign we = {6{eng}} & hw;
endmodule

(* keep_hierarchy = 1 *) module dsdv_eng_tap_hit #(parameter integer P = 0) (
    input wire [5:0] rci, input wire [3:0] sq, output wire hit
);
    assign hit = rci[0] && rci[5:2] == sq && (P == 1 ? rci[1] : !rci[1]);
endmodule

(* keep_hierarchy = 1 *) module dsdv_eng_tap_eng #(parameter integer MUT = 0) (
    input wire bv, input wire [9:0] bt, output wire eng
);
    assign eng = (MUT == 1) ? (bv && !bt[9] && bt[5:2] != 4'd0) : (bv && !bt[9] && bt[1] && bt[5:2] != 4'd0);
endmodule

// one 22-b bit slice of both lanes' hold rings and of the response-chain payload register
(* keep_hierarchy = 1 *) module dsdv_eng_tap_hs #(parameter integer MUT = 0, parameter integer W = 22) (
    input  wire        ck, input wire rn0, input wire rn1, input wire [3:0] sid,
    input  wire        pv_in, input wire [3:0] own,
    input  wire        bv0, input wire [9:0] bt0, input wire bv1, input wire [9:0] bt1,
    input  wire [W-1:0] hin0, input wire [W-1:0] hin1, input wire [W-1:0] pci_d,
    output reg  [W-1:0] pco_d
);
    localparam integer EH = 6;
    reg [3:0] sq;
    always @(posedge ck) sq <= sid;
    wire myslot, e0, e1;
    wire [1:0] tk_d, tk_c;
    dsdv_eng_tap_slot u_sl (.pv_in(pv_in), .own(own), .sq(sq), .myslot(myslot));
    dsdv_eng_tap_eng #(.MUT(MUT)) u_e0 (.bv(bv0), .bt(bt0), .eng(e0));
    dsdv_eng_tap_eng #(.MUT(MUT)) u_e1 (.bv(bv1), .bt(bt1), .eng(e1));
    reg [EH-1:0] hw0, hr0, hw1, hr1;
    reg [3:0]    hn0, hn1;
    wire nz0 = hn0 != 4'd0, nz1 = hn1 != 4'd0;
    dsdv_eng_tap_take u_td (.myslot(myslot), .nz0(nz0), .nz1(nz1), .take(tk_d));
    dsdv_eng_tap_take u_tc (.myslot(myslot), .nz0(nz0), .nz1(nz1), .take(tk_c));
    always @(posedge ck or negedge rn0)
        if (!rn0) begin hw0 <= EH'(1); hr0 <= EH'(1); hn0 <= 4'd0; end
        else begin
            if (e0) hw0 <= {hw0[EH-2:0], hw0[EH-1]};
            if (tk_c[0]) hr0 <= {hr0[EH-2:0], hr0[EH-1]};
            hn0 <= hn0 + (e0 ? 4'd1 : 4'd0) - (tk_c[0] ? 4'd1 : 4'd0);
        end
    always @(posedge ck or negedge rn1)
        if (!rn1) begin hw1 <= EH'(1); hr1 <= EH'(1); hn1 <= 4'd0; end
        else begin
            if (e1) hw1 <= {hw1[EH-2:0], hw1[EH-1]};
            if (tk_c[1]) hr1 <= {hr1[EH-2:0], hr1[EH-1]};
            hn1 <= hn1 + (e1 ? 4'd1 : 4'd0) - (tk_c[1] ? 4'd1 : 4'd0);
        end
    wire [EH-1:0] we0, we1;
    dsdv_eng_tap_we u_w0 (.eng(e0), .hw(hw0), .we(we0));
    dsdv_eng_tap_we u_w1 (.eng(e1), .hw(hw1), .we(we1));
    reg [W-1:0] he0 [0:EH-1];
    reg [W-1:0] he1 [0:EH-1];
    integer e;
    always @(posedge ck)
        for (e = 0; e < EH; e = e + 1) begin
            if (we0[e]) he0[e] <= hin0;
            if (we1[e]) he1[e] <= hin1;
        end
    reg [W-1:0] hs0, hs1;
    always @* begin
        hs0 = '0; hs1 = '0;
        for (e = 0; e < EH; e = e + 1) begin
            hs0 = hs0 | ({W{hr0[e]}} & he0[e]);
            hs1 = hs1 | ({W{hr1[e]}} & he1[e]);
        end
    end
    always @(posedge ck) pco_d <= tk_d[0] ? hs0 : tk_d[1] ? hs1 : pci_d;
endmodule

// 22 b of a lane's request data register (reader word, or the injected Engram word on a hit)
(* keep_hierarchy = 1 *) module dsdv_eng_tap_rqd #(parameter integer P = 0, parameter integer W = 22) (
    input wire ck, input wire [3:0] sid, input wire [5:0] rci,
    input wire [W-1:0] ew_d, input wire [W-1:0] rq_d, output reg [W-1:0] rqo_d
);
    reg [3:0] sq;
    always @(posedge ck) sq <= sid;
    wire hit;
    dsdv_eng_tap_hit #(.P(P)) u_h (.rci(rci), .sq(sq), .hit(hit));
    always @(posedge ck) rqo_d <= hit ? ew_d : rq_d;
endmodule

// one 8-entry bank (entries 8 B .. 8 B + 7) of a lane's 32-entry owner FIFO, with its own write-pointer copy
(* keep_hierarchy = 1 *) module dsdv_eng_tap_ofb #(parameter integer P = 0, parameter integer B = 0) (
    input wire ck, input wire rn, input wire [3:0] sid, input wire [5:0] rci, input wire rv,
    input wire [2:0] orp_lo, input wire popv, output wire rd
);
    reg [3:0] sq;
    always @(posedge ck) sq <= sid;
    wire hit;
    dsdv_eng_tap_hit #(.P(P)) u_h (.rci(rci), .sq(sq), .hit(hit));
    wire out_v = hit | rv;
    reg [4:0] owp;
    reg [7:0] ofi;
    always @(posedge ck or negedge rn) if (!rn) owp <= 5'd0; else if (out_v) owp <= owp + 5'd1;
    always @(posedge ck) if (out_v && owp[4:3] == 2'(B)) ofi[owp[2:0]] <= hit;
`ifdef OT_S81ENG_TAP_N32R2
    reg [2:0] rp;
    always @(posedge ck or negedge rn) if (!rn) rp <= 3'd0; else if (popv) rp <= rp + 3'd1;
    assign rd = ofi[rp];
`else
    assign rd = ofi[orp_lo];
`endif
endmodule

// a lane's request control: Engram-outstanding count, lane occupancy, owner FIFO read pointer, pops, request faults
(* keep_hierarchy = 1 *) module dsdv_eng_tap_rqc #(parameter integer P = 0, parameter integer RFD = 24,
                                                  parameter integer MUT = 0) (
    input  wire ck, input wire rn, input wire [3:0] sid, input wire [5:0] rci,
    input  wire rv, input wire rsl, input wire pop, input wire [3:0] bank_rd,
    output reg  rqo_v, output reg rqo_sl, output reg rro_pop, output wire [4:0] orp_o, output wire popv_o, output reg fl
);
    localparam integer OQ = 32;
    reg [3:0] sq;
    always @(posedge ck) sq <= sid;
    wire hit;
    dsdv_eng_tap_hit #(.P(P)) u_h (.rci(rci), .sq(sq), .hit(hit));
    wire out_v = hit | rv;
    reg [5:0] eo, on_;
    reg [4:0] orp;
    assign orp_o = orp;
    wire nz    = on_ != 6'd0;
    wire popv  = pop && nz;
    assign popv_o = popv;
    wire ofr   = bank_rd[orp[4:3]];
    wire pop_e = popv && ofr;
    wire pop_r = (MUT == 2) ? pop : (pop && !(nz && ofr));
    always @(posedge ck or negedge rn)
        if (!rn) begin rqo_v <= 1'b0; rqo_sl <= 1'b0; rro_pop <= 1'b0; eo <= '0; on_ <= '0; orp <= '0; fl <= 1'b0; end
        else begin
            rqo_v   <= out_v;
            rqo_sl  <= rsl | hit | (eo != 6'd0);
            rro_pop <= pop_r;
            eo  <= eo + (hit ? 6'd1 : 6'd0) - (pop_e ? 6'd1 : 6'd0);
            if (popv) orp <= orp + 5'd1;
            on_ <= on_ + (out_v ? 6'd1 : 6'd0) - (popv ? 6'd1 : 6'd0);
            if ((hit && rv) || (hit && on_ >= 6'(RFD)) || (out_v && on_ == 6'(OQ)) || (pop && on_ == 6'd0)) fl <= 1'b1;
        end
endmodule

// response control of both lanes: reader-valid demux, held-beat counts (fault copy), expected responses, chain valid
(* keep_hierarchy = 1 *) module dsdv_eng_tap_rsc #(parameter integer MUT = 0) (
    input  wire ck, input wire rn, input wire [3:0] sid, input wire [5:0] rci,
    input  wire pv_in, input wire [3:0] own,
    input  wire bv0, input wire [9:0] bt0, input wire bv1, input wire [9:0] bt1,
    output reg  rro_v0, output reg rro_v1, output reg pco_v, output reg [1:0] fxl
);
    localparam integer EH = 6;
    reg [3:0] sq;
    always @(posedge ck) sq <= sid;
    wire h0, h1, e0, e1, myslot;
    wire [1:0] tk;
    dsdv_eng_tap_hit #(.P(0)) u_h0 (.rci(rci), .sq(sq), .hit(h0));
    dsdv_eng_tap_hit #(.P(1)) u_h1 (.rci(rci), .sq(sq), .hit(h1));
    dsdv_eng_tap_eng #(.MUT(MUT)) u_e0 (.bv(bv0), .bt(bt0), .eng(e0));
    dsdv_eng_tap_eng #(.MUT(MUT)) u_e1 (.bv(bv1), .bt(bt1), .eng(e1));
    dsdv_eng_tap_slot u_sl (.pv_in(pv_in), .own(own), .sq(sq), .myslot(myslot));
    reg [3:0] hn0, hn1;
    reg [5:0] er0, er1;
    dsdv_eng_tap_take u_t (.myslot(myslot), .nz0(hn0 != 4'd0), .nz1(hn1 != 4'd0), .take(tk));
    always @(posedge ck or negedge rn)
        if (!rn) begin rro_v0 <= 1'b0; rro_v1 <= 1'b0; pco_v <= 1'b0; fxl <= 2'b0; hn0 <= '0; hn1 <= '0; er0 <= '0; er1 <= '0; end
        else begin
            rro_v0 <= bv0 && !e0;
            rro_v1 <= bv1 && !e1;
            pco_v  <= pv_in | (|tk);
            hn0 <= hn0 + (e0 ? 4'd1 : 4'd0) - (tk[0] ? 4'd1 : 4'd0);
            hn1 <= hn1 + (e1 ? 4'd1 : 4'd0) - (tk[1] ? 4'd1 : 4'd0);
            er0 <= er0 + (h0 ? 6'd1 : 6'd0) - (e0 ? 6'd1 : 6'd0);
            er1 <= er1 + (h1 ? 6'd1 : 6'd0) - (e1 ? 6'd1 : 6'd0);
            if ((e0 && hn0 == 4'(EH)) || (e0 && er0 == 6'd0)) fxl[0] <= 1'b1;
            if ((e1 && hn1 == 4'(EH)) || (e1 && er1 == 6'd0)) fxl[1] <= 1'b1;
        end
endmodule

