        .cfg_layer(ly), .cfg_rank(rk), .f_ks(f_ks), .rco(rco), .pci(pci), .vi_s(vi_s), .vo_s(vo_s), .vi_n(vi_n), .vo_n(vo_n),
        .st(st));
endmodule
