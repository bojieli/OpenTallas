#!/usr/bin/env python3
"""BINDER4-S81 10-23: S81 as-built die netlist for tools/die_plan/bind.py (plan v4.6, claude/s81-p9-1023).

Input : the cap30 gen-main strict-bound die top (tools/s81_dv/dv_bind.py, module dv_die, sha256 64d4be88...,
        die_port_bind PASS 42,351 instances; receipt scratch/s81c_die/cap30/cap30_main_receipt.tar.gz bind/bind/die.v).
Output: OUT/die_asb.v + OUT/s81_asb_models.sv, two mechanical, recorded rewrites:
  (1) FRAMES: every u_f_* (col_h9_l4_lp / col_h10_l4_lp, the rf3r landed frame) is re-instantiated as the S81-P7/P9
      plan band composition col_<M>_l4_lp_asb_<x|nx>: u_r0 (col_<M>_l4_lp_r0, or _r0_nx at plan positions p3/p6),
      u_r1, u_r2 (rtl/dsrom_sys/s81_dv/frame_lp/plan/col_<M>_l4_lp_plan_kit.sv = the plan type sources) joined by
      s81b_fint seam transports (2 register stages = the plan wrapper's src + dst boundary flops, frame_band_plan.py
      x_boundary_flops 2; removed by the binder, which re-emits its own boundary flop pair).  The plan's LK parameter
      ({4{3'd2}} on every r0 type) replaces the as-built per-frame lk strap port (12'h492/b6d/924); xk/xok (forwarded x
      clocks) are not plan ports (xk = clk, frame_band_plan.py), so they are dropped.  xo of p1/p4 (plan x forward
      p1 -> p2 -> p3, p4 -> p5 -> p6) is a new output, rewired by bind/plan_rewires_s81.json.
  (2) CLOCKS/RESET: the 482 regional clock roots ck_* and rst_n stop being die ports: one as-built source cell
      u_ckrst (s81b_ckrst, asbuilt.sources: clock core / reset low) drives them, so every partition loads the plan die
      clock (one domain, clock.source @die clk) and the plan reset spine.
"""
import json
import re
import sys
from pathlib import Path

FINT = """// s81b_fint: frame band seam (r_i -> r_j) of the S81-P7 plan wrapper = src + dst boundary flop (2 stages).
module s81b_fint #(parameter integer W = 1) (input wire cka, input wire ckb, input wire [W-1:0] d, output wire [W-1:0] q);
    reg [W-1:0] a, b;
    always @(posedge cka) a <= d;
    always @(posedge ckb) b <= a;
    assign q = b;
endmodule
"""
# frame_int widths per master (plan_kit.sv ports): r0 o0/i0, r1 i1/o1/o0/i0, r2 i0/o0
W = {"h9": dict(r0o0=1167, r0i0=261, r1o0=1167, r2o0=321), "h10": dict(r0o0=1264, r0i0=267, r1o0=1230, r2o0=384)}


def wrapper(m, var):
    w = W[m]
    r0 = f"col_{m}_l4_lp_r0" + ("_nx" if var == "nx" else "")
    xo = "    output wire [1103:0] xo,\n" if var == "x" else ""
    xoc = ", .xo_o0(xo)" if var == "x" else ""
    return f"""// GENERATED by physical/die_plan/s81/bind/asbuilt_s81.py: as-built frame = plan band composition ({var}).
module col_{m}_l4_lp_asb_{var} #(parameter INSTANCE = "col_{m}") (
    input  wire ck_r0, input wire ck_r1, input wire ck_r2, input wire rst_n,
    input  wire [1103:0] x,
{xo}    output wire [69:0] ret
);
    wire [{w['r0o0']-1}:0] r0_o0, r1_i1;
    wire [{w['r0i0']-1}:0] r1_o1, r0_i0;
    wire [{w['r1o0']-1}:0] r1_o0, r2_i0;
    wire [{w['r2o0']-1}:0] r2_o0, r1_i0;
    {r0} #(.INSTANCE(INSTANCE), .LK({{4{{3'd2}}}})) u_r0 (.clk(ck_r0), .rst_n(rst_n), .x_i0(x){xoc}, .ret_o0(ret),
        .frame_int_o0(r0_o0), .frame_int_i0(r0_i0));
    col_{m}_l4_lp_r1 #(.INSTANCE(INSTANCE), .LK({{4{{3'd2}}}})) u_r1 (.clk(ck_r1), .frame_int_i1(r1_i1), .frame_int_o1(r1_o1),
        .frame_int_o0(r1_o0), .frame_int_i0(r1_i0));
    col_{m}_l4_lp_r2 #(.INSTANCE(INSTANCE), .LK({{4{{3'd2}}}})) u_r2 (.clk(ck_r2), .frame_int_i0(r2_i0), .frame_int_o0(r2_o0));
    s81b_fint #(.W({w['r0o0']})) u_s01 (.cka(ck_r0), .ckb(ck_r1), .d(r0_o0), .q(r1_i1));
    s81b_fint #(.W({w['r0i0']})) u_s10 (.cka(ck_r1), .ckb(ck_r0), .d(r1_o1), .q(r0_i0));
    s81b_fint #(.W({w['r1o0']})) u_s12 (.cka(ck_r1), .ckb(ck_r2), .d(r1_o0), .q(r2_i0));
    s81b_fint #(.W({w['r2o0']})) u_s21 (.cka(ck_r2), .ckb(ck_r1), .d(r2_o0), .q(r1_i0));
endmodule
"""


def main():
    die, imap, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    t = die.read_text()
    frames = json.loads(imap.read_text())["frames"]          # plan fW0_p1 -> as-built f_0L01
    pos = {"u_" + v: int(k.split("_p")[1]) for k, v in frames.items()}
    rec = {"frames": {}, "clock_ports": [], "reset_ports": []}

    def fr(mm):
        master, params, inst, body = mm.group(1), mm.group(2) or "", mm.group(3), mm.group(4)
        m = "h9" if master == "col_h9_l4_lp" else "h10"
        var = "nx" if pos[inst] in (3, 6) else "x"
        lk = re.search(r"\.lk\s*\(([^)]*)\)", body).group(1).strip()
        had_xo = bool(re.search(r"\.xo\s*\(", body))
        body2 = re.sub(r"\s*\.(xk|lk|xok)\s*\((?:[^()]|\{[^}]*\})*\)\s*,?", "", body)
        body2 = re.sub(r",\s*$", "", body2.rstrip())
        if var == "nx":
            assert not had_xo, inst
        rec["frames"][inst] = dict(master=master, plan_pos=pos[inst], variant=f"col_{m}_l4_lp_asb_{var}", lk_asbuilt=lk,
                                   xo_asbuilt=had_xo)
        return f"\n    col_{m}_l4_lp_asb_{var} {params} {inst} ({body2});"
    t, n = re.subn(r"\n\s*(col_h9_l4_lp|col_h10_l4_lp)\s*(#\s*\(\s*\.INSTANCE\(\"[^\"]*\"\)\s*\))?\s*(u_f_\w+)\s*\((.*?)\);",
                   fr, t, flags=re.S)
    assert n == 72, n
    # die clock roots + reset -> one source cell
    hs = t.index("module dv_die")
    he = t.index(");", hs)
    ports = [p.strip() for p in t[hs:he].split("(", 1)[1].split(",")]
    cks = [p for p in ports if p.startswith("ck_")]
    keep = [p for p in ports if p not in cks and p != "rst_n"]
    rec["clock_ports"], rec["reset_ports"] = cks, ["rst_n"]
    t = t[:hs] + "module dv_die (" + ", ".join(keep) + t[he:]
    for p in cks + ["rst_n"]:
        t, k = re.subn(r"\n\s*input\s+(wire\s+)?" + re.escape(p) + r"\s*;", f"\n  wire {p};", t)
        assert k == 1, p
    conns = ", ".join(f".{p}({p})" for p in cks + ["rst_n"])
    t = t.replace("\nendmodule", f"\n  s81b_ckrst u_ckrst ({conns});\nendmodule", 1) if t.count("\nendmodule") else t
    (out / "die_asb.v").write_text(t)
    models = [FINT] + [wrapper(m, v) for m in ("h9", "h10") for v in ("x", "nx")]
    models.append("// as-built die clock roots + reset (source cell; asbuilt.sources)\n(* blackbox *)\nmodule s81b_ckrst (" +
                  ", ".join(f"output wire {p}" for p in cks + ["rst_n"]) + ");\nendmodule\n")
    (out / "s81_asb_models.sv").write_text("`timescale 1ns/1ps\n" + "\n".join(models))
    (out / "asb_record.json").write_text(json.dumps(rec, indent=1))
    print(json.dumps(dict(frames=len(rec["frames"]), clock_ports=len(cks)), indent=0))


if __name__ == "__main__":
    main()
