#!/usr/bin/env python3
"""S81 event3 part: kv_leaf__t2 SITE-RULE EXCEPTION + 183 static macro sites (DIE-S81-34/KVT2-SITE, 2026-10-30;
OWNER 12.20a form (ii); base = H2 plan plan_h2_2249.json @ codex/s81-lp-plan-2249 1837506a6).

Fix-only delta on ONE type, ot_s81sl_kv_leaf__t2 (instance s_3N_L0, CURRENT slot 1442.88 x 1226.88; no outline, bus,
ft slot, station count, clock, reset, partition, neighbour or die datum changes):
  * partition_types.ot_s81sl_kv_leaf__t2.macro_under_ft = declared per-type exception to the S81 MACRO site rule
    (DIE-S81-32 place_sites: "no macro inside an ft corridor or landing band +10.8"): SRAM macros may sit under the ten
    ft corridors because every placed master blocks M1-M4 only (LEF OBS M1/M2/M3/M4; all signal + PG pins on M4, signal
    pins at the W/E macro edges outside the M4 OBS, reached from the >= 10.8-um W/E column channels) while the corridors
    run on M5/M7 (ft_slots[].layers, partition_signal_max M7; corridor demand <= 0.33 of M7 alone, <= 0.15 of M5+M7).
    Kept clear (+10.8 halo): ft stations j >= 1 (route point L*j/k per bit, the check.py check_ft_macro_sites /
    face_flops.tcl point; band = bit-point bbox +10.8), station 0 face flops (43.2 edge band), landing bands
    (clock.landing_contract.bands), clock tap / landing pins / collector relays (+21.6).  Other types: rule unchanged.
  * contents[] += 183 macro rows in the DIE-S81-32 form (inst = flattened kit instance under u_bound, module, lef, TT lib,
    origin_um incl. per-master track offset, outline_um, orient R0, obs_max M4, status new) + core_pg_connect: true.

Sites: delta_kvt2site_1030.json (generated by kvt2site_1030/kvt2site.py, bus-first mixed-column packer, the packer's own
check() = kit_contract.macro_channels rules + exception keepouts: 0 problems).  The LEF facts are re-proved here at run
time.  Every edit asserts the exact old form; a second run refuses.   usage: python3 delta_kvt2site_1030.py
"""
import hashlib
import json
import re
from pathlib import Path

S81 = Path(__file__).resolve().parent
ROOT = S81.parents[2]
PLAN = S81 / "plan_h2_2249.json"
EV = S81 / "delta_kvt2site_1030.json"
TN = "ot_s81sl_kv_leaf__t2"
BASE_SHA = "9c36231151c91ee97f14bff1c1f6ebe919752f61b7bd074b89a2665831ed0b06"
TAG = "DIE-S81-34/KVT2-SITE 10-30 static macro site under the macro_under_ft exception (delta_kvt2site_1030.py)"
HALO = 10.8


def compact(o):
    return json.dumps(o, separators=(",", ":"))


def lef_proof(lef):
    txt = (ROOT / lef).read_text()
    W, H = map(float, re.search(r"SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", txt).groups())
    obs = re.findall(r"^\s*OBS(.*?)^\s*END\s*$", txt, re.M | re.S)
    assert len(obs) == 1, (lef, "expected one OBS block")
    olay = {}
    lay = None
    for m in re.finditer(r"LAYER\s+(\S+)|RECT\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)", obs[0]):
        if m.group(1):
            lay = m.group(1)
        else:
            olay.setdefault(lay, []).append(tuple(map(float, m.groups()[1:])))
    assert set(olay) <= {"M1", "M2", "M3", "M4"}, (lef, "OBS above M4", sorted(olay))
    for pm in re.finditer(r"^\s*PIN\s+(\S+)(.*?)^\s*END\s+\1\b", txt, re.M | re.S):
        pg = re.search(r"USE\s+(POWER|GROUND)", pm.group(2))
        lay = None
        for m in re.finditer(r"LAYER\s+(\S+)\s*;|RECT\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)", pm.group(2)):
            if m.group(1):
                lay = m.group(1)
                assert lay == "M4", (lef, pm.group(1), "pin layer", lay)
            elif not pg:
                x0, _, x1, _ = map(float, m.groups()[1:])
                assert any(x0 < r[0] - 1e-6 or x1 > r[2] + 1e-6 for r in olay["M4"]), \
                    (lef, pm.group(1), "signal pin fully inside the M4 OBS (no W/E edge access)")
    return W, H


def main():
    raw = PLAN.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == BASE_SHA, "plan_h2_2249.json is not the H2 base (second run?)"
    txt = raw.decode()
    plan = json.loads(txt)
    ev = json.loads(EV.read_text())
    t = plan["partition_types"][TN]
    assert t["contents"] == ev["old_contents"], "contents not in the expected old form"
    assert "core_pg_connect" not in t and "macro_under_ft" not in t, "exception already applied (second run?)"
    assert not t.get("hard_cores"), "type has hard_cores"
    assert t["outline_um"] == [1442.88, 1226.88], "outline changed"
    assert [p for p in plan["partitions"] if p["type"] == TN] == [
        {"name": "s_3N_L0", "type": TN, "origin_um": [14532.48, 16053.12], "orient": "R0"}], "slot changed"
    assert plan["die"]["layer_budget"]["partition_signal_max"] == "M7"
    exc = ev["exception"]
    names = {s["name"] for s in t["ft_slots"]}
    assert set(exc["slots"]) == names and len(names) == 10
    for s in t["ft_slots"]:
        assert set(s["layers"]) <= set(exc["corridor_layers"]), (s["name"], s["layers"])
        assert s["in_face"] + s["out_face"] in ("NS", "SN"), s["name"]
    # LEF proof (re-run): every master blocks M1-M4 only; pins on M4, signal pins reachable at the W/E edges
    sizes = {}
    for s in ev["sites"]:
        if s["lef"] not in sizes:
            sizes[s["lef"]] = lef_proof(s["lef"])
        assert tuple(s["outline_um"]) == sizes[s["lef"]], (s["inst"], "outline != LEF SIZE")
    assert len(ev["sites"]) == 183 and len({s["inst"] for s in ev["sites"]}) == 183
    W, H = t["outline_um"]
    bands = [b["rect_um"] for b in exc["station_bands"]]
    lb = [b["rect_um"] for b in t["clock"]["landing_contract"]["bands"].values()]
    boxes = []
    for s in ev["sites"]:
        x, y = s["origin_um"]; w, h = s["outline_um"]
        b = (x, y, x + w, y + h)
        assert 43.2 - 0.6 <= x and 43.2 - 0.6 <= y and x + w <= W - 43.2 + 0.6 and y + h <= H - 43.2 + 0.6, (s["inst"], "edge band")
        for r in bands + lb:
            assert not (b[0] < r[2] + HALO and r[0] - HALO < b[2] and b[1] < r[3] + HALO and r[1] - HALO < b[3]), \
                (s["inst"], "station / landing band +10.8", r)
        boxes.append(b)
    for i in range(len(boxes)):
        for j in range(i):
            a, c = boxes[i], boxes[j]
            assert not (a[0] < c[2] + HALO - 0.6 and c[0] < a[2] + HALO - 0.6 and a[1] < c[3] + HALO - 0.6 and c[1] < a[3] + HALO - 0.6), \
                (ev["sites"][i]["inst"], ev["sites"][j]["inst"], "macro spacing")
    # text edit of the unique type block
    head = f'\n  "{TN}": {{\n'
    assert txt.count(head) == 1
    a = txt.index(head)
    b = txt.index('\n  },\n', a)
    block = txt[a:b]
    old = '   "contents": [\n' + "".join(f"    {compact(c)}{',' if i < len(ev['old_contents']) - 1 else ''}\n"
                                          for i, c in enumerate(ev["old_contents"])) + '   ],\n'
    assert block.count(old) == 1, "old contents text form not found exactly once"
    rows = list(ev["old_contents"]) + [dict(inst=s["inst"], module=s["module"], status="new", lef=s["lef"], lib=s["lib"],
                                            origin_um=s["origin_um"], outline_um=s["outline_um"], orient="R0",
                                            obs_max="M4", note=TAG) for s in ev["sites"]]
    new = '   "contents": [\n' + "".join(f"    {compact(c)}{',' if i < len(rows) - 1 else ''}\n"
                                        for i, c in enumerate(rows)) + '   ],\n'
    hard_old = '   "hard": false,\n'
    assert block.count(hard_old) == 1
    nb = block.replace(old, new).replace(hard_old, hard_old + '   "core_pg_connect": true,\n'
                                         + '   "macro_under_ft": ' + compact(exc) + ',\n')
    txt = txt[:a] + nb + txt[b:]
    after = json.loads(txt)
    ta = after["partition_types"][TN]
    assert len(ta["contents"]) == 1 + 183 and ta["core_pg_connect"] is True and ta["macro_under_ft"] == exc
    for k in plan["partition_types"]:
        if k != TN:
            assert after["partition_types"][k] == plan["partition_types"][k]
    assert {k: v for k, v in after.items() if k != "partition_types"} == {k: v for k, v in plan.items() if k != "partition_types"}
    PLAN.write_text(txt)
    print(f"{TN}: +183 macro sites, core_pg_connect true, macro_under_ft exception; "
          f"plan sha256 {hashlib.sha256(txt.encode()).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
