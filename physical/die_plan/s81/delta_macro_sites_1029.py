#!/usr/bin/env python3
"""S81 macro-site event MACRO (DIE-S81-32/MACRO, 2026-10-29; COORD ruling 20:2x part (1) on the S81-KITS-A ASK 19:31).

Fix-only delta on frozen plan_s13r2: the core-free S81 types whose bound RTL reaches SRAM macros that the plan did not
place (synth stopped ORD-2013 'LEF master ... not found') get STATIC MACRO SITES as contents[] rows (KV kv3_sys_c form:
inst = flattened kit instance path under u_bound, module = master, lef + TT lib, origin_um, outline_um, orient R0,
obs_max M4, status new) plus core_pg_connect: true (PG-CORECONN-2: the kit PDN lands the macro PG pins).  No outline,
bus, ft slot, clock, reset, partition, neighbour or die datum changes.

Sites (delta_macro_sites_1029.json, generated by the lane's place_sites.py, record in
results/die_s81_32_1029/macro/RECORD.txt): 8.64-um lattice + per-master track offset (every signal pin on a plan
M2-M7 track), macro columns that never x-overlap with >= 10.8-um channels and every stack gap >= 10.8 um
(kit_contract MIN_CHANNEL_UM), clear of the ft corridors (+10.8), landing bands (+10.8), clock tap / landing pins /
reset relays (+21.6) and a 43.2-um edge band.  Instance list per type = yosys elaboration (hierarchy+flatten) of the
S81-KITS-A bind7 kit RTL with the as-built defines.

Every edit asserts the exact old contents form of each type; a second run refuses.  usage: python3 delta_macro_sites_1029.py
"""
import json
from pathlib import Path

S81 = Path(__file__).resolve().parent
PLAN = S81 / "plan_s13r2.json"
SITES = S81 / "delta_macro_sites_1029.json"
TAG = "DIE-S81-32/MACRO 10-29 static macro site (delta_macro_sites_1029.py)"


def compact(o):
    return json.dumps(o, separators=(",", ":"))


def main():
    txt = PLAN.read_text()
    plan = json.loads(txt)
    ev = json.loads(SITES.read_text())
    n_tot = 0
    for tn, e in ev["types"].items():
        t = plan["partition_types"][tn]
        assert t["contents"] == e["old_contents"], (tn, "contents not in the expected old form (second run?)")
        assert "core_pg_connect" not in t, (tn, "core_pg_connect already set (second run?)")
        assert not t.get("hard_cores"), (tn, "type has hard_cores; event form is for core-free types")
        W, H = t["outline_um"]
        for s in e["sites"]:
            x, y = s["origin_um"]
            w, h = s["outline_um"]
            assert 0 < x and 0 < y and x + w < W and y + h < H, (tn, s["inst"], "outside the outline")
        # the type block: unique "<tn>": { ... "contents": [ <old rows> ], ... }
        head = f'\n  "{tn}": {{\n'
        assert txt.count(head) == 1, (tn, "type block not unique")
        a = txt.index(head)
        b = txt.index('\n  },\n', a) if txt.find('\n  },\n', a) != -1 else len(txt)
        block = txt[a:b]
        old_rows = "".join(f"    {compact(c)}{',' if i < len(e['old_contents']) - 1 else ''}\n"
                           for i, c in enumerate(e["old_contents"]))
        old = '   "contents": [\n' + old_rows + '   ],\n'
        assert block.count(old) == 1, (tn, "old contents text form not found exactly once")
        rows = list(e["old_contents"]) + [dict(inst=s["inst"], module=s["module"], status="new", lef=s["lef"], lib=s["lib"],
                                              origin_um=s["origin_um"], outline_um=s["outline_um"], orient="R0",
                                              obs_max="M4", note=TAG) for s in e["sites"]]
        new = '   "contents": [\n' + "".join(f"    {compact(c)}{',' if i < len(rows) - 1 else ''}\n"
                                              for i, c in enumerate(rows)) + '   ],\n'
        hard_old = '   "hard": false,\n'
        assert block.count(hard_old) == 1, (tn, "hard: false line")
        nb = block.replace(old, new).replace(hard_old, hard_old + '   "core_pg_connect": true,\n')
        txt = txt[:a] + nb + txt[b:]
        n_tot += len(e["sites"])
        print(f"{tn}: +{len(e['sites'])} macro sites, core_pg_connect true")
    after = json.loads(txt)
    for tn, e in ev["types"].items():
        assert len(after["partition_types"][tn]["contents"]) == len(e["old_contents"]) + len(e["sites"])
    PLAN.write_text(txt)
    print(f"plan_s13r2.json: {len(ev['types'])} types, {n_tot} macro sites")


if __name__ == "__main__":
    main()
