#!/usr/bin/env python3
"""CORE-S81-ENG (10-23): ORFS kit for ONE planned hard core of the S81 eng__t1 split (dsdv_eng_rr -> LK + XQ).
Adapted from CORE-HBM physical/die_plan/hbm/cores/harden/gen_core_kit.py (claude/core-hbm-1023) for S81:
  * cores, outlines, macro sites, pins_file and RTL recipe come from cores_eng.json (this directory), not from
    plan hard_cores[] (the S81 plan v4.7b has no eng hard cores yet: S81-P9 adopts cores_eng.json);
  * S81 core track offset [0.108, 0.012] (gen_plan_v4.CORE_TRACK_OFFSET): with core origins on the 8.64 die lattice
    the die M4/M5 tracks (0.024 + k 0.048) land on core-frame 0.012 + k 0.048 = the ASAP7 PLATFORM tracks, so the kit
    keeps the platform make_tracks and every M4/M5 pin is checked on 0.012 + k 0.048;
  * S81 clock: period 833 ps (die period_ps), IO clock at the plan common latency 250 ps (clock.common_latency_ps);
  * SRAM / ROM views from physical/asap7_memory_macros or _v2 (TT lib), explicit sites (place_macro -exact).
    python3 gen_core_kit.py --cores cores_eng.json --core lk|xq --out kits [--repo REPO] [--tool PT4/tools/die_plan]
"""
import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
CORE_MARGIN_UM = 4.32
PIN_LEN_UM = 0.192
LAYER_W = dict(M2=0.018, M3=0.018, M4=0.024, M5=0.024, M6=0.032, M7=0.032)
IO_BUDGET = 0.2
UNC_SETUP_PS, UNC_HOLD_PS, UNC_SPLIT, IO_LOAD_FF = 60.0, 25.0, 0.5, 2.0
CLK_RE = r"^(ck|clk)$"
RST_RE = r"^(rst_n)$"
PERIOD_PS, COMMON_LATENCY_PS = 833.0, 250.0

PDN = """# GENERATED by gen_core_kit.py: core PDN (follow-pins + M5 stripes = core PG pins on the partition M5 grid).
add_global_connection -net {VDD} -inst_pattern {.*} -pin_pattern {^VDD$} -power
add_global_connection -net {VSS} -inst_pattern {.*} -pin_pattern {^VSS$} -ground
global_connect
set_voltage_domain -name {CORE} -power {VDD} -ground {VSS}
define_pdn_grid -name {top} -voltage_domains {CORE} -pins {M5}
add_pdn_stripe -grid {top} -layer {M1} -width {0.018} -pitch {0.54} -offset {0} -followpins
add_pdn_stripe -grid {top} -layer {M2} -width {0.018} -pitch {0.54} -offset {0} -followpins
add_pdn_stripe -grid {top} -layer {M5} -width {0.12} -spacing {0.072} -pitch {4.32} -offset {2.064}
add_pdn_connect -grid {top} -layers {M1 M2}
add_pdn_connect -grid {top} -layers {M2 M5}
"""
PDN_MACRO = """define_pdn_grid -macro -default -name {macro} -voltage_domains {CORE} -halo {2.0 2.0} -grid_over_boundary
add_pdn_connect -grid {macro} -layers {M4 M5}
"""


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def face_of(x, y, w, h):
    return min([(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")])[1]


def io_tcl(pins, w, h, name):
    out = [f"# GENERATED by gen_core_kit.py: exact plan pins of core {name} ({len(pins)} pins, core frame um)."]
    rows = []
    for p in pins:
        f = face_of(p["x"], p["y"], w, h)
        lw = LAYER_W.get(p["layer"], 0.04)
        x, y = p["x"], p["y"]
        if f in "EW":
            x = w if f == "E" else 0.0
            size, cx, cy = (PIN_LEN_UM, lw), (x - PIN_LEN_UM / 2 if f == "E" else x + PIN_LEN_UM / 2), y
        else:
            y = h if f == "N" else 0.0
            size, cx, cy = (lw, PIN_LEN_UM), x, (y - PIN_LEN_UM / 2 if f == "N" else y + PIN_LEN_UM / 2)
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{cx:.4f} {cy:.4f}}} "
                   f"-pin_size {{{size[0]:.4f} {size[1]:.4f}}}")
        m = re.match(r"^(.*)\[(\d+)\]$", p["name"])
        rows.append(dict(bus=m.group(1) if m else p["name"], bit=int(m.group(2)) if m else None, layer=p["layer"],
                         x=round(x, 4), y=round(y, 4), face=f))
    return "\n".join(out) + "\n", rows


def sdc(clks, rsts, name, half=()):
    per, ins, io = PERIOD_PS, COMMON_LATENCY_PS, IO_BUDGET * PERIOD_PS
    s = (f"# GENERATED by gen_core_kit.py: S81 core {name}; ps / fF (ASAP7 liberty units).\n"
         f"create_clock -name clk -period {per:.4f} [get_ports {{{' '.join(clks)}}}]\n"
         f"# the partition logic around the core runs on the plan common latency ({ins:g} ps): virtual IO clock\n"
         f"create_clock -name vclk -period {per:.4f}\n"
         f"set_clock_latency -source {ins:.4f} [get_clocks vclk]\n"
         f"set_clock_uncertainty {UNC_SETUP_PS:.4f} -setup [all_clocks]\n"
         f"set_clock_uncertainty {UNC_HOLD_PS:.4f} -hold [all_clocks]\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -setup {UNC_SPLIT * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -setup {(1 - UNC_SPLIT) * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -hold {UNC_SPLIT * UNC_HOLD_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -hold {(1 - UNC_SPLIT) * UNC_HOLD_PS:.4f}\n"
         f"set non_clk_in [lsearch -inline -all -not -regexp [all_inputs] {{^({'|'.join(clks)})$}}]\n"
         f"set_input_delay {io:.4f} -clock vclk $non_clk_in\n"
         f"set_output_delay {io:.4f} -clock vclk [all_outputs]\n"
         f"set_input_delay -min 0.0000 -clock vclk $non_clk_in\n")
    if rsts:   # OWNER DECISION 13 (reset wavefront, claude/reset-1024 @0a08a66af): the core reset is a SYNCHRONOUS
        # registered input from the partition's reset relay tree, budgeted like any data pin (no async model, no waiver)
        s += f"# reset {' '.join(rsts)}: wavefront relay -> registered synchronous input, data IO budget ({io:.4f})\n"
    for b in half:
        # half-cycle crossing input (launched on the partner core's ck NEGEDGE, as in the monolith): arrival T/2 + the
        # partner's clk->q + abutted 17-um drop (0.12 T); hold side unchanged (min 0)
        s += (f"# {b}: half-cycle crossing (partner negedge launch)\n"
              f"set_input_delay {0.5 * per + 0.12 * per:.4f} -clock vclk [get_ports {{{b}[*]}}]\n")
    return s + (f"set_load {IO_LOAD_FF:g} [all_outputs]\n"
                "set_driving_cell -lib_cell BUFx4_ASAP7_75t_R -pin Y $non_clk_in\n")


def kit_hash(kd):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(kd).rglob("*") if p.is_file() and "run" not in p.relative_to(kd).parts[:1]
                    and p.name != "freeze.json" and not p.name.startswith("run_")):
        h.update(str(f.relative_to(kd)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:16]


def macro_dir(repo, master):
    for d in ("asap7_memory_macros_v2", "asap7_memory_macros"):
        p = repo / "physical" / d / master
        if (p / f"{master}.lef").is_file():
            return p
    raise SystemExit(f"no view for {master}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cores", default=str(HERE / "cores_eng.json"))
    ap.add_argument("--core", required=True)
    ap.add_argument("--out", default=str(HERE / "kits"))
    ap.add_argument("--repo", default=str(HERE.parents[4]))
    ap.add_argument("--tool", default="/home/ubuntu/scratch/core-s81-1023/pt4/tools/die_plan")
    a = ap.parse_args()
    repo, tool = Path(a.repo), Path(a.tool)
    cj = json.load(open(a.cores))
    c = next(x for x in cj["cores"] if x["name"] == a.core)
    w, h = c["outline_um"]
    rec = c["recipe"]
    pins = json.load(open(repo / "physical/die_plan/s81" / c["pins_file"]))["pins"]
    kd = Path(a.out) / f"{c['module']}__{w:g}x{h:g}"
    if kd.exists():
        shutil.rmtree(kd)
    (kd / "rtl").mkdir(parents=True)
    srcs = []
    for f in rec["files"]:
        dst = kd / "rtl" / Path(f).name
        if dst.exists() and dst.read_bytes() != (repo / f).read_bytes():
            raise SystemExit(f"rtl name clash {dst.name}")
        shutil.copyfile(repo / f, dst)
        srcs.append(f"/work/rtl/{dst.name}")
    lefs, libs, masters = [], [], sorted({m["master"] for m in c["macros"]})
    for m in masters:
        md = macro_dir(repo, m)
        (kd / "macros").mkdir(exist_ok=True)
        for ext, lst in ((".lef", lefs), ("_tt.lib", libs)):
            shutil.copyfile(md / f"{m}{ext}", kd / "macros" / f"{m}{ext}")
            lst.append(f"/work/macros/{m}{ext}")
    off = [q["name"] for q in pins if q["layer"] in ("M4", "M5") and
           abs(((q["x"] if q["layer"] == "M5" else q["y"]) - 0.012) / 0.048 -
               round(((q["x"] if q["layer"] == "M5" else q["y"]) - 0.012) / 0.048)) > 1e-3]
    if off:
        raise SystemExit(f"{a.core}: {len(off)} M4/M5 pins off the core-frame track lattice 0.012 + k 0.048: {off[:3]}")
    io, prow = io_tcl(pins, w, h, c["module"])
    (kd / "io.tcl").write_text(io)
    (kd / "pins.json").write_text(json.dumps(prow) + "\n")
    names = [p["name"] for p in pins]
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    clks = [n for n in names if re.match(CLK_RE, base(n))]
    rsts = [n for n in names if re.match(RST_RE, base(n))]
    (kd / "constraint.sdc").write_text(sdc(clks, rsts, c["module"], rec.get("half_cycle_inputs", [])))
    (kd / "pdn.tcl").write_text(PDN + (PDN_MACRO if c["macros"] else ""))
    skip = "^(" + "|".join(re.escape(n) for n in clks + rsts) + ")$"
    ff = (tool / "face_flops.tcl").read_text()
    ff = ff.replace("set ff_skip_re {^(clk(_t[0-9]+)?|arst_n)$}", "set ff_skip_re {" + skip + "}")
    assert ("set ff_skip_re {" + skip + "}") in ff, "face_flops.tcl skip regex anchor changed"
    ff = ff.replace("set ff_out [open $::env(RESULTS_DIR)/ot_face_flops.txt w]",
                    "set ff_out [open $::env(RESULTS_DIR)/ot_face_flops.txt w]\n"
                    "set ff_unreg [open $::env(RESULTS_DIR)/ot_unreg_pins.txt w]")
    ff = ff.replace("    if {$f eq \"\"} { incr ff_miss; continue }",
                    "    if {$f eq \"\"} { incr ff_miss; puts $ff_unreg \"$pass\\t$nm\"; continue }")
    assert "ot_unreg_pins" in ff and "puts $ff_unreg" in ff, "face_flops.tcl miss anchor changed"
    (kd / "face_flops.tcl").write_text(ff)
    shutil.copyfile(tool / "face_flops_release.tcl", kd / "face_flops_release.tcl")
    shutil.copyfile(HERE / "pin_audit_core.py", kd / "pin_audit.py")
    (kd / "ft_stations.txt").write_text("# core kit: no ft slots\n")
    # macro sites: snap y so the macro's M4 pins sit on the core M4 tracks (0.012 + k 0.048)
    mp = []
    for m in c["macros"]:
        lef = (macro_dir(repo, m["master"]) / f"{m['master']}.lef").read_text()
        mm = re.search(r"LAYER M4 ;\s*RECT\s+[\d.]+\s+([\d.]+)\s+[\d.]+\s+([\d.]+)", lef)
        ph = (float(mm.group(1)) + float(mm.group(2))) / 2 if mm else 0.0
        x, y = m["at"]
        k = round((y + ph - 0.012) / 0.048)
        y2 = round(0.012 + k * 0.048 - ph, 4)
        if abs(y2 - y) > 1e-3:
            raise SystemExit(f"{m['inst']}: site y {y} is {y2 - y:+.3f} um off its M4 track phase (fix cores_eng.json)")
        mp.append(f"place_macro -macro_name {{{m['inst']}}} -location {{{x:.4f} {y2:.4f}}} "
                  f"-orientation {m.get('orient', 'R0')} -exact")
    if mp:
        (kd / "macro_place.tcl").write_text("# GENERATED by gen_core_kit.py: macro sites (core frame um, M4-track "
                                            "snapped).\n" + "\n".join(mp) + "\n")
    m_ = CORE_MARGIN_UM
    cfg = [f"# GENERATED by gen_core_kit.py (CORE-S81-ENG): planned hard core {c['name']} = {c['module']} of S81 eng__t1 "
           f"(dsdv_eng_rr split). Do not edit.",
           f"export DESIGN_NICKNAME = hc_{c['module']}",
           f"export DESIGN_NAME = {c['module']}",
           "export PLATFORM = asap7",
           "export VERILOG_FILES = " + " ".join(srcs),
           "export VERILOG_INCLUDE_DIRS = /work/rtl",
           "export VERILOG_DEFINES = " + " ".join(["-DSYNTHESIS"] + [f"-D{d}" for d in rec.get("defines", [])]),
           "export SDC_FILE = /work/constraint.sdc",
           f"export DIE_AREA = 0 0 {w:g} {h:g}",
           f"export CORE_AREA = {m_:g} {m_:g} {w - m_:g} {h - m_:g}",
           "export IO_CONSTRAINTS = /work/io.tcl",
           "export PDN_TCL = /work/pdn.tcl",
           "export MIN_ROUTING_LAYER = M2",
           "export MAX_ROUTING_LAYER = M5",
           f"export PLACE_DENSITY = {rec.get('util', 0.5):g}",
           "export SYNTH_HIERARCHICAL = 0",
           "export SYNTH_REPEATABLE_BUILD = 1",
           "export LEC_CHECK = 0",
           "export HOLD_SLACK_MARGIN = 15",
           "export SETUP_SLACK_MARGIN = 0",
           "export SKIP_LAST_GASP = 1",
           "export TNS_END_PERCENT = 100",
           "export PRE_GLOBAL_PLACE_TCL = /work/face_flops.tcl",
           "export PRE_DETAIL_PLACE_TCL = /work/face_flops_release.tcl",
           "export CORNER = TC",
           *([f"export ADDITIONAL_LEFS = {' '.join(lefs)}",
              f"export ADDITIONAL_LIBS = {' '.join(libs)}",
              "export MACRO_PLACE_HALO = 4.32 4.32",
              "export MACRO_PLACEMENT_TCL = /work/macro_place.tcl",
              "export CTS_ARGS = -sink_clustering_enable -repair_clock_nets -delay_buffer_derate 0.5"] if mp else
             ["export CTS_ARGS = -sink_clustering_enable -repair_clock_nets"]),
           *[f"export {k} = {v}" for k, v in rec.get("orfs_vars", {}).items()]]
    (kd / "config.mk").write_text("\n".join(cfg) + "\n")
    rec_sha = hashlib.sha256(json.dumps(rec, sort_keys=True).encode()).hexdigest()
    fz = dict(schema="opentallas.s81.core_freeze.v1", type=f"{c['module']}__{w:g}x{h:g}", module=c["module"],
              outline_um=[w, h], cores_json_sha256=sha(a.cores), pins_file=c["pins_file"],
              pins_sha256=sha(repo / "physical/die_plan/s81" / c["pins_file"]), pins=len(pins), clocks=clks,
              resets=rsts, recipe_sha256=rec_sha, period_ps=PERIOD_PS, common_latency_ps=COMMON_LATENCY_PS,
              signal_max="M5", macros=masters, kit_hash=kit_hash(kd))
    (kd / "freeze.json").write_text(json.dumps(fz, indent=1) + "\n")
    print(json.dumps(dict(kit=str(kd), pins=len(pins), clocks=clks, resets=rsts, kit_hash=fz["kit_hash"])))


if __name__ == "__main__":
    main()
