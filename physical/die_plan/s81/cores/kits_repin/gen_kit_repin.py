def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def face_of(x, y, w, h):
    return min([(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")])[1]


def lef_dirs(path):
    d, cur = {}, None
    for ln in Path(path).read_text().splitlines():
        t = ln.split()
        if t[:1] == ["PIN"]:
            cur = t[1]
        elif t[:1] == ["DIRECTION"] and cur:
            d[cur] = t[1]
        elif t[:1] == ["END"] and cur and t[1:2] == [cur]:
            cur = None
    return d


def kit_hash(kd):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(kd).rglob("*") if p.is_file() and p.relative_to(kd).parts[0] not in ("run", "views")
                    and p.name not in ("freeze.json", "image.txt") and not p.name.startswith(("run_", "sta_"))
                    and p.suffix not in (".log",) and p.name not in ("face_guard.json", "pin_audit.json")):
        h.update(str(f.relative_to(kd)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:16]


def sdc(per, ins, tol, clks, rsts, name):
    io = IO_BUDGET * per
    s = (f"# GENERATED by gen_kit_repin.py: core {name}; ps / fF (ASAP7 liberty units); gen_phys.sdc form (CP1-R10).\n"
         f"create_clock -name clk -period {per:.4f} [get_ports {{{' '.join(clks)}}}]\n"
         f"# the partition logic around the core runs on the budgeted insertion ({ins:g} ps): virtual IO clock\n"
         f"create_clock -name vclk -period {per:.4f}\n"
         f"set_clock_latency -source {ins:.4f} [get_clocks vclk]\n"
         f"set_clock_uncertainty {UNC_SETUP_PS:.4f} -setup [all_clocks]\n"
         f"set_clock_uncertainty {UNC_HOLD_PS:.4f} -hold [all_clocks]\n"
         f"# seam paths: uncertainty counted once per seam: {UNC_SPLIT:g} on each side\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -setup {UNC_SPLIT * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -setup {(1 - UNC_SPLIT) * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -hold {UNC_SPLIT * UNC_HOLD_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -hold {(1 - UNC_SPLIT) * UNC_HOLD_PS:.4f}\n"
         "set non_clk_in [all_inputs -no_clocks]\n"
         f"set_input_delay -max {io:.4f} -clock vclk $non_clk_in\n"
         f"set_output_delay -max {io:.4f} -clock vclk [all_outputs]\n")
    if rsts:
        s += (f"# reset: async assert, released by the partition's reset synchroniser one cycle ahead (recovery at 1 T)\n"
              f"set_input_delay -max {0.5 * per:.4f} -clock vclk [get_ports {{{' '.join(rsts)}}}]\n")
    s += (f"# seam hold: neighbour face flop launches from the fast end of the insertion window (-tol, no credit)\n"
          f"set_input_delay -min {-tol:.4f} -clock vclk $non_clk_in\n"
          f"set_output_delay -min 0.0000 -clock vclk [all_outputs]\n")
    return s + (f"set_load {IO_LOAD_FF:g} [all_outputs]\n"
                "set_driving_cell -lib_cell BUFx4_ASAP7_75t_R -pin Y $non_clk_in\n")


def apply_patch(text, edits, what):
    """kit-local RTL patch: each (old, new) must match exactly once."""
    for o, n in edits:
        if text.count(o) != 1:
            raise SystemExit(f"rtl_patch {what}: anchor matches {text.count(o)}x: {o[:60]!r}")
        text = text.replace(o, n)
    return text


