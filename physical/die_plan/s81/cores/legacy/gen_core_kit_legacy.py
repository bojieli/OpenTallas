def multi_root_sdc(text, mr, per):
    """rewrite the single-root SDC into the declared multi-root form: one create_clock per root base (bus roots: one
    clock over its pins, every pin its own tap), the vclk seam split on EVERY real clock; nothing else changes."""
    one = [l for l in text.splitlines() if l.startswith("create_clock -name clk ")]
    assert len(one) == 1, "sdc create_clock clk anchor"
    cc = "\n".join(f"create_clock -name {r['clock']} -period {per:.4f} [get_ports {{{r['base']}}}]" for r in mr["roots"])
    cc = ("# S81-CORE-LAT-R20 declared multi-root core: one clock per root (each root pin = one entry with its own 12.3\n"
          "# budget = the vclk insertion); inter-root paths are related same-PLL paths, timed (clock_roots.json)\n" + cc)
    text = text.replace(one[0], cc, 1)
    split = [l for l in text.splitlines() if l.startswith("set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk]")
             or l.startswith("set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk]")]
    assert len(split) == 4, "sdc seam split anchor"
    rep = "\n".join(l.replace("[get_clocks clk]", f"[get_clocks {r['clock']}]") for r in mr["roots"] for l in split)
    text = text.replace("\n".join(split), rep, 1)
    return text



def root_window_contract(spec, mr):
    """Optional canonical per-port source windows; no IO-budget or mask change.

    tap_window_port_ps is the existing gen_phys/sdc_lint contract, not a new
    clock relationship. Every scalar physical root must be explicitly covered.
    Bus-root aggregation cannot represent unequal source frames and is refused.
    """
    if "tap_window_port_ps" not in spec:
        return None
    if not mr:
        raise SystemExit("tap_window_port_ps requires an explicit multi-root contract")
    roots = [p for r in mr["roots"] for p in r["pins"]]
    if any(len(r["pins"]) != 1 or r["pins"][0] != r["base"] for r in mr["roots"]):
        raise SystemExit("tap_window_port_ps requires scalar root ports; scalarize bus entries without changing bindings")
    raw = spec["tap_window_port_ps"]
    if not isinstance(raw, dict) or set(raw) != set(roots):
        raise SystemExit("tap_window_port_ps must cover exactly every declared root port")
    out = {}
    for root, value in sorted(raw.items()):
        if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value) or value < 0:
            raise SystemExit(f"tap_window_port_ps: {root} needs a finite nonnegative window")
        out[root] = float(value)
