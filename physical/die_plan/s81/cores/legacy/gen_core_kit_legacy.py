def macro_pdn(mplace, macro_dir, obs_max=None):
    """Legacy SRAM M4 PG and signed native M5 PG, from the staged LEFs.

    M5-native children require real transverse M6 metal, not an empty M4/M5
    via grid. Signal routing stays unchanged; the added PG layer must be
    reserved in the eventual parent abstract/physical contract.
    """
    if not mplace:
        return PDN, None
    groups = {}
    for master in mplace:
        if not re.fullmatch(r"[A-Za-z_][\w$]*", master):
            raise ValueError(f"unsupported PG master identifier {master!r}")
        lef = Path(macro_dir) / (master + ".lef")
        text = lef.read_text()
        layers = []
        for pin in ("VDD", "VSS"):
            block = re.search(r"\bPIN\s+" + pin + r"\b(.*?)\bEND\s+" + pin + r"\b", text, re.S)
            got = set(re.findall(r"\bLAYER\s+(M[0-9]+)\s*;", block[1])) if block else set()
            if len(got) != 1 or not got <= {"M4", "M5"}:
                raise ValueError(f"{lef}: {pin} needs one M4/M5 PG interface, found {sorted(got)}")
            layers.append(next(iter(got)))
        if layers[0] != layers[1]:
            raise ValueError(f"{lef}: mismatched VDD/VSS PG interfaces {layers}")
        groups.setdefault(layers[0], []).append(master)
    if "M5" not in groups:
        return PDN + PDN_MACRO, None  # preserve all existing M4-only kit bytes
    if not isinstance(obs_max, str) or not re.fullmatch(r"M[6-9]", obs_max):
        raise ValueError(f"native M5 child PG requires declared obs_max>=M6, found {obs_max!r}")
    # Same transverse PG geometry as gen_phys.PDN. M6 has no native-child OBS;
    # parent M5 stripes alone are parallel to the child M5 pins and cannot land
    # an M4/M5 via on a child exposing only M5.
    bridge = ("# Native M5 child PG: transverse M6 bridge; signal routing ceiling unchanged.\n"
              "add_pdn_stripe -grid {top} -layer {M6} -width {0.288} -spacing {0.096} -pitch {4.32} -offset {1.968}\n"
              "add_pdn_connect -grid {top} -layers {M5 M6}\n")
    out = PDN + bridge
    for layer, masters in sorted(groups.items()):
        cells = " ".join("{^" + re.escape(m) + "$}" for m in sorted(masters))
        upper = "M5" if layer == "M4" else "M6"
        grid = "native_pg_" + layer
        halo = "2.0 2.0" if layer == "M4" else "0"
        out += (f"define_pdn_grid -macro -name {{{grid}}} -cells {{{cells}}} "
                f"-voltage_domains {{CORE}} -halo {{{halo}}} -grid_over_boundary\n"
                f"add_pdn_connect -grid {{{grid}}} -layers {{{layer} {upper}}}\n")
    info = dict(schema="opentallas.native_child_pg_interface.v1",
                masters_by_pg_pin_layer=groups, added_pg_layers=["M6"],
                added_signal_routing_layers=[], abstract_obstruction_min_layer="M6",
                declared_parent_obs_max=obs_max,
                parent_adoption="requires explicit M6 PG reservation/obstruction in published view",
                m6_stripe_um=dict(width=.288, spacing=.096, pitch=4.32, offset=1.968))
    return out, info


def pg_top_pdn(pdn, info, pg_top=None, obs_max=None):
    """Opt in to a real M6 exported supply interface above M6 signal OBS.

    The default preserves legacy PDN bytes. A label alone cannot lift PG:
    M6 stripes, M5/M6 vias and M6 boundary pins are generated together.
    The containing parent must reserve a real M7 landing bridge.
    """
    if pg_top is None or pg_top == "M5":
        return pdn, info
    if pg_top != "M6":
        raise ValueError(f"unsupported pg_top {pg_top!r}; supported M5/M6")
    if not isinstance(obs_max, str) or not re.fullmatch(r"M[6-9]", obs_max):
        raise ValueError(f"M6 PG interface requires declared obs_max>=M6, found {obs_max!r}")
    old = "define_pdn_grid -name {top} -voltage_domains {CORE} -pins {M5}"
    if pdn.count(old) != 1:
        raise ValueError("expected exactly one native M5 top PG grid")
    pdn = pdn.replace(old, old.replace("-pins {M5}", "-pins {M6}"), 1)
    if "add_pdn_stripe -grid {top} -layer {M6}" not in pdn:
        pdn += ("# Export actual M6 PG pins; parent landing requires M7.\n"
                "add_pdn_stripe -grid {top} -layer {M6} -width {0.288} -spacing {0.096} -pitch {4.32} -offset {1.968}\n"
                "add_pdn_connect -grid {top} -layers {M5 M6}\n")
    elif "add_pdn_connect -grid {top} -layers {M5 M6}" not in pdn:
        raise ValueError("existing M6 stripes lack M5/M6 PG connection")
    info = dict(info or {})
    info.update(schema="opentallas.core_pg_interface.v1", exported_pg_pin_layer="M6",
                added_pg_layers=["M6"], declared_parent_obs_max=obs_max,
                abstract_obstruction_min_layer="M6", parent_landing_layer="M7",
                parent_adoption="requires actual M6 PG pins and explicit parent M7 landing",
                m6_stripe_um=dict(width=.288, spacing=.096, pitch=4.32, offset=1.968))
    return pdn, info


