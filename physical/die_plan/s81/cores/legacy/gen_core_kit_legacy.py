def planned_pin_geometry(q, shapes, w, h, modern=True, interior_clock=None):
    """Preserve a declared edge rectangle; modern kits never silently move plan pins."""
    f = face_of(q["x"], q["y"], w, h)
    pw, ph = RECT[q["layer"]]
    shape = shapes.get(q["name"])
    if interior_clock is not None:
        layer, x, y, size = interior_clock
        if (layer != "M5" or q["layer"] != layer or
                abs(q["x"]-x) > 1e-4 or abs(q["y"]-y) > 1e-4 or
                abs((x-.012)/.048-round((x-.012)/.048)) > 1e-3 or
                not shape or len(shape) != 7 or shape[0] != layer):
            raise SystemExit("interior clock must match its explicit on-track M5 slice entry and LEF rectangle")
        _, sw, sh, x0, y0, x1, y1 = shape
        if (sw < size[0]-1e-4 or sh < size[1]-1e-4 or
                abs((x0+x1)/2-x) > 1e-4 or abs((y0+y1)/2-y) > 1e-4 or
                min(x0,y0) < 0 or x1 > w or y1 > h):
            raise SystemExit("interior clock LEF rectangle must be centred, full-sized and inside its outline")
        return q, sw, sh, 0
    if shape and len(shape) == 7 and shape[0] == q["layer"]:
        _, sw, sh, x0, y0, x1, y1 = shape
        centered = abs((x0+x1)/2-q["x"]) < 1e-4 and abs((y0+y1)/2-q["y"]) < 1e-4
        edge = {"W": abs(x0), "E": abs(w-x1), "S": abs(y0), "N": abs(h-y1)}[f]
        if centered and edge < 1e-4:
            pw, ph = sw, sh
    perp = {"W": ("x", pw/2), "E": ("x", w-pw/2), "S": ("y", ph/2), "N": ("y", h-ph/2)}[f]
    distance = abs(q[perp[0]]-perp[1])
    if distance > 1e-3:
        if modern:
            raise SystemExit(f"plan pin {q['name']} is {distance:.4f} um off its declared {f} edge rectangle; correct the plan pin contract (no implicit projection)")
        if distance > 3.0:
            raise SystemExit(f"pin {q['name']} {distance:.3f} um off its {f} face")
        q = dict(q, **{perp[0]: round(perp[1], 4)})
    return q, pw, ph, int(distance > 1e-3)


def kit_hash(kd):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(kd).rglob("*") if p.is_file() and p.relative_to(kd).parts[0] not in ("run", "views")
                    and p.name not in ("freeze.json", "image.txt") and not p.name.startswith(("run_", "sta_"))
                    and p.suffix not in (".log",) and p.name not in ("face_guard.json", "pin_audit.json")):
        h.update(str(f.relative_to(kd)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:16]


def half_cycle_input_bounds(selected, names, dirs, clock_ports, reset_ports, base, per, tol):
    """Opt-in FALL-launch -> RISE-capture data seam; never a clock/reset/output exception.
    The actual producer phase must be established separately; IO-HOLD parent
    qualification remains required. Absent selection returns no SDC changes.
    """
    forbidden = {base(n) for n in list(clock_ports) + list(reset_ports)}
    data = {base(n) for n in names if dirs[n] == "INPUT"} - forbidden
    chosen = list(selected or [])
    if len(set(chosen)) != len(chosen):
        raise SystemExit("half_cycle_inputs repeats a bus")
    bad = sorted(set(chosen) - data)
    if bad:
        raise SystemExit("half_cycle_inputs must name real DATA inputs only (not clocks/resets/outputs): " + str(bad))
    return ({b:round(0.5*per-tol,4) for b in chosen},
            {b:round((1-IO_BUDGET)*per,4) for b in chosen})



