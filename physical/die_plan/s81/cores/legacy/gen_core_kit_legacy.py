    m = "".join(f" {{{b}}} {{{p}}}" for b, p in mr["domain_of_bus"].items())
    (kd / "core_clock_map.tcl").write_text(
        "# GENERATED by gen_core_kit_legacy.py (S81-CORE-LAT-R20): declared multi-root IO bus -> root pin\n"
        f"set ::ot_fc_map [dict create{m}]\n")
