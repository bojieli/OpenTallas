def multi_root_refusal(module, spec):
    """None for a single-root core, else the refusal message.  This generator writes ONE kit clock (clk on clock_port,
    one vclk IO frame, one 12.3 latency target / one plan clock entry, tap_balance on that port).  A multi-root core
    (spec clock_ports with more than one base, e.g. dsfd_cfifo_crs4 cr + cr_s + forwarded lane clocks xk[0..3],
    ot_s81sl_capc5r ck_rt/ck_cw/ck_ce/ck_rn/ck_rs) would get a kit whose other roots are unclocked data pins -- refuse
    (fail closed) until per-root clocks, per-entry-domain IO frames (spec clock_entry_domains) and per-root 12.3 entries
    exist here."""
    roots = clock_roots(spec)
    if len(roots) <= 1:
        return None
    return (f"{module}: multi-root core {roots} (spec clock_ports {spec.get('clock_ports')}): gen_core_kit_legacy writes "
            f"one kit clock on {roots[0]} only; the other roots would be unclocked data pins (refused: needs per-root "
            f"create_clock + clock_entry_domains IO frames + one 12.3 entry per root)")


def root_clock_name(spec, b):
    """SDC clock name of root base b: the primary clock_port keeps 'clk' (every single-root consumer: corners.tcl,
    postcts_gate, signoff), every other root 'clk_<base>'."""
    return "clk" if b == spec["clock_port"] else "clk_" + re.sub(r"[^A-Za-z0-9_]", "_", b)


def multi_root_contract(module, spec, rec):
    """S81-CORE-LAT-R20 (COORD S81-CORES-R1 ruling (2)): DECLARED multi-root cores.  None for a single-root core; for a
    multi-root core the generator refuses (multi_root_refusal) unless the recipe declares multi_root: true AND the spec
    declares every root and its IO frame:
      * clock_relationship = same_pll_fixed_phase 1:1, phase 0 and clock_data_paths = related_same_frequency (all roots
        are taps of the one die clock: inter-root paths are RELATED synchronous paths, timed, never false paths /
        clock groups; a truly asynchronous root needs synchronisers + a CDC rule this contract does not cover);
      * clock_entry_domains: every root PIN (spec clock_ports, bus bits apart: xk[0] .. xk[3]) in exactly one domain
        (ratio 1:1), every non-clock IO bus of the plan pins in exactly one domain (checked in main against the pins).
    Each root pin is its own clock ENTRY (12.2a/12.8a: one entry / island per root) with its own 12.3 budget at the die
    common target (TT ins / FF ins_ff: the vclk insertion), balanced by tap_balance per port; the IO frame of every
    domain is the one vclk (all roots carry the same budget, sdc_lint: one virtual IO clock).  Inter-root paths are
    timed at policy uncertainty with each root's own tree from its pin; the root-to-root arrival difference is a die
    related-pair obligation (12.4a) recorded in clock_roots.json, which the die STA times on the routed die clock.
    -> dict(roots=[{base, clock, pins, domains}], domain_of_bus={bus: root pin}, pairs=[[launch, capture]])"""
    roots = clock_roots(spec)
    if len(roots) <= 1:
        return None
    if not rec.get("multi_root"):
        raise SystemExit(multi_root_refusal(module, spec) + " -- or declare recipe multi_root: true (S81-CORE-LAT-R20)")
    bad = []
    rel = spec.get("clock_relationship") or {}
    if rel.get("kind") != "same_pll_fixed_phase" or list(rel.get("ratio") or []) != [1, 1] \
            or float(rel.get("phase_ps", 1)) != 0.0:
        bad.append(f"clock_relationship {rel} is not same_pll_fixed_phase 1:1 phase 0")
    if spec.get("clock_data_paths") != "related_same_frequency":
        bad.append(f"clock_data_paths {spec.get('clock_data_paths')!r} != related_same_frequency")
    dom = spec.get("clock_entry_domains") or {}
    if not dom:
        bad.append("no clock_entry_domains")
    want_pins = [spec["clock_port"]] + [c for c in spec.get("clock_ports") or [] if c != spec["clock_port"]]
    seen, bus_root = {}, {}
    for d, v in sorted(dom.items()):
        if list(v.get("ratio") or [1, 1]) != [1, 1]:
            bad.append(f"domain {d} ratio {v.get('ratio')} != 1:1")
        ps = list(v.get("ports") or [])
        if len(ps) != 1:
            bad.append(f"domain {d} has {len(ps)} root pins (want exactly one: one IO frame per entry)")
        for p in ps:
            if p in seen:
                bad.append(f"root pin {p} in domains {seen[p]} and {d}")
            seen[p] = d
        for b in list(v.get("inputs") or []) + list(v.get("outputs") or []):
            if b in bus_root:
                bad.append(f"IO bus {b} in two domains")
            if ps:
                bus_root[b] = ps[0]
    if sorted(seen) != sorted(want_pins):
        bad.append(f"domain root pins {sorted(seen)} != spec clock_ports {sorted(want_pins)}")
    if bad:
        raise SystemExit(f"{module}: multi-root contract refused: " + "; ".join(bad))
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    out = []
    for b in roots:
        pins_b = [p for p in want_pins if base(p) == b]
        out.append(dict(base=b, clock=root_clock_name(spec, b), pins=pins_b, domains=sorted(seen[p] for p in pins_b)))
    clocks = [r["clock"] for r in out]
    return dict(roots=out, domain_of_bus=dict(sorted(bus_root.items())),
                pairs=[[a, b] for a in clocks for b in clocks if a != b])


