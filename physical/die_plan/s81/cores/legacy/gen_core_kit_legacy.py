def sdc(per, ins, tol, clks, rsts, name, in_min_ports=None, half_max=None):
    io = IO_BUDGET * per
    s = (f"# GENERATED by gen_core_kit_legacy.py: core {name}; ps / fF (ASAP7 liberty units); gen_phys.sdc form (CP1-R10).\n"
         f"create_clock -name clk -period {per:.4f} [get_ports {{{' '.join(clks)}}}]\n"
         f"# the partition logic around the core runs on the budgeted insertion ({ins:g} ps): virtual IO clock\n"
         f"create_clock -name vclk -period {per:.4f}\n"
         f"set_clock_latency -source {ins:.4f} [get_clocks vclk]\n"
         f"set_clock_uncertainty {UNC_SETUP_PS:.4f} -setup [all_clocks]\n"
         f"set_clock_uncertainty {UNC_HOLD_PS:.4f} -hold [all_clocks]\n"
         f"# seam paths: uncertainty counted once per seam: {UNC_SPLIT:g} on each side\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -setup {UNC_SPLIT * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -setup {(1 - UNC_SPLIT) * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -hold {UNC_SPLIT * UNC_HOLD_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -hold {(1 - UNC_SPLIT) * UNC_HOLD_PS:.4f}\n"
         "set non_clk_in [all_inputs -no_clocks]\n"
         f"set_input_delay -max {io:.4f} -clock vclk $non_clk_in\n"
         f"set_output_delay -max {io:.4f} -clock vclk [all_outputs]\n")
    if rsts:
        s += _reset_sdc(rsts, per)
    s += (f"# seam hold: neighbour face flop launches from the fast end of the insertion window (-tol, no credit)\n"
          f"set_input_delay -min {-tol:.4f} -clock vclk $non_clk_in\n"
          f"set_output_delay -min 0.0000 -clock vclk [all_outputs]\n")
    for v, ports in _group_in_min(half_max or {}):
        # Actual neighbour falling-edge launch: half a cycle + its output budget.
        # Keep this override on the declared DATA bus only.
        s += (f"# HALF-CYCLE input (neighbour negedge launch): max = (1 - {IO_BUDGET:g}) x T\n"
              f"set_input_delay -max {v:.4f} -clock vclk [get_ports {{{' '.join(p + '[*]' for p in ports)}}}]\n")
    for v, ports in _group_in_min(in_min_ports or {}):
        s += (f"# IO-HOLD A (COORD 2026-10-25 10:23, recipe io_hold sender_min): registered sender guaranteed output-min "
              f"(+{v:g} ps after vclk)\n"
              f"set_input_delay -min {v:.4f} -clock vclk [get_ports {{{' '.join(p + '[*]' for p in ports)}}}]\n")
    return s + (f"set_load {IO_LOAD_FF:g} [all_outputs]\n"
                "set_driving_cell -lib_cell BUFx4_ASAP7_75t_R -pin Y $non_clk_in\n")


def _group_in_min(m):
    """[(in_min_ps, [ports])] sorted, one SDC command per distinct value (gen_phys._group_in_min)."""
    g = {}
    for p, v in m.items():
        g.setdefault(v, []).append(p)
    return sorted((v, sorted(ps)) for v, ps in g.items())


def legacy_in_min_ports(rec, names, dirs, ckb, rsts, base):
    """IO-HOLD option A for a legacy hard core (recipe io_hold = "sender_min"; gen_phys.input_hold_min form):
    every VECTOR input bus (width > 1) is driven by a registered sender (S81 main RTL lands every station / core
    input in its own pin register), whose own output hold check (min output 0 vs vclk, (1 - UNC_SPLIT) x UNC_HOLD_PS
    of the seam uncertainty) guarantees it changes no earlier than vclk + 12.5 ps.  1-bit scalars, resets and the
    clock keep the flat -insertion_tol fallback (COORD 15:23 / GEOM-REVIEW-2 15:54 (b)).  The related tap-pair skew
    sender -> receiver is the parent's obligation (io_hold_parent.py; signoff.py apply_obligation keeps the local
    sign-off provisional until that receipt).  {input bus: in_min_ps}; empty when the recipe does not opt in."""
    mode = rec.get("io_hold", "legacy")
    if mode not in ("legacy", "sender_min"):
        raise SystemExit(f"recipe io_hold '{mode}' not in (legacy, sender_min)")
    if mode != "sender_min":
        return {}
    g = float(rec.get("io_hold_guarantee_ps", (1 - UNC_SPLIT) * UNC_HOLD_PS - 0.0))
    width = {}
    for n in names:
        if dirs[n] == "INPUT" and base(n) != ckb and base(n) not in rsts:
            width[base(n)] = width.get(base(n), 0) + 1
    return {b: round(g, 4) for b, w in sorted(width.items()) if w > 1}


