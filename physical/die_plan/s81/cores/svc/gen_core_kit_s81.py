#!/usr/bin/env python3
"""CORE-S81-SVC 10-23: ORFS kit for one S81 planned hard core (adapted copy of CORE-HBM gen_core_kit.py,
claude/core-hbm-1023 physical/die_plan/hbm/cores/harden/gen_core_kit.py).

    python3 gen_core_kit_s81.py --cores cores_svc.json --plan ../../die_plan.json --recipes recipes.json --out KITROOT
                                [--tool TOOLDIR] [--util 0.5]

S81 differences from the HBM generator: the core is read from cores_svc.json (not yet in the plan's hard_cores);
pins sit on the core-frame tracks 0.012 + k*0.048 (M4/M5) so that, at an 8.64-lattice origin plus the S81
track_offset_um [0.108, 0.012], they land on the die tracks; make_tracks = the asap7 platform tracks (M4/M5
0.012/0.048, M6/M7 0.016/0.064); period / insertion from the S81 plan clock (833 ps, 250 ps common latency).
config.mk / io.tcl / pdn.tcl / constraint.sdc / face_flops.tcl (register-on-every-pin audit) / freeze.json as HBM.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

CORE_MARGIN_UM = 4.32
PIN_LEN_UM = 0.192
LAYER_W = dict(M2=0.018, M3=0.018, M4=0.024, M5=0.024, M6=0.032, M7=0.032)
IO_BUDGET = 0.2
UNC_SETUP_PS, UNC_HOLD_PS, UNC_SPLIT, IO_LOAD_FF = 60.0, 25.0, 0.5, 2.0
CLK_RE = r"^(clk|clk_[a-z0-9_]+|[a-z0-9_]*_clk|ck|ck_[a-z0-9_]+)$"
RST_RE = r"^(rst_n|rst|arst_n|reset_n|rst_[a-z0-9_]+|[a-z0-9_]*_rst_n|[a-z0-9_]*rst_n)$"

M123_TRACKS = """make_tracks M3 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.009 -y_pitch 0.036
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.045 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.081 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.117 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.153 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.189 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.225 -y_pitch 0.270
make_tracks M2 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.270 -y_pitch 0.270
make_tracks M1 -x_offset 0.009 -x_pitch 0.036 -y_offset 0.009 -y_pitch 0.036
"""

PDN = """# GENERATED by gen_core_kit.py: core PDN (follow-pins + M5 stripes = core PG pins on the partition M5 grid).
add_global_connection -net {VDD} -inst_pattern {.*} -pin_pattern {^VDD$} -power
add_global_connection -net {VSS} -inst_pattern {.*} -pin_pattern {^VSS$} -ground
global_connect
set_voltage_domain -name {CORE} -power {VDD} -ground {VSS}
define_pdn_grid -name {top} -voltage_domains {CORE} -pins {M5}
add_pdn_stripe -grid {top} -layer {M1} -width {0.018} -pitch {0.54} -offset {0} -followpins
add_pdn_stripe -grid {top} -layer {M2} -width {0.018} -pitch {0.54} -offset {0} -followpins
add_pdn_stripe -grid {top} -layer {M5} -width {0.12} -spacing {0.072} -pitch {4.32} -offset {2.064}
add_pdn_connect -grid {top} -layers {M1 M2}
add_pdn_connect -grid {top} -layers {M2 M5}
"""
PDN_MACRO = """define_pdn_grid -macro -default -name {macro} -voltage_domains {CORE} -halo {2.0 2.0} -grid_over_boundary
add_pdn_connect -grid {macro} -layers {M4 M5}
"""


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def face_of(x, y, w, h):
    d = [(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")]
    return min(d)[1]


def split_name(n):
    m = re.match(r"^(.*)\[(\d+)\]$", n)
    return (m.group(1), int(m.group(2))) if m else (n, None)


def io_tcl(pins, w, h, tid):
    out = [f"# GENERATED by gen_core_kit.py: exact plan pins of core type {tid} ({len(pins)} pins, core frame um)."]
    rows = []
    for p in pins:
        f = face_of(p["x"], p["y"], w, h)
        lw = LAYER_W.get(p["layer"], 0.04)
        x, y = p["x"], p["y"]
        if f in "EW":
            x = w if f == "E" else 0.0
            size, cx, cy = (PIN_LEN_UM, lw), (x - PIN_LEN_UM / 2 if f == "E" else x + PIN_LEN_UM / 2), y
        else:
            y = h if f == "N" else 0.0
            size, cx, cy = (lw, PIN_LEN_UM), x, (y - PIN_LEN_UM / 2 if f == "N" else y + PIN_LEN_UM / 2)
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{cx:.4f} {cy:.4f}}} "
                   f"-pin_size {{{size[0]:.4f} {size[1]:.4f}}}")
        b, i = split_name(p["name"])
        rows.append(dict(bus=b, bit=i, layer=p["layer"], x=round(x if f in "EW" else p["x"], 4),
                         y=round(y if f in "NS" else p["y"], 4), face=f))
    return "\n".join(out) + "\n", rows


def make_tracks(plan):
    # S81 cores: core-frame tracks = the asap7 platform tracks (the die tracks after the [0.108, 0.012] core offset)
    return ("# GENERATED by gen_core_kit_s81.py: platform tracks M4-M7 (core frame; S81 core track offset) + M1-M3.\n"
            "make_tracks M7 -x_offset 0.016 -x_pitch 0.064 -y_offset 0.016 -y_pitch 0.064\n"
            "make_tracks M6 -x_offset 0.016 -x_pitch 0.064 -y_offset 0.016 -y_pitch 0.064\n"
            "make_tracks M5 -x_offset 0.012 -x_pitch 0.048 -y_offset 0.012 -y_pitch 0.048\n"
            "make_tracks M4 -x_offset 0.012 -x_pitch 0.048 -y_offset 0.012 -y_pitch 0.048\n" + M123_TRACKS)


def sdc(per, ins, clks, rsts, tid):
    io = IO_BUDGET * per
    skip = "|".join(re.escape(c) for c in clks + rsts)
    s = (f"# GENERATED by gen_core_kit.py: core type {tid}; ps / fF (ASAP7 liberty units).\n"
         f"create_clock -name clk -period {per:.4f} [get_ports {{{' '.join(clks)}}}]\n"
         f"# the partition logic around the core runs on the budgeted insertion ({ins:g} ps): virtual IO clock\n"
         f"create_clock -name vclk -period {per:.4f}\n"
         f"set_clock_latency -source {ins:.4f} [get_clocks vclk]\n"
         f"set_clock_uncertainty {UNC_SETUP_PS:.4f} -setup [all_clocks]\n"
         f"set_clock_uncertainty {UNC_HOLD_PS:.4f} -hold [all_clocks]\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -setup {UNC_SPLIT * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -setup {(1 - UNC_SPLIT) * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -hold {UNC_SPLIT * UNC_HOLD_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -hold {(1 - UNC_SPLIT) * UNC_HOLD_PS:.4f}\n"
         f"set non_clk_in [lsearch -inline -all -not -regexp [all_inputs] {{^({'|'.join(re.escape(c) for c in clks)})$}}]\n"
         f"set_input_delay {io:.4f} -clock vclk $non_clk_in\n"
         f"set_output_delay {io:.4f} -clock vclk [all_outputs]\n"
         f"set_input_delay -min 0.0000 -clock vclk $non_clk_in\n")
    if rsts:
        s += (f"# reset: async assert, released by the partition's reset synchroniser one cycle ahead (recovery at 1 T)\n"
              f"set_input_delay {0.5 * per:.4f} -clock vclk [get_ports {{{' '.join(rsts)}}}]\n")
    return s + (f"set_load {IO_LOAD_FF:g} [all_outputs]\n"
                "set_driving_cell -lib_cell BUFx4_ASAP7_75t_R -pin Y $non_clk_in\n")


def kit_hash(kd):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(kd).rglob("*") if p.is_file() and "run" not in p.relative_to(kd).parts[:1]
                    and p.name not in ("freeze.json",) and not p.name.startswith("run_")):
        h.update(str(f.relative_to(kd)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:16]


def main():
    global TOOL
    ap = argparse.ArgumentParser()
    ap.add_argument("--cores", required=True)
    ap.add_argument("--plan", required=True)
    ap.add_argument("--recipes", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parents[5]))
    ap.add_argument("--tool", default="/home/ubuntu/scratch/core-s81-1023/pt4/tools/die_plan")
    ap.add_argument("--plan-commit", default="2a90fc8c")
    ap.add_argument("--util", type=float, default=0.5)
    ap.add_argument("--sigmax", default="M5")
    a = ap.parse_args()
    TOOL = Path(a.tool)
    repo = Path(a.repo)
    plan = json.load(open(a.plan))
    cs = json.load(open(a.cores))
    c = dict(cs["core"])
    w, h = c["outline_um"]
    a.type = f"{c['module']}__{w:g}x{h:g}"
    tn = "svc_* (cores_svc.json)"
    c["inst"] = cs["placement"]["hard_cores"][0]["inst"]
    rec_all = json.load(open(a.recipes))
    rec = rec_all.get(a.type) or rec_all.get(c["module"])
    if not rec:
        raise SystemExit(f"no recipe for {a.type} / {c['module']}")
    plandir = Path(a.plan).resolve().parent
    pins = json.load(open(plandir / c["pins_file"]))["pins"]
    kd = Path(a.out) / a.type
    if kd.exists():
        shutil.rmtree(kd)
    (kd / "rtl").mkdir(parents=True)
    srcs = []
    for f in rec["files"]:
        src = repo / f
        dst = kd / "rtl" / Path(f).name
        if dst.exists() and dst.read_bytes() != src.read_bytes():
            raise SystemExit(f"rtl name clash {dst.name}")
        shutil.copyfile(src, dst)
        if not f.endswith((".svh", ".vh")):
            srcs.append(f"/work/rtl/{dst.name}")
    lefs, libs = [], []
    off = [q["name"] for q in pins if q["layer"] in ("M4", "M5") and
           abs(((q["x"] if q["layer"] == "M5" else q["y"]) - 0.012) / 0.048 - round(((q["x"] if q["layer"] == "M5" else q["y"]) - 0.012) / 0.048)) > 0.05]
    if off:
        raise SystemExit(f"{a.type}: {len(off)}/{len(pins)} M4/M5 pins off the core-frame tracks (0.012 + k*0.048), e.g. {off[:3]}")
    io, prow = io_tcl(pins, w, h, a.type)
    (kd / "io.tcl").write_text(io)
    (kd / "pins.json").write_text(json.dumps(prow) + "\n")
    names = [p["name"] for p in pins]
    pins_pending = None
    canon = Path(__file__).with_name("canonical_ports_split.json")
    ft = rec.get("functional_type")
    if ft and canon.is_file():
        ct = json.load(open(canon)).get("types", {}).get(ft)
        if ct:
            cn = [n if w == 1 else f"{n}[{lsb + i}]" for n, d, w, lsb in ct["ports"] for i in range(w)]
            if set(cn) != set(names):
                # the plan pins still carry the netlist-cut names: synth-only kit until the canonical re-pin lands
                pins_pending = f"plan pins use cut names ({len(names)}), RTL top has canonical ports ({len(cn)})"
                names = cn
                io = "# PINS PENDING: " + pins_pending + "\n"
                (kd / "io.tcl").write_text(io)
    base = lambda n: re.sub(r"\[\d+\]$", "", n)
    clks = [n for n in names if re.match(CLK_RE, base(n))]
    rsts = [n for n in names if re.match(RST_RE, base(n))]
    if not clks:
        raise SystemExit(f"{a.type}: no clock pin among {len(names)} pins")
    per = float(plan["die"]["period_ps"])
    ins = float(plan["clock"].get("common_latency_ps", plan["clock"]["insertion_ps"]))
    (kd / "constraint.sdc").write_text(sdc(per, ins, clks, rsts, a.type))
    (kd / "pdn.tcl").write_text(PDN + (PDN_MACRO if lefs else ""))
    (kd / "make_tracks.tcl").write_text(make_tracks(plan))
    skip = "^(" + "|".join(re.escape(n) for n in clks + rsts) + ")$"
    ff = (TOOL / "face_flops.tcl").read_text()
    ff = ff.replace("set ff_skip_re {^(clk(_t[0-9]+)?|arst_n)$}", "set ff_skip_re {" + skip + "}")
    assert ("set ff_skip_re {" + skip + "}") in ff, "face_flops.tcl skip regex anchor changed"
    # register-on-every-pin audit: list each signal port without a flop within 2 buffers
    ff = ff.replace("set ff_out [open $::env(RESULTS_DIR)/ot_face_flops.txt w]",
                    "set ff_out [open $::env(RESULTS_DIR)/ot_face_flops.txt w]\n"
                    "set ff_unreg [open $::env(RESULTS_DIR)/ot_unreg_pins.txt w]")
    ff = ff.replace("    if {$f eq \"\"} { incr ff_miss; continue }",
                    "    if {$f eq \"\"} { incr ff_miss; puts $ff_unreg \"$pass\\t$nm\"; continue }")
    assert "ot_unreg_pins" in ff and "puts $ff_unreg" in ff, "face_flops.tcl miss anchor changed"
    (kd / "face_flops.tcl").write_text(ff)
    shutil.copyfile(TOOL / "face_flops_release.tcl", kd / "face_flops_release.tcl")
    shutil.copyfile(Path(__file__).with_name("pin_audit_core.py"), kd / "pin_audit.py")
    shutil.copyfile(Path(__file__).with_name("run_kit.sh"), kd / "run_kit.sh")
    (kd / "ft_stations.txt").write_text("# core kit: no ft slots\n")
    m = CORE_MARGIN_UM
    params = rec.get("params", {})
    cfg = [f"# GENERATED by gen_core_kit_s81.py (CORE-S81-SVC): planned hard core {a.type} of S81 plan "
           f"{a.plan_commit} (first slot {tn}.{c['inst']}). Do not edit.",
           f"export DESIGN_NICKNAME = hc_{re.sub(r'[^A-Za-z0-9_]', '_', a.type)[:60]}",
           f"export DESIGN_NAME = {rec.get('top', c['module'])}",
           "export PLATFORM = asap7",
           "export VERILOG_FILES = " + " ".join(srcs),
           "export VERILOG_INCLUDE_DIRS = /work/rtl",
           "export VERILOG_DEFINES = " + " ".join(["-DSYNTHESIS"] + [f"-D{d}" for d in rec.get("defines", [])]),
           *([f"export VERILOG_TOP_PARAMS = " + " ".join(f"{k} {v}" for k, v in params.items())] if params else []),
           "export SDC_FILE = /work/constraint.sdc",
           f"export DIE_AREA = 0 0 {w:g} {h:g}",
           f"export CORE_AREA = {m:g} {m:g} {w - m:g} {h - m:g}",
           "export IO_CONSTRAINTS = /work/io.tcl",
           "export PDN_TCL = /work/pdn.tcl",
           "override export MAKE_TRACKS = /work/make_tracks.tcl",
           "export MIN_ROUTING_LAYER = M2",
           f"export MAX_ROUTING_LAYER = {a.sigmax}",
           f"export PLACE_DENSITY = {rec.get('util', a.util):g}",
           "export SYNTH_HIERARCHICAL = 0",
           "export SYNTH_REPEATABLE_BUILD = 1",
           "export LEC_CHECK = 0",
           "export HOLD_SLACK_MARGIN = 15",
           "export SETUP_SLACK_MARGIN = 0",
           "export SKIP_LAST_GASP = 1",
           "export TNS_END_PERCENT = 100",
           "export PRE_GLOBAL_PLACE_TCL = /work/face_flops.tcl",
           "export PRE_DETAIL_PLACE_TCL = /work/face_flops_release.tcl",
           "export CORNER = TC",
           *[f"export {k} = {v}" for k, v in rec.get("orfs_vars", {}).items()],
           *([f"export ADDITIONAL_LEFS = {' '.join(lefs)}", f"export ADDITIONAL_LIBS = {' '.join(libs)}",
              "export MACRO_PLACE_HALO = 4.32 4.32",
              # TritonCTS over-balances the SRAM clk tree with delay buffers (h9b: 9 delaybufs, SRAM clk 191 ps vs
              # flops 134 ps BC -> -64 ps hold on every SRAM wd_in); half the delay-buffer target puts them level
              "export CTS_ARGS = -sink_clustering_enable -repair_clock_nets -delay_buffer_derate "
              f"{rec.get('cts_delay_buffer_derate', 0.5)}"] if lefs else [])]
    if rec.get("synth_memory_max_bits"):
        # a logic ROM/LUT the closed view also built in std cells (e.g. the sfu lane function table, 15.6 kb)
        cfg.append(f"export SYNTH_MEMORY_MAX_BITS = {int(rec['synth_memory_max_bits'])}")
    mp = rec.get("macro_place")
    if mp:
        # explicit SRAM sites (CORE-HBM, GEOM: RTLMP put an SRAM on a pin face and pushed the face flops 50 um in)
        snapped = {}
        for i, v in mp.items():
            # SRAM M4 pins (E/W edges) must sit on the kit M4 tracks (0.024 + k*0.048): snap y by the LEF pin phase
            # (h9b gate 10-23: SRAM at y 30.24 put every wd/rd pin 12 nm off-track -> DRT-0255 at the macro edge)
            m0 = rec["macros"][0]
            lef = (repo / "physical" / "asap7_memory_macros_v2" / m0 / f"{m0}.lef").read_text()
            mm = re.search(r"LAYER M4 ;\s*RECT\s+[\d.]+\s+([\d.]+)\s+[\d.]+\s+([\d.]+)", lef)
            ph = (float(mm.group(1)) + float(mm.group(2))) / 2 if mm else 0.0
            y = v[1]
            k = round((y + ph - 0.024) / 0.048)
            snapped[i] = [v[0], round(0.024 + k * 0.048 - ph, 4)] + list(v[2:])
        mp = snapped
        (kd / "macro_place.tcl").write_text("# GENERATED by gen_core_kit.py: SRAM sites (core frame um), from the recipe.\n" +
            "".join(f"place_macro -macro_name {{{i}}} -location {{{v[0]:.4f} {v[1]:.4f}}} -orientation {v[2] if len(v) > 2 else 'R0'}"
                    " -exact\n" for i, v in sorted(mp.items())))
        cfg.append("export MACRO_PLACEMENT_TCL = /work/macro_place.tcl")
    (kd / "config.mk").write_text("\n".join(cfg) + "\n")
    rec_sha = hashlib.sha256(json.dumps(rec, sort_keys=True).encode()).hexdigest()
    try:
        tool_rev = subprocess.run(["git", "-C", str(TOOL), "rev-parse", "--short", "HEAD"], capture_output=True,
                                  text=True).stdout.strip()
    except Exception:
        tool_rev = "?"
    fz = dict(schema="opentallas.s81.core_freeze.v1", type=a.type, module=c["module"], top=rec.get("top", c["module"]),
              outline_um=[w, h], plan_commit=a.plan_commit, plan_sha256=sha(a.plan),
              pins_file=c["pins_file"], pins_sha256=sha(plandir / c["pins_file"]), cores_sha256=sha(a.cores), pins=len(pins),
              clocks=clks, resets=rsts, recipe_sha256=rec_sha, tool=f"{TOOL}@{tool_rev}",
              period_ps=per, insertion_budget_ps=ins, signal_max=a.sigmax, macros=rec.get("macros", []),
              pins_pending=pins_pending, kit_hash=kit_hash(kd))
    (kd / "freeze.json").write_text(json.dumps(fz, indent=1) + "\n")
    print(json.dumps(dict(kit=str(kd), pins=len(pins), clocks=clks, resets=rsts, kit_hash=fz["kit_hash"])))


if __name__ == "__main__":
    main()
