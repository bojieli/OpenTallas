#!/usr/bin/env python3
"""S81 plan event 2026-10-27 (S81-CORES-R26, COORD add-on: regenerate the held HCPL kit on main): project the 174
off-face ot_dsrom_su_hcpost_lane_pr plan pin centres onto their outline face.

Why: the modern gen_core_kit_legacy (no implicit projection) refuses HCPL: 174/277 plan centres sit 0.02-1.24 um
inside the N face (access-extension centres from the 10-23 extraction, e.g. c0[0] y 113.24 on a 114.48 outline).
The Codex shift-clock trial kit (codex/hcpl-shiftclk-2144@6599f6761a) was generated by the older generator, which
projected exactly these 174 pins onto the face ("174 pins snapped"); its measured GRT cohort used those positions.

Rule (= gen_core_kit_legacy.planned_pin_geometry projection, made explicit in the plan): x (along the face) is kept,
the perpendicular coordinate becomes the canonical face position of the pin's layer shape (RECT M3 0.018 x 0.038,
M5 0.024 x 0.084).  For 168 pins the new centre IS the centre of the pin's existing outline-face PORT RECT in the
LEF; for 6 pins (c0[2] c1[4] c2[2] c2[6] c3[2] p[28]) the plan x differs from the ref-tile LEF RECT x by 0.036-0.108
um (plan re-pinned after the LEF extraction); the plan x is kept (it is the pin contract and what the trial kit
placed), recorded in the delta json as lef_rect_dx_um.  All 277 new centres == the Codex kit io.tcl (CHECKED at
build).  Plan-only: LEF byte-identical, no body/clock/latency change.

Fail-closed: base pin-file sha256, LEF sha256, each pin old centre + layer, new centre = canonical face position
(x kept), recorded LEF RECT offset.  pinhash recomputed as in delta_kitsspare2_1025.py; the file's own
serialisation is kept (delta_ninepins_1027.FORMATS).

  python3 physical/die_plan/s81/delta_hcplpins_1027.py [--check]
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from delta_ninepins_1027 import FORMATS, PINS, EPS, lef_port_rects, lef_text  # noqa: E402

DELTA = HERE / "delta_hcplpins_1027.json"
TAG = "S81-CORES-R26"
SHAPE = {"M3": (0.018, 0.038), "M4": (0.084, 0.024), "M5": (0.024, 0.084)}   # == gen_core_kit_legacy.RECT


def face_pos(p, w, h):
    sw, sh = SHAPE[p["layer"]]
    x, y = p["x"], p["y"]
    d = {"W": x, "E": w - x, "S": y, "N": h - y}
    f = min(d, key=d.get)
    return f, {"W": [sw / 2, y], "E": [w - sw / 2, y], "S": [x, sh / 2], "N": [x, h - sh / 2]}[f]


def apply(check_only=False):
    delta = json.loads(DELTA.read_text())
    out = []
    for core in delta["cores"]:
        mod = core["module"]
        f = PINS / f"{mod}.json"
        raw = f.read_bytes()
        fmt = next((k for k in FORMATS if FORMATS[k](json.loads(raw)) == raw.decode()), None)
        if fmt is None:
            raise SystemExit(f"{mod}: unknown pin-table serialisation (refusing to reformat)")
        cur = hashlib.sha256(raw).hexdigest()
        d = json.loads(raw)
        lefb = lef_text(d["lef"])
        if hashlib.sha256(lefb).hexdigest() != core["base_lef_sha256"]:
            raise SystemExit(f"{mod}: LEF {d['lef']} differs from the delta base (no LEF move allowed)")
        lef = lefb.decode()
        w, h = core["outline_um"]
        by = {p["name"]: p for p in d["pins"]}
        done = all([by[m["pin"]]["x"], by[m["pin"]]["y"]] == m["new_center_um"] for m in core["pins"])
        if not done and cur != core["base_pins_sha256"]:
            raise SystemExit(f"{mod}: pin table changed since the delta base ({cur[:12]})")
        for m in core["pins"]:
            p = by[m["pin"]]
            if p["layer"] != m["layer"]:
                raise SystemExit(f"{mod}.{m['pin']}: layer {p['layer']} != {m['layer']}")
            if not done and [p["x"], p["y"]] != m["old_center_um"]:
                raise SystemExit(f"{mod}.{m['pin']}: old centre {[p['x'], p['y']]} != {m['old_center_um']}")
            fc, c = face_pos(dict(p, x=m["old_center_um"][0], y=m["old_center_um"][1]), w, h)
            c = [round(v, 4) for v in c]
            if any(abs(a - b) > EPS for a, b in zip(c, m["new_center_um"])) or fc != m["face"]:
                raise SystemExit(f"{mod}.{m['pin']}: new centre {m['new_center_um']} != canonical {fc} face {c}")
            rs = [r for r in lef_port_rects(lef, m["pin"], m["layer"])
                  if min(abs(r[0]), abs(r[1]), abs(r[2] - w), abs(r[3] - h)) < EPS]
            if len(rs) != 1:
                raise SystemExit(f"{mod}.{m['pin']}: expected one outline-face PORT RECT, LEF has {rs}")
            r = rs[0]
            dx = round((r[0] + r[2]) / 2 - c[0], 4) if fc in "NS" else round((r[1] + r[3]) / 2 - c[1], 4)
            if abs(dx - m["lef_rect_dx_um"]) > EPS:
                raise SystemExit(f"{mod}.{m['pin']}: LEF RECT offset {dx} != recorded {m['lef_rect_dx_um']}")
            p["x"], p["y"] = m["new_center_um"]
        d["pinhash"] = hashlib.sha256(json.dumps(d["pins"], sort_keys=True).encode()).hexdigest()[:12]
        if TAG not in d["source"]:
            d["source"] += (f"; S81 plan event 2026-10-27 {TAG} (delta_hcplpins_1027.py): {len(core['pins'])} pin "
                            "centre(s) projected onto the outline face (x kept), LEF unchanged")
        out.append((mod, len(core["pins"]), "already applied" if done else "applied"))
        if not check_only and not done:
            f.write_text(FORMATS[fmt](d))
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only, write nothing")
    for row in apply(ap.parse_args().check):
        print(*row)
