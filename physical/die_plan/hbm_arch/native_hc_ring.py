"""Native W128 HC ring geometry; exact pair cuts retained with shared pin templates.

This is an opt-in plan transformation. Its output still needs the full plan gates,
actual-bit FT audit, geometry review and native binder integration.
"""
import copy
import json
from pathlib import Path

PAIR_WH = (250.56, 267.84)
ROW_PITCH = 302.4
BANK_H = 1209.6
HALO = 8.64
TOP = ("q_b003", "q_b002", "q_b001", "q_b000")
BOTTOM = ("q_b013", "q_b012", "q_b011", "q_b010")

def apply(plan, out, inputs, log):
    out, inputs = Path(out), Path(inputs)
    T = plan["partition_types"]
    parts = {p["name"]: p for p in plan["partitions"]}
    # Reuse exactly the existing ring rectangle; no die-area expansion.
    old = [parts["NW_" + tn[2:]] for tn in TOP + BOTTOM]
    x0 = min(p["origin_um"][0] for p in old)
    x1 = max(p["origin_um"][0] + T[p["type"]]["outline_um"][0] for p in old)
    y0 = min(p["origin_um"][1] for p in old)
    total_w = round(x1 - x0, 4)
    # The existing rectangle is lattice aligned but may not divide into four
    # equal lattice cells. Give the final column the remainder.
    grid = 8.64
    col_w = int(total_w / 4 / grid) * grid
    widths = [round(col_w, 4)] * 3 + [round(total_w - 3 * col_w, 4)]
    if min(widths) < 2 * PAIR_WH[0] + 3 * HALO:
        raise ValueError("native ring cannot fit two pair columns and channels")
    if abs(max(p["origin_um"][1] + T[p["type"]]["outline_um"][1] for p in old)-y0-2*BANK_H) > 0.01:
        raise ValueError("native ring expects the 2419.2-um Rh row")
    connections = json.loads((inputs / "native_pair_connections.json").read_text())
    master_file = {}
    for first, src in ((False, "native_pair_pins.json"), (True, "native_first_pair_pins.json")):
        mod = "ot_hbm_hc_bank128_pair_" + ("first_core" if first else "core")
        rel = f"cores/{mod}__250.56x267.84.json"
        (out / "cores").mkdir(exist_ok=True)
        (out / rel).write_text((inputs / src).read_text())
        master_file[first] = (mod, rel)
    manifest = {"schema": "opentallas.native_hc_ring.v1", "scope": "PLAN_CANDIDATE",
                "die_area_delta_um2": 0, "rtl_cycle_delta": 0, "bank_rows": [],
                "pair_connections": connections, "binder_adoption": "REQUIRED"}
    for row, names in enumerate((BOTTOM, TOP)):
        xx = x0
        for col, tn in enumerate(names):
            t = T[tn]
            parent = next(c for c in t["contents"] if c["inst"].startswith("u_hcb_"))
            style = {"ot_hbm_hc_bankq0_static":"first_norst", "ot_hbm_hc_bankq_static":"plain_norst",
                     "ot_hbm_hc_bankq_ft_static":"feed_norst", "ot_hbm_hc_bankq_term_static":"term_norst"}[parent["module"]]
            mp = connections[style]
            if len(mp["pairs"]) != 8:
                raise ValueError(f"{tn}: native composition must contain eight exact pair cuts")
            ww = widths[col]
            t["outline_um"] = [ww, BANK_H]
            # Pair columns leave a broad central vertical station/control
            # corridor and outer access bands. All eight replicas use one
            # physical pin template. Top row mirrors the chain direction.
            xsites = [34.56, round(ww - 34.56 - PAIR_WH[0], 4)]
            orient = "MY" if row else "R0"
            cores = []
            for i, (cutname, cell) in enumerate(sorted(mp["pairs"].items())):
                first = style == "first_norst"
                mod, pf = master_file[first]
                if cell["type"] != mod:
                    raise ValueError(f"{tn}: native cut {cutname} master {cell['type']} != {mod}")
                cores.append(dict(inst=parent["inst"]+"_"+cutname, module=mod,
                    origin_um=[xsites[i//4], round(17.28+(i%4)*ROW_PITCH,4)],
                    outline_um=list(PAIR_WH), orient=orient, track_offset_um=[0.0,0.0], pins_file=pf,
                    native_connection_key=f"{style}:{cutname}", native_hierarchy=parent["inst"]+"."+cutname,
                    note="Exact native W128 pair cut; shared RTL master and pin table; control glue remains in parent"))
            t["hard_cores"] = cores
            t["clock"]["taps"] = []  # rebuilt from the actual new core terminals below
            t["clock"].pop("core_taps", None)
            parent["origin_um"] = [0.0,0.0]
            parent["outline_um"] = [ww,BANK_H]
            parent["note"] = "Native W128 compact parent: eight exact pair cuts plus retained control glue; binder adoption required"
            for side in ("NW_", "NE_"):
                pn = side+tn[2:]
                p = parts[pn]
                p["origin_um"][1] = round(y0 + row*BANK_H,4)
                p["origin_um"][0] = round(xx if side=="NW_" else plan["die"]["outline_um"][0]-xx-ww,4)
            # Soft reset entry remains at a legal external band. Pin paths
            # and new local clock taps are regenerated by the normal tools.
            t["clock"]["tap_um"] = [round(ww/2,4),17.28]
            t["reset"]["tap_um"] = [round(ww/2,4),8.64]
            manifest["bank_rows"].append(dict(type=tn, style=style, width_um=ww,height_um=BANK_H,
                row=row,col=col,pairs=8,orientation=orient,
                horizontal_channels_um=[17.28,34.56,34.56,34.56,17.28],
                central_channel_um=round(xsites[1]-xsites[0]-PAIR_WH[0]-2*HALO,4)))
            xx += ww
    # Kept core clock terminals are interfaces, not invented soft tap sites.
    import b2o
    import schema as S
    P = S.Plan(plan)
    for row in manifest["bank_rows"]:
        tn = row["type"]
        t = T[tn]
        t["clock"]["core_taps"] = "early"
        for c in t["hard_cores"]:
            pins = json.loads((out / c["pins_file"]).read_text())
            if c.get("orient", "R0") != "R0":
                offset = b2o.flip_track_offset(P, c, pins, [n for n,p in P.parts.items() if p["type"]==tn])
                if offset is None:
                    raise ValueError(f"{tn} {c['inst']}: mirrored native pins have no legal track offset")
                c["track_offset_um"] = offset
            pin = next(q for q in pins if q["name"]=="clk")
            px,py = pin["x"],pin["y"]
            if c.get("orient")=="MY":
                px=c["outline_um"][0]-px
            ox,oy=c["origin_um"]; dx,dy=c["track_offset_um"]
            t["clock"]["taps"].append(dict(name=c["inst"]+".clk",kind="core",
                xy=[round(ox+px+dx,4),round(oy+py+dy,4)],insertion_ps=250,
                budget_owner=c["module"],note="250ps common clock budget; native physical insertion measurement required"))
    (out / "native_hc_ring.json").write_text(json.dumps(manifest,indent=1)+"\n")
    log.append(f"native W128 HC ring: 2 x 4 direct-neighbour banks in unchanged {total_w:g}x2419.2 rectangle; each bank 2 x 4 exact pair cuts; binder adoption required")
    return manifest
