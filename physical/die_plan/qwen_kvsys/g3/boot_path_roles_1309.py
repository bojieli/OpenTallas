#!/usr/bin/env python3
"""Fold the actual KV boot/config/ACK audit into one per-die plan delta.

The audit is generated by kv_bootstrap_audit.py from actual native source.
This sets logical reset roles only: delivered wavefront/private stages stay,
and HOST mission admission must independently use its registered START.
"""
import argparse
import json
from pathlib import Path


def apply(raw, audit):
    types = raw['partition_types']
    parts = {p['name']: p for p in raw['partitions']}
    bootstrap = set(audit['bootstrap_types'])
    if audit['ack_count'] != 160 or audit['unique_ack_endpoints'] != 160:
        raise ValueError('KV boot audit must trace all 160 distinct applied ACK endpoints')
    if len(audit['ack_endpoints']) != 160:
        raise ValueError('incomplete ACK receipt')
    if bootstrap - types.keys():
        raise ValueError('audit refers to missing types: ' + str(sorted(bootstrap - types.keys())))
    if set(audit['bootstrap_parts']) - parts.keys():
        raise ValueError('audit refers to missing partitions')
    for name in audit['bootstrap_parts']:
        if parts[name]['type'] not in bootstrap:
            raise ValueError(f'audited part {name} has no uniform bootstrap type role')
    for endpoint in audit['ack_endpoints']:
        if endpoint['part'] not in audit['bootstrap_parts']:
            raise ValueError('ACK endpoint is not included in the audited boot closure')
    for name in bootstrap:
        types[name].setdefault('reset', {})['start_role'] = 'bootstrap'
    raw['reset']['start'] = 'broadcast'
    raw['reset']['start_port'] = 'mission_start_global'
    # Functional PHY service roles; these are not physical serialized bumps.
    # Explicit physical-only projection must preserve the seven real FDI ports.
    phy = [c for c in types['kv3_sys_c'].get('contents', [])
           if c['inst'] in ('ucie_rom', 'u_bound.u_ucie_rom') and c['module'] == 'ot_qkvd_ucie_x64_phy']
    if len(phy) != 1:
        raise ValueError('expected exactly one canonical SYS_C UCIe PHY')
    phy[0]['bump_ports'] = [
        dict(pin='link_v', dir='output', width=1),
        dict(pin='link_flit', dir='output', width=583),
        dict(pin='far_v', dir='input', width=1),
        dict(pin='far_flit', dir='input', width=583),
    ]
    return dict(bootstrap_types=sorted(bootstrap), bootstrap_parts=len(audit['bootstrap_parts']),
                actual_ack_endpoints=160, data_cycles_added=0,
                start_port='mission_start_global', behavioral_service_roles=phy[0]['bump_ports'], physical_bumps_added=0,
                host_mission_gate_required=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('plan')
    ap.add_argument('audit')
    ap.add_argument('out')
    ap.add_argument('--report', required=True)
    a = ap.parse_args()
    raw = json.loads(Path(a.plan).read_text())
    report = apply(raw, json.loads(Path(a.audit).read_text()))
    Path(a.out).write_text(json.dumps(raw, indent=1) + '\n')
    Path(a.report).write_text(json.dumps(report, indent=1) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
