#!/usr/bin/env python3
"""Match planned HR clock pins to the native host wrappers (BRIEFING 16a).

Only clock pins change. Data pins retain their name, layer and coordinate.
The provided *_core.json files are generated by kv_core_rtl.py --hr-elab;
ck_phy exists only in the PHY adapters/pad and the PHY-edge cdc_pc core.
This is a planned pin update, not physical signoff or adoption of data ties.
"""
import argparse
import json
import re
from pathlib import Path

OLD = {
    'cdc_ch': ['u_done__rclk', 'u_done__wclk', 'u_ing__rclk', 'u_ing__wclk'],
    'cdc_ci': ['u_ox__rclk', 'u_ox__wclk', 'u_rx__rclk', 'u_rx__wclk'],
    'cdc_hi': ['u_cx__rclk', 'u_cx__wclk', 'u_hx__rclk', 'u_hx__wclk'],
    'cdc_pc': ['u_rx__rclk', 'u_rx__wclk', 'u_tx__rclk', 'u_tx__wclk'],
    'core_guard': ['u_guard__ck_guard', 'u_native__ck'],
    'core_order': ['u_chain__ck_map', 'u_chain__ck_order', 'u_chain__ck_sum', 'u_dispatch__ck', 'u_dispatch__ck_order'],
    'core_peer': ['u_coordinator__ck_codec', 'u_coordinator__ck_lifecycle', 'u_coordinator__ck_post', 'u_peer__ck', 'u_peer_codec__ck', 'u_root_mux__ck'],
    'core_prompt': ['u_control__ck_csr', 'u_control__ck_ctl', 'u_control__ck_host', 'u_control__ck_prompt', 'u_control__ck_rst', 'u_program__ck', 'u_program_rx__ck', 'u_records__ck'],
    'core_queue': ['u_bootbarrier__ck', 'u_marker_consumer__ck', 'u_queue__ck'],
    'core_tx': ['u_axi__ck', 'u_ctrl__ck', 'u_tx__ck'],
    'host_qm': ['clk_h'], 'ingest_eng': ['clk', 'clk_bank', 'clk_out'],
    'phy_adp': ['ck'], 'phy_pad': ['clk'], 'core_rx': ['ck'],
}


def base(name):
    return re.sub(r'\[\d+\]$', '', name)


def update(plan, meta_dir, report):
    plan = Path(plan)
    raw = json.loads(plan.read_text())
    cores = plan.parent / 'cores'
    modules = {c['module']: c for c in raw['partition_types']['kv3_hub_Wi']['hard_cores']}
    records = []
    updates = []
    for short, old in OLD.items():
        module = 'qkd_hr_' + short
        hc = modules[module]
        meta = json.loads((Path(meta_dir) / module / (module + '_core.json')).read_text())
        clocks = meta['clocks']
        if any(x not in ('ck', 'ck_phy') for x in clocks):
            raise ValueError(f'{module}: unexpected native clocks {clocks}')
        if 'ck_phy' in clocks and short not in ('cdc_pc', 'phy_adp', 'phy_pad'):
            raise ValueError(f'{module}: PHY clock outside the PHY boundary')
        fn = cores / Path(hc['pins_file']).name
        pins = json.loads(fn.read_text())
        oldpins = [p for p in pins['pins'] if base(p['name']) in old]
        actual = {base(p['name']) for p in oldpins}
        if actual != set(old):
            raise ValueError(f'{module}: old clock mismatch {actual} vs {set(old)}')
        data = [p for p in pins['pins'] if base(p['name']) not in old]
        before = json.dumps(data, sort_keys=True)
        w, h = hc['outline_um']
        used = {(p['layer'], round(p['x'], 6), round(p['y'], 6)) for p in data}
        newpins = []
        for j, clock in enumerate(clocks):
            # N-face centre, M5 signal tracks. A displaced old clock on a
            # data face is not retained as the entry of the new core tree.
            x0 = 0.024 + round((w / 2 - 0.024) / 0.048) * 0.048
            for k in range(100):
                x = round(x0 + (j * 2 + k * 2) * 0.048, 6)
                key = ('M5', x, h)
                if key not in used and x < w - 2.16:
                    used.add(key)
                    newpins.append(dict(name=clock + '[0]', layer='M5', x=x, y=h))
                    break
            else:
                raise ValueError(f'{module}: no free clock track at N-face centre')
        pins['pins'] = data + newpins
        assert json.dumps([p for p in pins['pins'] if base(p['name']) not in clocks], sort_keys=True) == before
        pins['source'] = pins.get('source', '') + ' | native HR clocks from kv_core_rtl.py --hr-elab, data pins unchanged'
        updates.append((fn, pins))
        records.append(dict(module=module, old=sorted(actual), clocks=clocks,
                            pins_before=len(data) + len(oldpins), pins_after=len(data) + len(newpins),
                            data_pins_unchanged=True, constant_input_bits_unreviewed=meta.get('const_input_bits', 0)))
    for fn, pins in updates:
        fn.write_text(json.dumps(pins, indent=1) + '\n')
    Path(report).write_text(json.dumps(dict(source='claude/kv-core-rtl-hr-1025@591ac8caed', cores=records), indent=1) + '\n')
    print(f'HR native clock pins: {len(records)} cores, all data pin tables unchanged')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('plan')
    ap.add_argument('--meta-dir', required=True)
    ap.add_argument('--report', required=True)
    a = ap.parse_args()
    update(a.plan, a.meta_dir, a.report)


if __name__ == '__main__':
    main()
