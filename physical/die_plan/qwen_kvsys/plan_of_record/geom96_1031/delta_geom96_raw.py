#!/usr/bin/env python3
"""DIE-KV-58 10-31 step 2 (GEOM-93 r2r raw-reset part): add clock.landing_raw_branches (FE3 literal same-depth copies
of the original raw-reset relay chain; generated by raw_branches_gen.py from a strict bind of the step-1 plan) to
kv3_io_ft / kv3_io_ft_v1 / kv3_hroot, so the count origin and every FSTART face flop take a raw reset released next to
them instead of the E-bank tap rst_n_t15 / rst_n_t11 (kit u_rrl_5 -> u_cland_origin 979 um, -> fstart 1531 um).
Unchanged (asserted): everything else.  usage: delta_geom93b_raw.py PLAN_IN RAWBR.json PLAN_OUT"""
import copy, json, re, sys

TYPES = ("kv3_io_cor",)


def _fmt(x):
    return json.dumps(x, indent=1).replace("\n", "\n  ")


def main():
    src, rb, dst = sys.argv[1:4]
    text = open(src).read()
    raw = json.loads(text)
    orig = copy.deepcopy(raw)
    br = json.load(open(rb))
    for tn in TYPES:
        ck = raw["partition_types"][tn]["clock"]
        assert "landing_raw_branches" not in ck, tn
        ck["landing_raw_branches"] = br[tn]["branches"]
    for tn in raw["partition_types"]:
        x = copy.deepcopy(raw["partition_types"][tn])
        x.get("clock", {}).pop("landing_raw_branches", None) if tn in TYPES else None
        assert x == orig["partition_types"][tn], tn
    assert {k: v for k, v in raw.items() if k != "partition_types"} == {k: v for k, v in orig.items() if k != "partition_types"}
    for tn in TYPES:
        m = re.search(r'^  "' + re.escape(tn) + r'": ', text, re.M)
        _, j = json.JSONDecoder().raw_decode(text, m.end())
        text = text[:m.end()] + _fmt(raw["partition_types"][tn]) + text[j:]
    assert json.loads(text) == raw
    open(dst, "w").write(text)
    for tn in TYPES:
        print(tn, "raw branches", len(br[tn]["branches"]), "copies", sum(len(b["stages"]) for b in br[tn]["branches"]))


if __name__ == "__main__":
    main()
