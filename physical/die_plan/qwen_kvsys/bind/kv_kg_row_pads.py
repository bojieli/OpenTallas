#!/usr/bin/env python3
"""BINDER4 10-23 (COORD 20:38 KV rulings): kg row landing pads for the KV v3.6 bind (KV-P5 rule 'row start (o_kg
broadcast) per-row skew': one o_kg word per stack, type-parameter ECTL frames -> every row must see the same
Delta = landed - as-built; pad each row's kg landing up to the stack max).

    python3 kv_kg_row_pads.py PASS_A_BIND_DIR R8_TABLE OUT.json

Reads PASS_A/bus_groups.json (landing members, landed_stages incl. the r8 + PV-entry pads of pass a) and writes an
asbuilt.land_r8_extra table (r8 member schema, authoritative per id): every member sourced by kvs_hroot_<st>.o_kg gets
pad = (landed - bound) + (stack max Delta - row Delta).  RH a/b (the other KV-P6 item) is checked and reported only."""
import collections
import json
import re
import sys
from pathlib import Path


def rid(sink, m):
    """the r8 member id (r8.py): sink.port[lo:hi,...]<-source@as-built"""
    bits = ",".join(f"{a}:{b}" for a, b in m["sink_bits"])
    return f"{sink}.{m['sink_port']}[{bits}]<-{m['source']}@{m['asbuilt_stages']}"


def main(bind, r8_f, out_f):
    L = json.loads((Path(bind) / "bus_groups.json").read_text())["landing"]
    r8 = {m["id"]: m for m in json.loads(Path(r8_f).read_text())["members"]}
    rows = collections.defaultdict(lambda: collections.defaultdict(set))
    mem = []
    for g in L:
        for m in g["members"]:
            s = re.fullmatch(r"kvs_hroot_(\w\w)\.o_kg", m["source"])
            if s:
                d = m["landed_stages"] - m["asbuilt_stages"]
                rows[s.group(1)][g["sink_part"]].add(d)
                mem.append((g, m, s.group(1), d))
    bad = {f"{st}:{p}": sorted(v) for st, r in rows.items() for p, v in r.items() if len(v) != 1}
    if bad:
        raise SystemExit(f"kg rows with several Deltas (one row = one Delta expected): {bad}")
    mx = {st: max(next(iter(v)) for v in r.values()) for st, r in rows.items()}
    out, flops, known = [], 0, 0
    for g, m, st, d in mem:
        add = mx[st] - d
        i = rid(g["sink"], m)
        known += i in r8
        pad = m["landed_stages"] - m["bound_stages"] + add
        out.append(dict(id=i, sink=g["sink"], sink_part=g["sink_part"], src_part=g["src_part"], sink_port=m["sink_port"],
                        sink_bits=m["sink_bits"], source=m["source"], asbuilt=m["asbuilt_stages"], bound=m["bound_stages"],
                        pad=pad, landed=m["bound_stages"] + pad, lane=m["lane"], kg_row_pad=add))
        flops += add * sum(b - a + 1 for a, b in m["source_bits"])
    spread = {st: {p: next(iter(v)) for p, v in sorted(r.items())} for st, r in rows.items()}
    doc = dict(schema="opentallas.die_plan.r8_landing_extra.v1", die="qwen_kvsys",
               note="GENERATED by kv_kg_row_pads.py (BINDER4 10-23): kg row pads to the stack max Delta (KV-P5 rule)",
               pass_a=str(bind), summary=dict(members=len(out), r8_ids=known, stack_max_delta=mx, row_delta=spread,
                                               kg_pad_flops_per_member_bits=flops), members=out)
    Path(out_f).write_text(json.dumps(doc, indent=1) + "\n")
    print(json.dumps(doc["summary"]))


if __name__ == "__main__":
    main(*sys.argv[1:4])
