#!/usr/bin/env python3
"""KV-P8 10-23: vport W request-lane pads for the KV kv42 re-bind (KV-P7 23:00 finding A).

The KV boot generator (boot_v36, authoritative for PV RL / cfg_fia / DQ, KV owner) needs DQ <= 15 on every vport (RTL
bound of qkd_pv16_vport_b).  On kv41 the *_1 / *_3 vports exceed it, so the W request lane (pvw_<p>__u_ctl.req_t /
req_valid -> vport_<v>.pr_t / pr_valid, 14 + 1 b) needs pad_stages[v] extra stages: boot_v36/image_kv41/
vport_dq_pads.json (= prep/vport_dq_pads.json of the kv41 boot run).  This writes them as an r8 landing-extra table
(schema opentallas.die_plan.r8_landing_extra.v1, the bind's asbuilt.land_r8_extra): one member per R8 member of those
lanes, pad = pad_stages, landed = bound + pad (the R8 table pads them 0).
    python3 kv_vport_w_pads.py [PADS.json] [OUT.json]
"""
import hashlib
import json
import sys
from pathlib import Path

H = Path(__file__).resolve().parent
PADS = Path(sys.argv[1]) if len(sys.argv) > 1 else H.parent / "boot_v36" / "image_kv41" / "vport_dq_pads.json"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else H / "kv_vport_w_pads_v36.json"
R8 = H.parent / "r8" / "qwen_kvsys_r8_landing.json"

pads = json.loads(PADS.read_text())
r8 = json.loads(R8.read_text())
mem, flops = [], 0
for m in r8["members"]:
    if not (m["sink"].startswith("vport_") and m["sink_port"] in ("pr_t", "pr_valid")
            and m["source"].endswith(("u_ctl.req_t", "u_ctl.req_valid"))):
        continue
    p = pads["pad_stages"][m["sink"]]
    if m["pad"]:
        raise SystemExit(f"{m['id']}: R8 already pads it ({m['pad']}); merge rule undefined")
    bits = sum(b - a + 1 for a, b in m["sink_bits"])
    mem.append(dict(m, pad=p, landed=m["bound"] + p, w_req_pad=p))
    flops += bits * p
vp = {m["sink"] for m in mem}
if vp != set(pads["pad_stages"]) or len(mem) != 2 * len(vp):
    raise SystemExit(f"vport coverage: {sorted(vp)} / {len(mem)} members vs {sorted(pads['pad_stages'])}")
if flops != pads["pad_flops"]:
    raise SystemExit(f"pad flops {flops} != boot {pads['pad_flops']}")
doc = dict(schema="opentallas.die_plan.r8_landing_extra.v1", die="qwen_kvsys",
           note="GENERATED by kv_vport_w_pads.py (KV-P8 10-23): vport W request-lane pads from the KV boot generator "
                "(KV-P7 23:00 A; boot image authoritative, KV owner)",
           source=dict(pads=str(PADS.relative_to(H.parent)) if PADS.is_relative_to(H.parent) else str(PADS),
                       pads_sha=hashlib.sha256(PADS.read_bytes()).hexdigest()[:16],
                       r8=str(R8.relative_to(H.parent)), r8_sha=hashlib.sha256(R8.read_bytes()).hexdigest()[:16]),
           summary=dict(members=len(mem), vports=len(vp), pad_flops=flops, pad_stages=pads["pad_stages"]),
           members=sorted(mem, key=lambda m: m["id"]))
OUT.write_text(json.dumps(doc, indent=1) + "\n")
print(f"{OUT.name}: {len(mem)} members, {flops} pad flops, max pad {max(m['pad'] for m in mem)}")
