#!/usr/bin/env python3
"""KV-BIND 10-24: the kv42 PV W request-lane pads (KV-TOK kv_pv_wreq_pads.py, a post-bind edit on kv41) as a NATIVE bind
input: an asbuilt.land_r8_extra table in the r8 member schema, so bind.py lands the pad stages itself (ot_dp_dly after the
sink partition's in boundary flop) and records them in bus_groups / bind_latency.

    kv_wreq_r8_extra.py PASS_B_BIND_DIR R8_TABLE WREQ_PADS.json OUT.json [EXTRA_TABLE ...]

WREQ_PADS = tables/vport_dq_pads_kv44.json (kv_wreq_dq44.py: kv41 boot DQ re-derived for the v3.8x RT; pad_stages) or
bound_kv42/wreq_pads.json (the kv41 values).
The kv44 pads differ from kv42: plan v3.8x lengthens slg <-> vport lanes (RT +1/+2), see kv_wreq_dq44.py.  pad = (r8 / extra-table pad of that id) + wreq stages."""
import json, sys
from pathlib import Path

B, R8, WP, OUT = sys.argv[1:5]
extras = sys.argv[5:]
r8 = {m["id"]: m for m in json.load(open(R8))["members"]}
for x in extras:
    r8.update({m["id"]: m for m in json.load(open(x))["members"]})
W_ = json.load(open(WP))
pads = ({p["vport"]: p["stages"] for p in W_["pads"]} if "pads" in W_ else
        {k: v for k, v in W_["pad_stages"].items() if v > 0})
mem, seen = [], {}
for g in json.load(open(Path(B) / "bus_groups.json"))["landing"]:
    if g["sink"] not in pads:
        continue
    for m in g["members"]:
        if m["sink_port"] not in ("pr_t", "pr_valid"):
            continue
        bits = ",".join(f"{a}:{b}" for a, b in m["sink_bits"])
        i = f"{g['sink']}.{m['sink_port']}[{bits}]<-{m['source']}@{m['asbuilt_stages']}"
        base = r8.get(i)
        p0 = base["pad"] if base else 0
        st = pads[g["sink"]]
        mem.append(dict(id=i, sink=g["sink"], sink_part=g["sink_part"], src_part=g["src_part"], sink_port=m["sink_port"],
                        sink_bits=m["sink_bits"], source=m["source"], asbuilt=m["asbuilt_stages"], bound=m["bound_stages"],
                        pad=p0 + st, landed=m["bound_stages"] + p0 + st, lane=m["lane"], wreq_pad=st, r8_pad=p0))
        seen[f"{g['sink']}.{m['sink_port']}"] = m["bound_stages"]
miss = [(v, p) for v in pads for p in ("pr_t", "pr_valid") if f"{v}.{p}" not in seen]
if miss:
    sys.exit(f"missing W request members {miss}")
flops = sum(sum(b - a + 1 for a, b in m["sink_bits"]) * m["wreq_pad"] for m in mem)
doc = dict(schema="opentallas.die_plan.r8_landing_extra.v1", die="qwen_kvsys",
           note="GENERATED by kv44/kv_wreq_r8_extra.py: kv42 PV W request-lane pads as a native land_r8_extra table",
           source=WP, summary=dict(members=len(mem), wreq_pad_flops=flops, pads=pads, bound=seen), members=mem)
json.dump(doc, open(OUT, "w"), indent=1)
print(json.dumps(doc["summary"]))
