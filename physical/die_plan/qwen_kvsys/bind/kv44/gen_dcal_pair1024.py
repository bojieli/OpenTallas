#!/usr/bin/env python3
"""KV-BIND 10-24 (TOK-QK request KV-R4): the KV dcal tile qkd_d2d_cal_seq_pin_bc4 on the matching pair image
results/rtl/qwen_rom_pair_candidate_1024/d2d_cal_image.svh (period 293,376; seam C 0a010308 / K 03030443) instead of the
rtl6 image (kv41 bound qkd_d2d_cal_seq_bc4.sv = d2d_cal_image_mu.svh, the later `prefer` entry; mu period 249,600, stale per
TOK-QK).  Same module, ports and edges as the
as-built file rtl/qwen_sys/d2d_static_20261015/qkd_d2d_cal_seq_bc4_ew595_r16.sv (e33504a6f): only the `include is
replaced, and the image is inlined so no include path is needed in bind / lint / kit flows.

    gen_dcal_pair1024.py SRC_TREE OUT.sv      (SRC_TREE = e33504a6f tree + main results/rtl/qwen_rom_pair_candidate_1024)
"""
import hashlib, sys
from pathlib import Path
src, out = Path(sys.argv[1]), Path(sys.argv[2])
f = src / 'rtl/qwen_sys/d2d_static_20261015/qkd_d2d_cal_seq_bc4_ew595_r16.sv'
img = src / 'results/rtl/qwen_rom_pair_candidate_1024/d2d_cal_image.svh'
t = f.read_text()
inc = '`include "d2d_cal_image_mu_ew595_r16.svh"'
assert t.count(inc) == 1, 'include not found exactly once'
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
body = img.read_text().rstrip('\n')
assert 'D2D_TXDP_K' in body and "32'h03030443" in body.replace(' ', ''), 'pair image TXDP_K is not 03030443'
hdr = (f'// GENERATED by physical/die_plan/qwen_kvsys/bind/kv44/gen_dcal_pair1024.py (KV-R4): {f.name} (sha256 {sha(f)[:16]})\n'
       f'// with its image include replaced by results/rtl/qwen_rom_pair_candidate_1024/d2d_cal_image.svh (sha256 {sha(img)[:16]}).\n')
out.write_text(hdr + t.replace(inc, '// ---- inlined d2d_cal_image.svh (pair candidate 1024) ----\n' + body + '\n// ---- end image ----'))
print('wrote', out)
