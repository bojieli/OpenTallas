#!/usr/bin/env python3
"""BINDER4 10-23: KV-P6-V37 PV entry-pad table (@0ec5c902d kv_pv_entry_pads_v36.json) -> an asbuilt.land_r8_extra table
in the r8 member schema that tools/die_plan/bind.py applies (authoritative per id, INNER:<part>: = intra delays).

    python3 kv_pv_entry_to_r8.py ENTRY.json R8_TABLE.json OUT.json

* every covered id (3,100; pad 0 included) becomes one member: pad = its entry's pad (the shared delay on the sink
  partition input port; 0 if no entry covers it) + its residual member pad (table.members, pad = total - entry_pad).
  The record (sink, ports, bits, source, as-built, bound) is the table member's, else the r8 member's of that id.
  bind.py lands pads per crossing bit and shares one pad chain per (link bit, pad), so an entry pad shared by several
  sink members of one port bit is realised once per distinct total -- cycle-identical to the entry delay line.
* inner (128): INNER:<part>:<sink>.<port><-<source>@<old_D> with landed = new_D (bind.py _apply_inner re-sizes that
  edge per sink, so the two pv_N_7 ot_dp_dly that feed two new depths split per sink by construction).
* params are carried for the param_regen hook (kv_regen36e.py)."""
import hashlib
import json
import sys
from pathlib import Path


def main(entry_f, r8_f, out_f):
    T = json.loads(Path(entry_f).read_text())
    R = json.loads(Path(r8_f).read_text())
    rm = {m["id"]: m for m in R["members"]}
    tm = {m["id"]: m for m in T["members"]}
    ent = {}
    for e in T["entries"]:
        for i in e["covers"]:
            assert i not in ent, f"id {i} covered by two entries"
            ent[i] = e["pad"]
    keys = ("id", "sink", "sink_part", "src_part", "sink_port", "sink_bits", "source", "asbuilt", "bound", "lane")
    mem, flops = [], 0
    for i in T["covered_ids"]:
        base = tm.get(i) or rm[i]
        pad = ent.get(i, 0) + (tm[i]["pad"] if i in tm else 0)
        m = {k: base[k] for k in keys}
        m.update(pad=pad, landed=base["bound"] + pad, entry_pad=ent.get(i, 0), residual_pad=tm[i]["pad"] if i in tm else 0)
        mem.append(m)
        flops += pad * sum(b - a + 1 for a, b in base["sink_bits"])
    for x in T["inner"]:
        mem.append(dict(id=f"INNER:{x['part']}:{x['sink']}.{x['sink_port']}<-{x['source']}@{x['old_D']}", sink=x["sink"],
                        sink_part=x["part"], src_part=x["part"], sink_port=x["sink_port"], sink_bits=[], source=x["source"],
                        asbuilt=x["old_D"], bound=x["old_D"], pad=0, landed=x["new_D"], lane=None,
                        dly_insts=x["dly_insts"]))
    src_sha = hashlib.sha256(Path(entry_f).read_bytes()).hexdigest()[:16]
    out = dict(schema="opentallas.die_plan.r8_landing_extra.v1", die=T["die"],
               note="GENERATED by kv_pv_entry_to_r8.py (BINDER4 10-23) from KV-P6-V37 kv_pv_entry_pads_v36.json "
                    f"(@0ec5c902d, sha {src_sha}); member pad = entry pad + residual pad; INNER = re-chosen intra delays",
               source=dict(table=Path(entry_f).name, sha=src_sha, summary=T["summary"]), params=T["params"],
               summary=dict(members=len(T["covered_ids"]), inner=len(T["inner"]),
                            padded=sum(1 for m in mem if m["pad"]), member_bit_pad_sum=flops),
               members=mem)
    Path(out_f).write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out["summary"]))


if __name__ == "__main__":
    main(*sys.argv[1:4])
