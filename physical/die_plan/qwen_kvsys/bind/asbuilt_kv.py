#!/usr/bin/env python3
"""KV-P3b 10-23: the KV die's as-built binding inputs for tools/die_plan/bind.py (BINDER2), from the KV-P3 blocker work.

    python3 bind/asbuilt_kv.py            (run in physical/die_plan/qwen_kvsys)  -> bind/asbuilt.json, bind/asbuilt_map.json

As built = rtl6 GEN die.v (source e33504a6f, sha256 e1fc838f..., bind/inputs/die_rtl6.v.gz; 46,711 instances, 71 masters).
  map        census/census_map_v32.json parts (8,853 content instances -> 156 partitions, the reviewed v3.2 census map) +
             the PHY slice children (substitute below) + the bump models + the SerDes join gates.
  transport  the die's pass-through masters (extract_asbuilt.PASS_RE minus qkd_rlyi_258s, which v3.2 plans as pv contents):
             qkd_rlys_N / qkd_rlysh_N / qkd_rlysh0_N relays (1 stage), qkd_landsh_N / qkd_landsh0_N landings (ring; the
             plan latency table is the schedule source, `stages` here is only the bind_latency.json record), the astk
             face-landed relay qkd_astk_rly_296_fl and the reset sequencer repeaters qkd_rst_region.
  reducers   qkd_hp_or2 (the health fault-OR tree, 361 cells; 356 of its inputs were landing faults, dropped with the
             landings: blockers_v32.json landing_fault_inputs).
  sources    qkd_pllm clock outputs -> plan clock domains (clocks_v32.json: core + clk_hbm_<Q> + clk_phy/host/ingest +
             clk_fwd); host.die_rst_n is the plan reset root (clocks_v32.json reset_root).
  straps     class A leaf parameters (blockers_v32.json straps table, cls A).  Class B (position IDs) and class C (chain
             heads) are NOT straps: see kv_binder_requests.
  substitute qkd_hbm3e_phy_pc -> qkd_hbm3e_phy_pc_s8 (8 x 4-PC slices = phy_<Q>_0..7) and ot_qfd_serdes_112g_x12_phy ->
             ot_qfd_serdes_112g_x12_phy_s2 (two x6 halves = sys_SW / sys_SE), bind/models/kv_phy_slices.sv.
"""
import gzip
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
KV = HERE.parent
cmap = json.load(open(KV / "census" / "census_map_v32.json"))["parts"]
blk = json.load(open(HERE / "blockers_v32.json"))
straps_in = json.load(gzip.open(HERE / "v32_inputs.json.gz"))["straps"]

parts = dict(sorted(cmap.items()))
for q in ("WS", "WN", "ES", "EN"):
    parts.pop(f"phy_{q}", None)
    for k in range(8):
        parts.pop(f"phy_{q}__s{k}", None)
        parts[f"phy_{q}.u_s{k}"] = f"phy_{q}_{k}"
parts.pop("serdes_W", None)
parts.pop("serdes_E", None)
parts.update({"serdes_host.u_W": "sys_SW", "serdes_host.u_E": "sys_SE",
              "ckb_kv": "sys_c", "fwb_ep": "sys_c", "fwb_rs": "sys_c"})
rules = [[r"serdes_host\.\$(and|logic_and)\$.*", "hub_Wi"]]        # link-up / rx_v join of the two halves: host side

A = [r["port"] for r in blk["straps"]["table"] if r["cls"] == "A"]
straps = []
for mp in A:
    m, port = mp.split(".")
    insts = sorted(straps_in[mp])
    straps.append("(" + "|".join(re.escape(i) for i in insts) + r")\." + re.escape(port))

ab = dict(
    note="KV-P3b 10-23: Qwen KV/system die as-built = rtl6 GEN die.v (source e33504a6f, sha256 e1fc838f427551c7...) for "
         "plan v3.2 (main 6f76bdfcb, plan sha 0391633f). Generated by bind/asbuilt_kv.py; open items for the binder are "
         "kv_binder_requests (also bind/blockers_v32.json).",
    base="../../../..",
    netlist=["physical/die_plan/qwen_kvsys/bind/inputs/die_rtl6.v.gz"],
    top="qfd_die",
    rtl_roots=["rtl", "physical/asap7_memory_macros_v2", "physical/asap7_memory_macros", "physical/asap7_memory_macros_v2_ew"],
    files=["physical/die_plan/qwen_kvsys/bind/models/kv_phy_slices.sv",
           "results/arch/qwen_split_1014/kvsys_v1_4_3_design/port_bind_v2/current/kv_hard_models.sv",
           "physical/qwen_kv_die_phy/ot_qkvd_ucie_x64_phy/ot_qkvd_ucie_x64_phy_model.sv"],
    prefer=["rtl/qwen_sys/split_20261014/qkd_rst_region_pr_h273b.sv",
            "rtl/qwen_sys/kv_rly_std_20261016/qkd_rlys.sv", "rtl/qwen_sys/kv_fwd_lane_20261018/qkd_rlysh.sv",
            "rtl/lib/face_land/qkd_astk_rly_296_fl.sv", "rtl/qwen_sys/kv_health_20261019/qkd_hp_or2.sv"],
    source_check="the rtl6 GEN source list is gen_source_ports.json (scratch kv-p2-1023/case_kv, 71 masters with their "
                 "source files under codex-kvgen-2140/src_main = e33504a6f); BINDER2: resolve every master from that "
                 "list at e33504a6f (several masters have multiple same-name copies, e.g. qkd_kvs_pc in 5 "
                 "qkd_kvs_tiles*.sv; qkd_rst_region = module qkd_rst_region_pr_h273b)",
    dissolve=["qkd_hbm3e_phy_pc_s8", "ot_qfd_serdes_112g_x12_phy_s2"],
    substitute={
        "qkd_hbm3e_phy_pc": dict(module="qkd_hbm3e_phy_pc_s8", ports={},
                                 reason="plan v3.2 slices each quadrant HBM PHY abstract into 8 x 4-PC partitions "
                                        "phy_<Q>_0..7 (one 1.5-mm clock region per slice; census phy_<Q>__s<k>)"),
        "ot_qfd_serdes_112g_x12_phy": dict(module="ot_qfd_serdes_112g_x12_phy_s2", ports={},
                                           reason="plan v3.1+ mirrors the x12 host SerDes as two x6 halves sys_SW/sys_SE "
                                                  "(W flit[521:0], E flit[1042:522]); tx_up/rx_v = AND of the halves")},
    transport=[
        dict(module=r"qkd_rlys_\d+", map={"b": "a"}, drop_in=["ck"], stages=1),
        dict(module=r"qkd_rlysh_\d+", map={"b": "a", "eb": "ea"}, drop_in=["ckf"], drop_out=["ck_o"], stages=1),
        dict(module=r"qkd_rlysh0_\d+", map={"b": "a"}, drop_in=["ck", "en"], drop_out=["eb", "ck_o"], stages=1),
        dict(module=r"qkd_landsh_\d+", map={"b": "a"}, drop_in=["ea", "ck", "ckf", "rs", "k0", "k1", "k2"],
             drop_out=["fault", "tie_hi", "tie_lo"], stages=2),
        dict(module=r"qkd_landsh0_\d+", map={"b": "a"}, drop_in=["ck_s", "en", "ck", "rs", "k0", "k1", "k2"],
             drop_out=["fault", "tie_hi", "tie_lo"], stages=2),
        dict(module=r"qkd_astk_rly_296_fl", map={"b": "a"}, drop_in=["ck", "rst_n"], stages=1),
        dict(module=r"qkd_rst_region(_pr_h273b)?", map={"b": "a"}, drop_in=["ck", "dly", "por_n"], stages=1)],
    reducers=[dict(module=r"qkd_hp_or2", out="q", drop_in=["ck"], stages=1)],
    sources=[
        dict(module=r"qkd_pll_analog_model|qkd_pllm", kind="clock",
             outputs={r"pll_(WS|WN|ES|EN|c)": "core", r"pll_hbm_WS": "clk_hbm_WS", r"pll_hbm_WN": "clk_hbm_WN",
                      r"pll_hbm_ES": "clk_hbm_ES", r"pll_hbm_EN": "clk_hbm_EN", r"pll_phy": "clk_phy",
                      r"pll_host": "clk_host", r"pll_ingest": "clk_ingest", r"pll_fwd": "clk_fwd"})],
    resets_note="plan reset root = host.die_rst_n (hub_Wi) -> every partition synchroniser (clocks_v32.json reset_root); "
                "the as-built qkd_rst_region sequencer chain is transport above",
    default_clock="core",
    straps=straps,
    strap_note="class A only (type-constant leaf parameters, blockers_v32.json cls A: " + ", ".join(A) + ")",
    map_file="asbuilt_map.json",
    kv_binder_requests=[
        "per-INSTANCE substitute (asbuilt.substitute is per module): class C chain heads use the head variants of "
        "claude/kv-p3-rtl-1023 (rtl/qwen_sys/kv_plan_leaves_1023): ep_0 -> qkd_astk_ep_s_head_e, owner_0 -> "
        "qkd_astk_er_owner_st_head, zn_0 -> qkd_astk_zn_head_p, hsl_*S_31/hsl_*N_0 -> qkd_host_pc_slice_die_head, "
        "kvpc_*_0 (qkd_kvs_pc_h) -> qkd_kvs_pc_h_head_p; their removed inputs (5,672 b) must not appear as TIED",
        "class B position IDs (2,184 b: pc__pc, lpc, cfg_stack, cfg_group of kvs_grp_r2c, sq, owner_id, esh__stack; eo is "
        "computed from sq by qkd_astk_ep_s_e): plan v3.2 carries them as counted ID lanes (rtl/lib/ot_dp_id.sv src/add/rot "
        "cells) so replicated partitions stay identical; bind the leaf port to the plan ID lane instead of a parameter",
        "landing checks: the as-built landing fault outputs (dropped with the transport) are replaced in v3.2 by "
        "ot_dp_efault per receiving partition (23 types / 88 partitions) + per-column qkd_hp_or2 chains -> hub_C; "
        "params IN_LANES / REL_AGE from lat_v32/qwen_kvsys_latency.json",
        "multi-clock partitions: pc_<Q>_k and hroot_<Q> load core + clk_hbm_<Q>, hub_Wi loads core + clk_phy/host/ingest, "
        "phy_<Q>_k is entirely clk_hbm_<Q>, sys_c clk_fwd for the bump (clocks_v32.json; G2 die probe with all spines "
        "PASS, g2_clocks_v32_report.json)",
        "qkd_rlyi_258s (128, PV result T-chain select stage b <= s ? y : a) is LOGIC, not transport: v3.2 plans each as a "
        "pv content (blockers_v32.json pv_trunk_mux_relays); keep it as a leaf"])

(HERE / "asbuilt.json").write_text(json.dumps(ab, indent=1) + "\n")
(HERE / "asbuilt_map.json").write_text(json.dumps({"parts": parts, "rules": rules}, indent=1) + "\n")
print(f"asbuilt.json: {len(ab['transport'])} transport, {len(straps)} strap regexes; map {len(parts)} parts, {len(rules)} rules")
