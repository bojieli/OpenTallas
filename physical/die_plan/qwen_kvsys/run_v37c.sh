#!/usr/bin/env bash
# Emit plan v3.7-cores (= v3.6 + partition_types.*.hard_cores[], post_v37c.py) and G0.  Lanes / ports unchanged -> the
# v3.6 latency + R8 tables stand.  usage: run_v37c.sh V36_DIE_PLAN.json OUTDIR
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd); R=$(cd "$D/../../.." && pwd)
IN=${1:?v3.6 die_plan.json}; O=${2:?output directory}; mkdir -p "$O"
python3 "$D/post_v37c.py" "$IN" > "$O/die_plan.json"
cp -r "$D/cores" "$D/census" "$O/"   # pins_file / census paths are plan-relative
python3 "${OT_DIE_PLAN_TOOLS:-$R/tools/die_plan}/check.py" "$O/die_plan.json" --png --out "$O/g0"
python3 "$D/post_v37k.py" "$O/die_plan.json" > "$O/die_plan_k.json" && mv "$O/die_plan_k.json" "$O/die_plan.json" && python3 "${OT_DIE_PLAN_TOOLS:-$R/tools/die_plan}/check.py" "$O/die_plan.json" --png --out "$O/g0k"   # COORD 19:55 common clock latency
# v3.7p (KV-P6-PINS 10-23): top-down core pins.  cores/<module>_pins.json + core_conns.json + cores/core_patch_v37p.json are
# generated by core_pins_v37p.py from the bound partition netlists (binder3 kv39 rtl/<type>_part.sv):
#   python3 "$D/core_pins_v37p.py" "$O/die_plan.json" RTL_DIR "$D"   (re-run after a re-bind / core change)
python3 "$D/post_v37p.py" "$O/die_plan.json" "$D" > "$O/die_plan_p.json" && mv "$O/die_plan_p.json" "$O/die_plan.json"
cp -r "$D/cores" "$D/core_conns.json" "$O/"
python3 "${OT_DIE_PLAN_TOOLS:-$R/tools/die_plan}/check.py" "$O/die_plan.json" --png --out "$O/g0p"
python3 "${OT_DIE_PLAN_TOOLS:-$R/tools/die_plan}/check.py" "$O/die_plan.json" --completeness --out "$O/g0c" || true   # G0C per type
