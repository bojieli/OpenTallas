#!/usr/bin/env python3
"""gen_ectlk_pc.py -- KV-HG-CDE 11-25: per-core rsp_data ports for the ECTL columns wrapper (qkd_ectl3_kiss_st_cols_pc).

The checked-in qkd_ectl3_kiss_st_cols takes ONE rsp_data[1023:0] and the hard quarters u_q0..u_q3 read the slices [511:0], [1023:256], [767:0], [1023:512]
inside the leaf, so the lane pad's last flop drives up to three cores in one hop and no site reaches all of them (kv3_hg_v1p5 krsp -> ectl_q0,
37 endpoints, -127 ps).  The _pc wrapper has one input per core (rsp_data_q0 [511:0], q1 [767:0], q2 [767:0], q3 [511:0]; q1 bit j = old bit 256+j),
so the binder can give every core its own pad tail copy.  Instance names (u_cols, u_columns, u_q0..u_q3) and the hard quarters are unchanged.
The _pc modules are generated from the checked-in source (no hand edit); every substitution must hit exactly once.

usage: gen_ectlk_pc.py COLUMNS_SV WRAPPER_SV OUT_SV      (check: gen_ectlk_pc.py --check COLUMNS_SV WRAPPER_SV OUT_SV)
"""
import re
import sys

PORTS = "    input wire [511:0] rsp_data_q0,\n    input wire [767:0] rsp_data_q1,\n    input wire [767:0] rsp_data_q2,\n    input wire [511:0] rsp_data_q3"
CONN = "        .rsp_data_q0(rsp_data_q0),\n        .rsp_data_q1(rsp_data_q1),\n        .rsp_data_q2(rsp_data_q2),\n        .rsp_data_q3(rsp_data_q3)"


def module(text, name):
    m = re.search(r"^module %s\b.*?^endmodule\n" % re.escape(name), text, re.S | re.M)
    if not m:
        raise SystemExit(f"module {name} not found")
    return m.group(0)


def sub1(text, old, new, what):
    if text.count(old) != 1:
        raise SystemExit(f"{what}: expected exactly one {old!r}, found {text.count(old)}")
    return text.replace(old, new)


def build(columns, wrapper):
    c = module(columns, "qkd_ectlk_columns")
    c = sub1(c, "module qkd_ectlk_columns ", "module qkd_ectlk_columns_pc ", "columns name")
    c = sub1(c, "    input wire [1023:0] rsp_data,\n", PORTS + ",\n", "columns port")
    for q, old in (("q0", "rsp_data[511:0]"), ("q1", "rsp_data[1023:256]"), ("q2", "rsp_data[767:0]"), ("q3", "rsp_data[1023:512]")):
        c = sub1(c, f".rsp_data({old})", f".rsp_data(rsp_data_{q})", "columns " + q)
    g = module(columns, "qkd_ectlk_columns_legacy")
    g = sub1(g, "module qkd_ectlk_columns_legacy ", "module qkd_ectlk_columns_legacy_pc ", "legacy name")
    g = sub1(g, "    input wire [1023:0] rsp_data\n", PORTS + "\n", "legacy port")
    g = sub1(g, "    wire [1023:0] compact_rsp_data;\n", "", "legacy wire")
    g, n = re.subn(r"    assign compact_rsp_data\[(\d+)\] = rsp_data\[\1\];\n", "", g)
    if n != 1024:
        raise SystemExit(f"legacy compact assigns: {n} != 1024")
    g = sub1(g, "    qkd_ectlk_columns #(", "    qkd_ectlk_columns_pc #(", "legacy inst")
    g = sub1(g, "        .rsp_data(compact_rsp_data)\n", CONN + "\n", "legacy conn")
    if "compact_rsp_data" in g or re.search(r"\brsp_data\b", g):
        raise SystemExit("legacy_pc still mentions rsp_data")
    w = module(wrapper, "qkd_ectl3_kiss_st_cols")
    w = sub1(w, "module qkd_ectl3_kiss_st_cols #(", "module qkd_ectl3_kiss_st_cols_pc #(", "wrapper name")
    w = sub1(w, "    output wire [0:0] req_valid, input wire [1023:0] rsp_data\n", "    output wire [0:0] req_valid,\n" + PORTS + "\n", "wrapper port")
    w = sub1(w, "    qkd_ectlk_columns_legacy #(", "    qkd_ectlk_columns_legacy_pc #(", "wrapper inst")
    w = sub1(w, "        .rsp_data(rsp_data));\n", CONN.replace("rsp_data_q3(rsp_data_q3)", "rsp_data_q3(rsp_data_q3)") + ");\n", "wrapper conn")
    hdr = ("// GENERATED by gen_ectlk_pc.py from qkd_ectlk_columns.sv + qkd_ectl3_kiss_st_cols.sv (KV-HG-CDE 11-25); do not edit.\n"
           "// Per-core rsp_data inputs; needs the modules qkd_ectlk_q0..q3 of qkd_ectlk_columns.sv in the same compile.\n")
    return hdr + c + "\n" + g + "\n" + w


def main():
    a = sys.argv[1:]
    check = a and a[0] == "--check"
    if check:
        a = a[1:]
    cols, wrap, out = a
    text = build(open(cols).read(), open(wrap).read())
    if check:
        sys.exit(0 if open(out).read() == text else "OUT_OF_DATE " + out)
    open(out, "w").write(text)
    print("wrote", out, len(text.splitlines()), "lines")


main()
