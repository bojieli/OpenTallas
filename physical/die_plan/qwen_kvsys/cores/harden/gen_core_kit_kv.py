#!/usr/bin/env python3
"""KVG3-CORES 10-24: ORFS kit for one KV planned hard core (adapted from physical/die_plan/s81/cores/svc/gen_core_kit_s81.py).

    python3 gen_core_kit_kv.py --core-json RTLDIR/<module>/<module>_core.json --plan die_plan.json --out KITROOT
                               [--recipes recipes_kv.json] [--util 0.6]

KV differences from S81:
  * the core RTL is the generated kv_core_rtl.py module (member leaves of the bound kv41 partition) + the G3 kit leaf
    sources (kit_rtl.f); memory macros reached by the members are black boxes + LEF/LIB from kit_rtl.json hard_macros;
  * KV cores use track_offset_um [0, 0]: pins sit on the DIE symmetric tracks (offset = pitch / 2: M4/M5 0.024 + k 0.048,
    M6/M7 0.032 + k 0.064) -> make_tracks.tcl with the symmetric offsets (tools/die_plan/gen_phys.make_tracks_tcl);
  * pins = the plan pins file + the pins kv_core_rtl.py ADDED (clock / reset of the astk cores, kv39->kv41 drift, gap
    bits, straps): added pins go on free tracks of the face with most room, next to its centre, two free tracks apart
    (recorded in kit pins_added.json; the plan pins file must take them before the views are adopted);
  * clock = the one core clock pin (class clk); period / common latency from the KV plan clock (833 ps, 250 ps);
  * corners: run_kit_kv.sh runs ORFS (TC) to finish + generate_abstract, then corners.tcl re-times the routed design at
    TT / FF / SS (RCX SPEF), writes setup/hold WNS/TNS per corner and write_timing_model per corner.
PDN = core PG pins on the partition M5 grid (S81 core recipe: M1/M2 follow-pins + M5 stripes 4.32 pitch, 2.064 offset:
core origins sit on the 8.64 lattice, so the stripes line up with the partition M5 grid).
"""
