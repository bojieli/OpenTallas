CORE_MARGIN_UM = 4.32
PIN_LEN_UM = 0.192
LAYER_W = dict(M2=0.018, M3=0.018, M4=0.024, M5=0.024, M6=0.032, M7=0.032)
PITCH = dict(M4=0.048, M5=0.048, M6=0.064, M7=0.064)
OFFS = dict(M4=0.024, M5=0.024, M6=0.032, M7=0.032)
