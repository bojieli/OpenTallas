def kit_hash(kd):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(kd).rglob("*") if p.is_file() and "run" not in p.relative_to(kd).parts[:1]
                    and p.name not in ("freeze.json", "preflight.json") and not p.name.startswith("run_")):
        h.update(str(f.relative_to(kd)).encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:16]


def reached_modules(files, top):
    """module names reachable from top (regex closure over module bodies: `name [#(...)] inst (`)."""
    body = {}
    for f in files:
        txt = re.sub(r"//.*", "", Path(f).read_text(errors="replace"))
        txt = re.sub(r"/\*.*?\*/", "", txt, flags=re.S)
        for m in re.finditer(r"\bmodule\s+(\w+)(.*?)\bendmodule\b", txt, re.S):
            body[m.group(1)] = m.group(2)
    kw = {"module", "if", "for", "case", "assign", "always", "begin", "end", "else", "function", "task", "wire", "reg",
          "logic", "input", "output", "inout", "generate", "initial", "return", "localparam", "parameter", "genvar"}
    seen, todo = set(), [top]
    while todo:
        m = todo.pop()
        if m in seen:
            continue
        seen.add(m)
        for mm in re.finditer(r"^\s*([A-Za-z_]\w*)\s*(?:#\s*\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))?\s*(?:[A-Za-z_]\w*|\\\S+\s)\s*\(",
                              body.get(m, ""), re.M):
            if mm.group(1) not in kw:
                todo.append(mm.group(1))
    return " ".join(sorted(seen))


