def sdc(per, ins, tol, clks, rsts, tid, straps=(), in_min_ports=None, related=(), seam=None):
    """core SDC in the sdc_lint vocabulary (CP1-R10): one real clock 'clk' on the core clock pin(s), one virtual IO clock
    at the plan common latency, 60/25 ps uncertainty split once per seam, explicit max AND min delays on every port
    (min input = -insertion_tol: seam-hold padding as the partition kits; min output 0).  related: opt-in clock ports
    that are their own related root (related_clock_sdc); empty = byte-identical legacy text.
    seam: opt-in (sender_ps, seam_ps) = the shared CLOCK-RESET IO-HOLD contract (gen_phys.seam_hold): min output
    -sender_ps (the core's own outputs credit their clk->q), min input sender_ps - seam_ps (the parent logic driving the
    core is the sender and guarantees port data >= vclk + 12.5 + sender_ps); None = legacy (-insertion_tol / 0)."""
    io = IO_BUDGET * per
    in_min, out_min = (-tol, 0.0) if seam is None else (seam[0] - seam[1], -seam[0])
    related = [n for n in clks if n in set(related or ())]
    if related and len(related) >= len(clks):
        raise SystemExit(f"{tid}: --related-clock {related} leaves no core clock 'clk'")
    clks = [n for n in clks if n not in related]
    multi = ("# ASSUMPTION (labelled, COORD 10-24): clock pins " + " ".join(clks) + " are separate plan clock nets (e.g. kvs_pc"
             " ck = core clock, hck = HBM-side clock, async CDC); the plan gives no HBM clock period, so all are co-timed as"
             " ONE 833 ps clock (conservative: CDC paths timed synchronously). Pending KV-G3: HBM clock period.\n"
             if len(clks) > 1 else "")
    s = (f"# GENERATED by gen_core_kit_kv.py: core {tid}; ps / fF (ASAP7 liberty units).\n" + multi +
         f"create_clock -name clk -period {per:.4f} [get_ports {{{' '.join(clks)}}}]\n"
         f"# the partition logic around the core runs on the budgeted insertion ({ins:g} ps): virtual IO clock\n"
         + related_clock_sdc(per, related) +
         f"create_clock -name vclk -period {per:.4f}\n"
         f"set_clock_latency -source {ins:.4f} [get_clocks vclk]\n"
         f"set_clock_uncertainty {UNC_SETUP_PS:.4f} -setup [all_clocks]\n"
         f"set_clock_uncertainty {UNC_HOLD_PS:.4f} -hold [all_clocks]\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -setup {UNC_SPLIT * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -setup {(1 - UNC_SPLIT) * UNC_SETUP_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks vclk] -to [get_clocks clk] -hold {UNC_SPLIT * UNC_HOLD_PS:.4f}\n"
         f"set_clock_uncertainty -from [get_clocks clk] -to [get_clocks vclk] -hold {(1 - UNC_SPLIT) * UNC_HOLD_PS:.4f}\n"
         f"set non_clk_in [all_inputs -no_clocks]\n"
         f"set_input_delay -max {io:.4f} -clock vclk $non_clk_in\n"
         + (f"# CLOCK-RESET IO-HOLD seam_hold contract (--seam-hold): sender {seam[0]:g} ps / seam {seam[1]:g} ps\n" if seam else "") +
         f"set_input_delay -min {in_min + 0.0:.4f} -clock vclk $non_clk_in\n"
         f"set_output_delay -max {io:.4f} -clock vclk [all_outputs]\n"
         f"set_output_delay -min {out_min + 0.0:.4f} -clock vclk [all_outputs]\n")
    if in_min_ports:
        s += "# IO-HOLD option A (OT_IO_HOLD=sender_min): sender output-min guarantee; parent io_hold_parent.py check required\n"
        for v in sorted(set(in_min_ports.values())):
            ps = sorted(p for p, x in in_min_ports.items() if x == v)
            s += f"set_input_delay -min {v:.4f} -clock vclk [get_ports {{{' '.join(p + '[*]' for p in ps)}}}]\n"
    if rsts:
        s += _reset_sdc(rsts, per)
    if straps:
        # OWNER 10-25 option B rule 2: declared ID straps are quasi-static parent constants -> the one allowed exception
        s += ("# ID straps (OWNER 10-25 option B): tied at the parent, quasi-static\n"
              f"set_false_path -from [get_ports {{{' '.join(straps)}}}]\n")
    return s + (f"set_load {IO_LOAD_FF:g} [all_outputs]\n"
                "set_driving_cell -lib_cell BUFx4_ASAP7_75t_R -pin Y $non_clk_in\n")


