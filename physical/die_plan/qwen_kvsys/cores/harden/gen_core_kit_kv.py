def _effective_hook(cfg, name):
    """make semantics over config.mk lines: the last `override export` wins, else the last plain `export`
    (same rule as hbm_arch_cores/gen_core_kit_hbm.py _effective_hook)."""
    value, forced = None, False
    for line in cfg:
        m = re.match(r"^(override\s+)?export\s+" + name + r"\s*=\s*(.*?)\s*$", line)
        if m and (m[1] or not forced):
            value, forced = m[2], bool(m[1])
    if value and any(c in value for c in "$\n\r{}"):
        raise ValueError(f"{name} must be a literal Tcl path")
    return value or None


