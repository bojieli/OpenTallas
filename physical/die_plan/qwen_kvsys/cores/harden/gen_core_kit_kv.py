def face_of(x, y, w, h):
    d = [(x, "W"), (w - x, "E"), (y, "S"), (h - y, "N")]
    return min(d)[1]


def split_name(n):
    m = re.match(r"^(.*)\[(\d+)\]$", n)
    return (m.group(1), int(m.group(2))) if m else (n, None)


def place_added(pins, add, w, h):
    """add: [name] -> pin dicts on free tracks: the face with most free M4/M5 tracks, spiralling out from its centre,
    a track only when both neighbours are free too."""
    used = {}
    for p in pins:
        f = face_of(p["x"], p["y"], w, h)
        c = p["x"] if f in "NS" else p["y"]
        used.setdefault((f, p["layer"]), set()).add(round((c - OFFS[p["layer"]]) / PITCH[p["layer"]]))
    out = []
    for n in add:
        best = None
        for f, lay in (("N", "M5"), ("S", "M5"), ("E", "M4"), ("W", "M4")):
            L = w if f in "NS" else h
            ntr = int((L - 2 * KEEP) / PITCH[lay])
            free = ntr - len(used.get((f, lay), ()))
            if best is None or free > best[0]:
                best = (free, f, lay, L)
        _, f, lay, L = best
        u = used.setdefault((f, lay), set())
        lo = math.ceil((KEEP - OFFS[lay]) / PITCH[lay])
        hi = math.floor((L - KEEP - OFFS[lay]) / PITCH[lay])
        mid = (lo + hi) // 2
        for d in range(0, hi - lo):
            hit = None
            for k in (mid + d, mid - d):
                if lo <= k <= hi and not ({k - 1, k, k + 1} & u):
                    hit = k
                    break
            if hit is not None:
                break
        u.add(hit)
        c = round(OFFS[lay] + hit * PITCH[lay], 6)
        x, y = {"N": (c, round(h - 0.096, 6)), "S": (c, 0.096), "E": (round(w - 0.096, 6), c), "W": (0.096, c)}[f]
        out.append(dict(name=n, layer=lay, x=x, y=y, added=True))
    return out


def io_tcl(pins, w, h, tid, clk_pins=()):
    clk_pins = set(clk_pins)
    out = [f"# GENERATED by gen_core_kit_kv.py: exact plan pins of core {tid} ({len(pins)} pins, core frame um)."]
    rows = []
    for p in pins:
        f = face_of(p["x"], p["y"], w, h)
        lw = LAYER_W.get(p["layer"], 0.04)
        x, y = p["x"], p["y"]
        if min(x, w - x, y, h - y) > INTERIOR_TOL_UM:
            # KV-CORES-R2 10-27 (METHODOLOGY 12.8a): interior clock/reset entry pin (KV core slice centre entry island,
            # M5 via stack from M9) -- placed at its exact plan xy, never projected onto a face
            vert = p["layer"] in ("M3", "M5", "M7")
            if p["name"] in clk_pins:
                sz = (CLK_PORT_W_UM, CLK_PORT_L_UM) if vert else (CLK_PORT_L_UM, CLK_PORT_W_UM)
            else:
                sz = (lw, PIN_LEN_UM) if vert else (PIN_LEN_UM, lw)
            out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{x:.4f} {y:.4f}}} "
                       f"-pin_size {{{sz[0]:.4f} {sz[1]:.4f}}}   ;# 12.8a interior entry"
                       + (" (clock port >= 0.048x0.48)" if p["name"] in clk_pins else ""))
            b, i = split_name(p["name"])
            rows.append(dict(bus=b, bit=i, layer=p["layer"], x=round(x, 4), y=round(y, 4), face="interior",
                             size=[sz[0], sz[1]], clock=p["name"] in clk_pins))
            continue
        if f in "EW":
            x = w if f == "E" else 0.0
            size, cx, cy = (PIN_LEN_UM, lw), (x - PIN_LEN_UM / 2 if f == "E" else x + PIN_LEN_UM / 2), y
        else:
            y = h if f == "N" else 0.0
            size, cx, cy = (lw, PIN_LEN_UM), x, (y - PIN_LEN_UM / 2 if f == "N" else y + PIN_LEN_UM / 2)
        out.append(f"place_pin -pin_name {{{p['name']}}} -layer {p['layer']} -location {{{cx:.4f} {cy:.4f}}} "
                   f"-pin_size {{{size[0]:.4f} {size[1]:.4f}}}")
        b, i = split_name(p["name"])
        rows.append(dict(bus=b, bit=i, layer=p["layer"], x=round(x if f in "EW" else p["x"], 4),
                         y=round(y if f in "NS" else p["y"], 4), face=f))
    return "\n".join(out) + "\n", rows


