#!/usr/bin/env python3
"""KV-CORES-R9 kit input step: static FIRM memory-macro sites for a generated KV hard-core kit.

    python3 macro_sites.py SITES.json KITDIR

Why: a kit without MACRO_PLACEMENT_TCL leaves macro placement to rtlmp, so the macro halo blockage can remove the std
rows under a plan island_ft rect (ectlk_q0 PV2 3_3 GPL OT_ISLAND_FT_NO_ROW) and Preflight-2 macro_channels /
clock_entry_clear cannot check the placement.  This step writes KITDIR/macro_place.tcl (the kit_contract macro_boxes
`foreach {master sites}` form; sites = bbox lower-left in the core frame, instance-name order per master) and adds
MACRO_PLACEMENT_TCL to config.mk.  Like pass1_reserve it is a design input applied after gen_core_kit_kv.py, so the
canaried flow files stay unchanged.  Fail-closed: masters == the kit's macro LEFs, sites inside CORE_AREA, halo boxes
disjoint, every island_ft rect outside every macro + MACRO_PLACE_HALO box.
"""
import json
import re
import sys
from pathlib import Path

TCL = """# GENERATED by physical/die_plan/qwen_kvsys/cores/macro_sites/macro_sites.py from %s
# static FIRM memory-macro sites (core frame um, bbox lower-left); instances of one master take the sites in name order.
set b [ord::get_db_block]
set dbu [[ord::get_db_tech] getDbUnitsPerMicron]
foreach {master sites} {%s} {
  set hit {}
  foreach i [$b getInsts] { if {[[$i getMaster] getName] eq $master} { lappend hit $i } }
  if {[llength $hit] != [llength $sites]} { error "KV macro_sites: [llength $hit] instances of $master (want [llength $sites])" }
  set hit [lsort -command {apply {{a b} {string compare [$a getName] [$b getName]}}} $hit]
  foreach i $hit s $sites {
    lassign $s x y orient
    $i setOrient $orient
    $i setLocation 0 0
    set bb [$i getBBox]
    $i setLocation [expr {round($x * $dbu) - [$bb xMin]}] [expr {round($y * $dbu) - [$bb yMin]}]
    $i setPlacementStatus FIRM
    puts "KV macro_sites: [$i getName] $master at $x $y $orient"
  }
}
"""
LINE = "export MACRO_PLACEMENT_TCL = /work/macro_place.tcl"


def apply(sites_path, kd):
    kd = Path(kd)
    doc = json.load(open(sites_path))
    cfg_p = kd / "config.mk"
    cfg = cfg_p.read_text()
    if "MACRO_PLACEMENT_TCL" in cfg:
        raise SystemExit(f"{kd.name}: config.mk already sets MACRO_PLACEMENT_TCL")
    lefs = {p.stem: p for p in (kd / "macros").glob("*.lef")} if (kd / "macros").is_dir() else {}
    sites = doc.get("sites") or {}
    if not sites or set(sites) != set(lefs):
        raise SystemExit(f"{kd.name}: site masters {sorted(sites)} != kit macro LEFs {sorted(lefs)}")
    core = [float(v) for v in re.search(r"^export CORE_AREA = (.*)$", cfg, re.M).group(1).split()]
    halo = max(float(v) for v in re.search(r"^export MACRO_PLACE_HALO = (.*)$", cfg, re.M).group(1).split())
    isl = json.load(open(kd / "island_ft.json"))["arcs"] if (kd / "island_ft.json").is_file() else []
    boxes = []
    for m, lst in sites.items():
        mw, mh = (float(v) for v in re.search(r"SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", lefs[m].read_text()).groups())
        for x, y, o in lst:
            if o not in ("R0", "MX", "MY", "R180"):
                raise SystemExit(f"{kd.name}: macro {m} orient {o}: only R0/MX/MY/R180")
            boxes.append((m, x, y, x + mw, y + mh))

    def hit(a, b):
        return a[0] < b[2] - 1e-6 and b[0] < a[2] - 1e-6 and a[1] < b[3] - 1e-6 and b[1] < a[3] - 1e-6
    for i, (m, x0, y0, x1, y1) in enumerate(boxes):
        if x0 < core[0] - 1e-6 or y0 < core[1] - 1e-6 or x1 > core[2] + 1e-6 or y1 > core[3] + 1e-6:
            raise SystemExit(f"{kd.name}: macro {m} site {[x0, y0, x1, y1]} outside CORE_AREA {core}")
        hb = (x0 - halo, y0 - halo, x1 + halo, y1 + halo)
        for (m2, *b2) in boxes[i + 1:]:
            if hit(hb, b2):
                raise SystemExit(f"{kd.name}: macros {m} / {m2} closer than the {halo} um halo")
        for a in isl:
            if hit(hb, a["rect_um"]):
                raise SystemExit(f"{kd.name}: island_ft {a['source']} rect {a['rect_um']} inside macro {m} + halo")
    body = " ".join(f"{m} {{{' '.join('{%g %g %s}' % (x, y, o) for x, y, o in lst)}}}" for m, lst in sorted(sites.items()))
    (kd / "macro_place.tcl").write_text(TCL % (Path(sites_path).name, body))
    cfg = cfg.replace(re.search(r"^export MACRO_PLACE_HALO = .*$", cfg, re.M).group(0),
                      re.search(r"^export MACRO_PLACE_HALO = .*$", cfg, re.M).group(0) + "\n" + LINE, 1)
    cfg_p.write_text(cfg)
    return boxes


if __name__ == "__main__":
    b = apply(sys.argv[1], sys.argv[2])
    print(json.dumps(dict(kit=sys.argv[2], macro_sites=[[m, x0, y0, x1, y1] for m, x0, y0, x1, y1 in b])))
