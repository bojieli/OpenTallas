#!/usr/bin/env python3
"""DIE-QC-75 11-05: coll_core fold-slice hard cores (plan_qc52 delta). COORD 05:32 default: split by plan event.

coll_core is 560,700 std cells at floorplan (674,841 in synth), over the 400k run cap (FAIL PLAN, floorplan.tcl). 8 keep_hierarchy
instances of one master, ot_coll_fold_slice, take 459,352 of the synth count: 57,419 cells / 10,458 FF each [1_2_yosys.v of
coll_core attempt_3]. Both groups g_pf[0..3] and g_xf[0..3] become 8 instances of ONE hard core. Shell left: 215,257 synth
cells. Faces are already registered (SEAM 1: dq/vq in, sq/vq/eq out), 0 added cycles, no RTL change. The master closed in
October at 181.44 x 181.44 pd 0.55, TT +233.81, FF +1.76 (results/closure_loop/coll_fold_slice_rt-rt1-ae9fa22a9), old rules;
here outline 190.08 x 211.68 for util <= 0.45 (conservative form), M5 ceiling.

g_pf drives src[511:256] with 0 at the parent (RTL as-is); the master is one view, those pins are parent-tied.
Plan change, coll_core only: 8 hard_cores with physical_inst, 8 contents rows, clock.core_taps early with 8 core taps
at insertion 250/202.5 (ESTIMATE, target; re-measure from the core's own kit), 2 stale core taps u_coll_face_p/r dropped: these
name no hard_cores[] (no early mode so far, so no port). Collector tree re-derived if the reset obstacles move it.
usage: delta_collcore_fold_1105.py PLAN_IN PLAN_OUT [REPORT.json [SIDECAR_IN SIDECAR_OUT]]"""
import copy
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools" / "die_plan"))
import schema as S  # noqa: E402
import reset_tree as RT  # noqa: E402

T = "coll_core"
MOD = "ot_coll_fold_slice"
OUTLINE = [190.08, 211.68]
TOFF = [0.012, 0.012]
PINS = "cores/coll/ot_coll_fold_slice_pins.json"
TT, FF = 250.0, 202.5
CELLS, FFS = 57419, 10458
PARENT = "u_bound.u_io_collective_u_io_u_collective.u_coll"
SITES = {"g_xf_0": ("g_xf[0]", [8.64, 1105.92]), "g_xf_1": ("g_xf[1]", [203.04, 1105.92]),
         "g_xf_2": ("g_xf[2]", [406.08, 1123.2]), "g_xf_3": ("g_xf[3]", [406.08, 1343.52]),
         "g_pf_0": ("g_pf[0]", [492.48, 682.56]), "g_pf_1": ("g_pf[1]", [492.48, 466.56]),
         "g_pf_2": ("g_pf[2]", [492.48, 250.56]), "g_pf_3": ("g_pf[3]", [8.64, 1319.04])}
ID = "DIE-QC-75/FOLD-1105"


def pin_table():
    w, h = OUTLINE
    trk = lambda v: round(0.012 + 0.048 * round((v - 0.012) / 0.048), 3)
    pins = []
    n = 513                                 # src[511:0] + red_in, W face M4
    p0 = (h - (n - 1) * 0.288) / 2
    for i in range(512):
        pins.append(dict(name=f"src[{i}]", dir="in", face="W", x=0.042, y=trk(p0 + i * 0.288), layer="M4"))
    pins.append(dict(name="red_in", dir="in", face="W", x=0.042, y=trk(p0 + 512 * 0.288), layer="M4"))
    n = 130                                 # sum[127:0] + v_out + e_out, E face M4
    step = 1.44
    p0 = (h - (n - 1) * step) / 2
    for i in range(128):
        pins.append(dict(name=f"sum[{i}]", dir="out", face="E", x=round(w - 0.042, 3), y=trk(p0 + i * step), layer="M4"))
    pins.append(dict(name="v_out", dir="out", face="E", x=round(w - 0.042, 3), y=trk(p0 + 128 * step), layer="M4"))
    pins.append(dict(name="e_out", dir="out", face="E", x=round(w - 0.042, 3), y=trk(p0 + 129 * step), layer="M4"))
    pins.append(dict(name="rst_n", dir="in", face="S", x=trk(w / 2 - 28.8), y=0.048, layer="M5"))
    pins.append(dict(name="clk", dir="in", face="S", x=trk(w / 2), y=0.048, layer="M5"))
    return dict(schema="opentallas.core_pins.v1", core=MOD, frame="core R0, origin (0,0)", source="delta_collcore_fold_1105.py top-down plan pins", outline_um=OUTLINE, pins=pins,
                note=f"{ID}: plan pin table, generated by delta_collcore_fold_1105.py. E/W M4, S M5, kit track 0.012 + 0.048 k")


def main():
    pin, pout = sys.argv[1:3]
    rep_p = sys.argv[3] if len(sys.argv) > 3 else None
    text = open(pin).read()
    P0 = json.loads(text)
    seps = next((sp for sp in ((", ", ": "), (",", ":")) if json.dumps(P0, separators=sp) + "\n" == text), None)
    assert seps, "plan text style is not one-line json.dumps"
    P = copy.deepcopy(P0)
    t = P["partition_types"][T]
    assert not any(h["module"] == MOD for h in t["hard_cores"])
    assert t["clock"].get("core_taps") is None
    tree0 = RT.for_type(S.Plan(P0, pin), T)
    tbl = pin_table()
    pf = Path(pout).resolve().parent / PINS
    pf.parent.mkdir(parents=True, exist_ok=True)
    pf.write_text(json.dumps(tbl, indent=1) + "\n")
    ck = next(p for p in tbl["pins"] if p["name"] == "clk")
    dropped = [x["name"] for x in t["clock"]["taps"] if x.get("kind") == "core"]
    assert dropped == ["u_coll_face_p.ck", "u_coll_face_r.ck"], dropped
    t["clock"]["taps"] = [x for x in t["clock"]["taps"] if x.get("kind") != "core"]
    t["clock"]["core_taps"] = "early"
    for inst, (gen, org) in SITES.items():
        phys = f"{PARENT}.{gen}.u_fs"
        assert org[0] + OUTLINE[0] <= t["outline_um"][0] and org[1] + OUTLINE[1] <= t["outline_um"][1], inst
        t["hard_cores"].append(dict(inst=inst, module=MOD, origin_um=list(org), outline_um=list(OUTLINE), orient="R0",
                                    track_offset_um=list(TOFF), pins_file=PINS, physical_inst=phys, physical_master=MOD,
                                    sub_core_parent=T, sub_core_leaf_pin=f"rst_{'x' if inst[2] == 'x' else 'p'}fold{inst[-1]}",
                                    cells=CELLS, cells_basis=f"coll_core a3 1_2_yosys.v module count, {FFS} FF",
                                    note=f"{ID}: fold slice hard core, 0 added cycles; UNSIGNED until its kit signs off"))
        t["contents"].append(dict(inst=inst, module=MOD, status="reuse", physical_inst=phys, physical_master=MOD,
                                  note=f"{ID}: {gen} fold slice, placed as hard core"))
        t["clock"]["taps"].append(dict(
            name=f"{inst}.clk", kind="core", xy=[round(org[0] + ck["x"] + TOFF[0], 3), round(org[1] + ck["y"] + TOFF[1], 3)],
            insertion_ps=TT, insertion_ff_ps=FF,
            budget_owner=f"{ID}: target 250/202.5 ESTIMATE, re-measure from the core's own kit (12.28b)"))
    tree1 = RT.for_type(S.Plan(P, pout), T)
    moved = json.dumps(tree1, sort_keys=True) != json.dumps(tree0, sort_keys=True)
    if moved:
        assert RT.consumer_count(tree1) == RT.consumer_count(tree0), "consumer count moved"
        t["clock"]["landing_contract"]["collector_tree"] = json.loads(json.dumps(tree1))
    for tn in P["partition_types"]:
        if tn != T:
            assert P["partition_types"][tn] == P0["partition_types"][tn]
    assert {k: v for k, v in P.items() if k != "partition_types"} == {k: v for k, v in P0.items() if k != "partition_types"}
    out = json.dumps(P, separators=seps) + "\n"
    open(pout, "w").write(out)
    rep = dict(event=ID, type=T, sites=SITES, reset_tree_moved=moved, tap_dropped=dropped, added_cycles=0,
               cells_each=CELLS, ff_each=FFS, shell_synth_cells=215257,
               src_sha256=hashlib.sha256(text.encode()).hexdigest(), dst_sha256=hashlib.sha256(out.encode()).hexdigest())
    if len(sys.argv) > 5:
        stext = open(sys.argv[4]).read()
        side = json.loads(stext)
        sst = next((k for k in (1, None) if json.dumps(side, indent=k) + "\n" == stext), 1)
        if moved:
            side["collector"]["types"][T]["tree"] = copy.deepcopy(t["clock"]["landing_contract"]["collector_tree"])
        open(sys.argv[5], "w").write(json.dumps(side, indent=sst) + "\n")
        rep["sidecar_changed"] = moved
    if rep_p:
        open(rep_p, "w").write(json.dumps(rep, indent=1) + "\n")
    print(json.dumps({k: rep[k] for k in ("reset_tree_moved", "tap_dropped", "added_cycles")}))


if __name__ == "__main__":
    main()
