def sfu_lane(n, m):
    sfu = g.find_paths(n, m, r'ot_su12_sfu'); maps = g.find_paths(n, m, r'sfu_lane_map')
    out = {}
    for k in range(16):
        inc = [p for p in sfu + maps if f'g_lane[{k}].' in p]
        out[f'{m}__lane{k}'] = (inc, [])
    return out


