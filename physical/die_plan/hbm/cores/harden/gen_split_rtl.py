#!/usr/bin/env python3
"""CORE-HBM-SPLIT (2026-10-23): RTL tops for split pieces that are a REMAINDER of a pinned module (module minus a
member).  Each top is a verbatim text transform of the twin the split.json 'rtl' field names (no pinned file edited):
the removed member instance is replaced by ports, every other line is copied.  Run from the repo root:

    python3 physical/die_plan/hbm/cores/harden/gen_split_rtl.py
"""
import re, os

OUT = 'rtl/hbm_accel/cores_split'


def module_text(path, name):
    t = open(path).read()
    m = re.search(r'(?ms)^module\s+' + re.escape(name) + r'\b.*?^endmodule', t)
    assert m, (path, name)
    return m.group(0)


def must_sub(t, old, new, count=1):
    assert t.count(old) == count, (old, t.count(old))
    return t.replace(old, new)


def side_rest():
    src = 'rtl/hbm_accel/generic/adapters/static_su/arithmetic/ot_hbm_su_static_side_s.sv'
    t = module_text(src, 'ot_hbm_su_static_side_s')
    t = must_sub(t, 'module ot_hbm_su_static_side_s #(parameter integer MUT=0, parameter integer SMUT=0, parameter integer MLAT=3, ALAT=3) (',
                 'module ot_hbm_su_side_rest_core #(parameter integer MUT=0, parameter integer MLAT=3, ALAT=3) (')
    t = must_sub(t, '    input wire [5:0] clk,', '    input wire [2:0] clk_r,            // {clk_side[5], clk_side[1], clk_side[0]}')
    t = must_sub(t, '    output wire        fault\n);',
                 '    output wire        fault,\n'
                 '    // side_softplus core pins (u_sp of ot_hbm_su_static_side_s)\n'
                 '    output wire        sp_v,\n'
                 '    input  wire [31:0] sp_r,\n'
                 '    input  wire        sp_fault\n);\n'
                 '    wire [5:0] clk = {clk_r[2], 3\'b000, clk_r[1], clk_r[0]};   // clk[4:2] belong to side_softplus')
    i = t.index('    ot_hbm_su_static_side_softplus_s')
    j = t.index('    // Engram gate (unchanged)')
    t = t[:i] + ('    // u_sp (side_softplus core) removed: its pins are this core\'s sp_* ports\n'
                 '    assign sp_v = v && fn == SFU_SPSQRT;\n'
                 '    assign y_sp = sp_r;\n'
                 '    assign f_sp = sp_fault;\n') + t[j:]
    t = must_sub(t, 'y_sp_c, ', '')
    if os.environ.get('OT_HBM_ONECLOCK','0')=='1':
        t=t.replace('MLAT=3, ALAT=3','MLAT=4, ALAT=4')
    hdr = ('// GENERATED by physical/die_plan/hbm/cores/harden/gen_split_rtl.py (CORE-HBM-SPLIT 2026-10-23).  Do not edit.\n'
           '// Split piece ot_hbm_su_static_pgslice_lg__side_rest (masters ot_hbm_su_static_pgslice_lg__pv0, plan q_su0/q_su1):\n'
           '//   = ot_hbm_su_static_side_s (the HBM-P5-RTLB twin, ' + src + ') minus u_sp\n'
           '//   (rsqrt, sqrt, Engram gate, result mux, fault OR), text copied verbatim; u_sp -> ports sp_v / sp_r / sp_fault.\n'
           '// Parent wiring (as ot_hbm_su_static_side_s): clk_r = {clk_side[5], clk_side[1], clk_side[0]};\n'
           '//   side_softplus core: clk = clk_side[4:2], v = sp_v, x = the lane side_x (shared with this core\'s x),\n'
           '//   r -> sp_r, fault -> sp_fault.\n'
           '`timescale 1ns/1ps\n')
    open(f'{OUT}/ot_hbm_su_static_pgslice_lg/ot_hbm_su_side_rest_core.sv', 'w').write(hdr + t + '\n')


def side_softplus():
    t = '''// CORE-HBM-SPLIT 2026-10-23.  Split piece ot_hbm_su_static_pgslice_lg__side_softplus (master
// ot_hbm_su_static_pgslice_lg__pv0, plan q_su0/q_su1) = u_side.u_sp of the HBM-P5-RTLB twin ot_hbm_su_static_side_s
// (rtl/hbm_accel/generic/adapters/static_su/arithmetic/ot_hbm_su_static_side_s.sv): ot_hbm_su_static_side_softplus_s
// #(LM 3, LA 3, FREG 1) (pinned softplus + fault pin register).  Its 'sp' output is unread in the master (left open
// there), so it is not a pin of the core.
`timescale 1ns/1ps
module ot_hbm_su_side_softplus_core (
    input  wire [2:0]  clk,      // clk_side[4:2]
    input  wire        rst_n,
    input  wire        v,        // side_rest sp_v
    input  wire [31:0] x,        // lane side_x
    output wire [31:0] r,
    output wire        fault
);
    ot_hbm_su_static_side_softplus_s #(.LM(3), .LA(3), .FREG(1)) u_sp (.clk(clk), .rst_n(rst_n), .v(v), .x(x), .sp(),
        .r(r), .vo(), .fault(fault));
endmodule
'''
    if os.environ.get('OT_HBM_ONECLOCK','0')=='1':
        t=t.replace('LM(3), .LA(3)','LM(4), .LA(4)').replace('LM 3, LA 3','LM 4, LA 4')
    open(f'{OUT}/ot_hbm_su_static_pgslice_lg/ot_hbm_su_side_softplus_core.sv', 'w').write(t)


def hc_tail_rest():
    d = 'rtl/hbm_accel/generic/peers/static_hc'
    a = module_text(f'{d}/ot_hgi_hc_tail_static_s.sv', 'ot_hgi_hc_tail_static_s')
    a = must_sub(a, 'module ot_hgi_hc_tail_static_s #(', 'module ot_hbm_hc_tail_static_rest #(')
    a = must_sub(a, '    output reg fault\n);',
                 '    output reg fault,\n'
                 '    // the Sinkhorn cores (sink = ot_hdc_sinkhorn_s = sk_step0 | sk_steady) are outside this core\n'
                 '    output wire [511:0] sk_in_e,\n'
                 '    input wire sk_in_ready, sk_out_valid, sk_fault,\n'
                 '    input wire [511:0] sk_y\n);')
    i = a.index('    ot_hdc_sinkhorn_s #(.ITERS(ITERS),.EPS(HC_EPS)) sink(')
    j = a.index('    reg sink_fault;')
    a = a[:i] + ('    // sink (ot_hdc_sinkhorn_s) removed: in_valid = sink_launch, clk = sink_clk, rst_n = rst_n at the parent\n'
                 '    assign sk_in_e = se; assign sr = sk_in_ready; assign sv = sk_out_valid; assign sy = sk_y;\n'
                 '    assign sf = sk_fault; assign sbusy = 1\'b0;\n') + a[j:]
    b = module_text(f'{d}/ot_hbm_hc_tail_unit_static_s.sv', 'ot_hbm_hc_tail_unit_static_s')
    b = must_sub(b, 'module ot_hbm_hc_tail_unit_static_s #(', 'module ot_hbm_hc_tail_rest_core #(')
    b = must_sub(b, '    output wire          fault\n);',
                 '    output wire          fault,\n'
                 '    // Sinkhorn core pins (u_tail.sink of ot_hbm_hc_tail_unit_static_s)\n'
                 '    output wire          sk_clk,        // sink clock (core clock / SDIV), drives sk_step0 + sk_steady clk\n'
                 '    output wire          sk_in_valid,   // sink_launch\n'
                 '    output wire [511:0]  sk_in_e,\n'
                 '    input  wire          sk_in_ready, sk_out_valid, sk_fault,\n'
                 '    input  wire [511:0]  sk_y\n);')
    b = must_sub(b, 'ot_hgi_hc_tail_static_s #(.MUT_PRE(MUT_PRE)) u_tail (', 'ot_hbm_hc_tail_static_rest #(.MUT_PRE(MUT_PRE)) u_tail (')
    b = must_sub(b, '.e_ready(), .result_v(tv), .result(result), .fault(tf));',
                 '.e_ready(), .result_v(tv), .result(result), .fault(tf),\n'
                 '        .sk_in_e(sk_in_e), .sk_in_ready(sk_in_ready), .sk_out_valid(sk_out_valid), .sk_fault(sk_fault), .sk_y(sk_y));\n'
                 '    assign sk_clk = sclk; assign sk_in_valid = sl;')
    hdr = ('// GENERATED by physical/die_plan/hbm/cores/harden/gen_split_rtl.py (CORE-HBM-SPLIT 2026-10-23).  Do not edit.\n'
           '// Split piece ot_hbm_hc_root_static__tail{0,1}_rest (master ot_hbm_hc_root_static): the HBM-P5-RTLB integration\n'
           f'// twins {d}/ot_hbm_hc_tail_unit_static_s.sv + ot_hgi_hc_tail_static_s.sv, text verbatim, minus\n'
           '// u_tail.sink (ot_hdc_sinkhorn_s = the sk_step0 / sk_steady cores); sink pins -> sk_* ports.\n'
           '`timescale 1ns/1ps\n`default_nettype none\n')
    os.makedirs(f'{OUT}/ot_hbm_hc_root_static', exist_ok=True)
    open(f'{OUT}/ot_hbm_hc_root_static/ot_hbm_hc_tail_rest_core.sv', 'w').write(hdr + a + '\n\n' + b + '\n`default_nettype wire\n')


if __name__ == '__main__':
    side_rest()
    side_softplus()
    hc_tail_rest()
