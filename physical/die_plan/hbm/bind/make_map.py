#!/usr/bin/env python3
"""HBM d4g: as-built (r18h5 die.v) instance -> plan partition map for tools/die_plan/bind.py (BINDER4 10-23).

    python3 physical/die_plan/hbm/bind/make_map.py DIE_V [--out asbuilt_map.json]

* Die-level blocks: census/map_v2.json `parts` (the plan's own as-built -> partition map).  The local name of a block
  inside its partition is the plan generator's ROLE (gen_plan_v2.role_of over logical_labels: quadrant tokens -> Q,
  SM-side half families by index), so the four quadrant replicas of a type carry identical content names.
* SM: map_v2 `groups` maps sm_<half><k> -> <Q>_sm<k> -> 4 stacked quarter partitions <Q>_sm<k>a..d.  The SM parent
  ot_hbm_accel_smh_attn is dissolved (QSPLIT=1, define OT_SM_QSPLIT) and its children go to their quarter as
  sm_split/sm_split.json lays them out: columns c0,c1 -> d, c2,c3 + front + int8 tile + top glue -> c, c4,c5 -> b,
  c6,c7 -> a; the QSPLIT registers by the quarter in their name (u_qs_c_* -> c, u_qs_b_* -> b).
* hb_ckgen (hfd_ckgen_nolink) is the die clock/reset source (asbuilt.sources), not mapped.
"""
import argparse
import collections
import gzip
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLAN = HERE.parent
sys.path.insert(0, str(PLAN))
sys.path.insert(0, str(PLAN.parents[2] / "tools" / "die_plan"))
import gen_plan_v2 as G  # noqa: E402

INST_RE = re.compile(r'^\s*([A-Za-z_][\w$]*)\s+(?:#\((?:[^()]|\([^()]*\))*\)\s*)?(\\?[\w$\[\].]+)\s*\(', re.M)
RELAY = re.compile(r'^hbfd_(rly|lh|lh0|land|land0)_|^hbfd_pad$')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("die_v")
    ap.add_argument("--out", default=str(HERE / "asbuilt_map.json"))
    a = ap.parse_args()
    txt = gzip.open(a.die_v, "rt").read() if a.die_v.endswith(".gz") else Path(a.die_v).read_text()
    blk = {i: m for m, i in INST_RE.findall(txt)
           if m not in ("module", "input", "output", "wire", "assign") and not RELAY.match(m)}
    mp = json.loads((PLAN / "census" / "map_v2.json").read_text())
    cen = json.load(gzip.open(PLAN / "inputs" / "census" / "hbm_census.json.gz"))
    lab = G.logical_labels(list(blk), cen["groups"])
    plan = json.loads((PLAN / "die_plan.json").read_text())
    pnames = {p["name"] for p in plan["partitions"]}
    parts, rules, notes = {}, [], collections.Counter()
    clash = collections.defaultdict(list)
    for inst, mod in sorted(blk.items()):
        p = mp["parts"].get(inst)
        if p is None:
            notes[f"unmapped {mod}"] += 1
            continue
        if p in mp["groups"]:          # SM: quarters by rule below
            for q, sub in (("d", r"g_c\[[01]\]\..*"), ("c", r"g_c\[[23]\]\..*"), ("b", r"g_c\[[45]\]\..*"),
                           ("a", r"g_c\[[67]\]\..*"), ("c", r"(.*\.)?u_qs_c_\w+"), ("b", r"(.*\.)?u_qs_b_\w+"),
                           ("c", r"u_front"), ("c", r"g_int8\..*"), ("c", r"\$.*")):
                part = f"{p}{q}"
                assert part in pnames, part
                rules.append([re.escape(inst) + r"\." + sub, part])
            continue
        assert p in pnames, (inst, p)
        _, role = G.role_of(inst, lab)
        parts[inst] = [p, role]
        clash[(p, role)].append(inst)
    bad = {f"{k[0]}:{k[1]}": v for k, v in clash.items() if len(v) > 1}
    if bad:
        # two blocks of one partition with one role (should not happen): fall back to the instance name
        for k, v in bad.items():
            for inst in v:
                parts[inst] = [parts[inst][0], inst]
    out = dict(note="GENERATED by physical/die_plan/hbm/bind/make_map.py (BINDER4 10-23): r18h5 die.v -> plan 1098c8cc "
                    "partitions; local = gen_plan_v2 role (quadrant-free); SM children by sm_split quarters",
               parts=parts, rules=rules, role_clash=bad, unmapped=dict(notes))
    Path(a.out).write_text(json.dumps(out, indent=1) + "\n")
    print(f"parts {len(parts)} rules {len(rules)} role_clash {len(bad)} unmapped {dict(notes)} -> {a.out}")


if __name__ == "__main__":
    main()
