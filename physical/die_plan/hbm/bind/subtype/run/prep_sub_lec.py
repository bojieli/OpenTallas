#!/usr/bin/env python3
"""BIND-SUBTYPE-2 11-11 (DO_NOT_COUNT): build a repository-LEC (tools/die_plan/lec.py) kit that proves
NEW bound type == OLD bound type with every native leaf replaced by the rule's composition.

    prep_sub_lec.py OLD_RTL_DIR NEW_RTL_DIR RULE.json TYPE SUBS_DIR KIT [--neg]

gold (kit RTL) = OLD rtl/hbm_arch_<TYPE>.sv + OLD rtl/bind_cells.sv + native_as_comp.sv + the sub-core sources
                 (blackboxed: SYNTH_BLACKBOXES), where native_as_comp.sv defines module <rule.native> as a renamed copy
                 of the rule top (ports renamed by rule.rename, shared ports rule.share become internal wires driven by
                 the native port they share), so the gold hierarchy names equal the gate's;
gate (--netlist) = NEW rtl/hbm_arch_<TYPE>.sv + NEW rtl/bind_cells.sv + the rule top file (glue, wires only);
the sub-cores are stubs on both sides (lec.py: input pins = compare points, outputs = shared free inputs).
--neg: negative control, swap two bits of one substituted instance's 32-bit input in the gate copy (must FAIL).
All files are real copies inside KIT (docker mounts KIT at /work read-only)."""
import json
import re
import shutil
import sys
from pathlib import Path

a = [x for x in sys.argv[1:] if not x.startswith("--")]
neg = "--neg" in sys.argv
old_d, new_d, rule_p, typ, subs_d, kit = map(Path, a[:6]) if len(a) >= 6 else sys.exit(__doc__)
typ = str(typ)
rule = json.loads(rule_p.read_text())
rule = rule["subtype_bind"][0] if "subtype_bind" in rule else rule
native, top, rename, share = rule["native"], rule["top"], rule.get("rename", {}), rule.get("share", {})
glue_f = next(Path(f) for f in rule["files"] if f.endswith(top + ".sv"))
sub_fs = [Path(f) for f in rule["files"] if Path(f) != glue_f]
sub_fs = [subs_d / f.name if subs_d.is_dir() and (subs_d / f.name).is_file() else f for f in sub_fs]
kit.mkdir(parents=True, exist_ok=True)
(kit / "rtl").mkdir(exist_ok=True)
(kit / "gate").mkdir(exist_ok=True)
shutil.copyfile(old_d / f"hbm_arch_{typ}.sv", kit / "rtl" / f"hbm_arch_{typ}.sv")
shutil.copyfile(old_d / "bind_cells.sv", kit / "rtl" / "bind_cells.sv")
# sub-core masters = modules the glue instantiates that the glue does not define; port-only copies (black boxes)
gt = glue_f.read_text()
gdef = set(re.findall(r"^\s*module\s+(\w+)", gt, flags=re.M))
ginst = set(re.findall(r"^\s*(\w+)\s+(?:#\(.*?\)\s*)?u_\w+\s*\(", gt, flags=re.M)) - gdef
mods, bbf = [], []
for f in sub_fs:
    t = f.read_text()
    for mm in re.finditer(r"^\s*module\s+(\w+)\b.*?\);", t, flags=re.M | re.S):
        if mm.group(1) in ginst:
            mods.append(mm.group(1))
            p = kit / "rtl" / f"{mm.group(1)}_bb.sv"
            p.write_text(f"// port-only copy of {f}\n`default_nettype none\n{mm.group(0).strip()}\nendmodule\n")
            bbf.append(p.name)
assert sorted(mods) == sorted(ginst), (mods, ginst)

# gold: native := renamed copy of the rule top (only the top module changes name/ports; submodules keep their names,
# so the hierarchy below the leaf instance is identical on both sides)
g = glue_f.read_text()
m = re.search(r"module\s+" + re.escape(top) + r"\s*\((.*?)\);(.*?)endmodule", g, flags=re.S)
hdr, body = m.group(1), m.group(2)
inv = {}
for tp in re.findall(r"(?:input|output)\s+wire\s+(?:\[[^\]]*\]\s*)?(\w+)", hdr):
    inv[tp] = None if tp in share else rename.get(tp, tp)
decls = []
for d in re.finditer(r"(input|output)\s+wire\s+(\[[^\]]*\]\s*)?(\w+)", hdr):
    if inv[d.group(3)] is not None:
        decls.append(f"{d.group(1)} wire {d.group(2) or ''}{inv[d.group(3)]}")
shared = [f"    wire {tp} = {src};" for tp, src in share.items()]
body2 = body
for tp, nn in inv.items():   # rename references inside the top's body (port connections .x(tp))
    if nn is not None and nn != tp:
        body2 = re.sub(r"\(\s*" + re.escape(tp) + r"\s*\)", f"({nn})", body2)
rest = g[:m.start()] + g[m.end():]
comp = (f"// GENERATED by prep_sub_lec.py (BIND-SUBTYPE-2): {native} := {top} under rule rename/share\n"
        f"`default_nettype none\nmodule {native} (\n    " + ",\n    ".join(decls) + ");\n"
        + "\n".join(shared) + "\n" + body2 + "endmodule\n" + re.sub(r"`default_nettype\s+none", "", rest))
(kit / "rtl" / "native_as_comp.sv").write_text(comp)

# gate
n = (new_d / f"hbm_arch_{typ}.sv").read_text()
if neg:
    mm = re.search(r"(\b" + re.escape(top) + r"\s+(\S+)\s*\(.*?\.sfu_vi_q\()([^()]*?)(\))", n, flags=re.S)
    e = mm.group(3).strip()
    n = n[:mm.start(3)] + f"{{{e}[31:2], {e}[0], {e}[1]}}" + n[mm.end(3):]
    (kit / "NEG_CONTROL").write_text(f"gate {mm.group(2)}.sfu_vi_q bits 0/1 swapped ({e})\n")
gate = n + "\n" + (new_d / "bind_cells.sv").read_text() + "\n" + glue_f.read_text()
(kit / "gate" / f"new_{typ}.v").write_text(gate)
vf = " ".join(f"/work/rtl/{p}" for p in [f"hbm_arch_{typ}.sv", "bind_cells.sv", "native_as_comp.sv"] + bbf)
(kit / "config.mk").write_text(f"export DESIGN_NAME = hbm_arch_{typ}\nexport VERILOG_FILES = {vf}\n"
                               f"export SYNTH_BLACKBOXES = {' '.join(mods)}\n")
print("KIT", kit, "blackboxes", mods, "neg" if neg else "pos")
