"""PATH-HBM/Q3 10-25: the q3 (NW hub, TKM interface + ARGMAX + NLINK 3) over-cap split integration twin, as
gen_coll_q2_s.py does for q2.  Generated from the pinned rtl/hbm_accel/generic/collective/p2p/ot_hfd_coll_q_hard_v8g.sv
(read only):
  ot_hfd_coll_q3_hard_v8x_s = ot_hfd_coll_q3_hard_v8x on ot_hfd_coll_q_hard_v8g_body_s (defined in the generated
                              ot_hfd_coll_q2_hard_v8g_s.sv: u_reduce = ot_hgi_coll_reduce_static_pr; read both files).
Ports, children and every other edge unchanged; COMPILER: same +1 edge on the reduce-source capture slot as q2_s.
Edge _pr (PATH-HBM/Q3 10-25): the q3 body is its own copy ot_hfd_coll_q3_body_s of body_s with the coll_q3_edge
members swapped for their pin-registered twins (rtl/.../p2p/ot_hgi_coll_edge_pr.sv, same ports):
  g_link[k].u_link    ot_hgi_coll_link_e -> ot_hgi_coll_link_e_pr        (epoch select after the pin flops: 0 edges)
  g_q3.t192.u_arg     ot_hgi_coll_argmax_m_tp192 -> .._tp192_pr        (pin-captured fold only: ARG publish +1 edge;
                                                                          COMPILER: ARG-source capture slot +1 edge)
usage: gen_coll_q3_s.py REPO_ROOT"""
import sys
from pathlib import Path
root = Path(sys.argv[1]); P = root / "rtl/hbm_accel/generic/collective/p2p"
s = (P / "ot_hfd_coll_q_hard_v8g.sv").read_text()
k = s.index("module ot_hfd_coll_q3_hard_v8x #("); m = s.index("endmodule", k) + len("endmodule")
q3 = s[k:m]
def sub(t, a, b):
    assert t.count(a) == 1, (a, t.count(a)); return t.replace(a, b)
q3 = sub(q3, "module ot_hfd_coll_q3_hard_v8x #(", "module ot_hfd_coll_q3_hard_v8x_s #(")
q3 = sub(q3, " ot_hfd_coll_q_hard_v8g_body #(", " ot_hfd_coll_q3_body_s #(")
s2 = (P / "ot_hfd_coll_q2_hard_v8g_s.sv").read_text()
k = s2.index("module ot_hfd_coll_q_hard_v8g_body_s #("); m = s2.index("endmodule", k) + len("endmodule")
body = s2[k:m]
body = sub(body, "module ot_hfd_coll_q_hard_v8g_body_s #(", "module ot_hfd_coll_q3_body_s #(")
body = sub(body, "  ot_hgi_coll_argmax_m_tp192 u_arg(", "  ot_hgi_coll_argmax_m_tp192_pr u_arg(")
body = sub(body, "  ot_hgi_coll_link_e u_link(", "  ot_hgi_coll_link_e_pr u_link(")
hdr = ("`timescale 1ns/1ps\n`default_nettype none\n"
       "// GENERATED by physical/die_plan/hbm/over_cap_split/gen_coll_q3_s.py (PATH-HBM/Q3 10-25) from the pinned\n"
       "// ot_hfd_coll_q_hard_v8g.sv (q3_hard_v8x parent text verbatim except the module names). Body = body_s of\n"
       "// ot_hfd_coll_q2_hard_v8g_s.sv (u_reduce = ot_hgi_coll_reduce_static_pr): split ring_ag | reduce | body(q3) with\n"
       "// the same registered crossings as coll_q2.  q3 body copy ot_hfd_coll_q3_body_s: edge members = _pr twins\n"
       "// (ot_hgi_coll_edge_pr.sv: link_e_pr 0 edges, argmax_m_tp192_pr ARG publish +1 edge).\n")
(P / "ot_hfd_coll_q3_hard_v8x_s.sv").write_text(hdr + body + "\n\n" + q3 + "\n`default_nettype wire\n")
print("generated ot_hfd_coll_q3_hard_v8x_s.sv")
