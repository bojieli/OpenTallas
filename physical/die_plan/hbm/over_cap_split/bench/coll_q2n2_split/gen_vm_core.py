#!/usr/bin/env python3
"""gen_vm_core.py [REPO] (HBM-CORES-RTL 2026-10-26): ot_hfd_coll_q2n2_vm_core for the NE hub q2 NLINK 2 collective.

The q2n2 vm piece = u_body.u_vmasm + u_body.u_writer of ot_hfd_coll_q2_hard_v8g_s #(NLINK 2, TP 192, AR_ITER 1, ROWS 256,
VM_RT 81): the same two member instances (same module types, no parameters) as the q3 vm piece, whose top
ot_hfd_coll_q3_vm_core build_split_tops.py generated from the q3 as-built netlist.  The q2 parent has no TKM path: its
body drives the writer's tkw_v / tkw_d with the constant 0 (ot_hfd_coll_q2_hard_v8g_s.sv: tk_w_* = 0 when no tkx), so the
q2n2 plan pin file (plan_b1n5 cores/ot_hfd_coll_q2n2_vm_core__924.48x509.76*.json) carries no writer_tkw_v/_d and no
writer_clk_tkw.  This script derives the q2n2 top from the q3 top text: the three ports are removed, tkw_v / tkw_d are
driven by the same constant 0 the parent drives, and the tkw capture flops (a0/d0/m0 tkw slice, v0[4]) are clocked by
writer_clk_rgx_ctrl (another tap of the same writer clock root; they capture the constant 0, exactly as in the parent).
Everything else is byte-identical.  Composition vs the parent: lec_compose.sh (lec.py, mutant must be caught).
"""
import re, sys, os
R = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), *[".."] * 6))
src = os.path.join(R, "rtl/hbm_accel/cores_split/ot_hfd_coll_q3_hard_v8x/ot_hfd_coll_q3_vm_core.sv")
dst = os.path.join(R, "rtl/hbm_accel/cores_split/ot_hfd_coll_q2n2_hard_v8g/ot_hfd_coll_q2n2_vm_core.sv")
t = open(src).read()
rep = [
    ("module ot_hfd_coll_q3_vm_core (", "module ot_hfd_coll_q2n2_vm_core ("),
    ("    input wire writer_clk_tkw,\n", ""),
    ("    input wire writer_tkw_v,\n", ""),
    ("    input wire [567:0] writer_tkw_d,\n", ""),
    ("    assign u_writer__clk_tkw = writer_clk_tkw;\n",
     "    assign u_writer__clk_tkw = writer_clk_rgx_ctrl;   // q2: tkw capture flops load the constant 0 (no TKM)\n"),
    ("    assign u_writer__tkw_v = writer_tkw_v;\n", "    assign u_writer__tkw_v = 1'b0;   // q2 parent body: tk_w_v = 1'b0\n"),
    ("    assign u_writer__tkw_d[567:0] = writer_tkw_d[567:0];\n",
     "    assign u_writer__tkw_d[567:0] = 568'd0;   // q2 parent body: {tk_w_addr, tk_w_mask, tk_w_data} = 0\n"),
]
for a, b in rep:
    assert t.count(a) == 1, a
    t = t.replace(a, b)
hdr = [l for l in t.splitlines(True) if l.startswith("//")]
body = "".join(l for l in t.splitlines(True) if not l.startswith("//"))
assert "tkw" not in re.search(r"(?s)module ot_hfd_coll_q2n2_vm_core \((.*?)\);", body).group(1)
head = ("// GENERATED by physical/die_plan/hbm/over_cap_split/bench/coll_q2n2_split/gen_vm_core.py (HBM-CORES-RTL 2026-10-26)"
        " from ot_hfd_coll_q3_vm_core.sv. Do not edit.\n"
        "// Functional split-piece coll_q2n2_vm: master ot_hfd_coll_q2_hard_v8g_s #(NLINK 2, TP 192, AR_ITER 1, ROWS 256, VM_RT 81);"
        " members u_vmasm = ot_hgi_coll_vmasm_sliced_v7 (u_body.u_vmasm), u_writer = ot_hgi_coll_static_vmwrite_roots_v6_physical"
        " (u_body.u_writer).\n// tkw inputs = the parent's constant 0 (q2 has no TKM); see the generator docstring.\n")
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "w").write(head + body)
print(dst)
