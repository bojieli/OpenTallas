#!/usr/bin/env python3
"""Extract the RF4 owner (renamed ot_svgr_own_rf4x) + ot_svgr_rf4_skid from the RF4 ot_svgr_split.sv for the lock-step bench.
usage: python3 -I make_rf4x.py ot_svgr_split.sv rf4_only.sv"""
import sys
L = open(sys.argv[1]).read().split("\n")
def block(start):
    i = next(k for k, l in enumerate(L) if l.startswith(start))
    j = next(k for k in range(i, len(L)) if L[k].startswith("endmodule"))
    return L[i:j + 1]
sk = block("module ot_svgr_rf4_skid ")
own = block("module ot_svgr_own #(")  # first = the RF2-branch owner that carries RF4
own[0] = own[0].replace("module ot_svgr_own #(", "module ot_svgr_own_rf4x #(", 1)
out = ["`timescale 1ns/1ps", "// GENERATED by make_rf4x.py from " + sys.argv[1], "`ifdef OT_SVGR_OWN_RF4"] + sk + ["`endif"] + own
open(sys.argv[2], "w").write("\n".join(out) + "\n")
