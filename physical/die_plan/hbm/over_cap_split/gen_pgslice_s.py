"""HBM-P5-RTLB 10-23: generate the pgslice over-cap split twins from the pinned sources (read only; every replacement
must hit exactly once):
  ot_hbm_su_static_pgslice_s    = ot_hbm_su_static_pgslice, side pipe = ot_hbm_su_static_side_s (side_softplus | side_rest
                                  cut, fault pin register), PIN_REG default 1 (the plan variant: lane_pinreg leaves)
  ot_hbm_su_static_pgslice_lg_s = ot_hbm_su_static_pgslice_lg on pgslice_s, PIN_REG default 1
SMUT (bench mutant, 0 = design) is passed to the side twin.  usage: gen_pgslice_s.py REPO_ROOT"""
import sys
from pathlib import Path
root = Path(sys.argv[1]); T = root / 'rtl/hbm_accel/generic/adapters/static_su/top'
HDR = ('// GENERATED by physical/die_plan/hbm/over_cap_split/gen_pgslice_s.py (HBM-P5-RTLB 10-23) from the pinned {src}\n'
       '// (unchanged except the lines this generator replaces).  pgslice over-cap split plan variant: PIN_REG 1 (every lane\n'
       '// pin registered: +2 edges on store / RF requests, +4 on writes / reducer operands, su_top_compile --pin-reg 1)\n'
       '// and (Q0G0) the side pipe cut side_softplus | side_rest (ot_hbm_su_static_side_s: 0 data edges, +1 edge on the\n'
       '// sqrt(softplus) fault pulse only).\n')

def sub(s, a, b):
    assert s.count(a) == 1, (a, s.count(a))
    return s.replace(a, b)

def gen(src, dst, reps):
    s = (T / src).read_text()
    for a, b in reps:
        s = sub(s, a, b)
    i = s.index('`timescale'); j = s.index('\n', i) + 1
    (T / dst).write_text(s[:j] + HDR.format(src=src) + s[j:])

gen('ot_hbm_su_static_pgslice.sv', 'ot_hbm_su_static_pgslice_s.sv', [
    ('module ot_hbm_su_static_pgslice #(', 'module ot_hbm_su_static_pgslice_s #(\n parameter integer SMUT=0,'),
    (' parameter integer PIN_REG=0,', ' parameter integer PIN_REG=1,'),
    ('ot_hbm_su_static_side u_side(', 'ot_hbm_su_static_side_s #(.SMUT(SMUT)) u_side('),
])
gen('ot_hbm_su_static_pgslice_lg.sv', 'ot_hbm_su_static_pgslice_lg_s.sv', [
    ('module ot_hbm_su_static_pgslice_lg #(', 'module ot_hbm_su_static_pgslice_lg_s #(\n parameter integer SMUT=0,'),
    (' parameter integer PIN_REG=0,', ' parameter integer PIN_REG=1,'),
    ('ot_hbm_su_static_pgslice #(', 'ot_hbm_su_static_pgslice_s #(.SMUT(SMUT),'),
])
print('generated ot_hbm_su_static_pgslice_s.sv ot_hbm_su_static_pgslice_lg_s.sv')
