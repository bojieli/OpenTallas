"""HBM-P5-RTLB 10-23: generate the hc_root over-cap split INTEGRATION twins from the pinned sources (pinned files are
read only; every replacement must hit exactly once):
  ot_hgi_hc_tail_static_s      = ot_hgi_hc_tail_static with sink = ot_hdc_sinkhorn_s (core split: step0 | steady)
  ot_hbm_hc_tail_unit_static_s = ot_hbm_hc_tail_unit_static with the tail_s and the calendar's sink_capture moved by
                                 ONE sink edge: CAP 289 -> 289 + SDIV (L = 198 + SDIV + CAP + 2: 496 -> 503 core edges)
  ot_hbm_hc_root_static_s      = ot_hbm_hc_root_static scoped to the tail_unit_s (emit >= tail launch + L + 1 = 504)
SMUT (bench mutant, 0 = design): 1 = CAP NOT moved (capture one sink edge before the split Sinkhorn's out_valid).
usage: gen_hc_tail_s.py REPO_ROOT"""
import sys
from pathlib import Path
root = Path(sys.argv[1]); H = root / 'rtl/hbm_accel/generic/peers/static_hc'
HDR = ('// GENERATED by physical/die_plan/hbm/over_cap_split/gen_hc_tail_s.py (HBM-P5-RTLB 10-23) from the pinned {src}\n'
       '// (unchanged except the lines this generator replaces).  hc_root over-cap split: each tail\'s Sinkhorn is the\n'
       '// core-split twin ot_hdc_sinkhorn_s (ot_hdc_sk_step0 | ot_hdc_sk_steady, +1 sink edge: out_valid 2 ITERS + 2 = 42);\n'
       '// the tail calendar captures one sink edge (SDIV = 7 core edges) later: tail result latency L 496 -> 503.\n')

def sub(s, a, b, n=1):
    c = s.count(a)
    assert c == n, (a, c)
    return s.replace(a, b)

def gen(src, dst, reps):
    s = (H / src).read_text()
    for a, b in reps:
        s = sub(s, a, b)
    i = s.index('`timescale'); j = s.index('\n', i) + 1
    s = s[:j] + HDR.format(src=src) + s[j:]
    (H / dst).write_text(s)

gen('ot_hgi_hc_tail_static.sv', 'ot_hgi_hc_tail_static_s.sv', [
    ('module ot_hgi_hc_tail_static #(', 'module ot_hgi_hc_tail_static_s #('),
    ('ot_hdc_sinkhorn #(.ITERS(ITERS),.EPS(HC_EPS)) sink(', 'ot_hdc_sinkhorn_s #(.ITERS(ITERS),.EPS(HC_EPS)) sink('),
    ('// has completed (ITERS20).', '// has completed (ITERS20; the split Sinkhorn: 42nd edge).'),
])
gen('ot_hbm_hc_tail_unit_static.sv', 'ot_hbm_hc_tail_unit_static_s.sv', [
    ('module ot_hbm_hc_tail_unit_static #(', 'module ot_hbm_hc_tail_unit_static_s #('),
    ('    parameter integer CAP  = 289,\n', '    parameter integer SMUT = 0,\n    parameter integer CAP  = 289 + ((SMUT == 1) ? 0 : SDIV),   // split Sinkhorn: +1 sink edge\n'),
    ('    ot_hgi_hc_tail_static #(.MUT_PRE(MUT_PRE)) u_tail (', '    ot_hgi_hc_tail_static_s #(.MUT_PRE(MUT_PRE)) u_tail ('),
])
gen('ot_hbm_hc_root_static.sv', 'ot_hbm_hc_root_static_s.sv', [
    ('module ot_hbm_hc_root_static #(', 'module ot_hbm_hc_root_static_s #('),
    ('    parameter integer MUT  = 0\n)(', '    parameter integer MUT  = 0,\n    parameter integer SMUT = 0                   // split bench mutant (tail_unit_s SMUT)\n)('),
    ('ot_hbm_hc_tail_unit_static #(.MUT_PRE((MUT == 2 && gu == 0) ? 1 : 0)) u_t (',
     'ot_hbm_hc_tail_unit_static_s #(.MUT_PRE((MUT == 2 && gu == 0) ? 1 : 0), .SMUT(SMUT)) u_t ('),
])
print('generated ot_hgi_hc_tail_static_s.sv ot_hbm_hc_tail_unit_static_s.sv ot_hbm_hc_root_static_s.sv')
