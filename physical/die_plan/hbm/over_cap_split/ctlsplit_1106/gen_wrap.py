# Build clean-port wrappers for the split3__ctl 2-piece split from yosys split.v (submod output).
# out: ctl_pipe_core.v (pipe submod + pipe_core wrapper), ctl_rest_core.v (rest submod + rest_core wrapper),
#      ctl_compose.v (ot_hgi_sfu_split3_ctl_core = rest_core + pipe_core, same ports as the original), seam.json
import re, sys, json
src, out = sys.argv[1], sys.argv[2]
txt = open(src).read()
mods = {m.group(1).lstrip('\\'): m.group(0) for m in re.finditer(r'(?ms)^module\s+(\S+?)\s*\(.*?^endmodule\n', txt)}
top = mods['ot_hgi_sfu_split3_ctl_core']; pipe = mods['ot_hgi_sfu_split3_ctl_pipe']; rest = mods['ot_hgi_sfu_split3_ctl_rest']
m = re.search(r'(?ms)^  ot_hgi_sfu_split3_ctl_pipe ot_hgi_sfu_split3_ctl_pipe \((.*?)\n  \);\n', top)
inst = m.group(0); conns = re.findall(r'\.(\\\S+ |\w+)\s*\((.*?)\)(?:,|\n|$)', m.group(1), re.S)
# pipe port directions
pdir = {}
for d_, w_, n_ in re.findall(r'^\s*(input|output)\s+(\[\d+:\d+\]\s+)?(\\\S+ |\w+)\s*;', pipe, re.M):
    pdir[n_.strip()] = (d_, w_)
TOPP = {'clk', 'clk_lg', 'rst_lg_n'}
def key(n):
    return [int(x) if x.isdigit() else x for x in re.split(r'(\d+)', n)]
ins, outs, fixed = [], [], []
for pn, expr in conns:
    pn = pn.strip(); expr = expr.strip()
    if pn in TOPP: fixed.append((pn, expr)); continue
    d_, w_ = pdir[pn]; assert not w_, pn
    (ins if d_ == 'input' else outs).append((pn, expr))
rst = [x for x in ins if 'relay_q' in x[0]]; assert len(rst) == 1
ins = sorted([x for x in ins if 'relay_q' not in x[0]], key=lambda x: key(x[0])); outs = sorted(outs, key=lambda x: key(x[0]))
NI, NO = len(ins), len(outs)
seam = {'seam_d': [p for p, _ in ins], 'seam_q': [p for p, _ in outs], 'rst_vm_n': rst[0][0]}
json.dump(seam, open(out + '/seam.json', 'w'), indent=0)
hdr = '// HBM-FORM-TIMING-10 2026-11-06: split3__ctl 2-piece split (pure delay-line cut, 0 cycles). GENERATED by gen_wrap.py from yosys submod; do not edit.\n'
# pipe core wrapper
pw = [hdr, pipe, 'module ot_hgi_sfu_split3_ctl_pipe_core(\n input wire clk,\n input wire [3:0] clk_lg,\n input wire [3:0] rst_lg_n,\n input wire rst_vm_n,\n'
      f' input wire [{NI-1}:0] seam_d,\n output wire [{NO-1}:0] seam_q\n);\n ot_hgi_sfu_split3_ctl_pipe u_pipe(\n']
cl = [f'  .clk(clk)', f'  .clk_lg(clk_lg)', f'  .rst_lg_n(rst_lg_n)', f'  .{rst[0][0]} (rst_vm_n)']
cl += [f'  .{p} (seam_d[{i}])' for i, (p, _) in enumerate(ins)] + [f'  .{p} (seam_q[{i}])' for i, (p, _) in enumerate(outs)]
pw.append(',\n'.join(cl) + '\n );\nendmodule\n')
open(out + '/ctl_pipe_core.v', 'w').write(''.join(pw))
# rest core = original top with the pipe instance replaced by seam ports
hm = re.match(r'(?ms)module\s+ot_hgi_sfu_split3_ctl_core\((.*?)\);\n', top)
body = top[hm.end():]
body = body.replace(inst, '')
rc = 'module ot_hgi_sfu_split3_ctl_rest_core(' + hm.group(1) + ', seam_d, seam_q, rst_vm_n);\n'
rc += f'  output wire [{NI-1}:0] seam_d;\n  input wire [{NO-1}:0] seam_q;\n  output wire rst_vm_n;\n'
asg = [f'  assign seam_d[{i}] = {e} ;' for i, (_, e) in enumerate(ins)] + [f'  assign rst_vm_n = {rst[0][1]} ;']
asg += [f'  assign {e} = seam_q[{i}] ;' for i, (_, e) in enumerate(outs)]
for pn, e in fixed: assert e == pn, (pn, e)
body = body.replace('endmodule\n', '\n'.join(asg) + '\nendmodule\n')
open(out + '/ctl_rest_core.v', 'w').write(hdr + rest + rc + body)
# compose (proof top, original name and ports)
names = [x.strip() for x in hm.group(1).replace('\n', ' ').split(',')]
decl = re.findall(r'^\s*(input|output)\s+(\[\d+:\d+\]\s+)?(\w+)\s*;', top, re.M)
cp = [hdr, 'module ot_hgi_sfu_split3_ctl_core(' + ', '.join(names) + ');\n']
cp += [f'  {d_} {w_ or ""}{n_};\n' for d_, w_, n_ in decl]
cp += [f'  wire [{NI-1}:0] seam_d;\n  wire [{NO-1}:0] seam_q;\n  wire rst_vm_n;\n']
cp += ['  ot_hgi_sfu_split3_ctl_rest_core u_rest(' + ', '.join(f'.{n}({n})' for n in names) + ', .seam_d(seam_d), .seam_q(seam_q), .rst_vm_n(rst_vm_n));\n']
cp += ['  ot_hgi_sfu_split3_ctl_pipe_core u_pipe(.clk(clk), .clk_lg(clk_lg), .rst_lg_n(rst_lg_n), .rst_vm_n(rst_vm_n), .seam_d(seam_d), .seam_q(seam_q));\nendmodule\n']
open(out + '/ctl_compose.v', 'w').write(''.join(cp))
print('seam_d', NI, 'seam_q', NO, 'fixed', fixed)
