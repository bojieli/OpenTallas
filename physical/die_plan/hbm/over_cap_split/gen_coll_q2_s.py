"""HBM-P5-RTLB 10-23: generate the coll_q2 over-cap split integration twin from the pinned
rtl/hbm_accel/generic/collective/p2p/ot_hfd_coll_q_hard_v8g.sv (read only):
  ot_hfd_coll_q_hard_v8g_body_s = the v8g body with u_reduce = ot_hgi_coll_reduce_static_pr (input pin registers on every
                                  body -> reduce crossing + fault register: reduce +1 edge, fault +2)
  ot_hfd_coll_q2_hard_v8g_s     = ot_hfd_coll_q2_hard_v8g on body_s (ports, children, every other edge unchanged)
COMPILER: the qslots reduce-source capture (capture_calendar[NPT+6] = programme p_capture_slot) and every reduce
publication-relative constant +1 edge.  usage: gen_coll_q2_s.py REPO_ROOT"""
import sys
from pathlib import Path
root = Path(sys.argv[1]); P = root / 'rtl/hbm_accel/generic/collective/p2p'
s = (P / 'ot_hfd_coll_q_hard_v8g.sv').read_text()
i = s.index('module ot_hfd_coll_q_hard_v8g_body #('); j = s.index('endmodule', i) + len('endmodule')
body = s[i:j]
k = s.index('module ot_hfd_coll_q2_hard_v8g #('); m = s.index('endmodule', k) + len('endmodule')
q2 = s[k:m]
def sub(t, a, b):
    assert t.count(a) == 1, (a, t.count(a)); return t.replace(a, b)
body = sub(body, 'module ot_hfd_coll_q_hard_v8g_body #(', 'module ot_hfd_coll_q_hard_v8g_body_s #(')
body = sub(body, ' ot_hgi_coll_reduce_static u_reduce(', ' ot_hgi_coll_reduce_static_pr u_reduce(')
q2 = sub(q2, 'module ot_hfd_coll_q2_hard_v8g #(', 'module ot_hfd_coll_q2_hard_v8g_s #(')
q2 = sub(q2, ' ot_hfd_coll_q_hard_v8g_body #(', ' ot_hfd_coll_q_hard_v8g_body_s #(')
hdr = ('`timescale 1ns/1ps\n`default_nettype none\n'
       '// GENERATED by physical/die_plan/hbm/over_cap_split/gen_coll_q2_s.py (HBM-P5-RTLB 10-23) from the pinned\n'
       '// ot_hfd_coll_q_hard_v8g.sv (body + q2 parent text verbatim except the module names and u_reduce).\n'
       '// coll_q2 over-cap split ring_ag | reduce | body: the only unregistered crossings are body -> reduce (reduce captures\n'
       '// its strobes / tags / flit in logic) and reduce.fault (comb OR) -> u_fj; u_reduce = ot_hgi_coll_reduce_static_pr\n'
       '// registers them: AR reduce publication +1 edge (reduce-source qslots capture slot +1 in the programme), fault +2.\n'
       '// ring_ag <-> body: fault only (flop -> u_fj flop), no change.\n')
(P / 'ot_hfd_coll_q2_hard_v8g_s.sv').write_text(hdr + body + '\n\n' + q2 + '\n`default_nettype wire\n')
print('generated ot_hfd_coll_q2_hard_v8g_s.sv')
