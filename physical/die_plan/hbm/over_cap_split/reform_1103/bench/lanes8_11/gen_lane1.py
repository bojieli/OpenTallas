#!/usr/bin/env python3
"""DIE-HBM-61/SPLIT 11-03: RE-FORM split of ot_hbm_su_static_pgslice_lg__lanes8_11 (= ot_hbm_su_pg_lanes4_core, 244k
census cells, 24 SRAM macros).  The lanes4 core is 4 independent (lane k + bank k) pairs: the only member<->member nets
(n_int) join lane k to bank k (vi_re / vi_addr -> bank read port 4, bank read_data[159:128] -> vi_q); the pairs share
only broadcast INPUTS (lane0_* command/config bus, bank0_rst_n, bank0_read_v[4], bank0_read_addr).  Cut = FOUR
IDENTICAL sub-blocks ot_hbm_su_pg_lane1_core (one pair each, 6 SRAM macros), no crossing between them, every sub-block
pin = an uncut core pin (broadcast inputs land on every face): 0 added cycles on every port.
(The 2-pair form ot_hbm_su_pg_lanes2_core measured 169,093 ORFS cells > 150k: rejected.)

    gen_lane1.py LANES4_CORE.sv OUTDIR   -> ot_hbm_su_pg_lane1_core.sv + ot_hbm_su_pg_lanes4_core__split.sv
"""
import re, sys
src = open(sys.argv[1]).read().splitlines()
out = sys.argv[2]
drop = re.compile(r'\b(u_bank[123]|u_lane[123]|bank[123]_|lane[123]_)')
body = []
for ln in src:
    if ln.startswith('//'):
        continue
    if ln.startswith('module ot_hbm_su_pg_lanes4_core'):
        body.append(ln.replace('ot_hbm_su_pg_lanes4_core', 'ot_hbm_su_pg_lane1_core')); continue
    if drop.search(ln):
        continue
    body.append(ln.replace('wire [167:0] n_int;', 'wire [41:0] n_int;'))
txt = re.sub(r',\n\);', '\n);', '\n'.join(body))
# DIE-HBM-75 11-05 l1r5 RE-FORM (COORD 14:52, pin-cycle lever): lane1 cores use MLAT 5 (lat5i input-cut multiplier);
# the __split composition below keeps MLAT 4 as its default, so the lanes4 lock-step bench needs .MLAT(5) on both sides.
txt = txt.replace('parameter integer MLAT = 4,', 'parameter integer MLAT = 5,', 1)
hdr = ('// DIE-HBM-61/SPLIT 11-03 (OWNER TWO-STRIKES RE-FORM, HBM-RF1 / d44v): GENERATED by reform_1103/bench/lanes8_11/'
       'gen_lane1.py from rtl/hbm_accel/cores_split/ot_hbm_su_static_pgslice_lg/ot_hbm_su_pg_lanes4_core.sv (pairs 1-3 dropped;\n'
       '// members, params and wiring of pair 0 verbatim).  Sub-block of the lanes8_11 split: ot_hbm_su_static_lane_pinreg + '
       'ot_hbm_su_static_pinned_bank (6 SRAM macros).  4 identical replicas per lanes8_11.  Do not edit.\n')
open(f'{out}/ot_hbm_su_pg_lane1_core.sv', 'w').write(hdr + txt + '\n')
m = re.search(r'module ot_hbm_su_pg_lane1_core #\(.*?\) \((.*?)\n\);', txt, re.S)
ports = re.findall(r'(input|output) wire (\[[^\]]*\] )?(\w+)', m.group(1))
PER_LANE = ('clk_stage', 'clk_insert', 'rst_n', 'rd_q', 'lane_id')
SHARED = ('bank0_rst_n', 'bank0_read_addr')

def rep(name, d, k):
    if k == 0:
        return name
    kind, f = name.split('0_', 1)
    if kind == 'lane':
        return name if (d == 'input' and f not in PER_LANE) else f'lane{k}_{f}'
    if name in SHARED:
        return name
    if name == 'bank0_read_v':
        return f'{{bank0_read_v[4], bank{k}_read_v[3:0]}}'
    return f'bank{k}_{f}'

m4 = re.search(r'module ot_hbm_su_pg_lanes4_core #\(.*?\) \((.*?)\n\);', '\n'.join(src), re.S)
L = ['// DIE-HBM-61/SPLIT 11-03: GENERATED by gen_lane1.py.  Split composition of ot_hbm_su_pg_lanes4_core (same ports):',
     '// u_p<k> = pair k (lane k + bank k) = ot_hbm_su_pg_lane1_core in its face-shelled form (__fs = kit face shell model),',
     '// so this module is cycle-exact with the hardened composition.  No crossing between the sub-blocks.',
     '// Bench mutants (MUT 0 = the split form): 1 = u_p2 read_v[3:0] from bank0, 2 = u_p3 rd_q from lane2,',
     '// 3 = broadcast ld one edge late into u_p1.',
     '`timescale 1ns/1ps', '`default_nettype none',
     'module ot_hbm_su_pg_lanes4_core__split #(parameter integer MLAT = 4, parameter integer ALAT = 3, parameter integer WCOPY = 0, parameter integer MUT = 0) (',
     m4.group(1).strip('\n') + '\n);',
     '    reg ld_late; always @(posedge bank0_clk) ld_late <= lane0_ld;']
for k in range(4):
    c = []
    for d, w, n in ports:
        x = rep(n, d, k)
        if k == 2 and n == 'bank0_read_v':
            x = f'(MUT == 1) ? bank0_read_v : {x}'
        if k == 3 and n == 'lane0_rd_q':
            x = f'(MUT == 2) ? lane2_rd_q : {x}'
        if k == 1 and n == 'lane0_ld':
            x = f'(MUT == 3) ? ld_late : {x}'
        c.append(f'.{n}({x})')
    L.append(f'    ot_hbm_su_pg_lane1_core__fs u_p{k} (' + ', '.join(c) + ');')
L.append('endmodule\n`default_nettype wire\n')
open(f'{out}/ot_hbm_su_pg_lanes4_core__split.sv', 'w').write('\n'.join(L))
print(len(ports), 'sub-block ports')
