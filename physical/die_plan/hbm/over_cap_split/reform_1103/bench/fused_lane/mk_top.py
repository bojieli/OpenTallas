#!/usr/bin/env python3
"""DIE-HBM-61/SPLIT fused_lane bench: derive two bench tops from ot_hnx_fused_top (rtl/hbm_next/fused/ot_hnx_fused_eng.sv)
that host FACE-SHELLED lanes (the hardened form): the four lane-facing relays (dn, r, up, status) are one stage shorter
(RL - 1), because the lane face shell adds one flop on every lane input and one on every lane output (the plan counts
face flops as relay stages).  The bench VM model returns RR - 2 edges after rq (rq out face + rr in face).
    ot_hnx_fused_top_k : 32 x hnx_fused_lane          (the kit core: face shell + uncut lane)       = REFERENCE
    ot_hnx_fused_top_s : 32 x hnx_fused_lane__split   (ctl + 4 element pairs, each face-shelled)    = SPLIT
usage: mk_top.py ENG.sv OUT.sv"""
import re, sys
s = open(sys.argv[1]).read()
i = s.index('module ot_hnx_fused_top #('); j = s.index('endmodule', i) + len('endmodule')
top = s[i:j]
def mk(name, lane):
    t = top.replace('module ot_hnx_fused_top #(', f'module {name} #(', 1)
    for a, b in [('ot_hnx_fused_rly #(.W(139), .N(RL)) u_dn', 'ot_hnx_fused_rly #(.W(139), .N(RL - 1)) u_dn'),
                 ('ot_hnx_fused_rly #(.W(32), .N(RL)) u_rd', 'ot_hnx_fused_rly #(.W(32), .N(RL - 1)) u_rd'),
                 ('ot_hdc_delay #(.W(3), .D(RL), .RESET(1)) u_st', 'ot_hdc_delay #(.W(3), .D(RL - 1), .RESET(1)) u_st'),
                 ('ot_hnx_fused_rly #(.W(267), .N(RL)) u_up', 'ot_hnx_fused_rly #(.W(267), .N(RL - 1)) u_up')]:
        assert t.count(a) == 1, a; t = t.replace(a, b)
    a = 'ot_hnx_fused_lane #(.D(D), .KX(KX), .RR(RR), .MUT(MUT == 4 ? 0 : MUT)) u_l ('
    assert t.count(a) == 1; t = t.replace(a, lane + ' u_l (')
    return t
out = ['`timescale 1ns/1ps', '`default_nettype none', '// GENERATED by bench/fused_lane/mk_top.py from ' + sys.argv[1],
       mk('ot_hnx_fused_top_k', 'hnx_fused_lane'), '',
       mk('ot_hnx_fused_top_s', 'hnx_fused_lane__split #(.SMUT(SMUT))').replace('parameter integer MUT  = 0\n)', 'parameter integer MUT  = 0,\n    parameter integer SMUT = 0\n)', 1),
       '`default_nettype wire', '']
open(sys.argv[2], 'w').write('\n'.join(out))
