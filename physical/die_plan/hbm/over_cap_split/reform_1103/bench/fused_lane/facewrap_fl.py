#!/usr/bin/env python3
"""DIE-HBM-61/SPLIT 11-03: face-register shell MODEL for RE-FORM sub-blocks (bench + cell estimate only).
# bench/fused_lane copy of reform_1103/facewrap.py with `proc <top>` before write_json (a top with its own processes, e.g.
# hnx_fused_lane_elp, fails the shared copy: "contains processes").

The kit generator (physical/die_plan/hbm_arch_cores/face_shell.py) wraps every hardened core in one face flop per
signal pin bit (+1 cycle in, +1 cycle out; clock / reset pins pass through).  The split benches and the synth
estimates must see the sub-blocks exactly as they will be built, so this emits the same form:

    <module>__fs  : same ports as <module>; every non-clock / non-reset input bus -> ot_hbm_face_reg -> core,
                    every output bus <- ot_hbm_face_reg <- core; face flops on CLK (default: first clock port bit 0).

Ports come from yosys `write_json` of the elaborated module (no synthesis).  Clock = name matches CLK_RE, reset =
RST_RE (pass through).  Usage:
    facewrap.py --top M --out M__fs.sv [--yosys Y] [--clk-re RE] [--rst-re RE] [-D DEF] FILE.sv...
"""
import argparse, json, os, re, subprocess, sys, tempfile

ap = argparse.ArgumentParser()
ap.add_argument('--top', required=True)
ap.add_argument('--out', required=True)
ap.add_argument('--yosys', default=os.path.expanduser('~/.local/opentallas-tools/bin/yosys'))
ap.add_argument('--clk-re', default=r'^(clk|ck)(_|$|\b)|^clk_pair$|^clk$')
ap.add_argument('--rst-re', default=r'^(rst|rst_n|rst_col|rstn|rst_ni)$|^rst_')
ap.add_argument('--param', action='append', default=[], help='K=V chparam on the top')
ap.add_argument('-D', action='append', default=[])
ap.add_argument('--pass-param', action='append', default=[], help='integer parameter of the shell passed to the core (bench mutants)')
ap.add_argument('files', nargs='+')
a = ap.parse_args()

with tempfile.TemporaryDirectory() as td:
    js = os.path.join(td, 'p.json')
    defs = ' '.join('-D' + d for d in a.D)
    ch = ' '.join(f'-chparam {p.split("=")[0]} {p.split("=")[1]}' for p in a.param)
    scr = f"read_verilog -sv {defs} {' '.join(a.files)}; hierarchy -top {a.top} {ch}; select {a.top}; proc {a.top}; write_json -selected -noscopeinfo {js}"
    r = subprocess.run([a.yosys, '-q', '-p', scr], capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr[-2000:])
    mods = json.load(open(js))['modules']
mod = [m for k, m in mods.items() if k == a.top or k.startswith('$paramod') and a.top in k]
ports = (mod[0] if mod else mods[a.top])['ports']
clk = [n for n in ports if re.search(a.clk_re, n)]
rst = [n for n in ports if re.search(a.rst_re, n) and n not in clk]
assert clk, f'no clock port in {a.top}: {list(ports)}'
fclk = clk[0] + ('[0]' if len(ports[clk[0]]['bits']) > 1 else '')
L = [f'// GENERATED by reform_1103/facewrap.py: face-register shell model of {a.top} (kit face_shell form, +1 in / +1 out).',
     '`default_nettype none', f'module {a.top}__fs' + (' #(' + ', '.join(f'parameter integer {q} = 0' for q in a.pass_param) + ')' if a.pass_param else '') + ' (']
pl = []
for n, p in ports.items():
    w = len(p['bits'])
    pl.append(f"    {'input' if p['direction'] == 'input' else 'output'} wire {f'[{w-1}:0] ' if w > 1 else ''}{n}")
L.append(',\n'.join(pl) + '\n);')
conn = []
for n, p in ports.items():
    w = len(p['bits'])
    if n in clk or n in rst:
        conn.append(f'.{n}({n})'); continue
    L.append(f'    wire [{w-1}:0] {n}__f;')
    if p['direction'] == 'input':
        L.append(f'    (* keep *) ot_hbm_face_reg #(.W({w})) u_bin_{n} (.clk({fclk}), .d({n}), .q({n}__f));')
    else:
        L.append(f'    (* keep *) ot_hbm_face_reg #(.W({w})) u_bout_{n} (.clk({fclk}), .d({n}__f), .q({n}));')
    conn.append(f'.{n}({n}__f)')
pp = ''.join(f'.{p.split("=")[0]}({p.split("=")[1]}),' for p in a.param) + ''.join(f'.{q}({q}),' for q in a.pass_param)
pp = pp.rstrip(',')
L.append(f"    {a.top} {('#(' + pp + ') ') if pp else ''}u_fcore ({', '.join(conn)});")
L.append('endmodule\n`default_nettype wire\n')
open(a.out, 'w').write('\n'.join(L))
print(json.dumps(dict(top=a.top, clk=clk, rst=rst, ports={n: [p['direction'], len(p['bits'])] for n, p in ports.items()})))
