#!/usr/bin/env python3
"""SM internal split (HBM-QLOCAL Step C item 7): ot_hbm_accel_smh_attn -> 4 stacked partitions q_sm<k>a..d.

Inputs (all in this directory, regenerated by tools/ from the r18g/r18h5 SM synthesis; see README.md):
  inputs/sm_conn_r18g.json        child-to-child bit connections of the SM top (tools/net_analyze.py on the hierarchical
                                  yosys netlist), each with launch / capture kind (reg = flop, logic = gates)
  inputs/sm_child_cells_r18g.json measured yosys cell totals per child module (tools/stat_tree.py on the hier stat)
  ../die_plan.json                external SM lanes per quarter + the die lanes that already cross the SM's inner faces
Outputs: sm_split.json, sm_internal_census.tsv.   Deterministic; no P&R, no synthesis.
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda p: json.load(open(os.path.join(HERE, p)))
conn = J('inputs/sm_conn_r18g.json')
cc = J('inputs/sm_child_cells_r18g.json')
plan = J('../die_plan.json')

FACE_UM = 1944.0          # q_sm* partition width = the N/S face shared by stacked quarters
FACE_BUDGET = plan['budgets']['face_pins_per_um']
CORE_BUDGET = 350_000     # yosys cells per planned core (taps_cores_v2.py convention; L1 cap 400k OpenROAD cells)
CAP = 400_000
ORDER = 'abcd'            # a = VM / die-centre side (rdata, fault land here) ... d = die-edge side (command, packet, xw)

# ---------------------------------------------------------------- child -> quarter (column pairs; front with c2/c3)
COLQ = {0: 'd', 1: 'd', 2: 'c', 3: 'c', 4: 'b', 5: 'b', 6: 'a', 7: 'a'}
def quarter(inst):
    m = re.match(r'g_c\[(\d)\]', inst)
    if m: return COLQ[int(m.group(1))]
    if inst in ('u_front', 'g_int8.g_hard.u_int8', 'top_reg', 'top_glue'): return 'c'
    if inst.startswith('PORT:'):
        return {'command': 'd', 'kv_desc': 'd', 'packet': 'd', 'xw_en': 'd', 'xw_addr': 'd', 'xw_grp': 'd',
                'xw_data': 'd', 'rv': 'a', 'rrow': 'a', 'rdata': 'a', 'fault': 'a', 'schedule_fault': 'a',
                'request': '-'}[inst[5:]]
    return '?'

BE_HASH = {}
for mod, inst in conn['insts']:
    if inst.endswith('u_be'): BE_HASH[inst] = mod.split('$')[2].split('\\')[0]
TILE = cc['ot_hbm_sm_attn_tile']; LH = cc['ot_hbm_sm_attn_leafh']; NC = cc['ot_hbm_sm_attn_native_col']
XS = cc['ot_hbm_accel_smh_xs']; BDC = cc['ot_hbm_accel_smh_bdc']; PTW = cc['ot_hbm_accel_smh_pt_w']
PTE = cc['ot_hbm_accel_smh_pt_e']; FR = cc['ot_hbm_sm_attn_front_static']; SF = cc['ot_smh_static_front']
TOP_OWN = 1203            # SM top's own cells (int8 packet mux AO22 x1034 + be_cmd / i8 fault regs), from the stat
INT8 = 9140
LH_OWN = LH['cells'] - NC['cells'] - XS['cells'] - BDC['cells']
TP = TILE['cells'] - 2 * LH['cells']                     # pt_w + pt_e + pass/gather kregs + rst relay
FA = FR['cells'] - SF['cells']                           # attention front: kv_line, i8w, pstore, desc, row launch, own

# closed-run calibration (or_capacity_runs.csv: finish std cells; same module, possibly older variant)
CAL = [dict(module='ot_hbm_accel_smh_tcl_gu', yosys=48200, orfs=42938, run='smh_tcl_gu_ref-gu1-216dbd2f1'),
       dict(module='ot_hbm_sm_pv_merge(_s3)', yosys=80613, orfs=92030, run='smh_pvm_ref_s4a-852319483 (s3 variant)'),
       dict(module='ot_hbm_accel_smh_tct', yosys=65783, orfs=54226, run='smh_tct_ref_p50-r1-9214bae8b'),
       dict(module='ot_hbm_accel_smh_bdc', yosys=60410, orfs=60651, run='smh_bdc_ref_p50-r1-9214bae8b'),
       dict(module='ot_hbm_accel_smh_xs', yosys=54674, orfs=107190, run='smh_xs_p192d_bay-f61a12bcc (p192d variant)'),
       dict(module='ot_hbm_accel_smh_pt_w', yosys=26426, orfs=58063, run='smh_pt_w_ref_p45h-r1-6332f4e44'),
       dict(module='ot_hbm_accel_smh_pt_e', yosys=14826, orfs=49933, run='smh_pt_e_ref_p40s-r1-6332f4e44'),
       dict(module='ot_hbm_accel_smh_fc_b', yosys=19702, orfs=45423, run='smh_fcb_ref_p40-r1-9214bae8b'),
       dict(module='ot_hbm_accel_smh_fc_t', yosys=17134, orfs=31347, run='smh_fct_ref_p45-r1-9214bae8b'),
       dict(module='ot_hbm_accel_smh_fc_xl', yosys=14056, orfs=43436, run='smh_fcxl_ref_p45-r1-9214bae8b'),
       dict(module='ot_hbm_accel_smh_fc_xr', yosys=5290, orfs=21622, run='smn_fcxr_ref_fa-r2-c1dfe3d51'),
       dict(module='ot_smh_int8_tile(_safe)', yosys=9140, orfs=15493, run='smh_int8_s2-s2-b5739c671 (safe variant)')]
for c in CAL: c['ratio'] = round(c['orfs'] / c['yosys'], 2)
EST_LN = 2 * 42938 + 92030 + 54226 + 1665 + 1
EST_LX = (60651 + 54674 + LH_OWN, 60651 + 107190 + LH_OWN)
EST_TP = 58063 + 49933 + (TP - PTW['cells'] - PTE['cells'])
EST_SF = 2 * 45423 + 2 * 31347 + 43436 + 2 * 21622 + (SF['cells'] - 2 * 19702 - 2 * 17134 - 14056 - 2 * 5290)

# ---------------------------------------------------------------- children table
children = []
for mod, inst in conn['insts']:
    q = quarter(inst)
    if inst.endswith('u_t'):
        children.append(dict(inst=inst, module='ot_hbm_sm_attn_tile', quarter=q, cells=TILE['cells'], dff=TILE['dff'],
                             std_area_um2=TILE['area_um2'], srams=TILE['sram'], basis='MEASURED-SYNTH'))
    elif inst.endswith('u_be'):
        b = cc['be_by_hash'][BE_HASH[inst]]
        children.append(dict(inst=inst, module='ot_hbm_sm_attn_be', param_hash=BE_HASH[inst], quarter=q,
                             cells=b['cells'], dff=b['dff'], std_area_um2=b['area_um2'], srams=0, basis='MEASURED-SYNTH'))
    elif inst == 'u_front':
        children.append(dict(inst=inst, module='ot_hbm_sm_attn_front_static', quarter=q, cells=FR['cells'], dff=FR['dff'],
                             std_area_um2=FR['area_um2'], srams=FR['sram'], basis='MEASURED-SYNTH'))
    else:
        children.append(dict(inst=inst, module='ot_smh_int8_tile', quarter=q, cells=INT8, dff=2391, std_area_um2=1150.0,
                             srams=0, basis='MEASURED-SYNTH'))
children.append(dict(inst='(top glue)', module='ot_hbm_accel_smh_attn own cells', quarter='c', cells=TOP_OWN, dff=31,
                     std_area_um2=157.0, srams=0, basis='MEASURED-SYNTH',
                     note='int8 packet select (AO22 x1034), be_cmd[28:0] register, i8 fault/busy'))
SM_TOTAL = 13001312
assert sum(c['cells'] for c in children) == SM_TOTAL, sum(c['cells'] for c in children)

# ---------------------------------------------------------------- cores per quarter
quarters = {}
for q in ORDER:
    cores, glue = [], []
    for c in children:
        if c['quarter'] != q: continue
        i = c['inst']
        if i.endswith('u_t'):
            for j in (0, 1):
                cores.append(dict(name=f'{i}.g_lf[{j}].u_lh.u_nc', module='ot_hbm_sm_attn_native_col', role='ln',
                                  cells=NC['cells'], label='MEASURED-SYNTH', est_orfs=EST_LN,
                                  est_basis='closed tcl_gu x2 + pv_merge_s3 + tct + sum_capture yosys'))
                cores.append(dict(name=f'{i}.g_lf[{j}].u_lh (xs+bdc+leafh glue)', module='ot_hbm_sm_attn_leafh minus native_col',
                                  role='lx', cells=XS['cells'] + BDC['cells'] + LH_OWN, label='MEASURED-SYNTH',
                                  est_orfs=list(EST_LX), est_basis='closed bdc + xs yosys..closed p192d xs'))
            cores.append(dict(name=f'{i} (pt_w+pt_e+pass/gather regs)', module='ot_hbm_sm_attn_tile minus leafh', role='tp',
                              cells=TP, label='MEASURED-SYNTH', est_orfs=EST_TP, est_basis='closed pt_w p45h + pt_e p40s'))
        elif i == 'u_front':
            cores.append(dict(name='u_front.u_normal', module='ot_smh_static_front', role='fs', cells=SF['cells'],
                              label='MEASURED-SYNTH', est_orfs=EST_SF, est_basis='closed fc_b/fc_t/fc_xl/fc_xr + rest yosys'))
            cores.append(dict(name='u_front (attention: u_converter kv_line, u_i8w, u_p, u_desc, row launch, own)',
                              module='ot_hbm_sm_attn_front_static minus ot_smh_static_front', role='fa', cells=FA,
                              label='MEASURED-SYNTH', est_orfs=None, est_basis='no closed run (kv_line 100k + i8w 43k)'))
        else:
            glue.append(dict(inst=i, module=c['module'], cells=c['cells'], label='MEASURED-SYNTH'))
    quarters[q] = dict(cores=cores, glue=glue)

# ---------------------------------------------------------------- as-built internal census rows
rows = []
agg = {}
for r in conn['rows']:
    if r['dst_port'] in ('clk', 'rst_n'): continue
    if r['src'] in ('undriven', 'const'): continue          # straps / chain-end zeros: constants, not lanes
    kinds = collections.Counter()
    for k, v in r['kinds'].items():
        a, b = k.split('|')
        a = 'reg' if a in ('reg', 'top_reg') else ('port' if a.startswith('PORT') else 'logic')
        b = 'reg' if b == 'reg' else 'logic'
        kinds[(a, b)] += v
    src = 'top_reg(be_cmd)' if r['src'] == 'top_reg' else r['src']
    for (a, b), v in sorted(kinds.items()):
        key = (src, r['src_port'] if r['src'] != 'top_reg' else 'be_cmd', r['dst'], r['dst_port'], a, b)
        if key in agg:
            agg[key]['bits'] += v; continue
        agg[key] = dict(src=src, src_port=key[1], dst=r['dst'],
                        dst_port=r['dst_port'], bits=v, via_top_glue=r['via_top_glue'], launch=a, capture=b,
                        src_q=quarter(r['src'] if r['src'] != 'top_reg' else 'top_reg'), dst_q=quarter(r['dst']))
        rows.append(agg[key])
# SM outputs (front -> SM output ports; driver kinds from tools/front_out check: rv/rrow/fault reg, rdata logic (i8w
# select), schedule_fault logic (OR with the int8 fault at the top), request logic and unconnected on the die)
for p, w, k in (('rv', 1, 'reg'), ('rrow', 12, 'reg'), ('rdata', 256, 'logic'), ('fault', 1, 'reg'),
                ('schedule_fault', 1, 'logic'), ('request', 43, 'logic')):
    rows.append(dict(src='u_front', src_port=p, dst='PORT:' + p, dst_port=p, bits=w, via_top_glue=(p == 'schedule_fault'),
                     launch=k, capture='die-lane', src_q='c', dst_q=quarter('PORT:' + p)))

def rel(a, b):
    if '-' in (a, b): return 'unconnected'
    d = abs(ORDER.index(a) - ORDER.index(b))
    return 'same' if d == 0 else ('adjacent' if d == 1 else f'non-adjacent({d})')
for r in rows: r['crossing'] = rel(r['src_q'], r['dst_q'])

# ---------------------------------------------------------------- planned crossings (as-built + required relays)
X = []
def add(boundary, src, dst, bits, direction, launch, capture, registered, note, change=None):
    X.append(dict(boundary=boundary, src=src, dst=dst, bits=bits, dir=direction, launch=launch, capture=capture,
                  registered=registered, note=note, rtl_change=change))
for r in rows:
    if r['crossing'] != 'adjacent': continue
    if r['src'].startswith('PORT:') or r['dst'].startswith('PORT:'): continue
    if r['src'].startswith('top_reg'): continue        # be_cmd broadcast: planned as one lane per boundary below
    bd = ''.join(sorted(r['src_q'] + r['dst_q']))
    bd = bd[0] + '-' + bd[1]
    reg = r['launch'] == 'reg' and r['capture'] == 'reg'
    add(bd, f"{r['src']}.{r['src_port']}", f"{r['dst']}.{r['dst_port']}", r['bits'], f"{r['src_q']}->{r['dst_q']}",
        r['launch'], r['capture'], reg, 'as-built',
        None if reg else 'R1: front row-bundle launch register after the attention_q select (see README)')
# be_cmd: one 29-bit lane per boundary (forked in the receiving quarter); a's BEs via a relay in b
add('b-c', 'top_reg(be_cmd)', 'b: g_c[4..5].u_be.command + relay rl_becmd', 29, 'c->b', 'reg', 'reg', True,
    'as-built broadcast, one lane forked in b')
add('a-b', 'b: rl_becmd (new relay)', 'a: g_c[6..7].u_be.command', 29, 'b->a', 'reg', 'reg', True,
    'new relay (c->a is non-adjacent); BE CONTROL_DELAY -1 for c6/c7 keeps the control in step', 'R4')
add('c-d', 'top_reg(be_cmd)', 'd: g_c[0..1].u_be.command', 29, 'c->d', 'reg', 'reg', True, 'as-built broadcast')
# SM outputs: front (c) -> a, through b
add('b-c', 'c: sm_out pin regs (new) <- u_front rv/rrow/rdata/fault/schedule_fault', 'b: rl_smout (new relay)', 271,
    'c->b', 'reg', 'reg', True, 'rdata/schedule_fault are gate-driven at the front: pin register in c first', 'R3')
add('a-b', 'b: rl_smout (new relay)', 'a: die lanes L157/L158 (smq.fault/smq.rdata)', 271, 'b->a', 'reg', 'reg', True,
    'feedthrough relay in b', 'R3')
# SM inputs: land in d (die plan), front is in c
add('c-d', 'd: sm_in relay regs (new) <- die lanes L185/L186/L215/L216', 'c: u_front command/kv_desc/packet/xw_* '
    '(+ int8 tile / packet select)', 192 + 64 + 1099 + 1 + 7 + 7 + 2048, 'd->c', 'reg', 'logic', False,
    'front inputs feed gates directly (feed, kv_line, int8 select, x-write) -> needs c-side landing regs (R2) or '
    're-land the input lanes on c (R2-alt, removes these bits from the c-d face)', 'R2')

bt = collections.OrderedDict()
for bd in ('a-b', 'b-c', 'c-d'):
    xs = [x for x in X if x['boundary'] == bd]
    dirs = collections.Counter()
    for x in xs: dirs[x['dir']] += x['bits']
    bt[bd] = dict(bits=sum(x['bits'] for x in xs), by_dir=dict(dirs),
                  unregistered_bits=sum(x['bits'] for x in xs if not x['registered']))
# die lanes that already cross the SM's inner faces (die plan ft through the SM stack), worst SM group
die_ft = collections.Counter(); die_ft_by = collections.defaultdict(dict)
for p in plan['ports']:
    s, t = p['src']['part'], p['dst']['part']
    if '_sm' in s and '_sm' in t and s[:-1] == t[:-1]:
        pr = '-'.join(sorted([s[-1], t[-1]]))
        die_ft_by[pr][s[:-1]] = die_ft_by[pr].get(s[:-1], 0) + p['width']
face = collections.OrderedDict()
for bd in bt:
    worst_g = max(die_ft_by[bd], key=die_ft_by[bd].get)
    w = die_ft_by[bd][worst_g]
    tot = bt[bd]['bits'] + w
    face[bd] = dict(sm_internal_bits=bt[bd]['bits'], die_ft_bits_worst=w, worst_group=worst_g,
                    die_ft_bits_median=sorted(die_ft_by[bd].values())[len(die_ft_by[bd]) // 2],
                    total_worst=tot, pins_per_um_worst=round(tot / FACE_UM, 2),
                    pins_per_um_sm_only=round(bt[bd]['bits'] / FACE_UM, 2), budget_pins_per_um=FACE_BUDGET,
                    ok_worst=tot / FACE_UM <= FACE_BUDGET)
relanded = bt['c-d']['bits'] - 3418
face['c-d']['sm_internal_bits_if_inputs_relanded_on_c'] = relanded
face['c-d']['pins_per_um_worst_if_relanded'] = round((relanded + face['c-d']['die_ft_bits_worst']) / FACE_UM, 2)

# ---------------------------------------------------------------- per-quarter totals
NEWREG_BITS = {'a': 0, 'b': 271 + 29, 'c': 271 + 3418, 'd': 3418}     # R2 (c landing) + R3 + R4 relays
for q in ORDER:
    Q = quarters[q]
    ch = [c for c in children if c['quarter'] == q]
    core_cells = [c['cells'] for c in Q['cores']]
    glue_cells = sum(g['cells'] for g in Q['glue'])
    Q.update(children=[c['inst'] for c in ch], cells_measured=sum(c['cells'] for c in ch),
             dff_measured=sum(c['dff'] for c in ch), srams=sum(c['srams'] for c in ch),
             std_area_um2=round(sum(c['std_area_um2'] for c in ch)),
             n_cores=len(Q['cores']), core_cells_max=max(core_cells), core_cells_total=sum(core_cells),
             glue_cells_measured=glue_cells, new_relay_bits=NEWREG_BITS[q],
             glue_cells_with_relays_est=glue_cells + 2 * NEWREG_BITS[q] + (30000 if q == 'c' else 0),
             glue_note=('BEs + new pin/relay registers (EST 2 cells/bit)' +
                        ('; c also holds R1 (+14,820 front launch flops, EST +30k cells, inside core fs/fa) and the '
                         'int8 tile + top select' if q == 'c' else '')),
             ok_core_budget=max(core_cells) <= CORE_BUDGET, ok_glue_cap=glue_cells + 2 * NEWREG_BITS[q] + 30000 <= CAP)
assert sum(quarters[q]['cells_measured'] for q in ORDER) == SM_TOTAL

unreg = [x for x in X if not x['registered']]
out = collections.OrderedDict(
    schema='opentallas.hbm.sm_split.v1',
    note=('HBM d4g SM (ot_hbm_accel_smh_attn, ENABLE_INT8=1 INT8W=1) split into the 4 stacked plan partitions '
          'q_sm<k>a..d (each 1944 x 1736.64 um). Order a (VM / die-centre side: rdata+fault lanes land) .. d (die-edge '
          'side: command, kv_desc, packet, xw lanes land). Chain topology: front in the middle of 8 columns (c3 | F | c4); '
          'quarters = column pairs, front with c2/c3 in c. Generated by gen_sm_split.py; HBM-P3-SM 2026-10-23.'),
    source=dict(synth='ot-epyc5:/srv/opentallas-scratch/claude/hbmc-r18g-1021/chainsM/syn/ot_hbm_accel_smh_attn',
                view='r18h5 chainsM/views/synth/ot_hbm_accel_smh_attn (kind SYNTH, wrapper v16w_ot_hbm_accel_smh_attn)',
                source_commit='4027f385f', params=dict(ENABLE_INT8=1, INT8W=1),
                defines='OT_SMH_FC_HIER OT_SMH_HIER OT_SMH_XLK OT_FP_DATA_NORST OT_SMH_DRST0 OT_SMH_RSTRELAY (no OT_SMH_PINREG)',
                netlist_sha256='fab961855d5b28efbd346743742358e06bf9def1db16d1d84c2c16c91ec4b051',
                stat_sha256='78ed92699c49657000df67bd7df73418603cea61ad4f10cc6d5f98cac1a4081d',
                die_plan='physical/die_plan/hbm/die_plan.json (worktree claude/hbm-p3-1023)'),
    labels=dict(MEASURED_SYNTH='yosys synth + abc (ASAP7 all.lib) hierarchical stat of the die SM view; no P&R',
                EST_ORFS='calibrated with closed runs of the same sub-modules (calibration[]), OpenROAD finish std cells'),
    caps=dict(core_budget_yosys=CORE_BUDGET, or_run_cap=CAP, note='COORD 06:12 L1 cap; taps_cores_v2.py budgets cores '
              'at <= 350k yosys cells'),
    sm_total=dict(cells=SM_TOTAL, dff=2699351, std_area_um2=1519802, srams=169, label='MEASURED-SYNTH',
                  finding=('13.0M cells: a quarter is 3.17-3.50M cells, i.e. 20-22 planned hard cores, not one '
                           '<=400k core; the 4-partition plan is still right (one tap / reach per 1.74-mm quarter)')),
    calibration=CAL,
    children=children,
    quarters=quarters,
    crossings=X,
    boundary_totals=bt,
    face_check=face,
    unregistered=dict(count_groups=len(unreg), bits=sum(x['bits'] for x in unreg),
                      items=[dict(boundary=x['boundary'], src=x['src'], dst=x['dst'], bits=x['bits'],
                                  rtl_change=x['rtl_change']) for x in unreg]),
    rtl_changes=[
        dict(id='R1', what='front rl/rr/bl/br one output register stage (rows leave from flops; rows+beats in step)',
             bits=14820, cycles=1, note='BE_DELAY +1; 0-cycle variant = select before the launch registers (check)'),
        dict(id='R2', what='SM input relay regs in d + landing regs in c (command, kv_desc, packet, xw)', bits=3418,
             cycles=2, alt='R2-alt: re-land die lanes L185/L186/L215/L216 on c: +1 cycle, -3418 bits on the c-d face'),
        dict(id='R3', what='SM output pin regs in c + relay in b (rv, rrow, rdata, fault, schedule_fault)', bits=271,
             cycles=2),
        dict(id='R4', what='be_cmd relay in b for c6/c7 BEs', bits=29, cycles=0, note='CONTROL_DELAY -1 on c6/c7'),
        dict(id='R5', what='candidate: one shared x-write beat chain per column hop (p1 takes the beat from p0)',
             bits_saved_per_boundary=2069, cycles=0, status='NOT VERIFIED (bl[0] vs bl[1] equality/delay)')],
    benches=['rtl/test/hbm_accel/sm_attn/tb_hbm_smh_attn.sv', 'tools/hbm_sm_attention/sm_attn_bench.py (ds640, ds128, mutants)',
             'rtl/hbm_accel/sm/attn/run_pvacc.sh (PV merge)', 'rtl/test/hbm_accel/svg_rel/tb_toksim_smhbm.sv (SM token)',
             'tools/hbm_die_v16/d4g_layers per-layer token pass', 'smh_int8 exact + mutants'],
    alternative_single_partition=dict(
        outline_um=[1944.0, 6955.2], cells=SM_TOTAL, cores=82, glue_cells_measured=343000, glue_cells_with_relays_est=383000,
        tap_reach_um=dict(to_end=3478, l1_corner=4450, rule=1200), seam_pins=0,
        verdict='not recommended: one-tap/reach rule needs >= 6-8 internal taps anyway, glue near the cap, a single '
                '82-macro 13.5 mm2 assembly far beyond any closed block (max 517k / 0.40 mm2); same latency'),
    recommendation='4 stacked partitions, front in c, R1-R4 (+R2-alt); die plan moves SM-stack ft lanes off the inner '
                   'SM faces (M8/M9) or R5 verified, before G3',
    nonadjacent_as_built=[dict(src=r['src'], dst=r['dst'], bits=r['bits'], src_q=r['src_q'], dst_q=r['dst_q'],
                               fix='relay in b (R3/R4)') for r in rows if r['crossing'].startswith('non-adjacent')],
)
json.dump(out, open(os.path.join(HERE, 'sm_split.json'), 'w'), indent=1)
with open(os.path.join(HERE, 'sm_internal_census.tsv'), 'w') as f:
    f.write('src_inst\tsrc_port\tdst_inst\tdst_port\tbits\tsrc_quarter\tdst_quarter\tcrossing\tlaunch\tcapture\tvia_top_glue\n')
