#!/bin/bash
# cont-takeover 2026-10-09: per-run pclk SDC for ot_hbm_tu_retry_phy_port.  physical/phys_intake/tu_retry_pclk.sdc timed the
# pclk-domain ports against pclk itself (source edge 0, no latency) while the pclk flops sit at the tree insertion: every
# registered pclk output failed by ~the insertion (turetryphy-rio-g700 -496 on a registered fec_tx_data) and every pclk input
# was a hold violation of the same size (turetryphy-lk-g640 CTS hold stall, 10,092 endpoints).  Here the pclk ports are
# timed against a virtual clock vpclk at the same insertion L the core ports get (io_vclk_m_<L>: vclk at L, 0.2 T + 150),
# and pclk carries ideal latency L before CTS (the link budget measures it; propagated clocks override it after CTS).
#   mk_tu_pclk_sdc.sh <L ps> > out.sdc
L=${1:-770}
echo "# generated by physical/cont_takeover/mk_tu_pclk_sdc.sh $L"
# pclk is created only when the session has none: the flow (pre-CTS, ideal at L); corner_sta reads 6_final.sdc first, so
# its propagated pclk is kept (route_mtp passes SDCX to corner_sta as a post-SDC too)
echo "if {![llength [get_clocks -quiet pclk]]} { create_clock -name pclk -period 833.333 [get_ports pclk]; set_clock_latency $L [get_clocks pclk] }"
cat <<SDC
create_clock -name vpclk -period 833.333
set_clock_latency $L [get_clocks vpclk]
set_clock_uncertainty -setup 60 [get_clocks {pclk vpclk}]
set_clock_uncertainty -hold 25 [get_clocks {pclk vpclk}]
set_clock_groups -asynchronous -group [get_clocks {pclk vpclk}] -group [get_clocks -quiet {core_clk vclk}]
set ot_pp [get_ports -quiet {phy_link_up phy_session* fec_tx_ready fec_rx_v fec_rx_ue fec_rx_data* fec_rx_seq* fec_rx_session* fb_valid fb_good fb_nak fb_seq* fb_session* fb_pop*}]
set ot_po [get_ports -quiet {fec_tx_v fec_tx_data* fec_tx_seq* fec_tx_session* fec_rx_ready ack_seq* ack_nak ack_session* ack_pop*}]
foreach ot_c [list core_clk vclk pclk] { if {[llength [get_clocks -quiet \$ot_c]]} {
  if {[llength \$ot_pp]} { unset_input_delay -clock [get_clocks \$ot_c] \$ot_pp }
  if {[llength \$ot_po]} { unset_output_delay -clock [get_clocks \$ot_c] \$ot_po } } }
if {[llength \$ot_pp]} { set_input_delay [expr 833.333 * 0.2 + 150] -clock vpclk \$ot_pp; set_input_delay -min 0 -clock vpclk \$ot_pp }
if {[llength \$ot_po]} { set_output_delay [expr 833.333 * 0.2 + 150] -clock vpclk \$ot_po; set_output_delay -min 0 -clock vpclk \$ot_po }
set_false_path -from [get_ports -quiet {prst_n rst_n}]
SDC
