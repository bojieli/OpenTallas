import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

TYPES = ("sle_su_l1__cl5ea486db", "sle_su_l1__clc6d66f5b")
REACH_UM = 275.0
LEAF_MAX = 32
RSN_BAND = [6.48, 18.060387, 136.08, 62.64]
RSN_REF = (16.008, 0.0)          # generator reference point: old hop 392.688 = (350-16.008)+(58.696258-0)
READER_STAGES = {5: [121.0, 14.151], 6: [121.0, 14.151]}
CHAINS = {  # (conn, core, leaf) -> new stage-0 site
    ("bus:x_ctl_o", "u_lane4", (433.0, 256.667897)): [452.0, 272.0],
    ("bus:x_stm_o", "u_lane4", (465.4, 274.655845)): [466.0, 282.0],
    ("bus:x_su_c_o", "u_lane4", (476.2, 263.204013)): [470.0, 280.0],
}


def man(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])


def cen(pts):
    return (sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts))


def tap_sites(T):
    ct = T["clock"]["landing_contract"]["collector_tree"]
    names = ct["taps"]
    cs = {n: (x, y) for n, x, y in T["reset"]["consumer_sites_um"]}
    core = {f"core_rst{i}": tuple(c["xy"]) for i, c in enumerate(ct["core_resets"])}
    out = {}
    for i, n in enumerate(names):
        if n in cs:
            out[i] = (n, cs[n], True)
        elif n in core:
            out[i] = (n, core[n], False)
        else:
            out[i] = (n, None, False)
    return out


def bank_site(T, inst):
    m = re.fullmatch(r"u_ft_(\w+?)_o_(\d+)", inst)
    if not m:
        return None, None
    slot, k = m.group(1), int(m.group(2))
    fs = [f for f in T["ft_slots"] if f["name"] == slot]
    if not fs:
        return None, None
    f = fs[0]
    landed = f"{slot}_i" in T["clock"]["landing_contract"]["bands"]
    bs = f.get("bit_sites_um") or []
    if landed and k < len(bs):
        return cen(bs[k]), "bit_sites[%d] (landed: station k = stage k+1)" % k
    if not landed and 1 <= k <= len(bs):
        return cen(bs[k - 1]), "bit_sites[%d]" % (k - 1)
    regs = f.get("regs_um") or []
    if k < len(regs):
        return tuple(regs[k]), "regs_um[%d]" % k
    return None, None


def op_bank_taps(tn, T, rep):
    taps = tap_sites(T)
    rows = T["reset"].get("bank_taps") or []
    load = {}
    for r in rows:
        load[r["tap"]] = load.get(r["tap"], 0) + len(r["sinks"])
    assign = {}
    for r in rows:
        for s in r["sinks"]:
            assign[s] = r["tap"]
    changes = []
    for s in sorted(assign):
        site, why = bank_site(T, s)
        if site is None:
            continue
        t = assign[s]
        name, xy, mission = taps[t]
        d = man(site, xy) if xy else None
        if mission and d is not None and d <= REACH_UM:
            continue
        cands = sorted((man(site, v[1]), i) for i, v in taps.items() if v[2] and v[1] and load.get(i, 0) < LEAF_MAX)
        nd, ni = cands[0]
        if nd > REACH_UM:
            changes.append(dict(sink=s, site=[round(site[0], 3), round(site[1], 3)], kept=t, why="no mission tap within reach"))
            continue
        load[t] -= 1
        load[ni] = load.get(ni, 0) + 1
        assign[s] = ni
        changes.append(dict(sink=s, site=[round(site[0], 3), round(site[1], 3)], site_from=why, was_tap=t, was_name=name,
                            was_um=None if d is None else round(d, 1), tap=ni, name=taps[ni][0], um=round(nd, 1)))
    if any("tap" in c for c in changes):
        by = {}
        order = []
        for r in rows:
            for s in r["sinks"]:
                t = assign[s]
                if t not in by:
                    by[t] = []
                    order.append(t)
                by[t].append(s)
        T["reset"]["bank_taps"] = [dict(tap=t, sinks=by[t]) for t in sorted(by)]
    rep["bank_taps"] = changes
    return [c for c in changes if "tap" in c]


def hop(box, p):
    return max(abs(x - p[0]) + abs(y - p[1]) for x in (box[0], box[2]) for y in (box[1], box[3]))


def op_rsn_band(tn, T, rep):
    lc = T["clock"]["landing_contract"]
    b = lc["bands"]["rsn_i"]
    if b["rect_um"] == RSN_BAND:
        rep["rsn_band"] = "already"
        return False
    old = list(b["rect_um"])
    assert abs(hop(old, RSN_REF) - b["max_pin_to_band_hop_um"]) < 0.01, (hop(old, RSN_REF), b["max_pin_to_band_hop_um"])
    area = (RSN_BAND[2] - RSN_BAND[0]) * (RSN_BAND[3] - RSN_BAND[1])
    assert area >= b["area_reserve_um2"], area
    for o, ob in lc["bands"].items():
        if o == "rsn_i":
            continue
        r = ob.get("rect_um")
        assert not (r[0] < RSN_BAND[2] and RSN_BAND[0] < r[2] and r[1] < RSN_BAND[3] and RSN_BAND[1] < r[3]), (o, r)
    for h in T["hard_cores"]:
        x0, y0 = h["origin_um"]; w, hh = h["outline_um"]
        r = [x0 - 2.16, y0 - 2.16, x0 + w + 2.16, y0 + hh + 2.16]
        assert not (r[0] < RSN_BAND[2] and RSN_BAND[0] < r[2] and r[1] < RSN_BAND[3] and RSN_BAND[1] < r[3]), (h["inst"], r)
    nh = round(hop(RSN_BAND, RSN_REF), 3)
    b["rect_um"] = list(RSN_BAND)
    b["max_pin_to_band_hop_um"] = nh
    b["placement"] = ("QC-SUL1-PLACE SUL1-SLE-LAND 11-25: S-face strip under the rsn_i pins (x 13.47..100.96), was "
                      f"{old} hop {old and round(hop(old, RSN_REF), 3)} um; " + b.get("placement", ""))
    n = 0
    for s in lc.get("collector_local_sources") or []:
        if s.get("name") == "rsn_i" and isinstance(s.get("band"), dict):
            s["band"]["rect_um"] = list(RSN_BAND)
            s["band"]["max_pin_to_band_hop_um"] = nh
            s["band"]["placement"] = b["placement"]
            n += 1
    rep["rsn_band"] = dict(old=old, new=RSN_BAND, area_um2=round(area, 1), hop_old=round(hop(old, RSN_REF), 3), hop_new=nh,
                           cls_copies=n)
    return True


def op_reader(tn, T, rep):
    st = T["clock"]["landing_reader_start"]["branches"]["rsn_i"]["stages"]
    ch = []
    for i, xy in READER_STAGES.items():
        if st[i]["xy_um"] != xy:
            ch.append(dict(stage=i, old=st[i]["xy_um"], new=xy))
            st[i]["xy_um"] = list(xy)
    o = T["clock"]["landing_reader_start"]["origin_rect_um"]
    oc = ((o[0] + o[2]) / 2, (o[1] + o[3]) / 2)
    rep["reader_rsn_i"] = dict(changes=ch, origin_to_stage_um=round(man(oc, READER_STAGES[5]), 1),
                               stage_to_far_band_um=round(hop(RSN_BAND, READER_STAGES[6]), 1))
    return bool(ch)


def chain_hops(e):
    pts = [tuple(e["from_um"] if str(e["launch"]).startswith("face") else e["leaf_um"])] + [tuple(r) for r in e["regs_um"]]
    pts.append(tuple(e["to_um"]))
    return [man(a, b) for a, b in zip(pts, pts[1:])]


def op_chains(tn, T, rep):
    out = []
    for e in T["internal_stations"]:
        key = (e.get("conn"), e.get("core"), tuple(round(v, 6) for v in e.get("leaf_um", [])))
        for (c, core, leaf), s0 in CHAINS.items():
            if key[0] == c and key[1] == core and abs(key[2][0] - leaf[0]) < 1e-3 and abs(key[2][1] - leaf[1]) < 1e-3:
                n = len(e["regs_um"])
                to = e["to_um"]
                new = [list(s0)] + [[round(s0[0] + (to[0] - s0[0]) * j / n, 3), round(s0[1] + (to[1] - s0[1]) * j / n, 3)]
                                    for j in range(1, n)]
                if e["regs_um"] == new:
                    out.append(dict(conn=c, core=core, already=True))
                    continue
                before = max(chain_hops(e))
                old = e["regs_um"]
                e["regs_um"] = new
                e["note"] = (e.get("note", "") + " | QC-SUL1-PLACE SUL1-SLE-LAND 11-25: stage 0 seated next to the u_lane4 E-face "
                             "pins (shared vm_wdata/vm_waddr fan-out), later stages re-spaced evenly, same count, 0 cycles")
                out.append(dict(conn=c, core=core, n=n, old=old, new=new, max_hop_old=round(before, 1),
                                max_hop_new=round(max(chain_hops(e)), 1)))
    rep["internal_stations"] = out
    assert len([o for o in out if not o.get("already")]) in (0, len(CHAINS)), out
    return any(not o.get("already") for o in out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("plan"); ap.add_argument("out"); ap.add_argument("report"); ap.add_argument("row")
    ap.add_argument("--rt", required=True)
    a = ap.parse_args(argv)
    sys.path.insert(0, str(Path(a.rt) / "tools" / "die_plan"))
    import fstart_reset_delta as F
    rb = Path(a.plan).read_bytes()
    raw = json.loads(rb)
    dump = F.dumper(rb, raw)
    before = {tn: json.dumps(raw["partition_types"][tn], sort_keys=True) for tn in TYPES}
    rep = {"base_sha": hashlib.sha256(rb).hexdigest()[:12], "types": {}}
    sets = {}
    for tn in TYPES:
        T = raw["partition_types"][tn]
        r = rep["types"].setdefault(tn, {})
        s = sets.setdefault(tn, {"set": {}})["set"]
        if op_bank_taps(tn, T, r):
            s[f"partition_types.{tn}.reset.bank_taps"] = T["reset"]["bank_taps"]
        if tn == "sle_su_l1__cl5ea486db":
            if op_rsn_band(tn, T, r):
                s[f"partition_types.{tn}.clock.landing_contract.bands.rsn_i"] = T["clock"]["landing_contract"]["bands"]["rsn_i"]
                s[f"partition_types.{tn}.clock.landing_contract.collector_local_sources[name=rsn_i].band"] = \
                    [x for x in T["clock"]["landing_contract"]["collector_local_sources"] if x["name"] == "rsn_i"][0]["band"]
            if op_reader(tn, T, r):
                s[f"partition_types.{tn}.clock.landing_reader_start.branches.rsn_i"] = \
                    T["clock"]["landing_reader_start"]["branches"]["rsn_i"]
        if op_chains(tn, T, r):
            s[f"partition_types.{tn}.internal_stations"] = T["internal_stations"]
    # only the two types changed
    other = {k for k in raw["partition_types"] if k not in TYPES}
    ob = json.loads(rb)
    assert all(raw["partition_types"][k] == ob["partition_types"][k] for k in other)
    assert all(raw[k] == ob[k] for k in raw if k != "partition_types")
    data = dump(raw)
    Path(a.out).write_text(data) if isinstance(data, str) else Path(a.out).write_bytes(data)
    osha = hashlib.sha256(Path(a.out).read_bytes()).hexdigest()[:12]
    rep["out_sha"] = osha
    rep["changed_types"] = [tn for tn in TYPES if json.dumps(raw["partition_types"][tn], sort_keys=True) != before[tn]]
    Path(a.report).write_text(json.dumps(rep, indent=1) + "\n")
    row = dict(row="SUL1-SLE-LAND (C1p): sle_su_l1 x2 bank taps off lane core taps + rsn_i band under its pins + lane4 E "
                   "stage-0 seat column", lane="QC-SUL1-PLACE", ruling="Fable visual review 11-25 05:2x (QC-SUL1-PLACE)",
               base="c1o_v13", base_sha=rep["base_sha"], out_sha=osha, overlay={},
               script="sul1_sle_land.py (idempotent)", types={k: v for k, v in sets.items() if v["set"]})
    Path(a.row).write_text(json.dumps(row, indent=1) + "\n")
    print(f"SUL1-SLE-LAND base {rep['base_sha']} -> {osha}; changed {rep['changed_types']}")
    for tn in TYPES:
        r = rep["types"][tn]
        for c in r.get("bank_taps", []):
            print(f"  {tn} BANK {c}")
        if "rsn_band" in r:
            print(f"  {tn} RSN_BAND {r['rsn_band']}")
        if "reader_rsn_i" in r:
            print(f"  {tn} READER {r['reader_rsn_i']}")
        for c in r.get("internal_stations", []):
            print(f"  {tn} CHAIN {c.get('conn')} {c.get('core')} hop {c.get('max_hop_old')} -> {c.get('max_hop_new')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
